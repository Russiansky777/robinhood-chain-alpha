def проверить_пояс_строк(работы=РАБОТЫ) -> str | None:
    """В каждом таймере пояс назван явно. Не назван -- отказ словами.

    ЗАЧЕМ. OnCalendar без суффикса считается в часовом поясе ХОСТА, а он стоит
    на Europe/Amsterdam: «06:00:00» выстрелило бы в 04:00Z. Прежде здесь стоял
    сторож часов хоста (`смещение == "+0000"` или отказ), и 02.10 в 14:23Z он
    остановил установку целиком -- правильно по существу, но лечение предлагал
    неверное: переводить часы боевого хоста ради четырёх таймеров значит трогать
    всё, что на нём идёт. Пояс в строке решает то же самое и ничего не трогает.
    """
    без_пояса = [р["имя"] for р in работы
                  if not str(текст_таймера(р)).count(f" {ПОЯС_ТАЙМЕРОВ}\n")]
    if без_пояса:
        return (f"у таймеров {', '.join(без_пояса)} в OnCalendar нет явного пояса"
                 f" {ПОЯС_ТАЙМЕРОВ}: systemd считал бы их в поясе хоста, и 06:00"
                 " выстрелило бы не в 06:00Z")
    return None


def проверить_что_systemd_понимает_пояс() -> str | None:
    """Пояс в строке понимает systemd v240+. Старый systemd СТРОКУ ОТВЕРГНЕТ, и
    таймер не запустится вовсе -- это надо узнать здесь, а не по молчащему
    таймеру через сутки.

    Спрашиваем сам systemd той же строкой, что положим в юнит, и требуем, чтобы
    он назвал ближайшее срабатывание. Нет systemd-analyze -- не отказ: тогда
    проверить нечем, и об этом говорится словами.
    """
    образец = f"{РАБОТЫ[0]['когда']} {ПОЯС_ТАЙМЕРОВ}"
    try:
        код, вывод = _выполнить(["systemd-analyze", "calendar", образец])
    except (OSError, subprocess.SubprocessError) as сбой:
        return None if isinstance(сбой, FileNotFoundError) else (
            f"systemd-analyze не отработал ({type(сбой).__name__})")
    if код != 0:
        return (f"systemd не понял строку «{образец}» (код {код}): {вывод[:300]}."
                 " Пояс в OnCalendar умеет systemd v240 и новее.")
    return None


def записать_если_изменилось(путь: str, текст: str) -> bool:
    """Записать файл, только если содержимое другое. Вернуть: писали ли.

    ЗАЧЕМ ИМЕННО ТАК. Повторная установка обязана быть безвредной: деплой идёт
    много раз в день. Перезапись тем же текстом меняет mtime, а проверка "служба
    старше своих модулей" смотрит на mtime -- и каждый второй деплой давал бы
    ложную тревогу. Та же причина, по которой доставка кода не переписывает файл
    с совпавшей суммой sha256.
    """
    try:
        with open(путь, encoding="utf-8") as ф:
            if ф.read() == текст:
                return False
    except OSError:
        pass
    каталог = os.path.dirname(путь) or "."
    os.makedirs(каталог, exist_ok=True)
    with open(путь, "w", encoding="utf-8") as ф:
        ф.write(текст)
    return True


def _выполнить(команда: list) -> tuple:
    готово = subprocess.run(команда, capture_output=True, text=True,
                             timeout=120, check=False)
    return готово.returncode, (готово.stdout + готово.stderr).strip()


def установить(включить: bool) -> int:
    """Положить юниты, таймеры и обёртку; по слову -- включить таймеры."""
    for отказ in (проверить_пояс_строк(), проверить_что_systemd_понимает_пояс()):
        if отказ:
            print("ОТКАЗ: " + отказ)
            return 2
    # Часы хоста больше НЕ требование: пояс назван в каждой строке OnCalendar.
    # Печатаем их как сведение -- чтобы в журнале прогона было видно, что
    # таймеры стоят в UTC на хосте с другим поясом, и это так и задумано.
    print(f"пояс хоста {time.strftime('%z')}, таймеры в {ПОЯС_ТАЙМЕРОВ}:"
          " OnCalendar считается по строке, а не по хосту")
    if os.geteuid() != 0:
        print("ОТКАЗ: установка юнитов требует root, а мы не root."
              " Ставит прогон деплоя по ssh root@хост.")
        return 2
    for каталог in (КАТАЛОГ, КАТАЛОГ_УЧЁТА + "/analysis", КАТАЛОГ_УЧЁТА + "/data",
                    КАТАЛОГ_ВЫГРУЗОК, КАТАЛОГ_ЖИВУЧЕСТИ,
                    os.path.dirname(ПУТЬ_ВЫГРУЗКИ),
                    os.path.dirname(ПУТЬ_ОТПРАВКИ_ДЛЯ_СВЕРКИ)):
        os.makedirs(каталог, exist_ok=True)
    # Владелец каталогов -- bot: юниты работают от bot, и root-овый каталог
    # означал бы "таймер сработал и ничего не записал". Ровно так уже потерялся
    # весь учёт кредитов детектора.
    код, вывод = _выполнить(["chown", "-R", "bot:bot", КАТАЛОГ])
    if код != 0:
        print(f"ОТКАЗ: chown на {КАТАЛОГ} не прошёл: {вывод}")
        return 2
    изменилось = []
    if записать_если_изменилось(ОБЁРТКА_ВЫГРУЗКИ, текст_обёртки()):
        изменилось.append(os.path.basename(ОБЁРТКА_ВЫГРУЗКИ))
    os.chmod(ОБЁРТКА_ВЫГРУЗКИ, 0o755)
    for работа in РАБОТЫ:
        for путь, текст in ((f"{SYSTEMD}/{работа['имя']}.service", текст_службы(работа)),
                            (f"{SYSTEMD}/{работа['имя']}.timer", текст_таймера(работа))):
            if записать_если_изменилось(путь, текст):
                изменилось.append(os.path.basename(путь))
    print("изменено файлов: " + (", ".join(изменилось) if изменилось
                                  else "ни одного (всё уже стояло)"))
    if изменилось:
        код, вывод = _выполнить(["systemctl", "daemon-reload"])
        if код != 0:
            print(f"ОТКАЗ: daemon-reload не прошёл: {вывод}")
            return 2
        print("daemon-reload сделан")
    else:
        # daemon-reload без изменений не нужен, и это не "пропустили проверку":
        # перечитывать то же самое систему просить незачем.
        print("daemon-reload не нужен: ни один файл не изменился")
    if not включить:
        print("таймеры НЕ включены: шаг звали без --vkljuchit")
        return 0
    имена = [f"{р['имя']}.timer" for р in РАБОТЫ]
    код, вывод = _выполнить(["systemctl", "enable", "--now"] + имена)
    if код != 0:
        print(f"ОТКАЗ: enable --now не прошёл: {вывод}")
        return 2
    for имя in имена:
        код, вывод = _выполнить(["systemctl", "is-enabled", имя])
        print(f"{имя}: is-enabled={вывод or 'пусто'}")
        if вывод != "enabled":
            print(f"ОТКАЗ: {имя} не включён после enable --now")
            return 2
    код, вывод = _выполнить(["systemctl", "list-timers", "bloom-*", "--no-pager"])
    print(вывод)
    return 0


def _бюджет_учёта_из_модуля() -> int | None:
    """TIME_BUDGET_S прямо из solana_ledger_run.py. Модуля рядом нет -- None.

    ЗАЧЕМ ЧИТАТЬ, А НЕ ПОВТОРИТЬ ЧИСЛО. Повторённое число расходится молча:
    поднимут бюджет конвейера до 70 минут, предел юнита останется 55 -- и учёт
    снова начнёт умирать до того, как допишет свой файл. Модуль едет на хост
    в другой каталог, и его отсутствие рядом -- НАЗВАННЫЙ пропуск, а не
    тихое "сошлось".
    """
    модуль = (Path(__file__).resolve().parent.parent / "analysis"
              / "solana_ledger_run.py")
    if not модуль.exists():
        return None
    for строка in модуль.read_text(encoding="utf-8").splitlines():
        if not строка.startswith("TIME_BUDGET_S"):
            continue
        выражение = строка.partition("=")[2].split("#")[0]
        произведение = 1
        try:
            for к in выражение.split("*"):
                произведение *= int(к.strip())
        except ValueError:
            return None
        return произведение
    return None


