def текст_службы(работа: dict) -> str:
    """Юнит одной работы. Ужесточение то же, что у боевых служб стенда."""
    строки = [
        "[Unit]",
        f"Description={работа['описание']}",
        "After=network-online.target",
        "Wants=network-online.target",
        "",
        "[Service]",
        "Type=oneshot",
        "User=bot",
        "Group=bot",
        f"WorkingDirectory={работа['рабочий_каталог']}",
        # env службы нужен ради HELIUS_API/HELIUS_API_KEY и DBOT_API_KEY. Файл
        # читает systemd от root и отдаёт процессу: значения в журнал прогона не
        # попадают, потому что журнала прогона здесь нет вовсе.
        f"EnvironmentFile={ENV_ФАЙЛ}",
        # ДОПОЛНИТЕЛЬНОЕ ОКРУЖЕНИЕ РАБОТЫ -- ПОСЛЕ EnvironmentFile нарочно: так
        # явная строка юнита сильнее файла, а не наоборот.
        *[f"Environment={з}" for з in (работа.get("окружение") or ())],
        f"ExecStart={работа['команда']}",
        # ЖУРНАЛ -- ЭТО ЕДИНСТВЕННЫЙ СЛЕД ТАЙМЕРА. Без него "таймер сработал, но
        # ничего не сделал" неотличимо от "таймер не сработал".
        "StandardOutput=journal",
        "StandardError=journal",
        f"SyslogIdentifier={работа['имя']}",
        f"TimeoutStartSec={работа['предел_с']}",
        "NoNewPrivileges=true",
        "PrivateTmp=true",
        "ProtectSystem=strict",
        "ProtectHome=read-only",
        # ПИСАТЬ -- ТОЛЬКО В СВОЙ КАТАЛОГ. ProtectHome=read-only закрывает весь
        # /home, и ReadWritePaths возвращает право ровно на наш угол: каталог
        # состояния боевых служб остаётся таймерам недоступным на запись.
        f"ReadWritePaths={КАТАЛОГ}",
        "ProtectKernelTunables=true",
        "ProtectControlGroups=true",
        "RestrictSUIDSGID=true",
        "LockPersonality=true",
        f"MemoryMax={работа['память']}",
        "TasksMax=64",
    ]
    return "\n".join(строки) + "\n"


def текст_таймера(работа: dict) -> str:
    """Таймер одной работы."""
    строки = [
        "[Unit]",
        f"Description=Tajmer: {работа['описание']}",
        "",
        "[Timer]",
        # ПОЯС -- В САМОЙ СТРОКЕ, А НЕ У ХОСТА. OnCalendar без суффикса
        # считается в часовом поясе хоста, а хост стоит на Europe/Amsterdam
        # (+0200): «06:00:00» выстрелило бы в 04:00Z, окно суток поехало бы, а
        # файл назывался бы тем же именем -- такую ошибку по имени файла не
        # увидеть. Прежде установка из-за этого отказывалась целиком и требовала
        # переводить хост на UTC; но переводить часы боевого хоста ради таймера
        # -- это трогать всё, что на нём идёт. systemd умеет пояс в строке
        # (v240+), и здесь он назван явно: теперь зона хоста не решает ничего.
        f"OnCalendar={работа['когда']} {ПОЯС_ТАЙМЕРОВ}",
        "AccuracySec=30s",
        # ДОГОН ОБЯЗАТЕЛЕН. Перезагрузка хоста в 05:58 без Persistent означала
        # бы потерянную суточную выгрузку целиком: следующий тик только через
        # сутки. С Persistent=true systemd помнит последнее срабатывание на
        # диске и догоняет пропущенное сразу после загрузки.
        "Persistent=true",
        f"Unit={работа['имя']}.service",
        "",
        "[Install]",
        "WantedBy=timers.target",
    ]
    return "\n".join(строки) + "\n"


