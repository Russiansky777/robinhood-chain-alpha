        # расписанию и может попасть в середину записи. Полуфайл не разберётся
        # как json, и прогон скажет "выгрузки нет" при живом таймере.
        f"{ПИТОН} -u {ПУТЬ_ВЫГРУЗКИ} \\",
        f"  --state-dir {КАТАЛОГ_СОСТОЯНИЯ} \\",
        '  --s "$S_OKNA" --do "$DO_OKNA" --polnye \\',
        '  --karta-regionov "$KARTA" \\',
        '  --out "$OUT.chast"',
        'mv "$OUT.chast" "$OUT"',
        'echo "gotovo: $OUT"',
