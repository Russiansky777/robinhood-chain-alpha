def самопроверка() -> int:
    пройдено = провалено = 0

    def ок(условие, что):
        nonlocal пройдено, провалено
        if условие:
            пройдено += 1
            print(f"  [ok  ] {что}")
        else:
            провалено += 1
            print(f"  [ПРОВАЛ] {что}")

    ок(len(РАБОТЫ) == 3, "работ ровно три: учёт, живучесть, суточная выгрузка")
    имена = [р["имя"] for р in РАБОТЫ]
    ок(len(set(имена)) == 3, "имена юнитов не совпадают между собой")
    ок(all(и.replace("-", "").isalnum() and и.isascii() for и in имена),
       "имена юнитов только ASCII: systemd кириллицы в имени не любит")

    for работа in РАБОТЫ:
        с = текст_службы(работа)
        т = текст_таймера(работа)
        имя = работа["имя"]
        ок("Type=oneshot" in с, f"{имя}: юнит oneshot, а не демон")
        ок("User=bot" in с and "Group=bot" in с,
           f"{имя}: работает от bot, а не от root")
        ок(f"EnvironmentFile={ENV_ФАЙЛ}" in с, f"{имя}: env службы подключён")
        ок("StandardOutput=journal" in с and "StandardError=journal" in с,
           f"{имя}: пишет в журнал -- иначе сбой таймера невидим")
        ок(f"ReadWritePaths={КАТАЛОГ}" in с,
           f"{имя}: писать можно только в каталог таймеров")
        ок(КАТАЛОГ_СОСТОЯНИЯ not in с.split("ReadWritePaths=")[1],
           f"{имя}: каталог состояния боевых служб на запись НЕ открыт")
        ок("ProtectSystem=strict" in с and "NoNewPrivileges=true" in с,
           f"{имя}: ужесточение то же, что у боевых служб")
        ок(f"TimeoutStartSec={работа['предел_с']}" in с,
           f"{имя}: у прогона есть предел времени ({работа['предел_с']} с)")
        ок("Persistent=true" in т,
           f"{имя}: пропущенный из-за перезагрузки запуск догоняется")
        ок(f"OnCalendar={работа['когда']}" in т,
           f"{имя}: расписание {работа['когда']}")
        ок(f"Unit={имя}.service" in т, f"{имя}: таймер зовёт свою службу")
        ок("WantedBy=timers.target" in т, f"{имя}: таймер можно включить enable")

    часовые = [р for р in РАБОТЫ if р["когда"].startswith("*:")]
    ок(len(часовые) == 2, "часовых работ ровно две: учёт и живучесть")
    ок(часовые[0]["когда"] != часовые[1]["когда"],
       "часовые работы стартуют в РАЗНЫЕ минуты: иначе живучесть мерится под"
       " нагрузкой учёта")
    суточные = [р for р in РАБОТЫ if "06:00:00" in р["когда"]]
    ок(len(суточные) == 1 and суточные[0]["имя"] == "bloom-vygruzka-sutki",
       "суточная выгрузка назначена на 06:00 (часы хоста обязаны быть UTC)")
    ок(all(р["предел_с"] <= 3000 for р in часовые),
       "часовой прогон обязан умереть до следующего тика, иначе час пропадёт")

    # ОТКАЗ ПРИ НЕ-UTC ЧАСАХ. Это и есть защита от тихого чужого часа.
    ок(проверить_часы("+0000") is None, "часы UTC -- установка разрешена")
    отказ = проверить_часы("+0200")
    ок(отказ and "не UTC" in отказ and "отменена" in отказ,
       "часы не UTC -- отказ СЛОВАМИ с причиной, а не выгрузка в чужой час")

    о = текст_обёртки()
    ок(о.startswith("#!/bin/sh") and "set -eu" in о,
       "обёртка выгрузки падает на первой же ошибке, а не идёт дальше")
    ок("sdelki_polosy_$DEN.json" in о,
       "имя файла выгрузки -- sdelki_polosy_<дата>, как ждёт Code-2")
    ок('--s "$S_OKNA" --do "$DO_OKNA"' in о,
       "окно задано с двух сторон: без верхней границы в файл попадут сутки+")
    ок("+%Y-%m-%dT06:00" in о and "yesterday" in о,
       "границы -- 06:00Z вчера .. 06:00Z сегодня, ровно как у прогона GitHub")
    ок('"$OUT.chast"' in о and 'mv "$OUT.chast" "$OUT"' in о,
       "выгрузка пишется в полуфайл и переименовывается: забор не увидит"
       " середину записи")
    ок("sdelki_polosy_vygruzka.py" in о,
       "зовётся УЖЕ СУЩЕСТВУЮЩАЯ выгрузка репозитория, своей копии счёта нет")
    ок("--polnye" in о, "выгрузка полная: Code-2 ждёт все поля позиции")
    ок("HELIUS" not in о and "KEY=" not in о,
       "в обёртке нет ни одного ключа: значения даёт EnvironmentFile")

    # Денежного пути в юнитах нет -- и это проверка, а не обещание.
    все_юниты = "".join(текст_службы(р) for р in РАБОТЫ)
    денежные = [с for с in ("bloom_seller.py", "bloom_detector.py",
                             "bloom_own_send", "--poslat", "--pisat",
                             "PERESCHITAT")
                 if с in все_юниты]
    ок(not денежные, f"ни один юнит не зовёт денежный путь (нашли: {денежные})")

    # Повторная установка не ломает: тот же текст второй раз не пишется.
    import tempfile
    with tempfile.TemporaryDirectory() as каталог:
        путь = os.path.join(каталог, "глубже", "bloom-uchet-chas.timer")
        первый = записать_если_изменилось(путь, "A\n")
        второй = записать_если_изменилось(путь, "A\n")
        третий = записать_если_изменилось(путь, "B\n")
        ок(первый is True, "первая установка пишет файл")
        ок(второй is False,
           "повторная установка тем же текстом НЕ пишет: иначе mtime поедет и"
           " проверка 'служба старше модулей' даст ложную тревогу")
        ок(третий is True, "изменившийся текст перезаписывается")
        ок(open(путь, encoding="utf-8").read() == "B\n",
           "на диске лежит последний текст")

    проверки, пропуск = _проводка_прогонов()
    for условие, что in проверки:
        ок(условие, что)
    if пропуск:
        print(f"  [пропуск] {пропуск}")

    итог = (f"самопроверка хостовых таймеров: {пройдено}/{пройдено + провалено}"
            " пройдено")
    print(итог if not пропуск else итог + " (часть проверок пропущена, см. выше)")
    return 1 if провалено else 0


def main() -> int:
    р = argparse.ArgumentParser()
    р.add_argument("--self-test", action="store_true")
    р.add_argument("--pokazat", action="store_true",
                   help="напечатать юниты, таймеры и обёртку и ничего не ставить")
    р.add_argument("--ustanovit", action="store_true",
                   help="положить юниты и таймеры на ЭТОТ хост (нужен root)")
    р.add_argument("--vkljuchit", action="store_true",
                   help="вместе с --ustanovit: systemctl enable --now на таймеры")
    а = р.parse_args()
    if а.self_test:
        return самопроверка()
    if а.pokazat:
        for работа in РАБОТЫ:
            print(f"===== {работа['имя']}.service =====")
            print(текст_службы(работа))
            print(f"===== {работа['имя']}.timer =====")
            print(текст_таймера(работа))
        print(f"===== {ОБЁРТКА_ВЫГРУЗКИ} =====")
        print(текст_обёртки())
        return 0
    if а.ustanovit:
        return установить(а.vkljuchit)
    # БЕЗ ФЛАГА -- САМОПРОВЕРКА, А НЕ УСТАНОВКА. Установка правит
    # /etc/systemd/system, и случиться она должна только по явному слову; а
    # запуск без флага у нас по дому означает самопроверку. Молчать и выходить
    # нулём нельзя -- говорим, что сделали и чего не сделали.
    print("флага нет -- гоню самопроверку; установка требует явного --ustanovit",
          file=sys.stderr)
    return самопроверка()


if __name__ == "__main__":
    raise SystemExit(main())
