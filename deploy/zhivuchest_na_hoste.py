"""Живучесть служб, посчитанная САМИМ ХОСТОМ и записанная в файл.

ЗАЧЕМ. Почасовую живучесть до сих пор считал прогон GitHub по расписанию
(run_vps_health_nl.yml): он спрашивал хост по ssh и коммитил ответ. За ночь
01->02.10 GitHub пропустил пять назначенных прогонов учёта, и таблица полосы
отставала на шесть часов -- тот же планировщик везёт и живучесть, значит и она
стоит ровно столько же, сколько его доброе настроение. Поэтому считает теперь
хост своим таймером, а прогон GitHub только ЗАБИРАЕТ готовый файл.

ЧЕМ ЭТО НЕ ЧАСОВАЯ СТРОКА ВЛАДЕЛЬЦУ. bloom_host_stroki.py --rezhim chas уже
живёт на хосте своим таймером, но он ОТПРАВЛЯЕТ текст в Telegram и ничего не
оставляет после себя: в ветку по нему не приедет ничего, и сверить числа задним
числом нечем. Здесь наоборот -- ни одной отправки, только файл на диске.

ЧЕГО ЭТОТ СЧЁТ НЕ ЗНАЕТ, И ЭТО СКАЗАНО ВСЛУХ. Свежесть учёта в ветке и
незавершённые прогоны Actions живут в GitHub, а не на хосте: их здесь нет и вид,
что они проверены, не делается. Отсутствие службы -- это ФАКТ, а не сбой (так же
считает и прогон живучести): тревога только если юнит установлен и не активен.

ДЕНЕЖНОГО ПУТИ НЕТ. Модуль спрашивает systemctl, смотрит mtime признаков жизни и
пишет один json. Ни покупки, ни продажи, ни подписи, ни записи в позиции здесь
нет -- это проверяет самопроверка, и она падает, если денежный вызов появится.
"""

from __future__ import annotations

import argparse
import json
import os
import subprocess  # noqa: S404 -- только systemctl show, только чтение
import sys
import time

# Те же пять служб, что перечисляет прогон живучести. Список держится рядом с
# ним нарочно: расхождение списков означало бы, что хост и прогон считают
# живучесть разных стендов.
СЛУЖБЫ = ("dbot-sold-guard", "dbot-detect-probe", "bloom-seller",
           "bloom-detector", "grpc-feed-probe")
# Признак жизни и ТА служба, которая его пишет. Пара нужна ради честности:
# отсутствующий признак у остановленной службы -- это не тревога, а следствие;
# тревога -- отсутствующий признак у РАБОТАЮЩЕЙ службы.
ПРИЗНАКИ = (
    ("/home/bot/bloom_executor_live_data/detector_status.json", "bloom-detector"),
    ("/home/bot/bloom_executor_live_data/seller_heartbeat.json", "bloom-seller"),
    ("/home/bot/dbot_detect_probe/status.json", "dbot-detect-probe"),
    ("/home/bot/grpc_feed_probe_data/heartbeat.json", "grpc-feed-probe"),
)
# Порог тот же, что у прогона живучести: 10 минут. Два разных порога на одном
# стенде значили бы два разных ответа на один вопрос.
ПОРОГ_ПРИЗНАКА_S = 600
ПО_УМОЛЧАНИЮ = "/home/bot/host_tajmery/zhivuchest/zhivuchest.json"
# LoadState, при котором юнита на хосте просто нет. not-found -- обычный случай
# (служба не ставилась), остальные -- юнит есть, но systemd его не принял: это
# НЕ "нет службы", это сломанный юнит, и молчать о нём нельзя.
НЕТ_ЮНИТА = ("not-found",)


def разобрать_show(текст: str) -> dict:
    """Вывод `systemctl show -p ... ` в словарь. KEY=value построчно.

    Пустое значение systemd печатает как KEY= -- оставляем пустую строку, а не
    None: отсутствие значения и строка "неизвестно" тут одно и то же, и
    придумывать разницу незачем.
    """
    из_: dict = {}
    for строка in (текст or "").splitlines():
        if "=" in строка:
            ключ, _, значение = строка.partition("=")
            из_[ключ.strip()] = значение.strip()
    return из_


def спросить_systemctl(служба: str) -> dict:
    """Четыре поля одной службы от systemd. Нечитаемый ответ -- это причина.

    Только чтение: show ничего не запускает и не останавливает.
    """
    поля = ("LoadState", "ActiveState", "UnitFileState", "NRestarts",
            "ActiveEnterTimestamp")
    команда = ["systemctl", "show", служба] + [f"-p{п}" for п in поля]
    try:
        готово = subprocess.run(команда, capture_output=True, text=True,
                                 timeout=20, check=False)
    except (OSError, subprocess.SubprocessError) as сбой:
        return {"why_not": f"systemctl не ответил: {type(сбой).__name__}"}
    if готово.returncode != 0 and not готово.stdout.strip():
        # НЕ ТИХИЙ НОЛЬ: без ответа systemd мы не знаем состояния службы, и
        # "не активна" тут такая же выдумка, как "активна".
        return {"why_not": f"systemctl код {готово.returncode}"}
    return разобрать_show(готово.stdout)


def состояние_службы(имя: str, поля: dict) -> dict:
    """Одна строка доклада по службе и есть ли по ней тревога."""
    из_ = {"служба": имя, "установлена": None, "active": None, "enabled": None,
            "restarts": None, "с": None, "тревога": None, "why_not": None}
    if поля.get("why_not"):
        # Состояние не прочитано -- это тревога, а не "наверное живёт". Ровно
        # этот случай прогон живучести когда-то печатал как "ssh не ответил" и
        # шёл дальше.
        из_["why_not"] = поля["why_not"]
        из_["тревога"] = f"{имя}: состояние не прочитано ({поля['why_not']})"
        return из_
    загрузка = поля.get("LoadState", "")
    из_["установлена"] = загрузка not in НЕТ_ЮНИТА
    из_["active"] = поля.get("ActiveState") or None
    из_["enabled"] = поля.get("UnitFileState") or None
    из_["restarts"] = поля.get("NRestarts") or None
    из_["с"] = поля.get("ActiveEnterTimestamp") or None
    if не_юнит := (загрузка in НЕТ_ЮНИТА):
        из_["why_not"] = "юнита на хосте нет -- это факт, а не сбой"
    if не_юнит:
        return из_
    if загрузка != "loaded":
        из_["тревога"] = f"{имя}: юнит есть, но systemd его не принял ({загрузка})"
        return из_
    if из_["active"] != "active":
        из_["тревога"] = f"{имя}: установлена, но не активна ({из_['active']})"
    return из_


def возраст_признака(путь: str, сейчас: float) -> dict:
    """Возраст признака жизни в секундах. Нет файла -- причина, а не ноль."""
    из_ = {"файл": путь, "возраст_с": None, "why_not": None}
    try:
        статистика = os.stat(путь)
    except OSError as сбой:
        из_["why_not"] = f"нет или не читается ({type(сбой).__name__})"
        return из_
    if статистика.st_size == 0:
        из_["why_not"] = "файл пуст"
        return из_
    из_["возраст_с"] = round(сейчас - статистика.st_mtime, 1)
    return из_


def состояние_признака(путь: str, служба: str, возраст: dict,
                        службы: dict) -> dict:
    """Строка доклада по признаку жизни и тревога по нему.

    Тревога только если ПИШУЩАЯ его служба активна: у остановленной службы
    отсутствие или старость признака -- следствие остановки, и называть это
    второй тревогой значит считать одну беду дважды.
    """
    из_ = dict(возраст)
    из_["служба"] = служба
    из_["тревога"] = None
    активна = (службы.get(служба) or {}).get("active") == "active"
    из_["служба_активна"] = активна
    if not активна:
        из_["why_not"] = (из_.get("why_not")
                           or f"{служба} не активна -- признак не ждём")
        return из_
    if из_["возраст_с"] is None:
        из_["тревога"] = f"{служба} активна, а признака жизни нет: {из_['why_not']}"
        return из_
    if из_["возраст_с"] > ПОРОГ_ПРИЗНАКА_S:
        из_["тревога"] = (f"{служба}: признак жизни старше "
                           f"{ПОРОГ_ПРИЗНАКА_S} с ({из_['возраст_с']} с)")
    return из_


def собрать(сейчас: float, спросить=спросить_systemctl,
             возраст=возраст_признака) -> dict:
    """Весь доклад одним словарём. Значений ключей здесь нет и быть не может."""
    службы = {имя: состояние_службы(имя, спросить(имя)) for имя in СЛУЖБЫ}
    признаки = [состояние_признака(путь, служба, возраст(путь, сейчас), службы)
                 for путь, служба in ПРИЗНАКИ]
    тревоги = [с["тревога"] for с in службы.values() if с["тревога"]]
    тревоги += [п["тревога"] for п in признаки if п["тревога"]]
    return {
        "utc": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime(сейчас)),
        "кем": "таймер хоста bloom-zhivuchest-chas",
        # ПРЯМО В ФАЙЛЕ: чего этот счёт не знает. Иначе читающий решит, что
        # зелёный файл означает зелёный стенд целиком.
        "чего_не_знает": ("свежесть учёта в ветке и незавершённые прогоны"
                           " Actions живут в GitHub, а не на хосте"),
        "порог_признака_с": ПОРОГ_ПРИЗНАКА_S,
        "службы": [службы[имя] for имя in СЛУЖБЫ],
        "признаки": признаки,
        "тревоги": тревоги,
        "итог": "тревог нет" if not тревоги else f"тревог {len(тревоги)}",
    }


def записать(доклад: dict, путь: str) -> None:
    """Запись через временный файл и rename.

    ЗАЧЕМ АТОМАРНО. Файл забирает прогон GitHub по своему расписанию, и он
    может попасть ровно в середину записи: полуфайл не разберётся как json, и
    прогон скажет "выгрузки нет" при полностью живом таймере.
    """
    каталог = os.path.dirname(путь) or "."
    os.makedirs(каталог, exist_ok=True)
    временный = путь + ".chast"
    with open(временный, "w", encoding="utf-8") as ф:
        json.dump(доклад, ф, ensure_ascii=False, indent=2)
        ф.write("\n")
    os.replace(временный, путь)


def самопроверка() -> int:
    пройдено = провалено = 0

    def ок(условие, что):
        nonlocal пройдено, провалено
        if условие:
            пройдено += 1
            print(f"  [ok  ] {что}")
        else:
            провалено += 1
            print(f"  [ПРОВАЛ] {что}")

    р = разобрать_show("LoadState=loaded\nActiveState=active\nNRestarts=3\n")
    ок(р.get("ActiveState") == "active", "разбор systemctl show: поля на месте")
    ок(разобрать_show("мусор без равно") == {},
       "строка без = в разбор не попадает")
    ок(разобрать_show("UnitFileState=")["UnitFileState"] == "",
       "пустое значение остаётся пустой строкой, а не None")

    живая = состояние_службы("bloom-seller", {
        "LoadState": "loaded", "ActiveState": "active",
        "UnitFileState": "enabled", "NRestarts": "0"})
    ок(живая["тревога"] is None and живая["установлена"] is True,
       "активная служба тревоги не даёт")
    мертвая = состояние_службы("bloom-seller", {
        "LoadState": "loaded", "ActiveState": "failed", "NRestarts": "7"})
    ок(мертвая["тревога"] and "не активна" in мертвая["тревога"],
       "установлена и не активна -- тревога")
    нету = состояние_службы("grpc-feed-probe", {"LoadState": "not-found"})
    ок(нету["тревога"] is None and нету["установлена"] is False,
       "отсутствие службы -- факт, а не сбой")
    битый = состояние_службы("bloom-detector", {"LoadState": "bad-setting",
                                                 "ActiveState": "inactive"})
    ок(битый["тревога"] and "не принял" in битый["тревога"],
       "юнит есть, но systemd его не принял -- тревога, а не 'нет службы'")
    молчит = состояние_службы("bloom-seller", {"why_not": "systemctl код 1"})
    ок(молчит["тревога"] and "не прочитано" in молчит["тревога"],
       "непрочитанное состояние -- тревога, а не 'наверное живёт'")

    ок(возраст_признака("/нет/такого/файла", 1000.0)["why_not"],
       "отсутствующий признак жизни -- причина словами, а не ноль")

    службы = {"bloom-seller": {"active": "active"},
               "bloom-detector": {"active": "inactive"}}
    свежий = состояние_признака("/x", "bloom-seller",
                                 {"файл": "/x", "возраст_с": 12.0,
                                  "why_not": None}, службы)
    ок(свежий["тревога"] is None, "свежий признак активной службы -- без тревоги")
    старый = состояние_признака("/x", "bloom-seller",
                                 {"файл": "/x", "возраст_с": 601.0,
                                  "why_not": None}, службы)
    ок(старый["тревога"] and "старше" in старый["тревога"],
       "признак старше порога у активной службы -- тревога")
    ровно = состояние_признака("/x", "bloom-seller",
                                {"файл": "/x", "возраст_с": float(ПОРОГ_ПРИЗНАКА_S),
                                 "why_not": None}, службы)
    ок(ровно["тревога"] is None, "ровно порог -- ещё не тревога (строгое >)")
    нет_признака = состояние_признака("/x", "bloom-seller",
                                       {"файл": "/x", "возраст_с": None,
                                        "why_not": "нет или не читается"}, службы)
    ок(нет_признака["тревога"] and "признака жизни нет" in нет_признака["тревога"],
       "активная служба без признака жизни -- тревога")
    у_мертвой = состояние_признака("/x", "bloom-detector",
                                    {"файл": "/x", "возраст_с": None,
                                     "why_not": "нет или не читается"}, службы)
    ок(у_мертвой["тревога"] is None,
       "у неактивной службы отсутствие признака не считается второй тревогой")

    # Весь доклад на подставных ответах: ни одного обращения к systemd.
    def спросить_подставой(имя):
        if имя == "bloom-seller":
            return {"LoadState": "loaded", "ActiveState": "active",
                    "UnitFileState": "enabled", "NRestarts": "0"}
        return {"LoadState": "not-found"}

    доклад = собрать(1_700_000_000.0, спросить=спросить_подставой,
                      возраст=lambda п, с: {"файл": п, "возраст_с": 30.0,
                                             "why_not": None})
    ок(доклад["тревоги"] == [] and доклад["итог"] == "тревог нет",
       "доклад собирается целиком и без тревог на живом стенде")
    ок(len(доклад["службы"]) == len(СЛУЖБЫ),
       "в докладе столько служб, сколько в списке")
    ок(доклад["чего_не_знает"],
       "границы счёта названы В САМОМ файле, а не только в коде")
    текст = json.dumps(доклад, ensure_ascii=False)
    ок("key" not in текст.lower() and "token" not in текст.lower(),
       "в докладе нет ни слова key/token -- значениям ключей взяться негде")

    # Атомарная запись: пока файл не переименован, его на месте нет вовсе.
    import tempfile
    with tempfile.TemporaryDirectory() as каталог:
        путь = os.path.join(каталог, "вложенный", "zhivuchest.json")
        записать(доклад, путь)
        ок(os.path.exists(путь) and json.load(open(путь, encoding="utf-8")),
           "запись создаёт каталог и разбирается как json")
        ок(not os.path.exists(путь + ".chast"),
           "временного полуфайла после записи не остаётся")
        записать(доклад, путь)
        ок(json.load(open(путь, encoding="utf-8"))["итог"] == "тревог нет",
           "повторная запись поверх не ломает файл")

    # ДЕНЕЖНОГО ПУТИ НЕТ -- и это проверка, а не обещание.
    свой = open(__file__, encoding="utf-8").read()
    рабочая = свой.split("\ndef самопроверка(")[0]
    денежные = [с for с in ("sendTransaction", "signTransaction", "Keypair",
                             "EXEC_WALLET_KEY", "requests.post", "urlopen")
                 if с in рабочая]
    ок(not денежные, f"в рабочей части нет денежных вызовов (нашли: {денежные})")

    print(f"самопроверка живучести на хосте: {пройдено}/{пройдено + провалено} пройдено")
    return 1 if провалено else 0


def main() -> int:
    р = argparse.ArgumentParser()
    р.add_argument("--out", default=ПО_УМОЛЧАНИЮ,
                   help="куда положить доклад (его забирает прогон живучести)")
    р.add_argument("--self-test", action="store_true")
    а = р.parse_args()
    if а.self_test:
        return самопроверка()
    доклад = собрать(time.time())
    записать(доклад, а.out)
    print(json.dumps({"utc": доклад["utc"], "итог": доклад["итог"],
                       "тревоги": доклад["тревоги"]},
                      ensure_ascii=False, indent=2))
    # НЕНУЛЕВОЙ КОД -- ЧТОБЫ ТАЙМЕР ПОМЕТИЛ ПРОГОН СБОЕМ. Файл при этом уже
    # записан: доклад о тревоге нужен сильнее, чем доклад о тишине.
    return 1 if доклад["тревоги"] else 0


if __name__ == "__main__":
    raise SystemExit(main())
