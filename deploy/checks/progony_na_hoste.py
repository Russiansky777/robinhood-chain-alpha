#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Окна прогонов Actions на торговом хосте против минут сделок.

ЗАЧЕМ (слово владельца 29.09 ночью, п.5): "были ли проверки на хосте в минуты
сделок". Два имевшихся ответа оба косвенные:
  * время КОММИТА прогона -- это его конец, а не длительность: прогон, начатый
    за десять минут до сделки, виден одной точкой;
  * created_at/updated_at из API GitHub включают ОЧЕРЕДЬ: раннер на хосте один,
    и три "активных" окна разом означают, что два из трёх стояли в очереди, а
    хост не занимали.

ТОЧНЫЙ ИСТОЧНИК ЛЕЖИТ НА САМОМ ХОСТЕ. Раннер на каждую задачу пишет файл
_diag/Worker_<ГГГГММДД>-<ЧЧММСС>-utc.log: в ИМЕНИ -- метка начала задачи, а
mtime файла -- время последней записи, то есть её конец. Отсюда окно каждой
задачи, без догадок и без очереди.

Вход -- вывод `ls -l --time-style=full-iso` по этим файлам, потоком со stdin.
Выход -- окна и по каждой сделке: шла ли задача на хосте в её минуту.

ЧЕГО ЭТОТ СЧЁТ НЕ ЗНАЕТ, И ЭТО СКАЗАНО ВСЛУХ: mtime -- последняя запись в
журнал задачи, а не мгновение её завершения; задача, чей файл уже удалён
уборкой раннера, не видна вовсе. Оба ограничения печатаются рядом с числом.
"""

from __future__ import annotations

import argparse
import calendar
import json
import re
import sys
import time

# Worker_20260929-202429-utc.log -- метка НАЧАЛА задачи в имени файла.
ИМЯ = re.compile(r"Worker_(\d{8})-(\d{6})-utc\.log$")
# ls -l --time-style=full-iso: "... 12345 2026-09-29 20:24:51.000000000 +0000 путь"
СТРОКА = re.compile(r"(\d{4}-\d{2}-\d{2})\s+(\d{2}:\d{2}:\d{2})(?:\.\d+)?\s+"
                     r"([+-]\d{4})\s+(\S+)$")


def метка(дата: str, время: str, сдвиг: str = "+0000") -> float | None:
    """Метка UTC из даты, времени и часового сдвига. Не разобралось -- None."""
    try:
        т = calendar.timegm(time.strptime(f"{дата} {время}", "%Y-%m-%d %H:%M:%S"))
    except ValueError:
        return None
    знак = -1 if сдвиг.startswith("-") else 1
    try:
        часы, мин = int(сдвиг[1:3]), int(сдвиг[3:5])
    except ValueError:
        return None
    # ls печатает МЕСТНОЕ время со сдвигом: приводим к UTC, вычитая сдвиг.
    return т - знак * (часы * 3600 + мин * 60)


def окно_из_строки(строка: str) -> dict:
    """Окно одной задачи из строки ls. {начало, конец, файл, why_not}."""
    с = (строка or "").rstrip("\n")
    м = СТРОКА.search(с)
    if not м:
        return {"начало": None, "конец": None, "файл": None,
                "why_not": "строка не похожа на вывод ls --time-style=full-iso"}
    путь = м.group(4)
    ми = ИМЯ.search(путь)
    if not ми:
        return {"начало": None, "конец": None, "файл": путь,
                "why_not": "имя файла не Worker_ГГГГММДД-ЧЧММСС-utc.log"}
    д, в = ми.group(1), ми.group(2)
    начало = метка(f"{д[:4]}-{д[4:6]}-{д[6:8]}", f"{в[:2]}:{в[2:4]}:{в[4:6]}")
    конец = метка(м.group(1), м.group(2), м.group(3))
    if начало is None or конец is None:
        return {"начало": None, "конец": None, "файл": путь,
                "why_not": "метка не разобралась"}
    if конец < начало:
        # ЧАСЫ НЕ ПЕРЕВОРАЧИВАЕМ: конец раньше начала -- признак чужого сдвига,
        # и молча менять их местами значило бы выдумать окно.
        return {"начало": начало, "конец": конец, "файл": путь,
                "why_not": "конец раньше начала -- сдвиг времён не сошёлся"}
    return {"начало": начало, "конец": конец, "файл": путь, "why_not": None}


def окна(поток) -> dict:
    """Окна всех задач из потока строк ls. {окна, отброшено, причины}."""
    гот, отбр, прич = [], 0, {}
    for строка in поток:
        о = окно_из_строки(строка)
        if о["why_not"]:
            отбр += 1
            прич[о["why_not"]] = прич.get(о["why_not"], 0) + 1
            continue
        гот.append(о)
    гот.sort(key=lambda x: x["начало"])
    return {"окна": гот, "отброшено": отбр, "причины": прич}


def пересечение(окна_: list, с: float, до: float) -> list:
    """Задачи, шедшие на хосте хоть мгновение в отрезке [с, до]."""
    return [о for о in окна_ if о["начало"] <= до and о["конец"] >= с]


def одновременно(окна_: list) -> dict:
    """Сколько задач шло разом. Раннер один -- больше одной быть не должно."""
    точки = []
    for о in окна_:
        точки.append((о["начало"], 1))
        точки.append((о["конец"], -1))
    точки.sort()
    тек = макс = 0
    for _, д in точки:
        тек += д
        макс = max(макс, тек)
    return {"максимум_разом": макс, "задач": len(окна_)}


def разбор_utc(строка: str) -> float | None:
    """Метка из 2026-09-29T20:24:29Z."""
    if not строка:
        return None
    с = строка.strip().replace("Z", "")
    for ф in ("%Y-%m-%dT%H:%M:%S", "%Y-%m-%dT%H:%M"):
        try:
            return calendar.timegm(time.strptime(с, ф))
        except ValueError:
            continue
    return None


def самопроверка() -> int:
    всего = сбоев = 0

    def chk(имя, ок, что=None):
        nonlocal всего, сбоев
        всего += 1
        print(f"  [{'ok  ' if ок else 'СБОЙ'}] {имя}")
        if not ок:
            сбоев += 1
            if что is not None:
                print(f"         {что!r}")

    л = ("-rw-r--r-- 1 root root 12345 2026-09-29 20:24:51.000000000 +0000 "
         "/home/actions-runner/_diag/Worker_20260929-202429-utc.log")
    о = окно_из_строки(л)
    chk("начало берётся из имени файла, конец -- из mtime",
        о["why_not"] is None
        and о["начало"] == calendar.timegm((2026, 9, 29, 20, 24, 29, 0, 0, 0))
        and о["конец"] == calendar.timegm((2026, 9, 29, 20, 24, 51, 0, 0, 0)), о)
    chk("длительность задачи 22 с", о["конец"] - о["начало"] == 22)
    # ХОСТ ЖИВЁТ В CEST: ls печатает МЕСТНОЕ время со сдвигом, а имя файла --
    # всегда UTC. Тот же самый миг конца задачи в CEST выглядит как 22:24:51
    # +0200. Первый заход этой самопроверки подсунул 20:24:51 +0200 -- и
    # проверка "конец раньше начала" его отвергла, как и должна была.
    л2 = л.replace("20:24:51", "22:24:51").replace("+0000", "+0200")
    о2 = окно_из_строки(л2)
    chk("местное время CEST приводится к UTC: тот же конец, что и в +0000",
        о2["why_not"] is None and о2["конец"] == о["конец"], о2)
    chk("чужое имя файла -- отказ словами, а не окно",
        окно_из_строки(л.replace("Worker_20260929-202429-utc.log",
                                  "Runner_1.log"))["why_not"])
    chk("мусорная строка -- отказ словами",
        окно_из_строки("просто текст")["why_not"])
    о3 = окно_из_строки(
        "-rw-r--r-- 1 root root 1 2026-09-29 20:24:00.000000000 +0000 "
        "/x/Worker_20260929-202429-utc.log")
    chk("конец раньше начала -- причина, а не перевёрнутое окно",
        о3["why_not"] and "сдвиг" in о3["why_not"], о3)
    сп = окна([л, "мусор", л2])
    chk("поток: два окна приняты, мусор отброшен с причиной",
        len(сп["окна"]) == 2 and сп["отброшено"] == 1 and сп["причины"], сп)
    а = {"начало": 100.0, "конец": 200.0, "файл": "a", "why_not": None}
    б = {"начало": 300.0, "конец": 400.0, "файл": "b", "why_not": None}
    chk("сделка между окнами -- ни одной задачи",
        пересечение([а, б], 250.0, 260.0) == [])
    chk("сделка внутри окна -- задача найдена",
        [о["файл"] for о in пересечение([а, б], 150.0, 160.0)] == ["a"])
    chk("сделка на границе окна считается пересечением",
        len(пересечение([а, б], 200.0, 210.0)) == 1)
    chk("раннер один: два окна встык -- максимум разом 1",
        одновременно([а, б])["максимум_разом"] == 1, одновременно([а, б]))
    в = {"начало": 150.0, "конец": 250.0, "файл": "c", "why_not": None}
    chk("наложение окон видно числом 2 (раннер не один или уборка соврала)",
        одновременно([а, в])["максимум_разом"] == 2)
    chk("метка сделки разбирается", разбор_utc("2026-09-29T20:24:29Z") is not None)
    chk("пустая метка -- None, а не ноль", разбор_utc("") is None)
    print(f"самопроверка окон прогонов: {всего - сбоев}/{всего} пройдено")
    return 1 if сбоев else 0


def main() -> int:
    р = argparse.ArgumentParser()
    р.add_argument("--sdelki", default="",
                    help="выгрузка сделок полосы (JSON с полем ряды)")
    р.add_argument("--okno-s", type=float, default=60.0,
                    help="длина минуты сделки в секундах (по умолчанию 60)")
    р.add_argument("--out", default="")
    р.add_argument("--self-test", action="store_true")
    а = р.parse_args()
    if а.self_test:
        return самопроверка()

    сп = окна(sys.stdin)
    ок = сп["окна"]
    если_пусто = None
    if not ок:
        если_пусто = ("журналов задач раннера не видно: либо путь _diag другой, "
                      "либо уборка раннера их уже удалила")
        print(f"ПОЧЕМУ ПУСТО: {если_пусто}")
    else:
        од = одновременно(ок)
        print(f"задач раннера в разборе: {len(ок)}, отброшено строк "
              f"{сп['отброшено']}")
        print(f"первая {time.strftime('%H:%M:%SZ', time.gmtime(ок[0]['начало']))}, "
              f"последняя до "
              f"{time.strftime('%H:%M:%SZ', time.gmtime(ок[-1]['конец']))}")
        print(f"максимум задач разом: {од['максимум_разом']}"
              + (" (раннер один -- так и должно быть)"
                 if од["максимум_разом"] <= 1
                 else " -- окна наложились, раннер не один или mtime соврал"))
        общее = sum(о["конец"] - о["начало"] for о in ок)
        размах = ок[-1]["конец"] - ок[0]["начало"]
        доля = (общее / размах) if размах > 0 else None
        print(f"хост был занят задачами {общее:.0f} с из {размах:.0f} с размаха"
              + (f" -- {доля * 100:.1f} %" if доля is not None else ""))
    итог = {"снято_utc": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
            "задач": len(ок), "отброшено_строк": сп["отброшено"],
            "причины_отказа": сп["причины"], "почему_пусто": если_пусто,
            "оговорка": ("mtime -- последняя запись в журнал задачи, а не "
                         "мгновение её конца; удалённые уборкой раннера журналы "
                         "не видны вовсе"),
            "задачи": [{"начало_utc": time.strftime("%Y-%m-%dT%H:%M:%SZ",
                                                     time.gmtime(о["начало"])),
                         "конец_utc": time.strftime("%Y-%m-%dT%H:%M:%SZ",
                                                     time.gmtime(о["конец"])),
                         "секунд": round(о["конец"] - о["начало"], 1),
                         "файл": о["файл"]} for о in ок],
            "сделки": []}
    if а.sdelki:
        try:
            with open(а.sdelki, encoding="utf-8") as ф:
                ряды = (json.load(ф) or {}).get("ряды") or []
        except Exception as e:  # noqa: BLE001
            print(f"выгрузка сделок не прочиталась: {type(e).__name__}")
            ряды = []
        с_задачей = 0
        print("\n--- минуты сделок против окон задач на хосте ---")
        for р_ in sorted(ряды, key=lambda x: x.get("utc") or ""):
            т = разбор_utc(р_.get("utc") or "")
            if т is None:
                continue
            пер = пересечение(ок, т, т + а.okno_s)
            с_задачей += bool(пер)
            имена = ", ".join(
                f"{time.strftime('%H:%M:%S', time.gmtime(о['начало']))}"
                f"-{time.strftime('%H:%M:%S', time.gmtime(о['конец']))}"
                for о in пер) or "ни одной"
            print(f"  {р_.get('utc')}  {str(р_.get('mint'))[:6]}  "
                  f"S+{р_.get('s_plus')}  {р_.get('region_lidera') or '-'}  "
                  f"задач: {len(пер)} [{имена}]")
            итог["сделки"].append(
                {"utc": р_.get("utc"), "mint": р_.get("mint"),
                 "s_plus": р_.get("s_plus"),
                 "region_lidera": р_.get("region_lidera"),
                 "zadach_v_minutu": len(пер),
                 "okna": [о["файл"] for о in пер]})
        всего_сд = len(итог["сделки"])
        if всего_сд:
            print(f"сделок с задачей раннера в ту же минуту: {с_задачей} из "
                  f"{всего_сд}")
        итог["sdelok_s_zadachej"] = с_задачей
    if а.out:
        with open(а.out, "w", encoding="utf-8") as ф:
            json.dump(итог, ф, ensure_ascii=False, indent=1)
        print(f"записано: {а.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
