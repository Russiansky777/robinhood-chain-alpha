#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""ЧИСЛО ДЛЯ ШТАБА: DLMM БЕЗ ЧТЕНИЙ -- сколько сигналов прошло бы, сколько нет.

ЭТО ЗАМЕР, А НЕ МОДУЛЬ. Слово владельца 30.09: «прочитать, одной строкой штабу --
сколько из 46 при запасе 5 % / 10 % прошли бы, отказали, ошиблись >1 %. Решение
штаба после строки; до него модуль не писать». Поэтому здесь нет ни строителя, ни
котировщика, ни флага -- только счёт по сбору Code-2 и печать чисел.

ЧТО ЗНАЧИТ «БЕЗ ЧТЕНИЙ». Цена берётся из СОБЫТИЯ ПРЕДЫДУЩЕГО СВОПА этого пула
(amount_out / amount_in), и по ней предсказывается выход НАШЕЙ сделки того же
размера. Ни пул, ни массивы корзин не читаются -- ни одного getMultipleAccounts.
Это не то же, что c2_dlmm_odno_chtenie.py (там ОДНО чтение вместо двух: адреса
массивов берутся из сделки источника, а состояние всё равно читается).

ЧТО СЧИТАЕТСЯ ОШИБКОЙ, А ЧТО ОТКАЗОМ -- РАЗНЫЕ ВЕЩИ, И СКЛАДЫВАТЬ ИХ НЕЛЬЗЯ.
  * ОТКАЗ -- предыдущий своп пула шёл в ДРУГУЮ сторону, и его цену как есть
    применить нельзя (обратная сторона у DLMM -- другие корзины и другая
    комиссия). Это не ошибка предсказания, это «сказать нечего».
  * ОШИБКА ЗАВЫШЕНИЯ -- предсказали БОЛЬШЕ факта. Опасна только она: min_out
    оказался бы выше того, что пул отдал, и транзакция откатилась бы.
  * ЗАПАС -- на сколько процентов min_out опускается ниже предсказания. «Прошло
    бы» = предсказание минус запас не выше факта.

Сбор: data/podbivka/dlmm_bez_chteniy_sbor.json (ветка Code-2 claude/podbivka),
46 свопов: «предыдущий своп пула + сделка + пул».

Запуск: python3 deploy/checks/dlmm_bez_chteniy_chislo.py --sbor <путь>
"""
from __future__ import annotations

import argparse
import json
import os
import statistics
import sys
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parents[2]
ДЛЯ_МОДУЛЕЙ = str(КОРЕНЬ / "analysis")
ЗАПАСЫ = (0.05, 0.10)
ПОРОГ_ОШИБКИ = 1.0          # процент, о котором спросил штаб


def _кирпичи(каталог: str):
    if каталог not in sys.path:
        sys.path.insert(0, каталог)
    import c2_swap_build as B  # noqa: PLC0415

    return B


def строки_сбора(сбор: dict, B) -> list:
    """По каждому ряду: предсказание без чтений, факт и ошибка (или отказ)."""
    из_ = []
    for р in (сбор.get("ряды") or []):
        пул = р.get("пул")
        свои = [е for е in B.события_dlmm(р.get("транзакция") or {})
                if е.get("пул") == пул]
        пред = [е for е in ((р.get("предыдущий_своп") or {}).get("события") or [])
                if е.get("lb_pair") == пул and е.get("вид") == "Swap"]
        общее = {"пул": пул, "сделка": р.get("сделка"),
                  "между": (р.get("предыдущий_своп") or {}).get("транзакций_между")}
        if not свои or not пред:
            из_.append(dict(общее, ok=False,
                             почему="события свопа этого пула нет у своей или у "
                                    "предыдущей сделки"))
            continue
        c, p = свои[0], пред[0]
        if int(c.get("swap_for_y") or 0) != int(bool(p.get("swap_for_y"))):
            из_.append(dict(общее, ok=False,
                             почему="предыдущий своп пула шёл в другую сторону"))
            continue
        if int(p.get("amount_in") or 0) <= 0 or int(c.get("amount_out") or 0) <= 0:
            из_.append(dict(общее, ok=False, почему="нулевые суммы в событии"))
            continue
        # ЦЕЛОЧИСЛЕННО ВНИЗ, КАК В МОДУЛЕ. Определение цены обязано быть ОДНО:
        # считай замер во float, а модуль в целых -- и сверка "до единицы" всегда
        # расходилась бы на единицу, причём это выглядело бы как ошибка модуля.
        предсказ = (int(c["amount_in"]) * int(p["amount_out"])
                    // int(p["amount_in"]))
        факт = int(c["amount_out"])
        из_.append(dict(общее, ok=True, предсказ=предсказ, факт=факт,
                         ошибка=(предсказ - факт) / факт * 100.0,
                         корзин_пред=abs(int(p.get("end") or 0)
                                          - int(p.get("start") or 0)) + 1))
    return из_


def событие_для_модуля(ев: dict) -> dict:
    """Событие из разбора Code-2 -> вид, который читает модуль.

    Переименование, и только оно: у Code-2 корзины зовутся `start`/`end`, у
    разбора денежного пути (c2_swap_build.событие_dlmm) -- `start_bin_id` /
    `end_bin_id`. Суммы и сторона называются одинаково. Ничего не считается.
    """
    return {"пул": ев.get("lb_pair"),
            "start_bin_id": ев.get("start"), "end_bin_id": ев.get("end"),
            "amount_in": ев.get("amount_in"), "amount_out": ев.get("amount_out"),
            "swap_for_y": int(bool(ев.get("swap_for_y")))}


def сверка_с_модулем(сбор: dict, B, каталог: str) -> dict:
    """ТРИ ЧИСЛА: даёт ли модуль-тень РОВНО то, что этот замер, до единицы.

    ЗАЧЕМ ОТДЕЛЬНО. Замер выше -- арифметика в двадцать строк прямо здесь; модуль
    analysis/c2_dlmm_bez_chteniy.py -- то, что Code-1 поставит в полосу. Если они
    считают разное, то любое число из замера про полосу ничего не говорит. Поэтому
    сверяются: сколько посчитано, совпадает ли цена ДО ЕДИНИЦЫ и совпадают ли
    отказы по причине.
    """
    из_ = {"ok": False, "why_not": None}
    if каталог not in sys.path:
        sys.path.insert(0, каталог)
    try:
        import c2_dlmm_bez_chteniy as Т  # noqa: PLC0415
    except Exception as exc:  # noqa: BLE001
        из_["why_not"] = f"модуля-тени нет: {type(exc).__name__}: {exc}"
        return из_
    из_.update(ok=True, посчитано_замером=0, посчитано_модулем=0,
                цена_до_единицы=0, отказов_замером=0, отказов_модулем=0,
                отказ_той_же_причины=0, корзин_доказано=0, корзин_оценка=0,
                расхождения=[])
    for р in (сбор.get("ряды") or []):
        пул = р.get("пул")
        свои = [е for е in B.события_dlmm(р.get("транзакция") or {})
                if е.get("пул") == пул]
        пред = [е for е in ((р.get("предыдущий_своп") or {}).get("события") or [])
                if е.get("lb_pair") == пул and е.get("вид") == "Swap"]
        if not свои or not пред:
            continue
        c, p = свои[0], пред[0]
        наша_сторона = int(c.get("swap_for_y") or 0)
        о = Т.котировка_по_событию(событие_для_модуля(p),
                                    swap_for_y=bool(наша_сторона),
                                    лампорты=int(c.get("amount_in") or 0),
                                    проскальзывание=0.0)
        своё = None
        если_можно = (int(bool(p.get("swap_for_y"))) == наша_сторона
                      and int(p.get("amount_in") or 0) > 0
                      and int(c.get("amount_out") or 0) > 0)
        if если_можно:
            своё = (int(c["amount_in"]) * int(p["amount_out"])
                    // int(p["amount_in"]))
            из_["посчитано_замером"] += 1
        else:
            из_["отказов_замером"] += 1
        if о.get("ok"):
            из_["посчитано_модулем"] += 1
            if о.get("корзин_доказано") is True:
                из_["корзин_доказано"] += 1
            elif о.get("корзин_доказано") is False:
                из_["корзин_оценка"] += 1
            if своё is not None and int(о["expected_out"]) == своё:
                из_["цена_до_единицы"] += 1
            elif своё is not None:
                из_["расхождения"].append(
                    f"{str(пул)[:8]}: модуль {о['expected_out']} != замер {своё}")
        else:
            из_["отказов_модулем"] += 1
            if not если_можно and Т.ПРИЗНАК_ДРУГАЯ_СТОРОНА in (о.get("why_not") or ""):
                из_["отказ_той_же_причины"] += 1
    из_["расхождения"] = из_["расхождения"][:5]
    return из_


def свод(строки: list) -> dict:
    ок = [с for с in строки if с.get("ok")]
    оши = sorted(с["ошибка"] for с in ок)
    причины = {}
    for с in строки:
        if not с.get("ok"):
            причины[с["почему"]] = причины.get(с["почему"], 0) + 1
    из_ = {"рядов": len(строки), "посчитано": len(ок),
            "отказ": len(строки) - len(ок), "причины_отказа": причины,
            "завысили_больше_порога": sum(1 for x in оши if x > ПОРОГ_ОШИБКИ),
            "по_модулю_больше_порога": sum(1 for x in оши
                                            if abs(x) > ПОРОГ_ОШИБКИ),
            "порог_%": ПОРОГ_ОШИБКИ, "запасы": {}}
    if ок:
        из_.update(медиана_ошибки=round(statistics.median(оши), 4),
                    p90_ошибки=round(оши[min(len(оши) - 1, int(len(оши) * 0.9))], 4),
                    макс_ошибки=round(оши[-1], 4), мин_ошибки=round(оши[0], 4))
        for q in ЗАПАСЫ:
            прошло = sum(1 for с in ок if с["предсказ"] * (1 - q) <= с["факт"])
            из_["запасы"][f"{int(q * 100)}%"] = {
                "прошло": прошло, "не_прошло": len(ок) - прошло}
        худшие = sorted(ок, key=lambda с: -abs(с["ошибка"]))[:3]
        из_["худшие"] = [{"ошибка_%": round(с["ошибка"], 3),
                           "корзин_у_предыдущего": с["корзин_пред"],
                           "транзакций_между": с["между"],
                           "сделка": с["сделка"]} for с in худшие]
    return из_


def печать(с: dict) -> None:
    print("=== DLMM БЕЗ ЧТЕНИЙ: число для штаба (замер, не модуль) ===")
    print(f"  рядов {с['рядов']}: посчитано {с['посчитано']}, отказ {с['отказ']}")
    for к, в in (с.get("причины_отказа") or {}).items():
        print(f"      отказ {в}: {к}")
    if not с.get("посчитано"):
        return
    print(f"  ошибка предсказания, %: медиана {с['медиана_ошибки']:+}, "
          f"p90 {с['p90_ошибки']:+}, макс {с['макс_ошибки']:+}, "
          f"мин {с['мин_ошибки']:+}")
    print(f"  завысили больше чем на {с['порог_%']} %: "
          f"{с['завысили_больше_порога']} из {с['посчитано']} "
          f"(по модулю {с['по_модулю_больше_порога']})")
    for имя, з in (с.get("запасы") or {}).items():
        print(f"  запас {имя}: прошло бы {з['прошло']} из {с['посчитано']}, "
              f"не прошло {з['не_прошло']}")
    for х in (с.get("худшие") or []):
        print(f"      худшая {х['ошибка_%']:+} %: корзин у предыдущего свопа "
              f"{х['корзин_у_предыдущего']}, транзакций между "
              f"{х['транзакций_между']}")


def печать_модуля(см: dict) -> None:
    print("  МОДУЛЬ-ТЕНЬ (analysis/c2_dlmm_bez_chteniy.py) против этого замера:")
    if not см.get("ok"):
        print(f"      не сверено: {см.get('why_not')}")
        return
    print(f"      посчитано: модулем {см['посчитано_модулем']}, замером "
          f"{см['посчитано_замером']}")
    print(f"      цена ДО ЕДИНИЦЫ: {см['цена_до_единицы']} из "
          f"{см['посчитано_замером']}")
    print(f"      отказов: модулем {см['отказов_модулем']}, замером "
          f"{см['отказов_замером']}, из них той же причиной "
          f"{см['отказ_той_же_причины']}")
    print(f"      корзины нашего размера: доказано {см['корзин_доказано']}, "
          f"оценка {см['корзин_оценка']}")
    for р in (см.get("расхождения") or []):
        print(f"      РАСХОЖДЕНИЕ: {р}")


def main() -> int:
    р = argparse.ArgumentParser(description=__doc__)
    р.add_argument("--sbor", default=str(КОРЕНЬ / "data" / "podbivka"
                                          / "dlmm_bez_chteniy_sbor.json"))
    р.add_argument("--moduli", default=ДЛЯ_МОДУЛЕЙ)
    р.add_argument("--out", default=None)
    а = р.parse_args()
    if not os.path.exists(а.sbor):
        print("=== DLMM БЕЗ ЧТЕНИЙ: число для штаба (замер, не модуль) ===")
        print(f"  не сделано: файла нет: {а.sbor} -- сбор Code-2 лежит в его ветке "
              f"(data/podbivka/dlmm_bez_chteniy_sbor.json); укажите --sbor")
        return 2
    B = _кирпичи(а.moduli)
    with open(а.sbor, encoding="utf-8") as ф:
        сбор = json.load(ф)
    строки = строки_сбора(сбор, B)
    с = свод(строки)
    печать(с)
    см = сверка_с_модулем(сбор, B, а.moduli)
    печать_модуля(см)
    if а.out:
        with open(а.out, "w", encoding="utf-8") as ф:
            json.dump({"свод": с, "модуль": см, "строки": строки}, ф,
                       ensure_ascii=False, indent=1)
        print(f"  отчёт: {а.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
