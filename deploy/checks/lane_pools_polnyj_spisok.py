#!/usr/bin/env python3
"""Полный список lane_pools для включения типа пула -- ТОЙ ЖЕ функцией, что решает полоса.

ЗАЧЕМ. Владелец 30.09: "включение утром: lane_pools -- полным списком (всё, что
торгует сейчас, + clmm), флаг строителя BLOOM_CLMM_STROITEL=1 одновременно".
Список lane_pools ПОЛНЫЙ И ЗАПРЕЩАЮЩИЙ: что в нём не названо -- то выключено. Значит
написать его по памяти нельзя: забытый в списке тип молча перестанет торговать. Здесь он
считается вызовом bloom_own_send.типы_полосы(группа) -- ровно тем кодом, по которому
полоса принимает решение, -- и к нему добавляется новый тип.

ДВУХШАГОВЫЙ МАРШРУТ СЧИТАЕТСЯ ОТДЕЛЬНО и попадает в тот же список под именем
two_step: он не тип пула, а способ сборки, и полоса спрашивает его своей функцией
(двухшаговый_включён). Не назвать его в полном списке значит его выключить.

ТОЛЬКО ЧТЕНИЕ: файл групп и окружение читаются, ничего не пишется на место. Предложение
кладётся отдельным файлом (--out) и применяется человеком отдельным прогоном.
"""
import argparse
import json
import os
import sys

# Полоса и её модули лежат на хосте; путь даёт BLOOM_CODE_DIR, как у прочих проверок.
КОД = os.environ.get("BLOOM_CODE_DIR") or "/home/bot/bloom_executor"
if КОД not in sys.path:
    sys.path.insert(0, КОД)

ИМЯ_ДЛЯ_НОВОГО = {"clmm": "BLOOM_CLMM_STROITEL", "whirlpool": "BLOOM_WHIRLPOOL_STROITEL",
                   "dbc": "BLOOM_DBC_STROITEL", "dlmm": None, "damm2": None,
                   "bonding": None, "launchlab": None, "pump_amm": None, "cpmm": None,
                   "two_step": None}


def имена_по_программам(OS, B) -> dict:
    """{адрес программы: имя в lane_pools} -- из ИМЕНА_ТИПОВ самой полосы."""
    из_ = {}
    for имя_конст, слово in (getattr(OS, "ИМЕНА_ТИПОВ", {}) or {}).items():
        адрес = getattr(B, имя_конст, None)
        if адрес:
            из_[адрес] = слово
    return из_


def состояние_группы(OS, B, группа: str) -> dict:
    """Что группа торгует СЕЙЧАС: имена типов + двухшаговый, как решает полоса."""
    карта = имена_по_программам(OS, B)
    программы = sorted(OS.типы_полосы(группа) or [])
    имена = sorted({карта.get(п) or f"НЕИЗВЕСТНЫЙ:{п}" for п in программы})
    двух = bool(OS.двухшаговый_включён(группа))
    if двух:
        имена = sorted(set(имена) | {getattr(OS, "ИМЯ_ДВУХШАГОВОГО", "two_step")})
    return {"программы": программы, "сейчас": имена, "двухшаговый": двух,
             "неизвестных_программ": [и for и in имена if и.startswith("НЕИЗВЕСТНЫЙ:")]}


def предложение(сейчас: list, добавить: list) -> list:
    """Полный список = что торгует сейчас + новые типы. Без повторов, по алфавиту."""
    return sorted(set(сейчас) | {str(т).strip().lower() for т in добавить if str(т).strip()})


def флаги_строителей() -> dict:
    """Флаги строителей и типов из окружения ЭТОГО процесса -- значения, не секреты."""
    из_ = {}
    for имя, зн in sorted(os.environ.items()):
        if имя.startswith("LANE_") or (имя.startswith("BLOOM_") and имя.endswith("_STROITEL")):
            из_[имя] = зн
    return из_


def main() -> int:
    р = argparse.ArgumentParser(description=__doc__)
    р.add_argument("--dobavit", default="clmm",
                   help="какие типы добавить, через запятую (clmm, whirlpool, ...)")
    р.add_argument("--out", default=None, help="куда положить предложение json")
    р.add_argument("--self-test", dest="self_test", action="store_true")
    а = р.parse_args()
    if а.self_test:
        return self_test()
    добавить = [т.strip().lower() for т in (а.dobavit or "").split(",") if т.strip()]

    import bloom_own_send as OS  # noqa: PLC0415
    import bloom_source_groups as SG  # noqa: PLC0415
    import c2_swap_build as B  # noqa: PLC0415

    д = SG.загрузить()
    файл = д.get("file")
    политики = д.get("политики") or {}
    print(f"файл групп: {файл or '(не найден)'}"
           + (f" -- {д.get('why_not')}" if д.get("why_not") else ""))
    print(f"групп в файле: {len(политики)}; добавляем: {', '.join(добавить) or '(ничего)'}")
    фл = флаги_строителей()
    print("флаги окружения процесса: "
           + (", ".join(f"{к}={v}" for к, v in фл.items()) if фл else "(ни одного)"))
    for т in добавить:
        имя_флага = ИМЯ_ДЛЯ_НОВОГО.get(т)
        if имя_флага:
            есть = фл.get(имя_флага)
            print(f"  тип {т}: флаг строителя {имя_флага}="
                   f"{есть if есть is not None else 'НЕ ЗАДАН'}"
                   + ("" if есть == "1" else "  <-- без него тип пойдёт ПРЕЖНИМ путём"))

    строки = []
    for группа in sorted(политики):
        п = политики[группа] or {}
        торгует = bool(п.get("lane_trades")) and (п.get("lane_sol") is not None)
        с = состояние_группы(OS, B, группа)
        нов = предложение(с["сейчас"], добавить) if торгует else None
        строки.append({
            "группа": группа, "торгует_полосой": торгует,
            "lane_sol": п.get("lane_sol"),
            "lane_pools_в_файле": п.get("lane_pools"),
            "сейчас_берёт": с["сейчас"], "двухшаговый": с["двухшаговый"],
            "неизвестных_программ": с["неизвестных_программ"],
            "предложение_lane_pools": нов,
            "что_изменится": (sorted(set(нов or []) - set(с["сейчас"])) if нов else []),
            "что_пропадёт": (sorted(set(с["сейчас"]) - set(нов or [])) if нов else []),
        })
        print(f"  {группа}: торгует={торгует} lane_sol={п.get('lane_sol')} "
               f"в файле={п.get('lane_pools')}")
        print(f"      сейчас берёт: {', '.join(с['сейчас']) or '(ничего)'}")
        if нов is not None:
            print(f"      ПРЕДЛОЖЕНИЕ:  {json.dumps(нов, ensure_ascii=False)}")
            if с["сейчас"] and set(с["сейчас"]) - set(нов):
                print(f"      ТРЕВОГА: из списка пропали {sorted(set(с['сейчас']) - set(нов))}")

    итог = {"файл_групп": файл, "почему_нет": д.get("why_not"),
             "добавляем": добавить, "флаги": фл, "группы": строки,
             "как_считано": ("bloom_own_send.типы_полосы + двухшаговый_включён -- "
                              "те же функции, по которым решает полоса")}
    if а.out:
        with open(а.out, "w", encoding="utf-8") as ф:
            json.dump(итог, ф, ensure_ascii=False, indent=1)
        print(f"предложение записано: {а.out}")
    пропажи = [с["группа"] for с in строки if с["что_пропадёт"]]
    if пропажи:
        print(f"СБОЙ: у групп {пропажи} полный список терял бы типы")
        return 1
    return 0


def self_test() -> int:
    """Только своя арифметика списков: ни сети, ни файла групп, ни модулей полосы."""
    всего = [0, 0]

    def chk(имя, условие, факт=None):
        всего[0] += 1
        if условие:
            всего[1] += 1
            print(f"  [ok  ] {имя}")
        else:
            print(f"  [ПЛОХО] {имя} -- {факт}")

    chk("полный список = что было + новое, по алфавиту и без повторов",
        предложение(["pump_amm", "cpmm"], ["clmm"]) == ["clmm", "cpmm", "pump_amm"],
        предложение(["pump_amm", "cpmm"], ["clmm"]))
    chk("добавление того, что уже есть, ничего не меняет",
        предложение(["clmm", "cpmm"], ["clmm"]) == ["clmm", "cpmm"])
    # ГЛАВНОЕ: ДВУХШАГОВЫЙ НЕ ТЕРЯЕТСЯ. Он не тип пула, и типы_полосы его не
    # возвращает; если не внести его в полный список -- он выключится молча.
    chk("двухшаговый из состояния попадает в предложение",
        "two_step" in предложение(["pump_amm", "two_step"], ["clmm"]))
    chk("пустое добавление законно -- список просто повторяет нынешнее",
        предложение(["pump_amm"], []) == ["pump_amm"])
    chk("мусор в добавлении отбрасывается, регистр приводится",
        предложение(["pump_amm"], [" CLMM ", ""]) == ["clmm", "pump_amm"])

    class _B:
        PUMP_AMM = "pAMM"
        CPMM = "cpamd"
        CLMM = "CAMM"

    class _OS:
        ИМЕНА_ТИПОВ = {"PUMP_AMM": "pump_amm", "CPMM": "cpmm", "CLMM": "clmm",
                        "НЕТ_ТАКОГО": "vydumka"}
        ИМЯ_ДВУХШАГОВОГО = "two_step"

        @staticmethod
        def типы_полосы(группа):
            return {"pAMM", "cpamd"} if группа == "torg" else set()

        @staticmethod
        def двухшаговый_включён(группа):
            return группа == "torg"

    карта = имена_по_программам(_OS, _B)
    chk("карта программ строится по ИМЕНА_ТИПОВ, без выдуманных",
        карта == {"pAMM": "pump_amm", "cpamd": "cpmm", "CAMM": "clmm"}, карта)
    с = состояние_группы(_OS, _B, "torg")
    chk("состояние группы: имена типов плюс two_step",
        с["сейчас"] == ["cpmm", "pump_amm", "two_step"], с)
    chk("группа без типов -- пустой список, а не догадка",
        состояние_группы(_OS, _B, "off")["сейчас"] == [])
    # ПРОГРАММА, КОТОРОЙ НЕТ В ИМЕНАХ, НЕ ПРЯЧЕТСЯ: без этого полный список молча
    # выключил бы тип, которого мы не умеем назвать.
    class _B2(_B):
        pass

    class _OS2(_OS):
        @staticmethod
        def типы_полосы(группа):
            return {"pAMM", "ЧУЖАЯ_ПРОГРАММА"}

        @staticmethod
        def двухшаговый_включён(группа):
            return False

    с2 = состояние_группы(_OS2, _B2, "torg")
    chk("неназываемая программа помечена, а не потеряна",
        с2["неизвестных_программ"] == ["НЕИЗВЕСТНЫЙ:ЧУЖАЯ_ПРОГРАММА"], с2)
    chk("флаги читаются только по префиксам LANE_/BLOOM_*_STROITEL",
        all(к.startswith("LANE_")
            or (к.startswith("BLOOM_") and к.endswith("_STROITEL"))
            for к in флаги_строителей()), sorted(флаги_строителей()))
    print(f"самопроверка полного списка lane_pools: {всего[1]}/{всего[0]}"
           f"{' пройдено' if всего[1] == всего[0] else ' ПРОВАЛ'}")
    return 0 if всего[1] == всего[0] else 1


if __name__ == "__main__":
    raise SystemExit(main())
