#!/usr/bin/env python3
"""Шреды против WS: насколько наш сигнал позже последнего шреда слота.

Числа, которые просил владелец (пункт 4, утро 27.09):
  * медиана и p90 разницы "WS - последний шред слота" по ВСЕМ слотам;
  * то же отдельно по слотам, где был НАШ сигнал (transactionSubscribe);
  * шредов принято, слотов покрыто.

Измерительный код: тестов нет по правилу владельца ("самопроверки -- только
денежный путь"). Только чтение: slots.jsonl читается потоком, ничего не
пишется на хост.

ЧАСЫ. Все времена в записи -- монотонные (time.monotonic) ОДНОГО процесса,
поэтому вычитать их друг из друга можно. Стенные часы для этого не годятся:
на них правится время по NTP, и разница в десятки миллисекунд утонула бы.
"""
import argparse
import gzip
import json
import os
import statistics
import sys
import urllib.error
import urllib.request


def строки(путь: str):
    откр = gzip.open if путь.endswith(".gz") else open
    with откр(путь, "rt", encoding="utf-8", errors="replace") as ф:
        for ln in ф:
            ln = ln.strip()
            if ln.startswith("{"):
                try:
                    yield json.loads(ln)
                except ValueError:
                    continue


def процентиль(ряд: list, доля: float):
    if not ряд:
        return None
    р = sorted(ряд)
    i = min(len(р) - 1, max(0, int(round(доля * (len(р) - 1)))))
    return р[i]


def свод(ряд: list, имя: str) -> dict:
    return {"имя": имя, "n": len(ряд),
            "медиана_мс": (round(statistics.median(ряд) * 1000, 2) if ряд else None),
            "p90_мс": (round(процентиль(ряд, 0.9) * 1000, 2) if ряд else None),
            "мин_мс": (round(min(ряд) * 1000, 2) if ряд else None),
            "макс_мс": (round(max(ряд) * 1000, 2) if ряд else None)}


ИМЕНА_КЛЮЧА = ("HELIUS_API_KEY2", "HELIUS_API_KEY", "HELIUS_API")


def слоты_с_блоками(от_слота: int, до_слота: int) -> dict:
    """Какие слоты диапазона ВЫПУСТИЛИ блок. getBlocks -- один вызов на диапазон.

    ЗАЧЕМ. Слот без шредов -- это два РАЗНЫХ случая, и смешивать их нельзя:
    лидер слота вообще не выпустил блок (пропуск лидера, шредов и не было), либо
    блок был, а шреды до нас не дошли (потеря). Первое о сети Solana, второе о
    нас, и решение "поднимать ли буфер дальше" зависит от того, какое из них.

    Ключ берётся из окружения, СВОЙ ключ проверок первым. Значение наружу не
    отдаётся: печатается только имя переменной.
    """
    из_ = {"ok": False, "why_not": None, "имя_ключа": "не задан",
            "слотов_с_блоками": None, "множество": set()}
    ключ = ""
    for имя in ИМЕНА_КЛЮЧА:
        зн = (os.environ.get(имя) or "").strip()
        if зн:
            ключ, из_["имя_ключа"] = зн, имя
            break
    if not ключ:
        из_["why_not"] = ("ключ Helius не задан: " + ", ".join(ИМЕНА_КЛЮЧА)
                           + " -- пропуски лидера от потерь не отличить")
        return из_
    тело = json.dumps({"jsonrpc": "2.0", "id": 1, "method": "getBlocks",
                        "params": [int(от_слота), int(до_слота)]}).encode()
    зап = urllib.request.Request(f"https://mainnet.helius-rpc.com/?api-key={ключ}",
                                  data=тело,
                                  headers={"Content-Type": "application/json"})
    try:
        with urllib.request.urlopen(зап, timeout=30) as о:  # noqa: S310
            отв = json.loads(о.read().decode())
    except (urllib.error.URLError, OSError, ValueError) as exc:
        из_["why_not"] = f"getBlocks не отдался: {type(exc).__name__}"
        return из_
    рез = отв.get("result")
    if not isinstance(рез, list):
        из_["why_not"] = f"getBlocks вернул не список: {str(отв.get('error'))[:120]}"
        return из_
    из_.update(ok=True, слотов_с_блоками=len(рез), множество=set(int(с) for с in рез))
    return из_



def самопроверка() -> int:
    """Числа новых рядов и оценки повторов -- на выдуманном файле с известным ответом.
    ЗАЧЕМ. По этим числам решается «медленный поток или поздний хвост», и знак
    разницы тут решает всё: перепутанный знак поменял бы вывод на обратный.
    Поэтому пример разобран руками, и самопроверка сторожит именно его."""
    import tempfile
    ошибок = 0

    def chk(имя, условие, факт=None):
        nonlocal ошибок
        if условие:
            print(f"  [ok  ] {имя}")
        else:
            ошибок += 1
            print(f"  [СБОЙ] {имя} -- факт: {факт!r}")

    записи = [
        # слот, шредов, первый, последний, ws слота, наш сигнал, index_min, index_max
        (100, 10, 1.000, 1.400, 1.100, 1.150, 0, 9),
        (101, 12, 2.000, 2.500, 2.050, None,  0, 9),   # 12 шредов на 10 индексов -> не менее 2 повторов
        (102,  8, 3.000, 3.300, 2.900, 2.950, 0, 7),   # WS РАНЬШЕ первого шреда -> знак плюс
        (103,  5, 4.000, 4.200, None,  None,  0, 4),   # без WS: в ряды не идёт, в оценку повторов идёт
        (104,  0, None,  None,  5.000, 5.010, None, None),  # без шредов вовсе
    ]
    кат = tempfile.mkdtemp()
    with open(os.path.join(кат, "slots.jsonl"), "w", encoding="utf-8") as ф:
        for с, ш, пе, по, ws, сиг, i1, i2 in записи:
            ф.write(json.dumps({"slot": с, "shreds": ш, "first_mono": пе, "last_mono": по,
                                 "ws_slot_mono": ws, "ws_signal_mono": сиг,
                                 "index_min": i1, "index_max": i2}) + "\n")

    import subprocess
    гот = subprocess.run([sys.executable, os.path.abspath(__file__), "--out-dir", кат,
                          "--json", os.path.join(кат, "out.json"), "--imya-okna", "самопроверка"],
                         capture_output=True, text=True)
    chk("прогон не упал", гот.returncode == 0, гот.stderr[-300:])
    with open(os.path.join(кат, "out.json"), encoding="utf-8") as ф:
        и = json.load(ф)

    # Первый шред минус первая WS: слоты 100 (-100), 101 (-50), 102 (+100).
    а = и["первый_шред_минус_первая_ws"]
    chk("первый шред минус первая WS: n=3", а["n"] == 3, а)
    chk("медиана -50 мс", а["медиана_мс"] == -50.0, а)
    chk("p90 +100 мс -- знак плюса означает, что шред ПОЗЖЕ WS", а["p90_мс"] == 100.0, а)
    # Только слоты с нашим сигналом: 100 (-100) и 102 (+100).
    б = и["первый_шред_минус_первая_ws_по_слотам_с_сигналом"]
    chk("по слотам с нашим сигналом: n=2, медиана 0", б["n"] == 2 and б["медиана_мс"] == 0.0, б)
    # Первый шред минус наш сигнал: 100 (-150), 102 (+50).
    в = и["первый_шред_минус_наш_сигнал"]
    chk("первый шред минус наш сигнал: n=2, медиана -50", в["n"] == 2 and в["медиана_мс"] == -50.0, в)
    # Слот без WS в ряды не попал, слот без шредов тоже.
    chk("слот без WS в ряды не попал", а["n"] == 3 and в["n"] == 2, (а, в))
    # Прежние ряды не сломались: WS минус последний шред = -300, -450, -400.
    г = и["ws_минус_последний_шред"]
    chk("прежний ряд цел: медиана -400 мс", г["медиана_мс"] == -400.0, г)
    # Повторы: только слот 101, сверх 2; шредов всего 35.
    д = и["повторы"]
    chk("оценка снизу повторов 2", д["оценка_снизу_повторов"] == 2, д)
    chk("шредов 35 и доля 2/35", и["шредов_принято_по_слотам"] == 35
        and д["оценка_снизу_доля"] == round(2 / 35, 6), (и["шредов_принято_по_слотам"], д))
    chk("слотов с повторами не менее 1", д["слотов_с_повторами_не_менее"] == 1, д)
    chk("в оценку вошли 4 слота: без шредов не считается",
        д["слотов_учтено_в_оценке"] == 4, д)
    chk("сказано, что точной доли в файле нет", bool(д["точной_доли_в_файле_нет"]), д)
    chk("оговорка про данные и восстановительные шреды на месте", bool(д["оговорка"]), д)
    chk("слот без шредов посчитан отдельно", и["слотов_без_шредов"] == 1, и)

    import shutil
    shutil.rmtree(кат, ignore_errors=True)
    print(f"самопроверка шредов против WS: {'всё сошлось' if not ошибок else 'ОШИБОК ' + str(ошибок)}"
          f" ({ошибок} ошибок)")
    return 1 if ошибок else 0


def main() -> int:
    р = argparse.ArgumentParser()
    р.add_argument("--out-dir", default="/home/bot/shred_probe_data")
    р.add_argument("--json", default=None, help="куда положить числа (по желанию)")
    # ОКНО ПО СЛОТУ. Файл slots.jsonl НЕ обнуляется при смене поставщика: в нём
    # лежат и слоты BlockRazor с 26-27.09, и слоты Triton с 30.09. Без окна
    # медиана считается по всем 255 тысячам слотов сразу, то есть отвечает про
    # BlockRazor, а не про того поставщика, о котором спрашивают. Такое число
    # выглядит как замер и им не является.
    р.add_argument("--ot-slota", type=int, default=0,
                   help="считать только слоты НЕ НИЖЕ этого (0 -- все)")
    р.add_argument("--do-slota", type=int, default=0,
                   help="считать только слоты НЕ ВЫШЕ этого (0 -- без предела)")
    р.add_argument("--imya-okna", default="",
                   help="как назвать окно в отчёте, например 'Triton с 11:25:32Z'")
    р.add_argument("--razobrat-bez-shredov", action="store_true",
                   help="слоты без шредов разделить на пропуски лидера и потери (getBlocks)")
    р.add_argument("--self-test", action="store_true",
                   help="числа на выдуманном файле с известным ответом, без сети")
    а = р.parse_args()

    if а.self_test:
        return самопроверка()

    пути = [os.path.join(а.out_dir, "slots.jsonl")]
    пути += sorted(os.path.join(а.out_dir, ф) for ф in os.listdir(а.out_dir)
                   if ф.startswith("slots.jsonl.") and ф.endswith(".gz")) \
        if os.path.isdir(а.out_dir) else []

    все, с_сигналом, разброс = [], [], []
    # ПЕРВЫЙ ШРЕД ПРОТИВ ПЕРВОЙ WS-ТРАНЗАКЦИИ СЛОТА (вопрос владельца 30.09).
    # Прежние числа отвечали про ПОСЛЕДНИЙ шред слота, то есть про хвост. Этот
    # ряд отвечает про НАЧАЛО: если первый шред приходит раньше первой
    # WS-транзакции, поток не медленный, и виноват поздний хвост; если позже --
    # медленный сам поток.
    первый_минус_ws, первый_минус_ws_сиг, первый_минус_сигнал = [], [], []
    # ПОВТОРЫ. Слушатель хранит по слоту только index_min и index_max, а НЕ
    # множество индексов, поэтому точную долю повторов файл не содержит вовсе.
    # Что он содержит -- строгую ОЦЕНКУ СНИЗУ: различных индексов в слоте не
    # больше, чем index_max - index_min + 1, значит всё, что сверх этого,
    # пришло повторно. ОГОВОРКА: данные и восстановительные шреды нумеруются
    # каждый в своём пространстве, и пара (слот, индекс) законно повторяется
    # между ними -- поэтому эта оценка снизу смешивает пересылку с таким
    # пересечением и НЕ равна доле пересылок.
    повторов_не_менее = 0
    слотов_с_повторами = 0
    слотов_для_оценки = 0
    слотов = шредов = с_ws = с_нашим = вне_окна = 0
    # СЛОТЫ БЕЗ ШРЕДОВ -- отдельным списком: ниже они делятся на пропуски
    # лидера и наши потери, и это разные выводы.
    без_шредов: list = []
    первый_слот = последний_слот = None
    for путь in пути:
        if not os.path.exists(путь):
            continue
        for з in строки(путь):
            с = з.get("slot")
            # ВНЕ ОКНА -- НЕ СЧИТАЕМ ВОВСЕ, включая счётчики: иначе "шредов
            # принято" осталось бы про обоих поставщиков, а медиана -- про одного.
            if а.ot_slota and (not isinstance(с, int) or с < а.ot_slota):
                вне_окна += 1
                continue
            if а.do_slota and (not isinstance(с, int) or с > а.do_slota):
                вне_окна += 1
                continue
            слотов += 1
            шредов += int(з.get("shreds") or 0)
            if isinstance(с, int):
                первый_слот = с if первый_слот is None else min(первый_слот, с)
                последний_слот = с if последний_слот is None else max(последний_слот, с)
            посл = з.get("last_mono")
            перв = з.get("first_mono")
            if перв is not None and посл is not None:
                разброс.append(float(посл) - float(перв))
            ws = з.get("ws_slot_mono")
            сиг = з.get("ws_signal_mono")
            if ws is not None:
                с_ws += 1
            if сиг is not None:
                с_нашим += 1
            # РАЗНИЦА СЧИТАЕТСЯ ТОЛЬКО когда в слоте есть И шреды, И WS:
            # иначе это не замер, а дырка в данных.
            if посл is None:
                if isinstance(с, int):
                    без_шредов.append(с)
                continue
            if ws is not None:
                все.append(float(ws) - float(посл))
            if сиг is not None:
                с_сигналом.append(float(сиг) - float(посл))
            # ПЕРВЫЙ шред слота против ПЕРВОЙ WS-транзакции слота. Знак тот же,
            # что у остальных рядов: отрицательное -- шред раньше WS.
            if перв is not None:
                if ws is not None:
                    первый_минус_ws.append(float(перв) - float(ws))
                    if сиг is not None:
                        первый_минус_ws_сиг.append(float(перв) - float(ws))
                if сиг is not None:
                    первый_минус_сигнал.append(float(перв) - float(сиг))
                i_min, i_max = з.get("index_min"), з.get("index_max")
                ш = int(з.get("shreds") or 0)
                if isinstance(i_min, int) and isinstance(i_max, int) and ш:
                    слотов_для_оценки += 1
                    разных_не_больше = i_max - i_min + 1
                    сверх = ш - разных_не_больше
                    if сверх > 0:
                        повторов_не_менее += сверх
                        слотов_с_повторами += 1

    признак = {}
    п_признака = os.path.join(а.out_dir, "heartbeat.json")
    if os.path.exists(п_признака):
        try:
            with open(п_признака, encoding="utf-8") as ф:
                признак = json.load(ф)
        except ValueError:
            признак = {}

    итог = {
        "каталог": а.out_dir,
        # ОКНО НАЗЫВАЕТСЯ В ОТЧЁТЕ ВСЕГДА, даже когда его нет: иначе по числу
        # нельзя понять, о каком поставщике шредов оно говорит.
        "окно_имя": а.imya_okna or ("все слоты файла" if not (а.ot_slota or а.do_slota)
                                     else "окно по слоту"),
        "окно_от_слота": а.ot_slota or None,
        "окно_до_слота": а.do_slota or None,
        "слотов_вне_окна_пропущено": вне_окна,
        "слотов_в_файле": слотов,
        "шредов_принято_по_слотам": шредов,
        "шредов_принято_по_признаку": признак.get("shreds"),
        "слотов_с_ws": с_ws,
        "слотов_с_нашим_сигналом": с_нашим,
        "слоты_от": первый_слот, "слоты_до": последний_слот,
        "обрывов_ws": признак.get("ws_breaks"),
        "пакетов_вне_окна": признак.get("packets_out_of_window"),
        "ws_минус_последний_шред": свод(все, "по всем слотам"),
        "ws_сигнал_минус_последний_шред": свод(с_сигналом, "по слотам с нашим сигналом"),
        "разброс_шредов_в_слоте": свод(разброс, "последний минус первый шред"),
        "первый_шред_минус_первая_ws": свод(первый_минус_ws, "по всем слотам, где есть и шреды и WS"),
        "первый_шред_минус_первая_ws_по_слотам_с_сигналом": свод(
            первый_минус_ws_сиг, "по слотам с нашим сигналом"),
        "первый_шред_минус_наш_сигнал": свод(первый_минус_сигнал, "первый шред минус наш сигнал"),
        "повторы": {
            "точной_доли_в_файле_нет": ("слушатель хранит по слоту только index_min и index_max, "
                                          "а не множество индексов: точное число повторов из файла "
                                          "не получить"),
            "оценка_снизу_повторов": повторов_не_менее,
            "оценка_снизу_доля": (round(повторов_не_менее / шредов, 6) if шредов else None),
            "слотов_с_повторами_не_менее": слотов_с_повторами,
            "слотов_учтено_в_оценке": слотов_для_оценки,
            "оговорка": ("данные и восстановительные шреды нумеруются каждый в своём пространстве, "
                          "и пара (слот, индекс) законно повторяется между ними: оценка снизу "
                          "смешивает пересылку с этим пересечением и НЕ равна доле пересылок"),
        },
        "слотов_без_шредов": len(без_шредов),
        "без_шредов_разбор": None,
    }
    if а.razobrat_bez_shredov and без_шредов:
        бл = слоты_с_блоками(min(без_шредов), max(без_шредов))
        разб = {"имя_ключа": бл["имя_ключа"], "why_not": бл["why_not"],
                 "слотов_без_шредов": len(без_шредов),
                 "пропуск_лидера": None, "потеряно_нами": None}
        if бл["ok"]:
            с_блоком = sum(1 for с_ in без_шредов if с_ in бл["множество"])
            разб.update(пропуск_лидера=len(без_шредов) - с_блоком,
                         потеряно_нами=с_блоком,
                         как=("блок у слота есть, а шредов нет -- потеря у нас; "
                               "блока нет -- лидер слот пропустил, шредов и не было"))
        итог["без_шредов_разбор"] = разб
    print(json.dumps(итог, ensure_ascii=False, indent=1))
    # Три строки словами -- их и читать владельцу.
    for ключ in ("ws_минус_последний_шред", "ws_сигнал_минус_последний_шред",
                  "первый_шред_минус_первая_ws",
                  "первый_шред_минус_первая_ws_по_слотам_с_сигналом",
                  "первый_шред_минус_наш_сигнал"):
        с = итог[ключ]
        print(f"{с['имя']}: n={с['n']}, медиана {с['медиана_мс']} мс, "
              f"p90 {с['p90_мс']} мс")
    print(f"шредов принято {итог['шредов_принято_по_слотам']}, "
          f"слотов покрыто {слотов} (с нашим сигналом {с_нашим})")
    рз = итог.get("без_шредов_разбор")
    if рз:
        if рз.get("потеряно_нами") is None:
            print(f"слотов без шредов {рз['слотов_без_шредов']}, разбор не вышел: {рз['why_not']}")
        else:
            print(f"слотов без шредов {рз['слотов_без_шредов']}: "
                  f"пропуск лидера {рз['пропуск_лидера']}, потеряно нами {рз['потеряно_нами']} "
                  f"(ключ {рз['имя_ключа']})")
    пв = итог["повторы"]
    print(f"повторы: точной доли файл не содержит (храним index_min/index_max, не множество); "
          f"оценка СНИЗУ {пв['оценка_снизу_повторов']} из {итог['шредов_принято_по_слотам']} "
          f"= {пв['оценка_снизу_доля']}, слотов с повторами не менее {пв['слотов_с_повторами_не_менее']} "
          f"из {пв['слотов_учтено_в_оценке']}")
    print("  оговорка: данные и восстановительные шреды нумеруются в своих пространствах, "
          "(слот, индекс) между ними повторяется законно -- это не доля пересылок")
    print(f"окно: {итог['окно_имя']}"
          + (f", от слота {а.ot_slota}" if а.ot_slota else "")
          + (f", до слота {а.do_slota}" if а.do_slota else "")
          + f", пропущено вне окна {вне_окна} слотов")
    if а.json:
        with open(а.json, "w", encoding="utf-8") as ф:
            json.dump(итог, ф, ensure_ascii=False, indent=1)
    return 0


