#!/usr/bin/env python3
"""ЖИВЫ ЛИ РЕГИОНАЛЬНЫЕ ТОЧКИ ОТПРАВИТЕЛЕЙ -- проверка соединения БЕЗ отправки.

ЗАЧЕМ (слово владельца, ночь 29.09, пункт 2). Утром региональная отправка
(III.14) включается на 0.1 SOL. До включения владелец хочет доказательство, что
точки, КОТОРЫЕ ВЫБЕРЕТ ДЕНЕЖНЫЙ ПУТЬ по каждому региону лидера, отвечают:
"проверка соединения без отправки". Здесь ровно это: один GET на точку, ни
одной транзакции, ни одного ключа.

ЧЕГО ЗДЕСЬ НЕТ И НЕ БУДЕТ.
  * POST. Отправка бывает ТОЛЬКО POST со sendTransaction, поэтому метод здесь
    прибит к GET и проверен assert-ом в _запрос(): опечатка, превратившая эту
    проверку в отправку, стоит денег.
  * Ключей. Прогрев у отправителей КЛЮЧ НЕ ПЕРЕДАЁТ (так написано в
    bloom_senders.прогреть) -- здесь так же: ни в строке запроса, ни в
    заголовках. Адрес в отчёт идёт без строки запроса вовсе.
  * Своей копии выбора точки. Адрес спрашивается у bloom_region_send.адрес_для,
    то есть проверяется именно то, что подставит денежный путь, а не похожее.

ЧТО ЗНАЧИТ "ОТВЕТИЛА". ЛЮБОЙ код HTTP -- это живая точка. Точки отправителей
принимают только POST, и на GET они законно отвечают 405 Method Not Allowed
(а jito отдаёт 404 на корень) -- это ОТВЕТ сервера, то есть TCP и TLS прошли,
имя разрешилось, сервис слушает. Мертво -- только когда ответа нет вовсе:
таймаут, отказ соединения, имя не разрешилось. Эта разница вынесена отдельным
полем ответила и полем http_смысл, чтобы 405 никто не прочитал как поломку.

Выход всегда 0: это измерение, а решение включать ли утром -- за владельцем.
"""
