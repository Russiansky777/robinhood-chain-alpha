# --------------------------------------------------------------- самопроверка
def self_test() -> int:
    """Правило 8: измерение самопроверок не требует. Здесь она есть только для
    ЧИСТЫХ функций, чья арифметика могла бы соврать молча: если 405 посчитать
    смертью, утром выйдет "все точки мёртвые" на исправных серверах; если RTT
    подставить нулём, худшее время станет ложно хорошим. Сеть здесь не
    трогается ни разу.
    """
    проверки = []

    def chk(имя, ок, факт=""):
        проверки.append((имя, bool(ок), факт))

    # МЕТОД. Главное, что здесь проверяется: запрос -- GET и без тела.
    зап = _запрос("http://h.example/iris")
    chk("метод запроса -- GET", зап.get_method() == "GET", зап.get_method())
    chk("у запроса нет тела (это не отправка)", зап.data is None, зап.data)
    chk("в заголовках запроса нет ничего похожего на ключ",
        not any(к.lower() in ("apikey", "authorization", "x-api-key")
                for к in зап.headers), list(зап.headers))

    # АДРЕС БЕЗ ЗАПРОСА: ключ из строки запроса обязан исчезнуть, путь и порт --
    # остаться (без пути это другой endpoint, дефект найден 29.09).
    chk("строка запроса срезана вместе с ключом",
        адрес_без_запроса("http://h.example/iris?api-key=ZZZZZZZZ")
        == "http://h.example/iris",
        адрес_без_запроса("http://h.example/iris?api-key=ZZZZZZZZ"))
    chk("путь и нестандартный порт остаются",
        адрес_без_запроса("http://h.example:443/sendTransaction")
        == "http://h.example:443/sendTransaction")
    chk("мусор вместо адреса -- None, а не выдуманная строка",
        адрес_без_запроса("не адрес") is None and адрес_без_запроса(None) is None)

    # КЛАССИФИКАЦИЯ КОДОВ: 405 и 404 -- живая точка.
    chk("405 читается как ЖИВАЯ точка", "ЖИВА" in http_смысл(405, True),
        http_смысл(405, True))
    chk("404 читается как ЖИВАЯ точка", "ЖИВА" in http_смысл(404, True),
        http_смысл(404, True))
    chk("200 -- жива", "жив" in http_смысл(200, True), http_смысл(200, True))
    chk("нет ответа -- недоступна, и это единственная смерть",
        "недоступна" in http_смысл(None, False), http_смысл(None, False))

    # RTT: незнание не превращается в ноль.
    т = [{"отправитель": "a", "host": "h1", "port": 443, "мин_мс": 12.5,
          "медиана_мс": 13.0, "нет_ответа": 0, "замеров": 5},
         {"отправитель": "a", "host": "h2", "port": 443, "мин_мс": None,
          "медиана_мс": None, "нет_ответа": 5, "замеров": 0}]
    р1 = rtt_из_файла(т, "a", "h1", 443)
    chk("RTT взят и поле названо",
        р1["rtt_мс"] == 12.5 and р1["rtt_поле"] == ПОЛЕ_RTT, р1)
    р2 = rtt_из_файла(т, "a", "h2", 443)
    chk("замер был, но не удался -- None и причина, не 0",
        р2["rtt_мс"] is None and "не установлен" in (р2["rtt_почему_нет"] or ""), р2)
    р3 = rtt_из_файла(т, "a", "нет-такого", 443)
    chk("хоста нет в файле -- None и причина, не 0",
        р3["rtt_мс"] is None and "нет в" in (р3["rtt_почему_нет"] or ""), р3)
    р4 = rtt_из_файла([], "a", "h1", 443)
    chk("файла RTT нет -- None и причина", р4["rtt_мс"] is None
        and "пуст" in (р4["rtt_почему_нет"] or ""), р4)
    chk("порт различает точки одного хоста",
        rtt_из_файла(т, "a", "h1", 80)["rtt_мс"] is None,
        rtt_из_файла(т, "a", "h1", 80))

    # ХУДШЕЕ ВРЕМЯ: максимум среди ответивших; никто не ответил -- None.
    chk("худшее -- максимум среди ответивших",
        худшее_мс([{"ответила": True, "мс": 10.0},
                   {"ответила": True, "мс": 250.0},
                   {"ответила": False, "мс": 2500.0}])["худшее_мс"] == 250.0,
        худшее_мс([{"ответила": True, "мс": 10.0},
                   {"ответила": True, "мс": 250.0},
                   {"ответила": False, "мс": 2500.0}]))
    х = худшее_мс([{"ответила": False, "мс": 2500.0}])
    chk("никто не ответил -- худшее None и причина, а не 0 мс",
        х["худшее_мс"] is None and bool(х["худшее_почему_нет"]), х)

    # СВОД без сети не выдумывает живость.
    с_ = свод([{"адрес_разрешён": True, "свой_регион": True, "url_без_ключа": "u",
                "отправитель": "a", "регион_лидера": "EU", "регион_точки": "EU"}],
              была_сеть=False)
    chk("без сети ответили=None и причина названа",
        с_["ответили"] is None and bool(с_["почему_нет_живости"]), с_)

    плохо = [(и, ф) for и, ок, ф in проверки if not ок]
    for имя, ок, факт in проверки:
        print(f"  [{'ok  ' if ок else 'СБОЙ'}] {имя}" + ("" if ок else f"  -> {факт}"))
    print(f"самопроверка живости региональных точек: "
          f"{len(проверки) - len(плохо)}/{len(проверки)} пройдено")
    return 0 if not плохо else 1


