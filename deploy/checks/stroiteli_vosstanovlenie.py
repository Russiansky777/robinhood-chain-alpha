def self_test() -> int:
    """Проверяет саму проверку: ловит ли независимая сверка чужие счета.

    ЗАЧЕМ. Сверка, которая всегда говорит «сошлось», не стоит ничего. Здесь ей
    подсовывают четыре заведомо неверные сборки и требуют, чтобы она их
    отвергла, и одну верную -- чтобы приняла.
    """
    пройдено = провалено = 0

    def chk(что, ок, факт=None):
        nonlocal пройдено, провалено
        print(f"  [{'ok  ' if ок else 'ПРОВАЛ'}] {что}"
              + (f" -> {факт!r}" if факт is not None and not ок else ""))
        пройдено += bool(ок)
        провалено += (not ок)

    try:
        import solders.pubkey  # noqa: F401,PLC0415
    except Exception:  # noqa: BLE001
        print("  [проп ] сверка наших счетов: на этой машине нет solders")
        print("самопроверка восстановления строителей: пропущена -- нет solders")
        return 0

    SPL = "TokenkegQfeZyiNwAJbNbGKPFXCWuBvf9Ss623VQ5DA"
    T22 = "TokenzQdBNbLqP5VEhdkAS6EPFLC1PHnBqCXEpPxuEb"
    WSOL = "So11111111111111111111111111111111111111112"
    БАЗА = "EPjFWdd5AufqSSqeM2qN1xzybapC8G4wEGGkZwyTDt1v"
    ЧУЖОЙ = "11111111111111111111111111111111"

    class _М:
        """Подставной модуль: объявляет три своих места, как настоящие строители."""

        @staticmethod
        def наши_места_подробно(tpl):
            return [{"место": 0, "роль": "подписант", "минт": None, "программа": None},
                    {"место": 1, "роль": "наш счёт входа (котировка)",
                      "минт": (tpl or {}).get("минт_входа"),
                      "программа": (tpl or {}).get("программа_входа")},
                    {"место": 2, "роль": "наш счёт выхода (база)",
                      "минт": (tpl or {}).get("минт_выхода"),
                      "программа": (tpl or {}).get("программа_выхода")}]

        @staticmethod
        def обязаны_быть_записываемыми(tpl):
            return [1, 2]

    шаб = {"минт_входа": WSOL, "минт_выхода": БАЗА,
            "программа_входа": SPL, "программа_выхода": SPL}
    п = {"шаблон": шаб, "минт_базы": БАЗА, "минт_котировки": WSOL,
          "программа_базы": SPL, "программа_котировки": SPL}
    верно = [ЧУЖОЙ_КОШЕЛЁК, _ata(ЧУЖОЙ_КОШЕЛЁК, WSOL, SPL),
             _ata(ЧУЖОЙ_КОШЕЛЁК, БАЗА, SPL)]
    chk("верная сборка принимается", наши_счета_независимо(_М, п, верно)["ok"] is True)
    chk("ATA выведен с чужой программой токена -- отвергается",
        наши_счета_независимо(_М, п, [верно[0], верно[1],
                                       _ata(ЧУЖОЙ_КОШЕЛЁК, БАЗА, T22)])["ok"] is False)
    chk("ATA чужого владельца -- отвергается",
        наши_счета_независимо(_М, п, [верно[0], верно[1],
                                       _ata(ЧУЖОЙ, БАЗА, SPL)])["ok"] is False)
    chk("чужой подписант -- отвергается",
        наши_счета_независимо(_М, п, [ЧУЖОЙ, верно[1], верно[2]])["ok"] is False)
    # ГЛАВНОЕ УСЛОВИЕ: перестановка счёта входа со счётом выхода. Первая версия
    # сравнивала места множествами и такую сборку ПРИНИМАЛА, а на цепи это
    # покупка, превращённая в продажу базы.
    chk("счёт входа и счёт выхода ПЕРЕСТАВЛЕНЫ -- отвергается",
        наши_счета_независимо(_М, п, [верно[0], верно[2], верно[1]])["ok"] is False)
    chk("модуль не назвал программу токена -- отказ, а не «сошлось»",
        наши_счета_независимо(
            _М, dict(п, шаблон=dict(шаб, программа_выхода=None)), верно)["ok"] is False)

    # --- ФЛАГИ: записываемость и подпись
    def _метки(зап_1=True, зап_2=True, подп=True, кто=ЧУЖОЙ_КОШЕЛЁК):
        return [{"pubkey": кто, "signer": подп, "writable": True},
                {"pubkey": верно[1], "signer": False, "writable": зап_1},
                {"pubkey": верно[2], "signer": False, "writable": зап_2}]

    chk("флаги верной сборки принимаются",
        флаги_независимо(_М, п, _метки(), [])["ok"] is True)
    chk("наш счёт выхода не записываемый -- отвергается",
        флаги_независимо(_М, п, _метки(зап_2=False), [])["ok"] is False)
    chk("подписант без признака подписи -- отвергается",
        флаги_независимо(_М, п, _метки(подп=False), [])["ok"] is False)
    chk("подписант не наш кошелёк -- отвергается",
        флаги_независимо(_М, п, _метки(кто=ЧУЖОЙ), [])["ok"] is False)
    лишний = _метки()
    лишний[1]["signer"] = True
    chk("лишний подписант в инструкции -- отвергается",
        флаги_независимо(_М, п, лишний, [])["ok"] is False)

    # --- Подставной узел обязан отдавать ровно то, что записано, и None на то,
    # чего в снимке нет: иначе строитель «прочитает» выдуманное состояние.
    import base64 as _b64  # noqa: PLC0415

    снимок = {"slot": 7, "данные": {"A" * 32: _b64.b64encode(b"\x01\x02").decode()}}
    rpc, _ = узел_из_снимка(снимок)
    о = rpc("getMultipleAccounts", [["A" * 32, "B" * 32], {}])
    зн = о["result"]["value"]
    chk("подставной узел: записанный счёт отдан как есть",
        _b64.b64decode(зн[0]["data"][0]) == b"\x01\x02")
    chk("подставной узел: чего нет в снимке -- отдаётся как отсутствующий",
        зн[1] is None)
    try:
        rpc("simulateTransaction", [])
        сеть = False
    except OSError:
        сеть = True
    chk("подставной узел отвечает ТОЛЬКО на getMultipleAccounts", сеть)

    print(f"самопроверка восстановления строителей: {пройдено}/{пройдено + провалено} пройдено")
    return 0 if провалено == 0 else 1


def main() -> int:
    р = argparse.ArgumentParser(description=__doc__)
    р.add_argument("--tip", default="clmm", choices=sorted(ТИПЫ),
                   help="тип пула (clmm / whirlpool / dbc)")
    р.add_argument("--sbor", default=None,
                   help="файл сбора Code-2 (по умолчанию data/podbivka/<тип>_sbor.json)")
    р.add_argument("--moduli", default=ДЛЯ_МОДУЛЕЙ, help="каталог модулей службы")
    р.add_argument("--porty", default=None,
                   help="каталог с переносами Code-2 (podbivka_*_quote), если они "
                        "не лежат рядом с модулями")
    р.add_argument("--lamports", type=int, default=10_000_000)
    р.add_argument("--slippage", type=float, default=0.35)
    р.add_argument("--skolko", type=int, default=None, help="сколько снимков брать")
    р.add_argument("--pribliz", action="store_true",
                   help="DBC: разрешить ПРИБЛИЖЁННУЮ цену по событию сделки источника "
                        "(помечается точная=False); по умолчанию выключено")
    р.add_argument("--perehody", default=None,
                   help="через запятую: размеры покупки в лампортах, на которых посчитать, "
                        "сколько сигналов теряет правило перехода через тик "
                        "(например 10000000,5000000000)")
    р.add_argument("--out", default=None, help="куда положить отчёт json")
    р.add_argument("--self-test", dest="self_test", action="store_true",
                   help="проверить саму проверку (без сети и без данных)")
    а = р.parse_args()
    if а.self_test:
        return self_test()
    if а.moduli and а.moduli not in sys.path:
        sys.path.insert(0, а.moduli)
    if а.porty:
        os.environ["BLOOM_PODBIVKA_DIR"] = а.porty
    путь = а.sbor or os.path.join(КОРЕНЬ, "data", "podbivka", ТИПЫ[а.tip]["файл"])
    ряд = None
    if а.perehody:
        ряд = [int(x) for x in str(а.perehody).replace(";", ",").split(",") if x.strip()]
    о = прогон(тип=а.tip, путь_сбора=путь, лампорты=а.lamports,
                проскальзывание=а.slippage, сколько=а.skolko,
                приближение=bool(а.pribliz), переходы=ряд)
    печать(о)
    if а.out:
        with open(а.out, "w", encoding="utf-8") as ф:
            json.dump(о, ф, ensure_ascii=False, indent=1)
        print(f"  отчёт: {а.out}")
    # КОД ВОЗВРАТА -- НЕ ВСЕГДА НОЛЬ. Прогон, который ничего не проверил (файла
    # нет, модуль не загрузился), и прогон, где сборка не сверилась ни разу,
    # обязаны отличаться от успеха: иначе гейт перед включением флага пропустит
    # регресс. Тот же договор, что у --self-test.
    if о.get("why_not"):
        return 2
    св = о.get("свод") or {}
    плохо = []
    if not св.get("разобрано"):
        плохо.append("ни одного снимка не разобрано")
    if св.get("данные_совпали") != св.get("разобрано"):
        плохо.append(f"данные байт в байт {св.get('данные_совпали')} из {св.get('разобрано')}")
    if св.get("наша_сборка_ok") and св.get("сборка_сверена") != св.get("наша_сборка_ok"):
        плохо.append(f"обратный разбор сошёлся {св.get('сборка_сверена')} из "
                      f"{св.get('наша_сборка_ok')}")
    if св.get("наша_сборка_ok") and св.get("флаги_сверены") != св.get("наша_сборка_ok"):
        плохо.append(f"флаги сошлись {св.get('флаги_сверены')} из {св.get('наша_сборка_ok')}")
    if св.get("цена_против_факта_считано") and \
            св.get("цена_против_факта_до_единицы") != св.get("цена_против_факта_считано"):
        плохо.append(f"цена против факта сошлась {св.get('цена_против_факта_до_единицы')} "
                      f"из {св.get('цена_против_факта_считано')}")
    if св.get("по_хранилищу_считано") and \
            св.get("по_хранилищу_наш_пул") != св.get("по_хранилищу_считано"):
        плохо.append(f"по хранилищу выбран наш пул {св.get('по_хранилищу_наш_пул')} из "
                      f"{св.get('по_хранилищу_считано')}")
    if плохо:
        print("  ПРОГОН НЕ ЗЕЛЁНЫЙ: " + "; ".join(плохо))
        return 1
    return 0


