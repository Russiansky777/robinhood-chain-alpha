def разбор_снимка(снимок: dict, *, тип: str, лампорты: int,
                   проскальзывание: float, приближение: bool = False) -> dict:
    из_ = {"пул": снимок.get("пул"), "slot": снимок.get("slot"),
            "slot_сделки": снимок.get("slot_сделки"),
            "сделка": снимок.get("сделка"), "байт_в_байт": None, "why_not": None}
    сп = ТИПЫ[тип]
    М = __import__(сп["модуль"])
    tx = снимок.get("транзакция") or {}
    свои = [их for их in инструкции_программы(tx, сп["программа"])
            if снимок.get("пул") in (их.get("accounts") or [])]
    if not свои:
        из_["why_not"] = "инструкции программы по этому пулу в транзакции нет"
        return из_
    т = М.шаблон(tx, снимок.get("пул"))
    if not т.get("ok"):
        из_["why_not"] = f"шаблон: {т.get('why_not')}"
        return из_
    из_["вид"] = т.get("вид")
    из_["счетов"] = len(т["accounts"])
    из_["точный_вход_у_источника"] = т.get("точный_вход")

    # --- 1. БАЙТ В БАЙТ: его аргументы, его счета, его хвост.
    его = None
    for их in свои:
        if list(их.get("accounts") or []) == list(т["accounts"]):
            его = их
            break
    его = его or свои[0]
    его_счета = list(его.get("accounts") or [])
    его_байты = bytes(т["data"])
    # ПОЛЬЗОВАТЕЛЬ -- С МЕСТА, КОТОРОЕ НАЗЫВАЕТ РАСКЛАДКА, а не плательщик
    # транзакции: у части источников покупку подписывает один ключ, а комиссию
    # платит другой, и тогда сравнение проверяло бы не то.
    его_user = М.пользователь_шаблона(т)
    из_["пользователь_источника"] = его_user
    свой_tpl = М.шаблон_со_сторонами(т, tx)
    if not свой_tpl.get("ok"):
        из_["why_not"] = f"стороны пула не восстановились: {свой_tpl.get('why_not')}"
        return из_
    try:
        свой = М.инструкция_свопа(свой_tpl["шаблон"], user=его_user,
                                   amount_in=т["arg0"], min_out=т["arg1"],
                                   как_у_источника=True)
    except Exception as exc:  # noqa: BLE001
        из_["why_not"] = f"пересборка упала: {type(exc).__name__}: {str(exc)[:140]}"
        return из_
    свои_байты = bytes(свой.data)
    свои_счета = [str(м.pubkey) for м in свой.accounts]
    из_["данные_совпали"] = (свои_байты == его_байты)
    из_["счета_совпали"] = (свои_счета == его_счета)
    из_["байт_в_байт"] = bool(из_["данные_совпали"] and из_["счета_совпали"])
    из_["длина_данных"] = len(его_байты)
    if not из_["данные_совпали"]:
        из_["данные_его"] = его_байты.hex()
        из_["данные_наши"] = свои_байты.hex()
    if not из_["счета_совпали"]:
        расх = [{"i": и,
                  "его": (его_счета[и] if и < len(его_счета) else None),
                  "наш": (свои_счета[и] if и < len(свои_счета) else None)}
                 for и in range(max(len(его_счета), len(свои_счета)))
                 if (его_счета[и] if и < len(его_счета) else None)
                 != (свои_счета[и] if и < len(свои_счета) else None)]
        из_["счета_расхождение"] = расх[:6]
        из_["расхождений_мест"] = len(расх)
        # ПОЧЕМУ РАСХОЖДЕНИЕ. Если ВСЕ расхождения -- это места наших токеновых
        # счетов, значит у источника они не ATA подписанта инструкции (сделка
        # шла через агрегатор: подписант -- PDA роутера). Это не поломка
        # раскладки, и смешивать её с настоящим расхождением нельзя.
        места_наши = set(М.места_наших_счетов(т))
        из_["расхождения_только_наши_счета"] = bool(расх) and all(
            з["i"] in места_наши for з in расх)

    # --- 2. НАША сборка: стороны под покупку, точная котировка на записанном
    # состоянии, шаблон с нынешними счетами.
    rpc_call, сырые = узел_из_снимка(снимок)
    из_["счетов_в_снимке"] = len(сырые)
    было_флаг = os.environ.get(М.ИМЯ_ФЛАГА)
    os.environ[М.ИМЯ_ФЛАГА] = "1"
    try:
        доп = {"разрешить_приближение": True} if (приближение and тип == "dbc") else {}
        п = М.подготовить(tx, пул=снимок.get("пул"), лампорты=int(лампорты),
                           проскальзывание=float(проскальзывание),
                           rpc_call=rpc_call, сейчас=снимок.get("время_сделки"), **доп)
    except Exception as exc:  # noqa: BLE001
        п = {"ok": False, "why_not": f"{type(exc).__name__}: {str(exc)[:160]}"}
    finally:
        if было_флаг is None:
            os.environ.pop(М.ИМЯ_ФЛАГА, None)
        else:
            os.environ[М.ИМЯ_ФЛАГА] = было_флаг
    из_["подготовка"] = {к: п.get(к) for к in
                          ("ok", "why_not", "развёрнут", "min_out", "expected_out",
                            "fee_share", "чтений", "массивов_нужно",
                            "массивов_влезло", "массивов_дописано",
                            "мест_у_источника", "не_влезло_сколько",
                            "тиков_пересечено", "ставка_1e6", "tick_spacing",
                            "tick_current", "массивы_старты", "точная", "путь_цены")}

    # --- 3. СЧЕТА ИЗ СОСТОЯНИЯ ПРОТИВ СЧЕТОВ ЖИВОЙ СДЕЛКИ. Это и есть ответ на
    # вопрос «брать ли массивы у источника»: числом, а не мнением.
    из_["меняющиеся"] = М.сверка_меняющихся(т, п, его_счета)

    # --- 4. Наша транзакция: собирается ли и какого размера.
    if п.get("ok") and п.get("шаблон"):
        try:
            # СОБИРАЕМ ТОЙ ЖЕ ДВЕРЬЮ, КОТОРУЮ ПОЗОВЁТ ПОЛОСА: build_buy(tpl, tx,
            # …) с той же подписью, что у c2_swap_build.build_buy. Проверять
            # собственную функцию, а торговать другой -- значит мерить не то.
            сб = М.build_buy(п["шаблон"], tx, user=ЧУЖОЙ_КОШЕЛЁК,
                              payer=ЧУЖОЙ_КОШЕЛЁК, amount_in=int(лампорты),
                              min_out=int(п["min_out"] or 1),
                              cu_price_micro=100_000)
            из_["наша_сборка"] = {к: сб.get(к) for к in
                                   ("size", "n_instructions", "quote_mint", "base_mint")}
            из_["наша_сборка_ok"] = bool(сб.get("tx_base64"))
            из_["сборка_сверена"] = сверить_сборку(М, п, сб, лампорты)
        except Exception as exc:  # noqa: BLE001
            из_["наша_сборка_ok"] = False
            из_["наша_сборка_why_not"] = f"{type(exc).__name__}: {str(exc)[:140]}"
    else:
        из_["наша_сборка_ok"] = None
    return из_


# ------------------------------------------------------------ прогон

def прогон(*, тип: str, путь_сбора: str, лампорты: int, проскальзывание: float,
            сколько: int | None, приближение: bool = False) -> dict:
    сп = ТИПЫ[тип]
    # ПУТЬ В ОТЧЁТЕ -- ОТ КОРНЯ РЕПОЗИТОРИЯ, а не абсолютный: отчёт коммитится, и
    # /tmp одной машины в нём ничего не значит. Файл вне репозитория называется
    # своим именем с пометкой -- обычно это локальная копия сбора ветки Code-2.
    _отн = os.path.relpath(os.path.abspath(путь_сбора), КОРЕНЬ)
    из_ = {"тип": тип, "имя": сп["имя"], "программа": сп["программа"],
            "сбор": (_отн if not _отн.startswith("..")
                      else f"{os.path.basename(путь_сбора)} (вне репозитория -- "
                            f"локальная копия сбора ветки Code-2)"),
            "только_чтение": True, "сети_нет": True,
            "симуляции_нет": True, "лампорты": лампорты,
            "проскальзывание": проскальзывание, "why_not": None,
            "модуль_загружен": None, "порт_есть": None}
    if not os.path.exists(путь_сбора):
        из_["why_not"] = (f"файла нет: {путь_сбора} -- сбор Code-2 лежит в его ветке "
                           f"(data/podbivka/{сп['файл']}); укажите --sbor")
        return из_
    try:
        М = __import__(сп["модуль"])
    except Exception as exc:  # noqa: BLE001
        из_["модуль_загружен"] = False
        из_["why_not"] = f"модуль строителя не загружен: {type(exc).__name__}: {exc}"
        return из_
    из_["модуль_загружен"] = True
    # ПЕРЕНОС КОДА ПРОГРАММЫ (модуль Code-2 podbivka_*_quote) НЕ ОБЯЗАТЕЛЕН ДЛЯ
    # ПРОГОНА. Без него восстановление байт в байт всё равно считается -- оно
    # проверяет раскладку и роли счетов, а не цену; цена тогда честно
    # отказывает в каждой строке, и это видно в своде, а не скрыто.
    из_["порт_есть"] = bool(М.порт_есть())
    with open(путь_сбора, encoding="utf-8") as ф:
        сбор = json.load(ф)
    снимки = list(сбор.get("снимки") or []) if isinstance(сбор, dict) else []
    if not снимки:
        # ОБРАЗЦЫ ВМЕСТО СНИМКОВ. У типов, по которым сбора Code-2 нет (DBC),
        # живые транзакции лежат в data/c2_pool_samples/<программа>.json списком
        # {source, mint, pool_vault, quote_mint, tx}. Состояния счетов там нет --
        # значит точная цена честно откажет, а восстановление байт в байт
        # посчитается.
        образцы = сбор if isinstance(сбор, list) else (сбор.get("образцы") or [])
        for о in образцы:
            tx = о.get("tx") or {}
            пул = None
            for их in инструкции_программы(tx, сп["программа"]):
                счета = их.get("accounts") or []
                if len(счета) > 2:
                    пул = счета[2]
                    break
            if пул:
                снимки.append({"пул": пул, "транзакция": tx, "данные": {},
                                "slot": (tx or {}).get("slot"),
                                "время_сделки": (tx or {}).get("blockTime"),
                                "сделка": ((tx.get("transaction") or {})
                                            .get("signatures") or [None])[0]})
        из_["откуда"] = "образцы (сбора Code-2 по этому типу нет)"
    if сколько:
        снимки = снимки[:int(сколько)]
    из_["снимков"] = len(снимки)
    из_["версия_программы"] = сбор.get("версия") if isinstance(сбор, dict) else None
    т0 = time.perf_counter()
    строки = []
    for с in снимки:
        try:
            строки.append(разбор_снимка(с, тип=тип, лампорты=лампорты,
                                         проскальзывание=проскальзывание,
                                         приближение=приближение))
        except Exception as exc:  # noqa: BLE001
            строки.append({"пул": с.get("пул"), "byte_в_байт": None,
                            "why_not": f"разбор упал: {type(exc).__name__}: {str(exc)[:160]}"})
    из_["мс"] = round((time.perf_counter() - т0) * 1000.0, 1)
    из_["строки"] = строки

    считанные = [с for с in строки if с.get("байт_в_байт") is not None]
    # ПУЛЫ НЕ ПРОТИВ SOL -- ВНЕ ПРАВИЛА ПОЛОСЫ, а не провал строителя. Полоса
    # берёт только пулы с котировкой SOL ("котировка пула не SOL -- полоса только
    # одношаговая", bloom_own_send). Снимки Code-2 собраны по ВСЕМ сделкам
    # источников, и пулов против USDC там большинство; складывать их в отказы
    # котировки значило бы мерить не то.
    def _вне_sol(с):
        п = с.get("подготовка") or {}
        return (not п.get("ok")) and "котировка пула не " in str(п.get("why_not") or "")

    вне_sol = [с for с in считанные if _вне_sol(с)]
    в_правиле = [с for с in считанные if not _вне_sol(с)]
    из_["свод"] = {
        "разобрано": len(считанные),
        "вне_правила_котировка_не_SOL": len(вне_sol),
        "в_правиле_SOL": len(в_правиле),
        "котировка_ok_из_SOL": sum(1 for с in в_правиле
                                    if (с.get("подготовка") or {}).get("ok")),
        "не_разобрано": len(строки) - len(считанные),
        "байт_в_байт": sum(1 for с in считанные if с.get("байт_в_байт")),
        "данные_совпали": sum(1 for с in считанные if с.get("данные_совпали")),
        "счета_совпали": sum(1 for с in считанные if с.get("счета_совпали")),
        "счета_разошлись_только_наши": sum(
            1 for с in считанные if с.get("расхождения_только_наши_счета")),
        "котировка_ok": sum(1 for с in считанные
                             if (с.get("подготовка") or {}).get("ok")),
        "наша_сборка_ok": sum(1 for с in считанные if с.get("наша_сборка_ok")),
        "сборка_сверена": sum(1 for с in считанные
                               if (с.get("сборка_сверена") or {}).get("ok")),
        # ТОЧНАЯ ЦЕНА И ПРИБЛИЖЕНИЕ СЧИТАЮТСЯ ОТДЕЛЬНО. Сложить их в одно число
        # значило бы выдать приближение за точность -- ровно то, из-за чего у
        # DBC вообще стоит отказ по умолчанию.
        "цена_точная": sum(1 for с in считанные
                            if (с.get("подготовка") or {}).get("ok")
                            and (с.get("подготовка") or {}).get("точная") is not False),
        "цена_приближённая": sum(1 for с in считанные
                                  if (с.get("подготовка") or {}).get("ok")
                                  and (с.get("подготовка") or {}).get("точная") is False),
    }
    # ПОЧЕМУ КОТИРОВКА НЕ ВЫШЛА -- по причинам, а не одним числом: часть причин
    # это предел ЗАПИСАННОГО снимка (нужного массива в нём нет), а не порт.
    причины = {}
    for с in в_правиле:
        п = с.get("подготовка") or {}
        if not п.get("ok"):
            причины[str(п.get("why_not"))[:110]] = причины.get(str(п.get("why_not"))[:110], 0) + 1
    из_["свод"]["почему_не_вышла_котировка"] = dict(
        sorted(причины.items(), key=lambda x: -x[1]))
    м = [с.get("меняющиеся") or {} for с in считанные]
    из_["свод"]["меняющиеся"] = М.свод_меняющихся(м)
    размеры = [(с.get("наша_сборка") or {}).get("size") for с in считанные]
    из_["свод"]["размер_нашей_tx"] = {"p50": процентиль(размеры, 0.5),
                                       "max": процентиль(размеры, 1.0)}
    несовпавшие = [{"пул": с.get("пул"), "сделка": с.get("сделка"),
                     "вид": с.get("вид"), "мест": с.get("расхождений_мест"),
                     "только_наши": с.get("расхождения_только_наши_счета"),
                     "расхождение": с.get("счета_расхождение")}
                    for с in считанные if not с.get("байт_в_байт")]
    из_["не_совпавшие"] = несовпавшие
    return из_


def печать(о: dict) -> None:
    print(f"=== строитель {о.get('имя')} -- восстановление байт в байт, без сети ===")
    if о.get("why_not"):
        print(f"  не сделано: {о['why_not']}")
        return
    с = о["свод"]
    print(f"  снимков {о['снимков']}, разобрано {с['разобрано']}, "
          f"не разобрано {с['не_разобрано']}, время {о['мс']} мс"
          + (f"; источник: {о['откуда']}" if о.get("откуда") else ""))
    if not о.get("порт_есть"):
        print("  ВНИМАНИЕ: переноса кода программы (podbivka_*_quote, ветка Code-2) "
              "нет -- цена ниже не считалась, считалась только раскладка счетов")
    print(f"  БАЙТ В БАЙТ: {с['байт_в_байт']} из {с['разобрано']} "
          f"(данные {с['данные_совпали']}, счета {с['счета_совпали']}, "
          f"из расхождений только наши счета: {с['счета_разошлись_только_наши']})")
    print(f"  вне правила полосы (котировка пула не SOL): "
          f"{с['вне_правила_котировка_не_SOL']}; пулов против SOL: {с['в_правиле_SOL']}")
    print(f"  цена выдана: {с['котировка_ok_из_SOL']} из {с['в_правиле_SOL']} пулов "
          f"против SOL -- точной {с['цена_точная']}, приближением {с['цена_приближённая']}")
    print(f"  наша сборка: {с['наша_сборка_ok']}, из них сверено обратным разбором "
          f"транзакции: {с['сборка_сверена']}")
    if с.get("почему_не_вышла_котировка"):
        print("  почему котировка не вышла (только пулы против SOL):")
        for к, н in с["почему_не_вышла_котировка"].items():
            print(f"    {н} -- {к}")
    print(f"  меняющиеся счета: {json.dumps(с.get('меняющиеся'), ensure_ascii=False)}")
    print(f"  размер нашей транзакции: p50 {с['размер_нашей_tx']['p50']}, "
          f"max {с['размер_нашей_tx']['max']} байт")
    for н in (о.get("не_совпавшие") or [])[:6]:
        print(f"  НЕ СОВПАЛО: пул {str(н['пул'])[:8]} вид {н['вид']} "
              f"мест {н['мест']} только_наши={н['только_наши']}")


def self_test() -> int:
    """Проверяет саму проверку: ловит ли независимая сверка чужие счета.

    ЗАЧЕМ. Сверка, которая всегда говорит «сошлось», не стоит ничего. Здесь ей
    подсовывают четыре заведомо неверные сборки и требуют, чтобы она их
    отвергла, и одну верную -- чтобы приняла.
    """
    пройдено = провалено = 0

    def chk(что, ок, факт=None):
        nonlocal пройдено, провалено
        print(f"  [{'ok  ' if ок else 'ПРОВАЛ'}] {что}"
              + (f" -> {факт!r}" if факт is not None and not ок else ""))
        пройдено += bool(ок)
        провалено += (not ок)

    try:
        import solders.pubkey  # noqa: F401,PLC0415
    except Exception:  # noqa: BLE001
        print("  [проп ] сверка наших счетов: на этой машине нет solders")
        print("самопроверка восстановления строителей: пропущена -- нет solders")
        return 0

    SPL = "TokenkegQfeZyiNwAJbNbGKPFXCWuBvf9Ss623VQ5DA"
    T22 = "TokenzQdBNbLqP5VEhdkAS6EPFLC1PHnBqCXEpPxuEb"
    WSOL = "So11111111111111111111111111111111111111112"
    БАЗА = "EPjFWdd5AufqSSqeM2qN1xzybapC8G4wEGGkZwyTDt1v"
    ЧУЖОЙ = "11111111111111111111111111111111"

    class _М:
        @staticmethod
        def места_наших_счетов(tpl):
            return [0, 1, 2]

    п = {"шаблон": {}, "минт_базы": БАЗА, "минт_котировки": WSOL,
          "программа_базы": SPL, "программа_котировки": SPL}
    верно = [ЧУЖОЙ_КОШЕЛЁК, _ata(ЧУЖОЙ_КОШЕЛЁК, БАЗА, SPL),
             _ata(ЧУЖОЙ_КОШЕЛЁК, WSOL, SPL)]
    chk("верная сборка принимается", наши_счета_независимо(_М, п, верно)["ok"] is True)
    chk("ATA выведен с чужой программой токена -- отвергается",
        наши_счета_независимо(_М, п, [верно[0], _ata(ЧУЖОЙ_КОШЕЛЁК, БАЗА, T22),
                                       верно[2]])["ok"] is False)
    chk("ATA чужого владельца -- отвергается",
        наши_счета_независимо(_М, п, [верно[0], _ata(ЧУЖОЙ, БАЗА, SPL),
                                       верно[2]])["ok"] is False)
    chk("чужой подписант -- отвергается",
        наши_счета_независимо(_М, п, [ЧУЖОЙ, верно[1], верно[2]])["ok"] is False)
    chk("подготовить() не назвала программы токена -- отказ, а не «сошлось»",
        наши_счета_независимо(_М, dict(п, программа_базы=None), верно)["ok"] is False)

    # --- Подставной узел обязан отдавать ровно то, что записано, и None на то,
    # чего в снимке нет: иначе строитель «прочитает» выдуманное состояние.
    import base64 as _b64  # noqa: PLC0415

    снимок = {"slot": 7, "данные": {"A" * 32: _b64.b64encode(b"\x01\x02").decode()}}
    rpc, _ = узел_из_снимка(снимок)
    о = rpc("getMultipleAccounts", [["A" * 32, "B" * 32], {}])
    зн = о["result"]["value"]
    chk("подставной узел: записанный счёт отдан как есть",
        _b64.b64decode(зн[0]["data"][0]) == b"\x01\x02")
    chk("подставной узел: чего нет в снимке -- отдаётся как отсутствующий",
        зн[1] is None)
    try:
        rpc("simulateTransaction", [])
        сеть = False
    except OSError:
        сеть = True
    chk("подставной узел отвечает ТОЛЬКО на getMultipleAccounts", сеть)

    print(f"самопроверка восстановления строителей: {пройдено}/{пройдено + провалено} пройдено")
    return 0 if провалено == 0 else 1


def main() -> int:
    р = argparse.ArgumentParser(description=__doc__)
    р.add_argument("--tip", default="clmm", choices=sorted(ТИПЫ),
                   help="тип пула (clmm / whirlpool / dbc)")
    р.add_argument("--sbor", default=None,
                   help="файл сбора Code-2 (по умолчанию data/podbivka/<тип>_sbor.json)")
    р.add_argument("--moduli", default=ДЛЯ_МОДУЛЕЙ, help="каталог модулей службы")
    р.add_argument("--porty", default=None,
                   help="каталог с переносами Code-2 (podbivka_*_quote), если они "
                        "не лежат рядом с модулями")
    р.add_argument("--lamports", type=int, default=10_000_000)
    р.add_argument("--slippage", type=float, default=0.35)
    р.add_argument("--skolko", type=int, default=None, help="сколько снимков брать")
    р.add_argument("--pribliz", action="store_true",
                   help="DBC: разрешить ПРИБЛИЖЁННУЮ цену по событию сделки источника "
                        "(помечается точная=False); по умолчанию выключено")
    р.add_argument("--out", default=None, help="куда положить отчёт json")
    р.add_argument("--self-test", dest="self_test", action="store_true",
                   help="проверить саму проверку (без сети и без данных)")
    а = р.parse_args()
    if а.self_test:
        return self_test()
    if а.moduli and а.moduli not in sys.path:
        sys.path.insert(0, а.moduli)
    if а.porty:
        os.environ["BLOOM_PODBIVKA_DIR"] = а.porty
    путь = а.sbor or os.path.join(КОРЕНЬ, "data", "podbivka", ТИПЫ[а.tip]["файл"])
    о = прогон(тип=а.tip, путь_сбора=путь, лампорты=а.lamports,
                проскальзывание=а.slippage, сколько=а.skolko,
                приближение=bool(а.pribliz))
    печать(о)
    if а.out:
        with open(а.out, "w", encoding="utf-8") as ф:
            json.dump(о, ф, ensure_ascii=False, indent=1)
        print(f"  отчёт: {а.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
