def разбор_снимка(снимок: dict, *, тип: str, лампорты: int,
                   проскальзывание: float, приближение: bool = False) -> dict:
    из_ = {"пул": снимок.get("пул"), "slot": снимок.get("slot"),
            "slot_сделки": снимок.get("slot_сделки"),
            "сделка": снимок.get("сделка"), "байт_в_байт": None, "why_not": None}
    сп = ТИПЫ[тип]
    М = __import__(сп["модуль"])
    tx = снимок.get("транзакция") or {}
    свои = [их for их in инструкции_программы(tx, сп["программа"])
            if снимок.get("пул") in (их.get("accounts") or [])]
    if not свои:
        из_["why_not"] = "инструкции программы по этому пулу в транзакции нет"
        return из_
    т = М.шаблон(tx, снимок.get("пул"))
    if not т.get("ok"):
        из_["why_not"] = f"шаблон: {т.get('why_not')}"
        return из_
    из_["вид"] = т.get("вид")
    из_["счетов"] = len(т["accounts"])
    из_["точный_вход_у_источника"] = т.get("точный_вход")

    # --- 1. БАЙТ В БАЙТ: его аргументы, его счета, его хвост.
    его = None
    for их in свои:
        if list(их.get("accounts") or []) == list(т["accounts"]):
            его = их
            break
    его = его or свои[0]
    его_счета = list(его.get("accounts") or [])
    его_байты = bytes(т["data"])
    # ПОЛЬЗОВАТЕЛЬ -- С МЕСТА, КОТОРОЕ НАЗЫВАЕТ РАСКЛАДКА, а не плательщик
    # транзакции: у части источников покупку подписывает один ключ, а комиссию
    # платит другой, и тогда сравнение проверяло бы не то.
    его_user = М.пользователь_шаблона(т)
    из_["пользователь_источника"] = его_user
    свой_tpl = М.шаблон_со_сторонами(т, tx)
    if not свой_tpl.get("ok"):
        из_["why_not"] = f"стороны пула не восстановились: {свой_tpl.get('why_not')}"
        return из_
    try:
        свой = М.инструкция_свопа(свой_tpl["шаблон"], user=его_user,
                                   amount_in=т["arg0"], min_out=т["arg1"],
                                   как_у_источника=True)
    except Exception as exc:  # noqa: BLE001
        из_["why_not"] = f"пересборка упала: {type(exc).__name__}: {str(exc)[:140]}"
        return из_
    свои_байты = bytes(свой.data)
    свои_счета = [str(м.pubkey) for м in свой.accounts]
    из_["данные_совпали"] = (свои_байты == его_байты)
    из_["счета_совпали"] = (свои_счета == его_счета)
    из_["байт_в_байт"] = bool(из_["данные_совпали"] and из_["счета_совпали"])
    из_["длина_данных"] = len(его_байты)
    if not из_["данные_совпали"]:
        из_["данные_его"] = его_байты.hex()
        из_["данные_наши"] = свои_байты.hex()
    if not из_["счета_совпали"]:
        расх = [{"i": и,
                  "его": (его_счета[и] if и < len(его_счета) else None),
                  "наш": (свои_счета[и] if и < len(свои_счета) else None)}
                 for и in range(max(len(его_счета), len(свои_счета)))
                 if (его_счета[и] if и < len(его_счета) else None)
                 != (свои_счета[и] if и < len(свои_счета) else None)]
        из_["счета_расхождение"] = расх[:6]
        из_["расхождений_мест"] = len(расх)
        # ПОЧЕМУ РАСХОЖДЕНИЕ. Если ВСЕ расхождения -- это места наших токеновых
        # счетов, значит у источника они не ATA подписанта инструкции (сделка
        # шла через агрегатор: подписант -- PDA роутера). Это не поломка
        # раскладки, и смешивать её с настоящим расхождением нельзя.
        места_наши = set(М.места_наших_счетов(т))
        из_["расхождения_только_наши_счета"] = bool(расх) and all(
            з["i"] in места_наши for з in расх)

    # --- 2. НАША сборка: стороны под покупку, точная котировка на записанном
    # состоянии, шаблон с нынешними счетами.
    rpc_call, сырые = узел_из_снимка(снимок)
    из_["счетов_в_снимке"] = len(сырые)
    # УЗЕЛ ИЗ САМОЙ СДЕЛКИ -- только когда снимка состояния нет вовсе и модуль
    # умеет его собрать из фактов своей транзакции (сегодня так у AMM v4: сбора по
    # нему не существует). Отчёт это называет отдельной графой: цена там -- по
    # балансам ПЕРЕД сделкой источника, а не в наш слот.
    из_["узел_из_сделки"] = False
    if not сырые and hasattr(М, "узел_из_сделки"):
        свой_узел = М.узел_из_сделки(tx, т)
        if свой_узел is not None:
            rpc_call = свой_узел
            из_["узел_из_сделки"] = True
    было_флаг = os.environ.get(М.ИМЯ_ФЛАГА)
    os.environ[М.ИМЯ_ФЛАГА] = "1"
    доп = {"разрешить_приближение": True} if (приближение and тип == "dbc") else {}

    def _подготовить(**ещё):
        try:
            return М.подготовить(tx, пул=снимок.get("пул"), лампорты=int(лампорты),
                                  проскальзывание=float(проскальзывание),
                                  rpc_call=rpc_call,
                                  сейчас=снимок.get("время_сделки"), **доп, **ещё)
        except Exception as exc:  # noqa: BLE001
            return {"ok": False, "why_not": f"{type(exc).__name__}: {str(exc)[:160]}"}

    было_сверки = os.environ.get(getattr(М, "ИМЯ_ФЛАГА_СВЕРКИ", "") or "_нет_")
    try:
        п = _подготовить()
        # ЗАМОК «ПЕРЕНОС ЦЕНЫ СВЕРЕН ПО ЖИВЫМ СНИМКАМ» (пока только у DBC). Пока
        # Code-2 не доложил сверку, строитель точную цену НЕ даёт -- и это
        # правильный отказ, его и считаем отдельным числом. Но тогда остаток пути
        # (сборка, обратная сверка, флаги) на этом типе не измерялся бы вовсе,
        # поэтому второй проход с замком, ОТКРЫТЫМ ПРОГОНОМ, и он назван своим
        # именем: это не утверждение о сверке, а способ измерить остаток пути.
        замок = getattr(М, "ИМЯ_ФЛАГА_СВЕРКИ", None)
        признак_св = getattr(М, "ПРИЗНАК_ПОРТ_НЕ_СВЕРЕН", None)
        # ПРИЧИНУ ИЩЕМ И В ОТКАЗЕ ВСЕЙ ПОДГОТОВКИ, И В ОТКАЗЕ ТОЧНОЙ ЦЕНЫ:
        # с --pribliz подготовка возвращает ok по приближению, и по её why_not
        # отказ точной цены был бы не виден вовсе.
        из_["порт_не_сверен"] = bool(
            замок and признак_св and признак_св in
            f"{п.get('why_not')} {п.get('отказ_точной')}")
        if из_["порт_не_сверен"]:
            из_["подготовка_отказ_по_сверке"] = п.get("why_not")
            os.environ[замок] = "1"
            п = _подготовить()
            из_["замок_сверки_открыт_прогоном"] = True
        # НАЛОГ ПЕРЕВОДА Token-2022 ЖИВЁТ В СЧЁТЕ МИНТА, А ЕГО В СНИМКАХ НЕТ:
        # строитель на такой стороне честно отказывает, и это правильный отказ --
        # его и считаем отдельным числом. Но тогда весь остальной путь (массивы,
        # сборка, обратная сверка) на этих пулах не измерялся бы вовсе. Поэтому
        # второй проход с налогом, ПРИНЯТЫМ НУЛЕВЫМ, и он назван своим именем:
        # это не утверждение о минте, а способ измерить остаток пути.
        признак = getattr(М, "ПРИЗНАК_НАЛОГ_НЕ_НАЗВАН", "налог перевода не назван")
        из_["налог_не_передан"] = bool(
            (not п.get("ok")) and признак in str(п.get("why_not") or ""))
        if из_["налог_не_передан"]:
            из_["подготовка_отказ_по_налогу"] = п.get("why_not")
            п = _подготовить(налог_выхода=(0, None), налог_входа=(0, None))
            из_["налог_принят_нулевым"] = True
    finally:
        if было_флаг is None:
            os.environ.pop(М.ИМЯ_ФЛАГА, None)
        else:
            os.environ[М.ИМЯ_ФЛАГА] = было_флаг
        _з = getattr(М, "ИМЯ_ФЛАГА_СВЕРКИ", None)
        if _з:
            if было_сверки is None:
                os.environ.pop(_з, None)
            else:
                os.environ[_з] = было_сверки
    из_["подготовка"] = {к: п.get(к) for к in
                          ("ok", "why_not", "развёрнут", "min_out", "expected_out",
                            "fee_share", "чтений", "массивов_нужно",
                            "массивов_влезло", "массивов_дописано",
                            "мест_у_источника", "не_влезло_сколько",
                            "тиков_пересечено", "ставка_1e6", "tick_spacing",
                            "tick_current", "массивы_старты", "точная", "путь_цены",
                            "отказ_точной", "fee_share", "reserves_after",
                            "резерв_входа", "резерв_выхода")}

    # --- 3. СЧЕТА ИЗ СОСТОЯНИЯ ПРОТИВ СЧЕТОВ ЖИВОЙ СДЕЛКИ. Это и есть ответ на
    # вопрос «брать ли массивы у источника»: числом, а не мнением.
    из_["меняющиеся"] = М.сверка_меняющихся(т, п, его_счета)

    # --- 4. Наша транзакция: собирается ли и какого размера.
    if п.get("ok") and п.get("шаблон"):
        try:
            # СОБИРАЕМ ТОЙ ЖЕ ДВЕРЬЮ, КОТОРУЮ ПОЗОВЁТ ПОЛОСА: build_buy(tpl, tx,
            # …) с той же подписью, что у c2_swap_build.build_buy. Проверять
            # собственную функцию, а торговать другой -- значит мерить не то.
            сб = М.build_buy(п["шаблон"], tx, user=ЧУЖОЙ_КОШЕЛЁК,
                              payer=ЧУЖОЙ_КОШЕЛЁК, amount_in=int(лампорты),
                              min_out=int(п["min_out"] or 1),
                              cu_price_micro=100_000)
            из_["наша_сборка"] = {к: сб.get(к) for к in
                                   ("size", "n_instructions", "quote_mint", "base_mint")}
            из_["наша_сборка_ok"] = bool(сб.get("tx_base64"))
            из_["сборка_сверена"] = сверить_сборку(М, п, сб, лампорты)
        except Exception as exc:  # noqa: BLE001
            из_["наша_сборка_ok"] = False
            из_["наша_сборка_why_not"] = f"{type(exc).__name__}: {str(exc)[:140]}"
    else:
        из_["наша_сборка_ok"] = None

    # --- 5. ТА ЖЕ ИНСТРУКЦИЯ ЧЕРЕЗ РЕЕСТР -- дверь приёмки Code-1 (c2_stroiteli).
    из_["реестр"] = сверка_реестра(снимок, tx, тип=тип, шаблон=т,
                                    его_счета=его_счета, его_байты=его_байты,
                                    его_user=его_user)
    # --- 6. ВЫБОР ИНСТРУКЦИИ ПО ХРАНИЛИЩУ: так её выбирает полоса.
    из_["по_хранилищу"] = выбор_по_хранилищу(М, тип, tx, т)
    # --- 7. ЦЕНА ПРОТИВ ФАКТА ТОЙ ЖЕ СДЕЛКИ (у кого модуль это умеет): наша
    # формула на ЕГО входе и ЕГО резервах против ЕГО же выхода -- до единицы или нет.
    if hasattr(М, "сверка_цены_по_событию"):
        из_["цена_против_факта"] = М.сверка_цены_по_событию(tx, т)
    return из_


def свод_переходов(*, тип: str, снимки: list, лампорты_ряд: list,
                    проскальзывание: float) -> dict:
    """Сколько сигналов теряет правило перехода через тик -- по размеру покупки.

    ЗАЧЕМ ОТДЕЛЬНЫМ СЧЁТОМ. Code-2 требует на переходе отказывать (цена там
    переносом не подтверждена), и это правило стоит на денежном пути. Но
    «отказывать» стоит сигналов, а сколько -- зависит от размера покупки: на
    рабочих 0.01 SOL своп почти никогда не выходит за тик, а на нескольких SOL --
    выходит. Здесь это число, а не впечатление.

    Налог сторон принимается НУЛЕВЫМ (счёта минта в снимках нет) -- иначе
    измерялся бы отказ по налогу, а не по переходу.
    """
    из_ = {"ряд": [], "чем_мерили": ("доля сигналов, потерянных правилом перехода, "
                                      "по размеру покупки; налог принят нулевым")}
    сп = ТИПЫ[тип]
    try:
        М = __import__(сп["модуль"])
    except Exception as exc:  # noqa: BLE001
        из_["why_not"] = f"модуль не загружен: {type(exc).__name__}"
        return из_
    было = os.environ.get(М.ИМЯ_ФЛАГА)
    os.environ[М.ИМЯ_ФЛАГА] = "1"
    try:
        for лампорты in лампорты_ряд:
            счёт = {"лампорты": int(лампорты), "цена_выдана": 0, "отказ_по_переходу": 0,
                     "не_sol": 0, "прочий_отказ": 0}
            for с in снимки:
                rpc, _ = узел_из_снимка(с)
                try:
                    п = М.подготовить(с.get("транзакция") or {}, пул=с.get("пул"),
                                       лампорты=int(лампорты),
                                       проскальзывание=float(проскальзывание),
                                       rpc_call=rpc, сейчас=с.get("время_сделки"),
                                       налог_выхода=(0, None), налог_входа=(0, None))
                except Exception:  # noqa: BLE001
                    счёт["прочий_отказ"] += 1
                    continue
                причина = str(п.get("why_not") or "")
                if п.get("ok"):
                    счёт["цена_выдана"] += 1
                elif "переходит через тик" in причина:
                    счёт["отказ_по_переходу"] += 1
                elif "котировка пула не " in причина:
                    счёт["не_sol"] += 1
                else:
                    счёт["прочий_отказ"] += 1
            из_["ряд"].append(счёт)
    finally:
        if было is None:
            os.environ.pop(М.ИМЯ_ФЛАГА, None)
        else:
            os.environ[М.ИМЯ_ФЛАГА] = было
    return из_


