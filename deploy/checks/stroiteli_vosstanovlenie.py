def процентиль(ряд, доля):
    ч = sorted(x for x in ряд if isinstance(x, (int, float)))
    if not ч:
        return None
    м = min(len(ч) - 1, max(0, int(round(доля * (len(ч) - 1)))))
    return ч[м]


def инструкции_программы(tx: dict, программа: str) -> list:
    """Все инструкции программы -- внешние и внутренние, в порядке исполнения."""
    из_ = []
    сообщение = ((tx or {}).get("transaction") or {}).get("message") or {}
    for их in сообщение.get("instructions") or []:
        if (их.get("programId") or их.get("program")) == программа:
            из_.append(их)
    for группа in ((tx or {}).get("meta") or {}).get("innerInstructions") or []:
        for их in группа.get("instructions") or []:
            if (их.get("programId") or их.get("program")) == программа:
                из_.append(их)
    return из_


def транзакции_из_файлов(пути: list) -> list:
    """Все транзакции из указанных json-файлов -- где бы внутри они ни лежали.

    ЗАЧЕМ ОБХОД, А НЕ ФИКСИРОВАННЫЙ КЛЮЧ. У AMM v4 живые инструкции приходят
    ВНУТРИ транзакций роутеров, то есть лежат в файлах ДРУГИХ типов пулов и на
    разной глубине. Искать их по одному известному ключу значило бы потерять
    большую часть: из 22 живых инструкций в файле «своего» типа лежит ровно одна.
    """
    из_ = []

    def обойти(o, глуб=0):
        if глуб > 8:
            return
        if isinstance(o, dict):
            if "meta" in o and "transaction" in o:
                из_.append(o)
                return
            for v in o.values():
                обойти(v, глуб + 1)
        elif isinstance(o, list):
            for v in o:
                обойти(v, глуб + 1)

    for путь in пути:
        try:
            with open(путь, encoding="utf-8") as ф:
                обойти(json.load(ф))
        except Exception:  # noqa: BLE001
            continue
    return из_


def снимки_из_образцов(сп: dict, М, транзакции: list) -> list:
    """Снимки из живых транзакций, БЕЗ состояния счетов (его в образцах нет).

    Пул каждой инструкции берётся у САМОГО МОДУЛЯ (М.шаблон на одной инструкции),
    а не по зашитому месту в списке счетов: у AMM v4 пул на месте 1, у DBC на 2, у
    Whirlpool на 2 или 4, и зашитое число здесь молча указывало бы на чужой счёт.
    Одна транзакция роутера даёт СТОЛЬКО снимков, сколько в ней пулов этой
    программы.
    """
    из_ = []
    for tx in транзакции:
        if not isinstance(tx, dict):
            continue
        видели = set()
        for их in инструкции_программы(tx, сп["программа"]):
            одна = {"transaction": {"message": {"instructions": [их]}},
                     "meta": (tx.get("meta") or {})}
            т = М.шаблон(одна, None)
            пул = т.get("пул") if т.get("ok") else None
            if not пул or пул in видели:
                continue
            видели.add(пул)
            из_.append({"пул": пул, "транзакция": tx, "данные": {},
                         "slot": (tx or {}).get("slot"),
                         "время_сделки": (tx or {}).get("blockTime"),
                         "сделка": ((tx.get("transaction") or {})
                                     .get("signatures") or [None])[0]})
    return из_


def узел_из_снимка(снимок: dict):
    """Подставной узел: getMultipleAccounts отвечает из записанных байтов.

    Счёт, которого в снимке нет, отдаётся как отсутствующий (None) -- ровно так
    же ответил бы настоящий узел, и строитель обязан отказать честно, а не
    выдумать состояние.
    """
    данные = {а: (base64.b64decode(з) if isinstance(з, str) else None)
              for а, з in (снимок.get("данные") or {}).items()}

    def rpc_call(метод: str, параметры):
        if метод != "getMultipleAccounts":
            raise OSError(f"прогон без сети: метод {метод} не подставлен")
        адреса = list(параметры[0])
        значения = []
        for а in адреса:
            д = данные.get(а)
            значения.append(None if д is None else
                            {"data": [base64.b64encode(д).decode(), "base64"],
                             "owner": None, "lamports": 0, "executable": False,
                             "rentEpoch": 0, "space": len(д)})
        return {"result": {"context": {"slot": снимок.get("slot")}, "value": значения}}

    return rpc_call, данные


ATA_ПРОГРАММА = "ATokenGPvbdGVxr1b2hvZbsiqW5xWH25efTNsLJA8knL"


def _ata(владелец: str, минт: str, программа_токена: str) -> str:
    """Адрес ATA своим выводом -- по правилу ATA-программы, без модулей строителя."""
    from solders.pubkey import Pubkey  # noqa: PLC0415

    pda, _ = Pubkey.find_program_address(
        [bytes(Pubkey.from_string(владелец)), bytes(Pubkey.from_string(программа_токена)),
          bytes(Pubkey.from_string(минт))], Pubkey.from_string(ATA_ПРОГРАММА))
    return str(pda)


def наши_счета_независимо(М, подготовка: dict, счета_в_tx: list) -> dict:
    """На каждом месте, которое модуль объявил своим, стоит ИМЕННО нужный адрес.

    Проверка идёт мимо подстановки модуля: роли и минты берутся из его ОБЪЯВЛЕНИЯ
    (наши_места_подробно -- оно строится по таблице раскладки), а адреса ATA
    считаются здесь, своим выводом PDA по правилу ATA-программы.

    СВЕРКА ПОМЕСТНАЯ, А НЕ МНОЖЕСТВАМИ. Первая версия сравнивала два токеновых
    места как множества, и перестановка счёта входа со счётом выхода для неё
    «сходилась» -- а это ровно тот дефект, ради которого сверка и написана: у DBC
    и CLMM направление программа берёт из минта счёта входа, то есть покупка
    превратилась бы в продажу базы.
    """
    из_ = {"ok": False, "why_not": None, "места": []}
    шаблон = подготовка.get("шаблон") or {}
    объявлено = list(М.наши_места_подробно(шаблон) or [])
    if len(объявлено) != 3:
        из_["why_not"] = f"модуль объявил {len(объявлено)} своих мест, ожидалось три"
        return из_
    все_ок = True
    for об in объявлено:
        место = об.get("место")
        если_нет = (место is None or not isinstance(место, int)
                    or место >= len(счета_в_tx))
        if если_нет:
            из_["why_not"] = f"объявленное место {место!r} вне списка счетов"
            return из_
        факт = счета_в_tx[место]
        if об.get("минт") is None:
            ждём = ЧУЖОЙ_КОШЕЛЁК
        else:
            if not об.get("программа"):
                из_["why_not"] = (f"модуль не назвал программу токена для места "
                                   f"{место} ({об.get('роль')})")
                return из_
            ждём = _ata(ЧУЖОЙ_КОШЕЛЁК, об["минт"], об["программа"])
        сошлось = (факт == ждём)
        все_ок = все_ок and сошлось
        из_["места"].append({"место": место, "роль": об.get("роль"),
                              "сошлось": сошлось,
                              **({} if сошлось else {"ждём": ждём, "факт": факт})})
    из_["ok"] = все_ок
    return из_


def флаги_независимо(М, подготовка: dict, метки: list, ключи: list) -> dict:
    """Флаги записываемости и подписи -- по ОБЪЯВЛЕНИЮ программы, не по коду сборки.

    ЗАЧЕМ. Обе прежние сверки сравнивали только адреса счетов, а на цепи
    незаписываемый массив тиков или расширение -- это AccountNotMutable и откат:
    именно на этих флагах стоят два исправления этой ветки. Список мест, которые
    программа объявляет #[account(mut)], модуль отдаёт отдельной функцией
    (обязаны_быть_записываемыми), а здесь только сравнение.
    """
    из_ = {"ok": False, "why_not": None, "не_записываемые": [], "подписант_ок": None}
    шаблон = подготовка.get("шаблон") or {}
    надо = list(М.обязаны_быть_записываемыми(шаблон) or [])
    if not надо:
        из_["why_not"] = "модуль не назвал ни одного места, обязанного быть записываемым"
        return из_
    for место in надо:
        if место >= len(метки):
            из_["why_not"] = f"место {место} вне инструкции"
            return из_
        if not метки[место]["writable"]:
            из_["не_записываемые"].append({"место": место,
                                            "счёт": метки[место]["pubkey"]})
    объявлено = list(М.наши_места_подробно(шаблон) or [])
    место_подписанта = next((о["место"] for о in объявлено
                              if о.get("минт") is None), None)
    из_["подписант_ок"] = bool(место_подписанта is not None
                                and метки[место_подписанта]["signer"]
                                and метки[место_подписанта]["pubkey"] == ЧУЖОЙ_КОШЕЛЁК)
    # Больше одного подписанта в инструкции покупки быть не должно: лишний
    # потребовал бы чужой подписи, и транзакция не собралась бы.
    из_["подписантов"] = sum(1 for м in метки if м["signer"])
    из_["ok"] = bool(not из_["не_записываемые"] and из_["подписант_ок"]
                      and из_["подписантов"] == 1)
    return из_


def сверить_сборку(М, подготовка: dict, сборка: dict, лампорты: int) -> dict:
    """Инструкция свопа ВНУТРИ собранной транзакции -- та же, что отдаёт модуль.

    ЗАЧЕМ ОТДЕЛЬНАЯ СВЕРКА. Между «модуль умеет собрать инструкцию» и «в
    отправляемой транзакции лежит именно она» есть целый шаг: сборка добавляет
    бюджет, ATA, обёртку SOL и чаевые, компилует сообщение и переставляет счета
    по таблице ключей. Здесь транзакция РАЗБИРАЕТСЯ обратно и сравнивается с
    инструкцией, собранной напрямую: данные байт в байт, счета по порядку.
    Подписи нет, сети нет -- это чистый разбор своих же байтов.
    """
    из_ = {"ok": False, "why_not": None}
    try:
        from solders.transaction import VersionedTransaction  # noqa: PLC0415
    except Exception as exc:  # noqa: BLE001
        из_["why_not"] = f"нет solders: {type(exc).__name__}"
        return из_
    tx64 = (сборка or {}).get("tx_base64")
    if not tx64:
        из_["why_not"] = "собранной транзакции нет"
        return из_
    vtx = VersionedTransaction.from_bytes(base64.b64decode(tx64))
    ключи = [str(к) for к in vtx.message.account_keys]
    свои = [их for их in vtx.message.instructions
            if ключи[их.program_id_index] == М.ПРОГРАММА]
    из_["инструкций_пула"] = len(свои)
    if len(свои) != 1:
        из_["why_not"] = f"инструкций пула в транзакции {len(свои)}, а должна быть одна"
        return из_
    эталон = М.инструкция_свопа(подготовка["шаблон"], user=ЧУЖОЙ_КОШЕЛЁК,
                                 amount_in=int(лампорты),
                                 min_out=int(подготовка.get("min_out") or 1))
    в_tx_данные = bytes(свои[0].data)
    в_tx_счета = [ключи[и] for и in свои[0].accounts]
    # Флаги берутся ИЗ СООБЩЕНИЯ: is_writable и is_signer там определяются
    # заголовком и таблицей ключей, то есть это то, что увидит программа.
    хедер = vtx.message.header
    всего = len(ключи)
    n_подп = хедер.num_required_signatures
    n_подп_ro = хедер.num_readonly_signed_accounts
    n_неподп_ro = хедер.num_readonly_unsigned_accounts

    def _флаги(и: int) -> dict:
        подпись = и < n_подп
        если_подп_зап = и < (n_подп - n_подп_ro)
        если_непод_зап = (n_подп <= и < (всего - n_неподп_ro))
        return {"pubkey": ключи[и], "signer": подпись,
                "writable": (если_подп_зап if подпись else если_непод_зап)}

    метки = [_флаги(и) for и in свои[0].accounts]
    эт_счета = [str(м.pubkey) for м in эталон.accounts]
    из_["данные_совпали"] = (в_tx_данные == bytes(эталон.data))
    из_["счета_совпали"] = (в_tx_счета == эт_счета)
    # СМЕЩЕНИЕ АРГУМЕНТОВ -- НЕ ВСЕГДА 8. У Anchor-программ перед ними лежит
    # дискриминатор из восьми байт, а у Raydium AMM v4 -- ОДИН байт тега, и чтение
    # с восьмого дало бы там мусор (замер: 297 910 414 797 824 вместо 10 000 000).
    # Поэтому смещение спрашивается у модуля, а 8 -- лишь значение по умолчанию.
    сдвиг = int(getattr(М, "СДВИГ_АРГУМЕНТОВ", 8))
    из_["сдвиг_аргументов"] = сдвиг
    из_["amount_in"] = int.from_bytes(в_tx_данные[сдвиг:сдвиг + 8], "little")
    из_["min_out"] = int.from_bytes(в_tx_данные[сдвиг + 8:сдвиг + 16], "little")
    из_["аргументы_совпали"] = (из_["amount_in"] == int(лампорты)
                                 and из_["min_out"] == int(подготовка.get("min_out") or 1))
    # НАШИ СЧЕТА -- ПРОВЕРЯЮТСЯ НЕЗАВИСИМО ОТ МОДУЛЯ. Сравнение с эталоном выше
    # ловит только порчу при сборке сообщения: эталон строит та же функция, что и
    # сборка, и ошибка в выводе наших ATA прошла бы в обеих одинаково. Поэтому
    # адреса считаются ЗДЕСЬ, своим выводом PDA по правилу ATA-программы, и из
    # тех минтов и программ токена, которые назвала подготовить().
    из_.update(наши_счета_сверены=наши_счета_независимо(М, подготовка, в_tx_счета),
                флаги_сверены=флаги_независимо(М, подготовка, метки, ключи))
    из_["ok"] = bool(из_["данные_совпали"] and из_["счета_совпали"]
                      and из_["аргументы_совпали"]
                      and (из_["наши_счета_сверены"] or {}).get("ok")
                      and (из_["флаги_сверены"] or {}).get("ok"))
    if not из_["ok"]:
        из_["расхождение"] = [
            {"i": и, "в_tx": (в_tx_счета[и] if и < len(в_tx_счета) else None),
              "эталон": (эт_счета[и] if и < len(эт_счета) else None)}
            for и in range(max(len(в_tx_счета), len(эт_счета)))
            if (в_tx_счета[и] if и < len(в_tx_счета) else None)
            != (эт_счета[и] if и < len(эт_счета) else None)][:4]
    return из_


def выбор_по_хранилищу(М, тип: str, tx: dict, шаблон_пула: dict) -> dict:
    """Выбирает ли шаблон ИМЕННО НАШ пул, когда адреса пула нет -- только хранилище.

    ЗАЧЕМ. Полоса зовёт подготовить() БЕЗ адреса пула: у неё на руках только
    хранилище (C.identify_pool). На сделке РОУТЕРА инструкций этой программы
    несколько, и шаблон без пула берёт ПЕРВУЮ -- то есть чужой пул. Живой след:
    приёмка Code-1 22:42:46Z, сделка 2W78d2uZSk... -- две инструкции CLMM (пулы
    8sLbNZoA и BE9uiVCx), покупка во второй, и полоса отказала словами «строитель
    взял инструкцию другого пула той же программы». Поэтому у шаблона есть
    параметр хранилище, и здесь считается, что он и правда решает этот случай.

    Эталон -- шаблон, взятый ПО АДРЕСУ ПУЛА (он в снимке есть). Сравниваем с ним
    два захода: без пула вовсе и по хранилищу из эталона.
    """
    из_ = {"ok": None, "роутер": None, "без_пула_чужой": None, "по_хранилищу_наш": None}
    пул = (шаблон_пула or {}).get("пул")
    счета = list((шаблон_пула or {}).get("accounts") or [])
    if not пул or not счета:
        return из_
    р = (getattr(М, "РАСКЛАДКИ", None) or {}).get(шаблон_пула.get("вид")) \
        or getattr(М, "РАСКЛАДКА", None) or {}
    # ХРАНИЛИЩЕ БЕРЁМ ИЗ РАСКЛАДКИ, а не «какой-нибудь счёт»: полоса подаёт именно
    # хранилище стороны, и проверять надо на нём.
    место = None
    for ключ in ("хранилище_входа", "хранилище_a", "хранилище_котировки",
                 "хранилище_coin"):
        if isinstance(р.get(ключ), int):
            место = р[ключ]
            break
    if место is None or место >= len(счета):
        return из_
    хр = счета[место]
    без = М.шаблон(tx, None)
    по_хр = М.шаблон(tx, None, хранилище=хр)
    из_["хранилище"] = хр
    из_["без_пула_чужой"] = bool(без.get("ok") and без.get("пул") != пул)
    из_["по_хранилищу_наш"] = bool(по_хр.get("ok") and по_хр.get("пул") == пул)
    # РОУТЕР -- это когда в транзакции есть инструкция этой программы по ДРУГОМУ
    # пулу. Считается фактом: перебором инструкций, а не по числу счетов.
    пулы = set()
    for их in инструкции_программы(tx, М.ПРОГРАММА):
        т = М.шаблон({"transaction": {"message": {"instructions": [их]}},
                       "meta": (tx or {}).get("meta") or {}}, None)
        if т.get("ok"):
            пулы.add(т.get("пул"))
    из_["роутер"] = len(пулы) > 1
    из_["пулов_в_tx"] = len(пулы)
    из_["ok"] = bool(из_["по_хранилищу_наш"])
    return из_


def сверка_реестра(снимок: dict, tx: dict, *, тип: str, шаблон: dict,
                    его_счета: list, его_байты: bytes, его_user: str | None) -> dict:
    """ТА ЖЕ инструкция, но собранная ЧЕРЕЗ РЕЕСТР -- дверь, в которую стучится приёмка.

    ЗАЧЕМ ОТДЕЛЬНЫМ ШАГОМ. Приёмка Code-1 зовёт не модуль типа пула, а
    одноимённые функции денежного пути (extract_template, mints_and_vaults,
    swap_instruction, build_buy); после правки, описанной в analysis/c2_stroiteli.py,
    они делегируют в реестр. Если реестр отдаёт не то же, что модуль, приёмка
    проверит одно, а полоса пошлёт другое -- и разойдутся они молча. Поэтому
    сверка идёт на тех же живых сделках, а не на придуманном шаблоне.

    Заодно это измеряет mints_and_vaults: минты сторон обязаны быть двумя минтами
    пула, а хранилища -- ДВУМЯ СЧЕТАМИ ИЗ САМОЙ ИНСТРУКЦИИ источника. Хранилище,
    которого в инструкции нет, полоса записала бы в позицию как настоящее.
    """
    из_ = {"ok": False, "why_not": None}
    try:
        import c2_stroiteli as R  # noqa: PLC0415
    except Exception as exc:  # noqa: BLE001
        return {"ok": None, "why_not": f"реестр не загрузился: {type(exc).__name__}"}
    сп = ТИПЫ[тип]
    # Реестр не перехватывает CLMM и DBC, пока их флаг выключен: там уже работает
    # денежный путь Code-1. На время сверки флаг включаем -- как это сделает гейт.
    М = __import__(сп["модуль"])
    было = os.environ.get(R.ENV_ВЫКЛ)
    было_флаг = os.environ.get(М.ИМЯ_ФЛАГА)
    os.environ.pop(R.ENV_ВЫКЛ, None)
    os.environ[М.ИМЯ_ФЛАГА] = "1"
    try:
        tpl = R.extract_template(tx, сп["программа"], снимок.get("пул"))
        if tpl.get("why_not") or tpl.get("ok") is False:
            из_["why_not"] = f"шаблон через реестр: {tpl.get('why_not')}"
            return из_
        из_["шаблон_тот_же"] = (list(tpl.get("accounts") or []) == list(шаблон["accounts"])
                                 and bytes(tpl.get("data") or b"") == bytes(шаблон["data"]))
        из_["спец_есть"] = bool(tpl.get("спец"))
        try:
            их = R.swap_instruction(tpl, tx, его_user, шаблон["arg0"], шаблон["arg1"],
                                     True)
        except Exception as exc:  # noqa: BLE001
            из_["why_not"] = f"пересборка через реестр упала: {type(exc).__name__}: {str(exc)[:120]}"
            return из_
        из_["данные_совпали"] = (bytes(их.data) == bytes(его_байты))
        из_["счета_совпали"] = ([str(м.pubkey) for м in их.accounts] == list(его_счета))
        мв = R.mints_and_vaults(tpl, tx) or {}
        из_["минты_и_хранилища"] = {к: мв.get(к) for к in
                                     ("quote_mint", "base_mint", "quote_vault", "base_vault")}
        стороны = {мв.get("quote_mint"), мв.get("base_mint")}
        хранилища = {мв.get("quote_vault"), мв.get("base_vault")}
        из_["стороны_разные"] = (len(стороны) == 2 and None not in стороны)
        # Хранилища обязаны стоять В САМОЙ инструкции источника, иначе они выдуманы.
        из_["хранилища_из_инструкции"] = (len(хранилища) == 2 and None not in хранилища
                                           and хранилища <= set(его_счета))
        из_["ok"] = bool(из_["шаблон_тот_же"] and из_["данные_совпали"]
                          and из_["счета_совпали"] and из_["спец_есть"]
                          and из_["стороны_разные"] and из_["хранилища_из_инструкции"])
        return из_
    finally:
        if было is not None:
            os.environ[R.ENV_ВЫКЛ] = было
        if было_флаг is None:
            os.environ.pop(М.ИМЯ_ФЛАГА, None)
        else:
            os.environ[М.ИМЯ_ФЛАГА] = было_флаг


