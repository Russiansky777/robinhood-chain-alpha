"""НЕСОБРАННЫЕ ТЕНИ, ПРОШЕДШИЕ ПРАВИЛО СИГНАЛА -- то есть настоящие упущенные
сделки. Только чтение журнала решений, ни сети, ни ключей, ни записи.

ЗАЧЕМ (вопрос владельца 30.09, ночь, п.4): «из 453 теней lane_s0 и 33 batch5 --
сколько прошли правило сигнала (≥ 2 SOL, окно 1800), то есть настоящих
упущенных сделок, и по каким причинам».

ПОЧЕМУ ОДНОГО СЧЁТА ТЕНЕЙ МАЛО. Тень строится на КАЖДЫЙ сигнал, в том числе на
такой, который полоса и так не взяла бы: трата источника меньше порога, или это
не первый вход в минт (тот же минт куплен в предыдущие 1800 слотов). Считать
такие тени «упущенными сделками» -- завышать потерю в разы. Поэтому здесь тень
СШИВАЕТСЯ С РЕШЕНИЕМ по подписи, и в счёт идут только те, где решение говорит:
трата ≥ порога И первый вход.

ЧТО ОТКУДА БЕРЁТСЯ (одно чтение журнала, поток):
  * строка ТЕНИ    -- stage=shadow: why_not, pool_program, quote_mint, route;
  * строка РЕШЕНИЯ -- action=buy/skip: spend_sol_eq, first_entry, code, reason,
                      source и source_task (это и есть ГРУППА источника);
  * строка ПОЛОСЫ  -- stage=build/gate: её why_not (отказ самой полосы).
Группа берётся ИЗ ЗАПИСИ РЕШЕНИЯ (source_task), а не join-ом по файлу групп:
файл групп меняется, и вчерашнюю группу он уже не помнит.

ЧЕГО ЭТО ЧИСЛО НЕ ЗНАЕТ. Прибыль упущенной сделки. Оно говорит только «полоса
взяла бы этот сигнал, но сборщик не смог» -- сколько раз и почему.
"""

from __future__ import annotations

import argparse
import calendar
import collections
import glob
import gzip
import json
import os
import sys
import time

# ПОРОГ ВХОДА ИСТОЧНИКА. Слово владельца: 2 SOL-эквивалента -- столько же стоит
# в задачах DBot. Число не угадывается из окружения: его называют явно.
ПОРОГ_SOL_ПО_УМОЛЧАНИЮ = 2.0


def метка(текст: str) -> float:
    """'2026-09-30T00:00:00Z' -> секунды эпохи. Плохая метка -- отказ, не ноль."""
    т = str(текст or "").replace("Z", "").strip()
    return calendar.timegm(time.strptime(т, "%Y-%m-%dT%H:%M:%S"))


def файлы(каталог: str, *, ротация: bool = True) -> list:
    """Текущий журнал и, по слову, ротированные: без них теряются прошлые сутки."""
    из_ = [os.path.join(каталог, "decisions.jsonl")]
    if ротация:
        из_ += sorted(glob.glob(os.path.join(каталог, "decisions.jsonl.*")))
    return [п for п in из_ if os.path.exists(п)]


def строки(путь: str):
    откр = gzip.open if путь.endswith(".gz") else open
    with откр(путь, "rt", encoding="utf-8", errors="replace") as ф:
        for с in ф:
            с = с.strip()
            if с:
                yield с


def время(з: dict) -> float | None:
    for ключ in ("ts", "t_recv_ts", "t_decide_ts"):
        зн = з.get(ключ)
        if isinstance(зн, (int, float)) and зн > 0:
            return float(зн)
    т = з.get("ts_utc")
    if isinstance(т, str) and т.endswith("Z"):
        try:
            return метка(т)
        except Exception:  # noqa: BLE001
            return None
    return None


def собрать(каталог: str, с_: float, по_: float, *, ротация: bool = True) -> dict:
    """Сшивка по подписи: тень, решение, отказ полосы. Одно чтение журнала."""
    по_подписи: dict = {}
    просмотрено = 0
    без_времени = 0
    for путь in файлы(каталог, ротация=ротация):
        for с in строки(путь):
            просмотрено += 1
            try:
                з = json.loads(с)
            except Exception:  # noqa: BLE001
                continue
            if not isinstance(з, dict):
                continue
            подпись = з.get("signature")
            if not подпись:
                continue
            т = время(з)
            if т is None:
                # Запись без времени НЕ выбрасывается молча: её считают отдельно,
                # иначе окно выглядело бы полным при потерянных строках.
                без_времени += 1
                continue
            if not (с_ <= т < по_):
                continue
            в = по_подписи.setdefault(подпись, {})
            if з.get("stage") == "shadow":
                в["тень"] = {"why_not": з.get("why_not"),
                              "pool_program": з.get("pool_program"),
                              "quote_mint": з.get("quote_mint"),
                              "route": з.get("route"),
                              "ok": з.get("ok"),
                              "tx_base64_есть": bool(з.get("tx_base64"))}
            elif з.get("action") in ("buy", "skip"):
                в["решение"] = {"action": з.get("action"), "code": з.get("code"),
                                 "reason": з.get("reason"),
                                 "source": з.get("source"),
                                 "группа": з.get("source_task"),
                                 "трата_sol": з.get("spend_sol_eq"),
                                 "первый_вход": з.get("first_entry"),
                                 "kind": з.get("kind")}
            elif з.get("stage") in ("build", "gate", "two_step_build"):
                в.setdefault("полоса", {})[з["stage"]] = з.get("why_not")
    return {"по_подписи": по_подписи, "просмотрено": просмотрено,
            "без_времени": без_времени}


def прошло_правило(реш: dict, порог: float) -> tuple:
    """Прошёл ли сигнал правило: трата ≥ порога И первый вход.

    Возвращает (да/нет, почему_нет). Неизвестная трата -- НЕ «прошло»: это
    «не знаем», и такие строки считаются отдельной корзиной, иначе пропуск
    поля читался бы как успех правила.
    """
    if not реш:
        return False, "решения по этой подписи в окне нет"
    трата = реш.get("трата_sol")
    if not isinstance(трата, (int, float)):
        return False, "трата источника не определена"
    if float(трата) < порог:
        return False, f"трата {float(трата):.3f} ниже порога {порог}"
    if реш.get("первый_вход") is not True:
        return False, "не первый вход (тот же минт куплен в окне 1800 слотов)"
    return True, None


def причина_строки(в: dict) -> str:
    """Причина, по которой сделки не случилось: тень, а если молчит -- полоса."""
    почему = str((в.get("тень") or {}).get("why_not") or "").strip()
    if почему:
        return почему
    пол = в.get("полоса") or {}
    for ключ in ("build", "two_step_build", "gate"):
        зн = str(пол.get(ключ) or "").strip()
        if зн:
            return зн
    return "причины нет в записи"


def свод(д: dict, *, порог: float = ПОРОГ_SOL_ПО_УМОЛЧАНИЮ,
         группы=()) -> dict:
    """Числа по группам: теней, из них прошли правило, и причины прошедших."""
    только = set(группы or ())
    по_группе: dict = {}
    for подпись, в in (д.get("по_подписи") or {}).items():
        тень = в.get("тень")
        if not тень:
            continue
        # СОБРАННАЯ тень -- не потеря: сборщик смог, и сделка если не случилась,
        # то по другой причине (её называет полоса, и это отдельный разговор).
        if тень.get("ok") and тень.get("tx_base64_есть"):
            continue
        реш = в.get("решение") or {}
        гр = реш.get("группа") or "группы в записи нет"
        if только and гр not in только:
            continue
        з = по_группе.setdefault(гр, {
            "теней": 0, "прошли_правило": 0, "не_прошли": 0,
            "почему_не_прошли": collections.Counter(),
            "причины_прошедших": collections.Counter(),
            "источники_прошедших": collections.Counter(),
            "минты_прошедших": set()})
        з["теней"] += 1
        да, почему = прошло_правило(реш, порог)
        if not да:
            з["не_прошли"] += 1
            з["почему_не_прошли"][почему] += 1
            continue
        з["прошли_правило"] += 1
        з["причины_прошедших"][причина_строки(в)[:90]] += 1
        з["источники_прошедших"][(реш.get("source") or "?")[:8]] += 1
    из_ = {"порог_sol": порог, "по_группе": {}}
    for гр, з in sorted(по_группе.items(), key=lambda кв: -кв[1]["теней"]):
        из_["по_группе"][гр] = {
            "теней": з["теней"],
            "прошли_правило": з["прошли_правило"],
            "не_прошли": з["не_прошли"],
            "почему_не_прошли": dict(з["почему_не_прошли"].most_common(6)),
            "причины_прошедших": dict(з["причины_прошедших"].most_common(8)),
            "топ3_источника_прошедших": dict(
                з["источники_прошедших"].most_common(3))}
    из_["всего_теней"] = sum(в["теней"] for в in из_["по_группе"].values())
    из_["всего_прошли_правило"] = sum(в["прошли_правило"]
                                       for в in из_["по_группе"].values())
    return из_


def печать(о: dict) -> None:
    с = о.get("свод") or {}
    print(f"ОКНО: {о.get('с')} .. {о.get('до')}; строк просмотрено "
          f"{о.get('строк_просмотрено')}, подписей в окне {о.get('подписей')}")
    if о.get("без_времени"):
        print(f"  записей без времени (в окно не вошли): {о['без_времени']}")
    print(f"ПРАВИЛО: трата источника >= {с.get('порог_sol')} SOL-экв И первый вход")
    print(f"ВСЕГО несобранных теней {с.get('всего_теней')}, из них прошли правило "
          f"{с.get('всего_прошли_правило')}")
    for гр, з in (с.get("по_группе") or {}).items():
        print(f"\n{гр}: теней {з['теней']}, ПРОШЛИ ПРАВИЛО {з['прошли_правило']}, "
              f"не прошли {з['не_прошли']}")
        for п, н in (з.get("причины_прошедших") or {}).items():
            print(f"    упущено {н:>3d}  {п}")
        if з.get("топ3_источника_прошедших"):
            кто = ", ".join(f"{и}×{н}" for и, н
                            in з["топ3_источника_прошедших"].items())
            print(f"    источники упущенных: {кто}")
        for п, н in (з.get("почему_не_прошли") or {}).items():
            print(f"    (не правило) {н:>4d}  {п}")


def _разборщик() -> argparse.ArgumentParser:
    р = argparse.ArgumentParser(description=__doc__)
    р.add_argument("--state-dir", default="/home/bot/bloom_executor_live_data")
    р.add_argument("--s", required=False, default=None, help="начало окна UTC")
    р.add_argument("--po", required=False, default=None, help="конец окна UTC")
    р.add_argument("--porog", type=float, default=ПОРОГ_SOL_ПО_УМОЛЧАНИЮ)
    р.add_argument("--gruppy", default="", help="только эти группы, через запятую")
    р.add_argument("--bez-rotacii", dest="bez_rotacii", action="store_true")
    р.add_argument("--out", default=None)
    р.add_argument("--self-test", dest="self_test", action="store_true")
    return р


def main() -> int:
    а = _разборщик().parse_args()
    if а.self_test:
        return self_test()
    if not а.s or not а.po:
        print("не сделано: нужны --s и --po (окно UTC)")
        return 2
    try:
        с_, по_ = метка(а.s), метка(а.po)
    except Exception as exc:  # noqa: BLE001
        print(f"не сделано: метка окна не разобрана: {exc}")
        return 2
    if по_ <= с_:
        print("не сделано: конец окна не позже начала")
        return 2
    д = собрать(а.state_dir, с_, по_, ротация=not а.bez_rotacii)
    группы = [и.strip() for и in str(а.gruppy).split(",") if и.strip()]
    о = {"что": "несобранные тени, прошедшие правило сигнала",
         "utc": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
         "с": а.s, "до": а.po, "строк_просмотрено": д["просмотрено"],
         "без_времени": д["без_времени"],
         "подписей": len(д["по_подписи"]),
         "только_чтение": True,
         "свод": свод(д, порог=а.porog, группы=группы)}
    печать(о)
    if а.out:
        with open(а.out, "w", encoding="utf-8") as ф:
            json.dump(о, ф, ensure_ascii=False, indent=1)
        print(f"записано: {а.out}")
    return 0


def self_test() -> int:  # noqa: C901
    пройдено = провалено = 0

    def проба(что, ок, факт=None):
        nonlocal пройдено, провалено
        print(f"  [{'ok  ' if ок else 'ПРОВАЛ'}] {что}"
              + (f" -> {факт!r}" if факт is not None and not ок else ""))
        пройдено += bool(ок)
        провалено += (not ок)

    т0 = метка("2026-09-30T10:00:00Z")

    def тень(п, почему, ok=False, есть_tx=False, программа="pAMM"):
        return {"signature": п, "stage": "shadow", "why_not": почему,
                "pool_program": программа, "quote_mint": "So111", "ok": ok,
                "tx_base64": "AAA" if есть_tx else None, "ts": т0}

    def решение(п, трата, первый, группа="lane_s0", источник="ABCDEFGH1"):
        return {"signature": п, "action": "skip", "code": "X", "reason": "y",
                "source": источник, "source_task": группа,
                "spend_sol_eq": трата, "first_entry": первый, "ts": т0}

    записи = [
        # 1. прошёл правило: 3 SOL, первый вход, тень не собралась
        тень("s1", "тип пула не покрыт сборщиком: whirl"), решение("s1", 3.0, True),
        # 2. трата ниже порога -- НЕ упущенная сделка
        тень("s2", "котировка не SOL"), решение("s2", 0.5, True),
        # 3. не первый вход -- НЕ упущенная
        тень("s3", "котировка не SOL"), решение("s3", 9.0, False),
        # 4. трата не определена -- отдельная корзина, НЕ «прошло»
        тень("s4", "шаблон не тот"), решение("s4", None, True),
        # 5. тень СОБРАЛАСЬ -- не потеря вовсе
        тень("s5", None, ok=True, есть_tx=True), решение("s5", 5.0, True),
        # 6. другая группа
        тень("s6", "котировка не SOL"), решение("s6", 4.0, True, группа="batch5"),
        # 7. решения нет вовсе
        тень("s7", "котировка не SOL"),
    ]
    д = {"по_подписи": {}, "просмотрено": len(записи), "без_времени": 0}
    for з in записи:
        в = д["по_подписи"].setdefault(з["signature"], {})
        if з.get("stage") == "shadow":
            в["тень"] = {"why_not": з.get("why_not"),
                          "pool_program": з.get("pool_program"),
                          "quote_mint": з.get("quote_mint"), "route": None,
                          "ok": з.get("ok"), "tx_base64_есть": bool(з.get("tx_base64"))}
        else:
            в["решение"] = {"action": з["action"], "code": з["code"],
                             "reason": з["reason"], "source": з["source"],
                             "группа": з["source_task"], "трата_sol": з["spend_sol_eq"],
                             "первый_вход": з["first_entry"], "kind": None}
    с = свод(д, порог=2.0)
    л = с["по_группе"].get("lane_s0") or {}
    проба("собранная тень в потерю не идёт", "s5" not in json.dumps(с, ensure_ascii=False)
          and л.get("теней") == 4, с)
    проба("прошёл правило ровно один сигнал lane_s0", л.get("прошли_правило") == 1,
          л.get("прошли_правило"))
    проба("причина прошедшего названа",
          any("не покрыт сборщиком" in к for к in (л.get("причины_прошедших") or {})),
          л.get("причины_прошедших"))
    проба("трата ниже порога названа причиной «не правило»",
          any("ниже порога" in к for к in (л.get("почему_не_прошли") or {})),
          л.get("почему_не_прошли"))
    проба("не первый вход назван отдельно",
          any("не первый вход" in к for к in (л.get("почему_не_прошли") or {})))
    проба("неизвестная трата -- НЕ «прошло», а своя корзина",
          any("не определена" in к for к in (л.get("почему_не_прошли") or {})),
          л.get("почему_не_прошли"))
    б = с["по_группе"].get("batch5") or {}
    проба("вторая группа считается отдельно",
          б.get("теней") == 1 and б.get("прошли_правило") == 1, б)
    нгр = с["по_группе"].get("группы в записи нет") or {}
    проба("тень без решения -- в корзину «группы в записи нет», а не в lane_s0",
          нгр.get("теней") == 1 and нгр.get("прошли_правило") == 0, нгр)
    проба("всего прошли правило -- два (по одному в двух группах)",
          с["всего_прошли_правило"] == 2, с["всего_прошли_правило"])
    только = свод(д, порог=2.0, группы=["lane_s0"])
    проба("фильтр групп оставляет только названную",
          list(только["по_группе"]) == ["lane_s0"], list(только["по_группе"]))
    проба("порог -- число из входа, а не из кода",
          свод(д, порог=10.0)["всего_прошли_правило"] == 0,
          свод(д, порог=10.0)["всего_прошли_правило"])
    да, почему = прошло_правило({"трата_sol": 2.0, "первый_вход": True}, 2.0)
    проба("ровно на пороге -- правило пройдено", да is True, почему)
    да2, _ = прошло_правило({}, 2.0)
    проба("решения нет -- правило не пройдено", да2 is False)
    проба("окно с плохой меткой -- отказ, а не ноль",
          _плохая_метка() is True)
    print(f"самопроверка теней по правилу: {пройдено}/{пройдено + провалено} пройдено")
    return 0 if провалено == 0 else 1


def _плохая_метка() -> bool:
    try:
        метка("не метка")
    except Exception:  # noqa: BLE001
        return True
    return False


