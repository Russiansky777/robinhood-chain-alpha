#!/usr/bin/env python3
"""Имена переменных оболочки в прогонах -- только ASCII. Иначе bash отказывает.

ЗАЧЕМ. Я сам чуть не положил в прогон строку `НА_ХОСТЕ=$(...)`: читается
прекрасно, а bash на ней падает с syntax error, потому что имя переменной по
POSIX -- только буквы латиницы, цифры и подчёркивание. Поймать это глазами
нельзя: кириллица в комментариях и в echo по всему репозиторию законна, и взгляд
на ней не спотыкается. Поэтому проверка машинная и стоит рядом с проверкой
кавычек.

Проверяется ТОЛЬКО присваивание в начале строки (NAME=...) -- то есть ровно то
место, где имя обязано быть именем. Кириллица внутри строк, в комментариях, в
значениях и в путях не трогается вовсе.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

ПРИСВАИВАНИЕ = re.compile(r'^\s*([^\s=&|;()<>"\'`$]{1,64})=')


def плохие_имена(текст: str) -> list:
    """Строки, где имя переменной не ASCII. Номера с единицы."""
    из_ = []
    for н, стр in enumerate(текст.splitlines(), 1):
        м = ПРИСВАИВАНИЕ.match(стр)
        if not м:
            continue
        имя = м.group(1)
        # Не присваивание оболочки: ключ YAML (`имя: значение`), сравнение,
        # флаг с дефисом. Берём только то, что похоже на имя переменной.
        if not re.fullmatch(r"[\w]+", имя, flags=re.UNICODE):
            continue
        if not имя.isascii():
            из_.append((н, имя, стр.strip()[:80]))
    return из_


def main() -> int:
    корень = Path(sys.argv[1] if len(sys.argv) > 1 else ".github/workflows")
    файлы = sorted(корень.glob("*.yml")) + sorted(корень.glob("*.yaml"))
    всего = 0
    плохо = []
    for п in файлы:
        всего += 1
        for н, имя, стр in плохие_имена(п.read_text(encoding="utf-8")):
            плохо.append(f"{п.name}:{н}: имя переменной {имя!r} не ASCII -- bash откажет: {стр}")
    print(f"имена переменных в прогонах: проверено файлов {всего}, "
          f"не-ASCII имён {len(плохо)}")
    for с in плохо:
        print("  СБОЙ:", с)
    return 1 if плохо else 0


def self_test() -> int:
    плохо = []

    def chk(имя, усл, факт=""):
        if not усл:
            плохо.append(f"{имя}: {факт}")
        print(("ok   " if усл else "ПЛОХО") + f" {имя}")

    chk("кириллическое имя переменной найдено",
        [и for _, и, _ in плохие_имена("          НА_ХОСТЕ=$(echo 1)")] == ["НА_ХОСТЕ"])
    chk("латинское имя пропускается", плохие_имена("          NA_HOSTE=$(echo 1)") == [])
    chk("кириллица в значении не считается ошибкой",
        плохие_имена('          MSG="строка по-русски"') == [])
    chk("кириллица в комментарии не считается ошибкой",
        плохие_имена("          # это комментарий про НА_ХОСТЕ") == [])
    chk("ключ YAML с кириллицей не считается присваиванием",
        плохие_имена("          описание: что-то") == [])
    chk("echo с кириллицей не ломает проверку",
        плохие_имена('          echo "прежний ключ: длина 5"') == [])
    chk("несколько строк разбираются, номера с единицы",
        [н for н, _, _ in плохие_имена("A=1\nБ=2\nC=3")] == [2])
    print(f"\nитог: {'ВСЁ ОК' if not плохо else 'ОТКАЗ'}; проверок плохих {len(плохо)}")
    for с in плохо:
        print("  -", с)
    return 1 if плохо else 0


if __name__ == "__main__":
    if "--self-test" in sys.argv:
        raise SystemExit(self_test())
    raise SystemExit(main())
