def урл() -> str:
    к = (os.environ.get("HELIUS_API_KEY") or os.environ.get("HELIUS_API") or "").strip()
    return f"{HELIUS}/?api-key={к}"


def зов(метод: str, параметры, *, таймаут: float = 30.0) -> dict:
    import urllib.request  # noqa: PLC0415

    тело = json.dumps({"jsonrpc": "2.0", "id": 1, "method": метод,
                        "params": параметры}).encode()
    зпр = urllib.request.Request(урл(), data=тело,
                                  headers={"Content-Type": "application/json"})
    try:
        with urllib.request.urlopen(зпр, timeout=таймаут) as отв:  # noqa: S310
            о = json.loads(отв.read().decode())
    except Exception as exc:  # noqa: BLE001
        return {"ok": False, "why_not": f"{type(exc).__name__}: {str(exc)[:160]}"}
    if "error" in о:
        return {"ok": False, "why_not": f"RPC: {str(о['error'])[:200]}"}
    return {"ok": True, "result": о.get("result")}


def строки(путь: str):
    открыть = gzip.open if путь.endswith(".gz") else open
    try:
        ф = открыть(путь, "rt", encoding="utf-8", errors="replace")
    except Exception:  # noqa: BLE001
        return
    with ф:
        for стр in ф:
            стр = стр.strip()
            if not стр:
                continue
            try:
                yield json.loads(стр)
            except ValueError:
                continue


def подписи_dlmm(state_dir: str, *, сколько: int) -> list:
    """Подписи сделок источников, где виден пул DLMM. Журнал читается потоком."""
    найдено, видели = [], set()
    пути = sorted(glob.glob(os.path.join(state_dir, "decisions*.jsonl*")),
                   reverse=True)
    for путь in пути:
        for зап in строки(путь):
            строка = json.dumps(зап, ensure_ascii=False)
            if DLMM not in строка:
                continue
            п = зап.get("signature") or зап.get("source_sig")
            if not п or п in видели:
                continue
            видели.add(п)
            найдено.append({"подпись": п, "минт": зап.get("mint"),
                             "источник": зап.get("source"),
                             "stage": зап.get("stage")})
            if len(найдено) >= сколько:
                return найдено
    return найдено


def процентиль(ряд, доля):
    ч = sorted(x for x in ряд if isinstance(x, (int, float)))
    if not ч:
        return None
    м = min(len(ч) - 1, max(0, int(round(доля * (len(ч) - 1)))))
    return ч[м]


def разбор(подпись: str, *, кошелёк: str, лампорты: int, проскальзывание: float,
            симулировать: bool) -> dict:
    из_ = {"подпись": подпись, "байт_в_байт": None, "why_not": None}
    import c2_swap_build as B  # noqa: PLC0415

    о = зов("getTransaction", [подпись, {"encoding": "jsonParsed",
                                          "maxSupportedTransactionVersion": 1,
                                          "commitment": "finalized"}])
    if not о.get("ok") or not о.get("result"):
        из_["why_not"] = f"транзакция не прочиталась: {о.get('why_not')}"
        return из_
    tx = о["result"]
    # ХРАНИЛИЩЕ ПУЛА -- из самой транзакции: ищем инструкцию DLMM и берём её
    # счёт хранилища через mints_and_vaults по шаблону с любым счётом пула.
    инстр = [ix for ix in B.all_instructions(tx) if ix.get("programId") == DLMM]
    if not инстр:
        из_["why_not"] = "инструкции DLMM в транзакции нет"
        return из_
    счета = инстр[0]["accounts"]
    tpl = None
    for кандидат in счета:
        т = B.extract_template(tx, DLMM, кандидат)
        if т.get("ok"):
            tpl = т
            break
    if tpl is None:
        из_["why_not"] = "шаблон инструкции DLMM не восстановился"
        return из_
    из_["пул"] = (tpl.get("accounts") or [None])[0]
    из_["ix"] = tpl.get("ix")
    mv = B.mints_and_vaults(tpl, tx)
    if not mv:
        из_["why_not"] = "минты и хранилища не восстановились"
        return из_
    из_["база"] = mv.get("base_mint")
    # ПОЛЕ НАЗЫВАЕТСЯ минт_котировки, А НЕ котировка: под именем "котировка"
    # ниже лежит РАСЧЁТ котировки (словарь), и прогон 01:33:45Z упал на
    # 'str' object has no attribute 'get' ровно из-за этого столкновения имён.
    из_["минт_котировки"] = mv.get("quote_mint")

    # 1. БАЙТ В БАЙТ: его же аргументы, его же счета.
    # extract_template отдаёт arg0/arg1 ОТДЕЛЬНЫМИ ПОЛЯМИ, а не списком args:
    # прогон 01:33:45Z на tpl["args"] получал KeyError и писал "аргументы
    # инструкции источника не разобрались" на исправной сделке.
    а0, а1 = tpl.get("arg0"), tpl.get("arg1")
    if а0 is None or а1 is None:
        из_["why_not"] = "аргументы инструкции источника не разобрались"
        return из_
    # ПЕРЕСОБИРАЕМ ПОД ЕГО ЖЕ ПОЛЬЗОВАТЕЛЯ, а не под наш кошелёк: только тогда
    # список счетов обязан совпасть с его инструкцией, и сравнение проверяет
    # восстановление РОЛЕЙ счетов, а не переименование нашего кошелька.
    #
    # ПОЛЬЗОВАТЕЛЬ -- СО МЕСТА, КОТОРОЕ НАЗЫВАЕТ СПЕЦИФИКАЦИЯ, а не плательщик
    # транзакции: прогон 01:46:28Z брал accountKeys[0] и получал расхождение на
    # местах 4, 5, 10 -- у этого источника покупку подписывает один ключ, а
    # комиссию платит другой. Для DLMM место пользователя -- 10.
    сообщение = ((tx or {}).get("transaction") or {}).get("message") or {}
    ключи = [(к.get("pubkey") if isinstance(к, dict) else к)
              for к in (сообщение.get("accountKeys") or [])]
    места_пользователя = (B.spec_of(tpl).get("user") or [])
    if места_пользователя and места_пользователя[0] < len(tpl["accounts"]):
        его_user = tpl["accounts"][места_пользователя[0]]
        из_["откуда_пользователь"] = f"место {места_пользователя[0]} по спецификации"
    else:
        его_user = ключи[0] if ключи else кошелёк
        из_["откуда_пользователь"] = "плательщик транзакции (места в спецификации нет)"
    из_["пользователь_источника"] = его_user
    try:
        свой = B.swap_instruction(tpl, tx, его_user, а0, а1, keep_source_ix=True)
    except Exception as exc:  # noqa: BLE001
        из_["why_not"] = f"пересборка упала: {type(exc).__name__}: {str(exc)[:140]}"
        return из_
    свои_байты = bytes(свой.data)
    его_байты = base64.b64decode(инстр[0]["data_b64"]) if инстр[0].get("data_b64") \
        else bytes(tpl["data"])
    свои_счета = [str(м.pubkey) for м in свой.accounts]
    его_счета = list(инстр[0]["accounts"])
    из_["данные_совпали"] = (свои_байты == его_байты)
    из_["счета_совпали"] = (свои_счета == его_счета)
    из_["счетов"] = len(его_счета)
    # БАЙТ В БАЙТ = и данные, и список счетов. Данные при keep_source_ix --
    # это раскладка "дискриминатор + два u64 + хвост", собранная обратно из
    # его же чисел: она проверяет, что раскладка верна и инструкция вообще
    # разобралась, но сама по себе почти тождественна. Настоящая проверка --
    # СЧЕТА: их порядок и роли восстанавливает наш код.
    из_["байт_в_байт"] = bool(из_["данные_совпали"] and из_["счета_совпали"])
    из_["длина_данных"] = len(его_байты)
    из_["что_проверено"] = ("данные: раскладка дискриминатор+2*u64+хвост; "
                             "счета: порядок и роли из нашего user_accounts")
    if not из_["данные_совпали"]:
        из_["данные_его"] = его_байты.hex()[:80]
        из_["данные_наши"] = свои_байты.hex()[:80]
    if not из_["счета_совпали"]:
        из_["счета_расхождение"] = [
            {"i": и, "его": (его_счета[и] if и < len(его_счета) else None),
              "наш": (свои_счета[и] if и < len(свои_счета) else None)}
            for и in range(max(len(его_счета), len(свои_счета)))
            if (его_счета[и] if и < len(его_счета) else None)
            != (свои_счета[и] if и < len(свои_счета) else None)][:6]

    # 1б. ТОЧНАЯ КОТИРОВКА и ЦЕНА ЕЁ ЧТЕНИЙ (слово владельца 29.09, п.2 к
    # докладу): два getMultipleAccounts на горячем пути -- сколько это стоит.
    # ПОПРАВЛЕННЫЙ ШАБЛОН ОБЪЯВЛЕН ЗАРАНЕЕ: ниже он читается в блоке симуляции,
    # и если котировка не посчиталась, обращение к необъявленному имени уронило
    # бы разбор строки целиком вместо честного "поправленного шаблона нет".
    шаблон_поправленный = None
    try:
        import c2_dlmm_tochnaya_kotirovka as K  # noqa: PLC0415

        к = K.котировка(пул=из_["пул"], минт_базы=mv.get("base_mint"),
                         минт_котировки=mv.get("quote_mint"),
                         лампорты=лампорты, проскальзывание=проскальзывание,
                         rpc_call=lambda м, п_: зов(м, п_, таймаут=10.0))
        из_["котировка"] = {к_: к.get(к_) for к_ in
                             ("ok", "why_not", "expected_out", "min_out", "корзин",
                               "массивов", "чтений", "мс_чтение1", "мс_чтение2",
                               "мс_чтений_всего", "bin_step", "swap_for_y")}
        # ГЛАВНЫЙ ВОПРОС ПОСЛЕ ОТКАЗА 3005: массивы корзин в шаблоне -- ТЕ ЖЕ,
        # что нужны СЕЙЧАС, или это массивы того дня? Сравниваем множествами,
        # не зная раскладки структуры: сколько нынешних адресов вообще есть в
        # списке счетов источника.
        адреса_сейчас = list(к.get("массивы_адреса") or [])
        в_шаблоне = [а for а in адреса_сейчас if а in его_счета]
        индексы_сейчас = list(к.get("массивы_индексы") or [])
        из_["массивы"] = {"нужно_сейчас": len(адреса_сейчас),
                           "из_них_в_шаблоне": len(в_шаблоне),
                           "индексы_сейчас": индексы_сейчас[:6],
                           "адреса_сейчас": адреса_сейчас[:4]}
        # ПРЕДЛОЖЕНИЕ ВЛАДЕЛЬЦА (29.09, п.4): если брать адреса массивов из
        # транзакции ИСТОЧНИКА плюс-минус один сосед, пул и массивы читаются
        # ОДНИМ getMultipleAccounts вместо двух -- вопрос только в том, сколько
        # раз такой запас действительно накрывает нужное. Отвечаем числом.
        #
        # ИНДЕКСЫ ИСТОЧНИКА ВОССТАНАВЛИВАЮТСЯ ТОЧНО, а не угадываются: адрес
        # массива -- PDA от пула и индекса, поэтому достаточно перебрать окно
        # индексов вокруг нынешних и посмотреть, какие адреса есть в списке
        # счетов источника.
        индексы_источника: list = []
        адреса_шаблона: list = []
        if индексы_сейчас:
            try:
                Q_ = K._модуль()
                набор_счетов = set(его_счета)
                for и_ in range(min(индексы_сейчас) - ОКНО_ИНДЕКСОВ,
                                 max(индексы_сейчас) + ОКНО_ИНДЕКСОВ + 1):
                    а_ = Q_.адрес_массива(из_["пул"], и_)
                    if а_ in набор_счетов:
                        индексы_источника.append(и_)
                        адреса_шаблона.append(а_)
            except Exception as exc:  # noqa: BLE001
                из_["массивы"]["индексы_источника_why_not"] = (
                    f"{type(exc).__name__}: {str(exc)[:100]}")
        сосед = set()
        for и_ in индексы_источника:
            сосед.update((и_ - 1, и_, и_ + 1))
        нужные = set(индексы_сейчас)
        из_["массивы"].update({
            "индексы_источника": индексы_источника,
            "нужные_индексы": индексы_сейчас,
            "окно_поиска": ОКНО_ИНДЕКСОВ,
            "покрыто_ровно": (bool(нужные) and bool(индексы_источника)
                               and нужные <= set(индексы_источника)),
            "покрыто_плюс_минус_1": (bool(нужные) and bool(индексы_источника)
                                      and нужные <= сосед),
            "не_покрытые_индексы": sorted(нужные - сосед),
            "сдвиг_индексов": ((min(нужные) - min(индексы_источника))
                                if индексы_источника and нужные else None)})
        # ШАБЛОН С НЫНЕШНИМИ МАССИВАМИ. Порядок -- по возрастанию индекса у
        # обоих списков: программа получает массивы в порядке списка счетов, и
        # перепутать их местами значило бы отдать ей не тот массив.
        пары = sorted(zip(индексы_сейчас, адреса_сейчас))
        пр_ = B.шаблон_с_нынешними_массивами(
            tpl, массивы_шаблона=адреса_шаблона,
            массивы_сейчас=[а for _и, а in пары])
        из_["массивы"]["подстановка"] = {
            к_: пр_.get(к_) for к_ in ("ok", "why_not", "массивов_шаблона",
                                        "массивов_сейчас", "подставлено",
                                        "не_влезло", "места")}
        шаблон_поправленный = пр_.get("шаблон")
    except Exception as exc:  # noqa: BLE001
        из_["котировка"] = {"ok": False,
                             "why_not": f"{type(exc).__name__}: {str(exc)[:140]}"}
        шаблон_поправленный = None

    # 2. НАША сборка и (по просьбе) симуляция.
    try:
        сб = B.build_buy(tpl, tx, user=кошелёк, payer=кошелёк, amount_in=лампорты,
                          min_out=1, cu_price_micro=100_000, tip=None)
    except Exception as exc:  # noqa: BLE001
        сб = None
        из_["наша_сборка_why_not"] = f"{type(exc).__name__}: {str(exc)[:140]}"
    из_["наша_сборка_ok"] = isinstance(сб, dict) and bool(сб.get("tx_base64"))
    if isinstance(сб, dict):
        из_["наша_сборка"] = {к_: сб.get(к_) for к_ in ("size", "n_instructions")}
    # СТРУКТУРНОЕ СРАВНЕНИЕ БОЕВОЙ ВЕТКИ СБОРКИ (keep_source_ix=False): столько
    # же счетов и столько же байт данных, сколько у источника, или нет. Это
    # отвечает на вопрос "не хватило ключей" без всякой симуляции.
    try:
        боевая = B.swap_instruction(tpl, tx, кошелёк, лампорты, 1, keep_source_ix=False)
        из_["боевая_ветка"] = {
            "счетов": len(боевая.accounts), "счетов_у_источника": len(его_счета),
            "байт": len(bytes(боевая.data)), "байт_у_источника": len(его_байты),
            "счетов_совпало": len(боевая.accounts) == len(его_счета),
            "байт_совпало": len(bytes(боевая.data)) == len(его_байты)}
    except Exception as exc:  # noqa: BLE001
        из_["боевая_ветка"] = {"why_not": f"{type(exc).__name__}: {str(exc)[:140]}"}

    if симулировать:
        tx64 = сб if isinstance(сб, str) else (сб or {}).get("tx_base64")
        if not tx64:
            из_["симуляция"] = {"ok": False, "why_not": "нашей транзакции нет"}
        else:
            с = зов("simulateTransaction",
                     [tx64, {"sigVerify": False, "replaceRecentBlockhash": True,
                              "encoding": "base64", "commitment": "processed"}])
            зн = ((с.get("result") or {}).get("value") or {}) if с.get("ok") else {}
            из_["симуляция"] = {"ok": с.get("ok"), "err": зн.get("err"),
                                 "cu": зн.get("unitsConsumed"),
                                 "why_not": с.get("why_not"),
                                 "логи_хвост": (зн.get("logs") or [])[-4:]}
        # А/Б: ТА ЖЕ НАША СБОРКА, НО ПОД ЕГО ПОЛЬЗОВАТЕЛЯ. Разделяет две
        # причины отказа: наша подстановка счетов (тогда эта пройдёт, а наша
        # нет) или наша ветка данных и скелет транзакции (тогда обе упадут).
        try:
            сб_его = B.build_buy(tpl, tx, user=его_user, payer=его_user,
                                  amount_in=лампорты, min_out=1,
                                  cu_price_micro=100_000, tip=None)
        except Exception as exc:  # noqa: BLE001
            сб_его = None
            из_["симуляция_под_него"] = {"ok": False,
                                          "why_not": f"{type(exc).__name__}: {str(exc)[:140]}"}
        if isinstance(сб_его, dict) and сб_его.get("tx_base64"):
            с2 = зов("simulateTransaction",
                      [сб_его["tx_base64"],
                        {"sigVerify": False, "replaceRecentBlockhash": True,
                         "encoding": "base64", "commitment": "processed"}])
            зн2 = ((с2.get("result") or {}).get("value") or {}) if с2.get("ok") else {}
            из_["симуляция_под_него"] = {"ok": с2.get("ok"), "err": зн2.get("err"),
                                          "cu": зн2.get("unitsConsumed"),
                                          "why_not": с2.get("why_not"),
                                          "логи_хвост": (зн2.get("logs") or [])[-4:]}
        # ГЛАВНАЯ ПРОВЕРКА ПРАВКИ: та же наша сборка, но с массивами корзин из
        # НЫНЕШНЕГО состояния пула. Если дело было в устаревших массивах, здесь
        # ошибки не будет, а в двух симуляциях выше она останется.
        if шаблон_поправленный is None:
            из_["симуляция_с_массивами"] = {
                "ok": False,
                "why_not": ((из_.get("массивы") or {}).get("подстановка") or {}).get(
                    "why_not") or "поправленного шаблона нет"}
        else:
            try:
                сб_м = B.build_buy(шаблон_поправленный, tx, user=кошелёк,
                                    payer=кошелёк, amount_in=лампорты, min_out=1,
                                    cu_price_micro=100_000, tip=None)
            except Exception as exc:  # noqa: BLE001
                сб_м = None
                из_["симуляция_с_массивами"] = {
                    "ok": False, "why_not": f"{type(exc).__name__}: {str(exc)[:140]}"}
            if isinstance(сб_м, dict) and сб_м.get("tx_base64"):
                с3 = зов("simulateTransaction",
                          [сб_м["tx_base64"],
                            {"sigVerify": False, "replaceRecentBlockhash": True,
                             "encoding": "base64", "commitment": "processed"}])
                зн3 = ((с3.get("result") or {}).get("value") or {}) if с3.get("ok") else {}
                из_["симуляция_с_массивами"] = {
                    "ok": с3.get("ok"), "err": зн3.get("err"),
                    "cu": зн3.get("unitsConsumed"), "why_not": с3.get("why_not"),
                    "логи_хвост": (зн3.get("logs") or [])[-4:]}
    return из_


