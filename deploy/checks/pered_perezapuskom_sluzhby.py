#!/usr/bin/env python3
"""Можно ли перезапускать СЛУЖБУ прямо сейчас. Только чтение.

Это НЕ проверка перед перезагрузкой хоста (та -- pered_perezagruzkoy.py, и она
по-прежнему требует стоящий рубильник KILL, потому что перезагрузка уносит
сторожа вместе с хостом). Здесь речь о перезапуске одной службы на работающем
хосте: детектор держит политику групп источников в кэше и перечитывает файл
только при старте, а править потолок группы днём нужно.

Условия, и они про деньги, а не про удобство:
  * открытых позиций 0 -- по ВСЕМ группам полосы: позиция в воздухе на время
    перезапуска остаётся без своего сторожа. Это условие не пропускается ничем;
  * зависших 0 -- с одним НАЗВАННЫМ разовым исключением (вход прогона
    ZAVISSHIE_FANTOMY=yes) для фантомов: позиций, у которых токена на цепи уже
    нет, и которые держат деплой той самой починки, что их и закроет;
  * признак жизни детектора не старше 10 минут -- иначе числам о позициях
    верить нельзя вовсе;
  * рубильник продаж KILL_SELL НЕ стоит -- иначе после перезапуска купленное
    некому продать;
  * у СТОРОЖА загружен модуль второго мнения (правило 4). Слово владельца
    01.10, ночь: "без модуля как раньше" -- не режим, а ошибка. Живой случай
    того же вечера: позиция полосы на 0.1 SOL висела в UNSOLD, а пул своим
    строителем никто не спрашивал, и снаружи это выглядело обычным отказом по
    доле от входа. Перезапускать службу в такое состояние нельзя.
Рубильник покупок здесь не требуется: покупок в полёте нет (позиций 0), а
останавливать всю торговлю ради чтения одного числа из файла -- дороже, чем
польза от правки.

Выход 0 -- можно; иное -- нельзя, и причина напечатана словами.
"""
import json
import os
import time

ПРИЗНАК = "/home/bot/bloom_executor_live_data/detector_status.json"
ПРИЗНАК_СТОРОЖА = "/home/bot/bloom_executor_live_data/seller_heartbeat.json"
РУБИЛЬНИК_ПРОДАЖ = "/etc/bloom-executor/KILL_SELL"
ПРЕДЕЛ_ВОЗРАСТА_S = 600


def решение_по_второму_мнению(ст: dict, *, разрешено: bool) -> dict:
    """Пускать ли деплой по полю vtoroe_mnenie.module признака жизни сторожа.

    Чистая функция: ни файлов, ни окружения. Вынесена из main РОВНО потому, что
    в main она была написана ветками и УПАЛА на живом деплое 01.10 23:48:25Z:

        вм = ст.get("vtoroe_mnenie")
        if not isinstance(вм, dict) or "module" not in вм:
            if разрешено: print("РАЗРЕШЕНО ОДИН РАЗ: ...")   # нет выхода
            else: return 6
        if вм.get("module") is not True:                     # вм is None
            AttributeError: 'NoneType' object has no attribute 'get'

    Разовое разрешение печаталось и ТУТ ЖЕ падало на проверке того поля, чьё
    отсутствие само и разрешало. Гейт при этом вернул не "СТОП" и не "МОЖНО", а
    трассировку -- то есть сломался ровно в той ветке, которая и существует для
    первого деплоя. Самопроверки у него не было вовсе, и поэтому ветка ни разу
    не проверялась: тот же тихий зелёный, только наоборот.

    ФАЙЛА НЕТ ИЛИ ПОЛЯ НЕТ -- ЭТО СТОП, а не "наверное всё хорошо": поле
    появляется только у сторожа С правкой, и его отсутствие значит ровно то, от
    чего гейт и ставится. Разрешение разовое, явное и громкое, его ставит человек
    входом прогона.
    """
    вм = (ст or {}).get("vtoroe_mnenie")
    if not isinstance(вм, dict) or "module" not in вм:
        if разрешено:
            return {"можно": True, "поле_было": False, "строка": (
                "РАЗРЕШЕНО ОДИН РАЗ: поля vtoroe_mnenie.module в признаке "
                "сторожа нет, потому что правку оно и привозит. После этого "
                "перезапуска поле ОБЯЗАНО появиться -- иначе следующий деплой "
                "встанет здесь же.")}
        return {"можно": False, "поле_было": False, "строка": (
            "СТОП: в признаке жизни сторожа нет поля vtoroe_mnenie.module -- "
            "это сторож БЕЗ правки видимости правила 4. Разово пропустить: "
            "вход прогона VTOROE_MNENIE_PERVYJ_DEPLOJ=yes")}
    if вм.get("module") is not True:
        # ПОЛЕ ЕСТЬ И ОНО НЕ True -- РАЗОВОЕ РАЗРЕШЕНИЕ ЗДЕСЬ НЕ ДЕЙСТВУЕТ.
        # Оно дано ради отсутствия поля (курица и яйцо), а не ради выключенного
        # правила: модуль не загрузился -- это ошибка, и её разрешать нечем.
        return {"можно": False, "поле_было": True, "строка": (
            "СТОП: модуль второго мнения у сторожа НЕ загружен"
            + (f" ({вм.get('why_not')})" if вм.get("why_not") else "")
            + " -- правило 4 не ходит, перезапуск отменён")}
    return {"можно": True, "поле_было": True,
             "строка": "второе мнение: модуль загружен"}


def self_test() -> int:
    плохо = []

    def chk(имя, усл, факт=""):
        print(("ok    " if усл else "ПЛОХО ") + имя + ("" if усл else f" -> {факт!r}"))
        if not усл:
            плохо.append(имя)

    # ЖИВОЙ СЛУЧАЙ, НА КОТОРОМ ГЕЙТ УПАЛ: поля нет И разрешение стоит.
    р = решение_по_второму_мнению({}, разрешено=True)
    chk("поля нет + разрешено -- МОЖНО, и без падения", р["можно"] is True, р)
    chk("и сказано, что поле ОБЯЗАНО появиться после перезапуска",
        "ОБЯЗАНО появиться" in р["строка"], р)
    р = решение_по_второму_мнению({}, разрешено=False)
    chk("поля нет без разрешения -- СТОП", р["можно"] is False, р)
    chk("и назван вход, которым это пропускают",
        "VTOROE_MNENIE_PERVYJ_DEPLOJ=yes" in р["строка"], р)
    р = решение_по_второму_мнению({"vtoroe_mnenie": {"module": True}},
                                   разрешено=False)
    chk("модуль загружен -- МОЖНО без всяких разрешений", р["можно"] is True, р)
    р = решение_по_второму_мнению(
        {"vtoroe_mnenie": {"module": False, "why_not": "ImportError"}},
        разрешено=True)
    chk("модуль НЕ загружен -- СТОП, и разовое разрешение тут НЕ действует",
        р["можно"] is False and р["поле_было"] is True, р)
    chk("и причина отсутствия модуля напечатана",
        "ImportError" in р["строка"], р)
    р = решение_по_второму_мнению({"vtoroe_mnenie": None}, разрешено=True)
    chk("поле есть, но None -- как «поля нет», и тоже без падения",
        р["можно"] is True and р["поле_было"] is False, р)
    р = решение_по_второму_мнению({"vtoroe_mnenie": {"why_not": "x"}},
                                   разрешено=False)
    chk("словарь без ключа module -- «поля нет»", р["можно"] is False, р)
    р = решение_по_второму_мнению(None, разрешено=False)
    chk("признака жизни нет вовсе -- СТОП, без падения", р["можно"] is False, р)
    print(f"\nсамопроверка гейта перезапуска: {'ВСЁ ОК' if not плохо else 'ОТКАЗ'}; "
          f"проверок плохих {len(плохо)}")
    return 1 if плохо else 0


def main() -> int:
    try:
        возраст = time.time() - os.path.getmtime(ПРИЗНАК)
        с = json.load(open(ПРИЗНАК, encoding="utf-8"))
    except Exception as exc:  # noqa: BLE001
        print(f"СТОП: признак жизни не прочитан ({type(exc).__name__})")
        return 3
    if возраст > ПРЕДЕЛ_ВОЗРАСТА_S:
        print(f"СТОП: признаку жизни {возраст:.0f} с при пределе {ПРЕДЕЛ_ВОЗРАСТА_S}")
        return 3
    if os.path.exists(РУБИЛЬНИК_ПРОДАЖ):
        print("СТОП: стоит рубильник продаж -- после перезапуска купленное "
              "некому продать")
        return 5
    своя = (с.get("own_send") or {})
    группы = своя.get("lane_state_by_group") or {}
    состояния = list(группы.values()) if группы else [своя.get("lane_state") or {}]
    открытых = sum(int(х.get("open") or 0) for х in состояния)
    зависших = sum(int(х.get("stuck") or 0) for х in состояния)
    имена = list(группы) or ["деньги"]
    print(f"признак жизни: {возраст:.0f} с назад; группы {имена}; "
          f"открытых {открытых}, зависших {зависших}")
    if открытых:
        # ОТКРЫТАЯ ПОЗИЦИЯ НЕ ПРОПУСКАЕТСЯ НИКОГДА И НИЧЕМ. Она в воздухе, у неё
        # живой токен и живой срок продажи: перезапуск оставляет её без сторожа.
        print("СТОП: есть открытые позиции -- перезапуск отменён")
        return 4
    if зависших:
        # ЗАВИСШАЯ -- ТОЖЕ СТОП, НО У НЕГО ЕСТЬ НАЗВАННОЕ РАЗОВОЕ ИСКЛЮЧЕНИЕ, и
        # ставит его ЧЕЛОВЕК входом прогона. Причина -- замкнутый круг, найденный
        # 01.10 ночью: зависшая позиция, у которой токена на цепи УЖЕ НЕТ
        # (продана разовым прогоном, спасением, вручную), не закрывалась сама,
        # потому что служба подставляла lane_bought_raw вместо нуля и ветка
        # "продавать нечего" становилась недостижимой. Починка этого лежит в
        # самой службе -- но доехать она может только деплоем, а деплой держит
        # эта же зависшая позиция. Живой счёт круга: BTN (B5uMacHv) продана в
        # 21:58:35Z, счёт закрыт в 22:32Z, а в 23:19:09Z служба всё ещё читала
        # 497409866807 и сделала 2113 попыток; продавец вышел за суточный бюджет
        # Helius (15098 из 15000).
        #
        # ПОЧЕМУ ИСКЛЮЧЕНИЕ РУЧНОЕ, А НЕ АВТОМАТИЧЕСКОЕ. Гейт мог бы сам читать
        # цепь по каждой зависшей и решать, фантом она или нет. Но тогда у гейта
        # появляется свой узел и свой отказ сети, и "узел не ответил" однажды
        # прочитается как "можно". Пропуск проверки, которая про деньги, -- это
        # решение человека, и оно должно быть видно словами в журнале прогона.
        if (os.environ.get("ZAVISSHIE_FANTOMY") or "").strip() == "yes":
            print(f"РАЗРЕШЕНО ОДИН РАЗ: зависших {зависших}, открытых 0. "
                  "Человек подтвердил, что токена этих позиций на цепи нет и "
                  "держать деплой им нечем. После перезапуска служба с правкой "
                  "ОБЯЗАНА их закрыть веткой «продавать нечего» -- если они "
                  "останутся, следующий деплой встанет здесь же.")
        else:
            print(f"СТОП: зависших позиций {зависших} -- перезапуск отменён. "
                  "Если по цепи токена у них нет вовсе (фантом), разово "
                  "пропустить: вход прогона ZAVISSHIE_FANTOMY=yes")
            return 4
    # ВТОРОЕ МНЕНИЕ -- ОБЯЗАТЕЛЬНОЕ УСЛОВИЕ «МОЖНО». Признак жизни сторожа
    # читается ОТДЕЛЬНО от признака детектора: это разные службы и разные файлы,
    # и молча взять одно за другое значило бы проверить не то.
    #
    # ФАЙЛА НЕТ ИЛИ ПОЛЯ НЕТ -- ЭТО ТОЖЕ СТОП, а не "наверное всё хорошо":
    # поле появляется только у сторожа С ЭТОЙ правкой, и его отсутствие значит
    # ровно то, от чего гейт и ставится -- на хосте сторож, который мог тихо
    # работать без правила 4.
    try:
        возраст_ст = time.time() - os.path.getmtime(ПРИЗНАК_СТОРОЖА)
        ст = json.load(open(ПРИЗНАК_СТОРОЖА, encoding="utf-8"))
    except Exception as exc:  # noqa: BLE001
        print(f"СТОП: признак жизни СТОРОЖА не прочитан ({type(exc).__name__}) -- "
              "загружен ли модуль второго мнения, проверить нечем")
        return 6
    if возраст_ст > ПРЕДЕЛ_ВОЗРАСТА_S:
        print(f"СТОП: признаку жизни сторожа {возраст_ст:.0f} с при пределе "
              f"{ПРЕДЕЛ_ВОЗРАСТА_S} -- числам о правиле 4 верить нельзя")
        return 6
    реш = решение_по_второму_мнению(ст, разрешено=(
        (os.environ.get("VTOROE_MNENIE_PERVYJ_DEPLOJ") or "").strip() == "yes"))
    print(реш["строка"])
    if not реш["можно"]:
        return 6
    # СТРОКА «МОЖНО» НЕ ДОЛЖНА ВРАТЬ. Прежняя печатала "зависших 0" всегда, и
    # с разовым исключением это стало бы неправдой в журнале прогона.
    print(f"МОЖНО: открытых 0, зависших {зависших}"
          + (" (разовое исключение ZAVISSHIE_FANTOMY=yes)" if зависших else "")
          + ", признак свежий, продажи разрешены, модуль второго мнения загружен")
    return 0


if __name__ == "__main__":
    import sys

    raise SystemExit(self_test() if "--self-test" in sys.argv else main())
