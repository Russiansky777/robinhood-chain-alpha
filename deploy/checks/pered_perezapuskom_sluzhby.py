def main() -> int:
    try:
        возраст = time.time() - os.path.getmtime(ПРИЗНАК)
        с = json.load(open(ПРИЗНАК, encoding="utf-8"))
    except Exception as exc:  # noqa: BLE001
        print(f"СТОП: признак жизни не прочитан ({type(exc).__name__})")
        return 3
    if возраст > ПРЕДЕЛ_ВОЗРАСТА_S:
        print(f"СТОП: признаку жизни {возраст:.0f} с при пределе {ПРЕДЕЛ_ВОЗРАСТА_S}")
        return 3
    можно_имена, почему_имена = обязательные_имена()
    if not можно_имена:
        print(f"СТОП: {почему_имена}")
        return 6
    print(почему_имена)
    if os.path.exists(РУБИЛЬНИК_ПРОДАЖ):
        print("СТОП: стоит рубильник продаж -- после перезапуска купленное "
              "некому продать")
        return 5
    своя = (с.get("own_send") or {})
    группы = своя.get("lane_state_by_group") or {}
    состояния = list(группы.values()) if группы else [своя.get("lane_state") or {}]
    открытых = sum(int(х.get("open") or 0) for х in состояния)
    зависших = sum(int(х.get("stuck") or 0) for х in состояния)
    имена = list(группы) or ["деньги"]
    print(f"признак жизни: {возраст:.0f} с назад; группы {имена}; "
          f"открытых {открытых}, зависших {зависших}")
    if открытых:
        # ОТКРЫТАЯ ПОЗИЦИЯ НЕ ПРОПУСКАЕТСЯ НИКОГДА И НИЧЕМ. Она в воздухе, у неё
        # живой токен и живой срок продажи: перезапуск оставляет её без сторожа.
        print("СТОП: есть открытые позиции -- перезапуск отменён")
        return 4
    if зависших:
        # ЗАВИСШАЯ -- ТОЖЕ СТОП, НО У НЕГО ЕСТЬ НАЗВАННОЕ РАЗОВОЕ ИСКЛЮЧЕНИЕ, и
        # ставит его ЧЕЛОВЕК входом прогона. Причина -- замкнутый круг, найденный
        # 01.10 ночью: зависшая позиция, у которой токена на цепи УЖЕ НЕТ
        # (продана разовым прогоном, спасением, вручную), не закрывалась сама,
        # потому что служба подставляла lane_bought_raw вместо нуля и ветка
        # "продавать нечего" становилась недостижимой. Починка этого лежит в
        # самой службе -- но доехать она может только деплоем, а деплой держит
        # эта же зависшая позиция. Живой счёт круга: BTN (B5uMacHv) продана в
        # 21:58:35Z, счёт закрыт в 22:32Z, а в 23:19:09Z служба всё ещё читала
        # 497409866807 и сделала 2113 попыток; продавец вышел за суточный бюджет
        # Helius (15098 из 15000).
        #
        # ПОЧЕМУ ИСКЛЮЧЕНИЕ РУЧНОЕ, А НЕ АВТОМАТИЧЕСКОЕ. Гейт мог бы сам читать
        # цепь по каждой зависшей и решать, фантом она или нет. Но тогда у гейта
        # появляется свой узел и свой отказ сети, и "узел не ответил" однажды
        # прочитается как "можно". Пропуск проверки, которая про деньги, -- это
        # решение человека, и оно должно быть видно словами в журнале прогона.
        if (os.environ.get("ZAVISSHIE_FANTOMY") or "").strip() == "yes":
            print(f"РАЗРЕШЕНО ОДИН РАЗ: зависших {зависших}, открытых 0. "
                  "Человек подтвердил, что токена этих позиций на цепи нет и "
                  "держать деплой им нечем. После перезапуска служба с правкой "
                  "ОБЯЗАНА их закрыть веткой «продавать нечего» -- если они "
                  "останутся, следующий деплой встанет здесь же.")
        else:
            print(f"СТОП: зависших позиций {зависших} -- перезапуск отменён. "
                  "Если по цепи токена у них нет вовсе (фантом), разово "
                  "пропустить: вход прогона ZAVISSHIE_FANTOMY=yes")
            return 4
    # ВТОРОЕ МНЕНИЕ -- ОБЯЗАТЕЛЬНОЕ УСЛОВИЕ «МОЖНО». Признак жизни сторожа
    # читается ОТДЕЛЬНО от признака детектора: это разные службы и разные файлы,
    # и молча взять одно за другое значило бы проверить не то.
    #
    # ФАЙЛА НЕТ ИЛИ ПОЛЯ НЕТ -- ЭТО ТОЖЕ СТОП, а не "наверное всё хорошо":
    # поле появляется только у сторожа С ЭТОЙ правкой, и его отсутствие значит
    # ровно то, от чего гейт и ставится -- на хосте сторож, который мог тихо
    # работать без правила 4.
    try:
        возраст_ст = time.time() - os.path.getmtime(ПРИЗНАК_СТОРОЖА)
        ст = json.load(open(ПРИЗНАК_СТОРОЖА, encoding="utf-8"))
    except Exception as exc:  # noqa: BLE001
        print(f"СТОП: признак жизни СТОРОЖА не прочитан ({type(exc).__name__}) -- "
              "загружен ли модуль второго мнения, проверить нечем")
        return 6
    if возраст_ст > ПРЕДЕЛ_ВОЗРАСТА_S:
        print(f"СТОП: признаку жизни сторожа {возраст_ст:.0f} с при пределе "
              f"{ПРЕДЕЛ_ВОЗРАСТА_S} -- числам о правиле 4 верить нельзя")
        return 6
    реш = решение_по_второму_мнению(ст, разрешено=(
        (os.environ.get("VTOROE_MNENIE_PERVYJ_DEPLOJ") or "").strip() == "yes"))
    print(реш["строка"])
    if not реш["можно"]:
        return 6
    # СТРОКА «МОЖНО» НЕ ДОЛЖНА ВРАТЬ. Прежняя печатала "зависших 0" всегда, и
    # с разовым исключением это стало бы неправдой в журнале прогона.
    print(f"МОЖНО: открытых 0, зависших {зависших}"
          + (" (разовое исключение ZAVISSHIE_FANTOMY=yes)" if зависших else "")
          + ", признак свежий, продажи разрешены, модуль второго мнения загружен")
    return 0


