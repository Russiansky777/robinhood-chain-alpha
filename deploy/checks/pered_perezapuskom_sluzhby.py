#!/usr/bin/env python3
"""Можно ли перезапускать СЛУЖБУ прямо сейчас. Только чтение.

Это НЕ проверка перед перезагрузкой хоста (та -- pered_perezagruzkoy.py, и она
по-прежнему требует стоящий рубильник KILL, потому что перезагрузка уносит
сторожа вместе с хостом). Здесь речь о перезапуске одной службы на работающем
хосте: детектор держит политику групп источников в кэше и перечитывает файл
только при старте, а править потолок группы днём нужно.

Условия, и они про деньги, а не про удобство:
  * открытых позиций 0 и зависших 0 -- по ВСЕМ группам полосы: позиция в
    воздухе на время перезапуска остаётся без своего сторожа;
  * признак жизни детектора не старше 10 минут -- иначе числам о позициях
    верить нельзя вовсе;
  * рубильник продаж KILL_SELL НЕ стоит -- иначе после перезапуска купленное
    некому продать.
Рубильник покупок здесь не требуется: покупок в полёте нет (позиций 0), а
останавливать всю торговлю ради чтения одного числа из файла -- дороже, чем
польза от правки.

Выход 0 -- можно; иное -- нельзя, и причина напечатана словами.
"""
import json
import os
import time

ПРИЗНАК = "/home/bot/bloom_executor_live_data/detector_status.json"
РУБИЛЬНИК_ПРОДАЖ = "/etc/bloom-executor/KILL_SELL"
ПРЕДЕЛ_ВОЗРАСТА_S = 600


def main() -> int:
    try:
        возраст = time.time() - os.path.getmtime(ПРИЗНАК)
        с = json.load(open(ПРИЗНАК, encoding="utf-8"))
    except Exception as exc:  # noqa: BLE001
        print(f"СТОП: признак жизни не прочитан ({type(exc).__name__})")
        return 3
    if возраст > ПРЕДЕЛ_ВОЗРАСТА_S:
        print(f"СТОП: признаку жизни {возраст:.0f} с при пределе {ПРЕДЕЛ_ВОЗРАСТА_S}")
        return 3
    if os.path.exists(РУБИЛЬНИК_ПРОДАЖ):
        print("СТОП: стоит рубильник продаж -- после перезапуска купленное "
              "некому продать")
        return 5
    своя = (с.get("own_send") or {})
    группы = своя.get("lane_state_by_group") or {}
    состояния = list(группы.values()) if группы else [своя.get("lane_state") or {}]
    открытых = sum(int(х.get("open") or 0) for х in состояния)
    зависших = sum(int(х.get("stuck") or 0) for х in состояния)
    имена = list(группы) or ["деньги"]
    print(f"признак жизни: {возраст:.0f} с назад; группы {имена}; "
          f"открытых {открытых}, зависших {зависших}")
    if открытых or зависших:
        print("СТОП: есть открытые или зависшие позиции -- перезапуск отменён")
        return 4
    print("МОЖНО: позиций 0, зависших 0, признак свежий, продажи разрешены")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
