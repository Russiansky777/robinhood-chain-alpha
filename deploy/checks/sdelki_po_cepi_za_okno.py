def _tx(*, ликв: int, минты: dict, слот: int, время: int, кошелёк: str = "W",
         комиссия: int = 5000, рента: int = 0) -> dict:
    """Транзакция ровно с теми полями, по которым считает проверка."""
    до_т, после_т = [], []
    for и, (минт, (до, после)) in enumerate(минты.items(), start=1):
        до_т.append({"owner": кошелёк, "accountIndex": и, "mint": минт,
                      "uiTokenAmount": {"amount": str(до)}})
        после_т.append({"owner": кошелёк, "accountIndex": и, "mint": минт,
                         "uiTokenAmount": {"amount": str(после)}})
    счетов = 1 + len(минты)
    до_б = [1_000_000_000] + [0] * len(минты)
    после_б = [1_000_000_000 + ликв] + [рента] * len(минты)
    return {"slot": слот, "blockTime": время,
             "transaction": {"message": {"accountKeys": [кошелёк]
                                          + [f"ATA{и}" for и in range(1, счетов)]}},
             "meta": {"err": None, "fee": комиссия,
                       "preBalances": до_б, "postBalances": после_б,
                       "preTokenBalances": до_т, "postTokenBalances": после_т}}


def self_test() -> int:
    всего = сбоев = 0

    def chk(что, ок, факт=None):
        nonlocal всего, сбоев
        всего += 1
        if ок:
            print(f"  [ok  ] {что}")
        else:
            сбоев += 1
            print(f"  [СБОЙ] {что}" + (f" -> {факт!r}" if факт is not None else ""))

    W = "W"
    покупка = _tx(ликв=-10_005_000, минты={"M1": (0, 1000)}, слот=100, время=1000,
                   рента=2_039_280)
    продажа = _tx(ликв=+10_600_000, минты={"M1": (1000, 0)}, слот=112, время=1003)
    контроль = _tx(ликв=-5_000, минты={}, слот=101, время=1001)
    chk("покупка узнаётся по цепи: минт пришёл, SOL ушёл",
        вид_транзакции(покупка, W)["вид"] == "покупка",
        вид_транзакции(покупка, W))
    chk("продажа узнаётся: минт ушёл, SOL пришёл",
        вид_транзакции(продажа, W)["вид"] == "продажа")
    chk("транзакция без минтов -- не сделка, и так и названа",
        вид_транзакции(контроль, W)["вид"] == "прочее")
    chk("рента счёта названа отдельно от ликвидных денег",
        abs((вид_транзакции(покупка, W)["рента_sol"] or 0) - 0.00203928) < 1e-9,
        вид_транзакции(покупка, W)["рента_sol"])

    # --- ГЛАВНОЕ: ЖУРНАЛ ПУСТ, А НА ЦЕПИ ПОКУПКА. Ровно случай 01.10: по кодам
    # журнала ничего не видно, позиция уже закрыта, а сделка была.
    ц = {"цепь_ответила": True, "подписей_в_окне": 3, "прочитано": 3,
          "не_прочитано": 0, "прочее": 1, "странности": [],
          "покупки": [dict(вид_транзакции(покупка, W), подпись="SIG_BUY")],
          "продажи": [dict(вид_транзакции(продажа, W), подпись="SIG_SELL")]}
    о = проверить(кошелёк=W, с_ts=900, по_ts=1100, цепь=ц,
                   журнал={"позиций": 0, "по_группам": {}, "почему_нет": None})
    chk("цепь говорит 1 покупку -- вердикт по цепи, а не по пустому журналу",
        о["вердикт"] == "сделок 1" and о["покупок_по_цепи"] == 1, о["вердикт"])
    chk("расхождение с записями названо числом",
        "цепь: покупок 1" in (о.get("расхождение") or ""), о.get("расхождение"))
    п = о["пары"][0]
    chk("ушло и вернулось -- ликвидные деньги кошелька, итог их разность",
        abs(п["ушло_sol"] - 0.010005) < 1e-9
        and abs(п["вернулось_sol"] - 0.0106) < 1e-9
        and abs(п["итог_sol"] - 0.000595) < 1e-9, п)
    chk("продано ровно купленное -- проверено числами, а не словом",
        п["куплено"] == 1000 and п["продано"] == 1000
        and п["количество_сошлось"] is True, п)
    chk("удержание считается слотами цепи",
        п["удержание_слотов"] == 12, п["удержание_слотов"])

    # --- ПРОДАНО НЕ ВСЁ: пара обязана сказать об этом, а не промолчать.
    продажа_часть = _tx(ликв=+5_000_000, минты={"M1": (1000, 400)}, слот=112,
                         время=1003)
    ц2 = dict(ц, продажи=[dict(вид_транзакции(продажа_часть, W), подпись="S2")])
    п2 = проверить(кошелёк=W, с_ts=900, по_ts=1100, цепь=ц2,
                    журнал={"позиций": 1})["пары"][0]
    chk("продано меньше купленного -- количество НЕ сошлось",
        п2["продано"] == 600 and п2["количество_сошлось"] is False, п2)

    # --- ЦЕПЬ МОЛЧИТ -- "НЕ ЗНАЮ", А НЕ НОЛЬ. Это и есть правка 01.10.
    тихо = {"цепь_ответила": False, "почему_не_ответила": "узел не отдал список",
             "подписей_в_окне": 0, "прочитано": 0, "не_прочитано": 0,
             "прочее": 0, "странности": [], "покупки": [], "продажи": []}
    о3 = проверить(кошелёк=W, с_ts=900, по_ts=1100, цепь=тихо,
                    журнал={"позиций": 0})
    chk("цепь не ответила -- вердикт «не знаю» с причиной, а не «сделок не было»",
        о3["вердикт"] == "не знаю" and "узел не отдал список" in (о3["почему"] or ""),
        о3)
    о4 = проверить(кошелёк=W, с_ts=900, по_ts=1100,
                    цепь={"цепь_ответила": True, "почему_не_ответила": None,
                          "подписей_в_окне": 2, "прочитано": 2, "не_прочитано": 0,
                          "прочее": 2, "странности": [], "покупки": [],
                          "продажи": []},
                    журнал={"позиций": 0})
    chk("цепь ответила и покупок нет -- только тогда «сделок не было»",
        о4["вердикт"] == "сделок не было"
        and "ни одной покупки" in (о4["почему"] or ""), о4)

    # --- НЕ ДОЧИТАЛИ ДО ОКНА -- тоже "не знаю": самая старая подпись новее
    # начала окна. Иначе короткое окно истории читалось бы как тишина.
    было = P11.подписи_кошелька
    try:
        P11.подписи_кошелька = lambda к, **кв: {
            "записи": [{"signature": "A", "slot": 10, "blockTime": 2000}],
            "страниц": 1, "why_not": None, "дошли_до_слота": 10}
        ц5 = окно_по_цепи(W, с_ts=900, по_ts=1100)
        chk("страниц не хватило -- цепь считается НЕ ответившей",
            ц5["цепь_ответила"] is False
            and "страниц подписей не хватило" in (ц5["почему_не_ответила"] or ""),
            ц5)
        P11.подписи_кошелька = lambda к, **кв: {
            "записи": [], "страниц": 1, "why_not": "429 Too Many Requests",
            "дошли_до_слота": None}
        ц6 = окно_по_цепи(W, с_ts=900, по_ts=1100)
        chk("отказ списка подписей -- причина названа, покупок не ноль, а «не знаю»",
            ц6["цепь_ответила"] is False
            and "429" in (ц6["почему_не_ответила"] or ""), ц6)
    finally:
        P11.подписи_кошелька = было

    # --- НЕПРОЧИТАННАЯ ТРАНЗАКЦИЯ -- тоже не ноль.
    ц7 = {"цепь_ответила": False, "почему_не_ответила": "не прочитано транзакций: 1",
           "подписей_в_окне": 2, "прочитано": 1, "не_прочитано": 1,
           "прочее": 1, "странности": ["SIG: таймаут"], "покупки": [],
           "продажи": []}
    chk("одна непрочитанная транзакция -- вердикт «не знаю»",
        проверить(кошелёк=W, с_ts=900, по_ts=1100, цепь=ц7,
                   журнал={"позиций": 0})["вердикт"] == "не знаю")

    chk("разбор времени: Z-строка и мусор",
        разбор_времени("2026-09-30T23:30:00Z") == 1790811000.0
        and разбор_времени("") is None and разбор_времени("вчера") is None,
        разбор_времени("2026-09-30T23:30:00Z"))

    print(f"самопроверка сделок по цепи: {всего - сбоев}/{всего} пройдено")
    if сбоев:
        print(f"самопроверка не пройдена: {сбоев} из {всего}")
    return 1 if сбоев else 0


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--koshelek", default="")
    ap.add_argument("--s", default="")
    ap.add_argument("--po", default="")
    ap.add_argument("--state-dir", default="")
    ap.add_argument("--stranic", type=int, default=5)
    ap.add_argument("--predel-tx", type=int, default=200)
    ap.add_argument("--out", default="")
    ap.add_argument("--self-test", action="store_true")
    а = ap.parse_args()
    if а.self_test:
        return self_test()
    с_ts = разбор_времени(а.s)
    if с_ts is None:
        print("OTKAZ: --s обязателен в виде 2026-09-30T23:30:00Z")
        return 2
    по_ts = разбор_времени(а.po)
    кошелёк = (а.koshelek or "").strip()
    if not кошелёк:
        # АДРЕС СПРАШИВАЕТСЯ У САМОЙ ПОЛОСЫ, а не угадывается по имени
        # переменной: своё имя переменной (OWN_SEND_WALLET) знает bloom_own_send,
        # и там же лежит откат на кошелёк исполнителя. Угадывать адрес нельзя --
        # счёт по чужому кошельку выглядел бы как "сделок не было".
        try:
            import bloom_own_send as OS  # noqa: PLC0415

            кошелёк = (OS.кошелёк_полосы() or "").strip()
        except Exception as exc:  # noqa: BLE001
            print(f"OTKAZ: адрес полосы не спрошен ({type(exc).__name__}); "
                  "дайте --koshelek")
            return 2
    if not кошелёк:
        print("OTKAZ: кошелёк не задан (--koshelek или OWN_SEND_WALLET в env)")
        return 2
    о = проверить(кошелёк=кошелёк, с_ts=с_ts, по_ts=по_ts,
                   state_dir=(а.state_dir or None), страниц=а.stranic,
                   предел_транзакций=а.predel_tx)
    печать(о)
    if а.out:
        Path(а.out).write_text(json.dumps(о, ensure_ascii=False, indent=2),
                                encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
