ЛАМПОРТОВ_В_SOL = 1_000_000_000


def _время(т) -> str:
    try:
        return time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime(float(т)))
    except (TypeError, ValueError):
        return "—"


def разбор_времени(текст: str) -> float | None:
    """'2026-09-30T23:30:00Z' -> unix. Пусто или мусор -- None."""
    т = (текст or "").strip()
    if not т:
        return None
    for фмт in ("%Y-%m-%dT%H:%M:%SZ", "%Y-%m-%dT%H:%MZ", "%Y-%m-%d"):
        try:
            import calendar  # noqa: PLC0415

            return float(calendar.timegm(time.strptime(т, фмт)))
        except ValueError:
            continue
    return None


def вид_транзакции(tx: dict, кошелёк: str) -> dict:
    """Чем эта транзакция была для НАШЕГО кошелька: покупка, продажа, прочее.

    Решают два факта по цепи: куда пошли ЛИКВИДНЫЕ лампорты самого кошелька (без
    его токеновых счетов -- там рента) и куда пошли остатки минтов. Покупка --
    минт пришёл, SOL ушёл. Продажа -- минт ушёл, SOL пришёл. Ни одного минта --
    это не сделка (контроль доставки, чаевые, закрытие счёта), и называется она
    именно так, а не "непонятно".
    """
    из_ = {"вид": "прочее", "минты": {}, "ликвидные_sol": None,
            "рента_sol": None, "ошибка": None, "слот": None, "время": None,
            "комиссия_sol": None}
    мета = (tx or {}).get("meta") or {}
    из_["ошибка"] = мета.get("err") is not None
    из_["слот"] = (tx or {}).get("slot")
    из_["время"] = (tx or {}).get("blockTime")
    ликв = P11.дельта_наших(tx, кошелёк, только_кошелёк=True)
    всего = P11.дельта_наших(tx, кошелёк)
    if ликв.get("ok"):
        из_["ликвидные_sol"] = round(int(ликв["lamports"]) / ЛАМПОРТОВ_В_SOL, 9)
        из_["комиссия_sol"] = round(int(ликв.get("fee") or 0) / ЛАМПОРТОВ_В_SOL, 9)
    if ликв.get("ok") and всего.get("ok"):
        из_["рента_sol"] = round(
            (int(всего["lamports"]) - int(ликв["lamports"])) / ЛАМПОРТОВ_В_SOL, 9)
    минты = {м: д for м, д in (P11.дельты_наших_минтов(tx, кошелёк) or {}).items() if д}
    из_["минты"] = минты
    пришло = [м for м, д in минты.items() if д > 0]
    ушло = [м for м, д in минты.items() if д < 0]
    ликв_sol = из_["ликвидные_sol"]
    if пришло and (ликв_sol is None or ликв_sol < 0):
        из_["вид"] = "покупка"
    elif ушло and (ликв_sol is None or ликв_sol > 0):
        из_["вид"] = "продажа"
    elif пришло or ушло:
        # Минт двинулся, а деньги -- в другую сторону: так выглядит перевод
        # токена или сделка, у которой SOL прошёл не через сам кошелёк. Это НЕ
        # "прочее": назвать её сделкой нельзя, промолчать -- тоже.
        из_["вид"] = "минт двинулся, деньги не сошлись"
    return из_


def окно_по_цепи(кошелёк: str, *, с_ts: float, по_ts: float | None,
                  страниц: int = 5, предел_транзакций: int = 200) -> dict:
    """Что было на цепи у кошелька за окно. Отказ цепи -- НЕ ноль, а 'не знаю'."""
    из_ = {"кошелёк": кошелёк, "с": с_ts, "по": по_ts,
            "цепь_ответила": False, "почему_не_ответила": None,
            "подписей_в_окне": 0, "прочитано": 0, "не_прочитано": 0,
            "покупки": [], "продажи": [], "прочее": 0,
            "странности": [], "подписи_в_окне": []}
    список = P11.подписи_кошелька(кошелёк, страниц=страниц)
    if список.get("why_not"):
        из_["почему_не_ответила"] = (
            f"список подписей кошелька не отдался: {список['why_not']}")
        return из_
    записи = список.get("записи") or []
    # ОКНО ПО blockTime САМОЙ ЦЕПИ, а не по нашим часам: часы хоста и время
    # блока -- разные часы, и сделка на границе окна не должна зависеть от того,
    # чьи часы мы спросили.
    в_окне = []
    без_времени = 0
    for з in записи:
        т = з.get("blockTime")
        if not isinstance(т, (int, float)):
            без_времени += 1
            continue
        if float(т) < float(с_ts):
            continue
        if по_ts is not None and float(т) > float(по_ts):
            continue
        в_окне.append(з)
    если_мало = len(записи) and len(в_окне) == 0 and (
        min(float(з.get("blockTime") or 0) for з in записи if з.get("blockTime"))
        > float(с_ts))
    if если_мало:
        # Самая старая прочитанная подпись НОВЕЕ начала окна: значит страниц не
        # хватило и мы просто не дочитали до окна. Ноль тут соврал бы.
        из_["почему_не_ответила"] = (
            "страниц подписей не хватило: самая старая прочитанная подпись "
            "новее начала окна")
        return из_
    if без_времени:
        из_["странности"].append(f"подписей без blockTime: {без_времени}")
    из_["подписей_в_окне"] = len(в_окне)
    из_["подписи_в_окне"] = [з.get("signature") for з in в_окне]
    for з in в_окне[: int(предел_транзакций)]:
        подпись = з.get("signature")
        о = P11.зов("getTransaction",
                     [подпись, {"encoding": "jsonParsed",
                                "maxSupportedTransactionVersion": 1,
                                "commitment": "confirmed"}])
        if not о.get("ok") or о.get("result") is None:
            из_["не_прочитано"] += 1
            из_["странности"].append(
                f"{подпись[:12]}: {о.get('why_not') or 'узел не отдал транзакцию'}")
            continue
        из_["прочитано"] += 1
        в = вид_транзакции(о["result"], кошелёк)
        в["подпись"] = подпись
        if в["вид"] == "покупка":
            из_["покупки"].append(в)
        elif в["вид"] == "продажа":
            из_["продажи"].append(в)
        elif в["вид"] == "прочее":
            из_["прочее"] += 1
        else:
            из_["странности"].append(f"{подпись[:12]}: {в['вид']}")
    if len(в_окне) > int(предел_транзакций):
        из_["почему_не_ответила"] = (
            f"подписей в окне {len(в_окне)}, предел чтения {предел_транзакций}")
        return из_
    if из_["не_прочитано"]:
        из_["почему_не_ответила"] = (
            f"не прочитано транзакций: {из_['не_прочитано']}")
        return из_
    из_["цепь_ответила"] = True
    return из_


def пары(цепь: dict) -> list:
    """Покупка + её продажа по минту: ушло, вернулось, итог, количество.

    Пара строится ТОЛЬКО по цепи. Количество куплено и продано -- дельты
    остатков минта: если они не сошлись, значит продано не ровно купленное, и
    это сказано числом, а не словом "ок".
    """
    из_ = []
    продажи = list(цепь.get("продажи") or [])
    for п in (цепь.get("покупки") or []):
        минт = max((п.get("минты") or {}).items(), key=lambda кв: кв[1],
                    default=(None, 0))[0]
        куплено = (п.get("минты") or {}).get(минт, 0)
        подходящие = [с for с in продажи
                       if минт in (с.get("минты") or {})
                       and float(с.get("время") or 0) >= float(п.get("время") or 0)]
        подходящие.sort(key=lambda с: float(с.get("время") or 0))
        с = подходящие[0] if подходящие else None
        if с is not None:
            продажи.remove(с)
        ушло = (-float(п.get("ликвидные_sol") or 0.0)
                if п.get("ликвидные_sol") is not None else None)
        вернулось = (float(с.get("ликвидные_sol") or 0.0)
                      if с is not None and с.get("ликвидные_sol") is not None
                      else None)
        продано = -int((с.get("минты") or {}).get(минт, 0)) if с is not None else None
        ряд = {
            "минт": минт,
            "покупка": п.get("подпись"), "время_покупки": п.get("время"),
            "продажа": (с or {}).get("подпись"), "время_продажи": (с or {}).get("время"),
            "ушло_sol": (round(ушло, 9) if ушло is not None else None),
            "вернулось_sol": (round(вернулось, 9) if вернулось is not None else None),
            "итог_sol": (round(вернулось - ушло, 9)
                          if (ушло is not None and вернулось is not None) else None),
            "рента_покупки_sol": п.get("рента_sol"),
            "рента_продажи_sol": (с or {}).get("рента_sol"),
            "куплено": куплено, "продано": продано,
            "количество_сошлось": (None if продано is None else продано == куплено),
            "удержание_слотов": ((int(с.get("слот")) - int(п.get("слот")))
                                  if с is not None and isinstance(с.get("слот"), int)
                                  and isinstance(п.get("слот"), int) else None),
        }
        из_.append(ряд)
    return из_


def журнал_за_окно(state_dir: str, *, с_ts: float, по_ts: float | None) -> dict:
    """Второе мнение: что об этом окне говорят ЗАПИСИ службы (не вердикт)."""
    из_ = {"позиций": 0, "по_группам": {}, "почему_нет": None, "cid": []}
    try:
        поз = P11.позиции_полосы(state_dir, с_ts, по_ts)
    except Exception as exc:  # noqa: BLE001
        из_["почему_нет"] = f"{type(exc).__name__}: {str(exc)[:160]}"
        return из_
    из_["позиций"] = len(поз)
    из_["cid"] = sorted(поз)
    for п in поз.values():
        г = п.get("lane_group") or "—"
        из_["по_группам"][г] = из_["по_группам"].get(г, 0) + 1
    return из_


def проверить(*, кошелёк: str, с_ts: float, по_ts: float | None,
               state_dir: str | None = None, страниц: int = 5,
               предел_транзакций: int = 200, цепь: dict | None = None,
               журнал: dict | None = None) -> dict:
    """Один ответ на вопрос «были ли сделки за окно».

    `цепь` и `журнал` можно передать готовыми -- так самопроверка работает без
    сети. Вердикт считается ровно одним правилом, и оно тут одно на весь файл.
    """
    ц = цепь if цепь is not None else окно_по_цепи(
        кошелёк, с_ts=с_ts, по_ts=по_ts, страниц=страниц,
        предел_транзакций=предел_транзакций)
    ж = журнал if журнал is not None else (
        журнал_за_окно(state_dir or ".", с_ts=с_ts, по_ts=по_ts)
        if state_dir else {"позиций": None, "почему_нет": "каталог состояния не дан"})
    п = пары(ц)
    покупок = len(ц.get("покупки") or [])
    из_ = {
        "окно": {"с": _время(с_ts), "по": (_время(по_ts) if по_ts else "сейчас")},
        "кошелёк": кошелёк,
        "цепь": {к: ц.get(к) for к in
                  ("цепь_ответила", "почему_не_ответила", "подписей_в_окне",
                   "прочитано", "не_прочитано", "прочее", "странности")},
        "покупок_по_цепи": покупок,
        "продаж_по_цепи": len(ц.get("продажи") or []),
        "пары": п,
        "журнал": ж,
        "вердикт": None, "почему": None, "расхождение": None,
    }
    if not ц.get("цепь_ответила"):
        # ГЛАВНОЕ ПРАВИЛО ФАЙЛА: цепь молчит -- ответ "не знаю". Ноль тут и был
        # той самой ошибкой 01.10.
        из_["вердикт"] = "не знаю"
        из_["почему"] = ц.get("почему_не_ответила") or "цепь не ответила"
        return из_
    из_["вердикт"] = "сделок не было" if покупок == 0 else f"сделок {покупок}"
    из_["почему"] = ("по цепи за окно с кошелька не ушло ни одной покупки"
                      if покупок == 0 else "покупки найдены по цепи")
    # РАСХОЖДЕНИЕ С ЗАПИСЯМИ НАЗЫВАЕТСЯ, А НЕ СГЛАЖИВАЕТСЯ. Записи могут
    # отставать (покупка села, запись ещё пишется) и могут врать (тень, отказ
    # записи). Вердикт от этого не меняется -- меняется то, что мы знаем.
    жп = ж.get("позиций")
    if isinstance(жп, int) and жп != покупок:
        из_["расхождение"] = (
            f"цепь: покупок {покупок}; записи службы: позиций {жп}")
    return из_


def печать(о: dict) -> None:
    ок = о.get("окно") or {}
    print(f"# Сделки за окно {ок.get('с')} .. {ок.get('по')} -- ПО ЦЕПИ")
    print(f"кошелёк: {о.get('кошелёк')}")
    ц = о.get("цепь") or {}
    print(f"цепь ответила: {'да' if ц.get('цепь_ответила') else 'НЕТ'}"
          + ("" if ц.get("цепь_ответила") else f" ({ц.get('почему_не_ответила')})"))
    print(f"подписей в окне {ц.get('подписей_в_окне')}, прочитано "
          f"{ц.get('прочитано')}, не прочитано {ц.get('не_прочитано')}, "
          f"не сделок {ц.get('прочее')}")
    print(f"ВЕРДИКТ: {о.get('вердикт')} -- {о.get('почему')}")
    if о.get("расхождение"):
        print(f"ВНИМАНИЕ: {о['расхождение']}")
    for р in (о.get("пары") or []):
        кол = ("количество сошлось" if р.get("количество_сошлось")
               else ("КОЛИЧЕСТВО НЕ СОШЛОСЬ" if р.get("количество_сошлось") is False
                     else "продажи по цепи нет"))
        итог = р.get("итог_sol")
        print(f"  {_время(р.get('время_покупки'))} {str(р.get('минт'))[:6]}: "
              f"ушло {р.get('ушло_sol')} -> вернулось {р.get('вернулось_sol')} "
              f"= итог {итог}; куплено {р.get('куплено')}, продано {р.get('продано')} "
              f"({кол}); удержание {р.get('удержание_слотов')} слотов")
    ж = о.get("журнал") or {}
    print(f"записи службы: позиций {ж.get('позиций')}"
          + (f" ({ж.get('почему_нет')})" if ж.get("почему_нет") else "")
          + (f", по группам {ж.get('по_группам')}" if ж.get("по_группам") else ""))
    for с in (ц.get("странности") or []):
        print(f"  странность: {с}")


