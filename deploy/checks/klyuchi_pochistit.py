#!/usr/bin/env python3
"""Чистка ключей: копии env, права, EXEC_WALLET_KEY. Значения НЕ печатаются.

ЗАЧЕМ (слово владельца 01.10, вечер, п.2). Приватные ключи кошелька Bloom и
полосы лежат в /etc/bloom-executor/env и в 24 копиях env.bak.*. Ключ Bloom
4s87RRC2 утёк (перевод 06:52:54Z владелец не делал), Bloom выключен с 27.09, и
его ключу в окружении делать нечего. Ротации ключа полосы не требуется -- слово
владельца 18:31: LIVE никуда не импортировался.

ЧТО ДЕЛАЕТ, И В КАКОМ ПОРЯДКЕ:
  1. ЧТЕНИЕ. Копии env: сколько, какие, какие ИМЕНА ключей в каждой (значений
     нет). Права живого env. Имена ключей живого env.
  2. ПРОБА БЕЗ КЛЮЧА. Копия живого env без строки EXEC_WALLET_KEY, и по ней --
     проверка старта каждой службы её собственной проверкой (--check-only /
     --self-test). Это читает, но не трогает ни живой env, ни службы.
  3. ТОЛЬКО ПО СЛОВУ. Стереть копии, поставить 600, убрать строку ключа из
     живого env -- и последнее ТОЛЬКО если ни одна служба в пробе ключ не
     потребовала.

ИМЕНА КЛЮЧЕЙ ИЗ КОПИЙ -- В ОТЧЁТ, И ЭТО НЕ УКРАШЕНИЕ. Копии и есть единственное
место, откуда можно узнать, что в окружении когда-то было. Стереть их, не записав
имён, значит потерять этот список навсегда: если позже окажется, что служба ждёт
переменную, которой в живом env нет, искать будет негде.

ЗНАЧЕНИЙ НЕТ НИГДЕ. Ни в выводе, ни в отчёте, ни в журнале прогона -- только
имена, пути, числа и права. Отдельная самопроверка стоит именно на этом.
"""
from __future__ import annotations

import argparse
import glob
import json
import os
import re
import shutil
import stat
import subprocess
import sys
import tempfile
from pathlib import Path

ИМЯ_КЛЮЧА = "EXEC_WALLET_KEY"
ENV_ПО_УМОЛЧАНИЮ = "/etc/bloom-executor/env"
ОБРАЗЕЦ_КОПИЙ = "env.bak.*"
# ПРИСВОЕНИЕ В env: ИМЯ=значение. Имя -- только латиница, цифры и подчёркивание.
ПРИСВОЕНИЕ = re.compile(r"^([A-Za-z_][A-Za-z0-9_]*)=")


def имена_присвоений(текст: str) -> list:
    """Только ИМЕНА переменных. Значения не возвращаются и не хранятся."""
    из_ = []
    for строка in (текст or "").splitlines():
        м = ПРИСВОЕНИЕ.match(строка.strip())
        if м:
            из_.append(м.group(1))
    return из_


def права(путь: str) -> str:
    return oct(stat.S_IMODE(os.stat(путь).st_mode))[2:].rjust(3, "0")


def копии(каталог: str) -> list:
    """Копии env по образцу. ЖИВОЙ env сюда попасть не может: образец с точкой."""
    из_ = []
    for п in sorted(glob.glob(os.path.join(каталог, ОБРАЗЕЦ_КОПИЙ))):
        if os.path.basename(п) == "env":
            continue                     # на всякий случай: живой env не копия
        try:
            текст = Path(п).read_text(encoding="utf-8", errors="replace")
        except OSError as exc:
            из_.append({"файл": п, "почему": f"не прочитан ({type(exc).__name__})"})
            continue
        имена = имена_присвоений(текст)
        из_.append({"файл": п, "байт": os.path.getsize(п), "права": права(п),
                     "имён": len(имена), "имена": имена})
    return из_


def без_ключа(текст: str, имя: str = ИМЯ_КЛЮЧА) -> tuple:
    """Текст env без строк присвоения этого имени. Возвращает (текст, сколько)."""
    оставить, убрано = [], 0
    for строка in (текст or "").splitlines(keepends=True):
        м = ПРИСВОЕНИЕ.match(строка.strip())
        if м and м.group(1) == имя:
            убрано += 1
            continue
        оставить.append(строка)
    return "".join(оставить), убрано


def проба_служб(env_текст: str, службы: list, *, запуск=None) -> list:
    """Стартует ли каждая служба БЕЗ ключа. Копия env кладётся в свой файл.

    Проверка -- СОБСТВЕННАЯ У КАЖДОЙ СЛУЖБЫ (--check-only или --self-test), и
    запускается она тем же питоном, что у службы. Живой env и сами службы не
    трогаются вовсе.
    """
    из_ = []
    кат = tempfile.mkdtemp(prefix="proba_env_")
    файл = os.path.join(кат, "env")
    try:
        Path(файл).write_text(env_текст, encoding="utf-8")
        os.chmod(файл, 0o600)
        for сл in службы:
            имя = сл["имя"]
            cmd = сл["команда"]
            стр = {"служба": имя, "команда": cmd}
            try:
                р = (запуск or _запустить)(cmd, файл)
            except Exception as exc:  # noqa: BLE001
                стр.update(стартует=None,
                            почему=f"проба не выполнилась ({type(exc).__name__})")
                из_.append(стр)
                continue
            вывод = str(р.get("вывод") or "")
            # КЛЮЧ ПОТРЕБОВАЛСЯ -- ЭТО ИМЯ КЛЮЧА В ЖАЛОБЕ, а не просто код не 0:
            # у проверок бывают свои причины отказа, и путать их нельзя.
            требует = ИМЯ_КЛЮЧА in вывод or "BLOOM_WALLET_KEY" in вывод
            стр.update(код=р.get("код"), стартует=(р.get("код") == 0),
                        требует_ключ=требует,
                        хвост=вывод.strip().splitlines()[-3:] if вывод else [])
            из_.append(стр)
    finally:
        shutil.rmtree(кат, ignore_errors=True)
    return из_


def _запустить(cmd: str, env_файл: str) -> dict:
    полная = f"set -a; . {env_файл}; set +a; {cmd}"
    п = subprocess.run(["bash", "-lc", полная], capture_output=True, text=True,
                       timeout=180)
    return {"код": п.returncode, "вывод": (п.stdout or "") + (п.stderr or "")}


def кратко(свод: dict) -> str:
    """Сводка строками. Значений ключей здесь нет и быть не может: берутся
    только числа, имена и права."""
    стр = [f"копий env.bak: {свод.get('копий')}",
            f"права env: {свод.get('права_до')} -> "
            f"{свод.get('права_после', 'не менялись')}",
            f"строк {ИМЯ_КЛЮЧА} в живом env: {свод.get('строк_ключа_в_живом')}"]
    for п in свод.get("проба_без_ключа") or []:
        стр.append(f"  {п['служба']:<20} стартует={п.get('стартует')} "
                    f"требует_ключ={п.get('требует_ключ')} код={п.get('код')}")
        if п.get("почему"):
            стр.append(f"      почему: {п['почему']}")
    стр.append(f"ключ требуют: {', '.join(свод.get('ключ_требуют') or []) or 'никто'}")
    стр.append("проба не вышла у: "
                + (", ".join(свод.get("проба_не_вышла_у") or []) or "ни у кого"))
    стр.append(f"ключ убран: {свод.get('ключ_убран', 'не просили')} "
                f"{свод.get('почему_не_убран') or ''}".rstrip())
    if свод.get("стёрто_копий") is not None:
        стр.append(f"стёрто копий: {свод['стёрто_копий']}, "
                    f"осталось {свод.get('копий_осталось')}")
    стр.append("сделано: " + "; ".join(свод.get("сделано") or []))
    return "\n".join(стр)


def самопроверка() -> int:
    из_строя = []

    def chk(имя, усл, *лишнее):
        print(("ok  " if усл else "СБОЙ") + "  " + имя
               + ("" if усл else "  " + repr(лишнее)))
        if not усл:
            из_строя.append(имя)

    ТАЙНА = "СЕКРЕТНОЕ_ЗНАЧЕНИЕ_КОТОРОГО_НЕ_ДОЛЖНО_БЫТЬ_В_ОТЧЁТЕ"
    текст = (f"# коммент\nEXEC_WALLET_KEY={ТАЙНА}\n"
              f"OWN_SEND_WALLET_KEY={ТАЙНА}2\nHELIUS_API_KEY=abc\n\n"
              f"  OTSTUP_NE_PRISVOENIE\nEXEC_WALLET_KEY={ТАЙНА}3\n")
    имена = имена_присвоений(текст)
    chk("имена присвоений собраны, значения не возвращаются",
        имена == ["EXEC_WALLET_KEY", "OWN_SEND_WALLET_KEY", "HELIUS_API_KEY",
                   "EXEC_WALLET_KEY"], имена)
    chk("строка без '=' присвоением не считается", "OTSTUP_NE_PRISVOENIE" not in имена)
    chk("комментарий присвоением не считается", "#" not in "".join(имена))

    из_текста, убрано = без_ключа(текст)
    chk("убраны ВСЕ строки ключа, а не первая", убрано == 2, убрано)
    chk("ключа в остатке нет", "EXEC_WALLET_KEY" not in из_текста)
    chk("ключ полосы и прочие строки остались",
        "OWN_SEND_WALLET_KEY" in из_текста and "HELIUS_API_KEY" in из_текста
        and "# коммент" in из_текста)
    chk("значение ключа нигде не всплыло", ТАЙНА not in str(имена))

    # ПРОБА: ключ потребовался -- узнаётся ПО ИМЕНИ В ЖАЛОБЕ, а не по коду.
    вызовы = []

    def запуск_ок(cmd, env_файл):
        вызовы.append(cmd)
        текст_env = Path(env_файл).read_text(encoding="utf-8")
        assert ИМЯ_КЛЮЧА not in текст_env, "в пробу попал ключ!"
        return {"код": 0, "вывод": "всё хорошо"}

    def запуск_требует(cmd, env_файл):
        return {"код": 1, "вывод": f"СБОЙ: {ИМЯ_КЛЮЧА} пуст"}

    def запуск_иначе(cmd, env_файл):
        return {"код": 2, "вывод": "СБОЙ: узел не ответил"}

    службы = [{"имя": "детектор", "команда": "echo 1"}]
    п1 = проба_служб(из_текста, службы, запуск=запуск_ок)
    chk("проба: служба стартует, ключ не требуется",
        п1[0]["стартует"] is True and п1[0]["требует_ключ"] is False, п1)
    chk("проба: в файл пробы ключ не попал (проверено внутри запуска)", вызовы)
    п2 = проба_служб(из_текста, службы, запуск=запуск_требует)
    chk("проба: жалоба на имя ключа читается как 'требует ключ'",
        п2[0]["требует_ключ"] is True and п2[0]["стартует"] is False, п2)
    п3 = проба_служб(из_текста, службы, запуск=запуск_иначе)
    chk("проба: иной отказ НЕ выдаётся за требование ключа",
        п3[0]["требует_ключ"] is False and п3[0]["стартует"] is False, п3)

    def запуск_падает(cmd, env_файл):
        raise TimeoutError("не успел")

    п4 = проба_служб(из_текста, службы, запуск=запуск_падает)
    chk("проба: не выполнилась -- стартует НЕ ЗНАЮ (None), а не False",
        п4[0]["стартует"] is None and "не выполнилась" in п4[0]["почему"], п4)

    # КОПИИ: живой env не считается копией ни при каком образце.
    кат = tempfile.mkdtemp()
    try:
        Path(os.path.join(кат, "env")).write_text(текст, encoding="utf-8")
        Path(os.path.join(кат, "env.bak.111")).write_text(текст, encoding="utf-8")
        Path(os.path.join(кат, "env.bak.222")).write_text("A=1\n", encoding="utf-8")
        к = копии(кат)
        chk("копии найдены, живой env среди них НЕТ",
            [os.path.basename(x["файл"]) for x in к] == ["env.bak.111", "env.bak.222"],
            [os.path.basename(x["файл"]) for x in к])
        chk("у копии записаны имена, но не значения",
            к[0]["имена"][0] == "EXEC_WALLET_KEY"
            and ТАЙНА not in json.dumps(к, ensure_ascii=False), к[0]["имена"])
        chk("права копии прочитаны", len(к[0]["права"]) == 3, к[0]["права"])
    finally:
        shutil.rmtree(кат, ignore_errors=True)

    _св = {"копий": 2, "права_до": "644", "права_после": "600",
            "строк_ключа_в_живом": 1, "ключ_требуют": [], "проба_не_вышла_у": [],
            "ключ_убран": True, "стёрто_копий": 2, "копий_осталось": 0,
            "сделано": ["стёрто копий 2"],
            "проба_без_ключа": [{"служба": "детектор", "стартует": True,
                                  "требует_ключ": False, "код": 0}]}
    _т = кратко(_св)
    chk("кратко: числа и имена на месте",
        "копий env.bak: 2" in _т and "644 -> 600" in _т
        and "ключ требуют: никто" in _т and "детектор" in _т, _т)
    chk("кратко: значения ключей в сводку попасть не могут",
        ТАЙНА not in _т)

    print(f"итог: самопроверка {'норма' if not из_строя else 'СБОЙ'}; "
           f"провалов {len(из_строя)}")
    return 1 if из_строя else 0


def main() -> int:
    р = argparse.ArgumentParser()
    р.add_argument("--env", default=ENV_ПО_УМОЛЧАНИЮ)
    р.add_argument("--sluzhby", default="",
                    help="имя=команда через ';;' -- проверки старта служб")
    р.add_argument("--steret-kopii", action="store_true",
                    help="СТЕРЕТЬ копии env.bak.* (живой env не трогается)")
    р.add_argument("--prava-600", action="store_true")
    р.add_argument("--ubrat-kljuch", action="store_true",
                    help="убрать строку EXEC_WALLET_KEY из ЖИВОГО env; "
                         "делается только если ни одна служба её не потребовала")
    р.add_argument("--out", default=None)
    # КРАТКО -- ЧТОБЫ В ПРОГОНЕ НЕ БЫЛО ВСТАВОК ПИТОНА. Вставка питона внутри
    # YAML уже трижды ломала прогон на отступах: в блочном скаляре YAML
    # неотступленная строка закрывает блок. Печать живёт здесь.
    р.add_argument("--kratko", action="store_true",
                    help="печатать сводку строками вместо JSON")
    р.add_argument("--self-test", action="store_true")
    а = р.parse_args()
    if а.self_test:
        return самопроверка()

    каталог = os.path.dirname(os.path.abspath(а.env))
    свод = {"env": а.env, "каталог": каталог}
    if not os.path.exists(а.env):
        свод["почему"] = f"живого env {а.env} нет -- ничего не трогаю"
        print(json.dumps(свод, ensure_ascii=False, indent=1))
        return 1
    живой = Path(а.env).read_text(encoding="utf-8", errors="replace")
    свод["права_до"] = права(а.env)
    свод["имена_живого"] = имена_присвоений(живой)
    свод["ключ_в_живом"] = ИМЯ_КЛЮЧА in свод["имена_живого"]
    свод["копии"] = копии(каталог)
    свод["копий"] = len(свод["копии"])

    # 2. ПРОБА БЕЗ КЛЮЧА -- всегда, даже когда ничего не трогаем: это и есть
    # ответ на вопрос владельца "все пять служб стартуют без него".
    службы = []
    for кусок in (а.sluzhby or "").split(";;"):
        к = кусок.strip()
        if not к or "=" not in к:
            continue
        имя, _, cmd = к.partition("=")
        службы.append({"имя": имя.strip(), "команда": cmd.strip()})
    текст_без, убрано = без_ключа(живой)
    свод["строк_ключа_в_живом"] = убрано
    свод["проба_без_ключа"] = проба_служб(текст_без, службы) if службы else []
    требуют = [п["служба"] for п in свод["проба_без_ключа"] if п.get("требует_ключ")]
    не_знаю = [п["служба"] for п in свод["проба_без_ключа"] if п.get("стартует") is None]
    свод["ключ_требуют"] = требуют
    свод["проба_не_вышла_у"] = не_знаю

    # 3. ДЕЙСТВИЯ -- только по явным флагам.
    сделано = []
    if а.steret_kopii:
        стёрто = []
        for к in свод["копии"]:
            п = к["файл"]
            if os.path.basename(п) == "env":
                continue
            try:
                os.unlink(п)
                стёрто.append(п)
            except OSError as exc:
                к["почему_не_стёрт"] = f"{type(exc).__name__}"
        свод["стёрто_копий"] = len(стёрто)
        свод["стёрты"] = стёрто
        свод["копий_осталось"] = len(копии(каталог))
        сделано.append(f"стёрто копий {len(стёрто)}")
    if а.prava_600:
        os.chmod(а.env, 0o600)
        свод["права_после"] = права(а.env)
        сделано.append(f"права {свод['права_после']}")
    if а.ubrat_kljuch:
        if требуют or не_знаю:
            свод["ключ_убран"] = False
            свод["почему_не_убран"] = (
                "ключ потребовали: " + ", ".join(требуют) if требуют else
                "проба не вышла у: " + ", ".join(не_знаю))
        elif not службы:
            свод["ключ_убран"] = False
            свод["почему_не_убран"] = ("проб служб не было вовсе -- убирать ключ "
                                        "без пробы нельзя")
        elif not свод["ключ_в_живом"]:
            свод["ключ_убран"] = False
            свод["почему_не_убран"] = "строки ключа в живом env и так нет"
        else:
            # ЗАПИСЬ АТОМАРНАЯ: временный файл рядом и замена. Оборванная запись
            # env оставила бы службу без ВСЕХ переменных, не только без ключа.
            врем = а.env + ".nov"
            Path(врем).write_text(текст_без, encoding="utf-8")
            os.chmod(врем, 0o600)
            os.replace(врем, а.env)
            свод["ключ_убран"] = True
            свод["имена_живого_после"] = имена_присвоений(
                Path(а.env).read_text(encoding="utf-8", errors="replace"))
            сделано.append(f"убрана строка {ИМЯ_КЛЮЧА}")
    свод["сделано"] = сделано or ["ничего -- только чтение"]
    if а.kratko:
        print(кратко(свод))
    else:
        print(json.dumps(свод, ensure_ascii=False, indent=1))
    if а.out:
        Path(а.out).parent.mkdir(parents=True, exist_ok=True)
        with open(а.out, "w", encoding="utf-8") as ф:
            json.dump(свод, ф, ensure_ascii=False, indent=1)
    return 0


if __name__ == "__main__":
    sys.exit(main())
