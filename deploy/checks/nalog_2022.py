    print(f"  цена разбора на горячем пути (без сети, {ц['повторов']} замеров): "
          f"jsonParsed p50 {ц['разбор_jsonparsed_мс']['p50']} мс, max "
          f"{ц['разбор_jsonparsed_мс']['max']} мс; classic БЕЗ чтения p50 "
          f"{ц['classic_без_чтения_мс']['p50']} мс")
    print(f"  время СЕТЕВОГО чтения: {ц['время_сетевого_чтения']}")
    print(f"  самопроверка модуля: код возврата {о['самопроверка_модуля']}")
    if о.get("по_байтам"):
        б = о["по_байтам"]
        print(f"  байтовый путь на файле {б['файл']}: "
              + (f"ok, ставка {б.get('ставка')}" if б.get("ok")
                 else f"НЕ вышло: {б.get('why_not')}"))


