def процентиль(ряд, доля):
    ч = sorted(x for x in ряд if isinstance(x, (int, float)))
    if not ч:
        return None
    м = min(len(ч) - 1, max(0, int(round(доля * (len(ч) - 1)))))
    return ч[м]


def аудит(путь: str) -> dict:
    """Карта «минт -> запись аудита цепи». Нет файла -- пустая карта, и это видно."""
    п = путь if os.path.isabs(путь) else os.path.join(КОРЕНЬ, путь)
    if not os.path.exists(п):
        return {}
    try:
        with open(п, encoding="utf-8") as ф:
            return (json.load(ф) or {}).get("минты") or {}
    except Exception:  # noqa: BLE001
        return {}


# ------------------------------------- 1. какие базы на Token-2022 и таксируемы

def программы_минтов(tx: dict) -> dict:
    """Минт -> программа токена, ИЗ БАЛАНСОВ той же транзакции. Факт цепи."""
    из_ = {}
    for когда in ("preTokenBalances", "postTokenBalances"):
        for б in ((tx or {}).get("meta") or {}).get(когда) or []:
            if isinstance(б, dict) and б.get("mint") and б.get("programId"):
                из_.setdefault(б["mint"], б["programId"])
    return из_


def базы_сбора(тип: str, путь: str, ауд: dict) -> dict:
    """Базы пулов против SOL: программа минта и что про налог знает аудит."""
    import c2_nalog_2022 as N

    из_ = {"тип": тип, "имя": ТИПЫ[тип]["имя"], "файл": путь, "why_not": None,
            "sol_пулов": 0, "баз": 0, "token_2022": 0, "classic": 0,
            "программа_не_видна": 0, "минты": {}}
    if not os.path.exists(путь):
        из_["why_not"] = (f"файла нет: {путь} -- сбор Code-2 лежит в его ветке "
                           f"(data/podbivka/{ТИПЫ[тип]['файл']})")
        return из_
    М = __import__(ТИПЫ[тип]["модуль"])
    with open(путь, encoding="utf-8") as ф:
        сбор = json.load(ф)
    for с in (сбор.get("снимки") or []) if isinstance(сбор, dict) else []:
        tx = с.get("транзакция") or {}
        т = М.шаблон(tx, с.get("пул"))
        if not т.get("ok"):
            continue
        ш = М.шаблон_со_сторонами(т, tx)
        if not ш.get("ok"):
            continue
        шб = ш["шаблон"]
        стороны = ([шб.get("минт_входа"), шб.get("минт_выхода")] if тип == "clmm"
                    else [шб.get("минт_a"), шб.get("минт_b")])
        if WSOL not in стороны:
            continue
        из_["sol_пулов"] += 1
        база = next((m for m in стороны if m and m != WSOL), None)
        if not база or база in из_["минты"]:
            continue
        прог = программы_минтов(tx).get(база)
        а = ауд.get(база) or {}
        из_["минты"][база] = {
            "программа": прог,
            "token_2022": прог == N.ПРОГРАММА_2022,
            "аудит_есть": bool(а),
            "аудит_bps": а.get("ставка_комиссии_bps"),
            "аудит_таксируемый": а.get("таксируемый"),
            "аудит_расширения": а.get("расширения"),
        }
    из_["баз"] = len(из_["минты"])
    for з in из_["минты"].values():
        if з["token_2022"]:
            из_["token_2022"] += 1
        elif з["программа"]:
            из_["classic"] += 1
        else:
            из_["программа_не_видна"] += 1
    # СКОЛЬКО ИЗ Token-2022 НА САМОМ ДЕЛЕ С НАЛОГОМ. Это и есть цена прежнего
    # отказа: у минта без расширения налог ноль, и отказывать там было незачем.
    t22 = [з for з in из_["минты"].values() if з["token_2022"]]
    из_["t22_в_аудите"] = sum(1 for з in t22 if з["аудит_есть"])
    из_["t22_с_налогом"] = sum(1 for з in t22 if з["аудит_таксируемый"])
    из_["t22_без_налога"] = sum(1 for з in t22
                                 if з["аудит_есть"] and not з["аудит_таксируемый"])
    из_["t22_неизвестно"] = sum(1 for з in t22 if not з["аудит_есть"])
    return из_


# ------------------------- 2-3. правило налога против события и против аудита

# ЧТО СЧИТАЕТ «СУММОЙ» КАЖДАЯ ПРОГРАММА -- установлено перебором на живых
# сделках, а не взято из документации: у CLMM amount_N события -- сумма ПОСЛЕ
# налога (полная = amount + transfer_fee), у Whirlpool input_amount/output_amount
# -- ДО налога. Гипотеза проверяется здесь обе, и в отчёт идёт та, что сошлась.
ПОЛЯ = {
    "clmm": [("0", "amount_0", "transfer_fee_0"), ("1", "amount_1", "transfer_fee_1")],
    "whirlpool": [("in", "input_amount", "input_transfer_fee"),
                   ("out", "output_amount", "output_transfer_fee")],
}


def минт_поля(тип: str, ев: dict, роли: dict, имя: str):
    """Минт той стороны события, о которой идёт речь. Из разобранных ролей Code-2."""
    if тип == "clmm":
        z = ев.get("zero_for_one")
        вх, вых = роли.get("input_vault_mint"), роли.get("output_vault_mint")
        if имя == "0":
            return вх if z else вых
        return вых if z else вх
    a2b = ев.get("a_to_b")
    ма, мб = роли.get("token_mint_a"), роли.get("token_mint_b")
    вх, вых = (ма, мб) if a2b else (мб, ма)
    return вх if имя == "in" else вых


def правило_по_событиям(тип: str, путь: str, ауд: dict) -> dict:
    """Сверка правила налога с полем налога в событиях -- на живых сделках."""
    import c2_nalog_2022 as N

    из_ = {"тип": тип, "why_not": None, "сторон_всего": 0, "налог_ноль": 0,
            "налог_есть": 0, "правило_сошлось": 0, "правило_не_сошлось": 0,
            "гипотезы": collections.Counter(), "ставки": collections.Counter(),
            "аудит_совпал": 0, "аудит_разошёлся": 0, "минта_нет_в_аудите": 0,
            "разошлись": [], "не_сошлись": []}
    if not os.path.exists(путь):
        из_["why_not"] = f"файла нет: {путь}"
        return из_
    with open(путь, encoding="utf-8") as ф:
        сбор = json.load(ф)
    for с in (сбор.get("сделки") or []) if isinstance(сбор, dict) else []:
        инстр = с.get("инструкции") or []
        роли = (инстр[0].get("роли") or {}) if инстр else {}
        for ев in с.get("события") or []:
            for имя, к_сум, к_нал in ПОЛЯ[тип]:
                сум, нал = ев.get(к_сум), ев.get(к_нал)
                if сум is None or нал is None:
                    continue
                из_["сторон_всего"] += 1
                if not нал:
                    из_["налог_ноль"] += 1
                    continue
                из_["налог_есть"] += 1
                # Полная сумма -- либо сум+нал (налог уже вычтен), либо сум.
                сошлось = None
                for гип, полная in (("сумма_после_налога", сум + нал),
                                     ("сумма_до_налога", сум)):
                    if полная <= 0:
                        continue
                    bps = round(нал * N.BASIS_POINT_MAX / полная)
                    if нал == N.налог_с_суммы(полная, bps, None):
                        сошлось = (гип, полная, bps)
                        break
                if сошлось is None:
                    из_["правило_не_сошлось"] += 1
                    из_["не_сошлись"].append({"сторона": имя, "сумма": сум,
                                               "налог": нал,
                                               "сделка": с.get("signature")})
                    continue
                гип, полная, bps = сошлось
                из_["правило_сошлось"] += 1
                из_["гипотезы"][гип] += 1
                из_["ставки"][bps] += 1
                минт = минт_поля(тип, ев, роли, имя)
                а = ауд.get(минт) if минт else None
                if not а:
                    из_["минта_нет_в_аудите"] += 1
                    continue
                if а.get("ставка_комиссии_bps") == bps:
                    из_["аудит_совпал"] += 1
                else:
                    из_["аудит_разошёлся"] += 1
                    из_["разошлись"].append({"минт": минт,
                                              "из_события_bps": bps,
                                              "аудит_bps": а.get("ставка_комиссии_bps"),
                                              "сделка": с.get("signature")})
    из_["гипотезы"] = dict(из_["гипотезы"])
    из_["ставки"] = dict(sorted(из_["ставки"].items()))
    из_["разошлись"] = из_["разошлись"][:6]
    из_["не_сошлись"] = из_["не_сошлись"][:6]
    return из_


# --------------------------------------------- 4. цена разбора на горячем пути

def цена_разбора(повторов: int = 400) -> dict:
    """Сколько стоит РАЗБОР ответа (без сети). Первый вызов дороже -- импорт."""
    import c2_nalog_2022 as N

    зн = {"owner": N.ПРОГРАММА_2022, "data": {"parsed": {"info": {
        "decimals": 6, "extensions": [
            {"extension": "metadataPointer", "state": {}},
            {"extension": "transferFeeConfig", "state": {
                "olderTransferFee": {"epoch": 10, "maximumFee": 5,
                                      "transferFeeBasisPoints": 100},
                "newerTransferFee": {"epoch": 20, "maximumFee": 7,
                                      "transferFeeBasisPoints": 300}}},
            {"extension": "tokenMetadata", "state": {}}]}}}}
    for _ in range(5):
        N.из_jsonparsed(зн)
    ряд = []
    for _ in range(повторов):
        т0 = time.perf_counter()
        N.из_jsonparsed(зн)
        ряд.append((time.perf_counter() - т0) * 1000.0)
    # classic SPL -- вообще без разбора и без сети.
    было = os.environ.get(N.ИМЯ_ФЛАГА)
    os.environ[N.ИМЯ_ФЛАГА] = "1"
    ряд_cl = []
    for _ in range(повторов):
        т0 = time.perf_counter()
        N.налог("M" * 43, N.ПРОГРАММА_SPL)
        ряд_cl.append((time.perf_counter() - т0) * 1000.0)
    if было is None:
        os.environ.pop(N.ИМЯ_ФЛАГА, None)
    else:
        os.environ[N.ИМЯ_ФЛАГА] = было
    return {"повторов": повторов,
            "разбор_jsonparsed_мс": {"p50": round(процентиль(ряд, 0.5), 4),
                                      "max": round(процентиль(ряд, 1.0), 4)},
            "classic_без_чтения_мс": {"p50": round(процентиль(ряд_cl, 0.5), 4),
                                       "max": round(процентиль(ряд_cl, 1.0), 4)},
            "сети_нет": True,
            "время_сетевого_чтения": "не мерено -- сети нет; мерит Code-1 на хосте"}


# --------------------------------------------------- байтовый путь на хосте

def по_байтам_файла(путь: str, эпоха: int | None) -> dict:
    """Байтовый путь на НАСТОЯЩЕМ минте: файл с base64 или сырыми байтами счёта."""
    import base64  # noqa: PLC0415

    import c2_nalog_2022 as N

    из_ = {"файл": путь, "ok": False, "why_not": None}
    if not os.path.exists(путь):
        из_["why_not"] = f"файла нет: {путь}"
        return из_
    with open(путь, "rb") as ф:
        сырое = ф.read()
    if not сырое[:1].isdigit() and b"{" not in сырое[:2]:
        try:
            сырое = base64.b64decode(сырое.strip(), validate=True)
        except Exception:  # noqa: BLE001
            pass
    р = N.из_байтов(сырое)
    из_.update(разбор=р)
    if р.get("ok") and р.get("расширение_есть"):
        из_.update(ok=True, ставка=N.ставка_на_эпоху(р["older"], р["newer"], эпоха))
    elif р.get("ok"):
        из_.update(ok=True, ставка={"bps": 0, "почему": "расширения у минта нет"})
    else:
        из_["why_not"] = р.get("why_not")
    return из_


# ------------------------------------------------------------------- прогон

def прогон(*, сборы: dict, файл_аудита: str, байты: str | None,
            эпоха: int | None) -> dict:
    из_ = {"что": "налог перевода Token-2022", "только_чтение": True,
            "сети_нет": True, "симуляции_нет": True, "why_not": None}
    try:
        import c2_nalog_2022 as N
    except Exception as exc:  # noqa: BLE001
        из_["why_not"] = f"модуль не загружен: {type(exc).__name__}: {exc}"
        return из_
    ауд = аудит(файл_аудита)
    из_["аудит"] = {"файл": файл_аудита, "минтов": len(ауд),
                    "таксируемых": sum(1 for з in ауд.values()
                                        if isinstance(з, dict) and з.get("таксируемый"))}
    из_["по_типам"] = {}
    for тип, путь in сборы.items():
        из_["по_типам"][тип] = {"базы": базы_сбора(тип, путь, ауд),
                                 "правило": правило_по_событиям(тип, путь, ауд)}
    из_["цена_разбора"] = цена_разбора()
    из_["самопроверка_модуля"] = N.self_test()
    if байты:
        из_["по_байтам"] = по_байтам_файла(байты, эпоха)
    return из_


