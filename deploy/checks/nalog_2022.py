"""Проверка чтения налога Token-2022 -- офлайн, без сети и без симуляции.

Четыре вопроса, и на каждый -- число:

  1. У СКОЛЬКИХ баз сборов Code-2 программа минта Token-2022 -- и у скольких из
     них налог на самом деле есть? «Token-2022» и «таксируемый» -- разные вещи, и
     именно на этой разнице строители теряли сигналы зря.
  2. СОШЛОСЬ ЛИ ПРАВИЛО `налог = min(ceil(сумма*bps/10000), максимум)` с полем
     налога в событиях свопов -- на всех живых сделках, где этот налог не ноль.
  3. СОВПАЛИ ЛИ СТАВКИ, выведенные из событий, со ставками аудита цепи
     (data/solana_transfer_fee_audit.json). Расхождение здесь -- не ошибка, а
     СЛЕД ТОГО, ЧТО СТАВКА МЕНЯЕТСЯ, и ровно поэтому в модуле есть правило эпохи.
  4. СКОЛЬКО СТОИТ РАЗБОР на горячем пути (CPU, без сети).

Чего проверка НЕ делает: не ходит в сеть и не проверяет смещения расширения на
настоящих байтах минта Token-2022 -- ни одного такого счёта в репозитории нет.
Поэтому байтовый путь проверен только своими сторожами (длина записи, тип счёта,
потолок ставки), а основной путь -- jsonParsed, где раскладкой владеет узел.
Ключ `--bayty <файл>` даёт Code-1 проверить байтовый путь на хосте одним минтом.
"""

