"""Проверка пути «DLMM одним чтением» -- офлайн, без сети и без симуляции.

Три вопроса, и на каждый -- число, а не мнение:

  1. НАХОДЯТСЯ ЛИ массивы корзин в самой сделке источника -- и именно массивы
     ЭТОГО пула (совпадение с PDA, а не похожий адрес)? Считается по живым
     сделкам DLMM, которые лежат в репозитории.
  2. ХВАТИЛО БЫ ИХ через 1, 2 и 3 слота -- то есть прошла бы проверка «активный
     массив среди прочитанных»? Считается по замеру Code-2
     (data/podbivka/dlmm_pokrytie.json), но СВОЕЙ арифметикой: индекс массива
     выводится здесь заново, а не берётся из его поля «покрыта». Если наши числа
     разойдутся -- это видно отдельной строкой, и тогда верить нельзя никому.
  3. СКОЛЬКО СТОИТ САМ ТРЮК на горячем пути -- выводы PDA считаются, и если они
     дороже сэкономленного чтения, затея бессмысленна.

Чего проверка НЕ делает и сделать не может: не считает цену на живых данных.
Для этого нужны снимки состояния пула и массивов в слоте S (как сборы Code-2 по
CLMM и Whirlpool); сбора по DLMM такого вида в репозитории нет, и выдумывать
байты пула здесь никто не будет. Поэтому равенство цен двух путей здесь НЕ
заявлено -- заявлено лишь то, что перечислено выше.

Сети не делает, ключей не трогает, ничего не отправляет.
"""

