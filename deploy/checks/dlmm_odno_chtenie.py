def процентиль(ряд, доля):
    ч = sorted(x for x in ряд if isinstance(x, (int, float)))
    if not ч:
        return None
    м = min(len(ч) - 1, max(0, int(round(доля * (len(ч) - 1)))))
    return ч[м]


# ------------------------------------------------- 1. массивы из живых сделок

def по_живым_сделкам(путь: str) -> dict:
    из_ = {"файл": путь, "свопов": 0, "массивы_нашлись": 0, "адреса_pda": 0,
            "корзины_источника_покрыты": 0, "массивов_в_сделке": {},
            "окно_хватило": 0, "окно_шире": 16,
            "мс": [], "why_not": None, "строки": []}
    import c2_dlmm_odno_chtenie as М
    import c2_swap_build as B

    if not os.path.exists(путь):
        из_["why_not"] = f"файла живых сделок нет: {путь}"
        return из_
    Q = М._порт()
    with open(путь, encoding="utf-8") as ф:
        образцы = json.load(ф)
    for о in образцы:
        tx = о.get("tx") or {}
        for с in B.события_dlmm(tx):
            из_["свопов"] += 1
            м = М.массивы_сделки(tx, с["пул"])
            строка = {"пул": с["пул"], "start": с["start_bin_id"],
                       "end": с["end_bin_id"], "ok": м["ok"],
                       "индексы": м["индексы"], "why_not": м["why_not"]}
            if м.get("мс") is not None:
                из_["мс"].append(м["мс"])
            if м["ok"]:
                из_["массивы_нашлись"] += 1
                к = str(len(м["индексы"]))
                из_["массивов_в_сделке"][к] = из_["массивов_в_сделке"].get(к, 0) + 1
                # АДРЕС ОБЯЗАН БЫТЬ PDA МАССИВА ЭТОГО ПУЛА С ЭТИМ ИНДЕКСОМ.
                if all(а == Q.адрес_массива(с["пул"], и)
                       for и, а in zip(м["индексы"], м["адреса"])):
                    из_["адреса_pda"] += 1
                свои = {Q.индекс_массива(int(с["start_bin_id"])),
                        Q.индекс_массива(int(с["end_bin_id"]))}
                строка["массивы_своих_корзин"] = sorted(свои)
                if свои <= set(м["индексы"]):
                    из_["корзины_источника_покрыты"] += 1
                # ОКНО ИНДЕКСОВ ХВАТАЕТ? Считаем тем же вызовом с окном ВЧЕТВЕРО
                # шире: если набор тот же, узкое окно ничего не потеряло. Иначе
                # рабочее окно мало, и мы читали бы не все массивы источника.
                ш = М.массивы_сделки(tx, с["пул"], окно=из_["окно_шире"])
                строка["окно_шире_индексы"] = ш["индексы"] if ш["ok"] else None
                if ш["ok"] and set(ш["индексы"]) == set(м["индексы"]):
                    из_["окно_хватило"] += 1
            из_["строки"].append(строка)
    return из_


# --------------------------------------- 2. хватило бы через 1 / 2 / 3 слота

def по_замеру_покрытия(путь: str) -> dict:
    """Своей арифметикой: лежит ли активная корзина в массивах транзакции.

    Числа Code-2 не переписываются, а ПЕРЕСЧИТЫВАЮТСЯ: индекс массива выводится
    здесь (индекс_массива переноса), «покрыта» его поля идёт отдельной графой, и
    расхождение видно, а не спрятано.
    """
    из_ = {"файл": путь, "покупок": 0, "по_слотам": {}, "расхождений_с_Code_2": 0,
            "why_not": None}
    import c2_dlmm_odno_chtenie as М

    if not os.path.exists(путь):
        из_["why_not"] = (f"файла замера покрытия нет: {путь} -- он в ветке Code-2 "
                           f"(data/podbivka/dlmm_pokrytie.json); укажите --pokrytie")
        return из_
    Q = М._порт()
    with open(путь, encoding="utf-8") as ф:
        д = json.load(ф)
    покупки = list((д or {}).get("покупки") or [])
    из_["покупок"] = len(покупки)
    for k in ("1", "2", "3"):
        свои = чужие = нет_данных = 0
        for п in покупки:
            по = (п.get("по_слотам") or {}).get(k) or {}
            активная = по.get("активная")
            массивы = [int(и) for и in (п.get("массивы_в_tx") or [])]
            if активная is None or not массивы:
                нет_данных += 1
                continue
            наш = Q.индекс_массива(int(активная)) in массивы
            свои += bool(наш)
            чужие += (not наш)
            если_их = по.get("покрыта_без_соседей")
            if если_их is not None and bool(если_их) != наш:
                из_["расхождений_с_Code_2"] += 1
        из_["по_слотам"][k] = {"проверка_прошла_бы": свои, "отказ_бы": чужие,
                                "без_данных": нет_данных}
    return из_


# ------------------------------------------------- 3. цена самого трюка (CPU)

def цена_трюка(путь: str, повторов: int = 200) -> dict:
    """Сколько миллисекунд стоит вывод адресов массивов из сделки источника.

    ПЕРВЫЙ вызов дороже: в нём импорт solders внутри функции. Меряем ПОСЛЕ
    прогрева -- на горячем пути модуль уже загружен, и холодное число там врёт.
    """
    из_ = {"повторов": повторов, "мс_p50": None, "мс_max": None, "why_not": None}
    import c2_dlmm_odno_chtenie as М
    import c2_swap_build as B

    if not os.path.exists(путь):
        из_["why_not"] = "живых сделок нет -- мерить не на чем"
        return из_
    with open(путь, encoding="utf-8") as ф:
        образцы = json.load(ф)
    задачи = []
    for о in образцы:
        tx = о.get("tx") or {}
        for с in B.события_dlmm(tx):
            задачи.append((tx, с["пул"]))
    if not задачи:
        из_["why_not"] = "свопов DLMM в живых сделках нет"
        return из_
    for tx, пул in задачи[:3]:          # прогрев
        М.массивы_сделки(tx, пул)
    ряд = []
    for _ in range(max(1, повторов // max(1, len(задачи)))):
        for tx, пул in задачи:
            т0 = time.perf_counter()
            М.массивы_сделки(tx, пул)
            ряд.append((time.perf_counter() - т0) * 1000.0)
    из_["замеров"] = len(ряд)
    из_["мс_p50"] = round(процентиль(ряд, 0.5), 3)
    из_["мс_max"] = round(процентиль(ряд, 1.0), 3)
    return из_


# ------------------------------------------------------------------- прогон

def прогон(*, образцы: str, покрытие: str | None) -> dict:
    из_ = {"путь": "DLMM одним чтением", "только_чтение": True, "сети_нет": True,
            "симуляции_нет": True, "why_not": None, "модуль_загружен": None,
            "порт_есть": None}
    try:
        import c2_dlmm_odno_chtenie as М
    except Exception as exc:  # noqa: BLE001
        из_["модуль_загружен"] = False
        из_["why_not"] = f"модуль не загружен: {type(exc).__name__}: {exc}"
        return из_
    из_["модуль_загружен"] = True
    из_["порт_есть"] = bool(М.порт_есть())
    if not из_["порт_есть"]:
        из_["why_not"] = ("переноса podbivka_dlmm_quote нет -- без него ни адресов "
                           "массивов, ни цены; укажите --porty")
        return из_
    из_["чтений_было"] = 2
    из_["чтений_стало"] = 1
    из_["живые_сделки"] = по_живым_сделкам(образцы)
    из_["покрытие"] = по_замеру_покрытия(покрытие) if покрытие else {
        "why_not": "замер покрытия не указан (--pokrytie)"}
    из_["цена_трюка"] = цена_трюка(образцы)
    return из_


def печать(о: dict) -> None:
    print("=== DLMM одним чтением -- проверка офлайн, без сети ===")
    if о.get("why_not"):
        print(f"  не сделано: {о['why_not']}")
        return
    print(f"  запросов к узлу на горячем пути: было {о['чтений_было']}, "
          f"стало {о['чтений_стало']}")
    ж = о.get("живые_сделки") or {}
    if ж.get("why_not"):
        print(f"  живые сделки: {ж['why_not']}")
    else:
        print(f"  живые сделки DLMM в репозитории: свопов {ж['свопов']}; "
              f"массивы нашлись у {ж['массивы_нашлись']}; все адреса -- PDA "
              f"массива этого пула у {ж['адреса_pda']}; корзины самого источника "
              f"лежат в найденных массивах у {ж['корзины_источника_покрыты']}")
        print(f"  массивов в сделке источника: {ж['массивов_в_сделке']}; рабочего "
              f"окна индексов хватило (тот же набор при окне {ж['окно_шире']}) у "
              f"{ж['окно_хватило']} из {ж['массивы_нашлись']}")
    п = о.get("покрытие") or {}
    if п.get("why_not"):
        print(f"  хватило бы через 1/2/3 слота: {п['why_not']}")
    else:
        print(f"  замер Code-2, пересчитанный здесь ({п['покупок']} покупок): "
              f"проверка «активный массив среди прочитанных» прошла бы")
        for k in ("1", "2", "3"):
            с = п["по_слотам"][k]
            print(f"      через {k} слот(а): {с['проверка_прошла_бы']} из "
                  f"{п['покупок']}, отказ бы {с['отказ_бы']}, без данных "
                  f"{с['без_данных']}")
        print(f"  расхождений с полем «покрыта» у Code-2: "
              f"{п['расхождений_с_Code_2']}")
    ц = о.get("цена_трюка") or {}
    if ц.get("why_not"):
        print(f"  цена трюка: {ц['why_not']}")
    else:
        print(f"  цена трюка (вывод адресов массивов из сделки, {ц['замеров']} "
              f"замеров после прогрева): p50 {ц['мс_p50']} мс, max {ц['мс_max']} мс")
    print("  цена ДЕНЕГ здесь не считалась: снимков состояния DLMM в репозитории "
          "нет, и равенство цен двух путей НЕ заявлено")


def main() -> int:
    р = argparse.ArgumentParser(description=__doc__)
    р.add_argument("--obrazcy", default=os.path.join(КОРЕНЬ, ОБРАЗЦЫ),
                   help="файл живых сделок DLMM")
    р.add_argument("--pokrytie", default=None,
                   help="data/podbivka/dlmm_pokrytie.json из ветки Code-2")
    р.add_argument("--porty", default=None,
                   help="каталог с переносами Code-2 (podbivka_*_quote)")
    р.add_argument("--out", default=None, help="куда положить отчёт json")
    р.add_argument("--self-test", dest="self_test", action="store_true")
    а = р.parse_args()
    if а.porty:
        os.environ["BLOOM_PODBIVKA_DIR"] = а.porty
    if а.self_test:
        import c2_dlmm_odno_chtenie as М
        return М.self_test()
    о = прогон(образцы=а.obrazcy, покрытие=а.pokrytie)
    печать(о)
    if а.out:
        with open(а.out, "w", encoding="utf-8") as ф:
            json.dump(о, ф, ensure_ascii=False, indent=1)
        print(f"  отчёт: {а.out}")
    # КОД ВОЗВРАТА. 2 -- прогон не состоялся (нечего было проверять), 1 -- что-то
    # не сошлось, 0 -- всё сошлось. Молчаливый ноль на пустом прогоне пропустил
    # бы регресс мимо автоматики.
    if о.get("why_not"):
        return 2
    ж = о.get("живые_сделки") or {}
    if ж.get("why_not") or not ж.get("свопов"):
        return 2
    плохо = []
    if ж["массивы_нашлись"] != ж["свопов"]:
        плохо.append(f"массивы нашлись {ж['массивы_нашлись']} из {ж['свопов']}")
    if ж["адреса_pda"] != ж["массивы_нашлись"]:
        плохо.append(f"адреса -- PDA у {ж['адреса_pda']} из {ж['массивы_нашлись']}")
    if ж["корзины_источника_покрыты"] != ж["свопов"]:
        плохо.append(f"свои корзины покрыты у {ж['корзины_источника_покрыты']} "
                      f"из {ж['свопов']}")
    if ж["окно_хватило"] != ж["массивы_нашлись"]:
        плохо.append(f"рабочего окна индексов хватило у {ж['окно_хватило']} из "
                      f"{ж['массивы_нашлись']} -- окно мало")
    п = о.get("покрытие") or {}
    if not п.get("why_not") and п.get("расхождений_с_Code_2"):
        плохо.append(f"расхождений с замером Code-2: {п['расхождений_с_Code_2']}")
    if плохо:
        print("  НЕ СОШЛОСЬ: " + "; ".join(плохо))
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
