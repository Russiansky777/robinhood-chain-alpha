#!/usr/bin/env python3
"""Воронка полосы по журналу решений: gate / build / sent по группам + причины.

ЗАЧЕМ (слово владельца 04.10, 12:30Z, СРОЧНО): "воронка gate / build / sent по
группам с 10:40Z и верхние 5 причин отказов".

ПОЧЕМУ ПО ЖУРНАЛУ, А НЕ ПО ПРИЗНАКУ ЖИЗНИ. Счётчики признака жизни (own_send
by_stage, starts, sent) обнуляются ПЕРЕЗАПУСКОМ службы. Именно это и мешает:
деплой 10:43:26Z обнулил их, деплой 11:57:30Z обнулил снова, и окно 10:44-11:57,
про которое спрашивает владелец, в признаке жизни не существует вовсе. Журнал
решений лежит на диске и перезапуск переживает.

ЧЕГО ЗДЕСЬ НЕТ. Ни сети, ни хоста: на вход идёт готовый jsonl. Ни одного
значения ключа: в строках журнала их и не бывает, но на всякий случай наружу
уходят только имена этапов, групп и тексты причин, обрезанные по 160 знаков.
"""
from __future__ import annotations

import json
import sys
from collections import Counter
from pathlib import Path

# Строка ПОПЫТКИ ПОЛОСЫ узнаётся по полю own_send_total_ms: его ставит ровно
# тот кусок детектора, который ведёт полосу (bloom_detector.py:4757). Отбирать
# по наличию "stage" нельзя: это поле есть и у чужих строк.
ПРИЗНАК_ПОЛОСЫ = "own_send_total_ms"


def разобрать(строки, *, с: str | None = None, до: str | None = None) -> dict:
    """Воронка из строк журнала. Чистая функция.

    Время сравнивается как СТРОКА в формате ISO с Z: он лексикографически
    упорядочен, и это честнее разбора даты -- разбор упал бы на первой же
    строке с чужим форматом, а здесь такая строка просто не попадёт в окно.
    """
    из_: dict = {"строк_всего": 0, "попыток_полосы": 0, "в_окне": 0,
                  "с": с, "до": до, "по_этапам": {}, "по_группам": {},
                  "причины": {}, "первая_utc": None, "последняя_utc": None,
                  "отправлено": 0, "подписи": []}
    этапы: Counter = Counter()
    группы: dict = {}
    причины: dict = {}
    for сырая in строки:
        из_["строк_всего"] += 1
        с_ = сырая.strip()
        if not с_:
            continue
        try:
            р = json.loads(с_)
        except ValueError:
            continue
        if not isinstance(р, dict) or ПРИЗНАК_ПОЛОСЫ not in р:
            continue
        из_["попыток_полосы"] += 1
        т = str(р.get("ts_utc") or "")
        if с and т and т < с:
            continue
        if до and т and т > до:
            continue
        из_["в_окне"] += 1
        if т:
            из_["первая_utc"] = т if из_["первая_utc"] is None else min(из_["первая_utc"], т)
            из_["последняя_utc"] = т if из_["последняя_utc"] is None else max(из_["последняя_utc"], т)
        этап = str(р.get("stage") or "?")
        этапы[этап] += 1
        гр = str(р.get("group") or "?")
        группы.setdefault(гр, Counter())[этап] += 1
        if р.get("sent"):
            из_["отправлено"] += 1
            if р.get("signature"):
                из_["подписи"].append({"ts_utc": т, "group": гр,
                                        "signature": str(р["signature"])})
        if not р.get("ok"):
            почему = str(р.get("why_not") or "причина не названа")[:160]
            причины.setdefault(этап, Counter())[почему] += 1
    из_["по_этапам"] = dict(этапы)
    из_["по_группам"] = {г: dict(с_) for г, с_ in sorted(группы.items())}
    из_["причины"] = {э: [{"почему": п, "раз": н} for п, н in с_.most_common(5)]
                       for э, с_ in sorted(причины.items())}
    return из_


def _самопроверка() -> int:
    проверок = прошло = 0

    def сверить(что, дано, ждали):
        nonlocal проверок, прошло
        проверок += 1
        if дано == ждали:
            прошло += 1
        else:
            print(f"НЕ ПРОШЛО: {что}: дано {дано!r}, ждали {ждали!r}")

    def стр(**кв):
        return json.dumps({ПРИЗНАК_ПОЛОСЫ: 1.0, **кв}, ensure_ascii=False)

    журнал = [
        стр(ts_utc="2026-10-04T10:30:00Z", stage="gate", ok=False,
            why_not="предел за сутки", group="cand2"),
        стр(ts_utc="2026-10-04T10:50:00Z", stage="gate", ok=False,
            why_not="предел за сутки", group="cand2"),
        стр(ts_utc="2026-10-04T11:00:00Z", stage="build", ok=False,
            why_not="пул: в транзакции нет хранилища минта", group="batch5"),
        стр(ts_utc="2026-10-04T12:18:56Z", stage="sent", ok=True, sent=True,
            signature="ПОДПИСЬ1", group="cand2"),
        # Чужая строка БЕЗ признака полосы -- в воронку не попадает.
        json.dumps({"ts_utc": "2026-10-04T11:05:00Z", "stage": "gate",
                     "code": "NOT_A_BUY"}),
        "не json вовсе",
        "",
    ]
    в = разобрать(журнал, с="2026-10-04T10:40:00Z")
    сверить("строк всего считается по всем, включая чужие", в["строк_всего"], 7)
    сверить("попыток полосы -- только со своим признаком", в["попыток_полосы"], 4)
    сверить("в окно с 10:40Z попали три", в["в_окне"], 3)
    сверить("по этапам", в["по_этапам"], {"gate": 1, "build": 1, "sent": 1})
    сверить("по группам", в["по_группам"],
            {"batch5": {"build": 1}, "cand2": {"gate": 1, "sent": 1}})
    сверить("отправлено", в["отправлено"], 1)
    сверить("подпись отдана с временем и группой",
            в["подписи"], [{"ts_utc": "2026-10-04T12:18:56Z", "group": "cand2",
                             "signature": "ПОДПИСЬ1"}])
    сверить("причины по этапам",
            в["причины"],
            {"build": [{"почему": "пул: в транзакции нет хранилища минта", "раз": 1}],
             "gate": [{"почему": "предел за сутки", "раз": 1}]})
    сверить("границы окна названы фактическими строками",
            (в["первая_utc"], в["последняя_utc"]),
            ("2026-10-04T10:50:00Z", "2026-10-04T12:18:56Z"))
    # БЕЗ ОКНА -- ВСЁ, и строка до 10:40 тоже.
    без = разобрать(журнал)
    сверить("без окна попадают все попытки полосы", без["в_окне"], 4)
    сверить("и причина 'предел за сутки' стала двойной",
            без["причины"]["gate"], [{"почему": "предел за сутки", "раз": 2}])
    # ВЕРХНИЕ ПЯТЬ, А НЕ ВСЕ.
    много = [стр(ts_utc="2026-10-04T11:00:0%dZ" % (i % 10), stage="gate",
                 ok=False, why_not=f"причина {i}", group="g") for i in range(9)]
    сверить("причин отдаётся не больше пяти",
            len(разобрать(много)["причины"]["gate"]), 5)
    # ОТКАЗ БЕЗ ТЕКСТА -- НАЗВАН, А НЕ ПРОПУЩЕН: молчащий отказ хуже любого.
    сверить("отказ без причины назван словами",
            разобрать([стр(ts_utc="2026-10-04T11:00:00Z", stage="gate",
                            ok=False, group="g")])["причины"]["gate"],
            [{"почему": "причина не названа", "раз": 1}])
    # УДАЧНАЯ ПОПЫТКА В ПРИЧИНЫ НЕ ПОПАДАЕТ.
    сверить("удачная попытка не даёт причины отказа",
            разобрать([стр(ts_utc="2026-10-04T11:00:00Z", stage="sent",
                            ok=True, sent=True, group="g")])["причины"], {})
    # СТРОКА БЕЗ ВРЕМЕНИ не выкидывается из окна молча: окно её пропускает.
    сверить("строка без времени считается в окне",
            разобрать([стр(stage="gate", ok=False, group="g")],
                       с="2026-10-04T10:40:00Z")["в_окне"], 1)
    сверить("этап без имени назван вопросом, а не пропущен",
            разобрать([стр(ts_utc="2026-10-04T11:00:00Z", ok=False,
                            group="g")])["по_этапам"], {"?": 1})
    print(f"проверок {проверок}, прошло {прошло}, "
          f"не прошло {проверок - прошло}")
    return 0 if прошло == проверок else 1


def main(довод: list) -> int:
    if not довод:
        print("нужен путь к decisions.jsonl [с_utc] [до_utc]")
        return 2
    путь = Path(довод[0])
    с = довод[1] if len(довод) > 1 and довод[1] else None
    до = довод[2] if len(довод) > 2 and довод[2] else None
    with путь.open(encoding="utf-8", errors="replace") as ф:
        из_ = разобрать(ф, с=с, до=до)
    print(json.dumps(из_, ensure_ascii=False, indent=1))
    return 0


if __name__ == "__main__":
    if "--self-test" in sys.argv:
        sys.exit(_самопроверка())
    sys.exit(main([а for а in sys.argv[1:] if not а.startswith("--")]))
