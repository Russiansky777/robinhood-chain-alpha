#!/usr/bin/env python3
"""Куда ушла трата источника: по лампортам, а не по доле.

ЗАЧЕМ (вопрос второй сессии 27.09, п.22). У неё «доля траты, дошедшей до пула»
на четверти первых покупок Pump AMM ниже 0.80, и принятые 20 худших стоят ровно
у границы с расхождением -19 п.п. Её догадка: в трату берётся ВСЁ уменьшение
нативного SOL у кошелька источника, а туда входят выплаты мимо пула -- сбор
бота или маршрутизатора, чаевые, вторая нога маршрута. Тогда расхождение --
не комиссия пула, а способ счёта.

ЧТО СЧИТАЕТСЯ ЗДЕСЬ, по каждой подписи:
  трата           -- уменьшение нативного SOL у кошелька источника (как у неё);
  в_пул           -- НА СКОЛЬКО ВЫРОС котировочный склад пула в этой же
                     транзакции (WSOL как токен-счёт или нативный, смотрим оба);
  тариф           -- meta.fee целиком, и отдельно базовый 5000 на подпись;
  рента_ata       -- прирост нативного у счетов, созданных в этой транзакции;
  прочие_получатели -- все остальные адреса, у которых нативный SOL ВЫРОС, с
                     суммами: это и есть выплаты мимо пула;
  необъяснённое   -- трата минус всё перечисленное.

Ни одной отправки. Измерительный код -- без самопроверок (Правило 8).
"""
from __future__ import annotations

import argparse
import csv
import json
import sys
import time
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parent.parent.parent
sys.path.insert(0, str(КОРЕНЬ / "analysis"))

ЛАМПОРТОВ_В_SOL = 1_000_000_000
БАЗОВЫЙ_ТАРИФ = 5_000
WSOL = "So11111111111111111111111111111111111111112"


def счета_чаевых(путь) -> dict:
    """{адрес: имя отправителя} из реестра отправителей пула."""
    из_ = {}
    try:
        д = json.loads(Path(путь).read_text(encoding="utf-8"))
    except Exception:  # noqa: BLE001
        return из_
    for имя, тело in (д.get("senders") or {}).items():
        for а in (тело.get("tip_accounts") or []):
            из_[а] = имя
    return из_


def ключи(tx: dict) -> list:
    к = ((tx or {}).get("transaction") or {}).get("message", {}).get("accountKeys", [])
    return [(x.get("pubkey") if isinstance(x, dict) else x) for x in к]


def нативные_дельты(tx: dict) -> dict:
    мета = (tx or {}).get("meta") or {}
    до, после = мета.get("preBalances") or [], мета.get("postBalances") or []
    из_ = {}
    for и, адрес in enumerate(ключи(tx)):
        if и < len(до) and и < len(после):
            из_[адрес] = после[и] - до[и]
    return из_


def токен_дельты(tx: dict) -> dict:
    """{адрес счёта: (минт, дельта, владелец)} по индексу счёта."""
    мета = (tx or {}).get("meta") or {}
    к = ключи(tx)

    def собрать(ряды):
        из_ = {}
        for б in ряды or []:
            и = б.get("accountIndex")
            if и is None or и >= len(к):
                continue
            из_[к[и]] = (б.get("mint"),
                          int((б.get("uiTokenAmount") or {}).get("amount") or 0),
                          б.get("owner"))
        return из_

    до, после = собрать(мета.get("preTokenBalances")), собрать(мета.get("postTokenBalances"))
    из_ = {}
    for адрес in set(до) | set(после):
        осн = после.get(адрес) or до.get(адрес) or (None, 0, None)
        д_до = до.get(адрес, (осн[0], 0, осн[2]))[1]
        д_после = после.get(адрес, (осн[0], 0, осн[2]))[1]
        из_[адрес] = (осн[0], д_после - д_до, осн[2])
    return из_


def склад_по_цепи(ток: dict, кошелёк: str) -> tuple:
    """Котировочный склад пула, если его не дали: счёт WSOL, который ВЫРОС и
    принадлежит НЕ нам. Возвращает (адрес, лампорты, как определён)."""
    лучший, сколько = None, 0
    for адрес, (м, д, владелец) in ток.items():
        if м != WSOL or д <= 0 or владелец == кошелёк:
            continue
        if д > сколько:
            лучший, сколько = адрес, д
    if лучший:
        return лучший, сколько, "найден по цепи: счёт WSOL вырос, владелец не мы"
    return None, 0, "склад WSOL с приростом не найден"


def разобрать(tx: dict, кошелёк: str, склад_котировки: str | None,
              чаевые_метки: dict | None = None) -> dict:
    мета = (tx or {}).get("meta") or {}
    нат = нативные_дельты(tx)
    ток = токен_дельты(tx)
    подписей = len(((tx or {}).get("transaction") or {}).get("signatures") or []) or 1
    тариф = int(мета.get("fee") or 0)
    трата = -(нат.get(кошелёк) or 0)

    # В ПУЛ. Котировочный склад может быть токен-счётом WSOL или нативным.
    в_пул = 0
    как = "нет данных о складе"
    if склад_котировки and склад_котировки in ток:
        м, д, _вл = ток[склад_котировки]
        if д > 0:
            в_пул, как = д, f"склад из списка, токен-счёт ({(м or '?')[:6]})"
    if в_пул == 0 and склад_котировки and (нат.get(склад_котировки) or 0) > 0:
        в_пул, как = нат[склад_котировки], "склад из списка, нативный прирост"
    if в_пул == 0:
        склад_котировки, в_пул, как = склад_по_цепи(ток, кошелёк)

    метки = чаевые_метки or {}
    прочие = sorted(((а, д) for а, д in нат.items()
                     if д > 0 and а not in (кошелёк, склад_котировки)),
                    key=lambda x: -x[1])
    сумма_прочих = sum(д for _, д in прочие)
    чаевые = sum(д for а, д in прочие if а in метки)
    необъяснённое = трата - в_пул - тариф - сумма_прочих
    return {
        "трата_лампорты": трата,
        "в_пул_лампорты": в_пул, "в_пул_как": как,
        "тариф_лампорты": тариф,
        "базовый_лампорты": БАЗОВЫЙ_ТАРИФ * подписей,
        "приоритет_лампорты": max(0, тариф - БАЗОВЫЙ_ТАРИФ * подписей),
        "склад_котировки": склад_котировки,
        "чаевые_лампорты": чаевые,
        "прочие_получатели": [{"адрес": а, "лампорты": д,
                                "отправитель": метки.get(а)} for а, д in прочие[:8]],
        "прочих_всего_лампорты": сумма_прочих,
        "прочих_адресов": len(прочие),
        "необъяснённое_лампорты": необъяснённое,
        "доля_в_пул_от_траты": (round(в_пул / трата, 6) if трата else None),
        "доля_прочих_от_траты": (round(сумма_прочих / трата, 6) if трата else None),
    }


def main() -> int:
    р = argparse.ArgumentParser()
    р.add_argument("--csv", action="append", default=[],
                   help="списки Code-2 (с колонкой pool_vault_quote)")
    р.add_argument("--nashi", default="",
                   help="JSON наших покупок: signature, wallet, mint, program")
    р.add_argument("--senders", default=str(КОРЕНЬ / "data" / "senders.json"))
    р.add_argument("--out", required=True)
    а = р.parse_args()
    метки = счета_чаевых(а.senders)
    print(f"адресов чаевых в реестре: {len(метки)}")

    import solana_buyer200_fast_price as fp  # noqa: PLC0415

    ряды = []
    for путь in а.csv:
        for стр in csv.DictReader(open(путь, encoding="utf-8")):
            стр["_файл"] = Path(путь).name
            ряды.append(стр)
    if а.nashi:
        д = json.loads(Path(а.nashi).read_text(encoding="utf-8"))
        for стр in (д.get("ряды") if isinstance(д, dict) else д):
            ряды.append({"signature": стр["signature"], "wallet": стр["wallet"],
                          "mint": стр.get("mint") or "", "pool_vault_quote": "",
                          "трата_sol": стр.get("sol_in") or 0,
                          "f_факт": стр.get("f_факт") or 0,
                          "_файл": "наши"})
    print(f"подписей к разбору: {len(ряды)}")

    итоги = []
    for и, стр in enumerate(ряды, 1):
        подпись = стр["signature"]
        tx = fp.get_transaction(подпись)
        if tx is None:
            итоги.append({**{к: стр.get(к) for к in ("signature", "wallet", "mint",
                                                      "pool_vault_quote", "f_факт", "_файл")},
                           "почему": "getTransaction не отдал транзакцию"})
            continue
        раз = разобрать(tx, стр["wallet"], стр.get("pool_vault_quote") or None, метки)
        итоги.append({
            "signature": подпись, "файл": стр["_файл"],
            "wallet": стр["wallet"], "mint": стр["mint"],
            "f_факт_у_code2": float(стр["f_факт"]),
            "трата_sol_у_code2": float(стр["трата_sol"]),
            **{к: (round(v / ЛАМПОРТОВ_В_SOL, 9) if к.endswith("_лампорты")
                   and isinstance(v, int) else v)
               for к, v in раз.items() if к != "прочие_получатели"},
            "прочие_получатели": [{"адрес": п["адрес"],
                                    "sol": round(п["лампорты"] / ЛАМПОРТОВ_В_SOL, 9)}
                                   for п in раз["прочие_получатели"]],
        })
        if и % 5 == 0:
            print(f"  разобрано {и}/{len(ряды)}")

    ок = [x for x in итоги if "почему" not in x]

    def медиана(v):
        v = sorted(v)
        if not v:
            return None
        н = len(v)
        return round(v[н // 2] if н % 2 else (v[н // 2 - 1] + v[н // 2]) / 2, 6)

    def свод_по(файл):
        под = [x for x in ок if x["файл"] == файл]
        if not под:
            return None
        return {"n": len(под),
                "медиана_доли_в_пул": медиана([x["доля_в_пул_от_траты"] for x in под
                                                if x["доля_в_пул_от_траты"] is not None]),
                "медиана_доли_прочих": медиана([x["доля_прочих_от_траты"] for x in под
                                                 if x["доля_прочих_от_траты"] is not None]),
                "медиана_чаевых_sol": медиана([x["чаевые_лампорты"] for x in под]),
                "медиана_тарифа_sol": медиана([x["тариф_лампорты"] for x in под]),
                "медиана_траты_sol": медиана([x["трата_лампорты"] for x in под])}

    def сред(поле):
        v = [x[поле] for x in ок if x.get(поле) is not None]
        return round(sum(v) / len(v), 6) if v else None

    свод = {"снято_utc": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
            "подписей": len(итоги), "разобрано": len(ок),
            "средняя_доля_в_пул": сред("доля_в_пул_от_траты"),
            "средняя_доля_прочих": сред("доля_прочих_от_траты"),
            "средняя_f_факт_у_code2": (round(sum(x["f_факт_у_code2"] for x in ок) / len(ок), 6)
                                        if ок else None),
            "по_файлам": {ф: свод_по(ф) for ф in sorted({x["файл"] for x in ок})},
            "ряды": итоги}
    Path(а.out).write_text(json.dumps(свод, ensure_ascii=False, indent=1), encoding="utf-8")

    print(f"разобрано {len(ок)}/{len(итоги)}")
    for ф, с in (свод["по_файлам"] or {}).items():
        if с:
            print(f"  {ф}: n={с['n']} медиана доли в пул {с['медиана_доли_в_пул']}, "
                  f"прочим {с['медиана_доли_прочих']}, чаевые {с['медиана_чаевых_sol']}, "
                  f"тариф {с['медиана_тарифа_sol']}, трата {с['медиана_траты_sol']}")
    for x in итоги[:24]:
        if "почему" in x:
            print(f"  {x['signature'][:10]} -- {x['почему']}")
            continue
        п = ", ".join(f"{r['адрес'][:8]}:{r['sol']:.6f}" for r in x["прочие_получатели"][:3])
        print(f"  {x['signature'][:10]} {x['файл'][:14]} трата {x['трата_лампорты']:.6f} "
              f"в пул {x['в_пул_лампорты']:.6f} ({x['в_пул_как']}) "
              f"тариф {x['тариф_лампорты']:.6f} прочим {x['прочих_всего_лампорты']:.6f} "
              f"({x['прочих_адресов']} адр: {п}) "
              f"необъясн {x['необъяснённое_лампорты']:.6f} | доля в пул "
              f"{x['доля_в_пул_от_траты']}, у Code-2 {x['f_факт_у_code2']}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
