#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Что именно изменит деплой, и не потеряется ли при нём чужая правка.

ЗАЧЕМ. Над одним и тем же денежным модулем работают несколько исполнителей.
Найдено 29.09 ночью: bloom_own_send.py на хосте совпал по sha256 с версией
ветки claude/stroiteli, а не с моей рабочей -- то есть службы едут НЕ на том
коде, что лежит у меня. Деплой "своей" ветки в такой обстановке может молча
снести чужую правку, и узнать об этом можно будет только по сделкам.

ЧТО СЧИТАЕТСЯ. Для каждого модуля: sha256 того, что СТОИТ на хосте, и того, что
в ветке; если они разные -- сколько строк есть ТОЛЬКО на хосте (эти деплой
УНЕСЁТ) и сколько только в ветке (эти он добавит).

  строк_только_на_хосте == 0  ->  ветка -- надстройка над живым кодом,
                                  деплой ничего не теряет;
  строк_только_на_хосте  > 0  ->  ТРЕВОГА: деплой унесёт чужое, и разбираться
                                  надо до него, а не после.

Никаких догадок: файла нет с любой стороны -- так и сказано словами.
Только чтение, ни одной правки. Сравнение построчное (difflib), не по mtime:
mtime врёт при перезаписи байт в байт.
"""

from __future__ import annotations

import argparse
import difflib
import hashlib
import json
import os
import time

# ДЕНЕЖНЫЙ ПУТЬ ПОЛОСЫ. Список нарочно короткий: это те модули, чья подмена
# меняет деньги, а не отчёты.
МОДУЛИ = ("bloom_own_send.py", "bloom_detector.py", "bloom_seller.py",
           "bloom_exec_state.py", "bloom_region_send.py", "bloom_doklad.py",
           "c2_swap_build.py", "bloom_senders.py")


def отпечаток(путь: str):
    """sha256 файла (первые 16 знаков) или None, если файла нет."""
    if not путь or not os.path.isfile(путь):
        return None
    х = hashlib.sha256()
    with open(путь, "rb") as ф:
        for кусок in iter(lambda: ф.read(65536), b""):
            х.update(кусок)
    return х.hexdigest()[:16]


def строки_файла(путь: str) -> list:
    if not путь or not os.path.isfile(путь):
        return []
    with open(путь, encoding="utf-8", errors="replace") as ф:
        return ф.readlines()


def сравнить_один(на_хосте: str, в_ветке: str) -> dict:
    """Сравнение одного модуля. Ключи: sha_*, только_*, вердикт, why_not."""
    их = {"sha_на_хосте": отпечаток(на_хосте), "sha_в_ветке": отпечаток(в_ветке),
           "строк_только_на_хосте": None, "строк_только_в_ветке": None,
           "вердикт": None, "why_not": None}
    if их["sha_на_хосте"] is None and их["sha_в_ветке"] is None:
        их["why_not"] = "модуля нет ни на хосте, ни в ветке"
        их["вердикт"] = "нечего сравнивать"
        return их
    if их["sha_на_хосте"] is None:
        их["why_not"] = "на хосте модуля нет -- деплой его ДОБАВИТ"
        их["вердикт"] = "новый файл"
        return их
    if их["sha_в_ветке"] is None:
        их["why_not"] = "в ветке модуля нет -- деплой его не тронет"
        их["вердикт"] = "ветка молчит"
        return их
    if их["sha_на_хосте"] == их["sha_в_ветке"]:
        их.update(строк_только_на_хосте=0, строк_только_в_ветке=0,
                   вердикт="совпадает байт в байт")
        return их
    х, в = строки_файла(на_хосте), строки_файла(в_ветке)
    только_хост = только_ветка = 0
    for д in difflib.ndiff(х, в):
        if д.startswith("- "):
            только_хост += 1
        elif д.startswith("+ "):
            только_ветка += 1
    их.update(строк_только_на_хосте=только_хост,
               строк_только_в_ветке=только_ветка,
               вердикт=("ТРЕВОГА: деплой унесёт строки, которых в ветке нет"
                        if только_хост else "надстройка: деплой ничего не теряет"))
    return их


def свод(по_модулям: dict) -> dict:
    тревог = sum(1 for з in по_модулям.values()
                  if (з.get("строк_только_на_хосте") or 0) > 0)
    совпало = sum(1 for з in по_модулям.values()
                   if з.get("вердикт") == "совпадает байт в байт")
    надстройка = sum(1 for з in по_модулям.values()
                      if з.get("вердикт") == "надстройка: деплой ничего не теряет")
    return {"модулей": len(по_модулям), "тревог": тревог,
             "совпадает_байт_в_байт": совпало, "надстройка": надстройка,
             "можно_деплоить_без_разбора": тревог == 0}


def самопроверка() -> int:
    import tempfile  # noqa: PLC0415

    всего = сбоев = 0

    def chk(имя, ок, что=None):
        nonlocal всего, сбоев
        всего += 1
        print(f"  [{'ok  ' if ок else 'СБОЙ'}] {имя}")
        if not ок:
            сбоев += 1
            if что is not None:
                print(f"         {что!r}")

    with tempfile.TemporaryDirectory() as кат:
        х = os.path.join(кат, "host.py")
        в = os.path.join(кат, "vetka.py")
        with open(х, "w", encoding="utf-8") as ф:
            ф.write("a = 1\nb = 2\n")
        with open(в, "w", encoding="utf-8") as ф:
            ф.write("a = 1\nb = 2\n")
        р = сравнить_один(х, в)
        chk("одинаковые файлы -- совпадает байт в байт, нулей не выдумано",
            р["вердикт"] == "совпадает байт в байт"
            and р["строк_только_на_хосте"] == 0, р)
        with open(в, "w", encoding="utf-8") as ф:
            ф.write("a = 1\nb = 2\nc = 3\n")
        р = сравнить_один(х, в)
        chk("ветка -- надстройка: деплой ничего не теряет",
            р["вердикт"].startswith("надстройка")
            and р["строк_только_на_хосте"] == 0
            and р["строк_только_в_ветке"] == 1, р)
        with open(в, "w", encoding="utf-8") as ф:
            ф.write("a = 1\n")
        р = сравнить_один(х, в)
        chk("в ветке строки нет -- ТРЕВОГА, деплой её унесёт",
            р["вердикт"].startswith("ТРЕВОГА")
            and р["строк_только_на_хосте"] == 1, р)
        chk("на хосте файла нет -- деплой добавит, и это сказано словами",
            сравнить_один(os.path.join(кат, "нету.py"), в)["вердикт"]
            == "новый файл")
        chk("в ветке файла нет -- деплой не тронет",
            сравнить_один(х, os.path.join(кат, "нету.py"))["вердикт"]
            == "ветка молчит")
        chk("нет нигде -- причина словами, а не совпадение",
            сравнить_один(os.path.join(кат, "нет1.py"),
                           os.path.join(кат, "нет2.py"))["why_not"])
        chk("отпечаток отсутствующего файла -- None, а не пустая строка",
            отпечаток(os.path.join(кат, "нет3.py")) is None)
        с = свод({"a": {"строк_только_на_хосте": 0,
                         "вердикт": "совпадает байт в байт"},
                   "b": {"строк_только_на_хосте": 3, "вердикт": "ТРЕВОГА"}})
        chk("одна тревога запрещает деплой без разбора",
            с["тревог"] == 1 and с["можно_деплоить_без_разбора"] is False, с)
        с = свод({"a": {"строк_только_на_хосте": 0,
                         "вердикт": "надстройка: деплой ничего не теряет"}})
        chk("одни надстройки -- деплой разрешён",
            с["можно_деплоить_без_разбора"] is True, с)
    print(f"самопроверка «что изменит деплой»: {всего - сбоев}/{всего} пройдено")
    return 1 if сбоев else 0


def main() -> int:
    р = argparse.ArgumentParser()
    р.add_argument("--s-hosta", default="",
                    help="каталог с копиями модулей, снятыми с хоста")
    р.add_argument("--vetka", default="analysis",
                    help="каталог модулей рабочей ветки")
    р.add_argument("--moduli", default="",
                    help="список модулей через запятую (пусто -- денежный путь)")
    р.add_argument("--out", default="")
    р.add_argument("--self-test", action="store_true")
    а = р.parse_args()
    if а.self_test:
        return самопроверка()
    if not а.s_hosta:
        print("СБОЙ: --s-hosta не задан, сравнивать не с чем")
        return 2
    модули = ([м.strip() for м in а.moduli.split(",") if м.strip()]
               or list(МОДУЛИ))
    по_модулям = {}
    print("%-24s %-18s %-18s %-7s %-7s %s"
           % ("модуль", "на хосте", "в ветке", "только", "только", "вердикт"))
    print("%-24s %-18s %-18s %-7s %-7s %s"
           % ("", "sha256", "sha256", "хост", "ветка", ""))
    for м in модули:
        з = сравнить_один(os.path.join(а.s_hosta, м), os.path.join(а.vetka, м))
        по_модулям[м] = з
        print("%-24s %-18s %-18s %-7s %-7s %s"
               % (м, з["sha_на_хосте"] or "-", з["sha_в_ветке"] or "-",
                  "-" if з["строк_только_на_хосте"] is None
                  else з["строк_только_на_хосте"],
                  "-" if з["строк_только_в_ветке"] is None
                  else з["строк_только_в_ветке"], з["вердикт"]))
        if з.get("why_not"):
            print(f"      {з['why_not']}")
    с = свод(по_модулям)
    print()
    print(f"модулей {с['модулей']}, совпадает байт в байт "
           f"{с['совпадает_байт_в_байт']}, надстройка {с['надстройка']}, "
           f"ТРЕВОГ {с['тревог']}")
    print("деплой ничего не унесёт" if с["можно_деплоить_без_разбора"]
           else "ДЕПЛОЙ УНЕСЁТ ЧУЖИЕ СТРОКИ -- разобрать ДО него")
    итог = {"снято_utc": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
             "каталог_хоста": а.s_hosta, "каталог_ветки": а.vetka,
             **с, "по_модулям": по_модулям}
    if а.out:
        with open(а.out, "w", encoding="utf-8") as ф:
            json.dump(итог, ф, ensure_ascii=False, indent=1)
        print(f"записано: {а.out}")
    # НЕНУЛЕВОЙ КОД ПРИ ТРЕВОГЕ: прогон-предшественник деплоя должен ПАДАТЬ,
    # иначе тревога утонет в выводе.
    return 1 if с["тревог"] else 0


if __name__ == "__main__":
    raise SystemExit(main())
