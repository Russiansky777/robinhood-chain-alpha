def _t(ts) -> str:
    try:
        return time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime(float(ts)))
    except (TypeError, ValueError):
        return "—"


def разбор_времени(текст: str):
    т = (текст or "").strip()
    if not т:
        return None
    import calendar  # noqa: PLC0415

    for фмт in ("%Y-%m-%dT%H:%M:%SZ", "%Y-%m-%dT%H:%MZ", "%Y-%m-%d"):
        try:
            return float(calendar.timegm(time.strptime(т, фмт)))
        except ValueError:
            continue
    return None


