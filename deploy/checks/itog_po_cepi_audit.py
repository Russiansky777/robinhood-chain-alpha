def _tx_обр(*, кошелёк: str, кошелёк_лампорты: int, wsol_лампорты: int,
             рента_лампорты: int = 0, комиссия: int = 5000, слот: int = 1,
             время: int = 1000) -> dict:
    """Транзакция с НАШИМ кошельком, WSOL-счётом и счётом токена."""
    до = [1_000_000_000, 2_039_280, 2_039_280]
    после = [1_000_000_000 + кошелёк_лампорты,
              2_039_280 + wsol_лампорты,
              2_039_280 + рента_лампорты]
    ток = []
    for и, (минт, до_к, после_к) in enumerate(
            ((WSOL, 2_039_280, 2_039_280 + wsol_лампорты),
             ("МИНТ", 0, 1000)), start=1):
        ток.append((и, минт, до_к, после_к))
    return {"slot": слот, "blockTime": время,
             "transaction": {"message": {"accountKeys": [кошелёк, "WSOL_ATA", "ATA"]}},
             "meta": {"err": None, "fee": комиссия,
                       "preBalances": до, "postBalances": после,
                       "preTokenBalances": [
                           {"owner": кошелёк, "accountIndex": и, "mint": м,
                            "uiTokenAmount": {"amount": str(д)}}
                           for и, м, д, _ in ток],
                       "postTokenBalances": [
                           {"owner": кошелёк, "accountIndex": и, "mint": м,
                            "uiTokenAmount": {"amount": str(п)}}
                           for и, м, _, п in ток]}}


def self_test() -> int:
    всего = сбоев = 0

    def chk(что, ок, факт=None):
        nonlocal всего, сбоев
        всего += 1
        if ок:
            print(f"  [ok  ] {что}")
        else:
            сбоев += 1
            print(f"  [СБОЙ] {что}" + (f" -> {факт!r}" if факт is not None else ""))

    W = "W"
    # ПРОДАЖА, ВЫРУЧКА КОТОРОЙ ОСТАЛАСЬ ЗАВЁРНУТОЙ. Ровно случай Jevolution:
    # кошелёк почти не вырос, а WSOL-счёт получил 0.1035.
    прод = _tx_обр(кошелёк=W, кошелёк_лампорты=10_314_000, wsol_лампорты=103_213_000)
    д = дельты_сделки(прод, W)
    chk("завёрнутое названо отдельно и в ликвидную часть не входит",
        abs(д["завёрнутое_sol"] - 0.103213) < 1e-9
        and abs(д["кошелёк_sol"] - 0.010314) < 1e-9, д)
    chk("по цепи считается ВСЁ наше: кошелёк плюс завёрнутое",
        abs(д["все_sol"] - 0.113527) < 1e-9, д["все_sol"])
    chk("разница между «всем» и «кошельком» -- это и есть завёрнутое",
        abs((д["все_sol"] - д["кошелёк_sol"]) - д["завёрнутое_sol"]) < 1e-9, д)

    # ЗАПИСЬ СЧИТАЕТ ПО КОШЕЛЬКУ -- И ЗАНИЖАЕТ. Проверяется, что аудит ловит
    # ровно это: разница равна завёрнутому.
    пок = _tx_обр(кошелёк=W, кошелёк_лампорты=-102_005_000, wsol_лампорты=0)
    цепь = round(дельты_сделки(пок, W)["все_sol"] + д["все_sol"], 9)
    запись = round(дельты_сделки(пок, W)["кошелёк_sol"] + д["кошелёк_sol"], 9)
    chk(f"итог по цепи {цепь} против итога по кошельку {запись}: разница равна "
        "завёрнутому",
        abs((запись - цепь) + д["завёрнутое_sol"]) < 1e-9, (цепь, запись))
    chk("знак понятен: по цепи сделка в плюсе, по записи -- в минусе",
        цепь > 0 > запись, (цепь, запись))

    # ПОДПИСИ БЕРУТСЯ ИЗ ЗАПИСИ, И ИХ ОТСУТСТВИЕ -- НЕ НОЛЬ, А ПРИЧИНА.
    с_ = строка_аудита("c1", {"lane_group": "cand1", "state": "closed"}, W)
    chk("нет обеих подписей -- строка без итога и с причиной",
        с_["итог_по_цепи"] is None
        and "нет обеих подписей" in (с_["почему_нет"] or ""), с_)

    # СВОДКА ПОДПИСЫВАЕТСЯ «НЕ СВЕРЕНО», ЕСЛИ ЕСТЬ ХОТЬ ОДНА НЕСВЕДЁННАЯ СТРОКА.
    о = {"с_расхождением": 1, "не_посчитано": 0}
    chk("есть расхождение -- сводка «не сверено»",
        ("не сверено" if (о["с_расхождением"] or о["не_посчитано"]) else "сверено")
        == "не сверено")
    chk("порог расхождения -- слово владельца 0.00001", abs(ПОРОГ - 1e-5) < 1e-12)

    print(f"самопроверка аудита по цепи: {всего - сбоев}/{всего} пройдено")
    if сбоев:
        print(f"самопроверка не пройдена: {сбоев} из {всего}")
    return 1 if сбоев else 0


def дозаполнить(*, state_dir: str, кошелёк: str, с_ts: float,
                 по_ts: float | None = None, предел: int = 400) -> dict:
    """ПРАВИЛО 13, п.8: дописать итог по цепи в СТАРЫЕ закрытые записи.

    Пишутся ТОЛЬКО поля итога по цепи и подписи; ни одно денежное поле записи не
    трогается, состояние позиции не меняется. Журнал позиций append-only, поэтому
    дозапись -- это новая строка с теми же cid, а не правка прошлой.
    """
    из_ = {"посмотрено": 0, "дописано": 0, "уже_было": 0, "не_смогли": 0,
            "причины": {}, "кошелёк": кошелёк}
    C13 = _модуль()
    if C13 is None:
        из_["почему_нет"] = "модуль c2_itog_po_cepi не загружен"
        return из_
    try:
        import bloom_exec_state as ST  # noqa: PLC0415

        сч = ST.ExecState(base=Path(state_dir))
        закрыто = ST.STATE_CLOSED
    except Exception as exc:  # noqa: BLE001
        из_["почему_нет"] = f"состояние не открылось: {type(exc).__name__}"
        return из_
    поз = P11.позиции_полосы(state_dir, с_ts, по_ts)
    for cid in sorted(поз, key=lambda к: float(поз[к].get("ts_intent") or 0)):
        п = поз[cid]
        if п.get("state") != закрыто:
            continue
        if из_["посмотрено"] >= int(предел):
            из_["почему_оборвано"] = f"предел {предел}"
            break
        из_["посмотрено"] += 1
        if isinstance(п.get(C13.ПОЛЕ), (int, float)):
            из_["уже_было"] += 1
            continue
        с_ = строка_аудита(cid, п, кошелёк)
        if с_.get("итог_по_цепи") is None:
            из_["не_смогли"] += 1
            пр = (с_.get("почему_нет") or "неизвестно")[:80]
            из_["причины"][пр] = из_["причины"].get(пр, 0) + 1
            try:
                сч.update_position(cid, **{C13.ПОЛЕ_ПОЧЕМУ: пр})
            except Exception:  # noqa: BLE001
                pass
            continue
        части = {
            "покупка": {"все_sol": с_.get("покупка_все_sol"),
                         "кошелёк_sol": с_.get("покупка_кошелёк_sol"),
                         "завёрнутое_sol": с_.get("покупка_завёрнутое_sol")},
            "продажа": {"все_sol": с_.get("продажа_все_sol"),
                         "кошелёк_sol": с_.get("продажа_кошелёк_sol"),
                         "завёрнутое_sol": с_.get("продажа_завёрнутое_sol")},
            "итог_ликвидный_sol": с_.get("ликвидный_по_цепи"),
            "разница_с_ликвидным_sol": round(
                float(с_["итог_по_цепи"]) - float(с_["ликвидный_по_цепи"] or 0.0), 9),
            "дозаполнено": True}
        try:
            свежая = сч.update_position(
                cid, **{C13.ПОЛЕ: с_["итог_по_цепи"], C13.ПОЛЕ_ЧАСТИ: части,
                         C13.ПОЛЕ_ПОДПИСЬ_ПОКУПКИ: с_.get("подпись_покупки"),
                         C13.ПОЛЕ_ПОДПИСЬ_ПРОДАЖИ: с_.get("подпись_продажи"),
                         C13.ПОЛЕ_ПОЧЕМУ: None})
            св = C13.сверка(свежая or dict(п, **{C13.ПОЛЕ: с_["итог_по_цепи"]}))
            сч.update_position(cid,
                                lane_chain_sverka_sol=св.get("расхождение_sol"),
                                lane_chain_sverka_ok=св.get("сверено"))
            из_["дописано"] += 1
        except Exception as exc:  # noqa: BLE001
            из_["не_смогли"] += 1
            пр = f"запись не легла: {type(exc).__name__}"
            из_["причины"][пр] = из_["причины"].get(пр, 0) + 1
    return из_


