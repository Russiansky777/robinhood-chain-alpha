def дельты_сделки(tx: dict, кошелёк: str) -> dict:
    """Изменения НАШИХ счетов в одной транзакции, разложенные по смыслу.

    `все` -- кошелёк плюс его токеновые счета: это и есть деньги по цепи.
    `кошелёк` -- только ликвидная часть (её и видит запись службы).
    `завёрнутое` -- изменение остатка WSOL: деньги, которые лежат на токеновом
    счёте и в ликвидную часть не попали.
    """
    из_ = {"ok": False, "why_not": None, "все_sol": None, "кошелёк_sol": None,
            "завёрнутое_sol": None, "комиссия_sol": None, "слот": None,
            "время": None, "ошибка": None}
    ликв = P11.дельта_наших(tx, кошелёк, только_кошелёк=True)
    все = P11.дельта_наших(tx, кошелёк)
    if not (ликв.get("ok") and все.get("ok")):
        из_["why_not"] = ликв.get("why_not") or все.get("why_not") or "балансы не разобраны"
        return из_
    минты = P11.дельты_наших_минтов(tx, кошелёк) or {}
    из_.update(
        ok=True,
        все_sol=round(int(все["lamports"]) / ЛАМПОРТОВ_В_SOL, 9),
        кошелёк_sol=round(int(ликв["lamports"]) / ЛАМПОРТОВ_В_SOL, 9),
        завёрнутое_sol=round(int(минты.get(WSOL, 0)) / ЛАМПОРТОВ_В_SOL, 9),
        комиссия_sol=round(int(ликв.get("fee") or 0) / ЛАМПОРТОВ_В_SOL, 9),
        слот=(tx or {}).get("slot"), время=(tx or {}).get("blockTime"),
        ошибка=(((tx or {}).get("meta") or {}).get("err") is not None))
    return из_


def _подпись_покупки(п: dict) -> str | None:
    for поле in ("lane_landed_signature", "lane_signature", "signature_accepted"):
        зн = п.get(поле)
        if isinstance(зн, str) and зн:
            return зн
    for с in P11.подписи_покупки(п):
        return с
    return None


def _подпись_продажи(п: dict) -> str | None:
    for поле in ("last_sell_reported", "jup_signature", "sell_signature"):
        зн = п.get(поле)
        if isinstance(зн, str) and зн:
            return зн
    зн = п.get("last_sell_signatures")
    if isinstance(зн, list) and зн:
        return зн[-1]
    for с in P11.подписи_продажи(п):
        return с
    return None


def _tx(подпись: str) -> tuple:
    """(tx, почему_нет). Отказ узла и «нет такой подписи» -- РАЗНЫЕ случаи."""
    о = P11.зов("getTransaction", [подпись, {"encoding": "jsonParsed",
                                              "maxSupportedTransactionVersion": 1,
                                              "commitment": "confirmed"}])
    if not о.get("ok"):
        return None, f"узел отказал: {о.get('why_not')}"
    if о.get("result") is None:
        return None, "цепь не знает такой подписи"
    return о["result"], None


def строка_аудита(cid: str, п: dict, кошелёк: str) -> dict:
    """Одна строка таблицы: что говорит запись, что говорит цепь, разница."""
    из_ = {"cid": cid, "группа": п.get("lane_group") or "—",
            "источник": п.get("source_name") or (п.get("source") or "")[:8] or "—",
            "минт": п.get("mint"), "токен": п.get("token_name"),
            "utc": _t(п.get("ts_intent") or п.get("ts_sent")),
            "подпись_покупки": _подпись_покупки(п),
            "подпись_продажи": _подпись_продажи(п),
            "итог_записи": None, "итог_по_цепи": None, "разница": None,
            "ликвидный_по_цепи": None, "завёрнутое_на_продаже": None,
            "вошло": п.get("sol_in"), "вышло": п.get("closed_sol_net"),
            "расход": None, "почему_нет": None}
    try:
        import bloom_exec_state as ST  # noqa: PLC0415

        итог, расход = ST.итог_позиции(п)
        из_["итог_записи"] = (round(float(итог), 9) if итог is not None else None)
        из_["расход"] = (round(float(расход), 9) if расход is not None else None)
    except Exception as exc:  # noqa: BLE001
        из_["почему_нет"] = f"итог записи не посчитан ({type(exc).__name__})"
    # ЗАПИСЬ МОЖЕТ ИМЕТЬ СВОЙ СЧЁТ (pnl_counted_sol): берём его, если есть, --
    # это ровно то число, которое ушло в суточный счёт.
    if isinstance(п.get("pnl_counted_sol"), (int, float)):
        из_["итог_записи"] = round(float(п["pnl_counted_sol"]), 9)
    if not из_["подпись_покупки"] or not из_["подпись_продажи"]:
        из_["почему_нет"] = (из_["почему_нет"] or "") + \
            (" | " if из_["почему_нет"] else "") + "в записи нет обеих подписей"
        return из_
    сумма_все = 0.0
    сумма_ликв = 0.0
    for роль, подпись in (("покупка", из_["подпись_покупки"]),
                           ("продажа", из_["подпись_продажи"])):
        tx, почему = _tx(подпись)
        if tx is None:
            из_["почему_нет"] = (из_["почему_нет"] or "") + \
                (" | " if из_["почему_нет"] else "") + f"{роль}: {почему}"
            return из_
        д = дельты_сделки(tx, кошелёк)
        if not д["ok"]:
            из_["почему_нет"] = (из_["почему_нет"] or "") + \
                (" | " if из_["почему_нет"] else "") + f"{роль}: {д['why_not']}"
            return из_
        из_[f"{роль}_все_sol"] = д["все_sol"]
        из_[f"{роль}_кошелёк_sol"] = д["кошелёк_sol"]
        из_[f"{роль}_завёрнутое_sol"] = д["завёрнутое_sol"]
        из_[f"{роль}_комиссия_sol"] = д["комиссия_sol"]
        из_[f"{роль}_слот"] = д["слот"]
        сумма_все += float(д["все_sol"])
        сумма_ликв += float(д["кошелёк_sol"])
        if роль == "продажа":
            из_["завёрнутое_на_продаже"] = д["завёрнутое_sol"]
    из_["итог_по_цепи"] = round(сумма_все, 9)
    из_["ликвидный_по_цепи"] = round(сумма_ликв, 9)
    if из_["итог_записи"] is not None:
        из_["разница"] = round(из_["итог_записи"] - из_["итог_по_цепи"], 9)
    return из_


def аудит(*, state_dir: str, кошелёк: str, с_ts: float, по_ts: float | None = None,
           предел: int = 400) -> dict:
    """Таблица по всем ЗАКРЫТЫМ сделкам полосы за окно."""
    из_ = {"кошелёк": кошелёк, "с": _t(с_ts),
            "по": (_t(по_ts) if по_ts else "сейчас"),
            "порог": ПОРОГ, "строк": 0, "с_расхождением": 0,
            "не_посчитано": 0, "таблица": [], "по_группам": {},
            "сумма_записей": 0.0, "сумма_по_цепи": 0.0}
    try:
        import bloom_exec_state as ST  # noqa: PLC0415

        закрыто = ST.STATE_CLOSED
    except Exception:  # noqa: BLE001
        закрыто = "closed"
    поз = P11.позиции_полосы(state_dir, с_ts, по_ts)
    for cid in sorted(поз, key=lambda к: float(поз[к].get("ts_intent") or 0)):
        п = поз[cid]
        if п.get("state") != закрыто:
            continue
        if из_["строк"] >= int(предел):
            из_["почему_оборвано"] = f"предел строк {предел}"
            break
        с_ = строка_аудита(cid, п, кошелёк)
        из_["строк"] += 1
        из_["таблица"].append(с_)
        г = с_["группа"]
        в = из_["по_группам"].setdefault(
            г, {"n": 0, "записи_sol": 0.0, "цепь_sol": 0.0, "расхождений": 0,
                 "не_посчитано": 0})
        в["n"] += 1
        if с_["итог_по_цепи"] is None:
            из_["не_посчитано"] += 1
            в["не_посчитано"] += 1
            continue
        в["цепь_sol"] = round(в["цепь_sol"] + с_["итог_по_цепи"], 9)
        из_["сумма_по_цепи"] = round(из_["сумма_по_цепи"] + с_["итог_по_цепи"], 9)
        if с_["итог_записи"] is not None:
            в["записи_sol"] = round(в["записи_sol"] + с_["итог_записи"], 9)
            из_["сумма_записей"] = round(из_["сумма_записей"] + с_["итог_записи"], 9)
        if с_["разница"] is not None and abs(с_["разница"]) > ПОРОГ:
            из_["с_расхождением"] += 1
            в["расхождений"] += 1
    # СВОДКА ПОДПИСЫВАЕТСЯ ЧЕСТНО (слово владельца, п.7): есть расхождения --
    # сумма НЕ СВЕРЕНА, и так и называется.
    из_["подпись_сводки"] = ("не сверено" if (из_["с_расхождением"]
                                               or из_["не_посчитано"]) else "сверено")
    return из_


