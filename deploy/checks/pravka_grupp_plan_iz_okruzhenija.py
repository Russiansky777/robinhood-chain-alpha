#!/usr/bin/env python3
"""Собрать план правки групп ИЗ ОКРУЖЕНИЯ и напечатать его JSON.

ЗАЧЕМ (слово владельца 04.10 вечером, п.2). В прогоне run_vps_pravka_grupp_nl.yml
значения входов вклеивались прямо в команду, идущую root-ом на торговый хост:
шесть доводов вообще без кавычек и три значения в одинарных кавычках на
удалённой стороне. Пробел в первых или апостроф во вторых -- и это уже чужая
команда от root. Пометка по смыслу поля свободный текст, то есть апостроф там
был вопросом времени.

ЧЕМ ЭТОТ ФАЙЛ ЗАКРЫВАЕТ ДЫРУ. Правка собирается ЗДЕСЬ, из os.environ, и уезжает
на хост ФАЙЛОМ по stdin. os.environ не разбирается как код ни при каком
значении: ни пробел, ни апостроф, ни точка с запятой, ни перевод строки не
меняют смысла. В удалённой команде остаются только неизменяемые литералы.

ПОЧЕМУ ОТДЕЛЬНЫМ ФАЙЛОМ, А НЕ heredoc'ом В ШАГЕ -- И ЧЕГО ЗДЕСЬ НЕТ. Я сперва
написал сборку heredoc'ом, решил, что она ломается из-за отступа тела, и
проверил: НЕ ломается. YAML снимает общий отступ блочного скаляра, поэтому
бегунок получает тело python и терминатор в нулевой колонке. Мой первый тест был
построен неверно -- я написал строки с отступом руками, а так бегунку они не
приходят. Утверждение "heredoc был сломан" неверно, и повторять его не надо.
Файл оставлен по двум настоящим поводам: у него своя самопроверка, и в этом
репозитории правило прежнее -- скрипт едет файлом из дерева.

НОВОЙ ВЕТКИ В ПРАВИТЕЛЕ НЕ ЗАВЕЛОСЬ. Одиночная правка и план сходятся в
pravka_grupp.py в ОДИН И ТОТ ЖЕ список операций с теми же именами полей
(deploy/checks/pravka_grupp.py:415-425), поэтому план из одной правки -- это
ровно прежнее поведение, только без подстановок.
"""

from __future__ import annotations

import argparse
import json
import os
import sys

# Поля правки -- те же имена, что у операции в pravka_grupp.py.
ПОЛЯ = ("gruppa", "pole", "znachenie", "sozdat", "politika",
        "perenesti", "v", "pometka", "otklyuchit")

# По каким полям судим, что правка вообще заказана. Ровно те, по которым
# pravka_grupp.py собирает одиночную операцию: gruppa/sozdat/perenesti/otklyuchit.
# ПОЧЕМУ НЕ ПО ЛЮБОМУ НЕПУСТОМУ ПОЛЮ. Пометка или значение без названной группы
# и без адреса -- это не правка, а обрывок; прежний код в таком случае отдавал
# пустой список и получал сводку групп, и это поведение сохраняется.
ЗАКАЗЧИКИ = ("gruppa", "sozdat", "perenesti", "otklyuchit")


def план_из(окружение: dict) -> dict:
    """{"pravki": [одна правка]} либо {"pravki": []}, если правка не заказана."""
    правка = {п: (окружение.get(п.upper()) or "") for п in ПОЛЯ}
    заказана = any(правка[к] for к in ЗАКАЗЧИКИ)
    return {"pravki": ([правка] if заказана else [])}


def self_test() -> int:
    всего = [0]
    плохо = [0]

    def chk(имя, ок, что=""):
        всего[0] += 1
        if ок:
            print(f"  [ok  ] {имя}")
        else:
            плохо[0] += 1
            print(f"  [ПЛОХО] {имя} -- {что}")

    chk("пустое окружение -- пустой план, а не правка из пустых строк",
        план_из({}) == {"pravki": []}, план_из({}))

    п = план_из({"PERENESTI": "AFmiexHw", "V": "cand2", "POMETKA": "слово"})
    chk("перенос собрался и все девять полей на месте",
        len(п["pravki"]) == 1 and set(п["pravki"][0]) == set(ПОЛЯ)
        and п["pravki"][0]["perenesti"] == "AFmiexHw"
        and п["pravki"][0]["v"] == "cand2"
        and п["pravki"][0]["pometka"] == "слово", п)

    п = план_из({"POMETKA": "только пометка"})
    chk("одна пометка без адреса и группы -- правка НЕ заказана",
        п == {"pravki": []}, п)

    п = план_из({"GRUPPA": "cand2", "POLE": "lane_sol", "ZNACHENIE": "0.1"})
    chk("правка поля группы собралась",
        len(п["pravki"]) == 1 and п["pravki"][0]["pole"] == "lane_sol"
        and п["pravki"][0]["znachenie"] == "0.1", п)

    # ГЛАВНОЕ: злые значения проходят как ДАННЫЕ и ничего не ломают.
    зло = "a'; rm -rf / ; echo '"
    п = план_из({"PERENESTI": "ADR", "V": "cand2", "POMETKA": зло})
    chk("апостроф и точка с запятой в пометке -- это данные, а не код",
        п["pravki"][0]["pometka"] == зло, п["pravki"][0]["pometka"])
    текст = json.dumps(п, ensure_ascii=False)
    chk("и в JSON они уезжают экранированными, а JSON разбирается обратно",
        json.loads(текст)["pravki"][0]["pometka"] == зло, текст)

    зло2 = 'строка с "кавычками" и\nпереводом строки'
    п = план_из({"SOZDAT": "novaja", "POMETKA": зло2})
    chk("двойные кавычки и перевод строки тоже переживают путь",
        json.loads(json.dumps(п, ensure_ascii=False))["pravki"][0]["pometka"] == зло2,
        п["pravki"][0]["pometka"])

    chk("пробел в адресе не склеивает доводы: он остаётся одним значением",
        план_из({"PERENESTI": "ADR1 ADR2"})["pravki"][0]["perenesti"] == "ADR1 ADR2")

    п = план_из({"OTKLYUCHIT": "ADR", "V": "off"})
    chk("выключение адреса собралось",
        len(п["pravki"]) == 1 and п["pravki"][0]["otklyuchit"] == "ADR"
        and п["pravki"][0]["v"] == "off", п)

    chk("имена полей плана совпадают с именами операции правителя",
        ПОЛЯ == ("gruppa", "pole", "znachenie", "sozdat", "politika",
                 "perenesti", "v", "pometka", "otklyuchit"), ПОЛЯ)

    # Чужие переменные окружения в план не попадают.
    п = план_из({"PERENESTI": "ADR", "HELIUS_API": "secret", "PATH": "/bin"})
    chk("посторонние переменные окружения в план не попадают",
        set(п["pravki"][0]) == set(ПОЛЯ)
        and "secret" not in json.dumps(п, ensure_ascii=False), п)

    print(f"самопроверка сборки плана: {всего[0] - плохо[0]}/{всего[0]} пройдено")
    return 1 if плохо[0] else 0


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--self-test", action="store_true")
    а = ap.parse_args()
    if а.self_test:
        return self_test()
    print(json.dumps(план_из(dict(os.environ)), ensure_ascii=False))
    return 0


if __name__ == "__main__":
    sys.exit(main())
