КОНТЕЙНЕРЫ = ("addresses", "by_signal", "snipers", "dropped_by_credits")
# subscribe -- признак "подписываться ли на адреса группы живьём"
# (слово владельца 28.09: log_only снять с живой подписки).
ПРИЗНАКИ = ("bloom_trades", "lane_trades", "fanout", "subscribe",
             "skip_flippers", "allow_taxed_route")
СПИСКИ = ("lane_pools",)


def модуль_групп(файл: str):
    """bloom_source_groups -- тот же, что у службы; порядок каталогов важен."""
    for кат in ("/home/bot/bloom_executor",
                "/home/bot/robinhood-chain-alpha/analysis",
                os.path.join(os.path.dirname(os.path.dirname(
                    os.path.dirname(os.path.abspath(__file__)))), "analysis")):
        if not os.path.exists(os.path.join(кат, "bloom_source_groups.py")):
            continue
        if кат not in sys.path:
            sys.path.insert(0, кат)
        try:
            import importlib  # noqa: PLC0415

            м = importlib.import_module("bloom_source_groups")
            os.environ["BLOOM_SOURCE_GROUPS"] = файл
            if hasattr(м, "_КЭШ"):
                м._КЭШ = None
            return м
        except Exception as exc:  # noqa: BLE001
            print(f"группы из {кат} не загружены: {type(exc).__name__}", file=sys.stderr)
    return None


def разобрать(значение: str, поле: str):
    """Значение поля из строки: признак, список, число или строка -- по полю."""
    з = (значение or "").strip()
    if поле in ПРИЗНАКИ:
        if з.lower() in ("1", "true", "да", "yes", "on"):
            return True
        if з.lower() in ("0", "false", "нет", "no", "off"):
            return False
        raise ValueError(f"{поле} -- признак, а {з!r} на признак не похоже")
    if поле in СПИСКИ:
        if not з or з == "[]":
            return []
        return [x.strip() for x in з.strip("[]").replace('"', "").split(",") if x.strip()]
    if з == "" or з.lower() in ("none", "null", "нет"):
        return None
    т = з[1:] if з[:1] in "+-" else з
    if т.isdigit():
        return int(з)
    try:
        return float(з)
    except ValueError:
        return з


def адреса_группы(тело: dict) -> list:
    из_ = []
    for к in КОНТЕЙНЕРЫ:
        v = тело.get(к)
        if isinstance(v, dict):
            из_ += list(v.keys())
        elif isinstance(v, list):
            из_ += [(x.get("address") if isinstance(x, dict) else x) for x in v]
    return [а for а in из_ if а]


def убрать_адрес(тело: dict, адрес: str) -> int:
    убрано = 0
    for к in КОНТЕЙНЕРЫ:
        v = тело.get(к)
        if isinstance(v, dict) and адрес in v:
            v.pop(адрес)
            убрано += 1
        elif isinstance(v, list):
            было = len(v)
            тело[к] = [x for x in v
                       if (x.get("address") if isinstance(x, dict) else x) != адрес]
            убрано += было - len(тело[к])
    return убрано


def операции_имена(операции: list) -> list:
    """Короткие имена правок -- только для сообщений об отказе."""
    из_ = []
    for оп in операции:
        из_.append(оп.get("sozdat") or оп.get("perenesti") or оп.get("otklyuchit")
                   or f"{оп.get('gruppa')}.{оп.get('pole')}")
    return из_


def применить(гр: dict, оп: dict, ждём_группу: dict, ждём_поля: dict,
              ждём_списки: dict, ждём_убрано: dict | None = None) -> int:
    """Одна операция правки. 0 -- сделано, иначе код выхода как у прежних ветвей.

    ЗАЧЕМ ОТДЕЛЬНОЙ ФУНКЦИЕЙ. Слово владельца 28.09 пришло одним списком из
    четырёх правок групп сразу (новая группа, перенос девяти адресов, снятие
    log_only с подписки, clmm двум группам). По одной правке на прогон это
    двенадцать прогонов, и каждый -- отдельный шанс ошибиться половиной. Теперь
    список правок применяется одним прогоном, а самопроверка денежного пути и
    возврат из копии при отказе -- те же, что были.
    """
    сoздать = оп.get("sozdat") or ""
    группа_ = оп.get("gruppa") or ""
    поле_ = оп.get("pole") or ""
    значение_ = оп.get("znachenie")
    перенести_ = оп.get("perenesti") or ""
    в_ = оп.get("v") or ""
    пометка_ = оп.get("pometka") or ""
    отключить_ = оп.get("otklyuchit") or ""

    if сoздать:
        if сoздать in гр:
            print(f"СТОП: группа {сoздать} уже есть", file=sys.stderr)
            return 3
        политика = оп.get("politika")
        if isinstance(политика, str):
            try:
                политика = json.loads(политика) if политика else {}
            except ValueError as exc:
                print(f"СТОП: политика не JSON ({exc})", file=sys.stderr)
                return 4
        политика = dict(политика or {})
        # ВИД СПИСОЧНОГО ПОЛЯ -- ГЕЙТ, А НЕ ПОЖЕЛАНИЕ. ЖИВОЙ СЛУЧАЙ 02.10:
        # cand1_05 создана с lane_pools СТРОКОЙ "amm_v4,bonding,...". Строка --
        # скаляр, поэтому самопроверка ниже сверила строку со строкой и прошла,
        # а читатель полосы (bloom_own_send._типы_из_файла) берёт поле только
        # через isinstance(list, tuple): строку он молча отбрасывает и уходит на
        # флаги окружения. То есть группа торговала НЕ тем набором типов, и ни
        # одна проверка этого не сказала. У операции "поле" такого не бывает --
        # там строка проходит разобрать() и становится списком; а политика
        # новой группы ложится в файл КАК ЕСТЬ. Поэтому вид проверяется здесь.
        for к_сп in СПИСКИ:
            if к_сп in политика and not isinstance(политика[к_сп], (list, tuple)):
                print(f"СТОП: {сoздать}.{к_сп} задано не списком, а "
                      f"{type(политика[к_сп]).__name__} -- читатель полосы берёт "
                      f"только список и строку молча отбросит", file=sys.stderr)
                return 11
        политика.setdefault("addresses", {})
        гр[сoздать] = политика
        ждём_поля[сoздать] = {к: v for к, v in политика.items()
                               if not isinstance(v, (list, dict))}
        # СПИСКИ СВЕРЯЮТСЯ ОТДЕЛЬНО: в ждём_поля они не попадают (там только
        # скаляры), и без этого lane_pools новой группы не сверялся вовсе.
        for к_сп in СПИСКИ:
            if к_сп in политика:
                ждём_поля.setdefault(сoздать, {})
                ждём_списки.setdefault(сoздать, {})[к_сп] = list(политика[к_сп])
        print(f"создана группа {сoздать}: "
              f"{json.dumps(ждём_поля[сoздать], ensure_ascii=False)}")
        for к_сп, зн in (ждём_списки.get(сoздать) or {}).items():
            print(f"создана группа {сoздать}: {к_сп} = "
                  f"{json.dumps(зн, ensure_ascii=False)} ({len(зн)} шт.)")

    if группа_ and поле_:
        if группа_ not in гр:
            print(f"СТОП: группы {группа_} нет; есть {sorted(гр)}", file=sys.stderr)
            return 5
        было = гр[группа_].get(поле_)
        стало = (разобрать(значение_, поле_) if isinstance(значение_, str)
                 or значение_ is None else значение_)
        гр[группа_][поле_] = стало
        if isinstance(стало, (list, tuple)):
            # Список в ждём_поля не кладём: там сверяются скаляры. Своя полка --
            # ждём_списки, иначе правка списка остаётся несверенной.
            ждём_списки.setdefault(группа_, {})[поле_] = list(стало)
        else:
            ждём_поля.setdefault(группа_, {})[поле_] = стало
        print(f"{группа_}.{поле_}: было {было!r}, стало {стало!r}")

    убрать_поле_ = оп.get("udalit_pole") or ""
    if группа_ and убрать_поле_:
        # УБРАТЬ ПОЛЕ, А НЕ ОБНУЛИТЬ. Слово владельца 02.10 (Правило 16):
        # "дневные стопы групп (stop_loss_sol) УБРАТЬ у всех групп". null в
        # файле читался бы как "своего числа нет" и работал бы так же, но ключ
        # со словом stop остался бы в файле, который владелец читает глазами.
        if группа_ not in гр:
            print(f"СТОП: группы {группа_} нет; есть {sorted(гр)}", file=sys.stderr)
            return 12
        было = гр[группа_].pop(убрать_поле_, "(поля не было)")
        if ждём_убрано is not None:
            ждём_убрано.setdefault(группа_, []).append(убрать_поле_)
        print(f"{группа_}.{убрать_поле_}: было {было!r}, поле УБРАНО")

    if перенести_:
        if not в_ or в_ not in гр:
            print(f"СТОП: куда переносить -- группы {в_!r} нет", file=sys.stderr)
            return 6
        откуда = [имя for имя, тело in гр.items()
                  if перенести_ in адреса_группы(тело)]
        for имя in откуда:
            n = убрать_адрес(гр[имя], перенести_)
            print(f"убран из {имя} ({n} мест)")
        цель = гр[в_]
        if not isinstance(цель.get("addresses"), dict):
            цель["addresses"] = {}
        цель["addresses"][перенести_] = пометка_ or "перенос по слову владельца"
        ждём_группу[перенести_] = в_
        print(f"{перенести_[:8]}: {откуда or ['(нигде)']} -> {в_}")

    if отключить_:
        # ПРОСТО УБРАТЬ ИЗ ФАЙЛА НЕЛЬЗЯ. Адрес, которого в файле нет, модуль
        # относит к ГРУППЕ ПО УМОЛЧАНИЮ, а она может торговать -- то есть
        # удаление не выключает источник. Выключение -- перевод в группу, у
        # которой оба признака торговли сняты, и это проверяется здесь же.
        if not в_ or в_ not in гр:
            print(f"СТОП: куда выключать -- группы {в_!r} нет", file=sys.stderr)
            return 8
        цел = гр[в_]
        if цел.get("lane_trades") is not False or цел.get("bloom_trades") is not False:
            print(f"СТОП: группа {в_} торгует "
                  f"(lane_trades={цел.get('lane_trades')!r}, "
                  f"bloom_trades={цел.get('bloom_trades')!r}) -- "
                  "выключать в неё нельзя", file=sys.stderr)
            return 9
        откуда = [имя for имя, тело in гр.items()
                  if отключить_ in адреса_группы(тело)]
        for имя in откуда:
            n = убрать_адрес(гр[имя], отключить_)
            print(f"убран из {имя} ({n} мест)")
        if not isinstance(цел.get("addresses"), dict):
            цел["addresses"] = {}
        цел["addresses"][отключить_] = пометка_ or "выключен по слову владельца"
        ждём_группу[отключить_] = в_
        ждём_поля.setdefault(в_, {}).update(
            {"lane_trades": False, "bloom_trades": False})
        print(f"{отключить_[:8]}: {откуда or ['(нигде)']} -> {в_} (не торгует)")
    return 0


def main() -> int:
    р = argparse.ArgumentParser()
    р.add_argument("--file", required=True)
    р.add_argument("--pokazat", action="store_true", help="только показать")
    р.add_argument("--gruppa", default="")
    р.add_argument("--pole", default="")
    р.add_argument("--znachenie", default="")
    р.add_argument("--sozdat", default="", help="имя новой группы")
    р.add_argument("--politika", default="", help="JSON политики новой группы")
    р.add_argument("--perenesti", default="", help="адрес")
    р.add_argument("--v", default="", help="в какую группу перенести")
    р.add_argument("--pometka", default="", help="пометка адреса при переносе")
    р.add_argument("--otklyuchit", default="",
                   help="адрес -- перевести в НЕТОРГУЮЩУЮ группу (имя в --v)")
    р.add_argument("--plan", default="",
                   help="файл JSON со списком правок: {\"pravki\": [ {...}, ... ]}")
    а = р.parse_args()

    путь = Path(а.file)
    д = json.loads(путь.read_text(encoding="utf-8"))
    гр = д.get("groups")
    if not isinstance(гр, dict):
        print("СТОП: в файле нет словаря groups", file=sys.stderr)
        return 2

    операции = []
    if а.plan:
        # ПЛАН -- СПИСОК ПРАВОК В ОДНОМ ФАЙЛЕ. Порядок важен: сначала создать
        # группу, потом переносить в неё адреса.
        план = json.loads(Path(а.plan).read_text(encoding="utf-8"))
        операции = план.get("pravki") if isinstance(план, dict) else план
        if not isinstance(операции, list) or not операции:
            print("СТОП: в плане нет списка правок", file=sys.stderr)
            return 10
    elif а.gruppa or а.sozdat or а.perenesti or а.otklyuchit:
        операции = [{"gruppa": а.gruppa, "pole": а.pole, "znachenie": а.znachenie,
                      "sozdat": а.sozdat, "politika": а.politika,
                      "perenesti": а.perenesti, "v": а.v, "pometka": а.pometka,
                      "otklyuchit": а.otklyuchit}]

    if а.pokazat or not операции:
        свод = {}
        for имя, тело in гр.items():
            свод[имя] = {"адресов": len(адреса_группы(тело)),
                          **{к: v for к, v in тело.items()
                             if not isinstance(v, (list, dict))}}
        print(json.dumps(свод, ensure_ascii=False, indent=1))
        return 0

    копия = путь.with_suffix(путь.suffix + f".bak-{time.strftime('%Y%m%dT%H%M%SZ', time.gmtime())}")
    shutil.copy2(путь, копия)
    ждём_группу, ждём_поля, ждём_списки, ждём_убрано = {}, {}, {}, {}
    for номер, оп in enumerate(операции, 1):
        код = применить(гр, оп, ждём_группу, ждём_поля, ждём_списки,
                         ждём_убрано)
        if код:
            shutil.copy2(копия, путь)
            print(f"СТОП: правка {номер} из {len(операции_имена(операции))} не "
                  f"прошла, файл возвращён из копии", file=sys.stderr)
            return код

    путь.write_text(json.dumps(д, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")

    # --- САМОПРОВЕРКА ДЕНЕЖНОГО ПУТИ ---
    SG = модуль_групп(str(путь))
    плохо = []
    if SG is None:
        плохо.append("модуль групп не загружен -- проверить нечем")
    else:
        for адрес, ожидали in ждём_группу.items():
            есть = SG.группа(адрес)
            если_по_умолчанию = getattr(SG, "ГРУППА_ПО_УМОЛЧАНИЮ", None)
            надо = ожидали if ожидали is not None else если_по_умолчанию
            if есть != надо:
                плохо.append(f"адрес {адрес[:8]}: группа {есть!r}, ожидали {надо!r}")
        # ПРОВЕРЯЕМ ТОЛЬКО ТО, ЧТО МОДУЛЬ ЧИТАЕТ. У политики есть свой набор
        # полей (ПОЛИТИКА_ПО_УМОЛЧАНИЮ); пояснения вроде note в него не входят
        # и на деньги не влияют -- требовать их обратно значило бы падать на
        # ровном месте. Поля вне набора называются словами и не сверяются.
        # ЧТО СЧИТАТЬ "ЧИТАЕМЫМ ПОЛЕМ". Прежде брался набор ПОЛИТИКА_ПО_УМОЛЧАНИЮ,
        # и это было УЖЕ набора, который политика на самом деле отдаёт: per_day в
        # умолчаниях нет, а в прочитанной политике есть (и предел суток по нему
        # работает). Из-за этого прогон правок 02.10 написал про cand1_05
        # "поле per_day политика не читает -- не сверяю", и число 100 осталось
        # несверенным, хотя сверить его было чем. Правильный признак -- есть ли
        # ключ в том, что политика ОТДАЁТ для этой группы; пояснения вроде note в
        # неё не попадают и по-прежнему называются словами.
        for имя, поля in ждём_поля.items():
            пол = SG.политика(имя)
            for к, v in поля.items():
                if к not in пол:
                    print(f"поле {имя}.{к} политика не читает -- не сверяю")
                    continue
                if пол.get(к) != v:
                    плохо.append(f"{имя}.{к}: читается {пол.get(к)!r}, ожидали {v!r}")
        # СПИСКИ -- ТЕМ ЖЕ ЧТЕНИЕМ, ЧТО У ПОЛОСЫ. Сверяется не только равенство
        # значения, но и ВИД: читатель полосы берёт поле только списком, и
        # строка, равная строке, его бы устроила, а полосу -- нет.
        for имя, поля in ждём_списки.items():
            пол = SG.политика(имя)
            for к, v in поля.items():
                есть = пол.get(к)
                if not isinstance(есть, (list, tuple)):
                    плохо.append(f"{имя}.{к}: читается "
                                 f"{type(есть).__name__}, а полоса берёт только "
                                 f"список")
                elif list(есть) != list(v):
                    плохо.append(f"{имя}.{к}: читается {есть!r}, ожидали {v!r}")
                else:
                    print(f"{имя}.{к} сверено списком: {len(v)} шт.")
        # УБРАННЫЕ ПОЛЯ СВЕРЯЮТСЯ ДВАЖДЫ, И ЭТО НЕ ПЕДАНТИЗМ.
        # (1) В ФАЙЛЕ ключа быть не должно -- это и есть "убрать".
        # (2) ЧИТАТЕЛЬ ПОЛОСЫ должен отдавать None, то есть "своего числа у
        #     группы нет". Одной проверки по политике не хватает: политика
        #     достраивает известные ключи значением None, и удалённое поле
