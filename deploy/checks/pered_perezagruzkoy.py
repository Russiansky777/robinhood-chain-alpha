#!/usr/bin/env python3
"""Можно ли перезагружать хост прямо сейчас. Только чтение, ничего не меняет.

Перезагрузка с позицией в воздухе оставляет её без сторожа -- это деньги.
Поэтому условия жёсткие и проверяются здесь, а не на глаз:
  * рубильник /etc/bloom-executor/KILL стоит;
  * открытых позиций 0 и зависших 0 -- по ВСЕМ группам полосы;
  * признак жизни детектора не старше 10 минут (иначе числа о позициях
    вообще нельзя считать правдой).
Выход 0 -- можно; иное -- нельзя, и причина напечатана.
"""
import json
import os
import sys
import time

РУБИЛЬНИК = "/etc/bloom-executor/KILL"
ПРИЗНАК = "/home/bot/bloom_executor_live_data/detector_status.json"
ПРЕДЕЛ_ВОЗРАСТА_S = 600


def main() -> int:
    if not os.path.exists(РУБИЛЬНИК):
        print(f"СТОП: рубильника {РУБИЛЬНИК} нет -- перезагрузка отменена")
        return 3
    try:
        возраст = time.time() - os.path.getmtime(ПРИЗНАК)
        с = json.load(open(ПРИЗНАК, encoding="utf-8"))
    except Exception as exc:  # noqa: BLE001
        print(f"СТОП: признак жизни не прочитан ({type(exc).__name__})")
        return 3
    if возраст > ПРЕДЕЛ_ВОЗРАСТА_S:
        print(f"СТОП: признаку жизни {возраст:.0f} с при пределе {ПРЕДЕЛ_ВОЗРАСТА_S}")
        return 3
    своя = (с.get("own_send") or {})
    группы = своя.get("lane_state_by_group") or {}
    состояния = list(группы.values()) if группы else [своя.get("lane_state") or {}]
    открытых = sum(int(х.get("open") or 0) for х in состояния)
    зависших = sum(int(х.get("stuck") or 0) for х in состояния)
    имена = list(группы) or ["деньги"]
    print(f"признак жизни: {возраст:.0f} с назад; группы {имена}; "
          f"открытых {открытых}, зависших {зависших}; рубильник стоит")
    if открытых or зависших:
        print("СТОП: есть открытые или зависшие позиции -- перезагрузка отменена")
        return 4
    print("МОЖНО: рубильник стоит, позиций 0, зависших 0")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
