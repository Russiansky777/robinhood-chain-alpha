ПОХОЖ_НА_АДРЕС = re.compile(r"^[1-9A-HJ-NP-Za-km-z]{32,44}$")


def utc(т):
    """Секунды эпохи -> строка UTC. Не число или ноль -- None, не выдумка."""
    if not isinstance(т, (int, float)) or т <= 0:
        return None
    return time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime(float(т)))


# ГДЕ В ГРУППЕ ЛЕЖАТ АДРЕСА. Ровно те же три места, что читает сама служба
# (bloom_source_groups.загрузить): addresses словарём {адрес: партия},
# addresses списком (строк или объектов с полем address), и списки by_signal и
# snipers. Четвёртый вид не изобретаем. Прогон 02:58:34Z на живом файле сказал
# "в группе lane_s0 не нашлось списка адресов" именно потому, что здесь
# искался только список строк.
ПОЛЯ_АДРЕСОВ = ("addresses", "by_signal", "snipers")


def адреса_группы(группа: dict) -> list:
    """Адреса группы -- тем же чтением, каким их берёт служба."""
    из_: list = []

    def добавить(а):
        if isinstance(а, str) and ПОХОЖ_НА_АДРЕС.match(а) and а not in из_:
            из_.append(а)

    г = группа or {}
    адреса = г.get("addresses")
    if isinstance(адреса, dict):
        for а in адреса:
            добавить(а)
    elif isinstance(адреса, list):
        for з in адреса:
            добавить(з.get("address") if isinstance(з, dict) else з)
    for поле in ("by_signal", "snipers"):
        for з in г.get(поле) or []:
            добавить(з.get("address") if isinstance(з, dict) else з)
    return из_


def поле_адресов(группа: dict) -> str | None:
    """Ключ группы, откуда взяты адреса. Нужен для отчёта, не для чтения."""
    г = группа or {}
    for ключ in ПОЛЯ_АДРЕСОВ:
        зн = г.get(ключ)
        if isinstance(зн, dict) and зн:
            return ключ
        if isinstance(зн, list) and зн:
            return ключ
    return None


def план(живой: dict, *, откуда: str = "lane_s0") -> dict:
    """Каким станет файл на время круга. Возвращает и план, и план возврата."""
    из_ = {"ok": False, "why_not": None}
    группы = (живой or {}).get("groups")
    if not isinstance(группы, dict):
        из_["why_not"] = "в файле нет словаря groups"
        return из_
    if откуда not in группы:
        из_["why_not"] = f"группы {откуда} в файле нет; есть {sorted(группы)}"
        return из_
    поле = поле_адресов(группы[откуда])
    адреса = адреса_группы(группы[откуда])
    if not адреса:
        из_["why_not"] = (f"в группе {откуда} не нашлось адресов ни в "
                           f"{', '.join(ПОЛЯ_АДРЕСОВ)}")
        return из_

    новые = copy.deepcopy(группы)
    # 1. Все торгующие группы -- выключить, и запомнить, кто торговал.
    было_торгующих = sorted(г for г, п in группы.items() if п.get("lane_trades") is True)
    for г in новые:
        if новые[г].get("lane_trades") is True:
            новые[г]["lane_trades"] = False
    # 2. Группа круга: адреса lane_s0, числа владельца.
    круг = dict(КРУГ)
    # АДРЕСА В КРУГ -- СПИСКОМ СТРОК под ключом addresses: этот вид служба
    # читает, и он не тащит за собой чужие метки партий.
    круг["addresses"] = list(адреса)
    новые[ИМЯ_КРУГА] = круг

    из_.update(ok=True, поле_адресов=поле,
                адресов_в_круге=len(круг["addresses"]),
                было_торгующих=было_торгующих,
                план_групп={г: {"lane_trades": новые[г].get("lane_trades"),
                                 "lane_sol": новые[г].get("lane_sol")}
                             for г in sorted(новые)},
                возврат=({"убрать_группу": ИМЯ_КРУГА,
                           "вернуть_lane_trades_true": было_торгующих}),
                групп_после=len(новые))
    из_["новые_группы"] = новые
    return из_


