#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Свод всех живых сделок полосы с 27.09 в ОДИН файл, с суточной допиской.

СЛОВО ВЛАДЕЛЬЦА 03.10 (вечер, п.5): "Полная выгрузка живых сделок полосы с
27.09 одним файлом data/sdelki_polosy_vse_s_2709.json (поля суточных выгрузок:
группа, источник, билет, пул, резерв, итог по цепи) + дописывать каждые сутки.
Нужна Code-2 к понедельнику".

ПОЧЕМУ ДОПИСКА, А НЕ ПЕРЕСБОРКА КАЖДЫЕ СУТКИ. Пересборка за всё окно читает
журнал позиций целиком, включая ротированные .gz, и лазит в цепь за чужими
продажами: это десятки минут и кредиты Helius каждые сутки за те же самые
строки. Дописка берёт готовую суточную выгрузку (её всё равно делает таймер
хоста в 06:00Z) и кладёт её ряды в свод.

ЧТО ЗДЕСЬ ВАЖНО ПО СУЩЕСТВУ:

* КЛЮЧ -- cid, И НОВАЯ СТРОКА СИЛЬНЕЕ СТАРОЙ. Одна и та же сделка попадает в
  две суточные выгрузки, если её продажа села после границы суток: в первой
  она открыта и без итога, во второй закрыта. Склейка по cid с победой более
  поздней выгрузки оставляет в своде закрытую;
* ПОЛЯ НЕ ТЕРЯЮТСЯ, А ДОПОЛНЯЮТСЯ: у поздней строки часть полей может быть
  пустой (например пул не прочитался), и затирать ими живое число нельзя.
  Поэтому склейка идёт по полям: не-None из новой поверх старой;
* ОКНО СВОДА НЕ СУЖАЕТСЯ. "с" берётся минимумом по всем источникам, "до" --
  максимумом: дописка суток не имеет права сдвинуть начало окна на вчера;
* ЧУЖИЕ РЯДЫ НЕ ПРИНИМАЮТСЯ. Ряд без cid в свод не идёт: по нему нельзя ни
  склеить, ни проверить, и молча положить его значило бы задвоить сделку при
  следующей дописке.

Только чтение файлов и запись свода. Ни сети, ни цепи, ни ключей.
"""

from __future__ import annotations

import argparse
import json
import sys
import time
from pathlib import Path

ПОЛЯ_ОКНА = ("с", "до")
ИМЯ_СВОДА = "data/sdelki_polosy_vse_s_2709.json"
НАЧАЛО_ОКНА = "2026-09-27T00:00"


def _ряды(д: dict) -> list:
    """Ряды выгрузки: у суточной они под ключом 'ряды'."""
    if isinstance(д, list):
        return [р for р in д if isinstance(р, dict)]
    for к in ("ряды", "sdelki", "rows"):
        з = (д or {}).get(к)
        if isinstance(з, list):
            return [р for р in з if isinstance(р, dict)]
    return []


def склеить_ряд(старый: dict, новый: dict) -> dict:
    """Поля новой строки поверх старой, но ТОЛЬКО не-None: пустое поле поздней
    выгрузки не имеет права затереть живое число ранней."""
    из_ = dict(старый)
    for к, v in (новый or {}).items():
        if v is None and к in из_ and из_[к] is not None:
            continue
        из_[к] = v
    return из_


def свести(части: list) -> dict:
    """Свод из нескольких выгрузок. Части идут в порядке от старой к новой."""
    по_cid: dict = {}
    порядок: list = []
    без_cid = 0
    окно_с, окно_до = None, None
    источники = []
    for ч in части:
        д = ч.get("данные") or {}
        источники.append({"файл": ч.get("файл"),
                           "рядов": len(_ряды(д)),
                           "с": (д or {}).get("с"), "до": (д or {}).get("до")})
        с_, до_ = (д or {}).get("с"), (д or {}).get("до")
        if с_ and (окно_с is None or str(с_) < str(окно_с)):
            окно_с = с_
        if до_ and (окно_до is None or str(до_) > str(окно_до)):
            окно_до = до_
        for р in _ряды(д):
            cid = р.get("cid")
            if not cid:
                без_cid += 1
                continue
            if cid in по_cid:
                по_cid[cid] = склеить_ряд(по_cid[cid], р)
            else:
                по_cid[cid] = dict(р)
                порядок.append(cid)
    ряды = [по_cid[c] for c in порядок]
    ряды.sort(key=lambda р: (str(р.get("utc") or ""), str(р.get("cid") or "")))
    return {"что": ("Все живые сделки полосы одним файлом (слово владельца "
                     "03.10, п.5). Ключ -- cid; поздняя выгрузка правит поля "
                     "ранней, но пустым полем живое число не затирает."),
             "снято_utc": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
             "с": окно_с or НАЧАЛО_ОКНА, "до": окно_до,
             "рядов": len(ряды), "рядов_без_cid_отброшено": без_cid,
             "источники": источники, "ряды": ряды}


def прочитать(путь: str | Path) -> dict:
    п = Path(путь)
    if not п.exists():
        return {"файл": str(п), "данные": None, "why_not": "файла нет"}
    try:
        return {"файл": str(п), "данные": json.loads(п.read_text(encoding="utf-8")),
                "why_not": None}
    except Exception as exc:  # noqa: BLE001
        return {"файл": str(п), "данные": None,
                "why_not": f"{type(exc).__name__}: {str(exc)[:160]}"}


def self_test() -> int:
    проверки = []

    def chk(имя, ок, что=""):
        проверки.append((имя, bool(ок), что))

    сутки1 = {"с": "2026-09-27T00:00", "до": "2026-09-28T06:00", "ряды": [
        {"cid": "a", "utc": "2026-09-27T10:00:00Z", "group": "cand1",
         "source": "S1", "size_sol": 0.3, "pool": "P1",
         "pool_reserve_sol": 51.7, "итог_sol": None},
        {"cid": "b", "utc": "2026-09-27T11:00:00Z", "group": "cand2",
         "source": "S2", "size_sol": 0.1, "pool": None, "итог_sol": 0.02}]}
    сутки2 = {"с": "2026-09-28T06:00", "до": "2026-09-29T06:00", "ряды": [
        # та же сделка a -- теперь закрыта, но пул в этой выгрузке не прочитался
        {"cid": "a", "utc": "2026-09-27T10:00:00Z", "group": "cand1",
         "source": "S1", "size_sol": 0.3, "pool": None,
         "pool_reserve_sol": None, "итог_sol": -0.05},
        {"cid": "c", "utc": "2026-09-28T12:00:00Z", "group": "konveyer",
         "source": "S3", "size_sol": 0.1, "pool": "P3", "итог_sol": 0.4},
        {"utc": "2026-09-28T13:00:00Z", "group": "ничей"}]}
    с = свести([{"файл": "сутки1", "данные": сутки1},
                 {"файл": "сутки2", "данные": сутки2}])
    по = {р["cid"]: р for р in с["ряды"]}
    chk("свод склеил по cid: три сделки, а не пять", с["рядов"] == 3, с["рядов"])
    chk("ряд без cid отброшен и посчитан", с["рядов_без_cid_отброшено"] == 1)
    chk("поздняя выгрузка принесла итог закрытой сделки",
        по["a"]["итог_sol"] == -0.05, по["a"]["итог_sol"])
    chk("и НЕ затёрла пул с резервом пустыми полями",
        по["a"]["pool"] == "P1" and по["a"]["pool_reserve_sol"] == 51.7,
        {к: по["a"][к] for к in ("pool", "pool_reserve_sol")})
    chk("окно свода -- от самого раннего начала до самого позднего конца",
        с["с"] == "2026-09-27T00:00" and с["до"] == "2026-09-29T06:00",
        (с["с"], с["до"]))
    chk("ряды упорядочены по времени",
        [р["cid"] for р in с["ряды"]] == ["a", "b", "c"],
        [р["cid"] for р in с["ряды"]])
    chk("поля суточной выгрузки на месте: группа, источник, билет, пул, резерв, итог",
        all(к in по["a"] for к in ("group", "source", "size_sol", "pool",
                                    "pool_reserve_sol", "итог_sol")),
        sorted(по["a"]))
    # Дописка идемпотентна: те же сутки второй раз не задваивают сделку.
    снова = свести([{"файл": "свод", "данные": с},
                     {"файл": "сутки2", "данные": сутки2}])
    chk("повторная дописка тех же суток не задваивает ряды",
        снова["рядов"] == 3, снова["рядов"])
    # Пустая часть не ломает свод и не сужает окно.
    пусто = свести([{"файл": "свод", "данные": с}, {"файл": "нет", "данные": None}])
    chk("часть без данных не ломает свод и не сдвигает начало окна",
        пусто["рядов"] == 3 and пусто["с"] == "2026-09-27T00:00",
        (пусто["рядов"], пусто["с"]))
    chk("список без обёртки тоже читается как ряды",
        len(_ряды([{"cid": "x"}, "мусор"])) == 1)

    плохих = 0
    for имя, ок, что in проверки:
        print(f"  [{'ok  ' if ок else 'СБОЙ'}] {имя}"
               + (f"  -> {что}" if not ок and что != "" else ""))
        плохих += (not ок)
    print(f"самопроверка свода выгрузок: {len(проверки) - плохих}/{len(проверки)} пройдено")
    return 0 if плохих == 0 else 1


def main() -> int:
    р = argparse.ArgumentParser(description=__doc__)
    р.add_argument("--self-test", action="store_true")
    р.add_argument("--svod", default=ИМЯ_СВОДА,
                   help="файл свода (он же первая часть, если существует)")
    р.add_argument("--dopisat", nargs="*", default=[],
                   help="суточные выгрузки, которые дописываем в свод")
    а = р.parse_args()
    if а.self_test:
        return self_test()
    части = []
    есть_свод = Path(а.svod).exists()
    if есть_свод:
        части.append(прочитать(а.svod))
    for п in а.dopisat:
        ч = прочитать(п)
        if ч.get("why_not"):
            print(f"СТОП: {п}: {ч['why_not']}", file=sys.stderr)
            return 2
        части.append(ч)
    if not части:
        print("СТОП: ни свода, ни частей -- сводить нечего", file=sys.stderr)
        return 2
    итог = свести(части)
    Path(а.svod).parent.mkdir(parents=True, exist_ok=True)
    Path(а.svod).write_text(json.dumps(итог, ensure_ascii=False, indent=1) + "\n",
                            encoding="utf-8")
    print(json.dumps({к: итог[к] for к in ("с", "до", "рядов",
                                            "рядов_без_cid_отброшено")},
                     ensure_ascii=False))
    print(f"записано: {а.svod} (свод был: {'да' if есть_свод else 'нет'})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
