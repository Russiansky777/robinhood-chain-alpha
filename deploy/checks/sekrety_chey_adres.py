#!/usr/bin/env python3
"""Чей кошелёк лежит в каждом секрете GitHub. Сам секрет наружу НЕ выходит.

ЗАЧЕМ (слово владельца 01.10, п.2). С кошелька Bloom 4s87RRC2 ушли 0.024620982
SOL без его ведома. Нужно подтвердить, есть ли приватный ключ ЭТОГО кошелька в
GitHub secrets, и что ключ полосы (LIVE) читается только из секрета LIVE.

ИЗМЕРЕНИЕ, А НЕ ИМЯ ПЕРЕМЕННОЙ. Из каждого секрета выводится ПУБЛИЧНЫЙ адрес, и
сверяется адрес. Проверка по именам пропустила бы ключ кошелька, названный
BLOOM_KEY или PRIVATE_KEY_NOX, -- именно поэтому список имён намеренно шире, чем
"ключи кошельков", а решение принимает выведенный адрес.

ЧЕГО ЗДЕСЬ НЕТ. Печати секрета, его куска, его хвоста; текста исключений разбора
(в текст исключения может попасть сам секрет -- наружу идёт только имя класса).
Ни одной подписи и ни одной отправки: ключ читается только ради адреса.

Пустой секрет и "не ключ" -- РАЗНЫЕ ответы. Пустой означает "в этом хранилище
такого секрета нет", "не ключ" -- "секрет есть, но кошелька в нём нет". Сливать
их в одно "нет" нельзя: первое говорит про хранилище, второе про содержимое.
"""
from __future__ import annotations

import argparse
import json
import os
import sys
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parent.parent.parent
sys.path.insert(0, str(КОРЕНЬ / "analysis"))

BASE58 = set("123456789ABCDEFGHJKLMNPQRSTUVWXYZabcdefghijkmnopqrstuvwxyz")


def вид_секрета(с: str) -> str:
    """Каким видом записан секрет. Ни одного знака самого секрета."""
    т = с.strip()
    if т.startswith("[") and т.endswith("]"):
        return "массив байтов JSON"
    if т and all(ч in BASE58 for ч in т):
        return "base58"
    return "неопознанный вид"


def разобрать_цели(строка: str) -> dict:
    """"адрес=чей,адрес=чей" -> {адрес: чей}. Без чего -- адрес сам себе имя."""
    из_: dict = {}
    for кусок in (строка or "").split(","):
        к = кусок.strip()
        if not к:
            continue
        адрес, _, чей = к.partition("=")
        адрес = адрес.strip()
        if адрес:
            из_[адрес] = чей.strip() or адрес
    return из_


def адрес_из_секрета(сырое: str, *, загрузчик=None) -> dict:
    """Публичный адрес из секрета. Любой отказ -- словами, без секрета в них."""
    из_ = {"ok": False, "адрес": None, "почему": None,
            "длина_секрета": len(сырое or ""), "вид_секрета": None}
    т = (сырое or "").strip()
    if not т:
        из_["почему"] = "секрет пуст или не задан в этом хранилище"
        return из_
    из_["вид_секрета"] = вид_секрета(т)
    if загрузчик is None:
        try:
            from dbot_rescue import load_rescue_keypair as загрузчик  # noqa: PLC0415
        except Exception as exc:  # noqa: BLE001
            из_["почему"] = f"разборщик ключа не загружен: {type(exc).__name__}"
            return из_
    try:
        адрес = str(загрузчик(т).pubkey())
    except Exception as exc:  # noqa: BLE001
        # ТЕКСТ ИСКЛЮЧЕНИЯ НЕ ПЕЧАТАЕМ: в него может попасть сам секрет.
        из_["почему"] = f"не ключ кошелька ({type(exc).__name__})"
        return из_
    # Проверка наизнанку: адрес обязан выглядеть адресом Solana.
    if not (32 <= len(адрес) <= 44) or not all(ч in BASE58 for ч in адрес):
        из_["почему"] = f"полученный адрес не похож на адрес Solana (длина {len(адрес)})"
        return из_
    из_.update(ok=True, адрес=адрес)
    return из_


def свод(имена, цели: dict, *, окружение=None, загрузчик=None) -> dict:
    """По каждому имени: адрес или причина; и попадания по целям."""
    окр = os.environ if окружение is None else окружение
    строки: list = []
    for имя in имена:
        р = адрес_из_секрета(окр.get(имя) or "", загрузчик=загрузчик)
        стр = {"секрет": имя, "есть_в_хранилище": bool((окр.get(имя) or "").strip()),
                "ключ_кошелька": bool(р["ok"]), "адрес": р["адрес"],
                "чей": цели.get(р["адрес"]) if р["адрес"] else None,
                "вид_секрета": р["вид_секрета"], "длина_секрета": р["длина_секрета"],
                "почему": р["почему"]}
        строки.append(стр)
    попадания = [с for с in строки if с["чей"]]
    по_цели = {}
    for адрес, чей in цели.items():
        где = [с["секрет"] for с in строки if с["адрес"] == адрес]
        по_цели[адрес] = {"чей": чей, "в_секретах": где, "найден": bool(где)}
    return {"строки": строки, "попадания": попадания, "по_цели": по_цели,
             "секретов_просмотрено": len(строки),
             "ключей_кошельков": sum(1 for с in строки if с["ключ_кошелька"])}


def самопроверка() -> int:
    из_строя = []

    def chk(имя, усл, *лишнее):
        print(("ok  " if усл else "СБОЙ") + "  " + имя
               + ("" if усл else "  " + repr(лишнее)))
        if not усл:
            из_строя.append(имя)

    class КП:
        def __init__(self, адрес):
            self._а = адрес

        def pubkey(self):
            return self._а

    ТАЙНА = "СЕКРЕТНАЯ_СТРОКА_КОТОРОЙ_НЕ_ДОЛЖНО_БЫТЬ_В_ОТЧЁТЕ"
    АДР_B = "4s87RRC2V2XAJD6R8U2dP8kQH99Z2wA6fg88ZVfV4j4N"
    АДР_П = "4dPZMbReSobZVxfrzGLcD7xJN33pZhuUZix5HkTBTh4x"

    def загр(с):
        if с == "кБ":
            return КП(АДР_B)
        if с == "кП":
            return КП(АДР_П)
        raise ValueError(f"не ключ: {ТАЙНА}")

    цели = разобрать_цели(f"{АДР_B}=Bloom (исполнитель),{АДР_П}=полоса (LIVE)")
    chk("цели разобрались", цели.get(АДР_B) == "Bloom (исполнитель)", цели)
    chk("цель без 'чей' сама себе имя",
        разобрать_цели("АдресОдин").get("АдресОдин") == "АдресОдин")

    окр = {"EXEC_WALLET_KEY": "кБ", "LIVE_PRIVATE": "кП",
            "BLOOM_API_KEY_PRIVATE": ТАЙНА, "RESCUE_WALLET_KEY": "",
            "BLOOM_KEY": "   "}
    с = свод(list(окр), цели, окружение=окр, загрузчик=загр)

    по_имени = {р["секрет"]: р for р in с["строки"]}
    chk("ключ кошелька Bloom найден ВЫВОДОМ АДРЕСА",
        по_имени["EXEC_WALLET_KEY"]["адрес"] == АДР_B
        and по_имени["EXEC_WALLET_KEY"]["чей"] == "Bloom (исполнитель)",
        по_имени["EXEC_WALLET_KEY"])
    chk("ключ полосы найден и назван полосой",
        по_имени["LIVE_PRIVATE"]["чей"] == "полоса (LIVE)")
    # ИМЕНА НЕ РЕШАЮТ: секрет с "PRIVATE" в имени ключом кошелька не является.
    chk("секрет с PRIVATE в имени, но не ключ -- 'не ключ', а не попадание",
        по_имени["BLOOM_API_KEY_PRIVATE"]["ключ_кошелька"] is False
        and по_имени["BLOOM_API_KEY_PRIVATE"]["чей"] is None)
    # ПУСТОЙ И "НЕ КЛЮЧ" -- РАЗНЫЕ ОТВЕТЫ.
    chk("пустой секрет: есть_в_хранилище=False",
        по_имени["RESCUE_WALLET_KEY"]["есть_в_хранилище"] is False
        and "пуст" in (по_имени["RESCUE_WALLET_KEY"]["почему"] or ""))
    chk("секрет из пробелов считается пустым",
        по_имени["BLOOM_KEY"]["есть_в_хранилище"] is False)
    chk("непустой, но не ключ: есть_в_хранилище=True",
        по_имени["BLOOM_API_KEY_PRIVATE"]["есть_в_хранилище"] is True)
    chk("по_цели: кошелёк Bloom найден и назван свой секрет",
        с["по_цели"][АДР_B]["найден"] is True
        and с["по_цели"][АДР_B]["в_секретах"] == ["EXEC_WALLET_KEY"],
        с["по_цели"][АДР_B])
    chk("ключей кошельков ровно два", с["ключей_кошельков"] == 2,
        с["ключей_кошельков"])
    chk("попаданий ровно два", len(с["попадания"]) == 2)

    # ЦЕЛЬ, КОТОРОЙ В СЕКРЕТАХ НЕТ, ДОЛЖНА ЧИТАТЬСЯ КАК "НЕ НАЙДЕНА", а не
    # отсутствовать в отчёте: "строки нет" и "нет ключа" владелец прочтёт
    # по-разному.
    цели2 = разобрать_цели(f"{АДР_B}=Bloom,СтарыйАдрес=старый полосы")
    с2 = свод(["EXEC_WALLET_KEY"], цели2, окружение=окр, загрузчик=загр)
    chk("цель без ключа в секретах: найден=False и пустой список",
        с2["по_цели"]["СтарыйАдрес"]["найден"] is False
        and с2["по_цели"]["СтарыйАдрес"]["в_секретах"] == [],
        с2["по_цели"]["СтарыйАдрес"])

    # САМОЕ ГЛАВНОЕ: отчёт не должен содержать ни секрета, ни текста исключения.
    текст = json.dumps(с, ensure_ascii=False)
    chk("самого секрета в отчёте нет", "кБ" not in текст and "кП" not in текст)
    chk("тайны из текста исключения в отчёте нет", ТАЙНА not in текст)
    chk("имя класса исключения осталось", "ValueError" in текст)

    print(f"итог: самопроверка {'норма' if not из_строя else 'СБОЙ'}; "
           f"провалов {len(из_строя)}")
    return 1 if из_строя else 0


def main() -> int:
    р = argparse.ArgumentParser()
    р.add_argument("--imena", default="", help="имена секретов через запятую")
    р.add_argument("--celi", default="", help="адрес=чей через запятую")
    р.add_argument("--out", default=None)
    р.add_argument("--self-test", action="store_true")
    а = р.parse_args()
    if а.self_test:
        return самопроверка()

    имена = [и.strip() for и in (а.imena or "").split(",") if и.strip()]
    if not имена:
        print(json.dumps({"ok": False,
                           "почему": "--imena пуст: сверять нечего"},
                          ensure_ascii=False))
        return 1
    с = свод(имена, разобрать_цели(а.celi))
    print(json.dumps(с, ensure_ascii=False, indent=1))
    if а.out:
        Path(а.out).parent.mkdir(parents=True, exist_ok=True)
        with open(а.out, "w", encoding="utf-8") as ф:
            json.dump(с, ф, ensure_ascii=False, indent=1)
    return 0


if __name__ == "__main__":
    sys.exit(main())
