#!/usr/bin/env python3
"""Имена допусков, видимых заданию -- БЕЗ ЗНАЧЕНИЙ. Печатает только ключи.

ЗАЧЕМ. Владелец сказал 04.10 вечером: "секрет LAB_DISPATCH_TOKEN заведён
(fine-grained, один репозиторий, Actions: Read and write)". Прогон часов
лаборатории при этом не видит ни одного из пяти вероятных имён (прогоны
37198875680, 37198994037, 37200179744), а GH_RUNNER_PAT видит. Перебор имён
отвечает только на вопрос "есть ли ЭТО имя", и ответ "нет" ничего не говорит о
том, какое имя там ЕСТЬ. Список секретов репозитория мне не прочитать: прокси
отвечает 403 и на actions/secrets, и на environments.

ЧТО ДЕЛАЕТ. Берёт набор секретов задания одним выражением GitHub
(toJSON(secrets)) через ОКРУЖЕНИЕ и печатает ТОЛЬКО КЛЮЧИ, отсортированные.
Значения не печатаются, не складываются в строки и не возвращаются наружу: из
разобранного набора берётся keys(), остальное выбрасывается.

ПОЧЕМУ ЧЕРЕЗ ОКРУЖЕНИЕ, А НЕ ДОВОДОМ. Довод командной строки виден в списке
процессов и в журнале шага; окружение в журнал прогона не печатается само, а
значения секретов в нём ещё и маскируются. Слово владельца про этот пакет --
"токен нигде не печатать", и здесь он не печатается ни в каком виде.

ЧЕГО СПИСОК НЕ ПОКАЖЕТ, И ЭТО САМО ПО СЕБЕ ОТВЕТ. Секреты ОКРУЖЕНИЯ в набор не
попадают, пока у задания нет environment:, а секреты Dependabot не попадают
никогда. Поэтому если имя не видно здесь, а владелец его заводил -- значит оно
заведено не секретом репозитория, и искать надо ровно там.
"""
from __future__ import annotations

import json
import os
import sys

ПЕРЕМЕННАЯ = "NABOR_DOPUSKOV"


def имена_из(сырое) -> dict:
    """Ключи набора допусков. Чистая функция: ни сети, ни окружения.

    Возвращает {"ok", "имена", "why_not"}. Ни одно ЗНАЧЕНИЕ наружу не выходит
    ни при каком исходе -- в том числе в тексте причины отказа: разбор падает
    на произвольном содержимом, и класть его текст в причину значило бы
    напечатать то, чего печатать нельзя. Поэтому причина -- только имя типа
    исключения.
    """
    т = (сырое or "").strip()
    if not т:
        return {"ok": False, "имена": [],
                 "why_not": f"переменной {ПЕРЕМЕННАЯ} нет или она пуста"}
    try:
        набор = json.loads(т)
    except Exception as сбой:  # noqa: BLE001
        return {"ok": False, "имена": [],
                 "why_not": f"набор не разобран как JSON: {type(сбой).__name__}"}
    if not isinstance(набор, dict):
        return {"ok": False, "имена": [],
                 "why_not": f"набор не словарь, а {type(набор).__name__}"}
    return {"ok": True, "имена": sorted(str(к) for к in набор), "why_not": None}


def main() -> int:
    из_ = имена_из(os.environ.get(ПЕРЕМЕННАЯ))
    if not из_["ok"]:
        print(f"  imjon ne vidno: {из_['why_not']}")
        return 0
    for имя in из_["имена"]:
        print(f"  {имя}")
    print(f"  vsego imjon: {len(из_['имена'])}")
    return 0


def _самопроверка() -> int:
    проверок = прошло = 0

    def сверить(что, дано, ждали):
        nonlocal проверок, прошло
        проверок += 1
        if дано == ждали:
            прошло += 1
        else:
            print(f"НЕ ПРОШЛО: {что}: дано {дано!r}, ждали {ждали!r}")

    # ГЛАВНОЕ: ЗНАЧЕНИЯ НЕ ВЫХОДЯТ НАРУЖУ НИ ПРИ КАКОМ ИСХОДЕ.
    набор = {"LAB_DISPATCH_TOKEN": "ghp_sekret1", "VPS_SSH_KEY": "-----BEGIN-----",
             "GH_RUNNER_PAT": "ghp_sekret2"}
    из_ = имена_из(json.dumps(набор))
    сверить("имена отданы отсортированными",
            из_["имена"],
            ["GH_RUNNER_PAT", "LAB_DISPATCH_TOKEN", "VPS_SSH_KEY"])
    весь = json.dumps(из_, ensure_ascii=False)
    сверить("НИ ОДНОГО значения в ответе нет",
            [з for з in набор.values() if з in весь], [])
    сверить("ok при годном наборе", из_["ok"], True)

    пусто = имена_из("")
    сверить("пустая переменная -- отказ словами, а не падение",
            (пусто["ok"], bool(пусто["why_not"])), (False, True))
    сверить("и имён при этом ноль", пусто["имена"], [])
    нет_перем = имена_из(None)
    сверить("переменной нет вовсе -- тот же честный отказ",
            нет_перем["ok"], False)

    # СЛОМАННЫЙ JSON: причина -- ТОЛЬКО ИМЯ ТИПА, без содержимого. Иначе в
    # журнал уехал бы кусок секрета ровно в том случае, когда разбор и упал.
    битое = имена_из('{"LAB_DISPATCH_TOKEN": "ghp_sekret1"')
    сверить("битый JSON -- отказ, а не исключение", битое["ok"], False)
    сверить("и в причине нет ни знака из значения",
            "ghp_sekret1" in (битое["why_not"] or ""), False)
    сверить("а тип сбоя назван", "JSONDecodeError" in (битое["why_not"] or ""),
            True)

    не_словарь = имена_из('["LAB_DISPATCH_TOKEN"]')
    сверить("набор не словарём -- отказ и названо, чем он оказался",
            не_словарь["ok"] is False and "list" in (не_словарь["why_not"] or ""),
            True)

    # ПУСТОЙ НАБОР -- ЭТО ОТВЕТ "НИ ОДНОГО ИМЕНИ", А НЕ ОШИБКА.
    сверить("пустой словарь -- ok и ноль имён",
            имена_из("{}"), {"ok": True, "имена": [], "why_not": None})

    # ИМЯ С НЕОБЫЧНЫМИ ЗНАКАМИ НЕ РОНЯЕТ ПЕЧАТЬ.
    сверить("нелатинское имя проходит как имя",
            имена_из('{"ИМЯ_ДОПУСКА": "x"}')["имена"], ["ИМЯ_ДОПУСКА"])

    print(f"проверок {проверок}, прошло {прошло}, "
          f"не прошло {проверок - прошло}")
    return 0 if прошло == проверок else 1


if __name__ == "__main__":
    if "--self-test" in sys.argv:
        sys.exit(_самопроверка())
    sys.exit(main())
