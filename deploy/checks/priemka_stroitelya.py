def происхождение_сборки() -> dict:
    """ЧЬЮ сборку мы сейчас мерили: путь файла и его sha256.

    ЗАЧЕМ. Харнесс берёт сборку из BLOOM_CODE_DIR, и это правильно: так его
    можно навести и на то, что СТОИТ у службы, и на КАНДИДАТА из чужой ветки.
    Но отчёт, в котором не сказано, чей код мерили, опаснее отсутствия отчёта:
    "приняли CLMM" без этой строки не отличить от "приняли то, что уже стоит".
    Поэтому путь и отпечаток идут в отчёт всегда.
    """
    из_ = {"файл": None, "sha256": None, "why_not": None}
    try:
        import bloom_own_send as OS  # noqa: PLC0415
    except Exception as exc:  # noqa: BLE001
        из_["why_not"] = f"сборка не импортируется: {type(exc).__name__}"
        return из_
    путь = getattr(OS, "__file__", None)
    из_["файл"] = путь
    if not путь or not os.path.exists(путь):
        из_["why_not"] = "у модуля сборки нет файла на диске"
        return из_
    try:
        import hashlib  # noqa: PLC0415

        х = hashlib.sha256()
        with open(путь, "rb") as ф:
            for кусок in iter(lambda: ф.read(65536), b""):
                х.update(кусок)
        из_["sha256"] = х.hexdigest()[:16]
    except Exception as exc:  # noqa: BLE001
        из_["why_not"] = f"отпечаток не снялся: {type(exc).__name__}"
    return из_


def _по_целевому_типу(строки: list, программа: str) -> dict:
    """Корзины и CU ТОЛЬКО по тому типу пула, ради которого шёл прогон.

    pool_program полоса проставляет ДО гейта типов, поэтому строка, отказанная
    гейтом, сюда попадает (и это правда: тип отвергнут гейтом, а не строителем),
    а сделка роутера, собранная по другому типу, -- нет.
    """
    def прог(с):
        return (с.get("сборка") or {}).get("pool_program")

    целевые = [с for с in строки if прог(с) == программа]
    по_корзинам: dict = {}
    for с in целевые:
        к = корзина(с)
        по_корзинам[к] = по_корзинам.get(к, 0) + 1
    cu = [(с.get("симуляция") or {}).get("cu") for с in целевые
           if (с.get("симуляция") or {}).get("cu")]
    чем: dict = {}
    for с in строки:
        if (с.get("сборка") or {}).get("ok") is True:
            чем[прог(с) or "тип не назван"] = чем.get(прог(с) or "тип не назван", 0) + 1
    село_чужим = {к: v for к, v in чем.items() if к != программа}
    return {
        "целевой_тип": {
            "строк": len(целевые),
            "село": по_корзинам.get("село", 0),
            "отказы": по_корзинам.get("отказ", 0),
            "падения": по_корзинам.get("падение", 0),
            "прочее": по_корзинам.get("прочее", 0),
            "не_дошло": по_корзинам.get("не дошло", 0),
            "cu_p50": процентиль(cu, 0.5),
            "cu_max": (max(cu) if cu else None)},
        "чем_собрано": чем,
        "собрано_не_целевым_типом": (село_чужим or None),
    }


