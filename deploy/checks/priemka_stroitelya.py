def минт_покупки_из_tx(tx: dict, источник: str = "") -> tuple:
    """(минт, как_узнали, почему_нет): какой минт источник ПОЛУЧИЛ в сделке.

    ЗАЧЕМ. В сборе Code-2 по Whirlpool поля минта нет ни в одной строке: все 72
    строки приёмки 22:44:49Z пришли с минт=None. Полосе минт нужен обязательно --
    без него собрать() отказалась бы на каждой строке, и три числа показали бы
    изъян строителя там, где изъян сбора.

    Минт берётся НЕ ИЗ ДОГАДКИ, а из meta.pre/postTokenBalances самой
    транзакции: тот минт, чей остаток У ИСТОЧНИКА вырос больше всех и это не
    WSOL. Это ровно то, что источник купил. Если вычислить нечем -- пусто и
    причина словами; выдумывать минт нельзя.
    """
    мета = (tx or {}).get("meta") or {}
    до, после = мета.get("preTokenBalances"), мета.get("postTokenBalances")
    if not isinstance(после, list) or not после:
        return ("", None, "в транзакции нет postTokenBalances -- минт не вычислить")
    места = {}
    for ряд, знак in ((до, -1), (после, 1)):
        for б in (ряд or []):
            if not isinstance(б, dict):
                continue
            минт, и = б.get("mint"), б.get("accountIndex")
            if not минт or и is None:
                continue
            try:
                сум = int((б.get("uiTokenAmount") or {}).get("amount"))
            except (TypeError, ValueError):
                continue
            з = места.setdefault(и, {"минт": минт, "владелец": None, "дельта": 0})
            з["дельта"] += знак * сум
            if з["владелец"] is None:
                з["владелец"] = б.get("owner")
    свои = [з for з in места.values()
            if источник and з.get("владелец") == источник]
    как = "остаток источника вырос"
    ряд = [з for з in свои if з["дельта"] > 0 and з["минт"] != ВСОЛ]
    if not ряд:
        # У ИСТОЧНИКА МОЖЕТ НЕ БЫТЬ СВОЕГО СЧЁТА В БАЛАНСАХ: часть покупок идёт
        # через промежуточный кошелёк. Тогда берём любой выросший не-WSOL минт и
        # ГОВОРИМ, что владелец не совпал -- чтобы в отчёте было видно, чем
        # именно вычислено.
        как = "остаток вырос (счёта источника в балансах нет)"
        ряд = [з for з in места.values() if з["дельта"] > 0 and з["минт"] != ВСОЛ]
    if not ряд:
        return ("", None, "ни один минт кроме WSOL в сделке не вырос")
    ряд.sort(key=lambda з: -з["дельта"])
    минты = {з["минт"] for з in ряд}
    if len(минты) > 1:
        как += f"; выросло минтов {len(минты)}, берём наибольший"
    return (ряд[0]["минт"], как, None)


def корзина(строка: dict) -> str:
    """Одно правило на все типы пула: куда попадает эта строка.

    село        -- симуляция ответила без ошибки;
    падение     -- симуляция ответила ошибкой (err != None);
    отказ       -- полоса отказалась ДО сборки: в бою она не отправила бы и
                   ничего не потратила;
    прочее      -- узел или журнал не дали данных; про сборку это не говорит
                   ничего, и валить это в отказ было бы ложью;
    не дошло    -- строка не доведена до вердикта (симуляций меньше, чем строк).
    """
    if строка.get("прочее"):
        return "прочее"
    сб = строка.get("сборка") or {}
    if сб.get("ok") is False:
        return "отказ"
    сим = строка.get("симуляция")
    if not isinstance(сим, dict) or сим.get("ok") is None:
        return "не дошло"
    if сим.get("ok") is False:
        return "прочее"
    return "падение" if сим.get("err") is not None else "село"


def разбор(нч: dict, *, программа: str, кошелёк: str, лампорты: int,
            проскальзывание: float, симулировать: bool) -> dict:
    """Одна живая покупка: байт в байт, сборка полосой, симуляция."""
    из_ = {"подпись": нч.get("подпись"), "минт": нч.get("минт"),
            "источник": нч.get("источник"), "откуда": нч.get("откуда"),
            "байт_в_байт": None, "why_not": None, "прочее": None}
    import c2_swap_build as B  # noqa: PLC0415

    tx = нч.get("tx")
    if not isinstance(tx, dict):
        о = зов("getTransaction", [нч["подпись"], {
            "encoding": "jsonParsed", "maxSupportedTransactionVersion": 1,
            "commitment": "confirmed"}])
        if not о.get("ok") or not о.get("result"):
            из_["прочее"] = f"транзакция не прочиталась: {о.get('why_not')}"
            из_["why_not"] = из_["прочее"]
            return из_
        tx = о["result"]
        из_["tx_прочитана_узлом"] = True
    else:
        из_["tx_прочитана_узлом"] = False

    инстр = [ix for ix in B.all_instructions(tx) if ix.get("programId") == программа]
    if not инстр:
        из_["прочее"] = "инструкции этой программы в транзакции нет"
        из_["why_not"] = из_["прочее"]
        return из_
    # ПЕРЕБОР НАЧИНАЕТСЯ С КАНДИДАТОВ из сбора, потом все счета инструкции.
    порядок = [а for а in (нч.get("кандидаты") or []) if isinstance(а, str)]
    порядок += [а for а in (инстр[0].get("accounts") or []) if а not in порядок]
    tpl = None
    for кандидат in порядок:
        т = B.extract_template(tx, программа, кандидат)
        if т.get("ok"):
            tpl = т
            break
    # ШАБЛОН ЧЕРЕЗ B ЕСТЬ НЕ У ВСЕХ ТИПОВ, И ЭТО НЕ ОТКАЗ ТИПА.
    # extract_template и mints_and_vaults смотрят в c2_swap_build.SPECS, а у
    # Whirlpool записи там нет и не должно быть: счета делятся на A/B, а не на
    # вход/выход. Прежде харнесс обрывался здесь и выдавал 72 из 72
    # "шаблон инструкции не восстановился" -- то есть НИ ОДНОГО из трёх чисел, и
    # выглядело это изъяном строителя. Теперь байт в байт для таких типов честно
    # помечается неприменимым (его делает своя проверка Code-3,
    # deploy/checks/stroiteli_vosstanovlenie.py), а сборка и симуляция идут.
    свой_строитель_у_типа = программа in _реестр_строителей()
    if tpl is None and not свой_строитель_у_типа:
        из_["прочее"] = "шаблон инструкции не восстановился ни по одному счёту"
        из_["why_not"] = из_["прочее"]
        return из_
    if tpl is None:
        из_["байт_в_байт_why_not"] = (
            "шаблон через c2_swap_build не строится: у этого типа записи в SPECS "
            "нет по замыслу, он идёт своим строителем -- байт в байт проверяет "
            "deploy/checks/stroiteli_vosstanovlenie.py")
        из_["минт"] = из_["минт"] or ""
        минт = из_["минт"]
    else:
        из_["пул"] = (tpl.get("accounts") or [None])[0]
        из_["ix"] = tpl.get("ix")
        мв = B.mints_and_vaults(tpl, tx) or {}
        из_["база"] = мв.get("base_mint")
        из_["минт_котировки"] = мв.get("quote_mint")
        минт = из_["минт"] or мв.get("base_mint")
        из_["минт"] = минт

    # 1. БАЙТ В БАЙТ -- его аргументы, его пользователь.
    # ШАБЛОНА МОЖЕТ НЕ БЫТЬ ВОВСЕ: у типов со своим строителем (Whirlpool)
    # записи в SPECS нет по замыслу, why_not уже проставлен выше. Без этой
    # охраны падало AttributeError на tpl.get('arg0') -- и весь прогон
    # уходил в exit 1, не дав ни сборки, ни симуляции.
    if tpl is not None:
        а0, а1 = tpl.get("arg0"), tpl.get("arg1")
        если_аргументы = (а0 is not None and а1 is not None)
        его_user, откуда_user = пользователь_источника(tpl, tx, B)
        из_["пользователь_источника"] = его_user
        из_["откуда_пользователь"] = откуда_user
        if не_пусто(его_user) and если_аргументы:
            try:
                свой = B.swap_instruction(tpl, tx, его_user, а0, а1, keep_source_ix=True)
                свои_байты = bytes(свой.data)
                его_байты = (base64.b64decode(инстр[0]["data_b64"])
                              if инстр[0].get("data_b64") else bytes(tpl["data"]))
                свои_счета = [str(м.pubkey) for м in свой.accounts]
                его_счета = list(инстр[0]["accounts"])
                из_["данные_совпали"] = (свои_байты == его_байты)
                из_["счета_совпали"] = (свои_счета == его_счета)
                из_["счетов"] = len(его_счета)
                из_["длина_данных"] = len(его_байты)
                из_["байт_в_байт"] = bool(из_["данные_совпали"] and из_["счета_совпали"])
                if not из_["счета_совпали"]:
                    из_["счета_расхождение"] = [
                        {"i": и, "его": (его_счета[и] if и < len(его_счета) else None),
                          "наш": (свои_счета[и] if и < len(свои_счета) else None)}
                        for и in range(max(len(его_счета), len(свои_счета)))
                        if (его_счета[и] if и < len(его_счета) else None)
                        != (свои_счета[и] if и < len(свои_счета) else None)][:6]
            except Exception as exc:  # noqa: BLE001
                из_["байт_в_байт_why_not"] = (f"пересборка упала: {type(exc).__name__}: "
                                               f"{str(exc)[:140]}")
        else:
            из_["байт_в_байт_why_not"] = ("аргументы инструкции не разобрались"
                                           if не_пусто(его_user) else
                                           "пользователь источника не найден")

    # МИНТ ДЛЯ СБОРКИ. Сбор Code-2 по Whirlpool не несёт минта ни в одной
    # строке (72 из 72 с минт=None), а полосе он нужен обязательно. Выводим из
    # балансов самой транзакции -- что источник получил, то и покупаем.
    if not минт:
        минт, как_минт, поч_минт = минт_покупки_из_tx(tx, из_["источник"] or "")
        из_["минт"] = минт
        из_["минт_откуда"] = как_минт or поч_минт

    # 2. СБОРКА ПОЛОСОЙ -- её же правила, её же цена.
    try:
        import bloom_own_send as OS  # noqa: PLC0415

        сб = OS.собрать(tx_источника=tx, источник=(из_["источник"] or ""),
                         минт=(минт or ""), наш_кошелёк=кошелёк,
                         лампорты=лампорты, проскальзывание=проскальзывание,
                         rpc_call=lambda м, п_: зов(м, п_, таймаут=12.0))
    except Exception as exc:  # noqa: BLE001
        из_["прочее"] = f"сборка полосой упала: {type(exc).__name__}: {str(exc)[:140]}"
        из_["why_not"] = из_["прочее"]
        return из_
    из_["сборка"] = {к: сб.get(к) for к in (
        "ok", "why_not", "pool_program", "pool_label", "min_out", "expected_out",
        "build_ms", "tip_account", "size", "cu_units", "fee_share", "dlmm",
        "ценозависимые", "lane_route", "new_pool_size_sol")}
    из_["why_not"] = сб.get("why_not")
    tx64 = сб.get("tx_base64")

    # 3. СИМУЛЯЦИЯ собранного -- только если полоса собрала.
    if not сб.get("ok") or not tx64:
        return из_
    if not симулировать:
        return из_
    с = зов("simulateTransaction",
             [tx64, {"sigVerify": False, "replaceRecentBlockhash": True,
                      "encoding": "base64", "commitment": "processed"}])
    зн = ((с.get("result") or {}).get("value") or {}) if с.get("ok") else {}
    из_["симуляция"] = {"ok": с.get("ok"), "err": зн.get("err"),
                         "cu": зн.get("unitsConsumed"), "why_not": с.get("why_not"),
                         "логи_хвост": (зн.get("logs") or [])[-4:]}
    if зн.get("err") is not None:
        из_["падение_разбор"] = {
            "логи": list(зн.get("logs") or []),
            "счета_шаблона": list(tpl.get("accounts") or []),
            "минты_и_хранилища": мв, "наш_кошелёк": кошелёк,
            "лампорты": лампорты, "min_out": сб.get("min_out")}
    return из_


