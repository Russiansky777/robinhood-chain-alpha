def _реестр_строителей() -> dict:
    """Реестр "программа -> модуль строителя" из полосы. Пусто -- развилки нет.

    Читается через getattr нарочно: пока развилка в bloom_own_send.собрать() не
    поставлена, реестра нет, и харнесс ведёт себя ровно как прежде.
    """
    try:
        import bloom_own_send as _OS  # noqa: PLC0415

        return dict(getattr(_OS, "МОДУЛИ_СТРОИТЕЛЕЙ", {}) or {})
    except Exception:  # noqa: BLE001
        return {}


def ключ_и_имя() -> tuple:
    """(ключ, имя переменной). Свой ключ харнессов -- первым.

    Значение ключа наружу не отдаётся никогда: печатается только имя.
    """
    for имя in ("HELIUS_API_KEY_CHECKS", "HELIUS_API_KEY", "HELIUS_API"):
        зн = (os.environ.get(имя) or "").strip()
        if зн:
            return зн, имя
    return "", "не задан"


def урл() -> str:
    ключ, _ = ключ_и_имя()
    return f"{HELIUS}/?api-key={ключ}"


def зов(метод: str, параметры, *, таймаут: float = 30.0) -> dict:
    import urllib.request  # noqa: PLC0415

    тело = json.dumps({"jsonrpc": "2.0", "id": 1, "method": метод,
                        "params": параметры}).encode()
    зпр = urllib.request.Request(урл(), data=тело,
                                  headers={"Content-Type": "application/json"})
    try:
        with urllib.request.urlopen(зпр, timeout=таймаут) as отв:  # noqa: S310
            о = json.loads(отв.read().decode())
    except Exception as exc:  # noqa: BLE001
        return {"ok": False, "why_not": f"{type(exc).__name__}: {str(exc)[:160]}"}
    if "error" in о:
        return {"ok": False, "why_not": f"RPC: {str(о['error'])[:200]}"}
    return {"ok": True, "result": о.get("result")}


