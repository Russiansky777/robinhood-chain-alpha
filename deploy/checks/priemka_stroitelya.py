def строки_журнала(путь: str):
    открыть = gzip.open if путь.endswith(".gz") else open
    try:
        ф = открыть(путь, "rt", encoding="utf-8", errors="replace")
    except Exception:  # noqa: BLE001
        return
    with ф:
        for стр in ф:
            стр = стр.strip()
            if not стр:
                continue
            try:
                yield json.loads(стр)
            except ValueError:
                continue


def программа_сбора(путь: str, данные: dict) -> str | None:
    """Адрес программы у файла сбора: сперва поле внутри, потом метка имени."""
    зн = (данные or {}).get("программа") or (данные or {}).get("program")
    if isinstance(зн, str) and len(зн) >= 32:
        return зн
    return СБОР_ПО_МЕТКЕ.get(os.path.basename(путь))


def адреса_инструкции(инстр: dict) -> list:
    """Все адреса инструкции КАК НАБОР, без чтения имён ролей.

    Имена ключей внутри "роли" у каждой программы свои, и читать их значило бы
    привязать харнесс к типу пула -- ровно то, чего быть не должно. Харнессу
    нужен счёт пула, и он всё равно находит его перебором через extract_template;
    здесь собираются только кандидаты, чтобы перебор начинался с осмысленных.
    """
    из_: list = []
    роли = (инстр or {}).get("роли")
    if isinstance(роли, dict):
        из_.extend([v for v in роли.values() if isinstance(v, str)])
    for ключ in ("остаток", "счета", "accounts"):
        зн = (инстр or {}).get(ключ)
        if isinstance(зн, list):
            из_.extend([v for v in зн if isinstance(v, str)])
    видели, чисто = set(), []
    for а in из_:
        if а not in видели:
            видели.add(а)
            чисто.append(а)
    return чисто


def из_сбора(программа: str, *, каталог: str, сколько: int) -> dict:
    """Живые покупки из сборов Code-2. Файл выбирается по программе."""
    из_ = {"строки": [], "why_not": None, "файл": None, "сделок_в_файле": None}
    try:
        файлы = sorted(glob.glob(os.path.join(каталог, "*_sbor.json")))
    except Exception as exc:  # noqa: BLE001
        из_["why_not"] = f"каталог сборов не прочитан: {type(exc).__name__}"
        return из_
    if not файлы:
        из_["why_not"] = f"в {каталог} нет файлов *_sbor.json"
        return из_
    непонятные = []
    for путь in файлы:
        try:
            д = json.loads(open(путь, encoding="utf-8").read())
        except Exception as exc:  # noqa: BLE001
            непонятные.append(f"{os.path.basename(путь)}: {type(exc).__name__}")
            continue
        прог = программа_сбора(путь, д)
        if прог != программа:
            if прог is None:
                непонятные.append(f"{os.path.basename(путь)}: программа не названа")
            continue
        из_["файл"] = путь
        сделки = д.get("сделки")
        if not isinstance(сделки, list):
            из_["why_not"] = f"{os.path.basename(путь)}: нет раздела сделки"
            return из_
        из_["сделок_в_файле"] = len(сделки)
        из_["окно_с"] = д.get("окно_с")
        for с in сделки:
            подпись = (с or {}).get("signature")
            инстр = (с or {}).get("инструкции")
            if not подпись or not isinstance(инстр, list) or not инстр:
                continue
            кандидаты = []
            for и_ in инстр:
                кандидаты.extend(адреса_инструкции(и_))
            из_["строки"].append({
                "подпись": подпись, "минт": (с or {}).get("минт") or (с or {}).get("mint"),
                "источник": (с or {}).get("кошелёк") or (с or {}).get("источник"),
                "blockTime": (с or {}).get("blockTime"),
                "вид": (инстр[0] or {}).get("вид"),
                "кандидаты": кандидаты, "откуда": "sbor", "tx": None})
            if len(из_["строки"]) >= сколько:
                break
        return из_
    из_["why_not"] = ("файла сбора для этой программы нет"
                       + (f"; не разобраны: {'; '.join(непонятные[:3])}"
                          if непонятные else ""))
    return из_


def из_образцов(программа: str, *, сколько: int) -> dict:
    """Живые покупки из образцов пулов: транзакция уже лежит целиком."""
    из_ = {"строки": [], "why_not": None}
    try:
        import c2_common as C  # noqa: PLC0415
        import c2_swap_build as B  # noqa: PLC0415

        образцы = B.load_samples(программа) or []
    except Exception as exc:  # noqa: BLE001
        из_["why_not"] = f"образцы не прочитаны: {type(exc).__name__}: {str(exc)[:100]}"
        return из_
    for x in образцы:
        tx = (x or {}).get("tx")
        if not isinstance(tx, dict):
            continue
        try:
            подпись = C.first_signature(tx)
        except Exception:  # noqa: BLE001
            подпись = None
        if not подпись:
            continue
        из_["строки"].append({
            "подпись": подпись, "минт": x.get("mint"), "источник": x.get("source"),
            "blockTime": tx.get("blockTime"),
            "кандидаты": ([x["pool_vault"]] if x.get("pool_vault") else []),
            "откуда": "obrazcy", "tx": tx})
        if len(из_["строки"]) >= сколько:
            break
    if not из_["строки"] and not из_["why_not"]:
        из_["why_not"] = "образцов этой программы нет"
    return из_


def из_журнала(программа: str, *, state_dir: str, сколько: int) -> dict:
    """Живые покупки из журнала решений детектора. Журнал читается потоком."""
    из_ = {"строки": [], "why_not": None}
    пути = sorted(glob.glob(os.path.join(state_dir, "decisions*.jsonl*")),
                   reverse=True)
    if not пути:
        из_["why_not"] = f"в {state_dir} нет decisions*.jsonl"
        return из_
    видели = set()
    for путь in пути:
        for зап in строки_журнала(путь):
            строка = json.dumps(зап, ensure_ascii=False)
            if программа not in строка:
                continue
            п = зап.get("signature") or зап.get("source_sig")
            if not п or п in видели:
                continue
            видели.add(п)
            из_["строки"].append({
                "подпись": п, "минт": зап.get("mint"), "источник": зап.get("source"),
                "blockTime": None, "кандидаты": [], "откуда": "zhurnal",
                "tx": None, "stage": зап.get("stage")})
            if len(из_["строки"]) >= сколько:
                return из_
    if not из_["строки"] and not из_["why_not"]:
        из_["why_not"] = "в журнале сделок этой программы нет"
    return из_


def живые_покупки(программа: str, *, сколько: int, откуда: str, сборы: str,
                   state_dir: str, с_минтом: str = "") -> dict:
    """Живые покупки источников на этой программе. Порядок источников -- как задан.

    с_минтом -- взять только те покупки, среди счетов которых есть ЭТОТ адрес.
    Нужно, чтобы нацелить приёмку на пулы с котировкой в SOL: полоса берёт
    только их, и без отбора выборка из первых N упирается в отказ "котировка
    пула не SOL" вместо проверки сборки. Отбор по АДРЕСУ, а не по типу пула:
    харнесс о типах по-прежнему не знает ничего.
    """
    из_ = {"строки": [], "по_источникам": {}, "отказы": {},
            "отобрано_по_минту": (с_минтом or None), "отброшено_по_минту": 0}
    видели = set()
    for имя in [ч.strip() for ч in (откуда or "").split(",") if ч.strip()]:
        осталось = сколько - len(из_["строки"])
        if осталось <= 0:
            break
        # ПРИ ОТБОРЕ ПО МИНТУ БЕРЁМ ИЗ ИСТОЧНИКА ЗАПАС. Иначе отбор режет уже
        # урезанную выборку, и на выходе оказывается меньше строк, чем просили.
        просить = осталось * (20 if с_минтом else 1)
        if имя == "sbor":
            р = из_сбора(программа, каталог=сборы, сколько=просить)
        elif имя == "obrazcy":
            р = из_образцов(программа, сколько=просить)
        elif имя == "zhurnal":
            р = из_журнала(программа, state_dir=state_dir, сколько=просить)
        else:
            из_["отказы"][имя] = "неизвестный источник живых покупок"
            continue
        добавлено = 0
        for с in р.get("строки") or []:
            if с["подпись"] in видели:
                continue
            if с_минтом and с_минтом not in (с.get("кандидаты") or []):
                из_["отброшено_по_минту"] += 1
                continue
            видели.add(с["подпись"])
            из_["строки"].append(с)
            добавлено += 1
        из_["по_источникам"][имя] = добавлено
        if р.get("why_not"):
            из_["отказы"][имя] = р["why_not"]
        if р.get("файл"):
            из_["файл_сбора"] = р["файл"]
            из_["сделок_в_сборе"] = р.get("сделок_в_файле")
            из_["окно_сбора"] = р.get("окно_с")
    return из_


