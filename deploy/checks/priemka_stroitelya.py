def пользователь_источника(tpl: dict, tx: dict, B) -> tuple:
    """(адрес, откуда). Пользователь берётся с МЕСТА ПО СПЕЦИФИКАЦИИ.

    Не плательщик транзакции: у части источников покупку подписывает один ключ,
    а комиссию платит другой, и сравнение счетов тогда расходится на ровном месте.
    """
    места = (B.spec_of(tpl).get("user") or [])
    счета = tpl.get("accounts") or []
    if места and isinstance(места[0], int) and места[0] < len(счета):
        return счета[места[0]], f"место {места[0]} по спецификации"
    сообщение = ((tx or {}).get("transaction") or {}).get("message") or {}
    ключи = [(к.get("pubkey") if isinstance(к, dict) else к)
              for к in (сообщение.get("accountKeys") or [])]
    return (ключи[0] if ключи else None), "плательщик транзакции (места в спецификации нет)"


