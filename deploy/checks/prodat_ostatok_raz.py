def остаток_минта(счета: list, mint: str, кошелёк: str) -> dict:
    """Остаток названного минта у названного кошелька. Чужие счета не берём.

    Счетов по одному минту может быть несколько (ATA и не-ATA). Берём ТОТ, НА
    КОТОРОМ ЕСТЬ ОСТАТОК, и говорим, сколько счетов нашлось: продать с двух
    счетов одной транзакцией Jupiter всё равно нельзя, и прятать второй счёт за
    молчанием -- значит оставить на нём токен.
    """
    свои = [с for с in (счета or [])
            if с.get("mint") == mint and с.get("owner") == кошелёк]
    # ПОДСТАВЛЯТЬ "0" ВМЕСТО НЕПРОЧИТАННОГО НЕЛЬЗЯ: тогда проверка "это число"
    # всегда проходит, и дальше int(None) роняет прогон -- либо, хуже, не
    # прочитанный остаток читается как нулевой.
    def _число(с_):
        сырое = с_.get("amount_raw")
        return str(сырое).isdigit() and int(сырое) > 0

    с_остатком = [с for с in свои if _число(с)]
    из_ = {"счетов_минта": len(свои), "счетов_с_остатком": len(с_остатком),
            "счёт": None, "остаток_raw": 0, "decimals": None,
            "прочие_счета": [с.get("account") for с in с_остатком[1:]]}
    if not с_остатком:
        нечитаемые = [с.get("account") for с in свои
                       if not str(с.get("amount_raw")).isdigit()]
        если = ("остаток счёта не прочитан (" + ", ".join(map(str, нечитаемые))
                 + ") -- продавать нельзя" if нечитаемые
                 else "остатка этого минта у кошелька нет")
        из_["почему"] = если if свои else "счёта этого минта у кошелька нет"
        return из_
    лучший = max(с_остатком, key=lambda с: int(с["amount_raw"]))
    из_.update(счёт=лучший.get("account"), остаток_raw=int(лучший["amount_raw"]),
                decimals=лучший.get("decimals"), почему=None)
    return из_


def баланс_sol(вызов, кошелёк: str) -> int:
    от = вызов("getBalance", [кошелёк, {"commitment": "confirmed"}]) or {}
    зн = от.get("value") if isinstance(от, dict) else от
    return int(зн or 0)


def итог_по_цепи(вызов, кошелёк: str, mint: str, *, до_лампортов: int,
                  подпись: str | None, ждать_s: float = 60.0,
                  пауза_s: float = 3.0, спать=time.sleep) -> dict:
    """Что СТАЛО после отправки: дельта SOL кошелька и остаток минта.

    Ждём именно подтверждения подписи: баланс, прочитанный до того как
    транзакция села, покажет "ничего не изменилось" -- тихий зелёный ответ.
    """
    из_ = {"подпись": подпись, "подтверждена": False, "ошибка_цепи": None,
            "дельта_sol": None, "остаток_после_raw": None, "слот": None,
            "почему": None}
    if not подпись:
        из_["почему"] = "подписи нет -- по цепи сверять нечего"
        return из_
    срок = ждать_s
    while срок > 0:
        от = вызов("getTransaction",
                    [подпись, {"maxSupportedTransactionVersion": 0,
                               "commitment": "confirmed"}])
        if от:
            из_["подтверждена"] = True
            из_["слот"] = от.get("slot")
            из_["ошибка_цепи"] = ((от.get("meta") or {}).get("err"))
            break
        спать(пауза_s)
        срок -= пауза_s
    if not из_["подтверждена"]:
        из_["почему"] = f"подпись не подтвердилась за {ждать_s:.0f} с -- итог НЕ ЗНАЮ"
        return из_
    после = баланс_sol(вызов, кошелёк)
    из_["дельта_sol"] = round((после - до_лампортов) / 1e9, 9)
    from close_empty_token_accounts import счета_кошелька  # noqa: PLC0415
    сч = счета_кошелька(вызов, кошелёк)
    ост = остаток_минта(сч.get("счета") or [], mint, кошелёк)
    из_["остаток_после_raw"] = ост["остаток_raw"]
    из_["счёт"] = ост["счёт"]
    из_["счёт_пуст"] = ост["остаток_raw"] == 0
    return из_


def строка(свод: dict) -> str:
    """Одна строка владельцу. Чего не знаем -- так и говорим."""
    ц = свод.get("цепь") or {}
    if не := свод.get("why_not"):
        return f"{свод.get('mint')}: не продано -- {не}"
    if not ц.get("подтверждена"):
        return (f"{свод.get('mint')}: подпись {ц.get('подпись')}, "
                 f"{ц.get('почему') or 'итог по цепи НЕ ЗНАЮ'}")
    if ц.get("ошибка_цепи"):
        return (f"{свод.get('mint')}: подпись {ц.get('подпись')} села с ошибкой "
                 f"{ц['ошибка_цепи']} -- остаток на месте")
    д = ц.get("дельта_sol")
    ост = ц.get("остаток_после_raw")
    return (f"{свод.get('mint')}: продано, подпись {ц.get('подпись')}, "
             f"кошелёк {'+' if (д or 0) >= 0 else ''}{д} SOL по цепи, "
             f"остаток минта {ост}"
             + (", счёт пуст -- можно закрывать" if ост == 0
                else ", счёт НЕ пуст -- закрывать нельзя"))


def продать_раз(*, mint: str, кошелёк: str, вход_sol: float | None,
                 вызов, продать_фн=None, ключ_фн=None, окружение=None,
                 ждать_s: float = 60.0, спать=time.sleep) -> dict:
    """Один проход. Порядок: остаток -> ключ -> баланс до -> продажа -> цепь."""
    свод = {"mint": mint, "кошелёк": кошелёк, "вход_sol": вход_sol,
             "живьём": живой_режим(окружение), "why_not": None}
    from close_empty_token_accounts import счета_кошелька  # noqa: PLC0415
    сч = счета_кошелька(вызов, кошелёк)
    if сч.get("why_not"):
        свод["why_not"] = f"счета кошелька не прочитаны: {сч['why_not']}"
        return свод
    ост = остаток_минта(сч.get("счета") or [], mint, кошелёк)
    свод["остаток"] = ост
    if not ост["остаток_raw"]:
        свод["why_not"] = ост.get("почему") or "остаток ноль"
        return свод
    if ост["прочие_счета"]:
        # НЕ МОЛЧИМ. Второй счёт с остатком этот прогон не продаёт, и владелец
        # должен узнать это от нас, а не потом по "счёт не закрылся".
        свод["предупреждение"] = ("у минта есть ещё счета с остатком: "
                                   + ", ".join(ост["прочие_счета"]))

    if ключ_фн is None:
        from close_empty_token_accounts import ключ_кошелька as ключ_фн  # noqa: PLC0415
    к = ключ_фн(кошелёк)
    свод["ключ_наш"] = bool(к.get("ok"))
    if not к.get("ok"):
        свод["why_not"] = к.get("why_not") or "ключ не подошёл"
        return свод

    до = баланс_sol(вызов, кошелёк)
    свод["баланс_до_sol"] = round(до / 1e9, 9)

    if продать_фн is None:
        import bloom_jupiter_sell as J  # noqa: PLC0415
        продать_фн = J.продать
    р = продать_фн(mint=mint, amount_raw=ост["остаток_raw"], taker=кошелёк,
                    вход_sol=вход_sol, живьём=свод["живьём"],
                    секрет=к["секрет"],
                    # РОВНО ТО, ЧТО РАЗРЕШИЛ ВЛАДЕЛЕЦ: правило 30 % от входа
                    # снято. Пол 70 % от котировки остаётся внутри продажи.
                    мин_доля_от_входа=0.0)
    свод["jupiter"] = {"ok": bool(р.get("ok")), "why_not": р.get("why_not"),
                        "api_used": р.get("api_used"),
                        "подпись": р.get("signature"),
                        "котировка_lamports": ((р.get("floor") or {})
                                               .get("checks") or {}).get("out_amount"),
                        "доля_от_входа_pct": ((р.get("floor") or {})
                                              .get("checks") or {}).get("quote_share_of_entry_pct")}
    if not свод["живьём"]:
        свод["why_not"] = (f"живой режим выключен ({ФЛАГ_ЖИВЬЁМ} не равен 1): "
                            "котировка прочитана, подписи и отправки не было")
        return свод
    if not р.get("signature"):
        свод["why_not"] = р.get("why_not") or "подписи нет -- в сеть ничего не ушло"
        return свод
    свод["цепь"] = итог_по_цепи(вызов, кошелёк, mint, до_лампортов=до,
                                 подпись=р.get("signature"), ждать_s=ждать_s,
                                 спать=спать)
    свод["строка"] = строка(свод)
    return свод


