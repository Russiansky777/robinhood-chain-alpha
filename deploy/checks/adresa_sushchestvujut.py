#!/usr/bin/env python3
"""Каждый адрес из списка -- СУЩЕСТВУЮЩИЙ счёт на цепи. Иначе это не адрес.

ЗАЧЕМ, И ЭТО ПРО УТЕЧКУ КЛЮЧА, А НЕ ПРО ОПРЯТНОСТЬ. Бэкап хоста выгружает
окружение ТОЛЬКО ИМЕНАМИ, кроме короткого списка публичных адресов (nonce-счета
и адреса получателей): их владелец просил списком. Отбор по имени и по длине
32..44 знака base58 выглядел достаточным -- приватный ключ ed25519 в base58 это
87-88 знаков. Но 32-БАЙТНЫЙ СИД в base58 -- РОВНО 43-44 ЗНАКА, то есть длина
ключ от адреса НЕ ОТЛИЧАЕТ.

Отличает ЦЕПЬ, И ПРОВЕРОК ДВЕ, А НЕ ОДНА. Существующий nonce-счёт или кошелёк
с деньгами getAccountInfo отдаёт счётом. Но ПУСТОЙ кошелёк счёта НЕ ИМЕЕТ ВОВСЕ:
на Solana нулевой баланс -- это отсутствие счёта, и getAccountInfo отдаёт null.
Замерено 12.10: кошелёк исполнителя 4s87RRC2... с нулём SOL не прошёл проверку
"счёт есть", и это была МОЯ ошибка в проверке, а не находка.

Поэтому адрес считается подтверждённым, если выполнено ЛЮБОЕ из двух:
  * счёт существует (getAccountInfo отдал счёт), ЛИБО
  * у адреса ЕСТЬ ИСТОРИЯ подписей (getSignaturesForAddress отдал хоть одну).
Сид, принятый за адрес, -- это случайная точка: у неё НЕТ ни счёта, ни истории.
Пустой, но ПОЖИВШИЙ кошелёк историю имеет, и этим он от сида и отличается.
Ни одно из двух не выполнено -- считаем, что в списке НЕ АДРЕС, и падаем. Прогон
после такого падения не выкладывает ни артефакт, ни ветку, ни отчёт.

ЧТО ЗНАЧИТ "НЕ СОШЛОСЬ". Отказ сети и отказ узла -- это НЕ подтверждение: в
таком случае тоже отказ, потому что молча пропустить непроверенный адрес здесь
дороже, чем остановить прогон.

Только чтение: один getAccountInfo на адрес, ни одной подписи.

  python3 adresa_sushchestvujut.py adresa.txt     # по строке на адрес
"""
from __future__ import annotations

import json
import os
import sys
import urllib.error
import urllib.request

СИСТЕМНАЯ = "11111111111111111111111111111111"


def _зов(ключ: str, метод: str, параметры: list) -> dict:
    тело = json.dumps({"jsonrpc": "2.0", "id": 1, "method": метод,
                        "params": параметры}).encode()
    запрос = urllib.request.Request(
        f"https://mainnet.helius-rpc.com/?api-key={ключ}",
        data=тело, headers={"Content-Type": "application/json"})
    with urllib.request.urlopen(запрос, timeout=30) as ответ:
        return json.load(ответ)


def main() -> int:
    if len(sys.argv) < 2:
        print("нужен файл со списком адресов, по одному в строке")
        return 2
    # ПУСТОЙ СПИСОК ПРОВЕРЯЕТСЯ ДО КЛЮЧА: нечего сверять -- значит и ключ не
    # нужен, и отказывать не за что.
    адреса = [с.strip() for с in open(sys.argv[1], encoding="utf-8") if с.strip()]
    if not адреса:
        print("список пуст -- проверять нечего")
        return 0
    ключ = (os.environ.get("HELIUS_API_KEY") or "").strip()
    if not ключ:
        print("ОТКАЗ: HELIUS_API_KEY не задан -- сверять адреса нечем")
        return 1
    плохо = 0
    for адрес in адреса:
        # ДЛИНА ПРОВЕРЯЕТСЯ ТОЖЕ, но как грубое сито, а не как доказательство.
        if not (32 <= len(адрес) <= 44):
            print(f"  [ОТКАЗ] {адрес[:12]}... длина {len(адрес)} вне 32..44")
            плохо += 1
            continue
        try:
            о = _зов(ключ, "getAccountInfo", [адрес, {"encoding": "base64"}])
        except (urllib.error.URLError, OSError, ValueError) as сбой:
            print(f"  [ОТКАЗ] {адрес[:12]}... узел не ответил: "
                  f"{type(сбой).__name__} -- непроверенный адрес не пропускаем")
            плохо += 1
            continue
        значение = ((о.get("result") or {}) or {}).get("value")
        if значение:
            владелец = значение.get("owner")
            лампорты = значение.get("lamports")
            вид = ("nonce/системный" if владелец == СИСТЕМНАЯ
                   else f"владелец {str(владелец)[:12]}")
            print(f"  [ok  ] {адрес} счёт есть, {вид}, лампортов {лампорты} "
                  f"({(лампорты or 0) / 1e9:.9f} SOL)")
            continue
        # СЧЁТА НЕТ -- ЭТО ЕЩЁ НЕ ОТКАЗ. Пустой кошелёк на Solana счёта не
        # имеет вовсе. Спрашиваем ИСТОРИЮ: поживший адрес её имеет, случайная
        # точка (сид, принятый за адрес) -- нет.
        try:
            и = _зов(ключ, "getSignaturesForAddress", [адрес, {"limit": 1}])
        except (urllib.error.URLError, OSError, ValueError) as сбой:
            print(f"  [ОТКАЗ] {адрес[:12]}... счёта нет, историю узел не отдал: "
                  f"{type(сбой).__name__}")
            плохо += 1
            continue
        подписи = и.get("result") or []
        if подписи:
            когда = (подписи[0] or {}).get("blockTime")
            print(f"  [ok  ] {адрес} счёта нет (баланс 0), но ИСТОРИЯ есть "
                  f"(последняя подпись blockTime={когда}) -- адрес поживший")
            continue
        # ВОТ ЭТО И ЕСТЬ КРАСНОЕ: ни счёта, ни истории. Так выглядел бы
        # приватный сид, принятый за адрес.
        print(f"  [ОТКАЗ] {адрес[:12]}... НИ СЧЁТА, НИ ИСТОРИИ на цепи -- "
              "это не адрес; в выгрузку публичных адресов он попасть не должен")
        плохо += 1
    print(f"адресов {len(адреса)}, не подтвердилось {плохо}")
    if плохо:
        print("ОТКАЗ: в выгрузке публичных адресов есть значение, которое цепь "
              "не подтвердила счётом. Бэкап не выкладывается.")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
