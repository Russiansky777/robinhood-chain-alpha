# --------------------------------------------------------------- самопроверка
def self_test() -> int:
    """Правило 8 проекта: измерительному коду самопроверки не нужны. Здесь она
    есть ровно для трёх ЧИСТЫХ функций, чья арифметика может соврать молча:
    доля_проц (деление на ноль обязано дать None, а не 0), возраст_часов
    (секунды против часов) и свод_неизвестных (вес по СЛОТАМ, а не по личностям).
    Ничего, что ходит в узел или в файл, здесь не проверяется."""
    проверки = []

    def chk(имя, ок, факт=""):
        проверки.append((имя, bool(ок), факт))

    chk("доля: 1 из 4 -- это 25.0 %", доля_проц(1, 4) == 25.0, доля_проц(1, 4))
    chk("доля: ноль в целом -- None, а не 0 (незнание не ноль)",
        доля_проц(3, 0) is None, доля_проц(3, 0))
    chk("доля: не целые числа -- None", доля_проц(None, 10) is None)
    chk("доля: округление до 2 знаков", доля_проц(1, 3) == 33.33, доля_проц(1, 3))

    сейчас = calendar.timegm(time.strptime("2026-09-29T21:55:10Z",
                                            "%Y-%m-%dT%H:%M:%SZ"))
    # Ровно те три суток, что прошли от сборки карты 2026-09-26T21:55:10Z до
    # ночи 29.09: 72.0 часа, а не 72 минуты и не 259 200.
    chk("возраст: 26.09 21:55:10Z против 29.09 21:55:10Z -- 72.0 ч",
        возраст_часов("2026-09-26T21:55:10Z", сейчас) == 72.0,
        возраст_часов("2026-09-26T21:55:10Z", сейчас))
    chk("возраст: полчаса -- 0.5 ч",
        возраст_часов("2026-09-29T21:25:10Z", сейчас) == 0.5,
        возраст_часов("2026-09-29T21:25:10Z", сейчас))
    chk("возраст: поля нет -- None", возраст_часов(None, сейчас) is None)
    chk("возраст: чужой формат -- None, а не ноль часов",
        возраст_часов("29.09.2026 21:55", сейчас) is None)

    # ВЕС ПО СЛОТАМ ПРОТИВ ВЕСА ПО ЛИЧНОСТЯМ -- главная ловушка этой проверки.
    # Расписание: один крупный лидер на 90 слотов и три мелких по 1 слоту (всего
    # 93). Карта знает только мелких. По личностям неизвестен 1 из 4 (25 %), по
    # слотам -- 90 из 93 (96.77 %). Если эти два числа перепутать, владелец
    # включит региональную отправку, считая, что она сработает на 75 % сделок,
    # тогда как сработает она на 3 %.
    расписание = {"КРУПНЫЙ": list(range(90)), "М1": [90], "М2": [91], "М3": [92]}
    карта = {"М1": "EU", "М2": "Asia", "М3": "US-East"}
    с = свод_неизвестных(расписание, карта)
    chk("свод: личностей в расписании 4", с["личностей_в_расписании"] == 4, с)
    chk("свод: слотов в расписании 93", с["слотов_в_расписании"] == 93, с)
    chk("свод: неизвестна 1 личность", с["неизвестных_личностей"] == 1, с)
    chk("свод: доля по личностям 25.0 %",
        с["доля_неизвестных_личностей_проц"] == 25.0, с)
    chk("свод: слотов у неизвестных 90", с["слотов_у_неизвестных"] == 90, с)
    chk("свод: доля по слотам 96.77 %, а не 25 %",
        с["доля_слотов_у_неизвестных_проц"] == 96.77, с)
    chk("свод: крупнейший неизвестный назван первым",
        с["неизвестные_крупнейшие"][0] == {"личность": "КРУПНЫЙ", "слотов": 90},
        с["неизвестные_крупнейшие"][:2])
    пустой = свод_неизвестных({}, карта)
    chk("свод: пустое расписание -- доли None, а не 0",
        пустой["доля_неизвестных_личностей_проц"] is None
        and пустой["доля_слотов_у_неизвестных_проц"] is None, пустой)
    всё_знаем = свод_неизвестных({"М1": [0, 1]}, карта)
    chk("свод: все лидеры в карте -- ровно 0.0 %, и это уже не незнание",
        всё_знаем["доля_слотов_у_неизвестных_проц"] == 0.0, всё_знаем)

    плохо = [(и, ф) for и, ок, ф in проверки if not ок]
    for имя, ок, факт in проверки:
        print(f"  [{'ok  ' if ок else 'СБОЙ'}] {имя}" + ("" if ок else f"  -> {факт}"))
    print(f"самопроверка свежести карты регионов: "
          f"{len(проверки) - len(плохо)}/{len(проверки)} пройдено")
    return 0 if not плохо else 1


