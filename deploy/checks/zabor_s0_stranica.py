#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Страница опыта забора S+0 из отчёта json. Ни сети, ни хоста -- только разметка.

ЗАЧЕМ ОТДЕЛЬНЫМ ФАЙЛОМ. Прогон на хосте получает json от
`analysis/c2_zabor_s0_opyt.py` и должен положить в репозиторий ЧИТАЕМУЮ таблицу
(`docs/zabor_s0_opyt_<дата>_<отправитель>.md`). Делать это одной строкой python
внутри yml нельзя: такую строку не проверить офлайн, и ломается она уже в прогоне.
Здесь то же самое -- файл, у которого есть самопроверка.

ЧЕГО ЗДЕСЬ НЕТ. Ни одного числа своего: всё, что печатается, взято из отчёта.
Если отчёта нет или он пуст -- страница так и говорит, а не выдумывает нули.

СЕКРЕТА В ОТЧЁТЕ БЫТЬ НЕ МОЖЕТ, и это проверяется: страница отказывается писать
файл, если в отчёте нашлось имя переменной ключа или что-то похожее на ключ.
"""
from __future__ import annotations

import argparse
import json
import os
import re
import sys

ИМЯ_КЛЮЧА = "BLOOM_LIVE_TESTS_KEY"
# Имена, которых в странице быть не должно ни при каких условиях.
ЗАПРЕЩЁННЫЕ = (ИМЯ_КЛЮЧА, "LIVE_TESTS_KEY", "PRIVATE_KEY", "SECRET_KEY")
# Похожее на ключ: длинная строка base58 без пробелов. Подпись транзакции тоже
# такая, поэтому проверка смотрит ТОЛЬКО на поля, где подписи быть не может.
ПОХОЖЕ_НА_КЛЮЧ = re.compile(r"[1-9A-HJ-NP-Za-km-z]{80,}")


def безопасен(о: dict) -> dict:
    """В отчёте нет ни имени переменной ключа, ни самого ключа."""
    из_ = {"ok": True, "why_not": None}
    текст = json.dumps(о, ensure_ascii=False)
    for имя in ЗАПРЕЩЁННЫЕ:
        if имя in текст:
            return {"ok": False, "why_not": f"в отчёте встречается {имя}"}
    # Ключ Solana в base58 -- 87--88 знаков. Подписи (те же 87--88) лежат только
    # в полях "подпись"/"signature"; всё остальное длиной от 80 знаков подозрительно.
    def обойти(узел, путь=""):
        if isinstance(узел, dict):
            for к, v in узел.items():
                if str(к).lower() in ("подпись", "signature", "tx_base64",
                                       "signatures"):
                    continue
                r = обойти(v, f"{путь}.{к}")
                if r:
                    return r
        elif isinstance(узел, list):
            for и, v in enumerate(узел):
                r = обойти(v, f"{путь}[{и}]")
                if r:
                    return r
        elif isinstance(узел, str) and ПОХОЖЕ_НА_КЛЮЧ.search(узел):
            return f"поле {путь or '<корень>'} похоже на ключ ({len(узел)} знаков)"
        return None

    плохо = обойти(о)
    if плохо:
        return {"ok": False, "why_not": плохо}
    return из_


def страница(о: dict) -> list:
    """Строки страницы. Ничего не считает -- только раскладывает отчёт."""
    режим = str(о.get("режим") or "?")
    отпр = str(о.get("отправитель") or "?")
    стр = [f"# Опыт забора S+0 — {отпр}, режим {режим}", "",
            f"Отчёт: `{о.get('utc') or '?'}` · кошелёк опыта `{о.get('кошелёк') or '?'}` "
            f"· раундов {о.get('раундов') if о.get('раундов') is not None else '?'}", ""]
    if о.get("предел_расхода_sol") is not None:
        стр += [f"Потолок расхода, посчитанный заранее: **{о['предел_расхода_sol']} SOL**.",
                ""]
    if о.get("why_not"):
        стр += [f"**НЕ СДЕЛАНО:** {о['why_not']}", ""]
    ск = о.get("свод_кольца") or {}
    if ск.get("записей"):
        хватает = "хватает" if ск.get("хватает_на_срок_жизни") else "НЕ ХВАТАЕТ"
        стр += ["## Кольцо", "",
                f"Записей {ск['записей']}, `lastValidBlockHeight` "
                f"{ск.get('lastValid_от')}…{ск.get('lastValid_до')}, накрыто блоков "
                f"{ск.get('накрыто_блоков')} ({хватает}), разрывов "
                f"{ск.get('разрывов')}.", ""]
    таб = о.get("таблица") or []
    if таб:
        стр += ["## Отправки", ""]
        # Таблица из модуля -- строки, разделённые вертикальной чертой. Для
        # разметки к каждой добавляются крайние черты; разделитель уже есть
        # второй строкой, его только приводим к виду разметки.
        for и, т in enumerate(таб):
            ячейки = [я.strip() for я in str(т).split("|")]
            if и == 1:
                ячейки = ["---" for _ in ячейки]
            стр.append("| " + " | ".join(ячейки) + " |")
        стр.append("")
    с = о.get("свод") or {}
    if с:
        стр += ["## Числа", "",
                f"Отправок **{с.get('отправок')}**, правило сошлось "
                f"**{с.get('правило_сошлось')}**, не сошлось "
                f"**{с.get('правило_не_сошлось')}**, комиссий списано "
                f"**{с.get('комиссий_списано_всего')}**.", ""]
        по = с.get("по_сдвигу") or {}
        if по:
            стр += ["| сдвиг | отправок | село | не село | правило сошлось | "
                     "правило нет | комиссий |",
                     "| --- | --- | --- | --- | --- | --- | --- |"]
            for к in sorted(по, key=lambda x: (len(x), x)):
                з = по[к]
                стр.append(f"| {к} | {з.get('отправок')} | {з.get('село')} | "
                            f"{з.get('не_село')} | {з.get('правило_сошлось')} | "
                            f"{з.get('правило_нет')} | {з.get('комиссий_списано')} |")
            стр.append("")
        if с.get("вывод_для_полосы"):
            стр += [f"**Вывод:** {с['вывод_для_полосы']}", ""]
    if not таб and not о.get("why_not"):
        стр += ["**Отправок в отчёте нет.** Это не «ноль отправок прошло», а "
                "«мерить нечего»: смотри журнал прогона.", ""]
    стр += ["---", "",
            "Сделано прогоном `run_zabor_s0_opyt_nl.yml` на NL-хосте. Секрет "
            "`LIVE_TESTS` уходил в окружение файлом 600 и в argv не попадал; "
            "страница отказывается писаться, если в отчёте найдётся что-то "
            "похожее на ключ.", ""]
    return стр


def имя_файла(о: dict, каталог: str = "docs") -> str:
    дата = str(о.get("utc") or "")[:10] or "bez-daty"
    отпр = re.sub(r"[^a-z0-9_-]", "", str(о.get("отправитель") or "?").lower()) or "x"
    return os.path.join(каталог, f"zabor_s0_opyt_{дата}_{отпр}.md")


def self_test() -> int:
    пройдено = провалено = 0

    def chk(что, ок, факт=None):
        nonlocal пройдено, провалено
        print(f"  [{'ok  ' if ок else 'ПРОВАЛ'}] {что}"
              + (f" -> {факт!r}" if факт is not None and not ок else ""))
        пройдено += bool(ок)
        провалено += (not ок)

    о = {"utc": "2026-10-01T05:12:00Z", "режим": "opyt", "отправитель": "astralane",
         "раундов": 5, "кошелёк": "D3JuFoSXuWEMUUdCtoB5NYWnN87vjJSHtDP5rTD6qnph",
         "предел_расхода_sol": 0.00015,
         "свод_кольца": {"записей": 200, "lastValid_от": 1, "lastValid_до": 200,
                          "накрыто_блоков": 200, "хватает_на_срок_жизни": True,
                          "разрывов": 0},
         "таблица": ["отправитель | вариант | lastValid | села",
                      "------------|---------|-----------|-----",
                      "astralane   | H-1     | 100       | нет"],
         "свод": {"отправок": 3, "правило_сошлось": 3, "правило_не_сошлось": 0,
                   "комиссий_списано_всего": 1,
                   "по_сдвигу": {"0": {"отправок": 1, "село": 1, "не_село": 0,
                                        "правило_сошлось": 1, "правило_нет": 0,
                                        "комиссий_списано": 1}},
                   "вывод_для_полосы": "запас есть"}}
    с = страница(о)
    chk("заголовок называет отправителя и режим",
        с[0] == "# Опыт забора S+0 — astralane, режим opyt", с[0])
    chk("имя файла -- дата и отправитель",
        имя_файла(о) == "docs/zabor_s0_opyt_2026-10-01_astralane.md", имя_файла(о))
    chk("разделитель таблицы приведён к разметке",
        "| --- | --- | --- | --- |" in с, [x for x in с if x.startswith("| ---")])
    chk("строка отправки на месте и с крайними чертами",
        any(x.startswith("| astralane") and x.endswith("|") for x in с))
    chk("потолок расхода назван", any("0.00015 SOL" in x for x in с))
    chk("вывод перенесён дословно", any("запас есть" in x for x in с))

    пусто = {"utc": "2026-10-01T05:12:00Z", "отправитель": "helius", "режим": "opyt"}
    chk("пустой отчёт: сказано «мерить нечего», а не ноль отправок",
        any("мерить нечего" in x for x in страница(пусто)))
    отказ = dict(пусто, why_not="опыт выключен рубильником")
    chk("отказ из отчёта переносится в страницу",
        any("НЕ СДЕЛАНО" in x for x in страница(отказ)))

    # --- ОХРАНА СЕКРЕТА
    chk("чистый отчёт признаётся безопасным", безопасен(о)["ok"] is True)
    chk("имя переменной ключа в отчёте -- отказ",
        безопасен(dict(о, что=f"{ИМЯ_КЛЮЧА}=абв"))["ok"] is False)
    длинный = "5" * 88
    chk("длинная base58-строка в обычном поле -- отказ",
        безопасен(dict(о, странное=длинный))["ok"] is False)
    chk("та же строка в поле подписи -- НЕ отказ (подписи такие же длинные)",
        безопасен(dict(о, строки=[{"подпись": длинный}]))["ok"] is True)
    chk("ключ, спрятанный в глубине, тоже находится",
        безопасен(dict(о, раунды=[{"а": {"б": [длинный]}}]))["ok"] is False)

    print(f"самопроверка страницы опыта: {пройдено}/{пройдено + провалено} пройдено")
    return 0 if провалено == 0 else 1


def main() -> int:
    р = argparse.ArgumentParser(description=__doc__)
    р.add_argument("--otchet", default=None, help="json отчёта опыта")
    р.add_argument("--katalog", default="docs")
    р.add_argument("--out", default=None, help="перекрыть имя файла страницы")
    р.add_argument("--self-test", dest="self_test", action="store_true")
    а = р.parse_args()
    if а.self_test:
        return self_test()
    if not а.otchet or not os.path.exists(а.otchet):
        print(f"не сделано: отчёта нет: {а.otchet}")
        return 2
    with open(а.otchet, encoding="utf-8") as ф:
        о = json.load(ф)
    б = безопасен(о)
    if not б["ok"]:
        print(f"СБОЙ: страница не написана -- {б['why_not']}")
        return 1
    путь = а.out or имя_файла(о, а.katalog)
    os.makedirs(os.path.dirname(путь) or ".", exist_ok=True)
    with open(путь, "w", encoding="utf-8") as ф:
        ф.write("\n".join(страница(о)).rstrip() + "\n")
    print(f"страница: {путь}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
