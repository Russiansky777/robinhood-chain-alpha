ИМЯ_КЛЮЧА = "BLOOM_LIVE_TESTS_KEY"
# Имена, которых в странице быть не должно ни при каких условиях.
ЗАПРЕЩЁННЫЕ = (ИМЯ_КЛЮЧА, "LIVE_TESTS_KEY", "PRIVATE_KEY", "SECRET_KEY")
# Похожее на ключ: длинная строка base58 без пробелов. Подпись транзакции тоже
# такая, поэтому проверка смотрит ТОЛЬКО на поля, где подписи быть не может.
ПОХОЖЕ_НА_КЛЮЧ = re.compile(r"[1-9A-HJ-NP-Za-km-z]{80,}")


def безопасен(о: dict) -> dict:
    """В отчёте нет ни имени переменной ключа, ни самого ключа."""
    из_ = {"ok": True, "why_not": None}
    текст = json.dumps(о, ensure_ascii=False)
    for имя in ЗАПРЕЩЁННЫЕ:
        if имя in текст:
            return {"ok": False, "why_not": f"в отчёте встречается {имя}"}
    # Ключ Solana в base58 -- 87--88 знаков. Подписи (те же 87--88) лежат только
    # в полях "подпись"/"signature"; всё остальное длиной от 80 знаков подозрительно.
    def обойти(узел, путь=""):
        if isinstance(узел, dict):
            for к, v in узел.items():
                if str(к).lower() in ("подпись", "signature", "tx_base64",
                                       "signatures"):
                    continue
                r = обойти(v, f"{путь}.{к}")
                if r:
                    return r
        elif isinstance(узел, list):
            for и, v in enumerate(узел):
                r = обойти(v, f"{путь}[{и}]")
                if r:
                    return r
        elif isinstance(узел, str) and ПОХОЖЕ_НА_КЛЮЧ.search(узел):
            return f"поле {путь or '<корень>'} похоже на ключ ({len(узел)} знаков)"
        return None

    плохо = обойти(о)
    if плохо:
        return {"ok": False, "why_not": плохо}
    return из_


def страница(о: dict) -> list:
    """Строки страницы. Ничего не считает -- только раскладывает отчёт."""
    режим = str(о.get("режим") or "?")
    отпр = str(о.get("отправитель") or "?")
    # У ГОНКИ ОТПРАВИТЕЛЬ НЕ ОДИН. В отчёте гонки лежит список `отправители`, а
    # поля `отправитель` нет вовсе -- и заголовок выходил "Опыт забора S+0 — ?".
    если_гонка = (режим == "gonka") or bool((о.get("свод") or {}).get("по_отправителю"))
    if если_гонка:
        кто = ", ".join(str(и) for и in (о.get("отправители") or [])) or "?"
        заголовок = f"# Гонка отправителей — {кто}"
    else:
        заголовок = f"# Опыт забора S+0 — {отпр}, режим {режим}"
    стр = [заголовок, "",
            f"Отчёт: `{о.get('utc') or '?'}` · кошелёк опыта `{о.get('кошелёк') or '?'}` "
            f"· раундов {о.get('раундов') if о.get('раундов') is not None else '?'}", ""]
    if о.get("предел_расхода_sol") is not None:
        стр += [f"Потолок расхода, посчитанный заранее: **{о['предел_расхода_sol']} SOL**.",
                ""]
    if о.get("why_not"):
        стр += [f"**НЕ СДЕЛАНО:** {о['why_not']}", ""]
    # ЧАЕВЫЕ И ДЕНЬГИ -- НА СТРАНИЦЕ ЧИСЛАМИ. Опыт платит чаевые (без них
    # платный путь Helius отказывает), поэтому цена прогона и остаток на
    # кошельке должны читаться со страницы, а не из кода.
    ч = о.get("чаевые") or {}
    if ч.get("лампорты"):
        стр += [f"Чаевые: **{ч['лампорты']} лампортов** на `{ч.get('адрес')}` — "
                f"{ч.get('откуда')}.", ""]
    if о.get("баланс_до_sol") is not None:
        стр += [f"Кошелёк до опыта: **{о['баланс_до_sol']} SOL**, останется "
                f"**{о.get('останется_sol')} SOL**.", ""]
    ск = о.get("свод_кольца") or {}
    if ск.get("записей"):
        хватает = "хватает" if ск.get("хватает_на_срок_жизни") else "НЕ ХВАТАЕТ"
        стр += ["## Кольцо", "",
                f"Записей {ск['записей']}, `lastValidBlockHeight` "
                f"{ск.get('lastValid_от')}…{ск.get('lastValid_до')}, накрыто блоков "
                f"{ск.get('накрыто_блоков')} ({хватает}), разрывов "
                f"{ск.get('разрывов')}.", ""]
    таб = о.get("таблица") or []
    if таб:
        стр += ["## Отправки", ""]
        # Таблица из модуля -- строки, разделённые вертикальной чертой. Для
        # разметки к каждой добавляются крайние черты; разделитель уже есть
        # второй строкой, его только приводим к виду разметки.
        for и, т in enumerate(таб):
            ячейки = [я.strip() for я in str(т).split("|")]
            if и == 1:
                ячейки = ["---" for _ in ячейки]
            стр.append("| " + " | ".join(ячейки) + " |")
        стр.append("")
    с = о.get("свод") or {}
    if с and если_гонка:
        # ЧИСЛА ГОНКИ -- СВОИ. Здесь печатался свод ОПЫТА, которого у гонки нет:
        # страница сказала "Попыток None, ушло в сеть None" и затем
        # "**Вывода о цепи по этому прогону нет:** в сеть не ушла ни одна
        # попытка" -- при 50 ушедших и 50 севших. Это ровно та ложь, от которой
        # эта страница и заводилась: прочли бы её как итог прогона.
        по_о = с.get("по_отправителю") or {}
        всего_отпр = sum(int(в.get("отправок") or 0) for в in по_о.values())
        всего_село = sum(int(в.get("село") or 0) for в in по_о.values())
        всего_нет = sum(int(в.get("не_село") or 0) for в in по_о.values())
        стр += ["## Числа", "",
                f"Отправителей **{с.get('отправителей')}**, отправок "
                f"**{всего_отпр}**, село **{всего_село}**, не село "
                f"**{всего_нет}**, потрачено **{с.get('потрачено_sol')} SOL** "
                f"при потолке **{о.get('потолок_sol')} SOL**.", ""]
        п = с.get("парно") or {}
        if п.get("раундов_сравнимых"):
            счёт = ", ".join(f"{и} {к}" for и, к in
                              sorted((п.get("побед") or {}).items(),
                                     key=lambda кв: -кв[1]))
            стр += [f"Кто раньше в одном блоке: **{счёт}** "
                     f"(раундов сравнимых {п['раундов_сравнимых']}, ничьих "
                     f"{п.get('ничьих', 0)}, неполных {п.get('неполных', 0)}).", ""]
        if с.get("победитель"):
            стр += [f"**Победитель: {с['победитель']}** — "
                     f"{с.get('победитель_как')}.", ""]
        elif с.get("поровну_отправок") is False:
            стр += ["**Победителя нет:** отправок не поровну — сравнивать нельзя.",
                     ""]
        if с.get("медианы_и_парность_расходятся"):
            стр += [f"**Осторожно с медианами:** независимые медианы индекса "
                     f"дали бы {с.get('по_медианам')}, а в одном блоке раньше "
                     f"{(с.get('парно') or {}).get('победитель')}. Верен парный "
                     f"счёт: медиану сдвигают выбросы, а барьер сравнивает "
                     f"обоих в одном блоке.", ""]
        if не_село_всё(всего_отпр, всего_село):
            стр += ["**Вывода о цепи по этому прогону нет:** ни одна отправка не "
                     "села.", ""]
    elif с:
        # ПОПЫТКА И ОТПРАВКА -- РАЗНЫЕ ЧИСЛА, И ОБА НА СТРАНИЦЕ. 30.09 16:14Z
        # страница сказала "Отправок 6" при нуле ушедших в сеть: все шесть
        # попыток упали на PermissionError до сети. Читалось это как факт цепи.
        стр += ["## Числа", "",
                f"Попыток **{с.get('попыток', с.get('отправок'))}**, ушло в сеть "
                f"**{с.get('отправок')}**, не ушло **{с.get('не_ушло', 0)}**, "
                f"правило сошлось "
                f"**{с.get('правило_сошлось')}**, не сошлось "
                f"**{с.get('правило_не_сошлось')}**, комиссий списано "
                f"**{с.get('комиссий_списано_всего')}**.", ""]
        if с.get("не_ушло"):
            стр += ["Не ушло в сеть — по причинам:", ""]
            for пч, н in (с.get("не_ушло_почему") or {}).items():
                стр.append(f"* {н}× `{пч}`")
            стр.append("")
        if not с.get("отправок"):
            стр += ["**Вывода о цепи по этому прогону нет:** в сеть не ушла ни "
                     "одна попытка, а значит ни одна покупка не проверена цепью. "
                     "Строки выше — попытки, а не отправки.", ""]
        по = с.get("по_сдвигу") or {}
        if по:
            стр += ["| сдвиг | попыток | ушло | не ушло | село | не село | "
                     "правило сошлось | правило нет | комиссий |",
                     "| --- | --- | --- | --- | --- | --- | --- | --- | --- |"]
            for к in sorted(по, key=lambda x: (len(x), x)):
                з = по[к]
                стр.append(f"| {к} | {з.get('попыток', з.get('отправок'))} | "
                            f"{з.get('отправок')} | {з.get('не_ушло', 0)} | "
                            f"{з.get('село')} | "
                            f"{з.get('не_село')} | {з.get('правило_сошлось')} | "
                            f"{з.get('правило_нет')} | {з.get('комиссий_списано')} |")
            стр.append("")
        if с.get("вывод_для_полосы"):
            стр += [f"**Вывод:** {с['вывод_для_полосы']}", ""]
    if not таб and not о.get("why_not"):
        стр += ["**Отправок в отчёте нет.** Это не «ноль отправок прошло», а "
                "«мерить нечего»: смотри журнал прогона.", ""]
    стр += ["---", "",
            "Сделано прогоном `run_zabor_s0_opyt_nl.yml` на NL-хосте. Секрет "
            "`LIVE_TESTS` уходил в окружение файлом 600 и в argv не попадал; "
            "страница отказывается писаться, если в отчёте найдётся что-то "
            "похожее на ключ.", ""]
    return стр


def не_село_всё(отправок: int, село: int) -> bool:
    """Ни одна отправка не села -- вывода о цепи нет. Ноль отправок тоже сюда."""
    return int(село or 0) == 0


def имя_файла(о: dict, каталог: str = "docs") -> str:
    дата = str(о.get("utc") or "")[:10] or "bez-daty"
    # ГОНКА -- СВОЁ ИМЯ. У неё нет поля `отправитель`, и файл выходил
    # "..._x.md": по имени не понять, что это гонка и кто в ней участвовал.
    if str(о.get("режим") or "") == "gonka" or (о.get("свод") or {}).get("по_отправителю"):
        кто = "-".join(re.sub(r"[^a-z0-9]", "", str(и).lower())
                       for и in (о.get("отправители") or []) if str(и).strip())
        кто = кто or "otpraviteli"
        return os.path.join(каталог, f"zabor_gonka_{дата}_{кто}.md")
    отпр = re.sub(r"[^a-z0-9_-]", "", str(о.get("отправитель") or "?").lower()) or "x"
    return os.path.join(каталог, f"zabor_s0_opyt_{дата}_{отпр}.md")


