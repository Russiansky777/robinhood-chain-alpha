#!/usr/bin/env python3
"""Сверка ИМЁН окружения: живой процесс против файла против копии до деплоя.

ЗАЧЕМ (слово владельца 04.10, 12:30Z). Отправок полосы нет с ~10:44Z, а в
10:43:26Z деплой перезапустил детектор. Владелец назвал главную гипотезу своим
словом: "если причина -- переменная, которая жила только в памяти процесса, --
добавить её в обязательный список гейта, как BLOOM_SOURCE_GROUPS".

Такое уже было 03.10 в 20:2xZ: детектор работал БЕЗ BLOOM_SOURCE_GROUPS, читал
умолчание модуля, не находил файла групп и ставил политику off ВСЕМ адресам --
покупки встали. Разница между "что было в памяти старого процесса" и "что лежит
в файле" эту причину показывает прямо, а признак жизни -- нет: он печатает
выводы, а не то, из чего они сделаны.

ЗНАЧЕНИЙ ЗДЕСЬ НЕТ НИ ОДНОГО, И ЭТО НЕ ПРЕДОСТОРОЖНОСТЬ, А УСТРОЙСТВО. На вход
идут файлы, в которых уже только имена: их собирает оболочка на хосте выражением
`grep -oE '^[A-Za-z_][A-Za-z0-9_]*='`, то есть значение не покидает хост даже на
шаг. Модуль не умеет принять значение, даже если его подсунуть: всё после
первого `=` отбрасывается при чтении.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path


def имена_из_текста(текст: str) -> list:
    """Имена переменных из текста. Всё после первого '=' отбрасывается."""
    из_ = set()
    for строка in (текст or "").splitlines():
        с = строка.strip()
        if not с or с.startswith("#"):
            continue
        имя = с.split("=", 1)[0].strip()
        if имя and (имя[0].isalpha() or имя[0] == "_") and all(
                з.isalnum() or з == "_" for з in имя) and имя.isascii():
            из_.add(имя)
    return sorted(из_)


def сверка(*, в_памяти: list, в_файле: list, в_копии: list | None = None,
            следим: tuple = ()) -> dict:
    """Что где есть. Чистая функция, только множества имён.

    только_в_памяти -- САМОЕ ДЕНЕЖНОЕ ПОЛЕ: такая переменная жила в старом
    процессе и после перезапуска исчезла, то есть служба поднялась с другим
    поведением, чем работала. Именно этот случай владелец велел закрывать
    обязательным списком гейта.
    """
    п, ф = set(в_памяти), set(в_файле)
    к = set(в_копии or [])
    из_ = {
        "в_памяти": len(п), "в_файле": len(ф), "в_копии": (len(к) if в_копии is not None else None),
        "только_в_памяти": sorted(п - ф),
        "только_в_файле": sorted(ф - п),
        "совпало": len(п & ф),
    }
    if в_копии is not None:
        из_["было_в_копии_нет_в_файле"] = sorted(к - ф)
        из_["появилось_в_файле"] = sorted(ф - к)
    из_["следим"] = {имя: {"в_памяти": имя in п, "в_файле": имя in ф,
                            **({"в_копии": имя in к} if в_копии is not None else {})}
                      for имя in следим}
    пропали = [имя for имя in следим if имя in п and имя not in ф]
    из_["следим_пропали_из_файла"] = пропали
    из_["вывод"] = ("имена сходятся" if not из_["только_в_памяти"] and not из_["только_в_файле"]
                     else ("ПЕРЕМЕННАЯ ЖИЛА ТОЛЬКО В ПАМЯТИ: "
                            + ", ".join(из_["только_в_памяти"])
                            if из_["только_в_памяти"] else
                            "в файле есть имена, которых нет в памяти процесса -- "
                            "процесс поднят раньше правки файла"))
    return из_


def _самопроверка() -> int:
    проверок = прошло = 0

    def сверить(что, дано, ждали):
        nonlocal проверок, прошло
        проверок += 1
        if дано == ждали:
            прошло += 1
        else:
            print(f"НЕ ПРОШЛО: {что}: дано {дано!r}, ждали {ждали!r}")

    # ГЛАВНОЕ: ЗНАЧЕНИЕ НЕ ПРОХОДИТ ДАЛЬШЕ ЧТЕНИЯ НИ ПРИ КАКОМ ВИДЕ ВВОДА.
    сверить("имя берётся до первого '='",
            имена_из_текста("BLOOM_SOURCE_GROUPS=/home/bot/data/g.json\n"),
            ["BLOOM_SOURCE_GROUPS"])
    сверить("значение с '=' внутри не ломает имя",
            имена_из_текста("VPS_SSH_KEY=a=b=c\n"), ["VPS_SSH_KEY"])
    сверить("строка без '=' -- тоже имя (так печатает хост)",
            имена_из_текста("BLOOM_MODE\nBLOOM_TASKS\n"),
            ["BLOOM_MODE", "BLOOM_TASKS"])
    сверить("комментарий и пустые строки пропущены",
            имена_из_текста("# это комментарий\n\nBLOOM_MODE=live\n"),
            ["BLOOM_MODE"])
    сверить("нелатинское имя отброшено (bash такого не умеет)",
            имена_из_текста("ИМЯ=1\nBLOOM_MODE=live\n"), ["BLOOM_MODE"])
    сверить("повторы свёрнуты и отсортированы",
            имена_из_текста("B=1\nA=2\nB=3\n"), ["A", "B"])
    _весь = json.dumps(имена_из_текста("K=sekret_znachenie\n"), ensure_ascii=False)
    сверить("значения в ответе нет", "sekret_znachenie" in _весь, False)

    # Случай 03.10: имя было в памяти и исчезло из файла.
    с = сверка(в_памяти=["A", "BLOOM_SOURCE_GROUPS"], в_файле=["A"],
                следим=("BLOOM_SOURCE_GROUPS",))
    сверить("переменная только в памяти названа",
            с["только_в_памяти"], ["BLOOM_SOURCE_GROUPS"])
    сверить("и вывод говорит об этом прямо",
            "ЖИЛА ТОЛЬКО В ПАМЯТИ" in с["вывод"], True)
    сверить("и следящее имя помечено пропавшим",
            с["следим_пропали_из_файла"], ["BLOOM_SOURCE_GROUPS"])
    сверить("и по нему видно оба ответа",
            с["следим"]["BLOOM_SOURCE_GROUPS"],
            {"в_памяти": True, "в_файле": False})

    # Обратный случай: файл правили, процесс старый. Это НЕ та же беда.
    о = сверка(в_памяти=["A"], в_файле=["A", "НОВОЕ".encode().decode(), "B"])
    сверить("имена, которых нет в памяти, названы отдельно",
            о["только_в_файле"], ["B", "НОВОЕ"])
    сверить("и это не выдаётся за 'жила только в памяти'",
            "ЖИЛА ТОЛЬКО В ПАМЯТИ" in о["вывод"], False)

    р = сверка(в_памяти=["A", "B"], в_файле=["A", "B"])
    сверить("всё сошлось -- так и сказано", р["вывод"], "имена сходятся")
    сверить("и пустые списки, а не отсутствие полей",
            (р["только_в_памяти"], р["только_в_файле"]), ([], []))

    к = сверка(в_памяти=["A"], в_файле=["A"], в_копии=["A", "C"])
    сверить("копия: имя было и ушло из файла",
            к["было_в_копии_нет_в_файле"], ["C"])
    сверить("копия: новых имён нет", к["появилось_в_файле"], [])
    сверить("без копии поле не выдумывается",
            "было_в_копии_нет_в_файле" in сверка(в_памяти=[], в_файле=[]), False)

    print(f"проверок {проверок}, прошло {прошло}, "
          f"не прошло {проверок - прошло}")
    return 0 if прошло == проверок else 1


СЛЕДИМ = ("BLOOM_SOURCE_GROUPS", "BLOOM_OWN_SEND", "BLOOM_OWN_SEND_LIVE",
          "BLOOM_OWN_SEND_SOL", "BLOOM_LIVE_BUY", "BLOOM_MODE", "BLOOM_TASKS",
          "BLOOM_MIN_TARGET_SOL", "BLOOM_MAX_OPEN", "BLOOM_POOL_SEND",
          "BLOOM_SENDER_REGION", "OWN_SEND_WALLET_KEY", "BLOOM_STATE_DIR",
          "LANE_KILL_DROP_SOL", "LANE_GROUP_DAILY_STOP")


def main(довод: list) -> int:
    if len(довод) < 2:
        print("нужны два файла имён: в_памяти в_файле [в_копии]")
        return 2
    память = имена_из_текста(Path(довод[0]).read_text(encoding="utf-8"))
    файл = имена_из_текста(Path(довод[1]).read_text(encoding="utf-8"))
    копия = (имена_из_текста(Path(довод[2]).read_text(encoding="utf-8"))
             if len(довод) > 2 and Path(довод[2]).exists() else None)
    из_ = сверка(в_памяти=память, в_файле=файл, в_копии=копия, следим=СЛЕДИМ)
    print(json.dumps(из_, ensure_ascii=False, indent=1))
    # КОД ВОЗВРАТА -- НЕ ПРИГОВОР, А ПРИЗНАК: 3 значит "нашлось имя, жившее
    # только в памяти". Прогон это читает и говорит словами, а не падает: это
    # разбор, а не гейт.
    return 3 if из_["только_в_памяти"] else 0


if __name__ == "__main__":
    if "--self-test" in sys.argv:
        sys.exit(_самопроверка())
    sys.exit(main([а for а in sys.argv[1:] if not а.startswith("--")]))
