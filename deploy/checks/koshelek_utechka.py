#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Движение кошелька по цепи и АУДИТ: где вообще лежит его приватный ключ.

ЗАЧЕМ (слово владельца 01.10, п.2). С кошелька Bloom 4s87RRC2… между 06:36Z и
07:17Z ушли 0.024620982 SOL, и владелец этого перевода не делал. Нужны две вещи:
подпись с получателем по цепи -- и ответ, есть ли приватный ключ этого кошелька
на хосте, в секретах и в дереве репозитория.

КЛЮЧ ПРОВЕРЯЕТСЯ ВЫВОДОМ АДРЕСА, А НЕ ИМЕНЕМ ПЕРЕМЕННОЙ. Любая строка, которая
разбирается как ключ, превращается в публичный адрес, и сверяется адрес. Иначе
ключ под именем вида NOTES_BACKUP прошёл бы мимо проверки по именам.

САМ КЛЮЧ НИКУДА НЕ ПЕЧАТАЕТСЯ -- ни в вывод, ни в файл: только имя переменной,
путь файла и выведенный публичный адрес. Отчёт идёт в репозиторий, и секрет в нём
означал бы утечку уже нашими руками.

ТОЛЬКО ЧТЕНИЕ: getSignaturesForAddress, getTransaction и чтение файлов. Ничего
не удаляется и не правится -- удаление по слову владельца делается отдельно.
"""
from __future__ import annotations

import argparse
import json
import os
import re
import sys
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parent.parent.parent
sys.path.insert(0, str(КОРЕНЬ / "analysis"))

ЛАМПОРТОВ_В_SOL = 1_000_000_000
СИСТЕМНАЯ = "11111111111111111111111111111111"
# Длина base58 для 64-байтового ключа -- 87-88 знаков; берём с запасом.
Б58 = re.compile(r"[1-9A-HJ-NP-Za-km-z]{85,90}")
МАССИВ = re.compile(r"\[\s*(?:\d{1,3}\s*,\s*){63}\d{1,3}\s*\]")


def _ключи(tx: dict) -> list:
    сооб = ((tx or {}).get("transaction") or {}).get("message") or {}
    сырые = сооб.get("accountKeys") or []
    return [к.get("pubkey") if isinstance(к, dict) else к for к in сырые]


def разбор_транзакции(tx: dict, кошелёк: str) -> dict:
    """Что эта транзакция сделала с нашим кошельком: перевод, своп или прочее."""
    из_ = {"подпись": None, "слот": None, "время": None, "ошибка": None,
            "наш_делta_sol": None, "комиссия_sol": None, "мы_платили": None,
            "вид": None, "получатель": None, "получил_sol": None,
            "программы": [], "токенов_двигалось": None, "почему": None}
    мета = (tx or {}).get("meta") or {}
    ключи = _ключи(tx)
    подписи = ((tx or {}).get("transaction") or {}).get("signatures") or []
    из_["подпись"] = подписи[0] if подписи else None
    из_["слот"] = (tx or {}).get("slot")
    из_["время"] = (tx or {}).get("blockTime")
    из_["ошибка"] = мета.get("err")
    из_["комиссия_sol"] = round(int(мета.get("fee") or 0) / ЛАМПОРТОВ_В_SOL, 9)
    if кошелёк not in ключи:
        из_["почему"] = "нашего кошелька нет среди статических ключей"
        return из_
    и = ключи.index(кошелёк)
    # ПЛАТЕЛЬЩИК -- ВСЕГДА ПЕРВЫЙ КЛЮЧ. Если это мы, подпись наша: значит ключ
    # кошелька был у того, кто её собрал.
    из_["мы_платили"] = (и == 0)
    до = мета.get("preBalances") or []
    после = мета.get("postBalances") or []
    if и < len(до) and и < len(после):
        из_["наш_делta_sol"] = round((int(после[и]) - int(до[и])) / ЛАМПОРТОВ_В_SOL, 9)
    # ПРОГРАММЫ: по ним отличается перевод от свопа. Системная программа и
    # только она -- перевод; есть чужая программа -- не перевод, и мы это говорим.
    сооб = ((tx or {}).get("transaction") or {}).get("message") or {}
    прогр = []
    for ин in (сооб.get("instructions") or []):
        п = ин.get("programId") or (ключи[ин["programIdIndex"]]
                                     if isinstance(ин.get("programIdIndex"), int)
                                     and ин["programIdIndex"] < len(ключи) else None)
        if п:
            прогр.append(п)
    из_["программы"] = sorted(set(прогр))
    двиг = [з for з in (мета.get("postTokenBalances") or [])]
    из_["токенов_двигалось"] = len(двиг)
    только_система = bool(прогр) and set(прогр) == {СИСТЕМНАЯ}
    если_своп = any(п not in (СИСТЕМНАЯ,) for п in прогр) and двиг
    из_["вид"] = ("перевод" if только_система
                   else "своп" if если_своп
                   else "прочее" if прогр else "не разобрано")
    # ПОЛУЧАТЕЛЬ: у перевода это счёт, который вырос больше всех.
    if только_система:
        лучший, сколько = None, 0
        for j, (д, п) in enumerate(zip(до, после)):
            if j == и:
                continue
            рост = int(п) - int(д)
            if рост > сколько:
                лучший, сколько = (ключи[j] if j < len(ключи) else None), рост
        из_["получатель"] = лучший
        из_["получил_sol"] = round(сколько / ЛАМПОРТОВ_В_SOL, 9)
    return из_


def движение(rpc_call, кошелёк: str, *, с_ts: float, по_ts: float,
             страниц: int = 3) -> dict:
    """Все транзакции кошелька в окне. Цепь молчит -- так и говорим."""
    из_ = {"ok": False, "why_not": None, "кошелёк": кошелёк,
            "подписей_просмотрено": 0, "в_окне": 0, "прочитано": 0,
            "не_прочитано": 0, "строки": []}
    до_подписи, собрано = None, []
    for _ in range(max(1, страниц)):
        пар = {"limit": 1000}
        if до_подписи:
            пар["before"] = до_подписи
        ответ = rpc_call("getSignaturesForAddress", [кошелёк, пар])
        if not isinstance(ответ, list):
            из_["why_not"] = f"узел не отдал подписи: {str(ответ)[:160]}"
            return из_
        if not ответ:
            break
        из_["подписей_просмотрено"] += len(ответ)
        for з in ответ:
            бт = з.get("blockTime")
            if бт is None:
                continue
            if с_ts <= float(бт) <= по_ts:
                собрано.append(з.get("signature"))
        до_подписи = ответ[-1].get("signature")
        самая_старая = ответ[-1].get("blockTime")
        if самая_старая is not None and float(самая_старая) < с_ts:
            break
    из_["в_окне"] = len(собрано)
    for подпись in собрано:
        tx = rpc_call("getTransaction",
                       [подпись, {"encoding": "json", "commitment": "confirmed",
                                   "maxSupportedTransactionVersion": 0}])
        if not isinstance(tx, dict) or tx.get("meta") is None:
            из_["не_прочитано"] += 1
            из_["строки"].append({"подпись": подпись,
                                   "почему": "транзакция не прочитана"})
            continue
        из_["прочитано"] += 1
        из_["строки"].append(разбор_транзакции(tx, кошелёк))
    из_["ok"] = (из_["не_прочитано"] == 0)
    if not из_["ok"]:
        из_["why_not"] = f"не прочитано транзакций: {из_['не_прочитано']}"
    return из_


def адрес_ключа(строка: str):
    """Публичный адрес ключа или None, если строка ключом не является."""
    try:
        from solders.keypair import Keypair  # noqa: PLC0415

        кп = (Keypair.from_json(строка) if строка.strip().startswith("[")
              else Keypair.from_base58_string(строка))
        return str(кп.pubkey())
    except Exception:  # noqa: BLE001
        return None


def ключи_в_окружении(цели: dict) -> dict:
    """Переменные окружения, которые ЯВЛЯЮТСЯ ключами целевых адресов.

    Проверяются ВСЕ переменные, а не список имён: ключ под любым именем будет
    найден. Значения не печатаются никуда.
    """
    из_ = {"переменных_просмотрено": 0, "ключей_всего": 0, "попадания": [],
            "прочие_адреса": []}
    for имя, зн in os.environ.items():
        if not зн or len(зн) < 40:
            continue
        из_["переменных_просмотрено"] += 1
        адр = адрес_ключа(зн)
        if not адр:
            continue
        из_["ключей_всего"] += 1
        if адр in цели:
            из_["попадания"].append({"где": "переменная окружения", "имя": имя,
                                      "адрес": адр, "чей": цели[адр]})
        else:
            из_["прочие_адреса"].append({"имя": имя, "адрес": адр})
    return из_


def ключи_в_файлах(пути: list, цели: dict, *, предел_байт: int = 20_000_000) -> dict:
    """Файлы и каталоги, в которых лежат ключи целевых адресов."""
    из_ = {"файлов_просмотрено": 0, "ключей_всего": 0, "попадания": [],
            "прочие_адреса": [], "не_прочитано": []}
    очередь = []
    for п in пути:
        путь = Path(п)
        if путь.is_dir():
            for корень, каталоги, файлы in os.walk(путь):
                каталоги[:] = [к for к in каталоги
                                if к not in ("__pycache__", ".git", "venv",
                                              "node_modules")]
                очередь += [Path(корень) / ф for ф in файлы]
        elif путь.exists():
            очередь.append(путь)
    for ф in очередь:
        try:
            if ф.stat().st_size > предел_байт:
                continue
            текст = ф.read_text(encoding="utf-8", errors="ignore")
        except Exception as exc:  # noqa: BLE001
            из_["не_прочитано"].append({"файл": str(ф),
                                         "почему": type(exc).__name__})
            continue
        из_["файлов_просмотрено"] += 1
        for м in list(Б58.finditer(текст)) + list(МАССИВ.finditer(текст)):
            адр = адрес_ключа(м.group(0))
            if not адр:
                continue
            из_["ключей_всего"] += 1
            # ИМЯ ПЕРЕМЕННОЙ -- из той же строки файла, слева от знака равенства.
            начало = текст.rfind("\n", 0, м.start()) + 1
            строка_ф = текст[начало:м.start()]
            имя = (строка_ф.split("=")[0].strip().strip('"\' \t:,')
                    if "=" in строка_ф else строка_ф.strip()[:60])
            запись = {"где": "файл", "файл": str(ф), "имя": имя or "(без имени)",
                       "адрес": адр}
            if адр in цели:
                запись["чей"] = цели[адр]
                из_["попадания"].append(запись)
            else:
                из_["прочие_адреса"].append(запись)
    return из_


def self_test() -> int:
    всего = сбоев = 0

    def chk(что, ок, факт=None):
        nonlocal всего, сбоев
        всего += 1
        сбоев += (not ок)
        print(f"  [{'ok  ' if ок else 'СБОЙ'}] {что}"
              + (f" -> {факт!r}" if факт is not None and not ок else ""))

    # --- КЛЮЧ ОПОЗНАЁТСЯ ВЫВОДОМ АДРЕСА, А НЕ ИМЕНЕМ
    try:
        from solders.keypair import Keypair  # noqa: PLC0415

        кп = Keypair()
        ключ = str(кп)
        адр = str(кп.pubkey())
        chk("свежий ключ опознаётся и даёт свой адрес", адрес_ключа(ключ) == адр)
        chk("не ключ -- None, а не исключение",
            адрес_ключа("не ключ вовсе") is None
            and адрес_ключа("1" * 88) is None)
        # ИМЯ ПЕРЕМЕННОЙ НЕ ВАЖНО: ключ под чужим именем тоже находится.
        было = dict(os.environ)
        try:
            os.environ["ЗАМЕТКИ_РЕЗЕРВ"] = ключ
            р = ключи_в_окружении({адр: "тестовый"})
            chk("ключ под произвольным именем НАЙДЕН, и имя названо",
                any(п["имя"] == "ЗАМЕТКИ_РЕЗЕРВ" and п["адрес"] == адр
                    for п in р["попадания"]), р["попадания"])
            чужой = ключи_в_окружении({"ДРУГОЙ_АДРЕС": "чужой"})
            chk("чужой адрес в попадания не идёт, но ключ посчитан",
                not чужой["попадания"] and чужой["ключей_всего"] >= 1, чужой)
        finally:
            os.environ.clear()
            os.environ.update(было)
        # --- В ФАЙЛЕ
        import tempfile  # noqa: PLC0415

        with tempfile.TemporaryDirectory() as д:
            (Path(д) / "env").write_text(f"ЧТО_ТО_КЛЮЧ={ключ}\nПРОЧЕЕ=1\n",
                                          encoding="utf-8")
            р = ключи_в_файлах([д], {адр: "тестовый"})
            chk("ключ в файле найден, и названы файл и имя переменной",
                len(р["попадания"]) == 1
                and р["попадания"][0]["имя"] == "ЧТО_ТО_КЛЮЧ"
                and р["попадания"][0]["адрес"] == адр, р["попадания"])
            chk("сам ключ в ответ НЕ попадает",
                ключ not in json.dumps(р, ensure_ascii=False))
    except Exception as exc:  # noqa: BLE001
        chk("solders и разбор ключей доступны", False,
            f"{type(exc).__name__}: {str(exc)[:120]}")

    # --- РАЗБОР ТРАНЗАКЦИИ: перевод против свопа
    наш = "НАШ"
    перевод = {"slot": 1, "blockTime": 100,
                "transaction": {"signatures": ["ПОДПИСЬ"],
                                 "message": {"accountKeys": [наш, "ПОЛУЧАТЕЛЬ"],
                                              "instructions": [
                                                  {"programId": СИСТЕМНАЯ}]}},
                "meta": {"err": None, "fee": 5000,
                          "preBalances": [1_000_000_000, 0],
                          "postBalances": [975_000_000, 24_995_000],
                          "postTokenBalances": []}}
    р = разбор_транзакции(перевод, наш)
    chk("перевод опознан переводом, получатель и сумма названы",
        р["вид"] == "перевод" and р["получатель"] == "ПОЛУЧАТЕЛЬ"
        and р["получил_sol"] == 0.024995 and р["мы_платили"] is True, р)
    chk("наша дельта считается со знаком", р["наш_делta_sol"] == -0.025)
    своп = {"slot": 2, "blockTime": 101,
             "transaction": {"signatures": ["ПОДПИСЬ2"],
                              "message": {"accountKeys": [наш, "ПУЛ"],
                                           "instructions": [
                                               {"programId": "ПРОГРАММА_ПУЛА"}]}},
             "meta": {"err": None, "fee": 5000,
                       "preBalances": [1_000_000_000, 0],
                       "postBalances": [900_000_000, 0],
                       "postTokenBalances": [{"accountIndex": 1}]}}
    chk("своп опознан свопом, а получатель не выдумывается",
        (lambda к: к["вид"] == "своп" and к["получатель"] is None)(
            разбор_транзакции(своп, наш)))
    chk("нас нет в ключах -- причина словами, а не ноль",
        (lambda к: к["наш_делta_sol"] is None and к["почему"])(
            разбор_транзакции(перевод, "ЧУЖОЙ")))
    # --- ОКНО: цепь молчит -- отказ, а не «движения не было»
    р_м = движение(lambda *_а: "ошибка узла", "АДРЕС", с_ts=0, по_ts=1)
    chk("узел не ответил -- отказ словами, а не «движения нет»",
        р_м["ok"] is False and р_м["why_not"], р_м)
    пусто = движение(lambda м, п: [] if м == "getSignaturesForAddress" else {},
                      "АДРЕС", с_ts=0, по_ts=1)
    chk("подписей нет -- это ok и ноль в окне, и сказано сколько просмотрено",
        пусто["ok"] is True and пусто["в_окне"] == 0, пусто)
    print(f"самопроверка аудита кошелька: {всего - сбоев}/{всего} пройдено")
    return 1 if сбоев else 0


def main() -> int:
    р = argparse.ArgumentParser()
    р.add_argument("--self-test", action="store_true")
    р.add_argument("--koshelek", default="")
    р.add_argument("--s", default="", help="начало окна UTC")
    р.add_argument("--po", default="", help="конец окна UTC")
    р.add_argument("--stranic", type=int, default=3)
    р.add_argument("--puti", default="",
                    help="файлы и каталоги для аудита ключей, через запятую")
    р.add_argument("--out", default="")
    а = р.parse_args()
    if а.self_test:
        return self_test()
    import datetime  # noqa: PLC0415

    def ts(с):
        return datetime.datetime.strptime(с, "%Y-%m-%dT%H:%M:%SZ").replace(
            tzinfo=datetime.timezone.utc).timestamp()

    ЦЕЛИ = {"4s87RRC2V2XAJD6R8U2dP8kQH99Z2wA6fg88ZVfV4j4N": "Bloom (исполнитель)",
            "4dPZMbReSobZVxfrzGLcD7xJN33pZhuUZix5HkTBTh4x": "полоса (LIVE)",
            "21DqHDDPEfMhK1dHRkV9E8v8KTTSKQGApJAr1irC9j7w": "старый кошелёк полосы"}
    ответ: dict = {"цели": ЦЕЛИ}
    # --- АУДИТ КЛЮЧЕЙ: окружение службы и названные пути
    ответ["окружение"] = ключи_в_окружении(ЦЕЛИ)
    пути = [п.strip() for п in (а.puti or "").split(",") if п.strip()]
    ответ["пути"] = пути
    ответ["файлы"] = ключи_в_файлах(пути, ЦЕЛИ) if пути else {
        "почему": "пути не названы"}
    # --- ДВИЖЕНИЕ ПО ЦЕПИ
    if а.koshelek and а.s:
        import solana_rpc_client as RPC  # noqa: PLC0415

        клиент = RPC.SolanaRpc(service="koshelek_utechka")
        по = ts(а.po) if а.po else __import__("time").time()
        ответ["движение"] = движение(клиент.call, а.koshelek, с_ts=ts(а.s),
                                      по_ts=по, страниц=а.stranic)
    print("--- АУДИТ КЛЮЧЕЙ (сам ключ никуда не печатается) ---")
    о = ответ["окружение"]
    print(f"переменных окружения просмотрено {о['переменных_просмотрено']}, "
          f"из них являются ключами {о['ключей_всего']}")
    for п in о["попадания"]:
        print(f"  !!! КЛЮЧ ЦЕЛЕВОГО АДРЕСА: {п['имя']} -> {п['адрес']} ({п['чей']})")
    for п in о["прочие_адреса"]:
        print(f"  ключ другого адреса: {п['имя']} -> {п['адрес']}")
    ф = ответ.get("файлы") or {}
    if "почему" in ф:
        print(f"файлы не проверялись: {ф['почему']}")
    else:
        print(f"файлов просмотрено {ф['файлов_просмотрено']}, ключей в них "
              f"{ф['ключей_всего']}")
        for п in ф["попадания"]:
            print(f"  !!! КЛЮЧ ЦЕЛЕВОГО АДРЕСА В ФАЙЛЕ: {п['файл']} · "
                  f"{п['имя']} -> {п['адрес']} ({п['чей']})")
        for п in ф["прочие_адреса"]:
            print(f"  ключ другого адреса: {п['файл']} · {п['имя']} -> {п['адрес']}")
    if not о["попадания"] and not (ф.get("попадания") or []):
        print("  целевых ключей не найдено ни в окружении, ни в названных путях")
    д = ответ.get("движение")
    if д:
        print("\n--- ДВИЖЕНИЕ ПО ЦЕПИ ---")
        print(f"подписей просмотрено {д['подписей_просмотрено']}, в окне "
              f"{д['в_окне']}, прочитано {д['прочитано']}, не прочитано "
              f"{д['не_прочитано']}" + (f" · ОТКАЗ: {д['why_not']}"
                                         if not д["ok"] else ""))
        for с in д["строки"]:
            if с.get("почему"):
                print(f"  {с.get('подпись')}: {с['почему']}")
                continue
            print(f"  {с['подпись']}")
            print(f"     слот {с['слот']} · время {с['время']} · вид {с['вид']} · "
                  f"наша дельта {с['наш_делta_sol']} SOL · комиссия "
                  f"{с['комиссия_sol']} · платили мы: {с['мы_платили']}")
            if с["получатель"]:
                print(f"     получатель {с['получатель']} получил "
                      f"{с['получил_sol']} SOL")
            print(f"     программы: {', '.join(с['программы']) or '—'}")
    if а.out:
        Path(а.out).write_text(json.dumps(ответ, ensure_ascii=False, indent=1),
                                encoding="utf-8")
