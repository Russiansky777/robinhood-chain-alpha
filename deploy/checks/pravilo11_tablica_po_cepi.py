#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""ПРАВИЛО 11 ПО ЦЕПИ: таблица сделок полосы за окно, собранная заново.

ЗАЧЕМ. Правило 11 в службе ищет продажу в истории ТОКЕНОВОГО СЧЁТА позиции и
берёт оттуда подпись. Если тем же счётом потом занимался кто-то ещё -- владелец
своим ключом через Jupiter (29.09, 22:42-22:44Z, пять позиций) или прогон
закрытия пустых счетов (23:52Z) -- в строку попадает НЕ та транзакция: возврат
выходит нулём, а удержание -- 16-21 тысяча слотов при плане 12.

ЗДЕСЬ продажа берётся ПО ПОДПИСЯМ КОШЕЛЬКА: из окна движения кошелька выбирается
транзакция, в которой остаток ЭТОГО минта у нас уменьшился. Чья подпись -- по
цепи не видно и выдумывать этого нельзя; видно только, что минт ушёл и сколько
SOL пришло. Если выбранная подпись не совпала с той, что записала служба, это
названо отдельной колонкой -- в ней и виден дефект правила 11.

ДВА ИТОГА НА СДЕЛКУ, потому что это два разных вопроса:
  * итог по кошельку -- сумма нативных дельт кошелька по транзакциям сделки;
  * итог с нашими счетами -- то же плюс нативные остатки НАШИХ токеновых счетов
    (рента, которую покупка положила в наш же ATA и которая вернётся при его
    закрытии). Разница между этими двумя числами и есть та рента.

Вход -- два файла, оба только читаются:
  * выгрузка сделок полосы Code-1 (data/sdelki_polosy_*.json): cid, группа,
    минт, подписи, слоты, поля учёта;
  * окно движения кошелька (data/dvizhenie_koshelka.json): по транзакции
    нативная дельта кошелька, натив наших токеновых счетов, дельты минтов.

Измерительный код (Правило 8): самопроверок нет, числа берутся с цепи.
Сети не касается вовсе -- обе выгрузки уже на диске.
"""

from __future__ import annotations

import argparse
import json
import time

ЛАМПОРТ = 1_000_000_000


def utc(т) -> str | None:
    if not isinstance(т, (int, float)) or т <= 0:
        return None
    return time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime(float(т)))


def читать(путь: str) -> dict:
    with open(путь, encoding="utf-8") as ф:
        return json.load(ф)


def окно_по_подписям(окно: dict) -> dict:
    из_ = {}
    for р in (окно.get("строки") or []):
        п = р.get("подпись")
        if п:
            из_[п] = р
    return из_


def дельта_минта(строка: dict, минт: str) -> int:
    """На сколько изменился остаток ЭТОГО минта у нас в этой транзакции."""
    сумма = 0
    for т in (строка.get("токены") or []):
        if (т.get("минт") or "") == минт:
            сумма += int(т.get("дельта") or 0)
    return сумма


def собрать(сделки: dict, окно: dict) -> dict:
    по_подписи = окно_по_подписям(окно)
    ряды = []
    # ОДНА ПРОДАЖА -- ОДНОЙ СДЕЛКЕ. Минт C1mBfBoD за окно куплен трижды, и без
    # этого одна и та же продажа попала бы в три строки, утроив выручку.
    занятые: set = set()
    for с in (сделки.get("ряды") or []):
        минт = с.get("mint") or ""
        cid = с.get("cid") or ""
        покупка = с.get("landed_sig") or с.get("buy_sig")
        # ПОКУПКА: берём ту подпись, в которой минт у нас ПРИБАВИЛСЯ. Если
        # записанная подпись в окно не попала -- ищем по минту.
        if покупка not in по_подписи or дельта_минта(по_подписи[покупка], минт) <= 0:
            свои = [п for п in (с.get("our_signatures") or []) if п in по_подписи]
            нашлось = [п for п in свои if дельта_минта(по_подписи[п], минт) > 0]
            покупка = нашлось[0] if нашлось else (свои[0] if свои else покупка)
        # ПРОДАЖА ПО ПОДПИСЯМ КОШЕЛЬКА: транзакция окна, где этот минт у нас
        # уменьшился, ПОСЛЕ покупки. Именно тут правило 11 и ошибалось.
        т_покупки = (по_подписи.get(покупка) or {}).get("ts")
        продажи = []
        for п, р in по_подписи.items():
            if дельта_минта(р, минт) >= 0:
                continue
            if т_покупки is not None and float(р.get("ts") or 0) < float(т_покупки):
                continue
            if п in занятые:
                continue
            продажи.append((float(р.get("ts") or 0), п))
        продажи.sort()
        продажа = продажи[0][1] if продажи else None
        if продажа:
            занятые.add(продажа)

        подписи = [п for п in (покупка, продажа) if п and п in по_подписи]
        натив = 0.0
        с_рентой = 0.0
        for п in подписи:
            р = по_подписи[п]
            н = р.get("натив_sol")
            if н is None:
                continue
            натив += float(н)
            с_рентой += float(н) + float(р.get("натив_наших_счетов_sol") or 0.0)
        слот_п = (по_подписи.get(покупка) or {}).get("slot")
        слот_пр = (по_подписи.get(продажа) or {}).get("slot") if продажа else None
        ряды.append({
            "cid": cid, "cid_хвост": cid[-10:], "группа": с.get("group"),
            "минт": минт, "минт8": минт[:8],
            "подпись_покупки": покупка,
            "подпись_продажи_по_кошельку": продажа,
            "подпись_продажи_по_записи": с.get("sell_sig"),
            "продажа_та_же": (bool(продажа) and продажа == с.get("sell_sig")),
            "продажа_utc": utc((по_подписи.get(продажа) or {}).get("ts")) if продажа else None,
            "транзакций_в_окне": len(подписи),
            "итог_по_кошельку_sol": round(натив, 9) if подписи else None,
            "итог_с_нашими_счетами_sol": round(с_рентой, 9) if подписи else None,
            "рента_в_наших_счетах_sol": (round(с_рентой - натив, 9) if подписи else None),
            "итог_учёта_sol": с.get("итог_sol"),
            "расхождение_с_учётом_sol": (round(натив - float(с.get("итог_sol")), 9)
                                          if с.get("итог_sol") is not None and подписи
                                          else None),
            "слот_покупки": слот_п, "слот_продажи": слот_пр,
            "удержание_слотов_по_цепи": ((int(слот_пр) - int(слот_п))
                                          if isinstance(слот_п, int)
                                          and isinstance(слот_пр, int) else None),
            "удержание_слотов_записи": с.get("hold_slots_fact"),
            "удержание_слотов_план": с.get("hold_slots_plan"),
            "слот_источника": с.get("source_slot"),
            "лаг_слотов": ((int(слот_п) - int(с["source_slot"]))
                            if isinstance(слот_п, int)
                            and isinstance(с.get("source_slot"), int) else None),
            "chain_ok": с.get("chain_ok"),
            "причина_закрытия": str(с.get("closed_reason") or "")[:70],
        })
    return {"ряды": ряды}


def по_группам(ряды: list) -> dict:
    из_: dict = {}
    for р in ряды:
        г = р.get("группа") or "(без группы)"
        б = из_.setdefault(г, {"n": 0, "кошелёк_sol": 0.0, "с_рентой_sol": 0.0,
                                "рента_sol": 0.0, "учёт_sol": 0.0, "в_плюсе": 0,
                                "продажа_не_та": 0, "без_транзакций": 0})
        б["n"] += 1
        if р["итог_по_кошельку_sol"] is None:
            б["без_транзакций"] += 1
            continue
        б["кошелёк_sol"] += float(р["итог_по_кошельку_sol"])
        б["с_рентой_sol"] += float(р["итог_с_нашими_счетами_sol"])
        б["рента_sol"] += float(р["рента_в_наших_счетах_sol"])
        if р.get("итог_учёта_sol") is not None:
            б["учёт_sol"] += float(р["итог_учёта_sol"])
        if float(р["итог_по_кошельку_sol"]) > 0:
            б["в_плюсе"] += 1
        if р.get("подпись_продажи_по_кошельку") and not р.get("продажа_та_же"):
            б["продажа_не_та"] += 1
    for б in из_.values():
        for к in ("кошелёк_sol", "с_рентой_sol", "рента_sol", "учёт_sol"):
            б[к] = round(б[к], 9)
    return из_


def main() -> int:
    р = argparse.ArgumentParser()
    р.add_argument("--sdelki", default="data/sdelki_polosy_2026-09-29.json")
    р.add_argument("--okno", default="data/dvizhenie_koshelka.json")
    р.add_argument("--out", default="")
    р.add_argument("--sverka", default="",
                    help="ожидания Code-2 через запятую: lane_s0=0.184536,batch5=-0.031394")
    а = р.parse_args()

    сделки = читать(а.sdelki)
    окно = читать(а.okno)
    print(f"СДЕЛКИ: {а.sdelki} | окно выгрузки {сделки.get('с')} -> {сделки.get('до')} "
          f"| рядов {len(сделки.get('ряды') or [])}")
    print(f"ОКНО КОШЕЛЬКА: {окно.get('с')} -> {окно.get('по')} | транзакций "
          f"{окно.get('транзакций')} | сумма натив {окно.get('сумма_натив_sol')} "
          f"| с нашими счетами {окно.get('сумма_со_счетами_sol')}")

    из_ = собрать(сделки, окно)
    ряды = из_["ряды"]
    ряды.sort(key=lambda р_: (р_.get("группа") or "", р_.get("продажа_utc") or ""))
    print("")
    print(f"{'cid':11s} {'группа':11s} {'минт':9s} {'лаг':>4s} {'держ':>5s} "
          f"{'кошелёк':>12s} {'с рентой':>12s} {'рента':>10s} {'учёт':>12s} "
          f"{'разн':>10s} прод")
    for р_ in ряды:
        print(f"{р_['cid_хвост']:11s} {str(р_['группа']):11s} {р_['минт8']:9s} "
              f"{str(р_['лаг_слотов']):>4s} {str(р_['удержание_слотов_по_цепи']):>5s} "
              f"{str(р_['итог_по_кошельку_sol']):>12s} "
              f"{str(р_['итог_с_нашими_счетами_sol']):>12s} "
              f"{str(р_['рента_в_наших_счетах_sol']):>10s} "
              f"{str(р_['итог_учёта_sol']):>12s} "
              f"{str(р_['расхождение_с_учётом_sol']):>10s} "
              f"{'та же' if р_['продажа_та_же'] else ('ДРУГАЯ' if р_['подпись_продажи_по_кошельку'] else 'нет')}")

    группы = по_группам(ряды)
    из_["группы"] = группы
    print("")
    print("ПО ГРУППАМ:")
    for г, б in sorted(группы.items()):
        print(f"  {г:12s} n={б['n']:3d} кошелёк {б['кошелёк_sol']:+.9f} | "
              f"с рентой {б['с_рентой_sol']:+.9f} | рента {б['рента_sol']:+.9f} | "
              f"учёт {б['учёт_sol']:+.9f} | в плюсе {б['в_плюсе']} | "
              f"продажа не та у {б['продажа_не_та']} | без транзакций {б['без_транзакций']}")

    if а.sverka:
        print("")
        print("СВЕРКА С ОЖИДАНИЕМ:")
        for пара in а.sverka.split(","):
            пара = пара.strip()
            if not пара or "=" not in пара:
                continue
            г, зн = пара.split("=", 1)
            г = г.strip()
            try:
                ждём = float(зн)
            except ValueError:
                print(f"  {г}: {зн!r} не число")
                continue
            б = группы.get(г)
            if not б:
                print(f"  {г}: такой группы в таблице нет")
                continue
            for имя, ключ in (("кошелёк", "кошелёк_sol"), ("с рентой", "с_рентой_sol")):
                разница = round(float(б[ключ]) - ждём, 9)
                сошлось = abs(разница) <= 0.0005
                print(f"  {г:12s} ждём {ждём:+.6f} | {имя:9s} {б[ключ]:+.9f} | "
                      f"разница {разница:+.9f} | {'СОШЛОСЬ' if сошлось else 'НЕ СОШЛОСЬ'}")

    if а.out:
        with open(а.out, "w", encoding="utf-8") as ф:
            json.dump(из_, ф, ensure_ascii=False, indent=1)
        print("записано:", а.out)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
