#!/usr/bin/env python3
"""Строка тревоги по таблице Правила 11: печатает её или ничего.

ЗАЧЕМ ОТДЕЛЬНЫМ ФАЙЛОМ. Слово владельца: "вместо несчитаемого -- продажа не
найдена на цепи с тревогой в TG". Собирать текст питоном внутри YAML нельзя:
многострочный скрипт в нулевой колонке ломает разбор прогона (поймано дважды).
Здесь же тревога собирается одной строкой, а прогон только отправляет её.

Печатает ПУСТО, если тревог нет: прогон по пустой строке ничего не посылает.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ПРЕДЕЛ_В_СТРОКЕ = 5


def строка(итог: dict) -> str:
    св = (итог or {}).get("свод") or {}
    тревоги = св.get("тревоги") or []
    if not тревоги:
        return ""
    части = []
    for т in тревоги[:ПРЕДЕЛ_В_СТРОКЕ]:
        части.append(f"{т.get('статус')}: минт {str(т.get('минт'))[:12]}, "
                      f"покупка {str(т.get('подпись_покупки'))[:16]}")
    хвост = ("" if len(тревоги) <= ПРЕДЕЛ_В_СТРОКЕ
             else f" и ещё {len(тревоги) - ПРЕДЕЛ_В_СТРОКЕ}")
    return (f"ПРАВИЛО 11 ПО ЦЕПИ: тревог {св.get('тревог')} из "
             f"{св.get('сделок')} сделок; " + "; ".join(части) + хвост)


def self_test() -> int:
    пройдено = провалено = 0

    def chk(что, ок, факт=""):
        nonlocal пройдено, провалено
        if ок:
            пройдено += 1
            print(f"  [ok  ] {что}")
        else:
            провалено += 1
            print(f"  [ПРОВАЛ] {что}: {факт}")

    chk("без тревог строка пустая -- посылать нечего", строка({}) == "")
    chk("пустой свод тоже пустая строка",
        строка({"свод": {"тревоги": []}}) == "")
    с = строка({"свод": {"тревог": 2, "сделок": 30, "тревоги": [
        {"статус": "продажа не найдена на цепи", "минт": "МИНТ1234567890",
          "подпись_покупки": "ПОДПИСЬ1234567890"},
        {"статус": "покупка не найдена на цепи", "минт": "МИНТ2",
          "подпись_покупки": None}]}})
    chk("в строке есть число тревог, статус и обрезанные минт с подписью",
        "тревог 2 из 30" in с and "продажа не найдена на цепи" in с
        # минт обрезан до 12 знаков, подпись до 16: полные строки в тревоге не
        # нужны, а длинная строка в TG не читается.
        and "МИНТ12345678" in с and "МИНТ123456789" not in с
        and "ПОДПИСЬ123456789" in с and "ПОДПИСЬ1234567890" not in с, с)
    много = строка({"свод": {"тревог": 9, "сделок": 40, "тревоги": [
        {"статус": "продажа не найдена на цепи", "минт": f"М{i}",
          "подпись_покупки": f"П{i}"} for i in range(9)]}})
    chk("длинный список обрезан и остаток назван числом",
        "и ещё 4" in много, много[-20:])
    print(f"самопроверка строки тревоги: {пройдено}/{пройдено + провалено} пройдено")
    return 1 if провалено else 0


if __name__ == "__main__":
    if "--self-test" in sys.argv:
        raise SystemExit(self_test())
    путь = sys.argv[1] if len(sys.argv) > 1 else ""
    try:
        итог = json.loads(Path(путь).read_text(encoding="utf-8"))
    except Exception:  # noqa: BLE001
        print("")
        raise SystemExit(0)  # noqa: B904
    print(строка(итог))
