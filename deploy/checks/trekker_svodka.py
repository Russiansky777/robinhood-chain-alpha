#!/usr/bin/env python3
"""Сверка трекера: капитал против кошелька при НУЛЕ позиций. Чистые функции.

ЗАЧЕМ (слово владельца 04.10, 13:20Z): "когда Code-3 запушит исправление
трекера -- перезапустить трекер на lab-miami и сверить: при нуле позиций
капитал трекера = кошелёк +- 0.001. Больше ничего."

ПОЧЕМУ УСЛОВИЕ "ПРИ НУЛЕ ПОЗИЦИЙ" -- ЧАСТЬ ПРОВЕРКИ, А НЕ ПРИМЕЧАНИЕ. Пока у
трекера есть открытая позиция, его капитал И НЕ ДОЛЖЕН совпадать с кошельком:
часть денег лежит в токене. Сверять в таком состоянии -- значит получить
расхождение, которое ничего не значит, и либо зря объявить поломку, либо зря
объявить починку. Поэтому позиций не ноль -- вердикта НЕТ ВОВСЕ, и это
говорится словами.

ИЗМЕРЕНО 04.10 ДО ИСПРАВЛЕНИЯ: капитал трекера 6.391157 -> 6.512875 ->
6.560856 -> 6.702118 за час при кошельке полосы 6.26, то есть расхождение
росло (0.130 -> 0.442). Единственная позиция трекера -- USDC EPjFWdd5... с
входом 0 и остатком 1100.
"""
from __future__ import annotations

import json
import sys

ДОПУСК_SOL = 0.001
LAMPORTS = 1_000_000_000


def сверить(*, капитал_sol, кошелёк_lamports, позиций,
             допуск_sol: float = ДОПУСК_SOL) -> dict:
    """Сошлось ли. {вердикт, сошлось, разница_sol, почему}.

    вердикт -- одно из: "сошлось", "НЕ сошлось", "нет вердикта". Третье не
    поблажка, а честность: неизвестное число и ненулевые позиции не дают права
    сказать ни "да", ни "нет".
    """
    из_ = {"вердикт": "нет вердикта", "сошлось": None, "разница_sol": None,
            "разница_lamports": None, "капитал_sol": None, "кошелёк_sol": None,
            "позиций": None, "допуск_sol": float(допуск_sol),
            "допуск_lamports": None, "почему": None}
    try:
        к = float(капитал_sol)
    except (TypeError, ValueError):
        из_["почему"] = "капитал трекера не число -- сверять нечем"
        return из_
    try:
        л = int(кошелёк_lamports)
    except (TypeError, ValueError):
        из_["почему"] = "баланс кошелька не целое число лампортов -- сверять нечем"
        return из_
    try:
        п = int(позиций)
    except (TypeError, ValueError):
        из_["почему"] = "число позиций неизвестно -- сверять нельзя"
        return из_
    # СРАВНЕНИЕ В ЛАМПОРТАХ, А НЕ В SOL, И ЭТО НЕ ПРИДИРКА. В дробных числах
    # 6.261 - 6.26 даёт 0.0010000000000003339, то есть РОВНО допуск 0.001
    # оказывается "больше допуска", и граница, названная владельцем, работает
    # не так, как сказана. Моя же самопроверка это и поймала. Лампорты --
    # целые, и граница включительная становится ровно включительной.
    кош = л / LAMPORTS
    к_lam = int(round(к * LAMPORTS))
    допуск_lam = int(round(float(допуск_sol) * LAMPORTS))
    из_.update(капитал_sol=к, кошелёк_sol=кош, позиций=п,
                разница_sol=round((к_lam - л) / LAMPORTS, 9),
                разница_lamports=(к_lam - л), допуск_lamports=допуск_lam)
    if п != 0:
        из_["почему"] = (f"позиций {п}, а не ноль: часть денег в токене, и "
                          "капитал НЕ ДОЛЖЕН совпадать с кошельком -- сверка "
                          "в таком состоянии ничего не значит")
        return из_
    сошлось = abs(к_lam - л) <= допуск_lam
    из_.update(сошлось=сошлось,
                вердикт=("сошлось" if сошлось else "НЕ сошлось"),
                почему=(f"позиций 0; капитал {к:.9f}, кошелёк {кош:.9f}, "
                         f"разница {(к_lam - л) / LAMPORTS:+.9f} при допуске "
                         f"{float(допуск_sol):.3f} (в лампортах "
                         f"{к_lam - л:+d} при {допуск_lam})"))
    return из_


def _самопроверка() -> int:
    проверок = прошло = 0

    def сверить_(что, дано, ждали):
        nonlocal проверок, прошло
        проверок += 1
        if дано == ждали:
            прошло += 1
        else:
            print(f"НЕ ПРОШЛО: {что}: дано {дано!r}, ждали {ждали!r}")

    р = сверить(капитал_sol=6.26, кошелёк_lamports=6_260_000_000, позиций=0)
    сверить_("ровно равно -- сошлось", р["вердикт"], "сошлось")
    сверить_("и разница ноль", р["разница_sol"], 0.0)

    р = сверить(капитал_sol=6.2605, кошелёк_lamports=6_260_000_000, позиций=0)
    сверить_("0.0005 внутри допуска -- сошлось", р["вердикт"], "сошлось")
    # ГРАНИЦА ВКЛЮЧИТЕЛЬНО: владелец сказал "+- 0.001", и ровно 0.001 -- это
    # ещё "сошлось", а не "не сошлось".
    р = сверить(капитал_sol=6.261, кошелёк_lamports=6_260_000_000, позиций=0)
    сверить_("ровно 0.001 -- ещё сошлось", р["вердикт"], "сошлось")
    сверить_("и в лампортах это ровно допуск, а не больше",
             (р["разница_lamports"], р["допуск_lamports"]), (1_000_000, 1_000_000))
    # НА ОДИН ЛАМПОРТ ДАЛЬШЕ -- УЖЕ НЕ СОШЛОСЬ. Граница проверяется с двух
    # сторон, иначе "включительно" остаётся словом без доказательства.
    р = сверить(капитал_sol=6.261000001, кошелёк_lamports=6_260_000_000,
                 позиций=0)
    сверить_("на один лампорт за допуском -- НЕ сошлось",
             р["вердикт"], "НЕ сошлось")
    р = сверить(капитал_sol=6.2611, кошелёк_lamports=6_260_000_000, позиций=0)
    сверить_("0.0011 -- НЕ сошлось", р["вердикт"], "НЕ сошлось")
    сверить_("и разница названа со знаком", р["разница_sol"], 0.0011)
    # Расхождение в другую сторону тоже ловится.
    р = сверить(капитал_sol=6.2, кошелёк_lamports=6_260_000_000, позиций=0)
    сверить_("капитал НИЖЕ кошелька на 0.06 -- НЕ сошлось",
             (р["вердикт"], р["сошлось"]), ("НЕ сошлось", False))

    # ИЗМЕРЕННОЕ СОСТОЯНИЕ 04.10 ДО ИСПРАВЛЕНИЯ.
    р = сверить(капитал_sol=6.702118, кошелёк_lamports=6_260_165_036, позиций=1)
    сверить_("позиций не ноль -- вердикта НЕТ, и это сказано",
             (р["вердикт"], р["сошлось"]), ("нет вердикта", None))
    сверить_("и причина названа словами", "позиций 1, а не ноль" in р["почему"],
             True)
    сверить_("но разница всё равно посчитана -- для доклада",
             р["разница_sol"], 0.441952964)

    # ТО ЖЕ ЧИСЛО, НО ПРИ НУЛЕ ПОЗИЦИЙ -- УЖЕ ПРИГОВОР.
    р = сверить(капитал_sol=6.702118, кошелёк_lamports=6_260_165_036, позиций=0)
    сверить_("при нуле позиций то же расхождение -- НЕ сошлось",
             р["вердикт"], "НЕ сошлось")

    # НЕИЗВЕСТНОЕ -- НЕ "СОШЛОСЬ".
    for что, кв in (("капитала нет", {"капитал_sol": None,
                                        "кошелёк_lamports": 1, "позиций": 0}),
                     ("баланса нет", {"капитал_sol": 1.0,
                                        "кошелёк_lamports": None, "позиций": 0}),
                     ("позиций неизвестно", {"капитал_sol": 1.0,
                                               "кошелёк_lamports": 1,
                                               "позиций": None})):
        р = сверить(**кв)
        сверить_(f"{что} -- нет вердикта, а не «сошлось»",
                 (р["вердикт"], р["сошлось"]), ("нет вердикта", None))
        сверить_(f"{что}: причина названа", bool(р["почему"]), True)

    сверить_("допуск по умолчанию -- тот, что назвал владелец",
             ДОПУСК_SOL, 0.001)
    print(f"проверок {проверок}, прошло {прошло}, "
          f"не прошло {проверок - прошло}")
    return 0 if прошло == проверок else 1


def main(довод: list) -> int:
    if len(довод) < 3:
        print("нужно: капитал_sol кошелёк_lamports позиций [допуск_sol]")
        return 2
    из_ = сверить(капитал_sol=довод[0], кошелёк_lamports=довод[1],
                   позиций=довод[2],
                   допуск_sol=(float(довод[3]) if len(довод) > 3 else ДОПУСК_SOL))
    print(json.dumps(из_, ensure_ascii=False, indent=1))
    # 0 -- сошлось, 1 -- не сошлось, 2 -- вердикта нет. Прогон читает код и
    # говорит словами, а не падает: это сверка, а не гейт деплоя.
    return {"сошлось": 0, "НЕ сошлось": 1}.get(из_["вердикт"], 2)


if __name__ == "__main__":
    if "--self-test" in sys.argv:
        sys.exit(_самопроверка())
    sys.exit(main([а for а in sys.argv[1:] if not а.startswith("--")]))
