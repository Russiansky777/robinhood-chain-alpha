#!/usr/bin/env python3
"""Сверка трекера: chasti.sol против getBalance кошелька, ДО ЛАМПОРТА.

ПОПРАВКА ШТАБА 04.10 (и она отменяет мою прежнюю сверку). Я написал было
"капитал трекера = кошелёк +- 0.001". Это НЕВЕРНО, и слово штаба объясняет
почему: капитал с кошельком совпадать НЕ ДОЛЖЕН -- он больше на ренту
токен-счетов и на открытые позиции. Сверять надо не капитал, а его часть
chasti.sol из kapital.json с getBalance того же кошелька, взятым В ТУ ЖЕ
МИНУТУ, и совпадать она обязана ДО ЛАМПОРТА.

ПОЧЕМУ "В ТУ ЖЕ МИНУТУ" -- ЧАСТЬ ПРОВЕРКИ, А НЕ ПРИМЕЧАНИЕ. Кошелёк полосы
живой: за минуту проходит покупка или продажа, и тогда расхождение покажет не
ошибку трекера, а то, что числа взяты в разные моменты. Поэтому когда метки
времени разъехались, вердикта НЕТ ВОВСЕ -- и это говорится словами, а не
подменяется словом "не сошлось".

ПОЧЕМУ ДОПУСКА НЕТ СОВСЕМ. chasti.sol -- это и есть нативный баланс кошелька,
как его посчитал трекер по цепи. Любой допуск здесь прятал бы ровно ту ошибку,
которую ищем: расхождение на лампорты означает потерянную или задвоенную
транзакцию, а не округление.
"""
from __future__ import annotations

import json
import sys

LAMPORTS = 1_000_000_000
# МЕТКИ ВРЕМЕНИ СЧИТАЮТСЯ "ТОЙ ЖЕ МИНУТОЙ", если разошлись не больше чем на
# это. 60 с -- буквально "та же минута" из слова штаба.
ТА_ЖЕ_МИНУТА_С = 60


def сверить_sol(*, sol_lamports, кошелёк_lamports,
                 метка_трекера_utc=None, метка_баланса_utc=None,
                 та_же_минута_с: int = ТА_ЖЕ_МИНУТА_С) -> dict:
    """chasti.sol против getBalance. {вердикт, сошлось, разница_lamports, почему}.

    вердикт -- одно из: "сошлось", "НЕ сошлось", "нет вердикта". Третье не
    поблажка, а честность: неизвестное число и разъехавшиеся метки не дают
    права сказать ни "да", ни "нет".
    """
    из_ = {"вердикт": "нет вердикта", "сошлось": None,
            "разница_lamports": None, "sol_lamports": None,
            "кошелёк_lamports": None, "разрыв_меток_с": None,
            "та_же_минута_с": int(та_же_минута_с), "почему": None}
    try:
        с = int(sol_lamports)
    except (TypeError, ValueError):
        из_["почему"] = "chasti.sol не целое число лампортов -- сверять нечем"
        return из_
    try:
        л = int(кошелёк_lamports)
    except (TypeError, ValueError):
        из_["почему"] = "getBalance не отдал целое число лампортов -- сверять нечем"
        return из_
    из_.update(sol_lamports=с, кошелёк_lamports=л, разница_lamports=с - л)
    if метка_трекера_utc is not None and метка_баланса_utc is not None:
        try:
            разрыв = abs(int(метка_трекера_utc) - int(метка_баланса_utc))
        except (TypeError, ValueError):
            из_["почему"] = "метки времени не числа -- одна ли это минута, неизвестно"
            return из_
        из_["разрыв_меток_с"] = разрыв
        if разрыв > int(та_же_минута_с):
            из_["почему"] = (f"метки разъехались на {разрыв} с при пределе "
                              f"{int(та_же_минута_с)}: кошелёк полосы живой, и "
                              "расхождение покажет не ошибку трекера, а разные "
                              "моменты съёма")
            return из_
    сошлось = (с == л)
    из_.update(сошлось=сошлось,
                вердикт=("сошлось" if сошлось else "НЕ сошлось"),
                почему=(f"chasti.sol {с} лампортов, getBalance {л}, разница "
                         f"{с - л:+d} лампортов"
                         + (f"; метки разошлись на {из_['разрыв_меток_с']} с"
                            if из_["разрыв_меток_с"] is not None else
                            "; метки времени не переданы -- одна ли это минута, "
                            "не проверено")))
    return из_


def _самопроверка() -> int:
    проверок = прошло = 0

    def сверить_(что, дано, ждали):
        nonlocal проверок, прошло
        проверок += 1
        if дано == ждали:
            прошло += 1
        else:
            print(f"НЕ ПРОШЛО: {что}: дано {дано!r}, ждали {ждали!r}")

    р = сверить_sol(sol_lamports=6_260_165_036,
                     кошелёк_lamports=6_260_165_036,
                     метка_трекера_utc=1791120000, метка_баланса_utc=1791120005)
    сверить_("до лампорта равно и метки рядом -- сошлось", р["вердикт"], "сошлось")
    сверить_("и разница ровно ноль", р["разница_lamports"], 0)

    # ДОПУСКА НЕТ: ОДИН ЛАМПОРТ -- УЖЕ НЕ СОШЛОСЬ. Это и есть смысл поправки
    # штаба: прежняя моя сверка с допуском 0.001 SOL проглотила бы миллион
    # лампортов расхождения.
    р = сверить_sol(sol_lamports=6_260_165_037,
                     кошелёк_lamports=6_260_165_036,
                     метка_трекера_utc=1791120000, метка_баланса_utc=1791120000)
    сверить_("один лампорт разницы -- НЕ сошлось", р["вердикт"], "НЕ сошлось")
    сверить_("и он назван со знаком", р["разница_lamports"], 1)
    р = сверить_sol(sol_lamports=6_260_165_035,
                     кошелёк_lamports=6_260_165_036,
                     метка_трекера_utc=1791120000, метка_баланса_utc=1791120000)
    сверить_("недостача в один лампорт -- тоже НЕ сошлось и со знаком минус",
             (р["вердикт"], р["разница_lamports"]), ("НЕ сошлось", -1))

    # МЕТКИ РАЗЪЕХАЛИСЬ -- ВЕРДИКТА НЕТ, даже если числа равны.
    р = сверить_sol(sol_lamports=6_260_165_036,
                     кошелёк_lamports=6_260_165_036,
                     метка_трекера_utc=1791120000, метка_баланса_utc=1791120061)
    сверить_("61 с между метками -- вердикта НЕТ, хотя числа равны",
             (р["вердикт"], р["сошлось"]), ("нет вердикта", None))
    сверить_("и разрыв назван числом", р["разрыв_меток_с"], 61)
    сверить_("ровно 60 с -- ещё та же минута",
             сверить_sol(sol_lamports=1, кошелёк_lamports=1,
                          метка_трекера_utc=0,
                          метка_баланса_utc=60)["вердикт"], "сошлось")

    # МЕТОК НЕТ ВОВСЕ -- сверяем, но ГОВОРИМ, что минута не проверена.
    р = сверить_sol(sol_lamports=5, кошелёк_lamports=5)
    сверить_("без меток вердикт есть", р["вердикт"], "сошлось")
    сверить_("но сказано, что минута не проверена",
             "не проверено" in (р["почему"] or ""), True)

    # НЕИЗВЕСТНОЕ -- НЕ "СОШЛОСЬ".
    for что, кв in (("chasti.sol нет", {"sol_lamports": None,
                                          "кошелёк_lamports": 1}),
                     ("баланса нет", {"sol_lamports": 1,
                                        "кошелёк_lamports": None}),
                     ("метка не число", {"sol_lamports": 1,
                                          "кошелёк_lamports": 1,
                                          "метка_трекера_utc": "x",
                                          "метка_баланса_utc": 1})):
        р = сверить_sol(**кв)
        сверить_(f"{что} -- нет вердикта, а не «сошлось»",
                 (р["вердикт"], р["сошлось"]), ("нет вердикта", None))
        сверить_(f"{что}: причина названа", bool(р["почему"]), True)

    # ДРОБНОЕ ЧИСЛО SOL СВЕРЯТЬ ЭТОЙ ФУНКЦИЕЙ НЕЛЬЗЯ, и она это говорит:
    # 6.26 как строка в лампорты не превращается молча.
    сверить_("дробный SOL вместо лампортов -- отказ, а не тихое округление",
             сверить_sol(sol_lamports="6.26",
                          кошелёк_lamports=6_260_000_000)["вердикт"],
             "нет вердикта")

    сверить_("предел «та же минута» -- 60 секунд", ТА_ЖЕ_МИНУТА_С, 60)
    print(f"проверок {проверок}, прошло {прошло}, "
          f"не прошло {проверок - прошло}")
    return 0 if прошло == проверок else 1


def main(довод: list) -> int:
    if len(довод) < 2:
        print("нужно: chasti_sol_lamports koshelek_lamports "
              "[metka_trekera_utc] [metka_balansa_utc]")
        return 2
    из_ = сверить_sol(
        sol_lamports=довод[0], кошелёк_lamports=довод[1],
        метка_трекера_utc=(довод[2] if len(довод) > 2 and довод[2] else None),
        метка_баланса_utc=(довод[3] if len(довод) > 3 and довод[3] else None))
    print(json.dumps(из_, ensure_ascii=False, indent=1))
    # 0 -- сошлось, 1 -- не сошлось, 2 -- вердикта нет. Прогон читает код и
    # говорит словами, а не падает: это сверка, а не гейт деплоя.
    return {"сошлось": 0, "НЕ сошлось": 1}.get(из_["вердикт"], 2)


if __name__ == "__main__":
    if "--self-test" in sys.argv:
        sys.exit(_самопроверка())
    sys.exit(main([а for а in sys.argv[1:] if not а.startswith("--")]))
