#!/usr/bin/env python3
"""Сообщение коммита: только ASCII, без слов из смешанных алфавитов.

ЗАЧЕМ. В этом хозяйстве сообщения коммитов пишутся транслитом, и дважды за
одну смену я оставил в них слово, собранное из двух алфавитов: "zamenив" и
"pока". Глазами такое не видно -- латинская "p" и кириллическая "р"
неразличимы в шрифте, -- а в истории остаётся навсегда: верхушку можно
поправить только пока на неё не лёг чужой коммит, и во второй раз я не успел.
Поэтому проверка стоит отдельным файлом и зовётся ДО commit, а не после.

ЧТО СЧИТАЕТСЯ ОШИБКОЙ. Любой знак вне ASCII. Два случая названы отдельно,
потому что лечатся по-разному: слово из смешанных алфавитов -- это опечатка
раскладки (лечится заменой одной буквы), целиком кириллическое слово -- это
забытый транслит (лечится переписыванием слова).

ПОЧЕМУ НЕ git hook. Крючок живёт в .git/hooks, которого нет в ветке: на
свежем клоне и на бегунке его не будет, а значит он не защищает. Этот файл
едет в ветке и зовётся из командной строки.

ТОЛЬКО ДЛЯ СООБЩЕНИЙ, НАПИСАННЫХ РУКОЙ, И ЭТО ВАЖНО. Прогоны этого хозяйства
коммитят сами, и подписи у них кириллицей по сложившемуся правилу ("Журнал:
выборка по строкам [automated]", "NL-хост: проверка живучести служб"). Их эта
проверка справедливо забракует, и ставить её общим заслоном на все коммиты
нельзя -- она сломает прогоны. Зовётся она на СВОЁ сообщение перед commit:
  python3 deploy/checks/soobshchenie_kommita_ascii.py --fajl msg.txt && \
      git commit -F msg.txt
Прогон по истории 11.10 нашёл ровно одно заражённое сообщение из написанных
рукой -- d533a4bd со словом "zamenив"; поправить его уже нельзя, поверх лёг
автоматический коммит, а переписывать чужую историю нельзя.
"""
from __future__ import annotations

import argparse
import re
import sys
import unicodedata

СМЕШАННОЕ = re.compile(r"[A-Za-zЀ-ӿ_]{2,}")
КИРИЛЛИЦА = re.compile(r"[Ѐ-ӿ]")
ЛАТИНИЦА = re.compile(r"[A-Za-z]")


def разбор(текст: str) -> dict:
    """Что не так с сообщением. Числа и места, а не 'плохо'."""
    смешанные, целиком_кир, не_ascii = [], [], []
    for слово in СМЕШАННОЕ.findall(текст):
        есть_к = bool(КИРИЛЛИЦА.search(слово))
        есть_л = bool(ЛАТИНИЦА.search(слово))
        if есть_к and есть_л:
            смешанные.append(слово)
        elif есть_к:
            целиком_кир.append(слово)
    for н, знак in enumerate(текст):
        if ord(знак) > 127:
            не_ascii.append({"знак": знак, "смещение": н,
                              "имя": unicodedata.name(знак, "БЕЗ ИМЕНИ")})
    return {"смешанные": sorted(set(смешанные)),
            "целиком_кириллица": sorted(set(целиком_кир)),
            "не_ascii_знаков": len(не_ascii),
            "первые_не_ascii": не_ascii[:8],
            "ok": not смешанные and not целиком_кир and not не_ascii}


def словами(р: dict) -> str:
    if р["ok"]:
        return "сообщение коммита чистое: только ASCII, смешанных слов нет"
    части = []
    if р["смешанные"]:
        части.append("слова из ДВУХ алфавитов (опечатка раскладки, поправить "
                      f"букву): {', '.join(р['смешанные'])}")
    if р["целиком_кириллица"]:
        части.append("слова кириллицей (забыт транслит, переписать): "
                      f"{', '.join(р['целиком_кириллица'])}")
    прочие = [з for з in р["первые_не_ascii"]
              if not КИРИЛЛИЦА.search(з["знак"])]
    if прочие:
        части.append("прочие не-ASCII знаки: "
                      + ", ".join(f"{з['имя']} на {з['смещение']}" for з in прочие))
    return "ОТКАЗ. " + "; ".join(части)


def self_test() -> int:
    всего = провалов = 0

    def chk(имя: str, усл: bool, под: object = "") -> None:
        nonlocal всего, провалов
        всего += 1
        if not усл:
            провалов += 1
            print(f"  [ПРОВАЛ] {имя}" + (f" -- {под}" if под else ""))
        else:
            print(f"  [ok  ] {имя}")

    ч = разбор("Popravka: temp kolca tretij put\n\nVsjo chisto.")
    chk("чистое сообщение проходит", ч["ok"], ч)
    # ровно те две опечатки, на которых проверка и завелась
    п1 = разбор("zamenив ejo prjamym izlozheniem")
    chk("ловит 'zamenив' (латиница + кириллица)",
        п1["смешанные"] == ["zamenив"] and not п1["ok"], п1)
    п2 = разбор("razdelit drozhanie pока nechem")
    chk("ловит 'pока' (латинская p и кириллица)",
        п2["смешанные"] == ["pока"] and not п2["ok"], п2)
    п3 = разбор("забор otkazal")
    chk("ловит слово целиком кириллицей и зовёт это забытым транслитом",
        п3["целиком_кириллица"] == ["забор"] and not п3["смешанные"]
        and not п3["ok"], п3)
    п4 = разбор("tire — ne ASCII")
    chk("ловит не-ASCII знак, который не кириллица (длинное тире)",
        п4["не_ascii_знаков"] == 1 and not п4["смешанные"]
        and not п4["целиком_кириллица"] and not п4["ok"], п4)
    chk("длинное тире названо прочим знаком, а не словом",
        "прочие не-ASCII" in словами(п4), словами(п4))
    chk("слово из одной буквы не считается словом (порог 2 знака)",
        разбор("a о")["смешанные"] == [], разбор("a о"))
    chk("в отказе названы САМИ слова, а не только их число",
        "zamenив" in словами(п1), словами(п1))
    chk("подсказка для смешанного и для кириллического РАЗНАЯ",
        "раскладки" in словами(п1) and "транслит" in словами(п3))
    chk("чистому сообщению отказ не пишется",
        "ОТКАЗ" not in словами(ч), словами(ч))
    print(f"самопроверка сообщения коммита: {всего - провалов}/{всего} пройдено")
    return 1 if провалов else 0


def main() -> int:
    p = argparse.ArgumentParser()
    p.add_argument("--self-test", action="store_true")
    p.add_argument("--fajl", help="файл с сообщением коммита")
    a = p.parse_args()
    if a.self_test:
        return self_test()
    if not a.fajl:
        print("нужен --fajl с сообщением коммита или --self-test")
        return 2
    with open(a.fajl, encoding="utf-8") as f:
        р = разбор(f.read())
    print(словами(р))
    return 0 if р["ok"] else 1


if __name__ == "__main__":
    sys.exit(main())
