#!/usr/bin/env python3
"""Пакет 04.10, п. Б.5 (часть «горизонты»): удержание +108 против других горизонтов выхода.

Только чтение, офлайн по кэшу сигналов архива (`podbivka_paket_kesh.py`). Итог считается
формулой модели архива `podbivka_bilet.пп_по_состояниям` при входе S+1 и билете группы
источника; горизонты -- те, для которых в проходе СОХРАНЕНЫ состояния пула на выходе.

ЧТО МОЖНО И ЧЕГО НЕЛЬЗЯ. Состояния выхода пишутся только на фиксированных горизонтах
(в старых проходах 6/12/24/36/72/108/150; в проходах `paket_*` добавлены 30/60/300).
Поэтому выход «вслед за продажей источника», хвост «продать при падении X % от пика» и
«зафиксировать половину на +Y %» по этому кэшу посчитать НЕЛЬЗЯ: для них нужно состояние
пула на том слоте, где это происходит, а его в файлах нет. Эти три варианта считаются
отдельно, после прохода с новыми точками выхода (слот пика, слот первой чужой продажи,
слот продажи самого источника) -- см. страницу пакета.

Разрезы: по группам, по типам пулов, по главным источникам (n >= 20). Проверка вне выборки:
подбор -- ранние сутки, проверка -- последние; плюс две половины и «без двух лучших сделок».
Выход: data/podbivka/paket_vyhod.json и docs/podbivka_<метка>_vyhod_gorizonty.md.
Ничего не рекомендуется -- решает владелец.
"""
from __future__ import annotations

import argparse
import collections
import json
import sys
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import podbivka_paket_obshee as O  # noqa: E402

КОРЕНЬ = O.КОРЕНЬ
П = O.П
N_МИН = 20


def main() -> int:
    import podbivka_run as R  # noqa: PLC0415
    р = argparse.ArgumentParser()
    р.add_argument("--metka", default=time.strftime("%Y-%m-%d", time.gmtime()))
    р.add_argument("--podbor-sutok", type=int, default=8)
    а = р.parse_args()

    адр = O.реестр()
    счёт = collections.Counter()
    ряды: list = []
    горизонты: collections.Counter = collections.Counter()
    for р_ in O.сигналы():
        счёт["всего"] += 1
        г = O.группа_адреса(адр, р_.get("ист"))
        if not г:
            счёт["не_торгующая_группа"] += 1
            continue
        if р_.get("quoteMint") != O.WSOL:
            счёт["не_wsol"] += 1
            continue
        пол = O.ПОЛИТИКА.get(г) or {}
        if (р_.get("sol") or 0) < (пол.get("порог_источника_sol") or 2.0):
            счёт["ниже_порога"] += 1
            continue
        if not (р_.get("вход") or {}).get("S1"):
            счёт["нет_S1"] += 1
            continue
        б = пол.get("билет") or 0.1
        строка = {"ист": р_["ист"], "группа": г, "пул": р_.get("пул"), "билет": б,
                  "сутки": O.сутки(р_), "пп": {},
                  "первая_чужая_продажа_слотов": р_.get("первая_продажа_слотов"),
                  "пик_слотов": р_.get("пик_слотов"), "пик_пп_цены": р_.get("пик_пп")}
        for h in sorted(int(x) for x in (р_.get("выход") or {})):
            п = O.пп(р_, б, "S1", h)
            if п is not None:
                строка["пп"][str(h)] = п
                горизонты[str(h)] += 1
        if not строка["пп"]:
            счёт["нет_ни_одного_горизонта"] += 1
            continue
        счёт["в_счёте"] += 1
        ряды.append(строка)

    if not ряды:
        print("нет рядов", flush=True)
        return 1
    дни = sorted({р_["сутки"] for р_ in ряды})
    окна = O.окна(дни, а.podbor_sutok)
    все_h = [h for h, n in горизонты.items() if n >= 0.5 * счёт["в_счёте"]]
    все_h.sort(key=int)

    def свод(подмн: list, h: str, дни_: list) -> dict:
        от = [р_ for р_ in подмн if р_["сутки"] in дни_ and h in р_["пп"]]
        if not от:
            return {"n": 0}
        д = len({р_["сутки"] for р_ in от}) or 1
        sol = [р_["пп"][h] / 100 * р_["билет"] for р_ in от]
        с = O.стат([р_["пп"][h] for р_ in от], 2)
        верх = sorted(sol, reverse=True)
        return {"n": len(от), "суток": д, "медиана_пп": с["медиана"], "среднее_пп": с["среднее"],
                "в_плюсе": с["в_плюсе"], "итог_sol": round(sum(sol), 6),
                "sol_в_сутки": round(sum(sol) / д, 6),
                "sol_в_сутки_без_верхних_2": round(sum(верх[2:]) / д, 6) if len(верх) > 2 else None}

    разрезы: dict = {"все торгующие": ряды}
    for г in sorted({р_["группа"] for р_ in ряды}):
        разрезы[f"группа {г}"] = [р_ for р_ in ряды if р_["группа"] == г]
    for пул in sorted({р_["пул"] for р_ in ряды if р_["пул"]}):
        разрезы[f"пул {пул}"] = [р_ for р_ in ряды if р_["пул"] == пул]
    счёт_ист = collections.Counter(р_["ист"] for р_ in ряды)
    for a, n in счёт_ист.most_common():
        if n >= N_МИН:
            разрезы[f"источник {a[:8]}"] = [р_ for р_ in ряды if р_["ист"] == a]

    итог = {"что": "Б.5 (горизонты): удержание +108 против других горизонтов выхода",
            "источник_чисел": {"кэш": str(O.КЭШ),
                               "сводка_кэша": "data/podbivka/paket_kesh_svod.json",
                               "политика": "data/podbivka/code1_sources_live.json"},
            "счёт": dict(счёт), "горизонты_в_файлах": dict(sorted(горизонты.items(), key=lambda kv: int(kv[0]))),
            "окна": окна, "разрезы": {}}
    for имя, подмн in разрезы.items():
        итог["разрезы"][имя] = {h: {"подбор": свод(подмн, h, окна["подбор"]),
                                    "проверка": свод(подмн, h, окна["проверка"]),
                                    "всё": свод(подмн, h, окна["все"]),
                                    "половина_1": свод(подмн, h, окна["половина_1"]),
                                    "половина_2": свод(подмн, h, окна["половина_2"])}
                                for h in все_h}
    out = П / "paket_vyhod.json"
    out.write_text(json.dumps(итог, ensure_ascii=False, indent=1), encoding="utf-8")
    R.записано(out)

    def ф(v, формат="+.6f"):
        return "—" if v is None else format(v, формат)

    md = [f"# Выход: удержание +108 против других горизонтов ({а.metka})", "",
          f"Кэш сигналов архива ({O.КЭШ.name}), политика групп — "
          f"`data/podbivka/code1_sources_live.json`. Вход S+1, билет — группы источника, итог — "
          f"формулой модели архива. Окно {окна['все'][0]} — {окна['все'][-1]}: подбор "
          f"{len(окна['подбор'])} суток, проверка {len(окна['проверка'])} суток. В счёт пошли "
          f"{счёт['в_счёте']} сигналов; отброшено: не торгующая группа "
          f"{счёт.get('не_торгующая_группа', 0)}, не WSOL {счёт.get('не_wsol', 0)}, ниже порога "
          f"группы {счёт.get('ниже_порога', 0)}, нет состояния S1 {счёт.get('нет_S1', 0)}, нет "
          f"ни одного горизонта {счёт.get('нет_ни_одного_горизонта', 0)}.", "",
          f"Горизонты, которые есть в файлах (слотов → сигналов): "
          + ", ".join(f"{h} → {n}" for h, n in итог["горизонты_в_файлах"].items()) + ".", "",
          "**Чего здесь нет.** Выход «вслед за продажей источника», хвост «продать при падении "
          "X % от пика» и «зафиксировать половину на +Y %» по этому кэшу посчитать нельзя: "
          "состояния пула пишутся только на фиксированных горизонтах, а для этих вариантов нужно "
          "состояние на слоте события (пик, чужая продажа, продажа источника). Точки выхода "
          "«пик», «первая чужая продажа» и «продажа источника» добавлены в модель прохода, "
          "числа по ним будут после следующего прохода архива.", ""]
    for имя, по_h in итог["разрезы"].items():
        с_числом = {h: v for h, v in по_h.items() if v["проверка"].get("n")}
        if not с_числом:
            continue
        лучший = max(с_числом.items(), key=lambda kv: kv[1]["проверка"]["sol_в_сутки"])
        б108 = по_h.get("108", {}).get("проверка", {})
        md += [f"## {имя}", "",
               f"Лучший горизонт на проверке — **{лучший[0]} слотов**: "
               f"{ф(лучший[1]['проверка']['sol_в_сутки'])} SOL в сутки против "
               f"{ф(б108.get('sol_в_сутки'))} при +108.", "",
               "| горизонт, слотов | n | медиана п.п. | в плюсе | SOL/сутки на подборе "
               "| SOL/сутки на проверке | на проверке без верхних 2 | половина 1 | половина 2 |",
               "|---|---|---|---|---|---|---|---|---|"]
        for h in все_h:
            v = по_h[h]
            пр = v["проверка"]
            md.append(f"| {h} | {пр.get('n', 0)} | {ф(пр.get('медиана_пп'), '+.2f')} "
                      f"| {str(пр.get('в_плюсе')) + ' %' if пр.get('n') else '—'} "
                      f"| {ф(v['подбор'].get('sol_в_сутки'))} | {ф(пр.get('sol_в_сутки'))} "
                      f"| {ф(пр.get('sol_в_сутки_без_верхних_2'))} "
                      f"| {ф(v['половина_1'].get('sol_в_сутки'))} "
                      f"| {ф(v['половина_2'].get('sol_в_сутки'))} |")
        md.append("")
    общ = итог["разрезы"]["все торгующие"]
    с_числом = {h: v for h, v in общ.items() if v["проверка"].get("n")}
    лучший = max(с_числом.items(), key=lambda kv: kv[1]["проверка"]["sol_в_сутки"])
    md += ["## Вывод", "",
           f"По всем торгующим источникам лучший горизонт на проверке — **{лучший[0]} слотов**, "
           f"{ф(лучший[1]['проверка']['sol_в_сутки'])} SOL в сутки (без двух лучших сделок "
           f"{ф(лучший[1]['проверка'].get('sol_в_сутки_без_верхних_2'))}) против "
           f"{ф(общ.get('108', {}).get('проверка', {}).get('sol_в_сутки'))} SOL в сутки при "
           f"нынешнем +108; условие — вход S+1 и билет группы.", "",
           "Ничего не меняется и не рекомендуется — решает владелец.", ""]
    стр = КОРЕНЬ / "docs" / f"podbivka_{а.metka}_vyhod_gorizonty.md"
    стр.write_text("\n".join(md) + "\n", encoding="utf-8")
    R.записано(стр)
    print(f"{стр.name}: сигналов {счёт['в_счёте']}, горизонтов {len(все_h)}, лучший на проверке "
          f"{лучший[0]} ({лучший[1]['проверка']['sol_в_сутки']})", flush=True)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
