#!/usr/bin/env python3
"""Таблица трёх срезов головы очереди: 25.09 (слот 250 мс), 15.10 (200 мс), 22.10 (200 мс + Votor).

Читает готовые data/podbivka/golova_srez_{2509,1510,2210}.json и сводит их в одну таблицу
с n по каждому срезу, доверительными границами и рангованными сравнениями пар.

Наплыв и всё, что считается «на слот», пересчитывается ВО ВРЕМЯ: длина слота берётся
измеренной по самому архиву (медиана разницы timestamp соседних блоков), а не на слово.

Два контроля, без которых разница срезов не читается:
  * ОКНО. 22.10 -- неполные сутки (18 ч), поэтому сравнения считаются на общем окне 00--18Z
    всех трёх срезов, а полные сутки идут отдельной колонкой.
  * СОСТАВ. Доли покупок по источникам в срезах разные, и сдвиг медианы может быть просто
    сменой состава. Поэтому рядом -- равный вес на источник (медиана по-источниковых медиан
    на общих источниках) и знаковый тест по направлению сдвига на тех же источниках.

Статистика без scipy: ранговый критерий Манна -- Уитни с поправкой на связки (нормальное
приближение), Краскел -- Уоллис (df = 2, p = exp(-H/2)), две доли -- z с границами Уилсона,
медианы -- бутстрап 2000, поправка Холма на число показателей внутри пары.

Только чтение. Выход: data/podbivka/golova_srezy_tablica.json.
"""
from __future__ import annotations

import collections
import json
import math
import random
import statistics as st
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parent.parent
П = КОРЕНЬ / "data" / "podbivka"
СРЕЗЫ = (("2509", "25.09 (слот 250 мс)"), ("1510", "15.10 (200 мс, до Votor)"),
         ("2210", "22.10 (200 мс + Votor)"))
БУТСТРАП = 2000
ОКНО_Ч = 18          # общее окно всех трёх срезов: 00--18Z


def Ф(z: float) -> float:
    return 0.5 * (1 + math.erf(z / math.sqrt(2)))


def дву(z: float) -> float:
    return round(2 * (1 - Ф(abs(z))), 6)


def ранговый(a: list, b: list) -> dict:
    """Манн -- Уитни, двусторонний, с поправкой на связки. A = доля пар, где a > b."""
    n1, n2 = len(a), len(b)
    if n1 < 5 or n2 < 5:
        return {"n1": n1, "n2": n2, "p": None, "A": None}
    все = sorted([(v, 0) for v in a] + [(v, 1) for v in b])
    ранги = [0.0] * len(все)
    связки = 0
    i = 0
    while i < len(все):
        j = i
        while j + 1 < len(все) and все[j + 1][0] == все[i][0]:
            j += 1
        р = (i + j) / 2 + 1
        for k in range(i, j + 1):
            ранги[k] = р
        t = j - i + 1
        связки += t ** 3 - t
        i = j + 1
    R1 = sum(r for r, (_v, g) in zip(ранги, все) if g == 0)
    U = R1 - n1 * (n1 + 1) / 2
    N = n1 + n2
    disp = n1 * n2 / 12 * ((N + 1) - связки / (N * (N - 1)))
    if disp <= 0:
        return {"n1": n1, "n2": n2, "p": None, "A": round(U / (n1 * n2), 4)}
    z = (abs(U - n1 * n2 / 2) - 0.5) / math.sqrt(disp)
    return {"n1": n1, "n2": n2, "p": дву(z), "A": round(U / (n1 * n2), 4),
            "z": round(z, 3)}


def краскел(группы: list) -> dict:
    """Краскел -- Уоллис на три группы; df = 2, поэтому p = exp(-H/2) точно."""
    группы = [г for г in группы if len(г) >= 5]
    if len(группы) < 3:
        return {"H": None, "p": None}
    все = sorted([(v, i) for i, г in enumerate(группы) for v in г])
    N = len(все)
    ранги = [0.0] * N
    связки = 0
    i = 0
    while i < N:
        j = i
        while j + 1 < N and все[j + 1][0] == все[i][0]:
            j += 1
        р = (i + j) / 2 + 1
        for k in range(i, j + 1):
            ранги[k] = р
        t = j - i + 1
        связки += t ** 3 - t
        i = j + 1
    сум: dict = collections.defaultdict(float)
    счёт: dict = collections.Counter()
    for r, (_v, g) in zip(ранги, все):
        сум[g] += r
        счёт[g] += 1
    H = 12 / (N * (N + 1)) * sum(сум[g] ** 2 / счёт[g] for g in сум) - 3 * (N + 1)
    поправка = 1 - связки / (N ** 3 - N)
    if поправка > 0:
        H /= поправка
    return {"H": round(H, 3), "p": round(math.exp(-H / 2), 6)}


def уилсон(k: int, n: int, z: float = 1.96) -> tuple:
    if not n:
        return (None, None)
    p = k / n
    д = 1 + z * z / n
    ц = (p + z * z / (2 * n)) / д
    р = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / д
    return (round(ц - р, 4), round(ц + р, 4))


def две_доли(k1: int, n1: int, k2: int, n2: int) -> float | None:
    if not (n1 and n2):
        return None
    p = (k1 + k2) / (n1 + n2)
    se = math.sqrt(p * (1 - p) * (1 / n1 + 1 / n2))
    if se == 0:
        return None
    return дву((k1 / n1 - k2 / n2) / se)


def бутстрап_медианы(в: list, сид: int) -> tuple:
    if len(в) < 10:
        return (None, None)
    рнд = random.Random(сид)
    n = len(в)
    м = sorted(st.median(рнд.choices(в, k=n)) for _ in range(БУТСТРАП))
    return (round(м[int(0.025 * БУТСТРАП)], 4), round(м[int(0.975 * БУТСТРАП)], 4))


def холм(пары: list) -> dict:
    """Холм на список (имя, p); возвращает имя -> порог, который p должен пробить."""
    годные = sorted([(p, и) for и, p in пары if p is not None])
    m = len(годные)
    вых = {}
    for k, (p, и) in enumerate(годные):
        вых[и] = {"p": p, "порог": round(0.05 / (m - k), 6), "прошёл": p < 0.05 / (m - k)}
    for и, p in пары:
        if p is None:
            вых[и] = {"p": None, "порог": None, "прошёл": None}
    return вых


def знаковый(плюс: int, всего: int) -> float | None:
    """Точный двусторонний знаковый тест."""
    if not всего:
        return None
    к = min(плюс, всего - плюс)
    хвост = sum(math.comb(всего, i) for i in range(к + 1)) / 2 ** всего
    return round(min(1.0, 2 * хвост), 4)


