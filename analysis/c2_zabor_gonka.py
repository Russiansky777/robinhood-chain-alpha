def чаевые_всех(отправители, *, путь_реестра: str | None = None,
                 реестр=None, минимум=None) -> dict:
    """Чаевые каждому отправителю -- ЕГО функцией, не своей таблицей."""
    из_ = {"ok": True, "why_not": None, "по_отправителю": {}, "отказы": []}
    for имя in (отправители or ()):
        ч = Z.чаевые_отправителя(имя, путь_реестра=путь_реестра, реестр=реестр,
                                  минимум=минимум)
        if not ч.get("ok"):
            из_["отказы"].append({"отправитель": имя, "why_not": ч.get("why_not")})
            continue
        из_["по_отправителю"][имя] = ч
    if not из_["по_отправителю"]:
        из_.update(ok=False, why_not="ни одному отправителю чаевые не назначены")
    return из_


def цена_раунда_лампорты(чаевые: dict) -> int:
    """Комиссия плюс чаевые по ВСЕМ отправителям раунда -- одним числом."""
    всего = 0
    for ч in (чаевые or {}).values():
        всего += int(Z.КОМИССИЯ_ЛАМПОРТЫ) + int((ч or {}).get("лампорты") or 0)
    return всего


def предел_расхода_sol(раундов: int, чаевые: dict) -> float:
    return round(цена_раунда_лампорты(чаевые) * int(раундов)
                 / Z.ЛАМПОРТОВ_В_SOL, 9)


def проверить_потолок(раундов: int, чаевые: dict) -> dict:
    """Влезает ли гонка в потолок расхода. Не влезает -- отказ ПО ИМЕНИ.

    Урезать раунды молча нельзя: «30 раундов» в отчёте, где их было два, -- это
    ложь о выборке. Поэтому здесь только отказ и число, сколько влезает.
    """
    за_раунд = цена_раунда_лампорты(чаевые) / Z.ЛАМПОРТОВ_В_SOL
    предел = предел_расхода_sol(раундов, чаевые)
    из_ = {"ok": True, "why_not": None, "предел_расхода_sol": предел,
            "цена_раунда_sol": round(за_раунд, 9),
            "потолок_sol": Z.ПОТОЛОК_РАСХОДА_SOL,
            "влезает_раундов": (int(Z.ПОТОЛОК_РАСХОДА_SOL / за_раунд)
                                if за_раунд else 0)}
    if предел > Z.ПОТОЛОК_РАСХОДА_SOL:
        из_.update(ok=False,
                    why_not=(f"{ПРИЗНАК_ПОТОЛОК}: {раундов} раундов стоят "
                             f"{предел} SOL при потолке {Z.ПОТОЛОК_РАСХОДА_SOL} SOL "
                             f"(раунд {round(за_раунд, 9)} SOL, влезает "
                             f"{из_['влезает_раундов']})"))
    return из_


