def _медиана(ряд):
    ряд = [x for x in ряд if isinstance(x, (int, float)) and not isinstance(x, bool)]
    return round(statistics.median(ряд), 1) if ряд else None


def свод_гонки(строки: list) -> dict:
    """Числа по ОТПРАВИТЕЛЮ: сел / не сел, медианы, регионы лидера."""
    по = {}
    for с in (строки or []):
        имя = str((с or {}).get("отправитель") or "?")
        з = по.setdefault(имя, {"отправок": 0, "село": 0, "не_село": 0,
                                 "не_отправлено": 0, "слотов": [], "индексы": [],
                                 "доли": [], "регионы": {}, "цена_sol": 0.0,
                                 "чаевые_лампорты": None})
        if с.get("чаевые_лампорты") is not None:
            з["чаевые_лампорты"] = int(с["чаевые_лампорты"])
        if not с.get("ok"):
            з["не_отправлено"] += 1
            continue
        з["отправок"] += 1
        if с.get("села") is True:
            з["село"] += 1
            if isinstance(с.get("слотов_ждали"), int):
                з["слотов"].append(с["слотов_ждали"])
            if isinstance(с.get("индекс_в_блоке"), int):
                з["индексы"].append(с["индекс_в_блоке"])
            д = (с.get("место") or {}).get("доля")
            if isinstance(д, (int, float)):
                з["доли"].append(float(д))
            р = с.get("регион_лидера") or "неизвестно"
            з["регионы"][р] = з["регионы"].get(р, 0) + 1
            if isinstance(с.get("цена_sol"), (int, float)):
                з["цена_sol"] = round(з["цена_sol"] + float(с["цена_sol"]), 9)
        elif с.get("села") is False:
            з["не_село"] += 1
    из_ = {"по_отправителю": {}, "отправителей": len(по)}
    for имя, з in по.items():
        из_["по_отправителю"][имя] = {
            "отправок": з["отправок"], "село": з["село"], "не_село": з["не_село"],
            "не_отправлено": з["не_отправлено"],
            "чаевые_лампорты": з["чаевые_лампорты"],
            "медиана_слотов": _медиана(з["слотов"]),
            "медиана_индекса": _медиана(з["индексы"]),
            "медиана_доли": _медиана(з["доли"]),
            "регионы": dict(sorted(з["регионы"].items(), key=lambda кв: -кв[1])),
            "потрачено_sol": round(з["цена_sol"], 9)}
    из_["потрачено_sol"] = round(sum(в["потрачено_sol"]
                                      for в in из_["по_отправителю"].values()), 9)
    # ПОБЕДИТЕЛЬ НАЗЫВАЕТСЯ ТОЛЬКО ПРИ РАВНОМ ЧИСЛЕ ОТПРАВОК. Сравнивать медианы
    # у того, кто отправил 30 раз, и у того, кто 3, -- это не гонка.
    сел = {и: в for и, в in из_["по_отправителю"].items() if в["село"]}
    отправок = {в["отправок"] for в in из_["по_отправителю"].values()}
    если_поровну = len(отправок) == 1
    из_["поровну_отправок"] = если_поровну
    из_["победитель"] = None
    if сел and если_поровну:
        из_["победитель"] = sorted(
            сел.items(),
            key=lambda кв: (кв[1]["медиана_слотов"] if кв[1]["медиана_слотов"]
                            is not None else 1e9,
                            кв[1]["медиана_индекса"] if кв[1]["медиана_индекса"]
                            is not None else 1e9))[0][0]
    return из_


def таблица_гонки(строки: list) -> list:
    """Итог таблицей ПО ОТПРАВИТЕЛЮ -- по строке на каждого."""
    св = свод_гонки(строки)
    из_ = ["отправитель | чаевые     | отправок | село | не село | медиана слотов | "
            "медиана индекса | регионы лидера",
            "------------|------------|----------|------|---------|----------------|"
            "-----------------|---------------"]
    for имя, з in sorted(св["по_отправителю"].items()):
        регионы = ", ".join(f"{к} {v}" for к, v in (з["регионы"] or {}).items()) or "-"
        из_.append(
            f"{имя[:11]:11s} | "
            f"{(str(з['чаевые_лампорты']) if з['чаевые_лампорты'] is not None else '-'):>10s} | "
            f"{з['отправок']:>8d} | {з['село']:>4d} | {з['не_село']:>7d} | "
            f"{(str(з['медиана_слотов']) if з['медиана_слотов'] is not None else '-'):>14s} | "
            f"{(str(з['медиана_индекса']) if з['медиана_индекса'] is not None else '-'):>15s} | "
            f"{регионы}")
    return из_


def запустить(rpc_call, *, раундов: int = РАУНДОВ_ПО_УМОЛЧАНИЮ,
              отправители=ОТПРАВИТЕЛИ_ПО_УМОЛЧАНИЮ,
              ждать_с: float = ЖДАТЬ_ПОСАДКИ_С, пауза_слотов_=ПАУЗА_СЛОТОВ,
              секрет: str | None = None, отправить=None, спать=time.sleep,
              путь_реестра: str | None = None, реестр=None, минимум=None) -> dict:
    """Гонка целиком. Рубильник и потолок расхода проверяются ДО первой отправки."""
    о = {"что": "гонка отправителей", "режим": "gonka",
         "utc": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
         "кошелёк": Z.КОШЕЛЁК_ОПЫТА, "раундов": int(раундов),
         "отправители": list(отправители or ()), "why_not": None, "строки": []}
    if not включён():
        о["why_not"] = f"гонка выключена рубильником {ИМЯ_ФЛАГА} -- отправок не было"
        return о
    к = Z.кошелёк_проверен(секрет)
    if not к.get("ok"):
        о["why_not"] = к.get("why_not")
        return о
    # РЕЕСТР И МИНИМУМ -- ПАРАМЕТРАМИ, как у чаевые_отправителя Code-1. Без них
    # самопроверку пришлось бы гонять на настоящем реестре хоста, то есть она
    # проверяла бы не код, а содержимое чужого файла.
    ч = чаевые_всех(отправители, путь_реестра=путь_реестра, реестр=реестр,
                     минимум=минимум)
    о["чаевые"] = {и: {"лампорты": в.get("лампорты"), "откуда": в.get("откуда")}
                   for и, в in ч["по_отправителю"].items()}
    о["чаевые_отказы"] = ч["отказы"]
    if not ч["ok"]:
        о["why_not"] = ч["why_not"]
        return о
    п = проверить_потолок(раундов, ч["по_отправителю"])
    о.update(предел_расхода_sol=п["предел_расхода_sol"],
              цена_раунда_sol=п["цена_раунда_sol"],
              потолок_sol=п["потолок_sol"], влезает_раундов=п["влезает_раундов"])
    if not п["ok"]:
        о["why_not"] = п["why_not"]
        return о
    строки = []
    for н in range(int(раундов)):
        р = раунд_гонки(rpc_call, отправители=отправители,
                        чаевые=ч["по_отправителю"], ждать_с=ждать_с,
                        секрет=секрет, отправить=отправить, спать=спать,
                        номер=н + 1)
        о.setdefault("раунды", []).append(
            {к_: v for к_, v in р.items() if к_ != "строки"})
        строки += [с for с in (р.get("строки") or []) if с.get("ok")
                   or с.get("why_not")]
        if н + 1 < int(раундов):
            пз = пауза_слотов(rpc_call, слотов=int(пауза_слотов_), спать=спать)
            о.setdefault("паузы", []).append(пз)
    о["строки"] = строки
    о["свод"] = свод_гонки(строки)
    о["таблица"] = таблица_гонки(строки)
    return о


def печать(о: dict) -> None:
    print(f"=== гонка отправителей, кошелёк {о.get('кошелёк')} ===")
    if о.get("why_not"):
        print(f"  не сделано: {о['why_not']}")
    if о.get("цена_раунда_sol") is not None:
        print(f"  цена раунда {о['цена_раунда_sol']} SOL, {о.get('раундов')} "
              f"раундов -> {о.get('предел_расхода_sol')} SOL при потолке "
              f"{о.get('потолок_sol')} SOL (влезает {о.get('влезает_раундов')})")
    for стр in о.get("таблица") or []:
        print("  " + стр)
    св = о.get("свод") or {}
    if св:
        print(f"  потрачено {св.get('потрачено_sol')} SOL; победитель "
              f"{св.get('победитель') or 'не назван'}"
              + ("" if св.get("поровну_отправок")
                 else " (отправок не поровну -- сравнивать нельзя)"))


