def свежий_blockhash(rpc_call) -> dict:
    """Один blockhash НА ВСЕХ: гонка про отправителей, а не про срок жизни."""
    из_ = {"ok": False, "why_not": None}
    try:
        о = Z._результат(rpc_call("getLatestBlockhash",
                                   [{"commitment": "confirmed"}]))
    except Exception as exc:  # noqa: BLE001
        из_["why_not"] = f"{type(exc).__name__}: {str(exc)[:120]}"
        return из_
    зн = о.get("value") if isinstance(о, dict) and "value" in о else о
    if not isinstance(зн, dict) or not зн.get("blockhash"):
        из_["why_not"] = f"узел не отдал blockhash: {str(о)[:100]}"
        return из_
    из_.update(ok=True, blockhash=зн["blockhash"],
                lastValid=зн.get("lastValidBlockHeight"))
    return из_


def текущий_слот(rpc_call) -> dict:
    из_ = {"ok": False, "why_not": None, "слот": None}
    try:
        о = Z._результат(rpc_call("getSlot", [{"commitment": "confirmed"}]))
    except Exception as exc:  # noqa: BLE001
        из_["why_not"] = f"{type(exc).__name__}: {str(exc)[:120]}"
        return из_
    зн = о.get("value") if isinstance(о, dict) and "value" in о else о
    if not isinstance(зн, int) or isinstance(зн, bool):
        из_["why_not"] = f"узел вернул не слот: {str(о)[:100]}"
        return из_
    из_.update(ok=True, слот=int(зн))
    return из_


def место_в_блоке(rpc_call, слот, подпись: str) -> dict:
    """Индекс нашей подписи в блоке и сколько подписей всего.

    Запрос тот же, что у bloom_timing_breakdown.позиция_в_блоке: getBlock с
    transactionDetails=signatures. Своего способа тут быть не должно -- два
    способа считать одно место разошлись бы молча.
    """
    из_ = {"ok": False, "why_not": None, "индекс": None, "всего": None,
            "доля": None}
    if not isinstance(слот, int) or not подпись:
        из_["why_not"] = "нет слота или подписи"
        return из_
    try:
        о = Z._результат(rpc_call("getBlock", [int(слот), {
            "encoding": "json", "transactionDetails": "signatures",
            "rewards": False,
            "maxSupportedTransactionVersion": ПОТОЛОК_ВЕРСИИ_TX}]))
    except Exception as exc:  # noqa: BLE001
        из_["why_not"] = f"getBlock не отдался: {type(exc).__name__}"
        return из_
    подписи = (о or {}).get("signatures") if isinstance(о, dict) else None
    if not подписи:
        из_["why_not"] = "в ответе getBlock нет списка подписей"
        return из_
    try:
        и = list(подписи).index(подпись)
    except ValueError:
        из_.update(всего=len(подписи), why_not="нашей подписи в этом блоке нет")
        return из_
    из_.update(ok=True, индекс=и, всего=len(подписи),
                доля=round(и / len(подписи), 4))
    return из_


def регион_лидера(rpc_call, слот) -> dict:
    """Регион лидера слота -- функцией полосы, а не своей картой."""
    из_ = {"ok": False, "why_not": None, "регион": None, "лидер": None}
    if not isinstance(слот, int):
        из_["why_not"] = "слота нет"
        return из_
    try:
        import bloom_region_send as RS  # noqa: PLC0415

        р = RS.регион_слота(rpc_call, int(слот))
    except Exception as exc:  # noqa: BLE001
        из_["why_not"] = f"карта регионов не загружена: {type(exc).__name__}"
        return из_
    из_.update(ok=True, регион=(р or {}).get("регион") or "неизвестно",
                лидер=(р or {}).get("лидер"))
    return из_


def пауза_слотов(rpc_call, *, слотов: int = ПАУЗА_СЛОТОВ,
                  предел_с: float = ПРЕДЕЛ_ПАУЗЫ_С,
                  полл_мс: int = ПОЛЛ_ПАУЗЫ_МС, спать=time.sleep) -> dict:
    """Подождать смены слота не меньше чем на `слотов`.

    ЖДЁМ НОМЕР, А НЕ ВРЕМЯ. При заторе слот стоит дольше 400 мс, и пауза «0.8 с»
    оставила бы два раунда в одном слоте -- они соперничали бы между собой.
    """
    из_ = {"ok": False, "why_not": None, "было": None, "стало": None,
            "ждали_с": 0.0}
    н = текущий_слот(rpc_call)
    if not н.get("ok"):
        из_["why_not"] = н.get("why_not")
        return из_
    из_["было"] = н["слот"]
    т0 = time.time()
    while time.time() - т0 < float(предел_с):
        спать(max(0.01, int(полл_мс) / 1000.0))
        т = текущий_слот(rpc_call)
        if т.get("ok") and т["слот"] - н["слот"] >= int(слотов):
            из_.update(ok=True, стало=т["слот"],
                        ждали_с=round(time.time() - т0, 3))
            return из_
    из_.update(стало=(т.get("слот") if isinstance(т, dict) else None),
                ждали_с=round(time.time() - т0, 3),
                why_not=f"слот не сменился на {слотов} за {предел_с} с")
    return из_


# ------------------------------------------------------------ один раунд

def подготовить_гонку(вариант: dict, чаевые: dict, *, секрет: str | None = None,
                      кошелёк: str | None = None) -> list:
    """По одной ПОДПИСАННОЙ транзакции на отправителя, все с ОДНИМ blockhash."""
    кошелёк = кошелёк or Z.КОШЕЛЁК_ОПЫТА
    строки = []
    for имя, ч in (чаевые or {}).items():
        с = {"отправитель": имя, "чаевые_лампорты": int(ч.get("лампорты") or 0),
             "чаевые_адрес": ч.get("адрес"), "чаевые_откуда": ч.get("откуда"),
             "ok": False, "why_not": None}
        т = Z.транзакция_самоперевода(кошелёк=кошелёк,
                                       чаевые=(с["чаевые_адрес"],
                                               с["чаевые_лампорты"]))
        if not т.get("ok"):
            с["why_not"] = f"транзакция не собралась: {т.get('why_not')}"
            строки.append(с)
            continue
        п = Z.подписать_вариант(т["tx_base64"], вариант, секрет=секрет)
        if not п.get("ok"):
            с["why_not"] = f"не подписана: {п.get('why_not')}"
            строки.append(с)
            continue
        с.update(ok=True, tx_base64=п["tx_base64"], signature=п["signature"],
                 size=т.get("size"))
        строки.append(с)
    return строки


def отправить_гонкой(строки: list, *, отправить=None, таймаут: float = 5.0) -> list:
    """Все отправки ОДНОВРЕМЕННО, у каждой СВОЙ отправитель.

    Отличие от c2_zabor_s0_opyt.отправить_одновременно ровно одно: там один
    отправитель на все строки, здесь -- свой на каждую. Барьер тот же и по той же
    причине: ушедший первым получил бы фору в целый слот.
    """
    готовые = [с for с in (строки or []) if с.get("ok")]
    if not готовые:
        return list(строки or [])
    if отправить is None:
        import bloom_senders as SS  # noqa: PLC0415

        def отправить(имя, tx_base64):  # noqa: E306
            return SS.отправить_через(имя, tx_base64, таймаут=таймаут)

    барьер = threading.Barrier(len(готовые))

    def один(с: dict) -> None:
        try:
            барьер.wait(timeout=10.0)
        except Exception:  # noqa: BLE001
            pass
        т0 = time.perf_counter()
        try:
            о = отправить(с["отправитель"], с["tx_base64"])
        except Exception as exc:  # noqa: BLE001
            о = {"ok": False, "why_not": f"{type(exc).__name__}: {str(exc)[:120]}"}
        с["отправка"] = о
        с["отправка_мс"] = round((time.perf_counter() - т0) * 1000.0, 2)
        с["t_отправки"] = time.time()

    потоки = [threading.Thread(target=один, args=(с,), daemon=True)
              for с in готовые]
    for п in потоки:
        п.start()
    for п in потоки:
        п.join(timeout=таймаут + 12.0)
    return list(строки or [])


def добрать_по_цепи(rpc_call, строки: list, *, слот_отправки=None) -> list:
    """Что с каждой отправкой на цепи: слот, место в блоке, регион, деньги."""
    for с in (строки or []):
        if not с.get("ok") or not с.get("signature"):
            continue
        п = Z.посадка(rpc_call, с["signature"])
        с["посадка"] = п
        с["села"] = п.get("села")
        if not п.get("села"):
            continue
        слот = п.get("слот")
        с["слот_посадки"] = слот
        if isinstance(слот_отправки, int) and isinstance(слот, int):
            с["слотов_ждали"] = слот - слот_отправки
        м = место_в_блоке(rpc_call, слот, с["signature"])
        с["место"] = м
        с["индекс_в_блоке"] = м.get("индекс")
        с["подписей_в_блоке"] = м.get("всего")
        р = регион_лидера(rpc_call, слот)
        с["регион_лидера"] = р.get("регион")
        с["лидер"] = р.get("лидер")
        # ДЕНЬГИ -- КОМИССИЯ ПЛЮС ЧАЕВЫЕ. Комиссию называет цепь, чаевые мы
        # положили сами: складывать их надо, иначе цена отправки занижена вчетверо.
        к = п.get("комиссия")
        с["комиссия_лампорты"] = к
        if isinstance(к, int):
            с["цена_лампорты"] = int(к) + int(с.get("чаевые_лампорты") or 0)
            с["цена_sol"] = round(с["цена_лампорты"] / Z.ЛАМПОРТОВ_В_SOL, 9)
    return строки


def раунд_гонки(rpc_call, *, отправители=ОТПРАВИТЕЛИ_ПО_УМОЛЧАНИЮ,
                 чаевые=None, ждать_с: float = ЖДАТЬ_ПОСАДКИ_С,
                 секрет: str | None = None, отправить=None,
                 спать=time.sleep, номер: int = 1) -> dict:
    """Один раунд гонки целиком: подписать всех, отправить барьером, добрать."""
    из_ = {"ok": False, "why_not": None, "номер": int(номер), "строки": []}
    ч = чаевые if чаевые is not None else чаевые_всех(отправители)
    ч = ч.get("по_отправителю") if isinstance(ч, dict) and "по_отправителю" in ч else ч
    if not ч:
        из_["why_not"] = "чаевые ни одному отправителю не назначены"
        return из_
    б = свежий_blockhash(rpc_call)
    if not б.get("ok"):
        из_["why_not"] = f"blockhash: {б.get('why_not')}"
        return из_
    с0 = текущий_слот(rpc_call)
    из_["слот_отправки"] = с0.get("слот")
    вариант = {"blockhash": б["blockhash"], "lastValid": б.get("lastValid"),
               "сдвиг": None, "имя": "гонка"}
    строки = подготовить_гонку(вариант, ч, секрет=секрет)
    готовых = sum(1 for с in строки if с.get("ok"))
    если_нет = [с for с in строки if not с.get("ok")]
    из_["не_подписались"] = [{"отправитель": с.get("отправитель"),
                               "why_not": с.get("why_not")} for с in если_нет]
    if not готовых:
        из_["строки"] = строки
        из_["why_not"] = "ни одна транзакция раунда не подписалась"
        return из_
    строки = отправить_гонкой(строки, отправить=отправить)
    спать(float(ждать_с))
    строки = добрать_по_цепи(rpc_call, строки, слот_отправки=из_.get("слот_отправки"))
    for с in строки:
        с["раунд"] = int(номер)
        с["blockhash"] = б["blockhash"]
    из_.update(ok=True, строки=строки, отправлено=готовых)
    return из_


