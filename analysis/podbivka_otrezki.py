#!/usr/bin/env python3
"""Три отрезка живой полосы: до подъёма билета, подъём, после отката (задача владельца 08.10).

Рамки отрезков -- слово владельца: подъём билета включён 05.10 12:44Z, откат 06.10 17:01Z.
По каждому отрезку: по группам и по источникам с n >= 10 -- сделок, итог SOL, % на
вложенное, медиана (SOL и п.п.), доля в плюсе, итог без 5 лучших; отдельно разбивка по
посадке S+0/S+1/S+2.

«Рынок или мы»: по архиву за те же сутки -- те же источники при входе сразу после них
(без нас), п.п. при удержании группы. Если у источника в архиве тоже минус -- сменился
рынок; если в архиве плюс, а у нас минус -- дело в нашем входе.

Источники чисел: сделки -- файлы Code-1 (`data/sdelki_polosy_*`, ветка
claude/nifty-sagan-r0polg, коммит в выводе), архив -- кэш сигналов
(`podbivka_paket_kesh.py`), политика групп -- `data/podbivka/code1_sources_live.json`.
Только чтение, ничего не рекомендуется -- решает владелец.
"""
from __future__ import annotations

import argparse
import collections
import json
import os
import statistics
import sys
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import podbivka_paket_obshee as O  # noqa: E402
import podbivka_zhivye as Ж  # noqa: E402

КОРЕНЬ = O.КОРЕНЬ
П = O.П
ОТРЕЗКИ = (("до подъёма", "", "2026-10-05T12:44:00Z"),
           ("подъём", "2026-10-05T12:44:00Z", "2026-10-06T17:01:00Z"),
           ("после отката", "2026-10-06T17:01:00Z", ""))
N_МИН = 10


def свод(ряды: list) -> dict:
    """Сделок, итог, % на вложенное, медианы, в плюсе, итог без 5 лучших."""
    р = [x for x in ряды if x.get("итог") is not None]
    if not р:
        return {"n": 0, "n_всего": len(ряды)}
    итоги = [x["итог"] for x in р]
    влож = [x["вложено"] or 0.0 for x in р]
    пп = [100 * x["итог"] / x["вложено"] for x in р if x.get("вложено")]
    верх = sorted(итоги, reverse=True)
    суток = len({x["сутки"] for x in р if x["сутки"]}) or 1
    по_суткам: dict = collections.defaultdict(float)
    for x in р:
        if x["сутки"]:
            по_суткам[x["сутки"]] += x["итог"]
    return {"n": len(р), "n_всего": len(ряды), "суток": суток,
            "итог_sol": round(sum(итоги), 6),
            "вложено_sol": round(sum(влож), 6),
            "процент_на_вложенное": round(100 * sum(итоги) / sum(влож), 2) if sum(влож) else None,
            "медиана_sol": round(statistics.median(итоги), 6),
            "медиана_пп": round(statistics.median(пп), 2) if пп else None,
            "в_плюсе": round(100 * sum(1 for x in итоги if x > 0) / len(итоги)),
            "итог_без_5_лучших_sol": round(sum(верх[5:]), 6) if len(верх) > 5 else None,
            "sol_в_сутки": round(sum(итоги) / суток, 6),
            "худшие_сутки_sol": round(min(по_суткам.values()), 6) if по_суткам else None,
            "билет_медиана": round(statistics.median([x["вложено"] for x in р if x.get("вложено")]), 4)
            if any(x.get("вложено") for x in р) else None}


def по_посадке(ряды: list) -> dict:
    из_: dict = {}
    for s in (0, 1, 2):
        часть = [x for x in ряды if x.get("s_plus") == s]
        if часть:
            из_[f"S+{s}"] = свод(часть)
    прочее = [x for x in ряды if x.get("s_plus") not in (0, 1, 2)]
    if прочее:
        из_["без посадки"] = свод(прочее)
    return из_


def архив_по_источникам(истоки: set, сутки_по_отрезкам: dict, выход: int, места=("S0_дно", "S1")) -> dict:
    """«Рынок или мы»: п.п. тех же источников в архиве за те же сутки, вход сразу за ними."""
    if not O.КЭШ.exists():
        return {"нет_кэша": str(O.КЭШ)}
    нужные_сутки = {д for дни in сутки_по_отрезкам.values() for д in дни}
    собрано: dict = collections.defaultdict(lambda: collections.defaultdict(list))
    счёт = collections.Counter()
    for р in O.сигналы(фильтр=lambda r: r.get("ист") in истоки):
        счёт["источник_в_списке"] += 1
        д = O.сутки(р)
        if д not in нужные_сутки:
            счёт["сутки_вне"] += 1
            continue
        if р.get("quoteMint") != O.WSOL:
            счёт["не_wsol"] += 1
            continue
        if not р.get("первая"):
            счёт["не_первая"] += 1
            continue
        строка = {"сутки": д, "sol": р.get("sol"), "резерв_sol": р.get("резерв_sol"), "пул": р.get("пул")}
        есть = False
        for м in места:
            v = O.пп(р, 0.1, м, выход)
            строка[м] = v
            есть = есть or v is not None
        if not есть:
            счёт["нет_состояний"] += 1
            continue
        счёт["в_счёте"] += 1
        собрано[р["ист"]][д].append(строка)
    из_: dict = {"счёт": dict(счёт), "по_источникам": {}}
    for ист, по_суткам in собрано.items():
        по_отрезкам = {}
        for имя, дни in сутки_по_отрезкам.items():
            ряды = [x for д in дни for x in по_суткам.get(д, [])]
            if not ряды:
                continue
            по_отрезкам[имя] = {"n": len(ряды), "суток": len({x["сутки"] for x in ряды})}
            for м in места:
                v = [x[м] for x in ряды if x.get(м) is not None]
                по_отрезкам[имя][м] = {"n": len(v), "медиана_пп": round(statistics.median(v), 2),
                                       "в_плюсе": round(100 * sum(1 for y in v if y > 0) / len(v))} if v else None
        if по_отрезкам:
            из_["по_источникам"][ист] = по_отрезкам
    return из_


def ф(v, формат="+.4f"):
    return "—" if v is None else format(v, формат)


def main() -> int:
    import podbivka_run as R  # noqa: PLC0415
    р = argparse.ArgumentParser()
    р.add_argument("--metka", default=time.strftime("%Y-%m-%d", time.gmtime()))
    р.add_argument("--s", default="2026-09-27T00:00:00Z")
    р.add_argument("--vyhod", type=int, default=O.ВЫХОД_ГРУППЫ)
    р.add_argument("--bez-arhiva", action="store_true")
    а = р.parse_args()

    все = Ж.сделки(s=а.s)
    по_отрезкам: dict = {}
    for имя, с_, до_ in ОТРЕЗКИ:
        ряды = [x for x in все if (not с_ or x["utc"] >= с_) and (not до_ or x["utc"] < до_)]
        по_отрезкам[имя] = ряды

    итог: dict = {
        "что": "три отрезка живой полосы: до подъёма билета, подъём, после отката",
        "рамки": {имя: {"с": с_ or все[0]["utc"], "до": до_ or все[-1]["utc"]} for имя, с_, до_ in ОТРЕЗКИ},
        "источник_чисел": {"сделки": "data/sdelki_polosy_* ветки claude/nifty-sagan-r0polg",
                           "коммит_code1": os.environ.get("PODB_C1_REV", ""),
                           "кэш_архива": str(O.КЭШ),
                           "политика": "data/podbivka/code1_sources_live.json"},
        "окно_сделок": {"с": все[0]["utc"], "до": все[-1]["utc"], "всего": len(все),
                        "по_цепи": sum(1 for x in все if x["итог_откуда"] == "цепь"),
                        "из_полей": sum(1 for x in все if x["итог_откуда"] == "из полей"),
                        "без_итога": sum(1 for x in все if x["итог"] is None)},
        "удержание_слотов": а.vyhod, "отрезки": {}}

    for имя, ряды in по_отрезкам.items():
        о = {"всего": свод(ряды), "по_посадке": по_посадке(ряды), "по_группам": {}, "по_источникам": {}}
        for г in sorted({x["group"] for x in ряды if x.get("group")}):
            часть = [x for x in ряды if x.get("group") == г]
            о["по_группам"][г] = свод(часть) | {"по_посадке": по_посадке(часть)}
        счёт_ист = collections.Counter(x["source"] for x in ряды if x.get("source"))
        for a, n in счёт_ист.most_common():
            if n >= N_МИН:
                часть = [x for x in ряды if x.get("source") == a]
                о["по_источникам"][a] = свод(часть) | {
                    "имя": next((x.get("source_name") for x in часть if x.get("source_name")), None),
                    "группы": sorted({x["group"] for x in часть if x.get("group")}),
                    "по_посадке": по_посадке(часть)}
        итог["отрезки"][имя] = о

    # источники, у которых есть n >= N_МИН хотя бы в одном отрезке -- для «рынок или мы»
    истоки = {a for о in итог["отрезки"].values() for a in о["по_источникам"]}
    сутки_по_отрезкам = {имя: sorted({x["сутки"] for x in ряды if x["сутки"]})
                         for имя, ряды in по_отрезкам.items()}
    итог["сутки_по_отрезкам"] = сутки_по_отрезкам
    итог["рынок_или_мы"] = ({} if а.bez_arhiva
                            else архив_по_источникам(истоки, сутки_по_отрезкам, а.vyhod))

    # держится во всех трёх отрезках: итог > 0 и медиана > 0 там, где сделок хватает
    держатся = []
    for a in sorted(истоки):
        строки = {}
        for имя in итог["отрезки"]:
            с = итог["отрезки"][имя]["по_источникам"].get(a)
            строки[имя] = с
        если_есть = [имя for имя, с in строки.items() if с and с.get("n", 0) >= N_МИН]
        плюс = [имя for имя in если_есть if строки[имя]["итог_sol"] > 0]
        держатся.append({"ист": a, "отрезков_с_числом": len(если_есть), "в_плюсе_отрезков": len(плюс),
                         "во_всех_трёх": len(если_есть) == 3 and len(плюс) == 3,
                         "по_отрезкам": {имя: (строки[имя]["итог_sol"] if строки[имя] else None)
                                         for имя in итог["отрезки"]}})
    итог["держатся"] = sorted(держатся, key=lambda x: (-x["в_плюсе_отрезков"], -x["отрезков_с_числом"]))

    out = П / f"otrezki_{а.metka}.json"
    out.write_text(json.dumps(итог, ensure_ascii=False, indent=1), encoding="utf-8")
    R.записано(out)

    # ---- страница
    md = [f"# Три отрезка живой полосы ({а.metka})", "",
          f"Сделки -- по цепи, файлы Code-1 `data/sdelki_polosy_*` (ветка claude/nifty-sagan-r0polg"
          f"{', коммит ' + os.environ['PODB_C1_REV'][:8] if os.environ.get('PODB_C1_REV') else ''}). "
          f"Окно {итог['окно_сделок']['с']} .. {итог['окно_сделок']['до']}: сделок "
          f"{итог['окно_сделок']['всего']}, из них итог по цепи {итог['окно_сделок']['по_цепи']}, "
          f"из полей {итог['окно_сделок']['из_полей']}, без итога "
          f"{итог['окно_сделок']['без_итога']}. Вложенное -- `size_sol` (сколько SOL реально ушло "
          f"в покупку), не билет группы. Рамки отрезков -- слово владельца: подъём 05.10 12:44Z, "
          f"откат 06.10 17:01Z.", ""]
    for имя, с_, до_ in ОТРЕЗКИ:
        о = итог["отрезки"][имя]
        в = о["всего"]
        md += [f"## Отрезок «{имя}» ({с_ or итог['окно_сделок']['с']} .. {до_ or итог['окно_сделок']['до']})", "",
               f"Сделок с итогом {в.get('n', 0)} из {в.get('n_всего', 0)}, суток {в.get('суток')}, "
               f"итог **{ф(в.get('итог_sol'))} SOL**, на вложенное {ф(в.get('процент_на_вложенное'), '+.2f')} %, "
               f"медиана {ф(в.get('медиана_sol'))} SOL ({ф(в.get('медиана_пп'), '+.2f')} п.п.), "
               f"в плюсе {в.get('в_плюсе')} %, без 5 лучших {ф(в.get('итог_без_5_лучших_sol'))} SOL, "
               f"{ф(в.get('sol_в_сутки'))} SOL в сутки, худшие сутки {ф(в.get('худшие_сутки_sol'))} SOL.", "",
               "| группа | сделок | билет медиана | итог SOL | % на вложенное | медиана SOL | медиана п.п. "
               "| в плюсе | без 5 лучших | SOL/сутки | худшие сутки |", "|---|---|---|---|---|---|---|---|---|---|---|"]
        for г, с in sorted(о["по_группам"].items(), key=lambda kv: -(kv[1].get("итог_sol") or 0)):
            md.append(f"| {г} | {с.get('n', 0)} | {ф(с.get('билет_медиана'), '.3f')} | {ф(с.get('итог_sol'))} "
                      f"| {ф(с.get('процент_на_вложенное'), '+.2f')} | {ф(с.get('медиана_sol'))} "
                      f"| {ф(с.get('медиана_пп'), '+.2f')} | {с.get('в_плюсе')} % "
                      f"| {ф(с.get('итог_без_5_лучших_sol'))} | {ф(с.get('sol_в_сутки'))} "
                      f"| {ф(с.get('худшие_сутки_sol'))} |")
        md += ["", "Посадка: " + ", ".join(
            f"{к} -- сделок {v.get('n', 0)}, итог {ф(v.get('итог_sol'))} SOL, медиана "
            f"{ф(v.get('медиана_пп'), '+.2f')} п.п." for к, v in о["по_посадке"].items()) + ".", ""]
        if о["по_источникам"]:
            md += [f"Источники с n >= {N_МИН}:", "",
                   "| источник | имя | группы | сделок | итог SOL | % на вложенное | медиана SOL "
                   "| медиана п.п. | в плюсе | без 5 лучших |", "|---|---|---|---|---|---|---|---|---|---|"]
            for a, с in sorted(о["по_источникам"].items(), key=lambda kv: -(kv[1].get("итог_sol") or 0)):
                md.append(f"| `{a[:8]}` | {с.get('имя') or '—'} | {', '.join(с.get('группы') or []) or '—'} "
                          f"| {с.get('n', 0)} | {ф(с.get('итог_sol'))} "
                          f"| {ф(с.get('процент_на_вложенное'), '+.2f')} | {ф(с.get('медиана_sol'))} "
                          f"| {ф(с.get('медиана_пп'), '+.2f')} | {с.get('в_плюсе')} % "
                          f"| {ф(с.get('итог_без_5_лучших_sol'))} |")
            md.append("")

    рм = итог.get("рынок_или_мы") or {}
    md += ["## Рынок или мы", ""]
    if not рм or рм.get("нет_кэша"):
        md += [f"Кэша архива нет ({рм.get('нет_кэша', '—')}), раздел не посчитан.", ""]
    else:
        md += [f"По архиву за те же сутки, вход сразу за источником (S0_дно -- конец его слота, "
               f"S+1 -- следующий слот), билет 0.1 SOL, удержание {а.vyhod} слотов. В счёт пошло "
               f"{рм['счёт'].get('в_счёте', 0)} сигналов этих источников.", "",
               "| источник | отрезок | сигналов | медиана п.п. S0_дно | в плюсе | медиана п.п. S+1 "
               "| в плюсе | наш итог SOL | наша медиана п.п. |", "|---|---|---|---|---|---|---|---|---|"]
        for a in sorted(рм.get("по_источникам", {})):
            for имя in итог["отрезки"]:
                v = рм["по_источникам"][a].get(имя)
                наш = итог["отрезки"][имя]["по_источникам"].get(a)
                if not v and not наш:
                    continue
                s0 = (v or {}).get("S0_дно") or {}
                s1 = (v or {}).get("S1") or {}
                md.append(f"| `{a[:8]}` | {имя} | {(v or {}).get('n', 0)} "
                          f"| {ф(s0.get('медиана_пп'), '+.2f')} | {s0.get('в_плюсе', '—')} "
                          f"| {ф(s1.get('медиана_пп'), '+.2f')} | {s1.get('в_плюсе', '—')} "
                          f"| {ф((наш or {}).get('итог_sol'))} | {ф((наш or {}).get('медиана_пп'), '+.2f')} |")
        md.append("")

    md += ["## Держатся во всех трёх отрезках", "",
           "| источник | отрезков с n >= 10 | из них в плюсе | до подъёма | подъём | после отката |",
           "|---|---|---|---|---|---|"]
    for d in итог["держатся"]:
        md.append(f"| `{d['ист'][:8]}` | {d['отрезков_с_числом']} | {d['в_плюсе_отрезков']} | "
                  + " | ".join(ф(d["по_отрезкам"].get(имя)) for имя in итог["отрезки"]) + " |")
    md += ["", "Ничего не меняется и не рекомендуется -- решает владелец.", ""]
    стр = КОРЕНЬ / "docs" / f"podbivka_{а.metka}_otrezki.md"
    стр.write_text("\n".join(md) + "\n", encoding="utf-8")
    R.записано(стр)
    print(f"{стр.name}: сделок {len(все)}, " + ", ".join(
        f"{имя} n={итог['отрезки'][имя]['всего'].get('n', 0)} итог="
        f"{итог['отрезки'][имя]['всего'].get('итог_sol')}" for имя, _, _ in ОТРЕЗКИ), flush=True)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
