def окно(с: dict, f: str) -> bool:
    """Сутки файла без первого «разгонного» часа -- как в отборе cand1 / cand2."""
    м = re.search(r"\d{4}-\d{2}-\d{2}T\d{2}", Path(f).name)
    if not м:
        return False
    d0 = calendar.timegm(time.strptime(м.group(0), "%Y-%m-%dT%H")) + 3600
    return d0 <= K.ts(с) < d0 + 86400


def ключ(билет: float, выход: int = 108) -> str:
    return f"S0_дно|{билет:g}|{выход}"


def пп(с: dict, билет: float, выход: int = 108):
    return ((с.get("модель") or {}).get("пп") or {}).get(ключ(билет, выход))


def в_ячейке(с: dict, билет: float) -> bool:
    """Ячейка правила кандидатов, но п.п. -- по билету группы."""
    м = с.get("модель") or {}
