#!/usr/bin/env python3
"""Правило 14: порог размера покупки источника = билет группы. Офлайн, по готовому архиву porog14_*.

Зачем (слово владельца 02.10): порог размера покупки источника был 2.0 SOL для всех групп (лидеру 3) --
это поле `min_target_sol` политики группы у Code-1. Правило 14 ставит его равным билету группы. Проверка
числом: что даёт наш вход по корзинам размера покупки источника, в том числе НИЖЕ прежнего порога 2 SOL.

Вход: data/podbivka/arhiv_den/porog14_*T16.json.gz -- тот же суточный проход архива, что у cand1 / cand2
(вход «конец слота» S0_дно, окно 160 слотов, правило сигнала pyg7 с --okno-dokupki 1800, котировка не только
SOL), но с порогом сигнала 0.01 SOL вместо 2 и билетами модели 0.1 / 0.3 / 0.5 -- по билетам живых групп.
Адреса -- data/podbivka/porog14_adresa.json (43 адреса живых групп и билет каждой).
Выход: docs/podbivka_2026-10-02_porog_razmera.md и data/podbivka/porog_razmera.json.
"""
