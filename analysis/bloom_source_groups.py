def группа(адрес: str | None, путь: str | None = None) -> str:
    """Группа адреса. Незнакомый адрес -- off: не торгуем ничем.

    Слово владельца 27.09 (п.1а). Раньше здесь был bloom_lane, и адрес,
    появившийся в задачах DBot, начинал торговаться без строки в файле.
    """
    if not адрес:
        return ГРУППА_ПО_УМОЛЧАНИЮ
    return (загрузить(путь)["по_адресу"].get(адрес) or ГРУППА_ПО_УМОЛЧАНИЮ)


def метка_адреса(адрес: str | None, путь: str | None = None) -> dict:
    """Метки адреса из файла: flipper, имя, откуда пришёл.

    Отдельно от политики группы: признак skip_flippers включает ДЕЙСТВИЕ, а
    помечен перекупщиком конкретный адрес, и метка стоит у него.
    """
    if not адрес:
        return {}
    return dict(загрузить(путь).get("метки", {}).get(адрес) or {})


def перекупщик(адрес: str | None, путь: str | None = None) -> bool:
    """Помечен ли адрес перекупщиком (доля "продал в окне" выше 30 %)."""
    return bool(метка_адреса(адрес, путь).get("flipper"))


def политика(имя_группы: str | None, путь: str | None = None) -> dict:
    """Что группе можно. Неизвестной группе -- политика off (не торгует)."""
    п = загрузить(путь)["политики"].get(имя_группы or "")
    return dict(п) if п else dict(ПОЛИТИКА_ПО_УМОЛЧАНИЮ)


def адреса_всех_групп(путь: str | None = None) -> dict:
    """{адрес: группа} -- то, на что детектор обязан подписаться сверх DBot."""
    return dict(загрузить(путь)["по_адресу"])


def адреса_без_подписки(путь: str | None = None) -> set:
    """Адреса групп с subscribe=false -- их НЕ подписываем живьём.

    Возвращается множество адресов, а не имён групп: вызывающему нужно решить
    по КАЖДОМУ адресу, и пересчитывать группу на каждом сигнале незачем.
    """
    д = загрузить(путь)
    выкл = {имя for имя, п in д["политики"].items() if not п.get("subscribe", True)}
    if not выкл:
        return set()
    return {а for а, г in д["по_адресу"].items() if г in выкл}


def свод(путь: str | None = None) -> dict:
    """Сколько адресов в каждой группе -- для признака жизни и доклада."""
    д = загрузить(путь)
    счёт: dict = {}
    for _, г in д["по_адресу"].items():
        счёт[г] = счёт.get(г, 0) + 1
    return {"file": д.get("file"), "why_not": д.get("why_not"),
            # ХЭШ И mtime -- В КАЖДУЮ СТРОКУ ПРИЗНАКА ЖИЗНИ (слово владельца
            # 27.09): по ним сверяется, что в бою лежит ровно присланный файл.
            "hash": д.get("hash"), "mtime_utc": д.get("mtime_utc"),
            "alarm": д.get("тревога"),
            "by_group": счёт, "policies": д["политики"]}


