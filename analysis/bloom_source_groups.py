def _путь(путь: str | None = None) -> Path:
    п = Path(путь or файл())
    if п.exists():
        return п
    рядом = Path(__file__).resolve().parent.parent / (путь or файл())
    return рядом if рядом.exists() else п


def _метка_файла(п: Path) -> tuple:
    """(путь, mtime_ns, размер) -- по ней видно, что файл переписали."""
    try:
        с = п.stat()
        return (str(п), с.st_mtime_ns, с.st_size)
    except OSError:
        return (str(п), None, None)


def _хэш_файла(п: Path) -> str | None:
    """Первые 12 знаков sha256 содержимого. Для строки признака жизни.

    Владелец 27.09: "mtime и hash файла в каждой строке heartbeat" -- чтобы
    сверить, что в бою лежит ровно присланный файл, а не похожий.
    """
    try:
        return hashlib.sha256(п.read_bytes()).hexdigest()[:12]
    except OSError:
        return None


def записать(данные: dict, путь: str | None = None) -> dict:
    """АТОМАРНАЯ запись файла групп: tmp в том же каталоге -> fsync -> rename.

    Почему не обычная запись (слово владельца 27.09, п.1а). Файл читает живая
    служба, и читает она его на ходу. Обычная запись оставляет окно, в котором
    файл оборван на середине: служба прочитает половину, разбор упадёт -- а
    политика групп это деньги. rename в пределах каталога атомарен, поэтому
    служба видит либо старый файл целиком, либо новый целиком.
    """
    п = _путь(путь)
    текст = json.dumps(данные, ensure_ascii=False, indent=1) + "\n"
    вр = None
    try:
        фд, вр = tempfile.mkstemp(dir=str(п.parent), prefix=п.name + ".", suffix=".tmp")
        with os.fdopen(фд, "w", encoding="utf-8") as ф:
            ф.write(текст)
            ф.flush()
            os.fsync(ф.fileno())
        os.replace(вр, п)
        вр = None
        # Каталог тоже синхронизируем: без этого rename может не выжить после
        # отключения питания, и файла не станет вовсе.
        try:
            д = os.open(str(п.parent), os.O_RDONLY)
            try:
                os.fsync(д)
            finally:
                os.close(д)
        except OSError:
            pass
    except OSError as exc:
        if вр and os.path.exists(вр):
            try:
                os.unlink(вр)
            except OSError:
                pass
        return {"ok": False, "why_not": f"{type(exc).__name__}: {str(exc)[:160]}"}
    return {"ok": True, "file": str(п), "bytes": len(текст.encode("utf-8")),
            "hash": _хэш_файла(п)}


def загрузить(путь: str | None = None, *, заново: bool = False) -> dict:
    """{"по_адресу": {адрес: группа}, "политики": {...}, "why_not": ...}.

    ПЕРЕЧИТЫВАЕТСЯ ПО mtime (слово владельца 27.09, п.1а): кэш снимается вместе
    с меткой файла (путь, mtime_ns, размер), и как только файл переписали --
    политика читается заново, без перезапуска службы.

    ОШИБКА РАЗБОРА НЕ ОБНУЛЯЕТ ПОЛИТИКУ. Пустая политика -- это "каждый адрес
    off", то есть остановка торговли из-за одной запятой. Остаётся последняя
    хорошо прочитанная, а в отчёт кладётся текст тревоги (тревога), который
    служба отправляет в Telegram.
    """
    global _КЭШ, _МЕТКА, _ПОСЛЕДНИЙ_ХОРОШИЙ  # noqa: PLW0603
    п = _путь(путь)
    метка = _метка_файла(п)
    if (_КЭШ is not None and not заново and путь is None and _МЕТКА == метка):
        return _КЭШ
    из_ = {"по_адресу": {}, "политики": {}, "метки": {}, "why_not": None,
            "тревога": None, "file": None, "hash": None, "mtime_utc": None,
            "mtime_ns": метка[1]}

    def _запомнить(готовое: dict) -> dict:
        global _КЭШ, _МЕТКА  # noqa: PLW0603
        if путь is None:
            _КЭШ, _МЕТКА = готовое, метка
        return готовое

    def _откат(почему: str) -> dict:
        """Остаётся прежняя политика, а причина названа словами."""
        if _ПОСЛЕДНИЙ_ХОРОШИЙ:
            назад = dict(_ПОСЛЕДНИЙ_ХОРОШИЙ)
            назад["why_not"] = почему + " -- осталась прежняя политика"
            назад["тревога"] = назад["why_not"]
            return _запомнить(назад)
        из_["why_not"] = почему + " -- политики нет, все адреса off"
        из_["тревога"] = из_["why_not"]
        return _запомнить(из_)

    if not п.exists():
        return _откат(f"файла групп {п} нет")
    try:
        д = json.loads(п.read_text(encoding="utf-8"))
        if not isinstance(д, dict) or not isinstance(д.get("groups"), dict):
            raise ValueError("в файле нет раздела groups")
    except Exception as exc:  # noqa: BLE001
        return _откат(f"файл групп не прочитан ({type(exc).__name__}: "
                       f"{str(exc)[:120]})")
    из_["file"] = str(п)
    из_["hash"] = _хэш_файла(п)
    if метка[1]:
        из_["mtime_utc"] = time.strftime("%Y-%m-%dT%H:%M:%SZ",
                                          time.gmtime(метка[1] / 1e9))
    for имя, г in (д.get("groups") or {}).items():
        г = г or {}
        из_["политики"][имя] = {
            "lane_sol": г.get("lane_sol"),
            "bloom_trades": bool(г.get("bloom_trades")),
            # Поля нет -- полоса торгует. Явный False выключает её по группе.
            "lane_trades": (True if г.get("lane_trades") is None
                            else bool(г.get("lane_trades"))),
            "bloom_sol": г.get("bloom_sol"),
            "fanout": bool(г.get("fanout")),
            "day_cap_sol": г.get("day_cap_sol"),
            "stop_loss_sol": г.get("stop_loss_sol"),
            "min_target_sol": г.get("min_target_sol"),
            "lane_open_max": г.get("lane_open_max"),
            "lane_pools": г.get("lane_pools"),
            # Маршрут покупки полосы и порог налога маршрута -- поля 27.09.
            # Читаются как есть: нормализацию делает читатель полосы, а не
            # загрузчик, чтобы в файле было видно ровно то, что записали.
            "lane_route": г.get("lane_route"),
            "lane_route_tax_bps": г.get("lane_route_tax_bps"),
            # ---- ПОЛЯ ФИНАЛЬНОГО ПЛАНА 27.09 (п.1в) ----
            "max_slots_from_source": г.get("max_slots_from_source"),
            "skip_flippers": bool(г.get("skip_flippers")),
            "allow_taxed_route": г.get("allow_taxed_route"),
            "slippage": г.get("slippage"),
            "slippage_thin_pool": г.get("slippage_thin_pool"),
            "thin_pool_below_sol": г.get("thin_pool_below_sol"),
            "min_pool_sol_reserve": г.get("min_pool_sol_reserve"),
            # hold_slots: поля нет -- 72 (слово владельца). Ноль и минус
            # значили бы "продать немедленно", поэтому не принимаются.
            "hold_slots": (float(г["hold_slots"])
                            if isinstance(г.get("hold_slots"), (int, float))
                            and float(г["hold_slots"]) > 0
                            else HOLD_SLOTS_ПО_УМОЛЧАНИЮ),
            # Мелкая покупка источника -- свой таймер. Ноль и минус не
            # принимаются по той же причине, что и у hold_slots.
            "hold_slots_small": (float(г["hold_slots_small"])
                                  if isinstance(г.get("hold_slots_small"),
                                                (int, float))
                                  and float(г["hold_slots_small"]) > 0
                                  else None),
            "hold_slots_small_below_sol": (
                float(г["hold_slots_small_below_sol"])
                if isinstance(г.get("hold_slots_small_below_sol"), (int, float))
                and float(г["hold_slots_small_below_sol"]) > 0
                else None),
        }
        # ОДНО ЧИСЛО ПОД ДВУМЯ ИМЕНАМИ. lane_size -- имя финального плана,
        # lane_sol -- прежнее; читатели денежного пути спрашивают lane_sol, и
        # менять их всех ради имени значило бы трогать денежный путь без нужды.
        размер = (г.get("lane_size") if г.get("lane_size") is not None
                   else г.get("lane_sol"))
        из_["политики"][имя]["lane_size"] = размер
        из_["политики"][имя]["lane_sol"] = размер
        # Адреса лежат двумя видами: словарь {адрес: партия} и списки
        # объектов с полем address. Оба читаем, третий вид не изобретаем.
        адреса = г.get("addresses")
        if isinstance(адреса, dict):
            for а, п_ in адреса.items():
                из_["по_адресу"][а] = имя
                if isinstance(п_, dict):
                    из_["метки"][а] = dict(п_)
        elif isinstance(адреса, list):
            for з in адреса:
                а = з.get("address") if isinstance(з, dict) else з
                if а:
                    из_["по_адресу"][а] = имя
                    if isinstance(з, dict):
                        из_["метки"][а] = {k: v for k, v in з.items()
                                            if k != "address"}
        for поле in ("by_signal", "snipers"):
            for з in г.get(поле) or []:
                а = з.get("address") if isinstance(з, dict) else з
                if а:
                    из_["по_адресу"][а] = имя
                    if isinstance(з, dict):
                        из_["метки"][а] = {k: v for k, v in з.items()
                                            if k != "address"}
    _ПОСЛЕДНИЙ_ХОРОШИЙ = dict(из_)
    return _запомнить(из_)


def группа(адрес: str | None, путь: str | None = None) -> str:
    """Группа адреса. Незнакомый адрес -- off: не торгуем ничем.

    Слово владельца 27.09 (п.1а). Раньше здесь был bloom_lane, и адрес,
    появившийся в задачах DBot, начинал торговаться без строки в файле.
    """
    if not адрес:
        return ГРУППА_ПО_УМОЛЧАНИЮ
    return (загрузить(путь)["по_адресу"].get(адрес) or ГРУППА_ПО_УМОЛЧАНИЮ)


def метка_адреса(адрес: str | None, путь: str | None = None) -> dict:
    """Метки адреса из файла: flipper, имя, откуда пришёл.

    Отдельно от политики группы: признак skip_flippers включает ДЕЙСТВИЕ, а
    помечен перекупщиком конкретный адрес, и метка стоит у него.
    """
    if not адрес:
        return {}
    return dict(загрузить(путь).get("метки", {}).get(адрес) or {})


def перекупщик(адрес: str | None, путь: str | None = None) -> bool:
    """Помечен ли адрес перекупщиком (доля "продал в окне" выше 30 %)."""
    return bool(метка_адреса(адрес, путь).get("flipper"))


def политика(имя_группы: str | None, путь: str | None = None) -> dict:
    """Что группе можно. Неизвестной группе -- политика off (не торгует)."""
    п = загрузить(путь)["политики"].get(имя_группы or "")
    return dict(п) if п else dict(ПОЛИТИКА_ПО_УМОЛЧАНИЮ)


def адреса_всех_групп(путь: str | None = None) -> dict:
    """{адрес: группа} -- то, на что детектор обязан подписаться сверх DBot."""
    return dict(загрузить(путь)["по_адресу"])


def свод(путь: str | None = None) -> dict:
    """Сколько адресов в каждой группе -- для признака жизни и доклада."""
    д = загрузить(путь)
    счёт: dict = {}
    for _, г in д["по_адресу"].items():
        счёт[г] = счёт.get(г, 0) + 1
    return {"file": д.get("file"), "why_not": д.get("why_not"),
            # ХЭШ И mtime -- В КАЖДУЮ СТРОКУ ПРИЗНАКА ЖИЗНИ (слово владельца
            # 27.09): по ним сверяется, что в бою лежит ровно присланный файл.
            "hash": д.get("hash"), "mtime_utc": д.get("mtime_utc"),
            "alarm": д.get("тревога"),
            "by_group": счёт, "policies": д["политики"]}


