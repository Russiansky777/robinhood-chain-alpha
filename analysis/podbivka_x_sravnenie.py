#!/usr/bin/env python3
"""Первый пост в X против пути цены: пункт 1 проверки (описательно, по стандарту позже).

Складывает две вещи, уже посчитанные: выборку токенов (podbivka_x_vyborka.py -- метка
создания, пик внутри окна производной, волна первых секунд) и упоминания из X
(podbivka_x_upominania.py -- время первого поста, постов в первый час, подписчики).

Считает по группам: у скольких токенов нашёлся хоть один пост, у скольких первый пост
РАНЬШЕ пика и РАНЬШЕ первой сделки, медиану задержки «пост минус создание».

ДВЕ ГРАНИЦЫ ВМЕСТО ОДНОЙ ЦИФРЫ. Пик в производной лежит в СЛОТАХ от создания, а длина
слота в проекте мерилась и 0.226 с (замер Code-1 по выгрузке), и ~0.4 с (страницы
lane_s0). Поэтому доля «пост раньше пика» считается при обеих длинах -- как интервал, а
не как одно число. Отдельно сказано: пик взят ВНУТРИ окна производной (230 слотов у
кривых, 1121 у переехавших), настоящий пик может быть позже, значит доля «раньше пика» --
нижняя граница.

Первая сделка: если в блоке создания была покупка -- это само создание; иначе первая
непустая корзина волны (5/15/30/60 с) даёт верхнюю оценку её времени.

Только чтение. Выход: data/podbivka/x_sravnenie<метка>.json.
"""
from __future__ import annotations

import argparse
import collections
import json
import statistics as st
import time
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parent.parent
П = КОРЕНЬ / "data" / "podbivka"
ДЛИНЫ_СЛОТА = (0.226, 0.4)
КОРЗИНЫ_ВОЛНЫ = ("5с", "15с", "30с", "60с")


def мс(метка: str):
    """Метка поста из Apify -> unix-мс. Форматы у акторов разные, берём что есть."""
    if not метка:
        return None
    м = str(метка)
    for ф in ("%Y-%m-%dT%H:%M:%S.%fZ", "%Y-%m-%dT%H:%M:%SZ", "%Y-%m-%d %H:%M:%S%z",
              "%a %b %d %H:%M:%S %z %Y", "%Y-%m-%dT%H:%M:%S%z"):
        try:
            т = time.strptime(м[:26] if "." in м and ф.endswith("%fZ") else м, ф)
        except ValueError:
            continue
        return int(time.mktime(т) * 1000)
    try:                      # вдруг уже число
        v = float(м)
        return int(v * 1000) if v < 1e12 else int(v)
    except ValueError:
        return None


def первая_сделка_с(р: dict):
    """Верхняя оценка времени первой сделки, секунд от создания."""
    вб = р.get("в_блоке_создания") or {}
    if (вб.get("покупок") or 0) > 0:
        return 0.0
    в = р.get("волна") or {}
    for к in КОРЗИНЫ_ВОЛНЫ:
        if ((в.get(к) or {}).get("покупок") or 0) > 0:
            return float(к.rstrip("с"))
    return None


def главное(а) -> int:
    выб = json.loads(Path(а.vyborka).read_text(encoding="utf-8"))
    упом = json.loads(Path(а.upominania).read_text(encoding="utf-8"))
    по_минту = {р["минт"]: р for р in выб["ряды"]}
    группы: dict = collections.defaultdict(lambda: {
        "токенов": 0, "с_постом": 0, "раньше_пика": {str(д): 0 for д in ДЛИНЫ_СЛОТА},
        "пик_известен": 0, "раньше_первой_сделки": 0, "первая_сделка_известна": 0,
        "задержки_с": [], "подписчики": [], "постов_в_час": [], "постов_всего": []})
    ряды = []
    for у in упом["ряды"]:
        р = по_минту.get(у["минт"])
        if not р:
            continue
        к = группы[у["группа"]]
        к["токенов"] += 1
        т_созд = р.get("ts")
        т_пост = мс(у.get("первый_пост_utc"))
        пик_слотов = ((р.get("пик") or {}).get("слотов"))
        пс = первая_сделка_с(р)
        ряд = {"минт": у["минт"], "группа": у["группа"], "сутки": у["сутки"],
               "создание_ts": т_созд, "первый_пост_ts": т_пост,
               "постов_всего": у.get("постов_всего"),
               "постов_в_первый_час": у.get("постов_в_первый_час"),
               "подписчиков_автора": у.get("подписчиков_автора"),
               "пик_слотов": пик_слотов, "первая_сделка_с": пс,
               "окно_слотов": р.get("окно_слотов")}
        if т_пост and т_созд:
            задержка = (т_пост - т_созд) / 1000.0
            ряд["пост_минус_создание_с"] = round(задержка, 1)
            к["с_постом"] += 1
            к["задержки_с"].append(задержка)
            if у.get("подписчиков_автора") is not None:
                к["подписчики"].append(у["подписчиков_автора"])
            к["постов_в_час"].append(у.get("постов_в_первый_час") or 0)
            к["постов_всего"].append(у.get("постов_всего") or 0)
            if пик_слотов is not None:
                к["пик_известен"] += 1
                for д in ДЛИНЫ_СЛОТА:
                    ряд[f"пик_с_при_{д}"] = round(пик_слотов * д, 1)
                    if задержка < пик_слотов * д:
                        к["раньше_пика"][str(д)] += 1
            if пс is not None:
                к["первая_сделка_известна"] += 1
                if задержка < пс:
                    к["раньше_первой_сделки"] += 1
        ряды.append(ряд)

    таблица = []
    for г, к in sorted(группы.items()):
        стр = {"группа": г, "токенов": к["токенов"], "с_постом": к["с_постом"],
               "покрытие": (round(к["с_постом"] / к["токенов"], 4) if к["токенов"] else None),
               "пик_известен": к["пик_известен"],
               "раньше_пика": {д: {"штук": n, "доля": (round(n / к["пик_известен"], 4)
                                                       if к["пик_известен"] else None)}
                               for д, n in к["раньше_пика"].items()},
               "первая_сделка_известна": к["первая_сделка_известна"],
               "раньше_первой_сделки": к["раньше_первой_сделки"],
               "доля_раньше_первой_сделки": (
                   round(к["раньше_первой_сделки"] / к["первая_сделка_известна"], 4)
                   if к["первая_сделка_известна"] else None),
               "задержка_с_медиана": (round(st.median(к["задержки_с"]), 1)
                                      if к["задержки_с"] else None),
               "задержка_с_p10": (round(sorted(к["задержки_с"])[len(к["задержки_с"]) // 10], 1)
                                  if len(к["задержки_с"]) >= 10 else None),
               "подписчики_медиана": (round(st.median(к["подписчики"]), 1)
                                      if к["подписчики"] else None),
               "постов_в_час_медиана": (st.median(к["постов_в_час"])
                                        if к["постов_в_час"] else None),
               "постов_всего_медиана": (st.median(к["постов_всего"])
                                        if к["постов_всего"] else None)}
        таблица.append(стр)

    тело = {"что": "первый пост в X против пика цены и первой сделки",
            "описательно": "пункт 1 проверки; вердикт по стандарту -- позже и отдельно",
            "когда": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
            "выборка": Path(а.vyborka).name, "упоминания": Path(а.upominania).name,
            "актор": упом.get("актор"), "стоимость_usd": упом.get("стоимость_usd"),
            "стоимость_на_токен_usd": упом.get("стоимость_на_токен_usd"),
            "длины_слота_с": list(ДЛИНЫ_СЛОТА),
            "оговорки": [
                "пик взят внутри окна производной (230 слотов у кривых, 1121 у "
                "переехавших): настоящий пик может быть позже, значит доля «пост раньше "
                "пика» -- нижняя граница",
                "удалённые посты и неполнота поиска X смещают выборку к выжившим",
                "время первой сделки -- верхняя оценка по корзинам волны 5/15/30/60 с",
            ],
            "по_группам": таблица, "ряды": ряды}
    ф = П / f"x_sravnenie{а.metka}.json"
    ф.write_text(json.dumps(тело, ensure_ascii=False, indent=1), encoding="utf-8")
    print("%-16s %7s %8s %9s %14s %14s %12s" % (
        "группа", "токенов", "с постом", "покрытие", "раньше пика .226",
        "раньше пика .4", "задержка мед"), flush=True)
    for с in таблица:
        print("%-16s %7d %8d %9s %14s %14s %12s" % (
            с["группа"], с["токенов"], с["с_постом"], с["покрытие"],
            с["раньше_пика"]["0.226"]["доля"], с["раньше_пика"]["0.4"]["доля"],
            с["задержка_с_медиана"]), flush=True)
    print(f"записано {ф}", flush=True)
    try:
        import sys  # noqa: PLC0415
        sys.path.insert(0, str(Path(__file__).resolve().parent))
        import podbivka_run as R  # noqa: PLC0415
        R.записано(ф)
    except Exception:  # noqa: BLE001, S110
        pass
    return 0


def main() -> int:
    р = argparse.ArgumentParser()
    р.add_argument("--vyborka", default=str(П / "x_vyborka_pilot50.json"))
    р.add_argument("--upominania", default=str(П / "x_upominania_pilot50.json"))
    р.add_argument("--metka", default="")
    return главное(р.parse_args())


if __name__ == "__main__":
    raise SystemExit(main())
