def туда_обратно(tx_покупки: dict, *, программа: str, лампорты: int,
                  хранилище: str | None = None, минт_котировки: str | None = None,
                  проскальзывание: float = 0.0, rpc_call=None) -> dict:
    """Купили на L -> получили T -> продали T -> получили L'. {ok, L, T, L_назад}.

    Покупка котируется ТЕМ ЖЕ способом, что продажа, только сторонами вперёд:
    у кирпичей -- min_out_from_reserves по шаблону покупки, у строителей и DLMM --
    их котировка с нормальным порядком минтов. Иначе круг сравнивал бы два разных
    котировщика, а не одну кривую в двух направлениях.
    """
    из_ = {"ok": False, "why_not": None, "L": int(лампорты), "T": None,
            "L_назад": None, "доля_назад": None, "чтений": None,
            "fee_factor": None}
    try:
        SP = _продавец()
        _C, B = _кирпичи()
        кот = минт_котировки or WSOL
        ш_пр = SP.шаблон_продажи(tx_покупки, программа=программа,
                                  минт_котировки=кот, хранилище=хранилище)
        if not ш_пр.get("ok"):
            из_["why_not"] = ш_пр.get("why_not")
            return из_
        база = ш_пр.get("минт_базы")
        сп = способ(программа)
        # --- туда: покупка
        if сп == СПОСОБ_КИРПИЧИ:
            # ОТКАЗ ПРОДАЖИ ПРОВЕРЯЕТСЯ ПЕРВЫМ: у типов с виртуальными резервами
            # круга нет по названной причине, и котировать покупку там незачем
            # (а котировщик DAMM v2 без arg0 источника просто падает).
            почему_вирт = ВИРТУАЛЬНЫЕ_РЕЗЕРВЫ.get(программа)
            if почему_вирт:
                из_["why_not"] = почему_вирт
                return из_
            tpl_пок = _шаблон_покупки(B, SP, tx_покупки, программа, хранилище,
                                       ш_пр.get("имя_инструкции"))
            if tpl_пок is None:
                из_["why_not"] = "инструкция покупки не найдена"
                return из_
            мо = B.min_out_from_reserves(tpl_пок, tx_покупки, int(лампорты),
                                         float(проскальзывание))
            мо = мо if isinstance(мо, dict) else {}
            if not мо.get("ok"):
                из_["why_not"] = f"покупка не котируется: {мо.get('why_not')}"
                return из_
            из_["fee_factor"] = мо.get("fee_factor")
            # ПОКУПКА ВЫШЕ КРИВОЙ БЕЗ КОМИССИИ -- КРУГ НЕ СМЫКАЕТСЯ НИКАКОЙ
            # ПРОДАЖЕЙ. f > 1 значит, что котировщик покупки обещает больше, чем
            # даёт кривая по остаткам хранилищ; деньги появляются на ПЕРВОМ шаге,
            # и мерить вторым шагом нечего. Почему так бывает -- в описании у
            # ПРИЧИНА_F_БОЛЬШЕ_1 (не снятые protocol_fees внутри хранилища).
            ф = мо.get("fee_factor")
            if isinstance(ф, (int, float)) and float(ф) > 1.0:
                из_["why_not"] = f"{ПРИЧИНА_F_БОЛЬШЕ_1}: f = {float(ф):.6f}"
                return из_
            T = int(мо["expected_out"])
        elif сп == СПОСОБ_КРИВАЯ:
            # ПОКУПКА КРИВОЙ -- ЕЁ ЖЕ КОТИРОВЩИКОМ (c2_swap_build.bonding_min_out):
            # та же кривая по тем же виртуальным резервам, только вперёд.
            # КОТИРОВКА ТОКЕНОМ -- СВОИМ ЗЕРКАЛОМ (вход_кривой): чужой котировщик
            # читает ТОЛЬКО обязательную часть события, а она на токеновой
            # котировке пуста по SOL, и круг на таком образце не считался вовсе.
            # Числа тут не новые: та же кривая и те же две комиссии, что у продажи.
            своё_п = событие_кривой(tx_покупки or {}, база)
            пп = (своё_п.get("поля") or {}) if своё_п.get("ok") else {}
            токеновая_п = (int(пп.get("sol_amount") or 0) == 0
                           and int(пп.get("quote_amount") or 0) > 0)
            if токеновая_п:
                мо = вход_кривой(котировки=int(лампорты),
                                 вирт_котировка=int(пп["virtual_quote_reserves"]),
                                 вирт_токены=int(пп["virtual_token_reserves"]),
                                 fee_bps=int(пп["fee_basis_points"]),
                                 creator_bps=int(пп["creator_fee_basis_points"]))
                мо = dict(мо, expected_out=мо.get("выход"))
            else:
                мо = B.bonding_min_out(tx_покупки, база, int(лампорты),
                                       float(проскальзывание))
            мо = мо if isinstance(мо, dict) else {}
            if not мо.get("ok"):
                из_["why_not"] = f"покупка не котируется: {мо.get('why_not')}"
                return из_
            T = int(мо["expected_out"])
        elif сп == СПОСОБ_DAMM2:
            # ПОКУПКА DAMM v2 -- ЕЁ ЖЕ КОТИРОВЩИКОМ (damm2_min_out): та же кривая
            # по тому же событию, только вперёд.
            tpl_пок = _шаблон_покупки(B, SP, tx_покупки, программа, хранилище,
                                       ш_пр.get("имя_инструкции"))
            if tpl_пок is None:
                из_["why_not"] = "инструкция покупки не найдена"
                return из_
            мо = B.damm2_min_out(tpl_пок, tx_покупки, int(лампорты),
                                 float(проскальзывание))
            мо = мо if isinstance(мо, dict) else {}
            if not мо.get("ok"):
                из_["why_not"] = f"покупка не котируется: {мо.get('why_not')}"
                return из_
            T = int(мо["expected_out"])
        elif сп == СПОСОБ_LAUNCHLAB:
            # ПОКУПКА LAUNCHLAB -- ЕЁ ЖЕ КОТИРОВЩИКОМ (launchlab_min_out).
            мо = B.launchlab_min_out(tx_покупки, int(лампорты),
                                     float(проскальзывание))
            мо = мо if isinstance(мо, dict) else {}
            if not мо.get("ok"):
                из_["why_not"] = f"покупка не котируется: {мо.get('why_not')}"
                return из_
            T = int(мо["expected_out"])
        elif сп == СПОСОБ_DLMM:
            import c2_dlmm_bez_chteniy as DL  # noqa: PLC0415

            пул = (ш_пр["tpl"].get("accounts") or [None])[0]
            к = DL.котировка(пул=пул, минт_базы=база, минт_котировки=кот,
                             лампорты=int(лампорты),
                             проскальзывание=float(проскальзывание),
                             tx_источника=tx_покупки)
            if not (к or {}).get("ok"):
                из_["why_not"] = f"покупка не котируется: {(к or {}).get('why_not')}"
                return из_
            T = int(к["expected_out"])
        else:
            import importlib  # noqa: PLC0415

            # УЗЕЛ НУЖЕН ОБОИМ ПЛЕЧАМ: котировщики CLMM, Whirlpool, AMM v4 и DBC
            # читают пул (1-2 чтения), и без rpc_call круг не измерить вовсе.
            # Называется это отказом, а не прячется под ошибкой котировщика.
            if rpc_call is None:
                из_["why_not"] = ("нужен узел: котировщик этого типа читает пул "
                                   "(те же чтения, что у покупателя)")
                return из_
            имя, _ = КОТИРОВЩИКИ[программа]
            M = importlib.import_module(имя)
            т = M.шаблон(tx_покупки, None, хранилище=хранилище)
            пул = (т or {}).get("пул")
            к = M.котировка(пул=пул, минт_базы=база, минт_котировки=кот,
                            лампорты=int(лампорты),
                            проскальзывание=float(проскальзывание),
                            rpc_call=rpc_call)
            if not (к or {}).get("ok"):
                из_["why_not"] = f"покупка не котируется: {(к or {}).get('why_not')}"
                return из_
            T = int(к["expected_out"])
        из_["T"] = T
        if T <= 0:
            из_["why_not"] = "покупка дала ноль токенов"
            return из_
        # --- обратно: продажа тех же токенов
        пр = котировка_продажи(программа, остаток=T, tx_покупки=tx_покупки,
                                минт_базы=база, минт_котировки=кот,
                                хранилище=хранилище,
                                проскальзывание=float(проскальзывание),
                                rpc_call=rpc_call, шаблон=ш_пр)
        из_["чтений"] = пр.get("чтений")
        if not пр.get("ok"):
            из_["why_not"] = f"продажа не котируется: {пр.get('why_not')}"
            return из_
        L2 = int(пр["expected_out"])
        из_.update(L_назад=L2, доля_назад=(L2 / int(лампорты) if лампорты else None))
    except Exception as сбой:  # noqa: BLE001
        из_["why_not"] = f"круг не посчитан: {type(сбой).__name__}: {str(сбой)[:140]}"
        return из_
    из_["ok"] = True
    return из_


def круг_сходится(о: dict, *, потолок_потерь: float = ПОТОЛОК_ПОТЕРЬ_КРУГА) -> dict:
    """Сходится ли круг: назад не больше входа и не меньше, чем вход минус потолок."""
    из_ = {"ok": False, "why_not": None, "больше_входа": None, "слишком_мало": None}
    if not о.get("ok"):
        из_["why_not"] = о.get("why_not")
        return из_
    L, L2 = int(о["L"]), int(о["L_назад"])
    из_["больше_входа"] = L2 > L
    из_["слишком_мало"] = L2 < L * (1.0 - float(потолок_потерь))
    if из_["больше_входа"]:
        из_["why_not"] = (f"назад пришло БОЛЬШЕ входа ({L2} против {L}) -- котировка "
                           f"продажи смотрит не в ту сторону")
        return из_
    if из_["слишком_мало"]:
        из_["why_not"] = (f"назад пришло {L2} из {L} -- меньше, чем вход минус "
                           f"{потолок_потерь * 100:.0f} %")
        return из_
    из_["ok"] = True
    return из_


