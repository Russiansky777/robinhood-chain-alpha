def _шаблон_покупки(B, SP, tx: dict, программа: str, хранилище: str | None,
                     имя_инструкции: str | None = None) -> dict | None:
    """Шаблон ПОКУПКИ той же сделки -- тем же разбором, что у полосы.

    Сначала c2_swap_build.extract_template: он кладёт в шаблон и arg0/arg1 (их
    ждут котировщики DAMM v2 и DBC), и права счетов. Хранилища нет -- шаблон
    собирается из инструкции покупки, но без аргументов: тогда такому шаблону
    доступны только типы, которым аргументы источника не нужны.
    """
    if хранилище:
        т = B.extract_template(tx, программа, хранилище)
        if isinstance(т, dict) and т.get("ok"):
            return т
    пок = SP.инструкция_покупки(tx, программа=программа, хранилище=хранилище)
    if not пок.get("ok"):
        return None
    return {"ok": True, "program": программа, "accounts": пок["accounts"],
            "data": пок["data"], "writable": пок["writable"],
            "ix": имя_инструкции}


def _множитель_комиссии(B, tpl_покупки: dict | None, tx: dict) -> dict:
    """f сделки источника -- ТЕМ ЖЕ числом, которым котирует покупка.

    Своей ставки комиссии здесь не вводится: f читается из
    c2_swap_build.min_out_from_reserves по шаблону ПОКУПКИ (ему всё равно, какой
    amount_in ему дали -- f считается по сделке источника). Возвращается и сырое
    f, и применимое: выше единицы оно означало бы, что пул отдаёт больше кривой
    без комиссии, а на это полагаться нельзя, поэтому применимое ограничено 1.
    """
    из_ = {"ok": False, "why_not": None, "f": None, "f_сырой": None,
            "ограничено": False}
    if not isinstance(tpl_покупки, dict) or not tpl_покупки.get("ok"):
        из_["why_not"] = "шаблона покупки нет -- комиссию источника снять не с чего"
        return из_
    try:
        мо = B.min_out_from_reserves(tpl_покупки, tx, 1, 0.0)
    except Exception as сбой:  # noqa: BLE001
        из_["why_not"] = f"{type(сбой).__name__}: {str(сбой)[:100]}"
        return из_
    мо = мо if isinstance(мо, dict) else {}
    ф = мо.get("fee_factor")
    if not isinstance(ф, (int, float)) or not ф > 0:
        из_["why_not"] = мо.get("why_not") or "множитель комиссии не посчитан"
        return из_
    из_.update(ok=True, f_сырой=float(ф), f=min(1.0, float(ф)),
               ограничено=bool(float(ф) > 1.0))
    return из_


