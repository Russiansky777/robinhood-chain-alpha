def self_test() -> int:  # noqa: C901, PLR0912, PLR0915
    import json  # noqa: PLC0415

    SP = _продавец()
    C, B = _кирпичи()
    B.загрузить_ставки_clmm()
    проверки = []

    def chk(что, ок, факт=None):
        проверки.append((что, bool(ок), факт))

    # --------------------- 0. событие кривой по IDL и выход v2 на живых продажах
    import json as _js  # noqa: PLC0415

    путь_пр = Path(C.DATA) / "samples" / "prodazhi" / "krivaya_pump_fun.json"
    chk("файл живых продаж кривой на месте", путь_пр.exists(), str(путь_пр))
    v2_разобрано, v2_цена = 0, 0
    if путь_пр.exists():
        for о in (_js.loads(путь_пр.read_text(encoding="utf-8"))
                  .get("образцы") or []):
            соб = событие_кривой(о["tx_jsonParsed"], о["mint"])
            if not соб.get("ok") or not соб.get("v2"):
                continue
            v2_разобрано += 1
            п = соб["поля"]
            # Тело обязано разобраться РОВНО до конца -- иначе раскладка не та.
            if соб["разобрано"] != соб["длина"]:
                continue
            вк = int(п.get("virtual_quote_reserves") or п["virtual_sol_reserves"])
            к = выход_кривой(
                токенов=int(п["token_amount"]),
                вирт_sol=вк + int(п["sol_amount"]),
                вирт_токены=int(п["virtual_token_reserves"]) - int(п["token_amount"]),
                fee_bps=int(п["fee_basis_points"]),
                creator_bps=int(п["creator_fee_basis_points"]),
                cashback_bps=int(п.get("cashback_fee_basis_points") or 0))
            v2_цена += int(к["ok"] and к["с_кривой"] == int(п["sol_amount"])
                           and к["комиссия"] == int(п["fee"])
                           and к["комиссия_создателя"] == int(п["creator_fee"]))
    chk(f"событие по IDL разобралось до конца у всех {ЖДЁМ_СОБЫТИЙ_V2} живых "
        f"продаж с хвостом v2", v2_разобрано == ЖДЁМ_СОБЫТИЙ_V2, v2_разобрано)
    chk("кривая продажи повторила каждое из этих событий ДО ЛАМПОРТА",
        v2_цена == v2_разобрано == ЖДЁМ_СОБЫТИЙ_V2, (v2_цена, v2_разобрано))
    chk("события в транзакции нет -- отказ по имени, а не пустые поля",
        (lambda о: not о["ok"] and о["why_not"])(событие_кривой({})), None)
    к_к = выход_кривой(токенов=1_000_000, вирт_sol=1_000_000_000,
                        вирт_токены=1_000_000_000_000, fee_bps=95,
                        creator_bps=30, cashback_bps=25)
    chk("осторожное число ниже обычного ровно на кэшбэк",
        к_к["выход"] - к_к["выход_осторожный"] == к_к["кэшбэк"] > 0, к_к)
    chk("нулевая ставка кэшбэка -- осторожное число равно обычному",
        (lambda о: о["выход"] == о["выход_осторожный"] and о["кэшбэк"] == 0)(
            выход_кривой(токенов=1_000_000, вирт_sol=1_000_000_000,
                          вирт_токены=1_000_000_000_000, fee_bps=95,
                          creator_bps=30)), None)

    # ------------------------------------------- 1. таблица котировщиков
    chk("котировщиков в таблице 8: пять с чтениями, три по событию сделки",
        len(КОТИРОВЩИКИ) == 8, len(КОТИРОВЩИКИ))
    chk("каждый котировщик из таблицы -- тип, в котором полоса покупает",
        all(p in SP.ТИПЫ for p in КОТИРОВЩИКИ),
        [p for p in КОТИРОВЩИКИ if p not in SP.ТИПЫ])
    chk("у каждого типа полосы способ котировки назван",
        all(способ(p) in (СПОСОБ_СТРОИТЕЛЬ, СПОСОБ_DLMM, СПОСОБ_КИРПИЧИ,
                          СПОСОБ_КРИВАЯ, СПОСОБ_LAUNCHLAB, СПОСОБ_DAMM2)
            for p in SP.ТИПЫ), None)
    chk("незнакомая программа идёт кирпичами, а не падает",
        способ("НеПрограмма") == СПОСОБ_КИРПИЧИ, способ("НеПрограмма"))
    chk("у каждого типа с виртуальными резервами названа причина отказа",
        all(isinstance(v, str) and v for v in ВИРТУАЛЬНЫЕ_РЕЗЕРВЫ.values()), None)
    chk("типы с виртуальными резервами -- кирпичные (у строителей своя цена)",
        all(способ(p) == СПОСОБ_КИРПИЧИ for p in ВИРТУАЛЬНЫЕ_РЕЗЕРВЫ), None)
    for имя, сп_ in КОТИРОВЩИКИ.values():
        import importlib  # noqa: PLC0415

        M = importlib.import_module(имя)
        # У кривой котировщик не отдельный модуль, а виртуальные резервы события:
        # с неё спрашивается pump_trade_event, а не котировка().
        нужно = {СПОСОБ_КРИВАЯ: "pump_trade_event",
                 СПОСОБ_LAUNCHLAB: "launchlab_event",
                 СПОСОБ_DAMM2: "выход_по_кривой"}.get(сп_, "котировка")
        chk(f"{имя}: {нужно} на месте и зовётся по именам",
            callable(getattr(M, нужно, None)), имя)

    # ----------------------------------------------- 2. отказы на входе
    о = котировка_продажи("pAMMBay6oceH9fJKBRHGP5D4bD4sWpmSwMn52FMfXEA",
                           остаток=0, tx_покупки={})
    chk("остаток 0 -- отказ словами, а не котировка нуля",
        not о["ok"] and "остаток" in (о["why_not"] or ""), о.get("why_not"))
    о = котировка_продажи("pAMMBay6oceH9fJKBRHGP5D4bD4sWpmSwMn52FMfXEA",
                           остаток=-5, tx_покупки={})
    chk("остаток отрицательный -- отказ", not о["ok"] and о["why_not"],
        о.get("why_not"))
    о = котировка_продажи("pAMMBay6oceH9fJKBRHGP5D4bD4sWpmSwMn52FMfXEA",
                           остаток=10, tx_покупки={}, проскальзывание=1.0)
    chk("проскальзывание 1.0 -- отказ: минимум вышел бы нулём молча",
        not о["ok"] and "проскальзывание" in (о["why_not"] or ""), о.get("why_not"))
    о = котировка_продажи("pAMMBay6oceH9fJKBRHGP5D4bD4sWpmSwMn52FMfXEA",
                           остаток=10)
    chk("ни шаблона, ни покупки -- отказ по имени",
        not о["ok"] and ПРИЧИНА_НЕТ_ШАБЛОНА in (о["why_not"] or ""),
        о.get("why_not"))
    о = котировка_продажи("НеПрограмма", остаток=10, tx_покупки={})
    chk("незнакомый тип пула -- отказ словами", not о["ok"] and о["why_not"],
        о.get("why_not"))
    for p, почему in sorted(ВИРТУАЛЬНЫЕ_РЕЗЕРВЫ.items()):
        ш = {"ok": True, "program": p, "tpl": {}, "минт_базы": "B" * 32,
             "имя_инструкции": "sell", "accounts": [], "writable": {}}
        о = котировка_продажи(p, остаток=10, tx_покупки={}, шаблон=ш,
                               минт_базы="B" * 32)
        chk(f"{str(p)[:8]}: виртуальные резервы -- отказ по имени, чтений 0",
            not о["ok"] and почему == о["why_not"] and о["чтений"] == 0,
            о.get("why_not"))

    # --------------------------------------- 3. правило круга само по себе
    чс = круг_сходится({"ok": True, "L": 1000, "L_назад": 900})
    chk("круг сошёлся: назад меньше входа и в пределах потолка",
        чс["ok"] and not чс["больше_входа"], чс)
    чс = круг_сходится({"ok": True, "L": 1000, "L_назад": 1001})
    chk("назад больше входа -- не сошлось, и сказано про сторону",
        not чс["ok"] and чс["больше_входа"] and "не в ту сторону" in чс["why_not"],
        чс.get("why_not"))
    чс = круг_сходится({"ok": True, "L": 1000, "L_назад": 50})
    chk("назад на порядок меньше -- не сошлось по потолку потерь",
        not чс["ok"] and чс["слишком_мало"], чс.get("why_not"))
    чс = круг_сходится({"ok": False, "why_not": "причина круга"})
    chk("круг не посчитан -- причина переносится как есть",
        not чс["ok"] and чс["why_not"] == "причина круга", чс.get("why_not"))

    # --------------------------- 4. множитель комиссии: шапка на единице
    к = _множитель_комиссии(B, None, {})
    chk("без шаблона покупки множитель комиссии отказывает словами",
        not к["ok"] and к["why_not"], к.get("why_not"))

    # -------------------------------- 5. круг на живых покупках образцов
    видели = set()
    for p, т in sorted(SP.ТИПЫ.items(), key=lambda kv: kv[1]["метка"]):
        метка = т["метка"]
        путь = Path(C.DATA) / "c2_pool_samples" / f"{p}.json"
        ждём = ЖДЁМ_КРУГА.get(метка)
        if not путь.exists():
            chk(f"{метка}: образцов в репозитории нет -- и в таблице круга их нет",
                ждём is None, метка)
            continue
        видели.add(метка)
        chk(f"{метка}: тип есть в таблице круга", ждём is not None, метка)
        if ждём is None:
            continue
        сд = [x for x in json.loads(путь.read_text(encoding="utf-8"))
              if isinstance(x, dict) and isinstance(x.get("tx"), dict)]
        сошлось, безымянных, чужих = 0, 0, 0
        for x in сд:
            о = туда_обратно(x["tx"], программа=p, лампорты=КРУГ_ЛАМПОРТОВ,
                             хранилище=x.get("pool_vault"),
                             минт_котировки=x.get("quote_mint"))
