def котировка_продажи(программа: str, *, пул: str | None = None,
                       остаток: int, tx_покупки: dict | None = None,
                       минт_базы: str | None = None,
                       минт_котировки: str | None = None,
                       хранилище: str | None = None,
                       проскальзывание: float = 0.35, rpc_call=None,
                       налог_выхода=None, налог_входа=None,
                       программа_базы: str | None = None,
                       программа_котировки: str | None = None,
                       сейчас: float | None = None, шаблон=None,
                       группа: str | None = None) -> dict:
    """Сколько котировки дадут за `остаток` базы. Чтения -- котировщика типа.

    Возвращает {ok, why_not, expected_out, min_out, чтений, путь, способ}.
    `шаблон` -- готовый шаблон продажи (c3_prodavec_sborka.шаблон_продажи); не
    передан -- собирается здесь из tx_покупки, потому что кирпичному пути он нужен,
    а строителям нужны минты сторон.
    """
    из_ = {"ok": False, "why_not": None, "expected_out": None, "min_out": None,
            "чтений": None, "путь": None, "способ": способ(программа),
            "минт_базы": минт_базы, "минт_котировки": минт_котировки or WSOL}
    if not isinstance(остаток, int) or остаток <= 0:
        из_["why_not"] = f"остаток не положительное целое: {остаток!r}"
        return из_
    if not 0 <= float(проскальзывание) < 1:
        из_["why_not"] = f"проскальзывание вне [0, 1): {проскальзывание!r}"
        return из_
    try:
        SP = _продавец()
        _C, B = _кирпичи()
        ш = шаблон
        if ш is None:
            if not isinstance(tx_покупки, dict):
                из_["why_not"] = ПРИЧИНА_НЕТ_ШАБЛОНА
                return из_
            ш = SP.шаблон_продажи(tx_покупки, программа=программа,
                                   минт_базы=минт_базы,
                                   минт_котировки=из_["минт_котировки"],
                                   хранилище=хранилище)
        if not ш.get("ok"):
            из_["why_not"] = ш.get("why_not") or ПРИЧИНА_НЕТ_ШАБЛОНА
            return из_
        база = минт_базы or ш.get("минт_базы")
        из_["минт_базы"] = база
        if not база:
            из_["why_not"] = "минт базы не известен -- вход продажи назвать нечем"
            return из_
        сп = из_["способ"]
        if сп == СПОСОБ_КИРПИЧИ:
            # ДВУХРЕЗЕРВНЫЕ ПУЛЫ -- КРИВАЯ CODE-1 ПО ОСТАТКАМ ХРАНИЛИЩ, НУЛЬ
            # ЧТЕНИЙ. Берётся bloom_lane_sell.минимум_по_живым_резервам -- та же
            # функция, которой считает своя продажа Pump AMM; своей кривой здесь
            # не заводится, иначе два пути разошлись бы в цене.
            # min_out_from_reserves сюда не годится: она КАЛИБРУЕТСЯ на сделке
            # источника (покупке) и перевёрнутый шаблон честно отвергает.
            почему_вирт = ВИРТУАЛЬНЫЕ_РЕЗЕРВЫ.get(программа)
            if почему_вирт:
                из_.update(чтений=0, путь="нет", why_not=почему_вирт)
                return из_
            рез = _резервы_по_сделке(B, ш, tx_покупки or {}, база,
                                      из_["минт_котировки"], хранилище)
            из_.update(чтений=0, путь="bloom_lane_sell.минимум_по_живым_резервам",
                       резерв_базы=рез.get("база"), резерв_котировки=рез.get("котировка"))
            if not рез.get("ok"):
                из_["why_not"] = f"резервы пула не сняты: {рез.get('why_not')}"
                return из_
            import bloom_lane_sell as LS  # noqa: PLC0415

            м = LS.минимум_по_живым_резервам(база_в=int(остаток),
                                             резерв_базы=int(рез["база"]),
                                             резерв_котировки=int(рез["котировка"]),
                                             запас=float(проскальзывание))
            м = м if isinstance(м, dict) else {}
            из_.update(expected_out=м.get("po_krivoj"), min_out=м.get("min_out"))
            if not м.get("ok"):
                из_["why_not"] = f"кривая продажи отказала: {м.get('why_not')}"
                return из_
            # ВТОРОЕ ЧИСЛО, С КОМИССИЕЙ -- ТЕМ ЖЕ МНОЖИТЕЛЕМ, ЧТО У ПОКУПКИ.
            # expected_out выше -- кривая БЕЗ комиссии (так написана функция
            # Code-1, и менять её поведение здесь нельзя: по ней живёт продажа
            # Pump AMM на денежном пути). Поэтому комиссия даётся отдельным
            # полем: тот же f, что калибрует покупка, приложенный ко входу
            # продажи. Решать, каким числом пользоваться, -- не этому модулю.
            к_ = _множитель_комиссии(B, рез.get("tpl_покупки"), tx_покупки or {})
            из_.update(fee_factor=к_.get("f"), fee_factor_сырой=к_.get("f_сырой"),
                       комиссия_ограничена=к_.get("ограничено"))
            if к_.get("ok"):
                мк = LS.минимум_по_живым_резервам(
                    база_в=max(1, int(int(остаток) * к_["f"])),
                    резерв_базы=int(рез["база"]), резерв_котировки=int(рез["котировка"]),
                    запас=float(проскальзывание))
                мк = мк if isinstance(мк, dict) else {}
                из_.update(expected_out_s_komissiej=мк.get("po_krivoj"),
                           min_out_s_komissiej=мк.get("min_out"))
        elif сп == СПОСОБ_КРИВАЯ:
            # ВИРТУАЛЬНЫЕ РЕЗЕРВЫ -- ИЗ СОБЫТИЯ НАШЕЙ ПОКУПКИ, НУЛЬ ЧТЕНИЙ. Событие
            # несёт резервы ПОСЛЕ сделки источника, то есть ровно то состояние, из
            # которого продаём; ставки комиссий -- там же. Событие берётся чужой
            # проверенной функцией (c2_swap_build.pump_trade_event): она не берёт
            # событие, которое не воспроизвело собственную сделку.
            ев = B.pump_trade_event(tx_покупки or {}, база)
            из_.update(чтений=0, путь="c2_swap_build.pump_trade_event + кривая продажи")
            if not ев:
                из_["why_not"] = "нет события сделки кривой pump.fun в логах покупки"
                return из_
            к = выход_кривой(токенов=int(остаток),
                             вирт_sol=int(ев["virtual_sol_reserves"]),
                             вирт_токены=int(ев["virtual_token_reserves"]),
                             fee_bps=int(ев["fee_bps"]),
                             creator_bps=int(ев["creator_fee_bps"]))
            из_.update(expected_out=к.get("выход"), с_кривой=к.get("с_кривой"),
                       комиссия=к.get("комиссия"),
                       комиссия_создателя=к.get("комиссия_создателя"),
                       fee_bps=ев["fee_bps"], creator_bps=ев["creator_fee_bps"],
                       вирт_резервы=[ев["virtual_sol_reserves"],
                                      ев["virtual_token_reserves"]])
            if not к.get("ok"):
                из_["why_not"] = f"кривая продажи отказала: {к.get('why_not')}"
                return из_
            из_["min_out"] = int(int(к["выход"]) * (1.0 - float(проскальзывание)))
        elif сп == СПОСОБ_DAMM2:
            # ЦЕНА -- ИЗ СОБЫТИЯ СВОПА НАШЕЙ ПОКУПКИ, НУЛЬ ЧТЕНИЙ. Ликвидность,
            # цену после сделки и долю комиссии считает чужая проверенная функция
            # (c2_swap_build.damm2_min_out -> c2_cl_quote.минимум): она сверяет
            # событие с движением хранилищ и с аргументом инструкции и не берёт
            # событие, которое не воспроизвело сделку источника. Наше дело --
            # повернуть кривую в обратную сторону.
            из_.update(чтений=0, путь="c2_swap_build.damm2_min_out + кривая назад")
            tpl_пок = _шаблон_покупки(B, SP, tx_покупки or {}, программа, хранилище,
                                       ш.get("имя_инструкции"))
            if tpl_пок is None:
                из_["why_not"] = "инструкция покупки не найдена"
                return из_
            вх_ист = _вход_источника(B, tpl_пок, tx_покупки or {})
            if not вх_ист.get("ok"):
                из_["why_not"] = f"вход сделки источника не снят: {вх_ист.get('why_not')}"
                return из_
            мо = B.damm2_min_out(tpl_пок, tx_покупки or {}, int(вх_ист["вход"]), 0.0)
            мо = мо if isinstance(мо, dict) else {}
            if not мо.get("ok"):
                из_["why_not"] = f"кривая покупки не восстановлена: {мо.get('why_not')}"
                return из_
            к = выход_damm2(токенов=int(остаток), цена_после=мо["price_after"],
                            ликвидность=мо["liquidity"],
                            доля_комиссии=мо["fee_share"],
                            база_это_a=bool(вх_ист["база_это_a"]))
            из_.update(expected_out=к.get("выход"), брутто=к.get("брутто"),
                       fee_share=мо.get("fee_share"),
                       цена_после=мо.get("price_after"),
                       ликвидность=мо.get("liquidity"),
                       выход_комиссия_с_выхода=к.get("выход_комиссия_с_выхода"),
                       выход_комиссия_со_входа=к.get("выход_комиссия_со_входа"),
                       разница_сторон_комиссии=к.get("разница_сторон_комиссии"))
            if not к.get("ok"):
                из_["why_not"] = f"кривая продажи отказала: {к.get('why_not')}"
                return из_
            из_["min_out"] = int(int(к["выход"]) * (1.0 - float(проскальзывание)))
        elif сп == СПОСОБ_LAUNCHLAB:
            # ВИРТУАЛЬНЫЕ РЕЗЕРВЫ -- ИЗ СОБЫТИЯ НАШЕЙ ПОКУПКИ, НУЛЬ ЧТЕНИЙ. Событие
            # разбирает чужая проверенная функция (c2_swap_build.launchlab_event);
            # резервы берутся ПОСЛЕ сделки источника -- то состояние, из которого
            # продаём, -- и ровно теми же выражениями, что у котировщика покупки.
            ев = B.launchlab_event(tx_покупки or {})
            из_.update(чтений=0, путь="c2_swap_build.launchlab_event + кривая продажи")
            if not ев:
                из_["why_not"] = "нет события сделки LaunchLab в логах покупки"
                return из_
            вх = int(ев["amount_in"])
            прирост = int(ев["real_quote_after"]) - int(ев["real_quote_before"])
            к = выход_launchlab(токенов=int(остаток),
                                резерв_базы=int(ев["virtual_base"])
                                - int(ев["real_base_after"]),
                                резерв_котировки=int(ев["virtual_quote"])
                                + int(ев["real_quote_after"]),
                                комиссия_источника=вх - прирост, вход_источника=вх)
            из_.update(expected_out=к.get("выход"), брутто=к.get("брутто"),
                       комиссия=к.get("комиссия"), ставка=к.get("ставка"))
            if not к.get("ok"):
                из_["why_not"] = f"кривая продажи отказала: {к.get('why_not')}"
                return из_
            из_["min_out"] = int(int(к["выход"]) * (1.0 - float(проскальзывание)))
        elif сп == СПОСОБ_DLMM:
            import c2_dlmm_bez_chteniy as DL  # noqa: PLC0415
            import c2_dlmm_odno_chtenie as OD  # noqa: PLC0415

            пул_ = пул or (ш["tpl"].get("accounts") or [None])[0]
            # DLMM: ЗА ФЛАГОМ -- ОДНО ЧТЕНИЕ, БЕЗ ФЛАГА -- НУЛЬ ЧТЕНИЙ.
            # Котировка без чтений даёт ПЛОСКУЮ цену события и обратное
            # направление честно отказывает: цена корзины, снятая со сделки
            # ПОКУПКИ источника, продажу не котирует. Путь одного чтения
            # (c2_dlmm_odno_chtenie, флаг BLOOM_DLMM_ODNO_CHTENIE, по умолчанию
            # выключен) читает сам пул и массивы корзин ОДНИМ запросом -- массивы
            # берутся из сделки источника -- и направление у него общее: вход
            # задаётся минтом, значит те же два имени наоборот дают продажу.
            # Своего модуля для этого не заводится: берётся готовый, у которого
            # свой флаг, свой откат и своя проверка (deploy/checks/
            # dlmm_odno_chtenie.py).
            одно = bool(OD.включён(группа) and rpc_call is not None)
            из_["dlmm_одно_чтение"] = одно
            к = {}
            if одно:
                к = OD.котировка(пул=пул_, минт_базы=из_["минт_котировки"],
                                 минт_котировки=база, лампорты=int(остаток),
                                 проскальзывание=float(проскальзывание),
                                 rpc_call=rpc_call, tx_источника=tx_покупки,
                                 сейчас=сейчас, налог_выхода=налог_выхода,
                                 налог_входа=налог_входа)
                к = к if isinstance(к, dict) else {}
                из_.update(чтений=к.get("чтений"),
                           путь="c2_dlmm_odno_chtenie.котировка",
                           expected_out=к.get("expected_out"),
                           min_out=к.get("min_out"), точная=к.get("точная"),
                           активный_массив_совпал=к.get("активный_массив_совпал"))
                if к.get("ok"):
                    из_["ok"] = True
                    return из_
                # ОТКАТ ТОЛЬКО ПО ЕГО ЖЕ СПИСКУ ПРИЧИН: отставание массивов и
                # нехватка их свопу -- случаи, где прежний путь сработал бы.
                if not OD.откатный(к.get("why_not")):
                    из_["why_not"] = f"котировщик DLMM (одно чтение) отказал: {к.get('why_not')}"
                    return из_
                из_["dlmm_откат"] = к.get("why_not")
            # СТОРОНЫ НАОБОРОТ: вход продажи -- минт базы.
            к0 = DL.котировка(пул=пул_, минт_базы=из_["минт_котировки"],
                              минт_котировки=база, лампорты=int(остаток),
                              проскальзывание=float(проскальзывание),
                              tx_источника=tx_покупки, налог_выхода=налог_выхода,
                              программа_выхода=программа_котировки)
            к0 = к0 if isinstance(к0, dict) else {}
            из_.update(чтений=к0.get("чтений"), путь="c2_dlmm_bez_chteniy.котировка",
                       expected_out=к0.get("expected_out"), min_out=к0.get("min_out"))
            if not к0.get("ok"):
                из_["why_not"] = (f"котировщик DLMM отказал: {к0.get('why_not')}"
                                   + (f"; одно чтение откатилось: {из_['dlmm_откат']}"
                                      if из_.get("dlmm_откат") else ""))
                return из_
        else:
            import importlib  # noqa: PLC0415

            имя, _ = КОТИРОВЩИКИ[программа]
            M = importlib.import_module(имя)
            пул_ = пул or (ш["tpl"].get("пул") if isinstance(ш.get("tpl"), dict)
                           else None)
            if not пул_:
                из_["why_not"] = "адрес пула не известен -- котировщик типа без него не идёт"
                return из_
            # СТОРОНЫ НАОБОРОТ: минт_котировки -- это ВХОД, значит база.
            к = M.котировка(пул=пул_, минт_базы=из_["минт_котировки"],
                            минт_котировки=база, лампорты=int(остаток),
                            проскальзывание=float(проскальзывание),
                            rpc_call=rpc_call, сейчас=сейчас,
                            налог_выхода=налог_выхода, налог_входа=налог_входа,
                            программа_выхода=программа_котировки,
                            программа_входа=программа_базы)
            к = к if isinstance(к, dict) else {}
            из_.update(чтений=к.get("чтений"), путь=f"{имя}.котировка",
                       expected_out=к.get("expected_out"), min_out=к.get("min_out"),
                       точная=к.get("точная"))
            if not к.get("ok"):
                из_["why_not"] = f"котировщик типа отказал: {к.get('why_not')}"
                return из_
    except Exception as сбой:  # noqa: BLE001
        из_["why_not"] = f"котировка продажи: {type(сбой).__name__}: {str(сбой)[:140]}"
        return из_
    if not isinstance(из_.get("min_out"), int) or из_["min_out"] <= 0:
        из_["why_not"] = f"минимум выхода не положителен: {из_.get('min_out')!r}"
        return из_
    из_["ok"] = True
    return из_


def _вход_источника(B, tpl_покупки: dict, tx: dict) -> dict:
    """Сколько котировки вошло в пул в сделке источника и какая сторона -- база.

    Числа -- движение ХРАНИЛИЩ пула в той же транзакции (как их берёт
    c2_swap_build.damm2_min_out), роли -- его же mints_and_vaults.
    """
    из_ = {"ok": False, "why_not": None, "вход": None, "выход": None,
            "база_это_a": None}
    C, _B = _кирпичи()
    mv = B.mints_and_vaults(tpl_покупки, tx)
    if not mv or not mv.get("quote_vault") or not mv.get("base_vault"):
        из_["why_not"] = "роли хранилищ пула не восстановились"
        return из_
    строки = {r["account"]: r for r in C.token_rows(tx).values()}
    хк, хб = строки.get(mv["quote_vault"]), строки.get(mv["base_vault"])
    if not хк or not хб:
        из_["why_not"] = "хранилищ пула нет в балансах сделки"
        return из_
    вход, выход = int(хк["post"]) - int(хк["pre"]), int(хб["pre"]) - int(хб["post"])
    if вход <= 0 or выход <= 0:
        из_["why_not"] = (f"сделка источника не покупка по этим хранилищам: "
                           f"вход {вход}, выход {выход}")
        return из_
    к_ = B.DYN.get(tpl_покупки.get("program")) or {}
    ма = к_.get("ma")
    сч = tpl_покупки.get("accounts") or []
    if not isinstance(ма, int) or ма >= len(сч):
        из_["why_not"] = "место минта A этого типа не названо в DYN"
        return из_
    из_.update(ok=True, вход=вход, выход=выход,
               база_это_a=(mv["base_mint"] == сч[ма]))
    return из_


def _резервы_по_сделке(B, ш: dict, tx: dict, база: str, котировка: str,
                        хранилище: str | None = None) -> dict:
    """Остатки ДВУХ ХРАНИЛИЩ ПУЛА после сделки источника. Нуль чтений.

    Хранилища берутся по РОЛЯМ -- c2_swap_build.mints_and_vaults по шаблону
    ПОКУПКИ, -- а не по размеру остатка. Выбор "самого большого остатка" уже
    однажды взял чужой счёт: у Pump AMM в инструкции стоит и счёт WSOL торговца, и
    он бывает в десять раз больше хранилища пула (живой образец: 2174 SOL против
    228). Числа -- постостатки тех же счетов в балансах той же транзакции.
    """
    из_ = {"ok": False, "why_not": None, "база": None, "котировка": None,
            "хранилище_базы": None, "хранилище_котировки": None,
            "tpl_покупки": None}
    C, _B = _кирпичи()
    SP = _продавец()
    tpl_пок = _шаблон_покупки(B, SP, tx, ш["program"], хранилище,
                               ш.get("имя_инструкции"))
    if tpl_пок is None:
        из_["why_not"] = "инструкция покупки не найдена"
        return из_
    из_["tpl_покупки"] = tpl_пок
    mv = B.mints_and_vaults(tpl_пок, tx)
    if not mv or not mv.get("base_vault") or not mv.get("quote_vault"):
        из_["why_not"] = "роли хранилищ пула не восстановились"
        return из_
    # СТОРОНЫ СВЕРЯЮТСЯ С МИНТАМИ, А НЕ ПРИНИМАЮТСЯ НА СЛОВО: если роли покупки
    # назвали базой не наш токен, числа пошли бы не в ту сторону.
    if база and mv.get("base_mint") and mv["base_mint"] != база:
        из_["why_not"] = (f"база покупки {str(mv['base_mint'])[:8]} не наш токен "
                           f"{str(база)[:8]}")
        return из_
    if котировка and mv.get("quote_mint") and mv["quote_mint"] != котировка:
        из_["why_not"] = (f"котировка покупки {str(mv['quote_mint'])[:8]} не "
                           f"{str(котировка)[:8]}")
        return из_
    строки = {r["account"]: r for r in C.token_rows(tx).values()}
    хб, хк = строки.get(mv["base_vault"]), строки.get(mv["quote_vault"])
    if not хб or not хк:
        из_["why_not"] = "хранилищ пула нет в балансах сделки"
        return из_
    б, к = int(хб["post"]), int(хк["post"])
    из_.update(хранилище_базы=mv["base_vault"], хранилище_котировки=mv["quote_vault"])
    if б <= 0 or к <= 0:
        из_["why_not"] = f"остатки хранилищ не положительны: база {б}, котировка {к}"
        return из_
    из_.update(ok=True, база=б, котировка=к)
    return из_


