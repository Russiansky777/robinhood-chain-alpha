#!/usr/bin/env python3
"""Коллы TG-каналов: считается ли вход за каналом (задача владельца 09.10, п.2в-2г).

Берёт пути цены вокруг коллов (`podbivka_tg_cena.py`) и считает по каждому каналу и по всем
вместе: наш вход пост+2 с и пост+5 с, выход 10 / 30 / 60 / 120 / 300 с, билеты 0.1 / 0.3 /
0.5 SOL. Подбор и проверка разделены по суткам, порог -- тот же, что у полосы
(`podbivka_final`): на проверке не меньше 100 сделок, медиана по совершённым сделкам больше
нуля, итог без пяти лучших в плюсе, обе половины проверки в плюсе, худшие сутки не хуже
-2 SOL, уровень случайности p не больше 0.05, билет не больше 2 % резерва пула на 80 %
сделок.

Чем вход за каналом отличается от входа за кошельком. Состояние пула на пост+2 с уже
содержит чужие покупки этих двух секунд -- то есть наценка, которую мы платим из-за тех, кто
успел вперёд нас, посчитана по цепи, а не предположена. Сколько именно чужих покупок прошло
за 1 / 2 / 3 секунды, выписывается отдельным столбцом.

Уровень случайности: нуль -- случайный выбор того же числа коллов в тех же сутках из всех
коллов окна. Так проверяется канал, а не то, что коллы вообще бывают прибыльными.

Только чтение. Выход: docs/podbivka_tg.md и data/podbivka/tg_itog.json.
"""
from __future__ import annotations

import argparse
import collections
import glob
import gzip
import json
import random
import statistics
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import podbivka_bilet as B      # noqa: E402
import podbivka_volna as V      # noqa: E402

КОРЕНЬ = Path(__file__).resolve().parent.parent
П = КОРЕНЬ / "data" / "podbivka"
ПАПКА = П / "tg"
МЕСТА = ("2с", "5с")
ВЫХОДЫ = (10, 30, 60, 120, 300)
БИЛЕТЫ = (0.1, 0.3, 0.5)
ИЗДЕРЖКИ = 0.002015
К_G = 0.9908
ДОЛЯ_РЕЗЕРВА, ДОЛЯ_ГЛУБИНЫ = 0.02, 0.8
ПОВТОРОВ = 200
N_МИН_ПОДБОР = 30               # канал без этого числа коллов на подборе не рассматривается


def загрузить() -> list:
    ряды = []
    for п in sorted(glob.glob(str(ПАПКА / "cena_*.json.gz"))):
        with gzip.open(п, "rt", encoding="utf-8") as ф:
            ряды.extend((json.load(ф).get("ряды") or []))
    # один колл может попасть в два файла прохода -- оставляем свежайший по числу событий
    лучшие: dict = {}
    for x in ряды:
        к = (x["канал"], x["минт"], x.get("id"))
        если = лучшие.get(к)
        if если is None or (x.get("событий") or 0) > (если.get("событий") or 0):
            лучшие[к] = x
    return list(лучшие.values())


def модель(x: dict) -> dict | None:
    вх = {k: v for k, v in (x.get("вход") or {}).items()}
    if x.get("до_поста"):
        вх["пост"] = x["до_поста"]
    вых = {k.replace("с", ""): v for k, v in (x.get("выход") or {}).items()}
    if not вх or not вых:
        return None
    if x.get("пул") in {"meteora-dlmm", "raydium-clmm", "orca-whirlpool"}:
        return None               # сосредоточенная ликвидность: формула на резервах неверна
    return {"pool": x.get("пул"),
            "модель": {"f": x.get("f"), "g": x.get("g"), "fee": x.get("тариф") or 0,
                       "состояния": {"вход": вх, "выход": вых, "масштаб": 1.0}}}


def позже(x: dict, место: str, выход: int) -> bool:
    вх = (x.get("вход") or {}).get(место)
    вых = (x.get("выход") or {}).get(f"{выход}с")
    return bool(вх and вых and вых[2] > вх[2])


def круг(x: dict, место: str, выход: int, б: float) -> dict | None:
    с = модель(x)
    if not с:
        return None
    if позже(x, место, выход):
        return B.сделка_по_состояниям(с, б, место=место, выход=выход,
                                      издержки=ИЗДЕРЖКИ, к_g=К_G)
    # за нами никто не пришёл: продаём в неизменившийся пул
    вх = (x.get("вход") or {}).get(место)
    if not вх:
        return None
    с2 = {"pool": с["pool"], "модель": {**с["модель"],
          "состояния": {"вход": с["модель"]["состояния"]["вход"],
                        "выход": {"0": вх}, "масштаб": 1.0}}}
    return B.сделка_по_состояниям(с2, б, место=место, выход=0,
                                  издержки=ИЗДЕРЖКИ, к_g=К_G)


def свод(ряды: list, б: float) -> dict:
    v = [x["итог"] for x in ряды]
    if not v:
        return {"n": 0}
    верх = sorted(v, reverse=True)
    пс: dict = collections.defaultdict(float)
    for x in ряды:
        пс[x["сутки"]] += x["итог"]
    суток = len(пс) or 1
    return {"n": len(v), "суток": суток, "итог_sol": round(sum(v), 6),
            "sol_в_сутки": round(sum(v) / суток, 6),
            "сделок_в_сутки": round(len(v) / суток, 2),
            "медиана_пп": round(100 * statistics.median(v) / б, 3),
            "в_плюсе": round(100 * sum(1 for y in v if y > 0) / len(v), 1),
            "итог_без_5_лучших_sol": round(sum(верх[5:]), 6) if len(верх) > 5 else None,
            "итог_без_лучших_суток_sol": round(sum(v) - max(пс.values()), 6),
            "худшие_сутки_sol": round(min(пс.values()), 6),
            "доля_итога_у_1_процента": (round(100 * sum(верх[:max(1, len(верх) // 100)])
                                              / sum(v), 1) if sum(v) > 0 else None)}


def половины(ряды: list) -> tuple:
    дни = sorted({x["сутки"] for x in ряды})
    if len(дни) < 2:
        return (None, None)
    сер = дни[len(дни) // 2]
    a = [x for x in ряды if x["сутки"] < сер]
    b = [x for x in ряды if x["сутки"] >= сер]
    return ({"итог_sol": round(sum(x["итог"] for x in a), 6)} if a else None,
            {"итог_sol": round(sum(x["итог"] for x in b), 6)} if b else None)


def глубина_ок(ряды: list, б: float) -> tuple:
    рез = [x["резерв"] for x in ряды if x.get("резерв")]
    if not рез:
        return False, None
    доля = sum(1 for r in рез if б <= ДОЛЯ_РЕЗЕРВА * r) / len(рез)
    return доля >= ДОЛЯ_ГЛУБИНЫ, round(100 * доля, 1)


def перестановки(все_по_суткам: dict, выбор_по_суткам: dict, seed: int = 20261009) -> float | None:
    if not выбор_по_суткам:
        return None
    настоящий = sum(sum(v) for v in выбор_по_суткам.values())
    рнд = random.Random(seed)
    превзошли = 0
    for _ in range(ПОВТОРОВ):
        s = 0.0
        for д, вс in все_по_суткам.items():
            k = len(выбор_по_суткам.get(д, []))
            if k and вс:
                s += sum(рнд.sample(вс, min(k, len(вс))))
        if s >= настоящий:
            превзошли += 1
    return (превзошли + 1) / (ПОВТОРОВ + 1)


def ф(v, формат="+.4f"):
    return "—" if v is None else format(v, формат)


def main() -> int:  # noqa: PLR0912, PLR0915
    import podbivka_run as R  # noqa: PLC0415
    р_ = argparse.ArgumentParser()
    р_.add_argument("--proverka-s", required=True, help="сутки с этой даты -- проверка")
    р_.add_argument("--metka", default="")
    а = р_.parse_args()

    сырые = загрузить()
    if not сырые:
        print("нет путей цены: сначала podbivka_tg_cena.py", flush=True)
        return 1
    for x in сырые:
        x["сутки"] = (x.get("utc") or "")[:10]
    каналы = sorted({x["канал"] for x in сырые})
    дни = sorted({x["сутки"] for x in сырые if x["сутки"]})
    print(f"коллов {len(сырые)}, каналов {len(каналы)}, суток {len(дни)} "
          f"({дни[0] if дни else '?'} .. {дни[-1] if дни else '?'})", flush=True)

    # чужие покупки вперёд нас -- это описание, а не фильтр
    вперёд = {}
    for t in ("1с", "2с", "3с"):
        пк = [(x.get("вперёд") or {}).get(t, {}).get("покупок") or 0 for x in сырые]
        кш = [(x.get("вперёд") or {}).get(t, {}).get("кошельков") or 0 for x in сырые]
        сл = [(x.get("вперёд") or {}).get(t, {}).get("sol") or 0 for x in сырые]
        вперёд[t] = {"покупок": V.стат(пк), "кошельков": V.стат(кш), "sol": V.стат(сл, 3),
                     "доля_с_покупкой": round(100 * sum(1 for y in пк if y) / max(1, len(пк)), 1)}
    пики = [x["пик"]["рост_пп"] for x in сырые if x.get("пик")]
    через = [x["пик"]["через_с"] for x in сырые if x.get("пик")]

    # круги: один проход, все комбинации
    круги: dict = collections.defaultdict(list)
    для_нуля: dict = collections.defaultdict(lambda: collections.defaultdict(list))
    без_модели = 0
    for x in сырые:
        if not модель(x):
            без_модели += 1
            continue
        for м in МЕСТА:
            for h in ВЫХОДЫ:
                for б in БИЛЕТЫ:
                    к = круг(x, м, h, б)
                    if not к:
                        continue
                    ряд = {"сутки": x["сутки"], "канал": x["канал"], "минт": x["минт"],
                           "итог": к["итог_sol"], "резерв": к["резерв_вход_sol"]}
                    круги[(м, h, б)].append(ряд)
                    для_нуля[(м, h, б)][x["сутки"]].append(к["итог_sol"])
    print(f"кругов {sum(len(v) for v in круги.values())}, без модели {без_модели}", flush=True)

    строки = []
    for (м, h, б), все in sorted(круги.items()):
        for канал in ["ВСЕ", *каналы]:
            ряды = все if канал == "ВСЕ" else [y for y in все if y["канал"] == канал]
            подб = [y for y in ряды if y["сутки"] < а.proverka_s]
            пров = [y for y in ряды if y["сутки"] >= а.proverka_s]
            if len(подб) < N_МИН_ПОДБОР or not пров:
                continue
            сп, спр = свод(подб, б), свод(пров, б)
            if (сп.get("итог_sol") or 0) <= 0 or (сп.get("итог_без_5_лучших_sol") or 0) <= 0:
                continue                      # подбор не прошёл -- на проверку не смотрим
            выбор: dict = collections.defaultdict(list)
            for y in пров:
                выбор[y["сутки"]].append(y["итог"])
            нуль = {д: v for д, v in для_нуля[(м, h, б)].items() if д >= а.proverka_s}
            p = перестановки(нуль, выбор)
            гл, дгл = глубина_ок(пров, б)
            пол = половины(пров)
            да, нет = V.порог(спр, пол, p, гл, сп)
            строки.append({"канал": канал, "место": f"пост+{м}", "удержание_с": h, "билет": б,
                           "подбор_n": сп["n"], "подбор_sol": сп["итог_sol"],
                           "p": p, "глубина": гл, "доля_глубины": дгл,
                           "половина_1": (пол[0] or {}).get("итог_sol"),
                           "половина_2": (пол[1] or {}).get("итог_sol"),
                           "проходит": да, "почему_нет": нет, **спр})
    строки.sort(key=lambda x: -(x.get("sol_в_сутки") or 0))
    прошли = [x for x in строки if x["проходит"]]
    # поправка на множественный отбор: Холм по числу строк, дошедших до проверки
    по_p = sorted((x for x in строки if x.get("p") is not None), key=lambda x: x["p"])
    m = len(по_p)
    for i, x in enumerate(по_p):
        x["холм"] = x["p"] <= 0.05 / (m - i) if m else False
    прошли_строго = [x for x in прошли if x.get("холм")]
    print(f"строк до проверки {len(строки)}, прошли порог {len(прошли)}, "
          f"с поправкой Холма {len(прошли_строго)}", flush=True)

    тело = {"что": "коллы TG-каналов против нашего входа", "коллов": len(сырые),
            "каналов": len(каналы), "каналы": каналы, "сутки": дни,
            "проверка_с": а.proverka_s, "без_модели": без_модели,
            "калибровка": {"издержки_sol": ИЗДЕРЖКИ, "к_g": К_G},
            "вперёд_нас": вперёд, "пик_рост_пп": V.стат(пики), "пик_через_с": V.стат(через),
            "строк_до_проверки": len(строки), "прошли": len(прошли),
            "прошли_с_холмом": len(прошли_строго), "строки": строки}
    ф_ = П / "tg_itog.json"
    ф_.write_text(json.dumps(тело, ensure_ascii=False, indent=1, default=str), encoding="utf-8")
    R.записано(ф_)
    страница(тело, а.metka)
    return 0


