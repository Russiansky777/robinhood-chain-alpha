#!/usr/bin/env python3
"""Коллы TG-каналов: считается ли вход за каналом (задача владельца 09.10, п.2в-2г).

Берёт пути цены вокруг коллов (`podbivka_tg_cena.py`) и считает по каждому каналу и по всем
вместе: наш вход пост+2 с и пост+5 с, выход 10 / 30 / 60 / 120 / 300 с, билеты 0.1 / 0.3 /
0.5 SOL. Подбор и проверка разделены по суткам, порог -- тот же, что у полосы
(`podbivka_final`): на проверке не меньше 100 сделок, медиана по совершённым сделкам больше
нуля, итог без пяти лучших в плюсе, обе половины проверки в плюсе, худшие сутки не хуже
-2 SOL, уровень случайности p не больше 0.05, билет не больше 2 % резерва пула на 80 %
сделок.

Чем вход за каналом отличается от входа за кошельком. Состояние пула на пост+2 с уже
содержит чужие покупки этих двух секунд -- то есть наценка, которую мы платим из-за тех, кто
успел вперёд нас, посчитана по цепи, а не предположена. Сколько именно чужих покупок прошло
за 1 / 2 / 3 секунды, выписывается отдельным столбцом.

Уровень случайности: нуль -- случайный выбор того же числа коллов в тех же сутках из всех
коллов окна. Так проверяется канал, а не то, что коллы вообще бывают прибыльными.

Только чтение. Выход: docs/podbivka_tg.md и data/podbivka/tg_itog.json.
"""
