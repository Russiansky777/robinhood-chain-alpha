"""Две тревоги владельцу: «политик нет» и «сигналы идут, а покупок ноль».

ЗАЧЕМ ОТДЕЛЬНЫМ МОДУЛЕМ. Логика «когда звать владельца» решает, увидит он
поломку или нет, и проверять её надо так же строго, как деньги. В детекторе
13 тысяч строк; добавлять туда ещё и это значило бы править живую службу на
ощупь. Здесь -- чистые функции над числами, с самопроверкой на каждый случай,
а в детекторе остаётся крючок из трёх строк.

ЖИВОЙ СЛУЧАЙ, РАДИ КОТОРОГО МОДУЛЬ НАПИСАН (слово владельца 03.10, п.2).
03.10 покупки стояли с 18:33Z до 20:26Z. Служба ВСЁ ЭТО ВРЕМЯ писала в признак
жизни тревогу «файла групп нет -- политики нет, все адреса off», но это поле
никто не читал: ни строки владельцу, ни остановки. Снаружи отказы выглядели
законным отбором, потому что словами так и написано: «по группе off полоса не
торгует». Полтора часа молчания стоили примерно 8--10 сделок.

ЧЕГО ЗДЕСЬ НЕТ НАРОЧНО: ни отправки, ни сети, ни файлов. Модуль ОТВЕЧАЕТ, надо
ли звать и какими словами; отправляет вызывающий своим обычным оповещателем.
Так тревоги проверяемы без Telegram и не могут задержать горячий путь.
"""
