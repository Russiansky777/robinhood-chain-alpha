# ПОРОГ ТИШИНЫ (п.2б, «число назови»). Решений за полчаса, выше которого ноль
# отправленных покупок -- это уже тревога, а не тихий час.
#
# ОТКУДА ЧИСЛО. Признак жизни считает решения детектора по кодам (by_code). За
# мадридские сутки 03.10 их 113 769, то есть около 2370 за полчаса в обычный
# вечер. Порог 200 -- меньше десятой части обычного потока: в тихие ночные часы
# он не сработает, а при живом потоке и нуле отправок сработает обязательно.
#
# И ЧЕСТНО ПРО ПРЕДЕЛ ЭТОЙ ТРЕВОГИ: случай 03.10 она бы НЕ поймала. В том
# состоянии почти все адреса ушли в off, и сам поток решений просел до 22--33 за
# полчаса -- ниже любого разумного порога. Поэтому поломку ловит тревога (а),
# а эта -- другой случай: поток обычный, а покупок нет (подпись, баланс, гейт).
# Две тревоги не дублируют друг друга, они закрывают разные дыры.
ПОРОГ_РЕШЕНИЙ_ЗА_ОКНО = 200
ОКНО_ТИШИНЫ_С = 1800.0

# Хвост тревоги (а) из bloom_source_groups._откат: по нему отличается «политики
# нет вовсе» от «осталась прежняя политика». Первое -- стоп торговли, второе --
# работа на старых числах. Звать владельца надо в обоих, но разными словами.
ХВОСТ_НЕТ_ПОЛИТИК = "политики нет, все адреса off"
ХВОСТ_ПРЕЖНЯЯ = "осталась прежняя политика"


def тревога_групп(свод: dict | None) -> dict:
    """Надо ли звать владельца из-за файла групп. {звать, ключ, текст, почему}.

    НЕЗНАНИЕ -- ПОВОД ЗВАТЬ. Свода нет или он не словарь -- значит признак
    жизни собрался не до конца, и молчать об этом нельзя.
    """
    из_ = {"звать": False, "ключ": None, "текст": None, "почему": None}
    if not isinstance(свод, dict):
        из_.update(звать=True, ключ="gruppy:net-svoda",
                   текст=("ТРЕВОГА: свода групп в признаке жизни нет вовсе -- "
                          "политику источников проверить нечем"),
                   почему="свода нет")
        return из_
    тревога = свод.get("alarm") or свод.get("тревога")
    if not тревога:
        return из_
    текст_тревоги = str(тревога)
    политик = свод.get("policies") or {}
    файл = свод.get("file") or "не назван"
    if ХВОСТ_НЕТ_ПОЛИТИК in текст_тревоги:
        из_.update(
            звать=True, ключ="gruppy:net-politik",
            почему=ХВОСТ_НЕТ_ПОЛИТИК,
            текст=("ТРЕВОГА: политики источников НЕТ -- все адреса в группе off, "
                   "полоса откажет каждому пути и покупки встанут. "
                   f"Служба говорит: {текст_тревоги}. "
                   f"Файл групп: {файл}. "
                   "Проверить BLOOM_SOURCE_GROUPS в окружении службы."))
        return из_
    if ХВОСТ_ПРЕЖНЯЯ in текст_тревоги:
        из_.update(
            звать=True, ключ="gruppy:prezhnjaja-politika",
            почему=ХВОСТ_ПРЕЖНЯЯ,
            текст=("ТРЕВОГА: файл групп не прочитан, служба работает на ПРЕЖНЕЙ "
                   f"политике ({len(политик)} групп). Говорит: {текст_тревоги}. "
                   f"Файл групп: {файл}. Торговля идёт, но правки групп не видны."))
        return из_
    из_.update(звать=True, ключ="gruppy:inaja-trevoga", почему="иная тревога",
               текст=(f"ТРЕВОГА по файлу групп: {текст_тревоги}. Файл: {файл}."))
    return из_


def решений_всего(свод_кодов: dict | None) -> int:
    """Сумма решений по кодам. Не словарь -- ноль, а не падение."""
    if not isinstance(свод_кодов, dict):
        return 0
    всего = 0
    for з in свод_кодов.values():
        try:
            всего += int(з)
        except (TypeError, ValueError):
            continue
    return всего


class СторожТишины:
    """Помнит пары (время, решений, отправлено) и отвечает: пора ли звать.

    СЧЁТЧИКИ НАКОПИТЕЛЬНЫЕ ОТ СТАРТА ПРОЦЕССА, поэтому сравниваются РАЗНОСТИ:
    иначе после перезапуска тревога сработала бы на пустом месте.
    """

    def __init__(self, *, окно_с: float = ОКНО_ТИШИНЫ_С,
                 порог: int = ПОРОГ_РЕШЕНИЙ_ЗА_ОКНО):
        self.окно_с = float(окно_с)
        self.порог = int(порог)
        self._ряд: list = []

    def добавить(self, *, когда: float, решений: int, отправлено: int) -> dict:
        """{звать, ключ, текст, почему, решений_за_окно, отправлено_за_окно}."""
        из_ = {"звать": False, "ключ": None, "текст": None, "почему": None,
               "решений_за_окно": None, "отправлено_за_окно": None}
        self._ряд.append((float(когда), int(решений), int(отправлено)))
        # Хвост длиннее окна не нужен, но ОДНУ точку старее окна держим: по ней
        # и считается разность за полное окно.
        пока = [т for т in self._ряд if т[0] >= когда - self.окно_с * 2]
        self._ряд = пока[-400:]
        старые = [т for т in self._ряд if когда - т[0] >= self.окно_с]
        if not старые:
            из_["почему"] = (f"окна ещё нет: наблюдаем "
                             f"{когда - self._ряд[0][0]:.0f} с из {self.окно_с:.0f}")
            return из_
        начало = старые[-1]
        d_реш = решений - начало[1]
        d_отпр = отправлено - начало[2]
        из_["решений_за_окно"] = d_реш
        из_["отправлено_за_окно"] = d_отпр
        if d_реш < 0 or d_отпр < 0:
            из_["почему"] = ("счётчики пошли назад -- служба перезапускалась, "
                             "окно считаем заново")
            self._ряд = [self._ряд[-1]]
            return из_
        if d_отпр > 0:
            из_["почему"] = f"покупки идут: отправлено {d_отпр} за окно"
            return из_
        if d_реш < self.порог:
            из_["почему"] = (f"тихий час: решений {d_реш} за окно при пороге "
                             f"{self.порог} -- это не тревога")
            return из_
        из_.update(
            звать=True, ключ="tishina:nol-pokupok",
            почему=f"решений {d_реш} >= {self.порог}, отправлено 0",
            текст=("ТРЕВОГА: сигналы идут, а отправленных покупок НОЛЬ за "
                   f"{self.окно_с / 60:.0f} минут. Решений детектора за окно "
                   f"{d_реш} (порог {self.порог}), отправок полосы 0. "
                   "Смотреть: политика групп, подпись, баланс полосы, гейты."))
        return из_


class ОдинРаз:
    """Шлёт один раз на каждый РАЗНЫЙ текст, а не на каждый пульс.

    Пульс -- раз в минуту; без этого тревога превратилась бы в полторы тысячи
    сообщений за сутки, и владелец перестал бы их читать -- то есть тревога
    сломалась бы именно тогда, когда нужна.
    """

    def __init__(self, *, повтор_через_с: float = 6 * 3600.0):
        self.повтор_через_с = float(повтор_через_с)
        self._послано: dict = {}

    def надо(self, ключ: str | None, текст: str | None, *,
             когда: float | None = None) -> bool:
        if not ключ or not текст:
            return False
        когда = time.time() if когда is None else float(когда)
        было = self._послано.get(ключ)
        if было is not None and было[0] == текст and когда - было[1] < self.повтор_через_с:
            return False
        self._послано[ключ] = (текст, когда)
        return True

    def снять(self, ключ: str) -> None:
        """Тревога ушла -- забыть, чтобы следующий раз снова позвал."""
        self._послано.pop(ключ, None)


ЖДЁМ_ПРОВЕРОК = 31


def self_test() -> int:  # noqa: C901, PLR0915
    было = [0]
    плохо = [0]

    def chk(имя, усл, факт=""):
        было[0] += 1
        print(("  ok   " if усл else " ПЛОХО ") + имя + ("" if усл else f" -- {факт!r}"))
        if not усл:
            плохо[0] += 1

    print("bloom_trevogi: самопроверка")

    # --- тревога (а): файл групп
    р = тревога_групп({"alarm": None, "policies": {"leader": {}}})
    chk("тревоги нет -- звать не надо", р["звать"] is False, р)

    р = тревога_групп({"alarm": f"файла групп x нет -- {ХВОСТ_НЕТ_ПОЛИТИК}",
                        "policies": {}, "file": None})
    chk("«политики нет, все адреса off» -- ЗВАТЬ (случай 03.10)",
        р["звать"] is True, р)
    chk("и в тексте сказано, что покупки встанут",
        "покупки встанут" in (р["текст"] or ""), р)
    chk("и назван BLOOM_SOURCE_GROUPS -- куда смотреть",
        "BLOOM_SOURCE_GROUPS" in (р["текст"] or ""), р)
    chk("ключ отличает этот случай от прочих",
        р["ключ"] == "gruppy:net-politik", р)

    р2 = тревога_групп({"alarm": f"файл групп не прочитан (ValueError) -- {ХВОСТ_ПРЕЖНЯЯ}",
                         "policies": {"a": {}, "b": {}}, "file": "/x/y.json"})
    chk("«осталась прежняя политика» -- тоже звать, но ДРУГИМИ словами",
        р2["звать"] is True and р2["ключ"] == "gruppy:prezhnjaja-politika", р2)
    chk("и сказано, что торговля идёт", "Торговля идёт" in (р2["текст"] or ""), р2)
    chk("и названо число групп прежней политики", "2 групп" in (р2["текст"] or ""), р2)
    chk("ключи двух случаев РАЗНЫЕ -- иначе один заглушил бы другой",
        р["ключ"] != р2["ключ"], (р["ключ"], р2["ключ"]))

    р3 = тревога_групп(None)
    chk("свода нет вовсе -- ЗВАТЬ (незнание не повод молчать)",
        р3["звать"] is True and р3["ключ"] == "gruppy:net-svoda", р3)
    р4 = тревога_групп({"alarm": "что-то своё"})
    chk("незнакомая тревога -- звать, и текст её несёт",
        р4["звать"] is True and "что-то своё" in (р4["текст"] or ""), р4)
    р5 = тревога_групп({"тревога": f"x -- {ХВОСТ_НЕТ_ПОЛИТИК}"})
    chk("русский ключ «тревога» читается так же, как alarm",
        р5["звать"] is True, р5)

    # --- сумма решений
    chk("сумма решений по кодам", решений_всего({"A": 3, "B": 4}) == 7)
    chk("мусор в значениях не роняет сумму",
        решений_всего({"A": 3, "B": "x", "C": None}) == 3)
    chk("не словарь -- ноль, а не падение", решений_всего(None) == 0)

    # --- тревога (б): тишина
    с = СторожТишины(окно_с=1800.0, порог=200)
    р = с.добавить(когда=1000.0, решений=0, отправлено=0)
    chk("первая точка -- окна ещё нет, звать нельзя", р["звать"] is False, р)
    chk("и сказано, сколько наблюдаем", "окна ещё нет" in (р["почему"] or ""), р)
    р = с.добавить(когда=1000.0 + 1799, решений=5000, отправлено=0)
    chk("окно не добрало секунду -- всё ещё не звать", р["звать"] is False, р)
    р = с.добавить(когда=1000.0 + 1801, решений=5000, отправлено=0)
    chk("решений выше порога, отправок 0 -- ЗВАТЬ", р["звать"] is True, р)
    chk("и число решений за окно названо", р["решений_за_окно"] == 5000, р)
    chk("и в тексте стоит порог", "порог 200" in (р["текст"] or ""), р)

    с2 = СторожТишины(окно_с=1800.0, порог=200)
    с2.добавить(когда=0.0, решений=0, отправлено=0)
    р = с2.добавить(когда=1801.0, решений=5000, отправлено=1)
    chk("отправка была -- не звать, даже при тысячах решений",
        р["звать"] is False and "покупки идут" in (р["почему"] or ""), р)

    с3 = СторожТишины(окно_с=1800.0, порог=200)
    с3.добавить(когда=0.0, решений=0, отправлено=0)
    р = с3.добавить(когда=1801.0, решений=150, отправлено=0)
    chk("решений меньше порога -- тихий час, не тревога", р["звать"] is False, р)
    chk("и это названо словами «тихий час»", "тихий час" in (р["почему"] or ""), р)

    с4 = СторожТишины(окно_с=1800.0, порог=200)
    с4.добавить(когда=0.0, решений=9000, отправлено=5)
    р = с4.добавить(когда=1801.0, решений=10, отправлено=0)
    chk("счётчики пошли назад (перезапуск) -- не звать, окно заново",
        р["звать"] is False and "перезапуск" in (р["почему"] or ""), р)

    # --- один раз
    о = ОдинРаз(повтор_через_с=3600.0)
    chk("первый раз -- шлём", о.надо("k", "текст", когда=0.0) is True)
    chk("тот же текст в тот же пульс -- НЕ шлём",
        о.надо("k", "текст", когда=60.0) is False)
    chk("текст изменился -- шлём снова", о.надо("k", "другой", когда=120.0) is True)
    chk("через срок повтора -- шлём снова",
        о.надо("k", "другой", когда=120.0 + 3601) is True)
    chk("пустой ключ или текст -- ничего не шлём",
        о.надо(None, "т") is False and о.надо("k", None) is False)
    о.снять("k")
    chk("после снятия тревоги следующий раз снова зовёт",
        о.надо("k", "другой", когда=200.0) is True)

    print(f"\nпроверок {было[0]}, ждали {ЖДЁМ_ПРОВЕРОК}, не прошло {плохо[0]}")
    if было[0] != ЖДЁМ_ПРОВЕРОК:
        print(" ПЛОХО число проверок разошлось с объявленным")
        return 1
    return 1 if плохо[0] else 0


if __name__ == "__main__":
    sys.exit(self_test() if "--self-test" in sys.argv else self_test())
