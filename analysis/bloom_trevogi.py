ХВОСТ_ПРЕЖНЯЯ = "осталась прежняя политика"


def тревога_групп(свод: dict | None) -> dict:
    """Надо ли звать владельца из-за файла групп. {звать, ключ, текст, почему}.

    НЕЗНАНИЕ -- ПОВОД ЗВАТЬ. Свода нет или он не словарь -- значит признак
    жизни собрался не до конца, и молчать об этом нельзя.
    """
    из_ = {"звать": False, "ключ": None, "что": None, "подробно": None,
           "почему": None}
    if not isinstance(свод, dict):
        из_.update(звать=True, ключ="gruppy:net-svoda", почему="свода нет",
                   что="свода групп в признаке жизни нет",
                   подробно="политику источников проверить нечем")
        return из_
    тревога = свод.get("alarm") or свод.get("тревога")
    if not тревога:
        return из_
    текст_тревоги = str(тревога)
    политик = свод.get("policies") or {}
    файл = свод.get("file") or "не назван"
    if ХВОСТ_НЕТ_ПОЛИТИК in текст_тревоги:
        из_.update(
            звать=True, ключ="gruppy:net-politik",
            почему=ХВОСТ_НЕТ_ПОЛИТИК,
            что="политики источников НЕТ, все адреса в группе off",
            подробно=("покупки встанут: полоса откажет каждому пути. "
                      f"служба говорит: {текст_тревоги}; файл групп: {файл}; "
                      "смотреть BLOOM_SOURCE_GROUPS в окружении"))
        return из_
    if ХВОСТ_ПРЕЖНЯЯ in текст_тревоги:
        из_.update(
            звать=True, ключ="gruppy:prezhnjaja-politika",
            почему=ХВОСТ_ПРЕЖНЯЯ,
            что="файл групп не прочитан, работаем на ПРЕЖНЕЙ политике",
            подробно=(f"групп в прежней политике {len(политик)}; торговля идёт, "
                      f"но правки групп не видны; служба говорит: {текст_тревоги}; "
                      f"файл групп: {файл}"))
        return из_
    из_.update(звать=True, ключ="gruppy:inaja-trevoga", почему="иная тревога",
               что="тревога по файлу групп",
               подробно=f"{текст_тревоги}; файл: {файл}")
    return из_


def решений_всего(свод_кодов: dict | None) -> int:
    """Сумма решений по кодам. Не словарь -- ноль, а не падение."""
    if not isinstance(свод_кодов, dict):
        return 0
    всего = 0
    for з in свод_кодов.values():
        try:
            всего += int(з)
        except (TypeError, ValueError):
            continue
    return всего


def по_политике(why_not) -> bool:
    """Отказ полосы -- ПО ПОЛИТИКЕ, а не по поломке. Чистая функция."""
    т = str(why_not or "")
    return any(м in т for м in ПОЛИТИКА_МЕТКИ)


def кандидат_полосы(*, stage, why_not=None, sent: bool = False) -> dict:
    """Кандидат ли эта попытка полосы. Чистая функция. {кандидат, политика, почему}.

    Слово владельца 04.10: кандидат -- это живая группа, ДОШЕДШАЯ ДО СБОРКИ ИЛИ
    ОТПРАВКИ; отказы по политике кандидатами не считаются, но в тексте тревоги
    показываются.

    ОТПРАВЛЕННАЯ ПОПЫТКА -- КАНДИДАТ ВСЕГДА, И ЭТО НЕ МЕЛОЧЬ: иначе
    "кандидатов 0, отправок 1" стало бы возможным, и числа в тревоге
    противоречили бы друг другу.
    """
    с = str(stage or "?")
    пол = по_политике(why_not)
    из_ = {"кандидат": False, "политика": пол, "стадия": с, "почему": None}
    if sent or с == "sent":
        из_.update(кандидат=True, политика=False, почему="отправлено")
        return из_
    if с not in СТАДИИ_ДОШЛИ:
        из_["почему"] = (f"стадия {с}: до сборки полосы не дошло"
                          + (" (отказ по политике)" if пол else ""))
        return из_
    if пол:
        из_["почему"] = "дошло до сборки, но отказ по политике"
        return из_
    из_.update(кандидат=True, почему=f"стадия {с}: дошло до сборки")
    return из_


class СторожТишины:
    """Помнит (время, кандидатов, отправлено) и отвечает: пора ли звать.

    СЧЁТЧИКИ НАКОПИТЕЛЬНЫЕ ОТ СТАРТА ПРОЦЕССА, поэтому сравниваются РАЗНОСТИ:
    иначе после перезапуска тревога сработала бы на пустом месте.

    РЕДАКЦИЯ ВЛАДЕЛЬЦА 04.10: кандидаты полосы вместо всех решений, окно 90
    минут, порог 3 кандидата при нуле отправок, не чаще раза в окно.
    """

    def __init__(self, *, окно_с: float = ОКНО_ТИШИНЫ_С,
                 порог: int = ПОРОГ_КАНДИДАТОВ_ЗА_ОКНО,
                 повтор_через_с: float = ПОВТОР_ТРЕВОГИ_ТИШИНЫ_С):
        self.окно_с = float(окно_с)
        self.порог = int(порог)
        self.повтор_через_с = float(повтор_через_с)
        self._ряд: list = []
        self._последняя_тревога: float | None = None

    def добавить(self, *, когда: float, кандидатов: int, отправлено: int,
                  политика: dict | None = None) -> dict:
        """{звать, ключ, что, подробно, почему, кандидатов_за_окно, отправлено_за_окно}.

        политика -- накопительный свод "причина отказа по политике -> сколько
        раз". Разности по нему идут в ТЕКСТ тревоги и ни на что не влияют:
        владелец велел их показывать, но кандидатами не считать.
        """
        из_ = {"звать": False, "ключ": None, "что": None, "подробно": None,
                "почему": None, "кандидатов_за_окно": None,
                "отправлено_за_окно": None, "политика_за_окно": None}
        пол = {str(к): int(з) for к, з in (политика or {}).items()
               if isinstance(з, (int, float))}
        self._ряд.append((float(когда), int(кандидатов), int(отправлено), пол))
        # Хвост длиннее окна не нужен, но ОДНУ точку старее окна держим: по ней
        # и считается разность за полное окно.
        пока = [т for т in self._ряд if т[0] >= когда - self.окно_с * 2]
        self._ряд = пока[-400:]
        старые = [т for т in self._ряд if когда - т[0] >= self.окно_с]
        if not старые:
            из_["почему"] = (f"окна ещё нет: наблюдаем "
                              f"{когда - self._ряд[0][0]:.0f} с из {self.окно_с:.0f}")
            return из_
        начало_ = старые[-1]
        d_канд = кандидатов - начало_[1]
        d_отпр = отправлено - начало_[2]
        из_["кандидатов_за_окно"] = d_канд
        из_["отправлено_за_окно"] = d_отпр
        if d_канд < 0 or d_отпр < 0:
            из_["почему"] = ("счётчики пошли назад -- служба перезапускалась, "
                              "окно считаем заново")
            self._ряд = [self._ряд[-1]]
            return из_
        # РАЗНОСТИ ПО ПОЛИТИКЕ -- ТОЛЬКО В ТЕКСТ. Ключ, пропавший из свежего
        # свода (служба перезапускалась), в минус не уходит: отрицательные
        # разности отбрасываются, иначе в тревоге появились бы числа, за
        # которыми ничего не стоит.
        раньше = начало_[3]
        пол_окно = {к: (з - int(раньше.get(к, 0))) for к, з in пол.items()}
        пол_окно = {к: з for к, з in пол_окно.items() if з > 0}
        из_["политика_за_окно"] = пол_окно
        if d_отпр > 0:
            из_["почему"] = f"покупки идут: отправлено {d_отпр} за окно"
            return из_
        if d_канд < self.порог:
            из_["почему"] = (f"кандидатов полосы {d_канд} за окно при пороге "
                              f"{self.порог} -- это не тревога, а отсутствие "
                              "кандидатов"
                              + (f"; по политике отсечено "
                                 f"{sum(пол_окно.values())}" if пол_окно else ""))
            return из_
        # НЕ ЧАЩЕ РАЗА В ОКНО (слово владельца 04.10). Условие уже сошлось, и
        # это говорится прямо: холод -- не "тревоги нет", а "уже звали".
        if (self._последняя_тревога is not None
                and когда - float(self._последняя_тревога) < self.повтор_через_с):
            из_["почему"] = (f"условие сошлось, но звали "
                              f"{когда - float(self._последняя_тревога):.0f} с "
                              f"назад при холоде {self.повтор_через_с:.0f} с")
            return из_
        self._последняя_тревога = float(когда)
        хвост = ("; по политике отсечено: "
                 + ", ".join(f"{к} -- {з}" for к, з in sorted(пол_окно.items()))
                 ) if пол_окно else "; отказов по политике за окно нет"
        из_.update(
            звать=True, ключ="tishina:nol-pokupok",
            почему=f"кандидатов {d_канд} >= {self.порог}, отправлено 0",
            что=(f"кандидаты полосы есть, а отправленных покупок НОЛЬ за "
                 f"{self.окно_с / 60:.0f} минут"),
            подробно=(f"кандидатов полосы за окно {d_канд} при пороге "
                       f"{self.порог}, отправок 0{хвост}; смотреть политику "
                       "групп, подпись, баланс полосы и гейты"))
        return из_


class ОдинРаз:
    """Шлёт один раз на каждый РАЗНЫЙ текст, а не на каждый пульс.

    Пульс -- раз в минуту; без этого тревога превратилась бы в полторы тысячи
    сообщений за сутки, и владелец перестал бы их читать -- то есть тревога
    сломалась бы именно тогда, когда нужна.
    """

    def __init__(self, *, повтор_через_с: float = 6 * 3600.0):
        self.повтор_через_с = float(повтор_через_с)
        self._послано: dict = {}

    def надо(self, ключ: str | None, что: str | None, *,
             когда: float | None = None) -> bool:
        """что -- неизменная часть тревоги, по ней и считается «то же самое».

        Подробности меняются от пульса к пульсу (числа в окне), и сравнивать
        по ним значило бы звать владельца каждую минуту.
        """
        текст = что
        if not ключ or not текст:
            return False
        когда = time.time() if когда is None else float(когда)
        было = self._послано.get(ключ)
        if было is not None and было[0] == текст and когда - было[1] < self.повтор_через_с:
            return False
        self._послано[ключ] = (текст, когда)
        return True

    def снять(self, ключ: str) -> None:
        """Тревога ушла -- забыть, чтобы следующий раз снова позвал."""
        self._послано.pop(ключ, None)


