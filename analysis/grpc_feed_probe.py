КАНАЛ_WS = "helius_ws"
КАНАЛ_GRPC = "grpc"
КАНАЛ_GRPC2 = "grpc2"
ГРУППА_НАША = "источники"
ГРУППА_РАЗГОН = "разгонные"

# Сколько держать записи в памяти для сводки за окно.
ОКНО_S = 3600.0
# Слот Solana -- около 0.4 секунды. Нужно там, где blockTime не пришёл, а
# слот пришёл: слот тоже время, просто в других единицах.
СЕКУНД_В_СЛОТЕ = 0.4


def _процентиль(значения: list, доля: float) -> float | None:
    if not значения:
        return None
    з = sorted(значения)
    i = min(len(з) - 1, max(0, int(round(доля * (len(з) - 1)))))
    return з[i]


class Гонка:
    """Учёт НЕСКОЛЬКИХ каналов: все приходы одной подписи, все пары между ними.

    Почему не "первый и второй". С двумя каналами хватало пары, но с тремя
    (Helius WS, Shyft AMS, Shyft FRA) третий приход той же подписи -- это не
    дубль, а ещё одна точка сравнения. Поэтому хранятся ВСЕ времена по
    каналам, а дельты считаются по каждой паре каналов отдельно: каждый
    против Helius WS и Shyft-каналы между собой.

    Дубль -- это повтор ТОГО ЖЕ канала по той же подписи, и он считается
    отдельно: у детектора подписка на каждый адрес своя, и транзакция с двумя
    нашими адресами приходит дважды. Опережением это не является.

    Память не растёт: окно последних записей, старые подписи выселяются.
    """

    def __init__(self, окно_s: float = ОКНО_S, отстой_s: float = 5.0) -> None:
        self.окно_s = float(окно_s)
        # Подпись считается "только по одному каналу" не сразу: второму каналу
        # надо дать время дойти. Без отстоя доля "без пары" считала бы свежие
        # секунды и завышалась на ровном месте.
        self.отстой_s = float(отстой_s)
        self.события: dict = {}     # подпись -> {"t": {канал: t}, "группа", "слот"}
        self.порядок: list = []     # (t_первого, подпись) для выселения
        self.по_каналам: dict = {}  # канал -> сколько сообщений пришло
        self.дубли: dict = {}       # канал -> повторы той же подписи
        self.последний_t: float = 0.0

    def пришло(self, канал: str, подпись: str, *, слот: int | None = None,
                t: float | None = None, группа: str = ГРУППА_НАША) -> dict | None:
        """Одно сообщение. Возвращает описание пары, если она только что сошлась."""
        t = time.monotonic() if t is None else float(t)
        self.последний_t = max(self.последний_t, t)
        self.по_каналам[канал] = self.по_каналам.get(канал, 0) + 1
        if not подпись:
            return None
        з = self.события.get(подпись)
        if з is None:
            self.события[подпись] = {"t": {канал: t}, "группа": группа,
                                      "слот": слот, "первый": t}
            self.порядок.append((t, подпись))
            self._выселить(t)
            return None
        if канал in з["t"]:
            self.дубли[канал] = self.дубли.get(канал, 0) + 1
            return None
        было_каналов = sorted(з["t"].items(), key=lambda kv: kv[1])
        з["t"][канал] = t
        if з.get("слот") is None:
            з["слот"] = слот
        первый_канал, первый_t = было_каналов[0]
        пара = {"signature": подпись, "first": первый_канал, "second": канал,
                 "delta_ms": round((t - первый_t) * 1000.0, 3),
                 "group": з["группа"], "slot": з["слот"],
                 "channels": len(з["t"])}
        self._выселить(t)
        return пара

    def _выселить(self, t: float) -> None:
        граница = t - self.окно_s
        while self.порядок and self.порядок[0][0] < граница:
            _, подпись = self.порядок.pop(0)
            self.события.pop(подпись, None)

    def дельты(self, канал_a: str, канал_b: str) -> list:
        """Дельты в мс: плюс -- канал_a ПРИШЁЛ РАНЬШЕ канал_b.

        Считаются только подписи, которые видели ОБА канала: сравнивать
        приход с неприходом бессмысленно, и такие подписи идут отдельной
        строкой "без пары".
        """
        из_ = []
        for з in self.события.values():
            ta, tb = з["t"].get(канал_a), з["t"].get(канал_b)
            if ta is None or tb is None:
                continue
            из_.append((tb - ta) * 1000.0)
        return из_

    def без_пары(self, *, каналы: tuple = ()) -> dict:
        """Подписи, которые видел ровно один канал -- по каналам.

        Свежие подписи (моложе отстоя) не считаются: второй канал мог просто
        ещё не успеть.
        """
        порог = self.последний_t - self.отстой_s
        из_: dict = {}
        for з in self.события.values():
            if з["первый"] > порог:
                continue
            if len(з["t"]) != 1:
                continue
            канал = next(iter(з["t"]))
            из_[канал] = из_.get(канал, 0) + 1
        for к in каналы:
            из_.setdefault(к, 0)
        return из_

    def _числа(self, дельты: list) -> dict:
        return {"pairs": len(дельты),
                 "first_share": round(sum(1 for d in дельты if d > 0) / len(дельты), 4),
                 "median_ms": round(statistics.median(дельты), 2),
                 "p10_ms": round(_процентиль(дельты, 0.10), 2),
                 "p90_ms": round(_процентиль(дельты, 0.90), 2),
                 "p95_ms": round(_процентиль(дельты, 0.95), 2),
                 "mean_ms": round(sum(дельты) / len(дельты), 2)}

    def сводка(self, *, каналы: tuple = (КАНАЛ_GRPC, КАНАЛ_GRPC2),
                база: str = КАНАЛ_WS) -> dict:
        """Числа, и только наши. Плюс означает "опередил базу".

        Кроме сравнения с базой (Helius WS) даётся сравнение каналов между
        собой: владельцу нужен и вопрос "прод против беты", а не только
        "каждый против нашего WS".
        """
        все = tuple([база] + [к for к in каналы])
        из_ = {"base": база,
                "messages": dict(self.по_каналам),
                "duplicates": dict(self.дубли),
                "unpaired_single_channel": self.без_пары(каналы=все),
                "by_channel": {}, "by_group": {}, "pairwise": {}}
        всего_пар = 0
        for канал in каналы:
            д = self.дельты(канал, база)
            if not д:
                continue
            всего_пар = max(всего_пар, len(д))
            из_["by_channel"][канал] = self._числа(д)
        из_["pairs_total"] = sum(1 for з in self.события.values() if len(з["t"]) > 1)
        for i, a in enumerate(все):
            for b in все[i + 1:]:
                д = self.дельты(a, b)
                if д:
                    из_["pairwise"][f"{a}_vs_{b}"] = self._числа(д)
        for группа in (ГРУППА_НАША, ГРУППА_РАЗГОН):
            по_группе: dict = {}
            for канал in каналы:
                д = [(з["t"].get(база, 0) - з["t"].get(канал, 0)) * 1000.0
                      for з in self.события.values()
                      if з["группа"] == группа
                      and з["t"].get(база) is not None
                      and з["t"].get(канал) is not None]
                if д:
                    по_группе[канал] = self._числа(д)
            if по_группе:
                из_["by_group"][группа] = по_группе
        return из_


def скорость_адреса(helius, адрес: str, *, предел: int = 50) -> dict:
    """Сколько транзакций в минуту у адреса -- по его же подписям.

    Нужно именно измерить, а не прикинуть: разгонный адрес выбирается ради
    выборки, а не ради потока. На прогоне 13:49Z два адреса, взятых как
    "самые частые подписанты блока", дали 3142 сообщения за полминуты -- это
    в тысячу раз больше, чем нужно для трёхсот пар, и оплачивается кредитами
    на стороне Helius.
    """
    try:
        сп = helius.call("getSignaturesForAddress", [адрес, {"limit": предел}]) or []
    except Exception as exc:  # noqa: BLE001
        return {"known": False, "why_not": f"{type(exc).__name__}: {str(exc)[:120]}"}
    времена = sorted(z.get("blockTime") for z in сп
                      if isinstance(z, dict) and z.get("blockTime"))
    если_по_слотам = False
    if len(времена) < 3:
        # У свежих подписей blockTime приходит не всегда. Слот есть почти
        # всегда, а слот -- это время: около 0.4 с на слот. Отказ здесь
        # означал бы, что адрес выпал из отбора не по скорости, а по
        # отсутствию поля.
        слоты = sorted(z.get("slot") for z in сп
                        if isinstance(z, dict) and z.get("slot"))
        if len(слоты) < 3:
            return {"known": False,
                     "why_not": f"подписей мало: времён {len(времена)}, слотов {len(слоты)}"}
        времена = [int(x * СЕКУНД_В_СЛОТЕ) for x in слоты]
        если_по_слотам = True
    окно = времена[-1] - времена[0]
    if окно <= 0:
        # Все подписи в одной секунде -- это НЕ "скорость неизвестна", это
        # пожарный шланг. Отказ здесь был бы опасен: адрес просто выпал бы из
        # отбора вместо того, чтобы быть отвергнутым за скорость. Считаем по
        # нижней границе окна в одну секунду и помечаем, что это оценка снизу.
        return {"known": True, "per_min": round(len(времена) * 60.0, 2),
                 "window_s": 0, "signatures": len(времена),
                 "lower_bound": True, "by_slots": если_по_слотам,
                 "note": "все подписи в одной секунде -- оценка снизу"}
    return {"known": True, "per_min": round(len(времена) / (окно / 60.0), 2),
             "window_s": окно, "signatures": len(времена), "lower_bound": False,
             "by_slots": если_по_слотам}


def разгонные_по_цепи(helius, *, сколько: int = 3, исключить: set | None = None,
                       назад_слотов: int = 150, цель_в_минуту: float = 5.0,
                       кандидатов: int = 12, попыток_блока: int = 6,
                       мин_в_минуту: float = 0.2,
                       макс_в_минуту: float = 0.0) -> dict:
    """Разгонные адреса ПО ЦЕПИ, подобранные под нужную скорость выборки.

    Зачем вообще разгонные: девятнадцать наших источников дают несколько
    сделок в час, а для честной медианы нужны сотни пар. Владелец просил
    не меньше 300 парных подписей за час-два, то есть примерно 3-5
    транзакций в минуту суммарно -- НЕ больше.

    Почему не "самые частые подписанты блока", как было: такой отбор даёт
    маркет-мейкеров с сотнями транзакций в час, выборка набирается за
    секунды, а кредиты Helius горят впустую -- замер от этого не становится
    точнее. Теперь у каждого кандидата СПРАШИВАЕТСЯ его скорость, и адреса
    набираются жадно, пока сумма не покроет цель.

    Возвращает выбранные адреса вместе с ИЗМЕРЕННОЙ скоростью каждого -- в
    докладе они названы поимённо вместе со слотом, из которого взяты.
    """
    исключить = исключить or set()
    try:
        слот = helius.call("getSlot", [{"commitment": "confirmed"}])
    except Exception as exc:  # noqa: BLE001
        return {"known": False, "why_not": f"getSlot: {type(exc).__name__}: {exc}"}
    if not isinstance(слот, int):
        return {"known": False, "why_not": "getSlot не отдал число"}
    # Слот на 30 назад -- это 12 секунд, и узел такой блок ещё не отдаёт:
    # прогон 13:59Z получил -32004 "Block not available for slot". Плюс часть
    # слотов пропущена самой сетью, и блока там нет в принципе. Поэтому
    # отступаем дальше и перебираем несколько слотов, а не сдаёмся на первом.
    блок, цель, отказы_блока = None, None, []
    for шаг in range(попыток_блока):
        кандидат = слот - назад_слотов - шаг * 20
        if кандидат <= 0:
            break
        try:
            блок = helius.call("getBlock", [кандидат, {
                "encoding": "jsonParsed", "transactionDetails": "accounts",
                "rewards": False,
                "maxSupportedTransactionVersion": BD.ПОТОЛОК_ВЕРСИИ_TX}])
        except Exception as exc:  # noqa: BLE001
            отказы_блока.append(f"{кандидат}: {str(exc)[:90]}")
            блок = None
            continue
        if блок:
            цель = кандидат
            break
    if not блок:
        return {"known": False,
                 "why_not": ("ни один блок не отдался: " + "; ".join(отказы_блока[:3])
                              if отказы_блока else "блоки пусты")}
    счёт: dict = {}
    for tx in ((блок or {}).get("transactions") or []):
        ключи = ((tx or {}).get("transaction") or {}).get("accountKeys") or []
        for k in ключи:
            if not isinstance(k, dict) or not k.get("signer"):
                continue
            адрес = k.get("pubkey")
            if адрес and адрес not in исключить:
                счёт[адрес] = счёт.get(адрес, 0) + 1
    # Частота в блоке -- только порядок осмотра, а не отбор. Жёсткое правило
    # "встретился дважды" отсеивало бы как раз спокойные адреса и оставляло
    # шланги -- это поймала самопроверка, и это ровно та беда, от которой
    # разгонные и подбираются по скорости.
    порядок = [a for a, _ in sorted(счёт.items(), key=lambda kv: -kv[1])][:кандидатов]
    замеры: dict = {}
    for a in порядок:
        з = скорость_адреса(helius, a)
        if з.get("known"):
            замеры[a] = з["per_min"]
    if not замеры:
        return {"known": False, "slot": цель,
                 "why_not": "скорость ни одного кандидата не измерилась"}
    # ПОЛОСА скорости. Снизу -- чтобы адрес вообще давал поток. Сверху -- НЕ
    # сама цель: прогон 14:03Z показал, что в узкую полосу 0.2-6 не попал ни
    # один кандидат, и разгонных снова оказалось ноль. Подписанты блока
    # делятся на ботов (десятки в минуту) и разовые кошельки (доли в минуту),
    # середины между ними почти нет.
    #
    # Поэтому верх задаётся ОТДЕЛЬНО и с запасом (по умолчанию десять целей),
    # а настоящим ограничителем расхода служит сторож кредитов с порогом 70 %
    # и прогнозом -- ровно та роль, которую ему назначил владелец. Адрес на
    # 60 транзакций в минуту даёт 3600 пар в час и стоит около 17 000 кредитов
    # в сутки при пределе 300 000; шланг на 3600/мин сторож снимет сам.
    верх = макс_в_минуту if макс_в_минуту else цель_в_минуту * 10
    в_полосе = {a: v for a, v in замеры.items() if мин_в_минуту <= v <= верх}
    отброшены = {a: v for a, v in замеры.items() if a not in в_полосе}
    выбраны: list = []
    сумма = 0.0
    for a, скорость in sorted(в_полосе.items(), key=lambda kv: kv[1]):
        if сумма >= цель_в_минуту or len(выбраны) >= сколько:
            break
        выбраны.append(a)
        сумма += скорость
    запасной = ""
    if not выбраны and замеры:
        # Лучше самый спокойный из быстрых, чем пустой список: без разгонных
        # зонд не наберёт выборку вовсе, а расход всё равно стережёт сторож
        # кредитов. Подмены тут нет -- в записи сказано, что взят запасной.
        a, v = sorted(замеры.items(), key=lambda kv: kv[1])[0]
        выбраны, сумма = [a], v
        запасной = (f"в полосу {мин_в_минуту}-{верх} не попал никто; взят самый "
                     f"спокойный из измеренных: {v} транзакций в минуту")
    if not выбраны:
        return {"known": False, "slot": цель,
                 "measured": замеры,
                 "why_not": (f"ни один кандидат не попал в полосу "
                              f"{мин_в_минуту}-{верх} транзакций в минуту")}
    return {"known": True, "slot": цель, "accounts": выбраны,
             "rates_per_min": {a: замеры[a] for a in выбраны},
             "rejected_rates": {a: v for a, v in list(отброшены.items())[:6]},
             "fallback": запасной or None,
             "band": [мин_в_минуту, верх],
             "total_per_min": round(сумма, 2),
             "target_per_min": цель_в_минуту,
             "measured_candidates": len(замеры),
             "note": ("разгонные взяты по цепи из блока "
                       f"{цель} и подобраны ПО ИЗМЕРЕННОЙ скорости под цель "
                       f"{цель_в_минуту} транзакций в минуту. В торговлю не идут")}


class Бюджет:
    """Сторож расхода Helius у зонда. Детектор не трогается ни при каких условиях.

    Правило владельца 24.09: расход зонда за сутки не больше расхода
    детектора (около 9 000 кредитов), а на подходе к 70 % своего предела зонд
    САМ сбрасывает разгонные адреса и остаётся на 19 источниках.

    Два спусковых крючка, и оба нужны:

      * доля от предела >= 0.70 -- то, что просил владелец;
      * ПРОГНОЗ на сутки по текущей скорости больше предела. Без прогноза
        зонд с разгонными адресами успел бы сжечь дневной предел за пару
        часов и только потом заметить: разгонные адреса берутся как раз за
        то, что у них сотни транзакций в час.

    Сторож ничего не глушит целиком: он снимает разгонные адреса. Замер по
    нашим 19 источникам продолжается -- он и есть боевой вопрос.
    """

    def __init__(self, метр, предел: int, порог: float = 0.70) -> None:
        self.метр = метр
        self.предел = int(предел)
        self.порог = float(порог)
        self.сброшены = False
        self.почему = ""
        self.когда_utc = ""

    def кредиты(self) -> int:
        """Кредиты зонда за сегодня. При отказе учёта -- расход этой сессии."""
        try:
            from solana_rpc_client import CreditMeter  # noqa: PLC0415
            з = CreditMeter.over_budget("grpc_feed_probe", base=getattr(
                self.метр, "base", None))
            if з.get("потрачено"):
                return int(з["потрачено"])
        except Exception:  # noqa: BLE001
            pass
        return int(getattr(self.метр, "session_credits", 0) or 0)

    def состояние(self, uptime_s: float) -> dict:
        потрачено = self.кредиты()
        доля = round(потрачено / self.предел, 4) if self.предел else 0.0
        прогноз = None
        if uptime_s > 60:
            прогноз = int(потрачено / uptime_s * 86400)
        нужен_сброс = False
        почему = ""
        if доля >= self.порог:
            нужен_сброс, почему = True, (
                f"доля предела {доля} достигла порога {self.порог}: "
                f"потрачено {потрачено} из {self.предел}")
        elif прогноз is not None and прогноз > self.предел:
            нужен_сброс, почему = True, (
                f"прогноз на сутки {прогноз} кредитов больше предела "
                f"{self.предел} (потрачено {потрачено} за {int(uptime_s)} с)")
        return {"spent_today": потрачено, "limit": self.предел, "share": доля,
                 "projected_daily": прогноз, "threshold": self.порог,
                 "boosters_dropped": self.сброшены,
                 "drop_needed": нужен_сброс, "why": почему or self.почему}

    def проверить(self, uptime_s: float) -> bool:
        """True, если разгонные надо снять ПРЯМО СЕЙЧАС (и ещё не сняты)."""
        з = self.состояние(uptime_s)
        if з["drop_needed"] and not self.сброшены:
            self.сброшены = True
            self.почему = з["why"]
            self.когда_utc = time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())
            return True
        return False


class Отказы:
    """Последний отказ по каждому каналу -- в признак жизни, а не только в файл.

    Зачем отдельно. Вопрос владельца: если по gRPC ноль сообщений через пять
    минут, назвать КОД и то, что именно отверг сервер. Если отказ виден лишь
    в JSONL, за ним надо лезть на хост; в признаке жизни он виден сразу.

    Токен сюда не попадает никогда: у gRPC берутся код и текст сервера, у
    прочих -- имя класса и первые 200 символов, а сам токен уходит только в
    метаданных вызова и в тексты ошибок не подставляется.
    """

    def __init__(self) -> None:
        self.по_каналам: dict = {}
        self.счёт: dict = {}
        # Обрыв соединения -- это результат, а не помеха: бета-инфраструктура
        # может падать, и владелец спросил про обрывы отдельно.
        self.первый_utc: dict = {}

    def записать(self, канал: str, исключение) -> dict:
        код = detali = None
        try:
            import grpc  # noqa: PLC0415
            if isinstance(исключение, grpc.RpcError):
                код = str(исключение.code())
                detali = str(исключение.details())[:200]
        except Exception:  # noqa: BLE001
            pass
        з = {"utc": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
              "type": type(исключение).__name__,
              "code": код,
              "details": detali or str(исключение)[:200]}
        self.по_каналам[канал] = з
        self.счёт[канал] = self.счёт.get(канал, 0) + 1
        self.первый_utc.setdefault(канал, з["utc"])
        return з

    def сводка(self) -> dict:
        return {"last": dict(self.по_каналам), "count": dict(self.счёт),
                 "first_utc": dict(self.первый_utc)}


def адрес_grpc(url: str) -> tuple:
    """Адрес для gRPC из URL кабинета поставщика: (цель, нужен_ли_TLS).

    Кабинет Shyft показывает адрес со схемой (https://...), а grpc-клиент
    ждёт "host:port" без схемы -- и порт ОБЯЗАТЕЛЕН: без него канал
    открывается в никуда и молча не отдаёт ни одного сообщения. Поэтому
    схема снимается здесь, в коде, а не правкой секрета, и порт
    дописывается по схеме: 443 для https, 80 для http.

    Адрес в формате host:port тоже принимается как есть.
    """
    сырое = (url or "").strip().rstrip("/")
    tls = True
    if сырое.startswith("http://"):
        tls, сырое = False, сырое[len("http://"):]
    elif сырое.startswith("https://"):
        сырое = сырое[len("https://"):]
    elif сырое.startswith("grpc://"):
        tls, сырое = False, сырое[len("grpc://"):]
    elif сырое.startswith("grpcs://"):
        сырое = сырое[len("grpcs://"):]
    сырое = сырое.split("/", 1)[0]
    # Порт уже есть, если после последнего двоеточия только цифры. IPv6 в
    # скобках не трогаем: там двоеточий много, и правило другое.
    без_порта = True
    if сырое.startswith("["):
        без_порта = "]:" not in сырое
    elif ":" in сырое:
        без_порта = not сырое.rsplit(":", 1)[1].isdigit()
    if без_порта:
        сырое = f"{сырое}:{443 if tls else 80}"
    return сырое, tls


