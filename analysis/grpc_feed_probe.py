def без_молчания(имя: str, отказы: "Отказы | None", журнал_обёртки: Path | None,
                  работа, /, *арг, **кв) -> None:
    """Поток канала не имеет права умереть молча.

    Прогон 13:49Z: у gRPC 3142 и 3130 сообщений, у Helius WS -- НОЛЬ, и при
    этом ни одного отказа в признаке жизни. Так выглядит поток, умерший ДО
    своего цикла: например, на импорте модуля, который стоит выше try. Канал
    числится живым в списке, а на деле его нет.

    Обёртка ловит всё, что вылетело из работы потока, и пишет это отказом с
    пометкой "поток умер" -- в признак жизни, а не в пустоту.

    Свои четыре имени -- ТОЛЬКО позиционные (знак "/"), и своё имя журнала
    отличается от чужого. Первая редакция брала их обычными, и у работы,
    которая сама принимает "журнал", вызов падал ещё до входа в тело:
    "без_молчания() got multiple values for argument 'журнал'". Поток умирал
    в момент вызова -- то есть до try, и обёртка, поставленная ровно против
    тихой смерти, сама её и устроила: 24.09 с 14:03Z по 14:17Z все три канала
    стояли на нуле без единого отказа в признаке жизни.
    """
    try:
        работа(*арг, **кв)
    except BaseException as exc:  # noqa: BLE001
        if отказы is not None:
            отказы.записать(имя, RuntimeError(f"поток умер: {type(exc).__name__}: "
                                               f"{str(exc)[:180]}"))
        if журнал_обёртки is not None:
            запись_строки(журнал_обёртки, {"channel": имя, "thread_died":
                                            f"{type(exc).__name__}: {str(exc)[:200]}"})
