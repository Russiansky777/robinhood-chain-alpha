def load_json(path):
    p = Path(path)
    if not p.exists():
        return None
    try:
        return json.loads(p.read_text(encoding="utf-8"))
    except (json.JSONDecodeError, OSError):
        return None


def med(vals):
    v = [x for x in vals if x is not None]
    return statistics.median(v) if v else None


def квантиль(vals, доля):
    v = sorted(x for x in vals if x is not None)
    if not v:
        return None
    i = min(len(v) - 1, max(0, int(round(доля * (len(v) - 1)))))
    return v[i]


def разброс(vals) -> dict:
    """Медиана и разброс одного столбца. Пустой вход -- честные None."""
    v = [x for x in vals if x is not None]
    if not v:
        return {"n": 0, "медиана": None, "p10": None, "p90": None,
                "макс_по_модулю": None, "мин": None, "макс": None}
    return {"n": len(v), "медиана": round(statistics.median(v), 4),
            "p10": round(квантиль(v, 0.10), 4), "p90": round(квантиль(v, 0.90), 4),
            "макс_по_модулю": round(max(abs(x) for x in v), 4),
            "мин": round(min(v), 4), "макс": round(max(v), 4)}


# ------------------------------------------------------------------ цепь

def чаевые_и_прочее(tx: dict) -> tuple[float, float]:
    """(чаевые, прочие переводы) по одной транзакции из кэша цепи."""
    чаевые = 0.0
    прочее = 0.0
    for t in tx.get("sol_transfers") or []:
        лампорты = round(t["amount_sol"] * 1e9)
        if any(abs(лампорты - m) <= ДОПУСК_МАРКЕРА_ЛАМПОРТЫ
               for m in МАРКЕРЫ_ЧАЕВЫХ_ЛАМПОРТЫ):
            чаевые += t["amount_sol"]
        else:
            прочее += t["amount_sol"]
    return чаевые, прочее


def плоский_кэш_толпы(crowd: dict) -> list:
    out = []
    for ps in (crowd or {}).get("per_source") or []:
        for t in ps.get("trades") or []:
            r = dict(t)
            r["source_address"] = ps.get("address")
            r["source_remark"] = ps.get("remark") or ps.get("address")
            out.append(r)
    return out


def индекс_сигналов(flat: list) -> dict:
    idx = collections.defaultdict(list)
    for t in flat:
        idx[(t.get("mint"), t.get("source_address"))].append(t)
    return idx


def найти_сигнал(idx: dict, mint, source, block_time):
    """Сигнал источника для нашей сделки: тот же минт, тот же источник,
    время в пределах окна. Нет -- None (сделка не участвует, а не 'ноль')."""
    if block_time is None:
        return None
    cands = [c for c in idx.get((mint, source), [])
             if c.get("block_time") is not None
             and abs(c["block_time"] - block_time) <= ОКНО_СОПОСТАВЛЕНИЯ_С]
    if not cands:
        return None
    return min(cands, key=lambda c: abs(c["block_time"] - block_time))


# ------------------------------------------- измерение издержек по цепи

def измерить_издержки(сделки: list, кэш_цепи: dict, поле_заявки: str) -> dict:
    """Издержки площадки по цепи: фиксированная часть покупки и продажи.

    поле_заявки -- откуда брать РАЗМЕР ЗАЯВКИ (что площадка отправила в
    сделку): 'gross_sol_in' у DBot (её собственная запись) или 'intent' у
    наших покупок (интент позиции Bloom).
    """
    фикс_покупки, чаевые_п, сеть_п, прочее_п = [], [], [], []
    фикс_продажи, чаевые_пр, сеть_пр, прочее_пр, доля_площадки = [], [], [], [], []
    for t in сделки:
        заявка = t.get(поле_заявки)
        if заявка and t.get("sol_in"):
            фикс_покупки.append(t["sol_in"] - заявка)
        b = кэш_цепи.get(t.get("buy_signature") or "")
        if b:
            ч, пр = чаевые_и_прочее(b)
            чаевые_п.append(ч)
            сеть_п.append(b.get("fee_sol") or 0.0)
            прочее_п.append(пр)
        s = кэш_цепи.get(t.get("sell_signature") or "")
        if s:
            ч, пр = чаевые_и_прочее(s)
            чаевые_пр.append(ч)
            сеть_пр.append(s.get("fee_sol") or 0.0)
            прочее_пр.append(пр)
            фикс_продажи.append(ч + (s.get("fee_sol") or 0.0))
            брутто = (s.get("sol_delta_native") or 0.0) + ч + (s.get("fee_sol") or 0.0)
            if брутто > 0:
                доля_площадки.append(пр / брутто)
    return {
        "фикс_покупки_sol": med(фикс_покупки),
        "фикс_покупки_разброс": разброс(фикс_покупки),
        "чаевые_покупки_sol": med(чаевые_п),
        "сетевая_покупки_sol": med(сеть_п),
        "прочее_покупки_sol": med(прочее_п),
        "фикс_продажи_sol": med(фикс_продажи),
        "фикс_продажи_разброс": разброс(фикс_продажи),
        "чаевые_продажи_sol": med(чаевые_пр),
        "сетевая_продажи_sol": med(сеть_пр),
        "прочее_продажи_sol": med(прочее_пр),
        "доля_площадки_на_продаже": med(доля_площадки),
        "n_с_кэшем_покупки": len(чаевые_п),
        "n_с_кэшем_продажи": len(чаевые_пр),
        "n_с_заявкой": len(фикс_покупки),
    }


def измерить_исполнение(сделки: list, кэш_цепи: dict, idx: dict, minty: dict) -> dict:
    """Наценка нашего входа к spot_after и скидка выхода к цене горизонта.

    Только безналоговые минты с котировкой SOL -- почему, см. докстринг
    модуля. Смещение блока (S+0/S+1/S+2) -- слот нашей покупки минус слот
    сделки источника, оба из цепи.
    """
    измерения = []
    for t in сделки:
        b = кэш_цепи.get(t.get("buy_signature") or "")
        s = кэш_цепи.get(t.get("sell_signature") or "")
        if not b:
            continue
        c = найти_сигнал(idx, t.get("mint"), t.get("source_address"), t.get("buy_block_time"))
        if not c or c.get("quote_mint") != WSOL:
            continue
        if (minty.get(t.get("mint")) or {}).get("таксируемый"):
            continue
        spot = c.get("spot_after")
        токены = (b.get("token_deltas") or {}).get(t.get("mint"))
        if not spot or not токены:
            continue
        ч_b, _ = чаевые_и_прочее(b)
        в_пул = -(b.get("sol_delta_native") or 0.0) - ч_b - (b.get("fee_sol") or 0.0)
        if в_пул <= 0:
            continue
        наценка = (в_пул / токены) / float(spot) - 1.0
        строка = {"минт": t.get("mint"), "смещение_блока": (b.get("slot") or 0) - (c.get("slot") or 0),
                  "наценка_входа": наценка, "скидка_выхода": None, "заявка_sol": t.get("gross_sol_in")}
        держали = t.get("held_seconds") or 30
        цена_вых = c.get("price_30s") if abs(держали - 30) <= abs(держали - 60) else c.get("price_60s")
        продано = (s.get("token_deltas") or {}).get(t.get("mint")) if s else None
        if s and цена_вых and продано:
            ч_s, _ = чаевые_и_прочее(s)
            из_пула = (s.get("sol_delta_native") or 0.0) + ч_s + (s.get("fee_sol") or 0.0)
            if из_пула > 0:
                строка["скидка_выхода"] = 1.0 - (из_пула / abs(продано)) / float(цена_вых)
        измерения.append(строка)
    по_смещению = collections.defaultdict(list)
    for m in измерения:
        по_смещению[m["смещение_блока"]].append(m["наценка_входа"])
    наценки = [m["наценка_входа"] for m in измерения]
    скидки = [m["скидка_выхода"] for m in измерения if m["скидка_выхода"] is not None]
    порча = [(1 + m["наценка_входа"]) / (1 - m["скидка_выхода"])
             for m in измерения if m["скидка_выхода"] is not None]
    return {
        "измерений": len(измерения),
        "наценка_входа_медиана": med(наценки),
        "наценка_входа_разброс": разброс(наценки),
        "скидка_выхода_медиана": med(скидки),
        "скидка_выхода_разброс": разброс(скидки),
        "порча_множителя_медиана": med(порча),
        "по_смещению_блока": {str(k): {"n": len(v), "медиана_наценки": med(v)}
                              for k, v in sorted(по_смещению.items())},
        "строки": измерения,
    }


# --------------------------------------------------- исправленная модель

class Издержки:
    """Набор издержек площадки. Всё в SOL, кроме долей.

    фикс_покупки/фикс_продажи -- лампорты, которые НЕ зависят от размера
    (чаевые, приоритетная комиссия, аренда токен-аккаунта, сетевая
    комиссия). Именно это исходная модель считала долей от размера, из-за
    чего на входе 0.2 SOL недосчитывала издержки в разы.
    """

    def __init__(self, фикс_покупки: float, фикс_продажи: float,
                 доля_площадки: float, порча_множителя: float,
                 комиссия_пула_bps: float = 0.0, название: str = ""):
        self.фикс_покупки = фикс_покупки
        self.фикс_продажи = фикс_продажи
        self.доля_площадки = доля_площадки
        self.порча_множителя = порча_множителя
        self.комиссия_пула_bps = комиссия_пула_bps
        self.название = название

    def как_словарь(self) -> dict:
        return {"название": self.название, "фикс_покупки_sol": self.фикс_покупки,
                "фикс_продажи_sol": self.фикс_продажи, "доля_площадки": self.доля_площадки,
                "порча_множителя": self.порча_множителя,
                "комиссия_пула_bps": self.комиссия_пула_bps}


def чистый_результат_sol(рост: float | None, размер_sol: float, изд: Издержки,
                         ставка_налога_доля: float = 0.0, налоговых_переводов: int = 0,
                         учитывать_порчу: bool = True) -> tuple[float | None, str | None]:
    """Исправленная модель: чистый результат круга в SOL.

    рост -- отношение цены на горизонте к цене "сразу за источником"
    (growth_after_* из кэша толпы). размер_sol -- полный расход по цепи.

    Отличия от night_edge_model.net_pnl_sol (каждое -- своё измерение по
    цепи, см. докстринг модуля):
      1. фиксированные лампорты вместо доли от размера;
      2. цена входа выше spot_after на измеренную наценку, выход ниже цены
         горизонта на измеренную скидку -- одним множителем 'порча';
      3. налог снимается с КАЖДОГО перевода: (1-r)^k, а не один раз на
         сторону;
      4. доля площадки берётся с выручки продажи и с заявки покупки -- по
         своей измеренной ставке площадки, а не 1% Bloom для всех.
    """
    if рост is None:
        return None, "нет цены на этом горизонте"
    if размер_sol <= 0:
        return None, "размер сделки не положителен"
    заявка = размер_sol - изд.фикс_покупки
    if заявка <= 0:
        return -размер_sol, None  # фиксированные издержки съели всю ставку
    в_пул = заявка * (1.0 - изд.доля_площадки)
    множитель = рост / изд.порча_множителя if учитывать_порчу else рост
    налог = (1.0 - ставка_налога_доля) ** max(0, int(налоговых_переводов))
    пул = (1.0 - изд.комиссия_пула_bps / 10000.0) ** 2
    выручка = в_пул * множитель * налог * пул
    издержки_продажи = выручка * изд.доля_площадки + изд.фикс_продажи
    чистый = выручка - издержки_продажи - размер_sol
    return чистый, None


def налог_сделки(mint, quote_mint, minty: dict) -> tuple[bool, float]:
    """(известно_ли, ставка_доля) по справочнику минтов. Неизвестно -- НЕ ноль."""
    доля = 0.0
    for m, обязателен in ((mint, True), (quote_mint, quote_mint not in (None, WSOL))):
        if not обязателен:
            continue
        info = minty.get(m)
        if info is None:
            return False, 0.0
        if info.get("таксируемый"):
            доля += (info.get("ставка_комиссии_bps") or 0) / 10000.0
    return True, доля
