def достать(d: dict, имена: tuple):
    """Первое поле из `имена`, какое есть у элемента -- с его собственным именем."""
    if not isinstance(d, dict):
        return None, None
    for к in имена:
        if к in d and d[к] is not None:
            return к, d[к]
    атр = d.get("attributes")
    if isinstance(атр, dict):
        for к in имена:
            if к in атр and атр[к] is not None:
                return f"attributes.{к}", атр[к]
    return None, None


def разбор(тело, где) -> list:
    """Ранг, адрес, объём, ликвидность -- именами источника; порядок = ранг, если его нет."""
    массив = тело
    if где and isinstance(тело, dict):
        массив = тело.get(где)
    if isinstance(массив, dict):
        массив = (массив.get("data") or массив.get("items")
                  or массив.get("tokens") or массив.get("coins") or [])
    if not isinstance(массив, list):
        return []
    из_ = []
    for н, э in enumerate(массив, 1):
        если = э.get("item") if isinstance(э, dict) and "item" in э else э
        имя_р, ранг = достать(если, ПОЛЯ_РАНГА)
        имя_а, адрес = достать(если, ПОЛЯ_АДРЕСА)
        имя_о, объём = достать(если, ПОЛЯ_ОБЪЁМА)
        имя_л, ликв = достать(если, ПОЛЯ_ЛИКВ)
        из_.append({"по_порядку": н,
                    "ранг": ранг, "ранг_поле": имя_р,
                    "адрес": адрес, "адрес_поле": имя_а,
                    "объём": объём, "объём_поле": имя_о,
                    "ликвидность": ликв, "ликвидность_поле": имя_л})
    return из_


def снимок(источник: str, список_: str, url: str, где) -> dict:
    зап = urllib.request.Request(url, headers={
        "accept": "application/json", "user-agent": АГЕНТ})
    if источник == "birdeye":
        ключ = os.environ.get("BIRDEYE_API_KEY")
        if not ключ:
            return {"utc": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
                    "источник": источник, "список": список_, "url": url,
                    "код": None, "ошибка": "нет ключа BIRDEYE_API_KEY",
                    "элементов": None, "тело": None, "строки": []}
        зап.add_header("X-API-KEY", ключ)
        зап.add_header("x-chain", "solana")
    нач = time.time()
    стр = {"utc": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
           "источник": источник, "список": список_, "url": url}
    try:
        with urllib.request.urlopen(зап, timeout=ТАЙМАУТ) as о:
            сырое = о.read()
            стр["код"] = о.status
            стр["заголовки"] = {к.lower(): v for к, v in о.headers.items()
                                if к.lower() in ("content-type", "x-ratelimit-remaining",
                                                 "retry-after", "cf-ray", "server")}
    except urllib.error.HTTPError as e:
        сырое = e.read()[:20000]
        стр["код"] = e.code
        стр["ошибка"] = f"http {e.code}"
    except Exception as e:  # noqa: BLE001
        сырое, стр["код"], стр["ошибка"] = b"", None, f"{type(e).__name__}: {e}"[:200]
    стр["секунд"] = round(time.time() - нач, 3)
    стр["байт"] = len(сырое)
    тело = None
    if сырое:
        try:
            тело = json.loads(сырое.decode("utf-8", "replace"))
        except ValueError:
            тело = {"не_json": сырое[:4000].decode("utf-8", "replace")}
    стр["тело"] = тело
    стр["строки"] = разбор(тело, где) if тело is not None else []
    стр["элементов"] = len(стр["строки"])
    return стр


def файл_часа(источник: str, utc: str, длина: int = 0) -> Path:
    """Путь часового файла: <источник>/<дата>/<ЧЧ>.jsonl.gz, при переполнении -- partN.

    Потолок проверяется ДО записи и по сжатому размеру на диске: строка в gzip меньше,
    чем в исходнике, так что проверка консервативна -- файл кончится раньше потолка, а не
    позже. Так ни один файл не перейдёт предел GitHub, сколько бы элементов ни отдал
    источник.
    """
    д, ч = utc[:10], utc[11:13]
    п = ПАПКА / источник / д
    п.mkdir(parents=True, exist_ok=True)
    ф = п / f"{ч}.jsonl.gz"
    часть = 1
    while ф.exists() and ф.stat().st_size + длина > ПОТОЛОК_БАЙТ:
        часть += 1
        ф = п / f"{ч}.part{часть}.jsonl.gz"
    return ф


def записать(стр: dict) -> Path:
    строка = json.dumps(стр, ensure_ascii=False) + "\n"
    ф = файл_часа(стр["источник"], стр["utc"], len(строка.encode("utf-8")))
    with gzip.open(ф, "at", encoding="utf-8") as о:   # дописываем, снимок = строка
        о.write(строка)
    return ф


def файлы_суток(дата: str, источник: str = "") -> list:
    """Все файлы снимков за сутки -- и часовые, и суточные старого раскроя."""
    из_ = []
    for п in sorted(ПАПКА.glob("*")):
        if not п.is_dir() or п.name == "pervye" or (источник and п.name != источник):
            continue
        из_ += sorted((п / дата).glob("*.jsonl.gz")) if (п / дата).is_dir() else []
        ст = п / f"{дата}.jsonl.gz"
        if ст.exists():
            из_.append(ст)
    return из_


def вид_адреса(адр) -> tuple:
    """(адрес, вид): «пул» у GeckoTerminal («solana_<адрес>»), иначе «минт»."""
    if not isinstance(адр, str) or not адр:
        return (None, None)
    if адр.startswith("solana_"):
        х = адр.split("_", 1)[1]
        return (х, "пул") if 32 <= len(х) <= 44 and set(х) <= B58 else (адр, "иное")
    как_адрес = 32 <= len(адр) <= 44 and set(адр) <= B58
    return (адр, "минт" if как_адрес else "иное")


def читать_снимки(ф: Path) -> tuple:
    """Снимки файла и отчёт о нём: (список снимков, отчёт).

    ТЕРПИМО К ОБРЫВУ. Диск на lab-miami кончился 14-16.10, и 9 файлов из 47 остались с
    обрезанным gzip: начало цело, хвост потерян. Раньше на таком файле `--pervye` падал
    на zlib.error и считал только 12.10. Теперь прочитанное до обрыва идёт в счёт, а в
    отчёт пишется, сколько строк удалось прочитать и чем кончилось чтение. Файл нулевой
    длины -- пропуск с записью, а не исключение.

    ДВА РОДА ОБРЫВА, И ВТОРОЙ ТЕКСТОВЫЙ. Первый -- gzip кончился до конца потока
    (zlib.error / EOFError). Второй -- обрыв пришёлся на СЕРЕДИНУ многобайтового символа:
    в текстовом режиме строгий декодер валит чтение UnicodeDecodeError, и на нём остались
    13.10 и 15.10, когда zlib-обрыв уже был обойдён. Поэтому файл читается ДВОИЧНО, а
    каждая строка декодируется с errors="replace": недописанный символ становится U+FFFD,
    строка не разбирается json-ом и считается битой, а всё прочитанное до неё остаётся в
    счёте. UnicodeDecodeError оставлен в перехвате отдельно -- чтобы ни один путь чтения
    не свалил проход, даже если декодирование окажется строгим.

    Отчёт: {файл, байт, строк, оборван (число прочитанных строк либо None), причина,
    битых_строк}.
    """
    отчёт = {"файл": str(ф.relative_to(ПАПКА)) if ПАПКА in ф.parents else str(ф),
             "байт": ф.stat().st_size if ф.exists() else 0,
             "строк": 0, "оборван": None, "причина": None, "битых_строк": 0}
    снимки = []
    if отчёт["байт"] == 0:
        отчёт["причина"] = "файл нулевой длины"
        отчёт["оборван"] = 0
        return (снимки, отчёт)
    последняя_цела = True
    try:
        with gzip.open(ф, "rb") as о:
            for сырая in о:
                отчёт["строк"] += 1
                ln = сырая.decode("utf-8", "replace")
                try:
                    снимки.append(json.loads(ln))
                    последняя_цела = True
                except ValueError:
                    отчёт["битых_строк"] += 1
                    последняя_цела = False
    except (zlib.error, EOFError, OSError, UnicodeDecodeError) as e:
        # Последняя строка перед обрывом почти всегда обрезана на середине: её json не
        # разобрался и в снимки не попал -- это и есть вся потеря.
        отчёт["оборван"] = отчёт["строк"]
        отчёт["причина"] = f"{type(e).__name__}: {str(e)[:120]}"
    if отчёт["оборван"] is None and not последняя_цела:
        # gzip кончился ровно, а последняя строка не разобралась -- значит запись
        # оборвалась на середине строки (так ложится обрыв посреди многобайтового
        # символа: поток цел, текст -- нет). Это тот же обрыв, и он должен быть виден.
        отчёт["оборван"] = отчёт["строк"]
        отчёт["причина"] = "последняя строка не разобралась: запись оборвана"
    return (снимки, отчёт)


def первые(дата: str) -> int:
    """Суточная таблица первых появлений по спискам -> pervye/<дата>.jsonl.gz."""
    снимки: dict = {}
    отчёты = []
    for ф in файлы_суток(дата):
        сп_, отч = читать_снимки(ф)
        отчёты.append(отч)
        if отч["оборван"] is not None or отч["битых_строк"]:
            print(f"  ОБРЫВ {отч['файл']}: прочитано строк {отч['строк']}, "
                  f"битых {отч['битых_строк']}, {отч['причина']}", flush=True)
        for с in сп_:
            utc = с.get("utc") or ""
            if not utc.startswith(дата):
                continue      # в часовом файле хвост соседних суток не ждём, но проверим
            ключ = f"{с.get('источник')}/{с.get('список')}"
            # пометка идёт в сам снимок: из какого он файла и оборван ли тот файл
            с["_файл"], с["_оборван"] = отч["файл"], отч["оборван"]
            снимки.setdefault(ключ, []).append(с)
    всего = 0
    п = ПАПКА / "pervye"
    п.mkdir(parents=True, exist_ok=True)
    ф_вых = п / f"{дата}.jsonl.gz"
    with gzip.open(ф_вых, "wt", encoding="utf-8") as о:   # перезапись: таблица суток цельная
        for ключ, сп in sorted(снимки.items()):
            сп.sort(key=lambda с: с.get("utc") or "")
            метки = [с.get("utc") for с in сп]
            видели: set = set()
            for н, с in enumerate(сп):
                if с.get("код") != 200:
                    continue
                for р in (с.get("строки") or []):
                    адр, вид = вид_адреса(р.get("адрес"))
                    if not адр or адр in видели:
                        continue
                    видели.add(адр)
                    о.write(json.dumps({
                        "дата": дата, "список": ключ,
                        "источник": с.get("источник"), "имя_списка": с.get("список"),
                        "адрес": адр, "вид": вид, "адрес_как_отдан": р.get("адрес"),
                        "utc": с.get("utc"),
                        "ранг": р.get("ранг"), "по_порядку": р.get("по_порядку"),
                        "объём": р.get("объём"), "ликвидность": р.get("ликвидность"),
                        "ранг_поле": р.get("ранг_поле"),
                        "объём_поле": р.get("объём_поле"),
                        "ликвидность_поле": р.get("ликвидность_поле"),
                        "в_первом_снимке_суток": н == 0,
                        "от_предыдущего_снимка_с": (
                            None if н == 0 else
                            round((время_мс(метки[н]) - время_мс(метки[н - 1])) / 1000.0, 1)),
                        "снимков_в_сутках": len(сп),
                        "первый_снимок_суток": метки[0],
                        # из какого файла снимок и оборван ли тот файл (число
                        # прочитанных строк, иначе null) -- чтобы счёт по неполным
                        # суткам не выглядел полным
                        "файл": с.get("_файл"),
                        "файл_оборван": с.get("_оборван"),
                    }, ensure_ascii=False) + "\n")
                    всего += 1
            print(f"{ключ:34} снимков {len(сп):5d} впервые {len(видели):6d}", flush=True)
        # Последняя строка файла -- сводка по прочитанным файлам: сколько их, сколько
        # оборвано и по сколько строк взято. Читалки пропускают её по полю «вид_строки».
        оборванных = [о_ for о_ in отчёты if о_["оборван"] is not None]
