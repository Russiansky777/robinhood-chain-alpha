#!/usr/bin/env python3
"""Перекупщики: источники, продающие через секунды после своей покупки. Офлайн.

Задание владельца 03.10 (вне очереди). Считается по суточным файлам архива den_* (у них
--porog-dop 0 по 55 источникам, поэтому видны ВСЕ их покупки и продажи с временем) и по
выгрузкам живых сделок.

Разделы:
  п.2  по каждому источнику торгующих групп: доля его ПЕРВЫХ покупок от 2 SOL-экв, проданных
       им целиком или частично за 10 с и за 30 с; медиана времени до его продажи; доля тех,
       где продажи в окне файлов не нашлось. «Целиком» -- продано не меньше 90 % купленных
       токенов одной продажей.
  п.3  живые сделки: итог там, где источник продал РАНЬШЕ нашего выхода, против остальных --
       по каждому источнику. Наш выход -- время нашей продажи (sell_sig) по полю выгрузки;
       нет его -- сделка в счёт не идёт.
  п.4  архив: выход «вслед за продажей источника» против нашего фиксированного удержания --
       по источникам, у которых быстрых продаж (<= 10 с) не меньше 30 %. ВАЖНО: точного
       состояния пула на слоте продажи источника в суточных файлах нет, поэтому «вслед за
       ним» приближается БЛИЖАЙШИМ посчитанным горизонтом, не превышающим его продажу
       (6/12/24/36/72/108/150 слотов); это названо в документе и в JSON.
  п.5  строка итога: кого числа помечают перекупщиком и у кого выход вслед за источником
       лучше фиксированного. Решение -- владельца.

Выход: docs/podbivka_<дата>_perekupshiki.md, data/podbivka/perekupshiki_<дата>.json.
"""
from __future__ import annotations

import argparse
import collections
import glob
import gzip
import json
import statistics
import sys
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import podbivka_cand2 as C2  # noqa: E402
import podbivka_kandidaty_vne as K  # noqa: E402
import podbivka_masshtab as M  # noqa: E402

КОРЕНЬ = C2.КОРЕНЬ
П = C2.П
ТОРГУЮЩИЕ = ("lane_s0", "batch5", "cand1", "cand1_03", "cand1_05", "cand2", "cand3", "leader", "konveyer")
ГОРИЗОНТЫ = (6, 12, 24, 36, 72, 108, 150)
БЫСТРО_С = 10.0
БЫСТРО_ДОЛЯ = 0.30
ЦЕЛИКОМ = 0.90
СЛОТ_С = 0.4           # секунд в слоте (оценка для перевода секунд в слоты)
ПОРОГ_SOL = 2.0
N_МИН = 20


def группы(адр: dict, a: str) -> list:
    return [g for g in ((адр.get(a) or {}).get("группы") or []) if g in ТОРГУЮЩИЕ]


def события(файлы: list, цель: set) -> tuple[dict, dict, dict]:
    """Покупки и продажи источников из наши_события + сигналы с моделью."""
    покупки: dict = collections.defaultdict(list)
    продажи: dict = collections.defaultdict(list)
    сигналы: dict = collections.defaultdict(list)
    for f in файлы:
        д = json.loads(gzip.decompress(Path(f).read_bytes()))
        for e in (д.get("наши_события") or []):
            t = e.get("trader")
            if t not in цель:
                continue
            ts = (e.get("timestamp") or 0) / 1000
            ключ = (t, e.get("mint"))
            if e.get("action") == "buy":
                покупки[ключ].append({"ts": ts, "ток": float(e.get("tokens") or 0),
                                      "sol": e.get("sol_экв"), "первая": bool(e.get("первая")),
                                      "block": e.get("block"), "sig": e.get("signature")})
            elif e.get("action") == "sell":
                продажи[ключ].append({"ts": ts, "ток": float(e.get("tokens") or 0),
                                      "block": e.get("block")})
        for с in (д.get("сигналы") or []):
            if с.get("trader") in цель and (с.get("sol") or 0) >= ПОРОГ_SOL and C2.ячейка(с):
                сигналы[с["trader"]].append(с)
        del д
    return покупки, продажи, сигналы


def main() -> int:
    import podbivka_run as R  # noqa: PLC0415
    р = argparse.ArgumentParser()
    р.add_argument("--metka", default=time.strftime("%Y-%m-%d", time.gmtime()))
    р.add_argument("--shablon", default="den_*.json.gz")
    а = р.parse_args()
    адр = json.loads((П / "arhiv_adresa.json").read_text(encoding="utf-8"))["адреса"]
    цель = {a for a in адр if группы(адр, a)}
    файлы = sorted(glob.glob(str(П / "arhiv_den" / а.shablon)))
    покупки, продажи, сигналы = события(файлы, цель)

    # ---------- п.2
    п2: dict = {}
    for (t, m), пок in покупки.items():
        прод = sorted(продажи.get((t, m)) or [], key=lambda x: x["ts"])
        for b in пок:
            if not b["первая"] or not b["sol"] or b["sol"] < ПОРОГ_SOL:
                continue
            к = п2.setdefault(t, {"первых": 0, "за10": 0, "за30": 0, "целиком10": 0,
                                  "целиком30": 0, "без_продажи": 0, "времена": []})
            к["первых"] += 1
            после = [x for x in прод if x["ts"] >= b["ts"]]
            if not после:
                к["без_продажи"] += 1
                continue
            п1 = после[0]
            дт = п1["ts"] - b["ts"]
            к["времена"].append(дт)
            целиком = bool(b["ток"] and п1["ток"] >= ЦЕЛИКОМ * b["ток"])
            if дт <= 10:
                к["за10"] += 1
                к["целиком10"] += 1 if целиком else 0
            if дт <= 30:
                к["за30"] += 1
                к["целиком30"] += 1 if целиком else 0
    для_п2 = {}
    for t, к in п2.items():
        n = к["первых"]
        вр = sorted(к["времена"])
        для_п2[t] = {"группы": группы(адр, t), "первых_от_2": n,
                     "доля_за_10с": round(к["за10"] / n, 3) if n else None,
                     "доля_за_30с": round(к["за30"] / n, 3) if n else None,
                     "целиком_за_10с": round(к["целиком10"] / n, 3) if n else None,
                     "целиком_за_30с": round(к["целиком30"] / n, 3) if n else None,
                     "без_продажи_в_окне": round(к["без_продажи"] / n, 3) if n else None,
                     "медиана_до_продажи_с": round(statistics.median(вр), 1) if вр else None,
                     "p10_до_продажи_с": (round(вр[max(0, int(0.10 * len(вр)) - 1)], 1) if вр else None)}

    # ---------- п.3 (живые сделки)
    живые = []
    for кандидат in (КОРЕНЬ / "data" / "sdelki_polosy_vse_s_2709.json",
                     П / "sdelki" / "vse_s_2709.json"):
        if кандидат.exists():
            живые = json.loads(кандидат.read_text(encoding="utf-8")).get("ряды") or []
            откуда = кандидат.name
            break
    else:
        откуда = "выгрузок нет"
    по_cid: dict = {}
    for f in sorted((П / "sdelki").glob("sdelki_polosy_*.json")):
        for r in json.loads(f.read_text(encoding="utf-8")).get("ряды") or []:
            по_cid[r["cid"]] = r
    for r in живые:
        по_cid.setdefault(r["cid"], r)
    п3: dict = {}
    счёт3 = collections.Counter()
    for r in по_cid.values():
        итог = r.get("итог_po_cepi_sol")
        if итог is None:
            итог = r.get("итог_sol")
        ист, минт = r.get("source"), r.get("mint")
        if итог is None or not ист or not минт or not r.get("utc"):
            счёт3["без_итога_или_минта"] += 1
            continue
        try:
            наш_ts = time.mktime(time.strptime(r["utc"], "%Y-%m-%dT%H:%M:%SZ")) - time.timezone
        except ValueError:
            счёт3["время_не_прочитано"] += 1
            continue
        держ = float(r.get("hold_slots_fact") or 0) * СЛОТ_С
        наш_выход_ts = наш_ts + держ if держ else None
        прод = sorted(продажи.get((ист, минт)) or [], key=lambda x: x["ts"])
        после = [x for x in прод if x["ts"] >= наш_ts - 60]
        к = п3.setdefault(ист, {"группы": группы(адр, ист), "раньше": [], "позже": [], "нет_данных": 0})
        if not после or наш_выход_ts is None:
            к["нет_данных"] += 1
            счёт3["нет_продажи_источника_в_архиве"] += 1
            continue
        if после[0]["ts"] <= наш_выход_ts:
            к["раньше"].append(float(итог))
        else:
            к["позже"].append(float(итог))
        счёт3["посчитано"] += 1
    для_п3 = {}
    for t, к in п3.items():
        def св(v: list) -> dict:
            return {"n": len(v), "итог_sol": round(sum(v), 4) if v else 0.0,
                    "медиана_sol": round(statistics.median(v), 4) if v else None}
        для_п3[t] = {"группы": к["группы"], "источник_продал_раньше": св(к["раньше"]),
                     "остальные": св(к["позже"]), "нет_данных": к["нет_данных"]}

    # ---------- п.4 (архив: выход вслед за продажей источника, приближение горизонтом)
    # ПОРОГ ВЛАДЕЛЬЦА -- 30 %; рядом считаем и тех, кто близко (от 25 %), с явной пометкой:
    # так видно, меняет ли выход вслед за источником картину у почти-перекупщиков.
    быстрые = [t for t, v in для_п2.items()
               if (v["доля_за_10с"] or 0) >= 0.25 and v["первых_от_2"] >= N_МИН]
    для_п4 = {}
    for t in быстрые:
        стр = {"группы": группы(адр, t), "ячеек": 0, "вслед": [], "фикс": [],
               "по_суткам_вслед": collections.defaultdict(float),
               "по_суткам_фикс": collections.defaultdict(float)}
        for с in сигналы.get(t, []):
            # СЛОТ ЕГО СОБСТВЕННОЙ ПРОДАЖИ -- ИЗ СОБЫТИЙ, А НЕ ИЗ ПОЛЯ «удержание».
            # В суточном файле `первая_продажа_слотов` -- первая продажа ЛЮБОГО ДРУГОГО
            # кошелька (в коде прохода стоит `!= покупка["trader"]`), это не то, что спросили.
            свои = sorted((x for x in (продажи.get((t, с.get("mint"))) or [])
                           if x.get("block") and с.get("block") and x["block"] >= с["block"]),
                          key=lambda x: x["block"])
            if not свои:
                continue
            сл_прод = свои[0]["block"] - с["block"]
            гор = max([h for h in ГОРИЗОНТЫ if h <= max(6, int(сл_прод))] or [ГОРИЗОНТЫ[0]])
            v_вслед = K.пп(с, "108") if гор == 108 else ((с.get("модель") or {}).get("пп") or {}).get(
                f"S0_дно|0.3|{гор}")
            v_фикс = K.пп(с, "108")
            if v_вслед is None or v_фикс is None:
                continue
            стр["ячеек"] += 1
            стр["вслед"].append(v_вслед)
            стр["фикс"].append(v_фикс)
            сут = time.strftime("%Y-%m-%d", time.gmtime(K.ts(с)))
            стр["по_суткам_вслед"][сут] += 0.3 * v_вслед / 100.0
            стр["по_суткам_фикс"][сут] += 0.3 * v_фикс / 100.0
        if not стр["ячеек"]:
            continue
        def св2(зн: list, по_суткам: dict) -> dict:
            сут = sorted(по_суткам.items())
            return {"n": len(зн), "медиана": round(statistics.median(зн), 2),
                    "среднее": round(statistics.mean(зн), 2),
                    "sol_в_сутки": round(statistics.median([v for _, v in сут]), 4) if сут else None,
                    "sol_всего": round(sum(v for _, v in сут), 4),
                    "худшие_сутки": (min(сут, key=lambda kv: kv[1]) if сут else None)}
        для_п4[t] = {"группы": стр["группы"],
                     "доля_за_10с": для_п2[t]["доля_за_10с"],
                     "порог_владельца_пройден": bool(для_п2[t]["доля_за_10с"] >= БЫСТРО_ДОЛЯ),
                     "вслед_за_источником": св2(стр["вслед"], стр["по_суткам_вслед"]),
                     "фиксированное_108": св2(стр["фикс"], стр["по_суткам_фикс"])}

    дт = {"метка": а.metka, "файлов_архива": len(файлы), "источников": len(цель),
          "живые_откуда": откуда, "живых_сделок": len(по_cid), "счёт_живых": dict(счёт3),
          "порог_sol": ПОРОГ_SOL, "быстро_секунд": БЫСТРО_С, "быстро_доля": БЫСТРО_ДОЛЯ,
          "слот_секунд": СЛОТ_С, "п2": для_п2, "п3": для_п3, "п4": для_п4,
          "_про_п4": "«вслед за источником» -- ближайший посчитанный горизонт, не превышающий "
                     "слот первой продажи из поля удержание; точного состояния пула на слоте "
                     "продажи источника в суточных файлах нет"}
    out_j = П / f"perekupshiki_{а.metka}.json"
    out_j.write_text(json.dumps(дт, ensure_ascii=False, indent=1, default=str), encoding="utf-8")
    R.записано(out_j)

    md = [f"# Перекупщики: источники, продающие через секунды после своей покупки ({а.metka})", "",
          f"Архив: файлов суток {len(файлы)} (`{а.shablon}`; у этих проходов `--porog-dop 0` по 55 "
          f"источникам, поэтому видны все их покупки и продажи с временем). Источников торгующих "
          f"групп {len(цель)}. Живые сделки -- {откуда}, всего {len(по_cid)} (посчитано "
          f"{счёт3.get('посчитано', 0)}, без продажи источника в архиве "
          f"{счёт3.get('нет_продажи_источника_в_архиве', 0)}). «Целиком» -- одной продажей ушло не "
          f"меньше {ЦЕЛИКОМ:.0%} купленных токенов. Ничего не рекомендуется -- решает владелец.", "",
          "## п.2 Как быстро источник продаёт свою покупку", "",
          "| источник | группы | первых ≥ 2 SOL | продал ≤ 10 с | ≤ 30 с | целиком ≤ 10 с | "
          "медиана до продажи, с | p10, с | без продажи в окне |",
          "|---|---|---|---|---|---|---|---|---|"]
    for t, v in sorted(для_п2.items(), key=lambda kv: -(kv[1]["доля_за_10с"] or 0)):
        if v["первых_от_2"] < 5:
            continue
        md.append(f"| `{t[:8]}` | {', '.join(v['группы']) or '—'} | {v['первых_от_2']} | "
                  f"**{v['доля_за_10с']:.0%}** | {v['доля_за_30с']:.0%} | {v['целиком_за_10с']:.0%} | "
                  + (f"{v['медиана_до_продажи_с']:.1f}" if v["медиана_до_продажи_с"] is not None else "—")
                  + " | " + (f"{v['p10_до_продажи_с']:.1f}" if v["p10_до_продажи_с"] is not None else "—")
                  + f" | {v['без_продажи_в_окне']:.0%} |")
    md += ["", "## п.3 Живые сделки: источник продал раньше нашего выхода", "",
           "| источник | группы | раньше: n | раньше: итог SOL | раньше: медиана | остальные: n | "
           "остальные: итог SOL | остальные: медиана | нет данных |",
           "|---|---|---|---|---|---|---|---|---|"]
    for t, v in sorted(для_п3.items(), key=lambda kv: -(kv[1]["источник_продал_раньше"]["n"])):
        р_, о_ = v["источник_продал_раньше"], v["остальные"]
        if р_["n"] + о_["n"] == 0:
            continue
        md.append(f"| `{t[:8]}` | {', '.join(v['группы']) or '—'} | {р_['n']} | {р_['итог_sol']:+.4f} | "
                  + (f"{р_['медиана_sol']:+.4f}" if р_["медиана_sol"] is not None else "—")
                  + f" | {о_['n']} | {о_['итог_sol']:+.4f} | "
                  + (f"{о_['медиана_sol']:+.4f}" if о_["медиана_sol"] is not None else "—")
                  + f" | {v['нет_данных']} |")
    md += ["", f"## п.4 Архив: выход вслед за продажей источника против фиксированного +108", "",
           "Только источники, у которых доля продаж за 10 с не меньше "
           f"{БЫСТРО_ДОЛЯ:.0%} при n ≥ {N_МИН}. Слот ЕГО продажи берётся из событий суточного "
           "файла (поле `удержание.первая_продажа_слотов` для этого не годится: там первая "
           "продажа любого ДРУГОГО кошелька). «Вслед за ним» -- ближайший посчитанный горизонт, "
           "не превышающий этот слот (точного состояния пула на слоте его продажи в файлах нет, "
           "это приближение и оно названо). Билет 0.3.", "",
           "| источник | группы | доля ≤ 10 с | порог 30 % | n | вслед: медиана | вслед: SOL в сутки | "
           "вслед: худшие сутки | +108: медиана | +108: SOL в сутки | +108: худшие сутки |",
           "|---|---|---|---|---|---|---|---|---|---|---|"]
    for t, v in sorted(для_п4.items(), key=lambda kv: -(kv[1]["доля_за_10с"] or 0)):
        в, ф = v["вслед_за_источником"], v["фиксированное_108"]
        хв, хф = в.get("худшие_сутки"), ф.get("худшие_сутки")
        md.append(f"| `{t[:8]}` | {', '.join(v['группы']) or '—'} | {v['доля_за_10с']:.0%} | "
                  + ("да" if v["порог_владельца_пройден"] else "нет (ниже 30 %)")
                  + f" | {в['n']} | {в['медиана']:+.2f} | "
                  + (f"{в['sol_в_сутки']:+.4f}" if в["sol_в_сутки"] is not None else "—") + " | "
                  + (f"{хв[0]}: {хв[1]:+.4f}" if хв else "—") + f" | {ф['медиана']:+.2f} | "
                  + (f"{ф['sol_в_сутки']:+.4f}" if ф["sol_в_сутки"] is not None else "—") + " | "
                  + (f"{хф[0]}: {хф[1]:+.4f}" if хф else "—") + " |")
    пере = [t for t, v in для_п2.items()
            if (v["доля_за_10с"] or 0) >= БЫСТРО_ДОЛЯ and v["первых_от_2"] >= N_МИН]
    лучше = [t for t, v in для_п4.items()
             if v["вслед_за_источником"]["медиана"] > v["фиксированное_108"]["медиана"]
             and v["вслед_за_источником"]["n"] >= 10]
    md += ["", "## п.5 Итог строкой", "",
           f"Числа помечают перекупщиком (продажа за 10 с не реже {БЫСТРО_ДОЛЯ:.0%} при n ≥ {N_МИН}): "
           + (", ".join(f"`{t[:8]}` ({', '.join(группы(адр, t))}, "
                        f"{для_п2[t]['доля_за_10с']:.0%} за 10 с, медиана "
                        f"{для_п2[t]['медиана_до_продажи_с']:.0f} с)" for t in пере) if пере else "никого")
           + ".",
           f"Выход вслед за источником по медиане лучше фиксированного +108 у: "
           + (", ".join(f"`{t[:8]}`" for t in лучше) if лучше else "ни у кого") + ".",
           "Решение -- владельца.", ""]
    out_m = КОРЕНЬ / "docs" / f"podbivka_{а.metka}_perekupshiki.md"
    out_m.write_text("\n".join(md) + "\n", encoding="utf-8")
    R.записано(out_m)
    print(f"{out_m.name}: источников в п.2 {len(для_п2)}, перекупщиков {len(пере)}, "
          f"в п.4 {len(для_п4)}, вслед лучше у {len(лучше)}", flush=True)
