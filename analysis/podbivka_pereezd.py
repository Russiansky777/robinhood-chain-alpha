def сутки_файла(имя: str) -> str:
    return имя.replace(".json.gz", "").split("_", 1)[-1].split("T")[0]


def файлы(префикс: str) -> list:
    """Пути собранных суток. Читаются ПО ОДНИМ: все 17 суток zap_ разом -- это 6.5 ГБ
    и смерть по памяти (предел контейнера 7.5 ГБ). Проходу нужен один день за раз."""
    return [(сутки_файла(Path(ф).name), ф)
            for ф in sorted(glob.glob(str(П / "zapuski" / f"{префикс}*.json.gz")))]


def сутки(путь: str) -> dict:
    with gzip.open(путь, "rt", encoding="utf-8") as о:
        return json.load(о)


def подпись_выкупа(x: dict) -> tuple[str, dict]:
    """Срез выкупа по поведению покупателей окна + раскладка для пункта к."""
    пк = x.get("покупатели")
    if пк is None:
        return "нет данных", {}
    лучший, best = None, -1.0
    for к in пк:
        n, s = к.get("покупок") or 0, к.get("sol") or 0.0
        п0, п1 = к.get("первый_слот"), к.get("последний_слот")
        if п0 is None or п1 is None:
            continue
        if n >= ПАРТИЙ_МИН and s >= SOL_МИН and (п1 - п0) >= РАСТЯЖКА_МИН and s > best:
            лучший, best = к, s
    if лучший is None:
        return "без", {}
    n = лучший["покупок"]
    п0, п1 = лучший["первый_слот"], лучший["последний_слот"]
    return "BOOST", {"кошелёк": лучший["кто"], "партий": n, "sol": round(лучший["sol"], 4),
                     "первый_слот": п0, "последний_слот": п1,
                     "шаг_слотов": round((п1 - п0) / (n - 1), 1) if n > 1 else None}


def цена(сост: list) -> float | None:
    """SOL за токен из состояния [x, y, слот]."""
    x, y = float(сост[0]), float(сост[1])
    return x / y if y > 0 else None


def раскладка(с: dict, б: float, h: int, кр: dict) -> dict:
    """Пункт ж: из чего сложился круг. Всё в п.п. билета, чтобы складывалось с итогом."""
    сост = с["модель"]["состояния"]
    вх, вых = сост["вход"].get(МЕСТО), сост["выход"].get(str(h))
    p0, p1 = (цена(вх) if вх else None), (цена(вых) if вых else None)
    рост = 100 * (p1 / p0 - 1) if (p0 and p1) else None
    # Тариф пула и наценки отдельно: тот же круг без тарифа и без наценок.
    без = B.сделка_по_состояниям({"pool": с["pool"],
                                  "модель": {**с["модель"], "fee": 0.0, "f": 1.0, "g": 1.0}},
                                 б, место=МЕСТО, выход=h, издержки=0.0, к_g=1.0)
    тариф_пп = (100 * (без["итог_sol"] - (кр["итог_sol"] + Z.ИЗДЕРЖКИ)) / б) if без else None
    return {"рост_цены_пп": рост, "сдвиг_вход_пп": кр.get("сдвиг_вход_пп"),
            "сдвиг_выход_пп": кр.get("сдвиг_выход_пп"), "тариф_пула_пп": тариф_пп,
            "чаевые_приоритет_пп": 100 * Z.ИЗДЕРЖКИ / б, "итог_пп": кр["пп"],
            "итог_sol": кр["итог_sol"], "резерв_sol": кр.get("резерв_вход_sol")}


def вид_состояния(вх: list, вых: list) -> str:
    """Можно ли вообще считать круг по этой паре состояний.

    Зачем нужна эта проверка. На длинных горизонтах собранные состояния расходятся с любой
    возможной операцией пула, и считать по ним круг нельзя:

      * сегмент (б), горизонт 448+ слотов: SOL-плечо падает в 2400 раз (14.2 -> 0.006), а
        токенное РАСТЁТ в 28 раз (2.84e7 -> 7.68e8). Своп двигает плечи в разные стороны, но
        сохраняет произведение; добавление и вывод ликвидности двигают их В ОДНУ сторону.
        Падение произведения в 80 раз при разных направлениях плеч не делает ни одна
        операция пула -- это другое состояние, а не наш пул. Такие строки в счёт не идут, и
        сколько их -- сказано отдельной графой.
      * сегмент (в2), горизонт 1121: оба плеча в нуле -- пул закрыт. Это НЕ повод выкинуть
        строку: закрытый пул означает, что продать нельзя, то есть билет потерян целиком.
        Выкидывание таких строк и давало фальшивый плюс: до исправления медиана (в2) при
        билете 1.0 выходила +1.00 SOL на 1.00 SOL билета, потому что в счёт попадали только
        пулы, ДОЖИВШИЕ до выхода, а это известно лишь после входа.
    """
    x0, y0 = float(вх[0]), float(вх[1])
    x1, y1 = float(вых[0]), float(вых[1])
    if x0 <= 0 or y0 <= 0:
        return "не_тот_пул"
    if x1 <= 0 or y1 <= 0:
        return "закрыт"
    k = (x1 * y1) / (x0 * y0)
    одно = (x1 >= x0) == (y1 >= y0)
    if одно or 0.5 <= k <= 2.0:
        return "годно"
    return "не_тот_пул"


def нуль_строки(с: dict, горизонты: tuple, нуль: dict, д: str,
                счёт: collections.Counter) -> None:
    """Круги по ВСЕМ запускам суток -- совокупность, из которой срез мог быть выбран.

    Условия те же, что у среза: глубина (билет не больше 2 % резерва) и те же горизонты.
    Отличие одно -- пул и правило любые. Иначе p сравнивал бы срез не с «случайным
    запуском», а с самим собой.
    """
    сост = с["модель"]["состояния"]
    вх_с = сост["вход"].get(МЕСТО)
    if not вх_с:
        return
    x0 = float(вх_с[0])
    for h in горизонты:
        вых_с = (сост.get("выход") or {}).get(str(h))
        есть = bool(вых_с and Z.позже_входа(с, МЕСТО, h))
        вид = вид_состояния(вх_с, вых_с) if есть else "пусто"
        if вид == "не_тот_пул":
            счёт[f"нуль:не_тот_пул:{h}"] += 1
            continue
        for б in БИЛЕТЫ:
            if x0 * ДОЛЯ_РЕЗЕРВА < б:
                continue
            if вид == "пусто":
                кр = Z.круг_в_пустоту(с, б, МЕСТО)
                if кр is None:
                    continue
            elif вид == "закрыт":
                кр = None
            else:
                кр = Z.круг(с, б, МЕСТО, h)
            итог = кр["итог_sol"] if кр else -(б + Z.ИЗДЕРЖКИ)
            нуль[(h, б)][д].append(итог)
            счёт["нуль:кругов"] += 1


def деньги_сходятся(вх: list, вых: list, объём: float) -> bool:
    """Хватило ли замеченных денег окна на такой рост цены (см. ПРИТОК_РАЗ)."""
    x0, y0 = float(вх[0]), float(вх[1])
    x1, y1 = float(вых[0]), float(вых[1])
    if min(x0, y0, x1, y1) <= 0:
        return True                   # закрытый пул разбирается отдельным видом
    M = (x1 / y1) / (x0 / y0)
    if M <= 1:
        return True                   # цена не выросла -- приток не нужен
    нужно = x0 * (math.sqrt(M) - 1)
    return нужно <= max(1.0, объём) * ПРИТОК_РАЗ


def проход(префикс: str, горизонты: tuple, срезы: dict | None) -> tuple:
    """Один проход по собранным суткам. Возвращает компактные массивы по (сегмент, h, билет).

    Хранение массивами, а не словарями: 110 тыс. пулов на 5 билетов и 5 горизонтов -- это
    2.7 млн кругов, на словарях проход уже съедал больше 7 ГБ и был убит по памяти.
    """
    сп_файлов = файлы(префикс)
    дни_сп = [д for д, _ in сп_файлов]
    номер = {д: i for i, д in enumerate(дни_сп)}
    ключи = [(s, h, б) for s in ПОРЯДОК for h in горизонты for б in БИЛЕТЫ]
    стол = {k: {"итог": array("f"), "пп": array("f"), "резерв": array("f"),
                "объём": array("f"), "день": array("H"), "вид": bytearray()} for k in ключи}
    раскл = {k: {имя: array("f") for имя in ("рост", "вх", "вых", "тариф", "итог")}
             for k in ключи}
    # Нуль -- по ВСЕМ запускам суток, а не по срезу. Если взять за нуль сам срез, выбор
    # совпадает со всей совокупностью, и p выходит ровно 0.5 при любом результате (а при
    # k = N дисперсия выборки без возвращения ровно ноль, и p вообще не считается). На это
    # я уже наступал: первый счёт дал «0 годных строк из 63» именно поэтому.
    нуль: dict = {(h, б): collections.defaultdict(lambda: array("f"))
                  for h in горизонты for б in БИЛЕТЫ}
    примеры: dict = collections.defaultdict(list)
    выкуп: dict = collections.defaultdict(list)
    рост_пулов: dict = collections.defaultdict(lambda: [0, 0])
    счёт: collections.Counter = collections.Counter()
    мой_срез: dict = {}
    ВИД = {"годно": 0, "закрыт": 1, "нельзя_продать": 2, "пусто": 3,
           "деньги_не_сходятся": 4}
    for д, путь in сп_файлов:
        дн = номер[д]
        на_проверке = д >= ПРОВЕРКА_С
        тело = сутки(путь)
        for x in тело.get("ряды") or []:
            сег = СЕГМЕНТЫ.get((x.get("пул"), x.get("правило")))
            с = Z.модель(x)
            if с is not None and на_проверке:
                нуль_строки(с, горизонты, нуль, д, счёт)
            if not сег:
                continue
            счёт[f"{сег}:всего"] += 1
            if x.get("quoteMint") != WSOL:
                счёт[f"{сег}:квота_не_SOL"] += 1
                continue
            вх0 = (x.get("вход") or {}).get(МЕСТО)
            if not вх0 or float(вх0[0]) < 10.0:
                счёт[f"{сег}:резерв_меньше_10"] += 1
                continue
            if not с:
                счёт[f"{сег}:без_модели"] += 1
                continue
            if срезы is None:
                ср, разбор = подпись_выкупа(x)
                мой_срез[x["poolId"]] = ср
                if разбор:
                    разбор["сегмент"] = сег
                    разбор["poolId"] = x["poolId"]
                    разбор["минт"] = x["минт"]
                    разбор["сутки"] = д
                    выкуп[сег].append(разбор)
            else:
                ср = срезы.get(x["poolId"], "нет данных")
            свои = [сег] + ([f"а/{ср}"] if сег == "а" and ср in ("BOOST", "без") else [])
            # Объём покупок окна: по верхним покупателям (их десять) -- это НИЖНЯЯ оценка,
            # значит наша доля объёма (пункт л) выходит верхней оценкой.
            пк = x.get("покупатели")
            объём = (sum(к.get("sol") or 0.0 for к in пк) if пк
                     else ((x.get("волна") or {}).get("60с") or {}).get("sol") or 0.0)
            сост = с["модель"]["состояния"]
            вх_с = сост["вход"][МЕСТО]
            x0 = float(вх_с[0])
            for h in горизонты:
                вых_с = (сост.get("выход") or {}).get(str(h))
                есть = bool(вых_с and Z.позже_входа(с, МЕСТО, h))
                вид = вид_состояния(вх_с, вых_с) if есть else "пусто"
                if вид == "не_тот_пул":
                    for s in свои:
                        счёт[f"{s}:не_тот_пул:{h}"] += 1
                    continue
                if вид == "годно" and not деньги_сходятся(вх_с, вых_с, объём):
                    вид = "деньги_не_сходятся"
                    for s in свои:
                        счёт[f"{s}:деньги_не_сходятся:{h}"] += 1
                if вид in ("годно", "деньги_не_сходятся"):
                    p0, p1 = цена(вх_с), цена(вых_с)
                    for s in свои:
                        рост_пулов[(s, h)][0] += 1
                        рост_пулов[(s, h)][1] += 1 if (p1 and p0 and p1 > p0) else 0
                for б in БИЛЕТЫ:
                    # Глубина -- условие ВХОДА: резерв пула виден до покупки.
                    if x0 * ДОЛЯ_РЕЗЕРВА < б:
                        continue
                    if вид == "пусто":
                        кр, вид_б = Z.круг_в_пустоту(с, б, МЕСТО), "пусто"
                    elif вид == "закрыт":
                        кр, вид_б = None, "закрыт"
                    else:
                        кр = Z.круг(с, б, МЕСТО, h)
                        вид_б = ("годно" if вид == "годно" else "деньги_не_сходятся") \
                            if кр else "нельзя_продать"
                    if кр is None and вид_б == "пусто":
                        continue
                    if кр is None:
                        # Продать нельзя: пул закрыт или в нём меньше токена, чем у нас на
                        # руках. Честный итог -- билет потерян целиком плюс расходы круга.
                        итог_sol = -(б + Z.ИЗДЕРЖКИ)
                        пп = 100 * итог_sol / б
                        комп = (None, None, None, None, итог_sol)
                    else:
                        итог_sol, пп = кр["итог_sol"], кр["пп"]
                        r = раскладка(с, б, h, кр)
                        комп = (r["рост_цены_пп"], r["сдвиг_вход_пп"], r["сдвиг_выход_пп"],
                                r["тариф_пула_пп"], итог_sol)
                    for s in свои:
                        k = (s, h, б)
                        t = стол[k]
                        t["итог"].append(итог_sol)
                        t["пп"].append(пп)
                        t["резерв"].append(x0)
                        t["объём"].append(объём)
                        t["день"].append(дн)
                        t["вид"].append(ВИД[вид_б])
                        rr = раскл[k]
                        for имя, v in zip(("рост", "вх", "вых", "тариф", "итог"), комп):
                            rr[имя].append(float("nan") if v is None else v)
                        if б == 1.0:
                            примеры[k].append((итог_sol, x["poolId"], x["минт"], д, x["пул"],
                                               x0, x.get("событий") or 0, вид_б,
                                               x.get("блок") or 0, x.get("ts") or 0))
        del тело
    return (стол, раскл, нуль, dict(примеры), выкуп, рост_пулов, dict(счёт), дни_сп,
            мой_срез)


