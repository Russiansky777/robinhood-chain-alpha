def p_выбора(нуль_по_суткам: dict, выбор: dict) -> float | None:
    """Аналитический p: та же сумма k случайных из N в каждых сутках проверки."""
    μ = σ2 = s = 0.0
    for д, все in нуль_по_суткам.items():
        v = выбор.get(д)
        if not v or not все:
            continue
        N, k = len(все), len(v)
        if k < 1 or N < 2:
            continue
        m = statistics.fmean(все)
        d2 = statistics.pvariance(все)
        μ += k * m
        σ2 += k * d2 * (N - k) / (N - 1)
        s += sum(v)
    if σ2 <= 0:
        return None
    z = (s - μ) / math.sqrt(σ2)
    return 0.5 * math.erfc(z / math.sqrt(2))


