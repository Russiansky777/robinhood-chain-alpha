def цели(примеры: dict, выкуп: dict) -> dict:
    """Списки пулов для проходов по цепи: пункт и, пункт к и пункт 2 задачи."""
    рнд = random.Random(СЕМЯ)
    из_ = {"что": "цели проходов по цепи", "семя": СЕМЯ, "пункт_и": {}, "пункт_2": {},
           "пункт_к": {}}

    def стр(e):
        return {"poolId": e[1], "минт": e[2], "сутки": e[3], "пул": e[4],
                "итог_sol": round(e[0], 5), "резерв_sol": round(e[5], 2),
                "событий": e[6], "вид": e[7], "блок": e[8], "ts": e[9],
                "час": час_архива(e[9])}

    for s in ПОРЯДОК:
        for h in (230, 1121):
            р = примеры.get((s, h, 1.0)) or []
            if not р:
                continue
            р = sorted(р, key=lambda e: e[0])
            из_["пункт_и"][f"{s}|{h}"] = {"худшие_20": [стр(e) for e in р[:20]],
                                          "лучшие_20": [стр(e) for e in р[-20:]][::-1]}
    # Пункт 2: 50 пулов прошедшего среза createPool. В примерах лежат только те, кто прошёл
    # условие входа по глубине при билете 1.0, то есть ровно прошедший срез.
    # Пулы берутся СГУЩЁННО, из одного-двух часов архива: прицельный проход окна читает
    # ровно те часы, и 50 пулов из одного часа стоят два часа архива вместо восьмидесяти.
    for s in ("в1", "в2"):
        р = примеры.get((s, 1121, 1.0)) or примеры.get((s, 230, 1.0)) or []
        из_["пункт_2"][s] = [стр(e) for e in сгустить(р, 50)]
    # Пункт к: пулы (а) с подписью выкупа -- по ним считать слоты партий по цепи.
    из_["пункт_к"]["а_с_выкупом"] = [стр(e) for e in сгустить(
        примеры.get(("а", 1121, 1.0)) or [], 30)]
    # И десять пулов (б) -- проверить то самое состояние выхода, что не похоже на тот же пул.
    из_["пункт_к"]["б_проверить_состояние"] = [стр(e) for e in сгустить(
        примеры.get(("б", 1121, 1.0)) or примеры.get(("б", 230, 1.0)) or [], 10)]
    из_["пункт_к"]["сводка_архива"] = сводка_выкупа(выкуп)
    return из_


def час_архива(ts_мс: float) -> str:
    import time as _t   # noqa: PLC0415
    return _t.strftime("%Y/%m/%d/%H", _t.gmtime((ts_мс or 0) / 1000.0))


def сгустить(сп: list, n: int) -> list:
    """Взять n пулов из САМОГО густого часа архива, а не вразброс по 17 суткам.

    Прицельный проход окна читает архив почасовыми файлами. Разбросанные 50 пулов стоят 80
    часов архива, сгущённые -- два. Если в самом густом часе пулов меньше n, добираются
    следующие по густоте часы.
    """
    по_часу: dict = collections.defaultdict(list)
    for e in сп:
        по_часу[час_архива(e[9])].append(e)
    из_: list = []
    for _ч, гр in sorted(по_часу.items(), key=lambda kv: -len(kv[1])):
        из_ += гр[:n - len(из_)]
        if len(из_) >= n:
            break
    return из_


def сводка_выкупа(выкуп: dict) -> dict:
    из_ = {}
    for сег, сп in выкуп.items():
        if not сп:
            continue
        из_[сег] = {
            "пулов": len(сп),
            "первый_слот_медиана": statistics.median([x["первый_слот"] for x in сп]),
            "последний_слот_медиана": statistics.median([x["последний_слот"] for x in сп]),
            "партий_медиана": statistics.median([x["партий"] for x in сп]),
            "шаг_слотов_медиана": statistics.median([x["шаг_слотов"] for x in сп
                                                     if x["шаг_слотов"] is not None]),
            "sol_медиана": round(statistics.median([x["sol"] for x in сп]), 3),
            "sol_среднее": round(statistics.fmean([x["sol"] for x in сп]), 3),
            "sol_p90": round(кв([x["sol"] for x in сп], 0.90), 3),
            "кошельков_разных": len({x["кошелёк"] for x in сп}),
        }
    return из_


