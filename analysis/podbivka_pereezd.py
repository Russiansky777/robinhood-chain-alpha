def загрузить(префикс: str) -> dict:
    дни = {}
    for ф in sorted(glob.glob(str(П / "zapuski" / f"{префикс}*.json.gz"))):
        with gzip.open(ф, "rt", encoding="utf-8") as о:
            дни[Path(ф).name.replace(".json.gz", "").split("_", 1)[-1].split("T")[0]] = \
                json.load(о)
    return дни


def переезд(п: dict) -> bool:
    """Срез переезда: пул PumpSwap или DAMM v2, создание, резерв от 10 SOL."""
    return (п["пул"] in {"pump-amm", "meteora-damm-v2"}
            and п["правило"] in ("создание:createPool", "создание:migrate")
            and п["резерв"] >= 10.0)


def агент_boost(дни: dict) -> dict:
    """Опознать агента выкупа по данным: охват переездов и число покупок в каждом."""
    пулов: collections.Counter = collections.Counter()
    покупок: collections.Counter = collections.Counter()
    сол: dict = collections.defaultdict(float)
    слоты: dict = collections.defaultdict(list)
    всего = 0
    есть_поле = False
    for тело in дни.values():
        for x in тело.get("ряды") or []:
            if not переезд(Z.признаки(x)):
                continue
            всего += 1
            пк = x.get("покупатели")
            if пк is None:
                continue
            есть_поле = True
            for к in пк:
                if (к.get("покупок") or 0) < ПОРОГ_ПОКУПОК:
                    continue
                пулов[к["кто"]] += 1
                покупок[к["кто"]] += к["покупок"]
                сол[к["кто"]] += к.get("sol") or 0
                if к.get("последний_слот") is not None:
                    слоты[к["кто"]].append(к["последний_слот"])
    верх = [{"кошелёк": k, "пулов": v, "доля_пулов": round(100 * v / max(1, всего), 1),
             "покупок": покупок[k], "покупок_на_пул": round(покупок[k] / v, 1),
             "sol_на_пул": round(сол[k] / v, 3),
             "последний_слот_медиана": (statistics.median(слоты[k]) if слоты[k] else None)}
            for k, v in пулов.most_common(10)]
    агенты = [x["кошелёк"] for x in верх
              if x["доля_пулов"] >= 100 * ПОРОГ_ОХВАТА]
    return {"переездов": всего, "поле_покупателей_есть": есть_поле,
            "верхние": верх, "агенты": агенты}


def срез_boost(x: dict, агенты: set) -> str:
    """BOOST / без BOOST по данным: покупал ли опознанный агент в этом пуле."""
    пк = x.get("покупатели")
    if пк is None:
        return "неизвестно"
    for к in пк:
        if к["кто"] in агенты and (к.get("покупок") or 0) >= ПОРОГ_ПОКУПОК:
            return "BOOST"
    return "без BOOST"


def круги(дни: dict, место: str, выход: int, б: float, агенты: set) -> list:
    """Один круг на каждый переезд: итог, резерв, срез BOOST, время входа."""
    из_ = []
    for д, тело in sorted(дни.items()):
        for x in тело.get("ряды") or []:
            if not переезд(Z.признаки(x)):
                continue
            с = Z.модель(x)
            if not с:
                continue
            к = (Z.круг(с, б, место, выход) if Z.позже_входа(с, место, выход)
                 else Z.круг_в_пустоту(с, б, место))
            if not к:
                continue
            из_.append({"сутки": д, "ts": (x.get("ts") or 0) / 1000.0,
                        "итог": к["итог_sol"], "резерв": к["резерв_вход_sol"],
                        "срез": срез_boost(x, агенты), "минт": x["минт"]})
    из_.sort(key=lambda r: r["ts"])
    return из_


def жадно_по_капиталу(ряды: list, б: float, H: int, капитал: float) -> dict:
    """Переезды в порядке появления; позиция берётся, если свободен кусок капитала.

    Отвечает на вопрос владельца «SOL/сут при капитале 4.7 SOL»: упирается ли дело в
    капитал или в само число переездов. Заодно даёт одновременно открытые -- среднее и
    максимум -- при этом удержании.
    """
    мест = int(капитал // б) if б > 0 else 0
    if мест <= 0:
        return {"мест": 0, "взято": 0, "пропущено": len(ряды)}
    держать = H * СЕК_НА_СЛОТ
    свободно = [0.0] * мест          # время, когда место освободится
    взятые, пропущено = [], 0
    одновременно: list = []
    for r in ряды:
        занято = sum(1 for t in свободно if t > r["ts"])
        одновременно.append(занято)
        i = min(range(мест), key=lambda j: свободно[j])
        if свободно[i] <= r["ts"]:
            свободно[i] = r["ts"] + держать
            взятые.append(r)
        else:
            пропущено += 1
    суток = len({r["сутки"] for r in ряды}) or 1
    v = [r["итог"] for r in взятые]
    пс: dict = collections.defaultdict(float)
    for r in взятые:
        пс[r["сутки"]] += r["итог"]
    return {"мест": мест, "держать_с": round(держать, 1), "взято": len(взятые),
            "пропущено": пропущено,
            "доля_взятых": round(100 * len(взятые) / max(1, len(ряды)), 1),
            "сделок_в_сутки": round(len(взятые) / суток, 1),
            "одновременно_среднее": round(statistics.mean(одновременно), 2) if одновременно else 0,
            "одновременно_макс": max(одновременно) if одновременно else 0,
            "sol_в_сутки": round(sum(v) / суток, 6) if v else 0.0,
            "sol_в_сутки_по_медиане": (round(statistics.median(v) * len(v) / суток, 6)
                                       if v else 0.0),
            "медиана_пп": round(100 * statistics.median(v) / б, 3) if v else None,
            "в_плюсе": round(100 * sum(1 for y in v if y > 0) / len(v), 1) if v else None,
            "худшие_сутки_sol": round(min(пс.values()), 6) if пс else None}


def свод(ряды: list, б: float) -> dict:
    v = [r["итог"] for r in ряды]
    if not v:
        return {"n": 0}
    верх = sorted(v, reverse=True)
    пс: dict = collections.defaultdict(float)
    for r in ряды:
        пс[r["сутки"]] += r["итог"]
    суток = len(пс) or 1
    return {"n": len(v), "суток": суток, "итог_sol": round(sum(v), 6),
            "sol_в_сутки": round(sum(v) / суток, 6),
            "sol_в_сутки_по_медиане": round(statistics.median(v) * len(v) / суток, 6),
            "сделок_в_сутки": round(len(v) / суток, 1),
            "медиана_пп": round(100 * statistics.median(v) / б, 3),
            "в_плюсе": round(100 * sum(1 for y in v if y > 0) / len(v), 1),
            "итог_без_5_лучших_sol": round(sum(верх[5:]), 6) if len(верх) > 5 else None,
            "итог_без_лучших_суток_sol": round(sum(v) - max(пс.values()), 6),
            "худшие_сутки_sol": round(min(пс.values()), 6),
            "доля_итога_у_1_процента": (round(100 * sum(верх[:max(1, len(верх) // 100)])
                                              / sum(v), 1) if sum(v) > 0 else None)}


def половины(ряды: list) -> tuple:
    дни = sorted({r["сутки"] for r in ряды})
    if len(дни) < 2:
        return (None, None)
    сер = дни[len(дни) // 2]
    a = [r for r in ряды if r["сутки"] < сер]
    b = [r for r in ряды if r["сутки"] >= сер]
    return ({"итог_sol": round(sum(r["итог"] for r in a), 6)} if a else None,
            {"итог_sol": round(sum(r["итог"] for r in b), 6)} if b else None)


def глубина(ряды: list, б: float) -> tuple:
    рез = [r["резерв"] for r in ряды if r.get("резерв")]
    if not рез:
        return False, None
    доля = sum(1 for x in рез if б <= ДОЛЯ_РЕЗЕРВА * x) / len(рез)
    return доля >= ДОЛЯ_ГЛУБИНЫ, round(100 * доля, 1)


def p_выбора(все_по_суткам: dict, выбор_по_суткам: dict) -> float | None:
    """Нуль: случайный выбор того же числа переездов в тех же сутках (точный хвост)."""
    μ = σ2 = наст = 0.0
    for д, вс in все_по_суткам.items():
        выб = выбор_по_суткам.get(д)
        if not выб or len(вс) < 2:
            continue
        k, N = len(выб), len(вс)
        наст += sum(выб)
        ср = sum(вс) / N
        дис = sum((x - ср) ** 2 for x in вс) / (N - 1)
        μ += k * ср
        σ2 += k * дис * (N - k) / (N - 1)
    if σ2 <= 0:
        return None
    return 0.5 * math.erfc((наст - μ) / math.sqrt(σ2) / math.sqrt(2))


