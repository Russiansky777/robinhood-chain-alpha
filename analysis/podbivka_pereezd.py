def вердикт(c: dict) -> str:
    """Одной строкой: что с этой строкой не так -- или что всё так.

    Порядок проверок -- по силе возражения: если продать нельзя в каждой четвёртой сделке,
    спорить про среднее уже не о чем.
    """
    if c.get("нельзя_продать_доля", 0) >= 10:
        return (f"нет: продать нельзя в {c['нельзя_продать_доля']:.0f} % сделок "
                "(пул к выходу опустошён)")
    if (c.get("ожидание_sol") or 0) <= 0:
        return "нет: ожидание не выше нуля"
    if (c.get("ди_низ") or 0) <= 0:
        return "нет: доверительный интервал среднего накрывает ноль"
    if (c.get("без_верх_1") or 0) <= 0:
        return "нет: без верхнего 1 % сделок среднее уходит в минус"
    if (c.get("половина_1_sol") or 0) <= 0 or (c.get("половина_2_sol") or 0) <= 0:
        return "нет: одна из половин проверки в минусе"
    if c.get("p") is not None and c["p"] > 0.01:
        return f"нет: от случайного запуска тех же суток не отличается (p {c['p']:.2f})"
    if c.get("доля_объёма_выше_10", 0) >= 10:
        return (f"нет: в {c['доля_объёма_выше_10']:.0f} % пулов билет больше десятой доли "
                "объёма окна, модель там неверна")
    return "да"


