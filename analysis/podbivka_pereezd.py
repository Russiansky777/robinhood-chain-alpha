def кв(v: list, q: float) -> float | None:
    if not v:
        return None
    s = sorted(v)
    i = max(0, min(len(s) - 1, int(round(q * (len(s) - 1)))))
    return s[i]


def срезанное(v: list, доля: float) -> float | None:
    """Среднее без верхних `доля` значений -- то самое «без верхних 1 % / 5 %»."""
    if not v:
        return None
    s = sorted(v)
    k = int(len(s) * доля)
    о = s[:len(s) - k] if k else s
    return statistics.fmean(о) if о else None


def бутстрэп(по_суткам: dict, рнд: random.Random) -> tuple:
    """Доверительный интервал среднего бутстрэпом ПО СУТКАМ, а не по сделкам.

    Сделки одних суток зависимы: один и тот же рынок, одна и та же волна. Поэтому единица
    пересборки -- сутки: иначе интервал выйдет в разы уже, чем есть на деле.
    """
    дни = [d for d in по_суткам if по_суткам[d]]
    if len(дни) < 3:
        return None, None
    сум = {d: (sum(по_суткам[d]), len(по_суткам[d])) for d in дни}
    ср = []
    for _ in range(БУТСТРЭПОВ):
        s = n = 0.0
        for _ in дни:
            a, b = сум[рнд.choice(дни)]
            s += a
            n += b
        if n:
            ср.append(s / n)
    ср.sort()
    return ср[int(0.025 * len(ср))], ср[int(0.975 * len(ср)) - 1]


def половина(по_суткам: dict, какая: int) -> float | None:
    """Среднее по первой или второй половине суток проверки -- устойчивость во времени."""
    дни = sorted(д for д in по_суткам if д >= ПРОВЕРКА_С)
    if len(дни) < 2:
        return None
    сер = len(дни) // 2
    взять = дни[:сер] if какая == 0 else дни[сер:]
    v = [x for д in взять for x in по_суткам[д]]
    return statistics.fmean(v) if v else None


