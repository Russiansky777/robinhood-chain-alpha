# ---- статистика -----------------------------------------------------------------

def кв(v: list, q: float) -> float | None:
    if not v:
        return None
    s = sorted(v)
    i = max(0, min(len(s) - 1, int(round(q * (len(s) - 1)))))
    return s[i]


def срезанное(v: list, доля: float) -> float | None:
    """Среднее без верхних `доля` значений -- то самое «без верхних 1 % / 5 %»."""
    if not v:
        return None
    s = sorted(v)
    k = int(len(s) * доля)
    о = s[:len(s) - k] if k else s
    return statistics.fmean(о) if о else None


def бутстрэп(по_суткам: dict, рнд: random.Random) -> tuple:
    """Доверительный интервал среднего бутстрэпом ПО СУТКАМ, а не по сделкам.

    Сделки одних суток зависимы: один и тот же рынок, одна и та же волна. Поэтому единица
    пересборки -- сутки: иначе интервал выйдет в разы уже, чем есть на деле.
    """
    дни = [d for d in по_суткам if по_суткам[d]]
    if len(дни) < 3:
        return None, None
    сум = {d: (sum(по_суткам[d]), len(по_суткам[d])) for d in дни}
    ср = []
    for _ in range(БУТСТРЭПОВ):
        s = n = 0.0
        for _ in дни:
            a, b = сум[рнд.choice(дни)]
            s += a
            n += b
        if n:
            ср.append(s / n)
    ср.sort()
    return ср[int(0.025 * len(ср))], ср[int(0.975 * len(ср)) - 1]


def свод(t: dict, дни_сп: list, рнд: random.Random, б: float) -> dict:
    итог = list(t["итог"])
    if not итог:
        return {"сделок": 0}
    пп = list(t["пп"])
    по_суткам: dict = collections.defaultdict(list)
    for v, дн in zip(итог, t["день"]):
        по_суткам[дни_сп[дн]].append(v)
    низ, верх = бутстрэп(по_суткам, рнд)
    минус = [v for v in итог if v < 0]
    по_суткам_сум = {d: sum(v) for d, v in по_суткам.items()}
    худ = min(по_суткам_сум.items(), key=lambda kv: kv[1])
    доли = [о / max(1e-9, о + б) for о in t["объём"]]      # наш билет в объёме покупок окна
    return {
        "сделок": len(итог), "суток": len(по_суткам),
        "сделок_в_сутки": round(len(итог) / len(по_суткам), 1),
        "ожидание_sol": statistics.fmean(итог), "ди_низ": низ, "ди_верх": верх,
        "без_верх_1": срезанное(итог, 0.01), "без_верх_5": срезанное(итог, 0.05),
        "медиана_sol": statistics.median(итог), "медиана_пп": statistics.median(пп),
        "в_плюсе_доля": 100 * sum(1 for v in итог if v > 0) / len(итог),
        "в_плюсе": sum(1 for v in итог if v > 0), "в_минусе": len(минус),
        "медиана_убыточных_пп": statistics.median([p for p in пп if p < 0]) if минус else None,
        "p10_пп": кв(пп, 0.10), "p5_пп": кв(пп, 0.05), "p1_пп": кв(пп, 0.01),
        "худшая_сделка_пп": min(пп), "хуже_минус10": 100 * sum(1 for p in пп if p < -10) / len(пп),
        "хуже_минус50": 100 * sum(1 for p in пп if p < -50) / len(пп),
        "худшие_сутки": худ[0], "худшие_сутки_sol": худ[1],
        "sol_в_сутки": sum(итог) / len(по_суткам),
        "наша_доля_объёма_медиана": 100 * statistics.median([
            б / max(1e-9, о + б) for о in t["объём"]]) if len(t["объём"]) else None,
        "доля_объёма_выше_10": 100 * sum(1 for о in t["объём"]
                                         if б / max(1e-9, о + б) > 0.10) / len(t["объём"]),
        "нельзя_продать_доля": 100 * sum(1 for v in t["вид"] if v in (1, 2)) / len(итог),
        "пул_закрыт_доля": 100 * sum(1 for v in t["вид"] if v == 1) / len(итог),
        "никто_не_торговал_доля": 100 * sum(1 for v in t["вид"] if v == 3) / len(итог),
    }


def серединная(t: dict, rr: dict) -> dict | None:
    """Пункт ж: раскладка СЕРЕДИННОЙ по итогу сделки, а не среднее по компонентам."""
    итог = list(t["итог"])
    if not итог:
        return None
    пары = sorted(range(len(итог)), key=lambda i: итог[i])
    i = пары[len(пары) // 2]
    из_ = {имя: (None if rr[имя][i] != rr[имя][i] else rr[имя][i])
           for имя in ("рост", "вх", "вых", "тариф", "итог")}
    из_["вид"] = ИЗ_ВИДА.get(t["вид"][i], "?")
    из_["резерв_sol"] = t["резерв"][i]
    return из_


def p_выбора(нуль_по_суткам: dict, выбор: dict) -> float | None:
    """Аналитический p: та же сумма k случайных из N в каждых сутках проверки."""
    μ = σ2 = s = 0.0
    for д, все in нуль_по_суткам.items():
        v = выбор.get(д)
        if not v or not все:
            continue
        N, k = len(все), len(v)
        if k < 1 or N < 2:
            continue
        m = statistics.fmean(все)
        d2 = statistics.pvariance(все)
        μ += k * m
        σ2 += k * d2 * (N - k) / (N - 1)
        s += sum(v)
    if σ2 <= 0:
        return None
    z = (s - μ) / math.sqrt(σ2)
    return 0.5 * math.erfc(z / math.sqrt(2))


