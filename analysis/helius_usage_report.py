#!/usr/bin/env python3
"""Сводка расхода кредитов Helius по ВСЕМ службам за сутки.

Почему отдельным скриптом, а не строчкой в workflow: внутри блока
run: | нельзя написать heredoc -- его терминатор обязан стоять в нулевой
колонке, а это обрывает блочный скаляр YAML. Если же отступить
терминатор, YAML разберётся, `bash -n` промолчит (незакрытый heredoc он
принимает), и сломается только на прогоне. Такой класс ошибок в этом
репозитории уже стоил двух неудачных деплоев.

Только чтение data/helius_usage/*.json. Сети не касается.
"""
from __future__ import annotations

import argparse
import json
import sys
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from solana_rpc_client import (  # noqa: E402
    BUDGET_GROUPS, DAILY_BUDGET, GROUP_OF, WARN_AT, merge_usage, usage_shards)

REPO_ROOT = Path(__file__).resolve().parent.parent


def сводка(база: Path | None = None, день: str | None = None) -> dict:
    осколки = usage_shards(база) if база else usage_shards()
    данные = merge_usage(осколки)
    день = день or time.strftime("%Y-%m-%d", time.gmtime())
    d = (данные.get("дни") or {}).get(день) or {}
    # Бюджет берётся из МОДЕЛИ, а не из осколка: merge_usage сводит только
    # кредиты и байты, а бюджет принадлежит настройке, не файлу. Так сводку
    # ещё и нельзя обмануть устаревшим осколком с прежним порогом.
    расход = {имя: int((v or {}).get("кредитов_за_день", 0) or 0)
               for имя, v in d.items() if isinstance(v, dict)}
    по_группам: dict = {}
    for имя, c in расход.items():
        г = GROUP_OF.get(имя)
        if г:
            по_группам[г] = по_группам.get(г, 0) + c

    службы = []
    всего = 0
    без_бюджета = []
    выше_порога = []
    for имя in sorted(расход):
        c = расход[имя]
        всего += c
        г = GROUP_OF.get(имя)
        свой = DAILY_BUDGET.get(имя)
        if свой:
            б, потрачено = свой, c
        elif г and BUDGET_GROUPS.get(г):
            б, потрачено = BUDGET_GROUPS[г], по_группам.get(г, c)
        else:
            б, потрачено = None, c
        доля = round(потрачено / б, 4) if б else None
        выше = bool(доля is not None and доля >= WARN_AT)
        службы.append({"служба": имя, "кредитов": c, "бюджет": б, "доля": доля,
                        "группа": г, "потрачено_по_бюджету": потрачено,
                        "выше_70": выше})
        if not б:
            без_бюджета.append(имя)
        if выше:
            выше_порога.append(имя)
    return {"день": день, "осколков": len(осколки), "службы": службы,
             "всего_кредитов": всего,
             "без_бюджета": без_бюджета, "выше_70_процентов": выше_порога,
             "оговорка": ("Службы из списка без_бюджета расход тратят, но порога "
                          "у них нет: владелец его ещё не называл, а выдумывать "
                          "свой предел за него нельзя.")}


def печать(с: dict) -> None:
    if not с["службы"]:
        print(f"за {с['день']} расхода не записано (осколков {с['осколков']})")
        return
    for r in с["службы"]:
        хвост = f", доля {r['доля']}" if r["доля"] is not None else ""
        порог = "  ВЫШЕ 70%" if r["выше_70"] else ""
        print(f"  {r['служба']}: {r['кредитов']} кредитов, бюджет "
              f"{r['бюджет'] if r['бюджет'] else 'НЕ ЗАДАН ВЛАДЕЛЬЦЕМ'}{хвост}{порог}")
    print(f"  ВСЕГО за {с['день']}: {с['всего_кредитов']} кредитов")
    if с["без_бюджета"]:
        print(f"  без бюджета: {', '.join(с['без_бюджета'])} -- порог назовёт владелец")


def self_test() -> int:
    import tempfile  # noqa: PLC0415
    проверки = []

    def chk(имя, ок, факт=""):
        проверки.append((имя, bool(ок), факт))

    with tempfile.TemporaryDirectory() as d:
        база = Path(d)
        день = "2026-09-23"
        def осколок(имя, кредитов):
            (база / f"{имя}.json").write_text(json.dumps({"дни": {день: {
                имя: {"кредитов_за_день": кредитов, "байт_за_день": 0,
                       "по_часам": {}}}}}), encoding="utf-8")

        # ledger -- со своим бюджетом; bloom_detector -- без бюджета;
        # две службы группы "прогоны" -- с ОБЩИМ бюджетом.
        осколок("ledger", 100)
        осколок("bloom_detector", 50)
        осколок("разбор_пилота", 80_000)
        осколок("ретро", 80_000)
        с = сводка(база, день)
        по_имени = {r["служба"]: r for r in с["службы"]}
        chk("осколки собраны все", с["осколков"] == 4, с["осколков"])
        chk("службы просуммированы", с["всего_кредитов"] == 160_150, с["всего_кредитов"])
        chk("свой бюджет взят из модели",
            по_имени["ledger"]["бюджет"] == DAILY_BUDGET["ledger"], по_имени["ledger"])
        chk("служба без бюджета названа", с["без_бюджета"] == ["bloom_detector"],
            с["без_бюджета"])
        chk("бюджет группы общий, а не на каждого",
            по_имени["разбор_пилота"]["бюджет"] == BUDGET_GROUPS["прогоны"]
            and по_имени["разбор_пилота"]["потрачено_по_бюджету"] == 160_000,
            по_имени["разбор_пилота"])
        chk("порог считается по трате ГРУППЫ",
            по_имени["ретро"]["выше_70"] is True, по_имени["ретро"])
        chk("превышение названо для обеих служб группы",
            sorted(с["выше_70_процентов"]) == ["разбор_пилота", "ретро"],
            с["выше_70_процентов"])
        chk("служба со своим малым расходом порог не перешла",
            по_имени["ledger"]["выше_70"] is False, по_имени["ledger"])
        chk("в оговорке сказано, что порог за владельцем",
            "владелец" in с["оговорка"], с["оговорка"])
        пусто = сводка(база, "1999-01-01")
        chk("за день без данных -- пусто, а не ноль по всем",
            пусто["службы"] == [] and пусто["всего_кредитов"] == 0, пусто)

    прошло = sum(1 for _, ок, _ in проверки if ок)
    for имя, ок, факт in проверки:
        print(f"  [{'ok  ' if ок else 'ПЛОХО'}] {имя}" + (f" -- {факт}" if not ок else ""))
    print(f"самопроверка сводки кредитов: {прошло}/{len(проверки)} пройдено")
    return 0 if прошло == len(проверки) else 1


def main() -> int:
    p = argparse.ArgumentParser()
    p.add_argument("--self-test", action="store_true")
    p.add_argument("--day", default=None)
    p.add_argument("--base", default=None)
    p.add_argument("--json", action="store_true")
    a = p.parse_args()
    if a.self_test:
        return self_test()
    с = сводка(Path(a.base) if a.base else None, a.day)
    if a.json:
        print(json.dumps(с, ensure_ascii=False, indent=2))
    else:
        печать(с)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
