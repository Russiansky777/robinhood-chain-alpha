def перестановки_выбора(все_по_суткам: dict, выбор_по_суткам: dict,
                        повторов: int = ПОВТОРОВ, seed: int = 20261009) -> float | None:
    """Нуль: случайный выбор того же числа запусков в тех же сутках."""
    настоящий = sum(sum(v) for v in выбор_по_суткам.values())
    if not выбор_по_суткам:
        return None
    рнд = random.Random(seed)
    превзошли = 0
    for _ in range(повторов):
        s = 0.0
        for д, вс in все_по_суткам.items():
            k = len(выбор_по_суткам.get(д, []))
            if k and вс:
                s += sum(рнд.sample(вс, min(k, len(вс))))
        if s >= настоящий:
            превзошли += 1
    return (превзошли + 1) / (повторов + 1)


def свод_ряды(ряды: list, б: float) -> dict:
    """Те же числа, что у `podbivka_volna.свод`, но доля попадания уже учтена в отборе."""
    v = [x["итог"] for x in ряды]
    if not v:
        return {"n": 0}
    верх = sorted(v, reverse=True)
    пс: dict = collections.defaultdict(float)
    for x in ряды:
        пс[x["сутки"]] += x["итог"]
    суток = len(пс) or 1
    return {"n": len(v), "суток": суток, "итог_sol": round(sum(v), 6),
            "sol_в_сутки": round(sum(v) / суток, 6),
            "сделок_в_сутки": round(len(v) / суток, 1),
            "медиана_пп": round(100 * statistics.median(v) / б, 3),
            "в_плюсе": round(100 * sum(1 for y in v if y > 0) / len(v), 1),
            "итог_без_5_лучших_sol": round(sum(верх[5:]), 6) if len(верх) > 5 else None,
            "итог_без_лучших_суток_sol": round(sum(v) - max(пс.values()), 6),
            "худшие_сутки_sol": round(min(пс.values()), 6),
            # лотерея или ремесло: какую долю всего плюса несёт верхний процент сделок
            "доля_итога_у_1_процента": (round(100 * sum(верх[:max(1, len(верх) // 100)])
                                              / sum(v), 1) if sum(v) > 0 else None)}


def половины(ряды: list) -> tuple:
    дни = sorted({x["сутки"] for x in ряды})
    if len(дни) < 2:
        return (None, None)
    середина = дни[len(дни) // 2]
    a = [x for x in ряды if x["сутки"] < середина]
    b = [x for x in ряды if x["сутки"] >= середина]
    return ({"итог_sol": round(sum(x["итог"] for x in a), 6)} if a else None,
            {"итог_sol": round(sum(x["итог"] for x in b), 6)} if b else None)


def ф(v, формат="+.4f"):
    return "—" if v is None else format(v, формат)


def охват(дни: dict, словарь: collections.Counter) -> dict:
    """В.1: сколько запусков в сутки и из чего они состоят."""
    по_суткам, правила, пулы = {}, collections.Counter(), collections.Counter()
    минты: set = set()
    мульти_всего = 0
    for д, тело in sorted(дни.items()):
        р = тело.get("ряды") or []
        м = collections.Counter(x["минт"] for x in р if x["минт"])
        мульти = sum(1 for v in м.values() if v >= 2)
        мульти_всего += мульти
        минты |= set(м)
        по_суткам[д] = {
            "запусков": len(р), "минтов": len(м), "с_двумя_пулами": мульти,
            "строк": (тело.get("счёт") or {}).get("строк"),
            "часов": (тело.get("счёт") or {}).get("часов"),
            "кривых": sum(1 for x in р if x["пул"] == "pump"),
            "переездов": sum(1 for x in р if x["правило"] == "создание:migrate"),
            "sol_котировка": sum(1 for x in р if x.get("quoteMint") == WSOL),
            "купили_в_блоке": sum(1 for x in р if (x.get("в_блоке_создания") or {}).get("покупок")),
        }
        правила.update(x["правило"] for x in р)
        пулы.update(x["пул"] for x in р)
    сут = len(по_суткам) or 1
    return {"суток": сут, "по_суткам": по_суткам,
            "правила": dict(правила.most_common()), "пулы": dict(пулы.most_common(12)),
            "минтов_всего": len(минты), "с_двумя_пулами_всего": мульти_всего,
            "в_сутки": {k: round(sum(x[k] for x in по_суткам.values()) / сут, 1)
                        for k in ("запусков", "минтов", "кривых", "переездов",
                                  "с_двумя_пулами", "купили_в_блоке")},
            "словарь_действий": dict(словарь.most_common())}


def волна_профиль(дни: dict) -> dict:
    """В.3: кто покупает за создателем и когда цена на пике."""
    кош, сол, пик_пп, пик_сл, первая = [], [], [], [], []
    для_пика = 0
    for тело in дни.values():
        for x in тело.get("ряды") or []:
            в = (x.get("волна") or {}).get("60с") or {}
            кош.append(в.get("кошельков") or 0)
            сол.append(в.get("sol") or 0)
            if x.get("пик"):
                пик_пп.append(x["пик"]["рост_пп"])
                пик_сл.append(x["пик"]["слотов"])
                для_пика += 1
            if x.get("первая_продажа_слотов") is not None:
                первая.append(x["первая_продажа_слотов"])
    окна = {}
    for т in ("5с", "15с", "30с", "60с"):
        к = [(x.get("волна") or {}).get(т, {}).get("кошельков") or 0
             for тело in дни.values() for x in тело.get("ряды") or []]
        s = [(x.get("волна") or {}).get(т, {}).get("sol") or 0
             for тело in дни.values() for x in тело.get("ряды") or []]
        окна[т] = {"кошельков": V.стат(к), "sol": V.стат(s, 3),
                   "доля_с_покупкой": round(100 * sum(1 for y in к if y > 0) / max(1, len(к)), 1)}
    return {"окна": окна, "пик_рост_пп": V.стат(пик_пп), "пик_слотов": V.стат(пик_сл),
            "первая_продажа_слотов": V.стат(первая), "рядов_с_пиком": для_пика}


def сделки(дни: dict, место: str, выход: int, б: float, срез=None) -> list:
    """Один круг на каждый запуск, который проходит срез и у которого выход позже входа."""
    из_ = []
    for д, тело in дни.items():
        for x in тело.get("ряды") or []:
            if срез and not срез(признаки(x)):
                continue
            с = модель(x)
            if not с:
                continue
            к = (круг(с, б, место, выход) if позже_входа(x, место, выход)
                 else круг_в_пустоту(с, x, б, место))
            if not к:
                continue
            из_.append({"сутки": д, "минт": x["минт"], "пул": x["пул"],
                        "правило": x["правило"], "итог": к["итог_sol"],
                        "резерв": к["резерв_вход_sol"],
                        "волна60_кош": ((x.get("волна") or {}).get("60с") or {}).get("кошельков") or 0})
    return из_


def глубина_ок(ряды: list, б: float) -> tuple:
    """Билет не больше 2 % резерва пула на входе хотя бы у 80 % сделок."""
    рез = [x["резерв"] for x in ряды if x.get("резерв")]
    if not рез:
        return False, None
    доля = sum(1 for r in рез if б <= ДОЛЯ_РЕЗЕРВА * r) / len(рез)
    return доля >= ДОЛЯ_ГЛУБИНЫ, round(100 * доля, 1)


def куплено(сост, пул: str, f, fee: float, a: float) -> float | None:
    """Сколько токенов даст покупка на `a` SOL в этом состоянии пула."""
    x, y = float(сост[0]), float(сост[1])
    if x <= 0 or y <= 0 or a <= 0:
        return None
    if пул in B.XYK:
        if not f:
            return None
        т = y * f * a / (x + f * a)
    else:
        net = a / (1 + (fee or 0))
        т = y * net / (x + net)
    return т if т > 0 else None


def продано(сост, пул: str, g, fee: float, т: float) -> float | None:
    """Сколько SOL вернёт продажа `т` токенов в этом состоянии пула."""
    x, y = float(сост[0]), float(сост[1])
    if x <= 0 or y <= 0 or т <= 0:
        return None
    if пул in B.XYK:
        if not g:
            return None
        return x * g * т / (y + т)
    return x * т / (y + т) * (1 - (fee or 0)) * К_G


def ряды_пула(x: dict) -> list:
    """(блок, состояние) по возрастанию блока: вход и все выходы запуска."""
    из_ = []
    for v in (x.get("вход") or {}).values():
        из_.append((v[2], (v[0], v[1])))
    for v in (x.get("выход") or {}).values():
        из_.append((v[2], (v[0], v[1])))
    из_.sort()
    уник = []
    for б, с in из_:
        if not уник or уник[-1][0] != б:
            уник.append((б, с))
    return уник


def арбитраж(дни: dict, билеты=(0.1, 0.3, 1.0), допуск_слотов: int = 2) -> dict:
    """п.3б: минты с двумя и более пулами -- разница цен на совпадающих блоках.

    Круг арбитража считается до конца: покупка в одном пуле, продажа в другом, обе наценки,
    оба тарифа и издержки круга. Ограничение честное: наблюдения разрежены (вход и 7 выходов
    на каждый пул в первых 230 слотах его жизни), поэтому «не меньше 2 слотов» проверяется
    по двум РАЗНЫМ точкам наблюдения, а не по каждому слоту.
    """
    из_: dict = {"билеты": {}, "минтов_с_2_пулами": 0, "пар_пулов": 0, "сравнений": 0,
                 "по_суткам": {}}
    пары_типов: collections.Counter = collections.Counter()
    лучшие: list = []
    счёт: dict = {б: {"минтов_с_выгодой": collections.Counter(), "сравнений_в_плюсе": 0,
                      "итог_sol": 0.0, "пп": []} for б in билеты}
    for д, тело in sorted(дни.items()):
        по_минту: dict = collections.defaultdict(list)
        for x in тело.get("ряды") or []:
            # Слово владельца: завершившая кривая больше не торгует, значит пары
            # «кривая + пул» нет вовсе. Сосредоточенная ликвидность -- тоже мимо: на
            # полных резервах её цену не посчитать.
            вх = (x.get("вход") or {}).get("створ_дно")
            if (x.get("quoteMint") == WSOL and x.get("минт") and вх
                    and x.get("пул") not in КРИВЫЕ and x.get("пул") not in НЕ_СЧИТАЕМ
                    # пул должен быть настоящим, а не пылевой засевкой переезда
                    and вх[0] >= РЕЗЕРВ_АРБИТРАЖА and (x.get("событий") or 0) >= СОБЫТИЙ_АРБИТРАЖА):
                по_минту[x["минт"]].append(x)
        сут: dict = {б: 0.0 for б in билеты}
        for минт, пулы in по_минту.items():
            if len(пулы) < 2:
                continue
            из_["минтов_с_2_пулами"] += 1
            for i in range(len(пулы)):
                for j in range(len(пулы)):
                    if i == j:
                        continue
                    A, Б = пулы[i], пулы[j]
                    if A.get("poolId") == Б.get("poolId"):
                        continue
                    рA, рБ = ряды_пула(A), ряды_пула(Б)
                    if not рA or not рБ:
                        continue
                    if i < j:
                        из_["пар_пулов"] += 1
                        пары_типов[tuple(sorted((A["пул"] or "?", Б["пул"] or "?")))] += 1
                    в_плюсе_точек: dict = collections.Counter()
                    for бл, сA in рA:
                        близкие = [(abs(б2 - бл), с2) for б2, с2 in рБ
                                   if abs(б2 - бл) <= допуск_слотов]
                        if не_пусто := sorted(близкие):
                            сБ = не_пусто[0][1]
                        else:
                            continue
                        из_["сравнений"] += 1
                        for б in билеты:
                            т = куплено(сA, A["пул"], A.get("f"), A.get("тариф") or 0, б)
                            if not т:
                                continue
                            out = продано(сБ, Б["пул"], Б.get("g"), Б.get("тариф") or 0, т)
                            if not out:
                                continue
                            итог = out - б - ИЗДЕРЖКИ
                            счёт[б]["пп"].append(100 * итог / б)
                            if итог > 0:
                                счёт[б]["сравнений_в_плюсе"] += 1
                                в_плюсе_точек[б] += 1
                                счёт[б]["итог_sol"] += итог
                                сут[б] += итог
                                лучшие.append({"сутки": д, "минт": минт, "билет": б,
                                               "пулы": [A["пул"], Б["пул"]], "блок": бл,
                                               "итог_sol": round(итог, 6)})
                    for б, k in в_плюсе_точек.items():
                        счёт[б]["минтов_с_выгодой"][">=2 точек" if k >= 2 else "1 точка"] += 1
        из_["по_суткам"][д] = {б: round(v, 6) for б, v in сут.items()}
    сут_n = len(из_["по_суткам"]) or 1
    for б in билеты:
        c = счёт[б]
        из_["билеты"][б] = {
            "сравнений": len(c["пп"]), "в_плюсе": c["сравнений_в_плюсе"],
            "доля_в_плюсе": round(100 * c["сравнений_в_плюсе"] / max(1, len(c["пп"])), 2),
            "медиана_пп": round(statistics.median(c["пп"]), 3) if c["пп"] else None,
            "p95_пп": round(sorted(c["пп"])[int(0.95 * (len(c["пп"]) - 1))], 3) if c["пп"] else None,
            "итог_sol": round(c["итог_sol"], 6),
            "sol_в_сутки": round(c["итог_sol"] / сут_n, 6),
            "минтов_с_выгодой": dict(c["минтов_с_выгодой"])}
    лучшие.sort(key=lambda x: -x["итог_sol"])
    из_["пары_типов"] = {f"{a} + {b}": v for (a, b), v in пары_типов.most_common(12)}
    из_["верхние"] = лучшие[:15]
    return из_


def сетка(дни: dict, места=МЕСТА, выходы=ВЫХОДЫ, билеты=БИЛЕТЫ, срез=None) -> dict:
    """Один проход по рядам: все комбинации места, удержания и билета сразу.

    Подбор держится в виде итогов (сумма, пять лучших, суммы по суткам) -- значения не
    хранятся, иначе память. Проверка держится значениями: по ним медиана, половины,
    худшие сутки и перестановки.
    """
    from array import array           # noqa: PLC0415
    import heapq                      # noqa: PLC0415
    ключи = [(м, h, б) for м in места for h in выходы for б in билеты]
    подб: dict = {(ф_, k): {"n": 0, "сумма": 0.0, "верх": [], "по_суткам": collections.Counter()}
                  for ф_ in ФИЛЬТРЫ for k in ключи}
    пров: dict = {(ф_, k): {"знач": array("f"), "сутки": [], "резервы": array("f")}
                  for ф_ in ФИЛЬТРЫ for k in ключи}
    все_пров: dict = collections.defaultdict(lambda: collections.defaultdict(list))
    счёт = collections.Counter()
    for д, тело in sorted(дни.items()):
        проверка = д >= ПРОВЕРКА_С
        for x in тело.get("ряды") or []:
            п = признаки(x)
            if срез and not срез(п):
                continue
            с = модель(x)
            if not с:
                счёт["без_модели"] += 1
                continue
            подходят = [ф_ for ф_, пр in ФИЛЬТРЫ.items() if пр(п)]
            if not подходят:
                continue
            счёт["рядов"] += 1
            пустые: dict = {}
            for k in ключи:
                м, h, б = k
                if позже_входа(x, м, h):
                    кр = круг(с, б, м, h)
                else:
                    if (м, б) not in пустые:
                        пустые[(м, б)] = круг_в_пустоту(с, x, б, м)
                        if пустые[(м, б)]:
                            счёт["кругов_в_пустоту"] += 1
                    кр = пустые[(м, б)]
                if not кр:
                    continue
                v = кр["итог_sol"]
                счёт["кругов"] += 1
                if проверка:
                    все_пров[k][д].append(v)
                for ф_ in подходят:
                    if проверка:
                        t = пров[(ф_, k)]
                        t["знач"].append(v)
                        t["сутки"].append(д)
                        t["резервы"].append(кр["резерв_вход_sol"] or 0.0)
                    else:
                        t = подб[(ф_, k)]
                        t["n"] += 1
                        t["сумма"] += v
                        t["по_суткам"][д] += v
                        if len(t["верх"]) < 5:
                            heapq.heappush(t["верх"], v)
                        elif v > t["верх"][0]:
                            heapq.heapreplace(t["верх"], v)
    return {"ключи": ключи, "подбор": подб, "проверка": пров,
            "все_проверки": {k: dict(v) for k, v in все_пров.items()}, "счёт": dict(счёт)}


def подбор_прошёл(t: dict) -> bool:
    """Правило подбора: сумма в плюсе И без пяти лучших в плюсе И не меньше 100 кругов."""
    return bool(t["n"] >= 100 and t["сумма"] > 0 and (t["сумма"] - sum(t["верх"])) > 0)


def оценить(t: dict, б: float, все_пров: dict, подб: dict | None = None) -> dict:
    """Проверка одного кандидата: порог владельца плюс уровень случайности."""
    ряды = [{"итог": v, "сутки": д, "резерв": r}
            for v, д, r in zip(t["знач"], t["сутки"], t["резервы"])]
    if not ряды:
        return {"n": 0}
    св = свод_ряды(ряды, б)
    пол = половины(ряды)
    гл, доля_гл = глубина_ок(ряды, б)
    выбор: dict = collections.defaultdict(list)
    for x in ряды:
        выбор[x["сутки"]].append(x["итог"])
    p = перестановки_выбора(все_пров, выбор)
    подб_св = {"итог_без_5_лучших_sol": (подб["сумма"] - sum(подб["верх"])) if подб else 1.0}
    да, нет = V.порог(св, пол, p, гл, подб_св)
    return {**св, "p": p, "глубина": гл, "доля_глубины": доля_гл,
            "половина_1": (пол[0] or {}).get("итог_sol"),
            "половина_2": (пол[1] or {}).get("итог_sol"),
            "проходит": да, "почему_нет": нет}


