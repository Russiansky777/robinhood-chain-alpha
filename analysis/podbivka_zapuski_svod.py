#!/usr/bin/env python3
"""Запуски мемкоинов: охват, волна и вход от создания (п.В), переезд кривой и арбитраж (п.3).

Считает по собранным суткам `data/podbivka/zapuski/zap_*.json.gz` (сборщик
`podbivka_zapuski.py`). Своих запросов в сеть не делает -- только чтение файлов.

Что здесь есть.
  * В.1 -- охват: сколько запусков в сутки по цепи, по правилу опознания и по типу пула,
    сколько минтов, сколько переездов кривой, сколько минтов с двумя и более пулами.
  * В.2 -- наш вход от создания: у какой доли запусков есть состояние пула в конце блока
    создания, в +1 и в +2 слотах (это и есть наша калиброванная посадка относительно
    создания, а не сделки источника).
  * В.3 -- волна: разные кошельки-покупатели за 5/15/30/60 с, пик и первая продажа.
  * В.4 -- стратегии: место входа x удержание x билет, отбор правил ТОЛЬКО на подборе,
    порог владельца (`podbivka_final`) на проверке, медиана по совершённым сделкам.
  * п.3а -- переезд кривой: те же числа на срезе `создание:migrate`.
  * п.3б -- арбитраж: минты с двумя и более пулами, разница цен на совпадающих блоках.

Отбор правил: фильтры берут ТОЛЬКО то, что известно на момент входа -- тип пула, правило
опознания, покупки в блоке создания (сколько, какими кошельками, на сколько SOL, покупал ли
создатель). Волна 5-60 с на момент входа ещё не случилась, поэтому фильтром она быть не
может -- иначе это заглядывание вперёд.

Уровень случайности: нуль -- случайный выбор того же числа запусков в тех же сутках. Так
проверяется именно правило отбора, а не то, что запуски вообще бывают прибыльными.
"""
