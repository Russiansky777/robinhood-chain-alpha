def p_аналитически(все_по_суткам: dict, выбор_по_суткам: dict) -> float | None:
    """Тот же нуль, но без перебора: сумма k случайных из N в каждых сутках.

    Зачем. При 200 перестановках мельче p=0.005 не получить, а поправка Холма по сотне
    кандидатов требует p не хуже 0.0005 -- то есть перестановочный p её не берёт НИКОГДА,
    и «ноль прошедших» означал бы только грубость счёта, а не отсутствие находки. Здесь
    среднее и дисперсия суммы выбора без возвращения считаются точно (с поправкой на
    конечную совокупность), а хвост берётся нормальным приближением -- оно и даёт мелкие p.

    Приближение честно назвать приближением: итоги сделок с тяжёлым правым хвостом сходятся
    к нормальному медленно, поэтому рядом считается и перестановочный p, и в документе
    стоят оба.
    """
    μ = σ2 = 0.0
    настоящий = 0.0
    for д, вс in все_по_суткам.items():
        выб = выбор_по_суткам.get(д)
        if not выб:
            continue
        k, N = len(выб), len(вс)
        if N < 2 or k < 1:
            continue
        настоящий += sum(выб)
        ср = sum(вс) / N
        дис = sum((v - ср) ** 2 for v in вс) / (N - 1)
        μ += k * ср
        σ2 += k * дис * (N - k) / (N - 1)
    if σ2 <= 0:
        return None
    z = (настоящий - μ) / math.sqrt(σ2)
    # правый хвост нормального распределения
    return 0.5 * math.erfc(z / math.sqrt(2))


def перестановки_выбора(все_по_суткам: dict, выбор_по_суткам: dict,
                        повторов: int = ПОВТОРОВ, seed: int = 20261009) -> float | None:
    """Нуль: случайный выбор того же числа запусков в тех же сутках."""
    настоящий = sum(sum(v) for v in выбор_по_суткам.values())
    if not выбор_по_суткам:
        return None
    рнд = random.Random(seed)
    превзошли = 0
    for _ in range(повторов):
        s = 0.0
        for д, вс in все_по_суткам.items():
            k = len(выбор_по_суткам.get(д, []))
            if k and вс:
                s += sum(рнд.sample(вс, min(k, len(вс))))
        if s >= настоящий:
            превзошли += 1
    return (превзошли + 1) / (повторов + 1)


БУТСТРЭПОВ = 2000


def срезанное(v: list, доля: float):
    """Среднее без верхних `доля` значений."""
    if not v:
        return None
    s = sorted(v)
    k = int(len(s) * доля)
    о = s[:len(s) - k] if k else s
    return statistics.fmean(о) if о else None


def ди_по_суткам(по_суткам: dict, seed: int = 20261009) -> tuple:
    """Доверительный интервал среднего бутстрэпом ПО СУТКАМ, а не по сделкам.

    Запуски одних суток зависимы: один рынок, одна волна. Бутстрэп по сделкам дал бы
    интервал в разы уже, чем он есть.
    """
    дни = [d for d in по_суткам if по_суткам[d]]
    if len(дни) < 3:
        return None, None
    рнд = random.Random(seed)
    сум = {d: (sum(по_суткам[d]), len(по_суткам[d])) for d in дни}
    ср = []
    for _ in range(БУТСТРЭПОВ):
        s = k = 0.0
        for _ in дни:
            a, b = сум[рнд.choice(дни)]
            s += a; k += b
        if k:
            ср.append(s / k)
    ср.sort()
    return ср[int(0.025 * len(ср))], ср[int(0.975 * len(ср)) - 1]


def свод_ряды(ряды: list, б: float) -> dict:
    """Те же числа, что у `podbivka_volna.свод`, но доля попадания уже учтена в отборе."""
    v = [x["итог"] for x in ряды]
    if not v:
        return {"n": 0}
    виды = collections.Counter(x.get("вид") for x in ряды if x.get("вид"))
    объёмы = [x.get("объём") or 0.0 for x in ряды]
    доли = [б / max(1e-9, о + б) for о in объёмы]
    по_суткам_сп: dict = collections.defaultdict(list)
    for x in ряды:
        по_суткам_сп[x["сутки"]].append(x["итог"])
    низ, верх_ди = ди_по_суткам(по_суткам_сп)
    верх = sorted(v, reverse=True)
    пс: dict = collections.defaultdict(float)
    for x in ряды:
        пс[x["сутки"]] += x["итог"]
    суток = len(пс) or 1
    return {"n": len(v), "суток": суток, "итог_sol": round(sum(v), 6),
            "sol_в_сутки": round(sum(v) / суток, 6),
            "сделок_в_сутки": round(len(v) / суток, 1),
            "медиана_пп": round(100 * statistics.median(v) / б, 3),
            # Главное число для решения: средний итог тянет правый хвост (у запусков он в
            # разы больше медианы), поэтому рядом стоит доход, посчитанный по МЕДИАННОЙ
            # сделке -- столько выйдет, если хвоста в этих сутках не случится.
            "sol_в_сутки_по_медиане": round(statistics.median(v) * len(v) / суток, 6),
            "в_плюсе": round(100 * sum(1 for y in v if y > 0) / len(v), 1),
            "итог_без_5_лучших_sol": round(sum(верх[5:]), 6) if len(верх) > 5 else None,
            "итог_без_лучших_суток_sol": round(sum(v) - max(пс.values()), 6),
            "худшие_сутки_sol": round(min(пс.values()), 6),
            # лотерея или ремесло: какую долю всего плюса несёт верхний процент сделок
            "доля_итога_у_1_процента": (round(100 * sum(верх[:max(1, len(верх) // 100)])
                                              / sum(v), 1) if sum(v) > 0 else None),
            # Ожидание на ОДНУ сделку после всех расходов, его доверительный интервал по
            # суткам и то же среднее с отрезанным верхом -- порядок владельца 09.10.
            "ожидание_sol": statistics.fmean(v), "ди_низ": низ, "ди_верх": верх_ди,
            "без_верх_1": срезанное(v, 0.01), "без_верх_5": срезанное(v, 0.05),
            "медиана_sol": statistics.median(v),
            "нельзя_продать_доля": round(100 * виды["нельзя_продать"] / len(v), 1),
            "никто_не_торговал_доля": round(100 * виды["пусто"] / len(v), 1),
            "наша_доля_объёма_медиана": round(100 * statistics.median(доли), 1),
            "доля_объёма_выше_10": round(100 * sum(1 for d in доли if d > 0.10)
                                         / len(доли), 1)}


