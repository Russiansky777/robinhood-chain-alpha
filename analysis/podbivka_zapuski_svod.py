def сутки_файла(метка: str) -> str:
    """zap_2026-10-07T06 -> 2026-10-07 (окно суток начинается в 06Z, как у den_)."""
    return метка.replace("zap_", "").split("T")[0]


def загрузить(папка: Path) -> tuple:
    дни, словарь, счёт = {}, collections.Counter(), collections.Counter()
    for ф in sorted(папка.glob("zap_*.json.gz")):
        with gzip.open(ф, "rt", encoding="utf-8") as о:
            д = json.load(о)
        м = ф.name.replace(".json.gz", "")
        дни[сутки_файла(м)] = д
        словарь.update(д.get("словарь_действий") or {})
        счёт.update(д.get("счёт") or {})
    return дни, словарь, счёт


def модель(р: dict) -> dict | None:
    """Ряд запуска в том виде, в каком его читает `podbivka_bilet.сделка_по_состояниям`."""
    if р.get("quoteMint") != WSOL:
        return None               # котировка не SOL: курс на момент создания не собран
    if р.get("пул") in НЕ_СЧИТАЕМ:
        return None               # сосредоточенная ликвидность: формула на полных резервах неверна
    if р.get("правило") not in ПРАВИЛА_ЗАПУСКА:
        return None               # пул впервые замечен по сделке, а не по созданию
    вх = {k: v for k, v in (р.get("вход") or {}).items()}
    вых = {k: v for k, v in (р.get("выход") or {}).items()}
    if not вх or not вых:
        return None
    return {"pool": р.get("пул"),
            "модель": {"f": р.get("f"), "g": р.get("g"), "fee": р.get("тариф") or 0,
                       "состояния": {"вход": вх, "выход": вых, "масштаб": 1.0}}}


def круг(с: dict, б: float, место: str, выход: int) -> dict | None:
    return B.сделка_по_состояниям(с, б, место=место, выход=выход,
                                  издержки=ИЗДЕРЖКИ, к_g=К_G)


def позже_входа(р: dict, место: str, выход: int) -> bool:
    """Выход должен быть ПОЗЖЕ входа: иначе это не круг, а один и тот же блок."""
    вх = (р.get("вход") or {}).get(место)
    вых = (р.get("выход") or {}).get(str(выход))
    return bool(вх and вых and вых[2] > вх[2])


def круг_в_пустоту(с: dict, р: dict, б: float, место: str) -> dict | None:
    """Купили и продали в НЕ ИЗМЕНИВШИЙСЯ пул: за нами никто не пришёл.

    Зачем это нужно. Если считать только запуски, у которых есть состояние на горизонте
    выхода, в счёт попадут лишь те, за кем кто-то торговал -- а это известно ТОЛЬКО ПОСЛЕ
    входа, то есть заглядывание вперёд. Запуск, который после нас не торговался, продаётся
    по той же цене: итог -- минус наценка на вход, минус наценка на выход, минус издержки.
    """
    вх = (р.get("вход") or {}).get(место)
    if not вх:
        return None
    с2 = {"pool": с["pool"], "модель": {**с["модель"],
          "состояния": {"вход": с["модель"]["состояния"]["вход"],
                        "выход": {"0": вх}, "масштаб": 1.0}}}
    return круг(с2, б, место, 0)


def признаки(р: dict) -> dict:
    """Всё, что известно на момент входа -- включая резерв пула, в который мы покупаем."""
    бл = р.get("в_блоке_создания") or {}
    вх = (р.get("вход") or {}).get("створ_дно")
    return {"пул": р.get("пул"), "правило": р.get("правило"),
            "резерв": (вх[0] if вх else 0.0),
            "покупок": бл.get("покупок") or 0, "кошельков": бл.get("кошельков") or 0,
            "sol": бл.get("sol") or 0, "создатель_купил": bool(бл.get("создатель_купил"))}


# Переезд кривой в потоке размечен двумя событиями на один и тот же минт: настоящий пул
# (createPool или migrate с резервом около 85 SOL, сотни событий за 230 слотов) и пылевая
# засевка на 1e-5 SOL. Поэтому срез переезда -- по резерву, а не только по действию.
ПЕРЕЕЗД_ПУЛЫ = {"pump-amm", "meteora-damm-v2"}
РЕЗЕРВ_ПЕРЕЕЗДА = 10.0


