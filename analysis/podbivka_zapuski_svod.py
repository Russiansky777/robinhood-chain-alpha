def путь_цены(дни: dict, срез, горизонты) -> dict:
    """Рост цены пула от конца блока створа до каждого горизонта, в процентах.

    Это проверка механизма, а не счёт сделки: тут нет ни наценки, ни издержек. Нужна, чтобы
    видеть, откуда берётся плюс и где у режима настоящий максимум -- если медиана роста
    продолжает расти к краю собранного окна, значит окно коротко, а не режим лучший.
    """
    из_: dict = {}
    for h in горизонты:
        р = []
        for тело in дни.values():
            for x in тело.get("ряды") or []:
                if срез and not срез(признаки(x)):
                    continue
                вх = (x.get("вход") or {}).get("створ_дно")
                вых = (x.get("выход") or {}).get(str(h))
                if not вх or not вых:
                    continue
                if вых[2] <= вх[2]:
                    р.append(0.0)       # за нами никто не пришёл: цена не менялась
                    continue
                ц0, ц1 = вх[0] / вх[1], вых[0] / вых[1]
                if ц0 > 0:
                    р.append(100 * (ц1 / ц0 - 1))
        if р:
            s = sorted(р)
            из_[h] = {"n": len(р), "медиана": round(statistics.median(р), 3),
                      "p25": round(s[len(s) // 4], 3), "p75": round(s[3 * len(s) // 4], 3),
                      "доля_выше_нуля": round(100 * sum(1 for v in р if v > 0) / len(р), 1)}
    пк = [x["пик"]["рост_пп"] for тело in дни.values() for x in тело.get("ряды") or []
          if x.get("пик") and (not срез or срез(признаки(x)))]
    пс = [x["пик"]["слотов"] for тело in дни.values() for x in тело.get("ряды") or []
          if x.get("пик") and (not срез or срез(признаки(x)))]
    return {"по_горизонтам": из_, "пик_рост": V.стат(пк), "пик_слот": V.стат(пс)}


def сделки(дни: dict, место: str, выход: int, б: float, срез=None) -> list:
    """Один круг на каждый запуск, который проходит срез и у которого выход позже входа."""
    из_ = []
    for д, тело in дни.items():
        for x in тело.get("ряды") or []:
            if срез and not срез(признаки(x)):
                continue
            с = модель(x)
            if not с:
                continue
            к = (круг(с, б, место, выход) if позже_входа(с, место, выход)
                 else круг_в_пустоту(с, б, место))
            if not к:
                continue
            из_.append({"сутки": д, "минт": x["минт"], "пул": x["пул"],
                        "правило": x["правило"], "итог": к["итог_sol"],
                        "резерв": к["резерв_вход_sol"],
                        "волна60_кош": ((x.get("волна") or {}).get("60с") or {}).get("кошельков") or 0})
    return из_


def глубина_ок(ряды: list, б: float) -> tuple:
    """Билет не больше 2 % резерва пула на входе хотя бы у 80 % сделок."""
    рез = [x["резерв"] for x in ряды if x.get("резерв")]
    if not рез:
        return False, None
    доля = sum(1 for r in рез if б <= ДОЛЯ_РЕЗЕРВА * r) / len(рез)
    return доля >= ДОЛЯ_ГЛУБИНЫ, round(100 * доля, 1)


def куплено(сост, пул: str, f, fee: float, a: float) -> float | None:
    """Сколько токенов даст покупка на `a` SOL в этом состоянии пула."""
    x, y = float(сост[0]), float(сост[1])
    if x <= 0 or y <= 0 or a <= 0:
        return None
    if пул in B.XYK:
        if not f:
            return None
        т = y * f * a / (x + f * a)
    else:
        net = a / (1 + (fee or 0))
        т = y * net / (x + net)
    return т if т > 0 else None


def продано(сост, пул: str, g, fee: float, т: float) -> float | None:
    """Сколько SOL вернёт продажа `т` токенов в этом состоянии пула."""
    x, y = float(сост[0]), float(сост[1])
    if x <= 0 or y <= 0 or т <= 0:
        return None
    if пул in B.XYK:
        if not g:
            return None
        return x * g * т / (y + т)
    return x * т / (y + т) * (1 - (fee or 0)) * К_G


def ряды_пула(x: dict) -> list:
    """(блок, состояние) по возрастанию блока: вход и все выходы запуска."""
    из_ = []
    for v in (x.get("вход") or {}).values():
        из_.append((v[2], (v[0], v[1])))
    for v in (x.get("выход") or {}).values():
        из_.append((v[2], (v[0], v[1])))
    из_.sort()
    уник = []
    for б, с in из_:
        if not уник or уник[-1][0] != б:
            уник.append((б, с))
    return уник


def арбитраж(дни: dict, билеты=(0.1, 0.3, 1.0), допуск_слотов: int = 2) -> dict:
    """п.3б: минты с двумя и более пулами -- разница цен на совпадающих блоках.

    Круг арбитража считается до конца: покупка в одном пуле, продажа в другом, обе наценки,
    оба тарифа и издержки круга. Ограничение честное: наблюдения разрежены (вход и 7 выходов
    на каждый пул в первых 230 слотах его жизни), поэтому «не меньше 2 слотов» проверяется
    по двум РАЗНЫМ точкам наблюдения, а не по каждому слоту.
    """
    из_: dict = {"билеты": {}, "минтов_с_2_пулами": 0, "пар_пулов": 0, "сравнений": 0,
                 "по_суткам": {}}
    пары_типов: collections.Counter = collections.Counter()
    лучшие: list = []
    счёт: dict = {б: {"минтов_с_выгодой": collections.Counter(), "сравнений_в_плюсе": 0,
                      "итог_sol": 0.0, "пп": []} for б in билеты}
    for д, тело in sorted(дни.items()):
        по_минту: dict = collections.defaultdict(list)
        for x in тело.get("ряды") or []:
            # Слово владельца: завершившая кривая больше не торгует, значит пары
            # «кривая + пул» нет вовсе. Сосредоточенная ликвидность -- тоже мимо: на
            # полных резервах её цену не посчитать.
            вх = (x.get("вход") or {}).get("створ_дно")
            if (x.get("quoteMint") == WSOL and x.get("минт") and вх
                    and x.get("пул") not in КРИВЫЕ and x.get("пул") not in НЕ_СЧИТАЕМ
                    # пул должен быть настоящим, а не пылевой засевкой переезда
                    and вх[0] >= РЕЗЕРВ_АРБИТРАЖА and (x.get("событий") or 0) >= СОБЫТИЙ_АРБИТРАЖА):
                по_минту[x["минт"]].append(x)
        сут: dict = {б: 0.0 for б in билеты}
        for минт, пулы in по_минту.items():
            if len(пулы) < 2:
                continue
            из_["минтов_с_2_пулами"] += 1
            for i in range(len(пулы)):
                for j in range(len(пулы)):
                    if i == j:
                        continue
                    A, Б = пулы[i], пулы[j]
                    if A.get("poolId") == Б.get("poolId"):
                        continue
                    рA, рБ = ряды_пула(A), ряды_пула(Б)
                    if not рA or not рБ:
                        continue
                    if i < j:
                        из_["пар_пулов"] += 1
                        пары_типов[tuple(sorted((A["пул"] or "?", Б["пул"] or "?")))] += 1
                    в_плюсе_точек: dict = collections.Counter()
                    for бл, сA in рA:
                        близкие = [(abs(б2 - бл), с2) for б2, с2 in рБ
                                   if abs(б2 - бл) <= допуск_слотов]
                        if не_пусто := sorted(близкие):
                            сБ = не_пусто[0][1]
                        else:
                            continue
                        из_["сравнений"] += 1
                        for б in билеты:
                            т = куплено(сA, A["пул"], A.get("f"), A.get("тариф") or 0, б)
                            if not т:
                                continue
                            out = продано(сБ, Б["пул"], Б.get("g"), Б.get("тариф") or 0, т)
                            if not out:
                                continue
                            итог = out - б - ИЗДЕРЖКИ
                            счёт[б]["пп"].append(100 * итог / б)
                            if итог > 0:
                                счёт[б]["сравнений_в_плюсе"] += 1
                                в_плюсе_точек[б] += 1
                                счёт[б]["итог_sol"] += итог
                                сут[б] += итог
                                лучшие.append({"сутки": д, "минт": минт, "билет": б,
                                               "пулы": [A["пул"], Б["пул"]], "блок": бл,
                                               "итог_sol": round(итог, 6)})
                    for б, k in в_плюсе_точек.items():
                        счёт[б]["минтов_с_выгодой"][">=2 точек" if k >= 2 else "1 точка"] += 1
        из_["по_суткам"][д] = {б: round(v, 6) for б, v in сут.items()}
    сут_n = len(из_["по_суткам"]) or 1
    for б in билеты:
        c = счёт[б]
        из_["билеты"][б] = {
            "сравнений": len(c["пп"]), "в_плюсе": c["сравнений_в_плюсе"],
            "доля_в_плюсе": round(100 * c["сравнений_в_плюсе"] / max(1, len(c["пп"])), 2),
            "медиана_пп": round(statistics.median(c["пп"]), 3) if c["пп"] else None,
            "p95_пп": round(sorted(c["пп"])[int(0.95 * (len(c["пп"]) - 1))], 3) if c["пп"] else None,
            "итог_sol": round(c["итог_sol"], 6),
            "sol_в_сутки": round(c["итог_sol"] / сут_n, 6),
            "минтов_с_выгодой": dict(c["минтов_с_выгодой"])}
    лучшие.sort(key=lambda x: -x["итог_sol"])
    из_["пары_типов"] = {f"{a} + {b}": v for (a, b), v in пары_типов.most_common(12)}
    из_["верхние"] = лучшие[:15]
    return из_


def сетка(дни: dict, места=МЕСТА, выходы=ВЫХОДЫ, билеты=БИЛЕТЫ, срез=None,
          кандидаты: set | None = None) -> dict:
    """Один проход по рядам: все комбинации места, удержания и билета сразу.

    Два прохода вместо одного -- иначе память. Первый (`кандидаты=None`) считает ТОЛЬКО
    итоги подбора (сумма, пять лучших, суммы по суткам) и заодно складывает все значения
    проверки по каждой комбинации -- они нужны как нуль для перестановок. Значения проверки
    по каждому ФИЛЬТРУ при этом не хранятся: при 13 фильтрах и 84 комбинациях это гигабайты.
    Второй проход получает множество прошедших подбор ключей и держит значения только по
    ним -- их десятки, а не тысячи.
    """
    from array import array           # noqa: PLC0415
    import heapq                      # noqa: PLC0415
    ключи = [(м, h, б) for м in места for h in выходы for б in билеты]
    дни_сп = sorted(дни)
    номер_дня = {д: i for i, д in enumerate(дни_сп)}
    подб: dict = {}
    пров: dict = {}
    если_первый = кандидаты is None
    if если_первый:
        подб = {(ф_, k): {"n": 0, "сумма": 0.0, "верх": [],
                          "по_суткам": collections.Counter()}
                for ф_ in ФИЛЬТРЫ for k in ключи}
    else:
        пров = {kk: {"знач": array("f"), "дни": array("H"), "резервы": array("f"),
                     "объёмы": array("f"), "виды": bytearray()}
                for kk in кандидаты}
    все_пров: dict = collections.defaultdict(lambda: collections.defaultdict(
        lambda: array("f")))
    счёт = collections.Counter()
    for д, тело in sorted(дни.items()):
        проверка = д >= ПРОВЕРКА_С
        дн = номер_дня[д]
        for x in тело.get("ряды") or []:
            п = признаки(x)
            if срез and not срез(п):
                continue
            с = модель(x)
            if not с:
                счёт["без_модели"] += 1
                continue
            подходят = [ф_ for ф_, пр in ФИЛЬТРЫ.items() if пр(п)]
            if not подходят:
                continue
            счёт["рядов"] += 1
            # Объём покупок окна -- для пункта «наш объём»: при билете больше десятой доли
            # объёма мы сами и есть рынок, и модель круга там неверна.
            объём_окна = ((x.get("волна") or {}).get("60с") or {}).get("sol") or 0.0
            for k in ключи:
                м, h, б = k
                v, вид, резерв = круг_с_видом(с, б, м, h)
                счёт[f"вид:{вид}"] += 1
                if v is None:
                    continue
                # Глубина -- условие ВХОДА: резерв виден до покупки, в мелкий пул мы просто
                # не входим. Прежде это была проверка ПОСЛЕ, и такие круги сперва попадали
                # в среднее.
                if резерв is not None and б > ДОЛЯ_РЕЗЕРВА * резерв:
                    счёт["мелкий_пул"] += 1
                    continue
                счёт["кругов"] += 1
                if проверка and если_первый:
                    все_пров[k][д].append(v)
                for ф_ in подходят:
                    kk = (ф_, k)
                    if проверка:
                        t = пров.get(kk)
                        if t is None:
                            continue
                        t["знач"].append(v)
                        t["дни"].append(дн)
                        t["резервы"].append(резерв or 0.0)
                        t["объёмы"].append(объём_окна)
                        t["виды"].append(КОД_ВИДА.get(вид, 0))
                    elif если_первый:
                        t = подб[kk]
                        t["n"] += 1
                        t["сумма"] += v
                        t["по_суткам"][д] += v
                        if len(t["верх"]) < 5:
                            heapq.heappush(t["верх"], v)
                        elif v > t["верх"][0]:
                            heapq.heapreplace(t["верх"], v)
    return {"ключи": ключи, "дни": дни_сп, "подбор": подб, "проверка": пров,
            "все_проверки": {k: dict(v) for k, v in все_пров.items()},
            "счёт": dict(счёт)}


def подбор_прошёл(t: dict) -> bool:
    """Правило подбора: сумма в плюсе И без пяти лучших в плюсе И не меньше 100 кругов."""
    return bool(t["n"] >= 100 and t["сумма"] > 0 and (t["сумма"] - sum(t["верх"])) > 0)


def оценить(t: dict, б: float, все_пров: dict, подб: dict | None = None) -> dict:
    """Проверка одного кандидата: порог владельца плюс уровень случайности."""
    дни_сп = t.get("дни_сп") or []
    ряды = [{"итог": v, "сутки": дни_сп[i] if i < len(дни_сп) else str(i), "резерв": r,
             "объём": о, "вид": ИЗ_КОДА_ВИДА.get(вд, "годно")}
            for v, i, r, о, вд in zip(t["знач"], t["дни"], t["резервы"],
                                      t.get("объёмы") or t["знач"],
                                      t.get("виды") or bytes(len(t["знач"])))]
    if not ряды:
        return {"n": 0}
    св = свод_ряды(ряды, б)
    пол = половины(ряды)
    гл, доля_гл = глубина_ок(ряды, б)
    выбор: dict = collections.defaultdict(list)
    for x in ряды:
        выбор[x["сутки"]].append(x["итог"])
    p = перестановки_выбора(все_пров, выбор)
    p_ан = p_аналитически(все_пров, выбор)
    подб_св = {"итог_без_5_лучших_sol": (подб["сумма"] - sum(подб["верх"])) if подб else 1.0}
    да, нет = V.порог(св, пол, p, гл, подб_св)
    # Ожидание -- после порога владельца, и раньше него: строка, у которой среднее держится
    # только верхним процентом сделок, «прошедшей» считаться не может.
    if да:
        if (св.get("ожидание_sol") or 0) <= 0:
            да, нет = False, ["ожидание на сделку не выше нуля"]
        elif (св.get("ди_низ") or 0) <= 0:
            да, нет = False, ["доверительный интервал среднего накрывает ноль"]
        elif (св.get("без_верх_1") or 0) <= 0:
            да, нет = False, ["без верхнего 1 % сделок среднее уходит в минус"]
        elif (св.get("без_верх_5") or 0) <= 0:
            # Владелец просил ожидание и без верхних 5 %. Если на пяти процентах сделок
            # знак переворачивается, это лотерея, а не ремесло, и «прошло» ставить нельзя.
            да, нет = False, ["без верхних 5 % сделок среднее уходит в минус"]
        elif (св.get("нельзя_продать_доля") or 0) >= 10:
            да, нет = False, [f"продать нельзя в {св['нельзя_продать_доля']:.0f} % сделок"]
        elif (св.get("доля_объёма_выше_10") or 0) >= 10:
            да, нет = False, [f"в {св['доля_объёма_выше_10']:.0f} % пулов билет больше "
                              "десятой доли объёма окна -- модель там неверна"]
    return {**св, "p": p, "p_аналитический": p_ан, "глубина": гл, "доля_глубины": доля_гл,
            "половина_1": (пол[0] or {}).get("итог_sol"),
            "половина_2": (пол[1] or {}).get("итог_sol"),
            "проходит": да, "почему_нет": нет}


