def сутки_файла(метка: str) -> str:
    """zap_2026-10-07T06 -> 2026-10-07 (окно суток начинается в 06Z, как у den_)."""
    return метка.split("_", 1)[-1].split("T")[0]


def загрузить(папка: Path, префикс: str = "zap_") -> tuple:
    дни, словарь, счёт = {}, collections.Counter(), collections.Counter()
    for ф in sorted(папка.glob(f"{префикс}*.json.gz")):
        with gzip.open(ф, "rt", encoding="utf-8") as о:
            д = json.load(о)
        м = ф.name.replace(".json.gz", "")
        дни[сутки_файла(м)] = д
        словарь.update(д.get("словарь_действий") or {})
        счёт.update(д.get("счёт") or {})
    return дни, словарь, счёт


def наценки_годны(пул: str | None, тариф, f, g) -> tuple:
    """Привести наценку к годной или сказать, что пул в счёт не идёт.

    Возвращает (годен, тариф, f, g). Правила -- по замерам, а не по вкусу:
      * тариф больше ТАРИФ_ПРЕДЕЛ -- это не дробь (у DAMM v2 встречается 0.5 и 1.188, как
        дробь это даёт отрицательную выручку на продаже); пул в счёт не идёт;
      * f и g вне ГОДНО_НАЦЕНКЕ -- подгонка сорвалась; берётся запас 1 - тариф;
      * у pump-amm f = 1 ровно: тариф берётся с ВЫХОДА. Замерено на 3884 пулах суток 24.09:
        медиана f 1.00000 при g 0.99702 и тарифе 0.003. Подгонка по несоседним событиям
        давала там 0.77-0.81, то есть минус 20-24 п.п. на круге из ничего.
    """
    т = float(тариф or 0)
    if т > ТАРИФ_ПРЕДЕЛ:
        return False, т, f, g
    запас = 1 - т
    годно = ГОДНО_НАЦЕНКЕ
    if пул == "pump-amm":
        f = 1.0
    elif f is None or not (годно[0] <= f <= годно[1]):
        f = запас
    if g is None or not (годно[0] <= g <= годно[1]):
        g = запас
    return True, т, f, g


def модель(р: dict) -> dict | None:
    """Ряд запуска в том виде, в каком его читает `podbivka_bilet.сделка_по_состояниям`."""
    if р.get("quoteMint") != WSOL:
        return None               # котировка не SOL: курс на момент создания не собран
    if р.get("пул") in НЕ_СЧИТАЕМ:
        return None               # сосредоточенная ликвидность: формула на полных резервах неверна
    if р.get("правило") not in ПРАВИЛА_ЗАПУСКА:
        return None               # пул впервые замечен по сделке, а не по созданию
    вх = {k: v for k, v in (р.get("вход") or {}).items()}
    # Перенос вперёд. Если в слоте +1 или +2 события не было, состояния там в файле нет --
    # но МЫ-то входим всё равно, и платим по последней известной цене. Без переноса в счёт
    # по «створ+1» попадали бы только запуски, где в этом слоте КТО-ТО уже торговал, а это
    # известно только после входа: на сутках 07.10 это 3226 переездов из 27 663, то есть
    # выборка смещена к живым. С переносом места сравниваются на одной совокупности.
    посл = None
    for имя in МЕСТА:
        if имя in вх:
            посл = вх[имя]
        elif посл is not None:
            вх[имя] = посл
    вых = {k: v for k, v in (р.get("выход") or {}).items()}
    if not вх or not вых:
        return None
    годен, тариф, f, g = наценки_годны(р.get("пул"), р.get("тариф"), р.get("f"), р.get("g"))
    if not годен:
        return None
    return {"pool": р.get("пул"),
            "модель": {"f": f, "g": g, "fee": тариф,
                       "состояния": {"вход": вх, "выход": вых, "масштаб": 1.0}}}


КОД_ВИДА = {"годно": 0, "пусто": 1, "нельзя_продать": 2, "не_тот_пул": 3, "без_входа": 4}
ИЗ_КОДА_ВИДА = {v: k for k, v in КОД_ВИДА.items()}


def вид_состояния(вх, вых) -> str:
    """Можно ли вообще считать круг по этой паре состояний.

    Своп сохраняет произведение резервов (k = x*y растёт только на тариф), изменение
    ликвидности двигает оба плеча в ОДНУ сторону. Плечи в разные стороны при рухнувшем
    произведении -- не наш пул, а другое состояние: такие строки в счёт не идут. Оба плеча
    в нуле -- пул закрыт, и это НЕ повод выкинуть строку: продать в закрытом пуле нельзя,
    значит билет потерян целиком.
    """
    if not (вх and вых):
        return "пусто"
    x0, y0 = float(вх[0]), float(вх[1])
    x1, y1 = float(вых[0]), float(вых[1])
    if x0 <= 0 or y0 <= 0:
        return "не_тот_пул"
    if x1 <= 0 or y1 <= 0:
        return "закрыт"
    k = (x1 * y1) / (x0 * y0)
    одно = (x1 >= x0) == (y1 >= y0)
    return "годно" if (одно or 0.5 <= k <= 2.0) else "не_тот_пул"


def круг_с_видом(с: dict, б: float, место: str, выход: int) -> tuple:
    """(итог_sol, вид, резерв). Невозможная продажа -- это итог, а не пропуск строки.

    Прежде `круг` возвращал None и строка МОЛЧА выпадала из счёта -- то есть в счёт шли
    только запуски, чьи пулы дожили до выхода, а это известно лишь ПОСЛЕ входа. На срезе
    createPool это и давало фальшивый плюс: медиана +1.00 SOL на билете 1.00 SOL.
    """
    сост = с["модель"]["состояния"]
    вх = (сост.get("вход") or {}).get(место)
    if not вх:
        return None, "без_входа", None
    резерв = float(вх[0])
    вых = (сост.get("выход") or {}).get(str(выход))
    если_позже = позже_входа(с, место, выход)
    вид = вид_состояния(вх, вых) if (если_позже and вых) else "пусто"
    if вид == "не_тот_пул":
        return None, вид, резерв
    if вид == "закрыт":
        return -(б + ИЗДЕРЖКИ), "нельзя_продать", резерв
    if вид == "пусто":
        кр = круг_в_пустоту(с, б, место)
        if кр is None:
            return -(б + ИЗДЕРЖКИ), "нельзя_продать", резерв
        return кр["итог_sol"], "пусто", резерв
    кр = круг(с, б, место, выход)
    if кр is None:
        return -(б + ИЗДЕРЖКИ), "нельзя_продать", резерв
    return кр["итог_sol"], "годно", резерв


