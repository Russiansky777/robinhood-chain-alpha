#
# ЧЕМ ЭТОТ СЛУЧАЙ ОТЛИЧАЕТСЯ ОТ ОТКАЗА ПОЛА. Отказ пола -- это цена: котировка
# упала, и правило 4 решает, настоящее ли падение. Здесь цена В ПОРЯДКЕ: Jupiter
# отдаёт и котировку, и порог, и маршрут, и не отдаёт транзакцию. Снимать порог
# 30 % тут нечему помочь -- транзакции всё равно нет, и "продать по любой цене"
# означало бы продать НИЧЕМ. Поэтому правило 4 (б) на этот признак НЕ ходит.
#
# ЖИВОЙ СЛУЧАЙ, ПО КОТОРОМУ ЭТО НАПИСАНО. BTN (B5uMacHv, вход 0.1, пул 6EF8 --
