# остаётся порогом "спроси второго".
#
# ПОЧЕМУ ДВА ОТКАЗА, А НЕ ОДИН. Один отказ пола -- это одна котировка, а
# котировка живёт секунды: продавать по любой цене с одного числа значит
# отдавать позицию рынку на мгновенном шуме. Второй отказ подряд говорит, что
# это не шум.
ОТКАЗ_ТИП_ПУЛА_МЕТКА = "своим строителем его не котировать"
ОТКАЗОВ_ПОЛА_ДЛЯ_ЛЮБОЙ_ЦЕНЫ = 2

# ---- ТРЕТИЙ СЛУЧАЙ: КОТИРОВКА ЕСТЬ, ТРАНЗАКЦИИ НЕТ ----
# Слово владельца в ночь 01->02.10, после разбора BTN: "по любой цене по этому
