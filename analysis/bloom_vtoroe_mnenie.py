"""Второе мнение о цене: котировка пула покупки против котировки Jupiter.

ПРАВИЛО 4 В НОВОЙ РЕДАКЦИИ (слово владельца 01.10, 11:09). Пол 30 % от входа
перестаёт быть поводом НЕ продавать и становится проверкой МАРШРУТА:

  Jupiter даёт меньше 30 % от входа -> котировать тот же пул, в котором мы
  покупали, СВОИМ строителем, ОДНИМ чтением резервов:
    * пул тоже меньше 30 %  -- падение настоящее: продать немедленно по любой
      цене тем путём, который даёт больше;
    * пул не меньше 30 %    -- маршрут Jupiter плохой: продать своим путём в
      пул;
    * свой путь отказал     -- UNSOLD и тревога.

ПОЧЕМУ ЭТО НЕ "ОТМЕНА ПОЛА". Пол 70 % от котировки в ПОДПИСАННЫХ БАЙТАХ
остаётся всем и всегда: он защищает не от дешёвой котировки, а от подмены
минимума выхода на цепи. Меняется смысл только порога 30 %: раньше он означал
UNSOLD, теперь -- "спроси второго".

ЧЕГО ЗДЕСЬ НЕТ. Ни сети, ни подписи, ни отправки. решение(...) -- чистая
функция от трёх чисел; котировка_пула(...) ходит в сеть ТОЛЬКО тем читателем,
который ей передали. Неизвестное число никогда не трактуется в сторону денег:
нет котировки пула -- нет и решения "продать за бесценок", есть UNSOLD и
тревога.

КАКОЕ ЧИСЛО ПУЛА СРАВНИВАЕТСЯ -- ГАРАНТИРОВАННЫЙ ВЫХОД, А НЕ ЦЕНА. Выход по
кривой (`по_кривой`) -- это цена БЕЗ комиссии пула, а ставка комиссии Pump AMM
по цепи не вывелась (прогон 28.09: решения от 1 % до 18 %). Поэтому решение
считается по тому самому минимуму, с которым своя продажа и уйдёт в сеть
(кривая минус запас). Оба числа ложатся в запись: по_кривой -- чтобы видеть
цену, гарантированный -- чтобы видеть, за что мы подписываемся. Сравнивать
цену пула БЕЗ комиссии с чистой котировкой Jupiter было бы подтасовкой в
пользу своего пути.

КОТИРОВКА ПУЛА -- ТОЛЬКО В SOL. Котировка пула может быть не WSOL (у полосы
бывают покупки через USDC), и тогда её lamports -- это не SOL, и сравнивать их
с выходом Jupiter нельзя вовсе. Такой пул отказывает честно, а не отдаёт число
не в той единице.

ОПРОС UNSOLD -- РАЗ В МИНУТУ С НАРАСТАНИЕМ (то же слово владельца). Позиция в
UNSOLD опрашивается не кругом сторожа (3 с), а паузой, которая удваивается:
60 с, 120, 240 ... до потолка. Деньги от этого не двигаются, двигается только
число запросов к Jupiter.
"""
