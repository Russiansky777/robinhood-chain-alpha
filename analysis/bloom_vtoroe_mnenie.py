ПУТЬ_СВОЙ = "свой_в_пул"

# ---- ПРАВИЛО 4 (б) НА НОЧЬ: ОТКАЗ ПО ТИПУ ПУЛА НЕ ОСТАВЛЯЕТ ПОЗИЦИЮ ВИСЕТЬ ----
# Слово владельца в ночь 01->02.10: "зависшая позиция, по которой второе мнение
# отказывает ПО ТИПУ ПУЛА, после двух отказов пола продаётся по Jupiter по любой
# цене -- без отдельного слова на каждую".
#
# ЧТО ИМЕННО СНИМАЕТСЯ, А ЧТО НЕТ. Снимается ТОЛЬКО порог 30 % от входа (тот
# самый, что и так снимается, когда второе мнение подтвердило настоящее
# падение). Пол 70 % от котировки в ПОДПИСЫВАЕМЫХ БАЙТАХ не снимается никому и
