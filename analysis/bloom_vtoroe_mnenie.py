# количеством продался в 21:58Z с ТОЙ ЖЕ котировкой 13 742 144: параметры были
# те же, изменилось время.
ОТВЕТ_БЕЗ_TX_МЕТКА = "в ответе нет transaction/requestId"
БЕЗ_TX_ПОДРЯД_ДЛЯ_СВОЕГО = 3
# ПОЛ ПАУЗЫ, А НЕ ЕЁ ЗАМЕНА. Пауза опроса UNSOLD (60 с с удвоением) строже и
# остаётся; это нижняя граница, которая держится даже там, где той паузы нет.
ПАУЗА_БЕЗ_TX_S = 10.0


def _число(значение):
    """Число или None. Строка-число тоже число; None, "", "null" -- нет."""
    if значение is None or isinstance(значение, bool):
        return None
    try:
        ч = float(значение)
    except (TypeError, ValueError):
        return None
    if ч != ч or ч in (float("inf"), float("-inf")):
        return None
    return ч


def _env_число(имя: str, по_умолчанию: float) -> float:
    ч = _число(os.environ.get(имя))
    return по_умолчанию if ч is None else ч


def включено() -> bool:
    """Второе мнение включено. По умолчанию ДА: это слово владельца, а не опыт."""
    return str(os.environ.get("BLOOM_SELL_VTOROE_MNENIE", "1")).strip() == "1"


def порог_от_входа() -> float:
    return _env_число("BLOOM_SELL_VTOROE_PORG_PCT", ПОРОГ_ПО_УМОЛЧАНИЮ)


def вход_в_lamports(вход_sol) -> int | None:
    ч = _число(вход_sol)
    if ч is None or ч <= 0:
        return None
    return int(round(ч * 1e9))


def доля_pct(выход_lamports, вход_lamports) -> float | None:
    в = _число(выход_lamports)
    вх = _число(вход_lamports)
    if в is None or вх is None or вх <= 0 or в < 0:
        return None
    return round(100.0 * в / вх, 2)


def решение(*, jup_lamports, пул_lamports, вход_sol, порог: float | None = None) -> dict:
    """Каким путём продавать. Чистая функция: ни сети, ни состояния.

    путь: ПУТЬ_JUPITER | ПУТЬ_СВОЙ | None (None == UNSOLD и тревога).
    любая_цена: пол по доле от входа снят -- падение настоящее.
    """
    пор = порог_от_входа() if порог is None else float(порог)
    вх = вход_в_lamports(вход_sol)
    из_: dict = {"путь": None, "любая_цена": False, "тревога": True,
                  "порог_pct": пор, "вход_lamports": вх,
                  "котировка_jupiter_lamports": (None if _число(jup_lamports) is None
                                                  else int(_число(jup_lamports))),
                  "котировка_пула_lamports": (None if _число(пул_lamports) is None
                                               else int(_число(пул_lamports))),
                  "доля_jup_pct": None, "доля_пула_pct": None, "почему": None}
    if вх is None:
        из_["почему"] = ("вход позиции неизвестен -- доли от входа не посчитать, "
                          "а неизвестность в сторону денег не трактуется")
        return из_
    из_["доля_jup_pct"] = доля_pct(из_["котировка_jupiter_lamports"], вх)
    из_["доля_пула_pct"] = доля_pct(из_["котировка_пула_lamports"], вх)
    if из_["доля_jup_pct"] is None:
        из_["почему"] = "котировки Jupiter нет -- сравнивать нечего"
        return из_
    if из_["доля_jup_pct"] >= пор:
        из_.update(путь=ПУТЬ_JUPITER, тревога=False,
                    почему=(f"котировка Jupiter {из_['доля_jup_pct']:.1f} % от входа "
                             f"не ниже {пор:.0f} % -- второе мнение не нужно"))
        return из_
    if из_["доля_пула_pct"] is None:
        из_["почему"] = ("котировка Jupiter "
                          f"{из_['доля_jup_pct']:.1f} % ниже {пор:.0f} %, а котировка "
                          "пула не прочитана: продавать за бесценок на незнании "
                          "нельзя -- UNSOLD и тревога")
        return из_
    if из_["доля_пула_pct"] < пор:
        лучше = (ПУТЬ_СВОЙ if из_["котировка_пула_lamports"] > из_["котировка_jupiter_lamports"]
                  else ПУТЬ_JUPITER)
        из_.update(путь=лучше, любая_цена=True, тревога=False,
                    почему=(f"и Jupiter ({из_['доля_jup_pct']:.1f} %), и пул "
                             f"({из_['доля_пула_pct']:.1f} %) ниже {пор:.0f} % -- падение "
                             f"настоящее: продаём немедленно по любой цене путём "
                             f"{лучше}, он даёт больше"))
        return из_
    из_.update(путь=ПУТЬ_СВОЙ, любая_цена=False, тревога=False,
                почему=(f"пул даёт {из_['доля_пула_pct']:.1f} % от входа, а Jupiter "
                         f"{из_['доля_jup_pct']:.1f} % -- маршрут Jupiter плохой, "
                         "продаём своим путём в пул"))
    return из_


def котировка_пула(*, tx_покупки, наш_кошелёк: str, количество_raw: int,
                    остаток_фн, запас: float | None = None, модуль=None) -> dict:
    """Котировка пула НАШЕЙ покупки одним чтением резервов. Ничего не подписывает.

    остаток_фн(счёт) -> int | None. Зовётся РОВНО дважды: резерв базы и резерв
    котировки. Больше читать нечего: количество к продаже нам уже передали.
    Возвращает ещё и шаблон со счетами, чтобы своя продажа собралась БЕЗ
    второго чтения тех же резервов.
    """
    из_: dict = {"ok": False, "why_not": None, "lamports": None,
                  "по_кривой": None, "гарантированный": None,
                  "резерв_базы": None, "резерв_котировки": None,
                  "пул": None, "минт_котировки": None, "чтений_резервов": 0,
                  "шаблон": None, "минимум": None}
    LS = модуль
    if LS is None:
        try:
            import bloom_lane_sell as LS  # noqa: PLC0415
        except Exception as exc:  # noqa: BLE001
            из_["why_not"] = f"модуль своей продажи не загружен: {type(exc).__name__}"
            return из_
    кол = _число(количество_raw)
    if кол is None or int(кол) <= 0:
        из_["why_not"] = f"продавать нечего: количество {количество_raw}"
        return из_
    кол = int(кол)
    if not tx_покупки:
        из_["why_not"] = "нашей покупки нет -- пул брать негде"
        return из_
    шб = LS.шаблон_продажи_из_покупки(tx_покупки)
    if not шб.get("ok"):
        из_["why_not"] = шб.get("why_not") or "шаблон продажи из покупки не собрался"
        return из_
    сч = шб.get("accounts") or []
    if len(сч) < 9:
        из_["why_not"] = f"в шаблоне {len(сч)} счетов -- резервы пула брать негде"
        return из_
    из_.update(пул=сч[0], минт_котировки=сч[4], шаблон=шб)
    if сч[1] != наш_кошелёк:
        из_["why_not"] = (f"это не наша покупка: на месте кошелька {str(сч[1])[:8]}, "
                           f"а не {str(наш_кошелёк)[:8]}")
        return из_
    if сч[4] != WSOL:
        из_["why_not"] = (f"котировка пула не SOL, а {str(сч[4])[:8]} -- её lamports "
                           "с выходом Jupiter несравнимы")
        return из_
    рез_б = остаток_фн(сч[7])
    рез_к = остаток_фн(сч[8])
    из_["чтений_резервов"] = 2
    из_.update(резерв_базы=рез_б, резерв_котировки=рез_к)
    if рез_б is None or рез_к is None:
        из_["why_not"] = "резервы пула не прочитаны"
        return из_
    м = LS.минимум_по_живым_резервам(база_в=кол, резерв_базы=int(рез_б),
                                      резерв_котировки=int(рез_к), запас=запас)
    из_["минимум"] = м
    из_["по_кривой"] = м.get("po_krivoj")
    if not м.get("ok"):
        из_["why_not"] = м.get("why_not")
        return из_
    из_.update(ok=True, гарантированный=int(м["min_out"]),
                lamports=int(м["min_out"]))
    return из_


def пауза_unsold(pos: dict, *, now: float, база: float | None = None,
                  множитель: float | None = None, предел: float | None = None) -> dict:
    """Можно ли опрашивать позицию в UNSOLD прямо сейчас. Пауза нарастает.

    Считает по числу уже сделанных опросов (поле unsold_polls) и по отметке
    последнего (ts_unsold_poll). Первый опрос после попадания в UNSOLD -- сразу:
    нарастание начинается со второго.
    """
    б = _env_число("BLOOM_UNSOLD_POLL_S", ПАУЗА_UNSOLD_БАЗА) if база is None else float(база)
    м = (_env_число("BLOOM_UNSOLD_POLL_MULT", ПАУЗА_UNSOLD_МНОЖИТЕЛЬ)
         if множитель is None else float(множитель))
    п = (_env_число("BLOOM_UNSOLD_POLL_MAX_S", ПАУЗА_UNSOLD_ПОТОЛОК)
         if предел is None else float(предел))
    сделано = _число((pos or {}).get("unsold_polls")) or 0.0
    сделано = max(0, int(сделано))
    пауза = min(п, б * (м ** max(0, сделано - 1))) if сделано > 0 else 0.0
    последний = _число((pos or {}).get("ts_unsold_poll"))
    прошло = (None if последний is None else max(0.0, float(now) - последний))
    можно = (сделано == 0 or последний is None or прошло >= пауза)
    return {"можно": bool(можно), "пауза_с": round(пауза, 1),
             "прошло_с": (None if прошло is None else round(прошло, 1)),
             "опросов": сделано,
             "почему": (None if можно else
                         f"опрос UNSOLD раз в {пауза:.0f} с: прошло {прошло:.0f} с")}


def отказ_по_типу_пула(why_not) -> bool:
    """Отказ второго мнения -- ИМЕННО по типу пула, а не по чему-то другому.

    Проверяется по метке, которую пишет сам отказ ("своим строителем его не
    котировать"): это единственная причина, по которой котировка пула невозможна
    НЕ из-за сети и НЕ из-за данных, а потому что строителя для такого пула у нас
    пока нет вовсе. Отказы "резервы пула не прочитаны" или "узел не отдал" сюда
    НЕ попадают намеренно: там повтор помогает, а здесь нет.
    """
    return ОТКАЗ_ТИП_ПУЛА_МЕТКА in str(why_not or "")


def правило_4б(*, why_not, зависла, отказов_пола, порог_отказов: int | None = None) -> dict:
    """Можно ли продавать по любой цене по ночному правилу. Чистая функция.

    Ни сети, ни состояния, ни подписи: три условия и ответ. Одно написание на
    весь репозиторий -- иначе правило "по любой цене" разойдётся между службой и
    проверкой, а расходятся такие правила молча и в сторону денег.
    """
    пор = (ОТКАЗОВ_ПОЛА_ДЛЯ_ЛЮБОЙ_ЦЕНЫ if порог_отказов is None
           else int(порог_отказов))
    n = _число(отказов_пола)
    n = 0 if n is None else int(n)
    из_ = {"можно": False, "отказов_пола": n, "порог_отказов": пор,
            "по_типу_пула": отказ_по_типу_пула(why_not),
            "зависла": bool(зависла), "почему": None}
    if not из_["по_типу_пула"]:
        из_["почему"] = ("второе мнение отказало не по типу пула -- ночное "
                          "правило 4 (б) тут не при чём")
        return из_
    if not из_["зависла"]:
        из_["почему"] = ("позиция ещё не зависла -- у обычного пути время есть, "
                          "и отдавать её по любой цене рано")
        return из_
    if n < пор:
        из_["почему"] = (f"отказов пола {n} из {пор}: одна котировка живёт "
                          "секунды, по одной такую позицию не отдаём")
        return из_
    из_.update(можно=True,
                почему=(f"зависла, второе мнение отказало по типу пула, отказов "
                         f"пола {n} из {пор} -- правило 4 (б): Jupiter по любой "
                         "цене; пол 70 % от котировки в байтах остаётся"))
    return из_


def ответ_без_транзакции(why_not) -> bool:
    """Jupiter отдал котировку и НЕ отдал транзакцию. Третий случай."""
    return ОТВЕТ_БЕЗ_TX_МЕТКА in str(why_not or "")


def третий_случай(*, why_not, подряд, порог_подряд: int | None = None) -> dict:
    """Что делать с ответом без транзакции. Чистая функция.

    своим_строителем -- пора идти своим путём (если он умеет тип пула; умеет ли,
    решает НЕ эта функция: здесь нет ни сети, ни записи).
    любая_цена -- ВСЕГДА False: продавать по любой цене по этому признаку нельзя,
    транзакции всё равно нет.
    """
    пор = (БЕЗ_TX_ПОДРЯД_ДЛЯ_СВОЕГО if порог_подряд is None else int(порог_подряд))
    n = _число(подряд)
    n = 0 if n is None else int(n)
    из_ = {"без_транзакции": ответ_без_транзакции(why_not),
            "подряд": n, "порог_подряд": пор,
            "своим_строителем": False,
            # НЕ ПОЛЕ-ЗАГЛУШКА. Оно стоит здесь именно для того, чтобы
            # "по любой цене" по этому признаку нельзя было включить случайно:
            # проверка держит его False, и любая правка, которая это меняет,
            # падает самопроверкой.
            "любая_цена": False,
            "пауза_с": ПАУЗА_БЕЗ_TX_S, "почему": None}
    if not из_["без_транзакции"]:
        из_["почему"] = "ответ не про отсутствие транзакции -- третий случай не при чём"
        return из_
    if n < пор:
        из_["почему"] = (f"ответов без транзакции {n} из {пор}: ждём, повтор не "
                          f"чаще раза в {ПАУЗА_БЕЗ_TX_S:.0f} с")
        return из_
    из_.update(своим_строителем=True,
                почему=(f"{n} ответов без транзакции подряд (порог {пор}) -- идём "
                         "своим строителем; не умеет тип пула -- повтор не чаще "
                         f"раза в {ПАУЗА_БЕЗ_TX_S:.0f} с и одна тревога"))
    return из_


def пауза_без_транзакции(pos: dict, *, now: float, пауза: float | None = None) -> dict:
    """Можно ли спрашивать Jupiter снова после ответа без транзакции.

    Своя, НЕ зависящая от паузы UNSOLD: та живёт на другом счётчике и может
    вовсе не включиться. Здесь нижняя граница, и она держится всегда.
    """
    п = (_env_число("BLOOM_JUP_BEZ_TX_PAUZA_S", ПАУЗА_БЕЗ_TX_S)
         if пауза is None else float(пауза))
    подряд = _число((pos or {}).get("bez_tx_podryad")) or 0.0
    подряд = max(0, int(подряд))
    последний = _число((pos or {}).get("ts_bez_tx"))
    прошло = (None if последний is None else max(0.0, float(now) - последний))
    можно = (подряд == 0 or последний is None or прошло >= п)
    return {"можно": bool(можно), "пауза_с": round(п, 1), "подряд": подряд,
             "прошло_с": (None if прошло is None else round(прошло, 1)),
             "почему": (None if можно else
                         f"после ответа без транзакции повтор не чаще раза в "
                         f"{п:.0f} с: прошло {прошло:.0f} с")}


