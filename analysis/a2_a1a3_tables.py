def пп(sol):
    """SOL на сделку -> проценты от размера сделки."""
    return None if sol is None else sol / РАЗМЕР_SOL * 100.0


def строка_свода(rows: list, horizon: str) -> dict:
    s = свод(rows, horizon)
    if not s["n_trades"]:
        return {"n": 0, "нет_данных": True, "не_посчитано": s["n_missing"]}
    boot = бутстрэп_среднего(rows, horizon)
    b3 = свод(без_n_лучших(rows, horizon, 3), horizon)
    b5 = свод(без_n_лучших(rows, horizon, 5), horizon)
    return {
        "n": s["n_trades"], "не_посчитано": s["n_missing"],
        "среднее_sol": s["mean_sol"], "среднее_pct": round(пп(s["mean_sol"]), 3),
        "медиана_sol": s["median_sol"], "медиана_pct": round(пп(s["median_sol"]), 3),
        "доля_в_плюс": s["share_positive"], "сумма_sol": s["sum_sol"],
        "ci95_lo_sol": boot["ci95_lo_sol"], "ci95_hi_sol": boot["ci95_hi_sol"],
        "ci95_lo_pct": round(пп(boot["ci95_lo_sol"]), 3),
        "ci95_hi_pct": round(пп(boot["ci95_hi_sol"]), 3),
        "ноль_внутри_ci": boot["zero_inside_ci"], "вывод": вывод_по_интервалу(boot),
        "n_boot": boot["n_boot"], "seed": boot["seed"],
        "без3_сумма_sol": b3["sum_sol"], "без3_среднее_sol": b3["mean_sol"],
        "без3_n": b3["n_trades"],
        "без5_сумма_sol": b5["sum_sol"], "без5_среднее_sol": b5["mean_sol"],
        "без5_n": b5["n_trades"],
    }


def статистика_при_наценке(signals: list, изд: A.Издержки, скидка: float, переводов: int,
                           наценка: float, horizon: str, что: str = "среднее"
                           ) -> tuple[float | None, int]:
    входы = {"проба": {"наценка": наценка}}
    rows = a1(signals, входы, изд, скидка, переводов)["проба"]
    vals = [r[horizon]["net_sol"] for r in rows if r[horizon]["net_sol"] is not None]
    if not vals:
        return None, 0
    ф = statistics.fmean if что == "среднее" else statistics.median
    return ф(vals), len(vals)


def среднее_при_наценке(signals, изд, скидка, переводов, наценка, horizon):
    return статистика_при_наценке(signals, изд, скидка, переводов, наценка, horizon, "среднее")


def наценка_нуля(signals: list, изд: A.Издержки, скидка: float, переводов: int,
                 horizon: str, лево: float = 0.0, право: float = 5.0,
                 шагов: int = 60, что: str = "среднее") -> dict:
    """Наценка, при которой среднее (или медиана) на сделку = 0.
    Деление отрезка пополам."""
    def зн_при(m):
        return статистика_при_наценке(signals, изд, скидка, переводов, m, horizon, что)
    сл, n = зн_при(лево)
    ср, _ = зн_при(право)
    if сл is None:
        return {"известно": False, "почему": "ни одной сделки с посчитанным результатом"}
    if сл <= 0:
        return {"известно": False,
                "почему": f"среднее уже неположительно при наценке 0 ({сл:.6f} SOL) -- "
                          "порога выше нуля не существует", "среднее_при_нуле_sol": round(сл, 6)}
    if ср is not None and ср > 0:
        return {"известно": False,
                "почему": f"среднее остаётся положительным даже при наценке {право * 100:.0f}% "
                          f"({ср:.6f} SOL) -- корень вне проверенного отрезка"}
    a, b = лево, право
    for _ in range(шагов):
        m = (a + b) / 2.0
        зн, n = зн_при(m)
        if зн is None:
            break
        if зн > 0:
            a = m
        else:
            b = m
    корень = (a + b) / 2.0
    зн, n = зн_при(корень)
    rows = a1(signals, {"проба": {"наценка": корень}}, изд, скидка, переводов)["проба"]
    s = свод(rows, horizon)
    return {"известно": True, "что_обнуляем": что,
            "наценка_доля": корень, "наценка_pct": round(корень * 100, 2),
            "среднее_в_корне_sol": round(зн, 8) if зн is not None else None,
            "сделок": n, "медиана_в_корне_sol": s["median_sol"],
            "доля_в_плюс_в_корне": s["share_positive"],
            "метод": f"деление отрезка пополам, {шагов} шагов, отрезок "
                     f"[{лево * 100:.0f}%; {право * 100:.0f}%]"}


def доля_ниже(значения: list, порог: float) -> dict:
    v = [x for x in значения if x is not None]
    if not v:
        return {"n": 0, "нет_данных": True}
    ниже = [x for x in v if x < порог]
    return {"n": len(v), "ниже_порога": len(ниже),
            "доля_ниже": round(len(ниже) / len(v), 4),
            "медиана_pct": round(statistics.median(v) * 100, 2),
            "мин_pct": round(min(v) * 100, 2), "макс_pct": round(max(v) * 100, 2)}


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--a1a3", default=str(DATA / "a2_a1a3.json"))
    ap.add_argument("--a2", default=str(DATA / "a2_model_vs_chain.json"))
    ap.add_argument("--crowd", default=str(DATA / "a2_crowd_metric_2026-09-24.json"))
    ap.add_argument("--followers", default=str(DATA / "a2_followers_exec_markup.json"))
    ap.add_argument("--pilot", default=str(DATA / "solana_pilot_markup_split.json"))
    ap.add_argument("--out-json", default=str(DATA / "a2_a1a3_tables.json"))
    ap.add_argument("--out-md", default=str(DATA / "a2_a1a3_tables.md"))
    args = ap.parse_args()

    a13 = A.load_json(args.a1a3)
    a2 = A.load_json(args.a2)
    crowd = A.load_json(args.crowd)
    if not (a13 and a2 and crowd):
        raise SystemExit("нет одной из выгрузок A2/A1A3 или кэша толпы")
    aud = A.load_json(DATA / "solana_transfer_fee_audit.json") or {}
    minty = aud.get("минты") or {}
    leg = A.load_json(DATA / "c2_leg_pools_2026-09-24.json") or {}
    depth = {k: v.get("sol_depth") for k, v in (leg.get("pools") or {}).items()
             if isinstance(v, dict)}

    signals = []
    for raw in A.плоский_кэш_толпы(crowd):
        s = build_signal(raw, minty, depth)
        s["_minty"] = minty
        signals.append(s)
    mid = window_midpoint({"window_from_utc": crowd.get("window_from_utc"),
                           "window_to_utc": crowd.get("window_to_utc")})
    первая, вторая = split_half(signals, mid) if mid is not None else ([], [])
    сиг1 = {s["signature"] for s in первая}
    сиг2 = {s["signature"] for s in вторая}

    изд_наши = a2["издержки_модели_после"]["наши"]
    изд = A.Издержки(изд_наши["фикс_покупки_sol"], изд_наши["фикс_продажи_sol"],
                     изд_наши["доля_площадки"], 1.0, изд_наши["комиссия_пула_bps"],
                     изд_наши["название"])
    скидка = a2["исполнение_по_цепи"]["скидка_выхода_медиана"] or 0.0
    переводов = a13["издержки_модели"]["налоговых_переводов"]
    входы = {k: {"наценка": v["наценка"], "откуда": v["откуда"]}
             for k, v in a13["входы"].items()}

    rows_by_entry = a1(signals, входы, изд, скидка, переводов)

    # ---------------------------------------------------------- 1. по входам
    по_входам = {}
    for имя, rows in rows_by_entry.items():
        по_входам[имя] = {"наценка_pct": round(входы[имя]["наценка"] * 100, 2),
                          "откуда_наценка": входы[имя]["откуда"], "горизонты": {}}
        for h in ГОРИЗОНТЫ:
            r1 = [r for r in rows if r["signature"] in сиг1]
            r2 = [r for r in rows if r["signature"] in сиг2]
            по_входам[имя]["горизонты"][h] = {
                "всё_окно": строка_свода(rows, h),
                "первая_половина": строка_свода(r1, h) if r1 else {"n": 0, "нет_данных": True},
                "вторая_половина": строка_свода(r2, h) if r2 else {"n": 0, "нет_данных": True},
            }

    # ------------------------------------------------------ 2. по источникам
    по_источникам = {}
    for h in ("t28_8", "t60s"):
        таблица = {}
        for имя, rows in rows_by_entry.items():
            групп = collections.defaultdict(list)
            for r in rows:
                групп[r["source"] or r["source_address"]].append(r)
            лист = []
            for ист, v in групп.items():
                s = свод(v, h)
                if not s["n_trades"]:
                    лист.append({"источник": ист, "n": 0, "нет_данных": True,
                                 "не_посчитано": s["n_missing"],
                                 "почему": "ни одной сделки с посчитанным результатом -- "
                                           "нет цены или налоговый статус неизвестен"})
                    continue
                лист.append({"источник": ист, "n": s["n_trades"], "не_посчитано": s["n_missing"],
                             "среднее_sol": s["mean_sol"], "среднее_pct": round(пп(s["mean_sol"]), 3),
                             "медиана_sol": s["median_sol"], "доля_в_плюс": s["share_positive"],
                             "сумма_sol": s["sum_sol"],
                             "мало_истории": s["n_trades"] < ПОРОГ_ИСТОЧНИКА})
            лист.sort(key=lambda x: (-(x.get("среднее_sol") if x.get("среднее_sol") is not None
                                       else -1e9)))
            таблица[имя] = лист
        по_источникам[h] = таблица

    # кто в минусе на ВСЕХ трёх главных входах
    в_минусе = {}
    for h in ("t28_8", "t60s"):
        наборы = []
        for вход in ГЛАВНЫЕ_ВХОДЫ:
            наборы.append({r["источник"] for r in по_источникам[h][вход]
                           if r.get("среднее_sol") is not None and r["среднее_sol"] < 0})
        всюду = set.intersection(*наборы) if наборы else set()
        подробно = []
        for ист in sorted(всюду):
            строка = {"источник": ист}
            for вход in ГЛАВНЫЕ_ВХОДЫ:
                r = next(x for x in по_источникам[h][вход] if x["источник"] == ист)
                строка[вход] = {"n": r["n"], "среднее_sol": r["среднее_sol"],
                                "медиана_sol": r["медиана_sol"], "доля_в_плюс": r["доля_в_плюс"]}
            подробно.append(строка)
        в_минусе[h] = подробно

    # ------------------------------------------------------- 3. наценка нуля
    порог = {h: наценка_нуля(signals, изд, скидка, переводов, h) for h in ("t28_8", "t60s")}
    порог_медианы = {h: наценка_нуля(signals, изд, скидка, переводов, h, что="медиана")
                     for h in ("t28_8", "t60s")}

    изм = a2["измерения_исполнения"]
    наши_наценки = [x["наценка_входа"] for x in изм]
    pilot = A.load_json(args.pilot) or {}
    пилот_наценки = []
    for grp in ("A", "Б"):
        for r in (pilot.get(grp) or []):
            m = r.get("наценка_к_лидеру_pct")
            if m is not None:
                пилот_наценки.append(m / 100.0)
    fol = A.load_json(args.followers) or {}
    чужие = [r["наценка_к_spot_after"] for r in (fol.get("строки") or [])]

    доли = {}
    for h in ("t28_8", "t60s"):
        p = порог[h]
        if not p.get("известно"):
            доли[h] = {"известно": False, "почему": p.get("почему")}
            continue
        t = p["наценка_доля"]
        pm = порог_медианы[h]
        доли[h] = {
            "порог_pct": p["наценка_pct"],
            "наши_по_цепи_n9": доля_ниже(наши_наценки, t),
            "наши_пилот_поблочно": доля_ниже(пилот_наценки, t),
            "наши_все_известные": доля_ниже(наши_наценки + пилот_наценки, t),
            "чужие_в_блоке_источника_справочно": доля_ниже(чужие, t),
        }
        if pm.get("известно"):
            tm = pm["наценка_доля"]
            доли[h]["по_порогу_медианы"] = {
                "порог_pct": pm["наценка_pct"],
                "наши_по_цепи_n9": доля_ниже(наши_наценки, tm),
                "наши_пилот_поблочно": доля_ниже(пилот_наценки, tm),
                "наши_все_известные": доля_ниже(наши_наценки + пилот_наценки, tm),
                "чужие_в_блоке_источника_справочно": доля_ниже(чужие, tm),
            }

    out = {
        "schema_version": 1,
        "сформировано_utc": datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
        "КРЕДИТОВ_HELIUS": 0,
        "ЧЕСТНЫЕ_ОГОВОРКИ": [
            "Новых обращений в сеть нет: всё по тем же сохранённым данным, что и "
            "data/a2_a1a3.json. Кредитов Helius 0.",
            "Окно 7 суток (кэш толпы 2026-09-17T16:02:53Z -- 2026-09-24T16:02:53Z), а не 14: "
            "досканировать нечем, ключа Helius нет, публичные RPC закрыты сетевой политикой "
            "окружения.",
            "Размер сделки 0.2 SOL. Проценты в таблицах -- от этого размера.",
            f"Бутстрэп: {N_BOOT} повторов, сид {SEED} -- те же, что в предыдущих прогонах.",
            "Наценка нуля найдена делением отрезка пополам по монотонной функции среднего "
            "от наценки, а не подбором: состав сделок от наценки не зависит, корень один.",
            "Комиссия пула (swap fee AMM) не измерена и в модель не входит: настоящий порог "
            "наценки нуля НИЖЕ посчитанного на её величину.",
            "Наценка входа измерена на 9 наших сделках по цепи и на 9 сделках пилота "
            "поблочным разбором; это всё, что есть. Клетки без данных помечены явно.",
        ],
        "источники": {"A1A3": args.a1a3, "A2": args.a2, "кэш_толпы": args.crowd,
                      "наценка_чужих": args.followers, "наценка_пилота": args.pilot},
        "окно": a13["окно"], "размер_sol": РАЗМЕР_SOL,
        "бутстрэп": {"n_boot": N_BOOT, "seed": SEED},
        "издержки_модели": изд.как_словарь() | {"скидка_выхода": скидка,
                                                "налоговых_переводов": переводов},
        "по_входам": по_входам,
        "по_источникам": по_источникам,
        "в_минусе_на_всех_входах": в_минусе,
        "наценка_нуля": порог,
        "наценка_нуля_по_медиане": порог_медианы,
        "доля_наших_входов_ниже_порога": доли,
        "наши_измеренные_наценки": {
            "по_цепи": [{"минт": x["минт"], "смещение_блока": x["смещение_блока"],
                         "наценка_pct": round(x["наценка_входа"] * 100, 2)} for x in изм],
            "пилот_поблочно_pct": [round(x * 100, 2) for x in пилот_наценки],
        },
    }
    Path(args.out_json).write_text(json.dumps(out, ensure_ascii=False, indent=2), encoding="utf-8")
    Path(args.out_md).write_text(отчёт(out), encoding="utf-8")
    print(f"выгрузка: {args.out_json}")
    print(f"отчёт: {args.out_md}")
    for h in ("t28_8", "t60s"):
        print(f"--- {h}: наценка нуля {порог[h].get('наценка_pct')}%")


