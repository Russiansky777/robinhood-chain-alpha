#!/usr/bin/env python3
"""Пакет 04.10, п. Д.15: из чего складывается постоянный расход сделки и что можно срезать.

Источники (только чтение):
  * `data/podbivka/rashod_prodazhi.json` -- разбор ПО ЦЕПИ двух подписей каждой сделки
    (261 сделка, 522 запроса Helius, ошибок 0): комиссия и чаевые покупки и продажи,
    сервис чаевых. Это единственное место, где расход взят с цепи, а не из полей.
  * `data/podbivka/sdelki/vse_s_2709.json` -- выгрузка Code-1 (578 сделок): поля
    `чаевые_sol`, `комиссия_sol`, `приоритет_sol`, `тариф_sol`, `рента_sol` и итог сделки.
    Поле `расход_sol` выгрузки НЕ используется: оно отрицательное у 90 строк из 578.
  * `data/podbivka/mesto/mesto_*.json` -- место в блоке по подписи покупки, если есть.

Что считается:
  1. Разложение постоянного расхода: чаевые покупки + комиссия покупки (приоритет + тариф)
     + комиссия продажи + чаевые продажи. Медиана, среднее, доля каждой части, SOL в сутки.
  2. Корзины чаевых покупки (0, 1e-06, 1e-04, 1e-03 и выше): n, медиана и среднее итога
     сделки, доля в плюсе, место в блоке, если известно. Отсюда видно, платим ли мы за место.
  3. Сколько SOL в сутки освободится, если срезать чаевые до каждой из корзин -- и что это
     стоит по итогу сделок (без двух лучших тоже), на подборе (ранние сутки) и на проверке
     (последние сутки).

Выход: data/podbivka/paket_rashod.json и docs/podbivka_<метка>_rashod_sdelki.md.
Ничего не рекомендуется -- решает владелец.
"""
from __future__ import annotations

import argparse
import collections
import glob
import json
import statistics
import sys
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import podbivka_cand2 as C2  # noqa: E402
import podbivka_nedelya_bilet as N  # noqa: E402

КОРЕНЬ = C2.КОРЕНЬ
П = C2.П
ТАРИФ_ПОДПИСИ = 0.000005          # базовая плата Solana за подпись, 5000 лампортов
КОРЗИНЫ_ЧАЕВЫХ = ((0.0, 0.0, "0"), (1e-09, 1e-05, "1e-06"), (1e-05, 5e-04, "1e-04"),
                  (5e-04, float("inf"), "1e-03 и выше"))


def стат(v: list, знаков: int = 6) -> dict:
    v = [x for x in v if x is not None]
    if not v:
        return {"n": 0}
    з = sorted(v, reverse=True)
    return {"n": len(v), "медиана": round(statistics.median(v), знаков),
            "среднее": round(statistics.mean(v), знаков),
            "сумма": round(sum(v), знаков),
            "в_плюсе": round(100 * sum(1 for x in v if x > 0) / len(v)),
            "сумма_без_верхних_2": round(sum(з[2:]), знаков) if len(з) > 2 else None}


def корзина_чаевых(ч: float | None) -> str | None:
    if ч is None:
        return None
    for н, к, имя in КОРЗИНЫ_ЧАЕВЫХ:
        if (н == к == 0.0 and ч == 0.0) or (н < ч <= к):
            return имя
    return None


def main() -> int:
    import podbivka_run as R  # noqa: PLC0415
    р = argparse.ArgumentParser()
    р.add_argument("--metka", default=time.strftime("%Y-%m-%d", time.gmtime()))
    а = р.parse_args()

    цеп = json.loads((П / "rashod_prodazhi.json").read_text(encoding="utf-8"))
    выг = json.loads((П / "sdelki" / "vse_s_2709.json").read_text(encoding="utf-8"))["ряды"]
    по_cid = {r.get("cid"): r for r in выг if r.get("cid")}

    # место в блоке по подписи покупки -- из готовых файлов «место в блоке», если есть
    место_по_cid: dict = {}
    for f in sorted((П / "mesto").glob("mesto_*.json")):
        try:
            д = json.loads(Path(f).read_text(encoding="utf-8"))
        except ValueError:
            continue
        for r in (д.get("ряды") if isinstance(д, dict) else д) or []:
            if r.get("cid") and r.get("i_наш") is not None:
                место_по_cid[r["cid"]] = r["i_наш"]

    ряды = []
    счёт = collections.Counter()
    for с in цеп["сделки"]:
        пок, прод = с.get("покупка") or {}, с.get("продажа") or {}
        if not (пок.get("ok") and прод.get("ok")):
            счёт["подпись_не_прочитана"] += 1
            continue
        ч_п = float(пок.get("чаевые_sol") or 0)
        к_п = float(пок.get("комиссия_sol") or 0)
        ч_пр = float(прод.get("чаевые_sol") or 0)
        к_пр = float(прод.get("комиссия_sol") or 0)
        выг_р = по_cid.get(с.get("cid")) or {}
        итог, откуда = N.итог_сделки(выг_р) if выг_р else (с.get("итог_po_cepi_sol"), "цепь")
        if итог is None:
            итог, откуда = с.get("итог_po_cepi_sol"), "цепь"
        д_ = N.сутки_мадрид(выг_р) if выг_р.get("utc") else None
        ряды.append({
            "cid": с.get("cid"), "группа": с.get("группа"), "билет_sol": с.get("билет_sol"),
            "источник": с.get("источник"), "сутки": д_, "итог_sol": итог, "итог_откуда": откуда,
            "чаевые_покупки": round(ч_п, 9), "комиссия_покупки": round(к_п, 9),
            "приоритет_покупки": round(max(к_п - ТАРИФ_ПОДПИСИ, 0.0), 9),
            "чаевые_продажи": round(ч_пр, 9), "комиссия_продажи": round(к_пр, 9),
            "приоритет_продажи": round(max(к_пр - ТАРИФ_ПОДПИСИ, 0.0), 9),
            "расход_всего": round(ч_п + к_п + ч_пр + к_пр, 9),
            "сервисы_покупки": list((пок.get("по_сервисам") or {})),
            "место_в_блоке": место_по_cid.get(с.get("cid")),
            "корзина_чаевых": корзина_чаевых(ч_п),
        })
    if not ряды:
        print("нет рядов", flush=True)
        return 1

    суток = len({r["сутки"] for r in ряды if r["сутки"]}) or 1
    части = {
        "чаевые покупки": стат([r["чаевые_покупки"] for r in ряды], 9),
        "приоритет покупки": стат([r["приоритет_покупки"] for r in ряды], 9),
        "тариф покупки (база подписи)": стат([ТАРИФ_ПОДПИСИ for _ in ряды], 9),
        "чаевые продажи": стат([r["чаевые_продажи"] for r in ряды], 9),
        "приоритет продажи": стат([r["приоритет_продажи"] for r in ряды], 9),
        "тариф продажи (база подписи)": стат([min(r["комиссия_продажи"], ТАРИФ_ПОДПИСИ)
                                              for r in ряды], 9),
        "ВСЕГО постоянный расход": стат([r["расход_всего"] for r in ряды], 9),
    }
    всего_мед = части["ВСЕГО постоянный расход"]["медиана"]

    по_корзинам = {}
    for _, _, имя in КОРЗИНЫ_ЧАЕВЫХ:
        от = [r for r in ряды if r["корзина_чаевых"] == имя]
        места = [r["место_в_блоке"] for r in от if r["место_в_блоке"] is not None]
        по_корзинам[имя] = {
            "сделок": len(от),
            "итог": стат([r["итог_sol"] for r in от if r["итог_sol"] is not None]),
            "расход": стат([r["расход_всего"] for r in от], 9),
            "место_в_блоке_медиана": round(statistics.median(места)) if места else None,
            "мест_известно": len(места),
            "сервисы": dict(collections.Counter(
                s for r in от for s in (r["сервисы_покупки"] or ["без сервиса"])).most_common()),
        }

    # подбор / проверка: ранние и последние сутки
    дни = sorted({r["сутки"] for r in ряды if r["сутки"]})
    поров = дни[:max(len(дни) - 2, 1)]
    полов1, полов2 = дни[:len(дни) // 2], дни[len(дни) // 2:]
    разрезы = {
        "все сутки": ряды,
        "подбор (без последних 2 суток)": [r for r in ряды if r["сутки"] in поров],
        "проверка (последние 2 суток)": [r for r in ряды if r["сутки"] and r["сутки"] not in поров],
        "первая половина": [r for r in ряды if r["сутки"] in полов1],
        "вторая половина": [r for r in ряды if r["сутки"] in полов2],
    }
    срез = {}
    for имя, от in разрезы.items():
        д_ = len({r["сутки"] for r in от if r["сутки"]}) or 1
        чаевые = sum(r["чаевые_покупки"] + r["чаевые_продажи"] for r in от)
        расход = sum(r["расход_всего"] for r in от)
        итог = sum(r["итог_sol"] for r in от if r["итог_sol"] is not None)
        срез[имя] = {
            "сделок": len(от), "суток": д_,
            "расход_всего_sol": round(расход, 6),
            "расход_sol_в_сутки": round(расход / д_, 6),
            "чаевые_sol_в_сутки": round(чаевые / д_, 6),
            "итог_sol_в_сутки": round(итог / д_, 6),
            "доля_расхода_в_итоге": round(расход / abs(итог), 3) if итог else None,
        }

    # широкий взгляд ПО ПОЛЯМ выгрузки: 578 сделок за 7 суток (разбор по цепи -- только 2 суток)
    по_полям_ряды = []
    for r in выг:
        и, _ = N.итог_сделки(r)
        ч = r.get("чаевые_sol")
        к = r.get("комиссия_sol")
        if ч is None and к is None:
            continue
        по_полям_ряды.append({"сутки": N.сутки_мадрид(r), "группа": r.get("group"),
                              "чаевые": float(ч or 0), "комиссия": float(к or 0),
                              "приоритет": float(r.get("приоритет_sol") or 0),
                              "итог": и})
    д_полей = sorted({r["сутки"] for r in по_полям_ряды if r["сутки"]})
    по_полям = {"сделок": len(по_полям_ряды), "суток": len(д_полей),
                "сутки": [д_полей[0], д_полей[-1]] if д_полей else [],
                "чаевые": стат([r["чаевые"] for r in по_полям_ряды], 9),
                "комиссия": стат([r["комиссия"] for r in по_полям_ряды], 9),
                "приоритет": стат([r["приоритет"] for r in по_полям_ряды], 9),
                "по_суткам": {}}
    for д_ in д_полей:
        от = [r for r in по_полям_ряды if r["сутки"] == д_]
        по_полям["по_суткам"][д_] = {
            "сделок": len(от),
            "чаевые_sol": round(sum(r["чаевые"] for r in от), 6),
            "комиссия_sol": round(sum(r["комиссия"] for r in от), 6),
            "итог_sol": round(sum(r["итог"] for r in от if r["итог"] is not None), 6)}

    итог_д = {"что": "постоянный расход сделки: разложение по цепи и что можно срезать",
              "по_полям_выгрузки": по_полям,
              "источники": {"цепь": "data/podbivka/rashod_prodazhi.json (261 сделка)",
                            "выгрузка": "data/podbivka/sdelki/vse_s_2709.json (578 строк)",
                            "место_в_блоке": f"mesto_*.json, сделок с местом "
                                             f"{sum(1 for r in ряды if r['место_в_блоке'] is not None)}"},
              "сделок": len(ряды), "суток": суток, "счёт": dict(счёт),
              "части": части, "по_корзинам_чаевых": по_корзинам, "разрезы": срез, "ряды": ряды}
    out = П / "paket_rashod.json"
    out.write_text(json.dumps(итог_д, ensure_ascii=False, indent=1), encoding="utf-8")
    R.записано(out)

    def ф(v, формат="+.6f"):
        return "—" if v is None else format(v, формат)

    md = [f"# Постоянный расход сделки: из чего складывается и что можно срезать ({а.metka})", "",
          f"Разбор ПО ЦЕПИ двух подписей каждой сделки: `data/podbivka/rashod_prodazhi.json` "
          f"({цеп['счёт']['сделок']} сделок, прочитано {цеп['счёт']['прочитано']}, не отдано "
          f"{цеп['счёт']['не_отдано']}, запросов Helius "
          f"{цеп['расход_узла']['вызовов']}, ошибок {цеп['расход_узла']['ошибок']}). Итог сделки "
          f"— из выгрузки Code-1 по кириллическому полю. Поле `расход_sol` выгрузки не "
          f"используется: оно отрицательное у 90 строк из 578. Сделок в счёте {len(ряды)}, "
          f"суток {суток}.", "",
          "## Разложение", "",
          "| часть | медиана, SOL | среднее, SOL | сумма, SOL | доля от медианы расхода |",
          "|---|---|---|---|---|"]
    for имя, v in части.items():
        доля = (f"{100 * v['медиана'] / всего_мед:.0f} %"
                if всего_мед and имя != "ВСЕГО постоянный расход" else "—")
        md.append(f"| {имя} | {ф(v.get('медиана'), '.9f')} | {ф(v.get('среднее'), '.9f')} "
                  f"| {ф(v.get('сумма'), '.6f')} | {доля} |")
    md += ["", "## Корзины чаевых покупки", "",
           "| чаевые покупки | сделок | медиана итога, SOL | среднее итога | в плюсе "
           "| медиана расхода | место в блоке (медиана) | мест известно | сервисы |",
           "|---|---|---|---|---|---|---|---|---|"]
    for имя, v in по_корзинам.items():
        и = v["итог"]
        md.append(f"| {имя} | {v['сделок']} | {ф(и.get('медиана'))} | {ф(и.get('среднее'))} "
                  f"| {str(и.get('в_плюсе')) + ' %' if и.get('n') else '—'} "
                  f"| {ф(v['расход'].get('медиана'), '.9f')} "
                  f"| {v['место_в_блоке_медиана'] if v['место_в_блоке_медиана'] is not None else '—'} "
                  f"| {v['мест_известно']} | {', '.join(f'{k} {n}' for k, n in v['сервисы'].items())} |")
    md += ["", "## Широкий взгляд: расход по полям выгрузки (не по цепи)", "",
           f"Разбор по цепи накрывает только {суток} суток, поэтому проверка вне выборки на нём "
           f"слабая. Для суточных сумм берётся выгрузка Code-1: {по_полям['сделок']} сделок за "
           f"{по_полям['суток']} суток"
           + (f" ({по_полям['сутки'][0]} — {по_полям['сутки'][-1]})" if по_полям['сутки'] else "")
           + ". Это ПОЛЯ журнала, не цепь: по 23 подписям чаевые по цепи расходятся с полями "
             "(файл `data/podbivka/chaevye_rashozhdenie_2026-10-03.json`).", "",
           "| сутки (Мадрид) | сделок | чаевые, SOL | комиссия, SOL | итог, SOL |",
           "|---|---|---|---|---|"]
    for д_, v in по_полям["по_суткам"].items():
        md.append(f"| {д_} | {v['сделок']} | {ф(v['чаевые_sol'], '.6f')} "
                  f"| {ф(v['комиссия_sol'], '.6f')} | {ф(v['итог_sol'])} |")
    md += ["", "## Подбор и проверка (только сделки с разбором по цепи)", "",
           "| разрез | сделок | суток | расход SOL в сутки | из них чаевые | итог SOL в сутки "
           "| расход к модулю итога |", "|---|---|---|---|---|---|---|"]
    for имя, v in срез.items():
        md.append(f"| {имя} | {v['сделок']} | {v['суток']} | {ф(v['расход_sol_в_сутки'], '.6f')} "
                  f"| {ф(v['чаевые_sol_в_сутки'], '.6f')} | {ф(v['итог_sol_в_сутки'])} "
                  f"| {ф(v['доля_расхода_в_итоге'], '.3f')} |")
    пров = срез["проверка (последние 2 суток)"]
    # сколько освободится, если чаевые покупки срезать до уровня корзины 1e-04
    низ = по_корзинам.get("1e-04") or {}
    верх = по_корзинам.get("1e-03 и выше") or {}
    мед_низ = (низ.get("расход") or {}).get("медиана")
    экономия = None
    if мед_низ is not None and верх.get("сделок"):
        сд_в_сутки = len(ряды) / суток
        экономия = round((всего_мед - мед_низ) * сд_в_сутки, 6)
    md += ["", "## Вывод", "",
           f"Постоянный расход сделки — медиана {ф(всего_мед, '.9f')} SOL, и "
           f"{100 * части['чаевые покупки']['медиана'] / всего_мед:.0f} % из неё — чаевые "
           f"покупки, ещё {100 * части['приоритет покупки']['медиана'] / всего_мед:.0f} % — приоритет покупки; база подписи "
           f"({ТАРИФ_ПОДПИСИ:.6f} SOL × 2) несрезаема. На проверке (последние 2 суток) расход "
           f"{ф(пров['расход_sol_в_сутки'], '.6f')} SOL в сутки, из них чаевые "
           f"{ф(пров['чаевые_sol_в_сутки'], '.6f')} SOL в сутки. Если чаевые покупки срезать до "
           f"уровня корзины 1e-04 (медиана расхода {ф(мед_низ, '.9f')} SOL против "
           f"{ф(всего_мед, '.9f')}), освободится около {ф(экономия, '.6f')} SOL в сутки при "
           f"нынешнем числе сделок; плата за это видна в месте в блоке — медиана "
           f"{верх.get('место_в_блоке_медиана')} при чаевых 1e-03 против "
           f"{низ.get('место_в_блоке_медиана')} при 1e-04, а итог тех 1e-04 сделок "
           f"(n {низ.get('сделок')}) по медиане "
           f"{ф((низ.get('итог') or {}).get('медиана'))} SOL против "
           f"{ф((верх.get('итог') or {}).get('медиана'))} у 1e-03 (n {верх.get('сделок')}) — "
           f"выборки малы, вывод на них не держится.", "",
           "Ничего не меняется и не рекомендуется — решает владелец.", ""]
    стр = КОРЕНЬ / "docs" / f"podbivka_{а.metka}_rashod_sdelki.md"
    стр.write_text("\n".join(md) + "\n", encoding="utf-8")
    R.записано(стр)
    print(f"{стр.name}: сделок {len(ряды)}, медиана расхода {всего_мед}, "
          f"чаевые в сутки на проверке {пров['чаевые_sol_в_сутки']}", flush=True)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
