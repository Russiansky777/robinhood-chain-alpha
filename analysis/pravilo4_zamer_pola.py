#!/usr/bin/env python3
"""Правило 4: сколько раз Jupiter давал ниже 30 % от входа -- и сколько из них
потом продались выше 30 %.

ЗАЧЕМ (слово владельца 04.10 вечером, п.1): "Сначала read-only, числом в доклад:
с 27.09 сколько было случаев «Jupiter < 30 %» и сколько из них потом продались
>= 30 % (плохой маршрут, а не скам)".

ЧТО ЭТОТ ЗАМЕР РЕШАЕТ. Новое правило (д) велит при котировке ниже 30 % и
недоступном втором мнении продавать СРАЗУ по 90 % от текущей котировки. Цена
ошибки разная в две стороны:
  * если доля случаев, где котировка потом ВОССТАНАВЛИВАЛАСЬ выше 30 %, велика --
    значит мы часто видим плохой маршрут, а не скам, и немедленная продажа по
    любой цене будет регулярно продавать живой токен за копейки;
  * если она мала -- значит ниже 30 % это почти всегда скам, и ждать нечего.
Поэтому число считается ДО правки, а не после.

КАК СЧИТАЕТСЯ -- ПО СОБЫТИЯМ СТОРОЖА, А НЕ ПО СДЕЛКАМ. Отказ пола не оставляет
следа в выгрузке сделок: он живёт в seller.jsonl как
jupiter.floor.checks.quote_share_of_entry_pct вместе с unsold=true. Одна позиция
даёт МНОГО таких строк (сторож переспрашивает каждый круг), поэтому
случай -- это ПОЗИЦИЯ (client_order_id), а не строка журнала.

ЧТО СЧИТАЕТСЯ "ПОТОМ ПРОДАЛОСЬ >= 30 %". Строго по журналу той же позиции:
  * либо позже встречается строка с долей >= 30 % (котировка восстановилась);
  * либо позже встречается подтверждённая продажа (подпись есть).
Если ни того, ни другого -- случай "так и не поднялась". Отдельно считается
максимум доли ПОСЛЕ первого отказа: он показывает, насколько близко подходило.

ОКНО НАЗЫВАЕТСЯ ФАКТОМ, А НЕ ЗАДАНИЕМ. Если журналы не достают до 27.09 --
печатается то окно, которое реально покрыто, и оно же идёт в доклад. Сказать
"с 27.09" по журналу, который начинается 01.10, значило бы соврать числом.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

# Порог владельца: ниже этой доли от входа котировка считается раздачей.
ПОРОГ_ДОЛИ_PCT = 30.0


def _доля(ряд: dict) -> float | None:
    """Доля котировки от входа из строки сторожа. None -- в строке её нет."""
    пол = ((ряд.get("jupiter") or {}).get("floor") or {})
    проверки = пол.get("checks") or {}
    д = проверки.get("quote_share_of_entry_pct")
    try:
        return float(д)
    except (TypeError, ValueError):
        return None


def _отказ_по_входу(ряд: dict) -> bool:
    """Это именно отказ «ниже 30 % от входа», а не отказ по минимуму в байтах.

    ДВА РАЗНЫХ ОТКАЗА ПОЛА, И ПУТАТЬ ИХ НЕЛЬЗЯ. Первый -- минимум выхода в
    подписываемых байтах ниже 70 % котировки (подмена минимума на цепи, он не
    отменяется никому). Второй -- котировка ниже 30 % от входа (раздача). Нас
    просили про ВТОРОЙ: у него стоит unsold=true.
    """
    пол = ((ряд.get("jupiter") or {}).get("floor") or {})
    if not пол.get("unsold"):
        return False
    д = _доля(ряд)
    return д is not None and д < ПОРОГ_ДОЛИ_PCT


def _подпись_продажи(ряд: dict) -> str | None:
    """Подпись подтверждённой продажи из строки, если она там есть."""
    ю = ряд.get("jupiter") or {}
    if ю.get("ok") and ю.get("подпись"):
        return str(ю["подпись"])
    for имя in ("signature", "подпись"):
        з = ряд.get(имя)
        if з and ряд.get("ok"):
            return str(з)
    return None


def собрать(ряды: list) -> dict:
    """Посчитать случаи. Ряды -- строки seller.jsonl в порядке времени."""
    ряды = [р for р in ряды if isinstance(р, dict)]
    ряды.sort(key=lambda р: str(р.get("ts_utc") or ""))
    метки = [str(р.get("ts_utc")) for р in ряды if р.get("ts_utc")]
    по_cid: dict[str, list] = {}
    for р in ряды:
        cid = str(р.get("client_order_id") or "")
        if cid:
            по_cid.setdefault(cid, []).append(р)

    случаи = []
    for cid, свои in по_cid.items():
        первый = None
        for i, р in enumerate(свои):
            if _отказ_по_входу(р):
                первый = i
                break
        if первый is None:
            continue
        после = свои[первый + 1:]
        доли_после = [д for д in (_доля(р) for р in после) if д is not None]
        поднялась = next((д for д in доли_после if д >= ПОРОГ_ДОЛИ_PCT), None)
        подпись = next((s for s in (_подпись_продажи(р) for р in после) if s), None)
        случаи.append({
            "cid": cid,
            "mint": str(свои[первый].get("mint") or ""),
            "первый_отказ_utc": str(свои[первый].get("ts_utc") or ""),
            "доля_при_отказе_pct": _доля(свои[первый]),
            "отказов_всего": sum(1 for р in свои if _отказ_по_входу(р)),
            "максимум_доли_после_pct": (max(доли_после) if доли_после else None),
            "поднялась_выше_порога_pct": поднялась,
            "продана_после_подписью": подпись,
        })

    случаи.sort(key=lambda с: с["первый_отказ_utc"])
    поднялись = [с for с in случаи if с["поднялась_выше_порога_pct"] is not None]
    продались = [с for с in случаи if с["продана_после_подписью"]]
    # ОБЪЕДИНЕНИЕ, А НЕ СУММА: одна позиция может и подняться, и продаться.
    хоть_что_то = [с for с in случаи
                   if с["поднялась_выше_порога_pct"] is not None
                   or с["продана_после_подписью"]]
    return {
        "окно_факт": {"с": (min(метки) if метки else None),
                      "до": (max(метки) if метки else None),
                      "строк_журнала": len(ряды)},
        "порог_pct": ПОРОГ_ДОЛИ_PCT,
        "случаев": len(случаи),
        "отказов_строками": sum(с["отказов_всего"] for с in случаи),
        "потом_поднялась_выше_порога": len(поднялись),
        "потом_продана_подписью": len(продались),
        "потом_хоть_что_то": len(хоть_что_то),
        "так_и_не_поднялась": len(случаи) - len(хоть_что_то),
        "случаи": случаи,
    }


def строка(св: dict) -> str:
    """Одна строка для доклада."""
    о = св["окно_факт"]
    return (f"окно по факту {о['с']} -> {о['до']}: случаев «Jupiter ниже "
            f"{св['порог_pct']:.0f} % от входа» {св['случаев']} "
            f"({св['отказов_строками']} строк журнала); из них потом "
            f"поднялась выше порога {св['потом_поднялась_выше_порога']}, "
            f"продана подписью {св['потом_продана_подписью']}, "
            f"так и не поднялась {св['так_и_не_поднялась']}")


def self_test() -> int:
    всего = [0]
    плохо = [0]

    def chk(имя, ок, что=""):
        всего[0] += 1
        if ок:
            print(f"  [ok  ] {имя}")
        else:
            плохо[0] += 1
            print(f"  [ПЛОХО] {имя} -- {что}")

    def отказ(cid, ts, доля, mint="M"):
        return {"ts_utc": ts, "client_order_id": cid, "mint": mint,
                "jupiter": {"ok": False, "floor": {
                    "ok": False, "unsold": True,
                    "checks": {"quote_share_of_entry_pct": доля,
                               "floor_pct": 70.0}}}}

    def ниже_пола_байтов(cid, ts):
        # Отказ ПЕРВОГО вида: минимум в байтах ниже 70 % котировки. unsold нет.
        return {"ts_utc": ts, "client_order_id": cid, "mint": "M",
                "jupiter": {"ok": False, "floor": {
                    "ok": False, "checks": {"floor_pct": 70.0,
                                            "out_amount": 100, "threshold": 10}}}}

    def котировка(cid, ts, доля):
        return {"ts_utc": ts, "client_order_id": cid, "mint": "M",
                "jupiter": {"ok": False, "floor": {
                    "ok": True, "checks": {"quote_share_of_entry_pct": доля}}}}

    def продажа(cid, ts, подпись="SIG"):
        return {"ts_utc": ts, "client_order_id": cid, "mint": "M",
                "jupiter": {"ok": True, "подпись": подпись, "floor": {"ok": True}}}

    # 1. Пустой вход -- нули, а не исключение.
    п = собрать([])
    chk("пустой журнал: случаев 0 и окно пустое",
        п["случаев"] == 0 and п["окно_факт"]["с"] is None, п)

    # 2. Один отказ без продолжения -- случай есть, не поднялась.
    п = собрать([отказ("a", "2026-09-27T01:00:00Z", 16.9)])
    chk("один отказ: случай 1, так и не поднялась 1",
        п["случаев"] == 1 and п["так_и_не_поднялась"] == 1
        and п["потом_хоть_что_то"] == 0, п)

    # 3. Отказ, потом котировка выше порога -- считается поднявшейся.
    п = собрать([отказ("b", "2026-09-27T01:00:00Z", 19.8),
                 котировка("b", "2026-09-27T01:30:00Z", 41.0)])
    chk("отказ, потом 41 % -- поднялась 1, не поднялась 0",
        п["потом_поднялась_выше_порога"] == 1 and п["так_и_не_поднялась"] == 0
        and п["случаи"][0]["максимум_доли_после_pct"] == 41.0, п)

    # 4. Отказ, потом котировка НИЖЕ порога -- не поднялась, но максимум виден.
    п = собрать([отказ("c", "2026-09-27T01:00:00Z", 10.0),
                 котировка("c", "2026-09-27T01:30:00Z", 29.9)])
    chk("отказ, потом 29.9 % -- НЕ поднялась, но максимум записан",
        п["потом_поднялась_выше_порога"] == 0 and п["так_и_не_поднялась"] == 1
        and п["случаи"][0]["максимум_доли_после_pct"] == 29.9, п)

    # 5. Отказ, потом подтверждённая продажа -- считается.
    п = собрать([отказ("d", "2026-09-27T01:00:00Z", 12.0),
                 продажа("d", "2026-09-27T01:40:00Z", "ПОДПИСЬ1")])
    chk("отказ, потом продажа подписью -- продана 1",
        п["потом_продана_подписью"] == 1
        and п["случаи"][0]["продана_после_подписью"] == "ПОДПИСЬ1", п)

    # 6. И поднялась, И продалась -- в объединении ОДИН случай, а не два.
    п = собрать([отказ("e", "2026-09-27T01:00:00Z", 12.0),
                 котировка("e", "2026-09-27T01:10:00Z", 55.0),
                 продажа("e", "2026-09-27T01:20:00Z")])
    chk("и поднялась, и продалась -- хоть_что_то 1, а не 2",
        п["потом_хоть_что_то"] == 1 and п["случаев"] == 1, п)

    # 7. Отказ ПО МИНИМУМУ В БАЙТАХ случаем НЕ считается: это другое правило.
    п = собрать([ниже_пола_байтов("f", "2026-09-27T01:00:00Z")])
    chk("отказ по минимуму в байтах -- НЕ наш случай",
        п["случаев"] == 0, п)

    # 8. Доля РОВНО на пороге -- не отказ (условие строгое: доля < порога).
    п = собрать([отказ("g", "2026-09-27T01:00:00Z", 30.0)])
    chk("ровно 30 % -- не случай, условие строгое",
        п["случаев"] == 0, п)

    # 9. Много отказов по одной позиции -- случай ОДИН, строк много.
    п = собрать([отказ("h", "2026-09-27T01:00:00Z", 19.0),
                 отказ("h", "2026-09-27T01:15:00Z", 19.1),
                 отказ("h", "2026-09-27T01:30:00Z", 18.8)])
    chk("три отказа по одной позиции -- случай 1, строк 3",
        п["случаев"] == 1 and п["отказов_строками"] == 3, п)

    # 10. Две позиции независимы.
    п = собрать([отказ("i", "2026-09-27T01:00:00Z", 11.0),
                 отказ("j", "2026-09-27T02:00:00Z", 12.0),
                 котировка("i", "2026-09-27T03:00:00Z", 44.0)])
    chk("две позиции: случаев 2, поднялась одна",
        п["случаев"] == 2 and п["потом_поднялась_выше_порога"] == 1, п)

    # 11. Порядок не зависит от порядка во входе: ряды сортируются сами.
    п = собрать([котировка("k", "2026-09-27T05:00:00Z", 60.0),
                 отказ("k", "2026-09-27T01:00:00Z", 9.0)])
    chk("неупорядоченный вход: продолжение найдено по времени",
        п["потом_поднялась_выше_порога"] == 1, п)

    # 12. Котировка ДО отказа продолжением не считается.
    п = собрать([котировка("l", "2026-09-27T01:00:00Z", 80.0),
                 отказ("l", "2026-09-27T02:00:00Z", 9.0)])
    chk("котировка ДО отказа -- не продолжение",
        п["потом_поднялась_выше_порога"] == 0
        and п["так_и_не_поднялась"] == 1, п)

    # 13. Строка без cid не роняет разбор и в счёт не идёт.
    п = собрать([{"ts_utc": "2026-09-27T01:00:00Z", "jupiter": {}},
                 отказ("m", "2026-09-27T02:00:00Z", 9.0)])
    chk("строка без cid пропускается, а не ломает",
        п["случаев"] == 1, п)

    # 14. Окно по факту -- из самих строк.
    п = собрать([отказ("n", "2026-10-01T22:00:00Z", 9.0),
                 котировка("n", "2026-10-02T19:00:00Z", 10.0)])
    chk("окно по факту взято из строк, а не из задания",
        п["окно_факт"]["с"] == "2026-10-01T22:00:00Z"
        and п["окно_факт"]["до"] == "2026-10-02T19:00:00Z", п["окно_факт"])

    # 15. Строка доклада называет окно и все четыре числа.
    с = строка(п)
    chk("строка доклада называет окно и числа",
        "окно по факту" in с and "случаев" in с and "поднялась" in с, с)

    print(f"самопроверка замера пола: {всего[0] - плохо[0]}/{всего[0]} пройдено")
    return 1 if плохо[0] else 0


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--diag", default="data/bloom_seller_diag.json",
                    help="файл диагностики сторожа (в нём seller_rows)")
    ap.add_argument("--jsonl", default="",
                    help="вместо диагностики -- прямо seller.jsonl")
    ap.add_argument("--out", default="data/pravilo4_zamer_pola.json")
    ap.add_argument("--self-test", action="store_true")
    а = ap.parse_args()
    if а.self_test:
        return self_test()

    ряды: list = []
    if а.jsonl:
        for строка_ in Path(а.jsonl).read_text(encoding="utf-8").splitlines():
            строка_ = строка_.strip()
            if not строка_:
                continue
            try:
                ряды.append(json.loads(строка_))
            except ValueError:
                continue
    else:
        д = json.loads(Path(а.diag).read_text(encoding="utf-8"))
        ряды = д.get("seller_rows") or []

    св = собрать(ряды)
    Path(а.out).parent.mkdir(parents=True, exist_ok=True)
    Path(а.out).write_text(json.dumps(св, ensure_ascii=False, indent=1),
                           encoding="utf-8")
    print(строка(св))
    for с in св["случаи"]:
        print(f"  {с['первый_отказ_utc']} {с['cid'][:34]} {с['mint'][:12]} "
              f"доля {с['доля_при_отказе_pct']} %, отказов {с['отказов_всего']}, "
              f"максимум после {с['максимум_доли_после_pct']}, "
              f"продана {'да' if с['продана_после_подписью'] else 'нет'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
