def progon(kat: str | Path | None = None, *, rpc_call=None,
           koshelek: str = КОШЕЛЕК, sutok: float = 3.0,
           sejchas: float | None = None, pisat_stranicu: bool = True,
           derzhim_sutok: int = ДЕРЖИМ_СУТОК,
           rjady_kesh: list | None = None, kotirovka_call=None,
           drugie_koshelki: tuple | None = None) -> dict:
    """ОДИН ТИК СБОРЩИКА: догнать цепь, посчитать ряд, записать всё.

    Вызывается раз в 15--30 с бегунком или циклом; состояние и ряд лежат на
    диске, поэтому перезапуск ничего не теряет, кроме времени простоя (и простой
    виден числом пропусков в выгрузке).
    """
    к = Path(kat) if kat else КАТАЛОГ
    к.mkdir(parents=True, exist_ok=True)
    сейчас = float(sejchas if sejchas else time.time())
    п_сост = к / ФАЙЛ_СОСТОЯНИЯ
    из_ = {"ok": False, "why_not": None, "kat": str(к)}
    сост = pustoe_sostojanie(koshelek)
    прочлось = False
    if п_сост.exists():
        try:
            прежнее = json.loads(п_сост.read_text(encoding="utf-8"))
            if isinstance(прежнее, dict) and прежнее.get("koshelek") == koshelek:
                сост = прежнее
                прочлось = True
            else:
                из_["why_not_sostojanie"] = ("состояние не того кошелька -- "
                                             "начато заново")
        except (ValueError, OSError) as сбой:
            из_["why_not_sostojanie"] = (f"состояние не прочиталось: "
                                          f"{type(сбой).__name__} -- начато заново")
    # РЯД ЖИВЁТ ДОЛЬШЕ СОСТОЯНИЯ, И ЭТО НЕ РЕДКОСТЬ: состояние можно потерять
    # диском, кривой записью или чужим кошельком в файле. Накопительные числа
    # (ввод-вывод, выручка без входа, расходы) при этом начались бы С НУЛЯ, а
    # окно считает их РАЗНОСТЬЮ по ряду -- и первая же разность дала бы
    # призрачные плюс-минус несколько SOL в изменении за период. Поэтому после
    # потери состояния счётчики СШИВАЮТСЯ с последней строкой ряда: сдвиг
    # считается ПОСЛЕ восстановления истории (оно само накопит часть заново).
    сшить = (not прочлось) and (к / ФАЙЛ_РЯДОВ).exists()
    хвост_ряда = poslednij_rjad(к / ФАЙЛ_РЯДОВ) if сшить else {}
    # КЭШ КОТИРОВОК -- ОТДЕЛЬНЫМ МАЛЕНЬКИМ ФАЙЛОМ, А НЕ В СОСТОЯНИИ. Состояние
    # на полосе весит сотни килобайт и пишется по делу (раз в пять минут), а
    # котировка живёт минуту: держать её там значило бы либо писать состояние
    # каждую минуту, либо каждый тик спрашивать Jupiter заново.
    п_кот = к / ФАЙЛ_КОТИРОВОК
    кэш_кот: dict = {}
    if п_кот.exists():
        try:
            прежние = json.loads(п_кот.read_text(encoding="utf-8"))
            if isinstance(прежние, dict):
                кэш_кот = прежние
        except (ValueError, OSError):
            кэш_кот = {}
    кот_было = json.dumps(кэш_кот, sort_keys=True)
    счётчик = Schjotchik(сост.get("kredity"))
    if rpc_call is None:
        url = uzel_iz_okruzheniya()
        if not url:
            из_["why_not"] = WHY_NET_UZLA
            return из_
        rpc_call = rpc_iz_url(url)
        из_["uzel"] = zateret(url)
    try:
        из_["dognali"] = dognat_cep(rpc_call, koshelek=koshelek, sostojanie=сост,
                                     sutok=sutok, schjotchik=счётчик,
                                     sejchas=сейчас)
        if сшить and хвост_ряда:
            сдвиги = {}
            for поле, накопитель in (
                    ("vvod_vyvod", "vvod_vyvod_lamports"),
                    ("vyruchka_bez_vhoda", "vyruchka_bez_vhoda_lamports"),
                    ("rashodov_lamports", "rashodov_lamports")):
                сдвиги[поле] = (int(хвост_ряда.get(поле) or 0)
                                - int(сост.get(накопитель) or 0))
            сост["sdvigi"] = сдвиги
            сост["sbros_sostojanija_utc"] = int(сейчас)
            из_["sshito"] = сдвиги
        кэш = сост.get("scheta_snimok") or {}
        возраст = сейчас - float(кэш.get("utc") or 0)
        читать_счета = bool(
            int(из_["dognali"].get("razobrano") or 0)       # прошла транзакция
            or not кэш.get("scheta")                        # первый тик
            or возраст >= СЧЕТА_НЕ_СТАРШЕ_СЕК)              # страховка
        из_["scheta_chitali"] = читать_счета
        р = rjad(rpc_call, koshelek=koshelek, sostojanie=сост,
                 schjotchik=счётчик, sejchas=сейчас,
                 schitat_scheta=читать_счета, kotirovka_call=kotirovka_call,
                 kesh_kotirovok=кэш_кот, drugie_koshelki=drugie_koshelki)
    except (ОшибкаТрекера, OSError, ValueError) as сбой:
        # УЗЕЛ МОЛЧИТ -- ЭТО НЕ ПОТЕРЯ РЯДА, А ПРОПУСК, И ОН НАЗЫВАЕТСЯ.
        из_["why_not"] = f"{type(сбой).__name__}: {zateret(str(сбой))[:160]}"
        сост["kredity"] = счётчик.po_sutkam
        п_сост.write_text(json.dumps(сост, ensure_ascii=False, indent=1),
                          encoding="utf-8")
        return из_
    # КЭШ КОТИРОВОК ПИШЕТСЯ, ТОЛЬКО ЕСЛИ ИЗМЕНИЛСЯ.
    if json.dumps(кэш_кот, sort_keys=True) != кот_было:
        п_кот.write_text(json.dumps(кэш_кот, ensure_ascii=False, indent=1),
                         encoding="utf-8")
        из_["kotirovki_pisali"] = True
    счётчик.obrezat()
    сост["kredity"] = счётчик.po_sutkam
    # СПИСКИ СОСТОЯНИЯ РЕЖУТСЯ ПО ТОМУ ЖЕ ОКНУ, ЧТО И РЯД. Сделки и отметки
    # копились НАВСЕГДА, а состояние пишется каждый тик: 350 сделок в сутки
    # за неделю дали бы файл в полмегабайта, который переписывается раз в 20
    # секунд. Окна страницы дальше трёх суток не смотрят, а «сделок всего»
    # живёт отдельным счётчиком и от обрезки не врёт.
    порог_сост = сейчас - derzhim_sutok * 86400.0
    сост["sdelki"] = [с for с in (сост.get("sdelki") or [])
                      if not isinstance(с.get("zakryta_utc"), int)
                      or float(с["zakryta_utc"]) >= порог_сост][-5000:]
    сост["metki"] = [м for м in (сост.get("metki") or [])
                     if not isinstance(м.get("utc"), int)
                     or float(м["utc"]) >= порог_сост][-500:]
    было_тронуто = bool(int(из_["dognali"].get("razobrano") or 0)
                        or int(из_["dognali"].get("net_tranzakcii") or 0)
                        or из_.get("sshito"))
    давно = (сейчас - float(сост.get("zapisano_utc") or 0)
             >= СОСТОЯНИЕ_НЕ_РЕЖЕ_СЕК)
    if было_тронуто or давно or not п_сост.exists():
        сост["zapisano_utc"] = int(сейчас)
        п_сост.write_text(json.dumps(сост, ensure_ascii=False, indent=1) + "\n",
                          encoding="utf-8")
        из_["sostojanie_pisali"] = True
    из_["zapis"] = dopisat_rjad(к / ФАЙЛ_РЯДОВ, р, derzhim_sutok=derzhim_sutok,
                                 sejchas=сейчас)
    # РЯД ДЛЯ ВЫГРУЗКИ -- ИЗ ПАМЯТИ, ЕСЛИ ЕСТЬ КТО ЕГО ДЕРЖИТ. Служба держит
    # (см. sluzhba), и тогда трое суток ряда не перечитываются с диска каждые
    # 20 секунд: это было второе место, где трекер молотил диск впустую.
    if rjady_kesh is None:
        ряды = prochitat_rjady(к / ФАЙЛ_РЯДОВ)
    else:
        if not rjady_kesh or из_["zapis"].get("perepisali"):
            rjady_kesh[:] = prochitat_rjady(к / ФАЙЛ_РЯДОВ)
        else:
            rjady_kesh.append(р)
        порог_кэша = сейчас - derzhim_sutok * 86400.0
        пока = 0
        while пока < len(rjady_kesh) and float(
                rjady_kesh[пока].get("utc") or 0) < порог_кэша:
            пока += 1
        if пока:
            del rjady_kesh[:пока]
        ряды = rjady_kesh
    в = vygruzka(ряды, сост, sejchas=сейчас)
    (к / ФАЙЛ_ВЫГРУЗКИ).write_text(json.dumps(в, ensure_ascii=False, indent=1)
                                   + "\n", encoding="utf-8")
    if pisat_stranicu:
        # СТРАНИЦА НЕ МЕНЯЕТСЯ МЕЖДУ ТИКАМИ, и перезаписывать её 4320 раз в
        # сутки незачем: пишем только когда её нет или она другая.
        п_стр = к / ФАЙЛ_СТРАНИЦЫ
        страница_ = stranica()
        if (not п_стр.exists()
                or п_стр.read_text(encoding="utf-8") != страница_):
            п_стр.write_text(страница_, encoding="utf-8")
            из_["stranicu_pisali"] = True
    из_.update(ok=True, rjad=р, vygruzka_bajt=len(json.dumps(в)),
               kapital_sol=round(int(р["kapital"]) / ЛАМПОРТОВ_В_SOL, 6),
               vyzovov_za_sutki=(счётчик.po_sutkam.get(
                   time.strftime("%Y-%m-%d", time.gmtime(сейчас))) or {}))
    return из_


def razbor(rpc_call=None, *, koshelek: str = КОШЕЛЕК, oprosov: int = 3,
           pauza: float = 5.0, kat: str | Path | None = None,
           spat=None) -> dict:
    """НЕСКОЛЬКО ОПРОСОВ ПОДРЯД, КАПИТАЛ ПО ЧАСТЯМ. ТОЛЬКО ЧТЕНИЕ.

    Зачем отдельный ход, а не «посмотреть в журнал». 04.10 капитал трекера
    разошёлся с кошельком и расхождение РОСЛО, а назвать растущую часть было
    нечем. Этот ход спрашивает цепь столько раз, сколько сказано, и печатает
    КАЖДУЮ часть и её изменение между опросами:

        SOL (getBalance) + WSOL + позиции по входу + рента токен-счетов

    Ничего не пишет на диск -- ни ряда, ни состояния, ни страницы: состояние
    берётся готовым (если каталог дан), иначе пустое, и в нём только читают.
    Секрета здесь нет вовсе: он к отдаче, а не к чтению цепи.
    """
    сост = pustoe_sostojanie(koshelek)
    к = Path(kat) if kat else None
    if к and (к / ФАЙЛ_СОСТОЯНИЯ).exists():
        try:
            прежнее = json.loads((к / ФАЙЛ_СОСТОЯНИЯ).read_text(encoding="utf-8"))
            if isinstance(прежнее, dict):
                сост = прежнее
        except (ValueError, OSError):
            pass
    if rpc_call is None:
        url = uzel_iz_okruzheniya()
        if not url:
            return {"ok": False, "why_not": WHY_NET_UZLA}
        rpc_call = rpc_iz_url(url)
    из_ = {"ok": True, "koshelek": koshelek, "uzel": zateret(uzel_iz_okruzheniya()),
            "oprosy": [], "rastjot": None}
    спать = spat if spat else time.sleep
    for и in range(max(1, int(oprosov))):
        if и:
            спать(max(0.0, float(pauza)))
        try:
            р = rjad(rpc_call, koshelek=koshelek, sostojanie=сост,
                     schitat_scheta=True)
        except (ОшибкаТрекера, OSError, ValueError) as сбой:
            из_["oprosy"].append({"why_not": f"{type(сбой).__name__}: "
                                              f"{zateret(str(сбой))[:160]}"})
            continue
        из_["oprosy"].append({k: р.get(k) for k in (
            "utc", "slot", "kapital", "sol", "wsol", "pozicii", "renta",
            "schetov", "schetov_pustyh", "pozicij", "bez_vhoda",
            "kotirovok_s_ostatkom")})
    годные = [о for о in из_["oprosy"] if о.get("kapital") is not None]
    if len(годные) >= 2:
        # РАСТЁТ ИЛИ НЕТ -- НАЗЫВАЕТСЯ ЧАСТЬЮ, А НЕ ВПЕЧАТЛЕНИЕМ.
        из_["rastjot"] = {ч: int(годные[-1].get(ч) or 0) - int(годные[0].get(ч) or 0)
                          for ч in ("kapital", "sol", "wsol", "pozicii",
                                     "renta", "schetov")}
        из_["sekund_mezhdu"] = int((годные[-1].get("utc") or 0)
                                   - (годные[0].get("utc") or 0))
        # ТОЖДЕСТВО ЧАСТЕЙ ПРОВЕРЯЕТСЯ ТУТ ЖЕ: капитал обязан быть ровно
        # суммой своих частей, иначе растёт что-то пятое.
        из_["chasti_sxodjatsja"] = all(
            int(о["kapital"]) == int(о["sol"]) + int(о["wsol"])
            + int(о["pozicii"]) + int(о["renta"]) for о in годные)
    return из_


