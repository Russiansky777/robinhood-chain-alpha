def prinjat_tranzakciju(sostojanie: dict, tx: dict,
                        koshelek: str | None = None) -> dict:
    """Применить ОДНУ транзакцию к состоянию. Порядок -- от старых к новым.

    ЧТО СЧИТАЕТСЯ ПОЗИЦИЕЙ. Один своп в полосе покупает ОДИН минт. Если в
    транзакции выросли остатки ДВУХ минтов и больше, делить потраченное между
    ними нечем -- и делить наугад на деньгах нельзя. Такая транзакция
    называется непонятной (`neopoznannyh`), позиции не трогает, и тогда капитал
    честно показывает убыль SOL: это видно, а не спрятано.
    """
    кош = koshelek or sostojanie.get("koshelek") or КОШЕЛЕК
    р = razbor_tranzakcii(tx, кош)
    из_ = {"vid": р.get("vid"), "pochemu": р.get("pochemu"),
            "sig": р.get("sig"), "ok": bool(р.get("ok")),
            "otkryto": [], "zakryto": [], "metka": None, "povtor": False}
    if not р["ok"]:
        return из_
    # --- ОДНА ПОДПИСЬ -- ОДИН РАЗ. Узел при протухшей `poslednjaja_sig`
    # отдаёт то же окно снова, и без этой памяти покупка легла бы в позицию
    # дважды: вход вдвое, капитал врёт ВВЕРХ на целый билет.
    сиг = р.get("sig")
    виденные = sostojanie.setdefault("razobrannye_sig", [])
    if сиг and сиг in виденные:
        sostojanie["povtorov_podpisi"] = int(
            sostojanie.get("povtorov_podpisi") or 0) + 1
        из_["povtor"] = True
        из_["pochemu"] = "эта подпись уже разобрана -- второй раз не считается"
        return из_
    if сиг:
        виденные.append(сиг)
        if len(виденные) > ПОМНИМ_ПОДПИСЕЙ:
            del виденные[:len(виденные) - ПОМНИМ_ПОДПИСЕЙ]
    sostojanie["podpisej_razobrano"] = int(
        sostojanie.get("podpisej_razobrano") or 0) + 1
    if р["vid"] == ВИД_ПЕРЕВОД:
        дельта = perevod_sol(р)
        if дельта:
            метка = {"utc": р.get("utc"), "sig": р.get("sig"),
                      "vid": ("ввод" if дельта > 0 else "вывод"),
                      "lamports": abs(дельта)}
            sostojanie["metki"] = (sostojanie.get("metki") or []) + [метка]
            sostojanie["vvod_vyvod_lamports"] = int(
                sostojanie.get("vvod_vyvod_lamports") or 0) + дельта
            из_["metka"] = метка
        return из_
    if р["vid"] == ВИД_РАСХОД:
        # РАСХОД НИЧЕГО НЕ ИСКЛЮЧАЕТ ИЗ ИЗМЕНЕНИЯ, его дело -- быть названным
        # числом: «за период ушло столько-то на чаевые и ренту чужих счетов».
        sostojanie["rashodov"] = int(sostojanie.get("rashodov") or 0) + 1
        sostojanie["rashodov_lamports"] = int(
            sostojanie.get("rashodov_lamports") or 0) - int(р.get("sol_delta") or 0)
        return из_
    if р["vid"] == ВИД_ЗАКРЫТИЕ:
        sostojanie["zakryto_schetov"] = int(
            sostojanie.get("zakryto_schetov") or 0) + int(
                р.get("zakryto_schetov") or 1)
        return из_
    if р["vid"] != ВИД_СВОП:
        sostojanie["neopoznannyh"] = int(
            sostojanie.get("neopoznannyh") or 0) + 1
        return из_
    # СВОП ПРИ УБОРКЕ ТОЖЕ ЗАКРЫВАЕТ СЧЕТА -- и они считаются счетами.
    if int(р.get("zakryto_schetov") or 0):
        sostojanie["zakryto_schetov"] = int(
            sostojanie.get("zakryto_schetov") or 0) + int(р["zakryto_schetov"])
    # КОТИРОВКИ ВЫБРАСЫВАЮТСЯ ДО ВСЯКОГО СЧЁТА. Рост USDC в транзакции
    # покупки -- это сдача ноги, а не вторая покупка; убыль USDC в транзакции
    # продажи -- это оплата, а не продажа позиции. Пока они считались
    # минтами, покупка через ногу выглядела как «два минта выросли», то есть
    # транзакция становилась непонятной и позиция не открывалась ВОВСЕ, а
    # пыль котировки навсегда оставалась «позицией» в состоянии.
    куплено = [(м, д) for м, д in (р["tokeny"] or {}).items()
               if д > 0 and м not in КОТИРОВОЧНЫЕ_МИНТЫ]
    продано = [(м, д) for м, д in (р["tokeny"] or {}).items()
               if д < 0 and м not in КОТИРОВОЧНЫЕ_МИНТЫ]
    котировки = sorted(ИМЕНА_КОТИРОВОК.get(м, м[:6])
                       for м in (р["tokeny"] or {})
                       if м in КОТИРОВОЧНЫЕ_МИНТЫ)
    котировка_выросла = sorted(ИМЕНА_КОТИРОВОК.get(м, м[:6])
                               for м, д in (р["tokeny"] or {}).items()
                               if м in КОТИРОВОЧНЫЕ_МИНТЫ and д > 0)
    котировка_убыла = sorted(ИМЕНА_КОТИРОВОК.get(м, м[:6])
                             for м, д in (р["tokeny"] or {}).items()
                             if м in КОТИРОВОЧНЫЕ_МИНТЫ and д < 0)
    # ВЫРУЧКА, УШЕДШАЯ В КОТИРОВКУ, -- НЕ НОЛЬ, И ВЫДАВАТЬ ЕЁ ЗА НОЛЬ НЕЛЬЗЯ.
    # Если токен продан, а в той же транзакции ВЫРОСЛА котировка, то чистый
    # поток SOL близок к нулю (ушла одна комиссия), и запись сделки дала бы
    # итог «минус весь вход» -- выдуманный убыток на целый билет. То же в
    # другую сторону: если при покупке котировка УБЫЛА, платили ею, а не SOL,
    # и вход в SOL придумывать нечем. Обе транзакции называются непонятными и
    # позиций не трогают.
    if продано and котировка_выросла:
        sostojanie["neopoznannyh"] = int(
            sostojanie.get("neopoznannyh") or 0) + 1
        sostojanie["prodazh_v_kotirovku"] = int(
            sostojanie.get("prodazh_v_kotirovku") or 0) + 1
        из_["pochemu"] = (f"продажа {len(продано)} минтов, а выручка ушла в "
                          f"{', '.join(котировка_выросла)} -- в SOL пришла "
                          f"только комиссия, итог считать нечем")
        return из_
    if куплено and котировка_убыла:
        sostojanie["neopoznannyh"] = int(
            sostojanie.get("neopoznannyh") or 0) + 1
        из_["pochemu"] = (f"покупка {len(куплено)} минтов оплачена "
                          f"{', '.join(котировка_убыла)}, а не SOL -- входа в "
                          f"SOL у неё нет")
        return из_
    # --- ТОКЕН В ТОКЕН ОДНОЙ ТРАНЗАКЦИЕЙ НЕ РАСКЛАДЫВАЕТСЯ, И ДЕЛИТЬ НАУГАД
    # НА ДЕНЬГАХ НЕЛЬЗЯ. У транзакции ОДНО число `polucheno` (чистый поток
    # SOL), а здесь две стороны сразу: продажа A и покупка B. Посчитать итог
    # продажи как `polucheno - вход_A` -- значит записать выдуманный убыток на
    # всю цену входа A (SOL с кошелька не уходил: он ушёл в покупку B).
    # Поэтому такая транзакция называется непонятной и позиций НЕ ТРОГАЕТ --
    # ровно как уже сделано для двух РОСТОВ сразу. На живых данных этого
    # кошелька случай не встречался ни раз (полоса покупает и продаёт разными
    # транзакциями), но «не встречалось» -- не защита.
    if куплено and продано:
        sostojanie["neopoznannyh"] = int(
            sostojanie.get("neopoznannyh") or 0) + 1
        из_["pochemu"] = (f"в одной транзакции продано {len(продано)} и куплено "
                          f"{len(куплено)} минтов -- одно `polucheno` на две "
                          f"стороны делить нечем, позиции не тронуты")
        return из_
    позиции = sostojanie.setdefault("pozicii", {})
    # --- ПРОДАЖА ПЕРВОЙ: в одной транзакции может быть и то и другое.
    for минт, дельта in продано:
        п = позиции.get(минт)
        ушло = -дельта
        if not п:
            # ПРОДАЖА БЕЗ ИЗВЕСТНОГО ВХОДА -- ЭТО НЕ ЗАРАБОТОК. Вход был до
            # начала ряда, в капитале он не стоял (позиция шла нулём, см.
            # `bez_vhoda`), поэтому выручка -- деньги, ПРИШЕДШИЕ в измеряемую
            # систему извне. Если её не исключить, изменение за период
            # покажет прибыль на всю выручку, которой не было.
            sostojanie["neopoznannyh"] = int(
                sostojanie.get("neopoznannyh") or 0) + 1
            sostojanie["vyruchka_bez_vhoda_lamports"] = int(
                sostojanie.get("vyruchka_bez_vhoda_lamports") or 0) + int(
                    р.get("polucheno") or 0)
            if int(р.get("polucheno") or 0):
                метка = {"utc": р.get("utc"), "sig": р.get("sig"),
                          "vid": "продажа без входа", "mint": минт,
                          "lamports": int(р.get("polucheno") or 0)}
                sostojanie["metki"] = (sostojanie.get("metki") or []) + [метка]
                из_["metka"] = метка
            continue
        было = int(п.get("ostatok") or 0)
        доля = (min(1.0, ушло / было) if было > 0 else 1.0)
        вход_части = int(round(int(п.get("vhod") or 0) * доля))
        итог = int(р.get("polucheno") or 0) - вход_части
        sostojanie["sdelok_vsego"] = int(
            sostojanie.get("sdelok_vsego") or 0) + 1
        sostojanie["sdelki"] = (sostojanie.get("sdelki") or []) + [{
            "mint": минт, "vhod": вход_части, "polucheno": int(р.get("polucheno") or 0),
            "itog": итог, "chast": round(доля, 6),
            "otkryta_utc": п.get("utc"), "zakryta_utc": р.get("utc"),
            "sig_pokupki": п.get("sig"), "sig_prodazhi": р.get("sig")}]
        из_["zakryto"].append({"mint": минт, "itog": итог, "chast": доля})
        остаток = было - ушло
        if остаток > 0 and доля < 1.0:
            п["vhod"] = int(п.get("vhod") or 0) - вход_части
            п["ostatok"] = остаток
        else:
            позиции.pop(минт, None)
    # --- ПОКУПКА: ровно один минт, иначе делить потраченное нечем.
    if len(куплено) == 1 and int(р.get("potracheno") or 0) <= 0:
        # ПОЗИЦИЯ -- ЭТО ТОКЕН, КУПЛЕННЫЙ ЗА SOL (слово владельца 04.10).
        # Если из системы «кошелёк плюс наши токен-счета» SOL не уходил,
        # платили не им: это или нога за котировку, или чужой перевод токена
        # (дарёная пыль). Открыть позицию с входом НОЛЬ значит потом принять
        # её продажу за чистый заработок, а до продажи держать в капитале
        # минт, за который мы не платили.
        sostojanie["neopoznannyh"] = int(
            sostojanie.get("neopoznannyh") or 0) + 1
        из_["pochemu"] = (f"минт {куплено[0][0][:6]}… вырос, но SOL из системы "
                          f"не уходил (потрачено 0"
                          + (f", котировки: {', '.join(котировки)}" if котировки else "")
                          + ") -- это не покупка за SOL, позиция не открыта")
        return из_
    if len(куплено) == 1:
        минт, дельта = куплено[0]
        п = позиции.get(минт)
        if п:
            п["vhod"] = int(п.get("vhod") or 0) + int(р.get("potracheno") or 0)
            п["ostatok"] = int(п.get("ostatok") or 0) + дельта
            п["dobavok"] = int(п.get("dobavok") or 0) + 1
        else:
            позиции[минт] = {"vhod": int(р.get("potracheno") or 0),
                              "ostatok": дельта, "sig": р.get("sig"),
                              "utc": р.get("utc"), "slot": р.get("slot"),
                              "dobavok": 0}
        из_["otkryto"].append({"mint": минт, "vhod": int(р.get("potracheno") or 0)})
    elif len(куплено) > 1:
        sostojanie["neopoznannyh"] = int(
            sostojanie.get("neopoznannyh") or 0) + 1
        из_["pochemu"] = (f"{len(куплено)} минтов выросли в одной транзакции -- "
                          f"потраченное между ними делить нечем")
    return из_


def сумма_ренты_пустых(scheta: list) -> int:
    """Рента ПУСТЫХ счетов -- та, что вернётся уборкой. Отдельным числом."""
    return sum(renta_scheta(с) for с in (scheta or [])
               if not int(с.get("amount") or 0))


def rjad(rpc_call, *, koshelek: str = КОШЕЛЕК, sostojanie: dict | None = None,
         schjotchik=None, sejchas: float | None = None,
         schitat_scheta: bool = True, kotirovka_call=None,
         kesh_kotirovok: dict | None = None,
         drugie_koshelki: tuple | None = None) -> dict:
    """ОДИН РЯД капитала: чтение цепи плюс арифметика. Сети внутри нет.

    schitat_scheta=False -- взять счета из состояния (кэш), не спрашивая узел.
    Тогда в ряде стоит поле `scheta_vozrast_sek`: по нему видно, насколько
    старым снимком счетов посчитаны рента и позиции.
    """
    сост = sostojanie if sostojanie is not None else pustoe_sostojanie(koshelek)
    сейчас_ = float(sejchas if sejchas else time.time())
    б = sol_koshelka(rpc_call, koshelek, schjotchik=schjotchik)
    кэш = сост.get("scheta_snimok") or {}
    if schitat_scheta or not кэш.get("scheta"):
        счета = tokennye_scheta(rpc_call, koshelek, schjotchik=schjotchik)
        сост["scheta_snimok"] = {"utc": int(сейчас_), "scheta": счета}
        возраст = 0
    else:
        счета = кэш.get("scheta") or []
        возраст = int(сейчас_ - int(кэш.get("utc") or сейчас_))
    # ПОЗИЦИИ -- ТОЛЬКО ПО ТОМУ, ЧТО ДЕЙСТВИТЕЛЬНО ЛЕЖИТ НА СЧЕТАХ. Позиция из
    # состояния, которой на цепи уже нет, в капитал не идёт: иначе капитал
    # помнил бы проданное.
    остатки: dict = {}
    котировок_с_остатком = 0
    for с in счета:
        if int(с.get("amount") or 0) <= 0:
            continue
        минт_с = str(с.get("mint"))
        if минт_с in КОТИРОВОЧНЫЕ_МИНТЫ:
            # КОТИРОВКА НЕ ПОЗИЦИЯ И НЕ «БЕЗ ВХОДА». Пыль USDC (0.0011 на
            # хосте) жила тут позицией с входом 0 и попадала в «позиций без
            # цены входа» -- строкой «капитал занижен», которой не было.
            # Рента её счёта в капитале остаётся: это наши лампорты.
            котировок_с_остатком += 1
            continue
        остатки[минт_с] = остатки.get(минт_с, 0) + int(с["amount"])
    # ПОЗИЦИЯ СТОИТ СТОЛЬКО, СКОЛЬКО ЗА НЕЁ ДАЮТ СЕЙЧАС, А НЕ СКОЛЬКО МЫ ЗА
    # НЕЁ ЗАПЛАТИЛИ (слово владельца 04.10). Вход остаётся рядом отдельным
    # числом: по нему видно, сколько позиция СТОИЛА, а по котировке -- сколько
    # она стоит. Рагпул, из которого выхода нет, даёт ноль и помечается
    # списанным, а не висит по входу вечно.
    позиции_стоимость: dict = {}
    позиции_табл: list = []
    вход_всего = 0
    списано = 0
    по_входу_нет_котировки = 0
    кэш_кот = (kesh_kotirovok if kesh_kotirovok is not None
               else сост.setdefault("kotirovki", {}))
    без_входа = []
    for минт, ост in остатки.items():
        п = (сост.get("pozicii") or {}).get(минт)
        вход = int((п or {}).get("vhod") or 0)
        if not (п and вход > 0):
            # ЦЕНЫ ВХОДА НЕТ -- И ЭТО НАЗЫВАЕТСЯ ЧИСЛОМ. Такой минт даёт нуль в
            # капитал, значит капитал ЗАНИЖЕН на его вход, и прятать это нельзя.
            без_входа.append(минт)
            continue
        ст = stoimost_pozicii(минт, int(ост), вход, kesh=кэш_кот,
                              sejchas=сейчас_, zov=kotirovka_call)
        позиции_стоимость[минт] = int(ст.get("stoimost") or 0)
        вход_всего += вход
        списано += bool(ст.get("spisana"))
        по_входу_нет_котировки += bool(ст.get("po_vhodu"))
        позиции_табл.append(ст)
    к = kapital(б["lamports"], счета, позиции_стоимость)
    # НАКОПИТЕЛЬНЫЕ ЧИСЛА ИДУТ СО СДВИГОМ: ряд живёт дольше состояния, и после
    # потери состояния счётчик обязан продолжить ряд, а не начаться с нуля.
    сдв = сост.get("sdvigi") or {}
    из_ = {"utc": int(sejchas if sejchas else time.time()),
            "slot": б.get("slot"),
            "sol": к["sol"], "wsol": к["wsol"], "renta": к["renta"],
            "pozicii": к["pozicii"], "kapital": к["kapital"],
            "pozicij": к["pozicij"], "schetov": к["schetov"],
            "schetov_pustyh": к["schetov_pustyh"],
            "bez_vhoda": len(без_входа),
            "vvod_vyvod": (int(сост.get("vvod_vyvod_lamports") or 0)
                           + int(сдв.get("vvod_vyvod") or 0)),
            "vyruchka_bez_vhoda": (
                int(сост.get("vyruchka_bez_vhoda_lamports") or 0)
                + int(сдв.get("vyruchka_bez_vhoda") or 0)),
            "rashodov_lamports": (int(сост.get("rashodov_lamports") or 0)
                                  + int(сдв.get("rashodov_lamports") or 0)),
            "rashodov": int(сост.get("rashodov") or 0),
            "upjorlis": bool(сост.get("upjorlis_v_predel")),
            "sdelok": len(сост.get("sdelki") or []),
            "zakrytyj_itog": sum(int(с.get("itog") or 0)
                                 for с in (сост.get("sdelki") or [])),
            "neopoznannyh": int(сост.get("neopoznannyh") or 0)}
    из_["bez_vhoda_minty"] = без_входа[:5]
    из_["pozicii_po_vhodu"] = вход_всего
    из_["spisano_pozicij"] = списано
    из_["pozicij_po_vhodu_bez_kotirovki"] = по_входу_нет_котировки
    # ТАБЛИЦА ПОЗИЦИЙ -- ДЛЯ СТРАНИЦЫ: минт, вход, котировка, возраст, пометка.
    из_["pozicii_tablica"] = sorted(
        ({"mint": т["mint"], "vhod": т["vhod"],
          "stoimost": int(т.get("stoimost") or 0),
          "ostatok": т["ostatok"], "vozrast_sek": т.get("vozrast_sek"),
          "spisana": bool(т.get("spisana")),
          "po_vhodu": bool(т.get("po_vhodu")),
          "why_not": т.get("why_not")} for т in позиции_табл),
        key=lambda т: -int(т.get("vhod") or 0))[:20]
    из_["kotirovok_s_ostatkom"] = котировок_с_остатком
    из_["scheta_vozrast_sek"] = возраст
    # --- КАПИТАЛ ВСЕЙ СИСТЕМЫ. Полоса считается полностью (позиции по
    # котировке), остальные -- одним чтением: SOL, WSOL, рента. Их открытые
    # позиции в капитал НЕ входят, и это названо числом `bez_pozicij`.
    кош = {"полоса": {"kapital": из_["kapital"], "sol": из_["sol"],
                       "wsol": из_["wsol"], "renta": из_["renta"],
                       "renta_pustyh": сумма_ренты_пустых(счета),
                       "pozicii": из_["pozicii"], "schetov": из_["schetov"],
                       "schetov_pustyh": из_["schetov_pustyh"],
                       "s_pozicijami": True}}
    для_других = (drugie_koshelki if drugie_koshelki is not None
                  else tuple(к for к in КОШЕЛЬКИ_СИСТЕМЫ
                             if к["adres"] != koshelek))
    # СЧЕТА ЧУЖИХ КОШЕЛЬКОВ ПЕРЕЧИТЫВАЮТСЯ РЕДКО. Их подписи мы не разбираем,
    # значит узнать о смене счетов можем только по времени: берём тот же срок,
    # что и для полосы (СЧЕТА_НЕ_СТАРШЕ_СЕК). Иначе три кошелька добавляли бы
    # по шесть вызовов в КАЖДЫЙ тик -- 26 тысяч вызовов в сутки впустую.
    кэш_других = сост.setdefault("scheta_drugih", {})
    for к_ in для_других:
        з = кэш_других.get(к_["adres"]) or {}
        свежие = (isinstance(з.get("utc"), int)
                  and (сейчас_ - з["utc"]) < СЧЕТА_НЕ_СТАРШЕ_СЕК
                  and isinstance(з.get("scheta"), list))
        try:
            if свежие:
                кк = kapital_koshelka(rpc_call, к_["adres"],
                                      schjotchik=schjotchik,
                                      scheta=з["scheta"])
            else:
                счета_ч = tokennye_scheta(rpc_call, к_["adres"],
                                          schjotchik=schjotchik)
                кэш_других[к_["adres"]] = {"utc": int(сейчас_),
                                            "scheta": счета_ч}
                кк = kapital_koshelka(rpc_call, к_["adres"],
                                      schjotchik=schjotchik, scheta=счета_ч)
        except (ОшибкаТрекера, OSError, ValueError) as сбой:
            кош[к_["imja"]] = {"why_not": f"{type(сбой).__name__}: "
                                           f"{zateret(str(сбой))[:100]}"}
            continue
        кош[к_["imja"]] = {"kapital": кк["kapital"], "sol": кк["sol"],
                            "wsol": кк["wsol"], "renta": кк["renta"],
                            "renta_pustyh": кк["renta_pustyh"],
                            "pozicii": 0, "schetov": кк["schetov"],
                            "schetov_pustyh": кк["schetov_pustyh"],
                            "bez_pozicij": кк["s_ostatkom"],
                            "s_pozicijami": False}
    из_["koshelki"] = кош
    из_["kapital_sistemy"] = sum(int(з.get("kapital") or 0)
                                 for з in кош.values())
    из_["renta_pustyh_sistemy"] = sum(int(з.get("renta_pustyh") or 0)
                                      for з in кош.values())
    return из_


def dognat_cep(rpc_call, *, koshelek: str = КОШЕЛЕК, sostojanie: dict,
               sutok: float = 3.0, schjotchik=None,
               sejchas: float | None = None, predel_podpisej: int = 3000) -> dict:
    """Догнать цепь: разобрать НОВЫЕ подписи кошелька и обновить состояние.

    ПЕРВЫЙ ПРОГОН -- ВОССТАНОВЛЕНИЕ ИСТОРИИ ЗА `sutok` СУТОК по цепи: иначе у
    открытых позиций не будет цены входа, и капитал окажется занижен на всё, что
    куплено до запуска.

    ПОРЯДОК РАЗБОРА -- ОТ СТАРЫХ К НОВЫМ, и это не вкусовщина: позиция обязана
    открыться раньше, чем закроется, иначе продажа не найдёт входа.
    """
    из_ = {"ok": False, "why_not": None, "podpisej": 0, "razobrano": 0,
            "propushcheno_staryh": 0, "upjorlis_v_predel": False,
            "net_tranzakcii": 0, "povtorov": 0, "stranic": 0,
            "pervyj_progon": not bool(sostojanie.get("poslednjaja_sig"))}
    сейчас = float(sejchas if sejchas else time.time())
    порог = сейчас - float(sutok) * 86400.0
    # ПРЕДЕЛ СЧИТАЕТСЯ ПО ТОМУ, СКОЛЬКО СТРАНИЦ ВЗЯЛИ, А НЕ ПО ЧУЖОМУ ЧИСЛУ.
    # Раньше сравнение шло с predel_podpisej (3000), а обычный тик брал 2
    # страницы, то есть максимум 2000 подписей: признак не поднимался НИКОГДА,
    # и всё, что сверх 2000, терялось МОЛЧА. Теперь предел -- стр * 1000.
    стр = max(1, int(predel_podpisej // 1000))
    из_["stranic"] = стр
    подписи = podpisi_koshelka(
        rpc_call, koshelek, do_sig=sostojanie.get("poslednjaja_sig"),
        schjotchik=schjotchik, stranic=стр)
    из_["podpisej"] = len(подписи)
    if len(подписи) >= стр * 1000:
        из_["upjorlis_v_predel"] = True
    sostojanie["upjorlis_v_predel"] = bool(из_["upjorlis_v_predel"])
    # Новые идут первыми -- переворачиваем и отбрасываем то, что старше окна.
    годные = []
    for з in reversed(подписи):
        т = з.get("blockTime")
        if из_["pervyj_progon"] and isinstance(т, int) and т < порог:
            из_["propushcheno_staryh"] += 1
            continue
        годные.append(з)
    for з in годные:
        tx = tranzakciya(rpc_call, з["signature"], schjotchik=schjotchik)
        if not tx:
            # УЗЕЛ НЕ ОТДАЛ ТРАНЗАКЦИЮ -- И РЯД НЕ ЕДЕТ ДАЛЬШЕ ЭТОЙ ПОДПИСИ.
            # Раньше здесь стоял `continue`, а `poslednjaja_sig` шла вперёд на
            # следующей удачной: подпись терялась НАВСЕГДА и молча -- а это
            # могла быть покупка, то есть позиция без цены входа и капитал,
            # занижённый на целый билет.
            из_["net_tranzakcii"] += 1
            з_было = sostojanie.get("zastrjali") or {}
            застряли = ({"sig": з["signature"],
                          "tikov": int(з_было.get("tikov") or 0) + 1}
                        if з_было.get("sig") == з["signature"]
                        else {"sig": з["signature"], "tikov": 1})
            sostojanie["zastrjali"] = застряли
            if застряли["tikov"] >= ПРЕДЕЛ_ЗАСТРЕВАНИЯ:
                # После предела подпись НАЗЫВАЕТСЯ пропущенной навсегда (и
                # лежит в состоянии списком), а ряд едет: одна недоступная
                # транзакция не имеет права остановить трекер насовсем.
                sostojanie["propushcheno_navsegda"] = (
                    (sostojanie.get("propushcheno_navsegda") or [])
                    + [з["signature"]])[-50:]
                sostojanie["poslednjaja_sig"] = з["signature"]
                sostojanie["zastrjali"] = None
                continue
            из_["why_not"] = (f"узел не отдал транзакцию {з['signature'][:12]}… "
                              f"(тик {застряли['tikov']} из "
                              f"{ПРЕДЕЛ_ЗАСТРЕВАНИЯ}) -- ряд не двинут дальше "
                              f"неё, следующий тик спросит снова")
            break
        п = prinjat_tranzakciju(sostojanie, tx, koshelek)
        из_["povtorov"] += bool(п.get("povtor"))
        из_["razobrano"] += 1
        sostojanie["zastrjali"] = None
        sostojanie["poslednjaja_sig"] = з["signature"]
        if not sostojanie.get("pervaja_sig_istorii"):
            sostojanie["pervaja_sig_istorii"] = з["signature"]
    sostojanie["obnovleno_utc"] = time.strftime("%Y-%m-%dT%H:%M:%SZ",
                                                time.gmtime(сейчас))
    из_["ok"] = True
    return из_


# ------------------------------------------------- свёртка и монотонная кривая

def korziny(rjady: list, *, okno_sek: int, korzina_sek: int,
            sejchas: float | None = None) -> dict:
    """Свёртка ряда в корзины: значение корзины -- ПОСЛЕДНЕЕ в ней.

    ПУСТЫЕ КОРЗИНЫ НЕ ЗАПОЛНЯЮТСЯ. Протянуть последнее значение вперёд -- значит
    скрыть простой сборщика: график будет ровным там, где данных нет вовсе.
    Поэтому пустая корзина просто отсутствует, а число пропусков и самый долгий
    пропуск отдаются ЧИСЛОМ -- по ним видно, что сборщик стоял.
    """
    сейчас = float(sejchas if sejchas else time.time())
    порог = сейчас - float(okno_sek)
    по_корзинам: dict = {}
    for р in rjady:
        т = float(р.get("utc") or 0)
        if т < порог or т > сейчас + 1:
            continue
        к = int(т // korzina_sek)
        прежний = по_корзинам.get(к)
        if прежний is None or float(прежний.get("utc") or 0) <= т:
            по_корзинам[к] = р
    ключи = sorted(по_корзинам)
    точки = [{"utc": int(по_корзинам[к].get("utc") or 0),
               "lamports": int(по_корзинам[к].get("kapital") or 0)}
              for к in ключи]
    # ЧИСЛО КОРЗИН ОКНА -- ПО ЕГО РАЗМАХУ, А НЕ ДЕЛЕНИЕМ. Окно не выровнено по
    # границам корзин (сейчас -- произвольная секунда), поэтому делением
    # получалось на одну меньше, и «пропусков» уходило в ноль там, где их не
    # было, и наоборот.
    всего_корзин = int(сейчас // korzina_sek) - int(порог // korzina_sek) + 1
    пропусков = max(0, всего_корзин - len(ключи))
    долгий = 0
    for i in range(1, len(ключи)):
        долгий = max(долгий, (ключи[i] - ключи[i - 1] - 1) * korzina_sek)
    return {"tochki": точки, "korzin_vsego": всего_корзин,
            "korzin_est": len(ключи), "propuskov": пропусков,
            "dolgij_propusk_sek": долгий}


def monotonnye_tangensy(xs: list, ys: list) -> list:
    """Наклоны по Фричу--Карлсону: кривая не вылезает выше и ниже точек.

    ЗАЧЕМ ИМЕННО ЭТО (слово владельца: «кривая монотонная, без выбросов
    выше/ниже точек»). Обычный сглаженный сплайн на денежном графике ВЫДУМЫВАЕТ
    экстремумы: между двумя близкими точками он уходит выше максимума и ниже
    минимума, и владелец видит на картинке просадку, которой не было. Условие
    Фрича--Карлсона (ограничение наклонов тремя секущими) это запрещает, и
    запрет проверен числом: самопроверка сэмплирует готовую кривую и требует,
    чтобы на каждом отрезке она лежала между его концами.
    """
    n = len(xs)
    if n < 2:
        return [0.0] * n
    секущие = []
    for i in range(n - 1):
        dx = float(xs[i + 1] - xs[i]) or 1e-9
        секущие.append((float(ys[i + 1]) - float(ys[i])) / dx)
    m = [секущие[0]] + [0.0] * (n - 2) + [секущие[-1]]
    for i in range(1, n - 1):
        if секущие[i - 1] * секущие[i] <= 0:
            m[i] = 0.0
        else:
            m[i] = (секущие[i - 1] + секущие[i]) / 2.0
    for i in range(n - 1):
        if секущие[i] == 0:
            m[i] = 0.0
            m[i + 1] = 0.0
            continue
        a = m[i] / секущие[i]
        b = m[i + 1] / секущие[i]
        s = a * a + b * b
        if s > 9.0:
            t = 3.0 / (s ** 0.5)
            m[i] = t * a * секущие[i]
            m[i + 1] = t * b * секущие[i]
    return m


def put_krivoj(tochki: list, *, shirina: int = 1000, vysota: int = 320,
               pole: int = 8) -> dict:
    """SVG-путь линии и заливки по точкам. Чистая арифметика, без рисования.

    ПОЧЕМУ ПУТЬ СЧИТАЕТСЯ ЗДЕСЬ, А НЕ В СТРАНИЦЕ. Одна и та же арифметика в
    питоне и в JS однажды разойдётся, и разойдётся молча -- на картинке.
    Здесь она ОДНА, и её проверяет самопроверка; страница только подставляет
    готовую строку.
    """
    из_ = {"liniya": "", "zalivka": "", "tochek": len(tochki),
            "min": None, "max": None, "x": [], "y": []}
    if not tochki:
        return из_
    зн = [float(т["lamports"]) for т in tochki]
    вр = [float(т["utc"]) for т in tochki]
    низ, верх = min(зн), max(зн)
    из_["min"], из_["max"] = int(низ), int(верх)
    разброс = (верх - низ) or 1.0
    t0, t1 = вр[0], вр[-1]
    промежуток = (t1 - t0) or 1.0
    вн_ш = shirina - 2 * pole
    вн_в = vysota - 2 * pole
    xs = [pole + вн_ш * ((т - t0) / промежуток) for т in вр]
    ys = [pole + вн_в * (1.0 - (з - низ) / разброс) for з in зн]
    из_["x"], из_["y"] = [round(x, 2) for x in xs], [round(y, 2) for y in ys]
    if len(tochki) == 1:
        из_["liniya"] = f"M {xs[0]:.2f} {ys[0]:.2f} L {xs[0] + 0.01:.2f} {ys[0]:.2f}"
        из_["zalivka"] = (f"{из_['liniya']} L {xs[0] + 0.01:.2f} {vysota} "
                          f"L {xs[0]:.2f} {vysota} Z")
        return из_
    m = monotonnye_tangensy(xs, ys)
    части = [f"M {xs[0]:.2f} {ys[0]:.2f}"]
    for i in range(len(xs) - 1):
        dx = xs[i + 1] - xs[i]
        c1x, c1y = xs[i] + dx / 3.0, ys[i] + m[i] * dx / 3.0
        c2x, c2y = xs[i + 1] - dx / 3.0, ys[i + 1] - m[i + 1] * dx / 3.0
        части.append(f"C {c1x:.2f} {c1y:.2f} {c2x:.2f} {c2y:.2f} "
                      f"{xs[i + 1]:.2f} {ys[i + 1]:.2f}")
    из_["liniya"] = " ".join(части)
    из_["zalivka"] = (из_["liniya"] + f" L {xs[-1]:.2f} {vysota} "
                      f"L {xs[0]:.2f} {vysota} Z")
    return из_


def tochka_krivoj(put_x: list, put_y: list, tochki: list, dolya: float) -> tuple:
    """Значение кривой в доле от начала -- для проверки выбросов самопроверкой."""
    if not tochki:
        return (0.0, 0.0)
    i = min(len(tochki) - 2, max(0, int(dolya * (len(tochki) - 1))))
    т = (dolya * (len(tochki) - 1)) - i
    xs, ys = put_x, put_y
    m = monotonnye_tangensy(xs, ys)
    dx = xs[i + 1] - xs[i]
    p0, p1 = ys[i], ys[i + 1]
    m0, m1 = m[i] * dx, m[i + 1] * dx
    h00 = 2 * т ** 3 - 3 * т ** 2 + 1
    h10 = т ** 3 - 2 * т ** 2 + т
    h01 = -2 * т ** 3 + 3 * т ** 2
    h11 = т ** 3 - т ** 2
    return (i, h00 * p0 + h10 * m0 + h01 * p1 + h11 * m1)


