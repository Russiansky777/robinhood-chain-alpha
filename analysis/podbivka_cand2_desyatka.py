#!/usr/bin/env python3
"""Десятка для группы cand2 на билете 0.1 из прошедших отбор. Офлайн, без нового счёта.

Вход -- data/podbivka/cand2_otbor.json (уже посчитанный отбор cand2: окно 24.09 17Z → 01.10 17Z, правило кандидатов
без изменений). Условия владельца 02.10: из прошедших отбор -- n ≥ 50, медиана +108 ≥ +2 п.п., «толпа есть»;
кусты -- одним адресом; уже торгующие группы (lane_s0 / batch5 / leader) и cand1 исключены (cand1_03 и cand1_05 --
те же девять адресов cand1 с другими билетами, отдельной группы в реестре нет).
«Толпа есть» -- доля ячеек, где в слотах s0+1 / s0+2 был хотя бы один своп пула (обратное к «никто %»); за «толпу
есть» считается доля ≥ 0.5.
Выход: docs/podbivka_2026-10-02_cand2_desyatka.md. Ничего не рекомендуется, состав -- решение владельца.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

КОРЕНЬ = Path(__file__).resolve().parent.parent
П = КОРЕНЬ / "data" / "podbivka"
ЖИВЫЕ = {"lane_s0", "batch5", "leader", "cand1"}
N_МИН, МЕД_МИН, ТОЛПА_МИН = 50, 2.0, 0.5


def откуда(v: dict) -> str:
    г = [x for x in (v.get("группы") or []) if x != "log_only"]
    из_ = []
    if "543" in г:
        из_.append("543")
    if {"снайперские источники", "sniper_src"} & set(г):
        из_.append("снайперы")
    if "gmgn" in г or v.get("gmgn"):
        из_.append("GMGN")
    if v.get("fomo"):
        из_.append("Fomo")
    if "кандидат" in г:
        из_.append("кандидат 27.09")
    if "133" in г:
        из_.append("133")
    return ", ".join(из_) or "лог"


def строка(a: str, v: dict, ключ: str) -> str:
    s = v["отбор"][ключ]
    яч, никто = v["отбор_ячеек"], v["отбор_никто"]
    толпа = (1 - никто / яч) if яч else None
    s3 = v["отбор"]["108"]
    return (f"| `{a}` | {откуда(v)} | {s.get('n')} | {s.get('среднее'):+.2f} | {s.get('медиана'):+.2f} | "
            f"{100 * (s.get('в_плюсе') or 0):.0f} % | " + (f"{толпа:.2f}" if толпа is not None else "—") +
            f" | {s3.get('n')} / {s3.get('среднее'):+.2f} / {s3.get('медиана'):+.2f} |")


def main() -> int:
    import podbivka_run as R  # noqa: PLC0415
    д = json.loads((П / "cand2_otbor.json").read_text(encoding="utf-8"))
    r = д["ряды"]
    куст: dict = {}
    for п in д["кусты"]:
        куст.setdefault(п["a"], set()).add(п["b"])
        куст.setdefault(п["b"], set()).add(п["a"])

    def годные(ключ: str) -> list:
        из_ = []
        for a, v in r.items():
            if not v["прошёл_отбор"] or set(v["группы"] or []) & ЖИВЫЕ:
                continue
            s = v["отбор"][ключ]
            яч, никто = v["отбор_ячеек"], v["отбор_никто"]
            толпа = (1 - никто / яч) if яч else 0.0
            if (s.get("n") or 0) >= N_МИН and (s.get("медиана") or -99) >= МЕД_МИН and толпа >= ТОЛПА_МИН:
                из_.append(a)
        return sorted(из_, key=lambda a: (-(r[a]["отбор"][ключ]["медиана"]), -(r[a]["отбор"][ключ]["n"])))

    по_01, по_03 = годные("108_01"), годные("108")
    близко = sorted(((a, v) for a, v in r.items()
                     if v["прошёл_отбор"] and not (set(v["группы"] or []) & ЖИВЫЕ)
                     and (v["отбор"]["108_01"].get("n") or 0) >= N_МИН
                     and 0 < (v["отбор"]["108_01"].get("медиана") or -99) < МЕД_МИН),
                    key=lambda t: -t[1]["отбор"]["108_01"]["медиана"])
    загол = ("| адрес | откуда | n | среднее, п.п. | медиана, п.п. | в плюсе | толпа есть | "
             "для справки, билет 0.3: n / среднее / медиана |")
    линия = "|---|---|---|---|---|---|---|---|"
    кусты_строки = [f"- `{a[:8]}` и " + ", ".join(f"`{b[:8]}`" for b in sorted(куст[a]))
                    for a in dict.fromkeys(по_01 + по_03) if a in куст]

    md = ["# Кандидаты cand2: десятка на билете 0.1 из прошедших отбор (окно 24.09 17Z – 01.10 17Z)", "",
          "Без нового счёта: всё взято из `data/podbivka/cand2_otbor.json` "
          "(страница отбора -- `docs/podbivka_2026-10-02_kandidaty_cand2.md`). Условия: из прошедших отбор "
          f"(n ≥ 20, среднее ≥ +2 п.п., медиана > 0 на билете 0.3) оставлены те, у кого **n ≥ {N_МИН}**, "
          f"**медиана +108 ≥ +{МЕД_МИН:g} п.п.** и **«толпа есть»** (доля ячеек со свопом пула в s0+1 / s0+2 "
          f"не ниже {ТОЛПА_МИН:g}). Исключены уже торгующие группы (lane_s0 / batch5 / leader) и cand1 -- "
          "cand1_03 и cand1_05 это те же девять адресов cand1 с другими билетами, отдельной группы в реестре нет. "
          "Кусты -- одним адресом. Ничего не рекомендуется, состав группы -- решение владельца.", "",
          f"**Десятки не вышло: по билету 0.1 правило проходят {len(по_01)} адреса, не 10.** Поэтому ниже две "
          f"таблицы: сначала те {len(по_01)}, затем те {len(по_03)}, кто проходит то же правило по медиане "
          "главного билета 0.3 (первые пять входят и туда). Разница в том, что при билете 0.1 наш вход двигает "
          "цену слабее, и медиана считается по тому же набору сделок с другим размером.", ""]

    md += [f"## A. Правило на билете 0.1 ({len(по_01)} адреса)", "", загол, линия]
    md += [строка(a, r[a], "108_01") for a in по_01]
    md += ["", f"## Б. То же правило по медиане билета 0.3 ({len(по_03)} адресов)", "",
           "Столбцы -- числа билета 0.3; для справки в последнем столбце n / среднее / медиана того же билета 0.3.", "",
           загол, линия]
    md += [строка(a, r[a], "108") for a in по_03]
    md += ["", "## В. Ближе всех, но не проходят (медиана 0.1 от 0 до +2 п.п.)", "", загол, линия]
    md += [строка(a, v, "108_01") for a, v in близко]
    md += ["", "## Кусты среди отобранных", ""]
    md += кусты_строки or ["- нет: ни один из отобранных не входит в куст (49 кустов окна -- все на других адресах)"]
    md += ["", "Оговорка: `cand2_otbor.json` посчитан до того, как 493 кошелька GMGN были вынесены из реестра наших "
           "адресов в отдельный список, поэтому в столбце «откуда» метка GMGN сохранена -- счёт шёл с ними.", ""]
    out = КОРЕНЬ / "docs" / "podbivka_2026-10-02_cand2_desyatka.md"
    out.write_text("\n".join(md) + "\n", encoding="utf-8")
    R.записано(out)
    print(out.name, "по 0.1:", len(по_01), "по 0.3:", len(по_03), "близко:", len(близко), flush=True)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
