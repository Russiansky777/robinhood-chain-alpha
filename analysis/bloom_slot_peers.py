#!/usr/bin/env python3
"""Соседи по слоту: кто ещё купил тот же токен в том же блоке.

ЗАЧЕМ. Формат владельца (26.09, ночь) требует в строке BUY четвёртое поле:
"перед нами: N, копировщиков K" при S+0 и "в S+0 успели: N, копировщиков K"
иначе. N -- это чужие кошельки, купившие ТОТ ЖЕ минт в слоте источника; K -- те
из них, кто уже известен как копировщик (список строится отдельно).

ЧТО СЧИТАЕТСЯ ПОКУПКОЙ. Прирост остатка ЭТОГО минта у кошелька за транзакцию
(post минус pre по token balances) больше нуля, и транзакция не упала. Это
честный признак "получил токен", и он не путает покупку с продажей.

ЧЕГО ЗДЕСЬ НЕТ. Никаких "вероятно ботов" и никаких догадок по именам программ:
считаются кошельки, а известность копировщика решает список, а не этот модуль.
Свои кошельки (исполнитель и полоса) и кошелёк источника из счёта исключаются:
себя и того, за кем идём, в "перед нами" быть не может.

Один getBlock на слот -- вызывается ТОЛЬКО из фоновой догонялки, не с горячего
пути.
"""
from __future__ import annotations


def _прирост_по_кошелькам(tx: dict, минт: str) -> dict:
    """{кошелёк: прирост сырых единиц минта} по одной транзакции."""
    мета = (tx or {}).get("meta") or {}
    if мета.get("err") is not None:
        return {}
    до: dict = {}
    после: dict = {}
    for поле, куда in (("preTokenBalances", до), ("postTokenBalances", после)):
        for з in (мета.get(поле) or []):
            if (з or {}).get("mint") != минт:
                continue
            владелец = з.get("owner")
            сумма = (((з.get("uiTokenAmount") or {}).get("amount")) or "0")
            try:
                значение = int(сумма)
            except (TypeError, ValueError):
                continue
            if владелец:
                куда[владелец] = куда.get(владелец, 0) + значение
    из_: dict = {}
    for владелец in set(до) | set(после):
        дельта = после.get(владелец, 0) - до.get(владелец, 0)
        if дельта > 0:
            из_[владелец] = дельта
    return из_


def _подпись(tx: dict) -> str | None:
    подписи = ((tx or {}).get("transaction") or {}).get("signatures") or []
    return подписи[0] if подписи else None


def покупатели(блок: dict, *, минт: str, свои: set,
                исключить: set = frozenset()) -> list:
    """[{индекс, подпись, кошельки}] по порядку блока: кто получил минт.

    Порядок списка -- порядок транзакций в блоке, то есть по нему и считается
    "до нас" и "после нас".
    """
    из_ = []
    for и, tx in enumerate((блок or {}).get("transactions") or []):
        приросты = _прирост_по_кошелькам(tx, минт)
        кошельки = {к for к in приросты
                    if к not in свои and к not in исключить}
        if кошельки:
            из_.append({"индекс": и, "подпись": _подпись(tx),
                        "кошельки": sorted(кошельки)})
    return из_


def соседи(rpc_call, *, слот: int, минт: str, свои: set,
            наша_подпись: str | None = None, наш_индекс=None,
            источник: str | None = None, известные: set = frozenset()) -> dict:
    """Числа для строки: сколько чужих купили минт в слоте и сколько до нас.

    Наш индекс берётся из блока по нашей подписи, а не со стороны: так он точен
    даже если места посадки в позиции ещё нет. Нет нашей транзакции в этом слоте
    (мы сели позже) -- "до нас" считается по ВСЕМ найденным: они все успели
    раньше, и это тот самый случай "в S+0 успели".
    """
    из_ = {"known": False, "всего": None, "до_нас": None, "кошельки": [],
            "известных": None, "why_not": None, "наш_индекс": наш_индекс}
    try:
        import bloom_queue_price as QP  # noqa: PLC0415
    except Exception as exc:  # noqa: BLE001
        из_["why_not"] = f"нет модуля разбора блока ({type(exc).__name__})"
        return из_
    б = QP.блок(rpc_call, слот, детали="full")
    if not б.get("known"):
        из_["why_not"] = б.get("why_not")
        return из_
    исключить = {источник} if источник else set()
    ряды = покупатели(б, минт=минт, свои=set(свои or ()), исключить=исключить)
    if наша_подпись:
        for и, tx in enumerate((б.get("transactions") or [])):
            if _подпись(tx) == наша_подпись:
                из_["наш_индекс"] = и
                break
    все_кошельки = sorted({к for р in ряды for к in р["кошельки"]})
    предел = из_["наш_индекс"]
    if isinstance(предел, int):
        до = sorted({к for р in ряды if р["индекс"] < предел
                     for к in р["кошельки"]})
    else:
        до = list(все_кошельки)
    из_.update(known=True, всего=len(все_кошельки), до_нас=len(до),
               кошельки=все_кошельки,
               известных=len([к for к in все_кошельки if к in (известные or ())]),
               ряды=[{"индекс": р["индекс"], "кошельков": len(р["кошельки"])}
                      for р in ряды],
               всего_транзакций=б.get("total"))
    return из_


def self_test() -> int:
    пройдено = провалено = 0

    def chk(что, ок, факт=""):
        nonlocal пройдено, провалено
        if ок:
            пройдено += 1
            print(f"  [ok  ] {что}")
        else:
            провалено += 1
            print(f"  [ПРОВАЛ] {что}: {факт}")

    МИНТ = "MintAAA"
    НАШ = "WalletOurs"

    def tx(подпись, пары, ошибка=None):
        """пары: [(кошелёк, до, после)] по этому минту."""
        pre = [{"mint": МИНТ, "owner": к, "uiTokenAmount": {"amount": str(д)}}
               for к, д, _ in пары]
        post = [{"mint": МИНТ, "owner": к, "uiTokenAmount": {"amount": str(п)}}
                for к, _, п in пары]
        return {"transaction": {"signatures": [подпись]},
                "meta": {"err": ошибка, "preTokenBalances": pre,
                          "postTokenBalances": post}}

    блок = {"transactions": [
        tx("A", [("ЧужойРаз", 0, 100)]),
        tx("B", [("ЧужойДва", 0, 50)], ошибка={"InstructionError": [0, "X"]}),
        tx("C", [(НАШ, 0, 900)]),
        tx("D", [("ЧужойТри", 0, 10)]),
        tx("E", [("ЧужойРаз", 100, 40)]),        # продажа -- не покупка
        tx("F", [("Источник", 0, 500)]),
    ], "total": 6}

    def узел(метод, параметры=None, **кв):
        assert метод == "getBlock", метод
        return {"transactions": блок["transactions"], "blockTime": 1}

    р = соседи(узел, слот=100, минт=МИНТ, свои={НАШ}, наша_подпись="C",
               источник="Источник", известные={"ЧужойТри"})
    chk("упавшая транзакция не считается покупкой",
        "ЧужойДва" not in р["кошельки"], р["кошельки"])
    chk("продажа не считается покупкой (тот же кошелёк уже был до нас)",
        р["кошельки"] == ["ЧужойРаз", "ЧужойТри"], р["кошельки"])
    chk("свой кошелёк и источник исключены",
        НАШ not in р["кошельки"] and "Источник" not in р["кошельки"])
    chk("наш индекс найден по подписи", р["наш_индекс"] == 2, р["наш_индекс"])
    chk("до нас -- только те, кто раньше по порядку блока",
        р["до_нас"] == 1 and р["всего"] == 2, (р["до_нас"], р["всего"]))
    chk("известные копировщики посчитаны по списку", р["известных"] == 1,
        р["известных"])

    р2 = соседи(узел, слот=100, минт=МИНТ, свои={НАШ}, наша_подпись="НЕТ",
                источник="Источник")
    chk("нашей транзакции в слоте нет -- успели все найденные",
        р2["до_нас"] == 2 and р2["наш_индекс"] is None,
        (р2["до_нас"], р2["наш_индекс"]))

    def молчит(метод, параметры=None, **кв):
        raise RuntimeError("узел молчит")

    р3 = соседи(молчит, слот=100, минт=МИНТ, свои={НАШ})
    chk("узел молчит -- known=False и причина словами",
        р3["known"] is False and "getBlock" in (р3["why_not"] or ""),
        р3["why_not"])
    print(f"самопроверка соседей по слоту: {пройдено}/{пройдено + провалено} пройдено")
    return 0 if провалено == 0 else 1


if __name__ == "__main__":
    import sys
    raise SystemExit(self_test() if "--self-test" in sys.argv else 0)
