def включён(группа: str | None = None) -> bool:
    """Чтение налога -- ПО ФЛАГУ, по умолчанию ВЫКЛЮЧЕНО.

    Список групп бьёт общий флаг, незнакомая группа -- выключено: то же правило,
    что у строителей типов пулов.
    """
    список = [г.strip() for г in (os.environ.get(ИМЯ_ФЛАГА_ГРУППЫ) or "")
              .replace(";", ",").split(",") if г.strip()]
    if список:
        return bool(группа) and группа in список
    return (os.environ.get(ИМЯ_ФЛАГА) or "").strip() == "1"


# ------------------------------------------------------- арифметика налога

def налог_с_суммы(сумма: int, bps: int | None, максимум: int | None) -> int:
    """Сам налог: min(ceil(сумма*bps/10000), максимум). Сверено 56 из 56."""
    if not bps:
        return 0
    if int(bps) >= BASIS_POINT_MAX:
        # Ставка в потолок -- перевод уходит в комиссию целиком. Это не ошибка
        # разбора, а настоящая настройка минта, и вести себя надо так же.
        плата = int(сумма)
    else:
        плата = -(-int(сумма) * int(bps) // BASIS_POINT_MAX)
    if максимум is not None:
        плата = min(плата, int(максимум))
    return max(0, плата)


def без_налога(сумма: int, bps: int | None, максимум: int | None) -> int:
    """Сколько дойдёт до получателя."""
    return max(0, int(сумма) - налог_с_суммы(сумма, bps, максимум))


def назван(налог) -> bool:
    """Налог назван ЧИСЛОМ: (bps, максимум). None и пустое -- не назван."""
    if not isinstance(налог, (tuple, list)) or not налог:
        return False
    try:
        return int(налог[0]) >= 0
    except (TypeError, ValueError):
        return False


# --------------------------------------------------- выбор ставки по эпохе

def ставка_на_эпоху(older: dict, newer: dict, эпоха: int | None) -> dict:
    """Какая из двух ставок в силе. Правило программы -- get_epoch_fee."""
    o_bps, o_max, o_ep = (older or {}).get("bps"), (older or {}).get("максимум"), (older or {}).get("эпоха")
    n_bps, n_max, n_ep = (newer or {}).get("bps"), (newer or {}).get("максимум"), (newer or {}).get("эпоха")
    if o_bps is None and n_bps is None:
        return {"ok": False, "why_not": "в расширении нет ни одной ставки"}
    if эпоха is not None and n_ep is not None:
        если_newer = int(эпоха) >= int(n_ep)
        и = (n_bps, n_max) if если_newer else (o_bps, o_max)
        return {"ok": True, "bps": и[0], "максимум": и[1], "эпоха_известна": True,
                "выбор": "newer" if если_newer else "older", "эпоха": int(эпоха)}
    # ЭПОХА НЕ НАЗВАНА. Совпали -- двусмысленности нет; разошлись -- берём ХУДШУЮ.
    if (o_bps, o_max) == (n_bps, n_max):
        return {"ok": True, "bps": n_bps, "максимум": n_max, "эпоха_известна": False,
                "выбор": "older=newer", "эпоха": None}
    хуже_newer = (n_bps or 0) >= (o_bps or 0)
    и = (n_bps, n_max) if хуже_newer else (o_bps, o_max)
    return {"ok": True, "bps": и[0], "максимум": и[1], "эпоха_известна": False,
            "выбор": "худшая из двух", "эпоха": None,
            "older": {"bps": o_bps, "максимум": o_max, "эпоха": o_ep},
            "newer": {"bps": n_bps, "максимум": n_max, "эпоха": n_ep}}


# ------------------------------------------- разбор ответа узла: два пути

def из_jsonparsed(значение: dict) -> dict:
    """Ставки из разобранного узлом минта. Узел владеет раскладкой, мы -- правилом.

    Имена полей -- из account-decoder (`UiTransferFeeConfig`):
    olderTransferFee / newerTransferFee, у каждой epoch, maximumFee,
    transferFeeBasisPoints.
    """
    из_ = {"ok": False, "why_not": None, "расширение_есть": False}
    данные = (значение or {}).get("data")
    разбор = данные.get("parsed") if isinstance(данные, dict) else None
    info = разбор.get("info") if isinstance(разбор, dict) else None
    if not isinstance(info, dict):
        из_["why_not"] = "узел не разобрал счёт минта (jsonParsed не дал info)"
        return из_
    из_["десятичных"] = info.get("decimals")
    for e in info.get("extensions") or []:
        if not isinstance(e, dict):
            continue
        if str(e.get("extension") or "").lower() != ИМЯ_РАСШИРЕНИЯ:
            continue
        st = e.get("state") or {}

        def одна(к):
            з = st.get(к) or {}
            if not isinstance(з, dict):
                return {}
            return {"bps": з.get("transferFeeBasisPoints"),
                    "максимум": з.get("maximumFee"), "эпоха": з.get("epoch")}

        из_.update(ok=True, расширение_есть=True, older=одна("olderTransferFee"),
                    newer=одна("newerTransferFee"))
        return из_
    # РАСШИРЕНИЯ НЕТ -- это факт: узел разобрал счёт и перечислил расширения.
    из_.update(ok=True, расширение_есть=False)
    return из_


def из_байтов(сырое: bytes) -> dict:
    """Ставки из СЫРЫХ байтов минта -- запасной путь, если узел не разбирает.

    Идём по TLV честно: после базового минта (82 байта) и байта типа счёта на
    месте 165 лежат записи (тип u16, длина u16, значение). Берём запись типа
    TransferFeeConfig и внутри неё ШАГ ЗАПИСИ ВЫБИРАЕМ ПО ЕЁ ДЛИНЕ, а не по
    памяти: 108 -- без выравнивания, 120 -- с ним. Длина не та -- отказ с
    названным числом, а не ставка наугад.
    """
    из_ = {"ok": False, "why_not": None, "расширение_есть": False}
    if not сырое or len(сырое) <= МЕСТО_ТИПА_СЧЁТА:
        из_["why_not"] = (f"счёт короче минта с расширениями "
                           f"({0 if not сырое else len(сырое)} байт)")
        return из_
    if сырое[МЕСТО_ТИПА_СЧЁТА] != ТИП_СЧЁТА_МИНТ:
        из_["why_not"] = (f"на месте {МЕСТО_ТИПА_СЧЁТА} тип счёта "
                           f"{сырое[МЕСТО_ТИПА_СЧЁТА]}, а у минта он "
                           f"{ТИП_СЧЁТА_МИНТ}")
        return из_
    i = МЕСТО_ТИПА_СЧЁТА + 1
    while i + 4 <= len(сырое):
        тип = int.from_bytes(сырое[i:i + 2], "little")
        длина = int.from_bytes(сырое[i + 2:i + 4], "little")
        тело_с = i + 4
        тело_по = тело_с + длина
        if тело_по > len(сырое):
            из_["why_not"] = (f"запись TLV типа {тип} длиной {длина} не влезает в "
                               f"счёт ({len(сырое)} байт)")
            return из_
        if тип == ТИП_РАСШИРЕНИЯ:
            if длина == ДЛИНА_TLV_БЕЗ_ВЫРАВНИВАНИЯ:
                шаг = 18
            elif длина == ДЛИНА_TLV_С_ВЫРАВНИВАНИЕМ:
                шаг = 24
            else:
                из_["why_not"] = (f"длина расширения {длина}, а по раскладке она "
                                   f"{ДЛИНА_TLV_БЕЗ_ВЫРАВНИВАНИЯ} или "
                                   f"{ДЛИНА_TLV_С_ВЫРАВНИВАНИЕМ} -- ставку наугад "
                                   f"не берём")
                return из_
            о = тело_с + 32 + 32 + 8

            def одна(с: int) -> dict:
                эп = int.from_bytes(сырое[с:с + 8], "little")
                мак = int.from_bytes(сырое[с + 8:с + 16], "little")
                bps = int.from_bytes(сырое[с + 16:с + 18], "little")
                return {"эпоха": эп, "максимум": мак, "bps": bps}

            older, newer = одна(о), одна(о + шаг)
            for имя, з in (("older", older), ("newer", newer)):
                if з["bps"] > BASIS_POINT_MAX:
                    из_["why_not"] = (f"{имя}: ставка {з['bps']} больше потолка "
                                       f"{BASIS_POINT_MAX} -- смещения не те")
                    return из_
            из_.update(ok=True, расширение_есть=True, older=older, newer=newer,
                        шаг_записи=шаг, длина_расширения=длина)
            return из_
        i = тело_по
        if длина == 0 and тип == 0:
            break
    из_.update(ok=True, расширение_есть=False)
    return из_


# ----------------------------------------------------------------- чтение

def _счёт(rpc_call, минт: str, *, разбором: bool = True) -> dict:
    """ОДИН getAccountInfo минта. Ничего больше здесь не спрашивается."""
    из_ = {"ok": False, "why_not": None, "мс": None, "значение": None, "slot": None}
    кодировка = "jsonParsed" if разбором else "base64"
    т0 = time.perf_counter()
    try:
        о = rpc_call("getAccountInfo", [минт, {"encoding": кодировка,
                                               "commitment": "confirmed"}])
    except Exception as exc:  # noqa: BLE001
        из_["why_not"] = f"{type(exc).__name__}: {str(exc)[:120]}"
        из_["мс"] = round((time.perf_counter() - т0) * 1000.0, 2)
        return из_
    из_["мс"] = round((time.perf_counter() - т0) * 1000.0, 2)
    о = о if isinstance(о, dict) else {}
    рез = о.get("result") if "result" in о else о
    if not isinstance(рез, dict):
        из_["why_not"] = f"ответ узла не разобран: {str(о)[:120]}"
        return из_
    из_["slot"] = ((рез.get("context") or {}).get("slot")
                    if isinstance(рез.get("context"), dict) else None)
    зн = рез.get("value")
    if not зн:
        из_["why_not"] = "счёта минта нет на цепи"
        return из_
    из_.update(ok=True, значение=зн)
    return из_


def налог(минт: str | None, программа_минта: str | None, *, rpc_call=None,
           эпоха: int | None = None, группа: str | None = None,
           кеш: dict | None = None) -> dict:
    """Ставка налога перевода этого минта. Одно чтение, и только когда нужно.

    Возвращает {ok, bps, максимум, чтений, откуда, эпоха_известна, выбор,
    why_not}. bps=0 -- налога НЕТ (факт). bps=None при ok=False -- НЕ ЗНАЕМ, и
    вызывающий обязан отказать, а не подставить ноль.
    """
    из_ = {"ok": False, "bps": None, "максимум": None, "чтений": 0,
            "откуда": None, "why_not": None, "минт": минт,
            "программа": программа_минта, "эпоха_известна": None}
    if not включён(группа):
        из_["why_not"] = f"чтение налога выключено флагом {ИМЯ_ФЛАГА}"
        return из_
    if not минт:
        из_["why_not"] = "минт не назван"
        return из_
    if кеш is not None and минт in кеш:
        о = dict(кеш[минт])
        о["из_кеша"] = True
        return о
    if программа_минта == ПРОГРАММА_SPL:
        # КЛАССИЧЕСКИЙ ТОКЕН: расширений не бывает, читать нечего и незачем.
        из_.update(ok=True, bps=0, максимум=None, чтений=0,
                    откуда="classic SPL -- расширений не бывает",
                    эпоха_известна=True)
        if кеш is not None:
            кеш[минт] = dict(из_)
        return из_
    if программа_минта != ПРОГРАММА_2022:
        из_["why_not"] = (f"{ПРИЗНАК_НЕ_ПРОЧИТАН}: программа минта "
                           f"{str(программа_минта)[:8]} не известна -- ни classic, "
                           f"ни Token-2022")
        return из_
    if rpc_call is None:
        из_["why_not"] = f"{ПРИЗНАК_НЕ_ПРОЧИТАН}: узел недоступен"
        return из_
    ч = _счёт(rpc_call, минт)
    из_["чтений"] = 1
    из_["мс_чтения"] = ч.get("мс")
    из_["slot"] = ч.get("slot")
    if not ч["ok"]:
        из_["why_not"] = f"{ПРИЗНАК_НЕ_ПРОЧИТАН}: {ч['why_not']}"
        return из_
    зн = ч["значение"]
    владелец = зн.get("owner")
    if владелец and владелец != ПРОГРАММА_2022:
        из_["why_not"] = (f"{ПРИЗНАК_НЕ_ПРОЧИТАН}: счёт принадлежит "
                           f"{str(владелец)[:8]}, а не Token-2022 -- это не тот минт")
        return из_
    р = из_jsonparsed(зн)
    из_["откуда"] = "jsonParsed"
    if not р.get("ok"):
        # УЗЕЛ НЕ РАЗОБРАЛ -- пробуем сами, по байтам того же ответа.
        сырое = _сырое_из(зн)
        if сырое is None:
            из_["why_not"] = f"{ПРИЗНАК_НЕ_ПРОЧИТАН}: {р.get('why_not')}"
            return из_
        р = из_байтов(сырое)
        из_["откуда"] = "байты (узел не разобрал)"
        if not р.get("ok"):
            из_["why_not"] = f"{ПРИЗНАК_НЕ_ПРОЧИТАН}: {р.get('why_not')}"
            return из_
    if not р.get("расширение_есть"):
        из_.update(ok=True, bps=0, максимум=None, эпоха_известна=True,
                    расширение_есть=False,
                    откуда=f"{из_['откуда']}: расширения комиссии у минта нет")
        if кеш is not None:
            кеш[минт] = dict(из_)
        return из_
    в = ставка_на_эпоху(р.get("older") or {}, р.get("newer") or {}, эпоха)
    if not в.get("ok"):
        из_["why_not"] = f"{ПРИЗНАК_НЕ_ПРОЧИТАН}: {в.get('why_not')}"
        return из_
    bps = в.get("bps")
    if bps is None or int(bps) < 0 or int(bps) > BASIS_POINT_MAX:
        из_["why_not"] = (f"{ПРИЗНАК_НЕ_ПРОЧИТАН}: ставка {bps!r} вне 0..{BASIS_POINT_MAX}")
        return из_
    из_.update(ok=True, bps=int(bps),
                максимум=(int(в["максимум"]) if в.get("максимум") is not None else None),
                эпоха_известна=в.get("эпоха_известна"), выбор=в.get("выбор"),
                расширение_есть=True, older=в.get("older"), newer=в.get("newer"))
    if кеш is not None:
        кеш[минт] = dict(из_)
    return из_


def _сырое_из(значение: dict):
    """Сырые байты счёта из ответа узла -- и при base64, и при jsonParsed-списке."""
    import base64  # noqa: PLC0415

    д = (значение or {}).get("data")
    if isinstance(д, list) and д and isinstance(д[0], str):
        try:
            return base64.b64decode(д[0])
        except Exception:  # noqa: BLE001
            return None
    if isinstance(д, str):
        try:
            return base64.b64decode(д)
        except Exception:  # noqa: BLE001
            return None
    return None


# ------------------------------------------- подпись под вызов из строителей

def fee_bps(минт: str | None, программа_минта: str | None, *, rpc_call=None,
             эпоха: int | None = None, группа: str | None = None,
             кеш: dict | None = None):
    """Пара (bps, максимум) -- РОВНО то, что строители ждут в `налог_выхода`.

    None означает «не знаю», и строитель на этом ОТКАЖЕТ (у него так и написано:
    сторона на Token-2022 без названного числом налога -- отказ). Ноль означает
    «налога нет» и приходит только как факт цепи.

    Зовётся так:
        нал = fee_bps(минт_базы, программа_базы, rpc_call=rpc_call, эпоха=эпоха)
        М.подготовить(..., налог_выхода=нал)
    """
    о = налог(минт, программа_минта, rpc_call=rpc_call, эпоха=эпоха,
               группа=группа, кеш=кеш)
    if not о.get("ok") or о.get("bps") is None:
        return None
    return (int(о["bps"]), о.get("максимум"))


def пара_для_строителя(о: dict):
    """Та же пара, но из уже готового ответа налог() -- без второго чтения."""
    if not isinstance(о, dict) or not о.get("ok") or о.get("bps") is None:
        return None
    return (int(о["bps"]), о.get("максимум"))


