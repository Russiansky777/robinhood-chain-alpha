    в2 = ставка_на_эпоху({"bps": 300, "максимум": 7, "эпоха": 1},
                         {"bps": 100, "максимум": 5, "эпоха": 20}, None)
    chk("худшая -- это БОЛЬШАЯ ставка, даже если она older",
        в2["bps"] == 300 and в2["максимум"] == 7, в2)
    в3 = ставка_на_эпоху(o, dict(o, эпоха=20), None)
