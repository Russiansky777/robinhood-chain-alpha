"""НАЛОГ ПЕРЕВОДА Token-2022 НА ГОРЯЧЕМ ПУТИ -- за флагом, по умолчанию выключен.

ЗАЧЕМ. Строители типов пулов (CLMM, Whirlpool, DBC, AMM v4) принимают налог
перевода параметром `налог_выхода=(bps, максимум)` и на стороне Token-2022 БЕЗ
названного числа честно ОТКАЗЫВАЮТ: молчаливый ноль завысил бы expected_out и
min_out, и покупка откатывалась бы на каждой попытке. Числа же взяться было
негде -- полоса читает налог своим кешем (`bloom_detector.налоги_минтов`), но
строителю его не передавали. Здесь эта дыра закрыта одной функцией.

СКОЛЬКО ЭТО СТОИТ СИГНАЛОВ -- ЗАМЕР, а не рассуждение. По сборам Code-2 база на
Token-2022 у **6 из 11** пулов CLMM против SOL и у **5 из 12** Whirlpool. Но
Token-2022 -- ЕЩЁ НЕ НАЛОГ: из тех же минтов, что нашлись в аудите цепи
(`data/solana_transfer_fee_audit.json`, 338 минтов, снят 23.09), расширение
комиссии есть лишь у части -- 7 из 8 известных оказались БЕЗ налога, то есть
отказ там стоил сигнала зря. Поэтому правильный ответ на «Token-2022» -- не
отказ и не ноль, а ЧТЕНИЕ.

ЧТО ДЕЛАЕТ ФУНКЦИЯ, РОВНО:
  * программа минта -- классический SPL Token: **ноль без чтения вовсе**. У
    classic-токена расширений не бывает, и круг до сети здесь был бы платой ни
    за что;
  * программа минта -- Token-2022: **ОДНО** `getAccountInfo` минта, и из него
    расширение `transferFeeConfig`: ставка bps и максимум **на текущую эпоху**;
  * расширения у минта нет: ноль, и это факт цепи, а не догадка;
  * прочитать не удалось (узел молчит, счёт не минт, разбор не сошёлся):
    **None и отказ**, а не ноль. Ноль здесь означал бы «налога нет», а мы
    этого не знаем.

ЭПОХА -- ЧАСТЬ ПРАВИЛА, А НЕ УКРАШЕНИЕ. В расширении лежат ДВЕ ставки, older и
newer, у каждой своя эпоха, и программа берёт `newer`, только если
`эпоха >= newer.epoch` (spl-token-2022, `get_epoch_fee`: «if epoch >=
self.newer_transfer_fee.epoch { &self.newer_transfer_fee } else {
&self.older_transfer_fee }»). Ставка МЕНЯЕТСЯ: у минта `PresTj4Yc2...` аудит
23.09 показывает 100 bps, а живые сделки сбора Code-2 за 28--29.09 дают 300 --
то есть взять не ту из двух вполне реально.

Эпоху функция НЕ ходит спрашивать (это был бы второй круг до сети, а владелец
сказал «одно getAccountInfo»). Правило такое:
  * эпоху назвали параметром -- берём по правилу программы;
  * не назвали, но older и newer совпадают -- двусмысленности нет;
  * не назвали и они разные -- берём ХУДШУЮ (большую ставку, и её же максимум) и
    помечаем `эпоха_известна=False`, `выбор="худшая из двух"`. Ошибиться в
    сторону меньшего налога значит завысить min_out и получить откат; в нашу --
    лишь недооценить выход.

ПРАВИЛО СЧЁТА СВЕРЕНО НА ЖИВЫХ СДЕЛКАХ: `налог = min(ceil(сумма * bps / 10000),
максимум)`. По событиям свопов сборов Code-2 -- **56 из 56** сделок с ненулевым
налогом сошлись до единицы. Попутно выяснилось, чем «сумма» считает каждая
программа, и это важно вызывающему: у CLMM `amount_N` события -- сумма ПОСЛЕ
налога (полная = amount + transfer_fee, сошлось 45 из 45), у Whirlpool
`input_amount`/`output_amount` -- ДО налога (сошлось 11 из 11).

ЧЕГО ЗДЕСЬ НЕТ. Своего кеша на процесс -- по желанию вызывающего (`кеш=`), чтобы
на горячем пути не появлялось скрытого состояния, которого не видно в замере.
Общий код полосы не правится: это отдельный модуль, и строители зовут его сами.

Проверка без денег и без сети: deploy/checks/nalog_2022.py.
"""

