#!/usr/bin/env python3
"""Разбирается ли тело каждого шага run: как скрипт оболочки (bash -n).

ЗАЧЕМ. 25.09 деплой детектора упал ТРИ раза подряд из-за кавычек в шаге:
  * прогоны 61 и 62 -- одна кавычка в комментарии ВНУТРИ аргумента ssh закрыла
    аргумент, и остаток скрипта выполнился локально под ghrunner, которому
    /etc/bloom-executor/env читать нельзя. Журнал при этом показывал правильные
    команды, хост был исправен, а правки env молча не происходили;
  * прогон 63 -- комментарий-предупреждение о той же беде сам её и повторил:
    двух кавычек (чётное число!) хватило, чтобы текст между ними стал
    локальным, а апостроф в нём открыл одинарную строку. bash сказал
    syntax error near unexpected token на строке 107 -- за девяносто строк от
    настоящей причины.

Проверка кавычек (check_workflow_quotes.py) ловит ЭТОТ класс по признакам.
Здесь -- проверка сильнее и тупее: тело шага отдаётся самому bash с ключом -n
(разобрать, не выполняя). Что bash не разберёт, то и не заработает. Все три
падения она видит сразу, и видит их ДО деплоя, а не после потраченных денег.

ЧТО ДЕЛАЕМ С ПОДСТАНОВКАМИ ПРОГОНА. Выражения вида ${{ inputs.x }} для оболочки
не текст, а дырка, куда GitHub подставит значение. Подставляем безобидное слово
SUBST -- ровно то, что сделает и GitHub, если значение простое. Это значит, что
проверка НЕ ловит поломку от самого значения входа (кавычка в значении), и это
честное ограничение: там нужна не проверка тела, а кавычки вокруг подстановки.

ЧЕГО НЕ ПРОВЕРЯЕМ. Шаги с run: в одну строку и с shell: python -- у первых
нечего ломать переносами, вторые не оболочка вовсе.
"""
from __future__ import annotations

import re
import subprocess
import sys
from pathlib import Path

КАТАЛОГ = ".github/workflows"
ПОДСТАНОВКА = re.compile(r"\$\{\{[^}]*\}\}")
НАЧАЛО = re.compile(r"^(\s*)run:\s*\|\s*$")


def тела_шагов(текст: str) -> list:
    """Список (строка_начала, тело) для каждого run: | в прогоне."""
    строки = текст.split("\n")
    из_ = []
    i = 0
    while i < len(строки):
        м = НАЧАЛО.match(строки[i])
        if not м:
            i += 1
            continue
        отступ = len(м.group(1))
        тело, j = [], i + 1
        while j < len(строки):
            с = строки[j]
            # Тело кончается на первой непустой строке с отступом не больше
            # самого ключа run: дальше уже следующий шаг или ключ YAML.
            if с.strip() and (len(с) - len(с.lstrip())) <= отступ:
                break
            тело.append(с[отступ + 2:] if len(с) > отступ else "")
            j += 1
        из_.append((i + 1, "\n".join(тело)))
        i = j
    return из_


def разобрать_телом(тело: str) -> str:
    """Пустая строка, если bash разбирает тело; иначе жалоба bash."""
    сценарий = ПОДСТАНОВКА.sub("SUBST", тело)
    п = subprocess.run(["bash", "-n"], input=сценарий,
                       capture_output=True, text=True)
    if п.returncode == 0:
        return ""
    жалоба = (п.stderr or "").strip().splitlines()
    return жалоба[0][:200] if жалоба else f"bash вернул {п.returncode}"


def проверить(каталог: str = КАТАЛОГ) -> dict:
    из_ = {"files": 0, "blocks": 0, "findings": []}
    д = Path(каталог)
    if not д.exists():
        д = Path("..") / каталог
    for ф in sorted(д.glob("*.yml")):
        из_["files"] += 1
        for строка, тело in тела_шагов(ф.read_text(encoding="utf-8")):
            из_["blocks"] += 1
            беда = разобрать_телом(тело)
            if беда:
                из_["findings"].append((ф.name, строка, беда))
    return из_


def self_test() -> int:
    проверки = []

    def chk(имя, ок, факт=""):
        проверки.append((имя, bool(ок), факт))

    # ТА САМАЯ поломка прогона 63: пара кавычек и апостроф в комментарии
    # внутри аргумента ssh.
    сломанный = """set -e
ssh -n $SSH_OPTS root@$HOST "
  set -a; . /etc/bloom-executor/env; set +a
  # Именно так упали прогоны 61 и 62 с
  # "sed: can't read /etc/bloom-executor/env: Permission denied" при
  # полностью исправном хосте.
  sed -i '/^BLOOM_POOL_SEND=/d' /etc/bloom-executor/env
"
if [ "1" = "1" ]; then echo да; fi
"""
    chk("поломка прогона 63 видна bash", разобрать_телом(сломанный) != "",
        разобрать_телом(сломанный))

    # Поломка прогонов 61 и 62: ОДНА кавычка в комментарии. Аргумент ssh
    # закрывается, остаток уезжает локально. bash разберёт это не всегда --
    # там, где остаток остаётся законным скриптом, ошибки синтаксиса нет
    # вовсе, и ловит такое только проверка кавычек. Здесь проверяем честно:
    # либо bash жалуется, либо кавычечная проверка находит.
    одна_кавычка = """ssh -n $SSH_OPTS root@$HOST "
  # комментарий с "кавычкой
  sed -i '/^X=/d' /etc/bloom-executor/env
"
"""
    сам_bash = разобрать_телом(одна_кавычка) != ""
    из_кавычек = []
    try:
        sys.path.insert(0, str(Path(__file__).resolve().parent))
        import check_workflow_quotes as К
        из_кавычек = К.разбор(одна_кавычка)
    except Exception as exc:  # noqa: BLE001
        из_кавычек = [("сбой импорта", 0, str(exc), "")]
    chk("поломка прогонов 61 и 62 видна хотя бы одной из двух проверок",
        сам_bash or из_кавычек, (сам_bash, из_кавычек))

    хороший = """set -e
ssh -n $SSH_OPTS root@$HOST "
  sed -i '/^BLOOM_POOL_SEND=/d' $ENV_DIR/env
  echo 'BLOOM_POOL_SEND=1' >> $ENV_DIR/env
"
OUT=$(ssh -n $SSH_OPTS root@$HOST "wc -l < $ENV_DIR/env") || { echo нет; exit 1; }
echo "строк: $OUT"
"""
    chk("законный шаг разбирается", разобрать_телом(хороший) == "",
        разобрать_телом(хороший))

    # Подстановка прогона не должна сама ломать разбор.
    с_подстановкой = 'echo "режим: ${{ inputs.mode }}"\nif [ "${{ inputs.live }}" = "1" ]; then echo живьём; fi\n'
    chk("подстановки прогона не ломают разбор",
        разобрать_телом(с_подстановкой) == "", разобрать_телом(с_подстановкой))

    # Границу тела шага находим правильно: следующий шаг в тело не попадает.
    прогон = """jobs:
  deploy:
    steps:
      - name: "Первый"
        run: |
          set -e
          echo один

      - name: "Второй"
        run: |
          echo два
"""
    тела = тела_шагов(прогон)
    chk("тела шагов найдены по отдельности", len(тела) == 2, тела)
    chk("следующий шаг в тело не попал",
        тела and "Второй" not in тела[0][1], тела[0][1] if тела else "")

    итог = проверить()
    chk("все шаги прогонов репозитория разбираются bash",
        итог["findings"] == [],
        [f"{ф}:{с} {ч}" for ф, с, ч in итог["findings"]][:5])
    chk("шаги вообще найдены", итог["blocks"] > 100, итог["blocks"])

    плохо = [(и, ф) for и, ок, ф in проверки if not ок]
    for имя, ок, факт in проверки:
        print(f"  [{'ok  ' if ок else 'СБОЙ'}] {имя}"
              + ("" if ок else f" -- факт: {факт}"))
    print(f"самопроверка разбора шагов: {len(проверки) - len(плохо)}/"
          f"{len(проверки)} пройдено")
    return 1 if плохо else 0


def main() -> int:
    if "--self-test" in sys.argv:
        return self_test()
    аргументы = [а for а in sys.argv[1:] if not а.startswith("-")]
    итог = проверить(аргументы[0] if аргументы else КАТАЛОГ)
    for файл, строка, беда in итог["findings"]:
        print(f"{файл}:{строка}: {беда}")
    if итог["findings"]:
        print(f"шаги прогонов: не разбираются {len(итог['findings'])} из "
              f"{итог['blocks']} (файлов {итог['files']})")
        return 1
    print(f"шаги прогонов: разобрано {итог['blocks']} тел run в "
           f"{итог['files']} файлах, все разбираются bash")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
