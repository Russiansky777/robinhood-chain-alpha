#!/usr/bin/env python3
"""Подбивка, контроль цены: новый прогон против сохранённого, ряд к ряду.

Сходиться обязана медиана (передача: 1.272 п.п. на 80 сверенных). Кроме
медианы здесь видно, КАКИЕ ряды разошлись: тот же cid, те же подписи -- число
обязано быть тем же, если узел отдал те же транзакции.
"""
from __future__ import annotations

import argparse
import json
import statistics
from pathlib import Path


def медиана_абс(ряды: list):
    абс = [abs(r["расхождение_пп"]) for r in ряды if r.get("расхождение_пп") is not None]
    return round(statistics.median(абс), 3) if абс else None


def main() -> int:
    р = argparse.ArgumentParser()
    р.add_argument("--bylo", default="data/podbivka/kontrol_ceny.json")
    р.add_argument("--stalo", required=True)
    р.add_argument("--out", required=True)
    а = р.parse_args()
    было = json.loads(Path(а.bylo).read_text(encoding="utf-8"))
    стало = json.loads(Path(а.stalo).read_text(encoding="utf-8"))
    б = {r["cid"]: r for r in было["ряды"]}
    с = {r["cid"]: r for r in стало["ряды"]}
    с_отказ = {r["cid"]: r for r in стало["отказы"]}
    те_же = [cid for cid in б if cid in с]
    разошлись = []
    for cid in те_же:
        x, y = б[cid]["расхождение_пп"], с[cid]["расхождение_пп"]
        if abs(x - y) > 0.001 or б[cid].get("сим_токенов") != с[cid].get("сим_токенов") \
                or б[cid].get("факт_токенов") != с[cid].get("факт_токенов"):
            разошлись.append({"cid": cid, "было_пп": x, "стало_пп": y,
                              "сим_было": б[cid].get("сим_токенов"), "сим_стало": с[cid].get("сим_токенов"),
                              "факт_было": б[cid].get("факт_токенов"),
                              "факт_стало": с[cid].get("факт_токенов")})
    выпали = [{"cid": cid, "why_not": (с_отказ.get(cid) or {}).get("why_not")}
              for cid in б if cid not in с]
    новые = [cid for cid in с if cid not in б]
    итог = {
        "было": {"на_входе": было["свод"]["сделок_на_входе"], "сверено": было["свод"]["сверено"],
                 "медиана_пп": было["свод"]["медиана_расхождения_пп"],
                 "p90_пп": было["свод"]["p90_расхождения_пп"]},
        "стало": {"на_входе": стало["свод"]["сделок_на_входе"], "сверено": стало["свод"]["сверено"],
                  "медиана_пп": стало["свод"]["медиана_расхождения_пп"],
                  "p90_пп": стало["свод"]["p90_расхождения_пп"],
                  "по_методу": стало["свод"]["по_методу"],
                  "причины_отказов": стало["свод"]["причины_отказов"]},
        "на_тех_же_рядах": {"рядов": len(те_же),
                            "медиана_стало_пп": медиана_абс([с[cid] for cid in те_же]),
                            "медиана_было_пп": медиана_абс([б[cid] for cid in те_же]),
                            "разошлось_рядов": len(разошлись)},
        "разошлись": разошлись,
        "выпали_из_сверенных": выпали,
        "новые_сверенные": новые,
    }
    Path(а.out).write_text(json.dumps(итог, ensure_ascii=False, indent=1), encoding="utf-8")
    print("контроль: было {}/{} медиана {} | стало {}/{} медиана {} p90 {} | те же ряды {} медиана {} разошлось {} выпало {} новых {}".format(
        итог["было"]["сверено"], итог["было"]["на_входе"], итог["было"]["медиана_пп"],
        итог["стало"]["сверено"], итог["стало"]["на_входе"], итог["стало"]["медиана_пп"],
        итог["стало"]["p90_пп"], len(те_же), итог["на_тех_же_рядах"]["медиана_стало_пп"],
        len(разошлись), len(выпали), len(новые)))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
