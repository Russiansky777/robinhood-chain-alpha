#!/usr/bin/env python3
"""Как вывозит голова: где САМ источник стоит в своём слоте и что было до него.

Нового чтения архива нет -- всё из кэша сигналов. У каждого сигнала лежит список `перед`
(до двадцати событий пула перед ним: кто, за сколько слотов до сигнала, на сколько SOL),
поэтому считается:

  * ВНИМАНИЕ: своего слота в `перед` НЕТ. Сборщик кладёт туда только события из слотов
    СТРОГО раньше сигнала (`1 <= s0 - блок <= перед_слотов`, подбивка_arhiv_den стр. 708),
    поэтому «сколько покупок токена было в слоте источника до него» по кэшу не считается
    вовсе, и вопрос «источник первый или в толпе» этим кэшем не решается. Нужен новый
    проход с `0 <=` вместо `1 <=` -- цена в выходе (`цена_отдельного_прохода`);
  * что было в S-1...S-3: число событий и самая крупная покупка (признак «кто-то взял от
    5 SOL раньше него»). Создание и переезд по `перед` НЕ видны: там нет типа события --
    только кто, за сколько слотов и сколько SOL, так и сказано в выходе;
  * плательщики головы очереди (их список даёт Code-1, data/golova_ocheredi.json): как
    часто они встречаются в `перед` тех же токенов -- то есть покупают раньше нашего
    источника. Доля их покупок в слотах, где источника нет вовсе, по кэшу сигналов не
    считается: кэш хранит окрестность сигнала, а не все слоты подряд -- это отдельный
    проход по архиву, и его цена названа в выходе.

Выход: data/podbivka/golova_ocheredi_mesto<метка>.json. Только чтение.
"""
from __future__ import annotations

import argparse
import collections
import json
import statistics
import sys
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import podbivka_istochniki_novyj as И  # noqa: E402
import podbivka_paket_obshee as O      # noqa: E402

П = O.П
КРУПНАЯ = 5.0          # SOL: «кто-то взял крупно раньше головы»
ЦЕНА_ПРОХОДА = {"что": ["место источника в его СВОЁМ слоте",
                        "доля покупок головы в слотах, где источника нет вовсе"],
                "правка": "podbivka_arhiv_den стр. 708: 1 <= s0_ - бл_ -> 0 <= s0_ - бл_",
                "нужен": "новый проход по тем суткам: кэш держит окрестность сигнала",
                "гб_на_сутки": 11.2, "минут_на_сутки": [95, 230], "мест_разом": 6,
                "на_19_суток_часов": [5, 12]}


def адреса_головы() -> set:
    """Список плательщиков головы от Code-1; вложенность не угадываем, ищем адреса."""
    for путь in (П.parent / "golova_ocheredi.json", П / "golova_ocheredi.json"):
        if путь.exists():
            д = json.loads(путь.read_text(encoding="utf-8"))
            найдено: set = set()

            def обойти(x):
                if isinstance(x, str) and 32 <= len(x) <= 44:
                    найдено.add(x)
                elif isinstance(x, dict):
                    for v in x.values():
                        обойти(v)
                elif isinstance(x, list):
                    for v in x:
                        обойти(v)
            обойти(д)
            return найдено
    return set()


def главное(а) -> int:
    набор = set()
    if а.nabor:
        набор = {x.strip() for x in Path(а.nabor).read_text(encoding="utf-8").split() if x.strip()}
    голова = адреса_головы()
    по_ист: dict = collections.defaultdict(lambda: {
        "сигналов": 0, "первый": 0, "до_него_в_слоте": [], "крупная_до_5": 0,
        "событий_S1_S3": [], "голова_в_перед": 0, "перед_пусто": 0})
    счёт: collections.Counter = collections.Counter()
    for р in O.сигналы():
        счёт["сигналов"] += 1
        if р.get("quoteMint") != O.WSOL or not р.get("первая"):
            continue
        if (р.get("sol") or 0) < И.ПОРОГ_ИСТОЧНИКА:
            continue
        ист = р.get("ист")
        if not ист:
            continue
        if набор and ист not in набор:
            continue
        счёт["годных"] += 1
        с = по_ист[ист]
        с["сигналов"] += 1
        перед = р.get("перед") or []
        if not перед:
            с["перед_пусто"] += 1
        # своего слота в перед нет (см. шапку) -- этот счёт оставлен как проверка:
        # если он когда-нибудь станет непустым, значит сборщик поменяли
        в_слоте = [e for e in перед if (e.get("слотов") or 0) == 0]
        с["до_него_в_слоте"].append(len(в_слоте))
        s1s3 = [e for e in перед if 1 <= (e.get("слотов") or 0) <= 3]
        с["событий_S1_S3"].append(len(s1s3))
        if any((e.get("sol") or 0) >= КРУПНАЯ for e in s1s3 + в_слоте):
            с["крупная_до_5"] += 1
        if голова and any(e.get("кто") in голова for e in перед):
            с["голова_в_перед"] += 1
    таб = []
    for ист, с in по_ист.items():
        if с["сигналов"] < а.min_signalov:
            continue
        дс = с["до_него_в_слоте"]
        таб.append({
            "источник": ист, "сигналов": с["сигналов"],
            "в_своём_слоте_кэш_не_знает": True,
            "событий_своего_слота_в_перед": sum(дс),
            "событий_S1_S3_медиана": (statistics.median(с["событий_S1_S3"])
                                      if с["событий_S1_S3"] else None),
            "доля_крупная_до_него": round(с["крупная_до_5"] / с["сигналов"], 3),
            "доля_голова_в_перед": (round(с["голова_в_перед"] / с["сигналов"], 3)
                                    if голова else None),
            "перед_пусто": с["перед_пусто"]})
    таб.sort(key=lambda x: -x["сигналов"])
    фраза = ("по этому кэшу нельзя сказать: своего слота в «перед» нет, "
             "нужен проход с 0 <= вместо 1 <=")
    тело = {"что": "где сам источник стоит в своём слоте и что было до него",
            "когда": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
            "крупная_sol": КРУПНАЯ, "адресов_головы": len(голова),
            "перед_не_несёт_типа_события": True,
            "создание_и_переезд_по_перед_не_видны": True,
            "цена_отдельного_прохода": ЦЕНА_ПРОХОДА,
            "счёт": dict(счёт), "фраза": фраза, "таблица": таб}
    вых = П / f"golova_ocheredi_mesto{а.metka}.json"
    вых.write_text(json.dumps(тело, ensure_ascii=False, indent=1), encoding="utf-8")
    import podbivka_run as R  # noqa: PLC0415
    R.записано(вых)
    print(f"источников {len(таб)}, адресов головы {len(голова)}; {фраза}", flush=True)
    for x in таб[:12]:
        print(f"  {x['источник'][:10]}… сигналов {x['сигналов']:5d}, "
              f"S-1..S-3 медиана "
              f"{x['событий_S1_S3_медиана']}, крупная до него "
              f"{x['доля_крупная_до_него']:.3f}, голова в перед "
              f"{x['доля_голова_в_перед']}", flush=True)
    return 0


def main() -> int:
    р = argparse.ArgumentParser()
    р.add_argument("--nabor", default="", help="файл со списком источников (через пробел)")
    р.add_argument("--min-signalov", type=int, default=50)
    р.add_argument("--metka", default="")
    return главное(р.parse_args())


if __name__ == "__main__":
    raise SystemExit(main())
