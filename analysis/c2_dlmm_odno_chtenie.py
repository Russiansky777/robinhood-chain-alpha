# Причины отказа, при которых ПРЕЖНИЙ путь в два чтения сработает, а этот нет.
# Их и только их имеет смысл откатывать: остальные (пул не тот, минт не тот,
# узел молчит) двухчтенийный путь встретит точно так же.
ОТКАТНЫЕ = (ПРИЗНАК_МАССИВ_СМЕНИЛСЯ, ПРИЗНАК_НЕ_ХВАТИЛО,
             "массивы из сделки источника не взялись")


def откатный(why_not) -> bool:
    """Стоит ли на этом отказе идти прежним путём в два чтения."""
    с = str(why_not or "")
    return any(п in с for п in ОТКАТНЫЕ)


def котировщик_для(tx_источника: dict, *, откат=None, группа: str | None = None):
    """Котировщик с ТОЧНО ТОЙ подписью, которую зовёт полоса, -- одним чтением.

    ЗАЧЕМ ИМЕННО ТАК. Полоса (bloom_own_send, ветка DLMM) уже принимает
    `котировщик` параметром и зовёт его
    `котировщик(пул=…, минт_базы=…, минт_котировки=…, лампорты=…,
    проскальзывание=…, rpc_call=…)` -- без транзакции источника. Транзакция у
    полосы в руках есть, но менять её вызов -- это правка общего кода, а мне её
    делать нельзя. Поэтому транзакция замыкается здесь, и полосе остаётся ОДНА
    строка: подставить этот котировщик вместо K.котировка.

    ОТКАТ. `откат` -- прежний двухчтенийный котировщик (K.котировка). Если путь
    одного чтения отказал ПО СВОЕЙ причине (активный массив сменился, свопу не
    хватило массивов, массивов в сделке нет), зовётся он, и сигнал не теряется:
    одно чтение уже сделано, но прежнему пути оно всё равно было нужно. На
    прочих отказах откат не зовётся -- они у обоих путей одинаковые, и второй
    круг чтений был бы платой ни за что.

    Флаг проверяется ЗДЕСЬ же: выключен -- сразу прежний путь (или отказ, если
    откат не дан). Так включение остаётся одним рубильником, а не двумя.
    """
    def _зов(**кв):
        if not включён(группа):
            if откат is not None:
                о = откат(**{к: з for к, з in кв.items() if к != "tx_источника"})
                о = о if isinstance(о, dict) else {}
                о["путь"] = f"{о.get('путь') or 'два чтения DLMM'} (одно чтение выключено)"
                return о
            return {"ok": False, "чтений": 0, "путь": "одно чтение DLMM",
                     "why_not": f"путь одного чтения выключен флагом {ИМЯ_ФЛАГА}"}
        о = котировка(tx_источника=tx_источника, **кв)
        if о.get("ok") or откат is None or not откатный(о.get("why_not")):
            return о
        было = о.get("why_not")
        чтений = int(о.get("чтений") or 0)
        в = откат(**{к: з for к, з in кв.items() if к != "tx_источника"})
        в = в if isinstance(в, dict) else {}
        в["чтений"] = чтений + int(в.get("чтений") or 0)
        в["откат_с_одного_чтения"] = было
        в["путь"] = f"одно чтение -> {в.get('путь') or 'два чтения DLMM'}"
        return в

    return _зов


def _назван(налог) -> bool:
    """Налог назван ЧИСЛОМ: (bps, максимум). Пустое и None -- не назван."""
    if not isinstance(налог, (tuple, list)) or not налог:
        return False
    try:
        return int(налог[0]) >= 0
    except (TypeError, ValueError):
        return False


