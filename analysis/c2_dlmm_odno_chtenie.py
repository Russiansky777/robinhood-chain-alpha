# ------------------------------------------- массивы корзин из сделки источника

def массивы_сделки(tx: dict, пул: str, *, окно: int | None = None) -> dict:
    """Адреса массивов корзин ЭТОГО пула, стоящие в транзакции источника.

    Окно индексов задаётся СОБЫТИЕМ его же свопа (start_bin_id / end_bin_id):
    свои корзины сделка назвала сама, а массивы -- это они, делённые на 70.
    Дальше перебор PDA по окну и пересечение со счетами транзакции: совпало --
    значит это ровно массив этого пула с этим индексом, подделать нельзя.
    """
    из_ = {"ok": False, "why_not": None, "адреса": [], "индексы": [],
            "событие": None, "мс": None}
    т0 = time.perf_counter()
    if not пул:
        из_["why_not"] = "адрес пула не назван"
        return из_
    try:
        Q = _порт()
    except Exception:  # noqa: BLE001
        из_["why_not"] = "переноса podbivka_dlmm_quote нет -- индексы массивов не вывести"
        return из_
    B = _кирпичи()
    события = [с for с in B.события_dlmm(tx) if с.get("пул") == пул]
    if not события:
        из_["why_not"] = "события свопа DLMM по этому пулу в транзакции нет"
        return из_
    # Роутер трогает пул по нескольку раз: берём КРАЙНИЕ корзины всех его свопов,
    # иначе окно не накроет массивы, которые в транзакции всё-таки стоят.
    корзины = []
    for с in события:
        корзины += [int(с["start_bin_id"]), int(с["end_bin_id"])]
    из_["событие"] = {"свопов": len(события), "корзины": [min(корзины), max(корзины)],
                       "swap_for_y": bool(события[0].get("swap_for_y"))}
    и_мин = Q.индекс_массива(min(корзины))
    и_макс = Q.индекс_массива(max(корзины))
    # Счета берём ИЗ ИНСТРУКЦИЙ ПРОГРАММЫ DLMM по этому пулу, а не из всей
    # транзакции: в транзакции роутера стоят и чужие пулы, и их массивы -- PDA у
    # них другого пула, но пересечение по всей транзакции всё равно шире нужного.
    счета = set()
    for их in B.all_instructions(tx):
        if (их.get("programId") or их.get("program")) != DLMM:
            continue
        сч = list(их.get("accounts") or [])
        if пул in сч:
            счета.update(сч)
    if not счета:
        из_["why_not"] = "инструкции DLMM по этому пулу в транзакции нет"
        return из_
    ок = int(окно if окно is not None else ОКНО_ИНДЕКСОВ)
    for и in range(и_мин - ок, и_макс + ок + 1):
        try:
            а = Q.адрес_массива(пул, и)
        except Exception:  # noqa: BLE001
            continue
        if а in счета:
            из_["индексы"].append(и)
            из_["адреса"].append(а)
    из_["мс"] = round((time.perf_counter() - т0) * 1000.0, 3)
    if not из_["адреса"]:
        из_["why_not"] = (f"в транзакции источника нет ни одного массива корзин этого "
                           f"пула (окно индексов {и_мин - ок}..{и_макс + ок})")
        return из_
    из_["ok"] = True
    return из_


# ----------------------------------------------------------------- чтение

def _счета(rpc_call, адреса: list, *, таймаут: float = 3.0) -> dict:
    """getMultipleAccounts ОДНИМ запросом: адрес -> сырые байты (или None)."""
    из_ = {"ok": False, "данные": {}, "why_not": None, "slot": None, "мс": None}
    т0 = time.perf_counter()
    try:
        о = rpc_call("getMultipleAccounts",
                      [адреса, {"encoding": "base64", "commitment": "confirmed"}])
    except Exception as exc:  # noqa: BLE001
        из_["why_not"] = f"{type(exc).__name__}: {str(exc)[:120]}"
        из_["мс"] = round((time.perf_counter() - т0) * 1000.0, 2)
        return из_
    из_["мс"] = round((time.perf_counter() - т0) * 1000.0, 2)
    о = о if isinstance(о, dict) else {}
    рез = о.get("result") if "result" in о else о
    if not isinstance(рез, dict):
        из_["why_not"] = f"ответ узла не разобран: {str(о)[:120]}"
        return из_
    из_["slot"] = ((рез.get("context") or {}).get("slot")
                    if isinstance(рез.get("context"), dict) else None)
    значения = рез.get("value")
    if not isinstance(значения, list) or len(значения) != len(адреса):
        из_["why_not"] = "узел вернул не столько счетов, сколько спрашивали"
        return из_
    import base64  # noqa: PLC0415

    for адрес, зн in zip(адреса, значения):
        if not зн:
            из_["данные"][адрес] = None
            continue
        д = (зн.get("data") or [None, None])[0]
        try:
            из_["данные"][адрес] = base64.b64decode(д) if д else None
        except Exception:  # noqa: BLE001
            из_["данные"][адрес] = None
    из_["ok"] = True
    return из_


def не_та_котировка(минт_котировки: str, сторона_x: str, сторона_y: str) -> str:
    """Строка отказа «котировка пула не SOL» -- ТА ЖЕ, что ищет полоса подстрокой."""
    return (f"{ПРИЗНАК_КОТИРОВКИ_НЕ_SOL}: стороны пула "
            f"{str(сторона_x)[:8]}/{str(сторона_y)[:8]}, а просили "
            f"{str(минт_котировки)[:8]}")


# --------------------------------------------------------------- котировка

def котировка(*, пул: str, минт_базы: str, минт_котировки: str, лампорты: int,
               проскальзывание: float, rpc_call, tx_источника: dict,
               сейчас: float | None = None, налог_выхода=None, налог_входа=None,
               окно: int | None = None) -> dict:
    """Минимум выхода DLMM ОДНИМ чтением. Вид ответа -- как у двухчтенийного пути.

    Отличия в ответе: чтений всегда 1, есть массивы_индексы/массивы_адреса (они
    же -- места хвоста нашей инструкции) и активный_массив_совпал.
    """
    из_ = {"ok": False, "why_not": None, "чтений": 0, "путь": "одно чтение DLMM",
            "точная": True}
    if лампорты <= 0:
        из_["why_not"] = "сумма входа не положительна"
        return из_
    try:
        Q = _порт()
    except Exception as exc:  # noqa: BLE001
        из_["why_not"] = f"модуль котировки DLMM не загружен: {type(exc).__name__}"
        return из_

    м = массивы_сделки(tx_источника, пул, окно=окно)
    из_["массивы_из_сделки"] = {"ok": м["ok"], "индексы": м["индексы"],
                                 "мс": м.get("мс"), "событие": м.get("событие")}
    if not м["ok"]:
        из_["why_not"] = f"массивы из сделки источника не взялись: {м['why_not']}"
        return из_
    из_["массивы_адреса"] = list(м["адреса"])
    из_["массивы_индексы"] = list(м["индексы"])

    расширение = Q.адрес_расширения(пул)
    ч = _счета(rpc_call, [пул, расширение] + list(м["адреса"]))
    из_["чтений"] = 1
    из_["мс_чтений_всего"] = ч.get("мс")
    из_["slot"] = ч.get("slot")
    if not ч["ok"]:
        из_["why_not"] = f"состояние не прочитано: {ч['why_not']}"
        return из_
    данные_пула = ч["данные"].get(пул)
    if not данные_пула:
        из_["why_not"] = "счёта пула нет на цепи"
        return из_
    try:
        lb = Q.разобрать_пул(данные_пула)
    except Exception as exc:  # noqa: BLE001
        из_["why_not"] = f"пул не разобрался: {type(exc).__name__}: {str(exc)[:120]}"
        return из_
    ext = None
    д_ext = ч["данные"].get(расширение)
    if д_ext:
        try:
            ext = Q.разобрать_расширение(д_ext)
        except Exception:  # noqa: BLE001
            ext = None

    if lb.get("token_x_mint") == минт_котировки:
        swap_for_y = True
    elif lb.get("token_y_mint") == минт_котировки:
        swap_for_y = False
    else:
        из_["why_not"] = не_та_котировка(минт_котировки, lb.get("token_x_mint"),
                                          lb.get("token_y_mint"))
        return из_
    # МИНТ БАЗЫ ИЗ СИГНАЛА ОБЯЗАН БЫТЬ ВТОРОЙ СТОРОНОЙ ЭТОГО ПУЛА, иначе полоса
    # запишет позицию по одному токену, а купит другой.
    база_пула = lb.get("token_y_mint") if swap_for_y else lb.get("token_x_mint")
    if минт_базы and минт_базы != база_пула:
        из_["why_not"] = (f"минт сигнала {str(минт_базы)[:8]} не база этого пула "
                           f"({str(база_пула)[:8]}) -- купили бы не тот токен")
        return из_
    из_.update(swap_for_y=swap_for_y, bin_step=lb.get("bin_step"),
                active_id=lb.get("active_id"))

    # --- ПРОВЕРКА 1: АКТИВНЫЙ МАССИВ СРЕДИ ПРОЧИТАННЫХ.
    активный = Q.индекс_массива(int(lb["active_id"]))
    из_["активный_массив"] = активный
    из_["активный_массив_совпал"] = активный in м["индексы"]
    if not из_["активный_массив_совпал"]:
        из_["why_not"] = (f"{ПРИЗНАК_МАССИВ_СМЕНИЛСЯ}: сейчас {активный}, а в сделке "
                           f"источника {м['индексы']} -- цена считалась бы по чужим "
                           f"корзинам, нужен прежний путь в два чтения")
        return из_

    массивы = {}
    не_прочитаны = []
    for и, адрес in zip(м["индексы"], м["адреса"]):
        д = ч["данные"].get(адрес)
        if not д:
            не_прочитаны.append(и)
            continue
        try:
            ba = Q.разобрать_массив(д)
        except Exception:  # noqa: BLE001
            не_прочитаны.append(и)
            continue
        массивы[ba["index"]] = ba
    из_["массивов"] = len(массивы)
    из_["массивы_не_прочитаны"] = не_прочитаны
    if активный not in массивы:
        из_["why_not"] = (f"{ПРИЗНАК_МАССИВ_СМЕНИЛСЯ}: массив активной корзины "
                           f"{активный} на цепи не прочитан ({не_прочитаны})")
        return из_

    ts = int(сейчас if сейчас is not None else time.time())
    нв = Q.налог_2022(*налог_входа) if _назван(налог_входа) else None
    нвых = Q.налог_2022(*налог_выхода) if _назван(налог_выхода) else None
    из_["налог_применён"] = {"вход": bool(нв), "выход": bool(нвых)}
    try:
        q = Q.котировка_точный_вход(lb, пул, int(лампорты), swap_for_y, массивы, ts,
                                     ext, налог_вход=нв, налог_выход=нвых)
    except Exception as exc:  # noqa: BLE001
        текст = str(exc)[:140]
        # --- ПРОВЕРКА 2: СВОП ВЫШЕЛ ЗА ПРОЧИТАННОЕ. Перенос называет индекс.
        if "нет массива корзин" in текст:
            из_["why_not"] = (f"{ПРИЗНАК_НЕ_ХВАТИЛО}: {текст} -- вход больше, чем "
                               f"покрывают массивы источника, нужен прежний путь")
        else:
            из_["why_not"] = f"котировка не посчиталась: {type(exc).__name__}: {текст}"
        return из_
    ожидаем = int(q.get("amount_out") or 0)
    if ожидаем <= 0:
        из_["why_not"] = "котировка дала ноль на выходе"
        return из_
    мин = int(ожидаем * (1.0 - float(проскальзывание)))
    if мин <= 0:
        из_["why_not"] = "минимум выхода не положителен при этом проскальзывании"
        return из_
    из_.update(ok=True, expected_out=ожидаем, min_out=мин, fee=q.get("fee"),
                protocol_fee=q.get("protocol_fee"), корзин=q.get("корзин"),
                active_id_после=q.get("active_id_после"))
    return из_


# ------------------------------------------- дверь для полосы: тот же котировщик

# Причины отказа, при которых ПРЕЖНИЙ путь в два чтения сработает, а этот нет.
# Их и только их имеет смысл откатывать: остальные (пул не тот, минт не тот,
# узел молчит) двухчтенийный путь встретит точно так же.
ОТКАТНЫЕ = (ПРИЗНАК_МАССИВ_СМЕНИЛСЯ, ПРИЗНАК_НЕ_ХВАТИЛО,
             "массивы из сделки источника не взялись")


def откатный(why_not) -> bool:
    """Стоит ли на этом отказе идти прежним путём в два чтения."""
    с = str(why_not or "")
    return any(п in с for п in ОТКАТНЫЕ)


def котировщик_для(tx_источника: dict, *, откат=None, группа: str | None = None):
    """Котировщик с ТОЧНО ТОЙ подписью, которую зовёт полоса, -- одним чтением.

    ЗАЧЕМ ИМЕННО ТАК. Полоса (bloom_own_send, ветка DLMM) уже принимает
    `котировщик` параметром и зовёт его
    `котировщик(пул=…, минт_базы=…, минт_котировки=…, лампорты=…,
    проскальзывание=…, rpc_call=…)` -- без транзакции источника. Транзакция у
    полосы в руках есть, но менять её вызов -- это правка общего кода, а мне её
    делать нельзя. Поэтому транзакция замыкается здесь, и полосе остаётся ОДНА
    строка: подставить этот котировщик вместо K.котировка.

    ОТКАТ. `откат` -- прежний двухчтенийный котировщик (K.котировка). Если путь
    одного чтения отказал ПО СВОЕЙ причине (активный массив сменился, свопу не
    хватило массивов, массивов в сделке нет), зовётся он, и сигнал не теряется:
    одно чтение уже сделано, но прежнему пути оно всё равно было нужно. На
    прочих отказах откат не зовётся -- они у обоих путей одинаковые, и второй
    круг чтений был бы платой ни за что.

    Флаг проверяется ЗДЕСЬ же: выключен -- сразу прежний путь (или отказ, если
    откат не дан). Так включение остаётся одним рубильником, а не двумя.
    """
    def _зов(**кв):
        if not включён(группа):
            if откат is not None:
                о = откат(**{к: з for к, з in кв.items() if к != "tx_источника"})
                о = о if isinstance(о, dict) else {}
                о["путь"] = f"{о.get('путь') or 'два чтения DLMM'} (одно чтение выключено)"
                return о
            return {"ok": False, "чтений": 0, "путь": "одно чтение DLMM",
                     "why_not": f"путь одного чтения выключен флагом {ИМЯ_ФЛАГА}"}
        о = котировка(tx_источника=tx_источника, **кв)
        if о.get("ok") or откат is None or not откатный(о.get("why_not")):
            return о
        было = о.get("why_not")
        чтений = int(о.get("чтений") or 0)
        в = откат(**{к: з for к, з in кв.items() if к != "tx_источника"})
        в = в if isinstance(в, dict) else {}
        в["чтений"] = чтений + int(в.get("чтений") or 0)
        в["откат_с_одного_чтения"] = было
        в["путь"] = f"одно чтение -> {в.get('путь') or 'два чтения DLMM'}"
        return в

    return _зов


def _назван(налог) -> bool:
    """Налог назван ЧИСЛОМ: (bps, максимум). Пустое и None -- не назван."""
    if not isinstance(налог, (tuple, list)) or not налог:
        return False
    try:
        return int(налог[0]) >= 0
    except (TypeError, ValueError):
        return False


# ------------------------------------------------------------- самопроверка

def self_test() -> int:
    пройдено = провалено = пропущено = 0

    def chk(что, ок, факт=None):
        nonlocal пройдено, провалено
        print(f"  [{'ok  ' if ок else 'ПРОВАЛ'}] {что}"
              + (f" -> {факт!r}" if факт is not None and not ок else ""))
        пройдено += bool(ок)
        провалено += (not ок)

    def проп(что, почему):
        nonlocal пропущено
        пропущено += 1
        print(f"  [проп ] {что}: {почему}")

    было = os.environ.pop(ИМЯ_ФЛАГА, None)
    было_гр = os.environ.pop(ИМЯ_ФЛАГА_ГРУППЫ, None)
    chk("по умолчанию путь одного чтения ВЫКЛЮЧЕН", включён() is False)
    os.environ[ИМЯ_ФЛАГА] = "1"
    chk("флаг 1 включает", включён() is True)
    os.environ[ИМЯ_ФЛАГА_ГРУППЫ] = "lane_s0"
    chk("список групп бьёт общий флаг: своя группа включена",
        включён("lane_s0") is True)
    chk("список групп бьёт общий флаг: чужая группа выключена",
        включён("batch5") is False)
    chk("список групп бьёт общий флаг: без группы выключено", включён() is False)
    os.environ.pop(ИМЯ_ФЛАГА_ГРУППЫ, None)
    os.environ.pop(ИМЯ_ФЛАГА, None)
    if было is not None:
        os.environ[ИМЯ_ФЛАГА] = было
    if было_гр is not None:
        os.environ[ИМЯ_ФЛАГА_ГРУППЫ] = было_гр

    def _молчит(метод, параметры):
        raise OSError("сети нет")

    р = котировка(пул="1" * 32, минт_базы="A" * 32, минт_котировки=WSOL, лампорты=0,
                   проскальзывание=0.2, rpc_call=_молчит, tx_источника={})
    chk("нулевой вход -- отказ раньше всего",
        р["ok"] is False and "не положительна" in (р["why_not"] or ""))

    chk("налог назван числом только парой (bps, максимум)",
        _назван((100, None)) and _назван([0, 5]) and not _назван(None)
        and not _назван(()) and not _назван("100"))

    if not порт_есть():
        проп("массивы из сделки и отказы по состоянию",
             "нет podbivka_dlmm_quote (перенос кода DLMM, ветка Code-2)")
        print(f"самопроверка одного чтения DLMM: {пройдено}/{пройдено + провалено}"
              f" пройдено (пропущено {пропущено} -- нет переноса Code-2)")
        return 0 if провалено == 0 else 1

    Q = _порт()
    chk("индекс массива у отрицательных корзин округляется ВНИЗ (как div_rem)",
        (Q.индекс_массива(-1), Q.индекс_массива(-70), Q.индекс_массива(-71),
         Q.индекс_массива(0), Q.индекс_массива(69), Q.индекс_массива(70))
        == (-1, -1, -2, 0, 0, 1))

    # --- НА ЖИВЫХ СДЕЛКАХ: массивы находятся и это ИМЕННО массивы этого пула.
    import json  # noqa: PLC0415

    путь = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
                        "data", "c2_pool_samples", f"{DLMM}.json")
    if not os.path.exists(путь):
        проп("живые сделки", f"нет файла {путь}")
    else:
        with open(путь, encoding="utf-8") as ф:
            образцы = json.load(ф)
        B = _кирпичи()
        всего = нашли = свои_корзины = 0
        for о in образцы:
            tx = о.get("tx") or {}
            for с in B.события_dlmm(tx):
                всего += 1
                м = массивы_сделки(tx, с["пул"])
                if not м["ok"]:
                    continue
                нашли += 1
                # Корзины САМОГО источника обязаны лежать в найденных массивах:
                # иначе найдено не то.
                свои = {Q.индекс_массива(int(с["start_bin_id"])),
                        Q.индекс_массива(int(с["end_bin_id"]))}
                if свои <= set(м["индексы"]):
                    свои_корзины += 1
                # Найденный адрес обязан быть PDA массива ЭТОГО пула.
                assert all(а == Q.адрес_массива(с["пул"], и)
                           for и, а in zip(м["индексы"], м["адреса"]))
        chk(f"массивы нашлись у всех живых свопов ({нашли} из {всего})",
            всего > 0 and нашли == всего, {"всего": всего, "нашли": нашли})
        chk(f"корзины самого источника лежат в найденных массивах "
            f"({свои_корзины} из {всего})",
            всего > 0 and свои_корзины == всего,
            {"всего": всего, "свои": свои_корзины})

        # --- ОТКАЗЫ ПО СОСТОЯНИЮ: узел молчит и счёта пула нет.
        о = образцы[0]
        tx = о.get("tx") or {}
        с = B.события_dlmm(tx)[0]
        р = котировка(пул=с["пул"], минт_базы="A" * 32, минт_котировки=WSOL,
                       лампорты=10_000_000, проскальзывание=0.2, rpc_call=_молчит,
                       tx_источника=tx)
        chk("узел молчит -- отказ без минимума и ровно после одного чтения",
            р["ok"] is False and "состояние не прочитано" in (р["why_not"] or "")
            and р["чтений"] == 1 and "min_out" not in р, р)

        def _пусто(метод, параметры):
            return {"result": {"context": {"slot": 7},
                               "value": [None for _ in параметры[0]]}}

        р2 = котировка(пул=с["пул"], минт_базы="A" * 32, минт_котировки=WSOL,
                        лампорты=10_000_000, проскальзывание=0.2, rpc_call=_пусто,
                        tx_источника=tx)
        chk("счёта пула нет -- отказ, минимум не выдумывается",
            р2["ok"] is False and "нет на цепи" in (р2["why_not"] or "")
            and "min_out" not in р2, р2)

        # ЧИТАЕМ РОВНО ОДИН РАЗ И РОВНО ТО, ЧТО НУЖНО.
        спрошено = []

        def _счётчик(метод, параметры):
            спрошено.append((метод, list(параметры[0])))
            return {"result": {"context": {"slot": 7},
                               "value": [None for _ in параметры[0]]}}

        котировка(пул=с["пул"], минт_базы="A" * 32, минт_котировки=WSOL,
                   лампорты=10_000_000, проскальзывание=0.2, rpc_call=_счётчик,
                   tx_источника=tx)
        м = массивы_сделки(tx, с["пул"])
        chk("запрос к узлу РОВНО ОДИН", len(спрошено) == 1, спрошено)
        chk("спрошен только getMultipleAccounts",
            all(м_ == "getMultipleAccounts" for м_, _ in спрошено), спрошено)
        chk("в запросе пул, расширение и все массивы сделки -- и ничего лишнего",
            спрошено and спрошено[0][1] ==
            [с["пул"], Q.адрес_расширения(с["пул"])] + list(м["адреса"]),
            спрошено[0][1] if спрошено else None)

        # МАССИВОВ В СДЕЛКЕ НЕТ -- ОТКАЗ ДО ЧТЕНИЯ, а не пустой запрос.
        пустая = {"meta": {"innerInstructions": []},
                   "transaction": {"message": {"instructions": []}}}
        р3 = котировка(пул=с["пул"], минт_базы="A" * 32, минт_котировки=WSOL,
                        лампорты=10_000_000, проскальзывание=0.2, rpc_call=_молчит,
                        tx_источника=пустая)
        chk("сделки источника нет -- отказ ДО чтения",
            р3["ok"] is False and р3["чтений"] == 0
            and "не взялись" in (р3["why_not"] or ""), р3)

        # --- ДВЕРЬ ДЛЯ ПОЛОСЫ: подпись, откат и флаг.
        зовы = []

        def _прежний(**кв):
            зовы.append(sorted(кв))
            return {"ok": True, "min_out": 777, "expected_out": 1000, "чтений": 2,
                     "путь": "точная котировка DLMM"}

        имена = dict(пул=с["пул"], минт_базы="A" * 32, минт_котировки=WSOL,
                     лампорты=10_000_000, проскальзывание=0.2, rpc_call=_молчит)
        было_ф = os.environ.pop(ИМЯ_ФЛАГА, None)
        о = котировщик_для(tx, откат=_прежний)(**имена)
        chk("флаг выключен -- сразу прежний путь, и это сказано в ответе",
            о.get("ok") and "выключено" in (о.get("путь") or ""), о)
        os.environ[ИМЯ_ФЛАГА] = "1"
        о2 = котировщик_для(tx, откат=_прежний)(**имена)
        chk("узел молчит -- откат НЕ зовётся: прежнему пути он молчит так же",
            о2.get("ok") is False and "откат_с_одного_чтения" not in о2, о2)
        о3 = котировщик_для({}, откат=_прежний)(**имена)
        chk("массивов в сделке нет -- откат зовётся и чтения складываются",
            о3.get("ok") and о3.get("чтений") == 2
            and "одно чтение ->" in (о3.get("путь") or "")
            and "не взялись" in (о3.get("откат_с_одного_чтения") or ""), о3)
        chk("подпись прежнего котировщика не тронута (tx внутрь не просочился)",
            зовы and all("tx_источника" not in з for з in зовы), зовы)
        о4 = котировщик_для({})(**имена)
        chk("без отката отказ остаётся отказом, а не тихим успехом",
            о4.get("ok") is False, о4)
        os.environ.pop(ИМЯ_ФЛАГА, None)
        if было_ф is not None:
            os.environ[ИМЯ_ФЛАГА] = было_ф
        chk("откатными считаются только свои причины",
            откатный(f"x {ПРИЗНАК_МАССИВ_СМЕНИЛСЯ} y")
            and откатный(ПРИЗНАК_НЕ_ХВАТИЛО)
            and not откатный("счёта пула нет на цепи")
            and not откатный(None))

    хвост = (f" (пропущено {пропущено})" if пропущено else "")
    print(f"самопроверка одного чтения DLMM: {пройдено}/{пройдено + провалено}"
          f" пройдено{хвост}")
    return 0 if провалено == 0 else 1


if __name__ == "__main__":
    raise SystemExit(self_test() if "--self-test" in sys.argv else 0)
