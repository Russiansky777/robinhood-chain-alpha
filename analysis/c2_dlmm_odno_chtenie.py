def main() -> int:
    if "--self-test" in sys.argv:
        return self_test()
    if "--zamer" in sys.argv:
        i = sys.argv.index("--zamer")
        путь = (sys.argv[i + 1] if len(sys.argv) > i + 1
                and not sys.argv[i + 1].startswith("--") else None)
        д = {"что": ("DLMM одним чтением: покрытие массивов корзин на живых "
                     "сделках репозитория. Ни одного обращения к сети."),
             "запас_массивов": ЗАПАС_МАССИВОВ,
             "источник_адресов_умолчанием": ИСТОЧНИК_АДРЕСОВ,
             "покрытие": zamer_pokrytiya(), "отставание": zamer_sdviga()}
        # Строки замеров в выгрузку не кладутся целиком: в них лежат транзакции.
        for ключ in ("покрытие", "отставание"):
            д[ключ] = {к: v for к, v in д[ключ].items() if к != "строки"}
        текст = json.dumps(д, ensure_ascii=False, indent=1) + "\n"
        if путь:
            Path(путь).parent.mkdir(parents=True, exist_ok=True)
            Path(путь).write_text(текст, encoding="utf-8")
            print(f"записано: {путь}")
        else:
            print(текст)
        return 0
    print(__doc__.splitlines()[0])
    print("  --self-test   самопроверка (без сети)")
    print("  --zamer [файл] замер покрытия на живых сделках (без сети)")
    return 0


