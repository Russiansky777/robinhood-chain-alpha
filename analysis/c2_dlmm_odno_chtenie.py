"""DLMM: ОДНО чтение вместо двух -- массивы корзин берём из сделки источника.

ЗАЧЕМ. Нынешняя точная котировка DLMM (analysis/c2_dlmm_tochnaya_kotirovka.py)
стоит ДВУХ getMultipleAccounts ПОДРЯД, и второй нельзя начать раньше первого:

    чтение 1: [пул, расширение битовой карты]  -> active_id, направление
    чтение 2: [пул] + адреса массивов корзин   -> сами корзины (и пул из того же слота)

Адреса массивов нельзя назвать до чтения 1, потому что они PDA от индекса, а
индекс -- от активной корзины. Отсюда две задержки сети подряд на горячем пути.

ЧТО ЗДЕСЬ. Адреса массивов берутся НЕ из состояния, а ИЗ САМОЙ СДЕЛКИ ИСТОЧНИКА:
у DLMM массивы корзин стоят в списке счетов его инструкции. Тогда всё состояние
спрашивается ОДНИМ запросом:

    чтение 1: [пул, расширение] + массивы из сделки источника   -> и цена

ОСНОВАНИЕ -- ЗАМЕР, А НЕ ДОГАДКА. Code-2, docs/podbivka_2026-09-29_dlmm_pokrytie.md
(40 покупок источников в DLMM за 28--29.09): активная корзина через 1, 2 и 3
слота лежит в массивах из транзакции источника у **40 из 40**, активный массив
не сменился ни разу; массивов в транзакции 1 у 21 сделки, 2 у 7, 3 у 10, 4 у 2.

И РОВНО ТАМ ЖЕ -- ПРЕДЕЛ, КОТОРЫЙ ЭТОТ МОДУЛЬ ОБЯЗАН УВАЖАТЬ. Замер Code-1
(c2_swap_build.шаблон_с_нынешними_массивами, 29.09, 10 живых покупок) говорит
другое: у 6 из 10 в шаблоне НЕ ОСТАЛОСЬ ни одного нужного адреса, сдвиги
-8..+3. Противоречия нет -- меряли разное: Code-2 брал строго 1--3 слота и
только АКТИВНУЮ корзину, Code-1 -- весь набор массивов, которые котировке нужны
(активный плюс запас по ходу свопа), и на своём, большем, отставании. Значит
«массивы источника подходят» -- утверждение о МАЛОМ отставании и МАЛОМ свопе, и
проверять его надо на каждом сигнале, а не принимать на веру.

Поэтому путь отказывает, а не гадает, в двух местах, и оба проверяются по тому
же одному чтению:

  1. АКТИВНЫЙ МАССИВ. Прочитав пул, знаем active_id точно. Если индекс его
     массива не среди прочитанных -- отказ: отставание оказалось больше, чем
     мерил Code-2, и цена считалась бы по чужим корзинам.
  2. СВОП ВЫШЕЛ ЗА ПРОЧИТАННОЕ. Перенос Code-2 (podbivka_dlmm_quote) на нехватке
     массива поднимает ОшибкаDLMM с его индексом -- ловим и отказываем, а не
     дорисовываем ликвидность.

Отказ здесь дёшев: одно чтение уже сделано, и вызывающий волен пойти прежним
двухчтенийным путём -- он ничего не потерял, кроме этого чтения, которое ему
всё равно было нужно.

ЧЕГО МОДУЛЬ НЕ ДЕЛАЕТ. Не правит общие модули полосы (сборку, сторожа, детектор,
гейт) -- он отдельный и за своим флагом BLOOM_DLMM_ODNO_CHTENIE, по умолчанию
ВЫКЛЮЧЕН. Не подписывает и не отправляет. Не меняет правила налога перевода:
как и у нынешней точной котировки DLMM, налог принимается параметром и
применяется, если назван, -- своей политики отказа здесь не заводится.

Проверка без денег и без сети: deploy/checks/dlmm_odno_chtenie.py.
"""

