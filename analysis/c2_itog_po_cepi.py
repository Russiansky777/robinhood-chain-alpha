"""ПРАВИЛО 13: итог позиции ТОЛЬКО ПО ЦЕПИ. ОДНА формула на репозиторий.

ЗАЧЕМ ОТДЕЛЬНЫЙ МОДУЛЬ. Итог сделки считался по `closed_sol_net`, а это
нативная дельта ТОЛЬКО кошелька (`bloom_detector.балансы_кошелька` смотрит
единственный индекс -- сам кошелёк). Токеновые счета кошелька в это число не
входят, поэтому:

  * деньги, оставшиеся ЗАВЁРНУТЫМИ на WSOL-счёте, в итог не попадали вовсе
    (Jevolution 01.10 02:00:06Z: запись −0.09169105, цепь +0.01131123,
     разница 0.10300228 -- ровно завёрнутое плюс рента);
  * возврат завёрнутого в другой сделке выглядел прибылью
    (Freaky Dinosaurs 01:59:48Z: запись +0.09955831, цепь −0.00041629);
  * рента созданного токен-счёта считалась убытком, хотя она наша и
    возвращается при закрытии счёта (51 сделка из 59 за 29.09-01.10
    расходилась ровно на 0.00148844..0.0015748).

ЗДЕСЬ ИТОГ СЧИТАЕТСЯ ПО ДВУМ ПОДПИСЯМ как сумма изменений ВСЕХ НАШИХ счетов --
кошелька и его токеновых счетов, включая WSOL. Комиссия, приоритет, чаевые и
рента в эту сумму уже входят: они списаны с наших же счетов, а возврат ренты при
закрытии счёта в неё же и приходит.

ЧЕГО ЭТОТ МОДУЛЬ НЕ ДЕЛАЕТ. Он не трогает стопы: суточный стоп и KILL считаются
по балансу кошелька, как и были (слово владельца 01.10). Он не решает, покупать
или продавать, и в горячем пути покупки не зовётся.
"""
from __future__ import annotations

WSOL = "So11111111111111111111111111111111111111112"
ЛАМПОРТОВ_В_SOL = 1_000_000_000
# Слово владельца: расхождение больше этого -- тревога строкой, сводка "не сверено".
ПОРОГ_РАСХОЖДЕНИЯ_SOL = 0.00001

ПОЛЕ = "lane_chain_pnl_sol"
ПОЛЕ_ЧАСТИ = "lane_chain_pnl_parts"
ПОЛЕ_ПОЧЕМУ = "lane_chain_pnl_why_not"
ПОЛЕ_ПОДПИСЬ_ПОКУПКИ = "lane_chain_buy_sig"
ПОЛЕ_ПОДПИСЬ_ПРОДАЖИ = "lane_chain_sell_sig"


def _ключи(tx: dict) -> list:
    сооб = ((tx or {}).get("transaction") or {}).get("message") or {}
    сырые = сооб.get("accountKeys") or []
    return [к.get("pubkey") if isinstance(к, dict) else к for к in сырые]


def наши_индексы(tx: dict, кошелёк: str) -> dict:
    """Индексы НАШИХ счетов: сам кошелёк и его токеновые счета."""
    ключи = _ключи(tx)
    мета = (tx or {}).get("meta") or {}
    наши, свои_токен = set(), set()
    почему = None
    if кошелёк in ключи:
        наши.add(ключи.index(кошелёк))
    else:
        почему = "кошелька нет среди статических ключей"
    for где in ("preTokenBalances", "postTokenBalances"):
        for з in (мета.get(где) or []):
            if з.get("owner") == кошелёк and isinstance(з.get("accountIndex"), int):
                наши.add(int(з["accountIndex"]))
                свои_токен.add(int(з["accountIndex"]))
    return {"все": sorted(наши), "токеновые": sorted(свои_токен),
            "кошелёк": (ключи.index(кошелёк) if кошелёк in ключи else None),
            "ключи": ключи, "why_not": почему}


def дельта_транзакции(tx: dict, кошелёк: str) -> dict:
    """Изменения наших счетов в одной транзакции, разложенные по смыслу.

    `все_sol` -- деньги по цепи (кошелёк плюс его токеновые счета).
    `кошелёк_sol` -- ликвидная часть; ровно её и видела запись службы.
    `завёрнутое_sol` -- изменение остатка WSOL: наши деньги вне ликвидной части.
    """
    из_ = {"ok": False, "why_not": None, "все_sol": None, "кошелёк_sol": None,
            "завёрнутое_sol": None, "комиссия_sol": None, "слот": None,
            "время": None, "ошибка": None}
    мета = (tx or {}).get("meta") or {}
    до = мета.get("preBalances") or []
    после = мета.get("postBalances") or []
    if not до or not после:
        из_["why_not"] = "в транзакции нет балансов до и после"
        return из_
    н = наши_индексы(tx, кошелёк)
    if not н["все"]:
        из_["why_not"] = н["why_not"] or "наших счетов в транзакции нет"
        return из_
    def сумма(индексы):
        итог = 0
        for и in индексы:
            if и < len(до) and и < len(после):
                итог += int(после[и]) - int(до[и])
        return итог
    все = сумма(н["все"])
    кош = сумма([н["кошелёк"]] if н["кошелёк"] is not None else [])
    # ЗАВЁРНУТОЕ -- ПО ОСТАТКУ WSOL, а не по лампортам счёта: лампорты WSOL-счёта
    # это завёрнутое ПЛЮС рента, и смешивать их нельзя.
    завёрнутое = 0
    for где, знак in (("preTokenBalances", -1), ("postTokenBalances", 1)):
        for з in (мета.get(где) or []):
            if з.get("owner") != кошелёк or з.get("mint") != WSOL:
                continue
            try:
                завёрнутое += знак * int((з.get("uiTokenAmount") or {}).get("amount"))
            except (TypeError, ValueError):
                continue
    из_.update(ok=True,
                все_sol=round(все / ЛАМПОРТОВ_В_SOL, 9),
                кошелёк_sol=round(кош / ЛАМПОРТОВ_В_SOL, 9),
                завёрнутое_sol=round(завёрнутое / ЛАМПОРТОВ_В_SOL, 9),
                комиссия_sol=round(int(мета.get("fee") or 0) / ЛАМПОРТОВ_В_SOL, 9),
                слот=(tx or {}).get("slot"), время=(tx or {}).get("blockTime"),
                ошибка=(мета.get("err") is not None))
    return из_


def итог_по_двум(tx_покупки, tx_продажи, кошелёк: str) -> dict:
    """Итог сделки ПО ЦЕПИ по двум транзакциям. Нет данных -- НЕТ числа.

    Возвращает {'ok','итог_sol','части','why_not'}. Молчаливого нуля тут быть не
    может: не прочитана хоть одна транзакция -- ok=False и причина словами,
    потому что ноль в этом месте однажды уйдёт в отчёт как факт.
    """
    из_ = {"ok": False, "итог_sol": None, "части": {}, "why_not": None}
    части = {}
    сумма_все = сумма_ликв = 0.0
    for роль, tx in (("покупка", tx_покупки), ("продажа", tx_продажи)):
        if not isinstance(tx, dict) or not tx:
            из_["why_not"] = f"{роль}: транзакции нет"
            return из_
        д = дельта_транзакции(tx, кошелёк)
        if not д["ok"]:
            из_["why_not"] = f"{роль}: {д['why_not']}"
            return из_
        части[роль] = {к: д[к] for к in
                        ("все_sol", "кошелёк_sol", "завёрнутое_sol",
                         "комиссия_sol", "слот", "ошибка")}
        сумма_все += float(д["все_sol"])
        сумма_ликв += float(д["кошелёк_sol"])
    части["итог_ликвидный_sol"] = round(сумма_ликв, 9)
    части["разница_с_ликвидным_sol"] = round(сумма_все - сумма_ликв, 9)
    из_.update(ok=True, итог_sol=round(сумма_все, 9), части=части)
    return из_


def из_записи(поз: dict) -> dict:
    """Итог по цепи ИЗ ЗАПИСИ позиции: {'есть','итог_sol','почему_нет'}."""
    поз = поз if isinstance(поз, dict) else {}
    зн = поз.get(ПОЛЕ)
    if isinstance(зн, (int, float)):
        return {"есть": True, "итог_sol": round(float(зн), 9),
                 "почему_нет": None, "части": поз.get(ПОЛЕ_ЧАСТИ) or {}}
    return {"есть": False, "итог_sol": None,
             "почему_нет": (поз.get(ПОЛЕ_ПОЧЕМУ)
                             or "итог по цепи в записи не посчитан"),
             "части": {}}


def канонический(поз: dict) -> dict:
    """ЧТО ПОКАЗЫВАТЬ И СКЛАДЫВАТЬ: итог по цепи, если он есть.

    Нет его -- берётся прежний счёт по полям (bloom_exec_state.итог_позиции), и
    это НАЗВАНО в `откуда`: «цепь» или «поля». Молча подменить одно другим
    нельзя -- иначе в таблицах окажутся два разных числа под одним именем.
    """
    из_ = {"итог_sol": None, "откуда": None, "почему_нет": None,
            "расход_sol": None}
    ц = из_записи(поз)
    if ц["есть"]:
        из_.update(итог_sol=ц["итог_sol"], откуда="цепь")
    try:
        import bloom_exec_state as ST  # noqa: PLC0415

        итог, расход = ST.итог_позиции(поз or {})
        из_["расход_sol"] = (round(float(расход), 9) if расход is not None else None)
        if из_["откуда"] is None:
            из_.update(итог_sol=(None if итог is None else round(float(итог), 9)),
                        откуда="поля", почему_нет=ц["почему_нет"])
    except Exception as exc:  # noqa: BLE001
        if из_["откуда"] is None:
            из_["почему_нет"] = f"{ц['почему_нет']}; поля тоже не посчитаны ({type(exc).__name__})"
    return из_


def объяснённое(части: dict) -> dict:
    """Две НАЗВАННЫЕ величины, на которые счёт полей обязан отличаться от цепи.

    ЗАЧЕМ. Счёт службы (`bloom_exec_state.итог_позиции`) и итог по цепи считают
    РАЗНОЕ НАРОЧНО: служба считает ликвидные деньги кошелька, цепь -- все наши
    счета. Поэтому разность между ними не ошибка, пока она равна сумме двух
    величин, и обе берутся из тех же двух транзакций:

      * `рента_заперта_sol` -- рента счетов, созданных в сделке: деньги ушли с
        кошелька на НАШ же счёт и вернутся при его закрытии. Считается как
        (все − кошелёк − завёрнутое) по каждой подписи.
      * `завёрнутое_осталось_sol` -- остаток WSOL, перешедший через границу
        сделки: соседняя сделка его оборачивает, а эта возвращает (или наоборот).

    ТОЖДЕСТВО, проверенное на 67 закрытых сделках 30.09-01.10 (аудит
    data/itog_po_cepi_audit.json), выполняется ДО ДЕВЯТОГО ЗНАКА на ВСЕХ 67:

        итог_полей − итог_по_цепи + рента_заперта + завёрнутое_осталось = 0

    Поэтому тревога шлётся только на ОСТАТОК этого тождества. До этой правки
    тревога уходила на саму разность -- то есть на ренту, объяснённую и
    возвратную: 56 закрытых сделок суток из 66 дали бы по строке в чат.
    """
    из_ = {"ok": False, "почему_нет": None, "рента_заперта_sol": None,
            "завёрнутое_осталось_sol": None}
    ч = части if isinstance(части, dict) else {}
    пок, прод = ч.get("покупка"), ч.get("продажа")
    if not isinstance(пок, dict) or not isinstance(прод, dict):
        из_["почему_нет"] = "в записи нет обеих частей по цепи"
        return из_
    рента = завёрн = 0.0
    for часть in (пок, прод):
        все = часть.get("все_sol")
        кош = часть.get("кошелёк_sol")
        зав = часть.get("завёрнутое_sol")
        if not all(isinstance(з, (int, float)) for з in (все, кош, зав)):
            из_["почему_нет"] = "в части по цепи нет всех трёх чисел"
            return из_
        рента += float(все) - float(кош) - float(зав)
        завёрн += float(зав)
    из_.update(ok=True, рента_заперта_sol=round(рента, 9),
                завёрнутое_осталось_sol=round(завёрн, 9))
    return из_


def сверка(поз: dict) -> dict:
    """Расхождение «служба против цепи» по ОДНОЙ позиции.

    ПОЧЕМУ ПО ОДНОЙ, А НЕ СУММОЙ. Суточная сверка показывала 0.0, потому что
    сравнивала итог службы с ЛИКВИДНОЙ дельтой цепи -- то есть то же число с
    самим собой. А по 59 закрытым сделкам 29.09-01.10 суммы расходятся на
    0.0802 SOL: ошибки не гасятся, их просто никто не сравнивал.
    """
    из_ = {"сверено": False, "расхождение_sol": None, "порог": ПОРОГ_РАСХОЖДЕНИЯ_SOL,
            "итог_цепи_sol": None, "итог_полей_sol": None, "почему_нет": None,
            "тревога": False, "рента_заперта_sol": None,
            "завёрнутое_осталось_sol": None, "остаток_sol": None,
            "объяснено_почему_нет": None}
    ц = из_записи(поз)
    if not ц["есть"]:
        из_["почему_нет"] = ц["почему_нет"]
        return из_
    из_["итог_цепи_sol"] = ц["итог_sol"]
    try:
        import bloom_exec_state as ST  # noqa: PLC0415

        итог, _ = ST.итог_позиции(поз or {})
    except Exception as exc:  # noqa: BLE001
        из_["почему_нет"] = f"поля не посчитаны ({type(exc).__name__})"
        return из_
    if итог is None:
        из_["почему_нет"] = "итог по полям неизвестен"
        return из_
    из_["итог_полей_sol"] = round(float(итог), 9)
    из_["расхождение_sol"] = round(из_["итог_полей_sol"] - ц["итог_sol"], 9)
    # ОСТАТОК ТОЖДЕСТВА, А НЕ САМА РАЗНОСТЬ. Рента и перешедшее через границу
    # завёрнутое -- величины НАЗВАННЫЕ: на них счёт полей обязан отличаться от
    # цепи, и тревожить ими владельца значит звать его на объяснённое.
    об = объяснённое(ц.get("части") or {})
    if об["ok"]:
        из_.update(рента_заперта_sol=об["рента_заперта_sol"],
                    завёрнутое_осталось_sol=об["завёрнутое_осталось_sol"])
        из_["остаток_sol"] = round(из_["расхождение_sol"]
                                    + об["рента_заперта_sol"]
                                    + об["завёрнутое_осталось_sol"], 9)
    else:
        # ЧАСТЕЙ НЕТ -- ТРЕВОЖИМ ПО РАЗНОСТИ, как раньше, и говорим почему:
        # молча считать необъяснённое объяснённым -- та же тихая зелень.
        из_["объяснено_почему_нет"] = об["почему_нет"]
        из_["остаток_sol"] = из_["расхождение_sol"]
    из_["сверено"] = abs(из_["остаток_sol"]) <= ПОРОГ_РАСХОЖДЕНИЯ_SOL
    из_["тревога"] = not из_["сверено"]
    return из_


def строка_тревоги(поз: dict, с: dict) -> str:
    """Строка владельцу о расхождении -- с подписями, иначе её нечем проверить."""
    имя = поз.get("token_name") or str(поз.get("mint") or "")[:6] or "—"
    гр = поз.get("lane_group") or "—"
    return ("⚠️ сверка по цепи не сошлась: "
            f"{гр} · {имя} · поля {с.get('итог_полей_sol')} против цепи "
            f"{с.get('итог_цепи_sol')} · разность {с.get('расхождение_sol')} "
            f"· рента заперта {с.get('рента_заперта_sol')} · завёрнутое осталось "
            f"{с.get('завёрнутое_осталось_sol')} · НЕОБЪЯСНЁННЫЙ ОСТАТОК "
            f"{с.get('остаток_sol')} (порог {с.get('порог')})\n"
            f"покупка {поз.get(ПОЛЕ_ПОДПИСЬ_ПОКУПКИ) or '—'}\n"
            f"продажа {поз.get(ПОЛЕ_ПОДПИСЬ_ПРОДАЖИ) or '—'}")


