def статистика_p(v: list, доля: float) -> float:
    """Квантиль по отсортированному списку (без интерполяции)."""
    з = sorted(v)
    return з[min(len(з) - 1, int(доля * len(з)))]


def сделки() -> tuple[list, dict]:
    """Сделки всех выгрузок, ОДНА СТРОКА НА cid.

    Выгрузки Code-1 перекрываются по времени: 469 строк трёх файлов -- это 270
    разных сделок, 172 cid встречаются дважды. Без склейки каждая такая сделка
    входила в медиану и в счёт источника два раза. Итог по цепи в копиях
    одинаковый (проверено на всех 270: расхождений нет), поэтому берётся строка
    из файла, прочитанного последним.
    """
    по_cid: dict = {}
    строк = 0
    for f in sorted((П / "sdelki").glob("sdelki_polosy_*.json")):
        д = json.loads(f.read_text(encoding="utf-8"))
        for r in д.get("ряды") or []:
            r["_файл"] = f.name
            строк += 1
            по_cid.setdefault(r["cid"], []).append(r)
    расх = [c for c, сп in по_cid.items()
            if len({None if x.get("итог_po_cepi_sol") is None else round(x["итог_po_cepi_sol"], 9)
                    for x in сп}) > 1]
    из_ = [сп[-1] for сп in по_cid.values()]
    счёт = {"строк": строк, "сделок": len(из_), "копий": строк - len(из_),
            "cid_с_разным_итогом": len(расх),
            "файлы": sorted({r["_файл"] for сп in по_cid.values() for r in сп})}
    return из_, счёт


ПО_ЦЕПИ: dict | None = None


def расход_по_цепи() -> dict:
    """{cid: расход по цепи} из data/podbivka/rashod_prodazhi.json (чаевые и комиссии обеих подписей).

    Прогон 03.10 прочитал все 261 сделку с подписями: чаевых на ПРОДАЖЕ нет ни в одной
    (0 из 261), а чаевые ПОКУПКИ не всегда 0.001 -- 238 сделок по 0.001, 17 по 0.0001 и 6 по
    0.000001. Поэтому расход берётся по цепи, а поле выгрузки остаётся запасным путём.
    """
    global ПО_ЦЕПИ  # noqa: PLW0603
    if ПО_ЦЕПИ is None:
        п = П / "rashod_prodazhi.json"
        ПО_ЦЕПИ = {}
        if п.exists():
            д = json.loads(п.read_text(encoding="utf-8"))
            ПО_ЦЕПИ = {x["cid"]: x["расход_всего_sol"] for x in д.get("сделки") or []
                       if x.get("расход_всего_sol") is not None}
    return ПО_ЦЕПИ


def расход_постоянный(r: dict) -> float | None:
    """Постоянный расход сделки ПО ЦЕПИ: чаевые покупки и комиссии обеих подписей.

    Чаевые -- `чаевые_sol` записи полосы (lane_tips_total_sol; у всех 260 сделок
    с итогом по цепи это 0.001). Комиссии -- `meta.fee` каждой из двух
    транзакций из `итог_po_cepi_chasti` (на Solana приоритет -- часть комиссии).
    Поле `расход_sol` Code-1 здесь НЕ берётся: оно считается как
    −натив − вход + комиссия покупки и у 66 из 260 сделок отрицательно, потому
    что часть билета ушла с уже завёрнутого WSOL, а не из нативного остатка.
    Чаевые ПРОДАЖИ, если полоса их платит, сидят внутри возврата и тут не
    возвращаются: проверка по цепи отдельным прогоном.
    """
    по_цепи = расход_по_цепи().get(r.get("cid"))
    if по_цепи is not None:
        return float(по_цепи)
    ч = r.get("итог_po_cepi_chasti") or {}
    пок, прод = ч.get("покупка") or {}, ч.get("продажа") or {}
    # ЧАСТИ БЫВАЮТ БЕЗ КОМИССИИ. В сводной выгрузке с 27.09 части лежат как
    # {все_sol, кошелёк_sol, завёрнутое_sol} -- без `комиссия_sol`; тогда расход по цепи
    # не складывается и строка остаётся без числа, а не падает.
    if (r.get("чаевые_sol") is None or пок.get("комиссия_sol") is None
            or прод.get("комиссия_sol") is None):
        if r.get("чаевые_sol") is not None and r.get("комиссия_sol") is not None:
            return round(float(r["чаевые_sol"]) + float(r["комиссия_sol"]), 9)
        return None
    return round(float(r["чаевые_sol"]) + float(пок["комиссия_sol"])
                 + float(прод["комиссия_sol"]), 9)


def до_расходов(r: dict) -> float | None:
    """Сигнал сделки ДО постоянных расходов, п.п. к билету."""
    расх = расход_постоянный(r)
    if расх is None or r.get("итог_po_cepi_sol") is None or not r.get("sol_in"):
        return None
    return 100 * (float(r["итог_po_cepi_sol"]) + расх) / float(r["sol_in"])


def архив(цель: set) -> tuple[dict, dict]:
    по: dict = {a: {"ячеек": 0, "сигналов": 0, "пп": {}, "сост": [], "файлы": set(), "ts": [],
                    "резерв": []} for a in цель}
    счёт = {"файлов": 0, "сигналов": 0, "дублей": 0, "ошибки": []}
    видел = set()
    for шаб in ШАБЛОНЫ:
        for f in sorted(x for x in glob.glob(str(П / "arhiv_den" / шаб)) if "_vne_" not in Path(x).name):
            д = json.loads(gzip.decompress(Path(f).read_bytes()))
            счёт["файлов"] += 1
            счёт["ошибки"] += [f"{Path(f).name}: {x}" for x in (д.get("счёт") or {}).get("ошибки") or []]
            for с in д.get("сигналы") or []:
                if с.get("trader") not in по or not PR.окно(с, f):
                    continue
                счёт["сигналов"] += 1
                if с["signature"] in видел:
                    счёт["дублей"] += 1
                    continue
                видел.add(с["signature"])
                if (с.get("sol") or 0) < 2.0:
                    continue
                к = по[с["trader"]]
                к["сигналов"] += 1
                if not C2.ячейка(с):
                    continue
                к["ячеек"] += 1
                к["файлы"].add(Path(f).name.split("_")[0])
                ts = PR.K.ts(с)
                к["ts"].append(ts)
                if с.get("резерв_sol"):
                    к["резерв"].append(float(с["резерв_sol"]))
                for б in (0.1, 0.3, 0.5, 1.0, 3.0):
                    v = B.пп(с, б)
                    if v is not None:
                        к["пп"].setdefault(б, []).append((ts, v))
                if ((с.get("модель") or {}).get("состояния") or {}).get("вход"):
                    к["сост"].append(с)
            del д
    return по, счёт


