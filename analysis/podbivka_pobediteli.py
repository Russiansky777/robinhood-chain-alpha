def живые(каталог: Path) -> list:
    """157 рядов трёх выгрузок + q из уже посчитанных прогонов (ключ -- utc)."""
    q_по_utc = {}
    for имя in Q_ПРОГОНЫ:
        ф = П / f"{имя}.json"
        if not ф.exists():
            continue
        for с in json.loads(ф.read_text(encoding="utf-8")).get("сделки") or []:
            q_по_utc[с["utc"]] = с
    ряды = []
    for имя in ВЫГРУЗКИ:
        ф = каталог / f"{имя}.json"
        д = json.loads(ф.read_text(encoding="utf-8"))
        for с in (д.get("ряды") or д.get("сделки") or []):
            итог = с.get("итог_po_cepi_sol")
            итог = итог if итог is not None else с.get("итог_sol")
            o, s = с.get("our_slot"), с.get("source_slot")
            зам = q_по_utc.get(с["utc"]) or {}
            ряды.append({
                "выгрузка": имя, "utc": с["utc"], "источник": с.get("source"),
                "группа": с.get("group"), "билет": с.get("bilet_sol"),
                "итог": итог,
                "лаг": (o - s) if (o and s) else None,
                "доля_блока": с.get("our_block_share"),
                "q": зам.get("q_замеренное"),
                "наплыв_пп": зам.get("наплыв_слота_пп"),
                "между": зам.get("транзакций_между"),
            })
    return ряды


def фишер(a: int, b: int, c: int, d: int) -> float:
    """Точный тест Фишера, двусторонний: таблица [[a,b],[c,d]]."""
    н = a + b + c + d
    стр1, стр2 = a + b, c + d
    кол1 = a + c

    def вер(x):
        return (math.comb(стр1, x) * math.comb(стр2, кол1 - x)) / math.comb(н, кол1)

    p0 = вер(a)
    низ = max(0, кол1 - стр2)
    верх = min(стр1, кол1)
    return min(1.0, sum(вер(x) for x in range(низ, верх + 1)
                        if вер(x) <= p0 + 1e-12))


def ранговый(x: list, y: list, рнд: random.Random, повторов: int = 20000) -> float:
    """Перестановочный тест на разницу медиан (двусторонний)."""
    if not x or not y:
        return float("nan")
    набл = abs(st.median(x) - st.median(y))
    всё = x + y
    к = 0
    for _ in range(повторов):
        рнд.shuffle(всё)
        if abs(st.median(всё[:len(x)]) - st.median(всё[len(x):])) >= набл - 1e-12:
            к += 1
    return к / повторов


def доля_ди(k: int, n: int) -> tuple:
    """Доля и 95 % интервал Уилсона."""
    if not n:
        return (float("nan"), float("nan"), float("nan"))
    p = k / n
    z = 1.959964
    ц = (p + z * z / (2 * n)) / (1 + z * z / n)
    р = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / (1 + z * z / n)
    return (round(p, 4), round(max(0.0, ц - р), 4), round(min(1.0, ц + р), 4))


def разрез(ряды: list, рнд: random.Random, доля_верха: float = 0.05) -> dict:
    """Верхние `доля_верха` по итогу против остальных."""
    ряды = [с for с in ряды if с["итог"] is not None]
    по = sorted(ряды, key=lambda с: -с["итог"])
    к = max(1, math.ceil(доля_верха * len(по)))
    верх, низ = по[:к], по[к:]

    def срез(сп: str, гр: list) -> dict:
        v = [с[сп] for с in гр if с.get(сп) is not None]
        return {"n": len(v), "медиана": round(st.median(v), 4) if v else None,
                "среднее": round(st.fmean(v), 4) if v else None}

    def лаг0(гр: list) -> tuple:
        с_лагом = [с for с in гр if с["лаг"] is not None]
        k = sum(1 for с in с_лагом if с["лаг"] == 0)
        return k, len(с_лагом), доля_ди(k, len(с_лагом))

    kв, nв, дв = лаг0(верх)
    kн, nн, дн = лаг0(низ)
    qв = [с["q"] for с in верх if с.get("q") is not None]
    qн = [с["q"] for с in низ if с.get("q") is not None]
    нв = [с["наплыв_пп"] for с in верх if с.get("наплыв_пп") is not None]
    нн = [с["наплыв_пп"] for с in низ if с.get("наплыв_пп") is not None]
    return {
        "всего": len(по), "верхних": к,
        "итог_верх_sol": round(sum(с["итог"] for с in верх), 5),
        "итог_низ_sol": round(sum(с["итог"] for с in низ), 5),
        "итог_всего_sol": round(sum(с["итог"] for с in по), 5),
        "лаг0_верх": {"из": nв, "лаг0": kв, "доля": дв[0], "ди95": [дв[1], дв[2]]},
        "лаг0_низ": {"из": nн, "лаг0": kн, "доля": дн[0], "ди95": [дн[1], дн[2]]},
        "p_фишер_лаг0": round(фишер(kв, nв - kв, kн, nн - kн), 4) if nв and nн else None,
        "q_верх": срез("q", верх), "q_низ": срез("q", низ),
        "p_перест_q": (round(ранговый(qв, qн, рнд), 4) if qв and qн else None),
        "наплыв_верх": срез("наплыв_пп", верх), "наплыв_низ": срез("наплыв_пп", низ),
        "p_перест_наплыв": (round(ранговый(нв, нн, рнд), 4) if нв and нн else None),
        "доля_блока_верх": срез("доля_блока", верх),
        "доля_блока_низ": срез("доля_блока", низ),
        "верхние_сделки": [{k: с.get(k) for k in
                            ("utc", "выгрузка", "группа", "источник", "итог", "лаг",
                             "q", "наплыв_пп", "доля_блока")} for с in верх],
    }


