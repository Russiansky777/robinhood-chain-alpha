#!/usr/bin/env python3
"""Источник сделки -- ПОКУПАТЕЛЬ или только УПОМЯНУТ в чужой транзакции.

ЗАЧЕМ. Слово владельца 02.10: Code-2 нашёл, что 76 «подписей лидера»
Beqv6dzT -- чужие сделки трейдера ARu4n5mF, где подписанты 76dGp5DV, 5K7Sc2wq
и EBAQ17ZS, а лидеру достаётся доля 0.00015-0.00045 SOL (похоже на долю
создателя токена). То же подозрение на HYh78tNp (batch5, 157 пуловых
транзакций, подписант 0 раз) и 8RCEq8Rr (lane_s0, 133 транзакции, подписант 3).
Если наш классификатор считает такие упоминания сигналами, полоса покупает по
чужим сделкам -- и отбор источников считался по чужим числам.

ВОПРОС ОДИН, И ОТВЕТ НА НЕГО БЕРЁТСЯ ИЗ ТРАНЗАКЦИИ, А НЕ ИЗ ЖУРНАЛА:
  * подписанты (message.accountKeys, где signer),
  * плательщик (accountKeys[0] -- он же первый подписант),
  * владельцы токен-счетов, ПОЛУЧИВШИХ токены (postTokenBalances.owner там,
    где количество выросло против preTokenBalances),
  * дельта лампортов самого источника (pre/postBalances по его индексу).

ПРАВИЛО ВЛАДЕЛЬЦА: сигнал -- только если источник ПОДПИСАНТ ИЛИ ВЛАДЕЛЕЦ
токен-счёта, получившего токены. Второе нужно для покупок через посредников:
подписывает роутер или кошелёк-посредник, а токен приходит владельцу.

ТОЛЬКО ЧТЕНИЕ. Модуль разбирает УЖЕ СОХРАНЁННЫЙ сырой ответ узла
(data/bloom_tx_raw.json от analysis/bloom_tx_dump.py): сети здесь нет вовсе,
значит разбор повторяем и проверяется без узла.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parent.parent

# Вид ответа: что считается ПОКУПАТЕЛЕМ.
ПОКУПАТЕЛЬ = "покупатель"
УПОМЯНУТ = "только упомянут"
НЕ_ЗНАЮ = "не знаю"


def _ключи(tx: dict) -> list:
    """Полный список адресов транзакции в порядке индексов.

    ВЕРСИЯ 0 ХРАНИТ ЧАСТЬ АДРЕСОВ В ТАБЛИЦАХ, и без них индексы балансов
    съезжают: loadedAddresses.writable идут сразу за статическими ключами,
    затем readonly. Пропустить их значит прочитать дельту ЧУЖОГО счёта.
    """
    сооб = ((tx or {}).get("transaction") or {}).get("message") or {}
    ключи = []
    for к in (сооб.get("accountKeys") or []):
        ключи.append(к.get("pubkey") if isinstance(к, dict) else к)
    загр = ((tx or {}).get("meta") or {}).get("loadedAddresses") or {}
    ключи += list(загр.get("writable") or [])
    ключи += list(загр.get("readonly") or [])
    return [str(к) for к in ключи if к]


def подписанты(tx: dict) -> list:
    """Адреса, подписавшие транзакцию. Нет признака -- пусто, а не догадка."""
    сооб = ((tx or {}).get("transaction") or {}).get("message") or {}
    из_ = []
    ключи = сооб.get("accountKeys") or []
    # ВИД С ПРИЗНАКОМ: jsonParsed отдаёт {"pubkey":..., "signer": true}.
    if ключи and isinstance(ключи[0], dict):
        return [str(к.get("pubkey")) for к in ключи if к.get("signer")]
    # ВИД БЕЗ ПРИЗНАКА: число подписантов лежит в header, и первые N ключей --
    # подписанты. Выдумывать их по одному нельзя: порядок -- часть формата.
    н = (сооб.get("header") or {}).get("numRequiredSignatures")
    if isinstance(н, int) and н > 0:
        из_ = [str(к) for к in ключи[:н]]
    return из_


def плательщик(tx: dict) -> str | None:
    """Платит ВСЕГДА первый подписант -- это правило формата, не догадка."""
    п = подписанты(tx)
    return п[0] if п else None


def получатели_токенов(tx: dict) -> list:
    """Владельцы токен-счетов, у которых количество ВЫРОСЛО.

    Считается по сырым единицам (uiTokenAmount.amount): у токена с девятью
    знаками движение в единицах показывается в ui нулём, и покупка выглядела бы
    отсутствием покупки.
    """
    мета = (tx or {}).get("meta") or {}
    до = {}
    for б in (мета.get("preTokenBalances") or []):
        к = (б.get("accountIndex"), б.get("mint"))
        до[к] = int(((б.get("uiTokenAmount") or {}).get("amount") or 0) or 0)
    из_ = []
    for б in (мета.get("postTokenBalances") or []):
        к = (б.get("accountIndex"), б.get("mint"))
        было = до.get(к, 0)
        стало = int(((б.get("uiTokenAmount") or {}).get("amount") or 0) or 0)
        if стало > было and б.get("owner"):
            из_.append({"owner": str(б["owner"]), "mint": б.get("mint"),
                         "прирост_raw": стало - было})
    return из_


def дельта_лампортов(tx: dict, адрес: str) -> dict:
    """Сколько лампортов адрес потерял или получил этой транзакцией.

    Адреса нет в транзакции -- так и говорим. Ноль здесь был бы ложью: «не
    участвовал» и «участвовал, но без движения» -- разные вещи.
    """
    из_ = {"есть": False, "лампортов": None, "почему_нет": None}
    ключи = _ключи(tx)
    if адрес not in ключи:
        из_["почему_нет"] = "адреса нет среди счетов транзакции"
        return из_
    и = ключи.index(адрес)
    мета = (tx or {}).get("meta") or {}
    до, после = мета.get("preBalances") or [], мета.get("postBalances") or []
    if и >= len(до) or и >= len(после):
        из_["почему_нет"] = ("балансы короче списка счетов -- индекс не "
                              "сопоставить")
        return из_
    из_.update(есть=True, лампортов=int(после[и]) - int(до[и]))
    return из_


def разобрать(tx: dict, источник: str) -> dict:
    """Один ответ про одну транзакцию: покупатель источник или упомянут."""
    из_ = {"вердикт": НЕ_ЗНАЮ, "подписант": None, "владелец_получившего": None,
            "подписанты": [], "плательщик": None, "получатели": [],
            "дельта_лампортов": None, "почему": None}
    if not isinstance(tx, dict) or not tx:
        из_["почему"] = "транзакции нет -- судить не по чему"
        return из_
    из_["подписанты"] = подписанты(tx)
    из_["плательщик"] = плательщик(tx)
    из_["получатели"] = получатели_токенов(tx)
    д = дельта_лампортов(tx, источник)
    из_["дельта_лампортов"] = д.get("лампортов")
    if not из_["подписанты"]:
        из_["почему"] = ("подписантов в ответе узла нет (ни признака signer, ни "
                          "numRequiredSignatures) -- вердикта нет")
        return из_
    из_["подписант"] = источник in из_["подписанты"]
    из_["владелец_получившего"] = any(п["owner"] == источник
                                       for п in из_["получатели"])
    if из_["подписант"] or из_["владелец_получившего"]:
        из_["вердикт"] = ПОКУПАТЕЛЬ
        из_["почему"] = ("источник подписант" if из_["подписант"]
                          else "источник владеет счётом, получившим токены")
    else:
        из_["вердикт"] = УПОМЯНУТ
        из_["почему"] = ("источник не подписант и не владелец получившего "
                          "счёта -- это чужая сделка, в которой он упомянут")
    return из_


def свод(дамп: dict, источники: dict) -> dict:
    """{подпись: разбор} и счёт по вердиктам. `источники` -- {подпись: адрес}."""
    из_ = {"разборы": {}, "итог": {ПОКУПАТЕЛЬ: 0, УПОМЯНУТ: 0, НЕ_ЗНАЮ: 0},
            "по_источникам": {}}
    for подпись, тело in (дамп or {}).items():
        ист = (источники or {}).get(подпись)
        if not ист:
            continue
        tx = (тело or {}).get("tx") if isinstance(тело, dict) else None
        р = разобрать(tx if isinstance(tx, dict) else {}, ист)
        из_["разборы"][подпись] = {**р, "источник": ист}
        из_["итог"][р["вердикт"]] += 1
        с = из_["по_источникам"].setdefault(
            ист, {ПОКУПАТЕЛЬ: 0, УПОМЯНУТ: 0, НЕ_ЗНАЮ: 0})
        с[р["вердикт"]] += 1
    return из_


# ----------------------------------------------------------- самопроверка

def _tx(*, подписанты_=(), ключи=(), пре=(), пост=(), пре_т=(), пост_т=()):
    """Синтетическая транзакция вида jsonParsed. Сети в проверках нет."""
    все = list(подписанты_) + list(ключи)
    return {"transaction": {"message": {
                "accountKeys": [{"pubkey": к, "signer": к in подписанты_}
                                 for к in все]}},
            "meta": {"preBalances": list(пре) or [0] * len(все),
                      "postBalances": list(пост) or [0] * len(все),
                      "preTokenBalances": list(пре_т),
                      "postTokenBalances": list(пост_т)}}


def _ток(и, минт, количество, владелец):
    return {"accountIndex": и, "mint": минт, "owner": владелец,
             "uiTokenAmount": {"amount": str(количество)}}


def self_test() -> int:  # noqa: C901
    всего = [0, 0]

    def chk(что, ок, факт=None):
        всего[0] += 1
        всего[1] += bool(ок)
        print(f"  [{'ok  ' if ок else 'ПРОВАЛ'}] {что}"
              + (f" -> {факт!r}" if факт is not None and not ок else ""))

    ИСТ, ЧУЖОЙ, РОУТЕР = "ИСТОЧНИК", "ЧУЖОЙ_ПОДПИСАНТ", "РОУТЕР"

    # 1. ИСТОЧНИК САМ ПОДПИСАЛ -- покупатель, и это бесспорно.
    сам = _tx(подписанты_=(ИСТ,), ключи=("ПУЛ",),
               пре=(1_000_000_000, 0), пост=(900_000_000, 0),
               пост_т=[_ток(1, "МИНТ", 5_000_000, ИСТ)])
    р = разобрать(сам, ИСТ)
    chk("источник подписал -- покупатель, причина названа",
        р["вердикт"] == ПОКУПАТЕЛЬ and р["подписант"] is True
        and "подписант" in р["почему"], р)
    chk("дельта лампортов источника -- минус сто миллионов",
        р["дельта_лампортов"] == -100_000_000, р["дельта_лампортов"])

    # 2. ЧУЖАЯ СДЕЛКА, ИСТОЧНИК ТОЛЬКО УПОМЯНУТ и получил пыль -- НЕ покупатель.
    # Ровно случай Code-2: подписант чужой, лидеру капает доля создателя.
    чужая = _tx(подписанты_=(ЧУЖОЙ,), ключи=(ИСТ, "ПУЛ"),
                 пре=(1_000_000_000, 10_000, 0),
                 пост=(900_000_000, 10_000 + 450_000, 0),
                 пост_т=[_ток(2, "МИНТ", 5_000_000, ЧУЖОЙ)])
    р2 = разобрать(чужая, ИСТ)
    chk("чужая сделка: источник не подписант и не владелец -- ТОЛЬКО УПОМЯНУТ",
        р2["вердикт"] == УПОМЯНУТ and р2["подписант"] is False
        and р2["владелец_получившего"] is False, р2)
    chk("и доля ему ПРИШЛА, то есть плюс -- это и обманывало классификатор",
        р2["дельта_лампортов"] == 450_000, р2["дельта_лампортов"])

    # 3. ПОКУПКА ЧЕРЕЗ ПОСРЕДНИКА: подписал роутер, токен пришёл источнику.
    # Это ВТОРАЯ ветка правила владельца, и без неё мы потеряли бы настоящие
    # покупки тех, кто ходит через посредников.
    через = _tx(подписанты_=(РОУТЕР,), ключи=(ИСТ, "СЧЁТ"),
                 пре=(500_000_000, 2_000_000_000, 0),
                 пост=(499_000_000, 1_900_000_000, 0),
                 пост_т=[_ток(2, "МИНТ", 7_000_000, ИСТ)])
    р3 = разобрать(через, ИСТ)
    chk("через посредника: подписал роутер, токен источнику -- ПОКУПАТЕЛЬ",
        р3["вердикт"] == ПОКУПАТЕЛЬ and р3["подписант"] is False
        and р3["владелец_получившего"] is True
        and "владеет счётом" in р3["почему"], р3)

    # 4. КОЛИЧЕСТВО НЕ ВЫРОСЛО -- не получатель. Продажа чужого токена с его
    # счёта не должна читаться как покупка.
    продажа = _tx(подписанты_=(ЧУЖОЙ,), ключи=(ИСТ,),
                   пре_т=[_ток(1, "МИНТ", 9_000_000, ИСТ)],
                   пост_т=[_ток(1, "МИНТ", 1_000_000, ИСТ)])
    chk("количество упало -- источник НЕ получатель, значит упомянут",
        разобрать(продажа, ИСТ)["вердикт"] == УПОМЯНУТ)

    # 5. СЫРЫЕ ЕДИНИЦЫ, А НЕ ui: прирост в единицах при нулевом ui.
    пыль = _tx(подписанты_=(ЧУЖОЙ,), ключи=(ИСТ,),
                пре_т=[_ток(1, "МИНТ", 0, ИСТ)],
                пост_т=[_ток(1, "МИНТ", 3, ИСТ)])
    chk("прирост в СЫРЫХ единицах виден (ui показал бы ноль)",
        разобрать(пыль, ИСТ)["вердикт"] == ПОКУПАТЕЛЬ)

    # 6. НЕТ ПОДПИСАНТОВ В ОТВЕТЕ -- «не знаю», а не «упомянут». Молча назвать
    # чужой сделкой то, чего мы не прочитали, значит выбросить сигнал по своей
    # же слепоте.
    пусто = {"transaction": {"message": {"accountKeys": []}}, "meta": {}}
    р6 = разобрать(пусто, ИСТ)
    chk("подписантов не прочитали -- НЕ ЗНАЮ, и причина названа",
        р6["вердикт"] == НЕ_ЗНАЮ and "подписантов" in (р6["почему"] or ""), р6)
    chk("транзакции нет вовсе -- тоже НЕ ЗНАЮ",
        разобрать({}, ИСТ)["вердикт"] == НЕ_ЗНАЮ)

    # 7. ВИД БЕЗ ПРИЗНАКА signer: подписанты -- первые numRequiredSignatures.
    без_признака = {"transaction": {"message": {
                        "accountKeys": [ЧУЖОЙ, ИСТ, "ПУЛ"],
                        "header": {"numRequiredSignatures": 1}}},
                     "meta": {"preBalances": [0, 0, 0],
                              "postBalances": [0, 0, 0]}}
    р7 = разобрать(без_признака, ИСТ)
    chk("вид без признака signer: подписант один, источник среди них НЕ числится",
        р7["подписанты"] == [ЧУЖОЙ] and р7["вердикт"] == УПОМЯНУТ, р7)
    chk("плательщик -- первый подписант",
        плательщик(без_признака) == ЧУЖОЙ)

    # 8. ВЕРСИЯ 0: адреса из таблиц идут за статическими, и дельта берётся по
    # ПРАВИЛЬНОМУ индексу. Без loadedAddresses прочитали бы чужой счёт.
    v0 = {"transaction": {"message": {"accountKeys": [{"pubkey": ЧУЖОЙ,
                                                        "signer": True}]}},
           "meta": {"loadedAddresses": {"writable": [ИСТ], "readonly": []},
                    "preBalances": [0, 777], "postBalances": [0, 1_777]}}
    chk("версия 0: дельта источника из таблицы адресов прочитана верно",
        дельта_лампортов(v0, ИСТ)["лампортов"] == 1_000,
        дельта_лампортов(v0, ИСТ))
    chk("адреса нет в транзакции -- так и сказано, а не ноль",
        дельта_лампортов(сам, "НЕТ_ТАКОГО")["есть"] is False
        and дельта_лампортов(сам, "НЕТ_ТАКОГО")["лампортов"] is None)

    # 9. СВОД по нескольким подписям считает вердикты и режет по источникам.
    с = свод({"П1": {"ok": True, "tx": сам}, "П2": {"ok": True, "tx": чужая},
               "П3": {"ok": True, "tx": через}, "П4": {"ok": False}},
              {"П1": ИСТ, "П2": ИСТ, "П3": ИСТ, "П4": ИСТ})
    chk(f"свод: 2 покупателя, 1 упомянут, 1 не знаю -- {с['итог']}",
        с["итог"] == {ПОКУПАТЕЛЬ: 2, УПОМЯНУТ: 1, НЕ_ЗНАЮ: 1}, с["итог"])
    chk("свод режет по источникам тем же счётом",
        с["по_источникам"][ИСТ] == {ПОКУПАТЕЛЬ: 2, УПОМЯНУТ: 1, НЕ_ЗНАЮ: 1})

    print(f"самопроверка классификатора: {всего[1]}/{всего[0]} пройдено")
    return 0 if всего[1] == всего[0] else 1


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--self-test", action="store_true")
    ap.add_argument("--dump", default=str(КОРЕНЬ / "data" / "bloom_tx_raw.json"))
    ap.add_argument("--istochniki", default="",
                    help="файл JSON {подпись: адрес источника}")
    ap.add_argument("--out", default=str(КОРЕНЬ / "data"
                                         / "klassifikator_proverka.json"))
    а = ap.parse_args()
    if а.self_test:
        return self_test()
    дамп = json.loads(Path(а.dump).read_text(encoding="utf-8"))
    ист = json.loads(Path(а.istochniki).read_text(encoding="utf-8")) if а.istochniki else {}
    с = свод(дамп, ист)
    Path(а.out).write_text(json.dumps(с, ensure_ascii=False, indent=1),
                           encoding="utf-8")
    print(json.dumps({"итог": с["итог"], "по_источникам": с["по_источникам"]},
                     ensure_ascii=False, indent=1))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
