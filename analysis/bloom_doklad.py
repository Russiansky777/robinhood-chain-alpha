"""ОДИН докладчик сделки полосы: строка позиции, а не события путей.

ЗАЧЕМ (слово владельца 27.09, вечер). До этого о сделке докладывали САМИ пути:
одноногая покупка, двухшаговая, продажа своим строителем, продажа через
Jupiter -- каждый своей строкой и своими полями. Из-за этого в чате появлялись
прочерки там, где число есть в записи позиции, дубли строк продажи и события
без покупки. Владелец велел: "переделать на одну функцию-докладчик, которая
рисует строку позиции (выгрузка nashi_sdelki), а не события отдельных путей.
Все пути докладывают только через неё. Ответ площадки для этого не нужен".

ЧТО ЗДЕСЬ.
  * поля(поз) -- ОДНО место, где из записи позиции достаются все числа строки.
    Правила взятия полей те же, что в выгрузке nashi_sdelki (подпись покупки --
    lane_landed_signature, возврат -- closed_sol_net либо
    last_sell_outcome.sol_delta_net, издержки -- чаевые, приоритет и рента
    покупки по отдельности), чтобы чат и выгрузка не расходились числами.
  * строка_покупки / строка_продажи / сообщение -- вид строки.
  * доложить(поз, ...) -- единственный вход для всех путей: пока продажи нет,
    уходит строка покупки; когда продажа села, вторая строка ДОПИСЫВАЕТСЯ к тому
    же сообщению, а если сообщения покупки нет (например, служба перезапускалась)
    -- уходит полная строка покупка+продажа одним сообщением.

НИ ОДНОГО ПРОЧЕРКА. Слово владельца: "если поле неизвестно -- так и писать
словом, почему". Поэтому здесь нет "—": у каждого неизвестного поля своя
причина, и она печатается.
"""
