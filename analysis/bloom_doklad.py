def _чч_мм_сс(utc: str | None, ts=None) -> str:
    if isinstance(utc, str) and len(utc) >= 19:
        return utc[11:19]
    if isinstance(ts, (int, float)):
        return time.strftime("%H:%M:%S", time.gmtime(float(ts)))
    return "время не записано"


def _sol(x, знаков: int = 6) -> str:
    return f"{float(x):.{знаков}f}"


def _sol_зн(x, знаков: int = 6) -> str:
    з = float(x)
    return f"{'+' if з >= 0 else '−'}{abs(з):.{знаков}f}"


def _проц_зн(x, знаков: int = 2) -> str:
    з = float(x)
    return f"{'+' if з >= 0 else '−'}{abs(з):.{знаков}f} %"


def подпись_покупки(поз: dict):
    """Севшая подпись покупки. Те же поля, что в выгрузке."""
    for поле in ("lane_landed_signature", "closed_buy_signature"):
        з = поз.get(поле)
        if isinstance(з, str) and len(з) > 40:
            return з, поле
    з = поз.get("lane_signature")
    if isinstance(з, str) and len(з) > 40:
        # ПРИНЯТАЯ СЕТЬЮ, НО НЕ ПОДТВЕРЖДЁННАЯ. Это честно называется словом:
        # сказать "села" по принятой подписи нельзя.
        return з, "lane_signature (принята, посадка не подтверждена)"
    return None, None


def подпись_продажи(поз: dict):
    о = поз.get("last_sell_reported")
    if isinstance(о, dict):
        for поле in ("signature", "sig"):
            if isinstance(о.get(поле), str):
                return о[поле], f"last_sell_reported.{поле}"
        return None, None
    if isinstance(о, str) and len(о) > 40:
        return о, "last_sell_reported"
    список = поз.get("last_sell_signatures")
    if isinstance(список, list) and список and isinstance(список[0], str):
        return список[0], "last_sell_signatures[0]"
    return None, None


def возврат_sol(поз: dict):
    """Вышло из свопа продажи. Правило -- как в выгрузке."""
    з = поз.get("closed_sol_net")
    if з is None:
        з = (поз.get("last_sell_outcome") or {}).get("sol_delta_net")
    return None if з is None else float(з)


def издержки(поз: dict) -> dict:
    """Чаевые, приоритет и рента покупки по отдельности плюс их сумма."""
    из_ = {"чаевые": None, "приоритет": None, "рента": None, "сумма": None,
            "почему": None}
    ч = поз.get("lane_tips_total_sol")
    п = поз.get("lane_priority_lamports")
    if isinstance(ч, (int, float)):
        из_["чаевые"] = round(float(ч), 9)
    if isinstance(п, (int, float)):
        из_["приоритет"] = round(float(п) / ЛАМПОРТОВ_В_SOL, 9)
    расход = поз.get("pnl_counted_spend_sol")
    if (isinstance(расход, (int, float)) and из_["чаевые"] is not None
            and из_["приоритет"] is not None):
        рента = float(расход) - из_["чаевые"] - из_["приоритет"]
        из_["рента"] = round(рента, 9) if рента > 0 else 0.0
        из_["сумма"] = round(float(расход), 9)
    elif isinstance(расход, (int, float)):
        из_["сумма"] = round(float(расход), 9)
        из_["почему"] = "чаевые и приоритет в записи не сохранены"
    else:
        из_["почему"] = "расход сделки в записи не сохранён"
    return из_


def котировка_словом(минт: str | None) -> str:
    if not минт:
        return "SOL"
    return ИЗВЕСТНЫЕ_КОТИРОВКИ.get(минт, f"{str(минт)[:6]}…")


def поля(поз: dict, *, имя_токена: str | None = None,
          имя_источника: str | None = None) -> dict:
    """Все числа строки из ОДНОЙ записи позиции. Неизвестное -- со словом."""
    поз = поз or {}
    б, откуда_б = подпись_покупки(поз)
    пр, откуда_пр = подпись_продажи(поз)
    вход = поз.get("sol_in")
    вышло = возврат_sol(поз)
    изд = издержки(поз)
    двух = bool(поз.get("lane_two_step"))
    слот_наш = None
    for поле in ("lane_landed_slot", "our_slot", "entry_slot", "slot"):
        if isinstance(поз.get(поле), int):
            слот_наш = поз[поле]
            break
    слот_ист = поз.get("source_slot")
    s_n = (слот_наш - слот_ист
            if isinstance(слот_наш, int) and isinstance(слот_ист, int) else None)
    итог = None
    if вход is not None and вышло is not None and изд["сумма"] is not None:
        итог = round(float(вышло) - float(вход) - float(изд["сумма"]), 9)
    elif isinstance(поз.get("pnl_counted_sol"), (int, float)):
        итог = round(float(поз["pnl_counted_sol"]), 9)
    процент = None
    if итог is not None and вход:
        процент = итог / float(вход) * 100.0
    удержание = None
    т_куп = поз.get("ts_sent") or поз.get("ts_intent")
    т_прод = poz_ts(поз)
    if isinstance(т_куп, (int, float)) and isinstance(т_прод, (int, float)):
        удержание = max(0.0, float(т_прод) - float(т_куп))
    return {
        "cid": поз.get("client_order_id") or поз.get("cid"),
        "время": _чч_мм_сс(поз.get("ts_intent_utc"), поз.get("ts_intent")),
        "группа": поз.get("lane_group") or поз.get("group"),
        "источник": поз.get("source"),
        "имя_источника": имя_источника,
        "размер_sol": вход,
        "минт": поз.get("mint"),
        "имя_токена": имя_токена,
        "двухшаговый": двух,
        "котировка": котировка_словом(поз.get("lane_two_step_quote_mint")
                                       if двух else WSOL),
        "s_n": s_n,
        "слот_наш": слот_наш, "слот_источника": слот_ист,
        "перед_нами": поз.get("slot_peers_before_us"),
        "наценка": поз.get("entry_premium_pct"),
        "наценка_почему": поз.get("entry_premium_why_not"),
        "довёз": (поз.get("lane_pool_winner") or поз.get("lane_send_point")),
        "подпись_покупки": б, "откуда_подпись_покупки": откуда_б,
        "подпись_продажи": пр, "откуда_подпись_продажи": откуда_пр,
        "вышло_sol": вышло, "издержки": изд, "итог_sol": итог,
        "итог_процент": процент, "удержание_с": удержание,
        "продана": пр is not None or поз.get("state") == "closed",
        "причина_закрытия": поз.get("closed_reason") or поз.get("close_reason"),
    }


def poz_ts(поз: dict):
    """Время продажи: закрытие, иначе последняя попытка продажи."""
    for поле in ("ts_closed", "ts_last_sell_reported", "ts_last_sell_attempt"):
        if isinstance(поз.get(поле), (int, float)):
            return поз[поле]
    return None


def группа_словом(группа) -> str:
    """Слово группы. Пусто -- СЛОВО, а не прочерк формата 3."""
    if not группа:
        return "группа не записана"
    return _f3().слово_группы(группа)


def токен_словом(имя, минт) -> str:
    """Имя токена, иначе минт, иначе слово. Прочерка здесь быть не может."""
    if имя:
        return _f3().имя_токена(имя, минт)
    if минт:
        return _f3().имя_токена(None, минт)
    return "минт не записан"


def строка_покупки(п: dict) -> str:
    """🟢 покупка: все поля владельца, каждое неизвестное -- словом."""
    F3 = _f3()
    ист = (f"{F3.экран(п.get('имя_источника'))} "
            f"{str(п.get('источник') or '')[:6]}…"
            if п.get("имя_источника")
            else (f"{str(п['источник'])[:10]}… (имени в файле групп нет)"
                  if п.get("источник") else "источник не записан"))
    размер = (f"{float(п['размер_sol']):g} SOL" if п.get("размер_sol") is not None
              else "размер не записан")
    маршрут = (f"2 ноги через {п['котировка']}" if п.get("двухшаговый")
               else "1 нога, котировка SOL")
    if п.get("s_n") is not None:
        s = f"S+{int(п['s_n'])}"
    elif п.get("слот_источника") is None:
        s = "S+? слот источника не записан"
    else:
        s = "S+? слот нашей посадки не записан"
    если_перед = (f"свопов перед нами {int(п['перед_нами'])}"
                  if isinstance(п.get("перед_нами"), int)
                  else "свопов перед нами не записано")
    if п.get("наценка") is not None:
        нац = f"{_проц_зн(п['наценка'], 1)} к цене источника"
    else:
        нац = (f"наценка не посчитана ({F3.экран(п.get('наценка_почему'))})"
               if п.get("наценка_почему")
               else "наценка не посчитана (причина в записи не названа)")
    довёз = (f"довёз {F3.экран(п['довёз'])}" if п.get("довёз")
             else "довёз: отправитель не записан")
    ссыл = (F3.ссылка(п["подпись_покупки"]) if п.get("подпись_покупки")
            else "подпись покупки не записана")
    return (f"🟢 {п['время']} · {группа_словом(п.get('группа'))} · {ист} · "
            f"{размер} · {токен_словом(п.get('имя_токена'), п.get('минт'))} · "
            f"{маршрут} · {s} ({если_перед}) · {нац} · {довёз} · {ссыл}")


def строка_продажи(п: dict) -> str:
    """🟢/🔴 продажа: цвет по знаку итога (слово владельца 27.09, вечер)."""
    F3 = _f3()
    итог = п.get("итог_sol")
    знак = "🟢" if isinstance(итог, (int, float)) and float(итог) >= 0 else "🔴"
    держ = (f"удержание {float(п['удержание_с']):.0f} с"
            if п.get("удержание_с") is not None
            else "удержание не посчитано (нет времени покупки или продажи)")
    if п.get("размер_sol") is not None and п.get("вышло_sol") is not None:
        деньги = f"{_sol(п['размер_sol'])} → {_sol(п['вышло_sol'])} SOL"
    elif п.get("размер_sol") is None:
        деньги = "вошло не записано"
    else:
        деньги = f"{_sol(п['размер_sol'])} → вышло по цепи не записано"
    проц = (f"итог {_проц_зн(п['итог_процент'])}"
            if п.get("итог_процент") is not None
            else "итог % не посчитан (нет входа или выхода)")
    итог_с = (f"итог {_sol_зн(итог)} SOL" if isinstance(итог, (int, float))
              else "итог SOL не посчитан (нет выхода или издержек)")
    изд = п.get("издержки") or {}
    if изд.get("сумма") is not None:
        части = []
        for имя, ключ in (("чаевые", "чаевые"), ("приоритет", "приоритет"),
                           ("рента", "рента")):
            if изд.get(ключ) is not None:
                части.append(f"{имя} {_sol(изд[ключ])}")
        хвост = f" ({', '.join(части)})" if части else ""
        издержки_с = f"издержки {_sol(изд['сумма'])} SOL{хвост}"
    else:
        издержки_с = f"издержки не посчитаны ({изд.get('почему') or 'причина не названа'})"
    ссыл = (F3.ссылка(п["подпись_продажи"], "tx") if п.get("подпись_продажи")
            else "подпись продажи не записана")
    return (f"{знак} {держ} · {деньги} · {проц} · {итог_с} · "
            f"{издержки_с} · {ссыл}")


def сообщение(п: dict, *, пометка: str | None = None) -> str:
    """Полная строка позиции: покупка, и продажа -- если она есть."""
    строки = []
    if пометка:
        строки.append(_f3().экран(пометка))
    строки.append(строка_покупки(п))
    if п.get("продана"):
        строки.append(строка_продажи(п))
    return "\n".join(строки)


def доложить(поз: dict, *, оповещатель, имя_токена: str | None = None,
              имя_источника: str | None = None,
              пометка: str | None = None) -> dict:
    """ЕДИНСТВЕННЫЙ вход для всех путей. Возвращает, что ушло и почему.

    Покупка -- своим сообщением под ключом позиции. Продажа -- дописывается к
    нему; если сообщения покупки нет (перезапуск, потерянный ключ), уходит
    полная строка покупка+продажа одним сообщением: отдельная строка продажи
    без покупки владельцу не нужна (его слово, п.3).
    """
    п = поля(поз, имя_токена=имя_токена, имя_источника=имя_источника)
    ключ = п.get("cid") or (п.get("подпись_покупки") or "")[:32]
    if not п.get("продана"):
        итог = оповещатель.послать(сообщение(п, пометка=пометка), ключ=ключ)
        return {"вид": "покупка", "ключ": ключ, "отправка": итог, "поля": п}
    итог = оповещатель.дописать(ключ, строка_продажи(п),
                                 запасной_полный=сообщение(п, пометка=пометка))
    return {"вид": "продажа", "ключ": ключ, "отправка": итог, "поля": п}


