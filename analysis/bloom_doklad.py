# группы сам и отказывает по нему на КАЖДОМ сигнале, но говорит об этом только
# строкой в журнале хоста. 02.10 группа cand1 встала на свой стоп в 05:39:06Z
# (убыток по цепи -0.345571818 SOL при пороге -0.3), и владелец узнал об этом
# лишь потому, что строку нашли в журнале: за следующие пять часов гейт отказал
# по ней ещё 17 раз, а в чате всё это выглядело тишиной. Молчащий стоп не
