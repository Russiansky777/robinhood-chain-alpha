"""ОДИН докладчик сделки полосы. ОКОНЧАТЕЛЬНЫЙ ФОРМАТ владельца (28.09).

Слово владельца 28.09: "TELEGRAM -- ОКОНЧАТЕЛЬНЫЙ ФОРМАТ. Заменяет все прошлые
поручения по строкам (формат 2, формат 3, «ПЕРЕСБОРКА», докладчик). Основа --
формат владельца от 26.09. Один докладчик по строке позиции для всех путей
полосы (одна нога, две ноги, продажа своя, продажа через Jupiter); ответ
площадки не нужен. Без редактирования сообщений: BUY уходит один раз, когда
данные по цепи собраны (1-3 с после посадки). Строк Bloom нет."

ТРИ СТРОКИ И ВСЁ:
  BUY   -- одно сообщение из трёх строк (сделка, место источника, наше место и путь);
  SELL  -- одно сообщение (плюс вторая строка, если продажа не с первой попытки);
  СВОДКА раз в час -- четыре строки, окно времени в тексте не пишется.

ПОЛЕ -- ЛИБО ЧИСЛО, ЛИБО ПУСТО. Прежнее правило "если поле неизвестно -- писать
словом, почему" ОТМЕНЕНО владельцем (п.5: "убрать ... пояснения вместо чисел
(поле либо число, либо пусто)"). Поэтому неизвестное поле не печатается вовсе --
ни прочерком, ни причиной. Причины остаются в записи позиции и в отчётах.

ЧЕГО ЗДЕСЬ БОЛЬШЕ НЕТ (п.5 владельца): "новых соединений", "мс от решения / от
ответа", "покупка села, продажа подтверждена", плюс перед возвратом, дублей
строки продажи, разбивки издержек, "1 нога / 2 ноги", адреса рядом с именем.

РЕНТА В ИТОГ НЕ ВХОДИТ. Владелец 28.09: "рента 0.0015-0.0030 в издержках при
закрытии счёта в продаже -- почему считается расходом, если возвращается".
Она и возвращается: закрытие счёта токена возвращает ренту на кошелёк. Поэтому
итог считается чистыми ПОСЛЕ ЧАЕВЫХ И ПРИОРИТЕТА (слово владельца, п.2), а
рента из расхода строки убрана: в pnl_counted_spend_sol она по-прежнему лежит --
это учёт службы, а не строка.
"""
