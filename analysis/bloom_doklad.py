def не_число(x) -> bool:
    """True, если значение в деньги не годится. Строка "0.1" числом НЕ считается:
    подмена типа на деньгах молча даёт другой ответ, а не ошибку."""
    return not isinstance(x, (int, float)) or isinstance(x, bool)


def стопы_групп(позиции: dict, *, группы=None, сейчас=None,
                 счёт_полосы=None, порог_группы=None) -> dict:
    """По каждой группе: стоит ли её суточный стоп, убыток по цепи и порог.

    Отдаётся наружу СЛОВАРЁМ, а не строкой: по нему получасовая строка хоста
    (bloom_host_stroki.получасовая) может сказать "стопы: cand1 стоит
    (-0.346/-0.300)" вместо одного слова про рубильник, а доклад -- поставить ту
    же пару в сводку. Два написания одного вывода разойдутся, поэтому число здесь
    одно, а печатают его строкой ниже.

    Модуля полосы на хосте нет -- ОТКАЗ СЛОВАМИ. Вернуть пустые группы значило бы
    сказать "стопов нет" там, где мы просто не спросили.

    `счёт_полосы(позиции, группа)` и `порог_группы(группа)` -- те же две функции
    полосы, переданные извне; по умолчанию зовутся они сами. Это не украшение:
    у хоста суточный счёт уже посчитан, и второй его счёт разошёлся бы молча, а
    ветка "числа нет" иначе непроверяема -- состояние_полосы всегда отдаёт число,
    и подсунуть ей пустоту нечем.
    """
    из_ = {"ok": False, "почему_нет": None, "сутки": None, "как_сутки": None,
            "группы": {}, "стоят": []}
    try:
        import bloom_own_send as OS  # noqa: PLC0415
    except Exception as exc:  # noqa: BLE001
        из_["почему_нет"] = (f"модуль полосы не загрузился ({type(exc).__name__}) -- "
                              "про стопы групп сказать нечем")
        return из_
    позиции = позиции if isinstance(позиции, dict) else {}
    метка = getattr(OS, "МЕТКА", None)
    имена = []
    for г in (группы or []):
        if г and str(г) not in имена:
            имена.append(str(г))
    for п in позиции.values():
        п = п if isinstance(п, dict) else {}
        # ТОЛЬКО ПОЗИЦИИ ПОЛОСЫ: суточный счёт группы считается по ним же, и
        # чужая позиция завела бы в список группу, которой у полосы нет.
        if метка is not None and п.get("lane") != метка:
            continue
        г = п.get("lane_group") or п.get("group")
        if г and str(г) not in имена:
            имена.append(str(г))
    if not имена:
        из_["почему_нет"] = ("ни одной группы полосы не названо и в позициях их "
                              "нет -- считать стопы не по чему")
        return из_
    счёт = (счёт_полосы if callable(счёт_полосы)
            else (lambda п_, г_: OS.состояние_полосы(п_, сейчас=сейчас, группа=г_)))
    порог_ф = (порог_группы if callable(порог_группы) else OS.потолок_группы)
    for г in имена:
        try:
            с = счёт(позиции, г)
            пг = порог_ф(г)
        except Exception as exc:  # noqa: BLE001
            из_["группы"][г] = {"стоит": None, "убыток_по_цепи_sol": None,
                                 "порог_sol": None,
                                 "почему_нет": (f"счёт группы не посчитан "
                                                 f"({type(exc).__name__})")}
            continue
        убыток = с.get("pnl_chain_sol")
        порог_зн = (пг or {}).get("stop_loss_sol")
        з = {"стоит": None, "убыток_по_цепи_sol": None, "порог_sol": None,
              "сделок": с.get("today"), "по_учёту_sol": с.get("pnl_sol"),
              "по_цепи_n": с.get("pnl_chain_n"),
              "по_полям_n": с.get("pnl_chain_fields_n"),
              "открытых_n": с.get("pnl_chain_open_n"), "почему_нет": None}
        if не_число(убыток) or не_число(порог_зн):
            # НЕЗНАНИЕ НЕ ПРЕВРАЩАЕТСЯ В "СТОП СНЯТ". Гейт в этом же случае
            # считает стоп СТОЯЩИМ (незнание = замок); доклад не гейт и торговлю
            # не трогает, поэтому он говорит "не знаю" словами -- но ноль и
            # "снят" здесь одинаково врали бы.
            з["почему_нет"] = (f"убыток по цепи {убыток!r} или порог {порог_зн!r} "
                                "не прочитаны")
            из_["группы"][г] = з
            continue
        порог = -abs(float(порог_зн))
        з.update(убыток_по_цепи_sol=round(float(убыток), 9), порог_sol=порог,
                  стоит=float(убыток) <= порог)
        if з["стоит"]:
            из_["стоят"].append(г)
        из_["группы"][г] = з
        из_["сутки"] = с.get("day")
        из_["как_сутки"] = с.get("day_how")
    из_["ok"] = True
    return из_


def строка_стопов(ст: dict) -> str:
    """«стопы: cand1 стоит (−0.346/−0.300)» -- одной строкой для получасовой.

    ТРИ ЗНАКА, А НЕ ДВА (слово владельца 02.10 про итоги групп): порог −0.3 и
    убыток −0.346 на двух знаках читались бы как «−0.35/−0.30», и разница с
    порогом в полтысячных пропадала бы вовсе. Точное число цепи остаётся в
    тревоге и в поле убыток_по_цепи_sol.

    НИ ОДНОГО ТИХОГО ОТВЕТА. Не посчитали -- так и сказано; стоп не стоит ни у
    одной группы -- сказано и это, потому что «стопы: » без продолжения читалось
    бы как сбой строки.
    """
    ст = ст if isinstance(ст, dict) else {}
    if not ст.get("ok"):
        return f"стопы: не посчитаны ({ст.get('почему_нет') or 'причина не названа'})"
    части = []
    for г in ст.get("стоят") or []:
        з = (ст.get("группы") or {}).get(г) or {}
        части.append(f"{г} стоит ({_зн(з.get('убыток_по_цепи_sol'), 3)}/"
                      f"{_зн(з.get('порог_sol'), 3)})")
    # НЕПРОЧИТАННАЯ ГРУППА НАЗЫВАЕТСЯ ТУТ ЖЕ: иначе строка «ни один не стоит»
    # накрыла бы собой группу, про которую мы ничего не знаем.
    немые = [г for г, з in (ст.get("группы") or {}).items()
             if (з or {}).get("стоит") is None]
    if немые:
        части.append("не знаю: " + ", ".join(sorted(немые)))
    if not части:
        return "стопы: ни один не стоит"
    return "стопы: " + " · ".join(части)


def тревога_стопов_групп(позиции: dict, *, оповещатель, состояние,
                          группы=None, сейчас=None, пропущено=None) -> dict:
    """ОДНА тревога на группу за сутки в момент, когда её стоп сработал.

    Повтор гасится отметкой в счётчиках состояния (ОТМЕТКА_ТРЕВОГ_СТОПА:
    {группа: сутки}) -- тем же приёмом, что pravilo_4b_tg_poslano у продавца.
    Отметки негде поставить -- тревога НЕ ПОСЫЛАЕТСЯ и причина названа: без
    отметки строка ушла бы на каждом круге доклада, то есть десятки раз за час,
    и тревога перестала бы читаться как тревога.

    `пропущено` -- сколько сигналов группы гейт уже отклонил (см.
    пропущено_сигналов): в первой тревоге это обычно 1, и ноль тут не выдумывается.
    """
    из_ = {"послано": 0, "строки": [], "пропущено_уже_посланных": 0,
            "почему_нет": None, "стопы": None}
    ст = стопы_групп(позиции, группы=группы, сейчас=сейчас)
    из_["стопы"] = ст
    if not ст.get("ok"):
        из_["почему_нет"] = ст.get("почему_нет")
        return из_
    if not ст.get("стоят"):
        из_["почему_нет"] = "ни одна группа на стопе не стоит"
        return из_
    if состояние is None or not hasattr(состояние, "counters"):
        из_["почему_нет"] = ("отметку негде поставить (состояние не умеет "
                              "счётчики) -- без неё тревога уходила бы каждый круг")
        return из_
    try:
        счёт = состояние.counters() or {}
    except Exception as exc:  # noqa: BLE001
        из_["почему_нет"] = f"счётчики не прочитаны ({type(exc).__name__})"
        return из_
    отметки = счёт.get(ОТМЕТКА_ТРЕВОГ_СТОПА)
    отметки = dict(отметки) if isinstance(отметки, dict) else {}
    # СУТКИ НЕ НАЗВАНЫ -- ОТМЕТКА ВСЁ РАВНО РАБОТАЕТ. Здесь стояло «и сутки
    # непустые», и из-за этого при непрочитанных сутках отметка не совпадала
    # сама с собой: тревога уходила КАЖДЫЙ круг доклада, то есть десятки раз в
    # час -- ровно то, от чего отметка и поставлена. Пустые сутки -- это своё
    # значение отметки: пока они не прочитаны, тревога уходит один раз, а когда
    # дата появится, отметка не совпадёт и тревога уйдёт заново, как и должна.
    сутки = str(ст.get("сутки") or "")
    менялось = False
    for г in ст["стоят"]:
        if отметки.get(г) == сутки:
            из_["пропущено_уже_посланных"] += 1
            continue
        з = (ст.get("группы") or {}).get(г) or {}
        # ПРОПУЩЕННЫЕ -- ЛИБО СЛОВАРЁМ ПО ГРУППАМ, ЛИБО ОДНИМ ЧИСЛОМ: вызывающий
        # считает их пропущено_сигналов() и отдаёт как есть, своего счёта тут нет.
        n = ((пропущено or {}).get(г) if isinstance(пропущено, dict) else пропущено)
        # ЧИСЛО ЦЕПИ В ТРЕВОГЕ -- ПОЛНЫМ, А НЕ ТРЕМЯ ЗНАКАМИ. Три знака -- для
        # строк сводки, где числа стоят рядами; тревогу же сверяют со строкой
        # гейта в журнале хоста, а там лежит −0.345571818, и округление сделало
        # бы сверку невозможной.
        текст = (f"группа {г}: убыток за сутки ПО ЦЕПИ "
                  f"{_зн(з.get('убыток_по_цепи_sol'), 9)} SOL при пороге "
                  f"{_зн(з.get('порог_sol'), 3)} -- группа не торгует до полуночи "
                  f"Мадрида (сутки {сутки or 'не названы'}); сделок за сутки "
                  f"{з.get('сделок')}, из них по цепи {з.get('по_цепи_n')}, по "
                  f"полям {з.get('по_полям_n')}, открытых {з.get('открытых_n')}")
        if not не_число(n):
            текст += f"; пропущено {int(n)} сигналов"
        try:
            import bloom_notify as NT  # noqa: PLC0415

            текст = NT.строка_тревоги("стоп группы", текст)
        except Exception:  # noqa: BLE001
            текст = "⚠️ " + текст
        try:
            оповещатель.послать(текст)
        except Exception as exc:  # noqa: BLE001
            из_["почему_нет"] = f"тревога не ушла ({type(exc).__name__})"
            return из_
        из_["послано"] += 1
        из_["строки"].append(текст)
        отметки[г] = сутки
        менялось = True
    if менялось:
        # ОТМЕТКА ПИШЕТСЯ ПОСЛЕ ОТПРАВКИ, а не до: упасть на отправке и остаться
        # с отметкой значило бы проглотить тревогу навсегда.
        счёт[ОТМЕТКА_ТРЕВОГ_СТОПА] = отметки
        try:
            состояние.save_counters(счёт)
        except Exception as exc:  # noqa: BLE001
            из_["почему_нет"] = (f"отметка не записана ({type(exc).__name__}) -- "
                                  "следующий круг пошлёт тревогу снова")
    return из_


def _мгновение(ts_utc) -> float | None:
    """'2026-10-02T05:39:06Z' -> unix. Не разобралось -- None, а не ноль."""
    т = ts_utc if isinstance(ts_utc, str) else None
    if not т:
        return None
    try:
        import calendar  # noqa: PLC0415

        return float(calendar.timegm(time.strptime(т[:19] + "Z",
                                                    "%Y-%m-%dT%H:%M:%SZ")))
    except Exception:  # noqa: BLE001
        return None


def пропущено_сигналов(строки, *, с=None, до=None) -> dict:
    """Сколько сигналов группы гейт отклонил, пока она стоит на суточном стопе.

    СЧИТАЕТСЯ ПО ЖУРНАЛУ РЕШЕНИЙ, А НЕ НОВЫМ СЧЁТЧИКОМ. Гейт уже пишет каждый
    такой отказ строкой (stage=gate, group=<группа>, why_not="предел полосы:
    убыток полосы за сутки ПО ЦЕПИ ..."): это те самые строки, по которым стоп
    cand1 и нашли 02.10. Новый счётчик пришлось бы вызывать из гейта, то есть
    завести второе место, где число может разойтись с журналом.

    Окно `с`/`до` -- unix-секунды по метке ts_utc строки. Строка без метки в
    окно НЕ попадает и считается отдельно (`без_метки`): молча взять её значило
    бы приписать вчерашние отказы сегодняшнему стопу.
    """
    из_ = {"ok": True, "по_группам": {}, "строк": 0, "подошло": 0,
            "без_метки": 0, "негодных": 0, "почему_нет": None}
    try:
        перебор = list(строки or [])
    except Exception as exc:  # noqa: BLE001
        return {**из_, "ok": False,
                 "почему_нет": f"журнал не перебирается ({type(exc).__name__})"}
    for р in перебор:
        if not isinstance(р, dict):
            из_["негодных"] += 1
            continue
        из_["строк"] += 1
        почему = str(р.get("why_not") or "")
        if not any(с_ in почему for с_ in СЛОВА_СТОПА_В_ЖУРНАЛЕ):
            continue
        # СТАДИЯ ПРОВЕРЯЕТСЯ, А НЕ УГАДЫВАЕТСЯ ПО ТЕКСТУ: то же слово про стоп
        # стоит и в тревогах, и в строках признака жизни, и считать их как
        # отклонённые сигналы значило бы завысить число в разы.
        if str(р.get("stage") or "") not in ("gate", "lane_gate"):
            continue
        if р.get("ok") is True or р.get("sent") is True:
            continue
        if с is not None or до is not None:
            т = _мгновение(р.get("ts_utc"))
            if т is None:
                из_["без_метки"] += 1
                continue
            if с is not None and т < float(с):
                continue
            if до is not None and т >= float(до):
                continue
        г = str(р.get("group") or р.get("lane_group") or "?")
        из_["по_группам"][г] = из_["по_группам"].get(г, 0) + 1
        из_["подошло"] += 1
    return из_


def журнал_решений(путь, *, предел_строк: int = 500_000) -> dict:
    """Строки журнала решений из файла. Чужие строки НАЗВАНЫ, а не проглочены.

    Файл бывает двух видов: чистый decisions.jsonl службы и выгрузка журнала
    хоста, где строки решений лежат вперемешку с текстом systemd. Поэтому не-JSON
    строка здесь не ошибка файла, но и не невидимка: она идёт в `чужих`, и по
    этому числу видно, тот ли файл дали.
    """
    из_ = {"ok": False, "строки": [], "чужих": 0, "почему_нет": None}
    try:
        import json as _js  # noqa: PLC0415

        with open(str(путь), encoding="utf-8", errors="replace") as ф:
            for н, с_ in enumerate(ф):
                if н >= предел_строк:
                    из_["почему_нет"] = (f"прочитано {предел_строк} строк -- "
                                          "дальше не читаем")
                    break
                с_ = с_.strip()
                if not с_.startswith("{"):
                    из_["чужих"] += 1
                    continue
                try:
                    из_["строки"].append(_js.loads(с_))
                except Exception:  # noqa: BLE001
                    из_["чужих"] += 1
    except Exception as exc:  # noqa: BLE001
        из_["почему_нет"] = f"журнал не прочитан ({type(exc).__name__})"
        return из_
    из_["ok"] = True
    return из_


