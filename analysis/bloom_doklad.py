def поля(поз: dict, *, имя_токена: str | None = None,
          имя_источника: str | None = None) -> dict:
    """Все числа строк из ОДНОЙ записи позиции. Неизвестное -- None."""
    поз = поз or {}
    имя_токена = имя_токена or поз.get("token_name")
    имя_источника = имя_источника or поз.get("source_name")
    if not имя_источника and поз.get("source"):
        try:
            import bloom_source_groups as SG  # noqa: PLC0415

            имя_источника = (SG.метка_адреса(поз["source"]) or {}).get("name")
        except Exception:  # noqa: BLE001
            имя_источника = None
    вошло = поз.get("sol_in")
    вышло = возврат_sol(поз)
    # ИТОГ -- ОДНОЙ ФОРМУЛОЙ СЛУЖБЫ. Прежний счёт здесь вычитал только чаевые и
    # приоритет, а ренту созданных счетов и базовый тариф не видел вовсе: на
    # сделке 29.09 19:05:05Z строка показывала -0.000549 вместо -0.003531.
    счёт = итог_и_расход(поз)
    расход = счёт.get("расход")
    итог = счёт.get("итог")
    процент = (итог / float(вошло) * 100.0
               if итог is not None and вошло else None)
    слот_наш = _первое(поз, ("lane_landed_slot", "own_tx_seen_slot", "our_slot",
                              "entry_slot"), int)
    слот_ист = поз.get("source_slot")
    s_n = (слот_наш - слот_ист
            if isinstance(слот_наш, int) and isinstance(слот_ист, int) else None)
    т_покупки = _первое(поз, ("own_tx_seen_ts", "ts_accepted", "ts_sent", "ts_intent"))
    # ВРЕМЯ ПРОДАЖИ -- ВРЕМЯ САМОЙ ПРОДАЖИ, А НЕ ЗАПИСИ О ЗАКРЫТИИ. Замер 28.09
    # по девяти сделкам ночи: закрытие записывается РОВНО через 15.0 с после
    # отправки продажи -- это второй круг сторожа (период 15 с, закрытие по
    # двум нулям подряд). Считать по нему удержание значит завышать его на
    # целый круг: 43-52 с вместо настоящих 25-37 с.
    т_продажи = _первое(поз, ("ts_last_sell_attempt", "ts_jup_attempt",
                               "ts_closed"))
    удержание = (max(0.0, float(т_продажи) - float(т_покупки))
                 if т_покупки and т_продажи else None)
    # ПУТЬ: от посадки источника до нашей отправки, тремя куска́ми (слово
    # владельца). "Увидели" -- возраст сигнала на нашем узле (seen_lag_ms),
    # "решили" -- приход сигнала до решения, "собрали" -- решение до отправки.
    def мс(а, б):
        if not isinstance(а, (int, float)) or not isinstance(б, (int, float)):
            return None
        з = (float(б) - float(а)) * 1000.0
        return round(з, 0) if з >= 0 else None

    увидели = поз.get("seen_lag_ms")
    увидели = round(float(увидели), 0) if isinstance(увидели, (int, float)) else None
    # "СОБРАЛИ" -- ИЗМЕРЕННЫЕ КУСКИ СБОРКИ ПОЛОСЫ, а не разность ts_intent и
    # ts_sent: у своей отправки намерение ПИШЕТСЯ ПОСЛЕ отправки, и та разность
    # выходит отрицательной (проверено на всех девяти сделках ночи 27->28.09 --
    # путь в строке не печатался вовсе). Здесь: сборка + варианты + подпись +
    # nonce, всё по своим часам полосы.
    части_сборки = [поз.get(к) for к in ("lane_build_ms", "lane_variants_ms",
                                          "lane_sign_ms", "lane_nonce_ms")]
    части_сборки = [float(x) for x in части_сборки if isinstance(x, (int, float))]
    собрали = round(sum(части_сборки), 0) if части_сборки else None
    # ОТ ПРИЁМА СИГНАЛА ДО ОТПРАВКИ -- по времени самой отправки покупки.
    послано_в = _первое(поз, ("lane_ts_sent_buy", "ts_sent"))
    после_приёма = мс(поз.get("signal_recv_ts"), послано_в)
    решили = None
    if после_приёма is not None and собрали is not None:
        решили = max(0.0, round(после_приёма - собрали, 0))
    elif после_приёма is not None:
        решили = после_приёма
    # ПУТЬ ВСЕГО -- от посадки источника до нашей отправки: возраст сигнала
    # плюс всё, что мы потратили после его приёма.
    путь_всего = (round(увидели + после_приёма, 0)
                  if увидели is not None and после_приёма is not None else None)
    неудач = int(поз.get("sell_attempts") or 0) + int(поз.get("jup_attempts") or 0)
    исход = поз.get("last_sell_outcome") or {}
    причина = None
    if исход.get("ok") is False:
        причина = (исход.get("error_code") or исход.get("why_not")
                   or исход.get("error") or None)
    return {
        "cid": поз.get("client_order_id") or поз.get("cid"),
        "время": _чч_мм_сс(т_покупки),
        "время_продажи": _чч_мм_сс(т_продажи),
        "группа": поз.get("lane_group") or поз.get("group"),
        "имя_источника": имя_источника,
        "вошло_sol": вошло,
        "минт": поз.get("mint"),
        "имя_токена": имя_токена,
        "подпись_источника": поз.get("source_sig"),
        "подпись_покупки": подпись_покупки(поз),
        "подпись_продажи": подпись_продажи(поз),
        "место_источника": поз.get("source_block_index"),
        "место_источника_всего": поз.get("source_block_total"),
        "наше_место": поз.get("block_index"),
        "наше_место_всего": поз.get("block_total"),
        "s_n": s_n,
        "путь_увидели": увидели, "путь_решили": решили, "путь_собрали": собрали,
        "путь_всего": путь_всего,
        "довёз": (поз.get("lane_pool_winner") or поз.get("lane_send_point")),
        "перед_нами": поз.get("slot_peers_before_us"),
        "копировщиков": поз.get("slot_peers_known_copiers"),
        "вышло_sol": вышло, "расход_sol": расход,
        "итог_sol": итог, "итог_процент": процент,
        "удержание_с": удержание,
        # УДЕРЖАНИЕ В СЛОТАХ ПО ФАКТУ (решение владельца 28.09): слот посадки
        # продажи минус слот посадки покупки. Секунды и слоты -- разные величины:
        # длина слота по замеру 0.2659 с, а не 0.4, и показывать только секунды
        # значит скрывать, во сколько слотов уложилось удержание.
        "удержание_слотов": удержание_в_слотах(поз),
        "удержание_слотов_план": (int(поз["hold_slots"])
                                   if isinstance(поз.get("hold_slots"), (int, float))
                                   else None),
        "попыток_продажи": неудач if неудач > 1 else None,
        "причина_продажи": причина,
        "продана": подпись_продажи(поз) is not None or поз.get("state") == "closed",
    }


def кружки(процент) -> str:
    """Маркер продажи по итогу (слово владельца 28.09, п.2).

    Строка ВСЕГДА начинается с 🔴 -- это маркер продажи, а не убытка. Дальше:
    плюс с +20 % и до ×2 -- 🔴🟢; от ×2 -- 🔴 и по одному 🟢 за каждый X
    (×2 -> 🔴🟢🟢 ... ×5 -> 🔴 и пять 🟢); больше ×5 -- 🔴⭐; больше ×10 -- 🔴🌟.
    Минус до −20 % -- 🔴; от −20 % до −50 % -- 🔴🟠; хуже −50 % -- 🔴⚫.
    """
    if процент is None:
        return "🔴"
    п = float(процент)
    if п > 1000.0:
        return "🔴🌟"
    if п > 500.0:
        return "🔴⭐"
    if п >= 100.0:
        # ×2 -- это +100 %: кратность 2, и зелёных ровно столько же.
        кратность = min(5, int(п // 100.0) + 1)
        return "🔴" + "🟢" * кратность
    if п >= 20.0:
        return "🔴🟢"
    if п >= -20.0:
        return "🔴"
    if п >= -50.0:
        return "🔴🟠"
    return "🔴⚫"


def _через(части: list) -> str:
    return " · ".join([ч for ч in части if ч])


def строка_buy(п: dict) -> str:
    """BUY -- одно сообщение из трёх строк. Пустое поле не печатается."""
    первая = _через([
        f"🟢 {п['время']} BUY" if п.get("время") else "🟢 BUY",
        п.get("группа") and _экран(п["группа"]),
        п.get("имя_источника") and _экран(п["имя_источника"]),
        (f"{float(п['вошло_sol']):g} SOL" if п.get("вошло_sol") is not None else ""),
        (_экран(п.get("имя_токена")) if п.get("имя_токена")
         else (_экран(str(п["минт"])[:6]) if п.get("минт") else "")),
        ссылка(п.get("подпись_источника")),
    ])
    строки = [первая]
    # ПОЛЯ МЕСТА ВСЕГДА НА МЕСТЕ (слово владельца 28.09, п.3а): "поля места
    # (tx: место / мы: S+N, перед нами, копировщиков), если блок ещё не
    # прочитан, -- «—»". Раньше строка просто не печаталась, и по чату нельзя
    # было отличить "места нет" от "место не спросили".
    if isinstance(п.get("место_источника"), int) and isinstance(п.get("место_источника_всего"), int) and п["место_источника_всего"]:
        доля = п["место_источника"] / п["место_источника_всего"]
        строки.append(f"tx: место {п['место_источника']}/{п['место_источника_всего']} ({доля:.2f})")
    elif isinstance(п.get("место_источника"), int):
        строки.append(f"tx: место {п['место_источника']}")
    else:
        строки.append(НЕТ_ДАННЫХ_СТРОКА)
    наше = []
    if п.get("s_n") is not None:
        место = (f", {п['наше_место']}/{п['наше_место_всего']}"
                 if isinstance(п.get("наше_место"), int)
                 and isinstance(п.get("наше_место_всего"), int) else "")
        наше.append(f"S+{int(п['s_n'])}{место}")
    elif isinstance(п.get("наше_место"), int) and isinstance(п.get("наше_место_всего"), int):
        наше.append(f"{п['наше_место']}/{п['наше_место_всего']}")
    else:
        наше.append(f"S+{НЕТ_ДАННЫХ}")
    if п.get("путь_всего") is not None:
        куски_п = [п.get("путь_увидели"), п.get("путь_решили"), п.get("путь_собрали")]
        хвост_п = ""
        if all(x is not None for x in куски_п):
            хвост_п = (f" (увидели {int(куски_п[0])} · решили {int(куски_п[1])} · "
                       f"собрали {int(куски_п[2])})")
        наше.append(f"путь {int(п['путь_всего'])} мс{хвост_п}")
    if п.get("довёз"):
        наше.append(_экран(п["довёз"]))
    # ПЕРЕД НАМИ -- только при S+0; при S+1 и хуже вопрос другой: кто успел в S+0.
    соседи = []
    имя_соседей = "перед нами" if п.get("s_n") == 0 else "в S+0 успели"
    if isinstance(п.get("перед_нами"), int):
        соседи.append(f"{имя_соседей}: {int(п['перед_нами'])}")
    else:
        соседи.append(f"{имя_соседей}: {НЕТ_ДАННЫХ}")
    if isinstance(п.get("копировщиков"), int):
        соседи.append(f"копировщиков {int(п['копировщиков'])}")
    else:
        соседи.append(f"копировщиков {НЕТ_ДАННЫХ}")
    if соседи:
        наше.append(", ".join(соседи))
    if наше:
        строки.append("мы: " + " · ".join(наше))
    return "\n".join(строки)


def строка_sell(п: dict) -> str:
    """SELL -- одно сообщение; вторая строка только при повторных попытках."""
    деньги = ""
    if п.get("вошло_sol") is not None and п.get("вышло_sol") is not None:
        деньги = f"{_чис(п['вошло_sol'])} → {_чис(п['вышло_sol'])} SOL"
        if п.get("итог_процент") is not None:
            деньги += f" ({_проц(п['итог_процент'])})"
    первая = _через([
        f"{кружки(п.get('итог_процент'))} {п['время_продажи']} SELL"
        if п.get("время_продажи") else f"{кружки(п.get('итог_процент'))} SELL",
        (_экран(п.get("имя_токена")) if п.get("имя_токена")
         else (_экран(str(п["минт"])[:6]) if п.get("минт") else "")),
        удержание_словами(п),
        деньги,
        ссылка(п.get("подпись_продажи")),
    ])
    строки = [первая]
    if п.get("попыток_продажи"):
        хвост = (f" · причина: {_экран(п['причина_продажи'])}"
                 if п.get("причина_продажи") else "")
        строки.append(f"попыток {int(п['попыток_продажи'])}{хвост}")
    return "\n".join(строки)


def сводка_часа(*, сделок: int, объём_sol=None, итог_sol=None, итог_процент=None,
                 s0=None, в_цели=None, промахов=None, путь_медиана_мс=None,
                 довозили: dict | None = None, мест_нет=None) -> str:
    """Сводка раз в час. Окно времени в тексте НЕ пишется (слово владельца).

    СТРОКИ «стоп: полоса …» ЗДЕСЬ БОЛЬШЕ НЕТ (слово владельца 28.09, п.3г):
    "стопы -- только тревогой при срабатывании". Суточный стоп продолжает
    считаться и бить тревогу в момент срабатывания; в часовой сводке его
    цифра была шумом -- она повторялась каждый час, ничего не требуя.
    """
    первая = f"📊 сделок {int(сделок)}"
    if объём_sol is not None:
        первая += f" на {_чис(объём_sol, 2)} SOL"
    if итог_sol is not None:
        первая += f" · итог {_зн(итог_sol)} SOL"
        if итог_процент is not None:
            первая += f" ({_проц(итог_процент, 2)})"
    строки = [первая]
    вторая = []
    # ДОЛИ -- ПО СДЕЛКАМ С ИЗВЕСТНЫМ МЕСТОМ (слово владельца 28.09, п.3г:
    # "место неизвестно -- отдельно «место н/д N», не в ноль S+0"). Делить на
    # все сделки значило бы занизить долю S+0 ровно на те, у которых место не
    # прочитано, и выглядело бы это как промах полосы, которого не было.
    с_местом = int(сделок)
    if мест_нет is not None:
        с_местом = max(0, int(сделок) - int(мест_нет))
    if s0 is not None:
        доля = f" ({s0 / с_местом * 100:.0f} %)" if с_местом else ""
        вторая.append(f"S+0 {int(s0)}{доля}")
    if в_цели is not None:
        доля = f" ({в_цели / с_местом * 100:.0f} %)" if с_местом else ""
        вторая.append(f"в цели {int(в_цели)}{доля}")
    if мест_нет:
        вторая.append(f"место н/д {int(мест_нет)}")
    if промахов is not None:
        вторая.append(f"промахов наших {int(промахов)}")
    if путь_медиана_мс is not None:
        вторая.append(f"путь медиана {int(путь_медиана_мс)} мс")
    if вторая:
        строки.append(" · ".join(вторая))
    if довозили:
        части = [f"{_экран(к)} {int(v)}" for к, v in
                 sorted(довозили.items(), key=lambda кв: -int(кв[1])) if v]
        if части:
            строки.append("довозили: " + ", ".join(части))
    return "\n".join(строки)


def доложить_покупку(поз: dict, *, оповещатель, имя_токена: str | None = None,
                      имя_источника: str | None = None,
                      посадка_почему: str | None = None) -> dict:
    """BUY одним сообщением. Без редактирования: уходит один раз.

    `посадка_почему` -- причина, по которой посадка НЕ подтверждена к сроку
    (слово владельца 01.10, п.4). С ней строка называет причину вместо трёх
    прочерков "S+? · — мс · — / —→—": по прочеркам нельзя было отличить "покупка
    не села" от "узел не отдал место в блоке".
    """
    п = поля(поз, имя_токена=имя_токена, имя_источника=имя_источника)
    if посадка_почему:
        п["посадка_почему"] = str(посадка_почему)[:160]
    ключ = п.get("cid") or (п.get("подпись_покупки") or "")[:32]
    # НОВЫЙ ВИД СТРОКИ -- МОДУЛЕМ ФОРМАТА (слово владельца 30.09 вечером).
    # Модуль сам не падает НИКОГДА (у него второй аргумент -- прежняя строка, она
    # же ответ при любом сбое), но ИМПОРТ падает, если модуля нет на хосте --
    # поэтому обёртка. Молчание в чате хуже старого вида строки.
    #
    # `поз` передаётся целиком: регион отправки и регион лидера лежат в ЗАПИСИ
    # ПОЗИЦИИ (lane_region*), а в поля() их нет.
    прежняя = строка_buy(п)
    текст = прежняя
    try:
        import c2_doklad_format as C2F  # noqa: PLC0415
        текст = C2F.строка_buy(п, прежняя, поз=поз)
    except Exception:  # noqa: BLE001
        текст = прежняя
    # СТРОКА СЧИТАЕТСЯ ОДИН РАЗ. Раньше здесь было два вызова строка_buy: один в
    # отправку, второй в ответ. Пока формат один -- разницы нет, но два расчёта
    # одного текста однажды разойдутся, и доклад разошёлся бы с записью.
    итог = оповещатель.послать(текст, ключ=ключ)
    return {"вид": "BUY", "ключ": ключ, "отправка": итог, "поля": п,
            "текст": текст}


def доложить_продажу(поз: dict, *, оповещатель, имя_токена: str | None = None,
                      имя_источника: str | None = None) -> dict:
    """SELL отдельным сообщением. Прежняя дописка к сообщению покупки отменена."""
    п = поля(поз, имя_токена=имя_токена, имя_источника=имя_источника)
    ключ = п.get("cid") or (п.get("подпись_продажи") or "")[:32]
    итог = оповещатель.послать(строка_sell(п))
    return {"вид": "SELL", "ключ": ключ, "отправка": итог, "поля": п,
            "текст": строка_sell(п)}


def доложить(поз: dict, *, оповещатель, имя_токена: str | None = None,
              имя_источника: str | None = None, пометка: str | None = None) -> dict:
    """Общий вход: продана -- SELL, иначе BUY. Пометок в формате владельца нет."""
    п = поля(поз, имя_токена=имя_токена, имя_источника=имя_источника)
    if п.get("продана"):
        return доложить_продажу(поз, оповещатель=оповещатель, имя_токена=имя_токена,
                                 имя_источника=имя_источника)
    return доложить_покупку(поз, оповещатель=оповещатель, имя_токена=имя_токена,
                             имя_источника=имя_источника)


