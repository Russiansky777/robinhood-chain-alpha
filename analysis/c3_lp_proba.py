# НЕСВЯЗНОЕ ДВИЖЕНИЕ ЛИКВИДНОСТИ -- НЕ СОСТОЯНИЕ ПУЛА.
# Вклад и вывод обязаны двигать ОБЕ стороны в одной пропорции: цена при
# них не меняется, меняется глубина. Измерено на доставке 48 ч по всем
# 209 853 движениям: перекос |log10((y1/y0)/(x1/x0))| имеет медиану
# 0.0006 порядка, p90 = 0.0115, p99 = 0.131 -- то есть они и правда
# пропорциональны. Но у 208 событий (0.10 %) перекос больше ПОРЯДКА, а у
# 49 -- больше двух, вплоть до 12.3: например `remove`, роняющий токены с
# 212 589 до 0.000354 при котировке с 1.545 до 1.502. Это не вывод
# ликвидности и вообще не связная операция AMM -- ни одна цена так не
# ведёт себя при неизменной цене.
# ПОРОГ -- ТО ЖЕ ПРАВИЛО «ЦЕНА СТОИТ В ПРЕДЕЛАХ 2 %», что уже стоит для
# пути по резервам, и ни одного нового числа тут не вводится: перекос --
# это ровно log10 от того, во сколько раз изменилась цена. Сначала я
# поставил порог 1.0 порядка (по разрыву в распределении) -- и он оказался
# СЛИШКОМ СЛАБЫМ: шаг `remove` с котировкой 12.27 -> 2.27 при НЕИЗМЕННЫХ
# токенах его проходит, хотя цена изменилась в 5.4 раза. А главное --
# беда не в выбросах, а в НАКОПЛЕНИИ: в одном пуле 16 792 движения
# ликвидности из 23 373 событий, и даже медианный перекос 0.0006,
# повторённый 16 792 раза, даёт кратность 10^10.
# По измерению: под этот порог попадает около 89 % помеченных движений,
# остальные 11 % цену двигают, а значит чистым движением ликвидности не
# являются. Они пропускаются и считаются отдельной строкой.
ПЕРЕКОС_ПОРОГ = math.log10(1.02)


def _perekos(y0: float, x0: float, y1: float, x1: float) -> float:
    """На сколько ПОРЯДКОВ разошлись стороны. 0 -- строго пропорционально."""
    if min(y0, x0, y1, x1) <= 0:
        return math.inf
    return abs(math.log10((y1 / y0) / (x1 / x0)))


