#!/usr/bin/env python3
"""Подбивка: раздел «FROINK» разбора Pygoscelis -- та же схема а–в, е и сравнение.
Вызывается из podbivka_pygoscelis_svod.py. Только факты.

Сравнение:
  1. источник, продавцы первых 15 с после пика, общие кошельки обеих лент (цепь);
  2. «следом никто не пришёл»: покупатели после покупки источника (кроме него и нас)
     в его слоте, в +3 слота, в +15 с; их SOL (по хранилищу); сколько из наших списков;
  3. цена от покупки источника до нашей продажи: был ли слот выше цены после покупки
     источника; максимум и его время;
  4. источник за 7 суток (архив): доля покупок после роста ≥ 20 % за 750 слотов до
     покупки; доля покупок, после которых за 15 с не пришёл ни один покупатель от
     0.5 SOL; то же медианой по кошелькам групп Code-1.
"""
from __future__ import annotations

import json
import statistics
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parent.parent
НАШ = "4dPZMbReSobZVxfrzGLcD7xJN33pZhuUZix5HkTBTh4x"
SV = None          # модуль сводки -- передаётся из раздел()


def следом(к: dict) -> dict:
    L, dx, src, ключ = к["L"], к["dx"], к["src"], к["ключ"]
    пок_ист = next((x for x in L if x["кошелёк"] == src and x["сторона"] == "buy" and x["slot"] <= к["пк"]["slot"]), None) \
        if src else None
    if not пок_ист:
        return {"why_not": "покупки источника в ленте нет"}
    k0 = ключ(пок_ист)
    после = [x for x in L if x["сторона"] == "buy" and ключ(x) > k0 and x["кошелёк"] not in (src, НАШ)]
    def итог(сс):
        сс_ = {x["signature"]: x for x in сс}
        return {"n": len({x["кошелёк"] for x in сс}), "покупок": len(сс_), "sol": round(sum(dx.get(s) or 0 for s in сс_), 3),
                "из_списков": sorted({x["кошелёк"] for x in сс if SV.м(x.get("метка"))})}
    return {"в_слоте": итог([x for x in после if x["slot"] == пок_ист["slot"]]),
            "+3_слота": итог([x for x in после if x["slot"] <= пок_ист["slot"] + 3]),
            "+15_с": итог([x for x in после if (x["blockTime"] or 0) <= (пок_ист["blockTime"] or 0) + 15]),
            "пок_ист": пок_ист}


def цена_после_источника(к: dict) -> dict:
    сл = следом(к)
    if сл.get("why_not"):
        return сл
    п0 = сл["пок_ист"]
    P0 = п0["цена_после"]
    окно = [x for x in к["L"] if к["ключ"](x) > к["ключ"](п0) and x["slot"] <= к["пр"]["slot"] and x.get("цена_после")]
    выше = sorted({x["slot"] for x in окно if x["цена_после"] > P0})
    мx = max(окно, key=lambda x: x["цена_после"]) if окно else None
    return {"P0": P0, "слотов_выше": len(выше), "первый_выше": выше[0] if выше else None,
            "макс_пп": round((мx["цена_после"] / P0 - 1) * 100, 2) if мx else None,
            "макс_через_с": (мx["blockTime"] - п0["blockTime"]) if мx else None, "макс_слот": мx["slot"] if мx else None}


def раздел(d2: dict, к1: dict, отчёт, sv) -> list:
    global SV  # noqa: PLW0603
    SV = sv
    md2, к2 = отчёт(d2, "## FROINK (наша покупка 28.09, слот 451367519)",
                    "определён по спискам групп Code-1 как покупатель минта в слотах s_наш−3..s_наш; строку Code-1 не получил"
                    if d2.get("источник") else "в слотах s_наш−3..s_наш покупателя из групп Code-1 нет -- источник не установлен",
                    полный=False, ур="###")
    md = md2
    # б) по архиву -- лента минта целиком
    лента_а = []
    for a in SV.арх_загрузить():
        лента_а += (a.get("ленты_минтов") or {}).get(d2["mint"]) or []
    лента_а.sort(key=lambda e: (e.get("block") or 0, e.get("timestamp") or 0))
    if лента_а:
        md += [f"Лента FROINK в архиве PumpApi: {len(лента_а)} событий, "
               f"{SV.чч(лента_а[0]['timestamp'] / 1000)} – {SV.чч(лента_а[-1]['timestamp'] / 1000)}; по пулам: "
               + ", ".join(f"{p} {sum(1 for e in лента_а if str(e.get('pool')) == p)}" for p in sorted({str(e.get('pool')) for e in лента_а})) + ".", ""]
    # ---------- сравнение
    s1, s2 = к1["src"], к2["src"]
    пад1, пад2 = {x["кошелёк"] for x in к1["пад"]}, {x["кошелёк"] for x in к2["пад"]}
    к1_все, к2_все = {x["кошелёк"] for x in к1["L"]}, {x["кошелёк"] for x in к2["L"]}
    общие = sorted((к1_все & к2_все) - {НАШ})
    роль = lambda w, к, пад: ("источник" if w == к["src"] else ("продавец 15 с" if w in пад else  # noqa: E731
                             ("покупал" if any(x["кошелёк"] == w and x["сторона"] == "buy" for x in к["L"]) else "продавал")))
    md += ["## Сравнение Pygoscelis и FROINK", "",
           "### 1. Источник, продавцы на падении, общие кошельки", "",
           f"Источник: Pygoscelis -- `{s1}`; FROINK -- `{s2}`" + (" (тот же)." if s1 == s2 else " (разные)."), "",
           f"Продавцы первых 15 с после пика: общих {len(пад1 & пад2)}" + (" -- " + ", ".join(f"`{w}`" for w in sorted(пад1 & пад2)) if пад1 & пад2 else "") +
           f"; 2JptG7VJ на падении FROINK -- {'да' if any(w.startswith('2JptG7VJ') for w in пад2) else 'нет'}, 4ng4mJcY -- "
           f"{'да' if any(w.startswith('4ng4mJcY') for w in пад2) else 'нет'}.", "",
           f"Кошельки в обеих лентах цепи (Pygoscelis -- с 14:42:21 до продажи+150 слотов; FROINK -- с s_наш−5 до продажи+150): {len(общие)}.", ""]
    if общие:
        md += ["| кошелёк | в Pygoscelis | в FROINK | списки |", "|---|---|---|---|"]
        for w in общие:
            мет = next((x.get("метка") for x in к1["L"] + к2["L"] if x["кошелёк"] == w and x.get("метка")), None)
            md.append(f"| `{w}` | {роль(w, к1, пад1)} | {роль(w, к2, пад2)} | {SV.м(мет) or '—'} |")
        md.append("")
    md += ["### 2. Кто пришёл за источником", "",
           "Покупатели после покупки источника, кроме него и нас; SOL -- по хранилищу пула; «из списков» -- группы Code-1, "
           "543, 133, источники снайперов, снайперы KABUTSTR.", "",
           "| сделка | окно | кошельков | покупок | SOL | из наших списков |", "|---|---|---|---|---|---|"]
    for имя, к in (("Pygoscelis", к1), ("FROINK", к2)):
        сл = следом(к)
        if сл.get("why_not"):
            md.append(f"| {имя} | — | {сл['why_not']} | | | |")
            continue
        for окно in ("в_слоте", "+3_слота", "+15_с"):
            x = сл[окно]
            md.append(f"| {имя} | {окно.replace('_', ' ')} | {x['n']} | {x['покупок']} | {x['sol']:.3f} | "
                      f"{len(x['из_списков'])}{(' (' + ', '.join('`' + w[:8] + '`' for w in x['из_списков']) + ')') if x['из_списков'] else ''} |")
    md += ["", "### 3. Цена от покупки источника до нашей продажи", "",
           "| сделка | слотов с ценой выше цены после покупки источника | первый такой слот | максимум к цене источника, % | через, с |",
           "|---|---|---|---|---|"]
    for имя, к in (("Pygoscelis", к1), ("FROINK", к2)):
        ц = цена_после_источника(к)
        if ц.get("why_not"):
            md.append(f"| {имя} | {ц['why_not']} | | | |")
            continue
        md.append(f"| {имя} | {ц['слотов_выше']} | {ц['первый_выше'] or '—'} | {ц['макс_пп']:+.2f} | {ц['макс_через_с']} |")
    # 4. архив: покупки источников
    пок = []
    for a in SV.арх_загрузить():
        пок += a.get("покупки_ист") or []
    md += ["", "### 4. Источник за 7 суток (архив PumpApi): покупает вершину?", ""]
    if not пок:
        md += ["Архив с покупками источников (pyg3) ещё не готов.", ""]
        return md
    def доли(сс):
        с1 = [x for x in сс if x.get("рост_до_750") is not None]
        с2 = [x for x in сс if x.get("следом_05_15с") is not None]
        return (len(сс), (sum(1 for x in с1 if x["рост_до_750"] >= 20) / len(с1)) if с1 else None,
                (sum(1 for x in с2 if x["следом_05_15с"] == 0) / len(с2)) if с2 else None)
    по_ист: dict = {}
    for x in пок:
        по_ист.setdefault(x["trader"], []).append(x)
    md += ["Покупки в SOL-пулах (все размеры и от 2 SOL). «Рост» -- цена пула перед покупкой к наименьшей за 750 слотов "
           "(≈ 5 мин) до неё; «никто» -- за 15 с после покупки ни одной покупки от 0.5 SOL другого кошелька в том же пуле "
           "(по архиву; свопы через сторонние программы архив частично не видит).", "",
           "| кошелёк | покупок | рост ≥ 20 % за 5 мин | никто ≥ 0.5 SOL за 15 с | от 2 SOL: покупок | рост ≥ 20 % | никто |",
           "|---|---|---|---|---|---|---|"]
    def стр(имя, сс):
        n, р, н = доли(сс)
        n2, р2, н2 = доли([x for x in сс if (x.get("sol") or 0) >= 2])
        ф = lambda v: f"{100 * v:.0f} %" if v is not None else "—"  # noqa: E731
        return f"| {имя} | {n} | {ф(р)} | {ф(н)} | {n2} | {ф(р2)} | {ф(н2)} |"
    for w, имя in ((s1, "dreamloader (Pygoscelis)"), (s2, "источник FROINK")):
        if w:
            md.append(стр(f"{имя} `{w[:8]}`", по_ист.get(w, [])))
    прочие = [доли(v) for w, v in по_ист.items() if len(v) >= 5]
    ф = lambda v: f"{100 * statistics.median(v):.0f} %" if v else "—"  # noqa: E731
    md.append(f"| медиана по кошелькам групп Code-1 (≥ 5 покупок, {len(прочие)}) | — | "
              f"{ф([p[1] for p in прочие if p[1] is not None])} | {ф([p[2] for p in прочие if p[2] is not None])} | — | — | — |")
    md.append("")
    return md
