from __future__ import annotations

import argparse
import json
from datetime import datetime, timezone
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
DATA = REPO_ROOT / "data"


def f(x, знаков=2, плюс=False):
    if x is None:
        return "—"
    фмт = f"{{:+.{знаков}f}}" if плюс else f"{{:.{знаков}f}}"
    return фмт.format(x)


def причины(d: dict) -> str:
    if not d:
        return "нет"
    return "; ".join(f"{k} — {v}" for k, v in sorted(d.items(), key=lambda kv: -kv[1]))


def разброс_строка(d: dict) -> str:
    if not d or not d.get("n"):
        return "| — | — | — | — | — |"
    return (f"| {d['n']} | {f(d['медиана'], 2, True)} | {f(d['p10'], 2, True)} | "
            f"{f(d['p90'], 2, True)} | {f(d['макс_по_модулю'])} |")


