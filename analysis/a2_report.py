    A("|---|---|---|---|---|---|---|")
    for имя, ключ in (("DBot", "DBot"), ("наши покупки", "наши")):
        s = a2["издержки_покупки"][ключ]
        A(f"| {имя} | {s['сделок']} | {f(s['цепь_пп']['медиана'])} | "
          f"{f(s['модель_до_пп']['медиана'])} | {f(s['модель_после_пп']['медиана'])} | "
          f"{f(s['расхождение_до_пп']['медиана'], 2, True)} | "
          f"{f(s['расхождение_после_пп']['медиана'], 2, True)} |")
    A("")
    A("Наши покупки по размеру заявки — без этой разбивки пробные сделки на 0.001 SOL "
      "перекашивают медиану, потому что фиксированные лампорты у них больше самой ставки:")
