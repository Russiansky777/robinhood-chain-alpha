#!/usr/bin/env python3
"""Пакет 04.10, п. В.7: признаки ДО входа против итога и простые отсечки. Только чтение.

Офлайн по кэшу сигналов архива. Итог -- формулой модели (вход S+1, удержание и билет группы
источника). По каждому признаку, который ИЗВЕСТЕН ДО ВХОДА, сигналы раскладываются по
корзинам и считается: n, медиана и среднее п.п., доля в плюсе, SOL в сутки, то же без двух
лучших сделок -- отдельно на подборе (ранние сутки) и на проверке (последние).

Признаки из кэша (всё -- состояние на момент сигнала, ничего из будущего):
  * резерв пула в SOL-экв (`резерв_sol`) и виртуальный резерв кривой;
  * размер первой покупки источника (`sol`);
  * толпа за источником: сколько кошельков купили тот же пул за 10 слотов ДО него (`перед_n`);
  * час суток UTC и день недели;
  * тип пула; «первая покупка минта» против «повторной по правилу окна» (`первая`, `по_окну`);
  * сколько событий пула уже было в окне (`событий_пула_в_окне`), свопы в s+1 и s+2;
  * заполненность кривой pump.fun -- по резерву SOL на кривой (поле `резерв_sol` на `pump`).
Чего в кэше НЕТ и потому не считается: возраст токена и пула, число держателей и доля
крупнейших. Для них нужен отдельный проход (возраст -- первый слот пула в архиве, держатели --
getTokenLargestAccounts по Helius); это сказано в странице числом «не посчитано».

Отсечка оценивается так: берём сигналы, которые отсечка ОСТАВЛЯЕТ, и сравниваем SOL в сутки
на проверке с «без отсечки»; рядом -- сколько сделок она срезала и сколько из срезанных были
в плюсе («хорошие сделки»).
Выход: data/podbivka/paket_vhod.json и docs/podbivka_<метка>_vhod_otsechki.md.
Ничего не рекомендуется -- решает владелец.
"""
from __future__ import annotations

import argparse
import collections
import json
import sys
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import podbivka_paket_obshee as O  # noqa: E402

КОРЕНЬ = O.КОРЕНЬ
П = O.П


def корзина(значение, границы: tuple, имена: tuple) -> str:
    if значение is None:
        return "нет числа"
    for г, и in zip(границы, имена):
        if значение < г:
            return и
    return имена[-1]


ПРИЗНАКИ = {
    "резерв пула, SOL": lambda р: корзина(р.get("резерв_sol"), (10, 30, 60, 120, 1e18),
                                          ("<10", "10–30", "30–60", "60–120", "≥120")),
    "размер покупки источника, SOL": lambda р: корзина(р.get("sol"), (3, 5, 10, 20, 1e18),
                                                       ("2–3", "3–5", "5–10", "10–20", "≥20")),
    "толпа за источником (перед нами)": lambda р: корзина(р.get("перед_n"), (1, 2, 4, 1e18),
                                                          ("0", "1", "2–3", "≥4")),
    "час суток UTC": lambda р: f"{time.gmtime((р.get('ts') or 0) / 1000).tm_hour:02d}",
    "день недели": lambda р: ("пн", "вт", "ср", "чт", "пт", "сб", "вс")[
        time.gmtime((р.get("ts") or 0) / 1000).tm_wday],
    "тип пула": lambda р: р.get("пул") or "нет",
    "первая покупка минта или по окну": lambda р: ("первая" if р.get("первая")
                                                   else ("по окну" if р.get("по_окну") else "нет")),
    "событий пула в окне": lambda р: корзина(р.get("событий_пула_в_окне"), (5, 15, 40, 1e18),
                                             ("<5", "5–15", "15–40", "≥40")),
    "свопов в s+1": lambda р: корзина((р.get("свопов") or {}).get("s1"), (1, 3, 1e18),
                                      ("0", "1–2", "≥3")),
    "рост цены до 150 слотов у источника": lambda р: корзина(р.get("рост_до_150"), (0, 10, 50, 1e18),
                                                             ("<0", "0–10", "10–50", "≥50")),
}

# отсечки: оставляем сигнал, если условие True
ОТСЕЧКИ = {
    "резерв ≥ 30 SOL": lambda р: (р.get("резерв_sol") or 0) >= 30,
    "резерв ≥ 60 SOL": lambda р: (р.get("резерв_sol") or 0) >= 60,
    "покупка источника ≥ 3 SOL": lambda р: (р.get("sol") or 0) >= 3,
    "покупка источника ≥ 5 SOL": lambda р: (р.get("sol") or 0) >= 5,
    "никого перед нами (толпа 0)": lambda р: (р.get("перед_n") or 0) == 0,
    "толпа ≥ 1": lambda р: (р.get("перед_n") or 0) >= 1,
    "только первая покупка минта": lambda р: bool(р.get("первая")),
    "событий пула в окне ≥ 5": lambda р: (р.get("событий_пула_в_окне") or 0) >= 5,
    "без свопов в s+1": lambda р: ((р.get("свопов") or {}).get("s1") or 0) == 0,
    "только кривая pump.fun": lambda р: р.get("пул") == "pump",
    "только Pump AMM": lambda р: р.get("пул") == "pump-amm",
}


def main() -> int:
    import podbivka_run as R  # noqa: PLC0415
    р = argparse.ArgumentParser()
    р.add_argument("--metka", default=time.strftime("%Y-%m-%d", time.gmtime()))
    р.add_argument("--podbor-sutok", type=int, default=8)
    а = р.parse_args()

    адр = O.реестр()
    счёт = collections.Counter()
    ряды: list = []
    for р_ in O.сигналы():
        счёт["всего"] += 1
        г = O.группа_адреса(адр, р_.get("ист"))
        if not г or р_.get("quoteMint") != O.WSOL:
            счёт["не_наш_сигнал"] += 1
            continue
        пол = O.ПОЛИТИКА.get(г) or {}
        if (р_.get("sol") or 0) < (пол.get("порог_источника_sol") or 2.0):
            счёт["ниже_порога"] += 1
            continue
        б = пол.get("билет") or 0.1
        h = int(пол.get("удержание_слотов") or O.ВЫХОД_ГРУППЫ)
        п = O.пп(р_, б, "S1", h)
        if п is None:
            счёт["нет_модели"] += 1
            continue
        счёт["в_счёте"] += 1
        ряды.append({**р_, "группа": г, "билет": б, "пп": п, "sol_итог": п / 100 * б,
                     "сутки": O.сутки(р_)})

    if not ряды:
        print("нет рядов", flush=True)
        return 1
    окна = O.окна(sorted({р_["сутки"] for р_ in ряды}), а.podbor_sutok)

    def свод(подмн: list, дни: list) -> dict:
        от = [р_ for р_ in подмн if р_["сутки"] in дни]
        if not от:
            return {"n": 0}
        д = len({р_["сутки"] for р_ in от}) or 1
        sol = sorted((р_["sol_итог"] for р_ in от), reverse=True)
        с = O.стат([р_["пп"] for р_ in от], 2)
        return {"n": len(от), "суток": д, "медиана_пп": с["медиана"], "среднее_пп": с["среднее"],
                "в_плюсе": с["в_плюсе"], "итог_sol": round(sum(sol), 6),
                "sol_в_сутки": round(sum(sol) / д, 6),
                "sol_в_сутки_без_верхних_2": round(sum(sol[2:]) / д, 6) if len(sol) > 2 else None}

    признаки: dict = {}
    for имя, f in ПРИЗНАКИ.items():
        по_корзинам: dict = collections.defaultdict(list)
        for р_ in ряды:
            по_корзинам[f(р_)].append(р_)
        признаки[имя] = {к: {"подбор": свод(в, окна["подбор"]),
                             "проверка": свод(в, окна["проверка"]),
                             "всё": свод(в, окна["все"])}
                         for к, в in sorted(по_корзинам.items())}

    без = {"подбор": свод(ряды, окна["подбор"]), "проверка": свод(ряды, окна["проверка"]),
           "всё": свод(ряды, окна["все"])}
    отсечки: dict = {}
    for имя, усл in ОТСЕЧКИ.items():
        остались = [р_ for р_ in ряды if усл(р_)]
        срезаны = [р_ for р_ in ряды if not усл(р_)]
        с_пров = свод(остались, окна["проверка"])
        срез_пров = свод(срезаны, окна["проверка"])
        отсечки[имя] = {
            "оставлено": len(остались), "срезано": len(срезаны),
            "срезано_в_плюсе": sum(1 for р_ in срезаны if р_["пп"] > 0),
            "подбор": свод(остались, окна["подбор"]), "проверка": с_пров,
            "срезанные_на_проверке": срез_пров,
            "прирост_на_проверке": (round((с_пров.get("sol_в_сутки") or 0)
                                          - (без["проверка"].get("sol_в_сутки") or 0), 6)
                                    if с_пров.get("n") else None)}

    итог = {"что": "В.7 признаки до входа против итога и простые отсечки",
            "источник_чисел": {"кэш": str(O.КЭШ),
                               "сводка_кэша": "data/podbivka/paket_kesh_svod.json",
                               "политика": "data/podbivka/code1_sources_live.json"},
            "не_посчитано": {"возраст токена и пула": "в кэше нет первого слота пула",
                             "число держателей и доля крупнейших": "нужен Helius "
                                                                   "getTokenLargestAccounts"},
            "счёт": dict(счёт), "окна": окна, "без_отсечки": без,
            "признаки": признаки, "отсечки": отсечки}
    out = П / "paket_vhod.json"
    out.write_text(json.dumps(итог, ensure_ascii=False, indent=1), encoding="utf-8")
    R.записано(out)

    def ф(v, формат="+.6f"):
        return "—" if v is None else format(v, формат)

    md = [f"# Вход: признаки до входа и простые отсечки ({а.metka})", "",
          f"Кэш сигналов архива ({O.КЭШ.name}); вход S+1, удержание и билет — группы источника. "
          f"Окно {окна['все'][0]} — {окна['все'][-1]}: подбор {len(окна['подбор'])} суток, "
          f"проверка {len(окна['проверка'])} суток. В счёт {счёт['в_счёте']} сигналов "
          f"(не наш сигнал {счёт.get('не_наш_сигнал', 0)}, ниже порога группы "
          f"{счёт.get('ниже_порога', 0)}, модель не дала числа {счёт.get('нет_модели', 0)}).", "",
          f"Без отсечек на проверке: {ф(без['проверка'].get('sol_в_сутки'))} SOL в сутки "
          f"(n {без['проверка'].get('n')}, медиана {ф(без['проверка'].get('медиана_пп'), '+.2f')} п.п., "
          f"в плюсе {без['проверка'].get('в_плюсе')} %).", "",
          "Не посчитано по этим данным: возраст токена и пула (в кэше нет первого слота пула), "
          "число держателей и доля крупнейших (нужен запрос в Helius). Это не ноль — это "
          "«нет числа».", "",
          "## Признаки по корзинам", ""]
    for имя, по_к in признаки.items():
        md += [f"### {имя}", "",
               "| корзина | n (всё окно) | медиана п.п. | в плюсе | SOL/сутки на подборе "
               "| SOL/сутки на проверке | на проверке без верхних 2 |",
               "|---|---|---|---|---|---|---|"]
        for к, v in по_к.items():
            вс, пр = v["всё"], v["проверка"]
            md.append(f"| {к} | {вс.get('n', 0)} | {ф(вс.get('медиана_пп'), '+.2f')} "
                      f"| {str(вс.get('в_плюсе')) + ' %' if вс.get('n') else '—'} "
                      f"| {ф(v['подбор'].get('sol_в_сутки'))} | {ф(пр.get('sol_в_сутки'))} "
                      f"| {ф(пр.get('sol_в_сутки_без_верхних_2'))} |")
        md.append("")
    md += ["## Отсечки", "",
           "| отсечка | оставлено | срезано | из срезанных были в плюсе "
           "| SOL/сутки на подборе | SOL/сутки на проверке | прирост к «без отсечки» "
           "| срезанные на проверке давали |", "|---|---|---|---|---|---|---|---|"]
    for имя, v in sorted(отсечки.items(), key=lambda kv: -(kv[1]["прирост_на_проверке"] or -1e9)):
        md.append(f"| {имя} | {v['оставлено']} | {v['срезано']} | {v['срезано_в_плюсе']} "
                  f"| {ф(v['подбор'].get('sol_в_сутки'))} | {ф(v['проверка'].get('sol_в_сутки'))} "
                  f"| {ф(v['прирост_на_проверке'])} "
                  f"| {ф(v['срезанные_на_проверке'].get('sol_в_сутки'))} |")
    лучшая = max(отсечки.items(), key=lambda kv: (kv[1]["прирост_на_проверке"] or -1e9))
    md += ["", "## Вывод", "",
           f"Лучшая простая отсечка на проверке — **{лучшая[0]}**: "
           f"{ф(лучшая[1]['проверка'].get('sol_в_сутки'))} SOL в сутки против "
           f"{ф(без['проверка'].get('sol_в_сутки'))} без отсечки (прирост "
           f"{ф(лучшая[1]['прирост_на_проверке'])}), и она срезает {лучшая[1]['срезано']} "
           f"сделок, из которых {лучшая[1]['срезано_в_плюсе']} были в плюсе; срезанные на "
           f"проверке давали {ф(лучшая[1]['срезанные_на_проверке'].get('sol_в_сутки'))} SOL в "
           f"сутки.", "",
           "Ничего не меняется и не рекомендуется — решает владелец.", ""]
    стр = КОРЕНЬ / "docs" / f"podbivka_{а.metka}_vhod_otsechki.md"
    стр.write_text("\n".join(md) + "\n", encoding="utf-8")
    R.записано(стр)
    print(f"{стр.name}: сигналов {счёт['в_счёте']}, лучшая отсечка {лучшая[0]} "
          f"({лучшая[1]['прирост_на_проверке']})", flush=True)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
