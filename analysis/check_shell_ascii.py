#!/usr/bin/env python3
"""Имена переменных оболочки в workflow -- только ASCII. Только чтение.

Зачем отдельная проверка. Правило владельца: идентификаторы, ключи JSON и
имена переменных -- только ASCII; кириллица -- в комментариях, строках для
человека и докладах. Bash это правило не просит, он его ТРЕБУЕТ: имя
переменной может состоять лишь из [A-Za-z_][A-Za-z0-9_]*, и строка
`ПОРОГ="x"` для него не присваивание, а команда с таким именем. Оболочка
падает с "command not found" и кодом 127.

Цена ошибки уже заплачена: 2026-09-24T11:24Z деплой детектора упал на шаге
сверки именно так, и следующие шаги (юнит, перезапуск службы, проверка
признака жизни) были пропущены -- код на хост уехал, а служба осталась на
прежнем. Поэтому проверка стоит в самопроверках ДО доставки: пусть падает
за четыре секунды на бегунке, а не посреди деплоя.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

# Присваивание оболочки: имя -- ТОЛЬКО слово (буквы, цифры, подчёркивание) и
# сразу "=". Точка, скобка или кавычка в "имени" означают, что это не
# присваивание оболочки: так выглядит строка питона внутри heredoc
# (`отчёт.write_text(f.read(encoding="utf-8")`), и считать её нарушением --
# ложная тревога, из-за которой приходится корёжить рабочий код.
ПРИСВАИВАНИЕ = re.compile(r"^\s*(?:export\s+|local\s+|declare\s+(?:-\w+\s+)?)?(\w+)=")
# Подстановка $NAME или ${NAME} с не-ASCII в имени.
ПОДСТАНОВКА = re.compile(r"\$\{?([A-Za-z_Ѐ-ӿ][A-Za-z0-9_Ѐ-ӿ]*)\}?")
# Начало heredoc: <<EOF, <<-'PY', <<"X". Тело heredoc оболочка НЕ разбирает,
# там лежит чужой язык (обычно питон), и его имена -- не имена оболочки.
# Метка heredoc начинается с буквы: иначе сдвиг $((x << 2)) был бы принят за
# начало heredoc с меткой "2", и весь остаток файла ушёл бы из проверки.
HEREDOC = re.compile(r"<<-?\s*[\"']?([A-Za-z_]\w*)[\"']?")


def нарушения_текста(текст: str) -> list[dict]:
    """Строки с не-ASCII именами переменных. Комментарии не считаются."""
    из = []
    конец_heredoc: str | None = None
    for n, строка in enumerate(текст.splitlines(), start=1):
        без_пробелов = строка.strip()
        if конец_heredoc is not None:
            if без_пробелов == конец_heredoc:
                конец_heredoc = None
            continue
        m_here = HEREDOC.search(строка)
        if m_here:
            конец_heredoc = m_here.group(1)
            continue
        if без_пробелов.startswith("#"):
            continue
        m = ПРИСВАИВАНИЕ.match(строка)
        if m and any(ord(c) > 127 for c in m.group(1)):
            из.append({"line": n, "name": m.group(1), "kind": "присваивание",
                        "text": строка.strip()[:120]})
            continue
        for имя in ПОДСТАНОВКА.findall(строка):
            if any(ord(c) > 127 for c in имя):
                из.append({"line": n, "name": имя, "kind": "подстановка",
                            "text": строка.strip()[:120]})
                break
    return из


def проверить(пути: list[Path]) -> list[dict]:
    плохо = []
    for путь in пути:
        try:
            текст = путь.read_text(encoding="utf-8")
        except OSError as exc:
            плохо.append({"file": str(путь), "line": 0, "name": "",
                           "kind": "файл не читается", "text": str(exc)})
            continue
        for н in нарушения_текста(текст):
            плохо.append(dict(н, file=str(путь)))
    return плохо


def self_test() -> None:
    всего = [0, 0]

    def chk(имя, условие, факт=None):
        всего[0] += 1
        if условие:
            всего[1] += 1
            print(f"  [ok  ] {имя}")
        else:
            print(f"  [ПЛОХО] {имя} -- {факт}")

    н = нарушения_текста('          ПОРОГ_БАЛАНСА="${{ inputs.x }}"\n')
    chk("присваивание с кириллицей найдено",
        len(н) == 1 and н[0]["name"] == "ПОРОГ_БАЛАНСА", н)
    н2 = нарушения_текста('          if [ -n "$ПОРОГ" ]; then\n')
    chk("подстановка с кириллицей найдена",
        len(н2) == 1 and н2[0]["name"] == "ПОРОГ", н2)
    chk("ASCII-имя нарушением не считается",
        нарушения_текста('MIN_START_BALANCE="0.3"\nif [ -n "$MIN_START_BALANCE" ]; then\n') == [],
        нарушения_текста('MIN_START_BALANCE="0.3"'))
    chk("русский текст в строке для человека -- не нарушение",
        нарушения_текста('echo "СБОЙ: порог баланса не число"\n') == [])
    chk("русский комментарий -- не нарушение",
        нарушения_текста('  # порог=0.3 по умолчанию, менять по слову владельца\n') == [])
    chk("питон в heredoc не считается присваиванием оболочки",
        нарушения_текста('          python3 - <<\'PY\'\n'
                          '          отчёт.write_text(отчёт.read_text(encoding="utf-8"))\n'
                          '          путь="x"\n'
                          '          PY\n') == [],
        нарушения_текста('          python3 - <<\'PY\'\n'
                          '          отчёт.write_text(отчёт.read_text(encoding="utf-8"))\n'
                          '          PY\n'))
    chk("после heredoc проверка возобновляется",
        [н["name"] for н in нарушения_текста(
            'python3 - <<\'PY\'\nпуть="x"\nPY\nПОСЛЕ=1\n')] == ["ПОСЛЕ"],
        нарушения_текста('python3 - <<\'PY\'\nпуть="x"\nPY\nПОСЛЕ=1\n'))
    chk("метод с точкой присваиванием не считается",
        нарушения_текста('  отчёт.write(x, encoding="utf-8")\n') == [],
        нарушения_текста('  отчёт.write(x, encoding="utf-8")\n'))
    chk("export с кириллицей ловится",
        [н["name"] for н in нарушения_текста('export ПОРОГ=1\n')] == ["ПОРОГ"],
        нарушения_текста('export ПОРОГ=1\n'))
    chk("сдвиг влево -- не heredoc, проверка не глохнет",
        [н["name"] for н in нарушения_текста('X=$((1 << 2))\nПОСЛЕ=1\n')] == ["ПОСЛЕ"],
        нарушения_текста('X=$((1 << 2))\nПОСЛЕ=1\n'))
    chk("ключ YAML с двоеточием присваиванием не считается",
        нарушения_текста('  описание: "порог"\n') == [],
        нарушения_текста('  описание: "порог"\n'))
    print(f"самопроверка ASCII-имён: {всего[1]}/{всего[0]}"
          f"{' пройдено' if всего[1] == всего[0] else ' ПРОВАЛ'}")
    if всего[1] != всего[0]:
        raise SystemExit(1)


def main() -> int:
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--self-test", action="store_true")
    p.add_argument("paths", nargs="*", default=None,
                    help="файлы или каталоги; по умолчанию .github/workflows")
    a = p.parse_args()
    if a.self_test:
        self_test()
        return 0
    цели = [Path(x) for x in (a.paths or [".github/workflows"])]
    файлы: list[Path] = []
    for ц in цели:
        файлы.extend(sorted(ц.rglob("*.yml")) if ц.is_dir() else [ц])
    плохо = проверить(файлы)
    if not плохо:
        print(f"имена переменных оболочки: проверено файлов {len(файлы)}, "
               f"не-ASCII имён нет")
        return 0
    print(f"НАЙДЕНО не-ASCII имён переменных: {len(плохо)}")
    for н in плохо:
        print(f"  {н['file']}:{н['line']} {н['kind']} '{н['name']}': {н['text']}")
    print("Bash такие имена не принимает: строка выполняется как команда и даёт "
           "'command not found' (код 127). Переименуйте в ASCII.")
    return 1


if __name__ == "__main__":
    raise SystemExit(main())
