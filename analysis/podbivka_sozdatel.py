def ф(v, формат="+.4f", пусто="--"):
    return пусто if v is None else format(v, формат)


def стат(v: list, точность: int = 4) -> dict:
    if not v:
        return {"n": 0}
    return {"n": len(v), "медиана": round(statistics.median(v), точность),
            "p25": round(кв(v, 0.25), точность), "p75": round(кв(v, 0.75), точность),
            "среднее": round(statistics.fmean(v), точность)}


