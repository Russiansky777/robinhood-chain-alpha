#!/usr/bin/env python3
"""«Создатель купил сам»: пункты 1--9 на ИСПРАВЛЕННОЙ модели, по типам пулов раздельно.

Почему раздельно. Срез проходит по признаку «в блоке створа покупал сам создатель», а это
признак поведения, не площадки: за сутки 05.10 из 7 825 таких запусков кривая pump.fun --
3 366 (43 %), meteora-launchpad -- 2 902 (37 %), raydium-launchpad -- 1 114 (14 %),
DAMM v2 -- 284, PumpSwap -- 159. Модель круга сверена с цепью ТОЧНО только у кривой
pump.fun (22 718 сделок, модель/факт = 1.000000 на p10, медиане и p90 во всех размерах).
У PumpSwap она заведомо неверна -- продажа там на 7--19 % лучше модели; у двух launchpad и
DAMM v2 не сверена вовсе. Поэтому строка «все пулы» -- НЕ РЕШЕНО, а решать можно только по
кривой.

Момент знания признака (пункт 1). «Создатель купил сам» известно из блока створа, то есть к
КОНЦУ этого блока. Место входа «створ_дно» -- конец того же блока: чтобы им
воспользоваться, надо попасть в блок, который уже закрыт. Поэтому оно считается, но
помечено как недостижимое, а решать можно только по «створ+1» и «створ+2».

Множитель выхода к_g (пункт про расходы). Калибровка по живым сделкам дала по группам:
cand1_03 (билет 0.3, n 293) 1.0015, cand1 (n 218) 0.9953, lane_s0 (n 123) 0.9964,
batch5 (n 48) 0.9969, cand2 (n 341) 0.9793, konveyer (n 16) 0.9880, cand3 (n 43) 0.8761,
cand1_05 (n 28) 0.7486. Общий фит 0.9908 держится на двух малых группах. Поэтому счёт
ведётся ПРИ ТРЁХ значениях -- 1.0 (как считает программа), 0.991 (общий фит) и 0.979
(худшая крупная группа), -- и вердикт ставится только если он один и тот же при всех трёх.

Только чтение собранных файлов. Выход: docs/podbivka_sozdatel.md,
data/podbivka/sozdatel_itog.json и data/podbivka/sozdatel_celi.json (30 сделок для сверки
цен по соседям -- пункт 3).
"""
