def сутки_файла(имя: str) -> str:
    return имя.replace(".json.gz", "").split("_", 1)[-1].split("T")[0]


def файлы(префикс: str = "zap_") -> list:
    return [(сутки_файла(Path(ф).name), ф)
            for ф in sorted(glob.glob(str(П / "zapuski" / f"{префикс}*.json.gz")))]


def создатель_купил(x: dict) -> bool:
    return bool((x.get("в_блоке_создания") or {}).get("создатель_купил"))


def вид_состояния(вх, вых) -> str:
    """Можно ли считать круг по этой паре состояний (как в остальных счётах)."""
    if not (вх and вых):
        return "пусто"
    x0, y0 = float(вх[0]), float(вх[1])
    x1, y1 = float(вых[0]), float(вых[1])
    if x0 <= 0 or y0 <= 0:
        return "не_тот_пул"
    if x1 <= 0 or y1 <= 0:
        return "закрыт"
    k = (x1 * y1) / (x0 * y0)
    одно = (x1 >= x0) == (y1 >= y0)
    return "годно" if (одно or 0.5 <= k <= 2.0) else "не_тот_пул"


def деньги_сходятся(вх, вых, объём: float) -> bool:
    """Хватило ли замеченных денег окна на такой рост цены."""
    x0, y0 = float(вх[0]), float(вх[1])
    x1, y1 = float(вых[0]), float(вых[1])
    if min(x0, y0, x1, y1) <= 0:
        return True
    M = (x1 / y1) / (x0 / y0)
    if M <= 1:
        return True
    return x0 * (math.sqrt(M) - 1) <= max(1.0, объём) * ПРИТОК_РАЗ


def круг(с: dict, б: float, место: str, h: int, к_g: float) -> tuple:
    """(итог_sol, вид, резерв). Невозможная продажа -- итог, а не пропуск строки."""
    сост = с["модель"]["состояния"]
    вх = (сост.get("вход") or {}).get(место)
    if not вх:
        return None, "без_входа", None
    резерв = float(вх[0])
    вых = (сост.get("выход") or {}).get(str(h))
    есть = bool(вых and Z.позже_входа(с, место, h))
    вид = вид_состояния(вх, вых) if есть else "пусто"
    if вид == "не_тот_пул":
        return None, вид, резерв
    if вид == "закрыт":
        return -(б + Z.ИЗДЕРЖКИ), "нельзя_продать", резерв
    if вид == "пусто":
        с2 = {"pool": с["pool"], "модель": {**с["модель"],
              "состояния": {"вход": сост["вход"], "выход": {"0": вх}, "масштаб": 1.0}}}
        кр = B.сделка_по_состояниям(с2, б, место=место, выход=0,
                                    издержки=Z.ИЗДЕРЖКИ, к_g=к_g)
        return ((кр["итог_sol"], "пусто", резерв) if кр
                else (-(б + Z.ИЗДЕРЖКИ), "нельзя_продать", резерв))
    кр = B.сделка_по_состояниям(с, б, место=место, выход=h,
                                издержки=Z.ИЗДЕРЖКИ, к_g=к_g)
    if кр is None:
        return -(б + Z.ИЗДЕРЖКИ), "нельзя_продать", резерв
    return кр["итог_sol"], "годно", резерв


# ---- проход -----------------------------------------------------------------------

def проход() -> tuple:
    """Один проход по 17 суткам. Ключ -- (группа, место, горизонт, билет, к_g)."""
    сп = файлы()
    дни = [д for д, _ in сп]
    номер = {д: i for i, д in enumerate(дни)}
    группы = ("кривая pump.fun", "все пулы")
    ключи = [(г, м, h, б, k) for г in группы for м in МЕСТА
             for h in ГОРИЗОНТЫ for б in БИЛЕТЫ for k in К_G]
    стол = {k: {"итог": array("f"), "день": array("H"), "вид": bytearray(),
                "резерв": array("f"), "объём": array("f")} for k in ключи}
    ВИД = {"годно": 0, "пусто": 1, "нельзя_продать": 2, "деньги_не_сходятся": 3}
    охват: collections.Counter = collections.Counter()
    создатель: dict = {"sol": [], "покупок": [], "кошельков": [], "продаж": [],
                       "первая_продажа": []}
    по_пулам: collections.Counter = collections.Counter()
    крайние: dict = collections.defaultdict(list)
    for д, путь in сп:
        дн = номер[д]
        with gzip.open(путь, "rt", encoding="utf-8") as о:
            тело = json.load(о)
        for x in тело.get("ряды") or []:
            охват["запусков"] += 1
            if not создатель_купил(x):
                continue
            охват["создатель_купил"] += 1
            по_пулам[x.get("пул")] += 1
            бл = x.get("в_блоке_создания") or {}
            создатель["sol"].append(бл.get("sol") or 0.0)
            создатель["покупок"].append(бл.get("покупок") or 0)
            создатель["кошельков"].append(бл.get("кошельков") or 0)
            создатель["продаж"].append(x.get("продаж") or 0)
            if x.get("первая_продажа_слотов") is not None:
                создатель["первая_продажа"].append(x["первая_продажа_слотов"])
            # мёртвый запуск -- тот, у кого все выходы равны входу (никто не торговал)
            вх0 = (x.get("вход") or {}).get("створ_дно")
            вых = x.get("выход") or {}
            if вх0 and вых:
                мёртв = all(abs(float(v[0]) - float(вх0[0])) < 1e-12 for v in вых.values())
                охват["мёртвых"] += 1 if мёртв else 0
            if not вых:
                охват["без_выходов"] += 1
            с = Z.модель(x)
            if not с:
                охват["без_модели"] += 1
                continue
            охват["с_моделью"] += 1
            свои = ["все пулы"] + (["кривая pump.fun"] if x.get("пул") in СВЕРЕНО else [])
            объём = ((x.get("волна") or {}).get("60с") or {}).get("sol") or 0.0
            сост = с["модель"]["состояния"]
            for м in МЕСТА:
                вх = (сост.get("вход") or {}).get(м)
                if not вх:
                    continue
                for h in ГОРИЗОНТЫ:
                    вых_с = (сост.get("выход") or {}).get(str(h))
                    плохо = (вых_с is not None
                             and вид_состояния(вх, вых_с) == "годно"
                             and not деньги_сходятся(вх, вых_с, объём))
                    for б in БИЛЕТЫ:
                        if float(вх[0]) * ДОЛЯ_РЕЗЕРВА < б:
                            continue        # глубина -- условие ВХОДА
                        for k in К_G:
                            итог, вид, рез = круг(с, б, м, h, k)
                            if итог is None:
                                continue
                            if плохо:
                                вид = "деньги_не_сходятся"
                            for г in свои:
                                t = стол[(г, м, h, б, k)]
                                t["итог"].append(итог)
                                t["день"].append(дн)
                                t["вид"].append(ВИД.get(вид, 0))
                                t["резерв"].append(рез or 0.0)
                                t["объём"].append(объём)
                            if (б == 0.1 and k == 1.0 and м == "створ+1" and h == 230
                                    and x.get("пул") in СВЕРЕНО):
                                крайние[г].append(
                                    (итог, x["минт"], x.get("poolId"), д, x.get("блок"),
                                     x.get("ts"), x.get("пул"), вид))
        del тело
    return стол, дни, dict(охват), создатель, dict(по_пулам), крайние


