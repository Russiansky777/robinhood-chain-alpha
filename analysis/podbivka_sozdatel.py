def срезанное(v: list, доля: float):
    if not v:
        return None
    s = sorted(v)
    k = int(len(s) * доля)
    о = s[:len(s) - k] if k else s
    return statistics.fmean(о) if о else None


def бутстрэп(по_суткам: dict, рнд: random.Random) -> tuple:
    дни = [d for d in по_суткам if по_суткам[d]]
    if len(дни) < 3:
        return None, None
    сум = {d: (sum(по_суткам[d]), len(по_суткам[d])) for d in дни}
    ср = []
    for _ in range(БУТСТРЭПОВ):
        s = n = 0.0
        for _ in дни:
            a, b = сум[рнд.choice(дни)]
            s += a
            n += b
        if n:
            ср.append(s / n)
    ср.sort()
    return ср[int(0.025 * len(ср))], ср[int(0.975 * len(ср)) - 1]


def кв(v: list, q: float):
    if not v:
        return None
    s = sorted(v)
    return s[max(0, min(len(s) - 1, int(q * (len(s) - 1))))]


def свод(t: dict, дни: list, б: float, рнд: random.Random) -> dict:
    итог = list(t["итог"])
    if not итог:
        return {"сделок": 0}
    пп = [100 * v / б for v in итог]
    по_суткам: dict = collections.defaultdict(list)
    for v, дн in zip(итог, t["день"]):
        по_суткам[дни[дн]].append(v)
    низ, верх = бутстрэп(по_суткам, рнд)
    виды = collections.Counter(t["вид"])
    сум_по_суткам = {d: sum(v) for d, v in по_суткам.items()}
    худ = min(сум_по_суткам.items(), key=lambda kv: kv[1])
    дни_пр = sorted(d for d in по_суткам if d >= ПРОВЕРКА_С)
    сер = len(дни_пр) // 2
    пол = []
    for гр in (дни_пр[:сер], дни_пр[сер:]):
        v = [x for d in гр for x in по_суткам[d]]
        пол.append(statistics.fmean(v) if v else None)
    доли = [б / max(1e-9, о + б) for о in t["объём"]]
    return {
        "сделок": len(итог), "суток": len(по_суткам),
        "сделок_в_сутки": round(len(итог) / len(по_суткам), 1),
        "ожидание_sol": statistics.fmean(итог), "ди_низ": низ, "ди_верх": верх,
        "без_верх_1": срезанное(итог, 0.01), "без_верх_5": срезанное(итог, 0.05),
        "медиана_sol": statistics.median(итог), "медиана_пп": statistics.median(пп),
        "в_плюсе_доля": 100 * sum(1 for v in итог if v > 0) / len(итог),
        "без_5_лучших": (statistics.fmean(sorted(итог)[:-5]) if len(итог) > 5 else None),
        "половина_1": пол[0], "половина_2": пол[1],
        "p10_пп": кв(пп, 0.10), "p5_пп": кв(пп, 0.05), "p1_пп": кв(пп, 0.01),
        "худшая_пп": min(пп), "хуже_минус10": 100 * sum(1 for p in пп if p < -10) / len(пп),
        "хуже_минус50": 100 * sum(1 for p in пп if p < -50) / len(пп),
        "худшие_сутки": худ[0], "худшие_сутки_sol": худ[1],
        "sol_в_сутки": sum(итог) / len(по_суткам),
        "нельзя_продать_доля": round(100 * виды[2] / len(итог), 1),
        "никто_не_торговал_доля": round(100 * виды[1] / len(итог), 1),
        "деньги_не_сходятся_доля": round(100 * виды[3] / len(итог), 1),
        "наша_доля_объёма_медиана": round(100 * statistics.median(доли), 1),
        "доля_объёма_выше_10": round(100 * sum(1 for d in доли if d > 0.10) / len(доли), 1),
    }


def вердикт(c: dict) -> str:
    """Одной строкой. Порядок -- по силе возражения."""
    if c.get("нельзя_продать_доля", 0) >= 10:
        return f"нет: продать нельзя в {c['нельзя_продать_доля']:.0f} % сделок"
    if (c.get("ожидание_sol") or 0) <= 0:
        return "нет: ожидание не выше нуля"
    if (c.get("ди_низ") or 0) <= 0:
        return "нет: доверительный интервал среднего накрывает ноль"
    if (c.get("без_верх_1") or 0) <= 0:
        return "нет: без верхнего 1 % сделок среднее уходит в минус"
    if (c.get("без_верх_5") or 0) <= 0:
        return "нет: без верхних 5 % сделок среднее уходит в минус"
    if (c.get("половина_1") or 0) <= 0 or (c.get("половина_2") or 0) <= 0:
        return "нет: одна из половин проверки в минусе"
    if c.get("доля_объёма_выше_10", 0) >= 10:
        return (f"нет: в {c['доля_объёма_выше_10']:.0f} % пулов билет больше десятой доли "
                "объёма окна")
    return "да"


