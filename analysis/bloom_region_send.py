#!/usr/bin/env python3
"""Региональная отправка (III.14): вариант уходит в точку рядом с лидером слота.

ЗАЧЕМ. Числа II.14 за 26.09: по лидерам EU доля S+0 -- 31.6 % (18 из 57), по
Asia -- 0 % (0 из 10), по US-East -- 12.5 % (1 из 8). Мы стоим в Амстердаме и
отправляем всегда в европейские точки; когда лидер слота в Токио или Нью-Йорке,
транзакция идёт через океан дважды -- сначала до нашей точки отправителя, потом
от неё до лидера. Здесь выбирается точка ТОГО ЖЕ отправителя, что и сейчас, но
ближайшая к лидеру слота.

ЧТО ЗДЕСЬ НЕ ВЫДУМАНО. Точки читаются из data/sender_regions.json, который
собран ИЗ ДОКУМЕНТАЦИИ отправителей (у каждой точки поле "откуда" -- файл
документации, откуда взято имя). Ни одного имени хоста в этом модуле нет:
вернуть можно только то, что есть в файле. Регион лидера -- из карты
data/leader_regions.json (кто из валидаторов где), её строит отдельный прогон
по getClusterNodes и гео адресов.

ПО УМОЛЧАНИЮ ВЫКЛЮЧЕНО: нужен BLOOM_REGION_SEND=1. Без флага и при незнакомом
регионе функция отдаёт None, и вызывающий оставляет адрес, которым ходит сейчас.
"""
from __future__ import annotations

import json
import os
import time
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parent.parent
ФАЙЛ_ТОЧЕК = КОРЕНЬ / "data" / "sender_regions.json"
ФАЙЛ_ЛИДЕРОВ = КОРЕНЬ / "data" / "leader_regions.json"
СЛОТОВ_В_ЭПОХЕ = 432_000

# БЛИЗОСТЬ РЕГИОНОВ, от ближнего к дальнему. Порядок -- география, а не вкус:
# из Европы ближе восточный берег США, чем западный; из Азии ближе западный
# берег США, чем Европа. Точку берём первую, что есть у этого отправителя.
БЛИЗОСТЬ = {
    "EU": ("EU", "US-East", "US-West", "Asia"),
    "US-East": ("US-East", "US-West", "EU", "Asia"),
    "US-West": ("US-West", "US-East", "Asia", "EU"),
    "Asia": ("Asia", "US-West", "US-East", "EU"),
}
_ТОЧКИ: dict | None = None
_ЛИДЕРЫ: dict | None = None
_РАСПИСАНИЕ: dict = {"эпоха": None, "слоты": {}}


def включено() -> bool:
    return (os.environ.get("BLOOM_REGION_SEND") or "0").strip() == "1"


def точки(заново: bool = False) -> dict:
    """{отправитель: [точки]} из файла, собранного по документации."""
    global _ТОЧКИ  # noqa: PLW0603
    if _ТОЧКИ is not None and not заново:
        return _ТОЧКИ
    try:
        д = json.loads(ФАЙЛ_ТОЧЕК.read_text(encoding="utf-8"))
        _ТОЧКИ = д.get("точки") or {}
    except Exception:  # noqa: BLE001
        _ТОЧКИ = {}
    return _ТОЧКИ


def карта_лидеров(заново: bool = False) -> dict:
    """{лидер: регион}. Нет файла -- пустая карта, и регион будет неизвестен."""
    global _ЛИДЕРЫ  # noqa: PLW0603
    if _ЛИДЕРЫ is not None and not заново:
        return _ЛИДЕРЫ
    try:
        д = json.loads(ФАЙЛ_ЛИДЕРОВ.read_text(encoding="utf-8"))
        _ЛИДЕРЫ = д.get("по_лидеру") or {}
    except Exception:  # noqa: BLE001
        _ЛИДЕРЫ = {}
    return _ЛИДЕРЫ


def расписание(rpc, слот: int, *, заново: bool = False) -> dict:
    """{абсолютный слот: лидер} на эпоху слота. Держится в памяти процесса.

    Один вызов getLeaderSchedule на эпоху: расписание не меняется внутри неё, а
    спрашивать его на каждой сделке -- это лишние 400 мс в горячем пути.
    """
    эпоха = слот // СЛОТОВ_В_ЭПОХЕ
    if _РАСПИСАНИЕ["эпоха"] == эпоха and _РАСПИСАНИЕ["слоты"] and not заново:
        return _РАСПИСАНИЕ["слоты"]
    начало = эпоха * СЛОТОВ_В_ЭПОХЕ
    try:
        сырое = rpc("getLeaderSchedule", [начало])
    except Exception:  # noqa: BLE001
        сырое = None
    слоты = {}
    for лидер, индексы in (сырое or {}).items():
        for и in индексы:
            слоты[начало + и] = лидер
    if слоты:
        _РАСПИСАНИЕ["эпоха"] = эпоха
        _РАСПИСАНИЕ["слоты"] = слоты
    return слоты


def лидер_слота(rpc, слот: int):
    return расписание(rpc, слот).get(слот)


def регион_слота(rpc, слот: int) -> dict:
    """{'лидер','регион'} для слота. Незнакомый лидер -- регион 'неизвестно'."""
    лидер = лидер_слота(rpc, слот) if слот else None
    регион = (карта_лидеров().get(лидер) or "неизвестно") if лидер else "неизвестно"
    return {"лидер": лидер, "регион": регион, "слот": слот}


def точка(отправитель: str, регион: str) -> dict | None:
    """Ближайшая к региону лидера точка ЭТОГО отправителя или None.

    None значит "оставь адрес как есть": ни выдуманных имён, ни подмены
    отправителя на другого здесь быть не может.
    """
    список = [т for т in (точки().get(отправитель) or []) if т.get("host")]
    if not список:
        return None
    порядок = БЛИЗОСТЬ.get(регион)
    if not порядок:
        return None
    for желаемый in порядок:
        свои = [т for т in список if т.get("регион") == желаемый]
        if свои:
            # Из нескольких точек одного региона берём первую по имени: выбор
            # обязан быть одинаковым от запуска к запуску.
            return sorted(свои, key=lambda т: т["host"])[0]
    return None


def _порт_по_умолчанию(схема: str) -> int:
    """Порт, который в адресе можно не писать. У http это 80, и только 80."""
    return 443 if схема == "https" else 80


def адрес_точки(т: dict | None) -> str | None:
    """Адрес точки БЕЗ пути. Отдельно от адрес_точки_как_в_реестре намеренно:
    этим числом мерят живость и RTT, а отправке нужен путь отправителя."""
    if not т or not т.get("host"):
        return None
    схема = т.get("схема") or "https"
    порт = int(т.get("port") or _порт_по_умолчанию(схема))
    # ПОРТ СРАВНИВАЕТСЯ С УМОЛЧАНИЕМ ЭТОЙ СХЕМЫ, А НЕ С "80 ИЛИ 443". У
    # blockrazor схема http и порт 443: правило "порт в (80, 443) -- не писать"
    # выбрасывало :443 из адреса, и отправка уходила на 80-й порт.
    хвост = "" if порт == _порт_по_умолчанию(схема) else f":{порт}"
    return f"{схема}://{т['host']}{хвост}/"


def адрес_точки_как_в_реестре(т: dict | None, url_реестра: str | None) -> str | None:
    """Адрес точки С ПУТЁМ И ЗАПРОСОМ рабочего адреса этого же отправителя.

    ЗАЧЕМ (найдено 29.09 ночью, до включения флага). Адрес отправителя -- это не
    только хост: у helius путь /fast, у jito /api/v1/transactions, у astralane
    /iris, у blockrazor /sendTransaction на 443-м порту при схеме http. Прежний
    адрес_точки собирал "схема://хост/" и путь терял -- то есть при включённом
    флаге покупка ушла бы POST-ом не на тот endpoint у ЧЕТЫРЁХ отправителей из
    шести. Меняется ровно адрес хоста; путь, запрос и схема берутся у рабочего
    адреса из реестра.

    Реестр не читается здесь: его подаёт вызывающий, чтобы в репозитории не
    появилось второго места, знающего адреса отправителей.
    """
    if not т or not т.get("host"):
        return None
    if not url_реестра:
        return None
    from urllib.parse import urlsplit, urlunsplit  # noqa: PLC0415

    try:
        ч = urlsplit(url_реестра)
    except Exception:  # noqa: BLE001
        return None
    if not ч.scheme or not ч.netloc:
        return None
    порт_точки = т.get("port")
    порт = int(порт_точки) if порт_точки else None
    if порт is None:
        # Порта у точки нет -- берём порт рабочего адреса: он и есть тот, на
        # котором этот отправитель слушает.
        порт = ч.port
    netloc = т["host"] if порт is None or порт == _порт_по_умолчанию(ч.scheme) \
        else f"{т['host']}:{порт}"
    return urlunsplit((ч.scheme, netloc, ч.path, ч.query, ""))


def адрес_для(отправитель: str, регион: str, *,
               url_реестра: str | None = None) -> dict:
    """Что подставить вместо текущего адреса. ok=False -- ничего не менять."""
    из_ = {"ok": False, "sender": отправитель, "region": регион,
           "url": None, "host": None, "point_region": None, "why_not": None,
           "откуда": None}
    if not включено():
        из_["why_not"] = "путь выключен (BLOOM_REGION_SEND не равен 1)"
        return из_
    if регион == "неизвестно":
        из_["why_not"] = "регион лидера неизвестен -- адрес не меняем"
        return из_
    т = точка(отправитель, регион)
    if not т:
        из_["why_not"] = f"у {отправитель} нет точки для региона {регион} в файле точек"
        return из_
    # АДРЕС СОБИРАЕТСЯ ПО РАБОЧЕМУ: путь и запрос -- его, хост -- точки.
    # Рабочий адрес спрашивается у реестра отправителей; его нет -- отказ
    # словами, а не адрес без пути (см. адрес_точки_как_в_реестре).
    url_реестра = url_реестра if url_реестра is not None else _url_из_реестра(отправитель)
    адрес = адрес_точки_как_в_реестре(т, url_реестра)
    if not адрес:
        из_["why_not"] = ("рабочего адреса отправителя нет в реестре -- "
                           "региональный адрес без пути собирать нельзя")
        из_["url_без_пути"] = адрес_точки(т)
        return из_
    из_.update(ok=True, url=адрес, host=т["host"], point_region=т.get("регион"),
               откуда=т.get("откуда"), url_реестра=url_реестра)
    return из_


def _url_из_реестра(отправитель: str) -> str | None:
    """Рабочий адрес отправителя из реестра. Второго места с адресами нет."""
    try:
        import bloom_senders as SS  # noqa: PLC0415

        return ((SS.реестр() or {}).get(отправитель) or {}).get("url")
    except Exception:  # noqa: BLE001
        return None


# --------------------------------------------------------------- самопроверка
def self_test() -> int:
    проверки = []

    def chk(имя, ок, факт=""):
        проверки.append((имя, bool(ок), факт))

    было = os.environ.get("BLOOM_REGION_SEND")
    os.environ.pop("BLOOM_REGION_SEND", None)
    chk("по умолчанию путь выключен", включено() is False)
    r = адрес_для("helius", "Asia")
    chk("без флага адрес не меняется и причина названа",
        r["ok"] is False and "выключен" in (r["why_not"] or ""), r["why_not"])
    os.environ["BLOOM_REGION_SEND"] = "1"
    try:
        т = точки(заново=True)
        chk("файл точек прочитан и в нём есть отправители", bool(т), list(т)[:6])
        имена_всех = {x["host"] for сп in т.values() for x in сп}

        for отпр, рег, ожидаем_регион in (("helius", "Asia", "Asia"),
                                          ("helius", "US-East", "US-East"),
                                          ("helius", "US-West", "US-West"),
                                          ("helius", "EU", "EU")):
            р = адрес_для(отпр, рег)
            chk(f"{отпр}: для лидера {рег} точка региона {ожидаем_регион}",
                р["ok"] and р["point_region"] == ожидаем_регион, р)
            chk(f"{отпр}: имя точки взято из файла, не выдумано",
                р.get("host") in имена_всех, р.get("host"))
            chk(f"{отпр}: у точки назван источник (документация)",
                bool(р.get("откуда")), р.get("откуда"))

        # Незнакомый регион и незнакомый отправитель -- ничего не меняем.
        chk("незнакомый регион -- адрес как был",
            адрес_для("helius", "неизвестно")["ok"] is False)
        chk("незнакомый отправитель -- адрес как был",
            адрес_для("такого-нет", "Asia")["ok"] is False)

        # БЛИЗОСТЬ: если у отправителя нет точки нужного региона, берём соседний
        # по порядку, а не первую попавшуюся.
        global _ТОЧКИ  # noqa: PLW0603
        сохранить = _ТОЧКИ
        _ТОЧКИ = {"проба": [
            {"host": "slc-x.example", "port": 80, "схема": "http", "регион": "US-West",
             "откуда": "проба"},
            {"host": "ams-x.example", "port": 80, "схема": "http", "регион": "EU",
             "откуда": "проба"}]}
        # РАБОЧИЙ АДРЕС подаётся явно: у пробного отправителя его в реестре нет,
        # а собирать региональный адрес без пути нельзя (см. ниже).
        РАБОЧИЙ = "http://ams-x.example/fast"
        р_аз = адрес_для("проба", "Asia", url_реестра=РАБОЧИЙ)
        chk("нет точки в Азии -- берём западный берег США, не Европу",
            р_аз["ok"] and р_аз["point_region"] == "US-West", р_аз)
        р_ев = адрес_для("проба", "EU", url_реестра=РАБОЧИЙ)
        chk("для EU берём европейскую точку", р_ев["point_region"] == "EU", р_ев)
        # ПУТЬ РАБОЧЕГО АДРЕСА ОБЯЗАН ОСТАТЬСЯ: иначе покупка уйдёт POST-ом не
        # на тот endpoint. Это и был дефект, найденный до включения флага.
        chk("путь рабочего адреса сохранён, хост заменён на региональный",
            р_аз["url"] == "http://slc-x.example/fast", р_аз["url"])
        chk("без рабочего адреса -- отказ словами, а не адрес без пути",
            адрес_для("проба", "EU")["ok"] is False
            and "без пути" in (адрес_для("проба", "EU")["why_not"] or ""),
            адрес_для("проба", "EU"))
        # ПУТИ ВСЕХ ШЕСТИ ОТПРАВИТЕЛЕЙ -- по одному примеру на каждого.
        for имя_, раб_, ждём_ in (
                ("helius", "http://ams-sender.helius-rpc.com/fast",
                  "http://slc-x.example/fast"),
                ("jito", "https://amsterdam.mainnet.block-engine.jito.wtf/api/v1/transactions",
                  "https://slc-x.example/api/v1/transactions"),
                ("zeroslot", "http://ams1.0slot.trade", "http://slc-x.example"),
                ("blockrazor", "http://amsterdam.solana.blockrazor.xyz:443/sendTransaction",
                  "http://slc-x.example:443/sendTransaction"),
                ("nozomi", "https://ams1.nozomi.temporal.xyz/",
                  "https://slc-x.example/"),
                ("astralane", "http://fr.gateway.astralane.io/iris",
                  "http://slc-x.example/iris")):
            _ТОЧКИ = {имя_: [{"host": "slc-x.example", "регион": "US-West",
                               "откуда": "проба"}]}
            р_ = адрес_для(имя_, "US-West", url_реестра=раб_)
            chk(f"{имя_}: региональный адрес сохраняет путь и порт рабочего",
                р_["ok"] and р_["url"] == ждём_, (р_.get("url"), ждём_))
        # Порт 443 при схеме http обязан остаться и в адресе без пути.
        chk("http на 443 -- порт остаётся в адресе без пути",
            адрес_точки({"host": "h.example", "port": 443, "схема": "http"})
            == "http://h.example:443/",
            адрес_точки({"host": "h.example", "port": 443, "схема": "http"}))
        _ТОЧКИ = {"проба": [
            {"host": "slc-x.example", "port": 80, "схема": "http", "регион": "US-West",
             "откуда": "проба"},
            {"host": "ams-x.example", "port": 80, "схема": "http", "регион": "EU",
             "откуда": "проба"}]}
        _ТОЧКИ = {"пусто": []}
        chk("у отправителя нет точек вовсе -- адрес как был",
            адрес_для("пусто", "Asia")["ok"] is False)
        _ТОЧКИ = сохранить

        # Адрес собирается схемой и портом из файла, без выдуманных путей.
        chk("адрес точки: http на 80 без порта в строке",
            адрес_точки({"host": "h.example", "port": 80, "схема": "http"})
            == "http://h.example/",
            адрес_точки({"host": "h.example", "port": 80, "схема": "http"}))
        chk("нестандартный порт остаётся в адресе",
            адрес_точки({"host": "h.example", "port": 8899, "схема": "http"})
            == "http://h.example:8899/")

        # РАСПИСАНИЕ: один вызов узла на эпоху, а не на сделку.
        зовы = []

        def rpc(метод, парам):
            зовы.append(метод)
            return {"ЛИДЕР1": [0, 1], "ЛИДЕР2": [2]}

        _РАСПИСАНИЕ["эпоха"] = None
        _РАСПИСАНИЕ["слоты"] = {}
        начало = 3 * СЛОТОВ_В_ЭПОХЕ
        chk("лидер слота берётся из расписания",
            лидер_слота(rpc, начало + 2) == "ЛИДЕР2",
            лидер_слота(rpc, начало + 2))
        лидер_слота(rpc, начало + 1)
        лидер_слота(rpc, начало + 0)
        chk("расписание спрошено у узла ровно один раз на эпоху",
            зовы.count("getLeaderSchedule") == 1, зовы)

        global _ЛИДЕРЫ  # noqa: PLW0603
        _ЛИДЕРЫ = {"ЛИДЕР2": "Asia"}
        рс = регион_слота(rpc, начало + 2)
        chk("регион слота -- по карте лидеров",
            рс["регион"] == "Asia" and рс["лидер"] == "ЛИДЕР2", рс)
        рс_н = регион_слота(rpc, начало + 1)
        chk("лидера нет в карте -- регион неизвестен, и это не догадка",
            рс_н["регион"] == "неизвестно", рс_н)
        _ЛИДЕРЫ = None
    finally:
        if было is None:
            os.environ.pop("BLOOM_REGION_SEND", None)
        else:
            os.environ["BLOOM_REGION_SEND"] = было
        точки(заново=True)

    плохо = [(и, ф) for и, ок, ф in проверки if not ок]
    for имя, ок, факт in проверки:
        print(f"  [{'ok  ' if ок else 'СБОЙ'}] {имя}" + ("" if ок else f"  -> {факт}"))
    print(f"самопроверка региональной отправки: "
          f"{len(проверки) - len(плохо)}/{len(проверки)} пройдено")
    return 0 if not плохо else 1


