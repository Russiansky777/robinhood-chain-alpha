#!/usr/bin/env python3
"""Наценка нашего входа к цене входа источника. Одно число, честно или никак.

ЗАЧЕМ. Владелец 27.09 в формате сообщения о сделке просит поле "+6.3 % к цене
источника". Этого числа не было ни в одном журнале: в позиции лежат наша трата
и полученные токены, у источника -- своя транзакция, а сравнения между ними не
делал никто.

ГЛАВНОЕ ПРАВИЛО, И ОНО НЕ НАШЕ ИЗОБРЕТЕНИЕ. Курс считается ПО ОДНОМУ И ТОМУ ЖЕ
ХРАНИЛИЩУ ПУЛА на обеих сторонах. Это урок, уже оплаченный в bloom_ab_pairs:
когда вход мерили в одном пуле маршрута, а выход в другом, выходило +2920 % и
-96.8 % там, где итог был -10 %. Процент между ценами в разных единицах -- не
величина, а артефакт. Поэтому: не смогли посчитать обе цены в ОДНОМ хранилище
-- отдаём known=False с причиной словами, и в сообщении стоит черта. Черта
честнее артефакта.

ЧТО ЭТО ЗА ПРОЦЕНТ. Отношение цены, по которой токен достался НАМ, к цене, по
которой он достался ИСТОЧНИКУ, в процентах: положительное значит мы взяли
дороже. Чаевые и приоритет здесь не участвуют намеренно -- это отношение ЦЕН
в пуле, а не наш итог по деньгам; итог считается на продаже и показывается
отдельной строкой.
"""
from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))


def наценка_входа(helius, *, минт: str, подпись_источника: str | None,
                   кошелёк_источника: str | None, подпись_нашей: str | None,
                   tx_нашей: dict | None = None,
                   tx_источника: dict | None = None) -> dict:
    """Процент нашей цены входа к цене входа источника.

    Транзакции можно передать готовыми (tx_нашей/tx_источника) -- тогда сети
    не нужно вовсе. Это не роскошь: докладчик покупки уже держит НАШУ
    транзакцию в руках, и второй запрос за ней был бы кредитом впустую.
    """
    из_ = {"known": False, "pct": None, "why_not": None, "pool": None,
            "rate_ours": None, "rate_source": None}
    if not минт:
        из_["why_not"] = "минт не передан"
        return из_
    try:
        import bloom_price_curve as PC  # noqa: PLC0415
    except Exception as exc:  # noqa: BLE001
        из_["why_not"] = f"модуль цен не загружен: {type(exc).__name__}"
        return из_

    tx_и = tx_источника
    if tx_и is None:
        if not подпись_источника or helius is None:
            из_["why_not"] = "транзакции источника нет и запросить её нечем"
            return из_
        tx_и = helius.транзакция(подпись_источника)
    if not tx_и:
        из_["why_not"] = "узел не отдал транзакцию источника"
        return из_

    tx_н = tx_нашей
    if tx_н is None:
        if not подпись_нашей or helius is None:
            из_["why_not"] = "нашей транзакции нет и запросить её нечем"
            return из_
        tx_н = helius.транзакция(подпись_нашей)
    if not tx_н:
        из_["why_not"] = "узел не отдал нашу транзакцию"
        return из_

    # ПУЛ ИСТОЧНИКА -- эталон для обеих сторон. Берём его выбором, который
    # уже используют кривая и пары, а не угадываем по счетам.
    выбор = PC.пул_для_кривой(helius, минт=минт, tx_источника=tx_и,
                               кошелёк_источника=кошелёк_источника) or {}
    хранилище = выбор.get("pool")
    if not хранилище:
        из_["why_not"] = f"пул источника не выделить: {выбор.get('why_not')}"
        return из_
    из_["pool"] = хранилище

    ист = PC.курс_по_пулу(tx_и, минт, хранилище=хранилище)
    if not ист.get("known"):
        из_["why_not"] = f"курс входа источника: {ист.get('why_not')}"
        return из_
    наш = PC.курс_по_пулу(tx_н, минт, хранилище=хранилище)
    if not наш.get("known"):
        из_["why_not"] = f"курс нашего входа: {наш.get('why_not')}"
        return из_
    # ОДНО ХРАНИЛИЩЕ НА ОБЕИХ СТОРОНАХ -- проверяется, а не предполагается.
    if ист.get("vault") != наш.get("vault"):
        из_["why_not"] = ("наш вход и вход источника посчитаны по разным "
                           f"хранилищам ({str(ист.get('vault'))[:10]} и "
                           f"{str(наш.get('vault'))[:10]}) -- процент между "
                           "ними был бы артефактом")
        return из_
    if ист.get("quote_mint") != наш.get("quote_mint"):
        из_["why_not"] = "котировочные минты сторон различаются -- сравнивать нельзя"
        return из_
    try:
        r_и = float(ист["rate"])
        r_н = float(наш["rate"])
    except (TypeError, ValueError, KeyError):
        из_["why_not"] = "курс не число"
        return из_
    if r_и <= 0:
        из_["why_not"] = f"курс входа источника не положителен: {r_и}"
        return из_
    из_.update(known=True, rate_ours=r_н, rate_source=r_и,
               quote_mint=ист.get("quote_mint"),
               pct=round((r_н / r_и - 1.0) * 100.0, 2))
    return из_


# ------------------------------------------------------------------ самопроверка

def self_test() -> int:
    """Проверяется ровно то, чем этот модуль может соврать: сравнение цен,
    посчитанных в разных хранилищах или разных котировках."""
    всего = [0, 0]

    def chk(имя, условие, факт=None):
        всего[0] += 1
        if условие:
            всего[1] += 1
            print(f"  [ok  ] {имя}")
        else:
            print(f"  [ПЛОХО] {имя}" + (f" -- {факт}" if факт is not None else ""))

    import types  # noqa: PLC0415

    import bloom_price_curve as PC  # noqa: PLC0415

    ХРАН = "ХРАНИЛИЩЕ-ПУЛА"
    было_пул, было_курс = PC.пул_для_кривой, PC.курс_по_пулу
    состояние: dict = {}

    def пул_подмена(helius, *, минт, tx_источника, кошелёк_источника):
        return {"pool": состояние.get("пул", ХРАН), "pool_from": "подмена"}

    def курс_подмена(tx, минт, *, хранилище=None, кошелёк=None):
        # Курс берётся из самой транзакции-заглушки: так проверка сравнивает
        # именно логику модуля, а не разбор цепи.
        return dict(tx.get("курс") or {"known": False, "why_not": "нет курса"})

    PC.пул_для_кривой = пул_подмена
    PC.курс_по_пулу = курс_подмена
    try:
        ист = {"курс": {"known": True, "rate": 100.0, "vault": ХРАН,
                        "quote_mint": "WSOL"}}
        наш = {"курс": {"known": True, "rate": 106.3, "vault": ХРАН,
                        "quote_mint": "WSOL"}}
        р = наценка_входа(None, минт="М", подпись_источника="И",
                           кошелёк_источника="К", подпись_нашей="Н",
                           tx_нашей=наш, tx_источника=ист)
        chk("наценка считается и это +6.3 %", р["known"] is True and р["pct"] == 6.3, р)
        равные = {"курс": dict(ист["курс"])}
        chk("те же цены -- ровно ноль",
            наценка_входа(None, минт="М", подпись_источника="И",
                           кошелёк_источника="К", подпись_нашей="Н",
                           tx_нашей=равные, tx_источника=ист)["pct"] == 0.0, "")
        дешевле = {"курс": {"known": True, "rate": 90.0, "vault": ХРАН,
                             "quote_mint": "WSOL"}}
        chk("взяли дешевле источника -- процент отрицательный",
            наценка_входа(None, минт="М", подпись_источника="И",
                           кошелёк_источника="К", подпись_нашей="Н",
                           tx_нашей=дешевле, tx_источника=ист)["pct"] == -10.0, "")

        # ГЛАВНОЕ: разные хранилища -- отказ, а не число.
        чужое = {"курс": {"known": True, "rate": 3000.0, "vault": "ДРУГОЕ",
                           "quote_mint": "WSOL"}}
        р_ч = наценка_входа(None, минт="М", подпись_источника="И",
                             кошелёк_источника="К", подпись_нашей="Н",
                             tx_нашей=чужое, tx_источника=ист)
        chk("разные хранилища -- known=False и причина словами",
            р_ч["known"] is False and "артефакт" in (р_ч["why_not"] or ""), р_ч)
        chk("и числа при этом не отдаётся вовсе", р_ч["pct"] is None, р_ч)

        # Разные котировки -- тоже отказ.
        друг_кот = {"курс": {"known": True, "rate": 106.3, "vault": ХРАН,
                              "quote_mint": "USDC"}}
        chk("разные котировочные минты -- отказ",
            наценка_входа(None, минт="М", подпись_источника="И",
                           кошелёк_источника="К", подпись_нашей="Н",
                           tx_нашей=друг_кот, tx_источника=ист)["known"] is False, "")

        # Неизвестный курс одной из сторон -- отказ с указанием, чьей.
        нет_курса = {"курс": {"known": False, "why_not": "хранилище не встречается"}}
        р_н = наценка_входа(None, минт="М", подпись_источника="И",
                             кошелёк_источника="К", подпись_нашей="Н",
                             tx_нашей=нет_курса, tx_источника=ист)
        chk("курс нашего входа неизвестен -- сказано, что именно нашего",
            р_н["known"] is False and "нашего входа" in (р_н["why_not"] or ""), р_н)
        р_и = наценка_входа(None, минт="М", подпись_источника="И",
                             кошелёк_источника="К", подпись_нашей="Н",
                             tx_нашей=наш, tx_источника=нет_курса)
        chk("курс входа источника неизвестен -- сказано, что источника",
            р_и["known"] is False and "источника" in (р_и["why_not"] or ""), р_и)

        # Нулевой курс источника -- делить нельзя.
        ноль = {"курс": {"known": True, "rate": 0.0, "vault": ХРАН,
                          "quote_mint": "WSOL"}}
        chk("нулевой курс источника -- отказ, а не деление на ноль",
            наценка_входа(None, минт="М", подпись_источника="И",
                           кошелёк_источника="К", подпись_нашей="Н",
                           tx_нашей=наш, tx_источника=ноль)["known"] is False, "")

        # Пул не выделен -- отказ.
        состояние["пул"] = None
        chk("пул источника не выделен -- отказ словами",
            наценка_входа(None, минт="М", подпись_источника="И",
                           кошелёк_источника="К", подпись_нашей="Н",
                           tx_нашей=наш, tx_источника=ист)["known"] is False, "")
        состояние.pop("пул", None)

        # Транзакций нет и запросить нечем.
        chk("нет транзакции и узла -- отказ, а не падение",
            наценка_входа(None, минт="М", подпись_источника=None,
                           кошелёк_источника="К", подпись_нашей=None)["known"] is False, "")
        chk("нет минта -- отказ",
            наценка_входа(None, минт="", подпись_источника="И",
                           кошелёк_источника="К", подпись_нашей="Н",
                           tx_нашей=наш, tx_источника=ист)["known"] is False, "")
        del types
    finally:
        PC.пул_для_кривой, PC.курс_по_пулу = было_пул, было_курс

    print(f"самопроверка наценки входа: {всего[1]}/{всего[0]} пройдено")
    return 0 if всего[1] == всего[0] else 1


if __name__ == "__main__":
    sys.exit(self_test())
