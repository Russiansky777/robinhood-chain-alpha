def корзина(о: float) -> str:
    for имя, низ, верх in КОРЗИНЫ:
        if (низ is None or о >= низ) and (верх is None or о < верх):
            return имя
    return "> 1.03"


def разобрать(x: dict) -> dict | None:
    """Отношение списанного к билету и причина, или None -- если покупка не легла / части нет."""
    б = x.get("билет_sol")
    п = x.get("покупка") or {}
    все, кош = п.get("все_sol"), п.get("кошелёк_sol")
    if not б or все is None or x.get("итог_po_cepi_sol") is None:
        return None
    ком, чае, рен = x.get("комиссия_sol") or 0.0, x.get("чаевые_sol") or 0.0, x.get("рента_sol") or 0.0
    списано = abs(все) - ком - чае
    натив = (abs(кош) - ком - чае - рен) if кош is not None else None
    о = списано / б
    зав = x.get("завёрнутое_sol") or (x.get("lane") or {}).get("lane_buy_wrapped_sol") or 0.0
    л = x.get("lane") or {}
    куп, ожид = л.get("lane_bought_raw"), л.get("lane_expected_out")
    доля_токенов = (куп / ожид) if (куп and ожид) else None
    причина = None
    if о < 0.995:
        причина = "цена"  # в сам пул ушло меньше билета
    elif натив is not None and натив < списано - 0.005:
        причина = "остаток WSOL"
    return {"cid": x["cid"], "utc": x["utc"], "группа": x.get("group"), "токен": x.get("token_name"),
            "пул": ПУЛЫ.get(x.get("stroitel"), x.get("stroitel") or "нет"), "билет": б,
            "списано": списано, "списано_натив": натив, "завёрнутое": зав, "отношение": о, "корзина": корзина(о),
            "причина": причина, "доля_токенов": доля_токенов, "мин_выход": л.get("lane_min_out"),
            "итог_sol": x["итог_po_cepi_sol"], "итог_пп": x["итог_po_cepi_sol"] / б * 100.0,
            "s_plus": x.get("s_plus")}


def свод(ряды: list[dict]) -> str:
    if not ряды:
        return "| 0 | — | — | — |"
    и = [r["итог_пп"] for r in ряды]
    return (f"| {len(ряды)} | {statistics.median(и):+.1f} | {statistics.fmean(и):+.1f} | "
            f"{sum(1 for v in и if v > 0) / len(и) * 100:.0f} % |")


def выигрыш(ряды: list[dict], x_pct: float) -> tuple[int, float, float]:
    """«Купили дешевле плана на X % -> продать сразу»: сделки с отношением <= 1 − X/100 и их итог по цепи."""
    от = [r for r in ряды if r["отношение"] <= 1 - x_pct / 100.0]
    if not от:
        return 0, 0.0, 0.0
    и = [r["итог_пп"] for r in от]
    return len(от), statistics.median(и), statistics.fmean(и)


