#!/usr/bin/env python3
"""«Купили дешевле плана»: отношение фактически списанного на покупке к билету против итога по цепи. Офлайн.

Вход -- data/podbivka/deshevle_vhod_2026-10-01.json: поля Правила 13 из выгрузок Code-1
(data/sdelki_polosy_2026-10-01_pravilo13.json и data/sdelki_polosy_2026-10-01.json, объединение по cid).

Счёт:
  * списано_все = |покупка.все_sol| − комиссия − чаевые. «все_sol» -- изменение ВСЕХ наших счетов на покупке,
    то есть в пул ушло ровно это (рента возвращается при закрытии счёта токена и в «все_sol» не входит);
  * отношение = списано_все / билет -- корзины < 0.90 / 0.90–0.97 / 0.97–1.03 / > 1.03;
  * списано_натив = |покупка.кошелёк_sol| − комиссия − чаевые − рента -- сколько заплатили лампортами кошелька;
  * причина «ушло меньше»: если списано_натив заметно меньше списано_все -- часть билета закрыта остатком WSOL
    на счёте (завёрнутое_sol / lane_buy_wrapped_sol); иначе меньше ушло в сам пул -- причина в цене;
  * сторона цены: полоса просит exact-out (купить ровно lane_min_out токенов, не дороже билета), поэтому
    lane_bought_raw / lane_expected_out < 1 значит цену ВЫШЕ котировки (за те же токены больше SOL), > 1 -- ниже;
  * итог -- итог_po_cepi_sol в п.п. билета.
Выход: docs/podbivka_2026-10-01_deshevle_plana.md.
"""
