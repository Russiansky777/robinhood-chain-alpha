#!/usr/bin/env python3
"""Подбивка: снайперы -- сводка по data/podbivka/snaipery/*.json (офлайн).

Карточка на кошелёк:
 1. покупки: число, размер SOL-экв. (медиана / сумма), программы пулов,
    приоритет и чаевые (оценка), индекс в блоке;
 2. кого копируют: покупатели того же минта в слотах s0−3 .. s0 до снайпера --
    частотная таблица (все и «ближайший» -- последний перед ним), в наших списках
    ли (23 торгующих / лог 555 / нет; конфигурация Code-1 data/sources_2026-09-25.json,
    только чтение), слотов и позиций в блоке до снайпера;
 3. заработок по минтам окна: SOL вошло / вышло, удержание, доля проданного в
    слоте покупки; итог до и после чаевых и комиссий; закрыто в плюс;
 4. экономика места: чаевые / размер, связь чаевых с расстоянием от источника.
Итог -- карточки + список источников, которых нет ни в торгующих, ни в логе.
"""
from __future__ import annotations

import collections
import glob
import json
import statistics
import subprocess
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parent.parent


def мед(xs):
    xs = [x for x in xs if x is not None]
    return statistics.median(xs) if xs else None


def ф(x, z="+.3f"):
    return "—" if x is None else format(x, z)


def спирмен(a, b):
    п = [(x, y) for x, y in zip(a, b) if x is not None and y is not None]
    if len(п) < 5:
        return None, len(п)

    def ранги(v):
        о = sorted(range(len(v)), key=lambda i: v[i])
        р = [0.0] * len(v)
        i = 0
        while i < len(о):
            j = i
            while j + 1 < len(о) and v[о[j + 1]] == v[о[i]]:
                j += 1
            for k in range(i, j + 1):
                р[о[k]] = (i + j) / 2
            i = j + 1
        return р
    ra, rb = ранги([x for x, _ in п]), ранги([y for _, y in п])
    ma, mb = statistics.mean(ra), statistics.mean(rb)
    ч = sum((x - ma) * (y - mb) for x, y in zip(ra, rb))
    з = (sum((x - ma) ** 2 for x in ra) * sum((y - mb) ** 2 for y in rb)) ** 0.5
    return (ч / з if з else None), len(п)


def списки():
    конф = json.loads(subprocess.run(["git", "show", "origin/claude/nifty-sagan-r0polg:data/sources_2026-09-25.json"],
                                     cwd=КОРЕНЬ, capture_output=True, text=True, check=True).stdout)
    торг, лог = {}, set()
    for гр in ("leader", "batch5", "lane_s0"):
        for а, x in конф["groups"][гр]["addresses"].items():
            торг[а] = x.get("name") or а[:8]
    г = конф["groups"].get("log_only") or {}
    лог = set((г.get("addresses") if isinstance(г, dict) else г) or [])
    return торг, лог


def карточка(д: dict, торг: dict, лог: set, чужие: collections.Counter) -> list:
    кош = д["кошелёк"]
    сд = д["сделки"]
    пок = [с for с in сд if с["сторона"] == "buy" and not с.get("многоминтовая")]
    прод = [с for с in сд if с["сторона"] == "sell" and not с.get("многоминтовая")]
    мм = sum(1 for с in сд if с.get("многоминтовая"))
    размер = [-с["sol_экв"] for с in пок if not с.get("usd_без_курса")]
    md = [f"## {кош}", "",
          f"Окно: {д['часов']:.0f} ч с {д['с_utc']}; подписей {д['подписей']}; покупок {len(пок)}, продаж {len(прод)}"
          + (f"; сделок с несколькими минтами (не разбирались) {мм}" if мм else "") + ".", "",
          "### 1. Покупки", "",
          "| показатель | значение |", "|---|---|",
          f"| размер SOL-экв., медиана / сумма | {ф(мед(размер), '.3f')} / {ф(sum(размер), '.2f')} |",
          "| программы пулов | " + ", ".join(f"{(k or '?')[:8]} {v}" for k, v in collections.Counter(
              с.get("программа") for с in пок).most_common(6)) + " |",
          "| котировка пула | " + ", ".join(f"{(k or '?')[:6]} {v}" for k, v in collections.Counter(
              с.get("котировка_пула") for с in пок).most_common(4)) + " |",
          f"| приоритет, лампорты: медиана / p90 | {ф(мед([с['приоритет'] for с in пок]), '.0f')} / "
          f"{ф(sorted(с['приоритет'] for с in пок)[int(0.9 * len(пок))] if пок else None, '.0f')} |",
          f"| чаевые (оценка), SOL: медиана / сумма за окно | {ф(мед([с['чаевые_lamports'] / 1e9 for с in пок]), '.5f')} / "
          f"{ф(sum(с['чаевые_lamports'] for с in сд) / 1e9, '.4f')} |",
          f"| индекс в блоке: медиана / доля в первых 50 | {ф(мед([с.get('индекс') for с in пок]), '.0f')} / "
          f"{ф(sum(1 for с in пок if (с.get('индекс') or 10**9) < 50) / len(пок) * 100 if пок else None, '.0f')} % |",
          "| получатели чаевых (оценка), топ | " + ", ".join(f"{к[:8]} {v}" for к, v in collections.Counter(
              ч["куда"] for с in сд for ч in с.get("чаевые") or []).most_common(5)) + " |", ""]
    md += ["Покупки (первые 40 по времени):", "", "| слот | минт | SOL-экв. | программа | приоритет | чаевые (оценка) | индекс / в блоке |",
           "|---|---|---|---|---|---|---|"]
    for с in пок[:40]:
        md.append(f"| {с['slot']} | {с['mint'][:8]} | {ф(-с['sol_экв'], '.3f')} | {(с.get('программа') or '?')[:8]} | "
                  f"{с['приоритет']} | {с['чаевые_lamports'] / 1e9:.5f} | {с.get('индекс')} / {с.get('в_блоке')} |")
    # 2. источники
    все = collections.Counter()
    ближ = collections.Counter()
    сл, поз = collections.defaultdict(list), collections.defaultdict(list)
    без_ист = 0
    for с in пок:
        ист = [x for x in с.get("источники") or [] if x.get("адрес")]
        if not ист:
            без_ист += 1
            continue
        for а in {x["адрес"] for x in ист}:
            все[а] += 1
        б = max(ист, key=lambda x: (x["слот"], x["индекс"] if x["индекс"] is not None else -1))
        ближ[б["адрес"]] += 1
        сл[б["адрес"]].append(б["слотов_до"])
        поз[б["адрес"]].append(б.get("позиций_до"))
        с["_ближ"] = б

    def где(а):
        return f"торгующий ({торг[а]})" if а in торг else ("лог 555" if а in лог else "нет")
    md += ["", "### 2. Кого копируют", "",
           f"Покупок с покупателем того же минта в s0−3 .. s0 до снайпера: {len(пок) - без_ист} из {len(пок)} "
           f"(без такого покупателя -- {без_ист}). «Ближайший» -- последний перед ним.", "",
           "| источник | ближайший, раз | всего в окне, раз | наши списки | слотов до, медиана | позиций до в том же слоте, медиана |",
           "|---|---|---|---|---|---|"]
    for а, n in ближ.most_common(25):
        md.append(f"| {а} | {n} | {все[а]} | {где(а)} | {ф(мед(сл[а]), '.0f')} | {ф(мед(поз[а]), '.0f')} |")
        if где(а) == "нет":
            чужие[а] += n
    md.append(f"| прочие ({max(0, len(ближ) - 25)} адресов) | {sum(n for а, n in ближ.most_common()[25:])} | | | | |")
    # 3. заработок
    по_минту = collections.defaultdict(lambda: {"b": [], "s": []})
    for с in пок:
        по_минту[с["mint"]]["b"].append(с)
    for с in прод:
        по_минту[с["mint"]]["s"].append(с)
    закрытые, открытые, без_покупки = [], 0, 0
    for m, x in по_минту.items():
        if not x["b"]:
            без_покупки += 1
            continue
        куплено = sum(с["токенов"] for с in x["b"])
        продано = sum(с["токенов"] for с in x["s"])
        if продано < 0.99 * куплено:
            открытые += 1
            continue
        вход = sum(-с["sol_экв"] for с in x["b"])
        выход = sum(с["sol_экв"] for с in x["s"])
        издержки = sum(с["чаевые_lamports"] + (с["fee"] if с.get("плательщик") else 0) for с in x["b"] + x["s"]) / 1e9
        б0 = min(x["b"], key=lambda с: с["slot"])
        с0 = min(x["s"], key=lambda с: с["slot"])
        в_слоте = sum(с["токенов"] for с in x["s"] if с["slot"] == б0["slot"]) / куплено if куплено else None
        закрытые.append({"вход": вход, "выход": выход, "издержки": издержки, "слотов": с0["slot"] - б0["slot"],
                         "сек": (с0.get("blockTime") or 0) - (б0.get("blockTime") or 0), "в_слоте": в_слоте,
                         "usd": any(с.get("usd_без_курса") for с in x["b"] + x["s"])})
    итог_до = sum(з["выход"] - з["вход"] for з in закрытые)
    итог_после = итог_до - sum(з["издержки"] for з in закрытые)
    md += ["", "### 3. Заработок (минты окна, полностью проданные)", "",
           "| показатель | значение |", "|---|---|",
           f"| закрыто / открыто на конец окна / продажи без покупки в окне | {len(закрытые)} / {открытые} / {без_покупки} |",
           f"| SOL вошло / вышло | {sum(з['вход'] for з in закрытые):.3f} / {sum(з['выход'] for з in закрытые):.3f} |",
           f"| итог до чаевых и комиссий, SOL | {итог_до:+.3f} |",
           f"| итог после чаевых (оценка) и комиссий, SOL | {итог_после:+.3f} |",
           f"| закрыто в плюс (до / после издержек) | {sum(1 for з in закрытые if з['выход'] > з['вход'])} / "
           f"{sum(1 for з in закрытые if з['выход'] - з['издержки'] > з['вход'])} из {len(закрытые)} |",
           f"| удержание до первой продажи: медиана, слотов / секунд | {ф(мед([з['слотов'] for з in закрытые]), '.0f')} / "
           f"{ф(мед([з['сек'] for з in закрытые]), '.0f')} |",
           f"| доля проданного в слоте покупки: медиана / доля минтов с продажей в том же слоте | "
           f"{ф(мед([з['в_слоте'] for з in закрытые]), '.2f')} / "
           f"{ф(sum(1 for з in закрытые if (з['в_слоте'] or 0) > 0) / len(закрытые) * 100 if закрытые else None, '.0f')} % |",
           f"| минтов со стейблом без курса (SOL-экв. занижен) | {sum(1 for з in закрытые if з['usd'])} |", ""]
    # 4. экономика места
    доли = [с["чаевые_lamports"] / 1e9 / -с["sol_экв"] * 100 for с in пок if с["sol_экв"] < 0 and not с.get("usd_без_курса")]
    с_ист = [с for с in пок if с.get("_ближ")]
    r_сл, n1 = спирмен([с["чаевые_lamports"] for с in с_ист], [с["_ближ"]["слотов_до"] for с in с_ист])
    same = [с for с in с_ист if с["_ближ"]["слотов_до"] == 0 and с["_ближ"].get("позиций_до") is not None]
    r_поз, n2 = спирмен([с["чаевые_lamports"] for с in same], [с["_ближ"]["позиций_до"] for с in same])
    md += ["### 4. Экономика места", "",
           "| показатель | значение |", "|---|---|",
           f"| чаевые (оценка) / размер покупки, %: медиана / p90 | {ф(мед(доли), '.2f')} / "
           f"{ф(sorted(доли)[int(0.9 * len(доли))] if доли else None, '.2f')} |",
           f"| в том же слоте, что ближайший источник | {len(same)} из {len(с_ист)} |",
           f"| Спирмен: чаевые ↔ слотов от источника | {ф(r_сл, '+.2f')} (n {n1}) |",
           f"| Спирмен: чаевые ↔ позиций от источника в том же слоте | {ф(r_поз, '+.2f')} (n {n2}) |", ""]
    if с_ист:
        кв = sorted(с_ист, key=lambda с: с["чаевые_lamports"])
        md += ["| чаевые, четверть | чаевые, SOL (медиана) | слотов от источника, медиана | в том же слоте, % |", "|---|---|---|---|"]
        for k in range(4):
            ч = кв[k * len(кв) // 4:(k + 1) * len(кв) // 4]
            if ч:
                md.append(f"| {k + 1} | {мед([с['чаевые_lamports'] / 1e9 for с in ч]):.5f} | "
                          f"{мед([с['_ближ']['слотов_до'] for с in ч]):.0f} | "
                          f"{sum(1 for с in ч if с['_ближ']['слотов_до'] == 0) / len(ч) * 100:.0f} |")
    return md + [""]


def main() -> int:
    торг, лог = списки()
    чужие = collections.Counter()
    md = ["# Подбивка: снайперы из сделки KABUTSTR (слот 451134500)", "",
          "Только чтение цепи. Размер -- SOL-экв. сделки без комиссии сети и чаевых. Чаевые -- оценка: внешние "
          "системные переводы SOL от кошелька на чужой адрес. Источник -- покупатель того же минта в слотах s0−3 .. s0 "
          "до снайпера (кого он копирует -- оценка по времени, не доказательство). Наши списки -- конфигурация Code-1: "
          f"торгующих {len(торг)}, лог {len(лог)}.", ""]
    for f in sorted(glob.glob(str(КОРЕНЬ / "data" / "podbivka" / "snaipery" / "*.json"))):
        md += карточка(json.loads(Path(f).read_text(encoding="utf-8")), торг, лог, чужие)
    md += ["## Источники снайперов, которых нет ни в торгующих, ни в логе", "",
           "| адрес | раз «ближайшим» (оба снайпера) |", "|---|---|"]
    for а, n in чужие.most_common():
        md.append(f"| {а} | {n} |")
    md.append("")
    (КОРЕНЬ / "docs" / "podbivka_2026-09-28_snaipery.md").write_text("\n".join(md), encoding="utf-8")
    print("\n".join(md[:60]))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
