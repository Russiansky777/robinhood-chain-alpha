def self_test() -> int:
    всего = [0, 0]

    def chk(имя, условие, факт=None):
        всего[0] += 1
        if условие:
            всего[1] += 1
            print(f"  [ok  ] {имя}")
        else:
            print(f"  [ПЛОХО] {имя}" + (f" -- {факт}" if факт is not None else ""))

    def бал(индекс, минт):
        return {"accountIndex": индекс, "mint": минт,
                "uiTokenAmount": {"amount": "1", "decimals": 6, "uiAmount": 1e-6}}

    def передача(минт=None, источник=None, получатель=None, тип="transferChecked"):
        инфо = {"authority": "КТО-ТО"}
        if минт:
            инфо["mint"] = минт
        if источник:
            инфо["source"] = источник
        if получатель:
            инфо["destination"] = получатель
        return {"programId": "TokenkegQfeZyiNwAJbNbGKPFXCWuBvf9Ss623VQ5DA",
                 "parsed": {"type": тип, "info": инфо}}

    def tx_маршрут(передачи, балансы=()):
        return {"transaction": {"message": {
                    "accountKeys": [{"pubkey": f"СЧЁТ{и}"} for и in range(12)],
                    "instructions": []}},
                 "meta": {"err": None,
                           "preTokenBalances": list(балансы),
                           "postTokenBalances": list(балансы),
                           "innerInstructions": [{"instructions": list(передачи)}]}}

    налоги = {"PICKAXE": 300, "GP": 300, "GLDx": 0, "ОБЫЧНЫЙ": 0,
               "НАЛОГОВЫЙ_ПРЯМОЙ": 250}

    def налог_фн(минт):
        return {"taxed": bool(налоги.get(минт)), "fee_bps": налоги.get(минт, 0)}

    # --- ПЕРЕДАЧИ СЧИТАЮТСЯ ПО ИНСТРУКЦИЯМ, а не по балансам: туда-и-обратно
    # по балансам выглядит нулём, а налог снят дважды.
    t1 = tx_маршрут([передача("GP"), передача("GP"), передача("PICKAXE")])
    п1 = передачи_по_минтам(t1)
    chk("передачи считаются по каждому минту",
        п1["by_mint"] == {"GP": 2, "PICKAXE": 1} and п1["total"] == 3, п1)

    # Классический transfer без минта: минт берётся по счёту из балансов.
    t2 = tx_маршрут([передача(источник="СЧЁТ3", получатель="СЧЁТ4", тип="transfer")],
                     балансы=[бал(3, "GP"), бал(4, "GP")])
    п2 = передачи_по_минтам(t2)
    chk("классический transfer опознаётся по счёту в балансах",
        п2["by_mint"] == {"GP": 1} and п2["unknown"] == 0, п2)

    t3 = tx_маршрут([передача(источник="НЕИЗВЕСТНЫЙ", тип="transfer")])
    chk("передача без опознанного минта идёт в unknown, а не в ноль",
        передачи_по_минтам(t3)["unknown"] == 1, передачи_по_минтам(t3))

    # --- СЛУЧАЙ ВЛАДЕЛЬЦА: PICKAXE через GLDx и GP, GP передан дважды.
    t_pickaxe = tx_маршрут([передача(WSOL), передача(USDC), передача("GLDx"),
                             передача("GP"), передача("GP"), передача("PICKAXE")])
    р = налог_маршрута(t_pickaxe, "PICKAXE", налог_фн)
    chk("налог маршрута PICKAXE считает и промежуточный GP дважды",
        р["route_transfer_fee_bps"] == 300 * 2 + 300 * 1, р)
    chk("налог самого токена отделён от налога маршрута",
        р["token_fee_bps"] == 300, р)
    chk("налоговый промежуточный назван по имени",
        [з["mint"] for з in р["taxed_intermediates"]] == ["GP"], р["taxed_intermediates"])
    chk("котировочные монеты в налог не идут",
        set(р["quote_mints"]) == {WSOL, USDC}, р["quote_mints"])
    ф = фильтр_маршрута(р, прямой_пул=False, котировка=None)
    chk("PICKAXE режется фильтром владельца",
        ф["skip"] is True and ф["code"] == КОД_ПРОПУСКА
        and "GP" in ф["reason"], ф)

    # --- НАЛОГОВЫЙ ТОКЕН С ПРЯМЫМ ПУЛОМ К SOL -- покупаем (слово владельца).
    t_прямой = tx_маршрут([передача(WSOL), передача("НАЛОГОВЫЙ_ПРЯМОЙ")])
    р2 = налог_маршрута(t_прямой, "НАЛОГОВЫЙ_ПРЯМОЙ", налог_фн)
    ф2 = фильтр_маршрута(р2, прямой_пул=True, котировка=WSOL)
    chk("налоговый токен с прямым пулом к SOL проходит, но помечен",
        ф2["skip"] is False and ф2["would_skip_fee"] is True
        and "покупаем по слову владельца" in (ф2["reason"] or ""), (р2, ф2))
    chk("и его налог всё равно посчитан",
        р2["route_transfer_fee_bps"] == 250 and р2["token_fee_bps"] == 250, р2)

    # Тот же токен, но передан дважды: это уже маршрут, а не прямой пул.
    t_дважды = tx_маршрут([передача(WSOL), передача("НАЛОГОВЫЙ_ПРЯМОЙ"),
                            передача("НАЛОГОВЫЙ_ПРЯМОЙ")])
    р3 = налог_маршрута(t_дважды, "НАЛОГОВЫЙ_ПРЯМОЙ", налог_фн)
    ф3 = фильтр_маршрута(р3, прямой_пул=True, котировка=WSOL)
    chk("две передачи налогового токена режутся даже при прямом пуле к SOL",
        ф3["skip"] is True and ф3["would_skip_fee"] is True
        and "передан 2" in (ф3["reason"] or ""), (р3, ф3))
    t_трижды = tx_маршрут([передача(WSOL), передача("НАЛОГОВЫЙ_ПРЯМОЙ"),
                            передача("НАЛОГОВЫЙ_ПРЯМОЙ"),
                            передача("НАЛОГОВЫЙ_ПРЯМОЙ")])
    ф4 = фильтр_маршрута(налог_маршрута(t_трижды, "НАЛОГОВЫЙ_ПРЯМОЙ", налог_фн),
                          прямой_пул=True, котировка=WSOL)
    chk("три передачи -- уже не прямой пул, режем",
        ф4["skip"] is True, ф4)

    # --- ОБЫЧНЫЙ ТОКЕН БЕЗ НАЛОГА: ничего не режется.
    t_обычный = tx_маршрут([передача(WSOL), передача("ОБЫЧНЫЙ")])
    ро = налог_маршрута(t_обычный, "ОБЫЧНЫЙ", налог_фн)
    фо = фильтр_маршрута(ро, прямой_пул=True, котировка=WSOL)
    chk("обычный токен не режется и налог у него ноль",
        фо["skip"] is False and ро["route_transfer_fee_bps"] == 0
        and ро["token_fee_bps"] == 0, (ро, фо))

    # Обычный токен, но переданный дважды: правило владельца про число
    # передач работает и без налога? Налог маршрута тогда ноль, и резать
    # нечего -- пропускаем, но помечаем.
    t_об_дважды = tx_маршрут([передача(WSOL), передача("ОБЫЧНЫЙ"),
                               передача("ОБЫЧНЫЙ")])
    р_об = налог_маршрута(t_об_дважды, "ОБЫЧНЫЙ", налог_фн)
    ф_об = фильтр_маршрута(р_об, прямой_пул=True, котировка=WSOL)
    chk("у обычного токена две передачи налога не создают",
        р_об["route_transfer_fee_bps"] == 0, р_об)
    chk("и решение по нему -- покупать: без налога вторая передача не стоит ничего",
        ф_об["skip"] is False and ф_об["would_skip_fee"] is False, ф_об)

    # --- КОТИРОВКА НЕ SOL И НЕ USDC: исключение не применяется.
    t_чужая = tx_маршрут([передача(USDT), передача("НАЛОГОВЫЙ_ПРЯМОЙ"),
                           передача("НАЛОГОВЫЙ_ПРЯМОЙ")])
    ф_ч = фильтр_маршрута(налог_маршрута(t_чужая, "НАЛОГОВЫЙ_ПРЯМОЙ", налог_фн),
                           прямой_пул=True, котировка=USDT)
    chk("прямой пул к USDT исключением не считается -- режем",
        ф_ч["skip"] is True, ф_ч)

    # --- УСТОЙЧИВОСТЬ: пустая транзакция, нет минта, налог не читается.
    chk("пустая транзакция -- причина словами, а не падение",
        налог_маршрута({}, "М", налог_фн)["why_not"] is not None, "")
    chk("без минта -- тоже причина словами",
        налог_маршрута(t_обычный, "", налог_фн)["why_not"] is not None, "")

    def налог_рвётся(минт):
        raise RuntimeError("узел молчит")

    р_сбой = налог_маршрута(t_обычный, "ОБЫЧНЫЙ", налог_рвётся)
    chk("узел не отдал налог -- сказано, и ноль не выдаётся за ответ",
        р_сбой["why_not"] and р_сбой["token_fee_bps"] is None, р_сбой)

    # --- МНОГО МИНТОВ: спрашиваем не больше предела и говорим об этом.
    много = [передача(f"М{и}") for и in range(12)] + [передача("ОБЫЧНЫЙ")]
    р_много = налог_маршрута(tx_маршрут(много), "ОБЫЧНЫЙ", налог_фн,
                              предел_минтов=4)
    chk("предел числа опрашиваемых минтов соблюдён и назван",
        р_много["mints_asked"] <= 5 and "при пределе" in (р_много["why_not"] or ""),
        (р_много["mints_asked"], р_много["why_not"]))

    # --- КЛЮЧИ ЗАПИСИ -- ASCII: их читают разборы и отчёты.
    ключи = set(налог_маршрута(t_pickaxe, "PICKAXE", налог_фн)) | set(ф)
    chk("ключи записи только ASCII",
        all(к.isascii() for к in ключи), [к for к in ключи if not к.isascii()])

    print(f"самопроверка налога маршрута: {всего[1]}/{всего[0]} пройдено")
