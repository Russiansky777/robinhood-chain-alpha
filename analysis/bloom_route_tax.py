#!/usr/bin/env python3
"""Налог Token-2022 ПО ВСЕМУ МАРШРУТУ, а не только у покупаемого токена.

Слово владельца 25.09: "Не покупать, если на маршруте есть промежуточный
токен с налогом или покупаемый токен передаётся больше одного раза (налог
маршрута больше налога токена). Пример -- PICKAXE 2Vs5qv9V...:
WSOL->USDC->GLDx->GP->PICKAXE, GP передан дважды (-5.9 %). Налоговый токен с
прямым пулом к SOL или USDC пока покупаем."

ПОЧЕМУ ЭТО ОТДЕЛЬНЫЙ МОДУЛЬ. Налог у минта детектор уже спрашивает -- один
getAccountInfo на минт. Но налог берётся НА КАЖДОЙ ПЕРЕДАЧЕ, а маршрут
агрегатора передаёт токены по нескольку раз и тащит через промежуточные
монеты, у которых свой налог. Разница между "налог токена 300 bps" и "налог
маршрута 900 bps" -- это разница между сделкой в плюс и сделкой в минус, и
считать её надо по передачам в транзакции, а не по одному числу у минта.

ЧЕЙ МАРШРУТ МЫ СЧИТАЕМ. До покупки нашего маршрута ещё нет: его выберет
Bloom. Поэтому фильтр считает маршрут ИСТОЧНИКА (по его транзакции) и честно
помечает это в записи: route_from="source". После нашей покупки тот же разбор
идёт по НАШЕЙ транзакции (route_from="ours") -- так видно, совпал ли маршрут
и не оказался ли наш налог другим. Выдавать одно за другое нельзя: на этом
строится решение о деньгах.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

# Котировочные монеты, на которых прямой пул считается приемлемым. Слово
# владельца: налоговый токен с прямым пулом к SOL или USDC пока покупаем.
WSOL = "So11111111111111111111111111111111111111112"
USDC = "EPjFWdd5AufqSSqeM2qN1xzybapC8G4wEGGkZwyTDt1v"
USDT = "Es9vMFrzaCERmJfrF4H2FYD4KCoNkY11McCe8BenwNYB"
КОТИРОВОЧНЫЕ_ПРЯМЫЕ = (WSOL, USDC)
КОТИРОВОЧНЫЕ_ВСЕ = (WSOL, USDC, USDT)

КОД_ПРОПУСКА = "SKIP_TAXED_ROUTE"

# Типы инструкций токен-программ, которые ПЕРЕДАЮТ токен. Именно на них
# берётся комиссия Token-2022, поэтому считаем их, а не изменения балансов:
# по балансам "туда и обратно" выглядит как ноль движения, а налог с обеих
# передач уже снят.
ТИПЫ_ПЕРЕДАЧ = ("transfer", "transferChecked", "transferCheckedWithFee")


def _карта_счетов(tx: dict) -> dict:
    """Счёт -> минт. Нужна для классических transfer: у них минта в info нет.

    Источник карты -- pre/postTokenBalances, где у каждого счёта есть и
    индекс, и минт, плюс accountKeys, где по индексу лежит адрес счёта.
    Ошибиться тут значит приписать передачу не тому минту и посчитать чужой
    налог своим.
    """
    ключи = (((tx or {}).get("transaction") or {}).get("message") or {}).get("accountKeys") or []
    адреса = []
    for к in ключи:
        адреса.append(к.get("pubkey") if isinstance(к, dict) else к)
    мета = (tx or {}).get("meta") or {}
    карта: dict = {}
    for где in ("preTokenBalances", "postTokenBalances"):
        for б in (мета.get(где) or []):
            if not isinstance(б, dict):
                continue
            и = б.get("accountIndex")
            минт = б.get("mint")
            if минт is None or not isinstance(и, int) or и >= len(адреса):
                continue
            адрес = адреса[и]
            if адрес:
                карта[адрес] = минт
    return карта


def _инструкции(tx: dict) -> list:
    """Все инструкции транзакции: верхнего уровня и вложенные."""
    из_: list = []
    сообщение = ((tx or {}).get("transaction") or {}).get("message") or {}
    из_.extend(сообщение.get("instructions") or [])
    for гр in ((tx or {}).get("meta") or {}).get("innerInstructions") or []:
        если = гр.get("instructions") if isinstance(гр, dict) else None
        из_.extend(если or [])
    return из_


def передачи_по_минтам(tx: dict) -> dict:
    """Сколько РАЗ каждый минт передавался в этой транзакции.

    Возвращает {"by_mint": {минт: сколько}, "unknown": сколько передач без
    минта, "total": всего передач}. Передача без опознанного минта -- это не
    ноль: она идёт в unknown, и потребитель обязан знать, что часть маршрута
    он не видит.
    """
    карта = _карта_счетов(tx)
    по_минтам: dict = {}
    неизвестных = 0
    всего = 0
    for и in _инструкции(tx):
        if not isinstance(и, dict):
            continue
        разбор = и.get("parsed")
        if not isinstance(разбор, dict):
            continue
        if разбор.get("type") not in ТИПЫ_ПЕРЕДАЧ:
            continue
        всего += 1
        инфо = разбор.get("info") or {}
        минт = инфо.get("mint")
        if not минт:
            # Классический transfer: минт берём по счёту-источнику, а если и
            # его нет в карте -- по счёту-получателю.
            минт = карта.get(инфо.get("source")) or карта.get(инфо.get("destination"))
        if not минт:
            неизвестных += 1
            continue
        по_минтам[минт] = по_минтам.get(минт, 0) + 1
    return {"by_mint": по_минтам, "unknown": неизвестных, "total": всего}


def налог_маршрута(tx: dict, минт: str, налог_фн, *, откуда: str = "source",
                    предел_минтов: int = 8) -> dict:
    """Налог по ВСЕМ передачам маршрута и отдельно налог самого токена.

    налог_фн(минт) -> {"taxed": bool, "fee_bps": int|None, ...} -- у детектора
    это Helius.налог_минта с кешом на процесс. Каждый новый минт стоит один
    getAccountInfo (1 кредит), поэтому число опрашиваемых минтов ограничено:
    маршрут из восьми монет -- это уже не маршрут, а повод не покупать.

    route_transfer_fee_bps -- СУММА bps по всем передачам (ставка минта
    умножается на число его передач). Это не проценты от входа один к одному,
    а верхняя оценка суммарного удержания; в записи так и названо.
    """
    из_ = {"route_from": откуда, "mint": минт, "token_fee_bps": None,
            "route_transfer_fee_bps": None, "transfers_of_token": None,
            "transfers_total": None, "transfers_unknown": None,
            "taxed_intermediates": [], "intermediate_mints": [],
            "quote_mints": [], "mints_asked": 0,
            # СКОЛЬКО МИНТОВ НЕ ОТВЕТИЛИ. С 28.09 налог на пути покупки
            # спрашивается ТОЛЬКО из кеша процесса (решение владельца: чтение
            # налога убрать с пути покупки, читать после отправки фоном). У
            # свежего минта кеш пуст, и "ставки нет" это не "ставка ноль":
            # сумма по известным минтам становится НИЖНЕЙ ОЦЕНКОЙ, и это
            # сказано полем, а не подразумевается.
            "mints_unknown": 0, "route_tax_lower_bound": False,
            "why_not": None}
    if not isinstance(tx, dict) or not tx:
        из_["why_not"] = "транзакции нет -- маршрут не разобрать"
        return из_
    if not минт:
        из_["why_not"] = "минт не задан"
        return из_
    п = передачи_по_минтам(tx)
    из_.update(transfers_total=п["total"], transfers_unknown=п["unknown"],
               transfers_of_token=p_token(п, минт))
    минты = list(п["by_mint"].keys())
    if len(минты) > предел_минтов:
        # Считаем всё равно, но честно помечаем, что спрашивали не всех.
        из_["why_not"] = (f"минтов на маршруте {len(минты)} при пределе "
                           f"{предел_минтов}: налог считан по первым {предел_минтов}")
        минты = минты[:предел_минтов]
    сумма = 0
    промежуточные = []
    for м in минты:
        сколько = п["by_mint"].get(м, 0)
        if м in КОТИРОВОЧНЫЕ_ВСЕ:
            из_["quote_mints"].append(м)
            continue
        if м != минт:
            промежуточные.append(м)
        try:
            н = налог_фн(м) or {}
        except Exception as exc:  # noqa: BLE001
            из_["why_not"] = f"налог минта {м[:10]} не прочитан ({type(exc).__name__})"
            continue
        из_["mints_asked"] += 1
        bps = н.get("fee_bps")
        if not isinstance(bps, int):
            # НЕ ПРОЧИТАН. Ноль передач и неизвестная ставка -- разные вещи;
            # вторая делает сумму нижней оценкой.
            из_["mints_unknown"] += 1
            из_["route_tax_lower_bound"] = True
            continue
        if bps <= 0:
            continue
        сумма += bps * сколько
        if м == минт:
            из_["token_fee_bps"] = bps
        else:
            из_["taxed_intermediates"].append({"mint": м, "fee_bps": bps,
                                                "transfers": сколько})
    из_["intermediate_mints"] = промежуточные
    из_["route_transfer_fee_bps"] = сумма
    # FREEZE AUTHORITY ПОКУПАЕМОГО ТОКЕНА -- В ЗАПИСЬ, НЕ В РЕШЕНИЕ. Ответ на
    # вопрос владельца 28.09 (п.4б): полоса его не проверяет. Число берётся из
    # того же кеша минтов, что и налог, -- ни одного лишнего вызова сети.
    try:
        н_ток = налог_фн(минт) or {}
    except Exception:  # noqa: BLE001
        н_ток = {}
    if "freeze_authority" in н_ток:
        из_["freeze_authority"] = н_ток.get("freeze_authority")
        из_["freeze_authority_revoked"] = н_ток.get("freeze_authority_revoked")
        из_["mint_authority"] = н_ток.get("mint_authority")
    if из_["token_fee_bps"] is None:
        # Налог самого токена спрашиваем даже если он в маршруте не нашёлся:
        # ноль передач у покупаемого токена сам по себе странность, но ставку
        # знать надо -- по ней работает исключение про прямой пул.
        try:
            н = налог_фн(минт) or {}
            из_["mints_asked"] += 1
            bps = н.get("fee_bps")
            if isinstance(bps, int):
                из_["token_fee_bps"] = bps
            else:
                # СТАВКА НЕ ПРОЧИТАНА -- ОСТАВЛЯЕМ None, А НЕ НОЛЬ. Прежде тут
                # стоял ноль, и "не знаем" было не отличить от "налога нет".
                из_["token_fee_bps"] = None
                из_["mints_unknown"] += 1
                из_["route_tax_lower_bound"] = True
        except Exception as exc:  # noqa: BLE001
            из_["why_not"] = (из_["why_not"] or
                               f"налог покупаемого минта не прочитан ({type(exc).__name__})")
    return из_


def p_token(п: dict, минт: str) -> int:
    """Сколько раз передавался ИМЕННО покупаемый токен."""
    return int((п.get("by_mint") or {}).get(минт, 0))


def прямизна_по_маршруту(разбор: dict) -> tuple:
    """Прямой ли маршрут ПО ПЕРЕДАЧАМ и в какой котировке.

    Прямой -- это когда покупаемый токен передан один раз и кроме него на
    маршруте только котировочные монеты. Считать прямизну по наличию пула
    токен/WSOL в транзакции источника недостаточно: пул может быть, а
    агрегатор всё равно повёл покупку через три монеты, и налог берётся по
    фактическим передачам, а не по тому, какой пул существует.
    """
    промежуточные = [м for м in (разбор.get("intermediate_mints") or [])
                      if м not in КОТИРОВОЧНЫЕ_ВСЕ]
    передач = разбор.get("transfers_of_token")
    котировки = разбор.get("quote_mints") or []
    котировка = (WSOL if WSOL in котировки
                  else USDC if USDC in котировки
                  else (котировки[0] if котировки else None))
    прямой = (not промежуточные and isinstance(передач, int) and передач <= 1)
    return прямой, котировка


def фильтр_маршрута(разбор: dict, *, прямой_пул: bool | None = None,
                     котировка: str | None = None,
                     порог_bps: int | None = None) -> dict:
    """Решение владельца в одной функции: покупаем или пропускаем.

    ПОРОГ ВМЕСТО ОТКАЗА (слово владельца 27.09, для полосы и группы bloom_lane:
    "правило налогового маршрута -- не отказывать, а писать налог в строку
    решения; порог по налогу -- поле группы, по умолчанию 600 bps"). Когда
    порог_bps передан числом, режущие правила ниже заменяются ОДНИМ сравнением:
    налог маршрута в bps против порога. Ниже порога покупка идёт, а налог
    назван числом в строке решения; выше -- пропуск с тем же кодом, и порог
    назван в причине.

    порог_bps=None оставляет поведение ровно как до 27.09: ни один уже
    работающий путь (покупки Bloom, группы без поля) от этого не меняется.
    Неизвестный налог порогом НЕ прощается: если налог маршрута не посчитан
    (None), решают старые правила -- "неизвестно" не равно "нуля нет".

    Правило (25.09):
      * налоговый ПРОМЕЖУТОЧНЫЙ токен на маршруте -- пропуск;
      * покупаемый токен передан больше одного раза -- пропуск (налог
        маршрута больше налога токена: ровно случай PICKAXE, -5.9 %);
      * налоговый токен с ПРЯМЫМ пулом к SOL или USDC -- покупаем.

    Сам налог токена покупку НЕ отменяет: отменяют её лишние передачи и
    налоговые промежуточные. Но флаг would_skip_fee ставится всегда, когда
    налог вообще есть: владелец просил видеть в журнале, что фильтр по налогу
    тут срабатывал бы.

    прямой_пул и котировка можно не передавать: тогда прямизна считается по
    самому маршруту (прямизна_по_маршруту). Передают их, когда есть внешнее
    подтверждение -- например, найденный в транзакции источника пул токен/WSOL.
    """
    из_ = {"skip": False, "code": None, "reason": None, "would_skip_fee": False,
            "route_tax_unknown": False,
            "route_tax_threshold_bps": (int(порог_bps) if isinstance(порог_bps, int)
                                         and порог_bps >= 0 else None),
            "route_transfer_fee_bps": разбор.get("route_transfer_fee_bps"),
            "token_fee_bps": разбор.get("token_fee_bps"),
            "transfers_of_token": разбор.get("transfers_of_token"),
            "route_direct": None, "route_quote": None}
    сам_прямой, сама_котировка = прямизна_по_маршруту(разбор)
    if прямой_пул is None:
        прямой_пул = сам_прямой
    if котировка is None:
        котировка = сама_котировка
    из_["route_direct"] = bool(сам_прямой)
    из_["route_quote"] = котировка
    налоговые = разбор.get("taxed_intermediates") or []
    передач = разбор.get("transfers_of_token")
    налог_токена = разбор.get("token_fee_bps")
    if isinstance(налог_токена, int) and налог_токена > 0:
        из_["would_skip_fee"] = True
    причины = []
    if налоговые:
        причины.append("налоговый промежуточный токен: "
                        + ", ".join(f"{з['mint'][:10]} {з['fee_bps']} bps"
                                     f" x{з['transfers']}" for з in налоговые))
    налог_маршрута_bps = разбор.get("route_transfer_fee_bps")

    # ПОРОГ. Одно сравнение вместо двух режущих правил -- и только когда порог
    # передан числом И налог маршрута посчитан. Налог маршрута это СУММА bps по
    # всем передачам (см. налог_маршрута), поэтому он покрывает оба прежних
    # случая: и налоговый промежуточный токен, и лишние передачи покупаемого.
    if (isinstance(порог_bps, int) and порог_bps >= 0
            and isinstance(налог_маршрута_bps, int)):
        из_["route_tax_reported"] = True
        подробно = ("налог маршрута {} bps при пороге {} bps"
                     .format(налог_маршрута_bps, порог_bps))
        if налоговые:
            подробно += ("; налоговые промежуточные: "
                          + ", ".join(f"{з['mint'][:10]} {з['fee_bps']} bps x{з['transfers']}"
                                       for з in налоговые))
        if isinstance(передач, int):
            подробно += f"; передач покупаемого {передач}"
        if налог_маршрута_bps > порог_bps:
            # ИЗВЕСТНОГО НАЛОГА УЖЕ ХВАТИЛО. Даже если часть минтов не
            # прочитана, сумма по ПРОЧИТАННЫМ выше порога -- это факт, а не
            # оценка, и покупка не идёт.
            из_.update(skip=True, code=КОД_ПРОПУСКА,
                       reason=подробно + " -- выше порога, покупки нет",
                       would_skip_fee=True)
            return из_
        # НАЛОГ НЕ ПРОЧИТАН -- ПОКУПАЕМ, НЕ ЖДЁМ (решение владельца 28.09:
        # "чтение налога минта с пути покупки убрать; если значение
        # используется -- не ждать ответа, считать с запасом"). На пути покупки
        # ставка берётся только из кеша процесса, у свежего минта его нет, и
        # ждать круга до узла означало бы те самые 22 мс перед отправкой.
        # Настоящую ставку читает фон сразу после отправки и пишет в запись;
        # если она окажется выше порога, владелец видит тревогу -- позиция к
        # тому времени уже открыта, и сторож продаст её по таймеру.
        if разбор.get("mints_unknown"):
            из_["route_tax_unknown"] = True
            из_["reason"] = (подробно + f"; не прочитано минтов "
                              f"{int(разбор['mints_unknown'])} -- покупаем не ожидая, "
                              "ставка читается после отправки")
            return из_
        из_["reason"] = подробно + " -- ниже порога, покупаем, налог в строке решения"
        if налог_маршрута_bps > 0:
            из_["would_skip_fee"] = True
        return из_

    # ЛИШНИЕ ПЕРЕДАЧИ РЕЖУТ ТОЛЬКО ТАМ, ГДЕ ЕСТЬ НАЛОГ. Правило владельца
    # названо им же и объяснено: "налог маршрута больше налога токена". У
    # токена без налога вторая передача не стоит ничего, и резать такую
    # покупку значило бы терять сделку без денежной причины. Поэтому условие
    # -- передач больше одной И налог маршрута положителен.
    if (isinstance(передач, int) and передач > 1
            and isinstance(налог_маршрута_bps, int) and налог_маршрута_bps > 0):
        причины.append(f"покупаемый токен передан {передач} раз(а): налог "
                        f"маршрута {налог_маршрута_bps} bps "
                        f"больше налога токена {разбор.get('token_fee_bps')} bps")
    if причины:
        из_.update(skip=True, code=КОД_ПРОПУСКА, reason="; ".join(причины),
                   would_skip_fee=True)
        return из_
    if (isinstance(налог_токена, int) and налог_токена > 0
            and сам_прямой and котировка in КОТИРОВОЧНЫЕ_ПРЯМЫЕ):
        # Исключение владельца названо в записи словами, чтобы по журналу
        # было видно: покупку пропустили сознательно, а не проглядели налог.
        из_["reason"] = (f"налоговый токен {налог_токена} bps с прямым пулом к "
                          f"{'SOL' if котировка == WSOL else 'USDC'}: покупаем по "
                          "слову владельца, налог помечен")
    elif isinstance(налог_токена, int) and налог_токена > 0:
        # Налог есть, прямизны нет, но и лишних передач нет: режущего правила
        # владельца тут нет, поэтому покупаем и говорим, чего не хватило.
        из_["reason"] = (f"налоговый токен {налог_токена} bps, прямого пула к "
                          f"SOL или USDC не видно (котировка {котировка}); "
                          "режущего правила нет -- покупаем с пометкой")
    return из_


# ------------------------------------------------------------------ самопроверка

def self_test() -> int:
    всего = [0, 0]

    def chk(имя, условие, факт=None):
        всего[0] += 1
        if условие:
            всего[1] += 1
            print(f"  [ok  ] {имя}")
        else:
            print(f"  [ПЛОХО] {имя}" + (f" -- {факт}" if факт is not None else ""))

    def бал(индекс, минт):
        return {"accountIndex": индекс, "mint": минт,
                "uiTokenAmount": {"amount": "1", "decimals": 6, "uiAmount": 1e-6}}

    def передача(минт=None, источник=None, получатель=None, тип="transferChecked"):
        инфо = {"authority": "КТО-ТО"}
        if минт:
            инфо["mint"] = минт
        if источник:
            инфо["source"] = источник
        if получатель:
            инфо["destination"] = получатель
        return {"programId": "TokenkegQfeZyiNwAJbNbGKPFXCWuBvf9Ss623VQ5DA",
                 "parsed": {"type": тип, "info": инфо}}

    def tx_маршрут(передачи, балансы=()):
        return {"transaction": {"message": {
                    "accountKeys": [{"pubkey": f"СЧЁТ{и}"} for и in range(12)],
                    "instructions": []}},
                 "meta": {"err": None,
                           "preTokenBalances": list(балансы),
                           "postTokenBalances": list(балансы),
                           "innerInstructions": [{"instructions": list(передачи)}]}}

    налоги = {"PICKAXE": 300, "GP": 300, "GLDx": 0, "ОБЫЧНЫЙ": 0,
               "НАЛОГОВЫЙ_ПРЯМОЙ": 250}

    def налог_фн(минт):
        return {"taxed": bool(налоги.get(минт)), "fee_bps": налоги.get(минт, 0)}

    # --- ПЕРЕДАЧИ СЧИТАЮТСЯ ПО ИНСТРУКЦИЯМ, а не по балансам: туда-и-обратно
    # по балансам выглядит нулём, а налог снят дважды.
    t1 = tx_маршрут([передача("GP"), передача("GP"), передача("PICKAXE")])
    п1 = передачи_по_минтам(t1)
    chk("передачи считаются по каждому минту",
        п1["by_mint"] == {"GP": 2, "PICKAXE": 1} and п1["total"] == 3, п1)

    # Классический transfer без минта: минт берётся по счёту из балансов.
    t2 = tx_маршрут([передача(источник="СЧЁТ3", получатель="СЧЁТ4", тип="transfer")],
                     балансы=[бал(3, "GP"), бал(4, "GP")])
    п2 = передачи_по_минтам(t2)
    chk("классический transfer опознаётся по счёту в балансах",
        п2["by_mint"] == {"GP": 1} and п2["unknown"] == 0, п2)

    t3 = tx_маршрут([передача(источник="НЕИЗВЕСТНЫЙ", тип="transfer")])
    chk("передача без опознанного минта идёт в unknown, а не в ноль",
        передачи_по_минтам(t3)["unknown"] == 1, передачи_по_минтам(t3))

    # --- СЛУЧАЙ ВЛАДЕЛЬЦА: PICKAXE через GLDx и GP, GP передан дважды.
    t_pickaxe = tx_маршрут([передача(WSOL), передача(USDC), передача("GLDx"),
                             передача("GP"), передача("GP"), передача("PICKAXE")])
    р = налог_маршрута(t_pickaxe, "PICKAXE", налог_фн)
    chk("налог маршрута PICKAXE считает и промежуточный GP дважды",
        р["route_transfer_fee_bps"] == 300 * 2 + 300 * 1, р)
    chk("налог самого токена отделён от налога маршрута",
        р["token_fee_bps"] == 300, р)
    chk("налоговый промежуточный назван по имени",
        [з["mint"] for з in р["taxed_intermediates"]] == ["GP"], р["taxed_intermediates"])
    chk("котировочные монеты в налог не идут",
        set(р["quote_mints"]) == {WSOL, USDC}, р["quote_mints"])
    ф = фильтр_маршрута(р, прямой_пул=False, котировка=None)
    chk("PICKAXE режется фильтром владельца",
        ф["skip"] is True and ф["code"] == КОД_ПРОПУСКА
        and "GP" in ф["reason"], ф)

    # --- НАЛОГОВЫЙ ТОКЕН С ПРЯМЫМ ПУЛОМ К SOL -- покупаем (слово владельца).
    t_прямой = tx_маршрут([передача(WSOL), передача("НАЛОГОВЫЙ_ПРЯМОЙ")])
    р2 = налог_маршрута(t_прямой, "НАЛОГОВЫЙ_ПРЯМОЙ", налог_фн)
    ф2 = фильтр_маршрута(р2, прямой_пул=True, котировка=WSOL)
    chk("налоговый токен с прямым пулом к SOL проходит, но помечен",
        ф2["skip"] is False and ф2["would_skip_fee"] is True
        and "покупаем по слову владельца" in (ф2["reason"] or ""), (р2, ф2))
    chk("и его налог всё равно посчитан",
        р2["route_transfer_fee_bps"] == 250 and р2["token_fee_bps"] == 250, р2)

    # Тот же токен, но передан дважды: это уже маршрут, а не прямой пул.
    t_дважды = tx_маршрут([передача(WSOL), передача("НАЛОГОВЫЙ_ПРЯМОЙ"),
                            передача("НАЛОГОВЫЙ_ПРЯМОЙ")])
    р3 = налог_маршрута(t_дважды, "НАЛОГОВЫЙ_ПРЯМОЙ", налог_фн)
    ф3 = фильтр_маршрута(р3, прямой_пул=True, котировка=WSOL)
    chk("две передачи налогового токена режутся даже при прямом пуле к SOL",
        ф3["skip"] is True and ф3["would_skip_fee"] is True
        and "передан 2" in (ф3["reason"] or ""), (р3, ф3))
    t_трижды = tx_маршрут([передача(WSOL), передача("НАЛОГОВЫЙ_ПРЯМОЙ"),
                            передача("НАЛОГОВЫЙ_ПРЯМОЙ"),
                            передача("НАЛОГОВЫЙ_ПРЯМОЙ")])
    ф4 = фильтр_маршрута(налог_маршрута(t_трижды, "НАЛОГОВЫЙ_ПРЯМОЙ", налог_фн),
                          прямой_пул=True, котировка=WSOL)
    chk("три передачи -- уже не прямой пул, режем",
        ф4["skip"] is True, ф4)

    # --- ОБЫЧНЫЙ ТОКЕН БЕЗ НАЛОГА: ничего не режется.
    t_обычный = tx_маршрут([передача(WSOL), передача("ОБЫЧНЫЙ")])
    ро = налог_маршрута(t_обычный, "ОБЫЧНЫЙ", налог_фн)
    фо = фильтр_маршрута(ро, прямой_пул=True, котировка=WSOL)
    chk("обычный токен не режется и налог у него ноль",
        фо["skip"] is False and ро["route_transfer_fee_bps"] == 0
        and ро["token_fee_bps"] == 0, (ро, фо))

    # Обычный токен, но переданный дважды: правило владельца про число
    # передач работает и без налога? Налог маршрута тогда ноль, и резать
    # нечего -- пропускаем, но помечаем.
    t_об_дважды = tx_маршрут([передача(WSOL), передача("ОБЫЧНЫЙ"),
                               передача("ОБЫЧНЫЙ")])
    р_об = налог_маршрута(t_об_дважды, "ОБЫЧНЫЙ", налог_фн)
    ф_об = фильтр_маршрута(р_об, прямой_пул=True, котировка=WSOL)
    chk("у обычного токена две передачи налога не создают",
        р_об["route_transfer_fee_bps"] == 0, р_об)
    chk("и решение по нему -- покупать: без налога вторая передача не стоит ничего",
        ф_об["skip"] is False and ф_об["would_skip_fee"] is False, ф_об)

    # --- КОТИРОВКА НЕ SOL И НЕ USDC: исключение не применяется.
    t_чужая = tx_маршрут([передача(USDT), передача("НАЛОГОВЫЙ_ПРЯМОЙ"),
                           передача("НАЛОГОВЫЙ_ПРЯМОЙ")])
    ф_ч = фильтр_маршрута(налог_маршрута(t_чужая, "НАЛОГОВЫЙ_ПРЯМОЙ", налог_фн),
                           прямой_пул=True, котировка=USDT)
    chk("прямой пул к USDT исключением не считается -- режем",
        ф_ч["skip"] is True, ф_ч)

    # --- ПОРОГ ВМЕСТО ОТКАЗА (слово владельца 27.09). Это денежный путь:
    # порог решает, уходит ли покупка, поэтому проверяется и то, что он
    # пропускает, и то, что он режет, и то, что БЕЗ порога ничего не поменялось.
    р_pick = налог_маршрута(t_pickaxe, "PICKAXE", налог_фн)
    chk("без порога поведение прежнее: PICKAXE режется",
        фильтр_маршрута(р_pick, прямой_пул=False, котировка=None)["skip"] is True,
        фильтр_маршрута(р_pick))
    ф_п_низкий = фильтр_маршрута(р_pick, прямой_пул=False, котировка=None,
                                  порог_bps=600)
    chk("налог 900 bps выше порога 600 -- режем, и порог назван в причине",
        ф_п_низкий["skip"] is True
        and ф_п_низкий["code"] == КОД_ПРОПУСКА
        and "600" in (ф_п_низкий["reason"] or "")
        and "900" in (ф_п_низкий["reason"] or ""), ф_п_низкий)
    ф_п_высокий = фильтр_маршрута(р_pick, прямой_пул=False, котировка=None,
                                   порог_bps=1000)
    chk("тот же налог 900 bps ниже порога 1000 -- покупаем, налог в строке решения",
        ф_п_высокий["skip"] is False
        and ф_п_высокий["route_tax_reported"] is True
        and ф_п_высокий["route_tax_threshold_bps"] == 1000
        and "900" in (ф_п_высокий["reason"] or ""), ф_п_высокий)
    chk("и пометка налога при этом не теряется",
        ф_п_высокий["would_skip_fee"] is True, ф_п_высокий)
    # Ровно на пороге -- покупаем: порог это предел допустимого, а не запрет.
    ф_ровно = фильтр_маршрута(р_pick, прямой_пул=False, котировка=None,
                               порог_bps=900)
    chk("налог ровно на пороге -- покупаем",
        ф_ровно["skip"] is False, ф_ровно)
    # Порог 0 у налогового маршрута режет, у обычного -- нет.
    chk("порог 0 режет любой налог маршрута",
        фильтр_маршрута(р_pick, порог_bps=0)["skip"] is True, "")
    chk("порог 0 не режет маршрут без налога",
        фильтр_маршрута(ро, прямой_пул=True, котировка=WSOL,
                         порог_bps=0)["skip"] is False, ро)
    # НЕИЗВЕСТНЫЙ НАЛОГ ПОРОГОМ НЕ ПРОЩАЕТСЯ: решают старые правила.
    р_неизв = dict(р_pick)
    р_неизв["route_transfer_fee_bps"] = None
    ф_неизв = фильтр_маршрута(р_неизв, прямой_пул=False, котировка=None,
                               порог_bps=10_000)
    chk("налог не посчитан -- порог не прощает, решают старые правила",
        ф_неизв["skip"] is True and ф_неизв.get("route_tax_reported") is None,
        ф_неизв)
    # Нецелой или отрицательной строкой порог не задать.
    chk("порог не целым числом -- как будто порога нет",
        фильтр_маршрута(р_pick, порог_bps="600")["skip"] is True, "")
    chk("отрицательный порог -- как будто порога нет",
        фильтр_маршрута(р_pick, порог_bps=-1)["skip"] is True, "")

    # --- УСТОЙЧИВОСТЬ: пустая транзакция, нет минта, налог не читается.
    chk("пустая транзакция -- причина словами, а не падение",
        налог_маршрута({}, "М", налог_фн)["why_not"] is not None, "")
    chk("без минта -- тоже причина словами",
        налог_маршрута(t_обычный, "", налог_фн)["why_not"] is not None, "")

    def налог_рвётся(минт):
        raise RuntimeError("узел молчит")

    р_сбой = налог_маршрута(t_обычный, "ОБЫЧНЫЙ", налог_рвётся)
    chk("узел не отдал налог -- сказано, и ноль не выдаётся за ответ",
        р_сбой["why_not"] and р_сбой["token_fee_bps"] is None, р_сбой)

    # --- МНОГО МИНТОВ: спрашиваем не больше предела и говорим об этом.
    много = [передача(f"М{и}") for и in range(12)] + [передача("ОБЫЧНЫЙ")]
    р_много = налог_маршрута(tx_маршрут(много), "ОБЫЧНЫЙ", налог_фн,
                              предел_минтов=4)
    chk("предел числа опрашиваемых минтов соблюдён и назван",
        р_много["mints_asked"] <= 5 and "при пределе" in (р_много["why_not"] or ""),
        (р_много["mints_asked"], р_много["why_not"]))

    # --- НАЛОГ НЕ ПРОЧИТАН: ПОКУПАЕМ, НЕ ЖДЁМ, И ЭТО ВИДНО В ЗАПИСИ.
    # Решение владельца 28.09: чтение налога минта убрать с пути покупки. На
    # пути остаётся только кеш процесса, и у свежего минта он пуст.
    def кеш_пуст(м):  # noqa: ARG001
        return {"mint": м, "taxed": None, "fee_bps": None}

    р_нз = налог_маршрута(tx_маршрут([передача("ОБЫЧНЫЙ")]), "ОБЫЧНЫЙ", кеш_пуст)
    chk(f"не прочитанный налог -- не ноль, а None (ставка {р_нз['token_fee_bps']!r}, "
        f"не прочитано {р_нз['mints_unknown']})",
        р_нз["token_fee_bps"] is None and р_нз["mints_unknown"] >= 1
        and р_нз["route_tax_lower_bound"] is True, р_нз)
    ф_нз = фильтр_маршрута(р_нз, порог_bps=600)
    chk(f"и покупка НЕ отменяется: skip={ф_нз['skip']}, "
        f"неизвестно={ф_нз.get('route_tax_unknown')}",
        ф_нз["skip"] is False and ф_нз.get("route_tax_unknown") is True, ф_нз)
    # А вот известный налог выше порога режет по-прежнему -- даже если другие
    # минты маршрута не прочитаны.
    def кеш_злой(м):
        return ({"mint": м, "taxed": True, "fee_bps": 900} if м == "ОБЫЧНЫЙ"
                else {"mint": м, "taxed": None, "fee_bps": None})

    р_зл = налог_маршрута(tx_маршрут([передача("ОБЫЧНЫЙ"), передача("ДРУГОЙ")]),
                           "ОБЫЧНЫЙ", кеш_злой)
    ф_зл = фильтр_маршрута(р_зл, порог_bps=600)
    chk(f"известного налога {р_зл['route_transfer_fee_bps']} bps хватило: "
        f"skip={ф_зл['skip']}", ф_зл["skip"] is True, (р_зл, ф_зл))

    # --- FREEZE AUTHORITY: В ЗАПИСЬ ПОПАДАЕТ, НА РЕШЕНИЕ НЕ ВЛИЯЕТ.
    # Владелец 28.09 (п.4б) спросил, проверяет ли полоса freeze authority.
    # Не проверяет: поле идёт в запись и выгрузку, фильтр его не смотрит.
    def налог_с_заморозкой(м):
        из_ = dict(налог_фн(м) or {})
        из_.update(freeze_authority=("ЗАМОРОЗЧИК" if м == "ОБЫЧНЫЙ" else None),
                    freeze_authority_revoked=(м != "ОБЫЧНЫЙ"),
                    mint_authority=None)
        return из_

    р_зам = налог_маршрута(tx_маршрут([передача("ОБЫЧНЫЙ")]), "ОБЫЧНЫЙ",
                            налог_с_заморозкой)
    chk(f"freeze authority попал в запись ({р_зам.get('freeze_authority')!r}, "
        f"отозван {р_зам.get('freeze_authority_revoked')})",
        р_зам.get("freeze_authority") == "ЗАМОРОЗЧИК"
        and р_зам.get("freeze_authority_revoked") is False, р_зам)
    chk("и фильтр маршрута от него не изменился: решение только по налогу",
        фильтр_маршрута(р_зам) == фильтр_маршрута(
            налог_маршрута(tx_маршрут([передача("ОБЫЧНЫЙ")]), "ОБЫЧНЫЙ", налог_фн)),
        (фильтр_маршрута(р_зам),))
    chk("без поля в кеше минтов запись его и не придумывает",
        "freeze_authority" not in налог_маршрута(
            tx_маршрут([передача("ОБЫЧНЫЙ")]), "ОБЫЧНЫЙ", налог_фн))

    # --- КЛЮЧИ ЗАПИСИ -- ASCII: их читают разборы и отчёты.
    ключи = set(налог_маршрута(t_pickaxe, "PICKAXE", налог_фн)) | set(ф)
    chk("ключи записи только ASCII",
        all(к.isascii() for к in ключи), [к for к in ключи if not к.isascii()])

    print(f"самопроверка налога маршрута: {всего[1]}/{всего[0]} пройдено")
    return 0 if всего[1] == всего[0] else 1


