#!/usr/bin/env python3
"""Налог Token-2022 ПО ВСЕМУ МАРШРУТУ, а не только у покупаемого токена.

Слово владельца 25.09: "Не покупать, если на маршруте есть промежуточный
токен с налогом или покупаемый токен передаётся больше одного раза (налог
маршрута больше налога токена). Пример -- PICKAXE 2Vs5qv9V...:
WSOL->USDC->GLDx->GP->PICKAXE, GP передан дважды (-5.9 %). Налоговый токен с
прямым пулом к SOL или USDC пока покупаем."

ПОЧЕМУ ЭТО ОТДЕЛЬНЫЙ МОДУЛЬ. Налог у минта детектор уже спрашивает -- один
getAccountInfo на минт. Но налог берётся НА КАЖДОЙ ПЕРЕДАЧЕ, а маршрут
агрегатора передаёт токены по нескольку раз и тащит через промежуточные
монеты, у которых свой налог. Разница между "налог токена 300 bps" и "налог
маршрута 900 bps" -- это разница между сделкой в плюс и сделкой в минус, и
считать её надо по передачам в транзакции, а не по одному числу у минта.

ЧЕЙ МАРШРУТ МЫ СЧИТАЕМ. До покупки нашего маршрута ещё нет: его выберет
Bloom. Поэтому фильтр считает маршрут ИСТОЧНИКА (по его транзакции) и честно
помечает это в записи: route_from="source". После нашей покупки тот же разбор
идёт по НАШЕЙ транзакции (route_from="ours") -- так видно, совпал ли маршрут
и не оказался ли наш налог другим. Выдавать одно за другое нельзя: на этом
строится решение о деньгах.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

# Котировочные монеты, на которых прямой пул считается приемлемым. Слово
# владельца: налоговый токен с прямым пулом к SOL или USDC пока покупаем.
WSOL = "So11111111111111111111111111111111111111112"
USDC = "EPjFWdd5AufqSSqeM2qN1xzybapC8G4wEGGkZwyTDt1v"
USDT = "Es9vMFrzaCERmJfrF4H2FYD4KCoNkY11McCe8BenwNYB"
КОТИРОВОЧНЫЕ_ПРЯМЫЕ = (WSOL, USDC)
КОТИРОВОЧНЫЕ_ВСЕ = (WSOL, USDC, USDT)

КОД_ПРОПУСКА = "SKIP_TAXED_ROUTE"

# Типы инструкций токен-программ, которые ПЕРЕДАЮТ токен. Именно на них
# берётся комиссия Token-2022, поэтому считаем их, а не изменения балансов:
# по балансам "туда и обратно" выглядит как ноль движения, а налог с обеих
# передач уже снят.
ТИПЫ_ПЕРЕДАЧ = ("transfer", "transferChecked", "transferCheckedWithFee")


def _карта_счетов(tx: dict) -> dict:
    """Счёт -> минт. Нужна для классических transfer: у них минта в info нет.

    Источник карты -- pre/postTokenBalances, где у каждого счёта есть и
    индекс, и минт, плюс accountKeys, где по индексу лежит адрес счёта.
    Ошибиться тут значит приписать передачу не тому минту и посчитать чужой
    налог своим.
    """
    ключи = (((tx or {}).get("transaction") or {}).get("message") or {}).get("accountKeys") or []
    адреса = []
    for к in ключи:
        адреса.append(к.get("pubkey") if isinstance(к, dict) else к)
    мета = (tx or {}).get("meta") or {}
    карта: dict = {}
    for где in ("preTokenBalances", "postTokenBalances"):
        for б in (мета.get(где) or []):
            if not isinstance(б, dict):
                continue
            и = б.get("accountIndex")
            минт = б.get("mint")
            if минт is None or not isinstance(и, int) or и >= len(адреса):
                continue
            адрес = адреса[и]
            if адрес:
                карта[адрес] = минт
    return карта


def _инструкции(tx: dict) -> list:
    """Все инструкции транзакции: верхнего уровня и вложенные."""
    из_: list = []
    сообщение = ((tx or {}).get("transaction") or {}).get("message") or {}
    из_.extend(сообщение.get("instructions") or [])
    for гр in ((tx or {}).get("meta") or {}).get("innerInstructions") or []:
        если = гр.get("instructions") if isinstance(гр, dict) else None
        из_.extend(если or [])
    return из_


def передачи_по_минтам(tx: dict) -> dict:
    """Сколько РАЗ каждый минт передавался в этой транзакции.

    Возвращает {"by_mint": {минт: сколько}, "unknown": сколько передач без
    минта, "total": всего передач}. Передача без опознанного минта -- это не
    ноль: она идёт в unknown, и потребитель обязан знать, что часть маршрута
    он не видит.
    """
    карта = _карта_счетов(tx)
    по_минтам: dict = {}
    неизвестных = 0
    всего = 0
    for и in _инструкции(tx):
        if not isinstance(и, dict):
            continue
        разбор = и.get("parsed")
        if not isinstance(разбор, dict):
            continue
        if разбор.get("type") not in ТИПЫ_ПЕРЕДАЧ:
            continue
        всего += 1
        инфо = разбор.get("info") or {}
        минт = инфо.get("mint")
        if not минт:
            # Классический transfer: минт берём по счёту-источнику, а если и
            # его нет в карте -- по счёту-получателю.
            минт = карта.get(инфо.get("source")) or карта.get(инфо.get("destination"))
        if not минт:
            неизвестных += 1
            continue
        по_минтам[минт] = по_минтам.get(минт, 0) + 1
    return {"by_mint": по_минтам, "unknown": неизвестных, "total": всего}


def налог_маршрута(tx: dict, минт: str, налог_фн, *, откуда: str = "source",
                    предел_минтов: int = 8) -> dict:
    """Налог по ВСЕМ передачам маршрута и отдельно налог самого токена.

    налог_фн(минт) -> {"taxed": bool, "fee_bps": int|None, ...} -- у детектора
    это Helius.налог_минта с кешом на процесс. Каждый новый минт стоит один
    getAccountInfo (1 кредит), поэтому число опрашиваемых минтов ограничено:
    маршрут из восьми монет -- это уже не маршрут, а повод не покупать.

    route_transfer_fee_bps -- СУММА bps по всем передачам (ставка минта
    умножается на число его передач). Это не проценты от входа один к одному,
    а верхняя оценка суммарного удержания; в записи так и названо.
    """
    из_ = {"route_from": откуда, "mint": минт, "token_fee_bps": None,
            "route_transfer_fee_bps": None, "transfers_of_token": None,
            "transfers_total": None, "transfers_unknown": None,
            "taxed_intermediates": [], "intermediate_mints": [],
            "quote_mints": [], "mints_asked": 0, "why_not": None}
    if not isinstance(tx, dict) or not tx:
        из_["why_not"] = "транзакции нет -- маршрут не разобрать"
        return из_
    if not минт:
        из_["why_not"] = "минт не задан"
        return из_
    п = передачи_по_минтам(tx)
    из_.update(transfers_total=п["total"], transfers_unknown=п["unknown"],
               transfers_of_token=p_token(п, минт))
    минты = list(п["by_mint"].keys())
    if len(минты) > предел_минтов:
        # Считаем всё равно, но честно помечаем, что спрашивали не всех.
        из_["why_not"] = (f"минтов на маршруте {len(минты)} при пределе "
                           f"{предел_минтов}: налог считан по первым {предел_минтов}")
        минты = минты[:предел_минтов]
    сумма = 0
    промежуточные = []
    for м in минты:
        сколько = п["by_mint"].get(м, 0)
        if м in КОТИРОВОЧНЫЕ_ВСЕ:
            из_["quote_mints"].append(м)
            continue
        if м != минт:
            промежуточные.append(м)
        try:
            н = налог_фн(м) or {}
        except Exception as exc:  # noqa: BLE001
            из_["why_not"] = f"налог минта {м[:10]} не прочитан ({type(exc).__name__})"
            continue
        из_["mints_asked"] += 1
        bps = н.get("fee_bps")
        if not isinstance(bps, int) or bps <= 0:
            continue
        сумма += bps * сколько
        if м == минт:
            из_["token_fee_bps"] = bps
        else:
            из_["taxed_intermediates"].append({"mint": м, "fee_bps": bps,
                                                "transfers": сколько})
    из_["intermediate_mints"] = промежуточные
    из_["route_transfer_fee_bps"] = сумма
    if из_["token_fee_bps"] is None:
        # Налог самого токена спрашиваем даже если он в маршруте не нашёлся:
        # ноль передач у покупаемого токена сам по себе странность, но ставку
        # знать надо -- по ней работает исключение про прямой пул.
        try:
            н = налог_фн(минт) or {}
            из_["mints_asked"] += 1
            bps = н.get("fee_bps")
            из_["token_fee_bps"] = bps if isinstance(bps, int) else 0
        except Exception as exc:  # noqa: BLE001
            из_["why_not"] = (из_["why_not"] or
                               f"налог покупаемого минта не прочитан ({type(exc).__name__})")
    return из_


def p_token(п: dict, минт: str) -> int:
    """Сколько раз передавался ИМЕННО покупаемый токен."""
    return int((п.get("by_mint") or {}).get(минт, 0))


def прямизна_по_маршруту(разбор: dict) -> tuple:
    """Прямой ли маршрут ПО ПЕРЕДАЧАМ и в какой котировке.

    Прямой -- это когда покупаемый токен передан один раз и кроме него на
    маршруте только котировочные монеты. Считать прямизну по наличию пула
    токен/WSOL в транзакции источника недостаточно: пул может быть, а
    агрегатор всё равно повёл покупку через три монеты, и налог берётся по
    фактическим передачам, а не по тому, какой пул существует.
    """
    промежуточные = [м for м in (разбор.get("intermediate_mints") or [])
                      if м not in КОТИРОВОЧНЫЕ_ВСЕ]
    передач = разбор.get("transfers_of_token")
    котировки = разбор.get("quote_mints") or []
    котировка = (WSOL if WSOL in котировки
                  else USDC if USDC in котировки
                  else (котировки[0] if котировки else None))
    прямой = (not промежуточные and isinstance(передач, int) and передач <= 1)
    return прямой, котировка


def фильтр_маршрута(разбор: dict, *, прямой_пул: bool | None = None,
                     котировка: str | None = None) -> dict:
    """Решение владельца в одной функции: покупаем или пропускаем.

    Правило (25.09):
      * налоговый ПРОМЕЖУТОЧНЫЙ токен на маршруте -- пропуск;
      * покупаемый токен передан больше одного раза -- пропуск (налог
        маршрута больше налога токена: ровно случай PICKAXE, -5.9 %);
      * налоговый токен с ПРЯМЫМ пулом к SOL или USDC -- покупаем.

    Сам налог токена покупку НЕ отменяет: отменяют её лишние передачи и
    налоговые промежуточные. Но флаг would_skip_fee ставится всегда, когда
    налог вообще есть: владелец просил видеть в журнале, что фильтр по налогу
    тут срабатывал бы.

    прямой_пул и котировка можно не передавать: тогда прямизна считается по
    самому маршруту (прямизна_по_маршруту). Передают их, когда есть внешнее
    подтверждение -- например, найденный в транзакции источника пул токен/WSOL.
    """
    из_ = {"skip": False, "code": None, "reason": None, "would_skip_fee": False,
            "route_transfer_fee_bps": разбор.get("route_transfer_fee_bps"),
            "token_fee_bps": разбор.get("token_fee_bps"),
            "transfers_of_token": разбор.get("transfers_of_token"),
            "route_direct": None, "route_quote": None}
    сам_прямой, сама_котировка = прямизна_по_маршруту(разбор)
    if прямой_пул is None:
        прямой_пул = сам_прямой
    if котировка is None:
        котировка = сама_котировка
    из_["route_direct"] = bool(сам_прямой)
    из_["route_quote"] = котировка
    налоговые = разбор.get("taxed_intermediates") or []
    передач = разбор.get("transfers_of_token")
    налог_токена = разбор.get("token_fee_bps")
    if isinstance(налог_токена, int) and налог_токена > 0:
        из_["would_skip_fee"] = True
    причины = []
    if налоговые:
        причины.append("налоговый промежуточный токен: "
                        + ", ".join(f"{з['mint'][:10]} {з['fee_bps']} bps"
                                     f" x{з['transfers']}" for з in налоговые))
    налог_маршрута_bps = разбор.get("route_transfer_fee_bps")
    # ЛИШНИЕ ПЕРЕДАЧИ РЕЖУТ ТОЛЬКО ТАМ, ГДЕ ЕСТЬ НАЛОГ. Правило владельца
    # названо им же и объяснено: "налог маршрута больше налога токена". У
    # токена без налога вторая передача не стоит ничего, и резать такую
    # покупку значило бы терять сделку без денежной причины. Поэтому условие
    # -- передач больше одной И налог маршрута положителен.
    if (isinstance(передач, int) and передач > 1
            and isinstance(налог_маршрута_bps, int) and налог_маршрута_bps > 0):
        причины.append(f"покупаемый токен передан {передач} раз(а): налог "
                        f"маршрута {налог_маршрута_bps} bps "
                        f"больше налога токена {разбор.get('token_fee_bps')} bps")
    if причины:
        из_.update(skip=True, code=КОД_ПРОПУСКА, reason="; ".join(причины),
                   would_skip_fee=True)
        return из_
    if (isinstance(налог_токена, int) and налог_токена > 0
            and сам_прямой and котировка in КОТИРОВОЧНЫЕ_ПРЯМЫЕ):
        # Исключение владельца названо в записи словами, чтобы по журналу
        # было видно: покупку пропустили сознательно, а не проглядели налог.
        из_["reason"] = (f"налоговый токен {налог_токена} bps с прямым пулом к "
                          f"{'SOL' if котировка == WSOL else 'USDC'}: покупаем по "
                          "слову владельца, налог помечен")
    elif isinstance(налог_токена, int) and налог_токена > 0:
        # Налог есть, прямизны нет, но и лишних передач нет: режущего правила
        # владельца тут нет, поэтому покупаем и говорим, чего не хватило.
        из_["reason"] = (f"налоговый токен {налог_токена} bps, прямого пула к "
                          f"SOL или USDC не видно (котировка {котировка}); "
                          "режущего правила нет -- покупаем с пометкой")
    return из_


