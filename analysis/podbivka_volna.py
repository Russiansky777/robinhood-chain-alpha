#!/usr/bin/env python3
"""Гипотеза «вход S+0 -> выход в волну покупок за нами» (задача владельца 08.10).

Мысль владельца: единственный замеренный перевес полосы -- посадка в блок источника
(S+0, 37 % посадок, медиана на живых деньгах -0.39 п.п. против -1.69 п.п. у S+1). За нами
идут быстрые копировщики (слоты), затем ручная толпа и слабые боты (секунды) -- они и
поднимают цену после нас. Раньше полоса держала до продажи источника и отдавала этот
подъём обратно. Проверяем: вход в S+0 и выход В ВОЛНУ, а источник выбирается по размеру
толпы за ним, а не по его собственному доходу.

ЧТО СЧИТАЕТСЯ ПО СОБРАННЫМ ДАННЫМ, А ЧТО НЕТ. В суточных файлах архива на каждый сигнал
лежат состояния пула на входах (S0, S0_дно, S1, S2) и на десяти горизонтах выхода
(6/12/24/30/36/60/72/108/150/300 слотов) плюс события «пик» и «чужая продажа». Отсюда:
  * путь цены -- 14 точек от входа до +300 слотов; секунды на слот берутся из
    `секунд_до` самого сигнала (медиана по окну, если у сигнала их нет);
  * размер толпы -- числом событий пула: свопы в следующих слотах (`свопов` s1, s2),
    события до 30 слотов, события в окне 160 слотов, слоты и высота до пика.
НЕЛЬЗЯ без нового прохода: разные кошельки-покупатели и ОБЪЁМ покупок по окнам
5/15/30/60/120/300 с, слоты S+1..S+5 по отдельности и горизонты дальше 300 слотов
(~78 с). Это сказано в странице прямым текстом, а не обойдено молчанием.

ПРАВИЛА ВЫХОДА. Торгуемые -- только те, что видны в момент решения: фиксированный
горизонт из сетки и «цель +x %, иначе по времени», причём при достижении цели продажа
кладётся на СЛЕДУЮЩИЙ сохранённый горизонт (пока увидим посадку и пошлём продажу).
Выход «в пик» не торгуемый -- пик виден только потом; он считается как потолок.

Вход -- только S+0 (место S0_дно по калибровке); не попали в блок -- сделки нет и цена
ноль. Ожидание SOL в сутки множится на долю попадания в блок из живых сделок.

Выход: docs/podbivka_volna.md, data/podbivka/volna.json. Только чтение.
"""
