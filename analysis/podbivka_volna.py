    for a, ч in по_ист_волна.items():
        if len(ч) < N_МИН_ИСТОЧНИК:
            continue
        по_суткам = collections.defaultdict(list)
        for x in ч:
            по_суткам[x["сутки"]].append(x["свопов_2_слота"] or 0)
        мед_по_суткам = [statistics.median(v) for v in по_суткам.values() if v]
        итог["волна_по_источникам"][a] = {
            "n": len(ч),
            "свопов_2_слота": стат([x["свопов_2_слота"] for x in ч]),
            "событий_до_30": стат([x["событий_до_30"] for x in ч]),
            "вверх_пп": стат([x["вверх_пп"] for x in ч]),
            "пик_слотов": стат([x["пик_слотов"] for x in ч]),
            "толпа_стабильна": {"суток": len(мед_по_суткам),
                                "медиана_медиан": round(statistics.median(мед_по_суткам), 2)
                                if мед_по_суткам else None,
                                "разброс_медиан": round(statistics.pstdev(мед_по_суткам), 2)
                                if len(мед_по_суткам) > 1 else None}}

    # ---- п.2 и п.4: правило выхода подбирается на подборе, проверяется вне подбора
    def глубина(ч: list, б: float) -> bool:
        рез = [x["резерв"] for x in ч if x.get("резерв")]
        if not рез:
            return False
        return (sum(1 for r in рез if б <= ДОЛЯ_РЕЗЕРВА * r) / len(рез)) >= ДОЛЯ_ГЛУБИНЫ

    def оценить(ч: list, б: float, поле: str, p=None) -> dict:
        подб = свод([x for x in ч if x["сутки"] in подбор], поле, б, доля)
        пров = свод([x for x in ч if x["сутки"] in проверка], поле, б, доля)
        пол = (свод([x for x in ч if x["сутки"] in пол1], поле, б, доля),
               свод([x for x in ч if x["сутки"] in пол2], поле, б, доля))
        да, нет = порог(пров, пол, p, глубина(ч, б), подб)
        return {"подбор": подб, "проверка": пров, "половина_1": пол[0], "половина_2": пол[1],
                "p_случайности": p, "проходит": да, "почему_нет": нет,
                "глубина_ок": глубина(ч, б)}

    def перестановки_фильтра(все_ч: list, в_фильтре_ч: list, поле: str, б: float,
                             повторов: int, seed: int = 20261008) -> float | None:
        """Нуль для фильтра: случайная выборка того же размера из тех же суток.

        Метка «попал в фильтр» перемешивается внутри каждых суток проверки, число
        отобранных сигналов по суткам сохраняется. p -- доля повторов, где случайный
        отбор дал итог не хуже настоящего.
        """
        import random as _r  # noqa: PLC0415
        по_д: dict = collections.defaultdict(list)
        для_д: dict = collections.Counter()
        for x in все_ч:
            if x["сутки"] in проверка and поле in x["правила"]:
                по_д[x["сутки"]].append(x["правила"][поле])
        for x in в_фильтре_ч:
            if x["сутки"] in проверка and поле in x["правила"]:
                для_д[x["сутки"]] += 1
        настоящий = sum(x["правила"][поле] for x in в_фильтре_ч
                        if x["сутки"] in проверка and поле in x["правила"])
        if not по_д or not для_д:
            return None
        рнд = _r.Random(seed)
        не_хуже = 0
        for _ in range(повторов):
            s_ = 0.0
            for д, все_v in по_д.items():
                k = для_д.get(д, 0)
                if k:
                    s_ += sum(рнд.sample(все_v, min(k, len(все_v))))
            if s_ >= настоящий:
                не_хуже += 1
        return round((не_хуже + 1) / (повторов + 1), 4)

    # перестановки: метки источников внутри суток проверки, по лучшему правилу подбора
