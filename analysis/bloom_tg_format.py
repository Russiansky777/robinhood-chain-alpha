#!/usr/bin/env python3
"""Формат строк Telegram по пакету владельца (26.09, ночь).

Три вида сообщений и ничего больше:
  * BUY -- одно сообщение при покупке, дописывается правкой, когда добрались
    данные по цепи;
  * SELL -- одно сообщение вместо "продана" и "полного круга";
  * сводка раз в час вместо круга.
Плюс тревоги (они остаются как есть в bloom_notify).

ЧТО ЗДЕСЬ ТОЛЬКО ФОРМАТ. Модуль ничего не считает и никуда не ходит: на входе
готовые числа, на выходе текст. Так его видно в самопроверке целиком, а
измерения (место в блоке, кто успел до нас, копировщики) живут там, где им
место -- в детекторе и в отдельных прогонах.

РАЗМЕТКА -- HTML. Ссылка на транзакцию идёт как <a href=...>tx</a>: владелец
просил без хеша и адреса в тексте. Имена токенов приходят из цепи, поэтому
всякое <, > и & в них экранируется -- иначе Telegram отвергнет сообщение
целиком и строка не придёт вовсе.
"""
from __future__ import annotations

SOLSCAN = "https://solscan.io/tx/"


def экран(текст) -> str:
    """HTML-экранирование: имя токена из цепи может содержать что угодно."""
    return (str(текст if текст is not None else "")
            .replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;"))


def ссылка(подпись: str | None, ярлык: str = "tx") -> str:
    """Ссылка на Solscan. Нет подписи -- ярлык без ссылки, но и без хеша."""
    if not подпись:
        return ярлык
    return f'<a href="{SOLSCAN}{подпись}">{ярлык}</a>'


def _чч_мм_сс(строка_времени: str | None) -> str:
    """Из ISO-времени -- только часы:минуты:секунды, как в пакете."""
    т = str(строка_времени or "")
    if "T" in т and len(т) >= 19:
        return т[11:19]
    return т[:8] or "--:--:--"


def _мс(x) -> str:
    return "—" if x is None else f"{int(round(float(x)))}"


def _sol(x, знаков: int = 4) -> str:
    return "—" if x is None else f"{float(x):.{знаков}f}"


def _проц(x, знаков: int = 1) -> str:
    if x is None:
        return "—"
    з = float(x)
    знак = "+" if з > 0 else ("−" if з < 0 else "")
    return f"{знак}{abs(з):.{знаков}f} %"


def место_в_блоке(индекс, всего) -> str:
    """"место 0.62" -- доля индекса транзакции в блоке источника."""
    if индекс is None or not всего:
        return "место —"
    return f"место {float(индекс) / float(всего):.2f}"


def строка_buy(*, время_utc: str | None, размер_sol, имя_токена: str | None,
               подпись_источника: str | None, индекс_источника=None,
               всего_в_блоке=None,
               наш_s: int | None = None, наш_индекс=None, наш_всего=None,
               путь_мс=None, увидели_мс=None, решили_мс=None, собрали_мс=None,
               отправитель: str | None = None,
               перед_нами: int | None = None, копировщиков: int | None = None,
               bloom_s: int | None = None, bloom_индекс=None, bloom_всего=None,
               bloom_собрали_мс=None, имя_источника: str | None = None) -> str:
    """BUY одним сообщением. Правкой дописываются те же поля, когда доехали."""
    # Имени токена может не быть вовсе -- тогда, по слову владельца, в строке
    # стоит имя источника, а не пустое место и не адрес минта.
    имя = экран(имя_токена or имя_источника or "без имени")
    строки = [f"🟢 {_чч_мм_сс(время_utc)} BUY · {_sol(размер_sol, 2)} SOL · "
              f"{имя} · {ссылка(подпись_источника)}",
              f"tx: {место_в_блоке(индекс_источника, всего_в_блоке)}"]
    наше = (f"мы: S+{наш_s}" if наш_s is not None else "мы: S+?")
    if наш_индекс is not None and наш_всего:
        наше += f", {int(наш_индекс)}/{int(наш_всего)}"
    наше += (f" · путь {_мс(путь_мс)} мс (увидели {_мс(увидели_мс)} · "
             f"решили {_мс(решили_мс)} · собрали {_мс(собрали_мс)})")
    строки.append(наше)
    # Четвёртая строка: кто довёз и сколько успело до нас. При S+0 это "перед
    # нами", при S+1 и хуже -- "в S+0 успели": вопрос разный, и путать их
    # нельзя.
    подпись_поля = "перед нами" if (наш_s == 0) else "в S+0 успели"
    хвост = f"· {отправитель or '—'} · {подпись_поля}: {перед_нами if перед_нами is not None else '—'}"
    хвост += f", копировщиков {копировщиков if копировщиков is not None else '—'}"
    строки.append(хвост)
    if bloom_s is not None or bloom_собрали_мс is not None:
        б = f"Bloom: S+{bloom_s}" if bloom_s is not None else "Bloom: S+?"
        if bloom_индекс is not None and bloom_всего:
            б += f", {int(bloom_индекс)}/{int(bloom_всего)}"
        б += f" · собрали {_мс(bloom_собрали_мс)}"
        строки.append(б)
    return "\n".join(строки)


def строка_sell(*, время_utc: str | None, имя_токена: str | None, секунды,
                вход_sol, возврат_sol, подпись_продажи: str | None,
                попыток: int | None = None, причина: str | None = None,
                имя_источника: str | None = None) -> str:
    """SELL одним сообщением. Итог -- ЧИСТЫМИ, после чаевых и приоритета."""
    имя = экран(имя_токена or имя_источника or "без имени")
    доля = None
    if вход_sol and возврат_sol is not None:
        доля = (float(возврат_sol) / float(вход_sol) - 1.0) * 100.0
    кружок = "🟢" if (доля is not None and доля > 0) else "🔴"
    сек = "—" if секунды is None else f"{float(секунды):.1f}"
    первая = (f"{кружок} {_чч_мм_сс(время_utc)} SELL · {имя} · {сек} с · "
              f"{_sol(вход_sol)} → {_sol(возврат_sol)} SOL ({_проц(доля)}) · "
              f"{ссылка(подпись_продажи)}")
    if попыток and int(попыток) > 1:
        вторая = f"попыток {int(попыток)}"
        if причина:
            вторая += f" · причина: {экран(причина)[:120]}"
        return первая + "\n" + вторая
    return первая


def строка_сводки(*, окно: str, сделок: int, итог_sol, s0: int, в_цели: int,
                  промахов: int, путь_медиана_мс,
                  довозили: dict | None = None,
                  bloom_пар: int | None = None, bloom_впереди: int | None = None,
                  мы_впереди: int | None = None, bloom_s0: int | None = None,
                  стоп_полоса=None, порог_полоса=None,
                  стоп_bloom=None, порог_bloom=None) -> str:
    """Часовая сводка ВМЕСТО круга."""
    знак = "+" if (итог_sol or 0) >= 0 else "−"
    строки = [f"📊 {окно} · сделок {int(сделок)} · {знак}{abs(float(итог_sol or 0)):.3f} SOL"]
    доля_s0 = f"{round(s0 / сделок * 100)} %" if сделок else "—"
    доля_ц = f"{round(в_цели / сделок * 100)} %" if сделок else "—"
    строки.append(f"S+0 {int(s0)} ({доля_s0}) · в цели {int(в_цели)} ({доля_ц}) · "
                  f"промахов наших {int(промахов)} · путь медиана "
                  f"{_мс(путь_медиана_мс)} мс")
    if довозили:
        по_убыванию = sorted(довозили.items(), key=lambda кв: -кв[1])
        строки.append("довозили: " + ", ".join(f"{экран(и)} {н}" for и, н in по_убыванию))
    if bloom_пар is not None:
        строки.append(f"Bloom: {int(bloom_пар)} пар · впереди нас "
                      f"{int(bloom_впереди or 0)}, мы {int(мы_впереди or 0)} · "
                      f"S+0 {int(bloom_s0 or 0)}")
    if стоп_полоса is not None or стоп_bloom is not None:
        строки.append(f"стоп: полоса {_подписанное(стоп_полоса)} / "
                      f"{_подписанное(порог_полоса, отрицательный=True)} · "
                      f"Bloom {_подписанное(стоп_bloom)} / "
                      f"{_подписанное(порог_bloom, отрицательный=True)}")
    return "\n".join(строки)


def _подписанное(x, *, отрицательный: bool = False) -> str:
    if x is None:
        return "—"
    з = float(x)
    if отрицательный:
        з = -abs(з)
    знак = "−" if з < 0 else "+"
    return f"{знак}{abs(з):.2f}"


# --------------------------------------------------------------- самопроверка
def self_test() -> int:
    проверки = []

    def chk(имя, ок, факт=""):
        проверки.append((имя, bool(ок), факт))

    buy = строка_buy(время_utc="2026-09-26T22:35:26Z", размер_sol=0.01,
                     имя_токена="TOKENNAME",
                     подпись_источника="S" * 88, индекс_источника=750,
                     всего_в_блоке=1210, наш_s=0, наш_индекс=940,
                     наш_всего=1210, путь_мс=195, увидели_мс=118, решили_мс=6,
                     собрали_мс=71, отправитель="nozomi", перед_нами=2,
                     копировщиков=1, bloom_s=0, bloom_индекс=985,
                     bloom_всего=1210, bloom_собрали_мс=28)
    ряды = buy.split("\n")
    chk("BUY: пять строк при паре с Bloom", len(ряды) == 5, len(ряды))
    chk("BUY: первая строка -- время, размер, имя и ссылка",
        ряды[0].startswith("🟢 22:35:26 BUY · 0.01 SOL · TOKENNAME · <a href=")
        and ряды[0].endswith(">tx</a>"), ряды[0])
    chk("BUY: хеша в тексте нет, он только внутри ссылки",
        ряды[0].count("S" * 88) == 1 and ">tx</a>" in ряды[0], ряды[0])
    chk("BUY: место источника долей", ряды[1] == "tx: место 0.62", ряды[1])
    chk("BUY: наша строка с S+0, местом и разложением пути",
        ряды[2] == ("мы: S+0, 940/1210 · путь 195 мс "
                    "(увидели 118 · решили 6 · собрали 71)"), ряды[2])
    chk("BUY: при S+0 спрашивается 'перед нами'",
        ряды[3] == "· nozomi · перед нами: 2, копировщиков 1", ряды[3])
    chk("BUY: строка Bloom с его местом и временем ответа",
        ряды[4] == "Bloom: S+0, 985/1210 · собрали 28", ряды[4])

    buy1 = строка_buy(время_utc="2026-09-26T22:35:26Z", размер_sol=0.01,
                      имя_токена=None, имя_источника="BATCH-5 1.1",
                      подпись_источника=None, наш_s=1, перед_нами=3,
                      копировщиков=2, отправитель="astralane")
    ряды1 = buy1.split("\n")
    chk("BUY без пары -- четыре строки", len(ряды1) == 4, len(ряды1))
    chk("BUY: при S+1 спрашивается 'в S+0 успели'",
        "в S+0 успели: 3, копировщиков 2" in ряды1[3], ряды1[3])
    chk("BUY: нет имени токена -- стоит имя источника",
        "BATCH-5 1.1" in ряды1[0], ряды1[0])
    chk("BUY: нет подписи -- ярлык без ссылки и без хеша",
        ряды1[0].rstrip().endswith("· tx"), ряды1[0])
    chk("BUY: неизвестные числа -- чертой, а не нулём",
        "путь — мс (увидели — · решили — · собрали —)" in ряды1[2], ряды1[2])

    sell = строка_sell(время_utc="2026-09-26T22:36:29Z", имя_токена="TOKENNAME",
                       секунды=28.5, вход_sol=0.01, возврат_sol=0.0089,
                       подпись_продажи="P" * 88)
    chk("SELL: красный кружок при минусе и проценты со знаком минус",
        sell.startswith("🔴 22:36:29 SELL · TOKENNAME · 28.5 с · "
                        "0.0100 → 0.0089 SOL (−11.0 %)"), sell)
    sell_плюс = строка_sell(время_utc="2026-09-26T22:36:29Z", имя_токена="T",
                            секунды=30, вход_sol=0.01, возврат_sol=0.0115,
                            подпись_продажи="P" * 88)
    chk("SELL: зелёный кружок при плюсе", sell_плюс.startswith("🟢"), sell_плюс)
    sell_поп = строка_sell(время_utc="2026-09-26T22:36:29Z", имя_токена="T",
                           секунды=30, вход_sol=0.01, возврат_sol=0.009,
                           подпись_продажи="P" * 88, попыток=3,
                           причина="проскальзывание")
    chk("SELL: при нескольких попытках вторая строка с числом и причиной",
        sell_поп.split("\n")[1] == "попыток 3 · причина: проскальзывание",
        sell_поп)
    chk("SELL: одна попытка -- второй строки нет", "\n" not in sell, sell)

    св = строка_сводки(окно="22:00–23:00", сделок=18, итог_sol=0.031, s0=6,
                       в_цели=9, промахов=5, путь_медиана_мс=190,
                       довозили={"astralane": 7, "nozomi": 5, "helius": 3,
                                 "blockrazor": 2, "zeroslot": 1},
                       bloom_пар=12, bloom_впереди=5, мы_впереди=7, bloom_s0=5,
                       стоп_полоса=-0.12, порог_полоса=0.30,
                       стоп_bloom=-0.08, порог_bloom=0.50)
    ряды_с = св.split("\n")
    chk("сводка: пять строк", len(ряды_с) == 5, len(ряды_с))
    chk("сводка: окно, число сделок и итог",
        ряды_с[0] == "📊 22:00–23:00 · сделок 18 · +0.031 SOL", ряды_с[0])
    chk("сводка: доли считаются, а не переписываются",
        ряды_с[1] == ("S+0 6 (33 %) · в цели 9 (50 %) · промахов наших 5 · "
                      "путь медиана 190 мс"), ряды_с[1])
    chk("сводка: отправители по убыванию",
        ряды_с[2] == "довозили: astralane 7, nozomi 5, helius 3, blockrazor 2, zeroslot 1",
        ряды_с[2])
    chk("сводка: строка Bloom",
        ряды_с[3] == "Bloom: 12 пар · впереди нас 5, мы 7 · S+0 5", ряды_с[3])
    chk("сводка: стоп -- текущий итог против порога по обоим кошелькам",
        ряды_с[4] == "стоп: полоса −0.12 / −0.30 · Bloom −0.08 / −0.50", ряды_с[4])

    # HTML: имя токена из цепи не ломает разметку.
    злое = строка_buy(время_utc="2026-09-26T22:35:26Z", размер_sol=0.01,
                      имя_токена="<b>&hack</b>", подпись_источника="S" * 88,
                      наш_s=0)
    chk("имя токена экранировано -- разметку не ломает",
        "&lt;b&gt;&amp;hack&lt;/b&gt;" in злое and "<b>" not in злое, злое[:80])

    плохо = [(и, ф) for и, ок, ф in проверки if not ок]
    for имя, ок, факт in проверки:
        print(f"  [{'ok  ' if ок else 'СБОЙ'}] {имя}" + ("" if ок else f"  -> {факт}"))
    print(f"самопроверка формата Telegram: "
          f"{len(проверки) - len(плохо)}/{len(проверки)} пройдено")
    return 0 if not плохо else 1


if __name__ == "__main__":
    import sys
    raise SystemExit(self_test() if "--self-test" in sys.argv else 0)
