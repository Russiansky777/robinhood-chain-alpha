#!/usr/bin/env python3
"""Ревизия закрытий: длинные удержания, стоп по резерву и ночной срез -- на готовом кэше.

Нового чтения архива нет: всё считается по кэшу сигналов (подбивка_paket_kesh).

Что считается.
  (а) Стандарт по всей вселенной со входом S1 и удержаниями 36 / 60 / 108 / 150 / 300
      слотов, рядом -- те же удержания со СТОПОМ по падению реального резерва на 30 %.
      Стоп проверяется по сетке состояний выхода (6, 12, 24, 30, 36, 60, 72, 108, 150,
      300 слотов): выход -- первая точка сетки внутри удержания, где резерв упал на 30 %
      и больше. Это стоп, замеренный по сетке, а не по каждому событию -- так и подписано.
      Удержания 600 и 1200 слотов кэш НЕ содержит: суточные файлы собирались окном 160
      слотов, и состояния выхода идут только до 300. Цена расширения -- в счёте прогона
      (`цена_расширения`).
  (б) Отдельный срез «сигналы 00-08 UTC», заданный заранее, при тех же удержаниях.
      Поправка -- на все посчитанные сочетания (кошельки x удержание x билет x поправка
      круга x срез), число печатается.
  (в) Группа cand1 на сутках 04-10.10: итог по её собственному билету 0.1 и по 0.3, при
      входе S0_дно и S1, по всем удержаниям -- чтобы сверить «+0.43 SOL/сут на всех
      удержаниях» и сказать, что даёт S1.

Только чтение. Выход: data/podbivka/revizia_zakrytij<метка>.json.
"""
