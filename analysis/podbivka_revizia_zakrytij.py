П = O.П
УДЕРЖАНИЯ = (36, 60, 108, 150, 300)
СЕТКА = (6, 12, 24, 30, 36, 60, 72, 108, 150, 300)
СТОП = 0.30                  # падение реального резерва, при котором выходим
К_G = ("0.989", "1.013")     # осторожная поправка и калибровка по 4vw
НОЧЬ = range(0, 8)           # 00-08 UTC
БИЛЕТЫ = ("0.3", "глубина")
СЕМЯ = 20261010
# Цена расширения окна до 1200 слотов (для удержаний 600 и 1200): по замерам
# глубинного прохода -- 11.2 ГБ и 95-230 минут на сутки при окне 160; окно 1200 в 7.5
# раз шире, ряды пулов висят в памяти дольше (у Code-3 окно 2727 уже валило ядром).
ЦЕНА_РАСШИРЕНИЯ = {"гб_на_сутки": 11.2, "минут_на_сутки_при_окне_160": [95, 230],
                   "окно": 1200, "во_сколько_раз_шире": 7.5,
                   "заданий_на_44_суток": 44, "мест_разом": 6,
                   "оценка_часов_на_44_суток": [12, 30],
                   "риск": "ряды пулов в памяти: при окне 2727 прогон валило ядром (-9)"}


def слои(р: dict) -> tuple:
    ч = dt.datetime.fromtimestamp((р.get("ts") or 0) / 1000, dt.timezone.utc).hour
    return ("вся", "ночь") if ч in НОЧЬ else ("вся",)


def стоп_точка(вх: list, выход: dict, H: int) -> int:
    """Первая точка сетки внутри удержания, где реальный резерв упал на СТОП и больше."""
    x0 = float(вх[0])
    порог = x0 * (1.0 - СТОП)
    for h in СЕТКА:
        if h > H:
            break
        с = выход.get(str(h))
        if с and float(с[0]) <= порог:
            return h
    return H


def свод_окна(итоги: list, дни: list, с_ди: bool = True) -> dict:
    """Те же проверки, что в стандарте, но на готовых списках.

    `с_ди` -- считать ли бутстрэп. Он дорогой (две тысячи прогонов), поэтому зовётся
    только для окон, прошедших все дешёвые проверки: иначе на пятьдесят тысяч сочетаний
    уходят часы.
    """
    if not итоги:
        return {}
    по_дню: dict = collections.defaultdict(list)
    for д, v in zip(дни, итоги):
        по_дню[д].append(v)
    суммы = {д: sum(v) for д, v in по_дню.items()}
    низ, верх = Z.ди_по_суткам(по_дню, seed=СЕМЯ) if с_ди else (None, None)
    пол = sorted(по_дню)
    серёдка = len(пол) // 2
    пол1 = sum(суммы[д] for д in пол[:серёдка])
    пол2 = sum(суммы[д] for д in пол[серёдка:])
    плюс = sum(1 for s in суммы.values() if s > 0)
    return {"n": len(итоги), "суток": len(суммы),
            "ожидание_sol": round(statistics.fmean(итоги), 6),
            "sol_в_сутки": round(sum(итоги) / max(1, len(суммы)), 5),
            "ди_низ_sol": round(низ, 6) if низ is not None else None,
            "ди_верх_sol": round(верх, 6) if верх is not None else None,
            "без_верх_5_sol": round(Z.срезанное(итоги, 0.05), 6),
            "суток_в_плюсе": плюс,
            "доля_суток_в_плюсе": round(плюс / max(1, len(суммы)), 3),
            "половина_1": round(пол1, 5), "половина_2": round(пол2, 5),
            "суммы_по_суткам": суммы}


def окно_прошло(с: dict, с_ди: bool = True) -> tuple:
    нет = []
    if с.get("n", 0) < И.N_МИН:
        нет.append(f"n {с.get('n', 0)} < {И.N_МИН}")
    if (с.get("ожидание_sol") or 0) <= 0:
        нет.append("среднее не больше нуля")
    if с_ди and (с.get("ди_низ_sol") or 0) <= 0:
        нет.append("нижняя граница ДИ не выше нуля")
    if (с.get("без_верх_5_sol") or 0) <= 0:
        нет.append("без верхних 5 % не в плюсе")
    if (с.get("доля_суток_в_плюсе") or 0) < И.ДОЛЯ_СУТОК_В_ПЛЮСЕ:
        нет.append(f"суток в плюсе {с.get('доля_суток_в_плюсе')}")
    if (с.get("половина_1") or 0) <= 0 or (с.get("половина_2") or 0) <= 0:
        нет.append("половина окна не в плюсе")
    return (not нет), нет


def p_знаков(суммы: dict) -> float | None:
    v = [s for s in суммы.values() if s]
    if len(v) < 4:
        return None
    n, k = len(v), sum(1 for s in v if s > 0)
    return sum(math.comb(n, i) for i in range(k, n + 1)) / 2 ** n


def подряд(дни: list) -> bool:
    try:
        д = [dt.date.fromisoformat(x) for x in дни]
    except ValueError:
        return False
    return all((д[i + 1] - д[i]).days == 1 for i in range(len(д) - 1))


def главное(а) -> int:  # noqa: PLR0912, PLR0915
    кал = (json.loads((П / "kalibrovka.json").read_text(encoding="utf-8"))
           .get("калибровка") or {})
    изд = float(кал.get("издержки_медиана_sol") or 0.002)
    группы = (json.loads((П / "code1_sources_live.json").read_text(encoding="utf-8"))
              .get("groups") or {})
    def адреса(имя: str) -> set:
        v = группы.get(имя) or {}
        return set(v.get("addresses") or []) if isinstance(v, dict) else set(v)

    cand1 = адреса("cand1") | адреса("cand1_03")
    дни_индекс: dict = {}
    ряды: dict = collections.defaultdict(lambda: (array("f"), array("H")))
    cand_ряды: dict = collections.defaultdict(list)
    счёт: collections.Counter = collections.Counter()
    for р in O.сигналы():
        счёт["сигналов"] += 1
        if р.get("quoteMint") != O.WSOL or not р.get("первая"):
            continue
        if (р.get("sol") or 0) < И.ПОРОГ_ИСТОЧНИКА:
            continue
        ист = р.get("ист")
        вх_все = р.get("вход") or {}
        вых = р.get("выход") or {}
        if not (ист and вх_все.get(а.mesto)):
            continue
        сут = O.сутки(р)
        и_сут = дни_индекс.setdefault(сут, len(дни_индекс))
        счёт["годных"] += 1
        с = O.как_сигнал(р)
        бг = И.билет_по_глубине(р, а.mesto) if hasattr(И, "билет_по_глубине") else None
        if бг is None:
            рез = float(вх_все[а.mesto][0]) / float(р.get("масштаб") or 1.0)
            б_ = И.ДОЛЯ_РЕЗЕРВА * рез
            бг = round(min(б_, 3.0), 4) if б_ > 0.01 else None
        слои_ = слои(р)
        for H in УДЕРЖАНИЯ:
            для_стопа = стоп_точка(вх_все[а.mesto], вых, H)
            for имя_H, h in ((str(H), H), (f"{H}|стоп30", для_стопа)):
                if имя_H.endswith("стоп30") and для_стопа == H:
                    pass        # стоп не сработал: тот же выход, строка всё равно нужна
                for имя_б, б in (("0.3", И.БИЛЕТ), ("глубина", бг)):
                    if not б:
                        continue
                    for кг in К_G:
                        и_, вид = И.круг(с, б, а.mesto, h, изд, 1.0, float(кг))
                        if и_ is None:
                            счёт[f"нет_круга|{вид}"] += 1
                            continue
                        for сл in слои_:
                            зн, дн = ряды[(ист, сл, имя_H, имя_б, кг)]
                            зн.append(и_)
                            дн.append(и_сут)
        if ист in cand1:
            cand_ряды[ист].append(р)
    import podbivka_zabor_nabor as Н  # noqa: PLC0415
    неполные = Н.неполные_сутки()
    дни = [д for д, _ in sorted(дни_индекс.items(), key=lambda t: t[1])]
    порядок = sorted(range(len(дни)), key=lambda i: дни[i])
    сорт_дни = [дни[i] for i in порядок if дни[i] not in неполные]
    окна = [(п_, пр_) for п_, пр_ in И.окна_скольжения(
        сорт_дни, И.ПОДБОР_СУТОК, И.ПРОВЕРКА_СУТОК, И.СДВИГ_СУТОК) if подряд(п_ + пр_)]
    д_к_и = {д: и for и, д in enumerate(дни)}
    кошельки = {к[0] for к in ряды}
    вариантов = len({(к[1], к[2], к[3], к[4]) for к in ряды})
    сочетаний = len(кошельки) * вариантов
    порог_все = 0.05 / max(1, сочетаний)
    порог_N = 0.05 / max(1, len(кошельки))
    таб: list = []
    for (ист, сл, имя_H, имя_б, кг), (зн, дн) in ряды.items():
        окон, годных = [], 0
        все_суммы: dict = {}
        for подб, пров in окна:
            иды = {д_к_и[д] for д in пров if д in д_к_и and д not in неполные}
            итоги = [зн[i] for i in range(len(зн)) if дн[i] in иды]
            дни_ = [дни[дн[i]] for i in range(len(зн)) if дн[i] in иды]
            с_ = свод_окна(итоги, дни_, с_ди=False)
            if not с_:
                окон.append({"n": 0, "прошло": False})
                continue
            да, почему = окно_прошло(с_, с_ди=False)
            if да:          # дешёвые проверки прошли -- только теперь бутстрэп
                с_ = свод_окна(итоги, дни_, с_ди=True)
                да, почему = окно_прошло(с_, с_ди=True)
            годных += 1
            все_суммы.update(с_["суммы_по_суткам"])
            окон.append({"n": с_["n"], "sol_в_сутки": с_["sol_в_сутки"],
                         "без_верх_5": с_["без_верх_5_sol"], "прошло": да,
                         "почему_нет": почему})
        if not годных:
            continue
        p = p_знаков(все_суммы)
        прошло = bool(годных >= И.ОКОН_МИН
                      and all(o["прошло"] for o in окон if o["n"])
                      and p is not None and p < порог_все)
        таб.append({"источник": ист, "срез": сл, "удержание": имя_H, "билет": имя_б,
                    "к_g": кг, "окон_годных": годных,
                    "окон_в_плюсе": sum(1 for o in окон if o["прошло"]),
                    "n": sum(o["n"] for o in окон), "p": p,
                    "sol_в_сутки": round(statistics.fmean(
                        [o["sol_в_сутки"] for o in окон if o["n"]]), 5),
                    "прошло_с_полной_поправкой": прошло,
                    "прошло_по_N": bool(годных >= И.ОКОН_МИН
                                        and all(o["прошло"] for o in окон if o["n"])
                                        and p is not None and p < порог_N)})
    # (в) cand1 на сутках 04-10.10: по входам и удержаниям, билет 0.1 и 0.3
    cand_итог: dict = {}
    окно_c = {f"2026-10-{д:02d}" for д in range(4, 11)} - неполные
    for место in ("S0_дно", "S1"):
        for имя_б, б in (("0.1", 0.1), ("0.3", 0.3)):
            for H in УДЕРЖАНИЯ:
                по_дню: dict = collections.defaultdict(list)
                for ист, сп in cand_ряды.items():
                    for р in сп:
                        сут = O.сутки(р)
                        if сут not in окно_c or not (р.get("вход") or {}).get(место):
                            continue
                        и_, _ = И.круг(O.как_сигнал(р), б, место, H, изд, 1.0, 0.989)
                        if и_ is not None:
                            по_дню[сут].append(и_)
                if не_пусто := bool(по_дню):
                    все = [v for сп in по_дню.values() for v in сп]
                    суммы = {д: sum(v) for д, v in по_дню.items()}
                    cand_итог[f"{место}|{имя_б}|H{H}"] = {
                        "n": len(все), "суток": len(суммы),
                        "sol_в_сутки": round(sum(все) / len(суммы), 5),
                        "среднее_sol": round(statistics.fmean(все), 6),
                        "без_верх_5": round(Z.срезанное(все, 0.05), 6),
                        "суток_в_плюсе": sum(1 for s in суммы.values() if s > 0),
                        "по_суткам": {д: round(s, 5) for д, s in sorted(суммы.items())}}
                del не_пусто
    тело = {"что": "ревизия закрытий: длинные удержания, стоп по резерву, ночной срез",
            "когда": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
            "место_входа": а.mesto, "удержания": list(УДЕРЖАНИЯ),
            "стоп_по_резерву": СТОП, "стоп_как": "по сетке состояний выхода",
            "суток": len(сорт_дни), "окон": len(окна),
            "неполные_сутки": sorted(неполные),
            "кошельков": len(кошельки), "вариантов": вариантов,
            "сочетаний_посчитано": сочетаний,
            "порог_p_на_все_сочетания": порог_все, "порог_p_на_N_кошельков": порог_N,
            "цена_расширения_до_1200": ЦЕНА_РАСШИРЕНИЯ,
            "счёт": dict(счёт),
            "прошли_с_полной_поправкой": [t for t in таб
                                          if t["прошло_с_полной_поправкой"]],
            "прошли_по_N": [t for t in таб if t["прошло_по_N"]],
            "cand1_04_10": cand_итог}
    вых_ф = П / f"revizia_zakrytij{а.metka}.json"
    вых_ф.write_text(json.dumps(тело, ensure_ascii=False, indent=1), encoding="utf-8")
    import podbivka_run as R  # noqa: PLC0415
    R.записано(вых_ф)
    print(f"суток {len(дни)}, окон {len(окна)}, кошельков {len(кошельки)}, "
          f"вариантов {вариантов}, сочетаний {сочетаний}, порог p "
          f"{порог_все:.3e}", flush=True)
    print(f"прошли с полной поправкой: {len(тело['прошли_с_полной_поправкой'])}; "
          f"по N кошельков: {len(тело['прошли_по_N'])}", flush=True)
    for t in sorted(тело["прошли_с_полной_поправкой"],
                    key=lambda t: -t["sol_в_сутки"])[:10]:
        print(f"  {t['источник'][:8]}… срез {t['срез']} H {t['удержание']} билет "
              f"{t['билет']} k{t['к_g']}: n {t['n']}, окон+ {t['окон_в_плюсе']}"
              f"/{t['окон_годных']}, SOL/сут {t['sol_в_сутки']:+.4f}, p {t['p']:.2e}",
              flush=True)
    for к, v in sorted(cand_итог.items()):
        print(f"  cand1 {к}: n {v['n']}, SOL/сут {v['sol_в_сутки']:+.4f}, "
              f"среднее {v['среднее_sol']:+.5f}, без в5 {v['без_верх_5']:+.5f}, "
              f"сут+ {v['суток_в_плюсе']}/{v['суток']}", flush=True)
    return 0


def main() -> int:
    р = argparse.ArgumentParser()
    р.add_argument("--mesto", default="S1", choices=("S1", "S0_дно", "S2"))
    р.add_argument("--metka", default="")
    return главное(р.parse_args())


if __name__ == "__main__":
    raise SystemExit(main())
