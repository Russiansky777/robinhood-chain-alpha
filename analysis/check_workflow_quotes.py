#!/usr/bin/env python3
"""Кавычки в удалённых командах прогонов: ищем те, что рвут команду ssh.

ЗАЧЕМ. 25.09 деплой детектора упал дважды с сообщением
"sed: can't read /etc/bloom-executor/env: Permission denied" при полностью
исправном хосте: файловая система rw, файл читается, каталог пишется, флага
immutable нет. Причина оказалась в одной кавычке. В шаг деплоя был добавлен
комментарий ВНУТРИ двойных кавычек ssh:

    ssh -n $SSH_OPTS root@$HOST "
      ...
      # Решение владельца: "пул отправителей ... полосы". Значение ...
      sed -i '/^BLOOM_POOL_SEND=/d' $ENV_DIR/env
      ..."

Первая кавычка в комментарии ЗАКРЫЛА аргумент ssh, и всё, что шло дальше,
выполнилось ЛОКАЛЬНО на бегунке под пользователем ghrunner. Ему файл
/etc/bloom-executor/env (root:root, 600) читать нельзя -- отсюда Permission
denied. Ошибка тихая и злая: журнал показывает правильные команды, хост в
порядке, а правки env молча не происходят, зато часть скрипта делает не то,
что написано.

ЧТО ПРОВЕРЯЕМ. В каждом шаге run: находим строки, открывающие удалённую
команду двойной кавычкой (ssh ... "), и до её закрытия требуем, чтобы внутри не
было НЕэкранированной двойной кавычки. Считаем только кавычки: одинарные внутри
допустимы и нужны (в sed-выражениях), экранированные \\" допустимы тоже.

Это проверка на КЛАСС ошибки, а не на один файл: стоит в тех же прогонах, что и
проверка имён переменных оболочки (check_shell_ascii.py).
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

КАТАЛОГ = ".github/workflows"

# Строка, открывающая удалённую команду: ssh (с любыми ключами) и двойная
# кавычка, после которой команда продолжается на следующих строках.
ОТКРЫВАЕТ = re.compile(r'\bssh\b[^"\n]*"\s*$')
# Однострочный ssh "..." -- его баланс проверяем в этой же строке.
ОДНОЙ_СТРОКОЙ = re.compile(r'\bssh\b[^"\n]*"(?P<тело>(?:[^"\\]|\\.)*)"')


def _без_экранированных(текст: str) -> str:
    """Убрать экранированные кавычки: они законны и в подсчёт не идут."""
    return re.sub(r'\\.', "", текст)


def разбор(текст: str, *, имя: str = "") -> list:
    """Список находок: (строка, что не так, сама строка)."""
    находки = []
    строки = текст.split("\n")
    внутри = False
    начало = 0
    # Строка вида "имя: значение" -- это ключ YAML (например description с
    # текстом про ssh), а не команда. Считать её открытием команды значит
    # ловить собственные описания входов: так и случилось на прогоне
    # run_vps_feed_rabbit_verify.yml.
    КЛЮЧ_YAML = re.compile(r'^\s*[A-Za-z_][\w.-]*:\s')
    for i, с in enumerate(строки, start=1):
        чистая = _без_экранированных(с)
        if not внутри:
            if ОТКРЫВАЕТ.search(чистая) and not КЛЮЧ_YAML.match(чистая):
                внутри, начало = True, i
            continue
        # Внутри удалённой команды. Нечётное число кавычек в строке значит,
        # что дальше перевод строки ВНЕ кавычек -- и локальная оболочка на нём
        # команду завершит. Законные закрытия: строка НАЧИНАЕТСЯ кавычкой
        # (дальше перенаправления, `> файл 2>&1`, `|| true`) или ЗАКАНЧИВАЕТСЯ
        # ею (последняя команда и закрытие в одной строке).
        кавычек = чистая.count('"')
        if кавычек == 0:
            continue
        обрезанная = чистая.strip()
        # ЧТО ИДЁТ ПОСЛЕ ПОСЛЕДНЕЙ КАВЫЧКИ. Законное закрытие -- это конец
        # строки или локальный хвост: перенаправление, || и &&, закрывающая
        # скобка, труба, точка с запятой, продолжение строки. Всё остальное
        # (например текст комментария) значит, что кавычка стоит ПОСЕРЕДИНЕ
        # команды и рвёт её.
        хвост = обрезанная[обрезанная.rfind('"') + 1:].strip()
        ЛОКАЛЬНЫЙ_ХВОСТ = ("", "\\", ")", ");", "|| true")
        похож_на_хвост = (хвост in ЛОКАЛЬНЫЙ_ХВОСТ
                           or хвост.startswith(("||", "&&", ">", "<", "2>", "|",
                                                 ";", ")", "\\")))
        if кавычек % 2 == 1 and похож_на_хвост:
            внутри = False
            continue
        if кавычек % 2 == 0:
            # Пара кавычек внутри строки: состояние кавычек возвращается к
            # исходному, перевод строки остаётся внутри команды. Законно.
            continue
        находки.append((i, f"кавычка внутри команды ssh, открытой на строке "
                            f"{начало}: она закроет команду, и остаток пойдёт "
                            f"выполняться локально", с.strip()[:160]))
        внутри = False
    if внутри:
        находки.append((начало, "команда ssh не закрыта до конца шага", ""))
    return [(имя, *н) for н in находки]


def проверить(каталог: str = КАТАЛОГ) -> dict:
    из_ = {"files": 0, "findings": []}
    д = Path(каталог)
    if not д.exists():
        д = Path("..") / каталог
    for ф in sorted(д.glob("*.yml")):
        из_["files"] += 1
        из_["findings"] += разбор(ф.read_text(encoding="utf-8"), имя=ф.name)
    return из_


def self_test() -> int:
    проверки = []

    def chk(имя, ок, факт=""):
        проверки.append((имя, bool(ок), факт))

    # ИМЕННО ТА ОШИБКА, что уронила деплой 25.09.
    # Кавычка открывается на одной строке, закрывается на другой -- ровно как
    # в упавшем деплое: между ними перевод строки, и локальная оболочка на нём
    # команду завершает.
    плохой = '''
          ssh -n $SSH_OPTS root@$HOST "
            set -a; . /etc/bloom-executor/env; set +a
            # Решение владельца 25.09: "пул отправителей
            # шаг 1 включить сейчас; веер и пул идут параллельно".
            sed -i '/^BLOOM_POOL_SEND=/d' /etc/bloom-executor/env
            echo 'BLOOM_POOL_SEND=1' >> /etc/bloom-executor/env
          "
'''
    н = разбор(плохой)
    chk("кавычка в комментарии внутри ssh НАЙДЕНА", len(н) >= 1, н)
    chk("в находке названа строка, где команда ssh открыта",
        н and "открытой на строке" in н[0][2], н)

    # Законный случай: одинарные кавычки в sed и экранированные двойные.
    хороший = '''
          ssh -n $SSH_OPTS root@$HOST "
            sed -i '/^BLOOM_POOL_SEND=/d' $ENV_DIR/env
            echo 'BLOOM_POOL_SEND=1' >> $ENV_DIR/env
            if [ -z \\"\\$TELEGRAM_BOT_TOKEN\\" ]; then echo 'нет'; fi
            printf 'рубильник: %s\\\\n' \\"\\$F\\"
          "
'''
    chk("законная удалённая команда не даёт находок", разбор(хороший) == [],
        разбор(хороший))

    # Пара кавычек внутри строки -- законно (echo "текст").
    пара = '''
          ssh -n $SSH_OPTS root@$HOST "
            echo 'строка'
            grep -c '=' $ENV_DIR/env
          "
'''
    chk("строки без кавычек и с парой одинарных проходят", разбор(пара) == [])

    # Однострочная команда ssh не должна считаться незакрытой.
    одна = '''
          ssh -n $SSH_OPTS root@$HOST "ls -l /etc/bloom-executor/env"
          echo дальше
'''
    # Законное закрытие с перенаправлением В НАЧАЛЕ строки -- так написаны
    # несколько прогонов репозитория, и находкой это быть не должно.
    с_перенаправлением = '''
          ssh -n $SSH_OPTS root@127.0.0.1 "
            set -a; . /etc/bloom-executor/env; set +a
            /home/bot/venv/bin/python module.py --dry-run
          " > data/lane_dry_run.txt 2>&1
          RC=$?
'''
    chk("закрытие с перенаправлением в начале строки -- не находка",
        разбор(с_перенаправлением) == [], разбор(с_перенаправлением))
    chk("однострочная команда ssh не считается открытой", разбор(одна) == [],
        разбор(одна))

    # И боевая проверка: все прогоны репозитория.
    итог = проверить()
    chk("в прогонах репозитория таких кавычек нет",
        итог["findings"] == [],
        [f"{ф}:{с} {что}" for ф, с, что, _ in итог["findings"]][:5])
    chk("файлы прогонов вообще найдены", итог["files"] > 10, итог["files"])

    плохо = [(и, ф) for и, ок, ф in проверки if not ок]
    for имя, ок, факт in проверки:
        print(f"  [{'ok  ' if ок else 'СБОЙ'}] {имя}"
              + ("" if ок else f" -- факт: {факт}"))
    print(f"самопроверка кавычек в прогонах: {len(проверки) - len(плохо)}/"
          f"{len(проверки)} пройдено")
    return 1 if плохо else 0


def main() -> int:
    if "--self-test" in sys.argv:
        return self_test()
    # Каталог можно указать аргументом -- так же, как у check_shell_ascii.py:
    # прогоны зовут обе проверки одинаково.
    аргументы = [а for а in sys.argv[1:] if not а.startswith("-")]
    итог = проверить(аргументы[0] if аргументы else КАТАЛОГ)
    for файл, строка, что, текст in итог["findings"]:
        print(f"{файл}:{строка}: {что}\n    {текст}")
    if итог["findings"]:
        print(f"кавычки в прогонах: находок {len(итог['findings'])} "
               f"(файлов проверено {итог['files']})")
        return 1
    print(f"кавычки в прогонах: проверено файлов {итог['files']}, "
           "рвущих команду ssh кавычек нет")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
