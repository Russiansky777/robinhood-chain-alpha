#!/usr/bin/env python3
"""Кавычки в удалённых командах прогонов: ищем те, что рвут команду ssh.

ЗАЧЕМ. 25.09 деплой детектора упал дважды с сообщением
"sed: can't read /etc/bloom-executor/env: Permission denied" при полностью
исправном хосте: файловая система rw, файл читается, каталог пишется, флага
immutable нет. Причина оказалась в одной кавычке. В шаг деплоя был добавлен
комментарий ВНУТРИ двойных кавычек ssh:

    ssh -n $SSH_OPTS root@$HOST "
      ...
      # Решение владельца: "пул отправителей ... полосы". Значение ...
      sed -i '/^BLOOM_POOL_SEND=/d' $ENV_DIR/env
      ..."

Первая кавычка в комментарии ЗАКРЫЛА аргумент ssh, и всё, что шло дальше,
выполнилось ЛОКАЛЬНО на бегунке под пользователем ghrunner. Ему файл
/etc/bloom-executor/env (root:root, 600) читать нельзя -- отсюда Permission
denied. Ошибка тихая и злая: журнал показывает правильные команды, хост в
порядке, а правки env молча не происходят, зато часть скрипта делает не то,
что написано.

ЧТО ПРОВЕРЯЕМ. В каждом шаге run: находим строки, открывающие удалённую
команду двойной кавычкой (ssh ... "), и до её закрытия требуем, чтобы внутри не
было НЕэкранированной двойной кавычки. Считаем только кавычки: одинарные внутри
допустимы и нужны (в sed-выражениях), экранированные \\" допустимы тоже.

ВТОРОЙ РАЗ, 25.09, деплой 63. Комментарий-предупреждение о первой ошибке сам её
и повторил:

    # "sed: can't read /etc/bloom-executor/env: Permission denied" при

Кавычек здесь ДВЕ, то есть чётное число, и первая версия этой проверки считала
такую строку законной ("состояние кавычек вернулось"). Но первая кавычка
ЗАКРЫВАЕТ аргумент ssh, вторая открывает его снова, а текст между ними попадает
в ЛОКАЛЬНУЮ оболочку -- и апостроф в can't открыл там одинарную строку, которая
съела остаток скрипта. Bash сказал "syntax error near unexpected token `('" на
строке 107, за девяносто строк от настоящей причины.

Отсюда правило: внутри удалённой команды НЕ БЫВАЕТ законной вложенной двойной
кавычки. Первая же неэкранированная кавычка -- это закрытие, и законно оно
только если на строке она одна и после неё либо конец строки, либо локальный
хвост (перенаправление, || , && , скобка).

ТРЕТЬЯ БЕДА, найденная тогда же: строка echo "... ssh по петле" открывала
команду по одному слову ssh в ТЕКСТЕ, после чего проверка считала себя внутри
команды до конца файла и настоящие команды ssh ниже не проверяла вовсе
(run_vps_deploy_feed_probe_nl.yml: открытие на строке 94, реальный ssh на 138 --
непроверенный). Поэтому открытием считается только ssh в позиции команды: до
него на строке не должно быть ни кавычки, ни решётки.

Это проверка на КЛАСС ошибки, а не на один файл: стоит в тех же прогонах, что и
проверка имён переменных оболочки (check_shell_ascii.py).
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

КАТАЛОГ = ".github/workflows"

# Однострочный ssh "..." -- его баланс проверяем в этой же строке.
ОДНОЙ_СТРОКОЙ = re.compile(r'\bssh\b[^"\n]*"(?P<тело>(?:[^"\\]|\\.)*)"')


def открывает_команду(строка: str) -> bool:
    """Открывает ли строка МНОГОСТРОЧНУЮ удалённую команду ssh.

    Регулярка здесь не годится, и это проверено дважды:
      * echo "... ssh по петле" -- слово ssh в ТЕКСТЕ, команды нет;
      * printf '%s' "$KEY" | ssh $OPTS root@$H " -- команда ЕСТЬ, хотя до
        слова ssh на строке уже была кавычка.
    Поэтому читаем строку посимвольно и держим состояние кавычек: команда
    открыта, если к концу строки мы ВНУТРИ двойных кавычек и слово ssh
    встретилось ВНЕ кавычек (то есть как команда, а не как текст).
    """
    в_одинарных = в_двойных = False
    есть_ssh = False
    i = 0
    while i < len(строка):
        c = строка[i]
        if c == "\\" and not в_одинарных:
            i += 2
            continue
        if в_одинарных:
            if c == "'":
                в_одинарных = False
            i += 1
            continue
        if в_двойных:
            if c == '"':
                в_двойных = False
            i += 1
            continue
        if c == "#":
            break  # комментарий до конца строки
        if c == "'":
            в_одинарных = True
        elif c == '"':
            в_двойных = True
        elif строка.startswith("ssh", i):
            до = строка[i - 1] if i else " "
            после = строка[i + 3] if i + 3 < len(строка) else " "
            if not (до.isalnum() or до in "_-./") and not (после.isalnum()
                                                            or после in "_-"):
                есть_ssh = True
                i += 3
                continue
        i += 1
    return в_двойных and есть_ssh


def _без_экранированных(текст: str) -> str:
    """Убрать экранированные кавычки: они законны и в подсчёт не идут."""
    return re.sub(r'\\.', "", текст)


def разбор(текст: str, *, имя: str = "") -> list:
    """Список находок: (строка, что не так, сама строка)."""
    находки = []
    строки = текст.split("\n")
    внутри = False
    начало = 0
    # Строка вида "имя: значение" -- это ключ YAML (например description с
    # текстом про ssh), а не команда. Считать её открытием команды значит
    # ловить собственные описания входов: так и случилось на прогоне
    # run_vps_feed_rabbit_verify.yml.
    КЛЮЧ_YAML = re.compile(r'^\s*[A-Za-z_][\w.-]*:\s')
    # Граница шага прогона: следующий пункт списка или ключ YAML на малом
    # отступе. Если команда ssh не закрылась до границы, дальше считать себя
    # внутри неё нельзя -- иначе настоящие команды ниже не проверяются вовсе.
    ГРАНИЦА = re.compile(r'^\s{0,8}(-\s|[A-Za-z_][\w.-]*:)')
    for i, с in enumerate(строки, start=1):
        чистая = _без_экранированных(с)
        if not внутри:
            if открывает_команду(чистая) and not КЛЮЧ_YAML.match(чистая):
                внутри, начало = True, i
            continue
        if ГРАНИЦА.match(чистая) and чистая.strip():
            находки.append((начало, "команда ssh не закрыта до конца шага "
                                     f"(шаг кончается на строке {i})", ""))
            внутри = False
            continue
        # Внутри удалённой команды ПЕРВАЯ же неэкранированная двойная кавычка
        # ЗАКРЫВАЕТ аргумент ssh. Дальше по строке идёт уже ЛОКАЛЬНАЯ оболочка,
        # и вопрос один: похоже ли это на законный хвост команды
        # (перенаправление, || , && , закрывающая скобка) или на текст, который
        # попал в локальную оболочку случайно.
        #   ") || LANE_READY=""            -- законно: хвост и локальные кавычки
        #   fi" || echo "ssh не ответил")  -- законно
        #   # "sed: can't read ..." при    -- РАЗРЫВ: после кавычки текст, и
        #                                     апостроф в can't уедет локально
        # Считать кавычки нельзя: в законном хвосте их бывает и две, и четыре.
        if '"' not in чистая:
            continue
        где = чистая.index('"')
        остаток = чистая[где + 1:].strip()
        ЛОКАЛЬНЫЙ_ХВОСТ = ("", "\\", ")", ");", "|| true")
        похож_на_хвост = (остаток in ЛОКАЛЬНЫЙ_ХВОСТ
                           or остаток.startswith(("||", "&&", ">", "<", "2>", "|",
                                                  ";", ")", "}", "\\")))
        if похож_на_хвост:
            внутри = False
            # Хвост может открыть НОВУЮ удалённую команду (редко, но бывает).
            if открывает_команду(чистая[где + 1:]):
                внутри, начало = True, i
            continue
        находки.append((i, "кавычка внутри команды ssh, открытой на строке "
                            f"{начало}: она закроет команду, а текст после неё "
                            "уедет в локальную оболочку", с.strip()[:160]))
        внутри = False
    if внутри:
        находки.append((начало, "команда ssh не закрыта до конца шага", ""))
    return [(имя, *н) for н in находки]


def проверить(каталог: str = КАТАЛОГ) -> dict:
    из_ = {"files": 0, "findings": []}
    д = Path(каталог)
    if not д.exists():
        д = Path("..") / каталог
    for ф in sorted(д.glob("*.yml")):
        из_["files"] += 1
        из_["findings"] += разбор(ф.read_text(encoding="utf-8"), имя=ф.name)
    return из_


def self_test() -> int:
    проверки = []

    def chk(имя, ок, факт=""):
        проверки.append((имя, bool(ок), факт))

    # ИМЕННО ТА ОШИБКА, что уронила деплой 25.09.
    # Кавычка открывается на одной строке, закрывается на другой -- ровно как
    # в упавшем деплое: между ними перевод строки, и локальная оболочка на нём
    # команду завершает.
    плохой = '''
          ssh -n $SSH_OPTS root@$HOST "
            set -a; . /etc/bloom-executor/env; set +a
            # Решение владельца 25.09: "пул отправителей
            # шаг 1 включить сейчас; веер и пул идут параллельно".
            sed -i '/^BLOOM_POOL_SEND=/d' /etc/bloom-executor/env
            echo 'BLOOM_POOL_SEND=1' >> /etc/bloom-executor/env
          "
'''
    н = разбор(плохой)
    chk("кавычка в комментарии внутри ssh НАЙДЕНА", len(н) >= 1, н)
    chk("в находке названа строка, где команда ssh открыта",
        н and "открытой на строке" in н[0][2], н)

    # ИМЕННО ТА ОШИБКА, что уронила деплой 63: ПАРА кавычек в комментарии.
    # Число кавычек чётное, и первая версия проверки такую строку пропускала.
    пара_в_комментарии = '''
          ssh -n $SSH_OPTS root@$HOST "
            sed -i '/^BLOOM_POOL_SEND=/d' $ENV_DIR/env
            # Именно так упали прогоны 61 и 62 с
            # "sed: can't read /etc/bloom-executor/env: Permission denied" при
            # полностью исправном хосте.
            echo 'BLOOM_POOL_SEND=1' >> $ENV_DIR/env
          "
'''
    н2 = разбор(пара_в_комментарии)
    chk("ПАРА кавычек внутри ssh НАЙДЕНА (деплой 63)", len(н2) >= 1, н2)
    chk("в находке сказано про локальную оболочку",
        н2 and "локальную оболочку" in н2[0][2], н2)

    # Слово ssh в ТЕКСТЕ не открывает команду: иначе всё ниже не проверяется.
    слово_в_тексте = '''
          echo "где выполняюсь: свой раннер на NL-хосте, ssh по петле"
          ssh -n $SSH_OPTS root@$HOST "
            # Комментарий без кавычек -- законен.
            grep -c '=' $ENV_DIR/env
          "
'''
    chk("слово ssh в тексте echo не открывает команду",
        разбор(слово_в_тексте) == [], разбор(слово_в_тексте))

    # А если настоящая команда внутри такого файла разорвана, её всё равно
    # видно -- то есть охват не потерян.
    и_текст_и_разрыв = '''
          echo "свой раннер, ssh по петле"
          ssh -n $SSH_OPTS root@$HOST "
            # разрыв: "тут кавычки"
            grep -c '=' $ENV_DIR/env
          "
'''
    chk("разрыв в настоящей команде ниже текста про ssh найден",
        len(разбор(и_текст_и_разрыв)) >= 1, разбор(и_текст_и_разрыв))

    # Незакрытая команда обрывается на границе шага, а не тянется до конца
    # файла: так теряется охват проверки.
    незакрытая = '''
      - name: "Шаг с незакрытой командой"
        run: |
          ssh -n $SSH_OPTS root@$HOST "
            grep -c '=' $ENV_DIR/env

      - name: "Следующий шаг"
        run: |
          echo дальше
'''
    н3 = разбор(незакрытая)
    chk("незакрытая команда ssh найдена на границе шага",
        н3 and "не закрыта" in н3[0][2], н3)

    # Законный случай: одинарные кавычки в sed и экранированные двойные.
    хороший = '''
          ssh -n $SSH_OPTS root@$HOST "
            sed -i '/^BLOOM_POOL_SEND=/d' $ENV_DIR/env
            echo 'BLOOM_POOL_SEND=1' >> $ENV_DIR/env
            if [ -z \\"\\$TELEGRAM_BOT_TOKEN\\" ]; then echo 'нет'; fi
            printf 'рубильник: %s\\\\n' \\"\\$F\\"
          "
'''
    chk("законная удалённая команда не даёт находок", разбор(хороший) == [],
        разбор(хороший))

    # Пара кавычек внутри строки -- законно (echo "текст").
    пара = '''
          ssh -n $SSH_OPTS root@$HOST "
            echo 'строка'
            grep -c '=' $ENV_DIR/env
          "
'''
    chk("строки без кавычек и с парой одинарных проходят", разбор(пара) == [])

    # Однострочная команда ssh не должна считаться незакрытой.
    одна = '''
          ssh -n $SSH_OPTS root@$HOST "ls -l /etc/bloom-executor/env"
          echo дальше
'''
    # Законное закрытие с перенаправлением В НАЧАЛЕ строки -- так написаны
    # несколько прогонов репозитория, и находкой это быть не должно.
    с_перенаправлением = '''
          ssh -n $SSH_OPTS root@127.0.0.1 "
            set -a; . /etc/bloom-executor/env; set +a
            /home/bot/venv/bin/python module.py --dry-run
          " > data/lane_dry_run.txt 2>&1
          RC=$?
'''
    chk("закрытие с перенаправлением в начале строки -- не находка",
        разбор(с_перенаправлением) == [], разбор(с_перенаправлением))
    chk("однострочная команда ssh не считается открытой", разбор(одна) == [],
        разбор(одна))

    # И боевая проверка: все прогоны репозитория.
    итог = проверить()
    chk("в прогонах репозитория таких кавычек нет",
        итог["findings"] == [],
        [f"{ф}:{с} {что}" for ф, с, что, _ in итог["findings"]][:5])
    chk("файлы прогонов вообще найдены", итог["files"] > 10, итог["files"])

    плохо = [(и, ф) for и, ок, ф in проверки if not ок]
    for имя, ок, факт in проверки:
        print(f"  [{'ok  ' if ок else 'СБОЙ'}] {имя}"
              + ("" if ок else f" -- факт: {факт}"))
    print(f"самопроверка кавычек в прогонах: {len(проверки) - len(плохо)}/"
          f"{len(проверки)} пройдено")
    return 1 if плохо else 0


def main() -> int:
    if "--self-test" in sys.argv:
        return self_test()
    # Каталог можно указать аргументом -- так же, как у check_shell_ascii.py:
    # прогоны зовут обе проверки одинаково.
    аргументы = [а for а in sys.argv[1:] if not а.startswith("-")]
    итог = проверить(аргументы[0] if аргументы else КАТАЛОГ)
    for файл, строка, что, текст in итог["findings"]:
        print(f"{файл}:{строка}: {что}\n    {текст}")
    if итог["findings"]:
        print(f"кавычки в прогонах: находок {len(итог['findings'])} "
               f"(файлов проверено {итог['files']})")
        return 1
    print(f"кавычки в прогонах: проверено файлов {итог['files']}, "
           "рвущих команду ssh кавычек нет")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
