"""Пакет 04.10, пп. А.1--А.3: размер позиции по источнику, Келли, риск.

Только чтение. Числа -- из кэша сигналов архива (`podbivka_paket_kesh.py`), политика групп --
из живой выгрузки Code-1 `data/podbivka/code1_sources_live.json` (билет, допуск, open_max,
удержание), формула итога -- `podbivka_bilet.пп_по_состояниям` (вход S1, выход -- удержание
группы), своих копий формул нет.

А.1 Оптимальный билет. По каждому источнику с n >= 20 сигналов: итог в SOL в сутки как
    функция билета 0.05...3. Сдвиг цены НАШИМ входом учитывается сам: формула модели кладёт
    наш билет в состояние пула на входе и снимает токены с выхода, поэтому крупный билет
    штрафует себя. Ограничение `lane_open_max` группы проверяется по слотам: сигнал, который
    пришёл, когда у группы уже открыто open_max позиций (удержание группы в слотах), в счёт
    НЕ идёт -- и это считается отдельным числом. Нужный капитал = пик одновременно занятого
    капитала по архиву (не больше open_max x билет).
А.2 Келли и 1/2 Келли: доля капитала по распределению итогов сделки (численный максимум
    E[log(1 + f r)] на сетке f), и билет при капитале --kapital. Капитал файлом не
    подтверждён (в data/podbivka его нет), поэтому он ПАРАМЕТР и назван в странице.
А.3 Риск: бутстрэп по суткам (сутки берутся с возвратом) -- распределение суточного итога,
    максимальная просадка по накопленному итогу, вероятность суток хуже -2.0 SOL
    (LANE_KILL_DROP_SOL). При нынешнем билете группы и при билете А.1.

Проверка вне выборки у всего: подбор -- ранние сутки окна, проверка -- последние; плюс две
половины окна и «без двух лучших сделок».
Выход: data/podbivka/paket_bilet.json и docs/podbivka_<метка>_bilet_razmer.md.
Ничего не рекомендуется -- решает владелец.
"""
