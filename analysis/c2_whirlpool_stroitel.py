def _счета(rpc_call, адреса: list, *, таймаут: float = 3.0) -> dict:
    """getMultipleAccounts одним запросом: адрес -> сырые байты (или None)."""
    из_ = {"ok": False, "данные": {}, "why_not": None, "slot": None, "мс": None}
    т0 = time.perf_counter()
    try:
        о = rpc_call("getMultipleAccounts",
                      [адреса, {"encoding": "base64", "commitment": "confirmed"}])
    except Exception as exc:  # noqa: BLE001
        из_["why_not"] = f"{type(exc).__name__}: {str(exc)[:120]}"
        из_["мс"] = round((time.perf_counter() - т0) * 1000.0, 2)
        return из_
    из_["мс"] = round((time.perf_counter() - т0) * 1000.0, 2)
    о = о if isinstance(о, dict) else {}
    рез = о.get("result") if "result" in о else о
    if not isinstance(рез, dict):
        из_["why_not"] = f"ответ узла не разобран: {str(о)[:120]}"
        return из_
    из_["slot"] = ((рез.get("context") or {}).get("slot")
                    if isinstance(рез.get("context"), dict) else None)
    значения = рез.get("value")
    if not isinstance(значения, list) or len(значения) != len(адреса):
        из_["why_not"] = "узел вернул не столько счетов, сколько спрашивали"
        return из_
    import base64  # noqa: PLC0415

    for адрес, зн in zip(адреса, значения):
        if not зн:
            из_["данные"][адрес] = None
            continue
        д = (зн.get("data") or [None, None])[0]
        try:
            из_["данные"][адрес] = base64.b64decode(д) if д else None
        except Exception:  # noqa: BLE001
            из_["данные"][адрес] = None
    из_["ok"] = True
    return из_


def котировка(*, пул: str, минт_базы: str, минт_котировки: str, лампорты: int,
               проскальзывание: float, rpc_call, сейчас: float | None = None,
               налог_выхода=None, налог_входа=None,
               программа_выхода: str | None = None,
               программа_входа: str | None = None) -> dict:
    """Минимум выхода по Whirlpool из ЖИВОГО состояния пула, оракула и массивов.

    Возвращает тот же вид, что min_out_from_reserves: {ok, expected_out,
    min_out, ...} плюс адреса массивов и оракула (их требует сборка) и цену чтений.

    Массивов ровно три -- столько берёт и сама программа. Не хватило
    последовательности на всю сумму -- честный отказ, а не догадка: несозданный
    массив программа считает нулевым, и порт делает то же самое.
    """
    из_ = {"ok": False, "why_not": None, "чтений": 0,
            "путь": "точная котировка Whirlpool"}
    if лампорты <= 0:
        из_["why_not"] = "сумма входа не положительна"
        return из_
    # НАЛОГ СТОРОН -- ДО ЛЮБЫХ ЧТЕНИЙ, чтобы не платить за них зря.
    н = _налог_сторон(налог_выхода, налог_входа, программа_выхода, программа_входа)
    if not н["ok"]:
        из_["why_not"] = н["why_not"]
        return из_
    try:
        Q = _порт()
    except Exception as exc:  # noqa: BLE001
        из_["why_not"] = f"перенос кода Whirlpool не загружен: {type(exc).__name__}"
        return из_
    адр_оракула = Q.адрес_оракула(пул)
    из_["оракул"] = адр_оракула
    ч1 = _счета(rpc_call, [пул, адр_оракула])
    из_["чтений"] += 1
    из_["мс_чтение1"] = ч1.get("мс")
    if not ч1["ok"]:
        из_["why_not"] = f"пул не прочитан: {ч1['why_not']}"
        return из_
    данные_пула = ч1["данные"].get(пул)
    if not данные_пула:
        из_["why_not"] = "счёта пула нет на цепи"
        return из_
    try:
        pool = Q.разобрать_пул(данные_пула)
    except Exception as exc:  # noqa: BLE001
        из_["why_not"] = f"пул не разобрался: {type(exc).__name__}: {str(exc)[:120]}"
        return из_
    if pool.get("token_mint_a") == минт_котировки:
        a_to_b = True
    elif pool.get("token_mint_b") == минт_котировки:
        a_to_b = False
    else:
        из_["why_not"] = ("минт котировки не совпал ни с одной стороной пула: "
                           f"{минт_котировки[:8]} против "
                           f"{str(pool.get('token_mint_a'))[:8]}/"
                           f"{str(pool.get('token_mint_b'))[:8]}")
        return из_
    выход = pool.get("token_mint_b") if a_to_b else pool.get("token_mint_a")
    if минт_базы and выход != минт_базы:
        из_["why_not"] = (f"сторона выхода пула {str(выход)[:8]} не тот минт, "
                           f"который покупаем ({минт_базы[:8]})")
        return из_
    из_.update(a_to_b=a_to_b, tick_spacing=pool.get("tick_spacing"),
                tick_current=pool.get("tick_current_index"),
                fee_rate=pool.get("fee_rate"),
                оракул_есть=bool(ч1["данные"].get(адр_оракула)))
    try:
        старты = Q.старты_последовательности(pool, a_to_b)
    except Exception as exc:  # noqa: BLE001
        из_["why_not"] = f"последовательность массивов не выбралась: {type(exc).__name__}"
        return из_
    if not старты:
        из_["why_not"] = "последовательность массивов тиков пуста -- пул у края диапазона"
        return из_
    адреса = [Q.адрес_массива(пул, с) for с in старты]
    из_["массивы_адреса"] = list(адреса)
    из_["массивы_старты"] = list(старты)
    ч2 = _счета(rpc_call, [пул, адр_оракула] + адреса)
    из_["чтений"] += 1
    из_["мс_чтение2"] = ч2.get("мс")
    из_["мс_чтений_всего"] = round(float(из_.get("мс_чтение1") or 0.0)
                                    + float(ч2.get("мс") or 0.0), 2)
    if not ч2["ok"]:
        из_["why_not"] = f"массивы тиков не прочитаны: {ч2['why_not']}"
        return из_
    свежий = ч2["данные"].get(пул)
    if свежий:
        try:
            pool = Q.разобрать_пул(свежий)
        except Exception:  # noqa: BLE001
            pass
    # СОСТОЯНИЕ МЕЖДУ ЧТЕНИЯМИ МОГЛО УЙТИ, И ЭТО НАДО ПОЙМАТЬ ЗДЕСЬ. Массивы мы
    # выбрали по пулу ПЕРВОГО чтения, а цену считаем по пулу ВТОРОГО. Внутри порта
    # (как и в самой программе) последовательность пересчитывается по свежему
    # пулу, и массив, которого нет в переданном словаре, считается НЕСОЗДАННЫМ --
    # то есть пустым, без ликвидности. Молча это даёт завышенную цену, а на цепи
    # try_build обрывает последовательность на первом отсутствующем массиве
    # (sparse_swap.rs: `break`, дальше InvalidTickArraySequence, если пусто).
    # Поэтому сверяем старты и отказываемся, а не догадываемся.
    try:
        старты_свежие = Q.старты_последовательности(pool, a_to_b)
    except Exception as exc:  # noqa: BLE001
        из_["why_not"] = (f"последовательность по свежему пулу не посчиталась: "
                           f"{type(exc).__name__}")
        return из_
    if list(старты_свежие) != list(старты):
        из_["why_not"] = (f"состояние пула ушло между чтениями: массивы выбирали по "
                           f"{старты}, а свежий пул требует {старты_свежие} -- "
                           "считать по прочитанным значило бы принять несозданные "
                           "массивы за пустые")
        из_["старты_свежие"] = list(старты_свежие)
        return из_
    оракул = None
    д_оракула = ч2["данные"].get(адр_оракула)
    if д_оракула:
        try:
            оракул = Q.разобрать_оракул(д_оракула)
        except Exception:  # noqa: BLE001
            оракул = None
    из_["адаптивная"] = оракул is not None
    массивы = {}
    несозданные = []
    for с, адрес in zip(старты, адреса):
        д = ч2["данные"].get(адрес)
        if not д:
            # НЕСОЗДАННЫЙ МАССИВ -- НЕ ОШИБКА. Программа подставляет на его место
            # нулевой (ZeroedTickArray), и порт делает то же; адрес PDA всё равно
            # передаётся в инструкции.
            несозданные.append(с)
            continue
        try:
            массивы[с] = Q.разобрать_массив(д)
        except Exception as exc:  # noqa: BLE001
            из_["why_not"] = (f"массив тиков {с} не разобрался: "
                               f"{type(exc).__name__}: {str(exc)[:100]}")
            return из_
    из_["массивов"] = len(массивы)
    из_["массивы_несозданные"] = несозданные
    if not массивы:
        из_["why_not"] = (f"ни один массив тиков последовательности не создан: "
                           f"{несозданные} -- ликвидности по направлению нет")
        return из_
    ts = int(сейчас if сейчас is not None else time.time())
    try:
        q = Q.котировка_точный_вход(pool, массивы, оракул, int(лампорты), a_to_b, ts)
    except Exception as exc:  # noqa: BLE001
        из_["why_not"] = f"котировка не посчиталась: {type(exc).__name__}: {str(exc)[:160]}"
        return из_
    ожидаем = int(q.get("amount_out") or 0)
    if ожидаем <= 0:
        из_["why_not"] = "котировка дала ноль на выходе"
        return из_
    остаток = int(q.get("остаток_входа") or 0)
    if остаток:
        # ЭТО НАШ ОТКАЗ, А НЕ ЗАПРЕТ ПРОГРАММЫ, и разница важна. Whirlpool
        # запрещает частичное исполнение только при точном ВЫХОДЕ без предела
        # цены (swap_manager.rs: PartialFillError при !amount_specified_is_input);
        # при точном входе он спокойно возьмёт часть суммы. Но минимум выхода мы
        # считали на ВЕСЬ вход, и цепь такую сделку отвергла бы по
        # AmountOutBelowMinimum, сжёгши комиссию и приоритет. Отказываемся
        # заранее -- дешевле.
        из_["why_not"] = (f"ликвидности хватило не на весь вход: остаток {остаток} "
                           f"из {int(лампорты)}")
        из_["остаток_входа"] = остаток
        return из_
    # ПЕРЕХОД ЧЕРЕЗ ТИК -- РЕШЕНИЕ ДО МИНИМУМА. По умолчанию отказ; широкий пол --
    # только флагом и только с названным запасом.
    #
    # ЧИСЛО ОБНОВЛЕНО 30.09 по сдаче Code-2 (docs/podbivka_whirlpool_kak_vstroit.md,
    # коммит b7911200): сверка 33/33 до единицы, и переход через инициализированный
    # тик теперь подтверждён ОДНИМ свопом (прицельный сбор, 1 из 134 следующих
    # сделок; пул HNXTRVNo..., шаг тика 128, 3 динамических массива, адаптивная
    # комиссия, разница 0). Прежний комментарий говорил "не подтверждён НИ ОДНИМ
    # свопом (0 в выборке из 32)" -- это устарело, а по такому комментарию можно
    # принять решение о деньгах.
    #
    # ОТКАЗ ПО УМОЛЧАНИЮ ОСТАЁТСЯ: одного свопа мало, и сама Code-2 пишет, что
    # оговорку в шапке он не снимает. Многотиковые переходы не покрыты вовсе.
    пер = правило_перехода(q.get("тиков_пересечено"))
    из_["переход"] = пер
    if not пер["ok"]:
        из_["why_not"] = пер["why_not"]
        return из_

    # НАЛОГ ПЕРЕВОДА НА МИНТЕ ВЫХОДА. swap_v2 сравнивает other_amount_threshold с
    # суммой ПОСЛЕ налога (instructions/v2/swap.rs:
    # transfer_fee_excluded_output_amount < other_amount_threshold ->
    # AmountOutBelowMinimum), а порт отдаёт сырые единицы пула. По живому сбору у
    # 6 из 18 снимков, где модуль строит покупку, сторона базы -- Token-2022.
    сырой_выход = ожидаем
    if налог_назван(налог_выхода):
        ожидаем = без_налога(ожидаем, налог_выхода[0],
                              налог_выхода[1] if len(налог_выхода) > 1 else None)
        if ожидаем <= 0:
            из_["why_not"] = (f"налог перевода минта выхода съедает весь выход "
                               f"({сырой_выход} -> {ожидаем})")
            return из_
    доля = 1.0 - float(проскальзывание)
    if пер.get("запас"):
        доля *= (1.0 - float(пер["запас"]))
        из_["пол_расширен"] = float(пер["запас"])
    мин = int(ожидаем * доля)
    if мин <= 0:
        из_["why_not"] = "минимум выхода не положителен при этом проскальзывании"
        return из_
    # ДОЛЯ КОМИССИИ ПУЛА: НОЛЬ -- НЕ «КОМИССИИ НЕТ», А «ПОРТ НЕ ОТДАЛ fee».
    # Это замечание Code-1 с приёмки, и оно денежное: полоса проверяет потолок
    # комиссии пула по fee_share, а `if not д.get("fee_share")` у неё -- отказ.
    # Прежняя запись int(q.get("fee") or 0) превращала отсутствие поля в 0.0, и
    # тогда покупка не отказывалась, а проходила С НУЛЕВОЙ долей: потолок не
    # проверялся вовсе. Теперь отсутствие fee даёт None -- честное «не знаю», на
    # котором полоса отказывает сама.
    комиссия = (int(q["fee"]) if q.get("fee") is not None
                 else None)
    из_.update(ok=True, expected_out=ожидаем, min_out=мин, fee=комиссия,
                выход_до_налога=сырой_выход,
                налог_выхода_учтён=налог_назван(налог_выхода), точная=True,
                lp_fee=q.get("lp_fee"), protocol_fee=q.get("protocol_fee"),
                fee_share=(комиссия / float(лампорты)
                            if (комиссия is not None and лампорты) else None),
                тиков_пересечено=q.get("тиков_пересечено"),
                виды_массивов=q.get("виды_массивов"),
                fee_rate_последний=q.get("fee_rate_последний"),
                slot=ч2.get("slot"))
    return из_


