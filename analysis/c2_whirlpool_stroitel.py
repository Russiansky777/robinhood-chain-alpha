def шаблон_со_сторонами(tpl: dict, tx: dict) -> dict:
    """Шаблон с прикреплёнными минтами и программами сторон. Направление здесь не
    меняется: у Whirlpool оно живёт в данных, а не в порядке счетов."""
    с = стороны(tpl, tx)
    if not с.get("ok"):
        return {"ok": False, "why_not": с.get("why_not")}
    return {"ok": True, "стороны": с,
            "шаблон": dict(tpl, минт_a=с["минт_a"], минт_b=с["минт_b"],
                            программа_a=с["программа_a"], программа_b=с["программа_b"])}


def под_покупку(tpl: dict, tx: dict, *, минт_котировки: str = WSOL) -> dict:
    """Куда идёт наш своп: a_to_b = «платим A, получаем B».

    Счета НЕ переставляются -- у программы стоит проверка
    token_owner_account_a.mint == whirlpool.token_mint_a. Меняется только байт
    направления в данных и то, какой из наших ATA считается стороной входа.
    """
    ш = шаблон_со_сторонами(tpl, tx)
    if not ш.get("ok"):
        return {"ok": False, "why_not": ш.get("why_not")}
    с = ш["стороны"]
    if с["минт_a"] == минт_котировки:
        a_to_b = True
        минт_базы, программа_базы = с["минт_b"], с["программа_b"]
        программа_котировки = с["программа_a"]
    elif с["минт_b"] == минт_котировки:
        a_to_b = False
        минт_базы, программа_базы = с["минт_a"], с["программа_a"]
        программа_котировки = с["программа_b"]
    else:
        return {"ok": False,
                "why_not": не_та_котировка(минт_котировки, с["минт_a"], с["минт_b"])}
    return {"ok": True, "шаблон": dict(ш["шаблон"], a_to_b=a_to_b), "стороны": с,
            "a_to_b": a_to_b, "минт_базы": минт_базы, "минт_котировки": минт_котировки,
            "программа_базы": программа_базы, "программа_котировки": программа_котировки}


