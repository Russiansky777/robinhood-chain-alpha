def стороны(tpl: dict, tx: dict) -> dict:
    """Минты и программы токенов сторон A и B.

    У swap_v2 минты стоят в инструкции (5 и 6) и у каждой стороны своя программа
    токена (0 и 1). У swap (v1) минтов в инструкции нет вовсе, а программа токена
    одна и по проверке программы обязана быть SPL Token (в исходнике
    `#[account(address = token::ID)] pub token_program: Program<Token>`), поэтому
    минты берутся из БАЛАНСОВ транзакции по хранилищам пула -- это факт цепи.
    """
    из_ = {"ok": False, "why_not": None}
    import c2_common as C  # noqa: PLC0415

    р = РАСКЛАДКИ[tpl["вид"]]
    счета = tpl["accounts"]
    if р["минт_a"] is not None:
        минт_a, минт_b = счета[р["минт_a"]], счета[р["минт_b"]]
        прог_a, прог_b = счета[р["программа_a"]], счета[р["программа_b"]]
    else:
        строки = {с["account"]: с for с in C.token_rows(tx).values()}
        ха, хб = строки.get(счета[р["хранилище_a"]]), строки.get(счета[р["хранилище_b"]])
        if not ха or not хб:
            из_["why_not"] = "хранилищ пула нет в балансах транзакции"
            return из_
        минт_a, минт_b = ха.get("mint"), хб.get("mint")
        прог_a = прог_b = счета[р["программа_a"]]
    if not минт_a or not минт_b:
        из_["why_not"] = "минты сторон пула не восстановились"
        return из_
    return {"ok": True, "минт_a": минт_a, "минт_b": минт_b,
            "программа_a": прог_a or SPL_ТОКЕН, "программа_b": прог_b or SPL_ТОКЕН,
            "хранилище_a": счета[р["хранилище_a"]], "хранилище_b": счета[р["хранилище_b"]]}


