#!/usr/bin/env python3
"""Короткие строки о событиях стенда в Telegram. ТОЛЬКО тестовые источники.

Зачем отдельный модуль. Строки нужны и детектору, и сторожу, а правила у
них общие и цена ошибки одинаковая:

  * ОТПРАВКА НЕ МЕШАЕТ ТОРГОВЛЕ. Ни одно исключение отсюда наружу не
    выходит: сбой Telegram -- это запись в признак жизни, а не потерянное
    решение. Поэтому у отправителя нет ни одного raise, а вызов из горячего
    пути идёт в фоновом потоке.
  * БОЕВЫЕ ИСТОЧНИКИ МОЛЧАТ. Владелец просил строки только по стенду;
    решение о боевом источнике в Telegram не уходит вообще, чтобы поток не
    утонул в 100 решениях в час.
  * КЛЮЧИ НЕ ПЕЧАТАЮТСЯ. Всё, что уходит, проходит через вычистку.
  * ПОЛУЧАТЕЛЕЙ ДВА, И ОНИ НЕ РАВНОПРАВНЫ. Слово владельца 25.09: основной
    чат (TELEGRAM_CHAT_ID) -- покупки, продажи, круг, пары полосы, итоги
    теста, тревоги и одна сводка в час; журнал (TELEGRAM_LOG_CHAT_ID) --
    построчные решения детектора и служебные строки. Если ID журнала не
    задан, построчные решения НЕ ИДУТ НИКУДА: подмешивать их в основной чат
    нельзя, там их сто в час, и владелец перестанет читать главное.
    Ни адреса, ни токена в репозитории нет: и то и другое только из окружения.

Строки короткие намеренно: их читают с телефона в момент сделки, а не
разбирают потом. Полная картина остаётся в журнале и в докладе.
"""

from __future__ import annotations

import json
import os
import sys
import threading
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

try:
    import requests
except ImportError:  # pragma: no cover
    requests = None

API = "https://api.telegram.org"
ПРЕДЕЛ_ТЕКСТА = 3500


def включено() -> bool:
    """Строки стенда включены? Выключено -- полная тишина, без ошибок."""
    return (os.environ.get("BLOOM_TELEGRAM_LIVE_TEST", "0").strip() == "1")


def боевые_тоже() -> bool:
    """Слать ли строки по БОЕВЫМ источникам. По умолчанию нет.

    Решение владельца при переходе на live: боевые события тоже слать. Но
    включаться это должно явно: у боевых источников порядка 260 решений в
    сутки, и включить такой поток побочным следствием деплоя нельзя.
    """
    return (os.environ.get("BLOOM_TELEGRAM_REAL", "0").strip() == "1")


# Два адресата. Строка кода, а не строка для человека: по этим именам
# ветвится отправка.
КУДА_ОСНОВНОЙ = "main"
КУДА_ЖУРНАЛ = "log"
АДРЕСАТЫ = (КУДА_ОСНОВНОЙ, КУДА_ЖУРНАЛ)

# Какая переменная окружения держит чат каждого адресата.
ПЕРЕМЕННАЯ_ЧАТА = {КУДА_ОСНОВНОЙ: "TELEGRAM_CHAT_ID",
                    КУДА_ЖУРНАЛ: "TELEGRAM_LOG_CHAT_ID"}


def чат(куда: str = КУДА_ОСНОВНОЙ) -> str:
    """ID чата адресата. Пусто -- значит адресата нет.

    ЖУРНАЛ НЕ ПАДАЕТ В ОСНОВНОЙ ЧАТ. Отсутствие TELEGRAM_LOG_CHAT_ID
    означает молчание журнала, а не пересылку его строк владельцу.
    """
    имя = ПЕРЕМЕННАЯ_ЧАТА.get(куда) or ПЕРЕМЕННАЯ_ЧАТА[КУДА_ОСНОВНОЙ]
    return (os.environ.get(имя) or "").strip()


def настроен(куда: str = КУДА_ОСНОВНОЙ) -> tuple:
    токен = (os.environ.get("TELEGRAM_BOT_TOKEN") or "").strip()
    ч = чат(куда)
    if куда == КУДА_ЖУРНАЛ and токен and not ч:
        return False, ("журнал не настроен: нет TELEGRAM_LOG_CHAT_ID -- "
                        "построчные решения не идут никуда")
    if not токен or not ч:
        return False, "телеграм не настроен: нет токена или chat_id"
    return True, ""


def _секреты() -> list:
    return [v for v in (os.environ.get("TELEGRAM_BOT_TOKEN", ""),
                         os.environ.get("BLOOM_API_KEY", ""),
                         os.environ.get("HELIUS_API_KEY", ""),
                         os.environ.get("HELIUS_API", ""),
                         os.environ.get("DBOT_API_KEY", "")) if v]


def вычистить(текст: str) -> str:
    out = str(текст)
    for k in _секреты():
        if k:
            out = out.replace(k, "***")
    return out


def кратко(подпись: str | None, n: int = 10) -> str:
    s = str(подпись or "")
    return (s[:n] + "…") if len(s) > n else (s or "-")


def _время(ts: float | None = None) -> str:
    return time.strftime("%H:%M:%SZ", time.gmtime(ts if ts is not None else time.time()))


# ------------------------------------------------------------------ строки

def строка_решения(row: dict) -> str:
    """Решение детектора по тестовому источнику."""
    код = row.get("code") or row.get("action") or "?"
    лаг = row.get("slot_lag")
    путь = "MSG" if (row.get("parsed_from") or "").endswith("MSG") else (
        "RPC" if row.get("parsed_from") else "?")
    версия = row.get("tx_version")
    трата = row.get("spend_sol_eq")
    трата_s = f"{float(трата):.4f} SOL" if isinstance(трата, (int, float)) else "трата ?"
    # Кто источник -- ВИДНО В СТРОКЕ. Пока строки шли только по стенду, слово
    # "стенд" можно было писать всегда; с включением боевых источников это
    # стало ложью: владелец прочитал четыре боевых решения как стендовые.
    чей = ("стенд" if row.get("test_source")
           else f"боевой {row.get('source_task') or '?'}")
    return (f"🔎 {_время()} {чей} {код} · лаг {лаг if лаг is not None else '?'} сл · "
            f"{путь} v{версия if версия is not None else '?'} · {трата_s} · "
            f"{кратко(row.get('mint'), 6)} · src {кратко(row.get('signature'), 8)}")


def имя_источника_кратко(имя) -> str:
    """Имя источника для строки. Пусто -- "источник ?", а не молчание.

    Слово владельца 26.09 (I.5): в строке о покупке должно быть видно, ЧЬЮ
    сделку мы копировали. Без этого строка говорит, что мы купили, но не
    говорит, за кем.
    """
    и = (str(имя).strip() if имя not in (None, "") else "")
    return и[:24] if и else "источник ?"


def строка_покупки(*, exec_row: dict, наш_слот: int | None,
                    слот_источника: int | None, размер_sol, метки=None,
                    источник=None) -> str:
    """Наша покупка: подпись, S+N, куда покупали, размер, чей сигнал."""
    подписи = exec_row.get("signatures") or []
    вид = exec_row.get("buy_address_kind") or "?"
    адрес = exec_row.get("buy_address")
    куда = (f"пул {кратко(адрес, 8)}" if вид == "pool" else "минт")
    if (isinstance(наш_слот, int) and isinstance(слот_источника, int)):
            # S+N -- ТОЛЬКО по цепи: слот посадки нашей транзакции против слота
        # источника. В момент отправки слота посадки ещё нет, и писать его
        # тогда значило бы выдавать намерение за факт.
        дельта = f"S+{наш_слот - слот_источника} по цепи"
    else:
        дельта = "S+? (посадка не подтверждена)"
    размер = (f"{float(размер_sol):.4f} SOL"
              if isinstance(размер_sol, (int, float)) else "размер ?")
    хвост = (" · " + ",".join(метки)) if метки else ""
    код = exec_row.get("exec_code") or "?"
    return (f"🟢 {_время()} покупка {код} {кратко(подписи[0] if подписи else None, 10)} · "
            f"за {имя_источника_кратко(источник)} · {дельта} · по {куда} · {размер}{хвост}")


def строка_покупки_упала(*, exec_row: dict, наш_слот: int | None,
                          слот_источника: int | None, ошибка,
                          размер_sol=None, источник=None) -> str:
    """Покупка УПАЛА по цепи. Отдельная строка, а не зелёная с S+N.

    24.09 в 14:10:08Z владелец получил "🟢 покупка SENT ... S+0 по цепи",
    а транзакция в цепи упала: токена не было, продавать было нечего.
    Строка о покупке обязана отличать посадку от падения, иначе она
    докладывает намерение как факт.
    """
    подписи = exec_row.get("signatures") or [] if exec_row else []
    if isinstance(наш_слот, int) and isinstance(слот_источника, int):
        дельта = f"S+{наш_слот - слот_источника} по цепи"
    else:
        дельта = "S+? (слот неизвестен)"
    размер = (f"{float(размер_sol):.4f} SOL"
              if isinstance(размер_sol, (int, float)) else "размер ?")
    текст = (json.dumps(ошибка, ensure_ascii=False)[:120]
             if not isinstance(ошибка, str) else ошибка[:120])
    return (f"⚠️ {_время()} покупка УПАЛА · за {имя_источника_кратко(источник)} · "
            f"{текст} · {дельта} · {размер} · "
            f"{кратко(подписи[0] if подписи else None, 10)}")


def строка_продажи_не_подтверждена(*, через: str, секунды, почему: str,
                                    подпись: str | None = None) -> str:
    """Позиция закрылась, но продажа по цепи НЕ подтверждена.

    24.09 в 14:11:16Z ушла строка "🔵 продажа продана ... SOL ?" при том,
    что продажи не было вовсе: остаток токена был нулём с самого начала,
    потому что покупка упала. "SOL ?" -- это и был признак, что возврат не
    найден; значит и слова "продана" там быть не могло.
    """
    сек = (f"{float(секунды):.0f} с от покупки"
           if isinstance(секунды, (int, float)) else "время от покупки ?")
    return (f"⚠️ {_время()} продажа не подтверждена · через {через} · {сек} · "
            f"{почему} · {кратко(подпись, 10)}")


def строка_продажи(*, ok: bool, код: str | None, через: str, секунды,
                    sol_вернулось=None, подпись: str | None = None) -> str:
    """Продажа: успех или код ошибки, через что, секунды от покупки, SOL."""
    метка = "🔵" if ok else "🔴"
    итог = "продана" if ok else f"НЕ продана ({код or 'причина ?'})"
    сек = (f"{float(секунды):.0f} с от покупки"
           if isinstance(секунды, (int, float)) else "время от покупки ?")
    sol = (f"вернулось {float(sol_вернулось):+.6f} SOL"
           if isinstance(sol_вернулось, (int, float)) else "SOL ?")
    return (f"{метка} {_время()} продажа {итог} · через {через} · {сек} · {sol} · "
            f"{кратко(подпись, 10)}")


def строка_круга(*, поз: dict, секунды, sol_вернулось, подтверждена: bool,
                  через: str, слот_продажи=None) -> str:
    """ПОЛНЫЙ КРУГ одной сделки: решение -> Bloom -> блок -> продажа -> итог.

    Слово владельца: по первой живой покупке на новом коде нужна одна
    строка со всеми кругами сразу. Поля, которых нет, печатаются чертой, а
    не нулём: у сделок до замера кругов просто не было, и ноль миллисекунд
    здесь означал бы неправду.

    Места в блоке здесь нет и быть не может: его считает отдельный прогон
    по getBlock, а сторожу узел для этого не дают. Про это сказано словами,
    чтобы пустое место не читалось как "мы были первыми".
    """
    def ч(значение, единица=""):
        return "-" if значение is None else f"{значение}{единица}"

    s_plus = "-"
    if isinstance(поз.get("our_slot"), int) and isinstance(поз.get("source_slot"), int):
        s_plus = f"S+{поз['our_slot'] - поз['source_slot']}"
    сек = None if секунды is None else round(float(секунды), 1)
    итог = "по цепи подтверждена" if подтверждена else "по цепи НЕ подтверждена"
    цепь = поз.get("chain_ok")
    покупка = ("покупка села" if цепь else
                ("покупка УПАЛА" if цепь is False else "посадка покупки неизвестна"))
    return ("🔁 " + _время() + " полный круг " + кратко(поз.get("mint"), 10) + "\n"
            f"   Bloom {ч(поз.get('bloom_ms'), ' мс')}, новых соединений "
            f"{ч(поз.get('new_connections'))}\n"
            f"   наша тх в потоке: {ч(поз.get('own_tx_seen_ms'), ' мс')} от решения, "
            f"{ч(поз.get('bloom_to_seen_ms'), ' мс')} от ответа Bloom\n"
            f"   блок: {s_plus} (место в блоке -- отдельным прогоном)\n"
            f"   продажа: {ч(сек, ' с')} при плане {ч(поз.get('sell_after_s'), ' с')}, "
            f"слот {ч(слот_продажи)}, через {ч(через)}\n"
            f"   итог: {покупка}, продажа {итог}, вход {ч(поз.get('sol_in'))} SOL, "
            f"вернулось {ч(sol_вернулось)} SOL")


def строка_сводки(*, окно_мин: float, сигналов: int, покупок: int,
                   по_кодам: dict, сколько_кодов: int = 5) -> str:
    """Одна строка в час в ОСНОВНОЙ чат: что детектор решал за окно.

    Слово владельца 25.09: построчные решения уходят в журнал, а в основной
    чат -- сводка. Здесь только числа за ОКНО, а не с начала службы: "за час
    ноль покупок" и "с утра три покупки" -- разные сообщения, и путать их
    нельзя.
    """
    коды = sorted((по_кодам or {}).items(), key=lambda kv: -int(kv[1]))
    хвост = ", ".join(f"{к} {ч}" for к, ч in коды[:сколько_кодов]) or "пропусков нет"
    прочих = sum(int(ч) for _, ч in коды[сколько_кодов:])
    if прочих:
        хвост += f", прочих {прочих}"
    return (f"📊 {_время()} за {окно_мин:.0f} мин: сигналов {сигналов}, "
             f"покупок {покупок} · {хвост}")


def строка_тревоги(что: str, подробно: str = "") -> str:
    """UNSOLD, автопауза, рубильник -- отдельной строкой с пометкой."""
    хвост = f" · {подробно}" if подробно else ""
    return f"⚠️ {_время()} {что}{хвост}"


# ------------------------------------------------------------------ отправка

def код_итога(итог: dict) -> str:
    return f"код {итог.get('code')}" if итог.get("code") else "без причины"


class Оповещатель:
    """Отправитель без исключений наружу и без задержки горячего пути."""

    def __init__(self, *, отправитель=None, в_фоне: bool = True) -> None:
        # Отправитель подменяется в самопроверке: сети в ней быть не должно.
        self._отправитель = отправитель
        self._в_фоне = в_фоне
        self.послано = 0
        self.сбоев = 0
        self.последняя_ошибка = ""
        self.выключен_почему = ""
        # Счёт по адресатам: в признаке жизни видно, живы ли ОБА чата.
        # Один общий счётчик скрывал бы молчащий журнал за работающим
        # основным чатом.
        self.по_адресату = {к: {"sent": 0, "failed": 0, "last_error": ""}
                             for к in АДРЕСАТЫ}

    def _по_сети(self, текст: str, куда: str = КУДА_ОСНОВНОЙ) -> dict:
        if requests is None:
            return {"ok": False, "why_not": "requests недоступен"}
        токен = (os.environ.get("TELEGRAM_BOT_TOKEN") or "").strip()
        кому = чат(куда)
        try:
            r = requests.post(f"{API}/bot{токен}/sendMessage",
                               json={"chat_id": кому, "text": текст[:ПРЕДЕЛ_ТЕКСТА],
                                     "disable_web_page_preview": True}, timeout=10)
            if r.status_code == 200:
                return {"ok": True, "code": 200}
            return {"ok": False, "code": r.status_code,
                     "why_not": вычистить(r.text[:200])}
        except Exception as exc:  # noqa: BLE001
            return {"ok": False, "why_not": вычистить(f"{type(exc).__name__}: {exc}")}

    def _учесть(self, куда: str, итог: dict) -> None:
        строка = self.по_адресату.setdefault(
            куда, {"sent": 0, "failed": 0, "last_error": ""})
        if итог.get("ok"):
            self.послано += 1
            строка["sent"] += 1
            return
        if итог.get("skipped"):
            return
        self.сбоев += 1
        строка["failed"] += 1
        текст = str(итог.get("why_not") or код_итога(итог))[:200]
        строка["last_error"] = текст
        self.последняя_ошибка = текст

    def отправить(self, текст: str, *, куда: str = КУДА_ОСНОВНОЙ) -> dict:
        """Синхронно. Наружу не бросает НИЧЕГО -- это главное свойство.

        Адресат обязателен по смыслу, но по умолчанию основной: забытый
        параметр должен уводить строку владельцу, а не в тишину.
        """
        try:
            if not включено():
                self.выключен_почему = "строки стенда выключены (BLOOM_TELEGRAM_LIVE_TEST)"
                return {"ok": False, "skipped": True, "why_not": self.выключен_почему}
            готов, почему = настроен(куда)
            if not готов:
                # Ненастроенный ЖУРНАЛ -- это не сбой, а решение владельца:
                # ID не найден, значит построчные решения никуда не идут.
                # Считать это ошибкой значило бы завалить признак жизни.
                if куда == КУДА_ЖУРНАЛ:
                    self.выключен_почему = почему
                    return {"ok": False, "skipped": True, "why_not": почему}
                self.выключен_почему = почему
                итог = {"ok": False, "why_not": почему}
                self._учесть(куда, итог)
                return итог
            фн = self._отправитель or self._по_сети
            try:
                итог = фн(вычистить(текст), куда)
            except TypeError:
                # Старые подменные отправители принимают один довод. Ломать
                # их незачем: адресат у них один -- основной.
                итог = фн(вычистить(текст))
            self._учесть(куда, итог)
            return итог
        except Exception as exc:  # noqa: BLE001
            # Сюда попасть можно только на ошибке в самом этом коде -- и даже
            # она не имеет права остановить торговлю.
            self.сбоев += 1
            self.последняя_ошибка = вычистить(f"{type(exc).__name__}: {exc}")[:200]
            return {"ok": False, "why_not": self.последняя_ошибка}

    def послать(self, текст: str, *, куда: str = КУДА_ОСНОВНОЙ) -> dict:
        """Из горячего пути: в фоновом потоке, без ожидания ответа Telegram."""
        if not self._в_фоне:
            return self.отправить(текст, куда=куда)
        try:
            t = threading.Thread(target=self.отправить, args=(текст,),
                                  kwargs={"куда": куда}, daemon=True)
            t.start()
            return {"ok": None, "queued": True}
        except Exception as exc:  # noqa: BLE001
            self.сбоев += 1
            self.последняя_ошибка = вычистить(f"{type(exc).__name__}: {exc}")[:200]
            return {"ok": False, "why_not": self.последняя_ошибка}

    def статус(self) -> dict:
        """В признак жизни: сколько послано, сколько сбоев, последняя ошибка.

        По адресатам отдельно: молчащий журнал не должен прятаться за
        работающим основным чатом.
        """
        готов, почему = настроен(КУДА_ОСНОВНОЙ)
        готов_ж, почему_ж = настроен(КУДА_ЖУРНАЛ)
        return {"enabled": включено(), "configured": готов,
                 "sent": self.послано, "failed": self.сбоев,
                 "last_error": self.последняя_ошибка,
                 "off_reason": self.выключен_почему or почему,
                 "log_configured": готов_ж,
                 "log_off_reason": почему_ж,
                 "by_target": {к: dict(v) for к, v in self.по_адресату.items()}}


