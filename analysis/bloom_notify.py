def строка_решения(row: dict) -> str:
    """Решение детектора по тестовому источнику."""
    код = row.get("code") or row.get("action") or "?"
    лаг = row.get("slot_lag")
    путь = "MSG" if (row.get("parsed_from") or "").endswith("MSG") else (
        "RPC" if row.get("parsed_from") else "?")
    версия = row.get("tx_version")
    трата = row.get("spend_sol_eq")
    трата_s = f"{float(трата):.4f} SOL" if isinstance(трата, (int, float)) else "трата ?"
    # Кто источник -- ВИДНО В СТРОКЕ. Пока строки шли только по стенду, слово
    # "стенд" можно было писать всегда; с включением боевых источников это
    # стало ложью: владелец прочитал четыре боевых решения как стендовые.
    чей = ("стенд" if row.get("test_source")
           else f"боевой {row.get('source_task') or '?'}")
    return (f"🔎 {_время()} {чей} {код} · лаг {лаг if лаг is not None else '?'} сл · "
            f"{путь} v{версия if версия is not None else '?'} · {трата_s} · "
            f"{кратко(row.get('mint'), 6)} · src {кратко(row.get('signature'), 8)}")


def имя_источника_кратко(имя) -> str:
    """Имя источника для строки. Пусто -- "источник ?", а не молчание.

    Слово владельца 26.09 (I.5): в строке о покупке должно быть видно, ЧЬЮ
    сделку мы копировали. Без этого строка говорит, что мы купили, но не
    говорит, за кем.
    """
    и = (str(имя).strip() if имя not in (None, "") else "")
    return и[:24] if и else "источник ?"


def строка_покупки(*, exec_row: dict, наш_слот: int | None,
                    слот_источника: int | None, размер_sol, метки=None,
                    источник=None, место=None, путь=None, отправитель=None,
                    bloom=None, имя_токена=None,
                    подпись_источника=None,
                    группа=None, площадка=None, минт=None,
                    процент_к_источнику=None) -> str:
    """Наша покупка: подпись, S+N, куда покупали, размер, чей сигнал.

    В ФОРМАТЕ 2 (пакет владельца 26.09) строка собирается bloom_tg_format:
    время, размер, имя токена и ссылка на транзакцию ИСТОЧНИКА, место в его
    блоке, наше S+N с местом, разложение пути, кто довёз, сколько успело до нас
    и строка Bloom, если пара. Чего не измерено -- в строке черта, не ноль.
    """
    if формат_3():
        try:
            import bloom_tg_format3 as F3  # noqa: PLC0415
        except Exception:  # noqa: BLE001
            F3 = None
        if F3 is not None:
            м = место or {}
            s_наш = ((наш_слот - слот_источника)
                     if isinstance(наш_слот, int) and isinstance(слот_источника, int)
                     else None)
            return F3.строка_buy(
                время_utc=_время_iso(), группа=группа,
                площадка=(площадка or F3.ПЛОЩАДКА_BLOOM),
                размер_sol=размер_sol, имя=имя_токена, минт=минт,
                наш_s=s_наш, наш_индекс=м.get("наш_индекс"),
                наш_всего=(м.get("наш_всего") or м.get("всего")),
                процент_к_источнику=процент_к_источнику,
                довёз=отправитель,
                # ССЫЛКА НА НАШУ ПОКУПКУ, а не на транзакцию источника: в
                # формате 3 владелец смотрит нашу сделку, и подпись источника
                # в строке не упомянута вовсе.
                подпись=((exec_row or {}).get("signatures") or [None])[0])
    if формат_2():
        try:
            import bloom_tg_format as F  # noqa: PLC0415
        except Exception:  # noqa: BLE001
            F = None
        if F is not None:
            м = место or {}
            п_ = путь or {}
            б = bloom or {}
            s_наш = ((наш_слот - слот_источника)
                     if isinstance(наш_слот, int) and isinstance(слот_источника, int)
                     else None)
            return F.строка_buy(
                время_utc=_время_iso(), размер_sol=размер_sol,
                имя_токена=имя_токена, имя_источника=имя_источника_кратко(источник),
                подпись_источника=подпись_источника,
                индекс_источника=м.get("индекс_источника"),
                всего_в_блоке=м.get("всего"), наш_s=s_наш,
                наш_индекс=м.get("наш_индекс"),
                # НАШ БЛОК -- СВОЙ: раньше сюда шло "всего" блока ИСТОЧНИКА, и
                # при S+1 доля считалась по чужому блоку.
                наш_всего=(м.get("наш_всего") or м.get("всего")),
                путь_мс=п_.get("всего"), увидели_мс=п_.get("увидели"),
                решили_мс=п_.get("решили"), собрали_мс=п_.get("собрали"),
                отправитель=отправитель,
                перед_нами=п_.get("перед_нами"),
                копировщиков=п_.get("копировщиков"),
                bloom_s=б.get("s"), bloom_индекс=б.get("индекс"),
                bloom_всего=б.get("всего"), bloom_собрали_мс=б.get("собрали"))
    подписи = exec_row.get("signatures") or []
    вид = exec_row.get("buy_address_kind") or "?"
    адрес = exec_row.get("buy_address")
    куда = (f"пул {кратко(адрес, 8)}" if вид == "pool" else "минт")
    if (isinstance(наш_слот, int) and isinstance(слот_источника, int)):
            # S+N -- ТОЛЬКО по цепи: слот посадки нашей транзакции против слота
        # источника. В момент отправки слота посадки ещё нет, и писать его
        # тогда значило бы выдавать намерение за факт.
        дельта = f"S+{наш_слот - слот_источника} по цепи"
    else:
        дельта = "S+? (посадка не подтверждена)"
    размер = (f"{float(размер_sol):.4f} SOL"
              if isinstance(размер_sol, (int, float)) else "размер ?")
    хвост = (" · " + ",".join(метки)) if метки else ""
    код = exec_row.get("exec_code") or "?"
    return (f"🟢 {_время()} покупка {код} {кратко(подписи[0] if подписи else None, 10)} · "
            f"за {имя_источника_кратко(источник)} · {дельта} · по {куда} · {размер}{хвост}")


def строка_покупки_упала(*, exec_row: dict, наш_слот: int | None,
                          слот_источника: int | None, ошибка,
                          размер_sol=None, источник=None) -> str:
    """Покупка УПАЛА по цепи. Отдельная строка, а не зелёная с S+N.

    24.09 в 14:10:08Z владелец получил "🟢 покупка SENT ... S+0 по цепи",
    а транзакция в цепи упала: токена не было, продавать было нечего.
    Строка о покупке обязана отличать посадку от падения, иначе она
    докладывает намерение как факт.
    """
    подписи = exec_row.get("signatures") or [] if exec_row else []
    if isinstance(наш_слот, int) and isinstance(слот_источника, int):
        дельта = f"S+{наш_слот - слот_источника} по цепи"
    else:
        дельта = "S+? (слот неизвестен)"
    размер = (f"{float(размер_sol):.4f} SOL"
              if isinstance(размер_sol, (int, float)) else "размер ?")
    текст = (json.dumps(ошибка, ensure_ascii=False)[:120]
             if not isinstance(ошибка, str) else ошибка[:120])
    return (f"⚠️ {_время()} покупка УПАЛА · за {имя_источника_кратко(источник)} · "
            f"{текст} · {дельта} · {размер} · "
            f"{кратко(подписи[0] if подписи else None, 10)}")


def строка_продажи_не_подтверждена(*, через: str, секунды, почему: str,
                                    подпись: str | None = None) -> str:
    """Позиция закрылась, но продажа по цепи НЕ подтверждена.

    24.09 в 14:11:16Z ушла строка "🔵 продажа продана ... SOL ?" при том,
    что продажи не было вовсе: остаток токена был нулём с самого начала,
    потому что покупка упала. "SOL ?" -- это и был признак, что возврат не
    найден; значит и слова "продана" там быть не могло.
    """
    сек = (f"{float(секунды):.0f} с от покупки"
           if isinstance(секунды, (int, float)) else "время от покупки ?")
    return (f"⚠️ {_время()} продажа не подтверждена · через {через} · {сек} · "
            f"{почему} · {кратко(подпись, 10)}")


def строка_продажи(*, ok: bool, код: str | None, через: str, секунды,
                    sol_вернулось=None, подпись: str | None = None,
                    вход_sol=None, имя_токена=None, источник=None,
                    попыток=None, процент_чистый=None) -> str:
    """Продажа: успех или код ошибки, через что, секунды от покупки, SOL.

    В ФОРМАТЕ 2 это ЕДИНСТВЕННОЕ сообщение о выходе: "круг" отдельной строкой
    больше не идёт, а вход, возврат и доля стоят здесь.
    """
    if формат_3():
        try:
            import bloom_tg_format3 as F3  # noqa: PLC0415
        except Exception:  # noqa: BLE001
            F3 = None
        if F3 is not None:
            # ВТОРАЯ СТРОКА СДЕЛКИ, а не отдельное сообщение: вызывающий
            # обязан дописать её к сообщению покупки (Оповещатель.дописать).
            return F3.строка_sell(
                секунды=секунды, вход_sol=вход_sol, возврат_sol=sol_вернулось,
                процент=процент_чистый, подпись=подпись)
    if формат_2():
        try:
            import bloom_tg_format as F  # noqa: PLC0415
        except Exception:  # noqa: BLE001
            F = None
        if F is not None:
            return F.строка_sell(
                время_utc=_время_iso(), имя_токена=имя_токена,
                имя_источника=имя_источника_кратко(источник), секунды=секунды,
                вход_sol=вход_sol, возврат_sol=sol_вернулось,
                подпись_продажи=подпись, попыток=попыток,
                причина=(None if ok else (код or "причина не названа")))
    метка = "🔵" if ok else "🔴"
    итог = "продана" if ok else f"НЕ продана ({код or 'причина ?'})"
