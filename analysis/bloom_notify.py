class Оповещатель:
    """Отправитель без исключений наружу и без задержки горячего пути."""

    def __init__(self, *, отправитель=None, в_фоне: bool = True,
                  правщик=None) -> None:
        # Отправитель подменяется в самопроверке: сети в ней быть не должно.
        self._отправитель = отправитель
        self._правщик = правщик
        # {ключ сделки: номер сообщения} -- по нему строка правится на месте.
        self._сообщения: dict = {}
        # {ключ сделки: текст сообщения} -- нужен для формата 3, где продажа
        # ДОПИСЫВАЕТСЯ к сообщению о покупке. Без него дописать было бы нечего:
        # Telegram при правке требует ПОЛНЫЙ новый текст, а не добавку.
        self._тексты: dict = {}
        self._в_фоне = в_фоне
        self.послано = 0
        self.сбоев = 0
        self.последняя_ошибка = ""
        self.выключен_почему = ""
        # Счёт по адресатам: в признаке жизни видно, живы ли ОБА чата.
        # Один общий счётчик скрывал бы молчащий журнал за работающим
        # основным чатом.
        self.по_адресату = {к: {"sent": 0, "failed": 0, "last_error": ""}
                             for к in АДРЕСАТЫ}

    def _по_сети(self, текст: str, куда: str = КУДА_ОСНОВНОЙ) -> dict:
        if requests is None:
            return {"ok": False, "why_not": "requests недоступен"}
        токен = (os.environ.get("TELEGRAM_BOT_TOKEN") or "").strip()
        кому = чат(куда)
        try:
            тело = {"chat_id": кому, "text": текст[:ПРЕДЕЛ_ТЕКСТА],
                    "disable_web_page_preview": True}
            # РАЗМЕТКА ТОЛЬКО В ФОРМАТЕ 2: там ссылка идёт как <a href=...>tx</a>.
            # В прежнем формате разметки нет, и включать её задним числом нельзя:
            # старые строки содержат символы, на которых Telegram откажет.
            if разметка_нужна():
                тело["parse_mode"] = "HTML"
            r = requests.post(f"{API}/bot{токен}/sendMessage", json=тело, timeout=10)
            if r.status_code == 200:
                # НОМЕР СООБЩЕНИЯ нужен, чтобы потом ПРАВИТЬ эту же строку, а не
                # сыпать в чат новую на каждый шаг сделки.
                номер = None
                try:
                    номер = ((r.json() or {}).get("result") or {}).get("message_id")
                except Exception:  # noqa: BLE001
                    номер = None
                return {"ok": True, "code": 200, "message_id": номер}
            return {"ok": False, "code": r.status_code,
                     "why_not": вычистить(r.text[:200])}
        except Exception as exc:  # noqa: BLE001
            return {"ok": False, "why_not": вычистить(f"{type(exc).__name__}: {exc}")}

    def _правка_по_сети(self, номер: int, текст: str,
                         куда: str = КУДА_ОСНОВНОЙ) -> dict:
        """editMessageText: та же строка обновляется на месте."""
        if requests is None:
            return {"ok": False, "why_not": "requests недоступен"}
        токен = (os.environ.get("TELEGRAM_BOT_TOKEN") or "").strip()
        try:
            тело = {"chat_id": чат(куда), "message_id": int(номер),
                    "text": текст[:ПРЕДЕЛ_ТЕКСТА],
                    "disable_web_page_preview": True}
            if разметка_нужна():
                тело["parse_mode"] = "HTML"
            r = requests.post(f"{API}/bot{токен}/editMessageText", json=тело,
                               timeout=10)
            if r.status_code == 200:
                return {"ok": True, "code": 200, "edited": True,
                        "message_id": номер}
            return {"ok": False, "code": r.status_code,
                     "why_not": вычистить(r.text[:200])}
        except Exception as exc:  # noqa: BLE001
            return {"ok": False, "why_not": вычистить(f"{type(exc).__name__}: {exc}")}

    def _учесть(self, куда: str, итог: dict) -> None:
        строка = self.по_адресату.setdefault(
            куда, {"sent": 0, "failed": 0, "last_error": ""})
        if итог.get("ok"):
            self.послано += 1
            строка["sent"] += 1
            return
        if итог.get("skipped"):
            return
        self.сбоев += 1
        строка["failed"] += 1
        текст = str(итог.get("why_not") or код_итога(итог))[:200]
        строка["last_error"] = текст
        self.последняя_ошибка = текст

    def правка(self, ключ: str, текст: str, *,
                куда: str = КУДА_ОСНОВНОЙ) -> dict:
        """Обновить строку сделки на месте. Номера не знаем -- посылаем новую.

        Так честнее тишины: после перезапуска службы номера сообщений в памяти
        нет, и владелец всё равно должен увидеть исход сделки.
        """
        номер = (self._сообщения or {}).get(ключ)
        if not номер:
            итог = self.отправить(текст, куда=куда, ключ=ключ)
            итог["edited"] = False
            итог["fallback"] = "номер сообщения не известен -- послана новая строка"
            return итог
        try:
            фн = self._правщик or self._правка_по_сети
            итог = фн(номер, вычистить(текст), куда)
        except Exception as exc:  # noqa: BLE001
            итог = {"ok": False,
                     "why_not": вычистить(f"{type(exc).__name__}: {exc}")[:200]}
        self._учесть(куда, итог)
        return итог

    def отправить(self, текст: str, *, куда: str = КУДА_ОСНОВНОЙ,
                   ключ: str | None = None) -> dict:
        """Синхронно. Наружу не бросает НИЧЕГО -- это главное свойство.

        Адресат обязателен по смыслу, но по умолчанию основной: забытый
        параметр должен уводить строку владельцу, а не в тишину.
        """
        try:
            if not включено():
                self.выключен_почему = "строки стенда выключены (BLOOM_TELEGRAM_LIVE_TEST)"
                return {"ok": False, "skipped": True, "why_not": self.выключен_почему}
            готов, почему = настроен(куда)
            if not готов:
                # Ненастроенный ЖУРНАЛ -- это не сбой, а решение владельца:
                # ID не найден, значит построчные решения никуда не идут.
                # Считать это ошибкой значило бы завалить признак жизни.
                if куда == КУДА_ЖУРНАЛ:
                    self.выключен_почему = почему
                    return {"ok": False, "skipped": True, "why_not": почему}
                self.выключен_почему = почему
                итог = {"ok": False, "why_not": почему}
                self._учесть(куда, итог)
                return итог
            фн = self._отправитель or self._по_сети
            try:
                итог = фн(вычистить(текст), куда)
            except TypeError:
                # Старые подменные отправители принимают один довод. Ломать
                # их незачем: адресат у них один -- основной.
                итог = фн(вычистить(текст))
            self._учесть(куда, итог)
            # НОМЕР ПОД КЛЮЧОМ (cid сделки): по нему строку потом правят.
            if ключ and итог.get("message_id"):
                self._сообщения[ключ] = итог["message_id"]
                self._тексты[ключ] = текст
                # Память не растёт бесконечно: держим последние 500 сделок.
                if len(self._сообщения) > 500:
                    for к in list(self._сообщения)[:-500]:
                        self._сообщения.pop(к, None)
                        self._тексты.pop(к, None)
            return итог
        except Exception as exc:  # noqa: BLE001
            # Сюда попасть можно только на ошибке в самом этом коде -- и даже
            # она не имеет права остановить торговлю.
            self.сбоев += 1
            self.последняя_ошибка = вычистить(f"{type(exc).__name__}: {exc}")[:200]
            return {"ok": False, "why_not": self.последняя_ошибка}

    def дописать(self, ключ: str, строка: str, *,
                  куда: str = КУДА_ОСНОВНОЙ,
                  запасной_полный: str | None = None) -> dict:
        """Дописать СТРОКУ к сообщению сделки. Формат 3: одно сообщение на сделку.

        Telegram при правке требует полный новый текст, поэтому прежний текст
        помнится здесь. Не помним (перезапуск службы между покупкой и
        продажей) -- посылаем строку отдельным сообщением и говорим об этом в
        ответе: тишина была бы хуже, владелец всё равно должен увидеть исход.

        Одна и та же строка дважды не дописывается: продажу подтверждают из
        двух мест (сторож и догонялка), и без этой проверки вторая правка
        добавила бы к сделке ту же строку второй раз.
        """
        прежний = (self._тексты or {}).get(ключ)
        if not прежний:
            # ПОЛНАЯ СТРОКА ВМЕСТО ПОЛОВИНЫ. Слово владельца 27.09 (вечер, п.3):
            # "если сообщение покупки не найдено -- послать полную строку
            # покупки + продажи одним сообщением". Одна строка продажи без
            # покупки в чате не говорит, ЧТО продано и за кем мы шли.
            текст = запасной_полный or строка
            итог = self.отправить(текст, куда=куда, ключ=ключ)
            итог["appended"] = False
            итог["fallback"] = (
                "текста сделки в памяти нет -- послана полная строка покупки и "
                "продажи одним сообщением" if запасной_полный else
                "текста сделки в памяти нет -- строка послана отдельным сообщением")
            return итог
        if строка.strip() and строка.strip() in прежний:
            return {"ok": True, "appended": False, "skipped": True,
                     "why_not": "такая строка в сообщении сделки уже есть"}
        новый = прежний + "\n" + строка
        итог = self.правка(ключ, новый, куда=куда)
        if итог.get("ok"):
            self._тексты[ключ] = новый
            итог["appended"] = True
        return итог

    def послать(self, текст: str, *, куда: str = КУДА_ОСНОВНОЙ,
                 ключ: str | None = None) -> dict:
        """Из горячего пути: в фоновом потоке, без ожидания ответа Telegram."""
        if not self._в_фоне:
            return self.отправить(текст, куда=куда, ключ=ключ)
        try:
            t = threading.Thread(target=self.отправить, args=(текст,),
                                  kwargs={"куда": куда, "ключ": ключ}, daemon=True)
            t.start()
            return {"ok": None, "queued": True}
        except Exception as exc:  # noqa: BLE001
            self.сбоев += 1
            self.последняя_ошибка = вычистить(f"{type(exc).__name__}: {exc}")[:200]
            return {"ok": False, "why_not": self.последняя_ошибка}

    def статус(self) -> dict:
        """В признак жизни: сколько послано, сколько сбоев, последняя ошибка.

        По адресатам отдельно: молчащий журнал не должен прятаться за
        работающим основным чатом.
        """
        готов, почему = настроен(КУДА_ОСНОВНОЙ)
        готов_ж, почему_ж = настроен(КУДА_ЖУРНАЛ)
        return {"enabled": включено(), "configured": готов,
                 "format2": формат_2(), "format3": формат_3(),
                 "tracked_messages": len(self._сообщения),
                 "tracked_texts": len(self._тексты),
                 "sent": self.послано, "failed": self.сбоев,
                 "last_error": self.последняя_ошибка,
                 "off_reason": self.выключен_почему or почему,
                 "log_configured": готов_ж,
                 "log_off_reason": почему_ж,
                 "by_target": {к: dict(v) for к, v in self.по_адресату.items()}}


