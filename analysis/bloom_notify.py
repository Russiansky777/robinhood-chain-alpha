def формат_3() -> bool:
    """Формат 3 -- пакет владельца 27.09: ОДНО сообщение на сделку.

    Отдельным флагом, а не заменой формата 2: переключение формата это то, что
    владелец видит в чате, и включаться он должен осознанно, одной строкой
    окружения BLOOM_TG_FORMAT=3.
    """
    return (os.environ.get("BLOOM_TG_FORMAT") or "").strip() == "3"


def разметка_нужна() -> bool:
    """В каких форматах в сообщении есть HTML. В прежнем формате её нет и
    включать задним числом нельзя: там символы, на которых Telegram откажет."""
    return формат_2() or формат_3()


def формат_2() -> bool:
    """Формат владельца (пакет 26.09): BUY с правкой, SELL, часовая сводка,
    тревоги ВМЕСТО строки круга. По умолчанию выключен: без флага строки идут
    как сейчас, и ночной деплой ничего не меняет молча."""
    return (os.environ.get("BLOOM_TG_FORMAT") or "").strip() == "2"


def включено() -> bool:
    """Строки стенда включены? Выключено -- полная тишина, без ошибок."""
    return (os.environ.get("BLOOM_TELEGRAM_LIVE_TEST", "0").strip() == "1")


def боевые_тоже() -> bool:
    """Слать ли строки по БОЕВЫМ источникам. По умолчанию нет.

    Решение владельца при переходе на live: боевые события тоже слать. Но
    включаться это должно явно: у боевых источников порядка 260 решений в
    сутки, и включить такой поток побочным следствием деплоя нельзя.

    НЕ ЗОВЁТСЯ НИ ОДНИМ ЖИВЫМ ПУТЁМ, и подключать её НЕ НАДО. Проверено
    поиском по всему репозиторию 10.10: единственные вхождения -- эта
    функция, самопроверка этого модуля и список затираемых переменных в
    selftest_guard. Строку сделки посылают доложить_покупку/доложить_продажу
    без оглядки на боевой режим, поэтому «подключить флаг как задумано»
    означало бы ПОГАСИТЬ строки по боевым группам -- то есть сломать то, что
    владелец просил по vol_4vw. Если когда-нибудь поток основного чата
    придётся резать, резать надо по ВИДУ строки (построчные решения уже
    уходят в журнальный чат), а не по боевому признаку источника.
    """
    return (os.environ.get("BLOOM_TELEGRAM_REAL", "0").strip() == "1")


# Два адресата. Строка кода, а не строка для человека: по этим именам
# ветвится отправка.
КУДА_ОСНОВНОЙ = "main"
КУДА_ЖУРНАЛ = "log"
АДРЕСАТЫ = (КУДА_ОСНОВНОЙ, КУДА_ЖУРНАЛ)

# Какая переменная окружения держит чат каждого адресата.
ПЕРЕМЕННАЯ_ЧАТА = {КУДА_ОСНОВНОЙ: "TELEGRAM_CHAT_ID",
                    КУДА_ЖУРНАЛ: "TELEGRAM_LOG_CHAT_ID"}


def чат(куда: str = КУДА_ОСНОВНОЙ) -> str:
    """ID чата адресата. Пусто -- значит адресата нет.

    ЖУРНАЛ НЕ ПАДАЕТ В ОСНОВНОЙ ЧАТ. Отсутствие TELEGRAM_LOG_CHAT_ID
    означает молчание журнала, а не пересылку его строк владельцу.
    """
    имя = ПЕРЕМЕННАЯ_ЧАТА.get(куда) or ПЕРЕМЕННАЯ_ЧАТА[КУДА_ОСНОВНОЙ]
    return (os.environ.get(имя) or "").strip()


def настроен(куда: str = КУДА_ОСНОВНОЙ) -> tuple:
    токен = (os.environ.get("TELEGRAM_BOT_TOKEN") or "").strip()
    ч = чат(куда)
    if куда == КУДА_ЖУРНАЛ and токен and not ч:
        return False, ("журнал не настроен: нет TELEGRAM_LOG_CHAT_ID -- "
                        "построчные решения не идут никуда")
    if not токен or not ч:
        return False, "телеграм не настроен: нет токена или chat_id"
    return True, ""


def _секреты() -> list:
    return [v for v in (os.environ.get("TELEGRAM_BOT_TOKEN", ""),
                         os.environ.get("BLOOM_API_KEY", ""),
                         os.environ.get("HELIUS_API_KEY", ""),
                         os.environ.get("HELIUS_API", ""),
                         os.environ.get("DBOT_API_KEY", "")) if v]


def вычистить(текст: str) -> str:
    out = str(текст)
    for k in _секреты():
        if k:
            out = out.replace(k, "***")
    return out


def кратко(подпись: str | None, n: int = 10) -> str:
    s = str(подпись or "")
    return (s[:n] + "…") if len(s) > n else (s or "-")


def _время_iso(ts: float | None = None) -> str:
    """ISO-время для формата 2: из него берутся часы, минуты и секунды."""
    return time.strftime("%Y-%m-%dT%H:%M:%SZ",
                         time.gmtime(ts if ts is not None else time.time()))


def _время(ts: float | None = None) -> str:
    """Время строки Telegram ПО МАДРИДУ -- слово владельца 02.10 про UNSOLD.

    Отсюда берут время ⚠️ UNSOLD, ⚠️ «покупка УПАЛА» и остальные строки этого
    модуля. Зона считается ОДНИМ написанием с 📋 и с форматом 3: владелец читает
    один чат, и две зоны в нём читались бы как разница в час-два там, где её нет.
    Базы зон на хосте нет -- остаётся UTC С СУФФИКСОМ Z, а не Мадрид наугад.

    _время_iso НЕ меняется и остаётся в Z: это метка ДЛЯ ЗАПИСИ, её читает
    сверка, и сдвиг зоны сломал бы сшивку по времени.
    """
    т = ts if ts is not None else time.time()
    try:
        import c2_doklad_format as _CF  # noqa: PLC0415

        с = _CF.чч_мм_сс(т)
        if с:
            return с
    except Exception:  # noqa: BLE001
        pass
    return time.strftime("%H:%M:%SZ", time.gmtime(т))


