#!/usr/bin/env python3
"""Разбор 29 ненулевых позиций на три группы: не трогать / продавать / пыль.

Группы, как их задал владелец:
  (а) позиции, которые в учёте СЕЙЧАС открыты на BATCH-5 или BATCH-3 --
      их не трогать: задачи продолжают работать;
  (б) всё с оценкой выше порога (по умолчанию 0.02 SOL) -- продавать;
  (в) остальное -- пыль.

Открытой в учёте считается запись с покупкой и без продажи И со статусом
"незакрыта": запись со статусом "срыв" -- это несостоявшаяся покупка, там
токена на кошельке нет вообще, и считать её открытой позицией нельзя.

Сети не требует: работает по инвентаризации и по учёту.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
INV_PATH = REPO_ROOT / "data" / "solana_wallet_inventory.json"
TRADES_PATH = REPO_ROOT / "data" / "solana_trades_all.json"
OUT_PATH = REPO_ROOT / "data" / "solana_position_triage.json"

ПОРОГ_SOL = 0.02
ЗАЩИЩЁННЫЕ = ("BATCH-5", "BATCH-3")

# Остаток МЕНЬШЕ этого числа сырых единиц -- это крошка, и оценивать её
# умножением цены на количество нельзя. Проверено на живых данных: у NBIS
# осталось 149 сырых единиц, у LLY -- 2, а цена последней сделки выходила
# 3 279 и 222 007 SOL за токен. Умножение давало 0.489 и 0.444 SOL, то
# есть по полсоля на двух сырых единицах. Настоящие бумаги стоят порядка
# сотни долларов за штуку, так что это не цена, а артефакт: в той
# транзакции кошелёк получил крошку, а нога в SOL была от другой сделки.
МИН_СЫРЫХ_ЕДИНИЦ = 1000


def открытые_в_учёте(trades: list) -> dict:
    """{(кошелёк, минт): [записи]} -- только настоящие открытые позиции."""
    out: dict = {}
    for t in trades:
        if not t.get("buy_signature") or t.get("sell_signature"):
            continue
        if t.get("status") != "незакрыта":
            continue        # "срыв" -- покупки не было, позиции нет
        out.setdefault((t.get("wallet"), t.get("mint")), []).append(t)
    return out


def оценка_достоверна(поз: dict, мин_сырых: int = МИН_СЫРЫХ_ЕДИНИЦ) -> tuple[bool, str | None]:
    """Можно ли верить оценке позиции.

    Оценка = цена последней сделки x количество. На крошке это
    произведение врёт: цена берётся из транзакции, где движение в SOL
    относилось не к этой крошке.
    """
    сырое = поз.get("сырое_количество")
    try:
        сырое = int(сырое) if сырое is not None else None
    except (TypeError, ValueError):
        сырое = None
    if сырое is not None and сырое < мин_сырых:
        return False, (f"остаток {сырое} сырых единиц -- меньше порога {мин_сырых}: "
                        "оценка умножением цены на такое количество недостоверна")
    return True, None


def группа(поз: dict, защищена: bool, порог: float) -> str:
    if защищена:
        return "а: открыта в учёте на работающей задаче -- не трогать"
    if not поз.get("оценка_достоверна", True):
        return "в: пыль"
    if (поз.get("оценка_sol") or 0.0) > порог:
        return "б: дороже порога -- продавать"
    return "в: пыль"


def разбор(inv: dict, trades: list, порог: float = ПОРОГ_SOL,
            защищённые=ЗАЩИЩЁННЫЕ) -> dict:
    откр = открытые_в_учёте(trades)
    строки = []
    for имя, w in (inv.get("кошельки") or {}).items():
        адрес = w.get("адрес")
        for p in (w.get("позиции") or []):
            оц = p.get("оценка") or {}
            защищена = (имя in защищённые) and ((адрес, p.get("минт")) in откр)
            строки.append({
                "задача": имя, "кошелёк": адрес, "минт": p.get("минт"),
                "символ": p.get("символ"), "количество": p.get("количество"),
                "стандарт": p.get("программа_токена"),
                "налог_на_перевод_bps": p.get("ставка_комиссии_bps"),
                "есть_налог": bool(p.get("ставка_комиссии_bps")),
                "сырое_количество": p.get("сырое_количество"),
                "десятичных": p.get("десятичных"),
                "оценка_sol": p.get("оценка_sol"),
                "цена_sol_за_токен": оц.get("цена_sol_за_токен"),
                "оценка_по_сделке": оц.get("подпись"),
                "оценка_по_времени_utc": оц.get("время_utc"),
                "почему_нет_оценки": (None if p.get("оценка_sol") else оц.get("почему")),
                "открыта_в_учёте": (адрес, p.get("минт")) in откр,
                "счёт": p.get("счёт"),
                "лампорты_счёта": p.get("лампорты_счёта"),
            })
            дост, почему = оценка_достоверна(строки[-1])
            строки[-1]["оценка_достоверна"] = дост
            строки[-1]["почему_оценка_недостоверна"] = почему
            строки[-1]["группа"] = группа(строки[-1], защищена, порог)
    по_группам: dict = {}
    for r in строки:
        g = по_группам.setdefault(r["группа"], {"позиций": 0, "оценка_sol": 0.0,
                                                 "без_оценки": 0, "задачи": set()})
        g["позиций"] += 1
        g["задачи"].add(r["задача"])
        if r["оценка_sol"] and r.get("оценка_достоверна", True):
            g["оценка_sol"] += r["оценка_sol"]
        else:
            g["без_оценки"] += 1
        if not r.get("оценка_достоверна", True):
            g["недостоверных_оценок"] = g.get("недостоверных_оценок", 0) + 1
    for g in по_группам.values():
        g["оценка_sol"] = round(g["оценка_sol"], 9)
        g["задачи"] = sorted(g["задачи"])
    return {"порог_sol": порог, "защищённые_задачи": list(защищённые),
             "позиций": len(строки), "по_группам": по_группам, "позиции": строки}


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--порог", type=float, default=ПОРОГ_SOL)
    ap.add_argument("--self-test", action="store_true")
    args = ap.parse_args()
    if args.self_test:
        self_test()
        return
    if not INV_PATH.exists():
        raise SystemExit(f"нет {INV_PATH}")
    inv = json.loads(INV_PATH.read_text())
    trades = json.loads(TRADES_PATH.read_text()) if TRADES_PATH.exists() else []
    out = разбор(inv, trades, args.порог)
    out["источники"] = [str(INV_PATH.relative_to(REPO_ROOT)),
                         str(TRADES_PATH.relative_to(REPO_ROOT))]
    out["ЧЕСТНЫЕ_ОГОВОРКИ"] = [
        "Оценка -- по цене НАШЕЙ последней сделки по токену, а не по текущей "
        "цене пула: для зависшей позиции это верхняя граница.",
        "Позиция без оценки не считается нулевой -- она считается неоценённой "
        "и попадает в пыль только потому, что доказать её ценность нечем.",
        "Открытой в учёте считается только запись со статусом 'незакрыта'; "
        "запись со статусом 'срыв' -- несостоявшаяся покупка, позиции нет.",
        f"Остаток меньше {МИН_СЫРЫХ_ЕДИНИЦ} сырых единиц оценке не подлежит: "
        "произведение цены на крошку даёт правдоподобное с виду число, которое "
        "ничего не значит. Такие позиции уходят в пыль с указанием причины.",
    ]
    OUT_PATH.write_text(json.dumps(out, ensure_ascii=False, indent=2))
    print(json.dumps({k: v for k, v in out.items() if k != "позиции"},
                      ensure_ascii=False, indent=2))
    print(f"\nвыгрузка -> {OUT_PATH}")


def self_test() -> None:
    checks = []

    def chk(n, ok, got=""):
        checks.append((n, bool(ok), got))

    trades = [
        {"wallet": "W5", "mint": "M_OPEN", "buy_signature": "b", "sell_signature": None,
         "status": "незакрыта"},
        {"wallet": "W5", "mint": "M_FAIL", "buy_signature": "b", "sell_signature": None,
         "status": "срыв"},
        {"wallet": "W9", "mint": "M_OPEN9", "buy_signature": "b", "sell_signature": None,
         "status": "незакрыта"},
    ]
    откр = открытые_в_учёте(trades)
    chk("открытая позиция найдена", ("W5", "M_OPEN") in откр)
    chk("срыв открытой позицией не считается", ("W5", "M_FAIL") not in откр)

    inv = {"кошельки": {
        "BATCH-5": {"адрес": "W5", "позиции": [
            {"минт": "M_OPEN", "символ": "A", "количество": 1.0, "оценка_sol": 5.0,
             "программа_токена": "Token-2022", "ставка_комиссии_bps": 300,
             "оценка": {"подпись": "s1", "время_utc": "t"}},
            {"минт": "M_FAIL", "символ": "B", "количество": 2.0, "оценка_sol": 0.5,
             "программа_токена": "SPL Token (классический)", "ставка_комиссии_bps": None,
             "оценка": {"подпись": "s2"}},
        ]},
        "BATCH-9": {"адрес": "W9", "позиции": [
            {"минт": "M_OPEN9", "символ": "C", "количество": 3.0, "оценка_sol": 1.0,
             "программа_токена": "Token-2022", "ставка_комиссии_bps": None,
             "оценка": {"подпись": "s3"}},
            {"минт": "M_DUST", "символ": None, "количество": 4.0, "оценка_sol": None,
             "программа_токена": "SPL Token (классический)", "ставка_комиссии_bps": None,
             "оценка": {"почему": "в этой транзакции цена не выводится"}},
        ]},
    }}
    r = разбор(inv, trades, порог=0.02, защищённые=("BATCH-5", "BATCH-3"))
    по = {x["минт"]: x["группа"] for x in r["позиции"]}
    chk("открытая на защищённой задаче -- группа а", по["M_OPEN"].startswith("а"))
    chk("сорвавшаяся на защищённой задаче защитой НЕ накрывается",
        по["M_FAIL"].startswith("б"), по["M_FAIL"])
    chk("открытая на НЕзащищённой задаче защитой не накрывается",
        по["M_OPEN9"].startswith("б"), по["M_OPEN9"])
    chk("без оценки -- пыль", по["M_DUST"].startswith("в"))
    chk("налог отмечен там, где он есть",
        [x["есть_налог"] for x in r["позиции"] if x["минт"] == "M_OPEN"] == [True])
    chk("и не отмечен там, где его нет",
        [x["есть_налог"] for x in r["позиции"] if x["минт"] == "M_FAIL"] == [False])
    inv2 = {"кошельки": {"T": {"адрес": "W", "позиции": [
        {"минт": "CRUMB", "символ": "NBIS", "количество": 0.000149,
         "сырое_количество": "149", "десятичных": 6, "оценка_sol": 0.4885,
         "программа_токена": "Token-2022",
         "оценка": {"цена_sol_за_токен": 3278.67, "подпись": "s"}},
        {"минт": "REAL", "символ": "R", "количество": 2.29,
         "сырое_количество": "2288948160", "десятичных": 9, "оценка_sol": 0.0221,
         "программа_токена": "SPL Token", "оценка": {"цена_sol_за_токен": 0.0097}},
    ]}}}
    r2 = разбор(inv2, [], порог=0.02)
    по2 = {x["минт"]: x for x in r2["позиции"]}
    chk("крошка с абсурдной ценой уходит в пыль, а не в продажу",
        по2["CRUMB"]["группа"].startswith("в"), по2["CRUMB"]["группа"])
    chk("и причина названа",
        "сырых единиц" in (по2["CRUMB"]["почему_оценка_недостоверна"] or ""))
    chk("нормальный остаток остаётся достоверным",
        по2["REAL"]["оценка_достоверна"] is True)
    chk("недостоверная оценка в сумму группы не идёт",
        abs(r2["по_группам"]["в: пыль"]["оценка_sol"]) < 1e-12,
        str(r2["по_группам"]["в: пыль"]))

    g = r["по_группам"]
    chk("сумма по группе б считается",
        abs(g["б: дороже порога -- продавать"]["оценка_sol"] - 1.5) < 1e-9, str(g))
    chk("позиции без оценки посчитаны отдельно",
        g["в: пыль"]["без_оценки"] == 1)
    chk("порог соблюдается: 0.02 ровно -- это ещё пыль",
        разбор({"кошельки": {"T": {"адрес": "W", "позиции": [
            {"минт": "X", "оценка_sol": 0.02, "количество": 1,
             "программа_токена": "SPL", "оценка": {}}]}}}, [],
               порог=0.02)["позиции"][0]["группа"].startswith("в"))

    bad = 0
    for n, ok, got in checks:
        print(f"  [{'ok  ' if ok else 'СБОЙ'}] {n}" + (f"  -> {got}" if got and not ok else ""))
        bad += (not ok)
    print(f"самопроверка разбора позиций: {len(checks) - bad}/{len(checks)} пройдено")
    if bad:
        raise SystemExit(f"самопроверка не пройдена: {bad} из {len(checks)}")


if __name__ == "__main__":
    main()
