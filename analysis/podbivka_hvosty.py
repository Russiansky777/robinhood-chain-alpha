def п4() -> list:
    рр = лидер_р2(только_gor=True)
    ТЧ = (6, 12, 24, 36, 72, 150, 300)
    md = ["## п.4 Лидер: хвост на столе (нижняя граница)", "",
          f"Покупок с рядом точек выхода (прогон горизонтов gor_*): {len(рр)}. Цены на каждом свопе в окне не "
          "сохранялись и точек +600 / +1800 нет -- вместо максимума цены берётся лучший из выходов в точках "
          f"{', '.join('+' + str(t) for t in ТЧ)} (п.п. чистыми, потолок, 0.5 SOL). Это нижняя граница максимума.", "",
          "| вход | окно | лучший выход в окне: n | ср | медиана | p95 | макс | против таймера +36: ср разницы | против +150: ср разницы |",
          "|---|---|---|---|---|---|---|---|---|"]
    for e, имя in ВХОДЫ_Л:
        for W in (36, 150, 300):
            лучшие, р36, р150 = [], [], []
            for р in рр:
                т = [вх(р, e, t) for t in ТЧ if t <= W and вх(р, e, t) is not None]
                if not т:
                    continue
                м = max(т)
                лучшие.append(м)
                if вх(р, e, 36) is not None:
                    р36.append(м - вх(р, e, 36))
                if вх(р, e, 150) is not None:
                    р150.append(м - вх(р, e, 150))
            с = стат(лучшие)
            md.append(f"| {имя} | до +{W} | {с['n']} | {с['ср']:+.1f} | {с['мед']:+.1f} | {с['p95']:+.1f} | {с['макс']:+.1f} | "
                      f"{sum(р36) / len(р36):+.1f} | {sum(р150) / len(р150):+.1f} |")
        md.append(f"| {имя} | до +600 / +1800 | не считалось | | | | | | |")
    md += ["", "Доля сделок, где стоимость позиции на +300 в 2 раза и больше выше, чем на выходе (+36 / +150) -- "
           "одна точка после +150, нижняя граница доли «максимум после +150 ≥ 2× выхода»:", "",
           "| вход | против +36 | против +150 |", "|---|---|---|"]
    for e, имя in ВХОДЫ_Л:
        яч = []
        for Hв in (36, 150):
            пары = [(вх(р, e, Hв), вх(р, e, 300)) for р in рр if вх(р, e, Hв) is not None and вх(р, e, 300) is not None]
            k = sum(1 for a, b in пары if (100 + b) >= 2 * (100 + a))
            яч.append(f"{k} из {len(пары)} ({100 * k / len(пары):.0f}%)" if пары else "—")
        md.append(f"| {имя} | {яч[0]} | {яч[1]} |")
    return md + [""]


