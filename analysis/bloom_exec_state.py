    def db(self) -> sqlite3.Connection:
        """Соединение SQLite -- СВОЁ НА КАЖДЫЙ ПОТОК.

        Цена ошибки измерена: детектор разбирает сообщения подписки в
        asyncio.to_thread, то есть в разных рабочих потоках. Одно общее
        соединение приводило к sqlite3.ProgrammingError "objects created in
        a thread can only be used in that same thread" -- и это исключение
        не просто теряло решение, а рвало подписку целиком. Ровно так 24.09
        в 01:51:17 пропал сигнал п. 3 (покупка RED): решения в журнале нет,
        покупки нет, строки в Telegram нет.

        Одно соединение на поток безопасно: база в режиме WAL, а записи
        короткие и с commit сразу.
        """
        conn = getattr(self._потоковое, "db", None)
        if conn is None:
            conn = sqlite3.connect(str(self.db_path), timeout=30)
            # РЕЖИМ WAL СТАВИТСЯ ОДИН РАЗ НА ФАЙЛ и в файле остаётся. Перевод
            # режима требует момента без чужой записи, и timeout соединения на
            # него не распространяется: восемь потоков, поднимающих соединения
            # разом, получали "database is locked" ровно на этой строке --
            # самопроверка так упала на облачном бегунке 25.09 в 16:46Z.
            # Поэтому режим сперва читается, ставится только при расхождении и
            # с короткими повторами. Тихо работать без WAL нельзя: он и есть
            # причина, по которой соединение на поток безопасно.
            try:
                режим = (conn.execute("PRAGMA journal_mode").fetchone() or [""])[0]
            except sqlite3.Error:
                режим = ""
            if str(режим).lower() != "wal":
                for попытка in range(6):
                    try:
                        conn.execute("PRAGMA journal_mode=WAL")
                        break
                    except sqlite3.OperationalError:
                        if попытка == 5:
                            raise
                        time.sleep(0.05 * (попытка + 1))
            conn.execute("PRAGMA synchronous=FULL")
            conn.execute("CREATE TABLE IF NOT EXISTS seen "
                          "(sig TEXT PRIMARY KEY, ts REAL, source TEXT)")
            conn.execute("CREATE TABLE IF NOT EXISTS mint_last "
                          "(mint TEXT PRIMARY KEY, ts REAL, buys INTEGER)")
            # ПОКУПКИ САМИХ ИСТОЧНИКОВ по паре "источник + минт". Нужны, чтобы
            # отличить ДОКУПКУ от нового сигнала: слово владельца 27.09
            # (вечер) -- "докупка = тот же источник и тот же минт в пределах
            # 1800 слотов от его предыдущей покупки; позже -- новый сигнал".
            conn.execute("CREATE TABLE IF NOT EXISTS source_buys "
                          "(key TEXT PRIMARY KEY, slot INTEGER, ts REAL, sig TEXT)")
            # НАШИ ПОКУПКИ ПО ПАРЕ "ГРУППА + МИНТ". Отдельная таблица, а не
            # поле в source_buys: там счёт покупок ИСТОЧНИКОВ, и мешать с ним
            # наши покупки значило бы переписать смысл старого дедупа.
            conn.execute("CREATE TABLE IF NOT EXISTS group_mints "
                          "(key TEXT PRIMARY KEY, grp TEXT, mint TEXT, "
                          "slot INTEGER, ts REAL, sig TEXT)")
            conn.commit()
            self._потоковое.db = conn
            self._db = conn        # для совместимости со старым полем
        return conn

    def seen_signature(self, sig: str) -> bool:
        row = self.db().execute("SELECT ts FROM seen WHERE sig=?", (sig,)).fetchone()
        if not row:
            return False
        return (time.time() - float(row[0])) <= self.seen_ttl_s

    def mark_signature(self, sig: str, source: str = "") -> None:
        self.db().execute("INSERT OR REPLACE INTO seen(sig, ts, source) VALUES(?,?,?)",
                           (sig, time.time(), source))
        self.db().commit()

    @staticmethod
    def ключ_пары(mint: str, source: str | None) -> str:
        """Ключ счёта покупок: ПАРА "источник + минт", а не минт.

        Слово владельца 27.09 (вечер): "Лимит покупок на токен -- по паре
        «источник + минт», не по минту: первые покупки разных источников в один
        токен копируются каждая". Разделитель "|" в адресе base58 и в минте не
        встречается, поэтому ключ пары не может совпасть с ключом минта, и
        старые записи по минту остаются читаемыми как есть.
        """
        return f"{source}|{mint}" if source else mint

    def source_buy_state(self, source: str | None,
                          mint: str) -> tuple[int | None, float | None]:
        """(слот, время) ПРЕДЫДУЩЕЙ покупки этой пары САМИМ источником."""
        слот, вр, _ = self._source_buy_row(source, mint)
        return слот, вр

    def _source_buy_row(self, source: str | None, mint: str):
        """(слот, время, подпись) запомненной покупки пары."""
        row = self.db().execute(
            "SELECT slot, ts, sig FROM source_buys WHERE key=?",
            (self.ключ_пары(mint, source),)).fetchone()
        if not row:
            return None, None, None
        слот = int(row[0]) if row[0] is not None else None
        вр = float(row[1]) if row[1] is not None else None
        return слот, вр, (row[2] or None)

    def mark_source_buy(self, source: str | None, mint: str,
                         slot: int | None = None,
                         now: float | None = None,
                         sig: str | None = None) -> None:
        """Запомнить покупку ИСТОЧНИКА. Пишется на КАЖДЫЙ покупочный сигнал,
        купили мы по нему или нет: окно докупки считается от покупок источника,
        а не от наших."""
        if not mint:
            return
        self.db().execute(
            "INSERT OR REPLACE INTO source_buys(key, slot, ts, sig) VALUES(?,?,?,?)",
            (self.ключ_пары(mint, source),
             int(slot) if isinstance(slot, int) else None,
             float(now if now is not None else time.time()),
             str(sig) if sig else None))
        self.db().commit()

    def докупка_в_окне(self, source: str | None, mint: str,
                        slot: int | None = None,
                        now: float | None = None,
                        sig: str | None = None) -> tuple[bool, str]:
        """Докупка ли это: (да/нет, словами почему). ОКНА ВРЕМЕНИ БОЛЬШЕ НЕТ.

        Слово владельца 28.09: "Докупки -- только первая покупка на пару
        источник+минт, без окна времени (число: -18 медиана на 349 докупках
        лидера)". Значит правило простое: пара "источник + минт" уже покупалась
        -- докупка, сколько бы слотов ни прошло. Имя функции оставлено прежним:
        его знает детектор, а переименование ради красоты стоило бы правки
        денежного пути без нужды.
        """
        пред_слот, пред_ts, пред_sig = self._source_buy_row(source, mint)
        if пред_слот is None and пред_ts is None:
            return False, "предыдущей покупки этой пары источник+минт мы не видели"
        # ТА ЖЕ ПОДПИСЬ -- ТА ЖЕ ПОКУПКА, А НЕ ДОКУПКА. Один сигнал может
        # прийти дважды (два способа подписки, повтор после обрыва), и без
        # этой проверки повтор читался бы как докупка.
        if sig and пред_sig and str(sig) == str(пред_sig):
            return False, "это та же покупка источника (та же подпись), а не докупка"
        if isinstance(slot, int) and пред_слот is not None:
            разница = slot - int(пред_слот)
            return True, (f"источник уже покупал этот минт (разница {разница} "
                           f"слотов) -- берём только первую покупку пары")
        if пред_ts is not None:
            прошло = float(now if now is not None else time.time()) - float(пред_ts)
            return True, (f"источник уже покупал этот минт ({прошло:.0f} с назад, "
                           f"слота нет) -- берём только первую покупку пары")
        return True, "источник уже покупал этот минт -- берём только первую покупку пары"

    # ------------------------------------- запрет второго минта на группу

    @staticmethod
    def ключ_группы_минта(группа: str | None, mint: str) -> str:
        """Ключ НАШЕЙ покупки по паре "группа + минт".

        Разделитель "~": у ключа пары "источник + минт" он "|", и смешать их
        нельзя даже случайно -- иначе запрет группы читался бы как дедуп пары.
        """
        return f"{группа}~{mint}" if группа else f"~{mint}"

    def минт_группы_запись(self, группа: str | None, mint: str) -> dict:
        """Наша последняя покупка этой пары "группа + минт" -- как есть."""
        if not mint:
            return {}
        row = self.db().execute(
            "SELECT grp, mint, slot, ts, sig FROM group_mints WHERE key=?",
            (self.ключ_группы_минта(группа, mint),)).fetchone()
        if not row:
            return {}
        return {"группа": row[0], "минт": row[1],
                 "слот": int(row[2]) if row[2] is not None else None,
                 "ts": float(row[3]) if row[3] is not None else None,
                 "подпись": row[4] or None}

    def отметить_минт_группы(self, группа: str | None, mint: str, *,
                               slot: int | None = None,
                               now: float | None = None,
                               sig: str | None = None,
                               mode: str = MODE_LIVE) -> dict:
        """Запомнить НАШУ покупку пары "группа + минт".

        Для dry-run не пишем: придуманная покупка закрыла бы минт группы для
        настоящей. Запись перезаписывается -- окно считается от ПОСЛЕДНЕЙ
        нашей покупки, а не от первой.
        """
        if not mint or not is_real_mode(mode):
            return {"ok": False, "why_not": ("минта нет" if not mint
                                               else f"режим {mode} -- не пишем")}
        try:
            self.db().execute(
                "INSERT OR REPLACE INTO group_mints"
                "(key, grp, mint, slot, ts, sig) VALUES(?,?,?,?,?,?)",
                (self.ключ_группы_минта(группа, mint),
                 str(группа) if группа else None, str(mint),
                 int(slot) if isinstance(slot, int) else None,
                 float(now if now is not None else time.time()),
                 str(sig) if sig else None))
            self.db().commit()
        except Exception as сбой:  # noqa: BLE001
            return {"ok": False,
                     "why_not": f"{type(сбой).__name__}: {str(сбой)[:120]}"}
        return {"ok": True, "ключ": self.ключ_группы_минта(группа, mint)}

    def второй_минт_на_группу(self, группа: str | None, mint: str, *,
                                slot: int | None = None,
                                now: float | None = None,
                                sig: str | None = None,
                                окно_слотов: int | None = None,
                                окно_с: float | None = None) -> tuple[bool, str]:
        """Второй ли это минт на группу: (запрещать ли, словами почему).

        Слово владельца 02.10: "запрет второго минта на группу, окно 1800
        слотов; дедуп источник+минт не трогать". Значит: если ЭТА ЖЕ группа
        уже купила ЭТОТ минт не дальше 1800 слотов назад -- второй покупки
        нет, каким бы адресом группы сигнал ни пришёл.

        ЧАСЫ -- СЛОТЫ ЦЕПИ. Слота нет (его не прислал ни фид, ни сеть) --
        считаем по времени: окно_с задаёт вызывающий, потому что длина слота
        у нас ИЗМЕРЯЕМАЯ (решение владельца 28.09, вариант 2), а состояние её
        не мерит. Нет и его -- берём 0.4 с на слот и говорим об этом словами.

        НЕЯСНОСТЬ -- ЗАПРЕТ, как всюду на денежном пути: запись есть, а ни
        слота, ни времени в ней нет -- значит запрещаем.
        """
        окно = int(окно_слотов if окно_слотов is not None else self.group_mint_slots)
        if окно <= 0:
            return False, f"запрет второго минта на группу выключен (окно {окно})"
        if not mint:
            return False, "минта нет -- запрещать нечего"
        if not группа:
            return False, "группа не названа -- запрет второго минта её не касается"
        try:
            зап = self.минт_группы_запись(группа, mint)
        except Exception as сбой:  # noqa: BLE001
            return True, (f"таблица наших покупок группы не прочитана "
                           f"({type(сбой).__name__}) -- неясность на денежном пути "
                           "читается как запрет")
        if not зап:
            return False, f"группа {группа} этот минт ещё не покупала"
        # ТОТ ЖЕ СИГНАЛ -- ТА ЖЕ ПОКУПКА, А НЕ ВТОРОЙ МИНТ. Один сигнал
        # приходит дважды (два способа подписки, повтор после обрыва), и без
        # этой проверки повтор назывался бы вторым минтом на группу: 02.10 на
        # этом упала самопроверка "повтор по ключу операции". Правда о повторе
        # живёт в ключе операции, и подменять её этим запретом нельзя.
        if sig and зап.get("подпись") and str(sig) == str(зап["подпись"]):
            return False, ("это тот же сигнал источника (та же подпись), "
                            "а не второй минт на группу")
        if isinstance(slot, int) and зап.get("слот") is not None:
            прошло = int(slot) - int(зап["слот"])
            if прошло < 0:
                return True, (f"группа {группа} уже купила этот минт в слоте "
                               f"{зап['слот']}, а сигнал пришёл из слота {slot} "
                               "(слот назад) -- запрет")
            if прошло <= окно:
                return True, (f"группа {группа} уже купила этот минт {прошло} "
                               f"слотов назад при окне {окно} -- второй минт на "
                               "группу запрещён")
            return False, (f"группа {группа} покупала этот минт {прошло} слотов "
                            f"назад, это дальше окна {окно} -- новый сигнал")
        if зап.get("ts") is not None:
            с_окна = (float(окно_с) if окно_с is not None
                       else окно * 0.4)
            откуда = ("окно в секундах задано вызывающим" if окно_с is not None
                       else "длина слота не передана, взято 0.4 с на слот")
            прошло_с = float(now if now is not None else time.time()) - float(зап["ts"])
            if прошло_с <= с_окна:
                return True, (f"группа {группа} уже купила этот минт "
                               f"{прошло_с:.0f} с назад при окне {с_окна:.0f} с "
                               f"({окно} слотов, {откуда}) -- запрет")
            return False, (f"группа {группа} покупала этот минт {прошло_с:.0f} с "
                            f"назад, это дальше окна {с_окна:.0f} с -- новый сигнал")
        return True, (f"у покупки группы {группа} по этому минту нет ни слота, ни "
                       "времени -- неясность читается как запрет")

    def mint_state(self, mint: str, source: str | None = None) -> tuple[float | None, int]:
        """(когда покупали, сколько раз) по ПАРЕ, если назван источник."""
        ключ = self.ключ_пары(mint, source)
        row = self.db().execute("SELECT ts, buys FROM mint_last WHERE mint=?",
                                 (ключ,)).fetchone()
        return (float(row[0]), int(row[1])) if row else (None, 0)

    def mark_mint_buy(self, mint: str, *, mode: str = MODE_LIVE,
                       source: str | None = None) -> None:
        """Отметить покупку по паре "источник + минт". Для dry-run НЕ отмечаем:
        иначе придуманная покупка закроет пару для настоящей."""
        if not is_real_mode(mode):
            return
        self._mark_mint_buy(mint, source=source)

    def _mark_mint_buy(self, mint: str, source: str | None = None) -> None:
        ключ = self.ключ_пары(mint, source)
        ts, buys = self.mint_state(mint, source)
        self.db().execute("INSERT OR REPLACE INTO mint_last(mint, ts, buys) VALUES(?,?,?)",
                           (ключ, time.time(), buys + 1))
        self.db().commit()

    # --------------------------------------------------- аварии групп (Правило 16)

    def _аварии_групп_прочитать(self) -> tuple[dict, str | None]:
        """({группа: запись}, почему_нет). Файла нет -- пусто, это НЕ ошибка."""
        try:
            if not self.avarii_grupp_path.exists():
                return {}, None
            д = json.loads(self.avarii_grupp_path.read_text(encoding="utf-8"))
        except (OSError, ValueError) as сбой:
            return {}, f"{type(сбой).__name__}: {str(сбой)[:140]}"
        г = д.get("группы") if isinstance(д, dict) else None
        return (г if isinstance(г, dict) else {}), None

    def авария_группы_стоит(self, группа: str | None) -> dict:
        """Стоит ли авария этой группы. {'стоит', 'запись', 'почему_нет'}.

        ЧАСОВ ЗДЕСЬ НЕТ НАРОЧНО: авария снимается только словом владельца, и
        сутки её не снимают. Файл не прочитался -- говорим словами и НЕ
        отвечаем "не стоит": что делать с незнанием, решает гейт.
        """
        записи, почему = self._аварии_групп_прочитать()
        if почему:
            return {"стоит": None, "запись": None, "почему_нет": почему}
        з = записи.get(str(группа or ""))
        if not isinstance(з, dict):
            return {"стоит": False, "запись": None, "почему_нет": None}
        if з.get("снята"):
            return {"стоит": False, "запись": з, "почему_нет": None}
        return {"стоит": True, "запись": з, "почему_нет": None}

    def авария_группы_поставить(self, группа: str | None, *, признак: str,
                                 что: str, число=None,
                                 сутки: str | None = None) -> dict:
        """Поставить аварию группы. ПЕРВУЮ ПРИЧИНУ НЕ ЗАТИРАЕТ.

        Возвращает {'ok', 'already', 'запись', 'why_not'}. already=True --
        авария уже стояла, и значит сообщение владельцу уже ушло: по этому
        признаку оно и не повторяется.
        """
        if not группа:
            return {"ok": False, "already": False, "запись": None,
                     "why_not": "группа не названа -- аварию ставить нечему"}
        записи, почему = self._аварии_групп_прочитать()
        if почему:
            return {"ok": False, "already": False, "запись": None,
                     "why_not": f"файл аварий не прочитан: {почему}"}
        прежняя = записи.get(str(группа))
        if isinstance(прежняя, dict) and not прежняя.get("снята"):
            return {"ok": True, "already": True, "запись": прежняя,
                     "why_not": None}
        запись = {"группа": str(группа), "признак": str(признак),
                   "что": str(что)[:200],
                   "число": (число if число is None else str(число)[:120]),
                   "поставлена_utc": time.strftime("%Y-%m-%dT%H:%M:%SZ",
                                                    time.gmtime()),
                   "сутки": (str(сутки) if сутки else None),
                   "снята": False, "снята_кем": None, "снята_utc": None}
        записи[str(группа)] = запись
        try:
            atomic_write_json(self.avarii_grupp_path,
                               {"schema_version": SCHEMA_VERSION,
                                "обновлено_utc": time.strftime(
                                    "%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
                                "группы": записи})
        except Exception as сбой:  # noqa: BLE001
            return {"ok": False, "already": False, "запись": запись,
                     "why_not": f"{type(сбой).__name__}: {str(сбой)[:120]}"}
        return {"ok": True, "already": False, "запись": запись, "why_not": None}

    def авария_группы_снять(self, группа: str | None, *, кем: str) -> dict:
        """Снять аварию. ТОЛЬКО ПО СЛОВУ ВЛАДЕЛЬЦА -- служба этого не зовёт.

        Запись не удаляется, а помечается снятой: история аварий нужна, чтобы
        считать, сколько их было и по какому признаку.
        """
        записи, почему = self._аварии_групп_прочитать()
        if почему:
            return {"ok": False, "why_not": f"файл аварий не прочитан: {почему}"}
        з = записи.get(str(группа or ""))
        if not isinstance(з, dict) or з.get("снята"):
            return {"ok": False, "why_not": "аварии этой группы не стоит"}
        з["снята"] = True
        з["снята_кем"] = str(кем)[:80]
        з["снята_utc"] = time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())
        записи[str(группа)] = з
        try:
            atomic_write_json(self.avarii_grupp_path,
                               {"schema_version": SCHEMA_VERSION,
                                "обновлено_utc": time.strftime(
                                    "%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
                                "группы": записи})
        except Exception as сбой:  # noqa: BLE001
            return {"ok": False, "why_not": f"{type(сбой).__name__}"}
        return {"ok": True, "why_not": None, "запись": з}

    def аварии_групп(self) -> dict:
        """{группа: запись} по СТОЯЩИМ авариям. Для доклада и строк."""
        записи, почему = self._аварии_групп_прочитать()
        if почему:
            return {}
        return {г: з for г, з in записи.items()
                if isinstance(з, dict) and not з.get("снята")}

