def env_float(name: str, default: float) -> float:
    raw = os.environ.get(name, "").strip()
    if not raw:
        return default
    try:
        return float(raw)
    except ValueError:
        print(f"[состояние] {name}={raw!r} не число -- беру умолчание {default}")
        return default


def env_int(name: str, default: int) -> int:
    return int(env_float(name, float(default)))


def day_key(ts: float | None = None) -> tuple[str, bool]:
    """Дата по Мадриду и признак, что часовой пояс недоступен.

    Молча падать на UTC нельзя: смена суток сдвинется на час или два, и
    дневной лимит потерь будет считаться не за те сутки. Поэтому признак
    возвращается наружу и попадает в отчёт.
    """
    t = ts if ts is not None else time.time()
    try:
        from zoneinfo import ZoneInfo  # noqa: PLC0415
        import datetime as dt  # noqa: PLC0415
        return dt.datetime.fromtimestamp(t, ZoneInfo(DAY_TZ)).strftime("%Y-%m-%d"), False
    except Exception:  # noqa: BLE001 -- любая причина: нет tzdata, нет модуля
        return time.strftime("%Y-%m-%d", time.gmtime(t)), True


def atomic_write_json(path: Path, data) -> None:
    """Запись целиком или никак: .tmp + fsync + replace.

    Без этого читатель может поймать обрезанный JSON -- ровно то, из-за
    чего kill-switch не срабатывает в нужный момент.
    """
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_suffix(path.suffix + ".tmp")
    with tmp.open("w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=2)
        f.flush()
        os.fsync(f.fileno())
    tmp.replace(path)


def append_jsonl_fsync(path: Path, row: dict) -> None:
    """Дописать строку и ДОЖДАТЬСЯ диска.

    Именно fsync отличает журнал намерений от журнала пожеланий: без него
    запись о покупке может не дожить до перезапуска, и позиция потеряется.
    """
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("a", encoding="utf-8") as f:
        f.write(json.dumps(row, ensure_ascii=False) + "\n")
        f.flush()
        os.fsync(f.fileno())


def расход_отправки(поз: dict) -> float:
    """Сколько эта покупка стоила кошельку СВЕРХ купленной суммы.

    Чаевые (в пуле -- всем сервисам сразу), приоритет и базовый тариф сети.
    Берётся из полей самой позиции: их пишет отправка, и другого честного
    источника нет.

    ЧАЕВЫЕ УХОДЯТ ТОЛЬКО С УДАВШЕЙСЯ ТРАНЗАКЦИИ. Перевод чаевых -- инструкция
    внутри той же транзакции: упала транзакция -- перевода не было, платится
    только приоритет и базовый тариф. Живой пример 26.09 00:04:23Z: покупка
    0.05 отклонена пулом (Custom 6040), с кошелька полосы списано ровно
    0.001005 SOL, а чаевые 0.001 остались на месте.
    """
    п = поз or {}
    из_ = 0.0
    чаевые = п.get("lane_tips_total_sol")
    if чаевые and п.get("chain_ok") is not False:
        из_ += float(чаевые)
    приоритет = п.get("lane_priority_lamports")
    if приоритет:
        из_ += float(приоритет) / 1_000_000_000.0
    # Тариф платится, только если транзакция ушла: у брони (intent, до
    # отправки) не списано ничего.
    if п.get("lane_signature") or п.get("ts_sent") or п.get("signatures"):
        из_ += 5000 / 1_000_000_000.0
    return из_


def celoe_lines(кусок: bytes):
    """Непустые строки из куска байтов журнала. Имя латиницей -- ключи записей
    и имена, которые видит разбор журнала, в этом модуле проверяются на ascii."""
    for сырое in кусок.split(b"\n"):
        с = сырое.strip()
        if с:
            yield с.decode("utf-8", "replace")


def индекс_минтов(все: dict) -> dict:
    """{(полоса, минт): [(cid, позиция), ...]} в порядке обхода словаря.

    ЗАЧЕМ. делит_минт перебирает ВЕСЬ журнал на КАЖДУЮ позицию, а зовут его по
    разу на каждую сделку суток -- дважды, в двух счётах. Замер 01.10 на журнале
    5499 записей и 129 сделках суток: 158.9 мс на один состояние_полосы, из них
    97 % в делит_минт (12.98 млн обращений к словарю). Этот гейт стоит в пути
    решения полосы, и ровно это Р: ночью 10-22 мс, к 15:21 -- 144 мс.

    ПОРЯДОК ОБХОДА СОХРАНЁН НАМЕРЕННО. делит_минт возвращает ПЕРВОЕ совпадение
    по порядку словаря, и сравнивает он только записи с тем же минтом и той же
    полосой. Значит первое совпадение внутри корзины (полоса, минт) -- та же
    самая запись, что и при полном переборе. Это не "примерно так же", это то
    же самое, и самопроверка сверяет оба пути на случайном корпусе.
    """
    из_: dict = {}
    for cid, о in (все or {}).items():
        о = о or {}
        минт = о.get("mint")
        if not минт:
            continue
        из_.setdefault((о.get("lane"), минт), []).append((cid, о))
    return из_


def делит_минт(cid: str, поз: dict, все: dict, *, индекс: dict | None = None) -> str:
    """Делила ли эта пара свой минт с ДРУГОЙ позицией той же полосы.

    Продажа несчитаемой пары идёт по остатку кошелька. Если в то же окно на
    кошельке висела ещё одна позиция того же минта, возврат принадлежит им
    обеим, и разложить его нечем. Возвращает client_order_id такой позиции
    (строкой, для записи в журнал) или пустую строку.

    Окна сравниваются по ts_intent (открытие) и ts_closed (закрытие); у ещё не
    закрытой позиции конец окна -- бесконечность, а не "сейчас": она всё ещё
    держит тот же минт.
    """
    минт = (поз or {}).get("mint")
    if not минт:
        return ""
    начало = float((поз or {}).get("ts_intent") or 0.0)
    конец = float((поз or {}).get("ts_closed") or 0.0) or float("inf")
    # С ИНДЕКСОМ смотрим только корзину своего (полоса, минт); без него -- весь
    # журнал, как раньше. Ответ один и тот же: отбор ниже тот же самый.
    if индекс is not None:
        пары = индекс.get(((поз or {}).get("lane"), минт)) or ()
    else:
        пары = (все or {}).items()
    for чужой, о in пары:
        # Чужая полоса не в счёт: у Bloom свой кошелёк, и его остаток к
        # остатку полосы отношения не имеет.
        if чужой == cid or (о or {}).get("lane") != (поз or {}).get("lane"):
            continue
        if (о or {}).get("mint") != минт:
            continue
        о_начало = float(о.get("ts_intent") or 0.0)
        о_конец = float(о.get("ts_closed") or 0.0) or float("inf")
        if о_начало <= конец and о_конец >= начало:
            return str(чужой)
    return ""


def разложение_позиции(поз: dict) -> dict:
    """Итог позиции слагаемыми ПО ИМЕНАМ -- слово владельца 29.09 ночью.

    Одна формула на репозиторий остаётся одна: итог тут не считается заново, он
    берётся у итог_позиции. Это функция ИМЁН, а не второй счёт.

    Что как называется и откуда берётся:
      билет_sol      -- sol_in, сумма, ушедшая в своп;
      чаевые_sol     -- lane_tips_total_sol, всем сервисам пула сразу;
      приоритет_sol  -- lane_priority_lamports, плата за очередь;
      тариф_sol      -- базовый тариф сети = комиссия минус приоритет;
      комиссия_sol   -- lane_buy_fee_sol, приоритет ПЛЮС тариф (так её берёт
                        цепь: на Solana приоритет -- часть комиссии);
      рента_sol      -- lane_buy_rent_sol, заперта в созданных счетах и вернётся
                        только их закрытием (то есть НЕ "вернулась");
      завёрнутое_sol -- lane_buy_wrapped_sol, остаток на счёте WSOL: он тоже
                        вернётся закрытием, и рентой его называть нельзя;
      возврат_sol    -- closed_sol_net, нативная дельта кошелька на продаже.

    неназванное_sol -- НАЗВАННЫЙ остаток: то, что в нативной дельте покупки есть,
    а имени пока не имеет. У позиций, купленных до этой правки, полей ренты и
    завёрнутого нет вовсе, и весь их остаток честно лежит здесь. Ноль вместо
    незнания не ставится нигде.

    сходится -- итог равен сумме названных слагаемых и остатка до лампорта.
    """
    п = поз or {}
    итог, расход = итог_позиции(п)
    из_ = {"итог_sol": (None if итог is None else round(float(итог), 9)),
            "расход_отправки_sol": round(float(расход or 0.0), 9),
            "билет_sol": None, "чаевые_sol": None, "приоритет_sol": None,
            "тариф_sol": None, "комиссия_sol": None, "рента_sol": None,
            "завёрнутое_sol": None, "возврат_sol": None,
            "натив_покупки_sol": None, "неназванное_sol": None,
            "сходится": None, "ветвь": None, "почему": None}

    def чис(зн):
        return None if зн is None else float(зн)

    из_["билет_sol"] = чис(п.get("sol_in"))
    чаевые = чис(п.get("lane_tips_total_sol"))
    # Чаевые уходят ТОЛЬКО с удавшейся транзакции -- то же правило, что в
    # расход_отправки: у отклонённой цепью покупки перевода чаевых не было.
    из_["чаевые_sol"] = (0.0 if (чаевые is None or п.get("chain_ok") is False)
                          else round(чаевые, 9))
    приоритет = п.get("lane_priority_lamports")
    из_["приоритет_sol"] = (None if приоритет is None
                             else round(float(приоритет) / 1_000_000_000.0, 9))
    комиссия = чис(п.get("lane_buy_fee_sol"))
    из_["комиссия_sol"] = None if комиссия is None else round(комиссия, 9)
    if комиссия is not None and из_["приоритет_sol"] is not None:
        из_["тариф_sol"] = round(комиссия - из_["приоритет_sol"], 9)
    из_["рента_sol"] = чис(п.get("lane_buy_rent_sol"))
    из_["завёрнутое_sol"] = чис(п.get("lane_buy_wrapped_sol"))
    возврат = п.get("closed_sol_net")
    if возврат is None:
        возврат = (п.get("last_sell_outcome") or {}).get("sol_delta_net")
    из_["возврат_sol"] = чис(возврат)
    натив = чис(п.get("lane_buy_native_sol"))
    из_["натив_покупки_sol"] = None if натив is None else round(натив, 9)

    if п.get("chain_ok") is False:
        из_["ветвь"] = "покупка отклонена цепью -- билет не уходил"
        из_["почему"] = ("с кошелька списаны только приоритет и тариф: "
                          "переводы отклонённой транзакции откатываются")
        из_["сходится"] = (итог is not None
                            and abs(float(итог) + float(расход or 0.0)) <= 1e-9)
        return из_
    if натив is None:
        из_["ветвь"] = "нативной дельты покупки нет -- счёт по полям"
        из_["почему"] = ("рента и завёрнутое в полях не видны вовсе: у этой "
                          "позиции их не назвать")
        return из_
    из_["ветвь"] = "натив покупки плюс возврат"
    # НЕНАЗВАННОЕ считается ИЗ НАТИВА, а не из итога: натив -- это то, что
    # кошелёк отдал на покупке, и всё его содержимое обязано иметь имя.
    названо = 0.0
    for поле in ("билет_sol", "чаевые_sol", "рента_sol", "завёрнутое_sol"):
        зн = из_[поле]
        if зн is not None:
            названо += float(зн)
    из_["неназванное_sol"] = round(-float(натив) - названо, 9)
    if итог is not None and из_["возврат_sol"] is not None:
        собрано = (float(из_["возврат_sol"]) - названо
                    - float(из_["неназванное_sol"]) - float(комиссия or 0.0))
        из_["сходится"] = abs(собрано - float(итог)) <= 1e-9
    return из_


def итог_позиции(поз: dict) -> tuple:
    """Итог закрытой позиции и её расход на отправку: (итог, расход).

    ОДНА ФОРМУЛА НА РЕПОЗИТОРИЙ (I.5). Отсюда её берут и суточный счёт
    состояния, и суточный счёт полосы: когда их было две, числа расходились.

    Итог = возврат - вход - расход на отправку. Расход вычитается ВСЕГДА, даже
    когда покупка не села: с кошелька эти деньги уже ушли.

    Возвращает (None, расход), если вход или возврат неизвестны: выдумывать
    ноль нельзя -- ноль читался бы как "вышли в ноль".
    """
    п = поз or {}
    расход = расход_отправки(п)
    вход = п.get("sol_in")
    возврат = п.get("closed_sol_net")
    if возврат is None:
        возврат = (п.get("last_sell_outcome") or {}).get("sol_delta_net")
    # СЧЁТ ПО ЦЕПИ ИМЕЕТ ПРИОРИТЕТ НАД СЧЁТОМ ПО ПОЛЯМ. Поля не видят платы за
    # создание счетов: живая покупка 25.09 18:09:41Z стоила кошельку
    # 0.053493440, а поля дают 0.052005 -- разница 0.001488440. На 63 сделках
    # ночи это 0.09 SOL расхода мимо суточного стопа. Когда в позиции есть
    # нативная дельта самой покупки, итог считается по ней:
    #     итог = возврат + натив - комиссия покупки
    # (натив отрицателен и уже включает вход, чаевые и плату за счета).
    # ПОКУПКА ОТКЛОНЕНА ЦЕПЬЮ -- ВХОД НЕ УХОДИЛ. У отклонённой транзакции
    # откатываются все переводы: ни входа, ни чаевых с кошелька не списано,
    # платится только приоритет и тариф. Вычитать вход тут значило бы
    # выдумать убыток размером со сделку (26.09 00:04:23Z -- -0.051005
    # вместо -0.001005).
    if п.get("chain_ok") is False:
        return -расход, расход
    натив = п.get("lane_buy_native_sol")
    комиссия_покупки = п.get("lane_buy_fee_sol")
    # ЗАКРЫТА БЕЗ ПРОДАЖИ -- ЭТО НОЛЬ ВОЗВРАТА, А НЕ НЕИЗВЕСТНОСТЬ (слово
    # владельца 28.09 ночью, п.3г: "расход состоялся -> сделка в стопе,
    # «несчитаемые» не бывают"). Покупка села, позиция закрыта, следа продажи
    # нет -- значит с кошелька ушло всё и не вернулось ничего. Пока возврат
    # числился неизвестным, суточный стоп видел только расход отправки: 28.09
    # пять таких пар дали стопу 0.015 вместо 0.794226 SOL, и порог 0.45 не
    # сработал. Открытая позиция сюда не попадает: у неё продажа ещё впереди.
    if (возврат is None and натив is not None
            and п.get("state") == STATE_CLOSED
            and not п.get("sell_signature")
            and not п.get("last_sell_outcome")):
        возврат = 0.0
    # ОБЩИЙ МИНТ ПРОВЕРЯЕТСЯ ДО ВЕТКИ НАТИВА. Ветка "есть нативная дельта"
    # стояла ВЫШЕ и возвращалась раньше, поэтому проверка
    # uncountable_shared_mint была недостижима у любой сделки, где натив
    # известен, -- а он известен почти всегда (его дописывает сторож перед
    # закрытием). То есть защита "возврат принадлежит не только этой паре"
    # существовала только на бумаге: две позиции полосы в одном минте, проданные
    # по остатку кошелька, обе записали бы себе ВЕСЬ возврат. 30.09 не сработало
    # случайно -- позиция была одна.
    if п.get("result_uncountable") and п.get("uncountable_shared_mint"):
        if натив is not None:
            расход = round(-float(натив) - float(вход or 0.0)
                           + float(комиссия_покупки or 0.0), 9)
        return -расход, расход
    if натив is not None:
        расход = round(-float(натив) - float(вход or 0.0)
                       + float(комиссия_покупки or 0.0), 9)
        if возврат is None:
            return None, расход
        return (float(возврат) + float(натив) - float(комиссия_покупки or 0.0),
                расход)
    if п.get("result_uncountable"):
        # I.4 (поручение владельца 25.09: "итог полосы без количества -- по
        # возврату и входу; несчитаемых не оставлять"). Количество в формуле
        # итога не участвует: вход и возврат -- это SOL, и оба известны по
        # цепи. Не считается только одно: продажа по остатку кошелька, когда в
        # то же окно висела другая позиция ТОГО ЖЕ минта -- возврат тогда
        # принадлежит не только этой паре.
        if вход and возврат is not None and not п.get("uncountable_shared_mint"):
            return float(возврат) - float(вход) - расход, расход
        return -расход, расход
    if not вход or возврат is None:
        return None, расход
    return float(возврат) - float(вход) - расход, расход


