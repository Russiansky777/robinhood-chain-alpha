    def _учесть_закрытие(self, cid: str, поля: dict) -> dict:
        """Записать итог закрытой позиции в суточный счёт. РОВНО ОДИН РАЗ.

        Повторный учёт был бы хуже отсутствия: стоп сработал бы по выдуманному
        убытку. Защита -- отметка в самой позиции (pnl_counted) плюс проверка
        уже учтённых по журналу, чтобы перезапуск службы не посчитал дважды.
        """
        if str(поля.get("state") or "") != STATE_CLOSED:
            return {}
        try:
            все_позиции = self.positions()
        except Exception:  # noqa: BLE001
            все_позиции = {}
        прежние = все_позиции.get(cid) or {}
        # ВОЗВРАТ БЕРЁТСЯ ИЗ СЛИТОЙ ЗАПИСИ, А НЕ ТОЛЬКО ИЗ ЭТОГО ВЫЗОВА.
        # Сторож сначала докладывает закрытие (и пишет closed_sol_net), а потом
        # закрывает позицию отдельным вызовом. Пока возврат искался только в
        # полях самого закрывающего вызова, счёт видел None и не считал ничего:
        # выручка подтверждённой продажи в суточный счёт не попадала вовсе.
        чисто = поля.get("closed_sol_net")
        if чисто is None:
            чисто = прежние.get("closed_sol_net")
        if чисто is None:
            чисто = ((прежние.get("last_sell_outcome") or {}).get("sol_delta_net")
                     if isinstance(прежние.get("last_sell_outcome"), dict) else None)
        if чисто is None:
            return {}
        if прежние.get("pnl_counted"):
            return {}
        # ИТОГ -- ЭТО ВОЗВРАТ МИНУС ВХОД МИНУС РАСХОД НА ОТПРАВКУ, а не
        # возврат сам по себе. Первая версия этой правки писала в счёт
        # closed_sol_net (сколько вернулось), и на живой сделке 26.09 в
        # 00:11:40Z это дало бы +0.012913 вместо честных +0.0009: вход 0.01 и
        # чаевые с приоритетом в счёт не попадали. Такой счёт не просто врёт --
        # он НИКОГДА не даст сработать стопу по убытку.
        слитое = dict(прежние)
        слитое.update(поля)
        # I.4: несчитаемой пару делает неизвестное КОЛИЧЕСТВО, а не деньги.
        # Итог по возврату и входу количества не требует вовсе. Единственный
        # случай, когда так считать нельзя, -- продажа по остатку кошелька,
        # когда в то же время на кошельке висела ДРУГАЯ позиция того же минта:
        # возврат тогда принадлежит не только этой паре.
        общий_минт = ""
        if слитое.get("result_uncountable"):
            общий_минт = self._делит_минт(cid, слитое, все_позиции)
            if общий_минт:
                слитое["uncountable_shared_mint"] = общий_минт
        итог, расход = self.итог_позиции(слитое)
        if итог is None:
            return {"pnl_counted": False,
                    "pnl_count_why_not": "вход или возврат неизвестны"}
        try:
            self.add_pnl(realized_sol=float(итог), spent_sol=float(расход), sells=1)
        except Exception as exc:  # noqa: BLE001
            # Счёт не должен ронять закрытие позиции: позиция закрыта по цепи,
            # и это факт. Но молчать тоже нельзя -- причина уходит в запись.
            return {"pnl_counted": False,
                    "pnl_count_why_not": f"{type(exc).__name__}"}
        из_ = {"pnl_counted": True, "pnl_counted_sol": round(float(итог), 9),
                "pnl_counted_spend_sol": round(float(расход), 9)}
        # ОБЩИЙ МИНТ -- В САМУ ЗАПИСЬ. Он считался тут и тут же терялся: в
        # позиции оставался один расход без объяснения, почему возврат не
        # зачтён. Разбирать такое потом нечем -- второй позиции того же минта в
        # записи не видно. Денег это не меняет, это имя причины.
        if общий_минт:
            из_["uncountable_shared_mint"] = общий_минт
            из_["pnl_count_why_not"] = (
                "возврат делится с позицией " + str(общий_минт)
                + ": в счёт только расход")
        return из_

