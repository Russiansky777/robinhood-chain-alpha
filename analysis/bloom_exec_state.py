    def _стопы_групп_прочитать(self) -> tuple[dict, str | None]:
        """({группа: запись}, почему_нет). Файла нет -- пусто, это НЕ ошибка."""
        try:
            if not self.stopy_grupp_path.exists():
                return {}, None
            д = json.loads(self.stopy_grupp_path.read_text(encoding="utf-8"))
        except (OSError, ValueError) as сбой:
            return {}, f"{type(сбой).__name__}: {str(сбой)[:140]}"
        г = д.get("группы") if isinstance(д, dict) else None
        return (г if isinstance(г, dict) else {}), None

    def стоп_группы_стоит(self, группа: str | None, сутки: str | None) -> dict:
        """Стоит ли ЗАЩЁЛКНУТЫЙ стоп этой группы в эти сутки.

        {'стоит', 'запись', 'почему_нет'}. Запись чужих суток НЕ СЧИТАЕТСЯ -- это
        и есть "снимается только по часам": смена суток снимает стоп сама, а
        улучшение итога его не снимает.

        ФАЙЛ НЕ ПРОЧИТАЛСЯ -- говорим это словами и НЕ отвечаем "не стоит".
        Решать, что делать с незнанием, -- дело гейта (у него незнание = замок),
        а не дело читателя файла.
        """
        записи, почему = self._стопы_групп_прочитать()
        if почему:
            return {"стоит": None, "запись": None, "почему_нет": почему}
        з = записи.get(str(группа or ""))
        if not isinstance(з, dict):
            return {"стоит": False, "запись": None, "почему_нет": None}
        if сутки is not None and str(з.get("сутки")) != str(сутки):
            return {"стоит": False, "запись": з, "почему_нет": None}
        return {"стоит": True, "запись": з, "почему_нет": None}

    def стоп_группы_поставить(self, группа: str | None, *, сутки: str,
                               убыток_sol=None, порог_sol=None,
                               как_сутки: str | None = None) -> dict:
        """Защёлкнуть стоп группы на эти сутки. Повтор НЕ затирает первую запись.

        Важна та причина и то число, НА КОТОРЫХ стоп встал: позже итог может
        подняться, и перезапись сделала бы запись бессмысленной.
        """
        из_ = {"ok": False, "already": False, "why_not": None}
        имя = str(группа or "")
        if not имя:
            из_["why_not"] = "группа не названа -- защёлкивать нечего"
            return из_
        записи, почему = self._стопы_групп_прочитать()
        if почему:
            # Читать не смогли -- писать поверх НЕЛЬЗЯ: затёрли бы чужие стопы.
            из_["why_not"] = f"файл стопов не прочитан ({почему})"
            return из_
        прежняя = записи.get(имя)
        if isinstance(прежняя, dict) and str(прежняя.get("сутки")) == str(сутки):
            из_.update(ok=True, already=True, запись=прежняя)
            return из_
        записи[имя] = {
            "сутки": str(сутки), "как_сутки": как_сутки,
            "поставлен_utc": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
            "поставлен_ts": round(time.time(), 6),
            "убыток_при_постановке_sol": (round(float(убыток_sol), 9)
                                           if убыток_sol is not None else None),
            "порог_sol": (round(float(порог_sol), 9)
                           if порог_sol is not None else None)}
        try:
            atomic_write_json(self.stopy_grupp_path,
                               {"schema_version": SCHEMA_VERSION,
                                "обновлено_utc": time.strftime(
                                    "%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
                                "группы": записи})
        except OSError as сбой:
            из_["why_not"] = f"{type(сбой).__name__}: {str(сбой)[:140]}"
            return из_
        из_.update(ok=True, запись=записи[имя])
        return из_

    def стопы_групп_защёлкнутые(self, сутки: str | None = None) -> dict:
        """Все защёлкнутые стопы этих суток: {группа: запись}."""
        записи, почему = self._стопы_групп_прочитать()
        if почему:
            return {}
        if сутки is None:
            return dict(записи)
        return {г: з for г, з in записи.items()
                if isinstance(з, dict) and str(з.get("сутки")) == str(сутки)}

    # -------------------------------------------------------------- позиции

    def _ротированные_позиции(self) -> dict:
        """Позиции из ПОСЛЕДНЕГО ротированного журнала, через кэш.

        Найдено 25.09: на хосте стоит logrotate, и в 22:00Z сутки уезжают в
        positions.jsonl.1.gz. Читая только текущий файл, состояние теряло
        историю: в 22:25Z полоса показала "сделок сегодня 0" после 25 покупок
        за вечер, а её суточные пределы (50 сделок, стопы -0.3/-0.5, потолок
        расхода) считались по пустому журналу -- то есть стоп-лосс начинался
        заново каждую полночь по хосту.

        Берём ровно ОДИН, самый свежий ротированный файл: суточное окно им
        закрывается целиком, а тянуть всю историю в каждый вызов нельзя --
        positions() зовут гейты перед каждой сделкой. Разобранное держим в
        кэше по (путь, время правки, размер): ротированный файл больше не
        меняется, поэтому кэш точен, а не "почти точен".
        """
        свежий = None
        try:
            рот = sorted(self.base.glob(self.positions_path.name + ".*.gz"),
                         key=lambda п: п.stat().st_mtime, reverse=True)
            свежий = рот[0] if рот else None
        except OSError:
            return {}
        if свежий is None:
            return {}
        try:
            отметка = (str(свежий), свежий.stat().st_mtime, свежий.stat().st_size)
        except OSError:
            return {}
        ранее = _КЭШ_РОТАЦИИ.get(отметка[0])
        if ранее and ранее[0] == отметка[1] and ранее[1] == отметка[2]:
            return ранее[2]
        out: dict = {}
        try:
            import gzip  # noqa: PLC0415

            with gzip.open(свежий, "rt", encoding="utf-8", errors="replace") as f:
                for line in f:
                    line = line.strip()
                    if not line.startswith("{"):
                        continue
                    try:
                        row = json.loads(line)
                    except ValueError:
                        continue
                    cid = row.get("client_order_id")
                    if not cid:
                        continue
                    out.setdefault(cid, {}).update(row)
        except OSError:
            return {}
        _КЭШ_РОТАЦИИ[отметка[0]] = (отметка[1], отметка[2], out)
        return out

    def _ряды_позиций(self) -> list:
        """Разобранные строки журнала позиций. Дочитывается ТОЛЬКО ПРИРОСТ.

        ЗАЧЕМ (замер 01.10, п.1 владельца). positions() открывал и разбирал весь
        журнал на КАЖДЫЙ вызов, а зовут его в пути решения полосы. На журнале
        5499 строк: 44.6 мс на json.loads и 3.9 мс на сборку словаря -- то есть
        92 % цены в разборе. Журнал растёт с каждой сделкой, и ровно поэтому Р
        росло весь день: 14 мс в 22Z, 136 мс в 16Z.

        ЖУРНАЛ ТОЛЬКО ДОПИСЫВАЕТСЯ -- значит прирост можно дочитать с того места,
        где остановились в прошлый раз. Полное перечитывание остаётся для случаев,
        когда файл СТАЛ КОРОЧЕ (ротация, обрезка) или сменил путь: тогда прежнему
        смещению верить нельзя.

        НЕДОПИСАННАЯ ПОСЛЕДНЯЯ СТРОКА НЕ СЪЕДАЕТСЯ. Служба пишет строку не
        атомарно относительно нашего чтения, и прочитать её половину значило бы
        потерять правку позиции навсегда: смещение сдвинулось бы, а строка в
        разбор не попала. Поэтому берётся только то, что до последнего перевода
        строки, и смещение двигается ровно на это.
        """
        путь = str(self.positions_path)
        кэш = getattr(self, "_кэш_позиций", None)
        if not self.positions_path.exists():
            self._кэш_позиций = {"путь": путь, "смещение": 0, "ряды": []}
            return []
        ст_ = self.positions_path.stat()
        размер, время = ст_.st_size, ст_.st_mtime_ns
        # ГОДНОСТЬ КЭША. Прежнее условие было дырой, и дыра измерена (02.10,
        # рассвет): к размеру и времени стояло ИЛИ "размер > смещение", и эта
        # ветка сама делала кэш годным, обходя проверку времени. То есть ПОЛНАЯ
        # ПЕРЕЗАПИСЬ файла БОЛЬШЕГО размера читалась как дописывание: прежние
        # строки оставались, а начало нового файла не читалось ВОВСЕ. Воспроизведено
        # на двух записях -- после перезаписи наружу уходила старая позиция, а
        # новой не было ни одной. Прежний комментарий закрывал случай "та же
        # длина" и этот случай оставлял открытым.
        #
        # ТЕПЕРЬ ПРИРОСТ ПРИНИМАЕТСЯ ТОЛЬКО С ПРОВЕРКОЙ ПРЕФИКСА. Дописывание
        # earlier байты не трогает, поэтому проверяются ровно они: голова и хвост
        # уже прочитанного куска (до 256 байт каждый) плюс то, что он кончается
        # переводом строки. Это НЕ доказывает побайтовое равенство всего
        # префикса -- и тут это сказано прямо, а не выдано за доказательство:
        # чтение всего префикса стоило бы столько же, сколько полный разбор, ради
        # которого кэш и заведён. Для журнала, который служба только дописывает,
        # совпадения головы, хвоста и границы строки достаточно, а любая
        # перезапись чужой рукой на этих байтах и ловится.
        # ВРЕМЯ ФАЙЛА НЕ ДОКАЗЫВАЕТ НИЧЕГО, И ЭТО ПОЙМАНО НА ЖИВОМ ХОСТЕ.
        # Здесь стояло "кэш["время"] == время ИЛИ префикс цел", и на моей машине
        # это проходило: mtime с наносекундами, две записи подряд дают разное
        # время, значит доходило до проверки префикса. На хостовом бегунке
        # гранулярность mtime грубее -- две записи В ОДНУ СЕКУНДУ дают ОДИНАКОВОЕ
        # время, "или" замыкалось на нём, и перезапись файла в БОЛЬШУЮ длину
        # читалась как дописывание: в ответе оставались прежние сделки (k8),
        # а поля новой записи терялись. Деплой 02.10 13:59Z упал на этих трёх
        # проверках: 172/175 на хосте против 175/175 у меня.
        # Поэтому доказательство ровно одно -- ОТПЕЧАТОК ПРЕФИКСА. Время файла
        # осталось в кэше как сведение для отчёта, но решения не принимает.
        годен = (isinstance(кэш, dict) and кэш.get("путь") == путь
                 and кэш.get("смещение", 0) <= размер
                 and (кэш.get("смещение", 0) == 0
                      or self._префикс_цел(кэш)))
        if not годен:
            кэш = {"путь": путь, "смещение": 0, "ряды": [], "время": None,
                    "голова": b"", "хвост": b""}
        if размер > кэш["смещение"]:
            with self.positions_path.open("rb") as f:
                f.seek(кэш["смещение"])
                кусок = f.read(размер - кэш["смещение"])
            край = кусок.rfind(b"\n")
            if край >= 0:
                целое = кусок[:край + 1]
                кэш["смещение"] += len(целое)
                for line in celoe_lines(целое):
                    try:
                        кэш["ряды"].append(json.loads(line))
                    except ValueError:
                        continue      # битая строка не должна рушить разбор
        кэш["время"] = время
        кэш["голова"], кэш["хвост"] = self._отпечаток_префикса(кэш["смещение"])
        self._кэш_позиций = кэш
        return кэш["ряды"]

    ОТПЕЧАТОК_БАЙТ = 256

    def _отпечаток_префикса(self, смещение: int) -> tuple:
        """Голова и хвост уже прочитанного куска -- два коротких чтения.

        Снимается ПОСЛЕ дочитывания, то есть описывает ровно то, что попало в
        разбор. Пустой кусок даёт пустые байты, и тогда проверять нечего.
        """
        n = int(смещение or 0)
        if n <= 0:
            return b"", b""
        д = min(self.ОТПЕЧАТОК_БАЙТ, n)
        try:
            with self.positions_path.open("rb") as f:
                голова = f.read(д)
                f.seek(n - д)
                хвост = f.read(д)
        except OSError:
            return b"", b""
        return голова, хвост

    def _префикс_цел(self, кэш: dict) -> bool:
        """Не трогал ли кто уже прочитанные байты. Отказ -- в пользу перечтения.

        Нет отпечатка (кэш от прежней версии, или чтение не удалось) -- считаем
        префикс НЕ целым: лишнее перечтение стоит миллисекунды, а чужие строки
        под видом нынешних стоили бы доклада.
        """
        n = int(кэш.get("смещение") or 0)
        if n <= 0:
            return False
        голова_б, хвост_б = кэш.get("голова"), кэш.get("хвост")
        if not голова_б or not хвост_б:
            return False
        голова, хвост = self._отпечаток_префикса(n)
        if голова != голова_б or хвост != хвост_б:
            return False
        # ГРАНИЦА СТРОКИ. Смещение всегда стоит сразу за переводом строки (выше
        # берётся только то, что до последнего \n). Если на этом месте не \n --
        # файл писал кто-то другой, и прежнему смещению верить нельзя.
        return хвост.endswith(b"\n")

    def positions(self) -> dict:
        """Текущее состояние позиций -- ПЕРЕИГРОМ журнала, а не из памяти.

        Ротированный журнал читается ТОЖЕ и первым: строки текущего файла
        новее и правят поля поверх него.

        СЛОВАРЬ СОБИРАЕТСЯ ЗАНОВО КАЖДЫЙ РАЗ, а кэшируются только разобранные
        строки. Отдавать наружу сам кэш нельзя: вызывающие правят позицию у себя
        (dict(p), update), и правка в кэше стала бы невидимой подменой журнала.
        """
        out: dict = {}
        for cid, з in self._ротированные_позиции().items():
            out.setdefault(cid, {}).update(з)
        for row in self._ряды_позиций():
            cid = row.get("client_order_id")
            if not cid:
                continue
            out.setdefault(cid, {}).update(row)
        return out

    def open_positions(self, *, include_dry: bool = False,
                        lane: str | None = "any") -> list:
        """Открытые позиции. По умолчанию БЕЗ dry-run и ВСЕ полосы.

        include_dry=True нужен только отчётам, которые честно показывают
        оба раздела.

        lane задаёт, чьи позиции нужны:
          "any"            -- все (поведение как было; отчёты и сверка);
          None             -- только покупки Bloom, без полосы своей отправки;
          МЕТКА_ПОЛОСЫ     -- только позиции полосы.
        Гейт покупок Bloom обязан звать с lane=None: иначе одна позиция
        полосы на 0.01 SOL съедала бы место боевой покупки на 0.2 SOL.
        """
        out = [p for p in self.positions().values() if p.get("state") in STATES_OPEN]
        if not include_dry:
            out = [p for p in out if is_real_mode(p.get("mode"))]
        if lane == "any":
            return out
        if lane is None:
            return [p for p in out if not p.get("lane")]
        return [p for p in out if p.get("lane") == lane]

    def lane_positions(self, *, lane: str = МЕТКА_ПОЛОСЫ) -> list:
        """Все позиции полосы, включая закрытые: пределы полосы считаются по
        суткам, а не по открытым."""
        return [p for p in self.positions().values() if p.get("lane") == lane]

    def dry_positions(self) -> list:
        """Позиции dry-run отдельным списком: для отчёта и для откладывания
        при переходе в live-test."""
        return [p for p in self.positions().values()
                if p.get("state") in STATES_OPEN and not is_real_mode(p.get("mode"))]

