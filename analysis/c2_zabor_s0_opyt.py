def транзакция_самоперевода(*, кошелёк: str, лампорты: int = СУММА_ЛАМПОРТЫ,
                             предел_cu: int = ПРЕДЕЛ_CU,
                             цена_cu_микро: int = ЦЕНА_CU_МИКРО,
                             чаевые=None) -> dict:
    """Неподписанная транзакция самоперевода с ПУСТЫМ blockhash.

    Самоперевод нарочно: получатель -- тот же кошелёк, поэтому из денег уходит
    только комиссия. Подпись и настоящий blockhash подставит bloom_own_send.
    """
    import base64  # noqa: PLC0415

    from solders.hash import Hash  # noqa: PLC0415
    from solders.message import MessageV0  # noqa: PLC0415
    from solders.pubkey import Pubkey  # noqa: PLC0415
    from solders.signature import Signature  # noqa: PLC0415
    from solders.transaction import VersionedTransaction  # noqa: PLC0415

    import c2_swap_build as B  # noqa: PLC0415

    ixs = [B.cu_limit(int(предел_cu))]
    if цена_cu_микро:
        ixs.append(B.cu_price(int(цена_cu_микро)))
    ixs.append(B.sol_transfer(кошелёк, кошелёк, int(лампорты)))
    if чаевые:
        пары = (чаевые if isinstance(чаевые, (list, tuple)) and чаевые
                and isinstance(чаевые[0], (list, tuple)) else [чаевые])
        for адрес, л in пары:
            ixs.append(B.sol_transfer(кошелёк, str(адрес), int(л)))
    msg = MessageV0.try_compile(Pubkey.from_string(кошелёк), ixs, [], Hash.default())
    vtx = VersionedTransaction.populate(msg, [Signature.default()])
    сырое = bytes(vtx)
    return {"ok": True, "tx_base64": base64.b64encode(сырое).decode(),
            "size": len(сырое), "n_instructions": len(ixs),
            "лампорты": int(лампорты), "кошелёк": кошелёк}


def подписать_вариант(tx_base64: str, вариант: dict, *,
                       секрет: str | None = None) -> dict:
    """Подпись ОДНИМ blockhash'ем -- через общий путь полосы, со сверкой ключа."""
    из_ = {"ok": False, "why_not": None, "сдвиг": вариант.get("сдвиг"),
            "lastValid": вариант.get("lastValid")}
    к = кошелёк_проверен(секрет)
    if not к.get("ok"):
        из_["why_not"] = к.get("why_not")
        return из_
    try:
        import bloom_own_send as OS  # noqa: PLC0415
    except Exception as exc:  # noqa: BLE001
        из_["why_not"] = f"модуль подписи не загружен: {type(exc).__name__}"
        return из_
    п = OS.подписать(tx_base64, blockhash=вариант["blockhash"],
                      ожидаемый_кошелёк=КОШЕЛЁК_ОПЫТА,
                      секрет=(секрет if секрет is not None else секрет_из_окружения()))
    if not п.get("ok"):
        из_["why_not"] = п.get("why_not")
        return из_
    из_.update(ok=True, signature=п["signature"], tx_base64=п["tx_base64"])
    return из_


def отправить_одновременно(строки: list, *, имя_отправителя: str,
                            отправить=None, таймаут: float = 5.0) -> list:
    """Три отправки ОДНОВРЕМЕННО: потоки и один барьер на старте.

    Иначе вариант, ушедший первым, получил бы фору в целый блок -- а опыт
    именно про блок.
    """
    if отправить is None:
        import bloom_senders as SS  # noqa: PLC0415

        def отправить(имя, tx_base64):  # noqa: E306
            return SS.отправить_через(имя, tx_base64, таймаут=таймаут)

    барьер = threading.Barrier(len(строки))
    итог = [None] * len(строки)

    def один(и: int, с: dict) -> None:
        try:
            барьер.wait(timeout=10.0)
        except Exception:  # noqa: BLE001
            pass
        т0 = time.perf_counter()
        try:
            о = отправить(имя_отправителя, с["tx_base64"])
        except Exception as exc:  # noqa: BLE001
            о = {"ok": False, "why_not": f"{type(exc).__name__}: {str(exc)[:120]}"}
        итог[и] = dict(с, отправка=о, отправка_мс=round(
            (time.perf_counter() - т0) * 1000.0, 2), t_отправки=time.time())

    потоки = [threading.Thread(target=один, args=(и, с), daemon=True)
              for и, с in enumerate(строки)]
    for п in потоки:
        п.start()
    for п in потоки:
        п.join(timeout=таймаут + 12.0)
    return [з for з in итог if з is not None]


