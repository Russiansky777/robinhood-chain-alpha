def выбрать_по_lastvalid(кольцо: list, нужный: int) -> dict:
    """Запись кольца с ЭТИМ lastValidBlockHeight. Нет такой -- честный отказ.

    Выбор -- ТОЧНЫМ СОВПАДЕНИЕМ, без арифметики: узел сам назвал lastValid
    каждого blockhash'а, и пересчитывать его из высоты значило бы завести вторую
    версию правила -- ту самую ошибку на единицу, которую опыт и меряет.
    Ближайшего «примерно такого» не берём: опыт про границу, и подмена сдвига
    сделала бы результат необъяснимым.
    """
    из_ = {"ok": False, "why_not": None, "нужный_lastValid": int(нужный)}
    if not кольцо:
        из_["why_not"] = "кольцо пусто"
        return из_
    for з in кольцо:
        if int(з["lastValid"]) == int(нужный):
            из_.update(ok=True, blockhash=з["blockhash"], lastValid=int(нужный),
                        слот=з.get("слот"), высота_blockhash=з.get("высота_blockhash"))
            return из_
    lv = [int(з["lastValid"]) for з in кольцо]
    из_["why_not"] = (f"в кольце нет blockhash с lastValid={нужный} "
                       f"(есть {min(lv)}..{max(lv)}, записей {len(кольцо)})")
    return из_


def кольцо_стало_старым(кольцо: list, высота_H: int, *, сдвиги=СДВИГИ) -> bool:
    """Нужный lastValid УЖЕ выше всего, что есть в кольце.

    ЗАЧЕМ ОТДЕЛЬНО ОТ ОТКАЗА. Кольцо годится ровно пока высота не ушла выше его
    верхней границы: lastValid = высота_blockhash + 150, значит самый свежий
    blockhash кольца обслуживает высоты до (lastValid_до - сдвиг). Дальше КАЖДЫЙ
    раунд будет отказывать одинаково, сколько их ни запускай. Опыт 30.09 16:14Z:
    раунды 1-2 прошли, а 3, 4 и 5 отказали "в кольце нет blockhash с
    lastValid=4300553xx (есть ..430055228)" -- кольцо кончилось, и пауза между
    раундами тут не спасает, потому что высота растёт, а кольцо нет. Отличать
    это от дыры в середине надо, чтобы пересобрать кольцо, а не повторять.
    """
    if not кольцо:
        return True
    верх = max(int(з["lastValid"]) for з in кольцо)
    return (int(высота_H) + max(сдвиги)) > верх


def три_варианта(кольцо: list, высота_H: int, *, сдвиги=СДВИГИ) -> dict:
    """Три blockhash'а: lastValid = H−1, H, H+1. Не хватило -- отказ по имени."""
    из_ = {"ok": False, "why_not": None, "H": int(высота_H), "варианты": []}
    не_нашлись = []
    for сд in сдвиги:
        в = выбрать_по_lastvalid(кольцо, int(высота_H) + int(сд))
        if not в.get("ok"):
            не_нашлись.append(f"{сд:+d}: {в['why_not']}")
            continue
        из_["варианты"].append({
            "сдвиг": int(сд), "blockhash": в["blockhash"],
            "lastValid": в["lastValid"], "слот_кольца": в.get("слот"),
            "высота_blockhash": в.get("высота_blockhash"),
            "имя": f"lastValid=H{сд:+d}" if сд else "lastValid=H"})
    if len(из_["варианты"]) != len(сдвиги):
        из_["why_not"] = "; ".join(не_нашлись)
        return из_
    из_["ok"] = True
    return из_


def ожидание_варианта(вариант: dict, высота_посадки: int | None) -> dict:
    """Должна ли была сесть -- по правилу «высота посадки <= lastValid».

    Ответ на вопрос опыта: если факт и ожидание разошлись, неверно наше
    понимание правила, и это видно поимённо, а не одним «не село».
    """
    lv = int(вариант.get("lastValid"))
    if высота_посадки is None:
        return {"ожидали_посадку": None, "правило": "высота посадки не известна",
                "сошлось": None, "lastValid": lv}
    должна = int(высота_посадки) <= lv
    return {"ожидали_посадку": должна, "lastValid": lv,
            "высота_посадки": int(высота_посадки),
            "правило": (f"{высота_посадки} <= {lv}" if должна
                         else f"{высота_посадки} > {lv}")}


def чаевые_отправителя(имя: str, *, путь_реестра: str | None = None,
                        реестр=None, минимум=None) -> dict:
    """Куда и сколько чаевых платить ЭТОМУ отправителю.

    ОТКУДА ЧИСЛА. Счёт чаевых -- только из реестра полосы (`data/senders.json`,
    поле `tip_accounts`): свой адрес выдумывать нельзя, деньги ушли бы в пустоту.
    Минимум -- либо из таблицы подтверждённых минимумов выше (там сказано, чем
    каждый подтверждён), либо функцией самой полосы
    `bloom_senders.минимум_чаевых`. Ни одного числа "с потолка".
    """
    из_ = {"ok": False, "why_not": None, "отправитель": имя, "лампорты": None,
            "адрес": None, "откуда": None}
    if реестр is None or минимум is None:
        try:
            import bloom_senders as SS  # noqa: PLC0415
        except Exception as exc:  # noqa: BLE001
            из_["why_not"] = (f"реестр отправителей полосы не загружен: "
                               f"{type(exc).__name__}: {exc}")
            return из_
        реестр = реестр if реестр is not None else SS.реестр(путь_реестра)
        минимум = минимум if минимум is not None else (
            lambda и: SS.минимум_чаевых(и, путь=путь_реестра))
    з = (реестр or {}).get(имя) or {}
    счета = з.get("tip_accounts") or []
    if not счета:
        из_["why_not"] = f"у отправителя {имя} в реестре полосы нет счетов чаевых"
        return из_
    if имя in ЧАЕВЫЕ_МИНИМУМ_ЛАМПОРТЫ:
        л = int(ЧАЕВЫЕ_МИНИМУМ_ЛАМПОРТЫ[имя])
        откуда = "подтверждённый минимум (ответ отправителя / слово владельца)"
    else:
        л = int(минимум(имя))
        откуда = "bloom_senders.минимум_чаевых -- реестр полосы"
    if л <= 0:
        из_["why_not"] = f"минимум чаевых для {имя} не положительный: {л}"
        return из_
    из_.update(ok=True, лампорты=л, адрес=str(счета[0]), откуда=откуда)
    return из_


