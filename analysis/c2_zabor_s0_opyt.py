def отправить_одновременно(строки: list, *, имя_отправителя: str,
                            отправить=None, таймаут: float = 5.0) -> list:
    """Три отправки ОДНОВРЕМЕННО: потоки и один барьер на старте.

    Иначе вариант, ушедший первым, получил бы фору в целый блок -- а опыт
    именно про блок.
    """
    if отправить is None:
        import bloom_senders as SS  # noqa: PLC0415

        def отправить(имя, tx_base64):  # noqa: E306
            return SS.отправить_через(имя, tx_base64, таймаут=таймаут)

    барьер = threading.Barrier(len(строки))
    итог = [None] * len(строки)

    def один(и: int, с: dict) -> None:
        try:
            барьер.wait(timeout=10.0)
        except Exception:  # noqa: BLE001
            pass
        т0 = time.perf_counter()
        try:
            о = отправить(имя_отправителя, с["tx_base64"])
        except Exception as exc:  # noqa: BLE001
            о = {"ok": False, "why_not": f"{type(exc).__name__}: {str(exc)[:120]}"}
        итог[и] = dict(с, отправка=о, отправка_мс=round(
            (time.perf_counter() - т0) * 1000.0, 2), t_отправки=time.time())

    потоки = [threading.Thread(target=один, args=(и, с), daemon=True)
              for и, с in enumerate(строки)]
    for п in потоки:
        п.start()
    for п in потоки:
        п.join(timeout=таймаут + 12.0)
    return [з for з in итог if з is not None]


