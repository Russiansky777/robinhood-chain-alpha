def посадка(rpc_call, подпись: str) -> dict:
    """Села ли транзакция: слот, комиссия, ошибка. Одно getTransaction."""
    из_ = {"ok": False, "села": None, "why_not": None, "подпись": подпись}
    try:
        о = rpc_call("getTransaction", [подпись, {"encoding": "json",
                                                  "commitment": "confirmed",
                                                  "maxSupportedTransactionVersion": 0}])
    except Exception as exc:  # noqa: BLE001
        из_["why_not"] = f"{type(exc).__name__}: {str(exc)[:120]}"
        return из_
    рез = _результат(о)
    if рез is None:
        из_.update(ok=True, села=False)
        return из_
    if not isinstance(рез, dict):
        из_["why_not"] = f"ответ узла не разобран: {str(о)[:100]}"
        return из_
    мета = рез.get("meta") or {}
    из_.update(ok=True, села=True, слот=рез.get("slot"),
                комиссия=мета.get("fee"), ошибка=мета.get("err"),
                blockTime=рез.get("blockTime"))
    return из_


def высота_слота(rpc_call, слот: int) -> dict:
    """Высота блока этого слота. Решение лидера принимается по ВЫСОТЕ."""
    из_ = {"ok": False, "why_not": None, "слот": слот}
    try:
        о = rpc_call("getBlock", [int(слот), {"encoding": "json",
                                             "transactionDetails": "none",
                                             "rewards": False,
                                             "maxSupportedTransactionVersion": 0}])
    except Exception as exc:  # noqa: BLE001
        из_["why_not"] = f"{type(exc).__name__}: {str(exc)[:120]}"
        return из_
    рез = _результат(о)
    if not isinstance(рез, dict) or рез.get("blockHeight") is None:
        из_["why_not"] = "узел не отдал blockHeight этого слота"
        return из_
    из_.update(ok=True, высота=int(рез["blockHeight"]),
                blockhash=рез.get("blockhash"))
    return из_


