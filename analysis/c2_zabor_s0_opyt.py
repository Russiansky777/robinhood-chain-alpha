"""ОПЫТ ЗАБОРА S+0: живёт ли наша покупка до блока S+1 -- и когда её выбрасывают.

ЗАЧЕМ. Транзакция действительна, пока ВЫСОТА БЛОКА не превысила
`lastValidBlockHeight` её blockhash'а. Счёт идёт по ВЫСОТЕ, а не по слоту
(MAX_PROCESSING_AGE = 150; из-за нулевой индексации возраста «достаточно
свежими» считаются 151 блок -- solana.com/docs/core/transactions/confirmation).
Отсюда следствие, которое стоит денег: покупка, подписанная blockhash'ем с
`lastValidBlockHeight` = высота блока ИСТОЧНИКА, в блоке S+1 уже мертва --
лидер выбрасывает её БЕЗ включения. Ни комиссии, ни чаевых мы не платим, но и
сделки нет, а в журнале это выглядит как «отправили и не село».

Опыт отвечает числом на два вопроса сразу, и оба -- ошибка на единицу:
  * НЕ СЕЛА -- значит мы не зашли: blockhash был на один блок старше нужного;
  * СЕЛА В S+1 -- значит запас есть, и нынешнее поведение полосы верное.

ЧТО ДЕЛАЕТ СКРИПТ, тремя частями:

  (а) КОЛЬЦО. Опрашивает `getLatestBlockhash` каждые ~400 мс две минуты и
      складывает кольцо записей (lastValidBlockHeight, blockhash, слот). Глубина
      ~200 записей -- больше 151, то есть кольцо накрывает весь срок жизни
      blockhash'а. `lastValidBlockHeight` БЕРЁТСЯ У УЗЛА, а не считается из
      высоты: своя арифметика здесь -- лишний источник ошибки на единицу, ровно
      той, которую опыт и меряет.

  (б) ТРИ ОТПРАВКИ. При известной текущей высоте H берутся три blockhash'а из
      кольца -- с `lastValidBlockHeight` H−1, H и H+1 -- и ими подписываются три
      САМОПЕРЕВОДА по 0.00001 SOL с кошелька опыта на него же. Отправка
      одновременная (три потока, один барьер), отправитель -- параметром,
      skipPreflight как у полосы: предпроверка отклонила бы просроченный
      blockhash сама, и опыт мерил бы предпроверку, а не лидера.

  (в) ЧТО СЕЛО. Через 30 секунд по цепи: села ли, в каком слоте, НА КАКОЙ
      ВЫСОТЕ и с какой комиссией. Высота посадки -- из `getBlock` того слота
      (`blockHeight`), потому что решение лидера принимается по высоте.

ОЖИДАНИЕ (его и проверяем): садится ровно та, у которой
`lastValidBlockHeight >= высота блока посадки`. Если сядет вариант H−1 -- наше
понимание правила неверно; если не сядет H+1 -- неверно тоже, и оба случая
видны в таблице, а не только «не село».

ДЕНЬГИ И БЕЗОПАСНОСТЬ -- ЗАПРЕТАМИ, А НЕ ПРЕДУПРЕЖДЕНИЯМИ:
  * кошелёк опыта зашит ЗДЕСЬ, и публичный ключ секрета сверяется с ним ПЕРЕД
    каждой подписью; не совпал -- отказ, а не предупреждение. Боевым ключом
    этот скрипт подписать ничего не может;
  * секрет только из окружения, отдельной переменной, и в аргументы командной
    строки не принимается вовсе (в списке процессов он был бы виден всем);
  * самоперевод: получатель -- тот же кошелёк, поэтому тратится ТОЛЬКО комиссия
    (и чаевые, если их включить -- по умолчанию их нет);
  * потолок расхода считается ДО первого раунда и проверяется перед каждым;
  * отдельный флаг-рубильник: без него скрипт не отправляет ничего.

Сети сам по себе не зовёт: узел и отправитель приходят параметрами. Общие
модули полосы не правятся -- подпись берётся у `bloom_own_send.подписать`
(там уже стоит сверка публичного ключа), отправка у `bloom_senders`.

Страница: docs/stroiteli_zabor_s0_opyt.md.
"""

