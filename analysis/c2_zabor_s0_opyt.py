# --------------------------------------------------------------- (а) кольцо

def _результат(ответ):
    """Результат вызова узла при ЛЮБОМ из двух соглашений.

    ЗАЧЕМ ЭТО ОТДЕЛЬНОЙ ФУНКЦИЕЙ. Зонд писался под СЫРОЕ ТЕЛО ответа
    (`{"result": ...}`), а на хосте вызов идёт через
    `solana_rpc_client.SolanaRpc.call`, который отдаёт УЖЕ РАЗВЁРНУТЫЙ
    `result` -- у него последняя строка `return body.get("result")`. Прежний
    приём `о = о if isinstance(о, dict) else {}` подменял всё не-словарное
    пустым словарём, и оба соглашения переставали работать на СКАЛЯРНОМ и на
    ПУСТОМ результате:

      * getBlockHeight отдаёт ЧИСЛО. Число подменялось на {}, и раунд отказывал
        словами "узел вернул не высоту: {}". Опыт 30.09 (прогон 36740613644)
        упал так все 5 раундов: отправок 0, комиссий 0.
      * getTransaction отдаёт None, когда сделки ещё нет. None подменялся на {},
        а {} -- словарь, и посадка объявляла сделку СЕВШЕЙ со слотом None и
        комиссией None. Это молчаливое искажение: правило «сошлось/не сошлось»
        считалось бы по несуществующей посадке.

    Поэтому разворачиваем ОДНИМ местом и не подменяем ничего пустым словарём.
    """
    if isinstance(ответ, dict) and "result" in ответ:
        return ответ["result"]
    return ответ


def запись_кольца(ответ: dict, *, сейчас: float | None = None) -> dict | None:
    """Одна запись кольца из ответа getLatestBlockhash.

    `lastValidBlockHeight` берётся КАК ОТДАЛ УЗЕЛ. Высота самого blockhash'а
    выводится из него только для чтения глазами и в выборе НЕ участвует.
    """
    рез = _результат(ответ)
    if not isinstance(рез, dict):
        return None
    зн = рез.get("value") if isinstance(рез.get("value"), dict) else None
    if not зн:
        return None
    bh = зн.get("blockhash")
    lv = зн.get("lastValidBlockHeight")
    if not bh or lv is None:
        return None
    слот = ((рез.get("context") or {}).get("slot")
            if isinstance(рез.get("context"), dict) else None)
    return {"blockhash": bh, "lastValid": int(lv),
            "высота_blockhash": int(lv) - MAX_PROCESSING_AGE,
            "слот": слот, "t": (сейчас if сейчас is not None else time.time())}


def собрать_кольцо(rpc_call, *, секунд: float = СЕКУНД_КОЛЬЦА,
                    полл_мс: int = ПОЛЛ_МС,
                    глубина: int = ГЛУБИНА_КОЛЬЦА) -> dict:
    """Кольцо (lastValid, blockhash, слот) опросом getLatestBlockhash."""
    из_ = {"ok": False, "why_not": None, "кольцо": [], "опросов": 0,
            "ошибок": 0, "секунд": секунд, "полл_мс": полл_мс}
    если_до = time.time() + float(секунд)
    видели = {}
    while time.time() < если_до:
        т0 = time.perf_counter()
        из_["опросов"] += 1
        try:
            о = rpc_call("getLatestBlockhash", [{"commitment": "confirmed"}])
        except Exception:  # noqa: BLE001
            из_["ошибок"] += 1
            о = None
        з = запись_кольца(о) if о is not None else None
        if з and з["lastValid"] not in видели:
            видели[з["lastValid"]] = з
        осталось = float(полл_мс) / 1000.0 - (time.perf_counter() - т0)
        if осталось > 0:
            time.sleep(осталось)
    кольцо = [видели[k] for k in sorted(видели)]
    из_["кольцо"] = кольцо[-int(глубина):]
    из_["ok"] = bool(из_["кольцо"])
    if not из_["ok"]:
        из_["why_not"] = "узел не отдал ни одного blockhash"
        return из_
    из_.update(свод=свод_кольца(из_["кольцо"]))
    return из_


def свод_кольца(кольцо: list) -> dict:
    """Что за кольцо получилось: глубина, разрывы, шаг по высоте."""
    if not кольцо:
        return {"записей": 0}
    lv = [з["lastValid"] for з in кольцо]
    шаги = [b - a for a, b in zip(lv, lv[1:])]
    разрывы = [ш for ш in шаги if ш != 1]
    return {"записей": len(кольцо), "lastValid_от": lv[0], "lastValid_до": lv[-1],
            "накрыто_блоков": lv[-1] - lv[0] + 1,
            "хватает_на_срок_жизни": (lv[-1] - lv[0] + 1) >= ВАЛИДНЫХ_БЛОКОВ,
            "разрывов": len(разрывы), "шаг_максимум": (max(шаги) if шаги else None)}


# ------------------------------------------------- выбор blockhash по высоте

def выбрать_по_lastvalid(кольцо: list, нужный: int) -> dict:
    """Запись кольца с ЭТИМ lastValidBlockHeight. Нет такой -- честный отказ.

    Выбор -- ТОЧНЫМ СОВПАДЕНИЕМ, без арифметики: узел сам назвал lastValid
    каждого blockhash'а, и пересчитывать его из высоты значило бы завести вторую
    версию правила -- ту самую ошибку на единицу, которую опыт и меряет.
    Ближайшего «примерно такого» не берём: опыт про границу, и подмена сдвига
    сделала бы результат необъяснимым.
    """
    из_ = {"ok": False, "why_not": None, "нужный_lastValid": int(нужный)}
    if not кольцо:
        из_["why_not"] = "кольцо пусто"
        return из_
    for з in кольцо:
        if int(з["lastValid"]) == int(нужный):
            из_.update(ok=True, blockhash=з["blockhash"], lastValid=int(нужный),
                        слот=з.get("слот"), высота_blockhash=з.get("высота_blockhash"))
            return из_
    lv = [int(з["lastValid"]) for з in кольцо]
    из_["why_not"] = (f"в кольце нет blockhash с lastValid={нужный} "
                       f"(есть {min(lv)}..{max(lv)}, записей {len(кольцо)})")
    return из_


def три_варианта(кольцо: list, высота_H: int, *, сдвиги=СДВИГИ) -> dict:
    """Три blockhash'а: lastValid = H−1, H, H+1. Не хватило -- отказ по имени."""
    из_ = {"ok": False, "why_not": None, "H": int(высота_H), "варианты": []}
    не_нашлись = []
    for сд in сдвиги:
        в = выбрать_по_lastvalid(кольцо, int(высота_H) + int(сд))
        if not в.get("ok"):
            не_нашлись.append(f"{сд:+d}: {в['why_not']}")
            continue
        из_["варианты"].append({
            "сдвиг": int(сд), "blockhash": в["blockhash"],
            "lastValid": в["lastValid"], "слот_кольца": в.get("слот"),
            "высота_blockhash": в.get("высота_blockhash"),
            "имя": f"lastValid=H{сд:+d}" if сд else "lastValid=H"})
    if len(из_["варианты"]) != len(сдвиги):
        из_["why_not"] = "; ".join(не_нашлись)
        return из_
    из_["ok"] = True
    return из_


def ожидание_варианта(вариант: dict, высота_посадки: int | None) -> dict:
    """Должна ли была сесть -- по правилу «высота посадки <= lastValid».

    Ответ на вопрос опыта: если факт и ожидание разошлись, неверно наше
    понимание правила, и это видно поимённо, а не одним «не село».
    """
    lv = int(вариант.get("lastValid"))
    if высота_посадки is None:
        return {"ожидали_посадку": None, "правило": "высота посадки не известна",
                "сошлось": None, "lastValid": lv}
    должна = int(высота_посадки) <= lv
    return {"ожидали_посадку": должна, "lastValid": lv,
            "высота_посадки": int(высота_посадки),
            "правило": (f"{высота_посадки} <= {lv}" if должна
                         else f"{высота_посадки} > {lv}")}


