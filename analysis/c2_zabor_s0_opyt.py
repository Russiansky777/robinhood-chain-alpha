def таблица(строки: list) -> list:
    """Итог опыта таблицей: по одной строке на отправку."""
    # СТОЛБЕЦ "УШЛА" -- ПЕРВЫМ ДЕЛОМ. Без него не ушедшая отправка выглядела в
    # таблице как факт цепи: "села нет". Опыт 30.09 16:14Z так и вышел -- шесть
    # строк "нет" при нуле настоящих отправок, и страница объявила, что покупка
