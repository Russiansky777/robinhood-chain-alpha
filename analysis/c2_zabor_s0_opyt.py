def расход_раунда_sol(*, отправок: int = 1,
                       комиссия_лампорты: int = КОМИССИЯ_ЛАМПОРТЫ,
                       чаевые_лампорты: int = 0) -> float:
    """Сколько стоит ОДИН раунд: комиссия плюс ЧАЕВЫЕ.

    Чаевые -- расход, а не формальность: платный путь Helius без них отказывает
    (-32602, минимум 200 000 лампортов). Пока их не было в этом счёте, потолок
    опыта обещал 7.5e-05 SOL там, где настоящая цена в 40 раз больше.
    """
    за_одну = int(комиссия_лампорты) + int(чаевые_лампорты)
    return round(int(отправок) * за_одну / ЛАМПОРТОВ_В_SOL, 9)


def предел_расхода_sol(раундов: int, отправителей: int = 1, *,
                        чаевые_лампорты: int = 0) -> float:
    return round(расход_раунда_sol(чаевые_лампорты=чаевые_лампорты)
                 * int(раундов) * max(1, int(отправителей)), 9)


def подождать_смены_высоты(rpc_call, *, было, предел_с: float = 4.0,
                            полл_мс: int = 150, спать=time.sleep) -> dict:
    """Дождаться, пока высота блока станет другой.

    ЗАЧЕМ. Раунд берёт ТЕКУЩУЮ высоту H и требует в кольце ровно H-1, H, H+1.
    Нет одной из трёх -- отказ. Повтор раунда БЕЗ ПАУЗЫ берёт ТУ ЖЕ высоту и
    отказывает теми же словами: опыт 30.09 16:07Z отказал пять раз подряд с
    одним и тем же lastValid=430053416, то есть четыре раунда из пяти не
    проверяли ничего нового -- «пять раундов» было только на бумаге.
    """
    из_ = {"ok": False, "было": было, "стало": None, "why_not": None,
            "опросов": 0}
    if not isinstance(было, int):
        из_["why_not"] = "прошлая высота не известна -- ждать нечего"
        return из_
    до = time.time() + float(предел_с)
    while time.time() < до:
        из_["опросов"] += 1
        try:
            H = _результат(rpc_call("getBlockHeight", [{"commitment": "confirmed"}]))
        except Exception as exc:  # noqa: BLE001
            из_["why_not"] = f"высота не прочитана: {type(exc).__name__}"
            return из_
        if isinstance(H, int) and not isinstance(H, bool) and H != было:
            из_.update(ok=True, стало=H)
            return из_
        спать(float(полл_мс) / 1000.0)
    из_["why_not"] = f"высота не сменилась за {предел_с:g} с"
    return из_


def ожидание_по_окну(вариант: dict, *, высота_посадки, высота_после) -> dict:
    """Должна ли была сесть ОДИНОЧНАЯ отправка.

    ЗАЧЕМ ОТДЕЛЬНО ОТ ожидание_варианта. Пока раунд посылал три штуки одним
    барьером, высоту отсчёта давала та из них, что села. Одиночной отправке
    брать её неоткуда, и главный случай опыта -- "не села" -- остался бы без
    объяснения вовсе. Но высота после ожидания читается у того же узла и
    закрывает вопрос честно: если lastValid УЖЕ ниже текущей высоты, окно
    закрыто, и не сесть она была обязана. Если окно ещё открыто -- ожидание
    так и остаётся неизвестным, а не додумывается.
    """
    lv = int(вариант.get("lastValid"))
    if высота_посадки is not None:
        return ожидание_варианта(вариант, высота_посадки)
    if высота_после is not None and lv < int(высота_после):
        return {"ожидали_посадку": False, "lastValid": lv,
                "правило": (f"не села; lastValid {lv} ниже высоты {высота_после} "
                             f"после ожидания -- окно закрыто"),
                "сошлось": None}
    return {"ожидали_посадку": None, "lastValid": lv,
            "правило": ("не села, но окно ещё не закрыто -- ожидание неизвестно"
                         if высота_после is not None
                         else "высота после ожидания не прочитана"),
            "сошлось": None}


