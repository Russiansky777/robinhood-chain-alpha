def _кольцо_для_проверки(путь: str | None = None) -> tuple:
    """Кольцо для самопроверки: ЗАПИСАННОЕ, если оно есть, иначе построенное.

    Записанного кольца в репозитории пока нет -- его кладёт сюда первый же
    прогон части (а) на хосте (`--rezhim kolco --out …`). Пока его нет,
    проверяется АРИФМЕТИКА выбора на построенном кольце, и это честно: в выборе
    нет ничего, кроме точного совпадения lastValid, а «записанность» кольца на
    арифметику не влияет. Как только файл появится, та же проверка пойдёт по
    нему -- и скажет об этом словом «записанное».
    """
    if путь and os.path.exists(путь):
        try:
            with open(путь, encoding="utf-8") as ф:
                д = json.load(ф)
            к = (д.get("кольцо") if isinstance(д, dict) else д) or []
            if к:
                return list(к), f"записанное ({путь}, записей {len(к)})"
        except Exception:  # noqa: BLE001
            pass
    осн = 340_000_000
    к = [{"blockhash": f"bh{и:04d}", "lastValid": осн + и + MAX_PROCESSING_AGE,
          "высота_blockhash": осн + и, "слот": 500_000_000 + и * 2, "t": 1.0 * и}
         for и in range(ГЛУБИНА_КОЛЬЦА)]
    return к, "построенное (записанного ещё нет)"


