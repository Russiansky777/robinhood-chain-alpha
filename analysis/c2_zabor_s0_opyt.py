def транзакция_самоперевода(*, кошелёк: str, лампорты: int = СУММА_ЛАМПОРТЫ,
                             предел_cu: int = ПРЕДЕЛ_CU,
                             цена_cu_микро: int = ЦЕНА_CU_МИКРО,
                             чаевые=None) -> dict:
    """Неподписанная транзакция самоперевода с ПУСТЫМ blockhash.

    Самоперевод нарочно: получатель -- тот же кошелёк, поэтому из денег уходит
    только комиссия. Подпись и настоящий blockhash подставит bloom_own_send.
    """
    import base64  # noqa: PLC0415

    from solders.hash import Hash  # noqa: PLC0415
    from solders.message import MessageV0  # noqa: PLC0415
    from solders.pubkey import Pubkey  # noqa: PLC0415
    from solders.signature import Signature  # noqa: PLC0415
    from solders.transaction import VersionedTransaction  # noqa: PLC0415

    import c2_swap_build as B  # noqa: PLC0415

    ixs = [B.cu_limit(int(предел_cu))]
    if цена_cu_микро:
        ixs.append(B.cu_price(int(цена_cu_микро)))
    ixs.append(B.sol_transfer(кошелёк, кошелёк, int(лампорты)))
    if чаевые:
        пары = (чаевые if isinstance(чаевые, (list, tuple)) and чаевые
                and isinstance(чаевые[0], (list, tuple)) else [чаевые])
        for адрес, л in пары:
            ixs.append(B.sol_transfer(кошелёк, str(адрес), int(л)))
    msg = MessageV0.try_compile(Pubkey.from_string(кошелёк), ixs, [], Hash.default())
    vtx = VersionedTransaction.populate(msg, [Signature.default()])
    сырое = bytes(vtx)
    return {"ok": True, "tx_base64": base64.b64encode(сырое).decode(),
            "size": len(сырое), "n_instructions": len(ixs),
            "лампорты": int(лампорты), "кошелёк": кошелёк}


