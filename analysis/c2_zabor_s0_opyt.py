def таблица(строки: list) -> list:
    """Итог опыта таблицей: по одной строке на отправку."""
    # СТОЛБЕЦ "УШЛА" -- ПЕРВЫМ ДЕЛОМ. Без него не ушедшая отправка выглядела в
    # таблице как факт цепи: "села нет". Опыт 30.09 16:14Z так и вышел -- шесть
    # строк "нет" при нуле настоящих отправок, и страница объявила, что покупка
    # НЕ САДИТСЯ. Это вывод о цепи из того, чего в цепи не было.
    # СТОЛБЕЦ "H ОТПРАВКИ" -- слово владельца 30.09 16:40Z: у каждой отправки в
    # отчёте видна высота в момент отправки и её lastValid. Без них таблица не
    # даёт проверить сдвиг: "lastValid=H+1" -- это имя, а не число.
    из_ = ["отправитель | вариант      | H отправки | lastValid | ушла | села | "
            "высота посадки | комиссия | ожидали | сошлось",
            "------------|--------------|------------|-----------|------|------|"
            "----------------|----------|---------|--------"]
    for с in строки:
        из_.append(
            f"{str(с.get('отправитель') or '-')[:11]:11s} | "
            f"{str(с.get('имя') or '-')[:12]:12s} | "
            f"{str(с.get('высота_при_отправке') or '-'):>10s} | "
            f"{str(с.get('lastValid') or '-'):>9s} | "
            f"{('да' if с.get('отправлена') else 'НЕТ'):4s} | "
            f"{('да' if с.get('села') else 'нет' if с.get('села') is False else '?'):4s} | "
            f"{_высота_в_таблице(с):>14s} | "
            f"{str(с.get('комиссия') if с.get('комиссия') is not None else '-'):>8s} | "
            f"{('да' if с.get('ожидали_посадку') else 'нет' if с.get('ожидали_посадку') is False else '?'):7s} | "
            f"{('да' if с.get('сошлось_с_правилом') else 'НЕТ' if с.get('сошлось_с_правилом') is False else '?')}")
    return из_


def свод(строки: list) -> dict:
    """Числа опыта. Главное -- сошлось ли правило и где граница.

    ОТПРАВКА -- ТОЛЬКО ТА, ЧТО УШЛА. Попытка, упавшая ДО сети, отправкой не
    считается ни в числах, ни в выводе. 30.09 16:14Z все шесть попыток упали на
    `PermissionError: data/senders.json`, в сеть не ушло НИ ОДНОЙ -- а свод
    насчитал "отправок 6", таблица показала шесть "не села", и страница
    объявила: "покупка с lastValid = высота блока источника НЕ САДИТСЯ".
    Это утверждение о цепи, выведенное из того, чего в цепи не было; прогон при
    этом закончился успехом. Теперь попытки и отправки -- разные числа, а вывод
    для полосы делается только по УШЕДШИМ.
    """
    по_сдвигу = {}
    не_ушло_почему: dict[str, int] = {}
    for с in строки:
        к = с.get("сдвиг")
        з = по_сдвигу.setdefault(к, {"попыток": 0, "отправок": 0, "село": 0,
                                      "не_село": 0, "не_ушло": 0,
                                      "правило_сошлось": 0, "правило_нет": 0,
                                      "комиссий_списано": 0})
        з["попыток"] += 1
        if not с.get("отправлена"):
            з["не_ушло"] += 1
            пч = str(с.get("отправка_why_not") or "причина не названа")[:160]
            не_ушло_почему[пч] = не_ушло_почему.get(пч, 0) + 1
            continue
        з["отправок"] += 1
        if с.get("села") is True:
            з["село"] += 1
            if с.get("комиссия"):
                з["комиссий_списано"] += 1
        elif с.get("села") is False:
            з["не_село"] += 1
        if с.get("сошлось_с_правилом") is True:
            з["правило_сошлось"] += 1
        elif с.get("сошлось_с_правилом") is False:
            з["правило_нет"] += 1
    ушедшие = [с for с in строки if с.get("отправлена")]
    всего = len(ушедшие)
    сошлось = sum(1 for с in ушедшие if с.get("сошлось_с_правилом") is True)
    нет = sum(1 for с in ушедшие if с.get("сошлось_с_правилом") is False)
    # ЧТО ЭТО ЗНАЧИТ ДЛЯ ПОЛОСЫ -- одной строкой, без толкований задним числом.
    село_H = по_сдвигу.get(0, {}).get("село", 0)
    отправок_H = по_сдвигу.get(0, {}).get("отправок", 0)
    вывод = None
    if отправок_H:
        вывод = ("покупка с lastValid = высота блока источника САДИТСЯ в S+1 "
                 "-- запас есть" if село_H else
                 "покупка с lastValid = высота блока источника НЕ САДИТСЯ "
                 "-- в S+1 её выбрасывают, нужен blockhash на блок свежее")
    return {"попыток": len(строки), "отправок": всего,
            "не_ушло": len(строки) - всего,
            "не_ушло_почему": dict(sorted(не_ушло_почему.items(),
                                           key=lambda п: -п[1])),
            "правило_сошлось": сошлось, "правило_не_сошлось": нет,
            "по_сдвигу": {str(к): v for к, v in sorted(по_сдвигу.items())},
            "вывод_для_полосы": вывод,
            "комиссий_списано_всего": sum(v["комиссий_списано"]
                                           for v in по_сдвигу.values())}


