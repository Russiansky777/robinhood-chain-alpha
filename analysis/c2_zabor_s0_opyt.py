def расход_раунда_sol(*, вариантов: int = len(СДВИГИ),
                       комиссия_лампорты: int = 5_000) -> float:
    """Сколько стоит ОДИН раунд по заявке: только комиссии (перевод -- себе)."""
    return round(вариантов * комиссия_лампорты / 1e9, 9)


def предел_расхода_sol(раундов: int, отправителей: int) -> float:
    return round(расход_раунда_sol() * int(раундов) * max(1, int(отправителей)), 9)


def раунд(rpc_call, *, кольцо: list, имя_отправителя: str,
           секрет: str | None = None, ждать_с: float = ЖДАТЬ_ПОСАДКИ_С,
           отправить=None, лампорты: int = СУММА_ЛАМПОРТЫ,
           чаевые=None, спать=time.sleep) -> dict:
    """Один раунд: взять H, собрать три варианта, отправить, прочитать посадку."""
    из_ = {"ok": False, "why_not": None, "отправитель": имя_отправителя,
            "строки": [], "H": None}
    if not включён():
        из_["why_not"] = f"опыт выключен рубильником {ИМЯ_ФЛАГА}"
        return из_
    к = кошелёк_проверен(секрет)
    if not к.get("ok"):
        из_["why_not"] = к.get("why_not")
        return из_
    # ТЕКУЩАЯ ВЫСОТА -- отдельным вопросом: кольцо могло собираться минуту назад.
    try:
        о = rpc_call("getBlockHeight", [{"commitment": "confirmed"}])
    except Exception as exc:  # noqa: BLE001
        из_["why_not"] = f"высота не прочитана: {type(exc).__name__}"
        return из_
    H = _результат(о)
    # bool -- подклассы int: True прошло бы как высота 1.
    if not isinstance(H, int) or isinstance(H, bool):
        из_["why_not"] = f"узел вернул не высоту: {str(о)[:100]}"
        return из_
    из_["H"] = H
    тр = три_варианта(кольцо, H)
    if not тр.get("ok"):
        из_["why_not"] = f"варианты не собрались: {тр['why_not']}"
        return из_
    т = транзакция_самоперевода(кошелёк=КОШЕЛЁК_ОПЫТА, лампорты=лампорты,
                                 чаевые=чаевые)
    подписанные = []
    for в in тр["варианты"]:
        п = подписать_вариант(т["tx_base64"], в, секрет=секрет)
        if not п.get("ok"):
            из_["why_not"] = f"подпись {в['имя']}: {п['why_not']}"
            return из_
        подписанные.append(dict(в, tx_base64=п["tx_base64"],
                                 signature=п["signature"]))
    отправленные = отправить_одновременно(подписанные,
                                           имя_отправителя=имя_отправителя,
                                           отправить=отправить)
    спать(float(ждать_с))
    # СНАЧАЛА ЧИТАЕМ ПОСАДКИ ВСЕХ ТРЁХ, потом сверяем с правилом. Порядок важен:
    # у НЕ СЕВШЕЙ своей высоты посадки нет вовсе, а сверять её с правилом всё
    # равно надо -- иначе главный случай («не села») остаётся без объяснения.
    посадки = []
    for з in отправленные:
        п = посадка(rpc_call, з["signature"])
        высота = None
        if п.get("села") and п.get("слот") is not None:
            в = высота_слота(rpc_call, п["слот"])
            высота = в.get("высота") if в.get("ok") else None
        посадки.append((з, п, высота))
    # ВЫСОТА ОТСЧЁТА -- та, на которой лидер решал судьбу всей тройки. Все три
    # ушли одним барьером, поэтому высота посадки ЛЮБОЙ из них и есть момент
    # решения; если село несколько, берём САМУЮ РАННЮЮ. Не село ни одной --
    # отсчёта нет, и ожидание честно остаётся неизвестным (None), а не
    # додумывается из высоты отправки.
    высоты = [в for _, _, в in посадки if в is not None]
    высота_отсчёта = min(высоты) if высоты else None
    из_["высота_отсчёта"] = высота_отсчёта
    из_["откуда_отсчёт"] = ("высота посадки севшей из тройки" if высоты
                             else "не село ни одной -- отсчёта нет")
    для_отсчёта = высота_отсчёта
    for з, п, высота in посадки:
        ож = ожидание_варианта(з, высота if высота is not None else для_отсчёта)
        сошлось = (None if ож.get("ожидали_посадку") is None
                    else bool(п.get("села")) == bool(ож["ожидали_посадку"]))
        из_["строки"].append({
            "имя": з["имя"], "сдвиг": з["сдвиг"], "lastValid": з["lastValid"],
            "подпись": з["signature"],
            "отправлена": bool((з.get("отправка") or {}).get("ok")),
            "отправка_why_not": (з.get("отправка") or {}).get("why_not"),
            "отправка_мс": з.get("отправка_мс"),
            "села": п.get("села"), "слот_посадки": п.get("слот"),
            "высота_посадки": высота, "высота_отсчёта": для_отсчёта,
            "комиссия": п.get("комиссия"), "ошибка_цепи": п.get("ошибка"),
            "ожидали_посадку": ож.get("ожидали_посадку"),
            "правило": ож.get("правило"), "сошлось_с_правилом": сошлось})
    из_["ok"] = bool(из_["строки"])
    return из_


