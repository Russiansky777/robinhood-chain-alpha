def свод(строки: list) -> dict:
    """Числа опыта. Главное -- сошлось ли правило и где граница."""
    по_сдвигу = {}
    for с in строки:
        к = с.get("сдвиг")
        з = по_сдвигу.setdefault(к, {"отправок": 0, "село": 0, "не_село": 0,
                                      "правило_сошлось": 0, "правило_нет": 0,
                                      "комиссий_списано": 0})
        з["отправок"] += 1
        if с.get("села") is True:
            з["село"] += 1
            if с.get("комиссия"):
                з["комиссий_списано"] += 1
        elif с.get("села") is False:
            з["не_село"] += 1
        if с.get("сошлось_с_правилом") is True:
            з["правило_сошлось"] += 1
        elif с.get("сошлось_с_правилом") is False:
            з["правило_нет"] += 1
    всего = len(строки)
    сошлось = sum(1 for с in строки if с.get("сошлось_с_правилом") is True)
    нет = sum(1 for с in строки if с.get("сошлось_с_правилом") is False)
    # ЧТО ЭТО ЗНАЧИТ ДЛЯ ПОЛОСЫ -- одной строкой, без толкований задним числом.
    село_H = по_сдвигу.get(0, {}).get("село", 0)
    отправок_H = по_сдвигу.get(0, {}).get("отправок", 0)
    вывод = None
    if отправок_H:
        вывод = ("покупка с lastValid = высота блока источника САДИТСЯ в S+1 "
                 "-- запас есть" if село_H else
                 "покупка с lastValid = высота блока источника НЕ САДИТСЯ "
                 "-- в S+1 её выбрасывают, нужен blockhash на блок свежее")
    return {"отправок": всего, "правило_сошлось": сошлось, "правило_не_сошлось": нет,
            "по_сдвигу": {str(к): v for к, v in sorted(по_сдвигу.items())},
            "вывод_для_полосы": вывод,
            "комиссий_списано_всего": sum(v["комиссий_списано"]
                                           for v in по_сдвигу.values())}


