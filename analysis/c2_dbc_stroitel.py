def _плоско(сделки) -> list:
    """Инструкции из сбора Code-2 в любом из двух его видов.

    dbc_sbor.json: список сделок, у каждой ключ "инструкции".
    dbc_dlya_code3.json: сразу список инструкций (ключ "роли" на верхнем уровне).
    """
    из_ = []
    for з in (сделки or []):
        if not isinstance(з, dict):
            continue
        if isinstance(з.get("инструкции"), list):
            for их in з["инструкции"]:
                if isinstance(их, dict):
                    из_.append(dict(их, кошелёк=з.get("кошелёк"),
                                     signature=з.get("signature"), slot=з.get("slot")))
        elif isinstance(з.get("роли"), dict):
            из_.append(з)
    return из_


def сверка_по_разобранным(сделки) -> dict:
    """ТРИ ЧИСЛА ПО РАЗОБРАННЫМ ЖИВЫМ ИНСТРУКЦИЯМ СБОРА Code-2.

    ЧЕГО ЗДЕСЬ НЕЛЬЗЯ И ПОЧЕМУ -- СКАЗАНО ЧИСЛОМ, А НЕ УМОЛЧАНИЕМ. Сырых байтов
    данных сбор не сохранял (сказано в его же шапке: «Сырых байтов данных
    инструкции сбор не сохранял -- только разобранные поля»). Значит «байт в байт»
    по 55 не считается вовсе: считается, что из разобранных полей собирается ровно
    та длина и тот дискриминатор, которых требует раскладка, а объявление остатка
    счетов у варианта с хуком сверить НЕ НА ЧЕМ -- это отдельное число
    (объявление_не_на_чем_сверить). Байт в байт считается там, где сырые байты
    есть: внутри транзакций снимков (см. проверку восстановления).
    """
    ixs = _плоско(сделки)
    из_ = {"инструкций": len(ixs), "по_видам": {}, "по_режимам": {},
            "собираем": 0, "отказ_режим": 0, "отказ_котировка_не_SOL": 0,
            "счета_восстановлены": 0, "счета_проверено": 0,
            "данные_по_полям": 0, "данные_проверено": 0,
            "объявление_не_на_чем_сверить": 0,
            "хвост_привязан_к_минту": 0, "хвост_проверено": 0,
            "хвост_без_чужих_ключей": 0, "отказ_ключ_в_хвосте": 0,
            "хвост_один_на_минт": None, "минтов_с_хуком": 0,
            "отказ_по_первой_причине": {}, "почему": []}
    if not ixs:
        return из_
    B = _кирпичи()
    ядра = {}
    for их in ixs:
        вид = их.get("вид")
        роли = их.get("роли") or {}
        хвост = list(их.get("остаток") or [])
        режим = int(их.get("swap_mode") or 0)
        из_["по_видам"][вид] = из_["по_видам"].get(вид, 0) + 1
        из_["по_режимам"][режим] = из_["по_режимам"].get(режим, 0) + 1
        if вид not in ДЛИНЫ_ДАННЫХ and вид != ВИД_ХУК:
            из_["почему"].append(f"вид {вид} не собирается")
            continue
        if режим != SWAP_MODE_EXACT_IN:
            из_["отказ_режим"] += 1
            имя_реж = ИМЕНА_SWAP_MODE.get(режим, f"режим {режим}")
            из_["отказ_по_первой_причине"][имя_реж] = (
                из_["отказ_по_первой_причине"].get(имя_реж, 0) + 1)
            continue
        котировка_sol = (роли.get("quote_mint") == WSOL)
        if not котировка_sol:
            из_["отказ_котировка_не_SOL"] += 1
        # --- СЧЕТА. Список восстанавливается из ролей ПО РАСКЛАДКЕ и хвоста, и
        # проверяется тем же, чем проверяет шаблон: постоянные счета на местах,
        # реферал пустой, у варианта с хуком -- Token-2022 и чистый хвост.
        из_["счета_проверено"] += 1
        счета = [роли.get(и) for и in ИМЕНА_РОЛЕЙ] + хвост
        свои = {роли.get("input_token_account"), роли.get("output_token_account"),
                роли.get("payer"), их.get("кошелёк")}
        ок = (len(счета) == РАСКЛАДКА["счетов"] + len(хвост)
              and None not in счета[:РАСКЛАДКА["счетов"]]
              and счета[РАСКЛАДКА["pool_authority"]] == POOL_AUTHORITY
              and счета[РАСКЛАДКА["event_authority"]] == EVENT_AUTHORITY
              and счета[РАСКЛАДКА["программа"]] == ПРОГРАММА
              and счета[РАСКЛАДКА["реферал"]] in (ПРОГРАММА, EVENT_AUTHORITY)
              and счета[РАСКЛАДКА["минт_базы"]] != счета[РАСКЛАДКА["минт_котировки"]])
        if вид == ВИД_ХУК:
            из_["хвост_проверено"] += 1
            пр = хвост_к_минту(хвост, роли.get("base_mint") or "")
            из_["хвост_привязан_к_минту"] += bool(пр.get("ok"))
            бк = хвост_без_ключей(хвост, пр.get("программа_хука") or "")
            из_["хвост_без_чужих_ключей"] = (из_.get("хвост_без_чужих_ключей", 0)
                                              + bool(бк.get("ok")))
            ок = (ок and СЧЕТОВ_ХУКА_МИН <= len(хвост) <= СЧЕТОВ_ХУКА_МАКС
                  and роли.get("token_base_program") == ПРОГРАММА_2022
                  and not (свои & set(хвост)) and bool(пр.get("ok"))
                  and bool(бк.get("ok")))
            if not бк.get("ok"):
                из_["отказ_ключ_в_хвосте"] = из_.get("отказ_ключ_в_хвосте", 0) + 1
            ядро = tuple(а for а in хвост
                         if а != "Sysvar1nstructions1111111111111111111111111")
            ядра.setdefault(роли.get("base_mint"), set()).add(ядро)
        elif хвост:
            ок = False
        из_["счета_восстановлены"] += bool(ок)
        # СОБИРАЕМ -- ЭТО ПОСЛЕ ВСЕХ ОХРАН, а не после одной. Иначе число покрытия
        # обещало бы больше, чем строитель сделает.
        if ок and котировка_sol:
            из_["собираем"] += 1
        else:
            # ОТКАЗЫ СЧИТАЮТСЯ ПО ПЕРВОЙ ПРИЧИНЕ, И ИХ СУММА РАВНА ЧИСЛУ ОТКАЗОВ.
            # Отдельные счётчики выше пересекаются (13 сделок с чужим ключом в
            # хвосте ТОЖЕ не против SOL), и по ним сумма получалась больше, чем
            # сделок. Сумма, которая больше целого, -- это не отчёт.
            п = ("хвост хука с чужим ключом" if not ок else "котировка не SOL")
            из_["отказ_по_первой_причине"][п] = (
                из_["отказ_по_первой_причине"].get(п, 0) + 1)
        # --- ДАННЫЕ. Из полей собирается то, что уйдёт на цепь; для варианта с
        # хуком объявление остатка счетов взять негде -- считаем это отдельно.
        из_["данные_проверено"] += 1
        дан = B.disc(вид) + struct.pack("<QQ", int(их.get("amount_0") or 0),
                                         int(их.get("amount_1") or 0))
        if вид != "swap":
            дан += bytes([режим])
        if вид == ВИД_ХУК:
            из_["объявление_не_на_чем_сверить"] += 1
            из_["данные_по_полям"] += bool(len(дан) == НАЧАЛО_ОБЪЯВЛЕНИЯ
                                            and дан[:8] == B.disc(ВИД_ХУК))
        else:
            из_["данные_по_полям"] += bool(len(дан) == ДЛИНЫ_ДАННЫХ[вид]
                                            and дан[:8] == B.disc(вид))
    из_["минтов_с_хуком"] = len(ядра)
    из_["хвост_один_на_минт"] = (all(len(в) == 1 for в in ядра.values())
                                  if ядра else None)
    из_["почему"] = sorted(set(из_["почему"]))[:4]
    return из_


def данные_из_полей(вид: str, amount_0: int, amount_1: int, swap_mode: int,
                     объявление: bytes | None = None) -> bytes:
    """Данные инструкции ИЗ ПОЛЕЙ -- ровно так, как их собирает строитель.

    Отдельной функцией нарочно: по ней считается «байт в байт» на сырых байтах
    живых инструкций, и если строитель и сверка соберут данные ДВУМЯ РАЗНЫМИ
    кусками кода, то сверка подтвердит саму себя, а не строителя.
    """
    B = _кирпичи()
    д = B.disc(вид) + struct.pack("<QQ", int(amount_0), int(amount_1))
    if вид == "swap":
        return д
    д += bytes([int(swap_mode)])
    if вид == ВИД_ХУК:
        if not объявление:
            raise ОшибкаСтроителя(f"{ВИД_ХУК}: без объявления остатка счетов "
                                   "данные не собрать")
        д += bytes(объявление)
    return д


def сверка_сырых(снимки) -> dict:
    """БАЙТ В БАЙТ ПО СЫРЫМ БАЙТАМ живых инструкций DBC внутри транзакций снимков.

    ЗАЧЕМ ОТДЕЛЬНО ОТ ВОССТАНОВЛЕНИЯ. Восстановление меряет то, что строитель
    СОБИРАЕТ, и потому молчит про виды, которые он отказывается собирать
    (PartialFill, хвост с чужим ключом). А прочитана ли раскладка правильно --
    вопрос другой, и на него отвечают все сырые инструкции, включая отказные:
    поля разбираются, из полей собираются те же байты, длина совпадает.
    Именно здесь ловится, что у swap2_with_transfer_hook данных 31 байт, а не 25.
    """
    B = _кирпичи()
    из_ = {"инструкций": 0, "байт_в_байт": 0, "по_видам": {}, "длины": {},
            "хук_объявление_разобрано": 0, "хук_хвост_к_минту": 0, "хук_всего": 0,
            "расхождения": []}
    for с in (снимки or []):
        tx = с.get("транзакция") or с.get("tx") or с
        try:
            ixs = B.all_instructions(tx)
        except Exception:  # noqa: BLE001
            continue
        for их in ixs:
            if их.get("programId") != ПРОГРАММА:
                continue
            try:
                данные = B.b58decode(их.get("data") or "")
            except Exception:  # noqa: BLE001
                continue
            вид = вид_по_данным(данные, B)
            if вид is None:
                continue
            счета = list(их.get("accounts") or [])
            из_["инструкций"] += 1
            из_["по_видам"][вид] = из_["по_видам"].get(вид, 0) + 1
            из_["длины"][f"{вид}:{len(данные)}"] = (
                из_["длины"].get(f"{вид}:{len(данные)}", 0) + 1)
            объявл = None
            if вид == ВИД_ХУК:
                из_["хук_всего"] += 1
                о = объявление_остатка(данные)
                из_["хук_объявление_разобрано"] += bool(о.get("ok"))
                if о.get("ok"):
                    объявл = о["байты"]
                if len(счета) > РАСКЛАДКА["счетов"]:
                    пр = хвост_к_минту(счета[РАСКЛАДКА["счетов"]:],
                                        счета[РАСКЛАДКА["минт_базы"]])
                    из_["хук_хвост_к_минту"] += bool(пр.get("ok"))
            режим = (данные[МЕСТО_SWAP_MODE] if вид != "swap"
                     else SWAP_MODE_EXACT_IN)
            a0, a1 = struct.unpack_from("<QQ", данные, 8)
            try:
                своё = данные_из_полей(вид, a0, a1, режим, объявл)
            except Exception as exc:  # noqa: BLE001
                из_["расхождения"].append(f"{вид}: {type(exc).__name__}")
                continue
            if bytes(своё) == bytes(данные):
                из_["байт_в_байт"] += 1
            else:
                из_["расхождения"].append(
                    f"{вид}: наши {len(своё)} байт != живых {len(данные)}")
    из_["расхождения"] = из_["расхождения"][:5]
    return из_


# ---------------------------------------- событие свопа и цена против факта

# Дискриминатор обёртки события Anchor (#[event_cpi]): внутренняя инструкция самой
# программы, за ним 8 байт дискриминатора события и тело.
ДИСК_СОБЫТИЯ_CPI = bytes.fromhex("e445a52e51cb9a1d")
# EvtSwap2 -- 179 байт тела. Раскладка выведена из состава полей (сдача Code-2) и
# ПРОВЕРЕНА на живых: у всех 10 событий в транзакциях 12 снимков pool совпал с
# пулом снимка, а current_timestamp -- с blockTime транзакции. Сойтись случайно
# два таких поля на десяти событиях не могут.
ДЛИНА_EVTSWAP2 = 179
_П = {"pool": 0, "config": 32, "trade_direction": 64, "has_referral": 65,
      "amount_0": 66, "amount_1": 74, "swap_mode": 82,
      "included_fee_input_amount": 83, "excluded_fee_input_amount": 91,
      "amount_left": 99, "output_amount": 107, "next_sqrt_price": 115,
      "trading_fee": 131, "protocol_fee": 139, "referral_fee": 147,
      "quote_reserve_amount": 155, "migration_threshold": 163,
      "current_timestamp": 171}
# trade_direction: 1 -- котировка в базу (ПОКУПКА). Проверено на 10 живых
# событиях: перенос воспроизводит выход до единицы ровно при таком прочтении
# (10 из 10), а при обратном не сходится ни на одном.
НАПРАВЛЕНИЕ_ПОКУПКА = 1


def событие_свопа(данные: bytes, B=None) -> dict | None:
    """EvtSwap2 из данных внутренней инструкции программы (или None, если это не он)."""
    B = B or _кирпичи()
    if len(данные) != 16 + ДЛИНА_EVTSWAP2 or данные[:8] != ДИСК_СОБЫТИЯ_CPI:
        return None
    т = данные[16:]
    из_ = {"pool": B.b58encode(т[_П["pool"]:_П["pool"] + 32]),
            "config": B.b58encode(т[_П["config"]:_П["config"] + 32]),
            "trade_direction": т[_П["trade_direction"]],
            "has_referral": bool(т[_П["has_referral"]]),
            "swap_mode": т[_П["swap_mode"]],
            "next_sqrt_price": int.from_bytes(
                т[_П["next_sqrt_price"]:_П["next_sqrt_price"] + 16], "little")}
    for имя in ("amount_0", "amount_1", "included_fee_input_amount",
                 "excluded_fee_input_amount", "amount_left", "output_amount",
                 "trading_fee", "protocol_fee", "referral_fee",
                 "quote_reserve_amount", "migration_threshold", "current_timestamp"):
        (из_[имя],) = struct.unpack_from("<Q", т, _П[имя])
    из_["покупка"] = (из_["trade_direction"] == НАПРАВЛЕНИЕ_ПОКУПКА)
    return из_


def события_свопов(tx: dict) -> list:
    """Все EvtSwap2 транзакции, в порядке исполнения."""
    B = _кирпичи()
    из_ = []
    for их in B.all_instructions(tx):
        if их.get("programId") != ПРОГРАММА:
            continue
        try:
            д = B.b58decode(их.get("data") or "")
        except Exception:  # noqa: BLE001
            continue
        с = событие_свопа(д, B)
        if с:
            из_.append(с)
    return из_


def цена_из_снимка(снимок: dict, rpc_call, *, сейчас: float | None = None) -> dict:
    """ЦЕНА ПО СОСТОЯНИЮ ПРОТИВ ФАКТА СДЕЛКИ -- на снимке Code-2.

    Снимок -- это состояние (пул + config) в слоте S и ПЕРВАЯ успешная транзакция
    пула со слотом > S. Значит между чтением и сделкой другой сделки этого пула не
    было, и выход из события обязан совпасть с нашим счётом ДО ЕДИНИЦЫ, а не
    примерно.

    ДВА ПУТИ И ДВА ЧИСЛА. Покупку (котировка -> база, ExactIn) считает САМ
    СТРОИТЕЛЬ -- котировка(), тем же вызовом, что и в бою; всё остальное
    (продажи, PartialFill) считает перенос напрямую. Первое число говорит о
    строителе, второе -- о переносе; складывать их в одно значило бы выдать
    проверку переноса за проверку своего пути.
    """
    из_ = {"ok": False, "why_not": None, "путь": None, "совпало": None,
            "наш": None, "факт": None, "покупка": None, "swap_mode": None}
    tx = снимок.get("транзакция") or снимок.get("tx")
    if not tx:
        из_["why_not"] = "в снимке нет транзакции сделки"
        return из_
    соб = [с for с in события_свопов(tx) if с["pool"] == снимок.get("пул")]
    if not соб:
        из_["why_not"] = "в транзакции сделки нет события EvtSwap2 этого пула"
        return из_
    e = соб[0]
    из_.update(покупка=e["покупка"], swap_mode=e["swap_mode"], факт=e["output_amount"],
                конфиг=e["config"])
    вход = int(e["included_fee_input_amount"])
    if вход <= 0:
        из_["why_not"] = "вход сделки в событии не положителен"
        return из_
    # ТОЧКА РАСПИСАНИЯ КОМИССИИ -- ТА ЖЕ, ЧТО У СДЕЛКИ: слот сделки или её время.
    точка_время = e["current_timestamp"] or сейчас
    if e["покупка"] and e["swap_mode"] == SWAP_MODE_EXACT_IN:
        к = котировка(пул=снимок.get("пул"), минт_базы=None, минт_котировки=None,
                       лампорты=вход, проскальзывание=0.0, rpc_call=rpc_call,
                       сейчас=точка_время, конфиг=e["config"])
        из_["путь"] = "строитель"
        if not к.get("ok"):
            из_["why_not"] = к.get("why_not")
            return из_
        из_["наш"] = int(к.get("выход_до_налога") or 0)
    else:
        из_["путь"] = "перенос"
        try:
            Q = _порт()
        except Exception as exc:  # noqa: BLE001
            из_["why_not"] = f"переноса цены нет: {type(exc).__name__}"
            return из_
        ч = _счета(rpc_call, [снимок.get("пул"), e["config"]])
        if not ч["ok"]:
            из_["why_not"] = f"состояние не прочитано: {ч['why_not']}"
            return из_
        try:
            pool = Q.разобрать_пул(ч["данные"].get(снимок.get("пул")))
            cfg = Q.разобрать_конфиг(ч["данные"].get(e["config"]))
            точка = (снимок.get("slot_сделки") or ч.get("slot")
                     if int(cfg.get("activation_type") or 0) == 0 else точка_время)
            q = Q.котировка_точный_вход(pool, cfg, вход, e["покупка"], int(точка),
                                         has_referral=e["has_referral"],
                                         первый_своп_мин=False)
        except Exception as exc:  # noqa: BLE001
            из_["why_not"] = f"перенос не посчитал: {type(exc).__name__}: {str(exc)[:120]}"
            return из_
        из_["наш"] = int(q.get("output_amount") or 0)
    из_["ok"] = True
    из_["совпало"] = (из_["наш"] == из_["факт"])
    из_["разница"] = из_["наш"] - из_["факт"]
    return из_


def свод_цены_по_снимкам(строки: list) -> dict:
    """Два числа из цена_из_снимка: путь строителя и путь переноса, отдельно."""
    из_ = {"снимков": 0, "строитель_сверено": 0, "строитель_совпало": 0,
            "перенос_сверено": 0, "перенос_совпало": 0, "не_посчитано": 0,
            "почему": []}
    for с in (строки or []):
        с = с or {}
        из_["снимков"] += 1
        if not с.get("ok"):
            из_["не_посчитано"] += 1
            if с.get("why_not"):
                из_["почему"].append(str(с["why_not"])[:120])
            continue
        ключ = "строитель" if с.get("путь") == "строитель" else "перенос"
        из_[f"{ключ}_сверено"] += 1
        из_[f"{ключ}_совпало"] += bool(с.get("совпало"))
    из_["почему"] = sorted(set(из_["почему"]))[:3]
    return из_


