def объявление_остатка(данные: bytes) -> dict:
    """Vec<RemainingAccountsSlice> из хвоста данных swap2_with_transfer_hook.

    ЧТО ЗНАЧИТ length В СРЕЗЕ -- НЕ УСТАНОВЛЕНО, И ИМЕННО ПОЭТОМУ ОБЪЯВЛЕНИЕ
    ПЕРЕНОСИТСЯ КАК ЕСТЬ. В живых: 5 счетов хвоста при length 4 и 3 счёта при
    length 3. То есть length -- не «сколько счетов в хвосте»: при 5 счетах один
    под объявление не попадает, а сделка на цепи всё равно села. Без исходника
    ix_swap2_with_transfer_hook.rs объяснить это нечем, а значит СОБИРАТЬ это поле
    самим нельзя: мы переносим и хвост, и его объявление из инструкции источника
    неизменными, и тогда пара остаётся ровно той, что уже прошла на цепи.
    """
    if len(данные) < НАЧАЛО_ОБЪЯВЛЕНИЯ + 4:
        return {"ok": False,
                "why_not": (f"{ВИД_ХУК}: данных {len(данные)} байт -- объявление "
                             "остатка счетов в них не влезает")}
    (сколько,) = struct.unpack_from("<I", данные, НАЧАЛО_ОБЪЯВЛЕНИЯ)
    if not 1 <= сколько <= СРЕЗОВ_МАКС:
        return {"ok": False,
                "why_not": (f"{ВИД_ХУК}: срезов остатка объявлено {сколько}, "
                             f"а в живых сделках один")}
    нужно = НАЧАЛО_ОБЪЯВЛЕНИЯ + 4 + БАЙТ_НА_СРЕЗ * сколько
    if len(данные) != нужно:
        return {"ok": False,
                "why_not": (f"{ВИД_ХУК}: данных {len(данные)} байт, а по {сколько} "
                             f"срезам их должно быть {нужно}")}
    срезы = [(данные[НАЧАЛО_ОБЪЯВЛЕНИЯ + 4 + БАЙТ_НА_СРЕЗ * и],
              данные[НАЧАЛО_ОБЪЯВЛЕНИЯ + 5 + БАЙТ_НА_СРЕЗ * и])
             for и in range(сколько)]
    return {"ok": True, "срезы": срезы, "байты": данные[НАЧАЛО_ОБЪЯВЛЕНИЯ:]}


def хвост_к_минту(хвост, минт_базы: str) -> dict:
    """Привязан ли хвост счетов хука к ЭТОМУ минту -- выводом PDA, без сети.

    ЗАЧЕМ. Хвост мы переносим из чужой инструкции, и «перенесли что дали» -- не
    проверка. Проверка такая: среди счетов хвоста обязана найтись пара
    (программа хука P, счёт метаданных V), для которой
    V == PDA["extra-account-metas", минт_базы] у P. Это собственная арифметика
    spl-transfer-hook-interface, считается офлайн, и она доказывает, что хвост
    относится к минту НАШЕЙ покупки, а не к какому-то другому.
    У 22 живых инструкций с хуком из 22 такая пара находится (3 минта, 6
    подписантов).
    """
    try:
        from solders.pubkey import Pubkey  # noqa: PLC0415
    except Exception as exc:  # noqa: BLE001
        return {"ok": False,
                "why_not": f"вывести PDA хука нечем: нет solders ({type(exc).__name__})"}
    try:
        семя_минта = bytes(Pubkey.from_string(минт_базы))
    except Exception:  # noqa: BLE001
        return {"ok": False, "why_not": "минт базы не разбирается как адрес"}
    набор = set(хвост or [])
    for кандидат in (хвост or []):
        try:
            прог = Pubkey.from_string(кандидат)
        except Exception:  # noqa: BLE001
            continue
        pda = str(Pubkey.find_program_address(
            [СЕМЯ_МЕТАДАННЫХ_ХУКА, семя_минта], прог)[0])
        if pda in набор:
            return {"ok": True, "программа_хука": кандидат, "счёт_метаданных": pda}
    return {"ok": False, "why_not": ПРИЗНАК_ХВОСТ_НЕ_СВЕРЕН}


def хвост_без_ключей(хвост, программа_хука: str) -> dict:
    """В хвосте хука разрешены только PDA, сисвары и сама программа хука.

    ПОЧЕМУ ИМЕННО «НА КРИВОЙ». Счёт вне кривой ed25519 подписать невозможно: это
    PDA, и он принадлежит какой-то программе. Счёт НА кривой -- обычный ключ, у
    которого есть владелец с закрытой частью. Если такой ключ (кроме самой
    программы хука) стоит в хвосте, значит хук получает чужой ключ, и перенести
    его в свою покупку -- это либо подставить чужое, либо гадать, что хук
    проверяет. Проверка офлайн, сети не нужно.
    По 22 живым: вне кривой -- сисвар, счета метаданных и по одному доп-PDA на
    минт; на кривой -- две программы хука (это норма) и один плательщик.
    """
    try:
        from solders.pubkey import Pubkey  # noqa: PLC0415
    except Exception as exc:  # noqa: BLE001
        return {"ok": False,
                "why_not": f"проверить хвост нечем: нет solders ({type(exc).__name__})"}
    плохие = []
    for а in (хвост or []):
        if а == программа_хука:
            continue
        try:
            if Pubkey.from_string(а).is_on_curve():
                плохие.append(а)
        except Exception:  # noqa: BLE001
            плохие.append(а)
    if плохие:
        return {"ok": False,
                "why_not": f"{ПРИЗНАК_ХВОСТ_С_КЛЮЧОМ}: {плохие[0][:8]}",
                "ключи": плохие}
    return {"ok": True, "ключи": []}


def _подписанты(tx: dict) -> set:
    """Подписанты транзакции источника -- их в свой хвост тащить нельзя."""
    ключи = (((tx or {}).get("transaction") or {}).get("message") or {}).get("accountKeys") or []
    return {к.get("pubkey") for к in ключи
            if isinstance(к, dict) and к.get("signer")}


def шаблон(tx: dict, пул: str | None = None, *,
            хранилище: str | None = None) -> dict:
    """Шаблон инструкции swap DBC из транзакции источника.

    хранилище -- АДРЕС ХРАНИЛИЩА ПУЛА, а не пула. Полоса адреса пула не знает: у
    неё на руках только хранилище (C.identify_pool), и позвать шаблон по пулу она
    не может. Без этого на сделке РОУТЕРА, где инструкций этой программы
    несколько, брался бы ПЕРВЫЙ пул -- то есть чужой. Живой след: приёмка Code-1
    22:42:46Z, сделка 2W78d2uZSk... -- две инструкции CLMM (пулы 8sLbNZoA и
    BE9uiVCx), покупка во ВТОРОЙ, и полоса отказала словами «строитель взял
    инструкцию другого пула той же программы». По сборам Code-2 таких сделок
    1 из 34 у CLMM и 2 из 37 у Whirlpool.
    """
    из_ = {"ok": False, "why_not": None}
    B = _кирпичи()
    for их in B.all_instructions(tx):
        if их.get("programId") != ПРОГРАММА:
            continue
        счета = list(их.get("accounts") or [])
        try:
            данные = B.b58decode(их.get("data") or "")
        except Exception:  # noqa: BLE001
            continue
        вид = вид_по_данным(данные, B)
        if вид is None:
            continue
        if вид not in ДЛИНЫ_ДАННЫХ and вид != ВИД_ХУК:
            из_["why_not"] = (f"у источника инструкция {вид}: её раскладка и аргументы "
                               "другие, живых сделок с ней в данных нет")
            continue
        хук = (вид == ВИД_ХУК)
        хвост, объявл = [], None
        if хук:
            # У варианта с хуком к 15 местам раскладки ОБЯЗАН идти хвост счетов
            # хука: без него программа не сможет позвать хук перевода.
            if len(счета) <= РАСКЛАДКА["счетов"]:
                из_["why_not"] = (f"{ВИД_ХУК}: счетов {len(счета)}, а к 15 местам "
                                   "раскладки обязан идти хвост счетов хука")
                continue
            хвост = счета[РАСКЛАДКА["счетов"]:]
            if not СЧЕТОВ_ХУКА_МИН <= len(хвост) <= СЧЕТОВ_ХУКА_МАКС:
                из_["why_not"] = (f"{ВИД_ХУК}: в хвосте {len(хвост)} счетов, а в живых "
                                   f"их {СЧЕТОВ_ХУКА_МИН}--5 (потолок "
                                   f"{СЧЕТОВ_ХУКА_МАКС})")
                continue
            объявл = объявление_остатка(данные)
            if not объявл["ok"]:
                из_["why_not"] = объявл["why_not"]
                continue
        elif len(счета) != РАСКЛАДКА["счетов"]:
            из_["why_not"] = (f"счетов {len(счета)}, по раскладке "
                               f"{РАСКЛАДКА['счетов']}")
            continue
        мой_пул = счета[РАСКЛАДКА["пул"]]
        if пул and мой_пул != пул:
            continue
        if хранилище and хранилище not in счета:
            continue
        if not хук and len(данные) != ДЛИНЫ_ДАННЫХ[вид]:
            из_["why_not"] = (f"{вид}: данных {len(данные)} байт, по исходнику и по "
                               f"живым сделкам их {ДЛИНЫ_ДАННЫХ[вид]}")
            continue
        # SWAP_MODE -- ТОЛЬКО ExactIn. PartialFill (1) программа исполняет иначе:
        # берёт из входа столько, сколько уместилось, и остаток возвращает -- наш
        # min_out тогда сравнивается не с тем, что мы думаем. ExactOut (2) задаёт
        # выход, а не вход. Оба -- отказ по имени, а не попытка.
        режим = (данные[МЕСТО_SWAP_MODE] if вид in ("swap2", ВИД_ХУК)
                 else SWAP_MODE_EXACT_IN)
        if режим != SWAP_MODE_EXACT_IN:
            из_["why_not"] = (f"{вид}: swap_mode {режим} "
                               f"({ИМЕНА_SWAP_MODE.get(режим, 'неизвестный')}), а "
                               f"собирается только {SWAP_MODE_EXACT_IN} (ExactIn)")
            continue
        # ПОСТОЯННЫЕ СЧЕТА ПРОГРАММЫ ОБЯЗАНЫ СТОЯТЬ НА СВОИХ МЕСТАХ. Не стоят --
        # это не та раскладка, и подставлять в неё свой кошелёк нельзя.
        if счета[РАСКЛАДКА["pool_authority"]] != POOL_AUTHORITY:
            из_["why_not"] = (f"на месте 0 не распорядитель хранилищ программы "
                               f"({счета[0][:8]})")
            continue
        if счета[РАСКЛАДКА["программа"]] != ПРОГРАММА:
            из_["why_not"] = f"на месте 14 не сама программа ({счета[14][:8]})"
            continue
        # МЕСТО РЕФЕРАЛА -- ТОЛЬКО ПУСТОЕ. referral_token_account объявлен как
        # Option (ix_swap.rs), и когда реферала нет, Anchor ждёт на этом месте
        # саму программу -- так в обеих живых сделках. Перенести ЧУЖОЙ счёт
        # реферала нельзя: программа увидит has_referral и переведёт на него
        # реферальную комиссию из хранилища пула, причём минт этой комиссии
        # зависит от направления. Живой сделки с рефералом в данных нет, значит
        # путь не проверен -- честный отказ.
        if счета[РАСКЛАДКА["реферал"]] not in (ПРОГРАММА, EVENT_AUTHORITY):
            из_["why_not"] = (f"у источника на месте реферала стоит счёт "
                               f"{счета[РАСКЛАДКА['реферал']][:8]} -- переносить чужой "
                               "счёт реферала нельзя, а живой сделки с рефералом в "
                               "данных нет")
            continue
        хук_поля = {}
        if хук:
            # 1. ХУК БЫВАЕТ ТОЛЬКО У TOKEN-2022. Расширение TransferHook живёт в
            # Token-2022; если на месте программы базы обычный Token, то это не
            # тот вариант инструкции, и хвост объяснить нечем (в живых 22 из 22 --
            # Token-2022).
            if счета[РАСКЛАДКА["программа_базы"]] != ПРОГРАММА_2022:
                из_["why_not"] = (f"{ВИД_ХУК}: на месте программы базы не Token-2022 "
                                   f"({счета[РАСКЛАДКА['программа_базы']][:8]}), а хук "
                                   "перевода бывает только у него")
                continue
            # 2. В ХВОСТЕ НЕ ДОЛЖНО БЫТЬ НИ ОДНОГО СЧЁТА ИСТОЧНИКА. Хвост мы
            # переносим целиком, и попади в него его кошелёк или его токеновый
            # счёт -- мы бы тащили в свою покупку чужой счёт (а подписи его у нас
            # нет). В живых 22 из 22 чисто.
            свои_места = {счета[РАСКЛАДКА["счёт_входа"]],
                           счета[РАСКЛАДКА["счёт_выхода"]],
                           счета[РАСКЛАДКА["подписант"]]}
            грязь = sorted((свои_места | _подписанты(tx)) & set(хвост))
            if грязь:
                из_["why_not"] = (f"{ВИД_ХУК}: в хвосте хука счёт источника "
                                   f"{грязь[0][:8]} -- переносить его нельзя")
                continue
            # 3. ХВОСТ ОБЯЗАН БЫТЬ ХВОСТОМ ЭТОГО МИНТА -- выводом PDA, офлайн.
            пр = хвост_к_минту(хвост, счета[РАСКЛАДКА["минт_базы"]])
            if not пр["ok"]:
                из_["why_not"] = f"{ВИД_ХУК}: {пр['why_not']}"
                continue
            # 4. В ХВОСТЕ -- ТОЛЬКО PDA, СИСВАРЫ И САМА ПРОГРАММА ХУКА. Живой
            # случай: у минта ZrueWB1Y… в хвосте стоит плательщик транзакции
            # источника. Это его ключ, не наш.
            бк = хвост_без_ключей(хвост, пр["программа_хука"])
            if not бк["ok"]:
                из_["why_not"] = f"{ВИД_ХУК}: {бк['why_not']}"
                continue
            хук_поля = {"хвост": list(хвост),
                        "срезы": объявл["срезы"],
                        "объявление_остатка": объявл["байты"],
                        "программа_хука": пр["программа_хука"],
                        "счёт_метаданных_хука": пр["счёт_метаданных"]}
        arg0, arg1 = struct.unpack_from("<QQ", данные, 8)
        return {"ok": True, "program": ПРОГРАММА, "вид": вид, "ix": вид,
                "accounts": счета, "data": данные, "arg0": arg0, "arg1": arg1,
                "writable": B.writable_map(tx), "пул": мой_пул,
                "swap_mode": режим, "хук": хук,
                "конфиг": счета[РАСКЛАДКА["config"]], **хук_поля}
    из_["why_not"] = из_["why_not"] or (
        "инструкции swap DBC"
        + (f" по пулу {пул}" if пул else "")
        + (f" со хранилищем {хранилище}" if хранилище else "")
        + " в транзакции нет")
    return из_


def стороны(tpl: dict, tx: dict) -> dict:
    """Минты и программы базы и котировки -- прямо из инструкции (места 7, 8, 10, 11).

    Они не зависят от направления: программа проверяет их по хранилищам
    (`token::mint = base_mint`, `token::mint = quote_mint`).
    """
    счета = tpl["accounts"]
    return {"ok": True,
            "минт_базы": счета[РАСКЛАДКА["минт_базы"]],
            "минт_котировки": счета[РАСКЛАДКА["минт_котировки"]],
            "программа_базы": счета[РАСКЛАДКА["программа_базы"]],
            "программа_котировки": счета[РАСКЛАДКА["программа_котировки"]],
            "хранилище_базы": счета[РАСКЛАДКА["хранилище_базы"]],
            "хранилище_котировки": счета[РАСКЛАДКА["хранилище_котировки"]]}


def направление_источника(tpl: dict, tx: dict) -> dict:
    """Была ли сделка источника ПОКУПКОЙ (котировка -> база) по движению хранилищ.

    Признака направления в данных инструкции нет: программа берёт его из минта
    счёта входа. Поэтому направление сделки источника читается фактом цепи --
    движением хранилищ пула в его же транзакции.
    """
    import c2_common as C  # noqa: PLC0415

    с = стороны(tpl, tx)
    строки = {р["account"]: р for р in C.token_rows(tx).values()}
    хк = строки.get(с["хранилище_котировки"])
    хб = строки.get(с["хранилище_базы"])
    if not хк or not хб:
        return {"ok": False, "why_not": "хранилищ пула нет в балансах транзакции"}
    вход = хк["post"] - хк["pre"]
    выход = хб["pre"] - хб["post"]
    if вход > 0 and выход > 0:
        return {"ok": True, "покупка": True, "вход_источника": вход,
                "выход_источника": выход}
    if вход < 0 and выход < 0:
        return {"ok": True, "покупка": False, "вход_источника": -выход,
                "выход_источника": -вход}
    return {"ok": False,
            "why_not": (f"движение хранилищ не читается как своп "
                         f"(котировка {вход:+d}, база {выход:+d})")}


def пользователь_шаблона(tpl: dict) -> str | None:
    счета = (tpl or {}).get("accounts") or []
    м = РАСКЛАДКА["подписант"]
    return счета[м] if м < len(счета) else None


def места_наших_счетов(tpl: dict) -> list:
    return [РАСКЛАДКА["подписант"], РАСКЛАДКА["счёт_входа"], РАСКЛАДКА["счёт_выхода"]]


def шаблон_со_сторонами(tpl: dict, tx: dict) -> dict:
    """Шаблон с прикреплёнными сторонами и направлением САМОЙ сделки источника."""
    с = стороны(tpl, tx)
    н = направление_источника(tpl, tx)
    if not н.get("ok"):
        return {"ok": False, "why_not": н.get("why_not")}
    вх, вых = ((с["минт_котировки"], с["минт_базы"]) if н["покупка"]
               else (с["минт_базы"], с["минт_котировки"]))
    пвх, пвых = ((с["программа_котировки"], с["программа_базы"]) if н["покупка"]
                 else (с["программа_базы"], с["программа_котировки"]))
    return {"ok": True, "стороны": с, "направление": н,
            "шаблон": dict(tpl, минт_входа=вх, минт_выхода=вых,
                            программа_входа=пвх, программа_выхода=пвых)}


def под_покупку(tpl: dict, tx: dict, *, минт_котировки: str = WSOL) -> dict:
    """Шаблон, развёрнутый под покупку: вход -- минт котировки пула.

    Если сделка источника была ПРОДАЖЕЙ, переставляются ровно места 3 и 4:
    программа берёт направление из минта счёта входа, а места 5--8 (хранилища и
    минты базы и котировки) от направления не зависят.
    """
    ш = шаблон_со_сторонами(tpl, tx)
    if not ш.get("ok"):
        return {"ok": False, "why_not": ш.get("why_not")}
    с = ш["стороны"]
    if с["минт_котировки"] != минт_котировки:
        return {"ok": False,
                "why_not": не_та_котировка(минт_котировки, с["минт_базы"],
                                            с["минт_котировки"])}
    счета = list(tpl["accounts"])
    развёрнут = False
    if not ш["направление"]["покупка"]:
        и, ж = РАСКЛАДКА["счёт_входа"], РАСКЛАДКА["счёт_выхода"]
        счета[и], счета[ж] = счета[ж], счета[и]
        развёрнут = True
    return {"ok": True, "развёрнут": развёрнут, "стороны": с,
            "направление": ш["направление"],
            "минт_базы": с["минт_базы"], "минт_котировки": с["минт_котировки"],
            "программа_базы": с["программа_базы"],
            "программа_котировки": с["программа_котировки"],
            "шаблон": dict(tpl, accounts=счета,
                            минт_входа=с["минт_котировки"],
                            минт_выхода=с["минт_базы"],
                            программа_входа=с["программа_котировки"],
                            программа_выхода=с["программа_базы"])}


