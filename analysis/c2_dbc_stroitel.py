def хранилища_сторон(tpl: dict, минт_котировки: str, минт_базы: str) -> dict:
    """Хранилища пула ПО СТОРОНАМ ПОЛОСЫ (котировка/база).

    У DBC база и котировка стоят на своих местах инструкции (7 и 8, хранилища --
    5 и 6) и от направления не зависят. Но «котировка» у пула и «котировка» у
    полосы -- не одно и то же: полоса котировкой считает SOL. Поэтому
    сопоставление всё равно идёт ПО МИНТУ; не совпало -- отказ с None.
    """
    счета = list((tpl or {}).get("accounts") or [])
    if len(счета) < РАСКЛАДКА["счетов"]:
        return {"котировки": None, "базы": None,
                "why_not": "раскладка шаблона не опознана"}
    м_базы, м_кот = счета[РАСКЛАДКА["минт_базы"]], счета[РАСКЛАДКА["минт_котировки"]]
    if not м_базы or not м_кот or м_базы == м_кот:
        return {"котировки": None, "базы": None,
                "why_not": "минты сторон пула не известны"}
    хр = {м_базы: счета[РАСКЛАДКА["хранилище_базы"]],
          м_кот: счета[РАСКЛАДКА["хранилище_котировки"]]}
    if минт_котировки not in хр or минт_базы not in хр:
        return {"котировки": None, "базы": None,
                "why_not": "названный минт не совпал ни с одной стороной пула"}
    return {"котировки": хр[минт_котировки], "базы": хр[минт_базы]}


