def _счета(rpc_call, адреса: list, *, таймаут: float = 3.0) -> dict:
    """getMultipleAccounts одним запросом: адрес -> сырые байты (или None)."""
    из_ = {"ok": False, "данные": {}, "why_not": None, "slot": None, "мс": None}
    т0 = time.perf_counter()
    try:
        о = rpc_call("getMultipleAccounts",
                      [адреса, {"encoding": "base64", "commitment": "confirmed"}])
    except Exception as exc:  # noqa: BLE001
        из_["why_not"] = f"{type(exc).__name__}: {str(exc)[:120]}"
        из_["мс"] = round((time.perf_counter() - т0) * 1000.0, 2)
        return из_
    из_["мс"] = round((time.perf_counter() - т0) * 1000.0, 2)
    о = о if isinstance(о, dict) else {}
    рез = о.get("result") if "result" in о else о
    if not isinstance(рез, dict):
        из_["why_not"] = f"ответ узла не разобран: {str(о)[:120]}"
        return из_
    из_["slot"] = ((рез.get("context") or {}).get("slot")
                    if isinstance(рез.get("context"), dict) else None)
    значения = рез.get("value")
    if not isinstance(значения, list) or len(значения) != len(адреса):
        из_["why_not"] = "узел вернул не столько счетов, сколько спрашивали"
        return из_
    import base64  # noqa: PLC0415

    for адрес, зн in zip(адреса, значения):
        if not зн:
            из_["данные"][адрес] = None
            continue
        д = (зн.get("data") or [None, None])[0]
        try:
            из_["данные"][адрес] = base64.b64decode(д) if д else None
        except Exception:  # noqa: BLE001
            из_["данные"][адрес] = None
    из_["ok"] = True
    return из_


def котировка(*, пул: str, минт_базы: str, минт_котировки: str, лампорты: int,
               проскальзывание: float, rpc_call, сейчас: float | None = None,
               конфиг: str | None = None, налог_выхода=None, налог_входа=None,
               программа_выхода: str | None = None,
               программа_входа: str | None = None, **_прочее) -> dict:
    """ТОЧНАЯ цена DBC из живого состояния кривой: счёт пула и счёт конфигурации.

    Цену считает перенос кода программы Code-2 (analysis/podbivka_dbc_quote.py,
    коммит MeteoraAg/dynamic-bonding-curve f552f20): кусочная кривая до 20 точек,
    расписание базовой комиссии, ограничитель по размеру покупки и переменная
    комиссия по накопителю волатильности. Своей математики здесь нет.

    ЧТЕНИЕ ОДНО, А НЕ ДВА. У кривой нет массивов тиков или корзин, поэтому пул и
    конфигурация читаются ОДНИМ getMultipleAccounts -- и состояние заведомо из
    одного слота, без той развилки «между чтениями цена ушла», что есть у CLMM и
    Whirlpool.

    ВРЕМЯ ИЛИ СЛОТ -- ПО КОНФИГУРАЦИИ. Расписание комиссии считается от
    current_point, а чем он мерится, говорит cfg["activation_type"]: 0 -- слот,
    1 -- unix-время. Подставить не то значило бы взять комиссию другого периода.
    """
    из_ = {"ok": False, "why_not": None, "чтений": 0, "точная": True,
            "путь": "точная котировка DBC"}
    if лампорты <= 0:
        из_["why_not"] = "сумма входа не положительна"
        return из_
    н = _налог_сторон(налог_выхода, налог_входа, программа_выхода, программа_входа)
    if not н["ok"]:
        из_["why_not"] = н["why_not"]
        return из_
    try:
        Q = _порт()
    except Exception:  # noqa: BLE001
        из_["why_not"] = ("переноса математики кривой DBC нет (модуль "
                           "podbivka_dbc_quote), точную цену считать нечем")
        return из_
    for имя in ("разобрать_пул", "разобрать_конфиг", "котировка_точный_вход"):
        if not hasattr(Q, имя):
            из_["why_not"] = (f"перенос DBC есть, но в нём нет {имя} -- вид не тот, "
                               "что у переносов CLMM и Whirlpool")
            return из_
    if not порт_сверен():
        из_["why_not"] = (f"{ПРИЗНАК_ПОРТ_НЕ_СВЕРЕН}: перенос podbivka_dbc_quote "
                           f"подключён, но сбора состояний (dbc_sbor.json) нет и ни "
                           f"одной сделки им не проверено -- замок {ИМЯ_ФЛАГА_СВЕРКИ} "
                           f"открывает Code-1 после доклада Code-2")
        return из_
    if rpc_call is None:
        из_["why_not"] = "узел недоступен, состояние кривой не прочитать"
        return из_
    if not конфиг:
        из_["why_not"] = "адрес конфигурации пула не назван (место 1 инструкции)"
        return из_

    ч = _счета(rpc_call, [пул, конфиг])
    из_["чтений"] += 1
    из_["мс_чтений_всего"] = ч.get("мс")
    из_["slot"] = ч.get("slot")
    if not ч["ok"]:
        из_["why_not"] = f"состояние кривой не прочитано: {ч['why_not']}"
        return из_
    д_пула, д_конфига = ч["данные"].get(пул), ч["данные"].get(конфиг)
    if not д_пула:
        из_["why_not"] = "счёта пула нет на цепи"
        return из_
    if not д_конфига:
        из_["why_not"] = f"счёта конфигурации {конфиг} нет на цепи"
        return из_
    try:
        pool = Q.разобрать_пул(д_пула)
    except Exception as exc:  # noqa: BLE001
        из_["why_not"] = f"пул не разобрался: {type(exc).__name__}: {str(exc)[:120]}"
        return из_
    try:
        cfg = Q.разобрать_конфиг(д_конфига)
    except Exception as exc:  # noqa: BLE001
        из_["why_not"] = f"конфигурация не разобралась: {type(exc).__name__}: {str(exc)[:120]}"
        return из_
    # КОНФИГУРАЦИЯ ОБЯЗАНА БЫТЬ ЭТОГО ПУЛА. Её адрес мы берём с места 1
    # инструкции источника, а пул держит его у себя полем config: не сошлось --
    # прочитана чужая настройка, и комиссия с кривой тоже чужие.
    if pool.get("config") != конфиг:
        из_["why_not"] = (f"пул ссылается на конфигурацию {str(pool.get('config'))[:8]}, "
                           f"а прочитана {конфиг[:8]}")
        return из_
    if минт_базы and pool.get("base_mint") != минт_базы:
        из_["why_not"] = (f"база пула {str(pool.get('base_mint'))[:8]} не тот минт, "
                           f"который покупаем ({минт_базы[:8]})")
        return из_
    if минт_котировки and cfg.get("quote_mint") != минт_котировки:
        из_["why_not"] = не_та_котировка(минт_котировки, pool.get("base_mint"),
                                          cfg.get("quote_mint"))
        return из_
    из_.update(активация=pool.get("activation_point"),
                тип_активации=cfg.get("activation_type"),
                резерв_котировки=pool.get("quote_reserve"),
                порог_миграции=cfg.get("migration_quote_threshold"),
                режим_комиссии=cfg.get("collect_fee_mode"),
                был_своп=pool.get("has_swap"))
    # CURRENT_POINT -- СЛОТ ИЛИ ВРЕМЯ, как скажет конфигурация. Слот берём тот, в
    # котором прочитано состояние; время -- ожидаемое время сделки.
    if int(cfg.get("activation_type") or 0) == 0:
        точка = ч.get("slot")
        если_нет = "узел не назвал слот чтения, а расписание комиссии считается по слотам"
    else:
        точка = int(сейчас if сейчас is not None else time.time())
        если_нет = None
    if точка is None:
        из_["why_not"] = если_нет
        return из_
    из_["current_point"] = int(точка)
    try:
        # ПЕРВЫЙ СВОП С МИНИМАЛЬНОЙ КОМИССИЕЙ -- всегда False, и это выбор в
        # СТОРОНУ БЕЗОПАСНОСТИ. Скидка бывает, когда конфигурация её включила и
        # пул создан в той же транзакции; наша покупка -- копия чужой сделки в
        # уже существующем пуле, то есть своп там точно не первый. Ошибиться в
        # сторону скидки значило бы занизить комиссию, завысить min_out и
        # получить откат; ошибиться в нашу сторону -- лишь недооценить выход.
        q = Q.котировка_точный_вход(pool, cfg, int(лампорты), True, int(точка),
                                     has_referral=False, первый_своп_мин=False)
    except Exception as exc:  # noqa: BLE001
        из_["why_not"] = f"котировка не посчиталась: {type(exc).__name__}: {str(exc)[:160]}"
        return из_
    ожидаем = int(q.get("output_amount") or 0)
    if ожидаем <= 0:
        из_["why_not"] = "котировка дала ноль на выходе"
        return из_
    # НАЛОГ ПЕРЕВОДА МИНТА ВЫХОДА -- поверх комиссии пула: перенос отдаёт сырые
    # единицы хранилища, а на наш счёт придёт меньше на налог расширения.
    сырой = ожидаем
    if налог_назван(налог_выхода):
        ожидаем = без_налога(ожидаем, налог_выхода[0],
                              налог_выхода[1] if len(налог_выхода) > 1 else None)
    if ожидаем <= 0:
        из_["why_not"] = f"налог перевода минта выхода съедает весь выход ({сырой})"
        return из_
    мин = int(ожидаем * (1.0 - float(проскальзывание)))
    if мин <= 0:
        из_["why_not"] = "минимум выхода не положителен при этом проскальзывании"
        return из_
    из_.update(ok=True, expected_out=ожидаем, min_out=мин, выход_до_налога=сырой,
                налог_выхода_учтён=налог_назван(налог_выхода),
                fee=(int(q.get("trading_fee") or 0) + int(q.get("protocol_fee") or 0)
                      + int(q.get("referral_fee") or 0)),
                trading_fee=q.get("trading_fee"), protocol_fee=q.get("protocol_fee"),
                # ДОЛЯ КОМИССИИ ПУЛА -- по числителю из переноса, а не по делению
                # сборов на вход: при комиссии НА ВЫХОДЕ (collect_fee_mode = 1)
                # сборы сняты с выходного токена, и делить их на лампорты входа
                # значило бы сравнивать разные единицы. Потолок комиссии полосы
                # читает именно это число.
                fee_share=(int(q.get("fee_numerator") or 0) / Q.FEE_DENOMINATOR),
                fee_numerator=q.get("fee_numerator"),
                base_fee_numerator=q.get("base_fee_numerator"),
                комиссия_на_входе=q.get("fees_on_input"),
                sqrt_price_после=q.get("next_sqrt_price"))
    return из_


def приближение_по_событию(tpl: dict, tx: dict, *, лампорты: int,
                            проскальзывание: float, налог_выхода=None,
                            налог_входа=None, программа_выхода: str | None = None,
                            программа_входа: str | None = None) -> dict:
    """ПРИБЛИЖЁННАЯ цена: продолжение кривой от цены ПОСЛЕ сделки источника.

    Это уже существующий счёт полосы (c2_swap_build.dbc_min_out), позванный
    отсюда без правки общего кода. Он помечается точная=False и по умолчанию
    не используется: на входе больше участка кривой он врёт.
    """
    из_ = {"ok": False, "why_not": None, "точная": False,
            "путь": "по событию сделки источника (приближение)"}
    н = _налог_сторон(налог_выхода, налог_входа, программа_выхода, программа_входа)
    if not н["ok"]:
        из_["why_not"] = н["why_not"]
        return из_
    try:
        B = _кирпичи()
    except Exception as exc:  # noqa: BLE001
        из_["why_not"] = f"модуль сборки не загружен: {type(exc).__name__}"
        return из_
    # dbc_min_out читает роли по SPECS[DBC], поэтому ему нужен шаблон в том же
    # виде, в каком его отдаёт c2_swap_build.extract_template.
    свой = {"ok": True, "program": ПРОГРАММА, "ix": "swap",
            "accounts": list(tpl["accounts"]), "data": tpl["data"],
            "arg0": tpl["arg0"], "arg1": tpl["arg1"],
            "writable": tpl.get("writable") or {}, "signers": []}
    try:
        м = B.dbc_min_out(свой, tx, int(лампорты), float(проскальзывание))
    except Exception as exc:  # noqa: BLE001
        из_["why_not"] = f"приближение упало: {type(exc).__name__}: {str(exc)[:140]}"
        return из_
    м = м if isinstance(м, dict) else {}
    if not м.get("ok"):
        из_["why_not"] = f"приближение не выдано: {м.get('why_not')}"
        return из_
    # НАЛОГ МИНТА ВЫХОДА -- тем же правилом, что у CLMM и Whirlpool: dbc_min_out
    # считает по движению ХРАНИЛИЩА пула, то есть до налога перевода.
    ожидаем = int(м.get("expected_out") or 0)
    сырой = ожидаем
    if налог_назван(налог_выхода) and ожидаем > 0:
        ожидаем = без_налога(ожидаем, налог_выхода[0],
                              налог_выхода[1] if len(налог_выхода) > 1 else None)
    if ожидаем <= 0:
        из_["why_not"] = f"налог перевода минта выхода съедает весь выход ({сырой})"
        return из_
    мин = int(ожидаем * (1.0 - float(проскальзывание)))
    if мин <= 0:
        из_["why_not"] = "минимум выхода не положителен при этом проскальзывании"
        return из_
    из_.update(ok=True, min_out=мин, expected_out=ожидаем,
                выход_до_налога=сырой,
                налог_выхода_учтён=налог_назван(налог_выхода),
                fee_share=м.get("fee_share"), source_in=м.get("source_in"),
                source_out=м.get("source_out"), чтений=0)
    return из_


