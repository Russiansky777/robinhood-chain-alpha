def подготовить(tx_источника: dict, *, пул: str | None = None,
                 хранилище_пула: str | None = None,
                 лампорты: int, проскальзывание: float, rpc_call=None,
                 минт_котировки: str = WSOL, минт_базы: str | None = None,
                 группа: str | None = None, сейчас: float | None = None,
                 котировщик=None, налог_выхода=None, налог_входа=None,
                 разрешить_приближение: bool = False) -> dict:
    """ВСЁ, что полосе нужно от строителя DBC, одним вызовом. Смотри
    _подготовить_внутри: здесь только перевод сбоя в отказ, без исключений наружу."""
    try:
        о = _подготовить_внутри(
            tx_источника, пул=пул, хранилище_пула=хранилище_пула, лампорты=лампорты,
            проскальзывание=проскальзывание, rpc_call=rpc_call,
            минт_котировки=минт_котировки, минт_базы=минт_базы, группа=группа,
            сейчас=сейчас, котировщик=котировщик, налог_выхода=налог_выхода,
            налог_входа=налог_входа, разрешить_приближение=разрешить_приближение)
    except Exception as exc:  # noqa: BLE001
        return {"ok": False, "шаблон": None, "min_out": None, "expected_out": None,
                "why_not": f"строитель упал внутри: {type(exc).__name__}: {str(exc)[:160]}"}
    return о if isinstance(о, dict) else {
        "ok": False, "шаблон": None, "why_not": "строитель вернул не словарь"}


def _подготовить_внутри(tx_источника: dict, *, пул: str | None = None,
                 хранилище_пула: str | None = None,
                 лампорты: int, проскальзывание: float, rpc_call=None,
                 минт_котировки: str = WSOL, минт_базы: str | None = None,
                 группа: str | None = None, сейчас: float | None = None,
                 котировщик=None, налог_выхода=None, налог_входа=None,
                 разрешить_приближение: bool = False) -> dict:
    """ВСЁ, что полосе нужно от строителя DBC, одним вызовом.

    ПО УМОЛЧАНИЮ ОТКАЗЫВАЕТ, пока нет переноса математики кривой: приближение по
    одной точке на деньгах не выдаётся за точную цену. разрешить_приближение=True
    возвращает приближённый минимум с пометкой точная=False.
    
    ИСКЛЮЧЕНИЙ НАРУЖУ НЕ ОТДАЁТ. Замечание Code-1 с приёмки: «подготовить() внутри
    не обёрнут try/except -- сломанная meta или недостающий перенос цены вышли бы
    исключением наверх», и тогда причина в журнале выглядит как «строитель:
    KeyError:» без внятного смысла. Поэтому вся работа идёт во вложенной функции, а
    здесь только перевод любого сбоя в честный отказ словами.
    """
    из_ = {"ok": False, "why_not": None, "шаблон": None, "min_out": None,
            "expected_out": None, "чтений": None, "точная": None}
    if not включён(группа):
        из_["why_not"] = f"строитель DBC выключен флагом {ИМЯ_ФЛАГА}"
        return из_
    т = шаблон(tx_источника, пул, хранилище=хранилище_пула)
    if not т.get("ok"):
        из_["why_not"] = f"шаблон: {т.get('why_not')}"
        return из_
    из_.update(вид=т["вид"], пул=т["пул"], конфиг=т["конфиг"])
    п = под_покупку(т, tx_источника, минт_котировки=минт_котировки)
    if not п.get("ok"):
        из_["why_not"] = п.get("why_not")
        return из_
    # МИНТ БАЗЫ ИЗ СИГНАЛА ОБЯЗАН СОВПАСТЬ С БАЗОЙ ПУЛА. Иначе полоса запишет
    # позицию по одному токену, а транзакция купит другой: у DBC база стоит прямо
    # в инструкции (место 7), и сверить нечего не мешает. У CLMM и Whirlpool такая
    # сверка уже есть, здесь её не было.
    if минт_базы and минт_базы != п["минт_базы"]:
        из_["why_not"] = (f"минт сигнала {минт_базы[:8]} не база этого пула "
                           f"({п['минт_базы'][:8]}) -- купили бы не тот токен")
        return из_
    база = п["минт_базы"]
    из_.update(развёрнут=п["развёрнут"], минт_базы=база,
                минт_котировки=п["минт_котировки"],
                программа_базы=п["программа_базы"],
                программа_котировки=п["программа_котировки"],
                вход_источника=(п["направление"] or {}).get("вход_источника"),
                выход_источника=(п["направление"] or {}).get("выход_источника"))
    к = (котировщик or котировка)(
        пул=т["пул"], минт_базы=база, минт_котировки=п["минт_котировки"],
        лампорты=int(лампорты), проскальзывание=float(проскальзывание),
        rpc_call=rpc_call, сейчас=сейчас, конфиг=т["конфиг"],
        налог_выхода=налог_выхода, налог_входа=налог_входа,
        программа_выхода=п["программа_базы"],
        программа_входа=п["программа_котировки"])
    к = к if isinstance(к, dict) else {}
    # ПРИЧИНУ ОТКАЗА ТОЧНОЙ ЦЕНЫ СОХРАНЯЕМ ДАЖЕ ТОГДА, КОГДА ПОТОМ СРАБОТАЛО
    # ПРИБЛИЖЕНИЕ. Иначе ответ выглядит успехом, и почему точной цены не было --
    # не видно ни в проверке, ни в журнале.
    if not к.get("ok"):
        из_["отказ_точной"] = к.get("why_not")
    if not к.get("ok") and разрешить_приближение:
        к = приближение_по_событию(п["шаблон"], tx_источника, лампорты=лампорты,
                                    проскальзывание=проскальзывание,
                                    налог_выхода=налог_выхода,
                                    налог_входа=налог_входа,
                                    программа_выхода=п["программа_базы"],
                                    программа_входа=п["программа_котировки"])
    из_.update(чтений=к.get("чтений"), точная=к.get("точная"),
                путь_цены=к.get("путь"), fee_share=к.get("fee_share"))
    if not к.get("ok"):
        из_["why_not"] = f"цена не выдана: {к.get('why_not')}"
        return из_
    # У DBC меняющихся счетов нет: подставлять из состояния нечего, шаблон идёт
    # как есть (с переставленными местами 3 и 4, если источник продавал).
    из_.update(ok=True, шаблон=п["шаблон"], min_out=к.get("min_out"),
                expected_out=к.get("expected_out"))
    return из_


