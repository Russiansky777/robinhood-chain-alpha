def направление_источника(tpl: dict, tx: dict) -> dict:
    """Была ли сделка источника ПОКУПКОЙ (котировка -> база) по движению хранилищ.

    Признака направления в данных инструкции нет: программа берёт его из минта
    счёта входа. Поэтому направление сделки источника читается фактом цепи --
    движением хранилищ пула в его же транзакции.
    """
    import c2_common as C  # noqa: PLC0415

    с = стороны(tpl, tx)
    строки = {р["account"]: р for р in C.token_rows(tx).values()}
    хк = строки.get(с["хранилище_котировки"])
    хб = строки.get(с["хранилище_базы"])
    if not хк or not хб:
        return {"ok": False, "why_not": "хранилищ пула нет в балансах транзакции"}
    вход = хк["post"] - хк["pre"]
    выход = хб["pre"] - хб["post"]
    if вход > 0 and выход > 0:
        return {"ok": True, "покупка": True, "вход_источника": вход,
                "выход_источника": выход}
    if вход < 0 and выход < 0:
        return {"ok": True, "покупка": False, "вход_источника": -выход,
                "выход_источника": -вход}
    return {"ok": False,
            "why_not": (f"движение хранилищ не читается как своп "
                         f"(котировка {вход:+d}, база {выход:+d})")}


