    издержки = float((кал.get("калибровка") or {}).get("издержки_медиана_sol") or 0.002)

    сделки = Ж.сделки(s=а.s)
    посадка = RV.посадка_из_живых(сделки)
    доля_s0 = float(посадка["всего"]["S+0"])

    # ---------- п.1а: живые сделки, только S+0
    живые_s0 = [x for x in сделки if x.get("s_plus") == 0]
    п1а: dict = {"всего": свод_живых(живые_s0), "по_отрезкам": {}, "по_источникам": {}}
    for имя, с_, до_ in ОТРЕЗКИ:
        ч = [x for x in живые_s0 if (not с_ or x["utc"] >= с_) and (not до_ or x["utc"] < до_)]
        п1а["по_отрезкам"][имя] = свод_живых(ч)
    счёт_ист = collections.Counter(x["source"] for x in живые_s0 if x.get("source"))
    for a, n in счёт_ист.most_common():
        if n >= 10:
            ч = [x for x in живые_s0 if x.get("source") == a]
            п1а["по_источникам"][a] = свод_живых(ч) | {
                "имя": next((x.get("source_name") for x in ч if x.get("source_name")), None),
                "группы": sorted({x["group"] for x in ч if x.get("group")})}

    # ---------- п.1б: S+0 против S+1, разрезы
    по_подписи: dict = collections.defaultdict(list)
    for с in сделки:
        if с.get("source_sig") and с.get("s_plus") in (0, 1) and с.get("итог") is not None:
            по_подписи[с["source_sig"]].append(с)
    сигналы = {}
    for р in O.сигналы(фильтр=lambda r: r.get("подпись") in по_подписи):
        сигналы[р["подпись"]] = р
    пары = []
    for sig, сдс in по_подписи.items():
        р = сигналы.get(sig)
        for с in сдс:
            if not с.get("вложено"):
                continue
            св = ((р or {}).get("свопов") or {})
            пары.append({"ист": с.get("source"), "s_plus": с["s_plus"], "итог": с["итог"],
                         "пп": 100 * с["итог"] / с["вложено"],
                         "резерв": (р or {}).get("резерв_sol") or с.get("pool_reserve_sol"),
                         "час": int(с["utc"][11:13]) if len(с.get("utc") or "") > 12 else None,
                         # в проходе есть только свопы следующих слотов (s1/s2); берём s1 как
                         # меру занятости слота -- для S+0 своё число свопов внутри блока
                         # источника архив не пишет
                         "свопов": св.get("s1"),
                         "место_ист": с.get("source_block_index"),
                         "группа": с.get("group")})
    п1б = разрезы_s0_s1(пары)

    # ---------- п.1в / п.2 / п.3: архив, оба режима, все источники с n >= 50
    ряды, счёт = прогон(посадка, а.vyhod, издержки, к_g)
    дни = sorted({x["сутки"] for x in ряды})
    граница = max(len(дни) - max(4, round(len(дни) / 3)), 1)
    подбор, проверка = дни[:граница], дни[граница:]
    пол1, пол2 = проверка[:len(проверка) // 2], проверка[len(проверка) // 2:]
    адр = O.реестр()
    торг = {a for a in адр if O.группа_адреса(адр, a)}

    по_ист: dict = collections.defaultdict(list)
    for x in ряды:
        по_ист[x["ист"]].append(x)

    удача: dict = {}
    for режим in РЕЖИМЫ:
        поле = "итоги" if режим == "обычный" else "итоги_s0"
        пров = [{**x, "итоги": x[поле]} for x in ряды if x["сутки"] in проверка and x.get(поле)]
        удача[режим] = {б: RV.перестановки(пров, б, а.povtorov) for б in БИЛЕТЫ}

