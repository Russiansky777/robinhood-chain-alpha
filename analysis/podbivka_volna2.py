"""Волна, часть 2: можно ли включать 4vw54BmA и есть ли ещё такие (задача владельца 08.10).

А. 4vw54BmA при ОБЫЧНОЙ посадке полосы (S+0 37 % / S+1 57 % / S+2 6 %) и удержании 15 с --
   держится ли результат без режима «только S+0», и не стоит ли он на одной точке выхода.
   Отдельно S+1-сделки, соседние удержания, свежие сутки, и кто это такой.
Б. Сито «как 4vw54BmA» по признаку толпы и раннего пика -- и по реестру (765 адресов со
   состояниями пула), и по широкой вселенной (файлы cand2_*/konv_*, десять тысяч трейдеров
   в сутки). У вселенной состояний пула нет, но есть `свопов`, `рисунок`, `удержание` и
   готовые п.п. прохода при билете 0.1 -- этого хватает на сито; для билетов крупнее нужен
   прицельный проход, список на него печатается.

Модель -- калиброванная (`data/podbivka/kalibrovka.json`): место входа по посадке, издержки
круга по цепи, сдвиг цены по резервам пула, множитель наценки выхода к_g. Пороги -- как в
`docs/podbivka_final.md`: на проверке n >= 100, медиана > 0, итог без 5 лучших > 0, обе
половины проверки в плюсе, p перестановок <= 0.05, худшие сутки не хуже -2 SOL, плюс
правило глубины (билет <= 2 % резерва не меньше чем на 80 % сделок) и устойчивость на
подборе.

Выход: docs/podbivka_volna2.md, data/podbivka/volna2.json. Только чтение.
"""
