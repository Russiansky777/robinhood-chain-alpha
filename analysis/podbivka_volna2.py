def свод(ряды: list, б: float, доля: float = 1.0) -> dict:
    v = [x["итог"] for x in ряды if x.get("итог") is not None]
    if not v:
        return {"n": 0}
    верх = sorted(v, reverse=True)
    пс: dict = collections.defaultdict(float)
    for x in ряды:
        if x.get("итог") is not None:
            пс[x["сутки"]] += x["итог"]
    суток = len(пс) or 1
    return {"n": len(v), "суток": суток, "итог_sol": round(sum(v) * доля, 6),
            "sol_в_сутки": round(sum(v) * доля / суток, 6),
            "сделок_в_сутки": round(len(v) * доля / суток, 1),
            "медиана_пп": round(100 * statistics.median(v) / б, 3),
            "в_плюсе": round(100 * sum(1 for y in v if y > 0) / len(v), 1),
            "итог_без_5_лучших_sol": round(sum(верх[5:]) * доля, 6) if len(верх) > 5 else None,
            "итог_без_лучших_суток_sol": round((sum(v) - max(пс.values())) * доля, 6),
            "худшие_сутки_sol": round(min(пс.values()) * доля, 6)}


def прогон_адреса(адреса: set, выходы=УДЕРЖАНИЯ, билеты=БИЛЕТЫ) -> dict:
    """Ряды по адресу: итог при обычной посадке, только S+0 и только S+1, по удержаниям."""
    кал = (json.loads((П / "kalibrovka.json").read_text(encoding="utf-8")).get("калибровка") or {})
    к_g = float(кал.get("к_g") or 1.0)
    изд = float(кал.get("издержки_медиана_sol") or 0.002)
    посадка = RV.посадка_из_живых(Ж.сделки(s="2026-09-27T00:00:00Z"))
    доля_s0 = float(посадка["всего"]["S+0"])
    из_: dict = {"калибровка": {"к_g": к_g, "издержки_sol": изд, "доля_S+0": доля_s0,
                                "посадка": посадка["всего"]},
                 "ряды": collections.defaultdict(list), "волна": collections.defaultdict(list)}
    for р in O.сигналы(фильтр=lambda r: r.get("ист") in адреса):
        if р.get("quoteMint") != O.WSOL or not р.get("первая") or (р.get("sol") or 0) < 2.0:
            continue
        вх = р.get("вход") or {}
        if not вх:
            continue
        w = RV.веса(посадка, р.get("пул"), RV.корзина_размера(р.get("sol")))
        св = р.get("свопов") or {}
        из_["волна"][р["ист"]].append(
            {"сутки": O.сутки(р), "резерв": р.get("резерв_sol"), "вирт": р.get("вирт_резерв_sol"),
             "свопов2": (св.get("s1") or 0) + (св.get("s2") or 0), "пул": р.get("пул"),
             "минт": р.get("минт"), "sol": р.get("sol"), "вверх": р.get("рис_вверх_пп"),
             "пик_слотов": р.get("пик_слотов"), "пик_пп": р.get("пик_пп"),
             "первая_продажа_слотов": р.get("первая_продажа_слотов"),
             "событий_до_30": р.get("рис_событий_до_30")})
        for б in билеты:
            for H in выходы:
                if not (р.get("выход") or {}).get(str(H)):
                    continue
                смесь = RV.итог_сигнала(р, б, H, w, RV.ДОПУСК_ПО_УМОЛЧАНИЮ, изд, к_g)
                д0 = B.сделка_по_состояниям(O.как_сигнал(р), б, "S0_дно", H, издержки=изд, к_g=к_g)
                д1 = B.сделка_по_состояниям(O.как_сигнал(р), б, "S1", H, издержки=изд, к_g=к_g)
                для = {"обычная посадка": (смесь or {}).get("итог_sol"),
                       "только S+0": (д0 or {}).get("итог_sol"),
                       "только S+1": (д1 or {}).get("итог_sol")}
                for режим, итог_ in для.items():
                    if итог_ is None:
                        continue
                    из_["ряды"][(р["ист"], б, H, режим)].append(
                        {"сутки": O.сутки(р), "итог": итог_, "резерв": р.get("резерв_sol")})
    из_["ряды"] = dict(из_["ряды"])
    из_["волна"] = dict(из_["волна"])
    return из_


def глубина_ок(ряды: list, б: float) -> bool:
    рез = [x["резерв"] for x in ряды if x.get("резерв")]
    if not рез:
        return False
    return (sum(1 for r in рез if б <= V.ДОЛЯ_РЕЗЕРВА * r) / len(рез)) >= V.ДОЛЯ_ГЛУБИНЫ


