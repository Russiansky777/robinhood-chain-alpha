#!/usr/bin/env python3
"""Meteora DLMM: раскладка события свопа -- ВЫВЕДЕНА ПО ЖИВЫМ СДЕЛКАМ.

ЗАЧЕМ. Строитель N4 в очереди владельца -- Meteora DLMM. Сборка инструкции у
него уже есть (swap2/swap, роли счетов в c2_swap_build.DYN), а ЦЕНЫ нет:
min_out_from_reserves честно отказывает словами "сосредоточенная ликвидность:
резервы цену не дают". У DLMM цена живёт в корзинах (bin): у каждой своя цена,
и какая корзина активна -- по хранилищам не видно.

ЧТО НАЙДЕНО ЭТИМ РАЗБОРОМ (28.09, девять настоящих сделок из
data/c2_pool_samples, одиннадцать шагов DLMM):

1. СОБЫТИЯ DLMM НЕТ В "Program data:" ВОВСЕ. Первый заход искал его там и не
   нашёл ни в одной сделке (у двух образцов таких строк нет совсем). Событие
   уходит ПО CPI: внутренней инструкцией к самой программе DLMM, данные которой
   начинаются дискриминатором Anchor e445a52e51cb9a1d, а дальше идёт
   дискриминатор события и его тело.

2. Тел два на каждый своп: 145 байт (событие 516ce3becdd00ac4) и 163 байта
   (2e7452d7941b544d). Разобрано короткое -- его раскладка сошлась на всех
   одиннадцати шагах:
      0..32   lb_pair -- И ЭТО ПРОВЕРЕНО ФАКТОМ: адрес совпал со счётом 0
              вызова свопа во всех 11 шагах из 11;
      32..64  кто торговал;
      64      start_bin_id (i32), 68 end_bin_id (i32);
      72      amount_in (u64), 80 amount_out (u64) -- совпали с переводами
              токенов ЭТОГО шага (взяты из переводов, а не из события);
      88      swap_for_y (1 байт);
      89      fee (u64), 97 protocol_fee (u64);
      105     fee_bps (u128), 121 host_fee (u64) -- итого ровно 129 байт тела.
   Числа шагов брались ПО ПЕРЕВОДАМ ВНУТРИ КАЖДОГО ВЫЗОВА: все образцы --
   транзакции роутера, DLMM в них вызывается по одному-два раза на разных
   пулах, и разница балансов за всю транзакцию ни к одному событию не относится.

3. ЦЕНА КОРЗИНЫ. Для шага, который НЕ ВЫШЕЛ из своей корзины (start_bin_id ==
   end_bin_id), средняя цена сделки и есть цена корзины: делить нечего, вся
   сделка прошла по одной цене. Это готовый денежный путь для нашей покупки
   следом -- она идёт по той же корзине, пока та не кончится (кончится --
   наш минимум выхода не выполнится, и цепь ОТКАЖЕТ, то есть это промах, а не
   потеря).
   Для шага, который корзины сменил, конечная цена без шага корзины (bin_step
   из счёта пула) неизвестна, и тут разбор честно отказывает.
   ПРОВЕРКА ШАГА КОРЗИНЫ НА ДВУХ СДЕЛКАХ ОДНОГО ПУЛА (CJab6RE2...): цены на
   корзинах -346 и -362 дали отношение 1.17307 на 16 корзин, то есть
   (1 + bin_step/10000) = 1.01003 -- шаг корзины 100. При нём 1.01^-346 =
   0.03196 против измеренной средней цены 0.031974: сходится. Значит цена
   корзины в СЫРЫХ единицах равна (1 + bin_step/10000)^bin без всякого
   пересчёта по десятичным -- но сам bin_step лежит в счёте пула, и вслепую
   его брать нельзя: это следующий шаг строителя.

Ничего не подписывает и никуда не отправляет: только чтение файлов образцов.
"""
from __future__ import annotations

import hashlib
import json
import struct
import sys
from decimal import Decimal as D
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parent.parent

DLMM = "LBUZKhRxPF3XUpBCjp4YzTKgLccjZhTSDM9YuVaPwxo"
ОБРАЗЦЫ = КОРЕНЬ / "data" / "c2_pool_samples" / f"{DLMM}.json"
# Дискриминатор Anchor "событие по CPI". Сам по себе он не событие: за ним идёт
# дискриминатор события и тело.
CPI_ДИСК = bytes.fromhex("e445a52e51cb9a1d")
# Событие свопа DLMM. Имени мы не знаем и не выдумываем: дискриминатор снят с
# живых сделок, и раскладка подтверждена совпадением lb_pair со счётом 0.
СВОП_ДИСК = bytes.fromhex("516ce3becdd00ac4")
ДЛИНА_СВОПА = 145
СХЕМА = {"lb_pair": 0, "from": 32, "start_bin_id": 64, "end_bin_id": 68,
          "amount_in": 72, "amount_out": 80, "swap_for_y": 88, "fee": 89,
          "protocol_fee": 97, "fee_bps": 105, "host_fee": 121, "длина_тела": 129}

B58 = "123456789ABCDEFGHJKLMNPQRSTUVWXYZabcdefghijkmnopqrstuvwxyz"


def b58decode(s: str) -> bytes:
    n = 0
    for ch in s or "":
        n = n * 58 + B58.index(ch)
    b = n.to_bytes((n.bit_length() + 7) // 8, "big") if n else b""
    return b"\x00" * (len(s) - len(s.lstrip("1"))) + b


def b58encode(b: bytes) -> str:
    n = int.from_bytes(b, "big")
    s = ""
    while n:
        n, r = divmod(n, 58)
        s = B58[r] + s
    ведущие = len(b) - len(b.lstrip(b"\x00"))
    return "1" * ведущие + s


def событие_свопа(данные: bytes) -> dict | None:
    """Событие свопа DLMM из данных внутренней инструкции или None."""
    if (len(данные) != ДЛИНА_СВОПА or данные[:8] != CPI_ДИСК
            or данные[8:16] != СВОП_ДИСК):
        return None
    т = данные[16:]
    начало, конец = struct.unpack_from("<ii", т, СХЕМА["start_bin_id"])
    вошло, вышло = struct.unpack_from("<QQ", т, СХЕМА["amount_in"])
    комиссия, протокол = struct.unpack_from("<QQ", т, СХЕМА["fee"])
    return {"пул": b58encode(т[0:32]),
             "кто": b58encode(т[32:64]),
             "start_bin_id": начало, "end_bin_id": конец,
             "amount_in": вошло, "amount_out": вышло,
             "swap_for_y": т[СХЕМА["swap_for_y"]],
             "fee": комиссия, "protocol_fee": протокол,
             "fee_bps": int.from_bytes(т[СХЕМА["fee_bps"]:СХЕМА["fee_bps"] + 16],
                                        "little"),
             "host_fee": struct.unpack_from("<Q", т, СХЕМА["host_fee"])[0]}


def шаги_dlmm(tx: dict) -> list:
    """Шаги DLMM в транзакции: вызов свопа, его переводы и его событие.

    Все образцы -- транзакции роутера, и DLMM в них вызывается по нескольку
    раз: числа надо брать по каждому вызову отдельно, из ЕГО переводов.
    Внутренние инструкции лежат плоским списком с высотой стека: вызов на
    высоте h, его переводы и событие -- выше h до следующей инструкции с
    высотой <= h.
    """
    из_ = []
    for группа in ((tx or {}).get("meta") or {}).get("innerInstructions") or []:
        спис = группа.get("instructions") or []
        for н, их in enumerate(спис):
            if (их.get("programId") or их.get("program")) != DLMM:
                continue
            высота = их.get("stackHeight") or 2
            данные = b58decode(их.get("data") or "")
            if событие_свопа(данные) is not None:
                continue                      # это само событие, не вызов свопа
            счета = их.get("accounts") or []
            переводы, событие = [], None
            for сл in спис[н + 1:]:
                в_ = сл.get("stackHeight") or 0
                if в_ <= высота:
                    break
                разбор = сл.get("parsed") or {}
                инфо = разбор.get("info") or {}
                if разбор.get("type") in ("transfer", "transferChecked"):
                    сумма = инфо.get("amount")
                    if сумма is None:
                        сумма = (инфо.get("tokenAmount") or {}).get("amount")
                    if сумма is not None:
                        переводы.append({"откуда": инфо.get("source"),
                                          "куда": инфо.get("destination"),
                                          "сколько": int(сумма)})
                elif (сл.get("programId") or сл.get("program")) == DLMM:
                    с_ = событие_свопа(b58decode(сл.get("data") or ""))
                    if с_ is not None:
                        событие = с_
            if len(переводы) >= 2:
                из_.append({"пул_из_счетов": счета[0] if счета else None,
                             "вошло": переводы[0]["сколько"],
                             "вышло": переводы[-1]["сколько"],
                             "событие": событие})
    return из_


def цена_корзины(шаг: dict):
    """Цена корзины в СЫРЫХ единицах, если шаг из корзины не вышел.

    None -- корзина сменилась: конечную цену без шага корзины не узнать, и
    выдумывать её нельзя.
    """
    с = шаг.get("событие") or {}
    if not с or с["start_bin_id"] != с["end_bin_id"]:
        return None
    вошло_чистыми = с["amount_in"] - с["fee"]
    if вошло_чистыми <= 0 or с["amount_out"] <= 0:
        return None
    return D(вошло_чистыми) / D(с["amount_out"])


def main() -> int:
    if not ОБРАЗЦЫ.exists():
        print(f"нет файла образцов {ОБРАЗЦЫ}")
        return 2
    образцы = json.loads(ОБРАЗЦЫ.read_text(encoding="utf-8"))
    print(f"образцов DLMM: {len(образцы)}")
    шагов = совпал_пул = с_событием = в_одной_корзине = 0
    по_пулам: dict = {}
    for н, x in enumerate(образцы):
        for шаг in шаги_dlmm(x["tx"]):
            шагов += 1
            с = шаг.get("событие")
            if not с:
                print(f"  образец {н}: у шага {шаг['вошло']} -> {шаг['вышло']} "
                      f"события не нашлось")
                continue
            с_событием += 1
            сошлось = (с["пул"] == шаг["пул_из_счетов"])
            совпал_пул += 1 if сошлось else 0
            числа = (с["amount_in"] == шаг["вошло"]
                     and с["amount_out"] == шаг["вышло"])
            цена = цена_корзины(шаг)
            if цена is not None:
                в_одной_корзине += 1
            по_пулам.setdefault(с["пул"], []).append(
                (с["start_bin_id"], с["end_bin_id"],
                 D(с["amount_in"] - с["fee"]) / D(с["amount_out"])))
            print(f"  образец {н}: пул {с['пул'][:8]} счета {'=' if сошлось else '!='} "
                  f"событие, числа {'сошлись' if числа else 'РАЗОШЛИСЬ'}, "
                  f"корзины {с['start_bin_id']}..{с['end_bin_id']}, "
                  f"комиссия {с['fee'] / с['amount_in'] * 100:.4f} %, "
                  f"цена корзины {цена if цена is not None else 'нет (корзина сменилась)'}")
    print(f"шагов {шагов}, с событием {с_событием}, пул совпал со счётом 0 "
          f"{совпал_пул} из {с_событием}, в одной корзине {в_одной_корзине}")
    # ШАГ КОРЗИНЫ -- ПО ДВУМ СДЕЛКАМ ОДНОГО ПУЛА. Если у пула есть две сделки на
    # разных корзинах, отношение их цен даёт (1 + bin_step/10000) в степени
    # разности корзин. Это проверка модели, а не источник чисел для торговли.
    for пул, ряды in по_пулам.items():
        if len(ряды) < 2:
            continue
        (н1, к1, ц1), (н2, к2, ц2) = ряды[0], ряды[1]
        d = ((н1 + к1) - (н2 + к2)) / 2
        if not d or ц1 <= 0 or ц2 <= 0:
            continue
        шаг_корзины = (float(ц1 / ц2) ** (1.0 / d) - 1.0) * 10000.0
        print(f"  пул {пул[:8]}: цены на корзинах {(н1 + к1) / 2:.1f} и "
              f"{(н2 + к2) / 2:.1f} дают шаг корзины {шаг_корзины:.2f}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
