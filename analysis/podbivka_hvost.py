#!/usr/bin/env python3
"""Хвост у забора набором: числа для решения владельца, без вердикта.

Берётся то же правило, что в podbivka_zabor_nabor (подбор 7 суток -> верхние K торгуют
проверку 4 суток, сдвиг 4, окна только из суток ПОДРЯД), и по сделкам окон проверки
считается, насколько итог держится на верхних процентах сделок:

  * в скольких сутках проверки есть хотя бы одна сделка из верхних 5 % (верхние 5 %
    считаются по ВСЕМ сделкам проверки этого среза, а не по суткам);
  * какую долю суточного итога дают верхние 5 % внутри своих суток -- медиана и p10 по
    суткам (доля считается только по суткам с положительным итогом: у минусовых суток
    отношение к итогу смысла не имеет, их число печатается отдельно);
  * медиана суточного итога;
  * нижняя граница бутстрэпа по суткам (тот же бутстрэп, что в стандарте);
  * то же без верхних 1 % сделок.

Только чтение кэша. Выход: data/podbivka/hvost_nabora<метка>.json.
"""
from __future__ import annotations

import argparse
import collections
import json
import math
import statistics
import sys
