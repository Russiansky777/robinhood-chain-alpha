from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import podbivka_istochniki_novyj as И  # noqa: E402
import podbivka_paket_obshee as O      # noqa: E402
import podbivka_zabor_nabor as Н       # noqa: E402
import podbivka_zabor_s0 as З          # noqa: E402
import podbivka_zapuski_svod as Z      # noqa: E402

П = O.П
СЕМЯ = 20261010
# Срезы, по которым владелец просил хвост: доля 0.354 и доля по источнику.
СРЕЗЫ = (("S0_дно", 0.354, "H60|глубина|k1.013|K10"),
         ("S0_дно", 0.354, "H60|глубина|k1.013|K5"),
         ("S0_дно", "источник", "H108|глубина|k1.013|K20"),
         ("S0_дно", 0.209, "H108|глубина|k0.989|K5"))


def сделки_правила(ряды: dict, дни: list, кг: str, K: int) -> dict:
    """Сделки окон проверки по тому же правилу: верхние K по подбору торгуют проверку."""
    окна = [(п_, пр_) for п_, пр_ in И.окна_скольжения(
        дни, И.ПОДБОР_СУТОК, И.ПРОВЕРКА_СУТОК, И.СДВИГ_СУТОК) if Н.подряд(п_ + пр_)]
    по_дню: dict = collections.defaultdict(list)
    for подб, пров in окна:
        счёт = {}
        for ист, сп in ряды.items():
            v = [x["итоги"].get(кг) for x in сп if x["сутки"] in подб]
            v = [y for y in v if y is not None]
            if v:
                счёт[ист] = sum(v)
        верх = [и for и, _ in sorted(счёт.items(), key=lambda kv: -kv[1])[:K]]
        for и in верх:
            for x in ряды.get(и, ()):
                if x["сутки"] in пров and x["итоги"].get(кг) is not None:
                    по_дню[x["сутки"]].append(x["итоги"][кг])
    return dict(по_дню)


def хвост(по_дню: dict, доля_верха: float) -> dict:
    """Числа по хвосту: сколько суток его видят и сколько он весит."""
    все = sorted((v for сп in по_дню.values() for v in сп), reverse=True)
    if not все:
        return {}
    сколько = max(1, math.ceil(доля_верха * len(все)))
    порог = все[сколько - 1]
    суток_с_верхом = sum(1 for сп in по_дню.values() if any(v >= порог for v in сп))
    доли, плюс_суток, минус_суток = [], 0, 0
    for сп in по_дню.values():
        итог = sum(сп)
        верх = sum(v for v in сп if v >= порог)
        if итог > 0:
            плюс_суток += 1
            доли.append(верх / итог)
        else:
            минус_суток += 1
    доли.sort()
    без_верха = {д: [v for v in сп if v < порог] for д, сп in по_дню.items()}
    без_верха = {д: сп for д, сп in без_верха.items() if сп}
    суммы_без = {д: sum(сп) for д, сп in без_верха.items()}
    низ_без, _ = Z.ди_по_суткам(без_верха, seed=СЕМЯ)
    return {"сделок": len(все), "в_верхних": сколько,
            "порог_сделки_sol": round(порог, 6),
            "суток_с_верхом": суток_с_верхом, "суток": len(по_дню),
            "доля_итога_от_верха_медиана": (round(statistics.median(доли), 3)
                                            if доли else None),
            "доля_итога_от_верха_p10": (round(доли[int(0.1 * len(доли))], 3)
                                        if доли else None),
            "суток_в_плюсе": плюс_суток, "суток_в_минусе": минус_суток,
            "без_верха": {
                "суток": len(суммы_без),
                "суток_в_плюсе": sum(1 for s in суммы_без.values() if s > 0),
                "медиана_суточного_итога": (round(statistics.median(суммы_без.values()), 5)
                                            if суммы_без else None),
                "sol_в_сутки": (round(sum(суммы_без.values()) / len(суммы_без), 5)
                                if суммы_без else None),
                "бутстрэп_низ": round(низ_без, 6) if низ_без is not None else None}}


def главное(а) -> int:
    кал = (json.loads((П / "kalibrovka.json").read_text(encoding="utf-8"))
           .get("калибровка") or {})
    изд = float(кал.get("издержки_медиана_sol") or 0.002)
    Н.НЕПОЛНЫЕ = Н.неполные_сутки()
    пустой = __import__("argparse").Namespace(dolya=0.209, mesto="S0_дно",
                                              k_g_osnovnaya=1.0, metka="")
    доли_ист = None
    тело = {"что": "хвост у забора набором: числа без вердикта",
            "когда": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
            "неполные_сутки": sorted(Н.НЕПОЛНЫЕ), "срезы": {}}
    кэш_проходов: dict = {}
    for место, доля, ключ in СРЕЗЫ:
        метка = (место, доля)
        if метка not in кэш_проходов:
            if доля == "источник":
                доли_ист = доли_ист or З.доли_по_источникам(0.209)
                кэш_проходов[метка] = З.проход(пустой, изд, место=место, доля=0.209,
                                               доли_ист=доли_ист)
            else:
                кэш_проходов[метка] = З.проход(пустой, изд, место=место, доля=доля)
        п = кэш_проходов[метка]
        H, имя_б, кг_, K_ = ключ.split("|")
        H = int(H[1:])
        кг = кг_[1:]
        K = int(K_[1:])
        ряды: dict = collections.defaultdict(list)
        for (ист, H_, б_), сп in п["ряды"].items():
            if H_ == H and б_ == имя_б:
                ряды[ист].extend(сп)
        дни = sorted({x["сутки"] for сп in ряды.values() for x in сп} - Н.НЕПОЛНЫЕ)
        по_дню = сделки_правила(ряды, дни, кг, K)
        суммы = {д: sum(сп) for д, сп in по_дню.items()}
        низ, верх = Z.ди_по_суткам(по_дню, seed=СЕМЯ)
        имя = (f"{место}|доля {'по источнику' if доля == 'источник' else доля}|{ключ}")
        тело["срезы"][имя] = {
            "сделок": sum(len(сп) for сп in по_дню.values()),
            "суток": len(суммы),
            "суток_в_плюсе": sum(1 for s in суммы.values() if s > 0),
            "медиана_суточного_итога": round(statistics.median(суммы.values()), 5),
            "sol_в_сутки": round(sum(суммы.values()) / max(1, len(суммы)), 5),
            "бутстрэп_низ": round(низ, 6) if низ is not None else None,
            "бутстрэп_верх": round(верх, 6) if верх is not None else None,
            "верхние_5": хвост(по_дню, 0.05),
            "верхние_1": хвост(по_дню, 0.01),
            "по_суткам": {д: round(s, 5) for д, s in sorted(суммы.items())}}
        в5 = тело["срезы"][имя]["верхние_5"]
        print(f"{имя}: сделок {тело['срезы'][имя]['сделок']}, суток "
              f"{тело['срезы'][имя]['суток']}, медиана суточного итога "
              f"{тело['срезы'][имя]['медиана_суточного_итога']:+.5f}, бутстрэп низ "
              f"{тело['срезы'][имя]['бутстрэп_низ']}", flush=True)
        print(f"    верхние 5 %: суток с верхом {в5['суток_с_верхом']}/{в5['суток']}, "
              f"доля итога медиана {в5['доля_итога_от_верха_медиана']}, p10 "
              f"{в5['доля_итога_от_верха_p10']}; без верха: суток+ "
              f"{в5['без_верха']['суток_в_плюсе']}/{в5['без_верха']['суток']}, "
              f"медиана {в5['без_верха']['медиана_суточного_итога']}, бутстрэп низ "
              f"{в5['без_верха']['бутстрэп_низ']}", flush=True)
        в1 = тело["срезы"][имя]["верхние_1"]
        print(f"    верхние 1 %: суток с верхом {в1['суток_с_верхом']}/{в1['суток']}; "
              f"без верха: суток+ {в1['без_верха']['суток_в_плюсе']}"
              f"/{в1['без_верха']['суток']}, медиана "
              f"{в1['без_верха']['медиана_суточного_итога']}, бутстрэп низ "
              f"{в1['без_верха']['бутстрэп_низ']}", flush=True)
    вых = П / f"hvost_nabora{а.metka}.json"
    вых.write_text(json.dumps(тело, ensure_ascii=False, indent=1), encoding="utf-8")
    import podbivka_run as R  # noqa: PLC0415
    R.записано(вых)
    return 0


def main() -> int:
    р = argparse.ArgumentParser()
    р.add_argument("--metka", default="")
    return главное(р.parse_args())


if __name__ == "__main__":
    raise SystemExit(main())
