#!/usr/bin/env python3
"""Подбивка п.4: лидер и BATCH-5 -- S+0 / S+1 / S+2, выход +72 / +150, корзины по
размеру покупки источника (< 5 / 5–15 / 15+ SOL-экв. по курсу дня), наценка входа
и путь цены у лидера. Офлайн.

Режим 2 (котировка не SOL) -- data/podbivka/rezhim2/*.jsonl (модель A3);
SOL-пулы -- основной симулятор, числа из файлов источников (data/podbivka/nashi).
Потолок -- наша покупка остаётся в пуле до выхода (как во всех таблицах); дно --
наш след рассосался. 0.5 SOL, п.п. чистыми (минус 0.002 SOL).
"""
from __future__ import annotations

import glob
import json
import math
import statistics
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import podbivka_tablicy as T  # noqa: E402

КОРЕНЬ = T.КОРЕНЬ
ЛИДЕР = "Beqv6dzTcjV2eodo8RRXCiCcnSYrS1vkQKhfqwHXqeit"
SOL = ("So11111111111111111111111111111111111111112", "native_sol")
КОРЗИНЫ = (("< 5", 0, 5), ("5–15", 5, 15), ("15+", 15, 1e18))
ВХОДЫ = ("S0", "S0_дно", "S1", "S2")


def стат(xs):
    xs = sorted(x for x in xs if x is not None)
    n = len(xs)
    if not n:
        return {"n": 0}
    ус = xs[:n - math.ceil(0.05 * n)]
    return {"n": n, "ср": sum(xs) / n, "ус": (sum(ус) / len(ус)) if ус else None,
            "мед": statistics.median(xs), "p90": xs[min(n - 1, int(0.9 * n))],
            "плюс": sum(1 for x in xs if x > 0) / n}


def я(с):
    if not с.get("n"):
        return "0 | — | — | — | —"
    ус = f"{с['ус']:+.2f}" if с.get("ус") is not None else "—"
    return f"{с['n']} | {с['ср']:+.2f} | {ус} | {с['мед']:+.2f} | {100 * с['плюс']:.0f}%"


def main() -> int:
    имена = json.loads((КОРЕНЬ / "data" / "podbivka" / "imena_istochnikov.json").read_text(encoding="utf-8"))["имена"]
    ряды = []   # {группа, источник, sol_экв, режим, вход -> {H -> {потолок, дно}}, наценка, путь}
    отказы: dict = {}
    for f in sorted(glob.glob(str(КОРЕНЬ / "data" / "podbivka" / "rezhim2" / "*.jsonl"))):
        for l in open(f, encoding="utf-8"):
            р = json.loads(l)
            гр = "лидер" if р.get("wallet") == ЛИДЕР else "BATCH-5"
            if р.get("why_not"):
                ключ = (гр, р["why_not"].split(":")[0][:60])
                отказы[ключ] = отказы.get(ключ, 0) + 1
                continue
            вх = {}
            for e in ВХОДЫ:
                x = (р.get("входы") or {}).get(e) or {}
                вх[e] = {H: {"потолок": x.get(f"потолок_{H}"), "дно": x.get(f"дно_{H}")} for H in (72, 150)}
            ряды.append({"группа": гр, "источник": имена.get(р["wallet"], р["wallet"][:8]), "sol_экв": р.get("sol_экв"),
                         "режим": f"режим 2 ({р.get('режим')})", "вход": вх,
                         "наценка": {e: ((р.get("входы") or {}).get(e) or {}).get("наценка_пп") for e in ВХОДЫ},
                         "путь": р.get("путь_цены") or {}, "котировка": р.get("quote_mint")})
    # SOL-пулы -- основной симулятор
    for а, имя in имена.items():
        if "Brez" in имя:
            continue
        p = КОРЕНЬ / "data" / "podbivka" / "nashi" / f"{а}.json"
        if not p.exists():
            continue
        к = json.loads(p.read_text(encoding="utf-8"))
        гр = "лидер" if а == ЛИДЕР else "BATCH-5"
        for п in T.пересчёт_порога(к.get("покупки") or [], а):
            с = п.get("sim") or {}
            if с.get("quote_mint") not in SOL:
                continue
            if гр == "лидер" and not (1789689600 <= (п.get("blockTime") or 0) < 1790380800):
                continue   # окно 1б 18.09–25.09
            if с.get("why_not"):
                ключ = (гр, "SOL-пул: " + с["why_not"].split(":")[0][:50])
                отказы[ключ] = отказы.get(ключ, 0) + 1
                continue
            вх = {e: {H: {"потолок": T.чп(с, e, H), "дно": None} for H in (72, 150)} for e in ("S0", "S1", "S2")}
            ряды.append({"группа": гр, "источник": имена[а], "sol_экв": п.get("sol_экв"),
                         "режим": "SOL-пул (основной)", "вход": вх, "наценка": {}, "путь": {}, "котировка": "SOL"})
    md = ["# Подбивка п.4: лидер и BATCH-5 -- входы, выходы, корзины размера", "",
          "Режим 2 -- модель, сошедшаяся в A3 (медиана модуля ошибки 0.61 п.п., p90 7.4 на 16 сделках DBot); "
          "SOL-пулы -- основной симулятор. Потолок -- наша покупка остаётся в пуле; дно -- наш след рассосался "
          "(только режим 2). 0.5 SOL, п.п. чистыми. Ячейка: n | среднее | усечённое 5 % | медиана | в плюс.", "",
          "Флаги режима 2: курс котировочного на выходе = на входе; проскальзывание нашей ноги SOL↔котировочный не "
          "моделируется (в A3 это давало до −14 п.п. на тонкой котировке B5WTLa).", ""]
    for гр in ("лидер", "BATCH-5"):
        рр = [р for р in ряды if р["группа"] == гр]
        md += [f"## {гр}: {len(рр)} покупок с числом (режим 2: {sum(1 for р in рр if р['режим'].startswith('режим'))}, "
               f"SOL-пулы: {sum(1 for р in рр if р['режим'].startswith('SOL'))})", "",
               "| вход | выход | корзина, SOL-экв | потолок | дно (режим 2) |", "|---|---|---|---|---|"]
        for e in ВХОДЫ:
            for H in (72, 150):
                for имя, lo, hi in (("все", 0, 1e18),) + КОРЗИНЫ:
                    вк = [р for р in рр if р["sol_экв"] is not None and lo <= р["sol_экв"] < hi and e in р["вход"]]
                    п_ = стат([р["вход"][e][H]["потолок"] for р in вк])
                    д_ = стат([р["вход"][e][H]["дно"] for р in вк])
                    md.append(f"| {e} | +{H} | {имя} | {я(п_)} | {я(д_)} |")
        md.append("")
    # наценка и путь цены лидера
    лр = [р for р in ряды if р["группа"] == "лидер" and р["режим"].startswith("режим")]
    md += ["## Лидер: наценка входа к цене сразу после его сделки (режим 2)", "",
           "Наша цена за токен (котировочный, ушедший в пул / полученные токены до налога) к спот-цене пула сразу "
           "после сделки лидера; в неё входят сбор пула, проскальзывание нашего 0.5 SOL и сдвиг цены до нашего входа. "
           "Пилот DBot (18–19.09): наценка 26 % медиана (ведомость, USDC-база).", "",
           "| вход | n | медиана, % | p90, % | среднее, % |", "|---|---|---|---|---|"]
    for e, подпись in (("S0", "S+0 потолок (сразу после лидера)"), ("S0_дно", "S+0 дно (после всех свопов слота)"),
                       ("S1", "S+1"), ("S2", "S+2")):
        с = стат([р["наценка"].get(e) for р in лр])
        md.append(f"| {подпись} | {с.get('n', 0)} | {с.get('мед', 0):+.2f} | {с.get('p90', 0):+.2f} | {с.get('ср', 0):+.2f} |"
                  if с.get("n") else f"| {подпись} | 0 | — | — | — |")
    md += ["", "## Лидер: путь цены по слотам (спот пула к цене сразу после его сделки, п.п.)", "",
           "| точка | n | медиана | p90 |", "|---|---|---|---|"]
    for e, подпись in (("S0_дно", "конец s0"), ("S1", "конец s0+1"), ("S2", "конец s0+2")):
        с = стат([р["путь"].get(e) for р in лр])
        md.append(f"| {подпись} | {с.get('n', 0)} | {с.get('мед', 0):+.2f} | {с.get('p90', 0):+.2f} |"
                  if с.get("n") else f"| {подпись} | 0 | — | — |")
    md += ["", "## Без числа", "", "| группа | причина | число |", "|---|---|---|"]
    for (гр, пр), n in sorted(отказы.items(), key=lambda kv: -kv[1]):
        md.append(f"| {гр} | {пр} | {n} |")
    md.append("")
    (КОРЕНЬ / "docs" / "podbivka_2026-09-27_p4_lider.md").write_text("\n".join(md), encoding="utf-8")
    print("\n".join(md[:12]))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
