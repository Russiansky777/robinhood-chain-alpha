#!/usr/bin/env python3
"""cand3: 189 новых ведущих верхних 50 копировщиков через правило кандидатов. Офлайн, по готовому архиву cand3_*.

Правило кандидатов без изменений (счёт и ячейки -- кодом analysis/podbivka_kandidaty_vne.py, как в cand2):
наш вход «конец слота» за ним, билеты 0.1 и 0.3, выход +108 (главный), котировка WSOL, кривая pump.fun / LaunchLab /
CPMM / DAMM v1 плюс Pump AMM по модели v6, п.п. чистыми; n ≥ 20, среднее ≥ +2 п.п., медиана > 0, «толпа есть»
(доля ячеек со свопом пула в s0+1 / s0+2 ≥ 0.5 -- определение принято владельцем 02.10), кусты -- одним адресом.
Окно -- 24.09 17Z → 01.10 17Z (файлы cand3_*T16, у каждых суток первый «разгонный» час отброшен).

Вход: data/podbivka/arhiv_den/cand3_*T16.json.gz (прогон с --bez-adresov --dop-adresa: сигналы только по этим 189),
data/podbivka/vedushie_svyazi.json (кто из верхних 50 копировщиков за ним и односторонняя ли связь),
data/podbivka/arhiv_adresa.json. Выход: docs/podbivka_2026-10-02_cand3.md.
"""
from __future__ import annotations

import glob
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import podbivka_cand2 as C2  # noqa: E402

КОРЕНЬ = C2.КОРЕНЬ
П = C2.П
N_МИН, СР_МИН, ТОЛПА_МИН = 20, 2.0, 0.5


def main() -> int:
    import podbivka_run as R  # noqa: PLC0415
    файлы = sorted(glob.glob(str(П / "arhiv_den" / "cand3_*T16.json.gz")))
    if not файлы:
        print("нет файлов cand3_*T16 -- прогон архива не закончен", flush=True)
        return 1
    св = json.loads((П / "vedushie_svyazi.json").read_text(encoding="utf-8"))["ведущие"]
    цель = set(json.loads((П / "vedushie_adresa.json").read_text(encoding="utf-8"))["адреса"])
    адр = json.loads((КОРЕНЬ / "data" / "podbivka" / "arhiv_adresa.json").read_text(encoding="utf-8"))["адреса"]
    по, счёт = C2.собрать(файлы, C2.окно_отбора)
    ряды = {}
    for a in цель:
        к = по.get(a) or C2.копилка()
        с108, с108_01 = C2.стат(к["108"]), C2.стат(к["108_01"])
        толпа = (1 - к["никто"] / к["ячеек"]) if к["ячеек"] else 0.0
        прошёл = ((с108.get("n") or 0) >= N_МИН and (с108.get("среднее") or -99) >= СР_МИН
                  and (с108.get("медиана") or -99) > 0 and толпа >= ТОЛПА_МИН)
        прошёл_01 = ((с108_01.get("n") or 0) >= N_МИН and (с108_01.get("среднее") or -99) >= СР_МИН
                     and (с108_01.get("медиана") or -99) > 0 and толпа >= ТОЛПА_МИН)
        ряды[a] = {"сигналов": к["сигналов"], "ячеек": к["ячеек"], "толпа": round(толпа, 3),
                   "108": с108, "108_01": с108_01, "прошёл": прошёл, "прошёл_01": прошёл_01,
                   "минт_слот": к["минт_слот"],
                   "копировщиков": (св.get(a) or {}).get("копировщиков") or 0,
                   "односторонних": (св.get(a) or {}).get("односторонних") or 0,
                   "раз": (св.get(a) or {}).get("раз") or 0}
    # кусты среди прошедших: общих (минт, слот) не меньше половины сигналов
    прошли = [a for a, v in ряды.items() if v["прошёл"] or v["прошёл_01"]]
    пары, в_кусте = [], {}
    for i, a in enumerate(прошли):
        for b in прошли[i + 1:]:
            ма, мб = ряды[a]["минт_слот"], ряды[b]["минт_слот"]
            общ = len(ма & мб)
            if общ and 2 * общ >= min(len(ма), len(мб)):
                пары.append((a, b, общ, len(ма), len(мб)))
                в_кусте.setdefault(a, set()).add(b)
                в_кусте.setdefault(b, set()).add(a)
    # куст -- одним адресом: оставляем того, у кого больше n по билету 0.3
    убрать = set()
    for a, b, *_ in пары:
        если = sorted((a, b), key=lambda x: -(ряды[x]["108"].get("n") or 0))
        убрать.add(если[1])
    список = [a for a in прошли if a not in убрать]
    список.sort(key=lambda a: (-(ряды[a]["108"].get("медиана") or -99), -(ряды[a]["108"].get("n") or 0)))

    def ряд(a: str, ключ: str = "108") -> str:
        v, s = ряды[a], ряды[a][ключ]
        од = f"{v['копировщиков']} ({v['односторонних']} односторонних, {v['раз']} раз)"
        return (f"| `{a}` | {од} | {s.get('n')} | " +
                (f"{s.get('среднее'):+.2f} | {s.get('медиана'):+.2f} | " if s.get("n") else "— | — | ") +
                f"{v['толпа']:.2f} | {v['сигналов']} / {v['ячеек']} |")

    загол = ("| адрес | чей ведущий: копировщиков из верхних 50 | n | среднее, п.п. | медиана, п.п. | толпа есть | "
             "сигналов / ячеек |")
    линия = "|---|---|---|---|---|---|---|"
    свои = {b: (адр[b].get("группы") or []) for b in св if b in адр}
    живые = {b: г for b, г in свои.items() if {"cand2", "cand1", "lane_s0", "batch5", "leader"} & set(г)}

    md = ["# Подбивка: cand3 -- ведущие копировщиков через правило кандидатов (окно 24.09 17Z – 01.10 17Z)", "",
          f"189 новых ведущих верхних 50 копировщиков (`docs/podbivka_2026-10-02_kopirovschiki.md`) прогнаны "
          f"через архив отдельным проходом: {len(файлы)} суток, сигналов в окне {счёт['в_окне']}, адресов с "
          f"сигналами {sum(1 for v in ряды.values() if v['сигналов'])} из {len(цель)}. Правило кандидатов без "
          f"изменений: вход «конец слота» за ним, билеты 0.1 и 0.3, выход +108, n ≥ {N_МИН}, среднее ≥ "
          f"+{СР_МИН:g} п.п., медиана > 0, «толпа есть» (доля ячеек со свопом пула в s0+1 / s0+2 ≥ {ТОЛПА_МИН:g}), "
          "кусты -- одним адресом. Ошибок чтения часов: "
          f"{len(счёт['ошибки'])}. Ничего не рекомендуется, состав -- решение владельца.", "",
          f"**Список cand3 по правилу: {len(список)} адресов** (прошли по билету 0.3 или 0.1, после склейки "
          f"кустов: кустов {len(пары)}, убрано как второй адрес куста {len(убрать)}).", "",
          "## A. Прошедшие правило (столбцы -- билет 0.3)", "", загол, линия]
    md += [ряд(a) for a in список] or ["| — | | | | | | |"]
    по01 = [a for a in список if ряды[a]["прошёл_01"]]
    md += ["", f"## Б. Из них проходят и по билету 0.1 ({len(по01)})", "", загол, линия]
    md += [ряд(a, "108_01") for a in по01] or ["| — | | | | | | |"]

    md += ["", "## В. Кто из cand2 и живых групп сам оказался среди ведущих", "",
           f"Ведущих у верхних 50 копировщиков всего {len(св)}; из них в нашем реестре {len(свои)} "
           f"(поэтому в cand3 они не попали -- там только 189 новых). В торгующих группах из них {len(живые)}:", ""]
    for b, г in sorted(живые.items(), key=lambda kv: -(св[kv[0]]["копировщиков"])):
        гр = ", ".join(x for x in г if x != "log_only")
        md.append(f"- `{b}` ({гр}) -- за ним {св[b]['копировщиков']} копировщиков из верхних 50, "
                  f"{св[b]['односторонних']} односторонних, {св[b]['раз']} раз за неделю.")
    # Г. найдены по BLAST (слово владельца 02.10): верхние покупатели окна 15:45Z через то же правило
    бл = П / "blast_svod.json"
    if бл.exists():
        б = json.loads(бл.read_text(encoding="utf-8"))
        md += ["", "## Г. Найдены по BLAST (окно 02.10 15:45Z, `docs/podbivka_2026-10-02_blast_15-45.md`)", "",
               "Верхние покупатели того слота, где произошло движение, прогнаны через то же правило "
               "кандидатов на том же окне. Строка «найден по BLAST» -- те, кто правило проходит.", "",
               "| адрес | SOL покупок в окне BLAST | n | среднее, п.п. | медиана, п.п. | в плюсе | толпа | "
               "проходит правило | откуда |", "|---|---|---|---|---|---|---|---|---|"]
        for a in б.get("верх3") or []:
            пр = (б.get("правило") or {}).get(a) or {}
            s = пр.get("итог") or {"n": 0}
            у = (б.get("участники") or {}).get(a) or {}
            md.append(f"| `{a}` | {у.get('sol_покупок')} | {s.get('n', 0)} | "
                      + (f"{s['среднее']:+.2f} | {s['медиана']:+.2f} | {s['в_плюсе']:.0%} | "
                         if s.get("n") else "— | — | — | ")
                      + f"{пр.get('толпа') if пр.get('толпа') is not None else '—'} | "
                      + ("**да, найден по BLAST**" if пр.get("прошёл") else "нет") + " | "
                      + (", ".join(пр.get("файлы") or []) or "—") + " |")
        прошли_бл = [a for a in (б.get("верх3") or [])
                     if ((б.get("правило") or {}).get(a) or {}).get("прошёл")]
        md += ["", f"Проходят правило: **{len(прошли_бл)}** из {len(б.get('верх3') or [])}"
               + (" (" + ", ".join(f"`{a[:8]}`" for a in прошли_бл) + ")" if прошли_бл else "")
               + ". Состав -- решение владельца.", ""]
    прочие = {b: г for b, г in свои.items() if b not in живые}
    md += ["", f"Остальные {len(прочие)} из реестра -- это лог и наблюдаемые списки (543 / 133 / источники "
           "снайперов), не торгующие группы.", ""]
    out = КОРЕНЬ / "docs" / "podbivka_2026-10-02_cand3.md"
    out.write_text("\n".join(md) + "\n", encoding="utf-8")
    R.записано(out)
    дт = П / "cand3.json"
    дт.write_text(json.dumps({"окно": ["2026-09-24T17:00Z", "2026-10-01T17:00Z"], "файлы": [Path(f).name for f in файлы],
                              "счёт": счёт, "список": список, "по_01": по01,
                              "кусты": [{"a": a, "b": b, "общих": o, "n_a": na, "n_b": nb} for a, b, o, na, nb in пары],
                              "ряды": {a: {k: v for k, v in r.items() if k != "минт_слот"} for a, r in ряды.items()}},
                             ensure_ascii=False, indent=1), encoding="utf-8")
    R.записано(дт)
    print(out.name, "в списке", len(список), "по 0.1", len(по01), "кустов", len(пары), flush=True)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
