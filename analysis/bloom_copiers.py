#!/usr/bin/env python3
"""Список копировщиков: кошельки, которые не раз садились позади наших источников.

ОПРЕДЕЛЕНИЕ ВЛАДЕЛЬЦА (26.09, ночь): "копировщики -- кошельки, которые не менее
трёх раз садились позади наших источников в том же слоте; список обновляется
раз в сутки". Ровно это и считается: по записям соседей по слоту (их пишет
фоновая догонялка детектора в позиции) кошелёк попадает в список, когда он
встретился в РАЗНЫХ слотах не менее трёх раз.

ФАЙЛ. data/kopirovshchiki.json (на хосте -- рядом с состоянием, путь задаётся
окружением BLOOM_COPIERS_FILE). Читается на пути доклада, пишется суточным
прогоном. Нет файла -- пустое множество, и в строке стоит черта: пустой список
это "мы ещё не знаем", а не "копировщиков нет".
"""
from __future__ import annotations

import json
import os
import time
from pathlib import Path

ПОРОГ_ВСТРЕЧ = 3
ФАЙЛ_ПО_УМОЛЧАНИЮ = "data/kopirovshchiki.json"
_КЭШ: dict = {"путь": None, "время": 0.0, "множество": frozenset()}
СРОК_КЭША_С = 300.0


def файл() -> str:
    """Путь читается ПРИ ВЫЗОВЕ: смена окружения после старта должна работать."""
    return os.environ.get("BLOOM_COPIERS_FILE") or ФАЙЛ_ПО_УМОЛЧАНИЮ


def _путь(путь: str | None = None) -> Path:
    п = Path(путь or файл())
    if п.exists():
        return п
    рядом = Path(__file__).resolve().parent.parent / (путь or файл())
    return рядом if рядом.exists() else п


def список(путь: str | None = None, *, заново: bool = False) -> frozenset:
    """Множество адресов копировщиков. Кэш на пять минут: строка уходит часто."""
    п = str(_путь(путь))
    сейчас = time.time()
    if (not заново and _КЭШ["путь"] == п
            and сейчас - _КЭШ["время"] < СРОК_КЭША_С):
        return _КЭШ["множество"]
    из_: set = set()
    try:
        д = json.loads(Path(п).read_text(encoding="utf-8"))
        for з in (д.get("копировщики") or []):
            адрес = з.get("адрес") if isinstance(з, dict) else з
            if адрес:
                из_.add(адрес)
    except Exception:  # noqa: BLE001
        из_ = set()
    _КЭШ.update(путь=п, время=сейчас, множество=frozenset(из_))
    return _КЭШ["множество"]


def сосчитать(записи) -> dict:
    """{кошелёк: число РАЗНЫХ слотов, где он сел позади наших источников}.

    записи -- итерируемое из (слот, [кошельки]). Один слот считается один раз:
    иначе кошелёк, взявший в одном блоке три транзакции, стал бы "копировщиком"
    с одной встречи.
    """
    слоты_по_кошельку: dict = {}
    for слот, кошельки in записи:
        for к in (кошельки or []):
            слоты_по_кошельку.setdefault(к, set()).add(слот)
    return {к: len(с) for к, с in слоты_по_кошельку.items()}


def собрать(записи, *, порог: int = ПОРОГ_ВСТРЕЧ) -> dict:
    """Готовый файл: список с числом встреч, отсортированный по убыванию."""
    счёт = сосчитать(записи)
    ряды = [{"адрес": к, "встреч": n} for к, n in счёт.items() if n >= порог]
    ряды.sort(key=lambda з: (-з["встреч"], з["адрес"]))
    return {"обновлён_utc": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
            "порог_встреч": порог, "кошельков_видели": len(счёт),
            "копировщики": ряды}


def self_test() -> int:
    пройдено = провалено = 0

    def chk(что, ок, факт=""):
        nonlocal пройдено, провалено
        if ок:
            пройдено += 1
            print(f"  [ok  ] {что}")
        else:
            провалено += 1
            print(f"  [ПРОВАЛ] {что}: {факт}")

    записи = [(1, ["A", "B"]), (1, ["A"]), (2, ["A"]), (3, ["A", "B"]),
              (4, ["C"])]
    счёт = сосчитать(записи)
    chk("один слот считается один раз", счёт["A"] == 3, счёт)
    chk("встречи в разных слотах складываются", счёт["B"] == 2, счёт)
    д = собрать(записи)
    адреса = [з["адрес"] for з in д["копировщики"]]
    chk("в список попадает только тот, у кого встреч не меньше трёх",
        адреса == ["A"], адреса)
    chk("порог виден в файле и кошельки посчитаны",
        д["порог_встреч"] == 3 and д["кошельков_видели"] == 3, д)

    import tempfile  # noqa: PLC0415

    with tempfile.TemporaryDirectory() as кат:
        ф = os.path.join(кат, "k.json")
        Path(ф).write_text(json.dumps(д, ensure_ascii=False), encoding="utf-8")
        chk("список читается из файла", список(ф, заново=True) == {"A"},
            список(ф, заново=True))
        нет = os.path.join(кат, "нету.json")
        chk("нет файла -- пустое множество, а не падение",
            список(нет, заново=True) == frozenset())
        Path(ф).write_text("это не json", encoding="utf-8")
        chk("битый файл -- пустое множество",
            список(ф, заново=True) == frozenset())
    print(f"самопроверка списка копировщиков: {пройдено}/{пройдено + провалено} пройдено")
    return 0 if провалено == 0 else 1


if __name__ == "__main__":
    import sys
    raise SystemExit(self_test() if "--self-test" in sys.argv else 0)
