#!/usr/bin/env python3
"""Конвейер (Правило 18): правило кандидатов по ВСЕЙ вселенной архива, каждые сутки, без штаба.

ЧТО СЧИТАЕТСЯ. Каждый адрес, у которого в окне не меньше N_МИН первых покупок от 2 SOL-экв:
наш вход «конец слота» за ним, выход +108, билет 0.1 (и 0.3 для справки), п.п. чистыми.
Правило одно и не подгоняется: n >= 20, среднее >= +2 п.п., медиана > 0, «толпа есть»
(доля ячеек со свопом пула в s0+1 / s0+2 >= 0.5), медиана > 0 в ОБЕИХ половинах окна,
не меньше 60 % суток в плюсе, кусты (общие минт+слот не меньше половины сигналов) -- одним
адресом, ПОСЛЕДНИЕ СУТКИ ВНЕ ВЫБОРКИ и тоже в плюсе (медиана > 0 при n >= 5).

Формулы ячейки и п.п. -- кодом podbivka_cand2 / podbivka_kandidaty_vne, стабильность --
podbivka_stabilnost. Своих копий формул здесь нет.

Разделы страницы: «добавить» (не больше 5, по медиане, только адреса вне групп),
«запас» (прошли, но не вошли в пятёрку), «снова проходит» (адреса из log_only -- строкой,
НЕ добавлять), «действующие не держатся» (все торгующие источники групп тем же правилом).

Выход: docs/konveyer_<дата>.md и data/konveyer/<дата>.json.
Поля: адрес, дата, раздел, n, среднее, медиана, в_плюсе, толпа, медиана_1, медиана_2,
суток_в_плюсе, последние_сутки, типы_пулов, доля_usdc, куст.
"""
from __future__ import annotations

import argparse
import calendar
import collections
import glob
import gzip
import json
import statistics
import sys
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import podbivka_cand2 as C2  # noqa: E402
import podbivka_kandidaty_vne as K  # noqa: E402
import podbivka_stabilnost as ST  # noqa: E402

КОРЕНЬ = C2.КОРЕНЬ
П = C2.П
ШАБЛОНЫ = ("konv_*T*.json.gz", "cand2_*T16.json.gz", "cand2_vne_*.json.gz")
N_МИН, СР_МИН, ТОЛПА_МИН = 20, 2.0, 0.5
N_ВНЕ_МИН = 5
ПОРОГ_SOL = 2.0
ДОБАВИТЬ_МАКС = 5
USDC = {"EPjFWdd5AufqSSqeM2qN1xzybapC8G4wEGGkZwyTDt1v", "Es9vMFrzaCERmJfrF4H2FYD4KCoNkY11McCe8BenwNYB"}
ТОРГУЮЩИЕ = ("lane_s0", "batch5", "cand1", "cand1_03", "cand1_05", "cand2", "cand3", "leader", "konveyer")


def сутки_файла(f: str) -> str:
    """Дата суток файла по его имени (последний кусок <YYYY-MM-DDTHH>)."""
    return Path(f).name.replace(".json.gz", "").split("_")[-1][:10]


def начало_файла(f: str) -> float:
    хвост = Path(f).name.replace(".json.gz", "").split("_")[-1]
    return calendar.timegm(time.strptime(хвост[:13], "%Y-%m-%dT%H"))


def копилка() -> dict:
    return {"сигналов": 0, "первых": 0, "ячеек": 0, "никто": 0,
            "я01": [], "я03": [], "минт_слот": set(),
            "пулы": collections.Counter(), "котировки": collections.Counter(),
            "вне01": [], "вне_ячеек": 0}


def собрать(файлы: list, вне: set) -> tuple[dict, dict]:
    """Копилки по ВСЕМ адресам файлов. `вне` -- файлы последних суток (вне выборки)."""
    по: dict = {}
    счёт = {"файлов": 0, "сигналов": 0, "в_окне": 0, "дублей": 0, "ошибки": [], "сутки": []}
    видел: set = set()
    for f in файлы:
        try:
            д = json.loads(gzip.decompress(Path(f).read_bytes()))
        except Exception as exc:  # noqa: BLE001
            счёт["ошибки"].append(f"{Path(f).name}: {type(exc).__name__}")
            continue
        счёт["файлов"] += 1
        счёт["сутки"].append(Path(f).name.replace(".json.gz", ""))
        счёт["ошибки"] += [f"{Path(f).name}: {x}" for x in (д.get("счёт") or {}).get("ошибки") or []]
        д0 = начало_файла(f) + 3600       # первый «разгонный» час отбрасывается
        это_вне = f in вне
        for с in д.get("сигналы") or []:
            счёт["сигналов"] += 1
            ts = K.ts(с)
            if not (д0 <= ts < д0 + 86400):
                continue
            if с["signature"] in видел:
                счёт["дублей"] += 1
                continue
            видел.add(с["signature"])
            счёт["в_окне"] += 1
            к = по.setdefault(с["trader"], копилка())
            к["сигналов"] += 1
            if (с.get("sol") or 0) < ПОРОГ_SOL:
                continue
            к["первых"] += 1
            к["пулы"][с.get("pool") or "?"] += 1
            к["котировки"][с.get("quoteMint") or "?"] += 1
            if not C2.ячейка(с):
                continue
            v01, v03 = K.пп(с, "108_01"), K.пп(с, "108")
            if это_вне:
                к["вне_ячеек"] += 1
                if v01 is not None:
                    к["вне01"].append(v01)
                continue
            к["ячеек"] += 1
            к["никто"] += 1 if C2.никто(с) else 0
            к["минт_слот"].add((с.get("mint"), с.get("block")))
            if v01 is not None:
                к["я01"].append((ts, v01))
            if v03 is not None:
                к["я03"].append((ts, v03))
        del д
    return по, счёт


def правило(к: dict) -> dict:
    """Числа и флаг правила по копилке (билет 0.1 -- главный)."""
    зн = [v for _, v in к["я01"]]
    s = K.стат(зн)
    ст = ST.стабильность(к["я01"])
    толпа = round(1 - к["никто"] / к["ячеек"], 3) if к["ячеек"] else None
    вне_мед = round(statistics.median(к["вне01"]), 2) if к["вне01"] else None
    вне_ок = bool(len(к["вне01"]) >= N_ВНЕ_МИН and (вне_мед or -99) > 0)
    прошёл = bool((s.get("n") or 0) >= N_МИН and (s.get("среднее") or -99) >= СР_МИН
                  and (s.get("медиана") or -99) > 0 and (толпа or 0) >= ТОЛПА_МИН
                  and ст["стабилен"] and вне_ок)
    # ЧТО ИМЕННО НЕ СОШЛОСЬ. «Не держится» и «нет данных за последние сутки» -- разные вещи,
    # и в таблице они не должны читаться одинаково: порог не меняется, меняется только подпись.
    почему = []
    if (s.get("n") or 0) < N_МИН:
        почему.append(f"ячеек {s.get('n', 0)} < {N_МИН}")
    else:
        if (s.get("среднее") or -99) < СР_МИН:
            почему.append(f"среднее {s['среднее']:+.2f} < +{СР_МИН:g}")
        if (s.get("медиана") or -99) <= 0:
            почему.append(f"медиана {s['медиана']:+.2f} ≤ 0")
        if (толпа or 0) < ТОЛПА_МИН:
            почему.append(f"толпа {толпа} < {ТОЛПА_МИН:g}")
        if not ст["стабилен"]:
            if ст["медиана_1"] is None or ст["медиана_2"] is None:
                почему.append("нет обеих половин окна")
            elif ст["медиана_1"] <= 0 or ст["медиана_2"] <= 0:
                почему.append(f"половина окна в минусе ({ст['медиана_1']:+.2f} / {ст['медиана_2']:+.2f})")
            if (ст["доля_суток"] or 0) < ST.ДОЛЯ_СУТОК:
                почему.append(f"суток в плюсе {ст['суток_в_плюсе']} из {ст['суток']}")
        if not вне_ок:
            if len(к["вне01"]) < N_ВНЕ_МИН:
                почему.append(f"последние сутки: ячеек {len(к['вне01'])} < {N_ВНЕ_МИН} -- числа нет")
            else:
                почему.append(f"последние сутки: медиана {вне_мед:+.2f}")
    всего_кв = sum(к["котировки"].values()) or 1
    return {"n": s.get("n", 0), "среднее": s.get("среднее"), "медиана": s.get("медиана"),
            "в_плюсе": s.get("в_плюсе"), "толпа": толпа,
            "медиана_1": ст["медиана_1"], "медиана_2": ст["медиана_2"],
            "суток_в_плюсе": f"{ст['суток_в_плюсе']} / {ст['суток']}" if ст["суток"] else None,
            "доля_суток": ст["доля_суток"],
            "последние_сутки": (f"{вне_мед:+.2f} (n {len(к['вне01'])})" if вне_мед is not None
                                else f"нет ячеек (n {len(к['вне01'])})"),
            "последние_сутки_ок": вне_ок,
            "ячеек": к["ячеек"], "сигналов": к["сигналов"], "первых_от_2": к["первых"],
            "типы_пулов": ", ".join(f"{p} {n}" for p, n in к["пулы"].most_common(4)),
            "доля_usdc": round(sum(n for q, n in к["котировки"].items() if q in USDC) / всего_кв, 3),
            "стат_03": K.стат([v for _, v in к["я03"]]),
            "что_не_сошлось": "; ".join(почему) or None,
            "нет_данных_вне": bool(not вне_ок and len(к["вне01"]) < N_ВНЕ_МИН),
            "прошёл": прошёл}


def кусты(прошли: list, по: dict) -> dict:
    """{адрес: адрес-куст} -- пары с общими (минт, слот) не меньше половины сигналов."""
    в_кусте: dict = {}
    for i, a in enumerate(прошли):
        for b in прошли[i + 1:]:
            ма, мб = по[a]["минт_слот"], по[b]["минт_слот"]
            общих = len(ма & мб)
            if общих and общих >= 0.5 * min(len(ма), len(мб)):
                главный = a if по[a]["ячеек"] >= по[b]["ячеек"] else b
                второй = b if главный == a else a
                в_кусте[второй] = главный
    return в_кусте


def main() -> int:
    import podbivka_run as R  # noqa: PLC0415
    р = argparse.ArgumentParser()
    р.add_argument("--sutok", type=int, default=11, help="суток в окне отбора (без последних)")
    р.add_argument("--data", default=time.strftime("%Y-%m-%d", time.gmtime()))
    р.add_argument("--shablony", default=",".join(ШАБЛОНЫ))
    а = р.parse_args()
    файлы = []
    for ш in а.shablony.split(","):
        файлы += [x for x in glob.glob(str(П / "arhiv_den" / ш.strip()))]
    файлы = sorted(set(файлы), key=начало_файла)
    if not файлы:
        print("конвейер: суточных файлов нет", flush=True)
        return 1
    вне = {файлы[-1]}
    окно = файлы[-(а.sutok + 1):-1] if len(файлы) > 1 else файлы
    по, счёт = собрать(окно + sorted(вне), вне)
    адр = json.loads((П / "arhiv_adresa.json").read_text(encoding="utf-8"))["адреса"]

    годные = {a: к for a, к in по.items() if к["первых"] >= N_МИН}
    ряды = {a: правило(к) for a, к in годные.items()}
    прошли = sorted([a for a, v in ряды.items() if v["прошёл"]],
                    key=lambda a: -(ряды[a]["медиана"] or -99))
    в_кусте = кусты(прошли, по)
    for a, гл in в_кусте.items():
        ряды[a]["куст"] = гл
    прошли_без_кустов = [a for a in прошли if a not in в_кусте]

    def группы(a: str) -> list:
        return (адр.get(a) or {}).get("группы") or []

    новые = [a for a in прошли_без_кустов if not группы(a)]
    log_only = [a for a in прошли_без_кустов if "log_only" in группы(a)
                and not (set(группы(a)) & set(ТОРГУЮЩИЕ))]
    торгующие_прошли = [a for a in прошли_без_кустов if set(группы(a)) & set(ТОРГУЮЩИЕ)]
    добавить = новые[:ДОБАВИТЬ_МАКС]
    запас = новые[ДОБАВИТЬ_МАКС:]
    действующие = sorted({a for a in адр if set(группы(a)) & set(ТОРГУЮЩИЕ)})
    не_держатся = [a for a in действующие if not (ряды.get(a) or {}).get("прошёл")]

    разделы = {}
    for a in добавить:
        разделы[a] = "добавить"
    for a in запас:
        разделы[a] = "запас"
    for a in log_only:
        разделы[a] = "снова проходит"
    for a in торгующие_прошли:
        разделы[a] = "действующий держится"
    for a in не_держатся:
        разделы.setdefault(a, "действующие не держатся")

    def строка(a: str) -> dict:
        v = dict(ряды.get(a) or {"n": 0})
        v.update(адрес=a, дата=а.data, раздел=разделы.get(a), группы=группы(a),
                 куст=(ряды.get(a) or {}).get("куст"))
        return v

    дт = {"дата": а.data, "окно": {"суток_отбора": len(окно), "файлы": счёт["сутки"],
                                   "вне_выборки": [Path(x).name for x in sorted(вне)]},
          "счёт": счёт, "правило": {"n_мин": N_МИН, "среднее_мин": СР_МИН, "толпа_мин": ТОЛПА_МИН,
                                    "доля_суток_мин": ST.ДОЛЯ_СУТОК, "билет": 0.1, "выход": 108,
                                    "n_вне_мин": N_ВНЕ_МИН, "порог_sol": ПОРОГ_SOL},
          "адресов_в_окне": len(по), "с_n_мин_первых": len(годные),
          "прошли": len(прошли), "кустов_убрано": len(в_кусте),
          "разделы": {"добавить": добавить, "запас": запас, "снова проходит": log_only,
                      "действующий держится": торгующие_прошли,
                      "действующие не держатся": не_держатся},
          "ряды": {a: строка(a) for a in set(list(разделы) + прошли)}}
    (КОРЕНЬ / "data" / "konveyer").mkdir(parents=True, exist_ok=True)
    out_j = КОРЕНЬ / "data" / "konveyer" / f"{а.data}.json"
    out_j.write_text(json.dumps(дт, ensure_ascii=False, indent=1, default=str), encoding="utf-8")
    R.записано(out_j)

    загол = ("| адрес | n | среднее | медиана | в плюсе | толпа | мед. 1-й / 2-й пол. | суток в плюсе | "
             "последние сутки (вне выборки) | типы пулов | доля USDC | куст | что не сошлось |")
    черта = "|---|---|---|---|---|---|---|---|---|---|---|---|---|"

    def кл(a: str) -> str:
        v = ряды.get(a) or {}
        if not v.get("n"):
            return (f"| `{a[:8]}` | 0 | — | — | — | — | — | — | — | — | — | — | "
                    f"{v.get('что_не_сошлось') or 'ячеек нет вовсе'} |")
        return (f"| `{a[:8]}` | {v['n']} | "
                + (f"{v['среднее']:+.2f}" if v.get("среднее") is not None else "—") + " | "
                + (f"{v['медиана']:+.2f}" if v.get("медиана") is not None else "—") + " | "
                + (f"{v['в_плюсе']:.0%}" if v.get("в_плюсе") is not None else "—") + " | "
                + (f"{v['толпа']:.2f}" if v.get("толпа") is not None else "—") + " | "
                + (f"{v['медиана_1']:+.2f} / {v['медиана_2']:+.2f}"
                   if v.get("медиана_1") is not None and v.get("медиана_2") is not None else "—")
                + f" | {v.get('суток_в_плюсе') or '—'} | {v.get('последние_сутки') or '—'} | "
                + f"{v.get('типы_пулов') or '—'} | "
                + (f"{v['доля_usdc']:.0%}" if v.get("доля_usdc") is not None else "—") + " | "
                + (f"`{v['куст'][:8]}`" if v.get("куст") else "—") + " | "
                + (v.get("что_не_сошлось") or "—") + " |")

    md = [f"# Конвейер {а.data}: правило кандидатов по всей вселенной архива", "",
          f"Суточных файлов в окне отбора **{len(окно)}**, вне выборки -- "
          f"{', '.join(Path(x).name.replace('.json.gz', '') for x in sorted(вне))}. Сигналов в файлах "
          f"{счёт['сигналов']}, в окнах суток {счёт['в_окне']}, дублей подписи {счёт['дублей']}, "
          f"ошибок чтения {len(счёт['ошибки'])}. Адресов в окне **{len(по)}**, из них с {N_МИН} и более "
          f"первыми покупками от {ПОРОГ_SOL:g} SOL-экв -- **{len(годные)}**.", "",
          f"Правило (не подгоняется): вход «конец слота» за ним, выход +108, билет **0.1**, п.п. чистыми; "
          f"n ≥ {N_МИН}, среднее ≥ +{СР_МИН:g} п.п., медиана > 0, толпа ≥ {ТОЛПА_МИН:g}, медиана > 0 в "
          f"обеих половинах окна, ≥ {ST.ДОЛЯ_СУТОК:.0%} суток в плюсе, кусты одним адресом, последние "
          f"сутки вне выборки и тоже в плюсе (медиана > 0 при n ≥ {N_ВНЕ_МИН}). "
          f"Прошли **{len(прошли)}**, из них убрано как второй адрес куста {len(в_кусте)}. "
          f"Ничего не рекомендуется -- решает владелец.", "",
          f"## Добавить (не больше {ДОБАВИТЬ_МАКС}, по медиане)", ""]
    md += ([загол, черта] + [кл(a) for a in добавить]) if добавить else ["Никого: новых адресов, прошедших правило, нет.", ""]
    md += ["", "## Запас", ""]
    md += ([загол, черта] + [кл(a) for a in запас]) if запас else ["Пусто.", ""]
    md += ["", "## Снова проходит (log_only -- не добавлять, только строка)", ""]
    md += ([загол, черта] + [кл(a) for a in log_only]) if log_only else ["Пусто.", ""]
    md += ["", "## Действующие источники тем же правилом", ""]
    if торгующие_прошли:
        md += [f"Держатся: {', '.join('`' + a[:8] + '`' for a in торгующие_прошли)}.", ""]
    нет_данных = [a for a in не_держатся if (ряды.get(a) or {}).get("нет_данных_вне")
                  or not (ряды.get(a) or {}).get("n")]
    по_числам = [a for a in не_держатся if a not in нет_данных]
    md += [f"Правило не подтверждено у {len(не_держатся)} из {len(действующие)}: по числам "
           f"**{len(по_числам)}**, из-за отсутствия данных за последние сутки или в окне -- "
           f"**{len(нет_данных)}** (у них правило просто не проверяется, это не минус).", "",
           "### Не держатся по числам", "", загол, черта]
    md += [кл(a) for a in по_числам]
    md += ["", "### Нет данных для проверки", "", загол, черта]
    md += [кл(a) for a in нет_данных]
    md += [""]
    out_m = КОРЕНЬ / "docs" / f"konveyer_{а.data}.md"
    out_m.write_text("\n".join(md) + "\n", encoding="utf-8")
    R.записано(out_m)
    print(f"конвейер {а.data}: адресов {len(по)}, с n≥{N_МИН} первых {len(годные)}, прошли {len(прошли)}, "
          f"добавить {len(добавить)}, запас {len(запас)}, снова проходит {len(log_only)}, "
          f"действующие не держатся {len(не_держатся)} из {len(действующие)}", flush=True)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
