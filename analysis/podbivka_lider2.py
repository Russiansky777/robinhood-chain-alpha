#!/usr/bin/env python3
"""Подбивка: прогон режима 2 по лидеру (27.09 вечер) -- офлайн-сводка по
data/podbivka/rezhim2/l2_*.jsonl (и l2proba_* для пробы).

п.2  докупки (от 2 SOL) против первых; докупки по слотам от предыдущей покупки
     того же минта < 1800 / >= 1800 / предыдущей в окне скана нет.
п.4  хвост на столе: максимум нашего выхода-потолка по свопам в окне +36 / +150 /
     +600 / +1800 против таймера +36 / +150; доля удвоений после +150 (до +1800).
п.5  выход по первой продаже лидера (состояние пула сразу после неё) против +150.
Входы S+0 сразу за ним (S0) и конец слота (S0_дно); 0.5 SOL, п.п. чистыми, потолок.
Ячейка -- как в podbivka_hvosty.py.
"""
from __future__ import annotations

import argparse
import glob
import json
import statistics
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from podbivka_hvosty import КОРЕНЬ, стат, шапка, я  # noqa: E402

ВХОДЫ = (("S0", "сразу за ним"), ("S0_дно", "конец слота"))


def вх(р, e, H):
    return ((р.get("входы") or {}).get(e) or {}).get(f"потолок_{H}")


def мx(р, e, W):
    """Максимум по свопам в окне и точки таймера в нём (если в окне свопов не было,
    состояние на таймере -- то же, что до окна)."""
    if not р.get("максимум"):
        return None
    м = (((р.get("максимум") or {}).get(e) or {}).get(str(W)) or {}).get("пп")
    точки = [t for t in (36, 150, 600, 1800) if (W == "после_150" and t >= 600) or (W != "после_150" and t <= W)]
    xs = [x for x in [м] + [вх(р, e, t) for t in точки] if x is not None]
    return max(xs) if xs else None


def группа(р) -> str:
    if р.get("вид") != "докупка":
        return "первые"
    d = р.get("слотов_от_предыдущей")
    return "докупки: предыдущей в окне нет" if d is None else ("докупки < 1800" if d < 1800 else "докупки ≥ 1800")


def main() -> int:
    а_ = argparse.ArgumentParser()
    а_.add_argument("--prefiks", default="l2_")
    а = а_.parse_args()
    по: dict = {}
    for f in sorted(glob.glob(str(КОРЕНЬ / "data" / "podbivka" / "rezhim2" / f"{а.prefiks}*.jsonl"))):
        for l in open(f, encoding="utf-8"):
            р = json.loads(l)
            п = по.get(р["signature"])
            if п is None or (п.get("why_not") and not р.get("why_not")):
                по[р["signature"]] = р
    всё = list(по.values())
    ок = [р for р in всё if not р.get("why_not")]
    отказы: dict = {}
    for р in всё:
        if р.get("why_not"):
            к = (группа(р), р["why_not"].split(":")[0][:70])
            отказы[к] = отказы.get(к, 0) + 1
    спис = json.loads((КОРЕНЬ / "data" / "podbivka" / "rezhim2_spisok_lider2.json").read_text(encoding="utf-8"))["покупки"]
    md = ["# Подбивка: лидер, режим 2 -- докупки, хвост на столе, выход по его продаже", "",
          f"Список: {len(спис)} покупок (первые {sum(1 for x in спис if x['вид'] == 'первая')}, докупки от 2 SOL "
          f"{sum(1 for x in спис if x['вид'] == 'докупка')}); обработано {len(всё)}, с числом {len(ок)}. Модель режима 2 "
          "(A3); котировка SOL -- та же модель, цена q = 1 (флаг «SOL-пул режимом 2»). Потолок, 0.5 SOL, п.п. чистыми. "
          "Ячейка: n | среднее | усечённое | медиана | p95 | макс | доля итога от 5 % лучших.", "",
          "Докупки от 2 SOL в списке -- только те, у которых SOL-экв. считается по курсу детектора (ряд с 23.09 "
          "~20:20Z) или трата в SOL: ещё около 1432 докупок в USD до 23.09 в список не вошли (ошибка 20).", ""]
    # п.2
    md += ["## п.2 Докупки против первых покупок", ""] + шапка(["группа", "вход", "выход", "x"])
    for гр in ("первые", "докупки < 1800", "докупки ≥ 1800", "докупки: предыдущей в окне нет", "все докупки"):
        рр = [р for р in ок if (группа(р) == гр or (гр == "все докупки" and р.get("вид") == "докупка"))]
        for e, имя in ВХОДЫ:
            for H in (72, 150):
                md.append(f"| {гр} | {имя} | +{H} | {я(стат([вх(р, e, H) for р in рр]))} |")
    # п.4
    чт = [р.get("максимум_чтение") or {} for р in ок if р.get("максимум")]
    способы: dict = {}
    for x in чт:
        способы[x.get("способ")] = способы.get(x.get("способ"), 0) + 1
    md += ["", "## п.4 Хвост на столе", "",
           f"Максимум нашего выхода-потолка по состояниям пула после свопов (покупок с максимумом: {len(чт)}; чтение: "
           + ", ".join(f"{k} {v}" for k, v in способы.items()) + "; при > 300 свопов -- конец каждого слота, при > 300 "
           "слотов -- с шагом, максимум тогда нижняя граница).", ""]
    for гр in ("первые", "все докупки", "все"):
        рр = [р for р in ок if р.get("максимум") and (гр == "все" or (гр == "первые") == (р.get("вид") != "докупка"))]
        md += [f"### {гр}", "", "| вход | окно | " + " | ".join(["n", "ср макс", "медиана", "p95", "макс"]) +
               " | ср (макс − таймер +36) | ср (макс − таймер +150) |", "|---|---|---|---|---|---|---|---|---|"]
        for e, имя in ВХОДЫ:
            for W in (36, 150, 600, 1800):
                с = стат([мx(р, e, W) for р in рр])
                р36 = [мx(р, e, W) - вх(р, e, 36) for р in рр if мx(р, e, W) is not None and вх(р, e, 36) is not None]
                р150 = [мx(р, e, W) - вх(р, e, 150) for р in рр if мx(р, e, W) is not None and вх(р, e, 150) is not None]
                md.append(f"| {имя} | до +{W} | " + (f"{с['n']} | {с['ср']:+.1f} | {с['мед']:+.1f} | {с['p95']:+.1f} | {с['макс']:+.1f}"
                                                     if с.get("n") else "0 | — | — | — | —") +
                          f" | {(sum(р36) / len(р36)) if р36 else float('nan'):+.1f} | {(sum(р150) / len(р150)) if р150 else float('nan'):+.1f} |")
        md += ["", "Точки таймера +600 / +1800 (для сравнения с максимумом):", ""] + шапка(["вход", "таймер", "x"])
        for e, имя in ВХОДЫ:
            for H in (36, 150, 600, 1800):
                md.append(f"| {имя} | +{H} | {я(стат([вх(р, e, H) for р in рр]))} |")
        md += ["", "Доля удвоений: максимум после +150 (слоты s0+150 .. s0+1799) >= 2 × стоимость позиции на выходе "
               "по таймеру (стоимость = 100 + п.п.):", "", "| вход | против +36 | против +150 |", "|---|---|---|"]
        for e, имя in ВХОДЫ:
            яч = []
            for Hв in (36, 150):
                пары = [(вх(р, e, Hв), мx(р, e, "после_150")) for р in рр
                        if вх(р, e, Hв) is not None and мx(р, e, "после_150") is not None]
                k = sum(1 for a, b in пары if (100 + b) >= 2 * (100 + a))
                яч.append(f"{k} из {len(пары)} ({100 * k / len(пары):.0f}%)" if пары else "—")
            md.append(f"| {имя} | {яч[0]} | {яч[1]} |")
        md.append("")
    # п.5
    md += ["## п.5 Выход по первой продаже лидера против таймера +150", ""]
    for гр in ("первые", "все докупки", "все"):
        рр = [р for р in ок if (гр == "все" or (гр == "первые") == (р.get("вид") != "докупка"))]
        пр = [р for р in рр if ((р.get("продажи") or {}).get("первая"))]
        без = [р for р in рр if not ((р.get("продажи") or {}).get("первая"))]
        сл = sorted(р["продажи"]["первая"]["слотов_от_s0"] for р in пр)
        причины: dict = {}
        for р in без:
            к = (р.get("продажи") or {}).get("why_not") or "продажи не считались"
            причины[к] = причины.get(к, 0) + 1
        md += [f"### {гр}", "",
               f"С первой продажей: {len(пр)} из {len(рр)}; без: " + "; ".join(f"{k} -- {v}" for k, v in причины.items()) + ".",
               (f"Слотов от его покупки до первой продажи: медиана {statistics.median(сл):.0f}, до +150 -- "
                f"{sum(1 for x in сл if x < 150)}, до +1800 -- {sum(1 for x in сл if x < 1800)}, позже -- "
                f"{sum(1 for x in сл if x >= 1800)}." if сл else ""),
               f"Доля остатка в первой продаже: медиана {statistics.median([р['продажи']['первая']['доля'] or 0 for р in пр]):.2f}."
               if пр else "", ""] + шапка(["вход", "выход", "x"])
        for e, имя in ВХОДЫ:
            md.append(f"| {имя} | по его продаже | {я(стат([р['продажи']['первая']['выход'].get(e) for р in пр]))} |")
            md.append(f"| {имя} | таймер +150 (те же) | {я(стат([вх(р, e, 150) for р in пр]))} |")
            md.append(f"| {имя} | таймер +150 (все) | {я(стат([вх(р, e, 150) for р in рр]))} |")
        md.append("")
    md += ["## Без числа", "", "| группа | причина | число |", "|---|---|---|"]
    for (гр, пр_), n in sorted(отказы.items(), key=lambda kv: -kv[1]):
        md.append(f"| {гр} | {пр_} | {n} |")
    md.append("")
    имя_ф = "podbivka_2026-09-27_lider2.md" if а.prefiks == "l2_" else f"podbivka_2026-09-27_lider2_{а.prefiks.strip('_')}.md"
    (КОРЕНЬ / "docs" / имя_ф).write_text("\n".join(md), encoding="utf-8")
    print("\n".join(md))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
