#!/usr/bin/env python3
"""Описательная таблица: путь цены после первого появления токена в списке.

ОПИСАТЕЛЬНО, НЕ ПРОВЕРКА. Ни одно правило здесь не подбирается и не проверяется: таблица
нужна только чтобы увидеть, есть ли вообще движение цены после появления и в какую
сторону. Порогов, отбора списков и вердиктов тут нет.

Вход: data/podbivka/trending_arhiv<метка>.json (проход по архиву) и
data/podbivka/trending_pervye<метка>.json (первые появления). Для каждого списка:
сколько адресов нашлось в архиве, медиана отношения цены на +1 / +5 / +15 минут к цене на
момент появления (последнее событие не позже метки), медиана ликвидности пула на момент
появления и доля адресов, у которых после метки событий не было вовсе.

Выход: data/podbivka/trending_tablica<метка>.json и та же таблица в stdout.
"""
from __future__ import annotations

import argparse
import collections
import json
import statistics as st
import time
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parent.parent
П = КОРЕНЬ / "data" / "podbivka"
ШАГИ = ("60", "300", "900")
WSOL = "So11111111111111111111111111111111111111112"


def главное(а) -> int:
    арх = json.loads((П / f"trending_arhiv{а.metka}.json").read_text(encoding="utf-8"))
    ряды = арх["ряды"]
    по_списку: dict = collections.defaultdict(lambda: {
        "адресов": 0, "событий_0": 0, "без_событий_после": 0,
        "отношения": {ш: [] for ш in ШАГИ}, "ликвидность": [], "котировки": collections.Counter(),
        "пулы": collections.Counter()})
    for адр, р in ряды.items():
        сп = (р.get("заказ") or {}).get("список") or "?"
        к = по_списку[сп]
        к["адресов"] += 1
        к["котировки"][р.get("котировка")] += 1
        к["пулы"][р.get("пул")] += 1
        до = р.get("до")
        # ОДНА БАЗА НА ПАРУ. У кривой pump.fun виртуальные резервы (30 SOL / 1.073e9) и
        # реальные различаются на порядки: отношение цены «виртуальная к реальной» давало
        # −99 п.п. там, где ничего не падало. Поэтому база выбирается одна -- реальная,
        # если она есть у обоих событий пары, иначе виртуальная, -- и только внутри неё.
        if not до or (до.get("цена_реал") is None and до.get("цена_вирт") is None):
            к["событий_0"] += 1
            continue
        if р.get("котировка") == WSOL:
            л = до.get("ликв_реал")
            if л is None:
                л = до.get("ликв_вирт")
            if л is not None:
                к["ликвидность"].append(л)
        был_после = False
        for ш in ШАГИ:
            б = (р.get("шаги") or {}).get(ш)
            if not б or б["мс"] <= до["мс"]:
                continue
            for поле in ("цена_реал", "цена_вирт"):
                if до.get(поле) and б.get(поле):
                    к["отношения"][ш].append(б[поле] / до[поле])
                    был_после = True
                    break
        if not был_после:
            к["без_событий_после"] += 1

    строки = []
    for сп, к in sorted(по_списку.items()):
        ряд = {"список": сп, "адресов_в_архиве": к["адресов"],
               "без_цены_на_момент": к["событий_0"],
               "без_событий_после_появления": к["без_событий_после"],
               "котировка_WSOL": к["котировки"].get(WSOL, 0),
               "пулы": dict(к["пулы"].most_common(3))}
        for ш in ШАГИ:
            v = к["отношения"][ш]
            ряд[f"+{int(ш) // 60}мин"] = {
                "n": len(v),
                "медиана_пп": (round(100 * (st.median(v) - 1), 2) if v else None),
                "p25_пп": (round(100 * (sorted(v)[len(v) // 4] - 1), 2) if len(v) >= 4 else None),
                "p75_пп": (round(100 * (sorted(v)[3 * len(v) // 4] - 1), 2) if len(v) >= 4 else None),
                "в_плюсе": (sum(1 for x in v if x > 1) if v else None)}
        ряд["ликвидность_sol_медиана"] = (round(st.median(к["ликвидность"]), 3)
                                          if к["ликвидность"] else None)
        ряд["ликвидность_n"] = len(к["ликвидность"])
        строки.append(ряд)

    тело = {"что": "путь цены после первого появления в списке -- ОПИСАТЕЛЬНО, НЕ ПРОВЕРКА",
            "как_читать": "медиана отношения цены к цене на момент появления, в п.п.; "
                          "правил не подбирали, порогов не искали, вердикта нет",
            "когда": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
            "окно_часов": арх.get("окно_часов"), "заказано": арх.get("заказано"),
            "найдено_в_архиве": арх.get("найдено_в_архиве"), "строки": строки}
    ф = П / f"trending_tablica{а.metka}.json"
    ф.write_text(json.dumps(тело, ensure_ascii=False, indent=1), encoding="utf-8")
    print(f"{'список':34} {'в арх':>6} {'+1 мин':>16} {'+5 мин':>16} {'+15 мин':>16} "
          f"{'ликв SOL':>9}", flush=True)
    for р in строки:
        def кл(ш):
            z = р[f"+{ш}мин"]
            return f"{z['медиана_пп']:+.2f}пп n{z['n']}" if z["n"] else "— n0"
        print("%-34s %6d %16s %16s %16s %9s"
              % (р["список"], р["адресов_в_архиве"], кл(1), кл(5), кл(15),
                 р["ликвидность_sol_медиана"]), flush=True)
    try:
        import sys  # noqa: PLC0415
        sys.path.insert(0, str(Path(__file__).resolve().parent))
        import podbivka_run as R  # noqa: PLC0415
        R.записано(ф)
    except Exception:  # noqa: BLE001, S110
        pass
    print(f"записано {ф}", flush=True)
    return 0


def main() -> int:
    р = argparse.ArgumentParser()
    р.add_argument("--metka", default="")
    return главное(р.parse_args())


if __name__ == "__main__":
    raise SystemExit(main())
