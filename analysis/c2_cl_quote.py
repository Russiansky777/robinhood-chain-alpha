#!/usr/bin/env python3
"""Цена в пулах сосредоточенной ликвидности: Meteora DAMM v2 (cpAMM).

ЗАЧЕМ. Полоса берёт сигнал только если может посчитать МИНИМУМ ВЫХОДА: покупка
без минимума -- это покупка по любой цене. У обычного пула минимум считается по
резервам (x*y=k), а у DAMM v2 резервы цену не дают: ликвидность сосредоточена, и
в хранилищах лежит не то, что торгуется.

ЧТО ЗДЕСЬ. Кривая восстанавливается по САМОЙ СДЕЛКЕ ИСТОЧНИКА и по её событию:
  * next_sqrt_price -- цена ПОСЛЕ сделки источника, число из цепи (u128, Q64.64);
  * сколько вошло и сколько вышло -- по движению хранилищ пула;
  * комиссии -- из того же события.
Из пары "вход/выход" и цены после сделки решаются ДВА неизвестных -- цена до
сделки и ликвидность L, -- после чего наша покупка считается по той же кривой,
от цены источника. Формулы обычные для cpAMM:
    A = L/sqrt(P),  B = L*sqrt(P),
то есть при покупке B за A цена P = B/A падает, при покупке A за B -- растёт.

РАСКЛАДКА СОБЫТИЯ НЕ УГАДАНА. Смещения сняты с 15 живых сделок, и каждое
разобранное событие обязано СОЙТИСЬ со своей же транзакцией: заявленный вход
равен аргументу инструкции, а выход -- движению базового хранилища. Не сошлось --
цены нет, и полоса такой сигнал не берёт.

ЧЕГО ЗДЕСЬ НЕТ. Ни одного сетевого вызова и ни одной сделки: на входе сохранённая
транзакция источника, на выходе числа.
"""
from __future__ import annotations

from decimal import Decimal as D

# Дискриминатор самовызова события Anchor (emit_cpi!): данные инструкции это
# [8 байт этого дискриминатора][8 байт дискриминатора события][тело события].
ДИСК_СОБЫТИЯ = "e445a52e51cb9a1d"
# СХЕМЫ СОБЫТИЙ. Смещения в теле (после 8 байт дискриминатора самовызова) сняты
# с живых сделок и проверяются на КАЖДОЙ: заявленный вход обязан совпасть с
# аргументом инструкции, выход -- с движением хранилища пула.
#
# DAMM v2 -- 15 живых сделок, длина тела всегда 188.
# DBC (кривая запуска Meteora) -- 2 живые сделки, длина тела 162. Смещение цены
# найдено не на глаз: перебором ВСЕХ смещений тела осталось РОВНО ОДНО (106),
# при котором цена после сделки физически возможна (выше средней цены
# исполнения) сразу у обеих сделок, и комиссия при нём вышла ровно 2.00 % у
# обеих (1.60 % + 0.40 %). Две сделки -- мало, поэтому флаг DBC включается
# только после симуляции на хосте.
# CLMM (Raydium) -- СОБЫТИЕ В ЛОГАХ, А НЕ В САМОВЫЗОВЕ. Здесь оно приходит
# строкой "Program data: <base64>" с дискриминатором события
# sha256("event:SwapEvent")[:8] = 40c6cde8260871e2, а не инструкцией
# emit_cpi!. Раскладка SwapEvent (проверена на 8 живых сделках источников,
# тело 205 или 221 байт вместе с дискриминатором события):
#   8   pool_state (32)          -- пул, по нему событие и выбирается
#   40  sender (32)              -- кошелёк, у наших образцов это сам источник
#   72  token_account_0 (32)
#   104 token_account_1 (32)
#   136 amount_0 (8)             -- сколько прошло по стороне 0
#   144 transfer_fee_0 (8)
#   152 amount_1 (8)
#   160 transfer_fee_1 (8)
#   168 zero_for_one (1)         -- направление: сторона 0 -> сторона 1
#   169 sqrt_price_x64 (16)      -- цена ПОСЛЕ сделки, Q64.64
#   185 liquidity (16)           -- L отдаётся ПРЯМО, решать его не нужно
#   201 tick (4, со знаком)
# Хвост в 16 байт у части сделок -- более новая версия события; всё, что нам
# нужно, лежит до него, поэтому длина принимается любая из двух.
СХЕМА_CLMM = {"длины": (205, 221), "пул": 8, "amount_0": 136, "amount_1": 152,
              "fee_0": 144, "fee_1": 160, "направление": 168,
              "цена_после": 169, "ликвидность": 185, "тик": 201}
ДИСК_СОБЫТИЯ_CLMM = "40c6cde8260871e2"
# ГДЕ В ИНСТРУКЦИИ CLMM ЛЕЖИТ САМ ПУЛ. Проверено на живых сделках источников:
# счёт с индексом 2 равен pool_state из события у всех образцов (число счетов
# у них разное -- 12, 15, 17, -- а индекс пула один и тот же), хранилище пула
# при этом стоит шестым. По этому индексу событие и выбирается: в маршруте
# роутера событий столько же, сколько пулов.
СМ_ПУЛ_В_ИНСТРУКЦИИ_CLMM = 2

СХЕМЫ = {
    "DAMM2": {"длина": 188, "вход": 43, "минимум": 51, "выход": 84,
               "цена_после": 92, "комиссии": (108, 116, 124, 132)},
    "DBC": {"длина": 162, "вход": 74, "минимум": None, "выход": 98,
             "цена_после": 106, "комиссии": (122, 130)},
}
СМ_ПУЛ = 8                  # адрес пула в теле события (32 байта)
# ПРЕДЕЛ СДВИГА ЦЕНЫ ОДНОЙ СДЕЛКОЙ -- проверка разбора. Цена после сделки
# обязана быть выше средней цены исполнения (покупка двигает цену вверх), но не
# в разы: по 17 живым сделкам DAMM v2 сдвиг лежит между 1.02 и 1.51. Восьмёрка
# -- граница абсурда: выше неё смещение цены прочитано не то.
ПРЕДЕЛ_СДВИГА = D(8)
Q = 1 << 64
# ПРЕДЕЛ РАЗБОРА, А НЕ ДЕНЕГ. У Meteora есть расписание комиссии: свежий пул
# может брать десятки процентов и снижать их со временем -- в живой сделке 26.09
# (образец 9) комиссия была 50.9 %, и модель при ней воспроизвела сделку
# источника точно, то есть это ПРАВДА, а не ошибка разбора. Поэтому здесь порог
# только на правдоподобие разбора; решение "такая комиссия дорога, не покупаем"
# -- денежное, и живёт в полосе (bloom_own_send), а не здесь.
ПРЕДЕЛ_КОМИССИИ = D("0.60")


def _u(тело: bytes, смещение: int, байт: int) -> int:
    return int.from_bytes(тело[смещение:смещение + байт], "little")


def адрес_пула_события(тело: bytes) -> str | None:
    """Адрес пула из тела события -- чтобы не взять событие ЧУЖОГО пула."""
    if not тело or len(тело) < СМ_ПУЛ + 32:
        return None
    try:
        from solders.pubkey import Pubkey  # noqa: PLC0415

        return str(Pubkey(bytes(тело[СМ_ПУЛ:СМ_ПУЛ + 32])))
    except Exception:  # noqa: BLE001
        return None


def тело_события(tx: dict, программа: str, all_instructions, b58decode,
                  пул: str | None = None, длина: int | None = None) -> bytes | None:
    """Тело события свопа из самовызова программы пула. None -- события нет.

    ПУЛ ОБЯЗАТЕЛЕН, КОГДА ИЗВЕСТЕН: в маршруте через два пула DAMM v2 событий
    тоже два, и взять первое значило бы считать цену по чужому пулу.
    """
    for ix in all_instructions(tx):
        if ix.get("programId") != программа:
            continue
        try:
            raw = b58decode(ix.get("data") or "")
        except Exception:  # noqa: BLE001
            continue
        if raw[:8].hex() != ДИСК_СОБЫТИЯ:
            continue
        тело = raw[8:]
        if len(тело) != (длина if длина is not None else СХЕМЫ["DAMM2"]["длина"]):
            continue
        if пул and адрес_пула_события(тело) != пул:
            continue
        return тело
    return None


def тела_событий_clmm(tx: dict, base64_декод=None) -> list:
    """Тела событий SwapEvent из ЛОГОВ транзакции. [] -- событий нет.

    У Raydium CLMM событие не самовызов, а строка лога "Program data: ...".
    В одной транзакции роутера их несколько (по пулу на каждый шаг), поэтому
    возвращается СПИСОК, а выбор по пулу делает вызывающий: взять первое
    значило бы считать цену по чужому пулу.
    """
    import base64 as _b64  # noqa: PLC0415

    дек = base64_декод or _b64.b64decode
    из_ = []
    for строка in (((tx or {}).get("meta") or {}).get("logMessages") or []):
        if "Program data: " not in строка:
            continue
        try:
            сырое = дек(строка.split("Program data: ", 1)[1])
        except Exception:  # noqa: BLE001
            continue
        if сырое[:8].hex() != ДИСК_СОБЫТИЯ_CLMM:
            continue
        if len(сырое) in СХЕМА_CLMM["длины"]:
            из_.append(сырое)
    return из_


def событие_пула_clmm(tx: dict, пул: str, base58_кодер, base64_декод=None) -> dict:
    """Событие ИМЕННО ЭТОГО пула. {} -- события пула в транзакции нет."""
    for тело in тела_событий_clmm(tx, base64_декод):
        с = событие_clmm(тело)
        if base58_кодер(с["пул"]) == пул:
            return с
    return {}


def событие_clmm(тело: bytes, схема: dict | None = None) -> dict:
    """Числа события CLMM. Сверку со сделкой делает вызывающий."""
    с = схема or СХЕМА_CLMM
    return {"пул": тело[с["пул"]:с["пул"] + 32],
            "amount_0": _u(тело, с["amount_0"], 8),
            "amount_1": _u(тело, с["amount_1"], 8),
            "fee_0": _u(тело, с["fee_0"], 8),
            "fee_1": _u(тело, с["fee_1"], 8),
            "сторона_0_вход": bool(тело[с["направление"]]),
            "цена_после": _u(тело, с["цена_после"], 16),
            "ликвидность": _u(тело, с["ликвидность"], 16),
            "тик": int.from_bytes(тело[с["тик"]:с["тик"] + 4], "little", signed=True)}


def событие(тело: bytes, схема: dict) -> dict:
    """Числа события по схеме. Сверку со сделкой делает вызывающий."""
    комиссии = sum(_u(тело, см, 8) for см in схема["комиссии"])
    минимум_ = (_u(тело, схема["минимум"], 8)
                if схема.get("минимум") is not None else None)
    return {"вход_заявлен": _u(тело, схема["вход"], 8),
            "минимум_источника": минимум_,
            "выход": _u(тело, схема["выход"], 8),
            "цена_после": _u(тело, схема["цена_после"], 16),
            "комиссии": комиссии}


def кривая(*, вход_чистый: int, выход: int, цена_после: int,
            база_это_a: bool) -> dict:
    """Цена ДО сделки и ликвидность L по одной сделке и цене после неё.

    база_это_a -- базовый минт это токен A пула (тогда цена = B/A растёт при
    покупке базы за котировку; иначе падает). Направление ПРОВЕРЯЕТСЯ: если
    решённая цена до сделки лежит не с той стороны, значит раскладка или
    направление не те, и числа не годятся.
    """
    из_ = {"ok": False, "why_not": None, "цена_до": None, "L": None}
    if вход_чистый <= 0 or выход <= 0 or цена_после <= 0:
        из_["why_not"] = "вход, выход или цена после сделки не положительны"
        return из_
    if база_это_a:
        # Покупаем A за B: цена B/A росла, значит цена до меньше цены после.
        цена_до = (D(вход_чистый) * D(Q) * D(Q)) / (D(выход) * D(цена_после))
        if not (цена_до < D(цена_после)):
            из_["why_not"] = ("цена до сделки вышла не ниже цены после -- "
                               "направление или раскладка события не те")
            return из_
        L = D(вход_чистый) * D(Q) / (D(цена_после) - цена_до)
    else:
        # Покупаем B за A: цена B/A падала, значит цена до больше цены после.
        цена_до = (D(выход) * D(Q) * D(Q)) / (D(вход_чистый) * D(цена_после))
        if not (цена_до > D(цена_после)):
            из_["why_not"] = ("цена до сделки вышла не выше цены после -- "
                               "направление или раскладка события не те")
            return из_
        L = D(выход) * D(Q) / (цена_до - D(цена_после))
    if L <= 0:
        из_["why_not"] = "ликвидность вышла неположительной"
        return из_
    из_.update(ok=True, цена_до=цена_до, L=L)
    return из_


def выход_по_кривой(*, вход_чистый: int, цена: D, L: D, база_это_a: bool) -> D:
    """Сколько базы даст кривая при чистом входе от указанной цены."""
    if вход_чистый <= 0 or L <= 0:
        return D(0)
    if база_это_a:
        ц2 = D(цена) + D(вход_чистый) * D(Q) / L
        return L * D(Q) * (ц2 - D(цена)) / (D(цена) * ц2)
    ц2 = D(цена) * L * D(Q) / (L * D(Q) + D(вход_чистый) * D(цена))
    return L * (D(цена) - ц2) / D(Q)


def минимум(*, тело: bytes, вход_источника: int, выход_источника: int,
             аргумент_входа: int, база_это_a: bool, наш_вход: int,
             проскальзывание: float, схема: dict | None = None) -> dict:
    """Минимум выхода для НАШЕЙ покупки по кривой после сделки источника.

    вход_источника / выход_источника -- ФАКТ по движению хранилищ пула, а не
    слова события: событие сверяется с ними и при расхождении не берётся.
    """
    из_ = {"ok": False, "why_not": None}
    if not тело:
        из_["why_not"] = "события свопа DAMM v2 в транзакции нет"
        return из_
    схема = схема or СХЕМЫ["DAMM2"]
    с = событие(тело, схема)
    if с["вход_заявлен"] != аргумент_входа:
        из_["why_not"] = (f"событие не сошлось: вход {с['вход_заявлен']} против "
                           f"аргумента инструкции {аргумент_входа}")
        return из_
    if с["выход"] != выход_источника:
        из_["why_not"] = (f"событие не сошлось: выход {с['выход']} против движения "
                           f"хранилища {выход_источника}")
        return из_
    доля_комиссии = (D(с["комиссии"]) / D(вход_источника)
                     if вход_источника > 0 else D(1))
    if not (D(0) <= доля_комиссии < ПРЕДЕЛ_КОМИССИИ):
        из_["why_not"] = f"доля комиссии {доля_комиссии} вне разумного -- разбор не верен"
        return из_
    вход_чистый = вход_источника - с["комиссии"]
    к = кривая(вход_чистый=вход_чистый, выход=выход_источника,
               цена_после=с["цена_после"], база_это_a=база_это_a)
    if not к["ok"]:
        из_["why_not"] = к["why_not"]
        return из_
    # СДВИГ ЦЕНЫ -- ПРОВЕРКА РАЗБОРА. Решённая цена до сделки обязана быть с
    # правильной стороны от цены после и не в разы дальше (см. ПРЕДЕЛ_СДВИГА).
    сдвиг = (D(с["цена_после"]) / к["цена_до"] if база_это_a
             else к["цена_до"] / D(с["цена_после"]))
    if not (D(1) < сдвиг <= ПРЕДЕЛ_СДВИГА):
        из_["why_not"] = (f"сдвиг цены сделкой источника {сдвиг} вне разумного -- "
                           "разбор события не верен")
        return из_
    # СВЕРКА МОДЕЛИ С СОБСТВЕННОЙ СДЕЛКОЙ: кривая, решённая по паре
    # "вход/выход", обязана этот же выход и воспроизвести. Расхождение больше
    # одной десятимиллионной -- значит считаем не по той кривой.
    свой = выход_по_кривой(вход_чистый=вход_чистый, цена=к["цена_до"], L=к["L"],
                            база_это_a=база_это_a)
    откл = abs(свой - D(выход_источника)) / D(выход_источника)
    if откл > D("1e-7"):
        из_["why_not"] = f"модель не воспроизводит сделку источника (отклонение {откл})"
        return из_
    наш_чистый = int(D(наш_вход) * (D(1) - доля_комиссии))
    if наш_чистый <= 0:
        из_["why_not"] = "наш вход меньше комиссии пула"
        return из_
    ожидание = выход_по_кривой(вход_чистый=наш_чистый, цена=D(с["цена_после"]),
                                L=к["L"], база_это_a=база_это_a)
    if ожидание <= 0:
        из_["why_not"] = "кривая дала нулевой выход"
        return из_
    минимум_ = int(ожидание * D(1 - проскальзывание))
    if минимум_ <= 0:
        из_["why_not"] = "минимум после проскальзывания вышел нулём"
        return из_
    return {"ok": True, "expected_out": int(ожидание), "min_out": минимум_,
            "fee_share": float(доля_комиссии), "price_after": с["цена_после"],
            "price_shift": float(сдвиг),
            "price_before": str(int(к["цена_до"])), "liquidity": str(int(к["L"])),
            "source_in_net": вход_чистый, "model_error": float(откл)}
