def арх_файлы() -> list:
    """Архив 7 суток: pyg3 (все 7), иначе pyg2, иначе pyg."""
    for п in ("pyg3_", "pyg2_", "pyg_"):
        ф = sorted(glob.glob(str(КОРЕНЬ / "data" / "podbivka" / "arhiv_den" / f"{п}*.json.gz")))
        if len(ф) >= 7:
            return ф
    return sorted(glob.glob(str(КОРЕНЬ / "data" / "podbivka" / "arhiv_den" / "pyg_*.json.gz")))


АРХ: dict = {}


def арх_загрузить() -> list:
    if "данные" not in АРХ:
        АРХ["данные"] = [json.loads(gzip.decompress(Path(f).read_bytes())) for f in арх_файлы()]
    return АРХ["данные"]


def чч(bt):
    return time.strftime("%H:%M:%S", time.gmtime(bt)) if bt else "—"


def дата(bt):
    return time.strftime("%Y-%m-%d", time.gmtime(bt)) if bt else "—"


def м(x):
    г = (x or {}).get("группы") or []
    return ", ".join(г) if г else ""


