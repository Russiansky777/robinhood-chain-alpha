def строка_часа_без_сделок(*, окно: str, сигналов: int = 0,
                            по_кодам: dict | None = None) -> str:
    """Строка часа, когда сделок полосы за окно не было.

    ЗАЧЕМ ОТДЕЛЬНАЯ СТРОКА. Прежняя строка часа считает покупки ПЛОЩАДКИ, а
    площадка у нас выключена на всех группах (bloom_trades=false) -- её счётчик
    не может быть ничем, кроме нуля. "покупок 0" при 23 сделках полосы (27.09,
    17:49 Мадрид) -- ровно этот случай. Здесь говорится о ПОЛОСЕ, а рядом --
    сколько сигналов разобрано и какие причины отказа были чаще всего: по ним
    видно, молчит полоса из-за порогов источников или из-за поломки.
    """
    части = [f"📊 {экран(окно)}", "полоса 0 сделок", f"сигналов {int(сигналов)}"]
    верх = sorted((по_кодам or {}).items(), key=lambda кв: -int(кв[1]))[:3]
    if верх:
        части.append("чаще всего: "
                     + ", ".join(f"{экран(str(к))} {int(н)}" for к, н in верх))
    return " · ".join(части)


