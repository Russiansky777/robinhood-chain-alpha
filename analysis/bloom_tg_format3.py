"""Формат 3 в Telegram: ОДНО сообщение на сделку. Пакет владельца 27.09.

ЗАЧЕМ. К 27.09 в чат уходило по нескольку сообщений на одну сделку: покупка,
продажа, отдельный "полный круг" с миллисекундами и "новыми соединениями",
часовая таблица прогоном и сводка. Владелец 27.09: "ОДНО сообщение на сделку",
всё старое выключить, проценты чистыми после чаевых и приоритета, группу писать
словом, размер числом, имя токена (если нет -- первые 6 знаков минта).

ЧТО ЗДЕСЬ. Ровно четыре вида текста и ни одного лишнего:
  1. первая строка сделки (покупка);
  2. вторая строка (продажа) -- ДОПИСЫВАЕТСЯ к тому же сообщению правкой,
     новым сообщением не идёт;
  3. третья строка -- только если по этому сигналу есть пара DBot/Bloom;
  4. одна строка в час и тревоги (четыре повода, больше никаких).

Образцы владельца, дословно:
  🟢 14:02:11 leader · Bloom 0.2 · TOKEN · S+1 (312/1128) · +6.3 % к цене
     источника · довёз nozomi · [tx]
  🔴 29 с · 0.200 → 0.231 · +15.3 % · [tx]
  DBot: S+2 · +14.1 % к цене источника · итог +9.8 %
  📊 13–14 · leader 4 сделки +0.061 SOL · lane_s0 6 сделок +0.004 · S+0 3/10 ·
     DBot по тем же сигналам +0.048 · стоп: leader −0.06/−0.30
Самопроверка ниже собирает ровно эти строки и сверяет их посимвольно: формат --
это договор с владельцем, и "почти так" тут не считается.

ЧЕГО НЕТ И НЕ ДОЛЖНО БЫТЬ. Цвет второй строки всегда 🔴 -- так в образце
владельца, где 🔴 стоит при +15.3 %: зелёный кружок помечает вход, красный
выход, а прибыль видна процентом. Выдумывать свой цвет по знаку прибыли нельзя:
владелец прислал формат, а не задачу на оформление.
"""
from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

SOLSCAN = "https://solscan.io/tx/"
# Слова групп -- те, которыми пишет владелец. Слева имя группы в файле, справа
# слово в сообщении. Группы, которой тут нет, пишется её собственное имя: врать
# словом "leader" про чужую группу нельзя.
# ГРУППА -- СЛОВОМ, КАК ОНА НАЗЫВАЕТСЯ В ФАЙЛЕ. Подмены здесь больше нет: до
# 27.09 speed_only печаталась как "lane_s0", потому что группы lane_s0 не
# существовало. Теперь она есть, и подмена выдавала бы одну группу за другую --
# на строке с деньгами это прямая ложь.
СЛОВА_ГРУПП = {"leader": "leader", "batch5": "batch5", "lane_s0": "lane_s0",
                "off": "off", "log_only": "log_only"}
# Площадки. "Bloom" -- покупка площадки, "полоса" -- наша своя отправка.
ПЛОЩАДКА_BLOOM = "Bloom"
ПЛОЩАДКА_ПОЛОСА = "полоса"
# Поводы тревог -- закрытый список (слово владельца: "только на").
ТРЕВОГИ = {
    "нет_продажи": "покупка села, продажи нет через 60 с",
    "продажа_упала": "продажа упала",
    "учёт": "учёт не сошёлся",
    "kill": "KILL",
}


def экран(текст) -> str:
    return (str(текст if текст is not None else "")
            .replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;"))


def ссылка(подпись: str | None, ярлык: str = "tx") -> str:
    if not подпись:
        return f"[{ярлык}]"
    return f'<a href="{SOLSCAN}{подпись}">[{ярлык}]</a>'


def _чч_мм_сс(строка_времени: str | None) -> str:
    т = str(строка_времени or "")
    if "T" in т and len(т) >= 19:
        return т[11:19]
    return т[:8] or "--:--:--"


def имя_токена(имя: str | None, минт: str | None) -> str:
    """Имя токена, а нет имени -- первые 6 знаков минта (слово владельца)."""
    ч = str(имя or "").strip()
    if ч:
        return экран(ч)
    м = str(минт or "").strip()
    return экран(м[:6]) if м else "—"


def слово_группы(группа: str | None) -> str:
    г = str(группа or "").strip()
    if not г:
        return "—"
    return СЛОВА_ГРУПП.get(г, экран(г))


def _проц(x, знаков: int = 1) -> str:
    """Проценты со знаком. Минус -- типографский, как в образце владельца."""
    if x is None:
        return "—"
    з = float(x)
    знак = "+" if з > 0 else ("−" if з < 0 else "")
    return f"{знак}{abs(з):.{знаков}f} %"


def _sol(x, знаков: int = 3) -> str:
    return "—" if x is None else f"{float(x):.{знаков}f}"


def _sol_со_знаком(x, знаков: int = 3) -> str:
    if x is None:
        return "—"
    з = float(x)
    return f"{'+' if з >= 0 else '−'}{abs(з):.{знаков}f}"


def _размер(x) -> str:
    """Размер числом. Лишние нули не печатаем: 0.2, а не 0.2000."""
    if x is None:
        return "—"
    т = f"{float(x):.4f}".rstrip("0").rstrip(".")
    return т or "0"


def строка_buy(*, время_utc: str | None, группа: str | None, площадка: str,
                размер_sol, имя: str | None, минт: str | None,
                наш_s: int | None, наш_индекс=None, наш_всего=None,
                процент_к_источнику=None, довёз: str | None = None,
                подпись: str | None = None) -> str:
    """Первая строка сделки. Чего не измерено -- черта, а не ноль."""
    s = f"S+{int(наш_s)}" if наш_s is not None else "S+?"
    место = ""
    if наш_индекс is not None and наш_всего:
        место = f" ({int(наш_индекс)}/{int(наш_всего)})"
    кто = экран(довёз) if довёз else "—"
    return (f"🟢 {_чч_мм_сс(время_utc)} {слово_группы(группа)} · "
            f"{экран(площадка)} {_размер(размер_sol)} · "
            f"{имя_токена(имя, минт)} · {s}{место} · "
            f"{_проц(процент_к_источнику)} к цене источника · "
            f"довёз {кто} · {ссылка(подпись)}")


def строка_упала(*, время_utc: str | None, группа: str | None,
                  источник: str | None, имя: str | None, минт: str | None,
                  cu_потрачено=None, cu_предел=None,
                  ошибка: str | None = None) -> str:
    """Транзакция села, но упала: err не пустой -- позиция НЕ открывается.

    Слово владельца 28.09: "транзакция села, но упала (err != None) -- вместо
    зелёной строки красный крест с CU: потрачено из предела". CU показываются
    именно парой: 28.09 покупки кривой V2 падали ровно потому, что предел был
    меньше стоимости инструкции.
    """
    def _cu(зн) -> str:
        return (f"{int(зн):,}".replace(",", " ") if isinstance(зн, (int, float))
                 else "—")

    cu = "—"
    if cu_потрачено is not None or cu_предел is not None:
        cu = f"{_cu(cu_потрачено)} / {_cu(cu_предел)}"
    кто = экран((источник or "")[:8]) if источник else "—"
    хвост = f" · {экран(ошибка)}" if ошибка else ""
    return (f"❌ {_чч_мм_сс(время_utc)} упала: CU {cu} · {слово_группы(группа)} · "
            f"{кто} · {имя_токена(имя, минт)}{хвост}")


def строка_не_села(*, время_utc: str | None, группа: str | None,
                    источник: str | None, имя: str | None,
                    минт: str | None) -> str:
    """Покупка не села: подпись в записи есть, на цепи её нет.

    Слово владельца 28.09: "позиция не открывается, сторож её не трогает; в TG
    вместо зелёной строки BUY -- одна белая строка". Денег такая попытка не
    двигает вовсе (транзакции на цепи нет), поэтому ни размера, ни процента
    здесь быть не может -- только время, группа, источник и токен.
    """
    кто = экран((источник or "")[:8]) if источник else "—"
    return (f"⚪ {_чч_мм_сс(время_utc)} не села · {слово_группы(группа)} · "
            f"{кто} · {имя_токена(имя, минт)}")


def строка_sell(*, секунды, вход_sol, возврат_sol, процент=None,
                 подпись: str | None = None) -> str:
    """Вторая строка. Процент ЧИСТЫЙ: его считает вызывающий, здесь только вид.

    Процент можно не передавать -- тогда он считается из входа и возврата, но
    это будет доля БЕЗ вычета чаевых и приоритета, поэтому вызывающий обязан
    передавать чистый. Оба пути дают одно и то же число на одних данных, и
    подменять чистый процент грязным молча нельзя -- поэтому расчёт здесь
    только как запасной и ровно по переданным числам.
    """
    if процент is None and вход_sol and возврат_sol is not None:
        процент = (float(возврат_sol) / float(вход_sol) - 1.0) * 100.0
    сек = "—" if секунды is None else f"{int(round(float(секунды)))}"
    return (f"🔴 {сек} с · {_sol(вход_sol)} → {_sol(возврат_sol)} · "
            f"{_проц(процент)} · {ссылка(подпись)}")


def строка_dbot(*, s: int | None, процент_к_источнику=None, итог_процент=None,
                 ) -> str:
    """Третья строка -- ТОЛЬКО когда по этому сигналу есть пара DBot/Bloom."""
    ч = f"S+{int(s)}" if s is not None else "S+?"
    return (f"DBot: {ч} · {_проц(процент_к_источнику)} к цене источника · "
            f"итог {_проц(итог_процент)}")


def сообщение_сделки(*, buy: str, sell: str | None = None,
                      dbot: str | None = None) -> str:
    """Одно сообщение на сделку: строки складываются, а не рассылаются."""
    строки = [buy]
    if sell:
        строки.append(sell)
    if dbot:
        строки.append(dbot)
    return "\n".join(строки)


def строка_часа(*, окно: str, по_группам: list, s0: int | None = None,
                 сделок_всего: int | None = None, dbot_sol=None,
                 стоп_группа: str | None = None, стоп_текущий=None,
                 стоп_порог=None, сигналов: int | None = None,
                 по_кодам: dict | None = None) -> str:
    """Одна строка в час.

    по_группам -- список (слово_группы, сделок, итог_SOL) либо
    (слово_группы, сделок, s0_группы, итог_SOL): слово владельца 27.09 (вечер)
    -- "по группам: сделок, доля S+0, итог SOL". Оба вида принимаются, чтобы
    вызывающий мог не знать про S+0, когда его нечем посчитать.

    Сигналы и коды отказов дописываются ОДНОЙ строкой в конце (то же слово
    владельца): по ним видно, молчит полоса из-за порогов источников или
    из-за поломки.
    """
    части = [f"📊 {экран(окно)}"]
    for и, ряд in enumerate(по_группам or []):
        if len(ряд) >= 4:
            группа, сделок, s0_гр, итог = ряд[0], ряд[1], ряд[2], ряд[3]
        else:
            группа, сделок, итог = ряд[0], ряд[1], ряд[2]
            s0_гр = None
        хвост = " SOL" if и == 0 else ""
        доля = (f" S+0 {int(s0_гр)}/{int(сделок)}"
                if s0_гр is not None and сделок else "")
        части.append(f"{слово_группы(группа)} {int(сделок)} "
                     f"{_слово_сделок(int(сделок))}{доля} "
                     f"{_sol_со_знаком(итог)}{хвост}")
    if s0 is not None and сделок_всего:
        части.append(f"S+0 {int(s0)}/{int(сделок_всего)}")
    if dbot_sol is not None:
        части.append(f"DBot по тем же сигналам {_sol_со_знаком(dbot_sol)}")
    if стоп_группа is not None:
        части.append(f"стоп: {слово_группы(стоп_группа)} "
                     f"{_sol_со_знаком(стоп_текущий, 2)}/"
                     f"{_sol_со_знаком(стоп_порог, 2)}")
    if сигналов is not None:
        части.append(f"сигналов {int(сигналов)}")
        верх = sorted((по_кодам or {}).items(), key=lambda кв: -int(кв[1]))[:3]
        if верх:
            части.append("отказы: "
                         + ", ".join(f"{экран(str(к))} {int(н)}" for к, н in верх))
    return " · ".join(части)


def _слово_сделок(n: int) -> str:
    """сделка / сделки / сделок -- по-русски, а не "сделок 1"."""
    о10, о100 = n % 10, n % 100
    if о10 == 1 and о100 != 11:
        return "сделка"
    if о10 in (2, 3, 4) and о100 not in (12, 13, 14):
        return "сделки"
    return "сделок"


def строка_тревоги(вид: str, подробно: str = "") -> str:
    """Тревога -- ОТДЕЛЬНЫМ сообщением и только по закрытому списку поводов."""
    если = ТРЕВОГИ.get(вид)
    if не_повод(вид):
        # Незнакомый повод НЕ отправляется под видом тревоги: список закрыт
        # словом владельца, и тихо расширять его нельзя.
        return ""
    текст = f"⚠️ {если}"
    if подробно:
        текст += f" · {экран(подробно)[:200]}"
    return текст


def не_повод(вид: str) -> bool:
    return вид not in ТРЕВОГИ


