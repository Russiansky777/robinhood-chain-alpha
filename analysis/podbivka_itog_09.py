#!/usr/bin/env python3
"""Одна общая таблица по задаче владельца 09.10 и вердикт по каждому пункту одной строкой.

Ничего не считает сам -- собирает уже посчитанное из файлов итогов, чтобы числа в разных
документах не разошлись:
  * `data/podbivka/a_sverka.json`   -- п.1, 4vw54BmA (`podbivka_a_sverka.py`);
  * `data/podbivka/zapuski_itog.json` -- п.В, запуски и переезд (`podbivka_zapuski_svod.py`);
  * `data/podbivka/tg_itog.json`    -- п.2, коллы TG (`podbivka_tg_svod.py`);
  * `data/podbivka/arbitrazh_svod.json` -- п.3б, арбитраж (`podbivka_arbitrazh.py`).

Чего нет -- так и говорится строкой «нет данных», без выдумок.

Столбцы те, что просил владелец: что -> билет -> n проверки -> сделок/сут -> SOL/сут ->
медиана по сделкам -> без 5 лучших -> худшие сутки -> p -> проходит/нет.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parent.parent
П = КОРЕНЬ / "data" / "podbivka"


def читать(имя: str):
    ф = П / имя
    if not ф.exists():
        return None
    try:
        return json.loads(ф.read_text(encoding="utf-8"))
    except json.JSONDecodeError:
        return None


def ф(v, формат="+.4f"):
    return "—" if v is None else format(v, формат)


def строка(что: str, r: dict, билет) -> str:
    return (f"| {что} | {билет} | {r.get('n', '—')} | {r.get('сделок_в_сутки', '—')} | "
            f"{ф(r.get('sol_в_сутки'))} | {ф(r.get('sol_в_сутки_по_медиане'))} | "
            f"{ф(r.get('медиана_пп'), '+.2f')} | "
            f"{ф(r.get('итог_без_5_лучших_sol'))} | {ф(r.get('худшие_сутки_sol'))} | "
            f"{'—' if r.get('p') is None else format(r['p'], '.3f')} | "
            f"{'ДА' if r.get('проходит') else 'нет'} |")


def лучшая(строки: list, ключ="sol_в_сутки"):
    годн = [x for x in строки if x.get("проходит")]
    ряд = годн or строки
    return max(ряд, key=lambda x: (x.get(ключ) or -1e9)) if ряд else None


def main() -> int:
    р_ = argparse.ArgumentParser()
    р_.add_argument("--metka", default="2026-10-09")
    а = р_.parse_args()

    а_св = читать("a_sverka.json")
    зап = читать("zapuski_itog.json")
    тг = читать("tg_itog.json")
    арб = читать("arbitrazh_svod.json")

    ряды, вердикты = [], []

    # п.1 -- 4vw54BmA
    if а_св:
        п2 = а_св.get("п2") or {}
        билет = ((а_св.get("калибровка") or {}).get("билет")
                 or а_св.get("билет") or 0.3)
        лучш, имя = None, None
        for k, v in (п2.items() if isinstance(п2, dict) else []):
            if not isinstance(v, dict):
                continue
            пров = v.get("проверка") or {}
            кандидат = {**пров, "проходит": v.get("проходит"),
                        "p": v.get("p_случайности"),
                        "медиана_пп": пров.get("медиана_по_сделкам_пп"),
                        "сделок_в_сутки": v.get("сделок_в_сутки"), "n": пров.get("n")}
            if v.get("проходит") and (лучш is None
                                      or (кандидат.get("sol_в_сутки") or -1e9)
                                      > (лучш.get("sol_в_сутки") or -1e9)):
                лучш, имя = кандидат, k
        if лучш:
            реж, доп, H = (имя.split("|") + ["", ""])[:3]
            ряды.append(строка(f"1. 4vw54BmA: {реж}, допуск {100*float(доп):.0f} %, "
                               f"{H} слотов", лучш, билет))
            вердикты.append(f"**п.1 (4vw54BmA):** включать -- {реж}, допуск "
                            f"{100*float(доп):.0f} %, удержание {H} слотов, билет "
                            f"{билет} SOL, {ф(лучш.get('sol_в_сутки'))} SOL в сутки на "
                            f"проверке; медиана по совершённым сделкам "
                            f"{ф(лучш.get('медиана_пп'), '+.2f')} п.п., p="
                            f"{'—' if лучш.get('p') is None else format(лучш['p'], '.3f')}. "
                            f"Живых сделок по этому адресу нет (группы vol_4vw нет, полоса "
                            f"выключена) -- сверять нечем.")
        else:
            вердикты.append("**п.1 (4vw54BmA):** ни один режим порог не проходит.")
    else:
        вердикты.append("**п.1 (4vw54BmA):** нет данных (a_sverka.json не найден).")

    # п.В -- запуски
    if зап:
        стр = зап.get("строки") or []
        л = лучшая(стр)
        if л:
            ряды.append(строка(f"В. запуски: {л['фильтр']}, вход {л['место']}, "
                               f"{л['удержание']} слотов", л, л["билет"]))
        ох = (зап.get("охват") or {}).get("в_сутки") or {}
        если_да = [x for x in стр if x.get("проходит") and x.get("холм")]
        если_мягко = [x for x in стр if x.get("проходит")]
        if если_да:
            x = если_да[0]
            вердикты.append(
                f"**п.В (запуски):** да -- {x['фильтр']}, вход {x['место']}, удержание "
                f"{x['удержание']} слотов, билет {x['билет']} SOL: "
                f"{ф(x['sol_в_сутки'])} SOL в сутки, медиана "
                f"{ф(x['медиана_пп'], '+.2f')} п.п., p={x['p']:.3f}. Запусков по цепи "
                f"{ох.get('запусков', '—')} в сутки, из них кривых {ох.get('кривых', '—')}, "
                f"переездов {ох.get('переездов', '—')}.")
        elif если_мягко:
            x = если_мягко[0]
            вердикты.append(
                f"**п.В (запуски):** порог проходит {len(если_мягко)} комбинаций (лучшая -- "
                f"{x['фильтр']}, {x['место']}, {x['удержание']} сл, {x['билет']} SOL, "
                f"{ф(x['sol_в_сутки'])} SOL в сутки), но поправку на множественный отбор по "
                f"{зап.get('проверено')} кандидатам не держит ни одна.")
        else:
            вердикты.append("**п.В (запуски):** нет -- вход от создания порог не проходит "
                            "ни при одном месте, удержании и билете.")
        # п.3а -- переезд
        пер = зап.get("переезд") or []
        лп = лучшая(пер)
        if лп:
            ряды.append(строка(f"3а. переезд кривой: вход {лп['место']}, "
                               f"{лп['удержание']} слотов", лп, лп["билет"]))
            вердикты.append(
                f"**п.3а (переезд кривой):** "
                + (f"да -- вход {лп['место']}, удержание {лп['удержание']} слотов, билет "
                   f"{лп['билет']} SOL, {ф(лп['sol_в_сутки'])} SOL в сутки, медиана "
                   f"{ф(лп['медиана_пп'], '+.2f')} п.п."
                   if лп.get("проходит") else
                   "нет -- ни одно место входа, удержание и билет порог не проходят."))
        else:
            вердикты.append("**п.3а (переезд кривой):** нет данных.")
    else:
        вердикты.append("**п.В (запуски):** нет данных (zapuski_itog.json не найден).")
        вердикты.append("**п.3а (переезд кривой):** нет данных.")

    # п.2 -- коллы TG
    if тг:
        стр = тг.get("строки") or []
        л = лучшая(стр)
        if л:
            ряды.append(строка(f"2. TG: {л['канал']}, вход {л['место']}, выход "
                               f"{л['удержание_с']} с", л, л["билет"]))
        если_да = [x for x in стр if x.get("проходит") and x.get("холм")]
        если_мягко = [x for x in стр if x.get("проходит")]
        вп = (тг.get("вперёд_нас") or {}).get("2с") or {}
        хвост = (f" Чужих покупок вперёд нас за 2 с: медиана "
                 f"{(вп.get('покупок') or {}).get('медиана')}, кошельков "
                 f"{(вп.get('кошельков') or {}).get('медиана')}.")
        if если_да:
            x = если_да[0]
            вердикты.append(
                f"**п.2 (коллы TG):** да -- {x['канал']}, вход {x['место']}, выход "
                f"{x['удержание_с']} с, билет {x['билет']} SOL: {ф(x['sol_в_сутки'])} SOL в "
                f"сутки, медиана {ф(x['медиана_пп'], '+.2f')} п.п., p={x['p']:.3f}. "
                f"Каналов открытых без входа {тг.get('каналов')}, коллов "
                f"{тг.get('коллов')}." + хвост)
        elif если_мягко:
            x = если_мягко[0]
            вердикты.append(
                f"**п.2 (коллы TG):** порог проходит {len(если_мягко)} строк (лучшая -- "
                f"{x['канал']}, {x['место']}, {x['удержание_с']} с, {x['билет']} SOL, "
                f"{ф(x['sol_в_сутки'])} SOL в сутки), но поправку на множественный отбор не "
                f"держит ни одна." + хвост)
        else:
            вердикты.append(
                f"**п.2 (коллы TG):** нет -- вход за каналом порог не проходит ни по одному "
                f"из {тг.get('каналов')} каналов ({тг.get('коллов')} коллов)." + хвост)
    else:
        вердикты.append("**п.2 (коллы TG):** нет данных (tg_itog.json не найден).")

    # п.3б -- арбитраж
    if арб:
        всего = {"сравнений": 0, "в_плюсе": 0, "итог_sol": 0.0, "минтов": 0,
                 "серий2": 0, "суток": 0}
        по_билетам: dict = {}
        for _, тело in арб.items():
            всего["суток"] += 1
            for б, v in (тело.get("по_билетам") or {}).items():
                t = по_билетам.setdefault(б, {"сравнений": 0, "в_плюсе": 0, "итог_sol": 0.0,
                                              "минтов": 0, "серий2": 0})
                t["сравнений"] += v.get("сравнений") or 0
                t["в_плюсе"] += v.get("в_плюсе") or 0
                t["итог_sol"] += v.get("итог_sol") or 0
                t["минтов"] += v.get("минтов_с_выгодой") or 0
                t["серий2"] += v.get("серий_2_и_больше_слотов") or 0
        сут = max(1, всего["суток"])
        for б, t in sorted(по_билетам.items(), key=lambda x: float(x[0])):
            ряды.append(
                f"| 3б. арбитраж между пулами | {б} | {t['сравнений']} | "
                f"{round(t['в_плюсе'] / сут, 1)} | {ф(t['итог_sol'] / сут)} | — | — | — | — | "
                f"— | "
                f"{'ДА' if t['итог_sol'] > 0 and t['серий2'] > 0 else 'нет'} |")
        лучш_б = max(по_билетам.items(), key=lambda x: x[1]["итог_sol"]) if по_билетам else None
        if лучш_б and лучш_б[1]["итог_sol"] > 0:
            б, t = лучш_б
            вердикты.append(
                f"**п.3б (арбитраж):** есть, но редко -- при билете {б} SOL "
                f"{ф(t['итог_sol'] / сут)} SOL в сутки, в плюсе "
                f"{round(100 * t['в_плюсе'] / max(1, t['сравнений']), 2)} % сравнений, "
                f"минтов с выгодой {t['минтов']}, серий не короче 2 слотов {t['серий2']} "
                f"(суток в счёте {сут}).")
        else:
            вердикты.append(
                f"**п.3б (арбитраж):** нет -- разница цен между пулами одного минта не "
                f"перекрывает издержки круга ни при одном билете (суток в счёте {сут}).")
    else:
        вердикты.append("**п.3б (арбитраж):** нет данных (arbitrazh_svod.json не найден).")

    м = [f"# Итог задачи 09.10: одна таблица и вердикт по каждому пункту", "",
         "Числа взяты из файлов итогов соответствующих проходов, а не посчитаны заново -- "
         "чтобы таблица не разошлась с документами по пунктам. Порог владельца везде один: "
         "на проверке не меньше 100 сделок, медиана ПО СОВЕРШЁННЫМ СДЕЛКАМ больше нуля, итог "
         "без пяти лучших в плюсе, обе половины проверки в плюсе, худшие сутки не хуже "
         "-2 SOL, уровень случайности p не больше 0.05, билет не больше 2 % резерва пула на "
         "80 % сделок. Там, где средний итог и итог по медианной сделке сильно расходятся, "
         "решать надо по медианному: средний тянет правый хвост, а он в отдельных сутках "
         "может не случиться вовсе.", "",
         "| что | билет | n проверки | сделок/сут | SOL/сут средний | "
         "SOL/сут по медиане | медиана по сделкам | без 5 лучших | худшие сутки | p | "
         "проходит |",
         "|---|---|---|---|---|---|---|---|---|---|---|"]
    м += ряды or ["| нет ни одного посчитанного пункта | — | — | — | — | — | — | — | — | — |"]
    м += ["", "## Вердикты", ""]
    м += [f"* {в}" for в in вердикты]
    (КОРЕНЬ / "docs" / f"podbivka_itog_{а.metka}.md").write_text(
        "\n".join(м) + "\n", encoding="utf-8")
    print(f"итог: строк {len(ряды)}, вердиктов {len(вердикты)} -> "
          f"docs/podbivka_itog_{а.metka}.md", flush=True)
    for в in вердикты:
        print("  " + в.replace("**", ""), flush=True)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
