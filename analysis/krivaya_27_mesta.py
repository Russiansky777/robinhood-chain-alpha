def места_продажи_из_пары(счета_покупки: list, счета_продажи: list) -> dict:
    """Карта мест продажи по ПАРЕ одного пула. Чистая функция, без сети.

    Возвращает карту вида (место в покупке для каждого места продажи) -- ровно в
    том виде, в каком её читает сборщик (КРИВАЯ_МЕСТА_ПРОДАЖИ). Карта отдаётся
    ТОЛЬКО если каждое место продажи нашлось в покупке РОВНО ОДИН раз.

    ТРИ ВИДА НЕВЫВОДИМОСТИ, И КАЖДЫЙ НАЗВАН СВОИМ СЛОВОМ:
      нет_в_покупке -- счёт в продаже есть, в покупке его нет вовсе (такое место
        собирается не из покупки, и карта мест здесь не поможет);
      дважды_в_покупке -- адрес стоит в покупке на двух местах, и какое из них
        имел в виду продавец, по одной паре не узнать;
      пусто -- в списке продажи на этом месте не адрес.
    """
    # None -- ЭТО ДЫРКА, А НЕ АДРЕС "None". str(None) дал бы строку, которая
    # сравнивается как адрес и честный отказ "пусто" превращает в "нет в
    # покупке": причина была бы названа неверно ровно там, где она денежная.
    пок = ["" if к is None else str(к) for к in (счета_покупки or [])]
    прод = ["" if к is None else str(к) for к in (счета_продажи or [])]
    из_: dict = {"ok": False, "карта": None, "мест_продажи": len(прод),
                 "счетов_покупки": len(пок), "места": [], "не_выводятся": [],
                 "покупка_не_использована": [], "почему": None}
    if not пок or not прод:
        из_["почему"] = ("пара неполна: счетов покупки "
                         f"{len(пок)}, счетов продажи {len(прод)}")
        return из_
    где: dict = {}
    for i, к in enumerate(пок):
        где.setdefault(к, []).append(i)
    карта = []
    for j, к in enumerate(прод):
        места = где.get(к) or []
        запись = {"место_продажи": j, "ключ": к, "место_покупки": None,
                  "почему": None}
        if not к:
            запись["почему"] = "пусто"
        elif not места:
            запись["почему"] = "нет_в_покупке"
        elif len(места) > 1:
            запись["почему"] = "дважды_в_покупке"
            запись["места_покупки"] = места
        else:
            запись["место_покупки"] = места[0]
        из_["места"].append(запись)
        if запись["почему"]:
            из_["не_выводятся"].append(запись)
        карта.append(запись["место_покупки"])
    использованы = {з["место_покупки"] for з in из_["места"]
                    if з["место_покупки"] is not None}
    из_["покупка_не_использована"] = [
        {"место_покупки": i, "ключ": к} for i, к in enumerate(пок)
        if i not in использованы]
    if из_["не_выводятся"]:
        из_["почему"] = (f"мест продажи {len(прод)}, из них не выводятся "
                         f"{len(из_['не_выводятся'])}: "
                         + ", ".join(f"{з['место_продажи']} ({з['почему']})"
                                     for з in из_["не_выводятся"][:8])
                         + " -- карты нет, угадывать на деньгах нельзя")
        return из_
    из_.update(ok=True, карта=tuple(карта),
               почему=(f"все {len(прод)} мест продажи нашлись в покупке ровно по "
                       "одному разу -- карта измерена, а не угадана"))
    return из_


def подпись_покупки_из_журнала(минт: str, *, путь: str | None = None) -> dict:
    """Севшая подпись НАШЕЙ покупки названного минта -- из журнала позиций.

    ПОЧЕМУ ИЗ ЖУРНАЛА, А НЕ ПОИСКОМ ПО КОШЕЛЬКУ. У кошелька полосы по одному
    минту бывает несколько сделок (докупки), и какая из них та самая, по списку
    подписей не видно. В журнале позиция одна и подпись в ней та, которой
    покупка СЕЛА, -- ровно она и даёт раскладку счетов.
    """
    import os  # noqa: PLC0415

    из_: dict = {"ok": False, "why_not": None, "подпись": None,
                 "client_order_id": None, "путь": None}
    п = путь or os.path.join(
        (os.environ.get("BLOOM_STATE_DIR") or "").strip() or ".", "positions.jsonl")
    из_["путь"] = п
    if not минт:
        из_["why_not"] = "минт не назван"
        return из_
    # РОТИРОВАННЫЕ .gz -- ТОЖЕ ЖУРНАЛ. Закрытая ночью позиция в текущем файле
    # уже не лежит: logrotate унёс её в positions.jsonl.1.gz, и первый прогон
    # этого измерения получил "в журнале нет севшей покупки" ровно по этой
    # причине. Порядок чтения -- от старого к новому (.N.gz ... .1.gz, потом
    # текущий), чтобы последней осталась САМАЯ СВЕЖАЯ запись позиции.
    import glob  # noqa: PLC0415
    import gzip  # noqa: PLC0415

    def _номер(имя: str) -> int:
        хвост = имя[len(п) + 1:].split(".")[0]
        return int(хвост) if хвост.isdigit() else 0

    архивы = sorted(glob.glob(f"{п}.*.gz"), key=_номер, reverse=True)
    из_["файлы"] = архивы + [п]
    найдено = None
    прочитан = False
    for файл in из_["файлы"]:
        try:
            ф = (gzip.open(файл, "rt", encoding="utf-8") if файл.endswith(".gz")
                 else open(файл, encoding="utf-8"))
        except OSError:
            continue
        прочитан = True
        with ф:
            for стр in ф:
                стр = стр.strip()
                # БЫСТРЫЙ ОТСЕВ ПО ПОДСТРОКЕ ЦЕЛ, А НЕ ОПАСЕН: адрес минта --
                # base58, то есть только ASCII, и json его не переписывает ни
                # при каком ensure_ascii. Так журнал в тысячи строк не разбирается
                # целиком ради одной позиции.
                if not стр or минт not in стр:
                    continue
                try:
                    з = json.loads(стр)
                except Exception:  # noqa: BLE001, PERF203
                    continue
                if not isinstance(з, dict) or з.get("mint") != минт:
                    continue
                подпись = (з.get("lane_landed_signature") or з.get("lane_signature")
                           or з.get("buy_signature"))
                if подпись:
                    найдено = (str(подпись), з.get("client_order_id"), файл)
    if not прочитан:
        из_["why_not"] = f"журнал позиций не прочитан: ни {п}, ни его .gz"
        return из_
    if not найдено:
        из_["why_not"] = f"в журнале нет севшей покупки минта {минт[:10]}"
        return из_
    из_.update(ok=True, подпись=найдено[0], client_order_id=найдено[1],
               откуда=найдено[2])
    return из_


