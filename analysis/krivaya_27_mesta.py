def инструкции_кривой(tx: dict, *, модуль=None) -> list:
    """ВСЕ инструкции программы кривой: у продажи через Jupiter она внутренняя."""
    BV = модуль if модуль is not None else _цепь()
    ключи = BV.ключи_сообщения(tx)
    из_ = []
    for и in BV.инструкции(tx):
        if и.get("programId") != BONDING:
            continue
        данные = и.get("data") or ""
        сырое = BV.b58decode(данные) if данные else b""
        места = []
        for н in и["accounts"]:
            # Счета инструкции приходят либо адресами, либо НОМЕРАМИ в списке
            # ключей сообщения. Номер в адрес превращаем здесь: сопоставлять
            # номера двух разных транзакций нельзя -- это разные списки.
            if isinstance(н, int):
                места.append(ключи[н] if 0 <= н < len(ключи) else None)
            else:
                места.append(str(н))
        диск = сырое[:8].hex()
        из_.append({"accounts": места, "disc": диск, "n": len(места),
                    "событие": диск == СОБЫТИЕ_ANCHOR_ДИСК})
    return из_


def сделки_кривой(tx: dict, *, модуль=None) -> list:
    """Только настоящие сделки кривой: записи событий Anchor отброшены."""
    return [и for и in инструкции_кривой(tx, модуль=модуль) if not и["событие"]]


def подпись_покупки_по_счёту(счёт: str, *, модуль=None, читатель=None,
                             подписи_фн=None, читать_макс: int = 6) -> dict:
    """Подпись НАШЕЙ покупки по счёту токена: самая старая сделка этого счёта.

    ПОЧЕМУ НАДЁЖНЕЕ ЖУРНАЛА. Журнал позиций ротируется и обновляется записями,
    в которых подписи нет вовсе: живой прогон 02.10 достал сорок строк с одним
    client_order_id и ни одной с севшей подписью. У счёта токена история
    короткая и однозначная: он СОЗДАЁТСЯ покупкой, и покупка в нём первая.
    Проверяется не "первая", а разновидность: читаем от старых к новым и берём
    ту, где инструкция кривой именно 27-счётная.

    Читаем не больше читать_макс транзакций: покупка в начале истории, и
    перебирать весь счёт ради неё незачем.
    """
    BV = модуль if модуль is not None else _цепь()
    подписи_ = подписи_фн if подписи_фн is not None else (
        lambda: BV.зов("getSignaturesForAddress",
                       [счёт, {"limit": 1000, "commitment": "confirmed"}]))
    читать = читатель if читатель is not None else (
        lambda п: BV.зов("getTransaction",
                         [п, {"encoding": "jsonParsed", "commitment": "confirmed",
                              "maxSupportedTransactionVersion": 0}]))
    из_: dict = {"ok": False, "why_not": None, "подпись": None, "счёт": счёт,
                 "сделок_счёта": None, "прочитано": 0, "осмотрено": []}
    if not счёт:
        из_["why_not"] = "счёт токена не назван"
        return из_
    о = подписи_()
    if not (о or {}).get("ok"):
        из_["why_not"] = (f"история счёта не прочитана: "
                          f"{(о or {}).get('why_not') or 'узел не отдал'}")
        return из_
    ряды = [str((р or {}).get("signature") or "") for р in (о.get("result") or [])]
    ряды = [п for п in ряды if п]
    из_["сделок_счёта"] = len(ряды)
    if not ряды:
        из_["why_not"] = "у счёта токена нет ни одной сделки"
        return из_
    for подпись in list(reversed(ряды))[:max(1, int(читать_макс))]:
        о = читать(подпись)
        из_["прочитано"] += 1
        if not (о or {}).get("ok") or not (о or {}).get("result"):
            из_["осмотрено"].append({"подпись": подпись, "почему": "узел не отдал"})
            continue
        иксы = сделки_кривой(о["result"], модуль=BV)
        свои = [и for и in иксы if и["disc"] == ДИСК_ПОКУПКИ_27
                and и["n"] == СЧЕТОВ_ПОКУПКИ_27]
        из_["осмотрено"].append({"подпись": подпись,
                                 "диски": [и["disc"] for и in иксы],
                                 "счетов": [и["n"] for и in иксы]})
        if свои:
            из_.update(ok=True, подпись=подпись)
            return из_
    из_["why_not"] = (f"среди {из_['прочитано']} самых старых сделок счёта нет "
                      f"покупки {ДИСК_ПОКУПКИ_27} на {СЧЕТОВ_ПОКУПКИ_27} счетов")
    return из_


def дискриминатор_имени(имя: str) -> str:
    """Дискриминатор инструкции Anchor: первые 8 байт sha256("global:имя")."""
    import hashlib  # noqa: PLC0415

    return hashlib.sha256(f"global:{имя}".encode()).digest()[:8].hex()


def имена_мест_из_idl(idl: dict, диск: str) -> dict:
    """Имена счетов инструкции С ЭТИМ дискриминатором -- по IDL программы.

    ЗАЧЕМ ИМЕНА. Измерение по паре даёт МЕСТА, но не говорит, что это за счёт.
    Там, где место из покупки не выводится, решает именно имя: "накопитель
    объёма" выводится семенами, а "получатель сбора" выбирается программой, и
    тогда карты мест недостаточно по существу, а не по недостатку образцов.

    Инструкция ищется по дискриминатору, а не по имени: имя у разновидности
    может быть любым, а дискриминатор -- это то, что стоит в живых байтах.
    """
    из_: dict = {"ok": False, "why_not": None, "инструкция": None, "места": []}
    инструкции_ = (idl or {}).get("instructions") or []
    if not инструкции_:
        из_["why_not"] = "в IDL нет инструкций"
        return из_
    for и in инструкции_:
        имя = str(и.get("name") or "")
        if дискриминатор_имени(имя) != диск:
            continue
        из_["инструкция"] = имя
        for место, счёт in enumerate(и.get("accounts") or []):
            пда_ = счёт.get("pda") or {}
            из_["места"].append({"место": место, "имя": счёт.get("name"),
                                 "семена": пда_.get("seeds"),
                                 "программа_семян": пда_.get("program")})
        из_["ok"] = True
        return из_
    из_["why_not"] = f"инструкции с дискриминатором {диск} в IDL нет"
    return из_


def пара_по_подписям(подпись_покупки: str, подпись_продажи: str, *,
                     модуль=None, читатель=None, имена: bool = False) -> dict:
    """Пара одного пула с цепи: инструкция покупки и инструкция продажи."""
    BV = модуль if модуль is not None else _цепь()
    читать = читатель if читатель is not None else (
        lambda п: BV.зов("getTransaction",
                         [п, {"encoding": "jsonParsed", "commitment": "confirmed",
                              "maxSupportedTransactionVersion": 0}]))
    из_: dict = {"ok": False, "why_not": None, "покупка": None, "продажа": None,
                 "карта": None}
    for имя, подпись in (("покупка", подпись_покупки), ("продажа", подпись_продажи)):
        if not подпись:
            из_["why_not"] = f"подпись {имя} не названа"
            return из_
        о = читать(подпись)
        if not (о or {}).get("ok") or not (о or {}).get("result"):
            из_["why_not"] = (f"{имя} по подписи не прочитана: "
                              f"{(о or {}).get('why_not') or 'узел не отдал'}")
            return из_
        tx = о["result"]
        иксы = сделки_кривой(tx, модуль=BV)
        # КАНДИДАТЫ -- В ОТЧЁТ ВСЕГДА, даже когда отказываем. Иначе на отказ
        # "сделок кривой 2" приходится слать второй прогон только чтобы узнать,
        # ЧТО это за две, -- а это лишнее обращение к цепи за тем же самым.
        из_[f"{имя}_кандидаты"] = [{"disc": и["disc"], "счетов": и["n"]}
                                   for и in иксы]
        if not иксы:
            из_["why_not"] = f"в {имя} сделки программы кривой нет"
            return из_
        из_[имя] = {"подпись": подпись, "disc": иксы[0]["disc"],
                    "счетов": иксы[0]["n"], "accounts": иксы[0]["accounts"],
                    "слот": tx.get("slot"), "сделок": len(иксы),
                    "все": [и["accounts"] for и in иксы]}
        if имя == "покупка" and len(иксы) > 1:
            из_["why_not"] = (f"в покупке сделок кривой {len(иксы)} -- какая из "
                              "них наша, по одной транзакции не узнать")
            return из_
    пк = из_["покупка"]
    if пк["disc"] != ДИСК_ПОКУПКИ_27 or пк["счетов"] != СЧЕТОВ_ПОКУПКИ_27:
        из_["why_not"] = (f"покупка не та разновидность: дискриминатор {пк['disc']}, "
                          f"счетов {пк['счетов']}; ждали {ДИСК_ПОКУПКИ_27} и "
                          f"{СЧЕТОВ_ПОКУПКИ_27}")
        return из_
    # ПРОДАЖА, РАЗБИТАЯ НА НЕСКОЛЬКО СДЕЛОК, -- ЭТО НЕ ПОМЕХА, ЕСЛИ КАРТА У НИХ
    # ОДНА. Jupiter делит обмен на части, и каждая часть зовёт кривую своей
    # инструкцией. Карта мест -- это ПОРЯДОК счетов, а не их количество: если
    # все части дали ОДНУ И ТУ ЖЕ карту, она измерена, а не угадана. Разошлись
    # хоть в одном месте -- отказ, и обе карты в отчёте.
    карты = [места_продажи_из_пары(пк["accounts"], сч)
             for сч in (из_["продажа"]["все"] or [])]
    if имена:
        из_["имена"] = имена_мест_из_idl(
            (BV.idl_с_цепи() or {}).get("idl") or {}, из_["продажа"]["disc"])
        # ВЛАДЕЛЬЦЫ СПОРНЫХ СЧЕТОВ. IDL у кривой на цепи не выложен, имён
        # оттуда нет -- тогда единственное, что про спорное место говорит цепь
        # сама, это КАКАЯ ПРОГРАММА его держит и сколько в нём данных. Этого
        # мало для карты, но достаточно, чтобы не искать семена там, где счёт
        # вообще не PDA кривой.
        спорные = [з["ключ"] for к in карты for з in (к["не_выводятся"] or [])
                   if з.get("ключ")]
        лишние = [з["ключ"] for к in карты
                  for з in (к["покупка_не_использована"] or []) if з.get("ключ")]
        ключи_ = list(dict.fromkeys(спорные + лишние))
        из_["владельцы_спорных"] = BV.владельцы(ключи_) if ключи_ else {}
    из_["карты_частей"] = [{"ok": к["ok"], "карта": к["карта"],
                            "почему": к["почему"]} for к in карты]
    годные = [к for к in карты if к["ok"]]
    разные = {к["карта"] for к in годные}
    if годные and len(годные) == len(карты) and len(разные) == 1:
        из_["карта"] = годные[0]
        из_["ok"] = True
        из_["why_not"] = None
        из_["частей_продажи"] = len(карты)
        return из_
    из_["карта"] = карты[0] if карты else None
    из_["ok"] = False
    из_["why_not"] = (
        (f"части продажи дали разные карты ({len(разные)} разных) -- "
         "какая верна, по одной паре не узнать")
        if len(разные) > 1 else
        ((карты[0]["почему"] if карты else "сделок продажи нет")
         if len(карты) == 1 else
         (f"из {len(карты)} частей продажи карту дали {len(годные)}: "
          + "; ".join(str(к["почему"]) for к in карты if not к["ok"])[:400])))
    return из_


