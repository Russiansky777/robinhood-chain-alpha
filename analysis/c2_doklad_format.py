def свод(ряды, *, окно: str, итог_24h_sol=None, открытых=None,
          баланс_sol=None, поля=None, итог_подпись: str | None = None,
          зона_подпись: str | None = None, сейчас_метка: str | None = None,
          с_полуночи_sol=None, по_балансу_sol=None, ввод_sol=None,
          вывод_sol=None, рента_заперта_sol=None, рента_счетов=None,
          unsold=None, стопы=None, пропущено=None, тип_пула=None,
          группы_всегда=None, определения: bool = True) -> dict:
    """Числа окна из записей полосы. Считает ТОЛЬКО то, что есть в записях.

    24H, Open и BAL записями не считаются -- это состояние кошелька и цепи, и они
    приходят параметрами. Выдумывать их здесь значило бы печатать число, за
    которым ничего не стоит.

    `стопы` и `пропущено` приходят ГОТОВЫМИ (bloom_doklad.стопы_групп и
    bloom_doklad.пропущено_сигналов): суточный стоп группы считает гейт полосы, а
    отклонённые сигналы лежат в журнале решений -- в записях сделок нет ни того,
    ни другого, и посчитать их здесь было бы вторым написанием чужого счёта.
    Принимается И ОТВЕТ ЦЕЛИКОМ, и уже вынутые из него `группы`/`по_группам`:
    точка вызова передаёт то, что ей отдали, и помнить про лишний ключ ей негде.

    `поля` -- НЕОБЯЗАТЕЛЬНЫЙ переводчик записи в числа доклада
    (bloom_doklad.поля). С ним свод работает на ЖИВЫХ ПОЗИЦИЯХ службы, где итог,
    s_n и путь не лежат готовыми; без него -- на выгрузке сделок, где они уже
    посчитаны. Считать их вторым способом здесь нельзя: у полосы итог считается
    одной формулой, и второй счёт разошёлся бы с ней молча.
    """
    из_ = {"окно": окно, "сделок": 0, "объём_sol": 0.0, "итог_sol": 0.0,
            "итог_процент": None, "в_плюсе": 0, "s0": 0, "s1": 0, "s2plus": 0,
            "путь_медиана_мс": None, "Р_медиана_мс": None,
            "не_село": 0, "довозили": {}, "регионы": {},
            "итог_24h_sol": итог_24h_sol, "открытых": открытых,
            "баланс_sol": баланс_sol,
            # ПОДПИСЬ ЧИСЛА ХВОСТА. Служба отдаёт сюда суточный итог по цепи от
            # полуночи Мадрида, а хвост называл его «24H»: 30.09 в 22:02Z, через
            # две минуты после смены суток, строка печатала «24H (по цепи) 0.000»
            # при плюсе за день. Число честное, подпись врала -- значит подпись
            # приходит оттуда же, откуда число.
            "итог_подпись": итог_подпись,
            # ФОРМАТ 02.10: группы, сверка, S+0 по отправителям и регионам.
            # Числа ПРИХОДЯТ готовыми там, где их не из записей взять (баланс,
            # ввод/вывод, рента): выдумывать их здесь значило бы печатать число,
            # за которым ничего не стоит.
            "по_группам": {}, "довозили_s0": {}, "регионы_s0": {},
            "зона_подпись": зона_подпись, "сейчас_метка": сейчас_метка,
            "с_полуночи_sol": с_полуночи_sol, "по_балансу_sol": по_балансу_sol,
            "ввод_sol": ввод_sol, "вывод_sol": вывод_sol,
            "рента_заперта_sol": рента_заперта_sol,
            "рента_счетов": рента_счетов,
            "unsold": (list(unsold) if isinstance(unsold, (list, tuple)) else None),
            # СТОПЫ ГРУПП И ПРОПУЩЕННЫЕ СИГНАЛЫ -- КАК ПРИШЛИ. Своего счёта тут
            # нет: стоп считает гейт полосы, отказы лежат в журнале решений.
            # ОТВЕТ ЦЕЛИКОМ ТОЖЕ ГОДИТСЯ: ровно его и отдают стопы_групп и
            # пропущено_сигналов, и требовать от точки вызова помнить про
            # ["группы"]/["по_группам"] значило бы ждать тихой поломки.
            "стопы_групп": _по_группам_как_есть(стопы, "группы"),
            "пропущено_сигналов": _числа_по_группам(пропущено),
            # С (СБОРКА) ПО ТИПАМ ПУЛОВ -- считается ниже, из записей.
            "сборка_по_типам": {},
            "определения": bool(определения)}
    # ГРУППЫ БЕЗ СДЕЛОК ТОЖЕ ПЕЧАТАЮТСЯ, если их назвали: «leader 0 SOL» в
    # образце владельца. Без этого «группа не торговала» не отличить от «группы
    # нет в файле вовсе».
    for _г in (группы_всегда or []):
        из_["по_группам"].setdefault(str(_г), {"сделок": 0, "итог_sol": 0.0})
    пути = []
    # Р -- "решили": всё между приёмом сигнала и первым замеренным шагом сборки.
    # Берётся ТЕМ ЖЕ полем, что печатает BUY (путь_решили), а не считается здесь
    # заново: второй счёт одного числа расходится молча. Слово владельца 01.10:
    # Р выросло с 10-22 мс ночью до 144 мс к 15:21, и его надо видеть в 🧾.
    решили_мс = []
    сборка_по_типам: dict = {}
    for з in (ряды or []):
        if not isinstance(з, dict):
            continue
        з_ = з.get("zapis") if isinstance(з.get("zapis"), dict) else {}
        пф = {}
        if callable(поля):
            try:
                пф = поля(з) or {}
            except Exception:  # noqa: BLE001
                пф = {}
        из_["сделок"] += 1
        вошло = (_число(пф.get("вошло_sol")) if пф else None)
        if вошло is None:
            вошло = _число(з.get("sol_in")) or _число(з.get("size_sol")) or 0.0
        из_["объём_sol"] += вошло
        итог = _число(пф.get("итог_sol")) if пф else None
        if итог is None:
            итог = _число(з.get("итог_sol"))
        if итог is not None:
            из_["итог_sol"] += итог
            если_плюс = итог > 0
            из_["в_плюсе"] += 1 if если_плюс else 0
        # ПО ГРУППАМ -- В ТОМ ЖЕ ПРОХОДЕ, тем же итогом, что и общий: второй
        # счёт одного числа расходится молча.
        _гр = (пф.get("группа") if пф else None) or з.get("group") or з_.get("lane_group")
        if _гр:
            _зг = из_["по_группам"].setdefault(str(_гр),
                                                {"сделок": 0, "итог_sol": 0.0})
            _зг["сделок"] += 1
            if итог is not None:
                _зг["итог_sol"] = round(_зг["итог_sol"] + итог, 9)
        s = пф.get("s_n") if пф else None
        if s is None:
            s = з.get("s_plus")
        _в_s0 = False
        if isinstance(s, int):
            if s == 0:
                из_["s0"] += 1
                _в_s0 = True
            elif s == 1:
                из_["s1"] += 1
            else:
                из_["s2plus"] += 1
        # НЕ СЕЛО -- это НЕ «нет s_plus». Не села та покупка, у которой нет
        # подписи на цепи: посадка есть -- есть landed_sig.
        if not (з.get("landed_sig") or з_.get("lane_landed_signature")
                or з.get("lane_landed_signature")
                or (пф.get("подпись_покупки") if пф else None)):
            из_["не_село"] += 1
        р_ = _число(пф.get("путь_решили")) if пф else None
        if р_ is not None:
            решили_мс.append(р_)
        # КУСКИ СБОРКИ СКЛАДЫВАЮТСЯ ОДИН РАЗ НА ЗАПИСЬ. Их складывает и путь
        # (когда полей доклада нет), и разложение С по типам пулов; два места,
        # где эти четыре поля суммируются по-своему, однажды дадут разные «С».
        куски = [_число((з_ or з).get(к))
                 for к in ("lane_build_ms", "lane_variants_ms",
                            "lane_sign_ms", "lane_nonce_ms")]
        куски = [к for к in куски if к is not None]
        # С ПО ТИПУ ПУЛА. Число берётся ПОЛЕМ путь_собрали -- тем же, что печатает
        # BUY; своего счёта нет, иначе в докладе оказались бы два разных «С».
        собрали = _число(пф.get("путь_собрали")) if пф else None
        if собрали is None and куски:
            собрали = round(sum(куски), 3)
        if собрали is not None:
            _тип = тип_пула_записи(з, з_, имя_типа=тип_пула) or НЕТ_ТИПА
            сборка_по_типам.setdefault(_тип, []).append(собрали)
        п = _число(пф.get("путь_всего")) if пф else None
        if п is not None:
            пути.append(п)
        else:
            п = _число(з.get("путь_всего_мс")) or _число(з_.get("seen_lag_ms"))
            if п is not None:
                пути.append(п + (sum(куски) if куски else 0.0))
        довёз = (пф.get("довёз") if пф else None) or z_winner(з_, з)
        if довёз:
            из_["довозили"][str(довёз)] = из_["довозили"].get(str(довёз), 0) + 1
            # S+0 У ОТПРАВИТЕЛЯ -- ВТОРОЕ ЧИСЛО В ЕГО ПАРЕ (формат 02.10):
            # «сколько из них сели в S+0». Ключ ставится ВСЕГДА, даже нулём:
            # пропуск читался бы как «неизвестно», а это разные вещи.
            из_["довозили_s0"].setdefault(str(довёз), 0)
            if _в_s0:
                из_["довозили_s0"][str(довёз)] += 1
        # РЕГИОНЫ ЧАСА -- ЧЕРЕЗ регионы_записи, А НЕ ПОЛЕМ НАПРЯМУЮ. Поле
        # lane_region_point -- СЛОВАРЬ по отправителям ({отправитель: {host,
        # регион_точки}}), и прямое f"{точка}→{лидер}" печатало в часовую строку
        # весь словарь целиком (01.10, час 02:00-03:00). Тот же дефект уже был
        # починен в строке BUY -- и ровно той же функцией, которая умеет взять
        # регион точки ТОГО, КТО ДОВЁЗ. Второго написания этого правила быть не
        # должно: оно уже один раз разошлось.
        слито = dict(з)
        слито.update(з_ or {})
        р = регионы_записи(слито, довёз)
        точка, лидер = р.get("точка"), р.get("лидер")
        if точка and лидер:
            # ПАРА -- ЛИДЕР→ОТПРАВКА (подпись формата 02.10): слева регион
            # лидера слота, справа наша точка отправки.
            к = f"{лидер}→{точка}"
            из_["регионы"][к] = из_["регионы"].get(к, 0) + 1
            из_["регионы_s0"].setdefault(к, 0)
            if _в_s0:
                из_["регионы_s0"][к] += 1
        else:
            # НЕТ ДАННЫХ -- ЭТО ТОЖЕ ОТВЕТ (слово владельца 01.10: "нет данных
            # -- «—»"). Молчание тут читалось бы как "регионов не было".
            из_["регионы"][НЕТ] = из_["регионы"].get(НЕТ, 0) + 1
            # S+0 СЧИТАЕТСЯ И У «НЕТ РЕГИОНА»: в образце владельца эта строка
            # идёт с парой («нет региона 14 · 0»), а без ключа хвост пары
            # пропадал целиком -- и строка читалась как «S+0 не считали», хотя
            # считали и он ноль. Это разные вещи.
            из_["регионы_s0"].setdefault(НЕТ, 0)
            if _в_s0:
                из_["регионы_s0"][НЕТ] += 1
    if пути:
        из_["путь_медиана_мс"] = round(statistics.median(пути), 0)
    if решили_мс:
        из_["Р_медиана_мс"] = round(statistics.median(решили_мс), 0)
    из_["сборка_по_типам"] = {к: _медиана_p90(v)
                               for к, v in сборка_по_типам.items()}
    из_["объём_sol"] = round(из_["объём_sol"], 9)
    из_["итог_sol"] = round(из_["итог_sol"], 9)
    if из_["объём_sol"]:
        из_["итог_процент"] = из_["итог_sol"] / из_["объём_sol"] * 100.0
    if not из_["сделок"]:
        из_["итог_процент"] = None
    return из_


def подменить(вид: str, прежняя: str, п=None, *, поз=None) -> str:
    """ОДНА дверь для точек вызова: вид -> новая строка или прежняя.

    Сделано одной функцией нарочно: в чужом файле правка тогда -- одна строка на
    точку вызова, и снять её можно тоже одной строкой.
    """
    try:
        if вид == "buy":
            return строка_buy(п, прежняя, поз=поз)
        if вид == "sell":
            return строка_sell(п, прежняя, поз=поз)
        if вид == "час":
            return строка_часа(п, прежняя)
        if вид == "сутки":
            return строка_суток(п, прежняя)
        return прежняя
    except Exception:  # noqa: BLE001
        return прежняя


