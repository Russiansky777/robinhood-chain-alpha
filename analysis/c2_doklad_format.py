def _buy(п: dict, поз: dict | None) -> str:
    # НЕ СЛОВАРЬ -- ЭТО СЛОМАННЫЙ ВХОД, а не «пустая сделка». Собрать из него
    # строку значило бы напечатать в чат ряд прочерков вместо доклада; правильный
    # ответ -- прежняя строка, и обёртка её вернёт.
    if not isinstance(п, dict):
        raise TypeError("п не словарь")
    поз = поз if isinstance(поз, dict) else {}
    время = п.get("время")
    голова = f"🟢 {время} BUY" if время else "🟢 BUY"
    имя = (_экран(п.get("имя_токена")) if п.get("имя_токена")
           else (_экран(str(п.get("минт"))[:6]) if п.get("минт") else НЕТ))
    s = f"S+{int(п['s_n'])}" if п.get("s_n") is not None else "S+?"
    # ПУТЬ -- ТРЕМЯ БУКВАМИ, как в образце: У увидели, Р решили, С собрали.
    # Скобка печатается только целиком: половина кусков хуже, чем ни одного,
    # потому что сумма перестаёт сходиться с числом перед скобкой.
    куски = [п.get("путь_увидели"), п.get("путь_решили"), п.get("путь_собрали")]
    скобка = ""
    if all(isinstance(к, (int, float)) for к in куски):
        скобка = (f" (У{int(round(куски[0]))}·Р{int(round(куски[1]))}·"
                  f"С{int(round(куски[2]))})")
    путь = (f"{_цел(п.get('путь_всего'))} мс{скобка}"
            if п.get("путь_всего") is not None else f"{НЕТ} мс")
    # ОТПРАВИТЕЛЬ И РЕГИОНЫ. Регионы берутся из полей lane_region*: точка отправки
    # и регион лидера слота. Их пишет полоса (bloom_own_send), и в записи они
    # лежат рядом с позицией, а не внутри полей доклада -- поэтому смотрим и
    # туда, и туда.
    отпр = п.get("довёз") or поз.get("lane_pool_winner") or поз.get("lane_send_point")
    # РЕГИОНЫ -- ТОЛЬКО ЧЕРЕЗ регионы_записи. Прежний код брал поле региона точки
    # как есть, а там СЛОВАРЬ по отправителям -- и он печатался целиком.
    р = регионы_записи(поз, отпр)
    точка = _строка_или_нет(п.get("регион_точки")) or р["точка"]
    лидер = _строка_или_нет(п.get("регион_лидера")) or р["лидер"]
    хвост = (f"{_экран(отпр) if отпр else НЕТ} / "
             f"{_экран(точка) if точка else НЕТ}→{_экран(лидер) if лидер else НЕТ}")
    # ИСТОЧНИК КОРОТКИМ АДРЕСОМ -- СРАЗУ ЗА ИМЕНЕМ ТОКЕНА (слово владельца
    # 01.10, п.8). Имя источника остаётся на своём месте, когда оно есть; адрес
    # идёт всегда, потому что имя есть у единиц сделок из сотни.
    ист = короткий_адрес(п.get("источник"))
    части = [голова, п.get("группа") and _экран(п["группа"]),
             п.get("имя_источника") and _экран(п["имя_источника"]),
             _размер(п.get("вошло_sol")), имя, ист and f"ист {ист}",
             s, путь, хвост,
             ссылка(п.get("подпись_источника"))]
    # ПОСАДКА НЕ ПОДТВЕРЖДЕНА -- ПРИЧИНА, А НЕ ТРИ ПРОЧЕРКА (слово владельца
    # 01.10, п.4). За час 30.09 три строки из двенадцати ушли видом
    # "S+? · — мс · — / —→—": по ним нельзя отличить "покупка не села" от
    # "узел не отдал место в блоке", и владелец читал их как ошибку доклада.
    # Место в строке то же, текст -- причина словами.
    if п.get("посадка_почему"):
        части = [голова, п.get("группа") and _экран(п["группа"]),
                 п.get("имя_источника") and _экран(п["имя_источника"]),
                 _размер(п.get("вошло_sol")), имя, ист and f"ист {ист}",
                 f"посадка не подтверждена: {_экран(п['посадка_почему'])}",
                 ссылка(п.get("подпись_источника"))]
    return " · ".join([ч for ч in части if ч])


