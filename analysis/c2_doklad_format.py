def подменить(вид: str, прежняя: str, п=None, *, поз=None) -> str:
    """ОДНА дверь для точек вызова: вид -> новая строка или прежняя.

    Сделано одной функцией нарочно: в чужом файле правка тогда -- одна строка на
    точку вызова, и снять её можно тоже одной строкой.
    """
    try:
        if вид == "buy":
            return строка_buy(п, прежняя, поз=поз)
        if вид == "sell":
            return строка_sell(п, прежняя, поз=поз)
        if вид == "час":
            return строка_часа(п, прежняя)
        if вид == "сутки":
            return строка_суток(п, прежняя)
        return прежняя
    except Exception:  # noqa: BLE001
        return прежняя


