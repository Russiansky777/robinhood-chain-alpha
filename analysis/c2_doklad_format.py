def деньги_продажи(п: dict, поз: dict | None = None) -> dict:
    """ФАКТ ушло -> ФАКТ вернулось, и их разница ОБЯЗАНА быть итогом.

    ЧТО БЫЛО НЕ ТАК (живая запись 21:11:28Z). В строке стояло «0.100 -> 0.213»:
    слева ПЛАН билета (`sol_in` = 0.1), справа ВАЛОВЫЙ оборот закрытия
    (`возврат_sol` = 0.213063962). Читалось это как +113 %, а итог сделки был
    +0.006710482. Процент считался от плана и давал +6.7 % -- число, не связанное
    ни с одной из двух цифр рядом.

    ЧТО СЧИТАЕТСЯ ТЕПЕРЬ, И ПОЧЕМУ ИМЕННО ТАК:
        ушло      = вошло + расход - завёрнутое - рента
        вернулось = вышло          - завёрнутое - рента
        процент   = итог / ушло
    `расход` и `итог` берутся у полосы (bloom_doklad.итог_и_расход ->
    bloom_exec_state.итог_позиции) -- ОДНА формула на репозиторий, своей тут нет.
    Завёрнутый SOL и рента созданных счетов вычитаются ИЗ ОБЕИХ сторон: они
    проходят сквозь сделку и в риск не входят, а оставленные внутри раздувают оба
    числа (на 21:11Z завёрнутое было 0.1 -- ровно тот второй «билет», из-за
    которого валовая цифра выглядела вдвое больше).

    ВЫЧИТАНИЕ ОДНОГО И ТОГО ЖЕ ИЗ ОБЕИХ СТОРОН НЕ МЕНЯЕТ РАЗНИЦУ, и это главное:
    (вышло - з - р) - (вошло + расход - з - р) = вышло - вошло - расход = итог.
    Поэтому строка не может разойтись с итогом -- а если разойдётся (значит поля
    записи не сходятся), функция отказывает, и доклад печатает ПРЕЖНЮЮ строку.

    Сверено на живой записи 21:11:28Z: 0.103351 -> 0.110062, итог +0.006710482,
    +6.5 % -- «ушло» и процент совпали с чтением владельца до знака.
    """
    из_ = {"ok": False, "why_not": None, "ушло": None, "вернулось": None,
            "итог": None, "процент": None}
    if not isinstance(п, dict):
        из_["why_not"] = "полей доклада нет"
        return из_
    поз = поз if isinstance(поз, dict) else {}
    # ПРАВИЛО 13 (слово владельца 01.10, п.6): если итог посчитан ПО ЦЕПИ, то и
    # «ушло → вернулось» берутся ОТТУДА ЖЕ, симметрично с двух сторон: ушло --
    # сколько наших счетов убыло на покупке, вернулось -- сколько прибыло на
    # продаже. Тогда «вернулось − ушло = итог» выполняется ПО ПОСТРОЕНИЮ, а не
    # по совпадению полей, и строка не может разойтись с каноническим числом.
    части = п.get("цепь_части") if isinstance(п.get("цепь_части"), dict) else None
    if части and isinstance(части.get("покупка"), dict) \
            and isinstance(части.get("продажа"), dict):
        ушло_ц = _число((части["покупка"] or {}).get("все_sol"))
        верн_ц = _число((части["продажа"] or {}).get("все_sol"))
        if ушло_ц is not None and верн_ц is not None and ушло_ц < 0:
            ушло_ц = round(-ушло_ц, 9)
            верн_ц = round(верн_ц, 9)
            итог_ц = round(верн_ц - ушло_ц, 9)
            из_.update(ok=True, ушло=ушло_ц, вернулось=верн_ц, итог=итог_ц,
                        процент=(итог_ц / ушло_ц * 100.0 if ушло_ц else None),
                        сквозь=0.0, откуда="цепь")
            return из_
    вошло = _число(п.get("вошло_sol"))
    вышло = _число(п.get("вышло_sol"))
    расход = _число(п.get("расход_sol"))
    итог = _число(п.get("итог_sol"))
    if None in (вошло, вышло, расход, итог):
        из_["why_not"] = "в полях нет входа, возврата, расхода или итога"
        return из_
    # ИМЕНА ПОЛЕЙ -- И ВЫГРУЗКИ, И ЗАПИСИ ПОЗИЦИИ. В бою докладчик получает
    # ЗАПИСЬ ПОЗИЦИИ, где эти суммы зовутся lane_buy_wrapped_sol и
    # lane_buy_rent_sol; «завёрнутое_sol» и «рента_sol» -- имена выгрузки Code-1.
    # Смотреть только на одну пару значило бы считать по-разному в бою и в
    # проверке, а это ровно тот случай, когда расхождение не видно.
    сквозь = 0.0
    for имена in (("завёрнутое_sol", "lane_buy_wrapped_sol"),
                   ("рента_sol", "lane_buy_rent_sol")):
        зн = None
        for имя in имена:
            зн = _число(поз.get(имя))
            if зн is None:
                зн = _число(п.get(имя))
            if зн is not None:
                break
        сквозь += (зн or 0.0)
    ушло = round(вошло + расход - сквозь, 9)
    вернулось = round(вышло - сквозь, 9)
    if ушло <= 0:
        из_["why_not"] = f"фактически ушедшее не положительно: {ушло}"
        return из_
    # СТРОКА НЕ ИМЕЕТ ПРАВА РАСХОДИТЬСЯ С ИТОГОМ. Полампорта допуска -- это
    # округление девятого знака, а не расхождение счёта.
    if abs(round(вернулось - ушло, 9) - итог) > 1e-9:
        из_["why_not"] = (f"разница {round(вернулось - ушло, 9)} не равна итогу "
                           f"{итог} -- поля записи не сходятся")
        return из_
    из_.update(ok=True, ушло=ушло, вернулось=вернулось, итог=итог,
                процент=итог / ушло * 100.0, сквозь=round(сквозь, 9))
    return из_


def кружок(итог) -> str:
    """ОДИН кружок по знаку итога (слово владельца 30.09 вечером).

    Было «🔴🟢» на продаже 21:14:03Z: прежний маркер печатал 🔴 как признак
    продажи и добавлял 🟢 за каждый икс прибыли. Два кружка рядом читались как
    два события; знак итога -- одно, и кружок теперь один.
    """
    з = _число(итог)
    return "🟢" if (з is not None and з > 0) else "🔴"


def _sell(п: dict, поз: dict | None) -> str:
    if not isinstance(п, dict):
        raise TypeError("п не словарь")
    д = деньги_продажи(п, поз)
    if not д["ok"]:
        raise ValueError(д["why_not"])
    имя = (_экран(п.get("имя_токена")) if п.get("имя_токена")
           else (_экран(str(п.get("минт"))[:6]) if п.get("минт") else НЕТ))
    время = п.get("время_продажи")
    голова = f"{кружок(д['итог'])} {время} SELL" if время else f"{кружок(д['итог'])} SELL"
    держали = ""
    try:
        import bloom_doklad as DK  # noqa: PLC0415

        держали = DK.удержание_словами(п) or ""
    except Exception:  # noqa: BLE001
        держали = (f"{float(п['удержание_с']):.1f} с"
                   if _число(п.get("удержание_с")) is not None else "")
    части = [голова, имя, держали,
             f"{д['ушло']:.6f} → {д['вернулось']:.6f} SOL",
             # БЕЗ СЛОВА "ИТОГ" (слово владельца 01.10, п.5): число и процент
             # стоят сразу за "ушло → вернулось", и слово там ничего не добавляло.
             f"{_знак(д['итог'], 6, плюс=True)} "
             f"({_проц(д['процент'], плюс=True)})",
             ссылка(п.get("подпись_продажи"))]
    строки = [" · ".join([ч for ч in части if ч])]
    if п.get("попыток_продажи"):
        хвост = (f" · причина: {_экран(п['причина_продажи'])}"
                 if п.get("причина_продажи") else "")
        строки.append(f"попыток {int(п['попыток_продажи'])}{хвост}")
    return "\n".join(строки)


def строка_sell(п: dict, прежняя: str, *, поз: dict | None = None) -> str:
    """SELL с ФАКТАМИ и одним кружком. Любая ошибка -- прежняя строка."""
    try:
        т = _sell(п, поз)
        return т if isinstance(т, str) and т.strip() else прежняя
    except Exception:  # noqa: BLE001
        return прежняя


