# ЧТО ЗА «С». Это третий кусок пути из строки BUY (У·Р·С): сборка покупки --
# сборка плюс варианты плюс подпись плюс nonce, всё по часам полосы. В сводке он
# стоял одной медианой на все сделки, а сборка у типов пулов РАЗНАЯ: у DLMM
# поколения 2 она идёт 39-56 мс против 0.7 мс у прежнего пути (замер в ночь
# 29->30.09), и общая медиана прятала это в себе. Разложение по типам показывает,
# на каком типе мы теряем миллисекунды.
НЕТ_ТИПА = "тип не записан"


def тип_пула_записи(з: dict, з_: dict | None = None, *, имя_типа=None):
    """Тип пула сделки СЛОВОМ по программе пула из записи. Нет программы -- None.

    ПОЧЕМУ ИМЯ, А НЕ АДРЕС ПРОГРАММЫ. «pAMMBay6…» в сводке читается только по
    памяти, а имя типа («Pump AMM», «кривая pump.fun») -- сразу. Имена берутся у
    vtoroe_mnenie_reestr.имя_типа -- там они уже есть и там же их правят; своей
    таблицы адресов здесь нет намеренно, две копии такого списка разойдутся на
    первом же новом строителе.

    Реестра на хосте нет -- имя собирается из начала адреса и ЭТО ВИДНО по виду
    («пул pAMMBay6»), а не выглядит как настоящее имя типа.
    """
    з = з if isinstance(з, dict) else {}
    з_ = з_ if isinstance(з_, dict) else {}
    адрес = None
    for откуда, поле in ((з_, "program"), (з, "program"), (з, "pool_program"),
                          (з_, "pool_program"), (з, "stroitel")):
        зн = _строка_или_нет(откуда.get(поле))
        if зн:
            адрес = зн
            break
    if not адрес:
        return None
    if callable(имя_типа):
        try:
            имя = имя_типа(адрес)
        except Exception:  # noqa: BLE001
            имя = None
        if _строка_или_нет(имя):
            return имя
    try:
        import vtoroe_mnenie_reestr as VR  # noqa: PLC0415

        имя = VR.имя_типа(адрес)
        if _строка_или_нет(имя):
            return имя
    except Exception:  # noqa: BLE001
        pass
    return f"пул {адрес[:8]}"


def _медиана_p90(значения: list) -> dict:
    """n, медиана и p90 по списку миллисекунд. Пустой список -- None, не ноль.

    P90 СЧИТАЕТСЯ БЛИЖАЙШИМ РАНГОМ, БЕЗ ИНТЕРПОЛЯЦИИ: на четырёх сделках
    интерполяция выдаёт число, которого ни одна сборка не показывала, а здесь
    нужен ИЗМЕРЕННЫЙ хвост. При n=1 p90 равен единственному замеру -- и это
    честно: другого хвоста у одной сделки нет.
    """
    зн = sorted(float(x) for x in (значения or [])
                if isinstance(x, (int, float)) and not isinstance(x, bool))
    if not зн:
        return {"n": 0, "медиана": None, "p90": None}
    место = max(1, int(math.ceil(0.9 * len(зн))))
    return {"n": len(зн), "медиана": round(statistics.median(зн), 1),
            "p90": round(зн[место - 1], 1)}


def _строки_сборки(по_типам: dict) -> list:
    """Типы столбиком, пары выровнены: «Pump AMM 37 · 7.0 · 12.3»."""
    пары = [(к, v) for к, v in (по_типам or {}).items()
            if int((v or {}).get("n") or 0)]
    if not пары:
        return []
    # «ТИП НЕ ЗАПИСАН» -- ВСЕГДА ПОСЛЕДНИМ, остальные по числу сделок вниз: иначе
    # строка про непрочитанное всплывала бы в середину и читалась как тип пула.
    пары.sort(key=lambda кв: (кв[0] == НЕТ_ТИПА, -int((кв[1] or {}).get("n") or 0)))
    ширина = max(len(к) for к, _ in пары)
    строки = []
    for к, v in пары:
        строки.append(f"  {_экран(к.ljust(ширина))} {int(v['n'])} · "
                       f"{_цел_дробь(v.get('медиана'))} · {_цел_дробь(v.get('p90'))}")
    return строки


def _цел_дробь(x) -> str:
    """Миллисекунды одним знаком после запятой: 7.0, а не 7 и не 7.004.

    Один знак нарочно: сборка измеряется десятыми миллисекунды (lane_build_ms
    1.753), и округление до целого превратило бы 0.7 мс прежнего пути в «1».
    """
    з = _число(x)
    return НЕТ if з is None else f"{з:.1f}"


def _сводка(св: dict, значок: str) -> str:
    if not isinstance(св, dict):
        raise TypeError("свод не словарь")
    окно = св.get("окно") or "?"
    сделок = int(св.get("сделок") or 0)
    голова = f"{значок} {окно}"
    зона = св.get("зона_подпись")
    if зона:
        голова += f" ({_экран(зона)})"
    # ХВОСТ «СЕЙЧАС» СЧИТАЕТСЯ ДО РАЗВИЛКИ: он одинаков и для периода со
    # сделками, и для тихого периода. Собирать его дважды значило бы завести два
    # места, где он может разойтись.
    хвост = []
    if св.get("открытых") is not None:
        хвост.append(f"Open {int(св['открытых'])}")
    if св.get("баланс_sol") is not None:
        хвост.append(f"BAL {float(св['баланс_sol']):.2f}")
    if св.get("с_полуночи_sol") is not None:
        хвост.append(f"с полуночи {_знак(св['с_полуночи_sol'], 2, плюс=True)}")
    хвост_строка = None
    if хвост:
        метка = св.get("сейчас_метка")
        хвост_строка = ("Сейчас" + (f" ({_экран(метка)})" if метка else "")
                         + ": " + " · ".join(хвост))
    # ПЕРИОД БЕЗ СДЕЛОК -- ОДНА СТРОКА, НО С ПОЛЯМИ СОСТОЯНИЯ. Долей и медиан
    # тут нет: делить не на что, а нули говорили бы о том, чего не было.
    if not сделок:
        строки = [голова + " · сделок 0"]
        # СТОЯЩИЙ СТОП ПЕЧАТАЕТСЯ И В ТИХОМ ОКНЕ. Развилка «сделок 0» уходила
        # отсюда ДО блока групп, и остановленная группа в таком окне исчезала
        # целиком -- а именно так окно после 05:39 02.10 и выглядело: сделок у
        # cand1 больше нет, и «сделок 0» не отличить от «сигналов не было». Это
        # ровно та тишина, против которой весь раздел и написан.
        #
        # БЛОК ПОЯВЛЯЕТСЯ ТОЛЬКО КОГДА СТОП ЕСТЬ: тихий час без стопов остаётся
        # двумя строками, как в образце владельца.
        стопы_тихо = _строки_групп({}, св.get("стопы_групп") or {},
                                    св.get("пропущено_сигналов") or {})
        if стопы_тихо:
            строки += [ПОДПИСЬ_ГРУПП] + стопы_тихо
        if хвост_строка:
            строки.append(хвост_строка)
        return "\n".join(строки)
    первая = (f"Сделки {сделок} · оборот {float(св.get('объём_sol') or 0):.2f}"
              f" · итог {_знак(св.get('итог_sol'), 3, плюс=True)}")
    if св.get("итог_процент") is not None:
        первая += f" ({_проц(св.get('итог_процент'), 1, плюс=True)} от оборота)"
    в_плюсе = св.get("в_плюсе")
    if в_плюсе is not None:
        первая += (f" · в плюс {int(в_плюсе)}/{сделок} "
                    f"({_доля(в_плюсе, сделок)})")
    блоки = [голова, "", первая]
    группы = _строки_групп(св.get("по_группам") or {},
                            св.get("стопы_групп") or {},
                            св.get("пропущено_сигналов") or {})
    if группы:
        блоки += ["", ПОДПИСЬ_ГРУПП] + группы
    сверка = _строка_сверки(св)
    if сверка:
        блоки += ["", сверка]
    посадка = [ПОДПИСЬ_ПОСАДКИ]
    for подпись, ключ in (("S+0", "s0"), ("S+1", "s1"), ("S+2+", "s2plus")):
        n = int(св.get(ключ) or 0)
        посадка.append(f"• {подпись} {n} ({_доля(n, сделок)})")
    путь = []
    if св.get("путь_медиана_мс") is not None:
        путь.append(f"путь {_цел(св['путь_медиана_мс'])} мс")
    if св.get("Р_медиана_мс") is not None:
        путь.append(f"Р {_цел(св['Р_медиана_мс'])} мс")
    if св.get("не_село") is not None:
        путь.append(f"не село {int(св['не_село'])}")
    if путь:
        посадка.append(" · ".join(путь))
    блоки += [""] + посадка
    # С (СБОРКА) ПО ТИПАМ ПУЛОВ -- сразу за посадкой, где стоят остальные
    # миллисекунды пути: общая медиана С и её разложение читаются вместе.
    сборка = _строки_сборки(св.get("сборка_по_типам") or {})
    if сборка:
        блоки += ["", "Сборка С (тип пула · сделок · медиана · p90, мс):"] + сборка
    довозили = св.get("довозили") or {}
    if довозили:
        s0 = св.get("довозили_s0") or {}
        части = []
        for к, v in sorted(довозили.items(), key=lambda кв: -int(кв[1])):
            if not v:
                continue
            ч = f"{_экран(к)} {int(v)}"
            ч += f"/{int(s0[к])}" if isinstance(s0.get(к), int) else f"/{НЕТ}"
            части.append(ч)
        if части:
            блоки += ["", "Отправители (сделок / S+0): " + " · ".join(части)]
    рег = _строки_регионов(св.get("регионы") or {}, св.get("регионы_s0") or {})
    if рег:
        блоки += ["", "Регионы (лидер→отправка · сделок · S+0):"] + рег
    if хвост_строка:
        блоки += ["", хвост_строка]
    if св.get("определения") is not False:
        блоки += ["", ОПРЕДЕЛЕНИЯ]
    return "\n".join(блоки)


