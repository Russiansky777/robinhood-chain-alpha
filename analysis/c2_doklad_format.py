# Минус -- U+2212, как в образце владельца, а не дефис: в чате они выглядят
# по-разному, и образец написан именно этим знаком.
МИНУС = "−"
# Тире окна часа -- U+2013 (12:00–13:00Z), тоже из образца.
ТИРЕ = "–"
НЕТ = "—"          # длинное тире для неизвестного
SOLSCAN = "https://solscan.io/tx/"

# ВРЕМЯ В СТРОКАХ ДОКЛАДА -- ПО МАДРИДУ, БЕЗ СУФФИКСА (слово владельца 01.10
# ночью, п.1). Записи, выгрузки и журналы остаются в Z: там время читает не
# человек, а сверка, и сдвиг зоны сломал бы сшивку по времени. Переход зимнего
# времени 25.10 берётся из базы зон, а не из смещения +02:00.
ЗОНА_ДОКЛАДА = "Europe/Madrid"


def _зона():
    """Зона Мадрида или None, если базы зон на хосте нет."""
    try:
        from zoneinfo import ZoneInfo  # noqa: PLC0415

        return ZoneInfo(ЗОНА_ДОКЛАДА)
    except Exception:  # noqa: BLE001
        return None


def чч_мм_сс(ts) -> str:
    """'01:07:06' по Мадриду. Базы зон нет -- время UTC и суффикс Z.

    ПОЧЕМУ ИМЕННО ТАК ПРИ ОТСУТСТВИИ ЗОНЫ. Молча напечатать UTC под видом
    Мадрида -- это тихое искажение: строка выглядит правильной и врёт на час или
    два. Суффикс Z говорит, что перед владельцем UTC, и это видно с первого
    взгляда.
    """
    if not isinstance(ts, (int, float)) or ts <= 0:
        return ""
    з = _зона()
    if з is None:
        import time as _t  # noqa: PLC0415

        return _t.strftime("%H:%M:%SZ", _t.gmtime(float(ts)))
    import datetime as _d  # noqa: PLC0415

    return _d.datetime.fromtimestamp(float(ts), з).strftime("%H:%M:%S")



# ----------------------------------------------------------------- мелочи

def _экран(т) -> str:
    return (str(т if т is not None else "")
            .replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;"))


def ссылка(подпись, ярлык: str = "tx") -> str:
    """Ссылка на Solscan. Нет подписи -- ярлык без ссылки и без хеша."""
    if not подпись:
        return ярлык
    return f'<a href="{SOLSCAN}{подпись}">{ярлык}</a>'


def _число(x):
    """Число или None. Строка "0.1" числом НЕ считается: в деньгах подмена типа
    молча даёт другой ответ, а не ошибку."""
    return float(x) if isinstance(x, (int, float)) and not isinstance(x, bool) else None


def _строка_или_нет(зн):
    """Значение годится в строку ТОЛЬКО если это строка.

    ПОЧЕМУ ЭТО ОТДЕЛЬНАЯ ФУНКЦИЯ, А НЕ str(). Дефект 30.09 на живых записях:
    в поле региона точки лежит СЛОВАРЬ
    {'astralane': {'host': 'fr.gateway.astralane.io', 'регион_точки': 'EU'}, ...},
    и str() честно напечатал его целиком в строку BUY. Ошибка не в том поле, а в
    подходе: в текст доклада попадает только то, что УЖЕ текст, всё прочее --
    «неизвестно». Тогда следующее такое поле даст прочерк, а не простыню.
    """
    return зн if isinstance(зн, str) and зн.strip() else None


def регионы_записи(поз: dict, довёз=None) -> dict:
    """Регион ТОЧКИ ОТПРАВКИ и регион ЛИДЕРА из записи позиции.

    ОТКУДА ЧТО. Регион лидера -- строка (`region_lidera` / `lane_region_leader`).
    Регион точки живёт в записи ДВУМЯ видами, и это корень дефекта:
      * строкой -- `lane_region` / `region_otpravki` ("EU"): это выбранный регион
        отправки;
      * СЛОВАРЁМ по отправителям -- `lane_region_point` / `region_point`:
        {отправитель: {host, регион_точки}}.
    Нам нужен регион точки ТОГО, КТО ДОВЁЗ (lane_pool_winner): у разных
    отправителей точки в разных регионах, и брать «первую попавшуюся» значило бы
    печатать чужой регион. Нет записи о довёзшем -- падаем на строковое поле, а
    не на случайный элемент словаря.
    """
    поз = поз if isinstance(поз, dict) else {}
    лидер = (_строка_или_нет(поз.get("region_lidera"))
             or _строка_или_нет(поз.get("lane_region_leader")))
    словарь = None
    for имя in ("lane_region_point", "region_point"):
        зн = поз.get(имя)
        if isinstance(зн, dict) and зн:
            словарь = зн
            break
        точка_строкой = _строка_или_нет(зн)
        if точка_строкой:
            return {"точка": точка_строкой, "лидер": лидер, "откуда": имя}
    if словарь and довёз:
        свой = словарь.get(str(довёз))
        если_строка = (_строка_или_нет((свой or {}).get("регион_точки"))
                       if isinstance(свой, dict) else _строка_или_нет(свой))
        if если_строка:
            return {"точка": если_строка, "лидер": лидер,
                    "откуда": f"регион точки отправителя {довёз}"}
    for имя in ("lane_region", "region_otpravki"):
        точка = _строка_или_нет(поз.get(имя))
        if точка:
            return {"точка": точка, "лидер": лидер, "откуда": имя}
    return {"точка": None, "лидер": лидер, "откуда": None}


def _знак(x, знаков: int, *, плюс: bool = False) -> str:
    """Число со знаком владельца: минус U+2212. Плюс -- только где он нужен.

    ПЛЮС НЕ ВСЮДУ НАРОЧНО. В часовой сводке образец владельца -- «итог −0.1006»,
    без плюса на положительных; в строке продажи он написал «итог +0.006710».
    Поэтому плюс -- параметр, а не общее правило: иначе принятая байт в байт
    часовая перестала бы совпадать.
    """
    if x is None:
        return НЕТ
    з = float(x)
    if з < 0:
        return f"{МИНУС}{abs(з):.{знаков}f}"
    return f"{'+' if плюс else ''}{з:.{знаков}f}"


def _проц(x, знаков: int = 1, *, плюс: bool = False) -> str:
    if x is None:
        return НЕТ
    з = float(x)
    знак = МИНУС if з < 0 else ("+" if плюс else "")
    return f"{знак}{abs(з):.{знаков}f} %"


def _цел(x) -> str:
    return НЕТ if x is None else f"{int(round(float(x)))}"


def _размер(x) -> str:
    """Размер входа как в образце: 0.3, а не 0.3000 и не 0.30."""
    return НЕТ if x is None else f"{float(x):g}"


# ------------------------------------------- тень нуля чтений DLMM (01.10, п.1)

ПОРОГ_ТЕНИ_НУЛЯ_PCT = 1.0


def расхождение_минимума_pct(наш, источника, *,
                              имя_нашего: str = "наш минимум",
                              имя_источника: str = "минимум источника") -> dict:
    """РАСХОЖДЕНИЕ МИНИМУМОВ: (минимум источника − наш) / наш · 100.

    ЗАЧЕМ ОТДЕЛЬНОЕ ЧИСЛО, КОГДА РЯДОМ УЖЕ СТОИТ РАСХОЖДЕНИЕ ЦЕН. Цена -- это
    что пул отдаст, а min_out -- что мы согласились принять, и откатывает сделку
    ИМЕННО min_out. Два источника могут разойтись в цене на процент и при этом
    дать одинаковый минимум (проскальзывание его съедает) -- или наоборот. В
    докладе это поле было пустым: минимумы печатались оба, а их расхождение не
    считалось ВОВСЕ, и назвать разницу было нечем.

    ЗНАК СМЫСЛОВОЙ, как у расхождения цен: ПЛЮС -- минимум источника ВЫШЕ нашего,
    то есть по его минимуму сделка откатилась бы там, где наша прошла.

    НЕТ ОДНОГО ИЗ ДВУХ -- ОТКАЗ С ИМЕНЕМ ПОЛЯ, а не прочерк и не ноль: по
    прочерку "минимумы совпали" не отличить от "минимум не записан", а стоят эти
    два ответа разного.
    """
    из_ = {"ok": False, "pct": None, "почему_нет": None}
    н = _число(наш)
    и_ = _число(источника)
    если_нет = [имя for имя, зн in ((имя_нашего, н), (имя_источника, и_))
                if зн is None]
    if если_нет:
        из_["почему_нет"] = "в записи нет " + " и ".join(если_нет)
        return из_
    if н <= 0:
        из_["почему_нет"] = f"{имя_нашего} не положителен ({н}) -- делить не на что"
        return из_
    из_.update(ok=True, pct=(и_ - н) / н * 100.0)
    return из_


def строка_тени_нуля(поз: dict, *, порог_pct: float = ПОРОГ_ТЕНИ_НУЛЯ_PCT):
    """Строка ТОЛЬКО когда тень нуля чтений разошлась с боевой ценой больше порога.

    Слово владельца (утренний пакет 01.10, п.1): "писать обе цены и оба min_out,
    расхождение больше 1 % -- строкой". Строка идёт ОТДЕЛЬНО от BUY и только по
    делу: на совпадениях чат заливало бы, а числа и так лежат в записи и в
    выгрузке.

    Знак отклонения -- смысловой, а не косметический: ПЛЮС значит, что нуль
    чтений обещает БОЛЬШЕ, чем пул отдаёт по боевой цене, то есть его min_out
    был бы завышен и сделка откатилась бы. Так и написано словами.
    """
    если_нет = {"ok": False, "почему_нет": None, "текст": None, "отклонение": None,
                 "расхождение_минимума_pct": None, "минимум_почему_нет": None}
    п = поз if isinstance(поз, dict) else {}
    откл = _число(п.get("lane_dlmm_nol_otklonenie_pct"))
    if откл is None:
        если_нет["почему_нет"] = "отклонения тени в записи нет"
        return если_нет
    если_нет["отклонение"] = откл
    if abs(откл) <= float(порог_pct):
        если_нет["почему_нет"] = (f"расхождение {_проц(откл, 4, плюс=True)} "
                                   f"в пределах порога {порог_pct:g} %")
        return если_нет
    имя = _строка_или_нет(п.get("token_name")) or (str(п.get("mint") or "")[:8] or НЕТ)
    цена_п = п.get("lane_dlmm_nol_cena_polosy")
    цена_т = п.get("lane_dlmm_nol_cena_teni")
    мо_п = п.get("lane_dlmm_nol_min_out_polosy")
    мо_т = п.get("lane_dlmm_nol_min_out_teni")
    чем = ("тень ВЫШЕ боевой -- её min_out завысил бы и сделка откатилась бы"
            if откл > 0 else "тень НИЖЕ боевой -- отправка прошла бы с запасом")
    # РАСХОЖДЕНИЕ МИНИМУМОВ -- ЧИСЛОМ, А НЕ ПУСТЫМ МЕСТОМ (слово владельца 02.10).
    # Оба минимума в записи уже лежали, а их разница не считалась вовсе: строка
    # печатала два числа и молчала о том, расходятся они или нет. Нет одного из
    # полей -- на его месте стоит ИМЯ недостающего поля, а не прочерк.
    мин = расхождение_минимума_pct(
        мо_п, мо_т, имя_нашего="lane_dlmm_nol_min_out_polosy",
        имя_источника="lane_dlmm_nol_min_out_teni")
    про_мин = (f"расхождение минимума {_проц(мин['pct'], 4, плюс=True)}"
                if мин["ok"] else
                f"расхождение минимума не посчитано: {мин['почему_нет']}")
    # «РАСХОЖДЕНИЕ ЦЕНЫ», А НЕ ПРОСТО «РАСХОЖДЕНИЕ»: рядом теперь стоит второе
    # расхождение, и одно слово на два числа читалось бы как одно число.
    текст = (f"🔬 нуль чтений · {имя} · цена полосы {_цел(цена_п)} / тень "
              f"{_цел(цена_т)} · min_out {_цел(мо_п)} / {_цел(мо_т)} · "
              f"{про_мин} · расхождение цены {_проц(откл, 4, плюс=True)} при пороге "
              f"{порог_pct:g} % · {чем}")
    return {"ok": True, "почему_нет": None, "текст": текст, "отклонение": откл,
             "расхождение_минимума_pct": мин["pct"],
             "минимум_почему_нет": мин["почему_нет"]}


# --------------------------------------------- короткий адрес (01.10, п.8)
# ОДНО НАПИСАНИЕ НА ВСЕ СТРОКИ. Сокращать адрес в каждой строке по-своему значит
# однажды напечатать два разных сокращения одного кошелька и получить вопрос
# "это один источник или два".
ГОЛОВА_АДРЕСА = 4
ХВОСТ_АДРЕСА = 4


def короткий_адрес(адрес, *, голова: int = ГОЛОВА_АДРЕСА,
                    хвост: int = ХВОСТ_АДРЕСА) -> str | None:
    """«6qud…KMhy» из адреса. Не строка или слишком короткий -- None, не обрезок.

    None здесь означает "печатать нечего", и строка просто не получит этой части.
    Вернуть обрезок было бы хуже: по половине адреса источник не узнать, а
    выглядело бы это как настоящее сокращение.
    """
    а = адрес if isinstance(адрес, str) else None
    а = (а or "").strip()
    if not а:
        return None
    if len(а) <= голова + хвост + 1:
        return _экран(а)
    return _экран(f"{а[:голова]}…{а[-хвост:]}")


