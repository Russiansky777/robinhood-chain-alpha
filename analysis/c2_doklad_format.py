def _доля(часть, всего) -> str:
    """«(44 %)» -- доля в процентах целым числом. Делить не на что -- прочерк."""
    в = _число(всего)
    ч = _число(часть)
    if в is None or ч is None or в <= 0:
        return НЕТ
    return f"{round(100.0 * ч / в):.0f} %"


def _по_группам_как_есть(x, внутри: str) -> dict:
    """Карта {группа: запись} из того, что дали: и готовой карты, и ВСЕГО ответа.

    ЗАЧЕМ РАСПАКОВКА. bloom_doklad.стопы_групп отдаёт ответ целиком
    ({ok, почему_нет, сутки, группы, стоят}), а печатать надо его `группы`;
    пропущено_сигналов -- так же, с `по_группам` внутри. Передать ответ целиком
    -- первое, что сделает точка вызова, и до этой распаковки сводка на таком
    ответе ПАДАЛА: по ключу «ok» лежит True, а у True нет .get. Падала она ровно
    тогда, когда стоп ПРОЧИТАН (ok=True), то есть в том единственном случае, для
    которого весь раздел и написан.

    ЧУЖИЕ ЗНАЧЕНИЯ ВЫБРАСЫВАЮТСЯ ЗДЕСЬ, А НЕ У ПЕЧАТИ: запись группы -- словарь,
    и «мусор» на её месте должен стоить строки в сводке, а не всего доклада.
    """
    if not isinstance(x, dict):
        return {}
    # ОТВЕТ УЗНАЁТСЯ ПО «ok», А НЕ ПО ОДНОМУ ВНУТРЕННЕМУ КЛЮЧУ: иначе группа,
    # названную словом «группы», распаковали бы как ответ и потеряли.
    if "ok" in x and isinstance(x.get(внутри), dict):
        x = x[внутри]
    return {к: v for к, v in x.items() if isinstance(v, dict)}


def _числа_по_группам(x) -> dict:
    """{группа: число} из готовой карты или из всего ответа пропущено_сигналов."""
    if not isinstance(x, dict):
        return {}
    if "ok" in x and isinstance(x.get("по_группам"), dict):
        x = x["по_группам"]
    return dict(x)


def _хвост_стопа(имя, стопы, пропущено) -> str:
    """« · стоп (−0.346/−0.300) · пропущено 18 сигналов» к строке группы.

    ЗАЧЕМ ЭТО В СТРОКЕ ГРУППЫ. 02.10 cand1 встала на свой стоп в 05:39:06Z, и за
    пять часов гейт отклонил по ней 18 сигналов -- а в сводке она выглядела
    обычной строкой с итогом: стоп читался как тишина. Пара «убыток/порог» и
    число отклонённых стоят ровно там, где владелец читает группу.

    ТРИ ЗНАКА У ОБОИХ ЧИСЕЛ: на двух «−0.346 при пороге −0.3» превратилось бы в
    «−0.35/−0.30», и разницы с порогом в строке не осталось бы вовсе.

    ЧИСЛО ПРОПУЩЕННЫХ ПЕЧАТАЕТСЯ, ТОЛЬКО ЕСЛИ ЕГО СЧИТАЛИ. Ключа нет -- значит не
    считали, и строка молчит; ноль -- значит считали и он ноль. Выдуманный ноль
    обещал бы владельцу счёт, которого не было.
    """
    з = (стопы or {}).get(имя) if isinstance(стопы, dict) else None
    # ЗАПИСЬ ГРУППЫ -- СЛОВАРЬ, И ЧУЖОЕ НА ЕЁ МЕСТЕ СТОИТ СТРОКИ, А НЕ ДОКЛАДА:
    # до этой проверки «мусор» в одной группе ронял всю сводку целиком.
    з = з if isinstance(з, dict) else {}
    хвост = ""
    if з.get("стоит"):
        хвост += (f" · стоп ({_знак(з.get('убыток_по_цепи_sol'), 3, плюс=True)}/"
                   f"{_знак(з.get('порог_sol'), 3, плюс=True)})")
    elif з.get("стоит") is None and з:
        # «НЕ ЗНАЮ» ТОЖЕ ОТВЕТ: молчание здесь читалось бы как «стоп снят».
        хвост += f" · стоп не прочитан: {_экран(з.get('почему_нет') or 'причина не названа')}"
    n = _число((пропущено or {}).get(имя) if isinstance(пропущено, dict) else None)
    if n is not None:
        хвост += f" · пропущено {int(n)} сигналов"
    return хвост


def _строки_групп(по_группам: dict, стопы: dict | None = None,
                   пропущено: dict | None = None) -> list:
    """«lane_s0 12 · +0.44 SOL», а группа без сделок -- «leader 0 SOL».

    ПОРЯДОК -- ПО ИТОГУ ВНИЗ, а группы без сделок -- в конце. Это прочитано из
    образца владельца 02.10: там cand1 с 50 сделками стоит ПОСЛЕ lane_s0 с 12, а
    leader без сделок -- последним, хотя его ноль больше, чем −0.02 у batch5.
    Сортировать по числу сделок значило бы переставить его же строки.
    При равных итогах -- порядок появления (сортировка устойчивая).

    `стопы` и `пропущено` -- то, что отдают bloom_doklad.стопы_групп и
    bloom_doklad.пропущено_сигналов. Считать их здесь нечем и не нужно: суточный
    стоп считает гейт полосы, а отклонённые сигналы лежат в журнале решений.
    """
    по_группам = dict(по_группам or {})
    # ЧТО БЫ НИ ДАЛИ -- ПРИВОДИМ К КАРТЕ {группа: запись}: точка вызова передаёт
    # ответ bloom_doklad.стопы_групп целиком, и без этого доклад падал на .get у
    # True (ключ «ok»), причём ровно при прочитанном стопе.
    стопы = _по_группам_как_есть(стопы, "группы")
    пропущено = _числа_по_группам(пропущено)
    # ГРУППА НА СТОПЕ ПЕЧАТАЕТСЯ, ДАЖЕ ЕСЛИ СДЕЛОК У НЕЁ В ЭТОМ ОКНЕ НЕТ. Именно
    # так и выглядел стоп cand1 после 05:39: сделок больше нет, строки в сводке
    # нет -- и остановленная группа исчезала из доклада целиком.
    for имя, з in (стопы or {}).items():
        if (з or {}).get("стоит") and имя not in по_группам:
            по_группам[имя] = {"сделок": 0, "итог_sol": 0.0}
    строки = []
    for имя, зн in sorted(
            по_группам.items(),
            key=lambda кв: (not int((кв[1] or {}).get("сделок") or 0),
                             -(_число((кв[1] or {}).get("итог_sol")) or 0.0))):
        зн = зн or {}
        n = int(зн.get("сделок") or 0)
        итог = _число(зн.get("итог_sol"))
        хвост = _хвост_стопа(имя, стопы, пропущено)
        if not n:
            # ГРУППА БЕЗ СДЕЛОК ПЕЧАТАЕТСЯ ВСЁ РАВНО: её молчание -- тоже ответ
            # («leader 0 SOL» в образце владельца), и отличить «группа не
            # торговала» от «группы нет в файле» иначе нечем.
            строки.append(f"{_экран(имя)} 0 SOL{хвост}")
            continue
        # ТРИ ЗНАКА, А НЕ ДВА (слово владельца 02.10). На сутках 01.10 группа
        # test_krug с настоящим итогом −0.003200691 печаталась как «−0.00 SOL»:
        # знак есть, числа нет. Общий итог строки «Сделки» три знака имел и
        # раньше -- теперь группы считаются той же точностью, что и он.
        строки.append(f"{_экран(имя)} {n} · {_знак(итог, 3, плюс=True)} SOL{хвост}")
    return строки


def рента_заперта_по_цепи(снимок: dict) -> dict:
    """«Рента заперта» для сверки -- ИЗ СНИМКА СЧЕТОВ КОШЕЛЬКА, не из записей.

    Снимок -- то, что отдаёт bloom_token_accounts (ключи rent_locked_in_empty_sol
    и empty_count). Считается именно по ПУСТЫМ счетам: в счёте с остатком рента
    тоже заперта, но вместе с токеном, и пока токен не продан это не "деньги,
    которые забыли вернуть", а часть открытой позиции.

    ЗАЧЕМ ОТДЕЛЬНАЯ ФУНКЦИЯ, А НЕ ЧИСЛО ИЗ ЗАПИСЕЙ. Замер владельца 01.10: по
    записям суток выходило 142 счёта (0.215 SOL), а на кошельке в 19:55Z лежало
    11. Записи помнят КАЖДЫЙ созданный за сутки счёт, кошелёк -- только НЕ
    ЗАКРЫТЫЕ, и подставить первое под именем второго значило завысить запертые
    деньги в тринадцать раз. Теперь у этого числа одно место, и оно читает цепь.
    """
    с = снимок if isinstance(снимок, dict) else {}
    sol = _число(с.get("rent_locked_in_empty_sol"))
    n = _число(с.get("empty_count"))
    из_ = {"ok": False, "рента_заперта_sol": None, "рента_счетов": None,
            "почему_нет": None}
    if sol is None or n is None:
        из_["почему_нет"] = ("в снимке нет rent_locked_in_empty_sol/empty_count -- "
                              "ренту по цепи взять негде, а по записям её брать "
                              "нельзя: это другое число")
        return из_
    из_.update(ok=True, рента_заперта_sol=round(float(sol), 9),
                рента_счетов=int(n))
    return из_


def _строка_сверки(св: dict) -> str | None:
    """«Сверка: по балансу +0.91 (ввод 1.4 учтён) · рента заперта 0.02 · UNSOLD 1 (…)»"""
    части = []
    по_бал = _число(св.get("по_балансу_sol"))
    if по_бал is not None:
        кусок = f"по балансу {_знак(по_бал, 2, плюс=True)}"
        ввод = _число(св.get("ввод_sol"))
        вывод = _число(св.get("вывод_sol"))
        # ВВОД И ВЫВОД НАЗВАНЫ В СКОБКЕ, а не растворены в числе: иначе «по
        # балансу +0.91» не отличить от «заработали 0.91», а это разные вещи.
        if ввод:
            кусок += f" (ввод {float(ввод):g} учтён)"
        elif вывод:
            кусок += f" (вывод {float(вывод):g} учтён)"
        части.append(кусок)
    # РЕНТА -- ПО ЦЕПИ (счета кошелька x рента счёта), А НЕ СУММОЙ ПО ЗАПИСЯМ.
    # Замер владельца 01.10: по записям суток выходило 142 счёта (0.215 SOL), а
    # измеренных на кошельке в 19:55Z было 11. Разница не ошибка счёта, а разные
    # вещи: запись помнит КАЖДЫЙ созданный за сутки счёт, а на кошельке лежат
    # только НЕ ЗАКРЫТЫЕ. Печатать первое под именем второго значило бы завышать
    # запертые деньги в тринадцать раз. Число приходит параметром: считать его
    # здесь нечем -- для этого надо читать счета кошелька.
    рента = _число(св.get("рента_заперта_sol"))
    if рента is not None:
        кусок = f"рента заперта {abs(float(рента)):.3f}"
        сч = _число(св.get("рента_счетов"))
        if сч is not None:
            кусок += f" ({int(сч)} сч.)"
        части.append(кусок)
    # UNSOLD ПЕЧАТАЕТСЯ ТОЛЬКО ЕСЛИ ЕГО СЧИТАЛИ. Пустой список -- это «ни одной
    # непроданной», и он честно даёт «UNSOLD 0»; None -- «не считали», и тогда
    # строки нет вовсе. Печатать ноль там, где не считали, значит обещать
    # владельцу проверку, которой не было.
    unsold = св.get("unsold")
    if isinstance(unsold, list):
        куски = []
        for у in unsold:
            у = у if isinstance(у, dict) else {}
            имя = (_строка_или_нет(у.get("имя"))
                   or (str(у.get("минт") or "")[:8] or НЕТ))
            итог = _число(у.get("итог_sol"))
            куски.append(f"{_экран(имя)} {_знак(итог, 2, плюс=True)}"
                          if итог is not None else _экран(имя))
        части.append(f"UNSOLD {len(unsold)}"
                      + (f" ({' · '.join(куски)})" if куски else ""))
    return ("Сверка: " + " · ".join(части)) if части else None


def _строки_регионов(регионы: dict, регионы_s0: dict) -> list:
    """Регионы столбиком, пара выровнена по самой длинной: так читается глазами."""
    пары = [(к, int(v)) for к, v in (регионы or {}).items() if v]
    if not пары:
        return []
    # НЕТ РЕГИОНА -- ВСЕГДА ПОСЛЕДНИМ, остальные по числу вниз: иначе строка с
    # прочерком всплывала бы в середину и читалась как регион.
    пары.sort(key=lambda кв: (кв[0] in (НЕТ, НЕТ_РЕГИОНА), -кв[1]))
    ширина = max(len(к if к not in (НЕТ,) else НЕТ_РЕГИОНА) for к, _ in пары)
    строки = []
    for к, n in пары:
        имя = НЕТ_РЕГИОНА if к == НЕТ else к
        s0 = (регионы_s0 or {}).get(к)
        хвост = f" · {int(s0)}" if isinstance(s0, int) else ""
        строки.append(f"  {_экран(имя.ljust(ширина))} {n}{хвост}")
    return строки


