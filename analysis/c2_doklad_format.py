"""Формат докладчика по слову владельца 30.09 16:28. ОТДЕЛЬНЫМ МОДУЛЕМ.

ЧТО ЗДЕСЬ. Три строки нового вида -- BUY, часовая 🧾 и суточная 📋 -- и сбор чисел
часа из записей полосы. SELL не трогается вовсе: он остаётся как есть, и для него
здесь нет ни функции, ни правки в точке вызова.

ГЛАВНОЕ ПРАВИЛО, И ОНО ПРОВЕРЯЕТСЯ САМОПРОВЕРКОЙ: МОДУЛЬ НИКОГДА НЕ ПОДНИМАЕТ
ИСКЛЮЧЕНИЯ. Любая ошибка внутри -- хоть отсутствующий ключ, хоть строка вместо
числа, хоть None вместо словаря -- возвращает ПРЕЖНЮЮ строку, ту самую, которую
собрал bloom_doklad. Доклад не должен падать из-за формата: молчание в чате хуже
старого вида строки. Поэтому у каждой открытой функции второй обязательный
аргумент -- `прежняя`, и она же ответ при любом сбое.

ГДЕ ТОЧКИ ВЫЗОВА -- НЕ ТАМ, ГДЕ НАЗВАНО В ЗАДАНИИ. В задании сказано
`bloom_tg_format.py`, но живой докладчик -- `analysis/bloom_doklad.py`: именно его
`строка_buy(п)` зовут `доложить_покупку`/`доложить_продажу`, и именно его
импортируют bloom_detector и bloom_seller. `bloom_tg_format.py` и
`bloom_tg_format3.py` -- прежние модули формата, их зовёт bloom_notify. Правку я
описал для `bloom_doklad.py` (docs/doklad_format_kak_vstroit.md) и сам его НЕ
ТРОГАЛ: это файл Code-1.

ЧТО УБРАНО ПО СЛОВУ ВЛАДЕЛЬЦА. Из BUY -- «место», «в S+0 успели», «копировщиков»;
из часовой -- «в цели» и «промахов наших». Их здесь нет не по забывчивости: это
решение, и оно записано, чтобы никто не вернул их «обратно как было».
"""
from __future__ import annotations

import statistics

# Минус -- U+2212, как в образце владельца, а не дефис: в чате они выглядят
# по-разному, и образец написан именно этим знаком.
МИНУС = "−"
# Тире окна часа -- U+2013 (12:00–13:00Z), тоже из образца.
ТИРЕ = "–"
НЕТ = "—"          # длинное тире для неизвестного
SOLSCAN = "https://solscan.io/tx/"


# ----------------------------------------------------------------- мелочи

def _экран(т) -> str:
    return (str(т if т is not None else "")
            .replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;"))


def ссылка(подпись, ярлык: str = "tx") -> str:
    """Ссылка на Solscan. Нет подписи -- ярлык без ссылки и без хеша."""
    if not подпись:
        return ярлык
    return f'<a href="{SOLSCAN}{подпись}">{ярлык}</a>'


def _знак(x, знаков: int) -> str:
    """Число со знаком владельца: минус U+2212, плюс явный."""
    if x is None:
        return НЕТ
    з = float(x)
    if з < 0:
        return f"{МИНУС}{abs(з):.{знаков}f}"
    return f"{з:.{знаков}f}"


def _проц(x, знаков: int = 1) -> str:
    if x is None:
        return НЕТ
    з = float(x)
    знак = МИНУС if з < 0 else ""
    return f"{знак}{abs(з):.{знаков}f} %"


def _цел(x) -> str:
    return НЕТ if x is None else f"{int(round(float(x)))}"


def _размер(x) -> str:
    """Размер входа как в образце: 0.3, а не 0.3000 и не 0.30."""
    return НЕТ if x is None else f"{float(x):g}"


# ------------------------------------------------------------------- BUY

def _buy(п: dict, поз: dict | None) -> str:
    # НЕ СЛОВАРЬ -- ЭТО СЛОМАННЫЙ ВХОД, а не «пустая сделка». Собрать из него
    # строку значило бы напечатать в чат ряд прочерков вместо доклада; правильный
    # ответ -- прежняя строка, и обёртка её вернёт.
    if not isinstance(п, dict):
        raise TypeError("п не словарь")
    поз = поз if isinstance(поз, dict) else {}
    время = п.get("время")
    голова = f"🟢 {время} BUY" if время else "🟢 BUY"
    имя = (_экран(п.get("имя_токена")) if п.get("имя_токена")
           else (_экран(str(п.get("минт"))[:6]) if п.get("минт") else НЕТ))
    s = f"S+{int(п['s_n'])}" if п.get("s_n") is not None else "S+?"
    # ПУТЬ -- ТРЕМЯ БУКВАМИ, как в образце: У увидели, Р решили, С собрали.
    # Скобка печатается только целиком: половина кусков хуже, чем ни одного,
    # потому что сумма перестаёт сходиться с числом перед скобкой.
    куски = [п.get("путь_увидели"), п.get("путь_решили"), п.get("путь_собрали")]
    скобка = ""
    if all(isinstance(к, (int, float)) for к in куски):
        скобка = (f" (У{int(round(куски[0]))}·Р{int(round(куски[1]))}·"
                  f"С{int(round(куски[2]))})")
    путь = (f"{_цел(п.get('путь_всего'))} мс{скобка}"
            if п.get("путь_всего") is not None else f"{НЕТ} мс")
    # ОТПРАВИТЕЛЬ И РЕГИОНЫ. Регионы берутся из полей lane_region*: точка отправки
    # и регион лидера слота. Их пишет полоса (bloom_own_send), и в записи они
    # лежат рядом с позицией, а не внутри полей доклада -- поэтому смотрим и
    # туда, и туда.
    отпр = п.get("довёз") or поз.get("lane_pool_winner") or поз.get("lane_send_point")
    точка = (п.get("регион_точки") or поз.get("lane_region_point")
             or поз.get("lane_region") or поз.get("region_point")
             or поз.get("region_otpravki"))
    лидер = (п.get("регион_лидера") or поз.get("lane_region_leader")
             or поз.get("region_lidera"))
    хвост = (f"{_экран(отпр) if отпр else НЕТ} / "
             f"{_экран(точка) if точка else НЕТ}→{_экран(лидер) if лидер else НЕТ}")
    части = [голова, п.get("группа") and _экран(п["группа"]),
             п.get("имя_источника") and _экран(п["имя_источника"]),
             _размер(п.get("вошло_sol")), имя, s, путь, хвост,
             ссылка(п.get("подпись_источника"))]
    return " · ".join([ч for ч in части if ч])


def строка_buy(п: dict, прежняя: str, *, поз: dict | None = None) -> str:
    """BUY одной строкой. ЛЮБАЯ ошибка -- прежняя строка, без исключения наружу."""
    try:
        т = _buy(п, поз)
        return т if isinstance(т, str) and т.strip() else прежняя
    except Exception:  # noqa: BLE001
        return прежняя


# ------------------------------------------------- часовая и суточная

def _сводка(св: dict, значок: str) -> str:
    if not isinstance(св, dict):
        raise TypeError("свод не словарь")
    окно = св.get("окно") or "?"
    сделок = int(св.get("сделок") or 0)
    первая = f"{значок} {окно} · сделок {сделок}"
    # ЧАС БЕЗ СДЕЛОК -- ОДНА СТРОКА (слово владельца). Ни долей, ни медиан:
    # делить не на что, а печатать нули значило бы говорить о том, чего не было.
    if not сделок:
        return первая
    первая += f" на {float(св.get('объём_sol') or 0):.2f}"
    первая += f" · итог {_знак(св.get('итог_sol'), 4)}"
    if св.get("итог_процент") is not None:
        первая += f" ({_проц(св.get('итог_процент'))})"
    в_плюсе = св.get("в_плюсе")
    if в_плюсе is not None:
        первая += f" · в плюсе {int(в_плюсе)}/{сделок}"
    вторая = [f"S+0 ({int(св.get('s0') or 0)})",
              f"S+1 ({int(св.get('s1') or 0)})",
              f"S+2+ ({int(св.get('s2plus') or 0)})"]
    if св.get("путь_медиана_мс") is not None:
        вторая.append(f"путь медиана {_цел(св['путь_медиана_мс'])} мс")
    if св.get("не_село") is not None:
        вторая.append(f"не село {int(св['не_село'])}")
    строки = [первая, " · ".join(вторая)]
    третья = ""
    довозили = св.get("довозили") or {}
    if довозили:
        # ПОРЯДОК -- ПО УБЫВАНИЮ ЧИСЛА, А ПРИ РАВНЫХ -- ПОРЯДОК ПОЯВЛЕНИЯ.
        # Сортировка в Python устойчивая, поэтому второго ключа тут быть НЕ
        # ДОЛЖНО: с ним равные числа встали бы по алфавиту, и образец владельца
        # (jito 1 · astralane 1 · zeroslot 1) перестал бы сходиться.
        части = [f"{_экран(к)} {int(v)}" for к, v in
                 sorted(довозили.items(), key=lambda кв: -int(кв[1]))
                 if v]
        if части:
            третья = "довозили: " + " · ".join(части)
    регионы = св.get("регионы") or {}
    if регионы:
        куски = [f"{_экран(к)} {int(v)}" for к, v in
                 sorted(регионы.items(), key=lambda кв: -int(кв[1]))
                 if v]
        if куски:
            третья = (третья + " · " if третья else "") + "регион " + ", ".join(куски)
    if третья:
        строки.append(третья)
    четвёртая = []
    if св.get("итог_24h_sol") is not None:
        четвёртая.append(f"24H (по цепи) {_знак(св['итог_24h_sol'], 3)}")
    if св.get("открытых") is not None:
        четвёртая.append(f"Open {int(св['открытых'])}")
    if св.get("баланс_sol") is not None:
        четвёртая.append(f"BAL {float(св['баланс_sol']):.2f} SOL")
    if четвёртая:
        строки.append(" · ".join(четвёртая))
    return "\n".join(строки)


def строка_часа(св: dict, прежняя: str) -> str:
    """🧾 часовая. Любая ошибка -- прежняя строка."""
    try:
        т = _сводка(св, "🧾")
        return т if isinstance(т, str) and т.strip() else прежняя
    except Exception:  # noqa: BLE001
        return прежняя


def строка_суток(св: dict, прежняя: str) -> str:
    """📋 суточная -- ТЕМ ЖЕ форматом, другой значок и другое окно."""
    try:
        т = _сводка(св, "📋")
        return т if isinstance(т, str) and т.strip() else прежняя
    except Exception:  # noqa: BLE001
        return прежняя


# --------------------------------------------------- сбор чисел из записей

def окно_часа(час_utc: str) -> str:
    """'2026-09-30T12' -> '12:00–13:00Z'. Тире -- то же, что в образце."""
    ч = int(str(час_utc)[11:13])
    return f"{ч:02d}:00{ТИРЕ}{(ч + 1) % 24:02d}:00Z"


def окно_часа_из_времени(с) -> str:
    """Окно часа из unix-времени начала часа -- для точки вызова в детекторе.

    Детектор держит час числом (с = час * 3600), а не строкой. Пересчёт здесь,
    а не там: в чужом файле правка должна быть одной строкой.
    """
    import time as _t  # noqa: PLC0415

    ч = _t.gmtime(float(с)).tm_hour
    return f"{ч:02d}:00{ТИРЕ}{(ч + 1) % 24:02d}:00Z"


def сутки_из_времени(с) -> str:
    """Окно суток из unix-времени: '2026-09-30Z'."""
    import time as _t  # noqa: PLC0415

    return _t.strftime("%Y-%m-%dZ", _t.gmtime(float(с)))


def _число(x):
    return float(x) if isinstance(x, (int, float)) and not isinstance(x, bool) else None


def z_winner(з_: dict, з: dict):
    """Кто довёз: поле полосы лежит то в записи позиции, то в её подзаписи."""
    return (з_ or {}).get("lane_pool_winner") or (з or {}).get("lane_pool_winner") \
        or (з or {}).get("lane_send_point")


def свод(ряды, *, окно: str, итог_24h_sol=None, открытых=None,
          баланс_sol=None, поля=None) -> dict:
    """Числа окна из записей полосы. Считает ТОЛЬКО то, что есть в записях.

    24H, Open и BAL записями не считаются -- это состояние кошелька и цепи, и они
    приходят параметрами. Выдумывать их здесь значило бы печатать число, за
    которым ничего не стоит.

    `поля` -- НЕОБЯЗАТЕЛЬНЫЙ переводчик записи в числа доклада
    (bloom_doklad.поля). С ним свод работает на ЖИВЫХ ПОЗИЦИЯХ службы, где итог,
    s_n и путь не лежат готовыми; без него -- на выгрузке сделок, где они уже
    посчитаны. Считать их вторым способом здесь нельзя: у полосы итог считается
    одной формулой, и второй счёт разошёлся бы с ней молча.
    """
    из_ = {"окно": окно, "сделок": 0, "объём_sol": 0.0, "итог_sol": 0.0,
            "итог_процент": None, "в_плюсе": 0, "s0": 0, "s1": 0, "s2plus": 0,
            "путь_медиана_мс": None, "не_село": 0, "довозили": {}, "регионы": {},
            "итог_24h_sol": итог_24h_sol, "открытых": открытых,
            "баланс_sol": баланс_sol}
    пути = []
    for з in (ряды or []):
        if not isinstance(з, dict):
            continue
        з_ = з.get("zapis") if isinstance(з.get("zapis"), dict) else {}
        пф = {}
        if callable(поля):
            try:
                пф = поля(з) or {}
            except Exception:  # noqa: BLE001
                пф = {}
        из_["сделок"] += 1
        вошло = (_число(пф.get("вошло_sol")) if пф else None)
        if вошло is None:
            вошло = _число(з.get("sol_in")) or _число(з.get("size_sol")) or 0.0
        из_["объём_sol"] += вошло
        итог = _число(пф.get("итог_sol")) if пф else None
        if итог is None:
            итог = _число(з.get("итог_sol"))
        if итог is not None:
            из_["итог_sol"] += итог
            если_плюс = итог > 0
            из_["в_плюсе"] += 1 if если_плюс else 0
        s = пф.get("s_n") if пф else None
        if s is None:
            s = з.get("s_plus")
        if isinstance(s, int):
            if s == 0:
                из_["s0"] += 1
            elif s == 1:
                из_["s1"] += 1
            else:
                из_["s2plus"] += 1
        # НЕ СЕЛО -- это НЕ «нет s_plus». Не села та покупка, у которой нет
        # подписи на цепи: посадка есть -- есть landed_sig.
        if not (з.get("landed_sig") or з_.get("lane_landed_signature")
                or з.get("lane_landed_signature")
                or (пф.get("подпись_покупки") if пф else None)):
            из_["не_село"] += 1
        п = _число(пф.get("путь_всего")) if пф else None
        if п is not None:
            пути.append(п)
        else:
            п = _число(з.get("путь_всего_мс")) or _число(з_.get("seen_lag_ms"))
            куски = [_число((з_ or з).get(к))
                     for к in ("lane_build_ms", "lane_variants_ms",
                                "lane_sign_ms", "lane_nonce_ms")]
            куски = [к for к in куски if к is not None]
            if п is not None:
                пути.append(п + (sum(куски) if куски else 0.0))
        довёз = (пф.get("довёз") if пф else None) or z_winner(з_, з)
        if довёз:
            из_["довозили"][str(довёз)] = из_["довозили"].get(str(довёз), 0) + 1
        точка = (з_.get("lane_region_point") or з_.get("lane_region")
                 or з.get("lane_region_point") or з.get("lane_region")
                 or з.get("region_point") or з.get("region_otpravki"))
        лидер = (з_.get("lane_region_leader") or з.get("lane_region_leader")
                 or з.get("region_lidera"))
        if точка and лидер:
            к = f"{точка}→{лидер}"
            из_["регионы"][к] = из_["регионы"].get(к, 0) + 1
    if пути:
        из_["путь_медиана_мс"] = round(statistics.median(пути), 0)
    из_["объём_sol"] = round(из_["объём_sol"], 9)
    из_["итог_sol"] = round(из_["итог_sol"], 9)
    if из_["объём_sol"]:
        из_["итог_процент"] = из_["итог_sol"] / из_["объём_sol"] * 100.0
    if not из_["сделок"]:
        из_["итог_процент"] = None
    return из_


def подменить(вид: str, прежняя: str, п=None, *, поз=None) -> str:
    """ОДНА дверь для точек вызова: вид -> новая строка или прежняя.

    Сделано одной функцией нарочно: в чужом файле правка тогда -- одна строка на
    точку вызова, и снять её можно тоже одной строкой.
    """
    try:
        if вид == "buy":
            return строка_buy(п, прежняя, поз=поз)
        if вид == "час":
            return строка_часа(п, прежняя)
        if вид == "сутки":
            return строка_суток(п, прежняя)
        return прежняя
    except Exception:  # noqa: BLE001
        return прежняя


