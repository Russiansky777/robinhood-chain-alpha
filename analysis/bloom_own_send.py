def включена() -> bool:
    """Полоса вообще собрана? Сборка и симуляция идут и без этого флага."""
    return ST.env_int("BLOOM_OWN_SEND", 0) == 1


def живьём() -> bool:
    """ОТПРАВКА в сеть. Без этого не уходит ни одна транзакция полосы."""
    return ST.env_int("BLOOM_OWN_SEND_LIVE", 0) == 1


# ОТДЕЛЬНЫЙ КОШЕЛЁК ПОЛОСЫ (решение владельца 25.09). Причина прямая: автоордер
# Bloom продаёт ВЕСЬ баланс минта на кошельке, и на первой же живой отправке он
# смёл токены полосы вместе со своими -- итог полосы стало нечем считать. Свой
# кошелёк делает вход, остаток и выход полосы её собственными.
#
# Если переменных нет, полоса работает как раньше -- на кошельке исполнителя:
# так старые самопроверки и сухие прогоны остаются в силе, а не ломаются молча.
ENV_КОШЕЛЁК_ПОЛОСЫ = "OWN_SEND_WALLET"
ENV_КЛЮЧ_ПОЛОСЫ = "OWN_SEND_WALLET_KEY"


def кошелёк_полосы() -> str:
    """Публичный адрес, с которого полоса покупает и продаёт."""
    свой = (os.environ.get(ENV_КОШЕЛЁК_ПОЛОСЫ) or "").strip()
    return свой or ST.EXECUTOR_WALLET


def ключ_полосы() -> str | None:
    """Секрет кошелька полосы. None -- значит своего ключа нет и подписывать
    надо ключом исполнителя (старое поведение)."""
    к = (os.environ.get(ENV_КЛЮЧ_ПОЛОСЫ) or "").strip()
    return к or None


def свой_кошелёк() -> bool:
    return кошелёк_полосы() != ST.EXECUTOR_WALLET


def кошелёк_готов() -> dict:
    """Согласован ли кошелёк полосы с её ключом. Несогласован -- запрет.

    Проверка нужна ДО первой отправки и в признаке жизни: подписать чужим
    ключом значит отправить транзакцию, которую сеть отвергнет, потратив
    приоритет и чаевые, либо -- хуже -- подписать не тот кошелёк.
    """
    адрес, секрет = кошелёк_полосы(), ключ_полосы()
    из_ = {"wallet": адрес, "own_wallet": свой_кошелёк(), "ok": False,
            "why_not": None}
    if not свой_кошелёк():
        из_.update(ok=True, why_not=None,
                   note="своего кошелька нет -- полоса на кошельке исполнителя")
        return из_
    if not секрет:
        из_["why_not"] = f"{ENV_КЛЮЧ_ПОЛОСЫ} не задан -- подписывать нечем"
        return из_
    try:
        import bloom_jupiter_sell as J  # noqa: PLC0415
    except Exception as exc:  # noqa: BLE001
        из_["why_not"] = f"модуль проверки ключа не загружен: {type(exc).__name__}"
        return из_
    свой = J.ключ_от_нашего_кошелька(адрес, секрет)
    из_.update(ok=bool(свой.get("ok")), why_not=свой.get("why_not"))
    return из_


def адрес_сендера() -> str:
    регион = (os.environ.get("BLOOM_SENDER_REGION") or "ams").strip().lower()
    return SENDER_HOSTS.get(регион, SENDER_HOSTS["ams"])


def размер_sol() -> float:
    return ST.env_float("BLOOM_OWN_SEND_SOL", 0.01)


def чаевые_sol() -> float:
    """Чаевые Sender. Ниже документированного минимума не опускаемся.

    Меньший тип документация принимает, но он идёт мимо приоритетного
    буфера -- полоса тогда мерила бы не тот путь, ради которого заведена.
    """
    з = ST.env_float("BLOOM_OWN_SEND_TIP_SOL", TIP_MIN_SOL)
    return max(з, TIP_MIN_SOL)


def приоритет_sol() -> float:
    return ST.env_float("BLOOM_OWN_SEND_PRIORITY_SOL", 0.001)


def выбрать_чаевые(семя: str | None = None) -> str:
    """Адрес для чаевых. Разный от сделки к сделке.

    Документация даёт десять адресов не для красоты: один и тот же счёт на
    каждой отправке -- лишняя точка соперничества за запись.
    """
    if not семя:
        return random.choice(TIP_ACCOUNTS)
    return TIP_ACCOUNTS[sum(bytearray(семя.encode("utf-8"))) % len(TIP_ACCOUNTS)]


def цена_единицы_cu(приоритет_лампорты: int, cu_units: int) -> int:
    """Микролампорты за единицу CU, чтобы приоритет вышел заданной суммой."""
    if cu_units <= 0:
        return 0
    return int(приоритет_лампорты * 1_000_000 // cu_units)


