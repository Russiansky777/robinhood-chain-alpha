def кошелёк_полосы() -> str:
    """Публичный адрес, с которого полоса покупает и продаёт."""
    свой = (os.environ.get(ENV_КОШЕЛЁК_ПОЛОСЫ) or "").strip()
    return свой or ST.EXECUTOR_WALLET


def ключ_полосы() -> str | None:
    """Секрет кошелька полосы. None -- значит своего ключа нет и подписывать
    надо ключом исполнителя (старое поведение)."""
    к = (os.environ.get(ENV_КЛЮЧ_ПОЛОСЫ) or "").strip()
    return к or None


def свой_кошелёк() -> bool:
    return кошелёк_полосы() != ST.EXECUTOR_WALLET


def кошелёк_готов() -> dict:
    """Согласован ли кошелёк полосы с её ключом. Несогласован -- запрет.

    Проверка нужна ДО первой отправки и в признаке жизни: подписать чужим
    ключом значит отправить транзакцию, которую сеть отвергнет, потратив
    приоритет и чаевые, либо -- хуже -- подписать не тот кошелёк.
    """
    адрес, секрет = кошелёк_полосы(), ключ_полосы()
    из_ = {"wallet": адрес, "own_wallet": свой_кошелёк(), "ok": False,
            "why_not": None}
    if not свой_кошелёк():
        из_.update(ok=True, why_not=None,
                   note="своего кошелька нет -- полоса на кошельке исполнителя")
        return из_
    if not секрет:
        из_["why_not"] = f"{ENV_КЛЮЧ_ПОЛОСЫ} не задан -- подписывать нечем"
        return из_
    try:
        import bloom_jupiter_sell as J  # noqa: PLC0415
    except Exception as exc:  # noqa: BLE001
        из_["why_not"] = f"модуль проверки ключа не загружен: {type(exc).__name__}"
        return из_
    свой = J.ключ_от_нашего_кошелька(адрес, секрет)
    из_.update(ok=bool(свой.get("ok")), why_not=свой.get("why_not"))
    return из_


