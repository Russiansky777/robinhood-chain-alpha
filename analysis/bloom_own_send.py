def купленное_raw(tx: dict, кошелёк: str, минт: str) -> dict:
    """Сколько СЫРЫХ единиц минта прибыло на наш адрес этой транзакцией.

    Это количество -- то самое, которое сторож потом продаёт. Считается
    ТОЛЬКО в сырых единицах (uiTokenAmount.amount): у токена с девятью
    знаками движение в единицах показывается в ui нулём, а пыль -- числом.
    Цена ошибки прямая: по ui продали бы не то количество, что купили.

    Своих счетов минта может быть несколько (ATA плюс созданный в этой же
    транзакции), поэтому суммируем по всем, где владелец -- наш кошелёк.
    Отсутствие счёта в preTokenBalances -- обычный случай: счёт создан
    здесь же, и до транзакции его не было вовсе.
    """
    из_ = {"ok": False, "raw": None, "why_not": None}
    if not isinstance(tx, dict):
        из_["why_not"] = "транзакции нет"
        return из_
    мета = tx.get("meta")
    if not isinstance(мета, dict):
        из_["why_not"] = "у транзакции нет meta -- количество не посчитать"
        return из_
    if мета.get("err") is not None:
        из_["why_not"] = f"транзакция упала: {json.dumps(мета.get('err'), ensure_ascii=False)[:120]}"
        из_["chain_ok"] = False
        return из_
    if not кошелёк or not минт:
        из_["why_not"] = f"нужны кошелёк и минт (кошелёк {кошелёк!r}, минт {минт!r})"
        return из_
    было: dict = {}
    стало: dict = {}
    for где, куда in (("preTokenBalances", было), ("postTokenBalances", стало)):
        for б in (мета.get(где) or []):
            if not isinstance(б, dict) or б.get("owner") != кошелёк:
                continue
            if б.get("mint") != минт:
                continue
            сырое = (б.get("uiTokenAmount") or {}).get("amount")
            try:
                куда[б.get("accountIndex")] = int(сырое)
            except (TypeError, ValueError):
                из_["why_not"] = f"количество не число: {сырое!r}"
                return из_
    if not стало:
        из_["why_not"] = "нашего счёта этого минта в postTokenBalances нет"
        return из_
    дельта = sum(стало.values()) - sum(было.get(и, 0) for и in стало)
    if дельта <= 0:
        из_["why_not"] = f"приход не положителен: {дельта}"
        из_["raw"] = дельта
        return из_
    из_.update(ok=True, raw=дельта, chain_ok=True)
    return из_


# ЛЕСТНИЦЫ ПЛАТЫ (З3) ЗДЕСЬ НЕТ -- И НЕ ДОЛЖНО БЫТЬ. Владелец отменил её
# 25.09 по итогам З1, и вот почему, чтобы никто не добавил её обратно: в
# 66 % наших покупок перед нами в блоке стояли транзакции, заплатившие
# МЕНЬШЕ нас (171 более дешёвая против 19 более дорогих), а медиана платы
# тех, кто садится в S+0 сразу за источником, -- около 9 500 лампортов
# против наших 995 000. Ступени "средний" и "высокий" оказались бы ниже
# базового уровня, а вопрос "плата или путь" уже отвечен: путь. Тратить на
# лестницу 0.05 SOL и живые сигналы незачем.

# ------------------------------------------------- контроль доставки (З2)

# Слово владельца 25.09: "На каждом сигнале с покупкой полосы -- в ту же
# миллисекунду тем же путём (Helius Sender, те же чаевые) пустая транзакция
# без касания пула (memo или перевод 0 себе)". Смысл замера: если контроль
# садится заметно быстрее покупки, задержка -- это очередь к горячему пулу
# (плата). Если он так же медленный -- задержка в пути, и её надо разбирать
# по этапам.
#
# ПОЧЕМУ ПЕРЕВОД НУЛЯ СЕБЕ, А НЕ MEMO. Владелец разрешил и то и другое.
# Перевод нуля собирается теми же кирпичами, что уже проверены сборкой
# покупки (c2_swap_build.sol_transfer), и не требует заводить в репозитории
# ещё один адрес программы. Получатель -- наш же кошелёк, сумма ноль:
# ошибиться адресом тут нечем.
#
# ЧТО ЭТО СТОИТ. Приоритет и чаевые у контроля ровно те же, что у покупки
# (иначе сравнение нечестно): 0.001 + 0.001 SOL плюс базовая подпись. Отсюда
# два предела владельца: не больше 20 контролей в сутки и не больше 0.03 SOL
# на контроли. Первым срабатывает тот, который ближе.
ЛИМИТ_КОНТРОЛЕЙ_В_СУТКИ = 20
# ПОТОЛОК РАСХОДА НА КОНТРОЛИ. Решение владельца 25.09: "Потолок на контроли
# поднять до 0.1 SOL в сутки, 20 сигналов в сутки" (было 0.05, до того 0.03).
# Двадцать сигналов по пятерым сервисам стоят около 0.0625 SOL -- в 0.1 SOL
# они укладываются, то есть первым срабатывает счёт сигналов, а не деньги.
ПОТОЛОК_РАСХОДА_КОНТРОЛЯ_SOL = 0.1
# И ОТДЕЛЬНО НА СЕРВИС НА СИГНАЛ: "0.001 SOL на сервис на сигнал". Считается
# по УПРАВЛЯЕМОЙ части -- чаевые плюс приоритет; базовый тариф сети за подпись
# (5000 лампортов) неизбежен и в этот предел не входит, но в суточный расход
# считается полностью.
ПОТОЛОК_КОНТРОЛЯ_НА_СЕРВИС_SOL = 0.001
КЛЮЧ_СЧЁТЧИКА_КОНТРОЛЯ = "lane_control"

# ЗАМОК УЧЁТА КОНТРОЛЕЙ. Веер по сервисам уходит ПАРАЛЛЕЛЬНО, а расход
# считается чтением-изменением-записью одного файла счётчиков. Без замка два
# потока читают одно и то же число и по очереди записывают свой итог: один
# расход исчезает, и это ровно тот "неучтённый расход", из-за которого владелец
# велел рубить полосу. Поймано самопроверкой веера 25.09: из двух контролей в
# счётчике оставался один.
_ЗАМОК_КОНТРОЛЯ = threading.Lock()

# ФАЙЛ СЧЁТА КОНТРОЛЕЙ -- СВОЙ, А НЕ ОБЩИЙ counters.json. Общий файл пишут
# чтением-изменением-записью сразу несколько писателей, и один из них -- ДРУГОЙ
# ПРОЦЕСС: сторож продаж, а ещё note_api_result на каждый ответ Bloom. Наш
# внутрипроцессный замок для них не значит ничего: посторонняя запись, начатая
# до нашей, вернёт файл к своему снимку, и суточный расход контролей вместе с
# числом сигналов обнулится. Потолок владельца 0.1 SOL в сутки после каждого
# такого обнуления отсчитывался бы заново -- то есть предел не работал бы.
# Поэтому счёт контролей живёт отдельным файлом и правится под ФАЙЛОВЫМ
# замком: он виден всем процессам на хосте.
ИМЯ_ФАЙЛА_КОНТРОЛЯ = "lane_control_day.json"


def путь_счёта_контроля(состояние):
    """Свой файл счёта рядом с counters.json. Нет пути -- нет файла."""
    п = getattr(состояние, "counters_path", None)
    if п is None:
        return None
    try:
        from pathlib import Path as _P  # noqa: PLC0415

        return _P(п).parent / ИМЯ_ФАЙЛА_КОНТРОЛЯ
    except Exception:  # noqa: BLE001
        return None


class _ФайловыйЗамок:
    """Межпроцессный замок на правку счёта контролей.

    Без него два процесса (детектор и сторож, или два детектора после
    неудачного перезапуска) могут пройти предел одновременно. Не вышло взять
    замок -- работаем без него, но говорим об этом: замок это защита, а не
    условие работы, и молчать о его отсутствии нельзя.
    """

    def __init__(self, путь):
        self.путь = путь
        self.файл = None
        self.почему = None

    def __enter__(self):
        if self.путь is None:
            self.почему = "пути счёта нет -- замок не берётся"
            return self
        try:
            import fcntl  # noqa: PLC0415

            self.путь.parent.mkdir(parents=True, exist_ok=True)
            self.файл = open(str(self.путь) + ".lock", "a+")  # noqa: SIM115
            fcntl.flock(self.файл.fileno(), fcntl.LOCK_EX)
        except Exception as exc:  # noqa: BLE001
            self.почему = f"{type(exc).__name__}: {str(exc)[:120]}"
            self.файл = None
        return self

    def __exit__(self, *_):
        if self.файл is not None:
            try:
                import fcntl  # noqa: PLC0415

                fcntl.flock(self.файл.fileno(), fcntl.LOCK_UN)
            except Exception:  # noqa: BLE001, S110
                pass
            try:
                self.файл.close()
            except Exception:  # noqa: BLE001, S110
                pass
        return False


def _счёт_контроля_читать(состояние) -> dict:
    """Запись счёта контролей: сначала свой файл, потом старый общий.

    Переход со старого места сделан без потери: если своего файла ещё нет, а в
    общих счётчиках сегодняшняя запись есть, берём её как начало. Иначе в день
    перехода потолок начался бы заново.
    """
    п = путь_счёта_контроля(состояние)
    if п is not None and п.exists():
        try:
            return json.loads(п.read_text(encoding="utf-8")) or {}
        except (ValueError, OSError):
            # Битый счёт -- это не повод считать, что расхода не было.
            return {"corrupt": True}
    try:
        с = состояние.counters() or {}
    except Exception as exc:  # noqa: BLE001
        # НЕИЗВЕСТНЫЙ РАСХОД ЗАПРЕЩАЕТ ТРАТИТЬ. Своего файла ещё нет, а старые
        # счётчики не читаются -- значит сколько ушло сегодня, мы не знаем, и
        # это не то же самое, что "ушло ноль".
        return {"corrupt": True, "why_not": f"{type(exc).__name__}"}
    return dict(с.get(КЛЮЧ_СЧЁТЧИКА_КОНТРОЛЯ) or {})


def _счёт_контроля_писать(состояние, з: dict) -> dict:
    п = путь_счёта_контроля(состояние)
    if п is None:
        # Состояние без пути (заглушка в самопроверке) -- пишем как раньше, в
        # общие счётчики: на хосте этот путь есть всегда.
        try:
            с = состояние.counters() or {}
            с[КЛЮЧ_СЧЁТЧИКА_КОНТРОЛЯ] = з
            состояние.save_counters(с)
            return {"ok": True}
        except Exception as exc:  # noqa: BLE001
            return {"ok": False, "why_not": f"{type(exc).__name__}: {str(exc)[:160]}"}
    try:
        import bloom_exec_state as _ST  # noqa: PLC0415

        _ST.atomic_write_json(п, з)
        return {"ok": True}
    except Exception as exc:  # noqa: BLE001
        return {"ok": False, "why_not": f"{type(exc).__name__}: {str(exc)[:160]}"}


def проверить_и_учесть_контроль(состояние, *, цена_лампорты: int,
                                 сейчас: float | None = None,
                                 новый_сигнал: bool = True) -> dict:
    """Предел и запись расхода -- ОДНИМ неделимым шагом, под замком.

    Порядок именно такой: сначала убедиться, что можно, и сразу же записать
    расход. Между этими двумя действиями не должно влезать ничего -- ни
    соседний поток веера, ни отправка.
    """
    with _ЗАМОК_КОНТРОЛЯ, _ФайловыйЗамок(путь_счёта_контроля(состояние)):
        можно = можно_контроль(состояние, цена_лампорты=цена_лампорты,
                                сейчас=сейчас, новый_сигнал=новый_сигнал)
        if not можно.get("ok"):
            return {"ok": False, "why_not": можно.get("why_not"),
                     "limits": можно.get("state"), "accounted": None}
        учёт = учесть_контроль(состояние, цена_лампорты=цена_лампорты,
                                сейчас=сейчас, новый_сигнал=новый_сигнал)
    return {"ok": bool(учёт.get("ok")), "why_not": учёт.get("why_not"),
             "limits": можно.get("state"), "accounted": учёт}


def контроль_включён() -> bool:
    return (os.environ.get("BLOOM_LANE_CONTROL") or "").strip() == "1"


def цена_контроля_лампорты(*, приоритет_лампорты: int | None = None,
                            чаевые_лампорты: int | None = None) -> int:
    """Во сколько обходится один контроль, если он сядет.

    Считаем ПЕССИМИСТИЧНО и до отправки: приоритет платится за запрошенный
    предел CU целиком, чаевые -- полностью, плюс базовый тариф за подпись.
    Занизить эту цену значит прогрызть потолок 0.03 SOL незаметно.
    """
    п = (приоритет_лампорты if приоритет_лампорты is not None
         else int(round(приоритет_sol() * ЛАМПОРТОВ_В_SOL)))
    ч = (чаевые_лампорты if чаевые_лампорты is not None
         else int(round(чаевые_sol() * ЛАМПОРТОВ_В_SOL)))
    return int(п) + int(ч) + 5000


def _день_utc(сейчас: float | None = None) -> str:
    return time.strftime("%Y%m%d", time.gmtime(сейчас if сейчас else time.time()))


def расход_контроля(состояние, *, сейчас: float | None = None) -> dict:
    """Сколько контролей и на сколько лампортов уже ушло СЕГОДНЯ.

    Сутки -- UTC, как и суточный предел покупок полосы: два разных начала
    суток в одном модуле означали бы, что один предел уже сработал, а второй
    ещё нет, и объяснить это было бы нечем.
    """
    из_ = {"day": _день_utc(сейчас), "n": 0, "signals": 0,
           "spent_lamports": 0, "why_not": None}
    if состояние is None or not hasattr(состояние, "counters"):
        из_["why_not"] = "состояние не умеет считать -- расход контроля неизвестен"
        return из_
    try:
        з = _счёт_контроля_читать(состояние)
    except Exception as exc:  # noqa: BLE001
        из_["why_not"] = f"счёт контролей не прочитан: {type(exc).__name__}"
        return из_
    if з.get("corrupt"):
        из_["why_not"] = ("счёт контролей повреждён -- считаем, что тратить "
                           "нельзя, пока человек не разберётся")
        return из_
    if з.get("day") == из_["day"]:
        из_["n"] = int(з.get("n") or 0)
        # СИГНАЛЫ -- это события "контроль на сигнале", а не транзакции: с
        # веером по сервисам на один сигнал уходит несколько контролей.
        # У прежних записей поля signals нет -- там один контроль и был одним
        # сигналом, поэтому берём n.
        из_["signals"] = int(з.get("signals") if з.get("signals") is not None
                              else з.get("n") or 0)
        из_["spent_lamports"] = int(з.get("spent_lamports") or 0)
    из_["spent_sol"] = из_["spent_lamports"] / ЛАМПОРТОВ_В_SOL
    return из_


def можно_контроль(состояние, *, цена_лампорты: int,
                    сейчас: float | None = None,
                    новый_сигнал: bool = True) -> dict:
    """Пределы контроля: 20 СИГНАЛОВ в сутки И не больше 0.05 SOL. Оба -- до
    отправки.

    ПОЧЕМУ 20 СЧИТАЕТСЯ ПО СИГНАЛАМ, А НЕ ПО ТРАНЗАКЦИЯМ. Предел "не больше
    20 контролей в сутки" владелец назвал, когда контроль был один на сигнал.
    Веер по сервисам (владелец 25.09: "контрольную транзакцию через КАЖДЫЙ
    подключённый сервис") превращает один сигнал в несколько транзакций, и
    при счёте по транзакциям четырёх сервисов хватило бы на четыре сигнала --
    З2 на десяти парах стал бы недостижим. Поэтому счёт 20 -- по событиям
    "контроль на сигнале", а ДЕНЬГИ ограничены как сказано: 0.05 SOL в сутки
    и 0.001 SOL на сервис на сигнал. Потратить больше названного нельзя ни в
    какой трактовке -- меняется только, сколько сигналов в эти деньги влезет.

    Неизвестный расход запрещает отправку: "счётчики не прочитались" не
    имеет права означать "трать дальше".
    """
    р = расход_контроля(состояние, сейчас=сейчас)
    если = None
    потолок = int(round(ПОТОЛОК_РАСХОДА_КОНТРОЛЯ_SOL * ЛАМПОРТОВ_В_SOL))
    if р.get("why_not"):
        если = р["why_not"]
    elif новый_сигнал and р["signals"] >= ЛИМИТ_КОНТРОЛЕЙ_В_СУТКИ:
        если = (f"{р['signals']} сигналов с контролем за сутки при пределе "
                 f"{ЛИМИТ_КОНТРОЛЕЙ_В_СУТКИ}")
    elif р["spent_lamports"] + int(цена_лампорты) > потолок:
        если = (f"расход контроля {(р['spent_lamports'] + int(цена_лампорты)) / ЛАМПОРТОВ_В_SOL} "
                f"SOL вышел бы за потолок {ПОТОЛОК_РАСХОДА_КОНТРОЛЯ_SOL} SOL")
    return {"ok": если is None, "why_not": если, "state": р}


def учесть_контроль(состояние, *, цена_лампорты: int,
                     сейчас: float | None = None,
                     новый_сигнал: bool = True) -> dict:
    """Расход контроля на диск СРАЗУ, ещё до ответа Sender.

    Пессимизм намеренный: транзакция могла уйти и сесть, даже если ответ до
    нас не дошёл. Незаписанный расход -- это тихо прогрызенный потолок.
    """
    if состояние is None or not hasattr(состояние, "counters"):
        return {"ok": False, "why_not": "состояние не умеет считать"}
    try:
        день = _день_utc(сейчас)
        з = _счёт_контроля_читать(состояние)
        if з.get("corrupt"):
            return {"ok": False, "why_not": "счёт контролей повреждён"}
        if з.get("day") != день:
            з = {"day": день, "n": 0, "signals": 0, "spent_lamports": 0}
        было_сигналов = int(з.get("signals") if з.get("signals") is not None
                             else з.get("n") or 0)
        з["n"] = int(з.get("n") or 0) + 1
        з["signals"] = было_сигналов + (1 if новый_сигнал else 0)
        з["spent_lamports"] = int(з.get("spent_lamports") or 0) + int(цена_лампорты)
        з["last_ts"] = сейчас if сейчас else time.time()
        зап = _счёт_контроля_писать(состояние, з)
        if not зап.get("ok"):
            return {"ok": False, "why_not": зап.get("why_not")}
        return {"ok": True, "state": з}
    except Exception as exc:  # noqa: BLE001
        return {"ok": False, "why_not": f"{type(exc).__name__}: {str(exc)[:160]}"}


def отметить_сигнал_контроля(состояние, *, сейчас: float | None = None) -> dict:
    """Один сигнал -- одна отметка в суточном счёте СИГНАЛОВ.

    Зачем отдельно от учёта денег. Предел владельца "20 в сутки" считается по
    сигналам, а на сигнале уходит веер из нескольких транзакций. Пока был
    отдельный "основной" контроль, сигнал отмечал он; его убрали (Helius уже в
    веере), и без этой отметки предел 20 не срабатывал бы ВООБЩЕ -- сутки
    контролей ограничивались бы только деньгами. Проверка и запись -- один шаг
    под тем же замком, что и деньги: иначе два сигнала в двух потоках оба
    увидят "сигналов 19" и оба пройдут.
    """
    сейчас = сейчас if сейчас is not None else time.time()
    with _ЗАМОК_КОНТРОЛЯ, _ФайловыйЗамок(путь_счёта_контроля(состояние)) as фз:
        р = расход_контроля(состояние, сейчас=сейчас)
        if р.get("why_not"):
            return {"ok": False, "why_not": р["why_not"], "state": р}
        if р["signals"] >= ЛИМИТ_КОНТРОЛЕЙ_В_СУТКИ:
            return {"ok": False, "state": р,
                     "why_not": (f"{р['signals']} сигналов с контролем за сутки "
                                  f"при пределе {ЛИМИТ_КОНТРОЛЕЙ_В_СУТКИ}")}
        try:
            день = _день_utc(сейчас)
            з = _счёт_контроля_читать(состояние)
            if з.get("day") != день:
                з = {"day": день, "n": 0, "signals": 0, "spent_lamports": 0}
            з["signals"] = int(з.get("signals") if з.get("signals") is not None
                                else з.get("n") or 0) + 1
            з["last_signal_ts"] = сейчас
            зап = _счёт_контроля_писать(состояние, з)
            if not зап.get("ok"):
                return {"ok": False,
                         "why_not": f"отметка сигнала не записана: {зап.get('why_not')}"}
            return {"ok": True, "state": з, "lock_why_not": фз.почему}
        except Exception as exc:  # noqa: BLE001
            return {"ok": False,
                     "why_not": f"отметка сигнала не записана: {type(exc).__name__}"}


def собрать_контроль(*, наш_кошелёк: str, cu_units: int = 400_000,
                      приоритет_лампорты: int | None = None,
                      чаевые_лампорты: int | None = None,
                      семя: str | None = None,
                      сервис: str | None = None) -> dict:
    """Пустая транзакция ТЕМ ЖЕ путём: приоритет, перевод нуля себе, чаевые.

    Пула она не касается вовсе -- в этом и смысл: всё, что отличает её от
    покупки, это отсутствие свопа. Если она садится раньше -- мешает пул.

    СЕРВИС задаёт, КОМУ чаевые и сколько: адрес и минимум берутся из реестра
    отправителей (data/senders.json, собран из их документации). Без сервиса
    всё как раньше -- счёт Helius Sender из списка репозитория. У контроля
    приоритет по умолчанию НУЛЕВОЙ, когда сервис задан: пустая транзакция за
    место в пуле не соперничает, и платить за приоритет ей незачем -- мы мерим
    путь отправителя, а не очередь.
    """
    из_ = {"ok": False, "why_not": None, "tip_account": None, "build_ms": None}
    t0 = time.perf_counter()
    if not наш_кошелёк:
        из_["why_not"] = "кошелёк полосы не задан -- контроль собирать не на что"
        return из_
    реестр_сервиса = None
    if сервис:
        try:
            import bloom_senders as SS  # noqa: PLC0415
        except Exception as exc:  # noqa: BLE001
            из_["why_not"] = f"реестр отправителей не загружен: {type(exc).__name__}"
            return из_
        реестр_сервиса = SS.реестр().get(сервис)
        if not реестр_сервиса:
            из_["why_not"] = f"отправителя {сервис} нет в реестре"
            return из_
        if приоритет_лампорты is None:
            приоритет_лампорты = 0
        if чаевые_лампорты is None:
            чаевые_лампорты = SS.минимум_чаевых(сервис)
    приоритет_лампорты = (приоритет_лампорты if приоритет_лампорты is not None
                          else int(round(приоритет_sol() * ЛАМПОРТОВ_В_SOL)))
    чаевые_лампорты = (чаевые_лампорты if чаевые_лампорты is not None
                       else int(round(чаевые_sol() * ЛАМПОРТОВ_В_SOL)))
    # ПРЕДЕЛ НА СЕРВИС НА СИГНАЛ -- до сборки: управляемая часть (чаевые плюс
    # приоритет) не имеет права выйти за 0.001 SOL.
    if сервис:
        управляемое = int(приоритет_лампорты) + int(чаевые_лампорты)
        потолок_с = int(round(ПОТОЛОК_КОНТРОЛЯ_НА_СЕРВИС_SOL * ЛАМПОРТОВ_В_SOL))
        if управляемое > потолок_с:
            из_["why_not"] = (f"контроль через {сервис}: чаевые и приоритет "
                               f"{управляемое} лампортов выше предела {потолок_с} "
                               "на сервис на сигнал")
            return из_
    try:
        _, _, _, B = _модули()
        from solders.hash import Hash  # noqa: PLC0415
        from solders.message import MessageV0  # noqa: PLC0415
        from solders.pubkey import Pubkey  # noqa: PLC0415
        from solders.signature import Signature  # noqa: PLC0415
        from solders.transaction import VersionedTransaction  # noqa: PLC0415
    except Exception as exc:  # noqa: BLE001
        из_["why_not"] = f"модули сборки контроля не загружены: {type(exc).__name__}"
        return из_
    if сервис:
        import bloom_senders as SS  # noqa: PLC0415

        чаевые = SS.счёт_чаевых(сервис, семя=семя)
        разрешённые = set((реестр_сервиса or {}).get("tip_accounts") or [])
        if not чаевые or чаевые not in разрешённые:
            из_["why_not"] = (f"адрес чаевых не из списка сервиса {сервис} -- "
                               "сборка отменена")
            return из_
    else:
        чаевые = выбрать_чаевые(семя)
        if чаевые not in TIP_ACCOUNTS:
            из_["why_not"] = "адрес чаевых не из списка счетов Sender -- сборка отменена"
            return из_
    try:
        инструкции = [B.cu_limit(cu_units),
                      B.cu_price(цена_единицы_cu(приоритет_лампорты, cu_units)),
                      # ПЕРЕВОД НУЛЯ СЕБЕ. Ни пула, ни чужого адреса.
                      B.sol_transfer(наш_кошелёк, наш_кошелёк, 0),
                      B.sol_transfer(наш_кошелёк, чаевые, чаевые_лампорты)]
        сообщение = MessageV0.try_compile(Pubkey.from_string(наш_кошелёк),
                                           инструкции, [], Hash.default())
        подписей = сообщение.header.num_required_signatures
        vtx = VersionedTransaction.populate(сообщение,
                                             [Signature.default()] * подписей)
        сырое = bytes(vtx)
    except Exception as exc:  # noqa: BLE001
        из_["why_not"] = f"сборка контроля: {type(exc).__name__}: {str(exc)[:160]}"
        return из_
    import base64 as _b64  # noqa: PLC0415
    из_.update(ok=True, tx_base64=_b64.b64encode(сырое).decode(), size=len(сырое),
               tip_account=чаевые, priority_lamports=приоритет_лампорты,
               tip_lamports=чаевые_лампорты, sender=сервис,
               cost_lamports=цена_контроля_лампорты(
                   приоритет_лампорты=приоритет_лампорты,
                   чаевые_лампорты=чаевые_лампорты),
               build_ms=round((time.perf_counter() - t0) * 1000, 3))
    return из_


