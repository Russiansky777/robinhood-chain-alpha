def чаевые_пула(семя: str | None = None, *, сервисы: list | None = None,
                 путь: str | None = None) -> dict:
    """Кому и сколько чаевых в боевой покупке пула.

    Адрес каждого сервиса -- ТОЛЬКО из его списка в реестре: перевод на адрес
    не из списка это перевод неизвестно кому. Сумма сверяется с потолком
    владельца ДО сборки; вылезли за потолок -- пул не собирается вовсе, а не
    "урежем кому-нибудь": чаевые ниже минимума сервиса означают, что этот
    сервис молча выбросит транзакцию, и платить их бессмысленно.
    """
    из_ = {"ok": False, "tips": [], "total_lamports": 0, "senders": [],
            "why_not": None}
    try:
        import bloom_senders as SS  # noqa: PLC0415
    except Exception as exc:  # noqa: BLE001
        из_["why_not"] = f"реестр отправителей не загружен: {type(exc).__name__}"
        return из_
    имена = сервисы if сервисы is not None else SS.подключённые(путь)
    if not имена:
        из_["why_not"] = "подключённых отправителей нет -- пулу нечего слать"
        return из_
    пары = []
    всего = 0
    for имя in имена:
        з = (SS.реестр(путь) or {}).get(имя) or {}
        адрес = SS.счёт_чаевых(имя, семя=семя, путь=путь)
        разрешённые = set(з.get("tip_accounts") or [])
        if not адрес or адрес not in разрешённые:
            из_["why_not"] = (f"адрес чаевых не из списка сервиса {имя} -- "
                               "пул не собирается")
            return из_
        лам = SS.минимум_чаевых(имя, путь=путь)
        пары.append((адрес, int(лам)))
        всего += int(лам)
        из_["senders"].append({"sender": имя, "tip_account": адрес,
                                "tip_lamports": int(лам)})
    потолок = int(round(ПОТОЛОК_ЧАЕВЫХ_ПУЛА_SOL * ЛАМПОРТОВ_В_SOL))
    if всего > потолок:
        из_["why_not"] = (f"суммарные чаевые пула {всего} лампортов выше потолка "
                           f"{потолок} ({ПОТОЛОК_ЧАЕВЫХ_ПУЛА_SOL} SOL на сделку) "
                           "-- пул не собирается")
        из_["total_lamports"] = всего
        return из_
    из_.update(ok=True, tips=пары, total_lamports=всего)
    из_["total_sol"] = всего / ЛАМПОРТОВ_В_SOL
    return из_


def подогнать_чаевые_под_размер(*, сборщик, чаевые: list,
                                 сервисы: list | None = None) -> dict:
    """Убрать САМЫХ ДОРОГИХ сервисов, пока транзакция не влезет в пакет сети.

    Отдельной функцией, потому что это правило про деньги и его надо проверять:
    убранному сервису транзакция НЕ отправляется (чаевые ниже его минимума
    значат, что он молча её выбросит, и отправка была бы ложным замером), а
    если не влезло даже с одними чаевыми -- пул на этой сделке пропускается, но
    ПОКУПКА ОСТАЁТСЯ: терять сделку из-за замера нельзя.

    ПОЧЕМУ УБИРАЕМ ДОРОГИХ, А НЕ "С КОНЦА". Место в пакете одинаково стоит для
    любого сервиса, а чаевые -- нет: у Jito минимум 1 000 лампортов, у Helius,
    Nozomi и Astralane -- миллион. Убирая с конца алфавита, мы выбросили бы
    сначала Nozomi, а потом Jito -- то есть самого дешёвого и того, кому по З1
    платят те, кто садится в S+0 впереди нас. При равной цене порядок обратный
    алфавитному -- только чтобы решение было одинаковым от прогона к прогону.

    сборщик(чаевые_списком) -> результат собрать(); None значит обычный путь
    полосы с одними чаевыми.
    """
    из_ = {"сб": None, "чаевые": list(чаевые or []), "сервисы": list(сервисы or []),
            "убраны": [], "why_not": None, "пул": True}
    сб = сборщик(из_["чаевые"] or None)
    из_["сб"] = сб
    if not сб.get("too_big"):
        return из_
    подгон = list(из_["чаевые"])
    серв = list(из_["сервисы"])
    while подгон and сб.get("too_big"):
        # Кого убрать: самые дорогие чаевые, при равенстве -- обратный алфавит.
        порядок = sorted(range(len(подгон)),
                          key=lambda и: (-int(подгон[и][1]),
                                          серв[и] if и < len(серв) else ""),
                          reverse=False)
        # sorted по (-цена, имя) даёт самых дорогих первыми; при равной цене
        # берём ПОСЛЕДНЕГО по алфавиту, поэтому переворачиваем равную группу.
        дорогая_цена = -int(подгон[порядок[0]][1])
        равные = [и for и in порядок if -int(подгон[и][1]) == дорогая_цена]
        кого = равные[-1] if len(равные) > 1 else порядок[0]
        из_["убраны"].append(серв[кого] if кого < len(серв) else "?")
        подгон = [п for и, п in enumerate(подгон) if и != кого]
        серв = [с for и, с in enumerate(серв) if и != кого]
        сб = сборщик(подгон or None)
    из_["сб"] = сб
    if подгон:
        из_.update(чаевые=подгон, сервисы=серв,
                    why_not=("по размеру пакета сети убраны сервисы: "
                              + ", ".join(из_["убраны"])))
    else:
        из_.update(чаевые=[], сервисы=[], пул=False,
                    why_not=("покупка не влезает в пакет сети даже с одними "
                              "чаевыми -- пул на этой сделке пропущен, покупка "
                              "идёт обычным путём полосы"))
    return из_


def собрать(*, tx_источника: dict, источник: str, минт: str, наш_кошелёк: str,
             лампорты: int, проскальзывание: float = 0.35,
             cu_units: int = 400_000, приоритет_лампорты: int = 1_000_000,
             чаевые_лампорты: int = 1_000_000, семя: str | None = None,
             чаевые_списком: list | None = None) -> dict:
    """Наша покупка одной транзакцией: своп + приоритет + чаевые Sender.

    Возвращает НЕПОДПИСАННУЮ транзакцию. Ни подписи, ни отправки здесь нет
    намеренно: собрать -- дёшево и безопасно, а подпись это уже деньги.
    """
    из_ = {"ok": False, "why_not": None, "pool_program": None, "min_out": None,
            "expected_out": None, "tip_account": None, "build_ms": None}
    t0 = time.perf_counter()
    # ПОТОЛОК И КОШЕЛЁК -- ДО всякой работы. Проверять их после сборки
    # бессмысленно: собранную транзакцию уже можно подписать.
    if наш_кошелёк != кошелёк_полосы():
        из_["why_not"] = ("сборка не на кошелёк полосы: "
                           f"{str(наш_кошелёк)[:12]} вместо {кошелёк_полосы()[:12]}")
        return из_
    if not isinstance(лампорты, int) or лампорты <= 0:
        из_["why_not"] = f"размер не положительное целое: {лампорты!r}"
        return из_
    if лампорты > потолок_лампортов():
        из_["why_not"] = (f"размер {лампорты / ЛАМПОРТОВ_В_SOL} SOL выше потолка "
                           f"полосы {ПОТОЛОК_РАЗМЕРА_SOL} SOL")
        return из_
    try:
        C, PP, SB, B = _модули()
    except Exception as exc:  # noqa: BLE001
        # ИМЯ НЕДОСТАЮЩЕГО МОДУЛЯ -- В ПРИЧИНУ. Без него "ModuleNotFoundError"
        # не отличить от десятка других: ровно на этом сухой прогон 25.09
        # сказал "модули не загружены" и не сказал, какие. Имена модулей и
        # пакетов -- не секрет, в отличие от ключей.
        из_["why_not"] = (f"модули сборки не загружены: {type(exc).__name__}: "
                           f"{str(exc)[:120]}")
        return из_
    try:
        пул = C.identify_pool(tx_источника, источник, минт)
        if not пул.get("ok"):
            из_["why_not"] = f"пул: {пул.get('why_not')}"
            return из_
        прог = PP.pool_program(tx_источника, пул["pool_vault"], SB._labels())["pool_program"]
        из_["pool_program"] = прог
        if прог not in {getattr(B, имя) for имя in ПУЛЫ_ПОЛОСЫ}:
            из_["why_not"] = f"тип пула вне полосы: {прог}"
            return из_
        tpl = B.extract_template(tx_источника, прог, пул["pool_vault"])
        if not tpl.get("ok"):
            из_["why_not"] = f"шаблон: {tpl.get('why_not')}"
            return из_
        mv = B.mints_and_vaults(tpl, tx_источника)
        if not mv or mv.get("quote_mint") != C.WSOL:
            из_["why_not"] = "котировка пула не SOL -- полоса только одношаговая"
            return из_
        мо = B.min_out_from_reserves(tpl, tx_источника, лампорты, проскальзывание)
        if not мо.get("ok"):
            # Без минимума отправлять нельзя: это покупка по любой цене.
            из_["why_not"] = f"минимум не выдаётся: {мо.get('why_not')}"
            return из_
        # Флага ok мало: значение минимума тоже обязано быть положительным.
        # min_out=0 -- это и есть "куплю по любой цене", только под видом
        # посчитанного числа.
        if not isinstance(мо.get("min_out"), int) or мо["min_out"] <= 0:
            из_["why_not"] = f"минимум не положителен: {мо.get('min_out')!r}"
            return из_
        if чаевые_списком:
            # БОЕВОЙ ПУЛ: чаевые каждому подключённому сервису. Получателей и
            # сумму проверил чаевые_пула(); здесь ещё раз убеждаемся, что ни
            # один адрес не пустой и сумма не выше потолка -- это деньги, и
            # проверка на пути к ним дешевле разбора потом.
            чаевые = чаевые_списком[0][0]
            сумма_ч = sum(int(л) for _, л in чаевые_списком)
            потолок_ч = int(round(ПОТОЛОК_ЧАЕВЫХ_ПУЛА_SOL * ЛАМПОРТОВ_В_SOL))
            if any((not а) or int(л) <= 0 for а, л in чаевые_списком):
                из_["why_not"] = "в списке чаевых пула пустой адрес или ноль -- отказ"
                return из_
            if сумма_ч > потолок_ч:
                из_["why_not"] = (f"суммарные чаевые пула {сумма_ч} выше потолка "
                                   f"{потолок_ч} -- сборка отменена")
                return из_
            чаевые_для_сборки = list(чаевые_списком)
        else:
            чаевые = выбрать_чаевые(семя)
            # ПОЛУЧАТЕЛЬ ЧАЕВЫХ -- ТОЛЬКО СЧЁТ SENDER ИЗ ДОКУМЕНТАЦИИ. Проверка
            # стоит в рабочем пути, а не только в самопроверке: список правится
            # руками, и опечатка в нём отправила бы 0.001 SOL неизвестно кому.
            if чаевые not in TIP_ACCOUNTS:
                из_["why_not"] = ("адрес чаевых не из списка счетов Sender -- "
                                   "сборка отменена")
                return из_
            чаевые_для_сборки = (чаевые, чаевые_лампорты)
        собрано = B.build_buy(
            tpl, tx_источника, user=наш_кошелёк, payer=наш_кошелёк,
            amount_in=лампорты, min_out=мо["min_out"], cu_units=cu_units,
            cu_price_micro=цена_единицы_cu(приоритет_лампорты, cu_units),
            tip=чаевые_для_сборки, wrap_sol=True)
    except Exception as exc:  # noqa: BLE001
        из_["why_not"] = f"сборка: {type(exc).__name__}: {str(exc)[:160]}"
        return из_
    # РАЗМЕР -- ДО ПОДПИСИ И ДО ОТПРАВКИ. Сеть отвергнет пакет больше 1232
    # байт, а для полосы отвергнутая отправка -- упавшая сделка.
    if int(собрано.get("size") or 0) > ПРЕДЕЛ_РАЗМЕРА_TX:
        сколько_ч = (len(чаевые_списком) if чаевые_списком else 1)
        из_["size"] = собрано.get("size")
        из_["why_not"] = (f"транзакция {собрано.get('size')} байт при пределе сети "
                           f"{ПРЕДЕЛ_РАЗМЕРА_TX} (чаевых в ней {сколько_ч}) -- "
                           "отправлять нельзя, сеть отвергнет")
        из_["too_big"] = True
        return из_
    из_.update(ok=True, min_out=мо["min_out"], expected_out=мо.get("expected_out"),
               tip_account=чаевые,
               tips=(list(чаевые_списком) if чаевые_списком else None),
               tips_total_lamports=(sum(int(л) for _, л in чаевые_списком)
                                     if чаевые_списком else чаевые_лампорты),
               tx_base64=собрано["tx_base64"],
               size=собрано["size"], quote_mint=собрано.get("quote_mint"),
               build_ms=round((time.perf_counter() - t0) * 1000, 3))
    return из_


# ------------------------------------------------------------------ подпись

def подписать(tx_base64: str, *, blockhash: str, ожидаемый_кошелёк: str,
               секрет: str | None = None) -> dict:
    """Подставить настоящий blockhash и подписать нашим ключом.

    Сборщик компилирует сообщение с пустым blockhash -- подписывать такое
    бессмысленно, сеть его не примет. Здесь сообщение пересобирается с
    настоящим blockhash и только потом подписывается.

    Публичный ключ сверяется с кошельком позиции ПЕРЕД подписью и на каждой
    сделке. Чужой ключ подписал бы чужой кошелёк: это не предупреждение, а
    запрет.
    """
    из_ = {"ok": False, "why_not": None, "signature": None}
    try:
        import bloom_jupiter_sell as J  # noqa: PLC0415
        from solders.hash import Hash  # noqa: PLC0415
        from solders.message import MessageV0  # noqa: PLC0415
        from solders.transaction import VersionedTransaction  # noqa: PLC0415
    except Exception as exc:  # noqa: BLE001
        из_["why_not"] = f"модули подписи не загружены: {type(exc).__name__}"
        return из_
    # ПУСТОЙ BLOCKHASH -- ОТКАЗ. Сборщик компилирует сообщение с нулевым
    # хешем, и он же -- законный Hash.default(). Подписать такую транзакцию
    # можно, отправить тоже, а сеть её не примет: деньги на чаевые и
    # приоритет при этом уже потрачены. Проверка стоит ДО подписи.
    НУЛЕВОЙ = "1" * 32
    if not blockhash or str(blockhash) == НУЛЕВОЙ or set(str(blockhash)) == {"1"}:
        из_["why_not"] = "blockhash пустой -- такую транзакцию сеть не примет"
        return из_
    свой = J.ключ_от_нашего_кошелька(ожидаемый_кошелёк, секрет)
    if not свой.get("ok"):
        из_["why_not"] = свой.get("why_not") or "ключ не проверен"
        return из_
    try:
        сырой = base64.b64decode(tx_base64)
        tx = VersionedTransaction.from_bytes(сырой)
        msg = tx.message
        новое = MessageV0(msg.header, msg.account_keys, Hash.from_string(blockhash),
                           msg.instructions, msg.address_table_lookups)
        # Разбор ключа -- ОДИН на весь репозиторий, из dbot_rescue: он
        # понимает и base58, и массив байтов. Второй разборщик здесь значил
        # бы два разных понимания одного секрета, а это деньги.
        from dbot_rescue import load_rescue_keypair  # noqa: PLC0415
        # Разбор ключа -- в СВОЁМ try, и текст его исключения наружу не
        # уходит: в сообщение об ошибке разбора может попасть сам секрет.
        # Наружу идёт только имя класса исключения.
        try:
            kp = load_rescue_keypair(секрет if секрет is not None else J.ключ_сырой())
        except Exception as exc_ключ:  # noqa: BLE001
            из_["why_not"] = f"ключ не разобрался ({type(exc_ключ).__name__})"
            return из_
        if str(kp.pubkey()) != ожидаемый_кошелёк:
            из_["why_not"] = "публичный ключ не совпал с кошельком -- подпись отменена"
            return из_
        подписанная = VersionedTransaction(новое, [kp])
    except Exception as exc:  # noqa: BLE001
        из_["why_not"] = f"подпись: {type(exc).__name__}: {str(exc)[:160]}"
        return из_
    из_.update(ok=True, signature=str(подписанная.signatures[0]),
               tx_base64=base64.b64encode(bytes(подписанная)).decode())
    return из_


def запустить_тень_симуляции(rpc_call, tx_base64: str | None, *, журнал,
                              метка: dict | None = None) -> bool:
    """Симуляция СВОИМ потоком и только в журнал.

    Зачем отдельно: на пути сделки она стоила 52.95 мс и отняла у нас блок
    (пара 05:11Z -- мы позже Bloom на 11.4 мс). Здесь она уже ничего не
    задерживает: результат никому не нужен для решения, он нужен для разбора.
    Ошибка внутри не выходит наружу -- замер не имеет права уронить сделку.
    """
    if not tx_base64 or rpc_call is None or журнал is None:
        return False

    def работа():
        запись = {"stage": "lane_sim", **(метка or {})}
        t0 = time.perf_counter()
        try:
            _, _, SB, _ = _модули()
            знач = (rpc_call("simulateTransaction",
                             [tx_base64, SB.SIM_OPTS]) or {}).get("value") or {}
            запись.update(SB.classify_sim(знач))
        except Exception as exc:  # noqa: BLE001
            запись["why_not"] = f"{type(exc).__name__}: {str(exc)[:160]}"
        запись["sim_ms"] = round((time.perf_counter() - t0) * 1000, 2)
        try:
            журнал(запись)
        except Exception:  # noqa: BLE001
            pass

    try:
        threading.Thread(target=работа, name="lane-sim", daemon=True).start()
    except Exception:  # noqa: BLE001
        return False
    return True


# ------------------------------------------------------------------ отправка

# ОТПРАВЛЕННЫЕ КЛЮЧИ ОПЕРАЦИЙ. Одна операция -- одна отправка, и точка.
# Повторная сборка по тому же сигналу даёт ДРУГУЮ транзакцию с другой
# подписью, то есть вторую настоящую покупку. Защита здесь, у самой отправки,
# а не у вызывающего: вызывающих может стать больше.
_ОТПРАВЛЕНО: dict = {}
_ЗАМОК = threading.Lock()


def забыть_отправленные() -> None:
    """Только для самопроверки: очистить память отправленных ключей."""
    with _ЗАМОК:
        _ОТПРАВЛЕНО.clear()


def уже_отправляли(ключ: str) -> dict | None:
    with _ЗАМОК:
        з = _ОТПРАВЛЕНО.get(ключ)
    return dict(з) if з else None


def _запомнить_отказ(ключ: str | None, почему: str) -> None:
    """Неудачная отправка тоже занимает ключ операции.

    Повторять её вслепую нельзя: транзакция могла уйти в сеть и не дойти до
    нас ответом. Снимать замок вправе только человек, разобравшись.
    """
    if not ключ:
        return
    with _ЗАМОК:
        _ОТПРАВЛЕНО[ключ] = {"result": None, "why_not": почему}


def остановить_полосу(состояние, причина: str) -> dict:
    """Рубильник ТОЛЬКО полосы. Bloom и тень не трогаются вовсе.

    ПРАВИЛО ВЛАДЕЛЬЦА, уточнённое 25.09: рубильник -- только при РЕАЛЬНОЙ
    УТЕЧКЕ ДЕНЕГ, и утечка перечислена по именам:
      * сумма выше предела;
      * чужой получатель (адрес чаевых не из списка Sender);
      * неучтённый расход (потратили и не записали).
    Расхождение УЧЁТА ИТОГА на одной паре рубильником не является: такая пара
    помечается "итог несчитаем" (отметить_итог_несчитаемым), и полоса
    продолжает работать. Скорость -- слот, место, время -- считается по цепи
    и от учёта итога не зависит вовсе.

    Одна точка на модуль: иначе часть странностей останавливала бы полосу, а
    часть -- нет.
    """
    из_ = {"ok": False, "why": причина}
    if состояние is None or not hasattr(состояние, "set_lane_kill"):
        из_["error"] = "состояние не умеет останавливать полосу"
        return из_
    try:
        из_.update(состояние.set_lane_kill(причина))
    except Exception as exc:  # noqa: BLE001
        из_["error"] = f"{type(exc).__name__}: {str(exc)[:160]}"
    return из_


def отметить_итог_несчитаемым(состояние, cid: str, причина: str) -> dict:
    """Пара, у которой ИТОГ не сходится, помечается и живёт дальше.

    Уточнение владельца 25.09: расхождение учёта на одной паре -- это не
    рубильник. Пара помечается "итог несчитаем", её итог не идёт ни в PnL, ни
    в серию упавших, а полоса продолжает работать. Замер скорости у такой
    пары остаётся годным: слот, место и время считаются по цепи и об учёте
    итога ничего не знают.

    Пометка нужна именно явная. Молча забытая пара в отчёте выглядит как
    сделка с нулевым итогом, то есть как удачная.
    """
    из_ = {"ok": False, "cid": cid, "why": причина}
    if состояние is None or not cid:
        из_["error"] = "нечего помечать: нет состояния или ключа позиции"
        return из_
    try:
        состояние.update_position(cid, result_uncountable=True,
                                   result_uncountable_why=str(причина)[:300],
                                   result_uncountable_ts=time.time())
        из_["ok"] = True
    except Exception as exc:  # noqa: BLE001
        из_["error"] = f"{type(exc).__name__}: {str(exc)[:160]}"
    return из_


def _отправить_пулом(tx_base64: str, *, из_: dict, сервисы: list,
                      ключ_операции: str | None, отправитель=None,
                      таймаут: float = 5.0, состояние=None) -> dict:
    """Одни и те же подписанные байты -- всеми сервисами ПАРАЛЛЕЛЬНО.

    Успех -- это подпись хотя бы от одного: подпись у всех одна и та же (мы её
    сами и считали), поэтому "успел первый" не создаёт второй покупки. Кто
    ответил первым и кто вообще ответил -- в отчёт: это и есть замер пула.
    """
    try:
        import bloom_senders as SS  # noqa: PLC0415
    except Exception as exc:  # noqa: BLE001
        из_["why_not"] = f"реестр отправителей не загружен: {type(exc).__name__}"
        _запомнить_отказ(ключ_операции, из_["why_not"])
        return из_
    t0 = time.perf_counter()
    веер = SS.отправить_всеми(tx_base64, имена=сервисы, отправитель=отправитель,
                               таймаут=таймаут)
    из_["send_ms"] = round((time.perf_counter() - t0) * 1000, 2)
    строки = list((веер.get("results") or {}).values())
    из_["pool"] = {"senders": веер.get("senders"),
                    "ok_senders": веер.get("ok_senders"),
                    "total_ms": веер.get("total_ms"),
                    "signatures": веер.get("signatures"),
                    "one_signature": веер.get("one_signature"),
                    "rows": строки}
    # ПОДПИСЬ ОБЯЗАНА БЫТЬ ОДНА. Байт один и подпись мы считали сами: разные
    # подписи от разных сервисов означают, что кто-то отправил НЕ ТО, что мы
    # подписали. Это денежная странность, а не мелочь -- полоса встаёт до
    # разбора человеком.
    if веер.get("one_signature") is False:
        из_["why_not"] = ("сервисы вернули РАЗНЫЕ подписи "
                           f"{веер.get('signatures')} -- отправлено не то, что мы "
                           "подписали")
        из_["tamper"] = True
        # ЭТО РУБИЛЬНИК, А НЕ ОТКАЗ. Правило владельца 25.09 называет утечкой
        # "чужого получателя" и "неучтённый расход" -- а чужая подпись значит
        # ровно это: в цепь ушла транзакция, которой мы не подписывали, то есть
        # деньги кошелька полосы могли уйти по чужим правилам, и в цепи их две.
        # Отказаться и ждать следующего сигнала было бы приглашением повторить.
        # Bloom и тень при этом работают: рубильник только полосы.
        из_["kill_set"] = остановить_полосу(
            состояние, f"разные подписи от сервисов пула: {из_['why_not']}")
        _запомнить_отказ(ключ_операции, из_["why_not"])
        return из_
    удачные = [с for с in строки if с.get("ok") and с.get("signature")]
    if not удачные:
        причины = "; ".join(f"{с.get('sender')}: {с.get('why_not')}"
                             for с in строки) or "ни один сервис не ответил"
        из_["why_not"] = f"пул не довёз: {причины}"[:400]
        _запомнить_отказ(ключ_операции, из_["why_not"])
        return из_
    первый = min(удачные, key=lambda с: (с.get("send_ms") or 1e9))
    подпись = первый.get("signature")
    из_.update(ok=True, sent=True, result=подпись, http=первый.get("http"),
               pool_winner=первый.get("sender"))
    if ключ_операции:
        with _ЗАМОК:
            _ОТПРАВЛЕНО[ключ_операции] = {"result": подпись, "why_not": None}
    return из_


def отправить(tx_base64: str, *, состояние=None, ключ_операции: str | None = None,
               минт: str | None = None, лампорты: int | None = None,
               источник_подпись: str | None = None,
               источник_слот: int | None = None,
               адрес: str | None = None, таймаут: float = 5.0,
               отправитель=None, сейчас: float | None = None,
               без_учёта: bool = False, сервисы: list | None = None,
               группа: str | None = None) -> dict:
    """Одна отправка в Helius Sender. Метод и параметры -- из документации.

    Sender не тратит кредиты тарифа и берёт плату чаевыми в SOL; предел 50
    транзакций в секунду. skipPreflight=true и maxRetries=0 стоят так же,
    как в примере документации: предполётная проверка стоит задержки, а
    повторы делаем сами, зная своё состояние.

    Без BLOOM_OWN_SEND_LIVE=1 не уходит ничего. Это не настройка скорости,
    а рубильник живых денег.
    """
    из_ = {"ok": False, "sent": False, "why_not": None, "http": None,
            "result": None, "send_ms": None, "cid": None}
    if not живьём():
        из_["why_not"] = "BLOOM_OWN_SEND_LIVE не равен 1 -- отправка выключена"
        return из_
    # ВСЁ, ЧТО РЕШАЕТ ПРО ДЕНЬГИ, -- ПОД ОДНИМ ЗАМКОМ И ДО СЕТИ: ключ
    # операции, рубильник, пределы полосы и резервирующая запись позиции.
    # Раньше пределы проверял вызывающий, а замок держал только ключ
    # операции; два сигнала в двух потоках оба видели "открытых 0" и оба
    # отправляли -- предел "одна открытая" не работал именно тогда, когда он
    # нужен. Теперь позиция ложится на диск ЗДЕСЬ, внутри замка, и второй
    # поток видит её как открытую.
    with _ЗАМОК:
        if ключ_операции:
            прежнее = _ОТПРАВЛЕНО.get(ключ_операции)
            if прежнее is not None:
                из_["why_not"] = (f"по ключу операции {ключ_операции} уже отправляли: "
                                   f"{прежнее.get('result') or прежнее.get('why_not')}")
                из_["duplicate"] = True
                return из_
        if not без_учёта:
            if состояние is None:
                из_["why_not"] = ("состояние не передано -- ни рубильник, ни пределы "
                                   "полосы проверить нечем, отправка отменена")
                return из_
            убит, почему_kill = состояние.kill_active()
            if not убит and hasattr(состояние, "lane_kill_active"):
                убит, почему_kill = состояние.lane_kill_active()
            if убит:
                из_["why_not"] = f"рубильник: {почему_kill}"
                из_["kill"] = True
                return из_
            try:
                позиции = состояние.positions()
            except Exception as exc:  # noqa: BLE001
                из_["why_not"] = (f"позиции не прочитаны ({type(exc).__name__}) -- "
                                   "пределы полосы не проверить")
                return из_
            гейт = можно_отправлять(позиции, сейчас=сейчас, группа=группа,
                                      размер_лампорты=лампорты)
            if not гейт.get("ok"):
                из_["why_not"] = f"предел полосы: {гейт.get('why_not')}"
                из_["lane_state"] = гейт.get("state")
                return из_
            if not минт or not isinstance(лампорты, int) or лампорты <= 0:
                из_["why_not"] = ("для записи позиции полосы нужны минт и размер "
                                   f"(минт {минт!r}, лампорты {лампорты!r})")
                return из_
            if лампорты > потолок_лампортов():
                из_["why_not"] = (f"размер {лампорты} лампортов выше потолка полосы "
                                   f"{потолок_лампортов()} -- отправка отменена")
                # СЛОВО ВЛАДЕЛЬЦА 25.09: сумма выше предела -- это не просто
                # отказ, это денежная странность. Полоса встаёт до разбора
                # человеком; Bloom и тень продолжают работать.
                из_["kill_set"] = остановить_полосу(
                    состояние, f"сумма выше предела: {из_['why_not']}")
                return из_
            # РЕЗЕРВИРУЮЩАЯ ЗАПИСЬ. Позиция с state=intent и меткой полосы --
            # это и есть бронь: её видит и второй поток, и сторож, и она
            # остаётся на диске, если процесс упадёт между отправкой и ответом.
            cid = f"lane-{ключ_операции or int(time.time() * 1000)}"
            try:
                состояние.write_intent(
                    client_order_id=cid, mint=минт, source_sig=источник_подпись or "",
                    source_slot=источник_слот, sol_in=лампорты / ЛАМПОРТОВ_В_SOL,
                    pool=None, program=None, taxed=None, tax_bps=None,
                    mode=ST.MODE_LIVE, sell_after_s=СРОК_ПРОДАЖИ_S, lane=МЕТКА,
                    # ГРУППА ИСТОЧНИКА -- В ПОЗИЦИЮ. По ней считаются деньги:
                    # у speed_only свой потолок и свой стоп, и в общий итог её
                    # сделки не идут (слово владельца).
                    lane_group=(группа or None))
            except Exception as exc:  # noqa: BLE001
                из_["why_not"] = (f"позиция полосы не записана ({type(exc).__name__}) "
                                   "-- без записи отправлять нельзя: сторож о ней не "
                                   "узнает")
                return из_
            из_["cid"] = cid
        if ключ_операции:
            _ОТПРАВЛЕНО[ключ_операции] = {"result": None, "why_not": "отправка идёт"}
    # БОЕВОЙ ПУЛ: те же подписанные байты уходят ВСЕМИ сервисами сразу.
    # Гейт выше (ключ операции, рубильник, пределы, бронь) не меняется ни на
    # строку -- меняется только дорога. Подпись одна, поэтому в цепь транзакция
    # сядет один раз, кто бы её ни довёз.
    if сервисы:
        return _отправить_пулом(tx_base64, из_=из_, сервисы=сервисы,
                                 ключ_операции=ключ_операции,
                                 отправитель=отправитель, таймаут=таймаут,
                                 состояние=состояние)
    тело = {"jsonrpc": "2.0", "id": str(int(time.time() * 1000)),
             "method": "sendTransaction",
             "params": [tx_base64, {"encoding": "base64", "skipPreflight": True,
                                     "maxRetries": 0}]}
    t0 = time.perf_counter()
    try:
        if отправитель is None:
            import requests  # noqa: PLC0415

            def отправитель(url, данные, таймаут_):  # noqa: E306
                r = requests.post(url, json=данные, timeout=таймаут_,
                                  headers={"Content-Type": "application/json"})
                return r.status_code, r.text
        код, текст = отправитель(адрес or адрес_сендера(), тело, таймаут)
    except Exception as exc:  # noqa: BLE001
        из_["why_not"] = f"сеть: {type(exc).__name__}: {str(exc)[:160]}"
        из_["send_ms"] = round((time.perf_counter() - t0) * 1000, 2)
        _запомнить_отказ(ключ_операции, из_["why_not"])
        return из_
    из_["send_ms"] = round((time.perf_counter() - t0) * 1000, 2)
    из_["http"] = код
    try:
        ответ = json.loads(текст)
    except ValueError:
        из_["why_not"] = f"ответ не JSON: {текст[:160]}"
        return из_
    if isinstance(ответ, dict) and ответ.get("error"):
        из_["why_not"] = f"Sender отказал: {json.dumps(ответ['error'], ensure_ascii=False)[:200]}"
        # ОТКАЗ ОПРЕДЕЛЁННЫЙ: узел разобрал транзакцию и отверг её -- в цепь
        # она не попала. Только на таком отказе бронь можно закрывать. Все
        # прочие неудачи (сеть, не-JSON, 200 без подписи) неопределённы:
        # транзакция могла уйти, и закрывать бронь по ним нельзя.
        из_["definite_refusal"] = True
        return из_
    # УСПЕХ -- ЭТО HTTP 200 И ПОДПИСЬ В ОТВЕТЕ. Без подписи мы не знаем, что
    # ушло, и считать такую отправку удачной значит потом искать в цепи то,
    # чего, возможно, нет.
    подпись = (ответ or {}).get("result") if isinstance(ответ, dict) else None
    if код != 200:
        из_["why_not"] = f"Sender ответил кодом {код}, а не 200"
        return из_
    if not isinstance(подпись, str) or not подпись:
        из_["why_not"] = "Sender не вернул подпись -- отправка не подтверждена"
        return из_
    из_.update(ok=True, sent=True, result=подпись)
    if ключ_операции:
        with _ЗАМОК:
            _ОТПРАВЛЕНО[ключ_операции] = {"result": подпись, "why_not": None}
    return из_


# ------------------------------------------------------------------ пределы полосы

# Срок продажи позиции полосы. Слово владельца: сторожем через 28.8 с, как у
# боевых покупок -- сравнение честно только при одинаковом горизонте.
СРОК_ПРОДАЖИ_S = ST.env_float("BLOOM_OWN_SEND_SELL_AFTER_S", 28.8)

# ПРЕДЕЛЫ ПОЛОСЫ. Сводный промпт владельца 25.09 15:45 Madrid, пункт 3:
# "Одна открытая позиция, 50 сделок в сутки; стоп -0.3 SOL за сутки или 5
# упавших подряд". До этого было 20 сделок, -0.1 SOL и 3 упавших.
ЛИМИТ_ОТКРЫТЫХ = 1
ЛИМИТ_В_СУТКИ = 50
СТОП_ПОДРЯД_УПАВШИХ = 5
СТОП_УБЫТОК_SOL = 0.3
МЕТКА = ST.МЕТКА_ПОЛОСЫ        # одно написание на весь репозиторий

# ГРУППА СКОРОСТИ (пункт 1.2). Её сделки в деньги не входят, у них свой
# суточный потолок РАСХОДА (покупки плюс чаевые) и свой стоп. Значения берутся
# из файла групп, здесь -- только откат на случай, если файла нет.
ГРУППА_СКОРОСТИ = "speed_only"
ПОТОЛОК_СУТОК_СКОРОСТИ_SOL = 0.2
СТОП_УБЫТОК_СКОРОСТИ_SOL = 0.15


# БАЗОВЫЙ ТАРИФ СЕТИ ЗА ПОДПИСЬ. 5000 лампортов за подпись -- цена, которую
# Solana берёт с любой транзакции; у нас подпись одна.
БАЗОВЫЙ_ТАРИФ_ЛАМПОРТОВ = 5000


def стоимость_сделки_sol(позиция: dict) -> float:
    """Сколько эта покупка стоила кошельку полосы СВЕРХ купленной суммы.

    Чаевые (в пуле -- всем сервисам сразу), приоритет и базовый тариф сети.
    Берётся из полей самой позиции: их пишет отправка, и другого честного
    источника нет -- считать по нашим настройкам значило бы считать по тому,
    что мы хотели заплатить, а не по тому, что записали при отправке.

    Расход контролей (веер) сюда НЕ входит: у него свой суточный потолок и
    свой файл счёта, и это замер, а не сделка.
    """
    п = позиция or {}
    из_ = 0.0
    чаевые = п.get("lane_tips_total_sol")
    if чаевые:
        из_ += float(чаевые)
    приоритет = п.get("lane_priority_lamports")
    if приоритет:
        из_ += float(приоритет) / ЛАМПОРТОВ_В_SOL
    # Тариф платится, только если транзакция ушла: у брони (intent, до
    # отправки) не списано ничего.
    if п.get("lane_signature") or п.get("ts_sent"):
        из_ += БАЗОВЫЙ_ТАРИФ_ЛАМПОРТОВ / ЛАМПОРТОВ_В_SOL
    return round(из_, 9)


def состояние_полосы(позиции: dict, *, сейчас: float | None = None,
                      группа: str | None = None) -> dict:
    """Что полоса сделала за сутки и можно ли ей ещё.

    Считается по ПОЗИЦИЯМ с меткой полосы, а не по журналу: журнал говорит о
    намерениях, а пределы владельца -- про сделки. Упавшей считается покупка,
    которая по цепи не села (chain_ok=false), а не та, что ушла в минус:
    три убыточных подряд -- это рынок, три упавших -- это мы.
    """
    сейчас = сейчас if сейчас is not None else time.time()
    сутки_назад = сейчас - 86400.0
    все_свои = [p for p in (позиции or {}).values()
                if (p or {}).get("lane") == МЕТКА]
    # ГРУППЫ СЧИТАЮТСЯ ОТДЕЛЬНО. Владелец 25.09: сделки speed_only "в деньги не
    # входят", у них свой потолок и свой стоп. Значит суточный счёт и убыток
    # считаются ПО ГРУППЕ: группа скорости -- сама по себе, остальные -- вместе
    # (BATCH-3/5 и 38 кошельков пункта 1.1 идут в одни деньги).
    def своя(p):
        г = (p or {}).get("lane_group")
        if группа == ГРУППА_СКОРОСТИ:
            return г == ГРУППА_СКОРОСТИ
        return г != ГРУППА_СКОРОСТИ

    свои = [p for p in все_свои if своя(p)]
    за_сутки = [p for p in свои if float(p.get("ts_intent") or 0) >= сутки_назад]
    # А ВОТ ОТКРЫТАЯ ПОЗИЦИЯ СЧИТАЕТСЯ ПО ВСЕМ ГРУППАМ СРАЗУ: кошелёк у полосы
    # один, и две покупки одновременно он не вынесет, из какой бы группы они ни
    # пришли. Предел "одна открытая" -- про кошелёк, а не про учёт.
    открытых = [p for p in все_свои
                if p.get("state") not in (ST.STATE_CLOSED, "unsold", "closed")]
    по_времени = sorted(за_сутки, key=lambda p: float(p.get("ts_intent") or 0))
    подряд = 0
    for p in reversed(по_времени):
        if p.get("chain_ok") is False:
            подряд += 1
        elif p.get("chain_ok") is True:
            break
    итог_sol = 0.0
    расход_сделок_sol = 0.0
    for p in за_сутки:
        # РАСХОД НА САМУ ОТПРАВКУ СЧИТАЕТСЯ ВСЕГДА -- даже у несчитаемой пары и
        # даже у покупки, которая не села: чаевые и приоритет с кошелька уже
        # ушли. Стоп владельца -- "-0.1 SOL в сутки", и это про деньги
        # кошелька, а не про разницу цен.
        расход_сделок_sol += стоимость_сделки_sol(p)
        # ИТОГ НЕСЧИТАЕМОЙ ПАРЫ В PnL НЕ ИДЁТ (уточнение владельца 25.09):
        # посчитать его нечем, а ноль читался бы как "вышли в ноль".
        if p.get("result_uncountable"):
            continue
        вх = p.get("sol_in")
        наз = (p.get("closed_sol_net")
               if p.get("closed_sol_net") is not None
               else (p.get("last_sell_outcome") or {}).get("sol_delta_net"))
        if вх and наз is not None:
            итог_sol += float(наз) - float(вх)
    # ЧТО ИМЕННО СРАВНИВАЕТСЯ С ПОРОГОМ. Раньше это была только разница
    # "продали минус купили", то есть стоп не видел ни чаевых, ни приоритета,
    # ни базового тарифа. С боевым пулом чаевые платятся КАЖДОМУ сервису (до
    # 0.005 SOL на сделку по слову владельца), и двадцать сделок могли увести
    # кошелёк на 0.1 SOL мимо стопа, который при этом показывал бы "0.0".
    # Поэтому к итогу прибавляется расход на отправку -- он всегда в минус.
    итог_с_расходом = итог_sol - расход_сделок_sol
    несчитаемых = [p for p in за_сутки if p.get("result_uncountable")]
    return {"open": len(открытых), "today": len(за_сутки),
            "failed_in_row": подряд,
            # pnl_sol -- ИТОГ С РАСХОДОМ: именно его сравнивает стоп владельца.
            # Разница цен осталась отдельным полем, чтобы было видно, где
            # потеряно: на рынке или на доставке.
            "pnl_sol": round(итог_с_расходом, 9),
            "pnl_trade_sol": round(итог_sol, 9),
            "spend_sol": round(расход_сделок_sol, 9),
            # Несчитаемые считаются ОТДЕЛЬНО и НИЧЕГО не запрещают: они и
            # нужны для того, чтобы такие пары не притворялись удачными.
            "uncountable_today": len(несчитаемых),
            "uncountable_why": [str(p.get("result_uncountable_why") or "")[:80]
                                 for p in несчитаемых][:5],
            "total": len(свои),
            "group": группа or "деньги (все группы кроме скорости)",
            # РАСХОД ЗА СУТКИ вместе с купленной суммой: именно его сравнивает
            # потолок группы скорости (0.2 SOL "покупки плюс чаевые").
            "day_spend_sol": round(
                sum(float(p.get("sol_in") or 0.0) + стоимость_сделки_sol(p)
                    for p in за_сутки), 9)}


def можно_отправлять(позиции: dict, *, kill: bool = False,
                      сейчас: float | None = None,
                      группа: str | None = None,
                      размер_лампорты: int | None = None) -> dict:
    """Пропускать ли ещё одну сделку полосы. Отказ называется словами.

    Пределы зависят от ГРУППЫ ИСТОЧНИКА: у группы скорости свой суточный
    потолок РАСХОДА (0.2 SOL вместе с чаевыми) и свой стоп (-0.15 SOL), а числа
    сделок у неё нет вовсе -- потолок денег кончится раньше. У остальных групп
    пределы владельца: 50 сделок, -0.3 SOL, 5 упавших подряд.
    """
    с = состояние_полосы(позиции, сейчас=сейчас, группа=группа)
    пг = потолок_группы(группа)
    почему = None
    if kill:
        почему = "рубильник KILL включён"
    elif not включена():
        почему = "полоса выключена (BLOOM_OWN_SEND не равен 1)"
    elif с["open"] >= ЛИМИТ_ОТКРЫТЫХ:
        почему = f"открытых позиций полосы {с['open']} при пределе {ЛИМИТ_ОТКРЫТЫХ}"
    elif пг["per_day"] and с["today"] >= пг["per_day"]:
        почему = f"за сутки уже {с['today']} сделок при пределе {пг['per_day']}"
    elif с["failed_in_row"] >= СТОП_ПОДРЯД_УПАВШИХ:
        почему = (f"{с['failed_in_row']} упавших подряд -- полоса остановлена "
                   "до разбора")
    elif с["pnl_sol"] <= -float(пг["stop_loss_sol"]):
        почему = (f"убыток полосы за сутки {с['pnl_sol']} SOL при пороге "
                   f"-{пг['stop_loss_sol']}"
                   + (f" (группа {группа})" if группа else ""))
    elif пг["day_cap_sol"] is not None:
        # ПОТОЛОК РАСХОДА ГРУППЫ. Считается ВПЕРЁД: к уже потраченному за сутки
        # прибавляется размер этой сделки вместе с предельными чаевыми пула.
        # Проверять по факту значило бы разрешить сделку, которая сама и
        # прогрызает потолок.
        размер = ((размер_лампорты / ЛАМПОРТОВ_В_SOL)
                   if размер_лампорты else размер_sol(группа))
        вперёд = с["day_spend_sol"] + размер + ПОТОЛОК_ЧАЕВЫХ_ПУЛА_SOL
        if вперёд > float(пг["day_cap_sol"]):
            почему = (f"потолок расхода группы {группа}: за сутки "
                       f"{round(с['day_spend_sol'], 6)} SOL, эта сделка довела бы "
                       f"до {round(вперёд, 6)} при потолке {пг['day_cap_sol']}")
    из_ = {"ok": почему is None, "why_not": почему, "state": с}
    из_["group_limits"] = пг
    return из_


