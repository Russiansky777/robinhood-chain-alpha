def купленное_raw(tx: dict, кошелёк: str, минт: str) -> dict:
    """Сколько СЫРЫХ единиц минта прибыло на наш адрес этой транзакцией.

    Это количество -- то самое, которое сторож потом продаёт. Считается
    ТОЛЬКО в сырых единицах (uiTokenAmount.amount): у токена с девятью
    знаками движение в единицах показывается в ui нулём, а пыль -- числом.
    Цена ошибки прямая: по ui продали бы не то количество, что купили.

    Своих счетов минта может быть несколько (ATA плюс созданный в этой же
    транзакции), поэтому суммируем по всем, где владелец -- наш кошелёк.
    Отсутствие счёта в preTokenBalances -- обычный случай: счёт создан
    здесь же, и до транзакции его не было вовсе.
    """
    из_ = {"ok": False, "raw": None, "why_not": None}
    if not isinstance(tx, dict):
        из_["why_not"] = "транзакции нет"
        return из_
    мета = tx.get("meta")
    if not isinstance(мета, dict):
        из_["why_not"] = "у транзакции нет meta -- количество не посчитать"
        return из_
    if мета.get("err") is not None:
        из_["why_not"] = f"транзакция упала: {json.dumps(мета.get('err'), ensure_ascii=False)[:120]}"
        из_["chain_ok"] = False
        return из_
    if not кошелёк or not минт:
        из_["why_not"] = f"нужны кошелёк и минт (кошелёк {кошелёк!r}, минт {минт!r})"
        return из_
    было: dict = {}
    стало: dict = {}
    for где, куда in (("preTokenBalances", было), ("postTokenBalances", стало)):
        for б in (мета.get(где) or []):
            if not isinstance(б, dict) or б.get("owner") != кошелёк:
                continue
            if б.get("mint") != минт:
                continue
            сырое = (б.get("uiTokenAmount") or {}).get("amount")
            try:
                куда[б.get("accountIndex")] = int(сырое)
            except (TypeError, ValueError):
                из_["why_not"] = f"количество не число: {сырое!r}"
                return из_
    if not стало:
        из_["why_not"] = "нашего счёта этого минта в postTokenBalances нет"
        return из_
    дельта = sum(стало.values()) - sum(было.get(и, 0) for и in стало)
    if дельта <= 0:
        из_["why_not"] = f"приход не положителен: {дельта}"
        из_["raw"] = дельта
        return из_
    из_.update(ok=True, raw=дельта, chain_ok=True)
    return из_


# ЛЕСТНИЦЫ ПЛАТЫ (З3) ЗДЕСЬ НЕТ -- И НЕ ДОЛЖНО БЫТЬ. Владелец отменил её
# 25.09 по итогам З1, и вот почему, чтобы никто не добавил её обратно: в
# 66 % наших покупок перед нами в блоке стояли транзакции, заплатившие
# МЕНЬШЕ нас (171 более дешёвая против 19 более дорогих), а медиана платы
# тех, кто садится в S+0 сразу за источником, -- около 9 500 лампортов
# против наших 995 000. Ступени "средний" и "высокий" оказались бы ниже
# базового уровня, а вопрос "плата или путь" уже отвечен: путь. Тратить на
# лестницу 0.05 SOL и живые сигналы незачем.

# ------------------------------------------------- контроль доставки (З2)

# Слово владельца 25.09: "На каждом сигнале с покупкой полосы -- в ту же
# миллисекунду тем же путём (Helius Sender, те же чаевые) пустая транзакция
# без касания пула (memo или перевод 0 себе)". Смысл замера: если контроль
# садится заметно быстрее покупки, задержка -- это очередь к горячему пулу
# (плата). Если он так же медленный -- задержка в пути, и её надо разбирать
# по этапам.
#
# ПОЧЕМУ ПЕРЕВОД НУЛЯ СЕБЕ, А НЕ MEMO. Владелец разрешил и то и другое.
# Перевод нуля собирается теми же кирпичами, что уже проверены сборкой
# покупки (c2_swap_build.sol_transfer), и не требует заводить в репозитории
# ещё один адрес программы. Получатель -- наш же кошелёк, сумма ноль:
# ошибиться адресом тут нечем.
#
# ЧТО ЭТО СТОИТ. Приоритет и чаевые у контроля ровно те же, что у покупки
# (иначе сравнение нечестно): 0.001 + 0.001 SOL плюс базовая подпись. Отсюда
# два предела владельца: не больше 20 контролей в сутки и не больше 0.03 SOL
# на контроли. Первым срабатывает тот, который ближе.
ЛИМИТ_КОНТРОЛЕЙ_В_СУТКИ = 20
# ПОТОЛОК РАСХОДА НА КОНТРОЛИ. Сводный промпт владельца 25.09: "Предел
# <= 0.05 SOL в сутки на контроли" (было 0.03 -- взято новое, большее).
ПОТОЛОК_РАСХОДА_КОНТРОЛЯ_SOL = 0.05
# И ОТДЕЛЬНО НА СЕРВИС НА СИГНАЛ: "0.001 SOL на сервис на сигнал". Считается
# по УПРАВЛЯЕМОЙ части -- чаевые плюс приоритет; базовый тариф сети за подпись
# (5000 лампортов) неизбежен и в этот предел не входит, но в суточный расход
# считается полностью.
ПОТОЛОК_КОНТРОЛЯ_НА_СЕРВИС_SOL = 0.001
КЛЮЧ_СЧЁТЧИКА_КОНТРОЛЯ = "lane_control"


def контроль_включён() -> bool:
    return (os.environ.get("BLOOM_LANE_CONTROL") or "").strip() == "1"


def цена_контроля_лампорты(*, приоритет_лампорты: int | None = None,
                            чаевые_лампорты: int | None = None) -> int:
    """Во сколько обходится один контроль, если он сядет.

    Считаем ПЕССИМИСТИЧНО и до отправки: приоритет платится за запрошенный
    предел CU целиком, чаевые -- полностью, плюс базовый тариф за подпись.
    Занизить эту цену значит прогрызть потолок 0.03 SOL незаметно.
    """
    п = (приоритет_лампорты if приоритет_лампорты is not None
         else int(round(приоритет_sol() * ЛАМПОРТОВ_В_SOL)))
    ч = (чаевые_лампорты if чаевые_лампорты is not None
         else int(round(чаевые_sol() * ЛАМПОРТОВ_В_SOL)))
    return int(п) + int(ч) + 5000


def _день_utc(сейчас: float | None = None) -> str:
    return time.strftime("%Y%m%d", time.gmtime(сейчас if сейчас else time.time()))


def расход_контроля(состояние, *, сейчас: float | None = None) -> dict:
    """Сколько контролей и на сколько лампортов уже ушло СЕГОДНЯ.

    Сутки -- UTC, как и суточный предел покупок полосы: два разных начала
    суток в одном модуле означали бы, что один предел уже сработал, а второй
    ещё нет, и объяснить это было бы нечем.
    """
    из_ = {"day": _день_utc(сейчас), "n": 0, "spent_lamports": 0,
           "why_not": None}
    if состояние is None or not hasattr(состояние, "counters"):
        из_["why_not"] = "состояние не умеет считать -- расход контроля неизвестен"
        return из_
    try:
        с = состояние.counters() or {}
    except Exception as exc:  # noqa: BLE001
        из_["why_not"] = f"счётчики не прочитаны: {type(exc).__name__}"
        return из_
    з = с.get(КЛЮЧ_СЧЁТЧИКА_КОНТРОЛЯ) or {}
    if з.get("day") == из_["day"]:
        из_["n"] = int(з.get("n") or 0)
        из_["spent_lamports"] = int(з.get("spent_lamports") or 0)
    из_["spent_sol"] = из_["spent_lamports"] / ЛАМПОРТОВ_В_SOL
    return из_


def можно_контроль(состояние, *, цена_лампорты: int,
                    сейчас: float | None = None) -> dict:
    """Пределы контроля: 20 в сутки И не больше 0.03 SOL. Оба -- до отправки.

    Неизвестный расход запрещает отправку: "счётчики не прочитались" не
    имеет права означать "трать дальше".
    """
    р = расход_контроля(состояние, сейчас=сейчас)
    если = None
    потолок = int(round(ПОТОЛОК_РАСХОДА_КОНТРОЛЯ_SOL * ЛАМПОРТОВ_В_SOL))
    if р.get("why_not"):
        если = р["why_not"]
    elif р["n"] >= ЛИМИТ_КОНТРОЛЕЙ_В_СУТКИ:
        если = f"{р['n']} контролей за сутки при пределе {ЛИМИТ_КОНТРОЛЕЙ_В_СУТКИ}"
    elif р["spent_lamports"] + int(цена_лампорты) > потолок:
        если = (f"расход контроля {(р['spent_lamports'] + int(цена_лампорты)) / ЛАМПОРТОВ_В_SOL} "
                f"SOL вышел бы за потолок {ПОТОЛОК_РАСХОДА_КОНТРОЛЯ_SOL} SOL")
    return {"ok": если is None, "why_not": если, "state": р}


def учесть_контроль(состояние, *, цена_лампорты: int,
                     сейчас: float | None = None) -> dict:
    """Расход контроля на диск СРАЗУ, ещё до ответа Sender.

    Пессимизм намеренный: транзакция могла уйти и сесть, даже если ответ до
    нас не дошёл. Незаписанный расход -- это тихо прогрызенный потолок.
    """
    if состояние is None or not hasattr(состояние, "counters"):
        return {"ok": False, "why_not": "состояние не умеет считать"}
    try:
        с = состояние.counters() or {}
        день = _день_utc(сейчас)
        з = с.get(КЛЮЧ_СЧЁТЧИКА_КОНТРОЛЯ) or {}
        if з.get("day") != день:
            з = {"day": день, "n": 0, "spent_lamports": 0}
        з["n"] = int(з.get("n") or 0) + 1
        з["spent_lamports"] = int(з.get("spent_lamports") or 0) + int(цена_лампорты)
        з["last_ts"] = сейчас if сейчас else time.time()
        с[КЛЮЧ_СЧЁТЧИКА_КОНТРОЛЯ] = з
        состояние.save_counters(с)
        return {"ok": True, "state": з}
    except Exception as exc:  # noqa: BLE001
        return {"ok": False, "why_not": f"{type(exc).__name__}: {str(exc)[:160]}"}


def собрать_контроль(*, наш_кошелёк: str, cu_units: int = 400_000,
                      приоритет_лампорты: int | None = None,
                      чаевые_лампорты: int | None = None,
                      семя: str | None = None,
                      сервис: str | None = None) -> dict:
    """Пустая транзакция ТЕМ ЖЕ путём: приоритет, перевод нуля себе, чаевые.

    Пула она не касается вовсе -- в этом и смысл: всё, что отличает её от
    покупки, это отсутствие свопа. Если она садится раньше -- мешает пул.

    СЕРВИС задаёт, КОМУ чаевые и сколько: адрес и минимум берутся из реестра
    отправителей (data/senders.json, собран из их документации). Без сервиса
    всё как раньше -- счёт Helius Sender из списка репозитория. У контроля
    приоритет по умолчанию НУЛЕВОЙ, когда сервис задан: пустая транзакция за
    место в пуле не соперничает, и платить за приоритет ей незачем -- мы мерим
    путь отправителя, а не очередь.
    """
    из_ = {"ok": False, "why_not": None, "tip_account": None, "build_ms": None}
    t0 = time.perf_counter()
    if not наш_кошелёк:
        из_["why_not"] = "кошелёк полосы не задан -- контроль собирать не на что"
        return из_
    реестр_сервиса = None
    if сервис:
        try:
            import bloom_senders as SS  # noqa: PLC0415
        except Exception as exc:  # noqa: BLE001
            из_["why_not"] = f"реестр отправителей не загружен: {type(exc).__name__}"
            return из_
        реестр_сервиса = SS.реестр().get(сервис)
        if not реестр_сервиса:
            из_["why_not"] = f"отправителя {сервис} нет в реестре"
            return из_
        if приоритет_лампорты is None:
            приоритет_лампорты = 0
        if чаевые_лампорты is None:
            чаевые_лампорты = SS.минимум_чаевых(сервис)
    приоритет_лампорты = (приоритет_лампорты if приоритет_лампорты is not None
                          else int(round(приоритет_sol() * ЛАМПОРТОВ_В_SOL)))
    чаевые_лампорты = (чаевые_лампорты if чаевые_лампорты is not None
                       else int(round(чаевые_sol() * ЛАМПОРТОВ_В_SOL)))
    # ПРЕДЕЛ НА СЕРВИС НА СИГНАЛ -- до сборки: управляемая часть (чаевые плюс
    # приоритет) не имеет права выйти за 0.001 SOL.
    if сервис:
        управляемое = int(приоритет_лампорты) + int(чаевые_лампорты)
        потолок_с = int(round(ПОТОЛОК_КОНТРОЛЯ_НА_СЕРВИС_SOL * ЛАМПОРТОВ_В_SOL))
        if управляемое > потолок_с:
            из_["why_not"] = (f"контроль через {сервис}: чаевые и приоритет "
                               f"{управляемое} лампортов выше предела {потолок_с} "
                               "на сервис на сигнал")
            return из_
    try:
        _, _, _, B = _модули()
        from solders.hash import Hash  # noqa: PLC0415
        from solders.message import MessageV0  # noqa: PLC0415
        from solders.pubkey import Pubkey  # noqa: PLC0415
        from solders.signature import Signature  # noqa: PLC0415
        from solders.transaction import VersionedTransaction  # noqa: PLC0415
    except Exception as exc:  # noqa: BLE001
        из_["why_not"] = f"модули сборки контроля не загружены: {type(exc).__name__}"
        return из_
    if сервис:
        import bloom_senders as SS  # noqa: PLC0415

        чаевые = SS.счёт_чаевых(сервис, семя=семя)
        разрешённые = set((реестр_сервиса or {}).get("tip_accounts") or [])
        if not чаевые or чаевые not in разрешённые:
            из_["why_not"] = (f"адрес чаевых не из списка сервиса {сервис} -- "
                               "сборка отменена")
            return из_
    else:
        чаевые = выбрать_чаевые(семя)
        if чаевые not in TIP_ACCOUNTS:
            из_["why_not"] = "адрес чаевых не из списка счетов Sender -- сборка отменена"
            return из_
    try:
        инструкции = [B.cu_limit(cu_units),
                      B.cu_price(цена_единицы_cu(приоритет_лампорты, cu_units)),
                      # ПЕРЕВОД НУЛЯ СЕБЕ. Ни пула, ни чужого адреса.
                      B.sol_transfer(наш_кошелёк, наш_кошелёк, 0),
                      B.sol_transfer(наш_кошелёк, чаевые, чаевые_лампорты)]
        сообщение = MessageV0.try_compile(Pubkey.from_string(наш_кошелёк),
                                           инструкции, [], Hash.default())
        подписей = сообщение.header.num_required_signatures
        vtx = VersionedTransaction.populate(сообщение,
                                             [Signature.default()] * подписей)
        сырое = bytes(vtx)
    except Exception as exc:  # noqa: BLE001
        из_["why_not"] = f"сборка контроля: {type(exc).__name__}: {str(exc)[:160]}"
        return из_
    import base64 as _b64  # noqa: PLC0415
    из_.update(ok=True, tx_base64=_b64.b64encode(сырое).decode(), size=len(сырое),
               tip_account=чаевые, priority_lamports=приоритет_лампорты,
               tip_lamports=чаевые_лампорты, sender=сервис,
               cost_lamports=цена_контроля_лампорты(
                   приоритет_лампорты=приоритет_лампорты,
                   чаевые_лампорты=чаевые_лампорты),
               build_ms=round((time.perf_counter() - t0) * 1000, 3))
    return из_


def провести_контроль(*, состояние, blockhash: str | None,
                       blockhash_ts: float | None = None,
                       семя: str | None = None, ключ_операции: str | None = None,
                       секрет: str | None = None, отправитель=None,
                       сейчас: float | None = None,
                       подготовленное: dict | None = None) -> dict:
    """Контроль целиком: сборка, подпись, отправка -- со своими пределами.

    Рубильник проверяется здесь явно: отправка контроля идёт мимо учёта
    позиций (`без_учёта=True`), а значит и мимо проверки рубильника внутри
    отправить(). Остановленная полоса не должна тратить ни лампорта.
    """
    сейчас = сейчас if сейчас is not None else time.time()
    из_ = {"stage": "control", "ok": False, "sent": False, "why_not": None,
            "signature": None, "ts_sent": None}
    if not контроль_включён():
        из_["why_not"] = "контроль доставки выключен (BLOOM_LANE_CONTROL не равен 1)"
        return из_
    if состояние is not None:
        убит, почему = состояние.kill_active()
        if not убит and hasattr(состояние, "lane_kill_active"):
            убит, почему = состояние.lane_kill_active()
        if убит:
            из_.update(why_not=f"рубильник: {почему}", kill=True)
            return из_
    готово = подготовленное if подготовленное is not None else None
    if готово is None:
        сб = собрать_контроль(наш_кошелёк=кошелёк_полосы(), семя=семя)
        if not сб.get("ok"):
            из_["why_not"] = сб.get("why_not")
            return из_
        готово = {"сборка": сб}
    сб = готово.get("сборка") or {}
    if not сб.get("ok"):
        из_["why_not"] = сб.get("why_not") or "контроль не собран"
        return из_
    из_.update(tip_account=сб.get("tip_account"), build_ms=сб.get("build_ms"),
               cost_lamports=сб.get("cost_lamports"),
               cost_sol=(сб.get("cost_lamports") or 0) / ЛАМПОРТОВ_В_SOL)
    можно = можно_контроль(состояние, цена_лампорты=сб.get("cost_lamports") or 0,
                            сейчас=сейчас)
    из_["limits"] = можно.get("state")
    if not можно.get("ok"):
        из_["why_not"] = f"предел контроля: {можно.get('why_not')}"
        return из_
    подписано = готово.get("подпись")
    if подписано is None:
        if not blockhash:
            из_["why_not"] = "тёплого blockhash нет -- контроль подписывать нечем"
            return из_
        возраст = (сейчас - float(blockhash_ts)) if blockhash_ts else None
        if возраст is not None and возраст > СРОК_BLOCKHASH_S:
            из_["why_not"] = (f"тёплый blockhash старше {СРОК_BLOCKHASH_S} с "
                              f"(возраст {round(возраст, 2)} с)")
            return из_
        подписано = подписать(сб["tx_base64"], blockhash=blockhash,
                              ожидаемый_кошелёк=кошелёк_полосы(),
                              секрет=(секрет if секрет is not None else ключ_полосы()))
    if not подписано.get("ok"):
        из_["why_not"] = подписано.get("why_not")
        return из_
    из_["signature"] = подписано.get("signature")
    # РАСХОД -- ДО ОТПРАВКИ. Ответа может не быть, а лампорты уйти.
    # НЕ ЗАПИСАЛСЯ РАСХОД -- НЕ ОТПРАВЛЯЕМ. Это и есть "неучтённый расход" из
    # правила владельца, только предотвращённый: не отправив, мы не потратили,
    # и рубильник не нужен -- нужен честный отказ и строка о нём.
    из_["accounted"] = учесть_контроль(
        состояние, цена_лампорты=сб.get("cost_lamports") or 0, сейчас=сейчас)
    if not (из_["accounted"] or {}).get("ok"):
        из_["why_not"] = ("расход контроля не записан -- контроль не отправлен "
                          f"(иначе это неучтённый расход): "
                          f"{(из_['accounted'] or {}).get('why_not')}")
        return из_
    из_["ts_sent"] = time.time()
    о = отправить(подписано["tx_base64"], состояние=состояние,
                  ключ_операции=ключ_операции, отправитель=отправитель,
                  сейчас=сейчас, без_учёта=True)
    из_.update(sent=bool(о.get("sent")), ok=bool(о.get("ok")), http=о.get("http"),
               send_ms=о.get("send_ms"), signature_sender=о.get("result"))
    if not о.get("ok"):
        из_["why_not"] = о.get("why_not")
    return из_


def подготовить_контроль(*, семя: str | None, blockhash: str | None,
                          секрет: str | None = None) -> dict:
    """Сборка и подпись контроля ЗАРАНЕЕ, в своём потоке.

    Зачем: контроль обязан уйти в ту же миллисекунду, что и покупка, но ни
    одна его миллисекунда не должна лечь на путь покупки. Поэтому он
    собирается и подписывается параллельно, а после отправки покупки
    остаётся только отправить готовые байты.
    """
    из_: dict = {"сборка": None, "подпись": None}
    сб = собрать_контроль(наш_кошелёк=кошелёк_полосы(), семя=семя)
    из_["сборка"] = сб
    if not сб.get("ok") or not blockhash:
        return из_
    из_["подпись"] = подписать(сб["tx_base64"], blockhash=blockhash,
                                ожидаемый_кошелёк=кошелёк_полосы(),
                                секрет=(секрет if секрет is not None
                                        else ключ_полосы()))
    return из_



# ------------------------------------------------------------------ весь путь

# СРОК ГОДНОСТИ ТЁПЛОГО BLOCKHASH. Сеть держит хеш около 150 слотов (~60 с).
# Тёплый хеш обновляет пульс детектора; просроченным подписывать нельзя --
# транзакция уйдёт, сеть её отбросит, и замер выйдет ложным: "не доехало"
# вместо "доехало медленно". Держим запас вдвое.
СРОК_BLOCKHASH_S = 30.0

# СКОЛЬКО ЖДЁМ ГОТОВЫЙ КОНТРОЛЬ после отправки покупки. Сборка и подпись
# контроля занимают единицы миллисекунд; четверть секунды -- это запас на
# случай занятой машины, а не разрешение опаздывать. Не успел -- пары не
# будет, и в строке это написано.
ОЖИДАНИЕ_КОНТРОЛЯ_S = 0.25


def провести(*, tx_источника: dict, источник: str, минт: str, состояние,
              blockhash: str | None = None, blockhash_ts: float | None = None,
              лампорты: int | None = None, проскальзывание: float = 0.35,
              ключ_операции: str | None = None,
              источник_подпись: str | None = None,
              источник_слот: int | None = None,
              отправитель=None, rpc_call=None, секрет: str | None = None,
              тень_сим=None, сейчас: float | None = None) -> dict:
    """Весь путь полосы на один сигнал: сборка -> (симуляция | подпись и отправка).

    Одна точка входа нарочно. У полосы три шага, и каждый из них умеет
    отказать; если их вызывать по отдельности из детектора, порядок и
    причины отказа расползутся по вызывающим, а это деньги. Здесь же и
    стадия отказа называется словом: по ней видно, где полоса стоит.

    БЕЗ BLOOM_OWN_SEND_LIVE=1 доходит только до симуляции: ни подписи, ни
    отправки. Пределы и рубильник проверяются дважды -- дёшево здесь (чтобы
    не собирать зря) и обязательно внутри отправить() под замком, где
    делается бронь.
    """
    сейчас = сейчас if сейчас is not None else time.time()
    из_ = {"stage": "off", "ok": False, "sent": False, "dry": None,
            "why_not": None, "lane": МЕТКА, "mint": минт,
            "source_sig": источник_подпись, "cid": None, "signature": None}
    if not включена():
        из_["why_not"] = "полоса выключена (BLOOM_OWN_SEND не равен 1)"
        return из_
    лампорты = (лампорты if isinstance(лампорты, int)
                else int(round(размер_sol() * ЛАМПОРТОВ_В_SOL)))
    из_["lamports"] = лампорты
    из_["size_sol"] = лампорты / ЛАМПОРТОВ_В_SOL

    # ПРЕДВАРИТЕЛЬНЫЙ ГЕЙТ. Не заменяет тот, что внутри отправить(): он там
    # под замком и с бронью. Здесь только чтобы не тратить сеть на сборку,
    # когда полоса всё равно закрыта.
    из_["stage"] = "gate"
    if состояние is None:
        из_["why_not"] = "состояние не передано -- пределы полосы проверить нечем"
        return из_
    убит, почему_kill = состояние.kill_active()
    if убит:
        из_["why_not"] = f"рубильник: {почему_kill}"
        из_["kill"] = True
        return из_
    try:
        гейт = можно_отправлять(состояние.positions(), сейчас=сейчас)
    except Exception as exc:  # noqa: BLE001
        из_["why_not"] = f"позиции не прочитаны ({type(exc).__name__})"
        return из_
    из_["lane_state"] = гейт.get("state")
    if not гейт.get("ok"):
        из_["why_not"] = f"предел полосы: {гейт.get('why_not')}"
        return из_

    # КОНТРОЛЬ ДОСТАВКИ (З2, слово владельца 25.09) готовится ПАРАЛЛЕЛЬНО.
    # Он обязан уйти в ту же миллисекунду, что и покупка, но ни одна его
    # миллисекунда не имеет права лечь на путь покупки -- поэтому сборка и
    # подпись контроля идут своим потоком, а после отправки покупки остаётся
    # только отправить готовые байты.
    контроль_готов: dict = {}
    поток_контроля = None
    if контроль_включён() and живьём():
        def _готовить_контроль():
            try:
                контроль_готов.update(подготовить_контроль(
                    семя=(источник_подпись or ключ_операции),
                    blockhash=blockhash,
                    секрет=(секрет if секрет is not None else ключ_полосы())))
            except Exception as exc:  # noqa: BLE001
                контроль_готов["почему"] = f"{type(exc).__name__}: {str(exc)[:160]}"

        try:
            поток_контроля = threading.Thread(target=_готовить_контроль,
                                               name="lane-control-prep", daemon=True)
            поток_контроля.start()
        except Exception as exc:  # noqa: BLE001
            контроль_готов["почему"] = f"поток контроля не запустился: {type(exc).__name__}"

    # СБОРКА. Дёшево и безопасно: ни ключа, ни подписи, ни отправки.
    из_["stage"] = "build"
    сб = собрать(tx_источника=tx_источника or {}, источник=источник or "",
                 минт=минт or "", наш_кошелёк=кошелёк_полосы(),
                 лампорты=лампорты, проскальзывание=проскальзывание,
                 приоритет_лампорты=int(round(приоритет_sol() * ЛАМПОРТОВ_В_SOL)),
                 чаевые_лампорты=int(round(чаевые_sol() * ЛАМПОРТОВ_В_SOL)),
                 семя=источник_подпись or ключ_операции)
    из_.update(pool_program=сб.get("pool_program"), min_out=сб.get("min_out"),
               expected_out=сб.get("expected_out"), build_ms=сб.get("build_ms"),
               size=сб.get("size"), tip_account=сб.get("tip_account"))
    if not сб.get("ok"):
        из_["why_not"] = сб.get("why_not")
        # ЧУЖОЙ ПОЛУЧАТЕЛЬ -- ЭТО УТЕЧКА, И ТУТ РУБИЛЬНИК (владелец 25.09).
        # Сборка отказала, ни лампорта не ушло -- но список счетов Sender
        # правится руками, и адрес не из списка означает, что следующая
        # сборка могла бы отправить чаевые неизвестно кому. Останавливаемся
        # до разбора человеком.
        if "адрес чаевых не из списка" in (сб.get("why_not") or ""):
            из_["kill_set"] = остановить_полосу(
                состояние, f"чужой получатель чаевых: {сб.get('why_not')}")
            из_["kill"] = True
        return из_

    # СИМУЛЯЦИЯ -- ВНЕ ПУТИ СДЕЛКИ. Решение владельца 25.09 после первой живой
    # пары: симуляция стоила 52.95 мс, и ровно из-за неё мы пришли в блок на
    # 11.4 мс позже Bloom. Теперь она идёт СВОИМ потоком и только в журнал, а
    # защита сделки -- min_out внутри самой транзакции (проскальзывание уже
    # заложено в сборке). Путь сделки: сборка -> подпись -> отправка.
    #
    # В нежилом режиме (без BLOOM_OWN_SEND_LIVE) симуляция остаётся
    # ПОСЛЕДОВАТЕЛЬНОЙ: там торопиться некуда, а её вердикт -- единственный
    # смысл сухого прогона.
    if rpc_call is not None and тень_сим is not None and живьём():
        запустить_тень_симуляции(rpc_call, сб.get("tx_base64"),
                                  журнал=тень_сим,
                                  метка={"source_sig": источник_подпись,
                                          "mint": минт, "op": ключ_операции})
        из_["sim_shadow"] = "запущена в своём потоке"
    elif not живьём():
        из_["stage"] = "sim"
        if rpc_call is None:
            из_["why_not"] = "симулировать нечем (узел не передан)"
            из_["code"] = "SKIP_SIM_FAIL"
            return из_
        t_сим = time.perf_counter()
        try:
            _, _, SB, _ = _модули()
            знач = (rpc_call("simulateTransaction",
                            [сб["tx_base64"], SB.SIM_OPTS]) or {}).get("value") or {}
            из_.update(SB.classify_sim(знач))
        except Exception as exc:  # noqa: BLE001
            из_["why_not"] = f"симуляция: {type(exc).__name__}: {str(exc)[:160]}"
            из_["code"] = "SKIP_SIM_FAIL"
            из_["sim_ms"] = round((time.perf_counter() - t_сим) * 1000, 2)
            return из_
        из_["sim_ms"] = round((time.perf_counter() - t_сим) * 1000, 2)
    if not живьём():
        # Нежилой режим: дальше подписи нет и денег нет.
        из_.update(stage="dry", dry=True, ok=True)
        return из_

    # ПОДПИСЬ. Тёплый blockhash обязан быть свежим: просроченным подписывать
    # бессмысленно, сеть такую транзакцию отбросит.
    из_["stage"] = "blockhash"
    if not blockhash:
        из_["why_not"] = "тёплого blockhash нет -- подписывать нечем"
        return из_
    возраст = (сейчас - float(blockhash_ts)) if blockhash_ts else None
    из_["blockhash_age_s"] = round(возраст, 2) if возраст is not None else None
    if возраст is not None and возраст > СРОК_BLOCKHASH_S:
        из_["why_not"] = (f"тёплый blockhash старше {СРОК_BLOCKHASH_S} с "
                          f"(возраст {из_['blockhash_age_s']} с) -- сеть отбросит")
        return из_
    из_["stage"] = "sign"
    t_подпись = time.perf_counter()
    пд = подписать(сб["tx_base64"], blockhash=blockhash,
                   ожидаемый_кошелёк=кошелёк_полосы(),
                   секрет=(секрет if секрет is not None else ключ_полосы()))
    из_["sign_ms"] = round((time.perf_counter() - t_подпись) * 1000, 2)
    if not пд.get("ok"):
        из_["why_not"] = пд.get("why_not")
        return из_
    из_["signature"] = пд.get("signature")

    # ОТПРАВКА. Пределы, рубильник и бронь -- внутри, под замком.
    из_["stage"] = "send"
    из_["ts_sent_buy"] = time.time()
    о = отправить(пд["tx_base64"], состояние=состояние,
                  ключ_операции=ключ_операции, минт=минт, лампорты=лампорты,
                  источник_подпись=источник_подпись, источник_слот=источник_слот,
                  отправитель=отправитель, сейчас=сейчас)
    из_.update(sent=bool(о.get("sent")), http=о.get("http"),
               send_ms=о.get("send_ms"), cid=о.get("cid"),
               duplicate=о.get("duplicate"))
    if о.get("lane_state") is not None:
        из_["lane_state"] = о.get("lane_state")
    # КОНТРОЛЬ -- СРАЗУ ПОСЛЕ ПОКУПКИ и никогда до неё: покупка это деньги
    # и место в блоке, контроль -- замер. Отправляется он и при неудачной
    # покупке тоже: неудача покупки не делает замер пути ненужным, а пределы
    # у контроля свои.
    if поток_контроля is not None:
        # Ждать готовности долго нельзя: смысл контроля в том, что он уходит
        # рядом с покупкой. Не успел -- значит этой пары не будет, и это
        # сказано словами.
        поток_контроля.join(timeout=ОЖИДАНИЕ_КОНТРОЛЯ_S)
        if поток_контроля.is_alive() or not контроль_готов.get("сборка"):
            из_["control"] = {"ok": False, "sent": False,
                              "why_not": (контроль_готов.get("почему")
                                           or f"контроль не готов за {ОЖИДАНИЕ_КОНТРОЛЯ_S} с "
                                              "-- пара без контроля")}
        else:
            к = провести_контроль(
                состояние=состояние, blockhash=blockhash,
                blockhash_ts=blockhash_ts,
                семя=(источник_подпись or ключ_операции),
                ключ_операции=(f"ctl-{ключ_операции}" if ключ_операции else None),
                секрет=секрет, отправитель=отправитель, сейчас=сейчас,
                подготовленное=контроль_готов)
            к["ts_buy_sent"] = из_.get("ts_sent_buy")
            if к.get("ts_sent") and из_.get("ts_sent_buy"):
                к["after_buy_ms"] = round(
                    (float(к["ts_sent"]) - float(из_["ts_sent_buy"])) * 1000.0, 2)
            из_["control"] = к

    if о.get("ok"):
        из_.update(stage="sent", ok=True, dry=False)
        # Подпись из ответа Sender и наша сходятся по построению: мы её сами
        # и считали. Если вдруг нет -- это не успех, а расхождение, и в
        # позиции должны лежать обе.
        из_["signature_sender"] = о.get("result")
        try:
            состояние.update_position(
                о.get("cid"), state="bought", lane=МЕТКА,
                lane_signature=о.get("result") or пд.get("signature"),
                lane_signature_local=пд.get("signature"),
                ts_sent=сейчас, ts_accepted=time.time(),
                pool=None, program=сб.get("pool_program"),
                lane_min_out=сб.get("min_out"),
                lane_expected_out=сб.get("expected_out"),
                lane_send_ms=о.get("send_ms"), lane_build_ms=сб.get("build_ms"),
                lane_tip_account=сб.get("tip_account"),
                lane_priority_lamports=int(round(приоритет_sol() * ЛАМПОРТОВ_В_SOL)),
                lane_ts_sent_buy=из_.get("ts_sent_buy"),
                control_signature=(из_.get("control") or {}).get("signature"),
                control_ts_sent=(из_.get("control") or {}).get("ts_sent"),
                control_send_ms=(из_.get("control") or {}).get("send_ms"),
                control_after_buy_ms=(из_.get("control") or {}).get("after_buy_ms"),
                control_tip_account=(из_.get("control") or {}).get("tip_account"),
                control_cost_sol=(из_.get("control") or {}).get("cost_sol"),
                control_why_not=(из_.get("control") or {}).get("why_not"))
        except Exception as exc:  # noqa: BLE001
            # Отправка уже состоялась: молчать нельзя, но и "не ok" ставить
            # поздно -- деньги ушли. Причина идёт в отчёт отдельным полем.
            из_["position_update_why_not"] = f"{type(exc).__name__}: {str(exc)[:160]}"
        return из_

    из_["why_not"] = о.get("why_not")
    if о.get("kill"):
        из_["kill"] = True
    # БРОНЬ ПОСЛЕ НЕУДАЧИ. Закрываем её ТОЛЬКО на определённом отказе узла:
    # он разобрал транзакцию и отверг её, в цепи её нет. Любая другая
    # неудача (сеть молчит, ответ не JSON, 200 без подписи) неопределённа --
    # транзакция могла уйти, и бронь обязана остаться открытой, иначе сторож
    # не узнает о токене, который у нас на руках.
    if о.get("cid"):
        try:
            if о.get("definite_refusal"):
                состояние.update_position(
                    о["cid"], state=ST.STATE_CLOSED, lane=МЕТКА,
                    close_reason="sender_refused", chain_ok=False,
                    why_not=str(о.get("why_not"))[:300])
                из_["reservation"] = "closed"
            else:
                состояние.update_position(
                    о["cid"], lane=МЕТКА, lane_send_ambiguous=True,
                    lane_signature_local=пд.get("signature"),
                    why_not=str(о.get("why_not"))[:300])
                из_["reservation"] = "open_ambiguous"
        except Exception as exc:  # noqa: BLE001
            из_["position_update_why_not"] = f"{type(exc).__name__}: {str(exc)[:160]}"
    return из_


