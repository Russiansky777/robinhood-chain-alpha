def main() -> int:
    р = argparse.ArgumentParser()
    р.add_argument("--chto", required=True,
                    choices=("plan", "nonce", "probnyy", "ostatok", "self-test"),
                    help="plan -- только числа; nonce -- снять ренту nonce; "
                         "probnyy -- 0.001 SOL; ostatok -- весь остаток минус тариф")
    р.add_argument("--probnyy-sol", type=float, default=0.001)
    р.add_argument("--konfig", default=None)
    р.add_argument("--out", default=None)
    а = р.parse_args()

    if а.chto == "self-test":
        return self_test()

    итог: dict = {"чего": а.chto, "utc": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
                  "живьём": живьём()}
    конф = конфиг(а.konfig)
    if а.chto == "plan":
        call = _узел()
        итог.update(старый=конф.get("старый_адрес"), новый=цель(конф),
                    баланс_старого=баланс(call, конф["старый_адрес"]),
                    баланс_нового=баланс(call, цель(конф)))
        итог["остаток_к_переводу"] = сумма_остатка(итог["баланс_старого"])
    elif а.chto == "nonce":
        итог["результат"] = снять_нонс(путь_конфига=а.konfig)
    elif а.chto == "probnyy":
        итог["результат"] = перевод(
            сумма_лампорты=int(round(а.probnyy_sol * ЛАМПОРТОВ_В_SOL)),
            путь_конфига=а.konfig)
    elif а.chto == "ostatok":
        итог["результат"] = перевод(весь_остаток=True, путь_конфига=а.konfig)

    print(json.dumps(итог, ensure_ascii=False, indent=1))
    if а.out:
        with open(а.out, "w", encoding="utf-8") as ф:
            json.dump(итог, ф, ensure_ascii=False, indent=1)
    рез = итог.get("результат") or {}
    return 0 if (а.chto == "plan" or рез.get("ok")) else 1


if __name__ == "__main__":
    sys.exit(main())
