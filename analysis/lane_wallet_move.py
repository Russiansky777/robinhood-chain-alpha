#!/usr/bin/env python3
"""Переезд полосы на новый кошелёк владельца: перевод SOL и закрытие nonce.

ЗАЧЕМ. Владелец 27.09 (вне очереди): полоса переезжает на новый кошелёк, ключ
которого лежит в секрете LIVE_PRIVATE. Шаги, которые делает этот модуль:
  * снять ренту со счёта долговечного nonce СТАРОГО кошелька (он выведен из
    старого адреса семенем, и на новом адресе его не переиспользовать);
  * перевести SOL на новый адрес: сначала 0.001 с проверкой по цепи, потом
    весь остаток минус тариф.

ЕДИНСТВЕННАЯ ДВЕРЬ ДЛЯ SOL. Адрес получателя берётся ТОЛЬКО из конфига
data/lane_wallet_move.json и только если владелец его подтвердил полем
"подтверждён_владельцем": true. Правило владельца дословно: "Отправка SOL --
только на адреса кошельков наших задач из конфига (белый список). Адреса из
истории транзакций не использовать никогда". Поэтому адрес нельзя передать
аргументом: его негде взять, кроме конфига.

БЕЗ LANE_MOVE_LIVE=1 НИЧЕГО НЕ УХОДИТ. Сборка и подпись без живого флага не
делаются вовсе: подписанную транзакцию уже поздно отзывать.

Ключ старого кошелька читается из окружения службы (OWN_SEND_WALLET_KEY) и
никуда не печатается; текст исключений его разбора наружу не идёт.
"""
from __future__ import annotations

import argparse
import json
import os
import sys
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

ЛАМПОРТОВ_В_SOL = 1_000_000_000
БАЗОВЫЙ_ТАРИФ = 5_000
# Сколько оставляем на старом кошельке при переводе остатка. Ровно один тариф
# за одну подпись: больше оставлять незачем (кошелёк опустошается намеренно),
# меньше нельзя -- транзакция не пройдёт.
РЕЗЕРВ_ПО_УМОЛЧАНИЮ = БАЗОВЫЙ_ТАРИФ
КОНФИГ_ПО_УМОЛЧАНИЮ = "data/lane_wallet_move.json"
ENV_ЖИВЬЁМ = "LANE_MOVE_LIVE"


def живьём() -> bool:
    return (os.environ.get(ENV_ЖИВЬЁМ) or "0").strip() == "1"


def конфиг(путь: str | None = None) -> dict:
    п = Path(путь or КОНФИГ_ПО_УМОЛЧАНИЮ)
    if not п.exists():
        рядом = Path(__file__).resolve().parent.parent / (путь or КОНФИГ_ПО_УМОЛЧАНИЮ)
        п = рядом
    return json.loads(п.read_text(encoding="utf-8"))


def цель(конф: dict) -> str:
    """Адрес получателя. Не подтверждён владельцем -- отказ, а не адрес.

    Проверка на True именно строгая (is True): строка "yes" или число 1 в
    конфиге не должны открывать дверь деньгам.
    """
    if конф.get("подтверждён_владельцем") is not True:
        raise RuntimeError("новый адрес НЕ подтверждён владельцем в конфиге -- "
                           "перевод запрещён")
    адрес = str(конф.get("новый_адрес") or "").strip()
    if not (32 <= len(адрес) <= 44):
        raise RuntimeError(f"новый адрес в конфиге не похож на адрес Solana: {адрес!r}")
    старый = str(конф.get("старый_адрес") or "").strip()
    if адрес == старый:
        raise RuntimeError("новый адрес равен старому -- переводить некуда")
    return адрес


def сумма_остатка(баланс_лампорты: int, *, резерв: int = РЕЗЕРВ_ПО_УМОЛЧАНИЮ) -> dict:
    """Сколько переводить, когда просят "весь остаток минус комиссия"."""
    из_ = {"ok": False, "why_not": None, "лампорты": None}
    if not isinstance(баланс_лампорты, int) or баланс_лампорты <= 0:
        из_["why_not"] = f"баланс не положителен: {баланс_лампорты!r}"
        return из_
    сумма = int(баланс_лампорты) - int(резерв)
    if сумма <= 0:
        из_["why_not"] = (f"после резерва на тариф {резерв} переводить нечего "
                           f"(баланс {баланс_лампорты})")
        return из_
    из_.update(ok=True, лампорты=сумма, резерв=int(резерв))
    return из_


def проверить_перевод(*, откуда: str, куда: str, лампорты: int,
                      баланс_лампорты: int, конф: dict) -> dict:
    """Можно ли отправлять. Все проверки денежные, каждая -- отказ.

    Сюда собраны ровно те условия, невыполнение которых означает потерянные
    деньги: чужой получатель, перевод себе, ноль, сумма больше баланса, сумма
    без места под тариф.
    """
    из_ = {"ok": False, "why_not": None}
    try:
        ожидаемый = цель(конф)
    except RuntimeError as exc:
        из_["why_not"] = str(exc)
        return из_
    if куда != ожидаемый:
        из_["why_not"] = (f"получатель {куда[:12]} не равен подтверждённому адресу "
                           f"из конфига {ожидаемый[:12]} -- отправку отклоняю")
        return из_
    if откуда != str(конф.get("старый_адрес") or "").strip():
        из_["why_not"] = (f"отправитель {откуда[:12]} не тот кошелёк, который "
                           "переезжает по конфигу")
        return из_
    if откуда == куда:
        из_["why_not"] = "отправитель и получатель совпали"
        return из_
    if not isinstance(лампорты, int) or лампорты <= 0:
        из_["why_not"] = f"сумма не положительное целое: {лампорты!r}"
        return из_
    if лампорты + БАЗОВЫЙ_ТАРИФ > int(баланс_лампорты):
        из_["why_not"] = (f"сумма {лампорты} плюс тариф {БАЗОВЫЙ_ТАРИФ} больше "
                           f"баланса {баланс_лампорты}")
        return из_
    из_["ok"] = True
    return из_


# ------------------------------------------------------------------ цепь

def _узел():
    ключ = (os.environ.get("HELIUS_API") or os.environ.get("HELIUS_API_KEY") or "").strip()
    if not ключ:
        raise RuntimeError("HELIUS_API не задан")
    import urllib.request  # noqa: PLC0415

    def call(метод, параметры):
        тело = json.dumps({"jsonrpc": "2.0", "id": 1, "method": метод,
                           "params": параметры}).encode()
        req = urllib.request.Request(
            f"https://mainnet.helius-rpc.com/?api-key={ключ}", data=тело,
            headers={"Content-Type": "application/json"})
        with urllib.request.urlopen(req, timeout=40) as r:
            о = json.loads(r.read().decode())
        if "error" in о:
            raise RuntimeError(f"{метод}: {str(о['error'])[:200]}")
        return о.get("result")

    return call


def баланс(call, адрес: str) -> int:
    о = call("getBalance", [адрес]) or {}
    return int(о.get("value") if isinstance(о, dict) else о)


def _ключ_старого():
    """Keypair старого кошелька из окружения службы. Секрет не печатается."""
    сырое = (os.environ.get("OWN_SEND_WALLET_KEY") or "").strip()
    if not сырое:
        raise RuntimeError("OWN_SEND_WALLET_KEY не задан -- подписывать нечем")
    from dbot_rescue import load_rescue_keypair  # noqa: PLC0415
    try:
        return load_rescue_keypair(сырое)
    except Exception as exc:  # noqa: BLE001
        raise RuntimeError(f"ключ не разобрался ({type(exc).__name__})") from None


def отправить_и_дождаться(call, tx_b64: str, *, ждать_s: float = 45.0) -> dict:
    from dbot_rescue import send_raw_b64  # noqa: PLC0415

    # УРОВНИ СОГЛАСОВАНЫ: blockhash берётся на confirmed, значит и предполётная
    # проверка должна идти на confirmed. Иначе узел отвечает BlockhashNotFound
    # и транзакция не уходит -- так упал первый шаг переезда 27.09.
    подпись = send_raw_b64(call, tx_b64,
                            opts={"preflightCommitment": "confirmed"})
    из_ = {"подпись": подпись, "село": False, "слот": None, "ошибка": None}
    крайний = time.time() + ждать_s
    while time.time() < крайний:
        о = call("getSignatureStatuses", [[подпись], {"searchTransactionHistory": True}]) or {}
        зн = ((о.get("value") or [None])[0]) or None
        if зн:
            из_["слот"] = зн.get("slot")
            из_["ошибка"] = зн.get("err")
            из_["подтверждение"] = зн.get("confirmationStatus")
            if зн.get("err") is None and зн.get("confirmationStatus") in ("confirmed", "finalized"):
                из_["село"] = True
                return из_
            if зн.get("err") is not None:
                return из_
        time.sleep(2)
    из_["ошибка"] = из_["ошибка"] or "за отведённое время статус не подтвердился"
    return из_


def перевод(*, сумма_лампорты: int | None = None, весь_остаток: bool = False,
             резерв: int = РЕЗЕРВ_ПО_УМОЛЧАНИЮ, путь_конфига: str | None = None) -> dict:
    """Один перевод SOL на подтверждённый адрес. Живой флаг обязателен."""
    из_ = {"ok": False, "why_not": None, "живьём": живьём()}
    конф = конфиг(путь_конфига)
    откуда = str(конф.get("старый_адрес") or "").strip()
    try:
        куда = цель(конф)
    except RuntimeError as exc:
        из_["why_not"] = str(exc)
        return из_
    из_.update(откуда=откуда, куда=куда)
    call = _узел()
    бал = баланс(call, откуда)
    из_["баланс_до"] = бал
    if весь_остаток:
        с = сумма_остатка(бал, резерв=резерв)
        if not с.get("ok"):
            из_["why_not"] = с["why_not"]
            return из_
        сумма_лампорты = с["лампорты"]
    пр = проверить_перевод(откуда=откуда, куда=куда, лампорты=int(сумма_лампорты or 0),
                            баланс_лампорты=бал, конф=конф)
    из_["сумма_лампорты"] = сумма_лампорты
    из_["сумма_SOL"] = (сумма_лампорты or 0) / ЛАМПОРТОВ_В_SOL
    if not пр.get("ok"):
        из_["why_not"] = пр["why_not"]
        return из_
    if not живьём():
        из_.update(ok=True, dry=True,
                   why_not=f"сухой прогон: без {ENV_ЖИВЬЁМ}=1 ничего не уходит")
        return из_
    from dbot_rescue import build_sol_transfer, latest_blockhash  # noqa: PLC0415

    kp = _ключ_старого()
    if str(kp.pubkey()) != откуда:
        из_["why_not"] = ("ключ окружения даёт не тот адрес, что в конфиге -- "
                           "подписывать нельзя")
        return из_
    bh = latest_blockhash(call)
    tx = build_sol_transfer(kp, куда, int(сумма_лампорты), bh)
    рез = отправить_и_дождаться(call, tx)
    из_.update(подпись=рез["подпись"], село=рез["село"], слот=рез.get("слот"),
               ошибка_цепи=рез.get("ошибка"))
    из_["баланс_после"] = баланс(call, откуда)
    из_["баланс_получателя"] = баланс(call, куда)
    из_["ok"] = bool(рез["село"])
    if not из_["ok"]:
        из_["why_not"] = f"перевод не подтвердился: {рез.get('ошибка')}"
    return из_


def снять_нонс(*, путь_конфига: str | None = None) -> dict:
    """Забрать ренту со счёта nonce СТАРОГО кошелька на старый же кошелёк.

    Получатель тут -- сам старый кошелёк, а не новый адрес: это не отправка
    наружу, а возврат своей же ренты, и дальше она уедет общим переводом. Так
    у SOL остаётся ровно одна дверь наружу -- перевод().
    """
    из_ = {"ok": False, "why_not": None, "живьём": живьём()}
    конф = конфиг(путь_конфига)
    откуда = str(конф.get("старый_адрес") or "").strip()
    нонс = str(конф.get("старый_nonce") or "").strip()
    из_.update(кошелёк=откуда, нонс=нонс)
    if not (32 <= len(нонс) <= 44):
        из_["why_not"] = f"адрес счёта nonce в конфиге негодный: {нонс!r}"
        return из_
    call = _узел()
    о = call("getAccountInfo", [нонс, {"encoding": "jsonParsed"}]) or {}
    зн = о.get("value")
    if not зн:
        из_.update(ok=True, why_not="счёта nonce уже нет -- снимать нечего",
                   нечего=True)
        return из_
    лам = int(зн.get("lamports") or 0)
    разбор = ((зн.get("data") or {}).get("parsed") or {}).get("info") or {}
    полномочия = разбор.get("authority")
    из_.update(лампорты=лам, полномочия=полномочия)
    if полномочия != откуда:
        из_["why_not"] = (f"полномочия счёта nonce у {str(полномочия)[:12]}, а не у "
                           f"старого кошелька -- снимать нечем")
        return из_
    if лам <= 0:
        из_.update(ok=True, why_not="на счёте nonce нуль -- снимать нечего")
        return из_
    if not живьём():
        из_.update(ok=True, dry=True,
                   why_not=f"сухой прогон: без {ENV_ЖИВЬЁМ}=1 ничего не уходит")
        return из_
    import base64  # noqa: PLC0415

    import solders.system_program as sp  # noqa: PLC0415
    from solders.hash import Hash  # noqa: PLC0415
    from solders.message import MessageV0  # noqa: PLC0415
    from solders.pubkey import Pubkey  # noqa: PLC0415
    from solders.transaction import VersionedTransaction  # noqa: PLC0415

    from dbot_rescue import latest_blockhash  # noqa: PLC0415

    kp = _ключ_старого()
    if str(kp.pubkey()) != откуда:
        из_["why_not"] = "ключ окружения даёт не тот адрес, что в конфиге"
        return из_
    ix = sp.withdraw_nonce_account(sp.WithdrawNonceAccountParams(
        nonce_pubkey=Pubkey.from_string(нонс),
        authorized_pubkey=kp.pubkey(),
        to_pubkey=kp.pubkey(),
        lamports=лам))
    bh = latest_blockhash(call)
    msg = MessageV0.try_compile(kp.pubkey(), [ix], [], Hash.from_string(bh))
    vtx = VersionedTransaction(msg, [kp])
    рез = отправить_и_дождаться(
        call, base64.b64encode(bytes(vtx)).decode())
    из_.update(подпись=рез["подпись"], село=рез["село"], слот=рез.get("слот"),
               ошибка_цепи=рез.get("ошибка"),
               баланс_кошелька_после=баланс(call, откуда))
    из_["ok"] = bool(рез["село"])
    if not из_["ok"]:
        из_["why_not"] = f"снятие ренты nonce не подтвердилось: {рез.get('ошибка')}"
    return из_


