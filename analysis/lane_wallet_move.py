def self_test() -> int:
    всего = [0, 0]

    def chk(имя, условие, факт=None):
        всего[0] += 1
        if условие:
            всего[1] += 1
            print(f"  [ok  ] {имя}")
        else:
            print(f"  [ПЛОХО] {имя}" + (f" -- {факт}" if факт is not None else ""))

    СТАР = "21DqHDDPEfMhK1dHRkV9E8v8KTTSKQGApJAr1irC9j7w"
    НОВ = "4dPZMbReSobZVxfrzGLcD7xJN33pZhuUZix5HkTBTh4x"
    ЧУЖОЙ = "9WzDXwBbmkg8ZTbNMqUxvQRAyrZzDsGYdLVL9zYtAWWM"
    добрый = {"старый_адрес": СТАР, "новый_адрес": НОВ,
              "подтверждён_владельцем": True}

    # --- БОЕВОЙ КОНФИГ РЕПОЗИТОРИЯ: адрес именно подтверждённый владельцем.
    боевой = конфиг()
    chk("в боевом конфиге стоит подтверждение владельца",
        боевой.get("подтверждён_владельцем") is True, боевой.get("подтверждён_владельцем"))
    chk("и адрес получателя тот, что доложен владельцу",
        цель(боевой) == НОВ, цель(боевой))

    # --- ДВЕРЬ ОДНА: получатель только из конфига.
    chk("получатель не из конфига -- отказ",
        проверить_перевод(откуда=СТАР, куда=ЧУЖОЙ, лампорты=1_000_000,
                           баланс_лампорты=300_000_000,
                           конф=добрый)["ok"] is False, "")
    chk("и в причине сказано, что отклоняем",
        "отклоняю" in (проверить_перевод(откуда=СТАР, куда=ЧУЖОЙ, лампорты=1_000_000,
                                          баланс_лампорты=300_000_000,
                                          конф=добрый)["why_not"] or ""), "")
    chk("подтверждённый получатель проходит",
        проверить_перевод(откуда=СТАР, куда=НОВ, лампорты=1_000_000,
                           баланс_лампорты=300_000_000, конф=добрый)["ok"] is True, "")

    # --- НЕПОДТВЕРЖДЁННЫЙ КОНФИГ НЕ ОТКРЫВАЕТ ДВЕРЬ.
    for значение in (False, None, "yes", 1, "true"):
        к = dict(добрый, подтверждён_владельцем=значение)
        chk(f"подтверждение {значение!r} не считается подтверждением",
            проверить_перевод(откуда=СТАР, куда=НОВ, лампорты=1_000_000,
                               баланс_лампорты=300_000_000, конф=к)["ok"] is False,
            значение)

    # --- ОТПРАВИТЕЛЬ И СУММА.
    chk("отправитель не тот кошелёк -- отказ",
        проверить_перевод(откуда=ЧУЖОЙ, куда=НОВ, лампорты=1_000_000,
                           баланс_лампорты=300_000_000, конф=добрый)["ok"] is False, "")
    chk("перевод себе -- отказ",
        проверить_перевод(откуда=СТАР, куда=СТАР, лампорты=1_000_000,
                           баланс_лампорты=300_000_000,
                           конф=dict(добрый, новый_адрес=СТАР))["ok"] is False, "")
    chk("ноль -- отказ",
        проверить_перевод(откуда=СТАР, куда=НОВ, лампорты=0,
                           баланс_лампорты=300_000_000, конф=добрый)["ok"] is False, "")
    chk("отрицательная сумма -- отказ",
        проверить_перевод(откуда=СТАР, куда=НОВ, лампорты=-1,
                           баланс_лампорты=300_000_000, конф=добрый)["ok"] is False, "")
    chk("сумма без места под тариф -- отказ",
        проверить_перевод(откуда=СТАР, куда=НОВ, лампорты=300_000_000,
                           баланс_лампорты=300_000_000, конф=добрый)["ok"] is False, "")
    chk("сумма ровно баланс минус тариф -- проходит",
        проверить_перевод(откуда=СТАР, куда=НОВ,
                           лампорты=300_000_000 - БАЗОВЫЙ_ТАРИФ,
                           баланс_лампорты=300_000_000, конф=добрый)["ok"] is True, "")

    # --- ОСТАТОК СЧИТАЕТСЯ, А НЕ УГАДЫВАЕТСЯ.
    о = сумма_остатка(314_334_667)
    chk("остаток = баланс минус один тариф",
        о["ok"] is True and о["лампорты"] == 314_334_667 - БАЗОВЫЙ_ТАРИФ, о)
    chk("баланс меньше тарифа -- переводить нечего, и это сказано",
        сумма_остатка(1_000)["ok"] is False, сумма_остатка(1_000))
    chk("нулевой баланс -- отказ",
        сумма_остатка(0)["ok"] is False, "")

    # --- БЕЗ ЖИВОГО ФЛАГА НЕТ НИ ПОДПИСИ, НИ ОТПРАВКИ.
    было = os.environ.get(ENV_ЖИВЬЁМ)
    os.environ.pop(ENV_ЖИВЬЁМ, None)
    try:
        chk("без живого флага модуль считает себя сухим", живьём() is False, "")
    finally:
        if было is not None:
            os.environ[ENV_ЖИВЬЁМ] = было

    рабочая = Path(__file__).read_text(encoding="utf-8").split("def self_test")[0]
    chk("адрес получателя нигде не берётся из аргументов командной строки",
        "--kuda" not in рабочая and "--to" not in рабочая, "")
    # ОДНА ДВЕРЬ НАРУЖУ. Считаем именно ВЫЗОВ, а не упоминание: импорт этого
    # имени стоит рядом с вызовом, и считать оба означало бы проверять не то.
    chk("отправка в рабочей части ровно одна -- вызов send_raw_b64 в одном месте",
        рабочая.count("send_raw_b64(") == 1, рабочая.count("send_raw_b64("))
    chk("секрет нигде не печатается",
        "print(сырое" not in рабочая and "OWN_SEND_WALLET_KEY\")" in рабочая, "")

    print(f"самопроверка переезда полосы: {всего[1]}/{всего[0]} пройдено")
