#!/usr/bin/env python3
"""Билет для стабильных источников: что даёт билет 0.3 / 0.5 / 1 / 3 и сколько съедает сдвиг цены. Офлайн.

Вход: суточные файлы архива со состояниями пула (`bilet_*T16`, прогон 21.09 17Z – 01.10 17Z, билеты
0.3/0.5/1/3). Если их ещё нет -- считается по тем файлам, что есть (`porog14_*T16`, `kust_*T16`: билеты
0.1/0.3/0.5, состояний пула в них нет), и в странице это сказано.

Живое правило: покупка источника от 2 SOL-экв, наш вход «конец слота» (S0_дно) за ним, выход +108 слотов,
п.п. чистыми (0.002 SOL на круг), котировка WSOL, Pump AMM по модели v6. Ячейка -- как в отборе cand2.

Сдвиг цены считается аналитически по состояниям пула: на входе 100·f·a/(x+f·a) (у кривых 100·net/(x+net)),
на выходе 100·т/y_вых, где т -- купленные токены, y_вых -- токен-резерв состояния выхода. Это та доля
билета, которую забирает наш собственный сдвиг цены, отдельно от комиссии пула.

Выход: docs/podbivka_2026-10-03_bilet_stabilnye.md, data/podbivka/bilet_svod.json.
"""
from __future__ import annotations

import argparse
import collections
import glob
import gzip
import json
import statistics
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import podbivka_porog_razmera as PR  # noqa: E402

КОРЕНЬ = PR.КОРЕНЬ
П = PR.П
ЖИВОЙ_ПОРОГ = 2.0
ВЫХОД = 108
БИЛЕТЫ = (0.3, 0.5, 1.0, 3.0)
ДЛЯ_МОДЕЛИ = {"pump", "raydium-launchpad", "raydium-cpmm", "meteora-damm-v1"}
XYK = {"raydium-cpmm", "meteora-damm-v1", "pump-amm"}
N_МИН = 20


def ключи(б: float, H: int = ВЫХОД, вход: str = "S0_дно") -> list:
    """Модель пишет билет как repr float: 0.3 -> «0.3», 1 -> «1.0». Проверяем оба написания."""
    return [f"{вход}|{б}|{H}", f"{вход}|{б:g}|{H}"]


def пп(с: dict, б: float) -> float | None:
    пп_ = (с.get("модель") or {}).get("пп") or {}
    for k in ключи(б):
        if k in пп_:
            return пп_[k]
    return None


def причина(с: dict, б: float) -> str | None:
    """Почему сигнал не стал ячейкой правила -- по делу, а не «тип вне модели» на всё."""
    м = с.get("модель") or {}
    тип = с.get("pool")
    ок_тип = тип in ДЛЯ_МОДЕЛИ or (тип == "pump-amm" and м.get("модель_pump_amm") == "v6")
    if not ок_тип:
        return f"тип пула вне модели ({тип or 'нет типа'})"
    if с.get("quoteMint") != PR.K.WSOL:
        return "котировка не SOL"
    if с.get("по_окну") is not True:
        return "не первая покупка по окну 1800"
    if м.get("why_not"):
        return f"модель: {м['why_not']}"
    if пп(с, б) is None:
        return f"нет п.п. на выходе +{ВЫХОД} (ряд пула кончился раньше)"
    return None


def ячейка(с: dict, б: float) -> bool:
    return причина(с, б) is None


def пп_по_состояниям(с: dict, б: float, место: str = "S0_дно", выход: int | None = None):
    """п.п. при любом билете по состояниям пула -- та же формула, что в модели архива.

    Нужно для билетов, которых в прогоне не было (1 и 3 там, где считали 0.1/0.3), и для «минимального
    выгодного билета». Проверяется сверкой с собственными числами модели (--sverka).

    `место` -- точка входа из состояний прохода: «S0» (сразу после сделки источника), «S0_дно»
    (конец слота источника), «S1» (следующий слот) и «N16» / «N50», если они в проходе были.
    `выход` -- горизонт удержания в слотах; по умолчанию ВЫХОД.
    """
    д = сделка_по_состояниям(с, б, место, выход)
    if д is None:
        return None
    return round(д["пп"], 3)


def сделка_по_состояниям(с: dict, б: float, место: str = "S0_дно", выход: int | None = None,
                         издержки: float = 0.002, к_f: float = 1.0, к_g: float = 1.0,
                         налог_bps: float = 0.0) -> dict | None:
    """Круг по состояниям пула целиком: сколько токенов взяли, сколько SOL вернули, итог.

    Единственное место, где живёт формула модели архива; `пп_по_состояниям` -- обёртка над
    ней. Параметры сверх состояний нужны калибровке на живых сделках (`podbivka_kalibrovka`):
      * `издержки` -- SOL за круг (чаевые, приоритет, тариф, комиссия, запертая рента). В
        модели архива зашито 0.002; по живым сделкам расход другой, и это главная поправка;
      * `к_f`, `к_g` -- множители к наценке входа и выхода прохода (f и g подогнаны по
        хранилищам окна; на нашем фактическом месте в блоке они смещены);
      * `налог_bps` -- налог на перевод токена, если он есть (сотые доли процента).
    """
    м = с.get("модель") or {}
    сост = м.get("состояния") or {}
    вх = (сост.get("вход") or {}).get(место)
    вых = (сост.get("выход") or {}).get(str(выход if выход is not None else ВЫХОД))
    if not (вх and вых):
        return None
    масштаб = сост.get("масштаб") or 1.0
    x, y = float(вх[0]), float(вх[1])
    X0, Y0 = float(вых[0]), float(вых[1])
    пул = с.get("pool")
    fee = float(м.get("fee") or 0)
    f, g = м.get("f"), м.get("g")
    a = б * масштаб
    if пул in XYK:
        if not (f and g):
            return None
        f, g = f * к_f, g * к_g
        т = y * f * a / (x + f * a)
        вст = a if пул == "pump-amm" else f * a
    else:
        g = к_g
        net = a / (1 + fee)
        т = y * net / (x + net)
        вст = net
    if т <= 0:
        return None
    if налог_bps:
        т *= 1 - налог_bps / 10000.0
    X, Y = X0 + вст, Y0 - т
    if Y <= 0:
        return None
    out = X * g * т / (Y + т) if пул in XYK else X * т / (Y + т) * (1 - fee) * к_g
    итог = out - a - издержки * масштаб
    return {"out": out, "a": a, "токенов": т, "вставлено": вст, "масштаб": масштаб,
            "резерв_вход_sol": x / масштаб if масштаб else None,
            "сдвиг_вход_пп": 100 * (f if пул in XYK else 1) * a / (x + (f if пул in XYK else 1) * a),
            "сдвиг_выход_пп": 100 * т / (Y0 + т) if Y0 + т > 0 else None,
            "итог_sol": итог / масштаб if масштаб else итог,
            "пп": итог / a * 100}


def глубина(с: dict, б: float) -> dict:
    """Резерв на входе в SOL-экв., билет как % резерва и сдвиг цены на входе и выходе, п.п. билета."""
    м = с.get("модель") or {}
    сост = м.get("состояния") or {}
    масштаб = сост.get("масштаб") or 1.0
    вх = (сост.get("вход") or {}).get("S0_дно")
    вых = (сост.get("выход") or {}).get(str(ВЫХОД))
    из_ = {"резерв_sol": None, "билет_доля": None, "сдвиг_вход": None, "сдвиг_выход": None,
           "сдвиг_вход_прибл": None, "токенов": None}
    if not вх:
        # состояний пула в файле нет (прогон до правки): резерв берём из полей сигнала, сдвиг на входе --
        # приблизительно 100·a/(резерв+a) (без комиссии и без поправки f), выход не посчитать
        рез = с.get("резерв_sol") or с.get("вирт_резерв_sol")
        if рез:
            из_["резерв_sol"] = round(рез, 4)
            из_["билет_доля"] = round(100 * б / рез, 3)
            из_["сдвиг_вход_прибл"] = round(100 * б / (рез + б), 3)
        return из_
    x, y = float(вх[0]), float(вх[1])
    из_["резерв_sol"] = round(x / масштаб, 4) if масштаб else None
    a = б * масштаб                       # билет в единицах котировки
    f = м.get("f")
    fee = float(м.get("fee") or 0)
    if с.get("pool") in XYK and f:
        т = y * f * a / (x + f * a)
        из_["сдвиг_вход"] = round(100 * f * a / (x + f * a), 3)
    else:
        net = a / (1 + fee)
        т = y * net / (x + net)
        из_["сдвиг_вход"] = round(100 * net / (x + net), 3)
    из_["токенов"] = т
    if из_["резерв_sol"]:
        из_["билет_доля"] = round(100 * б / из_["резерв_sol"], 3)
    if вых and float(вых[1]) > 0:
        из_["сдвиг_выход"] = round(100 * т / float(вых[1]), 3)
    return из_


def стат(v: list) -> dict:
    v = [x for x in v if x is not None]
    if not v:
        return {"n": 0}
    return {"n": len(v), "среднее": round(statistics.mean(v), 2), "медиана": round(statistics.median(v), 2),
            "в_плюсе": round(sum(1 for x in v if x > 0) / len(v), 3)}


def кв(v: list, q: float) -> float | None:
    v = sorted(x for x in v if x is not None)
    if not v:
        return None
    i = min(len(v) - 1, max(0, int(round(q * (len(v) - 1)))))
    return round(v[i], 3)


def собрать(шаблоны: list, адреса: set) -> tuple[dict, dict]:
    по: dict = {a: {"сигналов": 0, "по_билету": {б: [] for б in БИЛЕТЫ}, "строки": [],
                    "вне_модели": collections.Counter(), "по_типам": {}} for a in адреса}
    счёт = {"файлов": 0, "сигналов": 0, "в_окне": 0, "от2": 0, "дублей": 0, "сутки": [], "ошибки": []}
    видел = set()
    for шаб in шаблоны:
        for f in sorted(x for x in glob.glob(str(П / "arhiv_den" / шаб)) if "_vne_" not in Path(x).name):
            д = json.loads(gzip.decompress(Path(f).read_bytes()))
            счёт["файлов"] += 1
            счёт["сутки"].append(Path(f).name)
            счёт["ошибки"] += [f"{Path(f).name}: {x}" for x in (д.get("счёт") or {}).get("ошибки") or []]
            for с in д.get("сигналы") or []:
                счёт["сигналов"] += 1
                if с.get("trader") not in по or not PR.окно(с, f):
                    continue
                if с["signature"] in видел:
                    счёт["дублей"] += 1
                    continue
                видел.add(с["signature"])
                счёт["в_окне"] += 1
                if (с.get("sol") or 0) < ЖИВОЙ_ПОРОГ:
                    continue
                счёт["от2"] += 1
                к = по[с["trader"]]
                к["сигналов"] += 1
                тип = с.get("pool")
                пр = причина(с, 0.3)
                if пр:
                    к["вне_модели"][пр] += 1
                    continue
                стр = {"signature": с["signature"], "mint": с.get("mint"), "block": с.get("block"),
                       "timestamp": с.get("timestamp"), "sol": с.get("sol"), "pool": тип,
                       "пп": {f"{б:g}": пп(с, б) for б in БИЛЕТЫ if пп(с, б) is not None},
                       **{f"гл_{k}": v for k, v in глубина(с, 0.3).items()}}
                к["строки"].append(стр)
                к["по_типам"].setdefault(тип, []).append(стр)
                for б in БИЛЕТЫ:
                    v = пп(с, б)
                    if v is not None:
                        к["по_билету"][б].append(v)
            del д
    return по, счёт


def main() -> int:
    import podbivka_run as R  # noqa: PLC0415
    р = argparse.ArgumentParser()
    р.add_argument("--shablony", default="", help="через запятую; по умолчанию bilet_*T16, иначе что есть")
    а = р.parse_args()
    адреса = json.loads((П / "bilet_adresa.json").read_text(encoding="utf-8"))["адреса"]
    шаб = [x for x in а.shablony.split(",") if x]
    полный = bool(glob.glob(str(П / "arhiv_den" / "bilet_*T16.json.gz")))
    if not шаб:
        шаб = ["bilet_*T16.json.gz"] if полный else ["porog14_*T16.json.gz", "kust_*T16.json.gz"]
    по, счёт = собрать(шаб, set(адреса))

    def клетка(s: dict) -> str:
        if not s.get("n"):
            return "— | — | — | —"
        if s["n"] < N_МИН:
            return f"n={s['n']} (мало) | — | — | —"
        return f"{s['n']} | {s['среднее']:+.2f} | {s['медиана']:+.2f} | {s['в_плюсе']:.0%}"

    md = ["# Подбивка: билет для стабильных источников (6qudAN2k и DYAn4XpA)", "",
          f"Файлы архива: {', '.join(шаб)} -- суток {счёт['файлов']}"
          + ("" if полный else " (прогон с билетами 1 и 3 ещё идёт: пока считаю по тем файлам, что есть --"
                               " билеты 0.3 и 0.5, состояний пула в них нет, поэтому сдвиг цены на выходе"
                               " не посчитан)")
          + f". Сигналов в окне {счёт['в_окне']}, из них по живому правилу (покупка источника от "
          f"{ЖИВОЙ_ПОРОГ:g} SOL-экв) {счёт['от2']}, дублей {счёт['дублей']}, ошибок чтения часов "
          f"{len(счёт['ошибки'])}.", "",
          "Живое правило: наш вход «конец слота» за источником, выход **+108** слотов, п.п. чистыми "
          "(0.002 SOL на круг), котировка WSOL, Pump AMM по модели v6; ячейка -- как в отборе cand2. "
          "«Сдвиг цены» -- та доля билета, которую забирает наше собственное движение цены, отдельно от "
          "комиссии пула: на входе 100·f·a/(x+f·a) (у кривых 100·net/(x+net)), на выходе 100·т/y_выхода. "
          "Ничего не рекомендуется.", "",
          "## 1. Сигнал при разном билете", "",
          "| адрес | билет | n | среднее, п.п. | медиана, п.п. | в плюсе | к 0.3: среднее / медиана, п.п. |",
          "|---|---|---|---|---|---|---|"]
    for a in адреса:
        к = по[a]
        б0 = к["по_билету"][0.3]
        for б in БИЛЕТЫ:
            s = стат(к["по_билету"][б])
            пары = [(x["пп"].get(f"{б:g}"), x["пп"].get("0.3")) for x in к["строки"]
                    if x["пп"].get(f"{б:g}") is not None and x["пп"].get("0.3") is not None]
            раз = [p - q for p, q in пары]
            к_03 = (f"{statistics.mean(раз):+.2f} / {statistics.median(раз):+.2f}"
                    if раз and б != 0.3 else ("— (это и есть 0.3)" if б == 0.3 else "—"))
            md.append(f"| `{a[:8]}` | {б:g} | " + клетка(s) + f" | {к_03} |")
        if not б0:
            md.append(f"| `{a[:8]}` | — | нет ячеек по живому правилу | | | | |")
    md += ["", "## 2. Глубина пула и сдвиг цены (на входе, билет 0.3)", "",
           "| адрес | тип пула | ячеек | резерв на входе, SOL: p10 / p50 / p90 | билет 0.3 как % резерва: "
           "p50 | сдвиг на входе, п.п.: p50 / p90 | сдвиг на выходе, п.п.: p50 / p90 |",
           "|---|---|---|---|---|---|---|"]
    for a in адреса:
        for тип, стр in sorted(по[a]["по_типам"].items(), key=lambda kv: -len(kv[1])):
            рез = [x["гл_резерв_sol"] for x in стр]
            дол = [x["гл_билет_доля"] for x in стр]
            св = [x["гл_сдвиг_вход"] if x["гл_сдвиг_вход"] is not None else x.get("гл_сдвиг_вход_прибл")
                  for x in стр]
            прибл = all(x["гл_сдвиг_вход"] is None for x in стр)
            сх = [x["гл_сдвиг_выход"] for x in стр]
            md.append(f"| `{a[:8]}` | {тип} | {len(стр)}"
                      + (f" | {кв(рез, 0.1)} / {кв(рез, 0.5)} / {кв(рез, 0.9)}" if any(рез) else " | —")
                      + (f" | {кв(дол, 0.5)} %" if any(дол) else " | —")
                      + (f" | {кв(св, 0.5)} / {кв(св, 0.9)}" + (" (прибл.)" if прибл else "")
                         if any(св) else " | не посчитано")
                      + (f" | {кв(сх, 0.5)} / {кв(сх, 0.9)}" if any(сх) else " | не посчитано") + " |")
    md += ["", "## 3. По типам пулов отдельно (билеты, n ≥ 20)", "",
           "| адрес | тип пула | n | 0.3: среднее / медиана | 0.5 | 1 | 3 |", "|---|---|---|---|---|---|---|"]
    for a in адреса:
        for тип, стр in sorted(по[a]["по_типам"].items(), key=lambda kv: -len(kv[1])):
            кл = []
            for б in БИЛЕТЫ:
                v = [x["пп"].get(f"{б:g}") for x in стр if x["пп"].get(f"{б:g}") is not None]
                s = стат(v)
                кл.append(f"{s['среднее']:+.2f} / {s['медиана']:+.2f}" if s.get("n", 0) >= N_МИН
                          else (f"n={s['n']} (мало)" if s.get("n") else "—"))
            md.append(f"| `{a[:8]}` | {тип} | {len(стр)} | " + " | ".join(кл) + " |")
    md += ["", "## 4. Что не посчитано и почему", "",
           "Сигналы живого правила, не ставшие ячейкой: по ним ни п.п., ни сдвиг цены не считаются. "
           "«Тип пула вне модели» -- DLMM, CLMM, DAMM v2, Whirlpool, агрегаторы: там состояние пула не "
           "x*y=k и не кривая. Остальные причины -- не про тип пула.", ""]
    for a in адреса:
        вм = по[a]["вне_модели"]
        md.append(f"- `{a}`: не стали ячейкой **{sum(вм.values())}** из {по[a]['сигналов']} сигналов "
                  "живого правила"
                  + (" -- " + ", ".join(f"{k}: {n}" for k, n in вм.most_common()) if вм else "") + ".")
    md.append("")
    out = КОРЕНЬ / "docs" / "podbivka_2026-10-03_bilet_stabilnye.md"
    out.write_text("\n".join(md) + "\n", encoding="utf-8")
    R.записано(out)
    дт = П / "bilet_svod.json"
    дт.write_text(json.dumps({"шаблоны": шаб, "полный_прогон": полный, "счёт": счёт,
                              "по_адресам": {a: {"сигналов": по[a]["сигналов"],
                                                 "вне_модели": dict(по[a]["вне_модели"]),
                                                 "по_билету": {f"{б:g}": стат(по[a]["по_билету"][б])
                                                               for б in БИЛЕТЫ},
                                                 "по_типам": {t: len(v) for t, v in по[a]["по_типам"].items()}}
                                             for a in адреса}},
                             ensure_ascii=False, indent=1), encoding="utf-8")
    R.записано(дт)
    print(out.name, "полный прогон" if полный else "предварительно (файлы 1/3 ещё идут)",
          {a[:8]: по[a]["сигналов"] for a in адреса}, flush=True)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
