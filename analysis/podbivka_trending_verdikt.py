# --- счёт круга -------------------------------------------------------------
def резервы(сост, кривая: bool):
    """(ts, q, t, q_реал) по той базе, какая верна для этого пула."""
    if not сост:
        return None
    ts, qр, tр, qв, tв = сост
    пары = ((qв, tв), (qр, tр)) if кривая else ((qр, tр), (qв, tв))
    for q, t in пары:
        try:
            q, t = float(q), float(t)
        except (TypeError, ValueError):
            continue
        if q > 0 and t > 0:
            try:
                qреал = float(qр)
            except (TypeError, ValueError):
                qреал = None
            return (ts, q, t, qреал)
    return None


def круг(вх, вых, билет: float):
    """Итог круга в SOL по инварианту x*y, издержки постоянные."""
    if not (вх and вых):
        return None
    _, q0, t0, _ = вх
    _, q1, t1, _ = вых
    if min(q0, t0, q1, t1) <= 0:
        return None
    токенов = t0 - (q0 * t0) / (q0 + билет)
    if токенов <= 0:
        return None
    выручка = q1 - (q1 * t1) / (t1 + токенов)
    return выручка - билет - ИЗДЕРЖКИ


# --- статистика -------------------------------------------------------------
def Ф(z: float) -> float:
    return 0.5 * (1 + math.erf(z / math.sqrt(2)))


def знаковый_односторонний(плюс: int, n: int) -> float:
    """P(X >= плюс) при p = 0.5: точно до n = 1000, дальше нормальное приближение."""
    if n <= 0:
        return 1.0
    if n <= 1000:
        return min(1.0, sum(math.comb(n, i) for i in range(плюс, n + 1)) / 2 ** n)
    z = (плюс - 0.5 - n / 2) / math.sqrt(n / 4)
    return max(0.0, min(1.0, 1 - Ф(z)))


def усечённое_без_верхних(в: list, доля: float = 0.05):
    if not в:
        return None
    с = sorted(в)
    к = int(len(с) * (1 - доля))
    с = с[:к] if к >= 1 else с
    return st.fmean(с) if с else None


def ди_низ_нормальное(в: list):
    if len(в) < 2:
        return None
    return st.fmean(в) - 1.96 * st.stdev(в) / math.sqrt(len(в))


def ди_низ_бутстрап(в: list, сид: int):
    if len(в) < 10:
        return None
    рнд = random.Random(сид)
    n = len(в)
    ср = sorted(st.fmean(рнд.choices(в, k=n)) for _ in range(БУТСТРАП))
    return ср[int(0.025 * БУТСТРАП)]


def половины(по_дням: dict) -> tuple:
    дни = sorted(по_дням)
    if len(дни) < 2:
        return (None, None)
    рез = len(дни) // 2
    а = [x for д in дни[:рез] for x in по_дням[д]]
    б = [x for д in дни[рез:] for x in по_дням[д]]
    return (st.fmean(а) if а else None, st.fmean(б) if б else None)


def стандарт(значения: list, по_дням: dict, сочетаний: int, сид: int,
             быстро: bool = False) -> dict:
    """Все пункты стандарта по одному сочетанию. быстро -- без бутстрапа (для перемешанных)."""
    n = len(значения)
    if not n:
        return {"n": 0, "прошёл": False}
    ср = st.fmean(значения)
    плюс = sum(1 for x in значения if x > 0)
    суток_в_плюсе = sum(1 for д, в in по_дням.items() if в and st.fmean(в) > 0)
    п1, п2 = половины(по_дням)
    ди = ди_низ_нормальное(значения) if быстро else ди_низ_бутстрап(значения, сид)
    усеч = усечённое_без_верхних(значения)
    p = знаковый_односторонний(плюс, n)
    порог = 0.05 / сочетаний
    пункты = {
        "n>=100": n >= 100,
        "среднее>0": ср > 0,
        "ди_низ>0": ди is not None and ди > 0,
        "усечённое>0": усеч is not None and усеч > 0,
        "суток_в_плюсе>=60%": len(по_дням) > 0 and суток_в_плюсе / len(по_дням) >= 0.6,
        "обе_половины>0": (п1 is not None and п2 is not None and п1 > 0 and п2 > 0),
        "знаковый<порог": p < порог,
    }
    return {"n": n, "среднее": round(ср, 6), "медиана": round(st.median(значения), 6),
            "усечённое_без_верхних5": None if усеч is None else round(усеч, 6),
            "ди_низ": None if ди is None else round(ди, 6),
            "доля_в_плюсе": round(плюс / n, 4),
            "суток": len(по_дням), "суток_в_плюсе": суток_в_плюсе,
            "половины": [None if п1 is None else round(п1, 6),
                         None if п2 is None else round(п2, 6)],
            "p_знаковый": round(p, 8), "порог_холма_бонферрони": round(порог, 8),
            "пункты": пункты, "прошёл": all(пункты.values())}


# --- чтение -----------------------------------------------------------------
def читать_первые(ф: Path) -> list:
    ряды = []
    with gzip.open(ф, "rb") as о:
        for б in о:
            try:
                р = json.loads(б.decode("utf-8", "replace"))
            except ValueError:
                continue
            if р.get("вид_строки") or "список" not in р:
                continue
            ряды.append(р)
    return ряды


def собрать_сделки(дни: list) -> dict:
    """По дням: сделки правила и контроля + описательное по адресам."""
    сделки = []          # {день, список, адрес, вид, пул, итог5/15/60, к5/15/60, билет}
    опис = {"создания": {}, "счёт": collections.Counter(),
            "покрытие": collections.defaultdict(collections.Counter)}
    появления_по_адресу = collections.defaultdict(list)   # (день, адрес) -> [(ts, список)]
    for день in дни:
        ф = П / f"trending_ceny_{день}.json.gz"
        if not ф.exists():
            опис["счёт"][f"нет_файла_{день}"] += 1
            continue
        с = json.loads(gzip.open(ф, "rt", encoding="utf-8").read())
        опис["счёт"]["суток"] += 1
        опис["счёт"]["часов"] += с["счёт"]["часов"]
        опис["счёт"]["строк_архива"] += с["счёт"]["строк"]
        if с["счёт"].get("ошибки"):
            опис["счёт"]["часов_с_ошибкой"] += len(с["счёт"]["ошибки"])
        for а, ts in с["создания"].items():
            стар = опис["создания"].get(а)
            if стар is None or ts < стар:
                опис["создания"][а] = ts
        for п in с["появления"]:
            адр, сп = п["а"], п["с"]
            появления_по_адресу[(день, адр)].append((п["t"], сп))
            свед = с["адреса"].get(адр) or {}
            пул = свед.get("пул")
            кот = свед.get("котировка")
            кривая = (пул or "") in КРИВЫЕ
            опис["покрытие"][сп]["появлений"] += 1
            if not свед.get("событий"):
                опис["покрытие"][сп]["нет_в_архиве"] += 1
                continue
            опис["покрытие"][сп]["в_архиве"] += 1
            if кот != WSOL:
                опис["покрытие"][сп]["котировка_не_sol"] += 1
                continue
            вх = резервы(п["к"].get("в"), кривая)
            свх = резервы(п["к"].get("с"), кривая)
            м = резервы(п["к"].get("м"), кривая)
            if м:
                опис["покрытие"][сп]["ликв_на_метке"] += 1
            if not вх:
                опис["покрытие"][сп]["нет_цены_на_входе"] += 1
                continue
            резерв = вх[3]
            билет = БИЛЕТ if резерв is None else min(БИЛЕТ, ДОЛЯ_РЕЗЕРВА * резерв)
            if билет <= БИЛЕТ_МИН:
                опис["покрытие"][сп]["билет_мал"] += 1
                continue
            билет_к = билет
            if свх and свх[3] is not None:
                билет_к = min(БИЛЕТ, ДОЛЯ_РЕЗЕРВА * свх[3])
            ряд = {"день": день, "список": сп, "адрес": адр, "вид": п["вид"],
                   "пул": пул, "билет": round(билет, 5), "метка": п["t"],
                   "ликв_на_метке": None if not м else м[3],
                   "итог": {}, "контроль": {}}
            for ш, ключ in zip(ВЫХОДЫ, ("в5", "в15", "в60")):
                вых = резервы(п["к"].get(ключ), кривая)
                ряд["итог"][ш] = (круг(вх, вых, билет)
                                  if вых and вых[0] >= вх[0] else None)
            if свх and билет_к > БИЛЕТ_МИН:
                for ш, ключ in zip(ВЫХОДЫ, ("с5", "с15", "с60")):
                    вых = резервы(п["к"].get(ключ), кривая)
                    ряд["контроль"][ш] = (круг(свх, вых, билет_к)
                                          if вых and вых[0] >= свх[0] else None)
            сделки.append(ряд)
            опис["покрытие"][сп]["в_счёте"] += 1
    return {"сделки": сделки, "опис": опис, "появления": появления_по_адресу}


# --- сочетания --------------------------------------------------------------
def пары_списков(появления: dict) -> set:
    """(день, адрес, список) второго появления, если две метки в разных списках за 10 мин."""
    вых = set()
    for (день, адр), в in появления.items():
        в = sorted(в)
        for i in range(1, len(в)):
            for j in range(i):
                if в[i][1] != в[j][1] and в[i][0] - в[j][0] <= ОКНО_ПАРЫ_С * 1000:
                    вых.add((день, адр, в[i][1]))
                    break
    return вых


def по_сочетаниям(сделки: list, пары: set, метки: dict | None = None) -> dict:
    """{(группа, выход): {день: [итоги]}} для правила; группа -- список или «пара»."""
    гр: dict = collections.defaultdict(lambda: collections.defaultdict(list))
    for i, с in enumerate(сделки):
        сп = метки[i] if метки else с["список"]
        for ш in ВЫХОДЫ:
            v = с["итог"].get(ш)
            if v is not None:
                гр[(сп, ш)][с["день"]].append(v)
        if (с["день"], с["адрес"], с["список"]) in пары:
            for ш in ВЫХОДЫ:
                v = с["итог"].get(ш)
                if v is not None:
                    гр[("в_двух_списках_за_10_мин", ш)][с["день"]].append(v)
    return гр


