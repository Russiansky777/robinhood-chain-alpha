#!/usr/bin/env python3
"""Пакет 04.10, п. А.4: капитал -- полоса против DBot (BATCH-5, BATCH-3). Только чтение.

Считается по живым сделкам, не по модели:
  * полоса -- выгрузки Code-1 (`data/podbivka/sdelki/vse_s_2709.json` и суточные файлы,
    склейка по `cid`): вложено `sol_in`, итог -- кириллическое `итог_po_cepi_sol`, иначе
    `итог_sol` с отметкой, время покупки -- `utc`, удержание по факту -- `hold_s_fact`
    (нет его -- `hold_s_plan`, нет и его -- удержание группы в слотах x 0.4 с);
  * DBot -- копия учёта Code-1 `data/podbivka/dbot/solana_trades_all_0410.json`: задачи
    BATCH-5 и BATCH-3, закрытые сделки, вложено `sol_in`, итог `net_sol`, удержание
    `held_seconds`.

Числа: SOL в сутки, ПИК одновременно занятого капитала (по времени открытия и закрытия
каждой сделки), SOL в сутки на 1 SOL пика, оборот, среднее занятое (интеграл занятого
капитала по времени / длину окна) и простой = 1 - среднее занятое / пик. Окно -- общее для
обеих сторон. Проверка вне выборки: ранние сутки против последних и две половины.

Капитал кошельков (сколько лежит) ни в одном файле подбивки не подтверждён, поэтому «простой
капитала» считается от ПИКА занятого, а не от баланса; баланс DBot ~4.9 SOL -- слово
владельца, здесь не проверялся.
Выход: data/podbivka/paket_kapital.json и docs/podbivka_<метка>_kapital.md.
"""
from __future__ import annotations

import argparse
import collections
import datetime as дт
import json
import statistics
import sys
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import podbivka_cand2 as C2  # noqa: E402
import podbivka_nedelya_bilet as N  # noqa: E402
import podbivka_paket_obshee as O  # noqa: E402

КОРЕНЬ = C2.КОРЕНЬ
П = C2.П
НАЧАЛО = "2026-09-27T00:00:00Z"
СЕК_В_СЛОТЕ = 0.4


def ts(с: str) -> float:
    return дт.datetime.strptime(с, "%Y-%m-%dT%H:%M:%SZ").replace(tzinfo=дт.timezone.utc).timestamp()


def utc(t: float) -> str:
    return дт.datetime.fromtimestamp(t, дт.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")


def полоса_сделки() -> tuple[list, dict]:
    по_cid: dict = {}
    откуда: list = []
    кандидаты = [П / "sdelki" / "vse_s_2709.json"]
    кандидаты += sorted((П / "sdelki").glob("sdelki_polosy_*.json"))
    кандидаты += sorted((П / "mesto").glob("vhod_*.json"))
    for f in кандидаты:
        if not f.exists():
            continue
        try:
            д = json.loads(f.read_text(encoding="utf-8"))
        except ValueError:
            continue
        ряды = д.get("ряды") if isinstance(д, dict) else д
        if not ряды:
            continue
        откуда.append({"файл": f.name, "рядов": len(ряды)})
        for r in ряды:
            if r.get("cid"):
                по_cid[r["cid"]] = r
    сделки, счёт = [], collections.Counter()
    for r in по_cid.values():
        и, из_ = N.итог_сделки(r)
        if и is None or not r.get("utc") or not r.get("sol_in"):
            счёт["без_итога_или_времени"] += 1
            continue
        держ = r.get("hold_s_fact") or r.get("hold_s_plan")
        if держ is None:
            слот = (O.ПОЛИТИКА.get(r.get("group")) or {}).get("удержание_слотов") or O.ВЫХОД_ГРУППЫ
            держ = float(слот) * СЕК_В_СЛОТЕ
            счёт["удержание_из_политики"] += 1
        сделки.append({"сторона": "полоса", "группа": r.get("group"), "cid": r.get("cid"),
                       "t0": ts(r["utc"]), "держ_с": float(держ), "вложено": float(r["sol_in"]),
                       "итог": float(и), "итог_откуда": из_})
    return сделки, {"файлы": откуда, "счёт": dict(счёт), "cid_всего": len(по_cid)}


def dbot_сделки(файл: Path) -> tuple[list, dict]:
    ряды = json.loads(файл.read_text(encoding="utf-8"))
    сделки, счёт = [], collections.Counter()
    for x in ряды:
        if x.get("task_name") not in ("BATCH-5", "BATCH-3"):
            continue
        if x.get("status") not in ("закрыта", "ручная продажа") or x.get("net_sol") is None:
            счёт["не_закрыта"] += 1
            continue
        if not x.get("buy_block_time") or not x.get("sol_in"):
            счёт["без_времени_или_вложения"] += 1
            continue
        сделки.append({"сторона": f"DBot {x['task_name']}", "группа": x["task_name"],
                       "cid": x.get("buy_signature"), "t0": float(x["buy_block_time"]),
                       "держ_с": float(x.get("held_seconds") or 0),
                       "вложено": float(x["sol_in"]), "итог": float(x["net_sol"]),
                       "итог_откуда": "учёт DBot"})
    return сделки, {"счёт": dict(счёт)}


def занятость(сделки: list) -> dict:
    """Пик и средняя занятость капитала по событиям открытия и закрытия."""
    if not сделки:
        return {}
    события = []
    for с in сделки:
        события.append((с["t0"], с["вложено"]))
        события.append((с["t0"] + max(с["держ_с"], 0.0), -с["вложено"]))
    # открытие раньше закрытия при одинаковом времени: иначе сделка с нулевым удержанием
    # закрывается до того, как открылась, и занятость «течёт» до конца окна
    события.sort(key=lambda e: (e[0], -e[1]))
    тек, пик, площадь = 0.0, 0.0, 0.0
    пред = события[0][0]
    for т, д in события:
        площадь += тек * (т - пред)
        пред = т
        тек += д
        пик = max(пик, тек)
    окно_с = события[-1][0] - события[0][0]
    среднее = площадь / окно_с if окно_с > 0 else 0.0
    # доля времени, когда открыта хотя бы одна позиция: иначе «простой» мерится о пустое окно
    # счёт открытых позиций -- ЦЕЛЫМ числом: сумма +x и -x по float оставляет остаток
    # порядка 1e-17, и «занято» потекло бы до конца окна
    открыто, занято_с, пред2 = 0, 0.0, события[0][0]
    for т, д in события:
        if открыто > 0:
            занято_с += т - пред2
        пред2 = т
        открыто += 1 if д > 0 else -1
    return {"пик_sol": round(пик, 4), "среднее_занято_sol": round(среднее, 4),
            "простой_доля": round(1 - среднее / пик, 3) if пик else None,
            "время_с_позицией_доля": round(занято_с / окно_с, 4) if окно_с > 0 else None,
            "занято_sol_на_занятую_секунду": (round(площадь / занято_с, 4) if занято_с else None),
            "окно_часов": round(окно_с / 3600, 2)}


def свод(сделки: list, н: float, к: float) -> dict:
    от = [с for с in сделки if н <= с["t0"] <= к]
    if не_пусто := bool(от):
        дни = len({time.strftime("%Y-%m-%d", time.gmtime(с["t0"])) for с in от}) or 1
    if not не_пусто:
        return {"n": 0}
    итог = sum(с["итог"] for с in от)
    вложено = sum(с["вложено"] for с in от)
    з = занятость(от)
    пик = з.get("пик_sol") or 0
    return {"n": len(от), "суток": дни, "итог_sol": round(итог, 6),
            "sol_в_сутки": round(итог / дни, 6),
            "оборот_sol": round(вложено, 4),
            "медиана_вложено": round(statistics.median([с["вложено"] for с in от]), 4),
            **з,
            "sol_в_сутки_на_1_sol_пика": round(итог / дни / пик, 6) if пик else None,
            "sol_в_сутки_на_1_sol_среднего": (round(итог / дни / з["среднее_занято_sol"], 6)
                                              if з.get("среднее_занято_sol") else None)}


def main() -> int:
    import podbivka_run as R  # noqa: PLC0415
    р = argparse.ArgumentParser()
    р.add_argument("--metka", default=time.strftime("%Y-%m-%d", time.gmtime()))
    р.add_argument("--dbot", default=str(П / "dbot" / "solana_trades_all_0410.json"))
    а = р.parse_args()

    пол, пол_счёт = полоса_сделки()
    дб, дб_счёт = dbot_сделки(Path(а.dbot))
    if not пол or not дб:
        print(f"нечего сравнивать: полоса {len(пол)}, DBot {len(дб)}", flush=True)
        return 1
    н = ts(НАЧАЛО)
    к = min(max(с["t0"] for с in пол), max(с["t0"] for с in дб))
    окно = {"с": utc(н), "до": utc(к),
            "суток": round((к - н) / 86400, 2)}

    дни_всех = sorted({time.strftime("%Y-%m-%d", time.gmtime(с["t0"]))
                       for с in пол + дб if н <= с["t0"] <= к})
    половина = ts(f"{дни_всех[len(дни_всех) // 2]}T00:00:00Z") if дни_всех else к
    посл = ts(f"{дни_всех[-1]}T00:00:00Z") if дни_всех else к

    стороны = {"полоса (все группы)": пол,
               "полоса: batch5 + lane_s0": [с for с in пол if с["группа"] in ("batch5", "lane_s0")],
               "DBot BATCH-5 + BATCH-3": дб,
               "DBot BATCH-5": [с for с in дб if с["группа"] == "BATCH-5"],
               "DBot BATCH-3": [с for с in дб if с["группа"] == "BATCH-3"]}
    разрезы = {"всё окно": (н, к), "первая половина": (н, половина),
               "вторая половина": (половина, к), "последние сутки (вне выборки)": (посл, к)}
    итог = {"что": "А.4 капитал: полоса против DBot, SOL в сутки на 1 SOL капитала и простой",
            "окно": окно, "полоса_источники": пол_счёт, "dbot_счёт": дб_счёт,
            "оговорка": "балансы кошельков ни одним файлом подбивки не подтверждены: "
                        "простой считается от ПИКА занятого капитала, а не от баланса; "
                        "баланс DBot ~4.9 SOL -- слово владельца, здесь не проверялся",
            "стороны": {}}
    for имя, сп in стороны.items():
        итог["стороны"][имя] = {подпись: свод(сп, *гр) for подпись, гр in разрезы.items()}
    out = П / "paket_kapital.json"
    out.write_text(json.dumps(итог, ensure_ascii=False, indent=1), encoding="utf-8")
    R.записано(out)

    def ф(v, формат="+.6f"):
        return "—" if v is None else format(v, формат)

    md = [f"# Капитал: полоса против DBot ({а.metka})", "",
          f"Окно общее: **{окно['с']} — {окно['до']}** ({окно['суток']} суток; конец — по той "
          f"стороне, где сделки кончаются раньше). Полоса — живые сделки из выгрузок Code-1 "
          f"(склейка по `cid`, {пол_счёт['cid_всего']} строк, в счёт {len(пол)}); DBot — учёт "
          f"Code-1 по задачам BATCH-5 и BATCH-3, закрытые сделки ({len(дб)}). Итог полосы — по "
          f"кириллическому полю, иначе `итог_sol`; итог DBot — `net_sol`.", "",
          f"Пик и средняя занятость считаются по времени открытия и закрытия каждой сделки "
          f"(полоса — `hold_s_fact`, нет его — план, нет и его — удержание группы × "
          f"{СЕК_В_СЛОТЕ} с, таких {пол_счёт['счёт'].get('удержание_из_политики', 0)}; "
          f"DBot — `held_seconds`). Балансы кошельков файлами не подтверждены, поэтому «простой» "
          f"— это доля пика, которая в среднем не занята, а не доля баланса.", ""]
    for имя, по_разрезам in итог["стороны"].items():
        md += [f"## {имя}", "",
               "| разрез | сделок | суток | итог SOL | SOL/сутки | пик занятого SOL "
               "| среднее занято | доля времени с позицией | занято на занятую секунду "
               "| SOL/сутки на 1 SOL пика | оборот SOL |",
               "|---|---|---|---|---|---|---|---|---|---|---|"]
        for подпись, v in по_разрезам.items():
            if not v.get("n"):
                md.append(f"| {подпись} | 0 | — | — | — | — | — | — | — | — | — |")
                continue
            md.append(f"| {подпись} | {v['n']} | {v['суток']} | {ф(v['итог_sol'], '+.4f')} "
                      f"| {ф(v['sol_в_сутки'])} | {ф(v.get('пик_sol'), '.4f')} "
                      f"| {ф(v.get('среднее_занято_sol'), '.4f')} "
                      f"| {ф(v.get('время_с_позицией_доля'), '.4f')} "
                      f"| {ф(v.get('занято_sol_на_занятую_секунду'), '.4f')} "
                      f"| {ф(v.get('sol_в_сутки_на_1_sol_пика'))} "
                      f"| {ф(v.get('оборот_sol'), '.2f')} |")
        md.append("")
    п_посл = итог["стороны"]["полоса (все группы)"]["последние сутки (вне выборки)"]
    д_посл = итог["стороны"]["DBot BATCH-5 + BATCH-3"]["последние сутки (вне выборки)"]
    п_всё = итог["стороны"]["полоса (все группы)"]["всё окно"]
    д_всё = итог["стороны"]["DBot BATCH-5 + BATCH-3"]["всё окно"]
    md += ["## Вывод", "",
           f"На всём окне полоса даёт {ф(п_всё.get('sol_в_сутки'))} SOL в сутки при пике "
           f"занятого капитала {ф(п_всё.get('пик_sol'), '.4f')} SOL — "
           f"{ф(п_всё.get('sol_в_сутки_на_1_sol_пика'))} SOL в сутки на 1 SOL пика; DBot "
           f"{ф(д_всё.get('sol_в_сутки'))} SOL в сутки при пике "
           f"{ф(д_всё.get('пик_sol'), '.4f')} SOL — "
           f"{ф(д_всё.get('sol_в_сутки_на_1_sol_пика'))} SOL в сутки на 1 SOL пика. На "
           f"последних сутках вне выборки: полоса {ф(п_посл.get('sol_в_сутки'))} против DBot "
           f"{ф(д_посл.get('sol_в_сутки'))} SOL в сутки.", "",
           f"Капитал простаивает почти всё время у обеих сторон: хоть одна позиция открыта "
           f"{ф((п_всё.get('время_с_позицией_доля') or 0) * 100, '.2f')} % времени у полосы и "
           f"{ф((д_всё.get('время_с_позицией_доля') or 0) * 100, '.2f')} % у DBot — удержание "
           f"меряется десятками секунд, а сделок в сутки единицы-десятки. Поэтому «простой» "
           f"здесь не про лишние SOL на кошельке, а про то, что один и тот же SOL успевает "
           f"обслужить много сделок: в среднем занято "
           f"{ф(п_всё.get('среднее_занято_sol'), '.4f')} SOL у полосы и "
           f"{ф(д_всё.get('среднее_занято_sol'), '.4f')} SOL у DBot при пиках "
           f"{ф(п_всё.get('пик_sol'), '.4f')} и {ф(д_всё.get('пик_sol'), '.4f')}.", "",
           "Ничего не меняется и не рекомендуется — решает владелец.", ""]
    стр = КОРЕНЬ / "docs" / f"podbivka_{а.metka}_kapital.md"
    стр.write_text("\n".join(md) + "\n", encoding="utf-8")
    R.записано(стр)
    print(f"{стр.name}: полоса {len(пол)} сделок, DBot {len(дб)}; на 1 SOL пика полоса "
          f"{п_всё.get('sol_в_сутки_на_1_sol_пика')} против DBot "
          f"{д_всё.get('sol_в_сутки_на_1_sol_пика')}", flush=True)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
