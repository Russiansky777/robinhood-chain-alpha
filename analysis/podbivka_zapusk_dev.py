#!/usr/bin/env python3
"""zapusk_dev по живому определению владельца: счёт на собранных сутках архива.

Определение (слово владельца 10.10): покупка создателя в транзакции создания, не Mayhem,
котировка SOL, наш вход в блок создания +1 / +2, выход 160 слотов, билет 0.01 и 0.1.

Как каждое условие читается из архива.

1. «Покупка создателя в транзакции создания». Архив её ВИДИТ -- на самой строке создания,
   а не отдельной строкой buy. Строка создания несёт и quoteAmount (сколько SOL вошло в
   кривую этой инструкцией), и состояние кривой уже ПОСЛЕ покупки. У кривой pump.fun
   канонический старт -- 30.0 SOL виртуальной квоты и 1 073 000 000 токенов; произведение
   k = x*y/1e9 = 32.19 на строке создания держится у ВСЕХ 48 075 SOL-кривых суток 07.10
   ровно. Значит x > 30.0 на строке создания -- это покупка внутри транзакции создания, а
   её размер восстанавливается как a = x - 30.0. Доля таких строк 81.8 % против 69.6 % в
   живом журнале Code-1: разница -- связки, где внутри транзакции создания покупает не сам
   создатель. Поэтому доля считается по обоим признакам, и это НЕ то же самое, что
   «создатель купил сам»; калибровка признака по журналу -- в sozdatel_ohvat.

2. «Не Mayhem». Флаг is_mayhem_mode лежит в счёте кривой (смещение 81 после
   дискриминатора), но RPC на каждый из 48 тысяч запусков в сутки не поставить. Архивный
   признак -- ДРЕЙФ k: у нормальной кривой произведение резервов держится ровно (своп его
   не двигает), у Mayhem правило цены другое и k уходит. На истине из 127 минтов, у которых
   флаг прочитан по цепи: дрейф есть у 105 из 109 Mayhem и у 0 из 18 не-Mayhem. Четыре
   промаха -- запуски с 1--3 событиями, где торговли не было и k двигаться не мог. Поэтому
   такие тихие запуски считаются отдельной строкой «неразличимо», и итог печатается и с
   ними, и без них.

3. Вход «створ+1» / «створ+2» -- с переносом вперёд (Z.модель): если в этом слоте никто не
   торговал, состояния в файле нет, но мы входим всё равно и платим по последней известной
   цене. Без переноса в счёт попадали бы только запуски, где в этом слоте УЖЕ кто-то
   торговал, а это известно лишь после входа.

4. Выход 160 слотов. Мёртвые запуски -- в счёт: пул, который после нас не торговался,
   продаётся по той же цене (круг_в_пустоту), а закрытый пул или пул, где продать нечем, --
   это потеря билета целиком, а не пропуск строки.

5. Глубина -- условие ВХОДА: билет не больше ДОЛЯ_РЕЗЕРВА от резерва пула.

Ожидание -- среднее после всех расходов, плюс срезанные средние без верхних 1 % и 5 %,
медиана, доверительный интервал бутстрэпом ПО СУТКАМ (сделки одних суток зависимы).

Только чтение собранных файлов. Выход: data/podbivka/zapusk_dev.json, docs/podbivka_zapusk_dev.md.
"""
from __future__ import annotations

import argparse
import collections
import glob
import gzip
import json
import statistics
import sys
import time
from array import array
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import podbivka_zapuski_svod as Z   # noqa: E402

КОРЕНЬ = Path(__file__).resolve().parent.parent
П = КОРЕНЬ / "data" / "podbivka"
WSOL = "So11111111111111111111111111111111111111112"
X0_КРИВОЙ = 30.0                 # канонический старт виртуальной квоты pump.fun, SOL
K0_КРИВОЙ = 32.19                # x0*y0/1e9 = 30.0 * 1.073e9 / 1e9
ДРЕЙФ_ПРЕДЕЛ = 1e-4             # больше -- кривая не константного произведения, Mayhem
СОБЫТИЙ_ТИХИЙ = 3                # столько событий и меньше -- дрейфу негде проявиться
БИЛЕТЫ = (0.01, 0.1)
МЕСТА = ("створ+1", "створ+2")
ВЫХОД = 160
ГОРИЗОНТЫ = ("20", "40", "60", "90", "120", "160", "230")
СЕМЯ = 20261010
ПРИЗНАК = "v_sozdanii"           # «v_sozdanii» или «dokupka» -- см. флаг --priznak


def файлы(префикс: str = "zap_") -> list:
    return [(Z.сутки_файла(Path(ф).stem), ф)
            for ф in sorted(glob.glob(str(П / "zapuski" / f"{префикс}*.json.gz")))]


def дрейф_k(р: dict) -> tuple:
    """(k0, максимальный относительный дрейф k по доступным горизонтам)."""
    вх = (р.get("вход") or {}).get("створ_дно")
    if not вх:
        return None, None
    k0 = float(вх[0]) * float(вх[1]) / 1e9
    if k0 <= 0:
        return None, None
    д = 0.0
    выход = р.get("выход") or {}
    for h in ГОРИЗОНТЫ:
        в = выход.get(h)
        if в and float(в[0]) > 0 and float(в[1]) > 0:
            д = max(д, abs(float(в[0]) * float(в[1]) / 1e9 / k0 - 1))
    return k0, д


def порода(р: dict) -> str:
    """«нормальная» / «mayhem» / «неразличимо» -- по дрейфу k и числу событий."""
    k0, д = дрейф_k(р)
    if k0 is None:
        return "без_створа"
    if д is not None and д > ДРЕЙФ_ПРЕДЕЛ:
        return "mayhem"
    if (р.get("событий") or 0) <= СОБЫТИЙ_ТИХИЙ:
        return "неразличимо"
    return "нормальная"


def проход(сп: list) -> tuple:  # noqa: PLR0912, PLR0915
    """Один проход по суткам. Ключ стола -- (порода, место, билет)."""
    дни = [д for д, _ in сп]
    номер = {д: i for i, д in enumerate(дни)}
    породы = ("нормальная", "неразличимо")
    ключи = [(г, м, б) for г in породы for м in МЕСТА for б in БИЛЕТЫ]
    стол = {k: {"итог": array("f"), "день": array("H"), "вид": bytearray()}
            for k in ключи}
    счёт: collections.Counter = collections.Counter()
    по_породе: collections.Counter = collections.Counter()
    dev_sol: list = []
    for д, путь in сп:
        дн = номер[д]
        тело = json.loads(gzip.open(путь, "rt", encoding="utf-8").read())
        for р in тело.get("ряды") or []:
            счёт["строк_всего"] += 1
            if р.get("правило") != "создание:create":
                continue
            счёт["создание_create"] += 1
            if р.get("пул") != "pump":
                счёт["не_кривая_pump"] += 1
                continue
            счёт["кривая_pump"] += 1
            if р.get("quoteMint") != WSOL:
                счёт["котировка_не_SOL"] += 1
                continue
            счёт["котировка_SOL"] += 1
            вх0 = (р.get("вход") or {}).get("створ_дно")
            if not вх0:
                счёт["без_состояния_створа"] += 1
                continue
            if ПРИЗНАК == "dokupka":
                # Подмножество «создатель докупил ОТДЕЛЬНОЙ транзакцией в блоке
                # создания»: это ровно тот признак, который сборщик ставил раньше --
                # строка buy в блоке створа, чей адрес совпал с адресом строки
                # создания. По суткам 07.10 таких 889 из 56 062 созданий pump (1.6 %).
                # Он НЕ пересекается с покупкой внутри транзакции создания: там
                # отдельной строки buy нет вовсе.
                бл = р.get("в_блоке_создания") or {}
                if not бл.get("создатель_купил"):
                    счёт["создатель_не_докупал_в_створе"] += 1
                    continue
                счёт["докупка_создателя_в_створе"] += 1
                dev_sol.append(float(бл.get("sol") or 0.0))
            else:
                if float(вх0[0]) <= X0_КРИВОЙ + 1e-9:
                    счёт["без_покупки_в_транзакции_создания"] += 1
                    continue
                счёт["покупка_в_транзакции_создания"] += 1
                dev_sol.append(float(вх0[0]) - X0_КРИВОЙ)
            г = порода(р)
            по_породе[г] += 1
            if г not in породы:
                continue
            с = Z.модель(р)
            if с is None:
                счёт["модель_не_собралась"] += 1
                continue
            счёт[f"в_счёте_{г}"] += 1
            for м in МЕСТА:
                for б in БИЛЕТЫ:
                    вх = (с["модель"]["состояния"].get("вход") or {}).get(м)
                    if not вх:
                        счёт[f"без_входа_{м}"] += 1
                        continue
                    if б > Z.ДОЛЯ_РЕЗЕРВА * float(вх[0]):
                        счёт[f"билет_глубже_{Z.ДОЛЯ_РЕЗЕРВА}_резерва|{м}|{б}"] += 1
                        continue
                    итог, вид, _ = Z.круг_с_видом(с, б, м, ВЫХОД)
                    if итог is None:
                        счёт[f"круг_нет|{вид}"] += 1
                        continue
                    т = стол[(г, м, б)]
                    т["итог"].append(итог)
                    т["день"].append(дн)
                    т["вид"].append(Z.КОД_ВИДА.get(вид, 255))
        del тело
        print(f"  {д}: строк {счёт['строк_всего']}, "
              f"с покупкой в створе {счёт['покупка_в_транзакции_создания']}", flush=True)
    return стол, дни, счёт, по_породе, dev_sol


def свод(т: dict, дни: list, б: float) -> dict:
    v = list(т["итог"])
    if not v:
        return {"сделок": 0}
    по_суткам: dict = collections.defaultdict(list)
    for итог, д in zip(v, т["день"]):
        по_суткам[дни[д]].append(итог)
    низ, верх = Z.ди_по_суткам(по_суткам, seed=СЕМЯ)
    виды = collections.Counter(Z.ИЗ_КОДА_ВИДА.get(к, "?") for к in т["вид"])
    среднее = statistics.fmean(v)
    из_ = {"сделок": len(v), "суток": len(по_суткам), "билет": б,
           "ожидание_sol": round(среднее, 8),
           "ожидание_пп": round(100 * среднее / б, 4),
           "ди_низ_sol": round(низ, 8) if низ is not None else None,
           "ди_верх_sol": round(верх, 8) if верх is not None else None,
           "без_верх_1_sol": round(Z.срезанное(v, 0.01), 8),
           "без_верх_5_sol": round(Z.срезанное(v, 0.05), 8),
           "медиана_sol": round(statistics.median(v), 8),
           "в_плюсе_проц": round(100 * sum(1 for x in v if x > 0) / len(v), 2),
           "худшая_sol": round(min(v), 8), "лучшая_sol": round(max(v), 8),
           "виды": dict(виды),
           "итог_sol_в_сутки": round(sum(v) / max(1, len(по_суткам)), 6),
           "сделок_в_сутки": round(len(v) / max(1, len(по_суткам)), 1)}
    из_["вердикт"] = (
        "плюс" if (из_["ди_низ_sol"] is not None and из_["ди_низ_sol"] > 0
                   and из_["без_верх_5_sol"] > 0 and из_["медиана_sol"] > 0)
        else "минус" if (из_["ди_верх_sol"] is not None and из_["ди_верх_sol"] < 0)
        else "не_решено")
    return из_


def кванты(v: list) -> dict:
    if not v:
        return {"n": 0}
    v = sorted(v)

    def q(p):
        return round(v[min(len(v) - 1, int(p * len(v)))], 6)
    return {"n": len(v), "p1": q(0.01), "p10": q(0.10), "p25": q(0.25),
            "медиана": q(0.5), "p75": q(0.75), "p90": q(0.90), "p99": q(0.99),
            "среднее": round(statistics.fmean(v), 6), "макс": round(v[-1], 4)}


def страница(т: dict) -> str:
    л = ["# zapusk_dev: покупка в транзакции создания, кривая pump.fun",
         "",
         f"Суток {т['суток']}, {т['дни'][0]} .. {т['дни'][-1]}. "
         f"Выход {ВЫХОД} слотов, издержки круга {Z.ИЗДЕРЖКИ} SOL, множитель выхода "
         f"к_g {Z.К_G}, билет не больше {Z.ДОЛЯ_РЕЗЕРВА:.0%} резерва на входе.",
         "",
         "## Доля в архиве", "",
         "| сито | строк |", "|---|---|"]
    for k in ("создание_create", "кривая_pump", "котировка_SOL",
              "покупка_в_транзакции_создания", "докупка_создателя_в_створе"):
        л.append(f"| {k} | {т['счёт'].get(k, 0)} |")
    for k, n in sorted(т["по_породе"].items(), key=lambda kv: -kv[1]):
        л.append(f"| порода: {k} | {n} |")
    л += ["",
          "Размер покупки в транзакции создания, восстановленный как x − 30.0 SOL: "
          + ", ".join(f"{k} {v}" for k, v in т["размер_покупки"].items()
                      if k in ("n", "p10", "медиана", "p90", "среднее", "макс")),
          "",
          "## Ожидание на сделку", "",
          "| порода | место | билет | сделок | суток | ожидание, SOL | ДИ | без верх.1 % | "
          "без верх.5 % | медиана | в плюсе | вердикт |",
          "|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for ключ, c in т["строки"].items():
        if not c.get("сделок"):
            continue
        г, м, б = ключ.split("|")
        ди = (f"{c['ди_низ_sol']:+.5f} .. {c['ди_верх_sol']:+.5f}"
              if c["ди_низ_sol"] is not None else "—")
        л.append(f"| {г} | {м} | {б} | {c['сделок']} | {c['суток']} | "
                 f"{c['ожидание_sol']:+.5f} | {ди} | {c['без_верх_1_sol']:+.5f} | "
                 f"{c['без_верх_5_sol']:+.5f} | {c['медиана_sol']:+.5f} | "
                 f"{c['в_плюсе_проц']} % | {c['вердикт']} |")
    л += ["", "## Чем «не Mayhem» читается из архива", "",
          "Флаг is_mayhem_mode лежит в счёте кривой, но RPC на каждый запуск не поставить. "
          "Архивный признак -- дрейф произведения резервов k: у нормальной кривой своп его "
          "не двигает, у Mayhem правило цены другое и k уходит. На 127 минтах, у которых "
          "флаг прочитан по цепи, дрейф есть у 105 из 109 Mayhem и у 0 из 18 не-Mayhem; "
          "четыре промаха -- запуски с 1--3 событиями, где k двигаться не мог. Такие "
          "запуски идут строкой «неразличимо» отдельно.", ""]
    return "\n".join(л)


def main() -> int:
    р_ = argparse.ArgumentParser()
    р_.add_argument("--prefiks", default="zap_")
    р_.add_argument("--metka", default="")
    р_.add_argument("--k-g", type=float, default=None,
                    help="множитель наценки выхода; по умолчанию общий фит 0.9908. "
                         "Вердикт обязан держаться и при 1.0 (как считает программа), "
                         "и при 0.979 (худшая крупная группа живых сделок)")
    р_.add_argument("--izderzhki", type=float, default=None,
                    help="издержки круга в SOL; по умолчанию замер на живых сделках")
    р_.add_argument("--priznak", default="v_sozdanii",
                    choices=("v_sozdanii", "dokupka"),
                    help="v_sozdanii -- покупка ВНУТРИ транзакции создания (x > 30.0 на "
                         "строке создания); dokupka -- создатель докупил ОТДЕЛЬНОЙ "
                         "транзакцией в блоке создания (строка buy с его адресом)")
    а = р_.parse_args()
    global ПРИЗНАК  # noqa: PLW0603
    ПРИЗНАК = а.priznak
    if а.k_g is not None:
        Z.К_G = а.k_g
    if а.izderzhki is not None:
        Z.ИЗДЕРЖКИ = а.izderzhki
    сп = файлы(а.prefiks)
    if not сп:
        print(f"нет файлов {а.prefiks}* -- считать нечего", flush=True)
        return 2
    print(f"суток {len(сп)}: {сп[0][0]} .. {сп[-1][0]}", flush=True)
    стол, дни, счёт, по_породе, dev_sol = проход(сп)
    строки = {}
    for (г, м, б), т in стол.items():
        c = свод(т, дни, б)
        if c.get("сделок"):
            строки[f"{г}|{м}|{б}"] = c
    тело = {"что": "zapusk_dev: покупка в транзакции создания на кривой pump.fun, "
                   "не Mayhem, вход створ+1/+2, выход 160 слотов",
            "когда": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
            "суток": len(дни), "дни": дни,
            "определение": {"площадка": "pump (кривая pump.fun)", "котировка": WSOL,
                            "признак": ПРИЗНАК,
                            "признак_покупки": (
                                f"x на строке создания > {X0_КРИВОЙ} SOL"
                                if ПРИЗНАК == "v_sozdanii"
                                else "строка buy в блоке створа с адресом создателя "
                                     "(покупка ОТДЕЛЬНОЙ транзакцией)"),
                            "не_mayhem": f"дрейф k не больше {ДРЕЙФ_ПРЕДЕЛ}",
                            "места": list(МЕСТА), "выход_слотов": ВЫХОД,
                            "билеты": list(БИЛЕТЫ),
                            "издержки": Z.ИЗДЕРЖКИ, "к_g": Z.К_G,
                            "доля_резерва": Z.ДОЛЯ_РЕЗЕРВА},
            "счёт": dict(счёт), "по_породе": dict(по_породе),
            "размер_покупки": кванты(dev_sol), "строки": строки}
    ф = П / f"zapusk_dev{('_' + а.metka) if а.metka else ''}.json"
    ф.write_text(json.dumps(тело, ensure_ascii=False, indent=1), encoding="utf-8")
    стр = КОРЕНЬ / "docs" / f"podbivka_zapusk_dev{('_' + а.metka) if а.metka else ''}.md"
    стр.write_text(страница(тело), encoding="utf-8")
    try:
        import podbivka_run as R  # noqa: PLC0415
        R.записано(ф)
        R.записано(стр)
    except Exception:  # noqa: BLE001, S110
        pass
    print(json.dumps({"счёт": {k: v for k, v in счёт.items() if "|" not in k},
                      "по_породе": dict(по_породе),
                      "размер_покупки": тело["размер_покупки"],
                      "строки": строки}, ensure_ascii=False, indent=1), flush=True)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
