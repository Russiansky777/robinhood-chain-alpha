#!/usr/bin/env python3
"""Разложение нашей наценки на составляющие -- по УЖЕ посчитанному кэшу.

Ни одного сетевого вызова: всё берётся из
data/solana_pilot_block_autopsy_cache.json, который собрал поблочный разбор.

Что раскладываем. Путь цены от той, что была ДО покупки лидера, до той, по
которой купили мы:

    (а) влияние лидера      цена лидера / цена до лидера - 1
    (б) дрейф до нас        цена последней сделки перед нами / цена лидера - 1
    (в) наше влияние        наша цена / цена последней сделки перед нами - 1

Части перемножаются ТОЧНО:
    (1+а)(1+б)(1+в) = наша цена / цена до лидера
поэтому сходимость проверяется на произведении, а не на сумме. Простая
сумма процентов расходится с итогом на перекрёстные члены -- это не
ошибка данных, а арифметика процентов, и она показывается отдельной
колонкой, а не замазывается.

Резерв пула. В кэше его НЕТ: поблочный разбор читал только транзакции и
ни разу не спрашивал состояние пула. Поэтому резерв здесь ОЦЕНИВАЕТСЯ из
собственного следа лидера в предположении постоянного произведения:
при покупке на x SOL средняя цена исполнения растёт как (R+x)/R, значит
    R ≈ x / p,   где p -- измеренное влияние лидера долей.
Это ОЦЕНКА, а не измерение: она наследует все погрешности p и неверна для
пулов с другой кривой. Проверяется она тем, что по тому же R
предсказывается НАШЕ влияние и сравнивается с измеренным (в).
"""

from __future__ import annotations

import argparse
import json
import statistics
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
CACHE_PATH = REPO_ROOT / "data" / "solana_pilot_block_autopsy_cache.json"
OUT_PATH = REPO_ROOT / "data" / "solana_pilot_markup_split.json"

# Сколько сделок в выборке A (остальные -- Б). Берётся из порядка кэша:
# разбор писал сначала всю A, потом всю Б.
A_SIZE = 7


def last_price_before_us(blocks: list[dict]) -> tuple[float | None, dict | None]:
    """Цена последней сделки с посчитанной ценой строго ДО нашей."""
    ours_at = None
    for i, b in enumerate(blocks):
        if b.get("кто") == "МЫ":
            ours_at = i
            break
    if ours_at is None:
        return None, None
    for b in reversed(blocks[:ours_at]):
        if b.get("цена") is not None:
            return b["цена"], b
    return None, None


def split_one(v: dict) -> dict:
    out: dict = {
        "mint": v.get("mint"),
        "когда": v.get("наша_покупка_utc"),
        "лидер_sol": v.get("лидер_sol"),
        "наш_вход_sol": v.get("наш_вход_sol"),
        "итог_gross_pct": v.get("итог_gross_pct"),
        "наценка_к_лидеру_pct": v.get("наша_наценка_к_лидеру_pct"),
    }
    p_before = v.get("цена_до_лидера")
    p_lead = v.get("лидер_цена")
    p_ours = v.get("наша_цена")
    blocks = v.get("блоки") or []
    p_prev, prev_row = last_price_before_us(blocks)

    if p_lead is None or p_ours is None:
        out["не_удалось"] = "нет цены лидера или нашей -- раскладывать нечего"
        return out

    # (а)
    if p_before:
        out["а_влияние_лидера_pct"] = round((p_lead / p_before - 1) * 100, 3)
    else:
        out["а_влияние_лидера_pct"] = None
        out["а_почему_нет"] = ("до сделки лидера в просмотренном окне (30 с) нет ни одной "
                                "сделки с посчитанной ценой; из резерва пула взять нельзя -- "
                                "разбор состояние пула не читал")
    # (б) и (в)
    if p_prev is None:
        # Мы -- первая сделка с ценой после лидера: дрейфа нет по определению,
        # и весь остаток наценки -- наше собственное влияние.
        out["б_дрейф_до_нас_pct"] = 0.0
        out["б_пояснение"] = "между лидером и нами не было сделок с посчитанной ценой"
        out["в_наше_влияние_pct"] = round((p_ours / p_lead - 1) * 100, 3)
    else:
        out["б_дрейф_до_нас_pct"] = round((p_prev / p_lead - 1) * 100, 3)
        out["в_наше_влияние_pct"] = round((p_ours / p_prev - 1) * 100, 3)
        out["б_последняя_сделка_перед_нами"] = {
            "кто": prev_row.get("кто"), "сторона": prev_row.get("сторона"),
            "sol": prev_row.get("sol"), "слот_плюс": prev_row.get("слот_плюс")}

    a, b, c = out.get("а_влияние_лидера_pct"), out["б_дрейф_до_нас_pct"], out["в_наше_влияние_pct"]
    # Сходимость проверяется на НЕокруглённых долях: округление до трёх
    # знаков само по себе даёт расхождение в тысячные, и проверка ловила бы
    # собственное форматирование вместо ошибки в данных.
    fa = (p_lead / p_before - 1) if p_before else None
    fb = (p_prev / p_lead - 1) if p_prev is not None else 0.0
    fc = (p_ours / p_prev - 1) if p_prev is not None else (p_ours / p_lead - 1)
    if a is not None:
        точно = ((1 + fa) * (1 + fb) * (1 + fc) - 1) * 100
        факт = (p_ours / p_before - 1) * 100
        out["итог_от_цены_до_лидера_pct"] = round(факт, 3)
        out["произведение_частей_pct"] = round(точно, 3)
        out["сходимость_произведения_пп"] = round(точно - факт, 6)
        out["простая_сумма_частей_pct"] = round(a + b + c, 3)
        out["перекрёстные_члены_пп"] = round((a + b + c) - факт, 3)
        out["расхождение_суммы_больше_1пп"] = abs((a + b + c) - факт) > 1.0
    # Наценка к лидеру -- это (б) и (в) вместе, без (а): (а) лежит НИЖЕ
    # нашей точки отсчёта.
    наценка_факт = (p_ours / p_lead - 1) * 100
    out["наценка_проверка_pct"] = round(наценка_факт, 3)
    out["наценка_произведение_бв_pct"] = round(((1 + fb) * (1 + fc) - 1) * 100, 3)
    out["наценка_сходимость_пп"] = round(((1 + fb) * (1 + fc) - 1) * 100 - наценка_факт, 9)

    # Оценка резерва пула из следа лидера (предположение о постоянном
    # произведении). Не измерение -- оценка, и она зависит от (а).
    if a is not None and a > 0 and v.get("лидер_sol"):
        R = v["лидер_sol"] / (a / 100)
        out["резерв_пула_sol_оценка"] = round(R, 2)
        out["покупка_лидера_к_резерву"] = round(v["лидер_sol"] / R, 4)
        # Резерв к моменту НАШЕЙ покупки вырос на покупки до нас.
        добавлено = sum(x.get("sol") or 0 for x in blocks
                        if x.get("сторона") == "покупка" and x.get("кто") != "МЫ")
        R_ours = R + добавлено
        ожид = (v.get("наш_вход_sol") or 0) / R_ours * 100 if R_ours else None
        out["наше_влияние_ожидаемое_pct"] = round(ожид, 3) if ожид is not None else None
        if ожид is not None and out.get("в_наше_влияние_pct") is not None:
            out["наше_влияние_модель_минус_факт_пп"] = round(ожид - out["в_наше_влияние_pct"], 3)
    else:
        out["резерв_пула_sol_оценка"] = None
        out["почему_нет_резерва"] = ("резерв оценивается из влияния лидера; влияния нет -- "
                                      "оценки нет. Прямое чтение резерва требует отдельного "
                                      "прохода по сети (getAccountInfo по хранилищам пула)")
    return out


def summarise(label: str, items: list[dict]) -> dict:
    def med(key):
        v = [x[key] for x in items if x.get(key) is not None]
        return round(statistics.median(v), 3) if v else None
    return {
        "выборка": label, "сделок": len(items),
        "медиана_а_влияние_лидера_pct": med("а_влияние_лидера_pct"),
        "медиана_б_дрейф_pct": med("б_дрейф_до_нас_pct"),
        "медиана_в_наше_влияние_pct": med("в_наше_влияние_pct"),
        "медиана_наценки_pct": med("наценка_проверка_pct"),
        "медиана_резерва_пула_sol_оценка": med("резерв_пула_sol_оценка"),
        "медиана_лидер_к_резерву": med("покупка_лидера_к_резерву"),
        "медиана_лидер_sol": med("лидер_sol"),
        "медиана_итог_gross_pct": med("итог_gross_pct"),
        "сделок_с_расхождением_суммы_больше_1пп": sum(
            1 for x in items if x.get("расхождение_суммы_больше_1пп")),
    }


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--cache", default=str(CACHE_PATH))
    ap.add_argument("--a-size", type=int, default=A_SIZE)
    ap.add_argument("--self-test", action="store_true")
    args = ap.parse_args()
    if args.self_test:
        self_test()
        return

    path = Path(args.cache)
    if not path.exists():
        raise SystemExit(f"кэша {path} нет -- раскладывать нечего")
    d = json.loads(path.read_text())
    rows = list((d.get("строки") or {}).values())
    items = [split_one(v) for v in rows]
    a_items, b_items = items[:args.a_size], items[args.a_size:]
    out = {
        "источник": str(path.relative_to(REPO_ROOT)),
        "кэш_сохранён_utc": d.get("сохранено_utc"),
        "разобрано_в_кэше": d.get("разобрано"), "всего": d.get("всего"),
        "ЧЕСТНЫЕ_ОГОВОРКИ": [
            "Ни одного сетевого вызова: всё из кэша поблочного разбора.",
            "Части перемножаются ТОЧНО: (1+а)(1+б)(1+в) = наша цена / цена до лидера. "
            "Простая сумма процентов расходится с итогом на перекрёстные члены -- это "
            "арифметика процентов, а не ошибка данных; расхождение показано колонкой.",
            "Наценка к лидеру -- это (б) и (в) вместе. (а) лежит НИЖЕ точки отсчёта "
            "наценки и в неё не входит.",
            "РЕЗЕРВ ПУЛА НЕ ИЗМЕРЕН. Поблочный разбор читал только транзакции и ни разу "
            "не спрашивал состояние пула. Здесь резерв ОЦЕНЁН из следа лидера при "
            "предположении постоянного произведения: R ~ x / p. Оценка наследует все "
            "погрешности p, неверна для пулов с другой кривой и не годится там, где "
            "влияние лидера не посчиталось. Прямое чтение резерва -- отдельный проход.",
            "Проверка оценки: по тому же R предсказано НАШЕ влияние и сопоставлено с "
            "измеренным (в) -- колонка 'модель минус факт'.",
        ],
        "A": a_items, "Б": b_items,
        "сводка_A": summarise("A -- серия минусов", a_items),
        "сводка_Б": summarise("Б -- плюсовые 19-21.09", b_items),
    }
    OUT_PATH.write_text(json.dumps(out, ensure_ascii=False, indent=2))
    print(json.dumps({"сводка_A": out["сводка_A"], "сводка_Б": out["сводка_Б"]},
                      ensure_ascii=False, indent=2))


def self_test() -> None:
    checks: list[tuple[str, bool, str]] = []

    def chk(name: str, ok: bool, got: str = "") -> None:
        checks.append((name, bool(ok), got))

    v = {"mint": "m", "цена_до_лидера": 100.0, "лидер_цена": 110.0, "наша_цена": 132.0,
         "лидер_sol": 10.0, "наш_вход_sol": 2.0,
         "блоки": [{"кто": "ЛИДЕР", "сторона": "покупка", "sol": 10.0, "цена": 110.0, "слот_плюс": 0},
                    {"кто": "чужой", "сторона": "покупка", "sol": 5.0, "цена": 120.0, "слот_плюс": 1},
                    {"кто": "МЫ", "сторона": "покупка", "sol": 2.0, "цена": 132.0, "слот_плюс": 1}]}
    r = split_one(v)
    chk("(а) = влияние лидера", r["а_влияние_лидера_pct"] == 10.0, str(r["а_влияние_лидера_pct"]))
    chk("(б) = дрейф до нас", r["б_дрейф_до_нас_pct"] == round((120/110-1)*100, 3),
        str(r["б_дрейф_до_нас_pct"]))
    chk("(в) = наше влияние", r["в_наше_влияние_pct"] == 10.0, str(r["в_наше_влияние_pct"]))
    chk("произведение частей сходится точно",
        abs(r["сходимость_произведения_пп"]) < 1e-6, str(r["сходимость_произведения_пп"]))
    chk("итог от цены до лидера верен", r["итог_от_цены_до_лидера_pct"] == 32.0,
        str(r["итог_от_цены_до_лидера_pct"]))
    chk("перекрёстные члены названы и не спрятаны",
        r["перекрёстные_члены_пп"] != 0 and r["расхождение_суммы_больше_1пп"] is True,
        f"{r['перекрёстные_члены_пп']} / {r['расхождение_суммы_больше_1пп']}")
    chk("наценка к лидеру = (б)(в), а не (а)(б)(в)",
        abs(r["наценка_сходимость_пп"]) < 1e-6 and r["наценка_проверка_pct"] == 20.0,
        str(r["наценка_проверка_pct"]))
    chk("резерв оценён из следа лидера", r["резерв_пула_sol_оценка"] == 100.0,
        str(r["резерв_пула_sol_оценка"]))
    chk("доля лидера к резерву", r["покупка_лидера_к_резерву"] == 0.1,
        str(r["покупка_лидера_к_резерву"]))
    chk("ожидаемое наше влияние считается от выросшего резерва",
        r["наше_влияние_ожидаемое_pct"] == round(2.0 / 115.0 * 100, 3),
        str(r["наше_влияние_ожидаемое_pct"]))

    v2 = dict(v); v2["цена_до_лидера"] = None
    r2 = split_one(v2)
    chk("без цены до лидера -- (а) None с причиной",
        r2["а_влияние_лидера_pct"] is None and "резерв" in r2["а_почему_нет"])
    chk("и резерв тогда тоже не оценивается",
        r2["резерв_пула_sol_оценка"] is None and "отдельного прохода" in r2["почему_нет_резерва"])
    chk("но наценка к лидеру всё равно считается", r2["наценка_проверка_pct"] == 20.0)

    v3 = dict(v); v3["блоки"] = [{"кто": "ЛИДЕР", "сторона": "покупка", "sol": 10.0,
                                   "цена": 110.0, "слот_плюс": 0},
                                  {"кто": "МЫ", "сторона": "покупка", "sol": 2.0,
                                   "цена": 132.0, "слот_плюс": 1}]
    r3 = split_one(v3)
    chk("мы сразу за лидером -- дрейф ровно 0", r3["б_дрейф_до_нас_pct"] == 0.0)
    chk("и весь остаток отнесён нам", r3["в_наше_влияние_pct"] == 20.0,
        str(r3["в_наше_влияние_pct"]))

    v4 = dict(v); v4["лидер_цена"] = None
    chk("без цены лидера раскладывать отказываемся",
        split_one(v4).get("не_удалось") is not None)

    s = summarise("тест", [r, r3])
    chk("сводка считает медианы", s["сделок"] == 2 and s["медиана_а_влияние_лидера_pct"] == 10.0)
    chk("сводка считает расхождения", s["сделок_с_расхождением_суммы_больше_1пп"] >= 1)

    bad = 0
    for name, ok, got in checks:
        print(f"  [{'ok  ' if ok else 'СБОЙ'}] {name}" + (f"  -> {got}" if got and not ok else ""))
        bad += (not ok)
    print(f"самопроверка разложения: {len(checks) - bad}/{len(checks)} пройдено")
    if bad:
        raise SystemExit(f"самопроверка не пройдена: {bad} из {len(checks)}")


if __name__ == "__main__":
    main()
