"""Забор НАБОРОМ источников: правило задано заранее, проверка идёт вперёд по времени.

Правило. На семи сутках подбора источники ранжируются по итогу забора; верхние K (5, 10 или
20) торгуются следующие четыре суток. Дальше окно сдвигается на четыре суток, и правило
применяется заново -- то есть набор каждый раз выбирается ТОЛЬКО по прошлому, без
подглядывания вперёд. Считается сумма НАБОРА: сделок, знаки суток, доверительный интервал
бутстрэпом по суткам и среднее без верхних пяти процентов.

Зачем набор. Поодиночке забор упирается не в доходность, а в число сделок: при доле
попадания 20.9 % даже busiest источник даёт около 58 сделок на окно из четырёх суток при
пороге сто. Набор из K источников складывает их сделки и проходит порог по n, не нарушая
правила «решение только по прошлому».

Поправка на перебор -- ×3: K перебирается по трём значениям, значит порог 0.05/3.
Отдельного N по кошелькам здесь нет: кошельки не отбираются по будущему, их выбирает
правило.

Рядом считаются оба места входа (S0_дно -- забор в блок источника по честной цене конца
слота, и S1 -- обычная посадка следующим слотом) и обе доли попадания (20.9 % по живым
сделкам vol_4vw и 35.4 % по счёту владельца для групп).

Только чтение кэша сигналов. Выход: data/podbivka/zabor_nabor.json.
"""
