def p_знаков(суммы: dict) -> float | None:
    v = [s for s in суммы.values() if s is not None and s != 0]
    if len(v) < 4:
        return None
    n = len(v)
    k = sum(1 for s in v if s > 0)
    return sum(math.comb(n, i) for i in range(k, n + 1)) / 2 ** n


def набор(ряды: dict, дни: list, кг: str, K: int) -> dict:
    """Правило вперёд по времени: верхние K по подбору торгуют проверку."""
    окна = И.окна_скольжения(дни, И.ПОДБОР_СУТОК, И.ПРОВЕРКА_СУТОК, И.СДВИГ_СУТОК)
    все_итоги: list = []
    по_суткам: dict = collections.defaultdict(list)
    окон_в_плюсе = 0
    окон_годных = 0
    выбор: list = []
    for подб_д, пров_д in окна:
        счёт_подб = {}
        for ист, сп in ряды.items():
            v = [x["итоги"].get(кг) for x in сп if x["сутки"] in подб_д]
            v = [y for y in v if y is not None]
            if v:
                счёт_подб[ист] = sum(v)
        верх = [и for и, _ in sorted(счёт_подб.items(), key=lambda kv: -kv[1])[:K]]
        окно_итоги = []
        for и in верх:
            for x in ряды.get(и, ()):
                if x["сутки"] in пров_д and x["итоги"].get(кг) is not None:
                    окно_итоги.append((x["сутки"], x["итоги"][кг]))
        выбор.append({"подбор": [подб_д[0], подб_д[-1]],
                      "проверка": [пров_д[0], пров_д[-1]],
                      "взято": len(верх), "сделок": len(окно_итоги),
                      "итог_sol": round(sum(y for _, y in окно_итоги), 5),
                      "источники": верх[:5]})
        if окно_итоги:
            окон_годных += 1
            if sum(y for _, y in окно_итоги) > 0:
                окон_в_плюсе += 1
        for с, y in окно_итоги:
            все_итоги.append(y)
            по_суткам[с].append(y)
    if not все_итоги:
        return {"n": 0, "K": K}
    низ, верх_ди = Z.ди_по_суткам(по_суткам, seed=СЕМЯ)
    суммы = {с: sum(v) for с, v in по_суткам.items()}
    плюс_сут = sum(1 for s in суммы.values() if s > 0)
    p = p_знаков(суммы)
    из_ = {"K": K, "n": len(все_итоги), "суток": len(суммы),
           "окон_годных": окон_годных, "окон_в_плюсе": окон_в_плюсе,
           "итог_sol": round(sum(все_итоги), 5),
           "sol_в_сутки": round(sum(все_итоги) / max(1, len(суммы)), 5),
           "сделок_в_сутки": round(len(все_итоги) / max(1, len(суммы)), 1),
           "среднее_sol": round(statistics.fmean(все_итоги), 6),
           "ди_низ": round(низ, 6) if низ is not None else None,
           "ди_верх": round(верх_ди, 6) if верх_ди is not None else None,
           "без_верх_5": round(Z.срезанное(все_итоги, 0.05), 6),
           "без_верх_1": round(Z.срезанное(все_итоги, 0.01), 6),
           "суток_в_плюсе": плюс_сут,
           "доля_суток_в_плюсе": round(плюс_сут / max(1, len(суммы)), 3),
           "p": p, "порог_p": 0.05 / ПОПРАВКА,
           "окна": выбор}
    из_["прошло"] = bool(
        из_["n"] >= И.N_МИН and (из_["среднее_sol"] or 0) > 0
        and (из_["ди_низ"] or 0) > 0 and (из_["без_верх_5"] or 0) > 0
        and из_["доля_суток_в_плюсе"] >= И.ДОЛЯ_СУТОК_В_ПЛЮСЕ
        and из_["окон_годных"] >= И.ОКОН_МИН
        and из_["окон_в_плюсе"] == из_["окон_годных"]
        and p is not None and p < из_["порог_p"])
    return из_


def главное(а) -> int:  # noqa: PLR0915
    кал = (json.loads((П / "kalibrovka.json").read_text(encoding="utf-8"))
           .get("калибровка") or {})
    изд = float(кал.get("издержки_медиана_sol") or 0.002)
    тело = {"что": "забор набором источников: правило задано заранее, проверка вперёд",
            "когда": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
            "правило": {"подбор_суток": И.ПОДБОР_СУТОК,
                        "проверка_суток": И.ПРОВЕРКА_СУТОК,
                        "сдвиг_суток": И.СДВИГ_СУТОК, "K": list(K_НАБОРА),
                        "поправка_на_перебор": f"0.05/{ПОПРАВКА}",
                        "издержки_sol": изд},
            "срезы": {}}
    пустой = argparse.Namespace(dolya=0.209, mesto="S0_дно",
                               k_g_osnovnaya=1.0, metka="")
    for место in ("S0_дно", "S1"):
        for доля in (0.209, 0.354):
            п = З.проход(пустой, изд, место=место, доля=доля)
            # ряды по (источник) отдельно на каждое (H, билет)
            по_ключу: dict = collections.defaultdict(lambda: collections.defaultdict(list))
            for (ист, H, имя_б), сп in п["ряды"].items():
                по_ключу[(H, имя_б)][ист].extend(сп)
            дни = sorted({x["сутки"] for сп in п["ряды"].values() for x in сп})
            имя_срез = f"{место}|доля {доля}"
            тело["срезы"][имя_срез] = {"счёт": п["счёт"], "суток": len(дни),
                                       "наборы": {}}
            for (H, имя_б), ряды in sorted(по_ключу.items()):
                for кг in (str(x) for x in И.К_G_РЯДОМ):
                    for K in K_НАБОРА:
                        р_ = набор(ряды, дни, кг, K)
                        if р_.get("n"):
                            тело["срезы"][имя_срез]["наборы"][
                                f"H{H}|{имя_б}|k{кг}|K{K}"] = р_
            print(f"  {имя_срез}: суток {len(дни)}, наборов "
                  f"{len(тело['срезы'][имя_срез]['наборы'])}", flush=True)
    ф = П / f"zabor_nabor{а.metka}.json"
    ф.write_text(json.dumps(тело, ensure_ascii=False, indent=1), encoding="utf-8")
    try:
        import podbivka_run as R  # noqa: PLC0415
        R.записано(ф)
    except Exception:  # noqa: BLE001, S110
        pass
    print(f"\n{'срез':22}{'ключ':24}{'n':>7}{'сд/сут':>8}{'SOL/сут':>10}"
          f"{'без в5':>10}{'окон+':>7}{'сут+':>7}{'p':>10} вердикт", flush=True)
    строки = []
    for имя, с in тело["срезы"].items():
        for к, v in с["наборы"].items():
            строки.append((имя, к, v))
    строки.sort(key=lambda t: -(t[2].get("sol_в_сутки") or -1e9))
    for имя, к, v in строки[:24]:
        print(f"{имя:22}{к:24}{v['n']:>7}{v['сделок_в_сутки']:>8}"
              f"{v['sol_в_сутки']:>+10.4f}{v['без_верх_5']:>+10.5f}"
              f"{v['окон_в_плюсе']}/{v['окон_годных']:<5}"
              f"{v['суток_в_плюсе']}/{v['суток']:<4}"
              f"{(v['p'] if v['p'] is not None else 1):>10.2e} "
              f"{'ПРОШЁЛ' if v['прошло'] else ''}", flush=True)
    прошли = [(и, к) for и, к, v in строки if v["прошло"]]
    print(f"\nпрошли наборов: {len(прошли)}", flush=True)
    for и, к in прошли[:20]:
        print(f"  {и} {к}", flush=True)
    return 0


