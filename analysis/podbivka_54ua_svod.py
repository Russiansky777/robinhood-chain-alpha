#!/usr/bin/env python3
"""Подбивка: 54uaRuJE -- следует за источником или общий триггер. Офлайн.

Вход: data/podbivka/snaipery/54ua_indeksy.json (блок слота его покупки целиком, покупатели того же
минта до и после него), data/podbivka/snaipery/54ua_cu.json (цена за CU у него и у источника;
индекс источника при S+1). Выход: docs/podbivka_2026-09-29_54ua.md.
"""
from __future__ import annotations

import json
import statistics
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parent.parent
П = КОРЕНЬ / "data" / "podbivka" / "snaipery"
КОРЗИНЫ = [(-10**6, -501), (-500, -201), (-200, -101), (-100, -30), (-29, -10), (-9, -1),
           (1, 9), (10, 29), (30, 100), (101, 200), (201, 500), (501, 10**6)]


def мед(v):
    v = [x for x in v if x is not None]
    return statistics.median(v) if v else None


def ф(x, fmt=".0f"):
    return "—" if x is None else format(x, fmt)


def кор(a, c):
    if a <= -10**6:
        return f"≤ {c}"
    if c >= 10**6:
        return f"≥ +{a}"
    return f"{a:+d}…{c:+d}"


def индексы() -> list:
    д = json.loads((П / "54ua_indeksy.json").read_text(encoding="utf-8"))
    P = [p for p in д["покупки"] if p["индекс_блок"] is not None]
    сдвиг = [p["индекс_блок"] - p["индекс_сбор"] for p in P if p["индекс_сбор"] is not None]
    md = ["## 1. Покупатели того же минта в его слоте -- до и после него", "",
          f"Покупок {д['покупок']}, блоков прочитано {д['слотов']}, ошибок {len(д['ошибки'])}. Блок целиком (getBlock, "
          "transactionDetails accounts, транзакции v0 и v1), покупатель -- по C.mint_buyers. Разность = его индекс − индекс "
          "покупателя: плюс -- покупатель до него, минус -- после.", "",
          f"Поправка к сбору 28.09: там блок читался без транзакций v1 (maxSupportedTransactionVersion 0), поэтому индекс "
          f"занижен у {sum(1 for x in сдвиг if x)} из {len(сдвиг)} покупок (до {max(сдвиг)} позиций). Здесь -- индексы по "
          "полному блоку; «индекс в блоке: медиана» в docs/podbivka_2026-09-28_snaipery.md -- по старому сбору.", "",
          "| порог покупателя | есть до него | ближайший до, медиана | есть после него | ближайший после, медиана | после в пределах 30 позиций |",
          "|---|---|---|---|---|---|"]
    for мин in (0, 0.5, 2):
        до, после = [], []
        for p in P:
            xs = [x for x in p["покупатели"] if (x.get("sol") or 0) >= мин]
            b = [x["разность"] for x in xs if x["разность"] > 0]
            a = [x["разность"] for x in xs if x["разность"] < 0]
            if b:
                до.append(min(b))
            if a:
                после.append(max(a))
        md.append(f"| {'любой' if not мин else f'≥ {мин} SOL'} | {len(до)} из {len(P)} | +{ф(мед(до))} | {len(после)} из {len(P)} | "
                  f"{ф(мед(после))} | {sum(1 for x in после if x >= -30)} |")
    все = [x["разность"] for p in P for x in p["покупатели"]]
    доля = [sum(1 for x in p["покупатели"] if x["разность"] > 0) / len(p["покупатели"]) for p in P if p["покупатели"]]
    md += ["", f"Покупателей того же минта в слоте, кроме него: медиана {ф(мед([len(p['покупатели']) for p in P]))}. Доля их, "
           f"стоящих до него: медиана {мед(доля):.2f} (четверти {statistics.quantiles(доля, n=4)[0]:.2f} / "
           f"{statistics.quantiles(доля, n=4)[2]:.2f}).", "",
           "Все пары «он − покупатель того же минта в том же слоте» (размер покупателя любой):", "",
           "| разность индексов | пар |", "|---|---|"]
    for a, c in КОРЗИНЫ:
        md.append(f"| {кор(a, c)} | {sum(1 for x in все if a <= x <= c)} |")
    return md + [""]


def cu() -> list:
    п = П / "54ua_cu.json"
    if not п.exists():
        return ["## 2. Цена за CU у него и у источника; S+1", "", "Считается в облаке (analysis/podbivka_54ua_cu.py).", ""]
    д = json.loads(п.read_text(encoding="utf-8"))
    З = д["записи"]
    for з in З:      # цена CU: ComputeBudget; у v1 -- priorityFee (лампорты на транзакцию) × 1e6 / лимит CU
        for к in ("его", "источника"):
            р = з.get(к) or {}
            if р.get("цена_мкл") is None and р.get("v1_priorityFee") is not None and р.get("лимит_cu"):
                р["цена_мкл"] = int(р["v1_priorityFee"]) * 1_000_000 // int(р["лимит_cu"])
    инд = json.loads((П / "54ua_indeksy.json").read_text(encoding="utf-8"))
    разн = {(p["signature"], x["подпись"]): x["разность"] for p in инд["покупки"] for x in p["покупатели"] if x.get("разность") is not None}
    for з in З:     # разность по полному блоку (v1 включительно), иначе -- из сбора 28.09
        з["позиций_до_сбор"] = з.get("позиций_до")
        if (з["signature"], з["подпись_источника"]) in разн:
            з["позиций_до"] = разн[(з["signature"], з["подпись_источника"])]
    same = [з for з in З if з["слотов_до"] == 0 and not з.get("why_not") and (з.get("его") or {}).get("стоимость")
            and (з.get("источника") or {}).get("стоимость")]
    md = ["## 2. Цена за CU у него и у ближайшего источника (источник в том же слоте)", "",
          "Ближайший источник -- как в сборе 28.09 (последний покупатель минта до него, окно s0−3..s0). Цена CU -- "
          "ComputeBudget, мкл/CU; у транзакций v1 (у него 201 из 229) бюджет в самом сообщении: priorityFee × 1e6 / лимит CU. "
          "«—» и 0 -- цена не задана. Приоритет -- формула Agave (награда × 1e6 / (стоимость + 1)), тот же расчёт, что в «месте в "
          "блоке». «С чаевыми» -- (плата за приоритет + чаевые) × 1e6 / (стоимость + 1); чаевые -- внешние системные переводы "
          "подписанта на чужой адрес. Куст -- по разности индексов в полном блоке (раздел 1); если источник там не найден -- "
          "по сбору 28.09.", "",
          "| куст (позиций до) | n | цена CU: его / ист., медианы | его цена CU выше | приоритет Agave: его / ист. | "
          "его приоритет выше | с чаевыми: его / ист. | его «с чаевыми» выше |", "|---|---|---|---|---|---|---|---|"]
    for имя, a, c in (("1–9", 1, 9), ("10–29", 10, 29), ("1–29", 1, 29), ("30–100", 30, 100), ("> 100", 101, 10**6)):
        сс = [з for з in same if з.get("позиций_до") is not None and a <= з["позиций_до"] <= c]
        if not сс:
            continue
        def пара(k):
            e, s = [з["его"].get(k) or 0 for з in сс], [з["источника"].get(k) or 0 for з in сс]
            return (f"{ф(мед(e))} / {ф(мед(s))}", sum(1 for x, y in zip(e, s) if x > y))
        ц, цв = пара("цена_мкл")
        пр, прв = пара("приоритет")
        сч, счв = пара("приоритет_с_чаевыми")
        md.append(f"| {имя} | {len(сс)} | {ц} | {цв} из {len(сс)} | {пр} | {прв} из {len(сс)} | {сч} | {счв} из {len(сс)} |")
    куст = sorted((з for з in same if з.get("позиций_до") is not None and з["позиций_до"] <= 29), key=lambda з: з["позиций_до"])
    md += ["", "Куст 1–29 построчно:", "",
           "| слот | источник | позиций до | цена CU его / ист. | приоритет его / ист. | чаевые его / ист., SOL | получатели чаевых его / ист. |",
           "|---|---|---|---|---|---|---|"]
    for з in куст:
        е, и = з["его"], з["источника"]
        md.append(f"| {з['slot']} | `{з['источник'][:8]}` | {з['позиций_до']} | {ф(е.get('цена_мкл'))} / {ф(и.get('цена_мкл'))} | "
                  f"{ф(е.get('приоритет'))} / {ф(и.get('приоритет'))} | {е.get('чаевые_lamports', 0) / 1e9:.5f} / "
                  f"{и.get('чаевые_lamports', 0) / 1e9:.5f} | {', '.join(x[:8] for x in е.get('чаевые_кому') or []) or '—'} / "
                  f"{', '.join(x[:8] for x in и.get('чаевые_кому') or []) or '—'} |")
    п_s1 = П / "54ua_s1.json"
    полный = п_s1.exists()
    if полный:       # индекс источника по полному блоку (v1 включительно)
        по = {x["signature"]: x for x in json.loads(п_s1.read_text(encoding="utf-8"))["записи"] if x.get("индекс_источника") is not None}
        for з in З:
            if з["слотов_до"] >= 1 and з["signature"] in по:
                з["индекс_источника_сбор"] = з["индекс_источника"]
                з["индекс_источника"], з["в_блоке_источника"] = по[з["signature"]]["индекс_источника"], по[з["signature"]]["в_блоке"]
    s1 = [з for з in З if з["слотов_до"] >= 1 and з.get("в_блоке_источника") and з.get("индекс_источника") is not None]
    отн = [з["индекс_источника"] / з["в_блоке_источника"] for з in s1]
    хвост = [з for з in s1 if з["в_блоке_источника"] - з["индекс_источника"] <= 50]
    md += ["", "## 3. Источник на слот раньше (S+1 и S+2): где он в своём блоке", "",
           f"Случаев {len([з for з in З if з['слотов_до'] >= 1])}, с индексом источника {len(s1)}. " + (
               "Индекс источника и размер блока -- по полному блоку (v1 включительно)." if полный else
               "Индекс источника -- по сбору 28.09 (там блок читался без транзакций v1 -- индекс мог быть занижен), размер "
               "блока -- полный; пересчёт по полному блоку идёт в облаке (analysis/podbivka_54ua_s1.py)."), "",
           f"Положение источника в блоке (индекс / размер): медиана {ф(мед(отн), '.2f')}; в последних 50 позициях -- "
           f"{len(хвост)} из {len(s1)}; в последней четверти блока -- {sum(1 for x in отн if x >= 0.75)} из {len(s1)}.", "",
           "| слот источника | источник | индекс / в блоке | с конца | его индекс в S+1 |", "|---|---|---|---|---|"]
    for з in sorted(s1, key=lambda з: з["индекс_источника"] / з["в_блоке_источника"], reverse=True):
        md.append(f"| {з['слот_источника']} | `{з['источник'][:8]}` | {з['индекс_источника']} / {з['в_блоке_источника']} | "
                  f"{з['в_блоке_источника'] - з['индекс_источника']} | {ф(з.get('индекс'))} |")
    return md + [""]


def main() -> int:
    md = ["# Подбивка: 54uaRuJE -- следует за источником или общий триггер", "",
          "279 покупок за 7 суток (как в docs/podbivka_2026-09-28_snaipery.md). Ничего не рекомендуется.", ""]
    md += индексы() + cu()
    (КОРЕНЬ / "docs" / "podbivka_2026-09-29_54ua.md").write_text("\n".join(md) + "\n", encoding="utf-8")
    print("\n".join(md))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
