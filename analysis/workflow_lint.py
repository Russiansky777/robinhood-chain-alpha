#!/usr/bin/env python3
"""Проверка workflow: YAML, shell и -- главное -- heredoc.

bash -n незакрытый heredoc ПРИНИМАЕТ: он считает, что тело идёт до конца
файла. Поэтому отступленный терминатор (а внутри run: | он обязан быть
отступлен, иначе рвётся блочный скаляр YAML) проходит обе прежние
проверки и ломается только на прогоне. Отсюда правило: внутри run: |
heredoc не используем вовсе.
"""
import glob
import os
import re
import subprocess
import sys
import tempfile

import yaml

HEREDOC = re.compile(r"<<-?\s*'?\"?([A-Za-z_][A-Za-z0-9_]*)'?\"?")
# Присваивание переменной с не-латинским именем. bash требует
# [a-zA-Z_][a-zA-Z0-9_]*, поэтому "ИМЯ=значение" он разбирает как запуск
# команды с таким именем: шаг падает, а bash -n молчит.
# Имя обязано быть словом целиком (без | и кавычек) и стоять в начале
# команды. Иначе ловится содержимое строк на других языках: первый вариант
# поймал "медиана|ошибки|=%s" внутри питоновского print.
НЕЛАТИНСКАЯ_ПЕРЕМЕННАЯ = re.compile(
    r"(?:^\s*|[;&]\s*|\|\|\s*|&&\s*)([^\W\d_]\w*)=(?![=~])", re.UNICODE)
# Строка кончается на `-c \`: сам текст программы перенесён на следующую
# строку. Без этого следующая строка читалась как shell.
ПЕРЕНОС_ПОСЛЕ_C = re.compile(r"(^|\s)-c\s*\\$")


def пустые_выражения(текст: str) -> list:
    """Подстановка GitHub с пустыми скобками: [(номер строки, что видно)].

    Ночь 04.10. Прогон трекера на claude/stroiteli нельзя было запустить
    ВОВСЕ: GitHub отвечал на запуск 422 "An expression was expected". Внутри
    блока run стояли два комментария оболочки, в которых для объяснения была
    приведена подстановка GitHub с ПУСТЫМИ фигурными скобками. Выражения
    GitHub вычисляются до всякой оболочки, и решётка их от него не прячет:
    один комментарий убил весь файл.

    Почему этого не видела ни одна прежняя проверка. YAML такой файл
    разбирает (PyYAML молчит), `bash -n` тела разбирает, кавычки целы, имена
    латиницей. Сломано только то, чего ни одна из них не смотрит -- сам язык
    выражений GitHub. Отсюда правило: ищем в СЫРОМ тексте файла, а не в
    разобранном дереве, потому что сломать так можно и `if:`, и `env:`, и
    `run:`, и имя шага.
    """
    найдено = []
    i = 0
    while True:
        н = текст.find("${{", i)
        if н < 0:
            return найдено
        к = текст.find("}}", н + 3)
        строка = текст.count("\n", 0, н) + 1
        if к < 0:
            найдено.append((строка, "${{ без закрывающих }}"))
            return найдено
        внутри = текст[н + 3:к]
        if not внутри.strip():
            найдено.append((строка, текст[н:к + 2]))
        i = н + 3
    return найдено


def нелатинские_переменные(тело: str) -> list:
    """Присваивания shell с нелатинским именем в теле run: [почему].

    bash требует [a-zA-Z_][a-zA-Z0-9_]*, поэтому `ИМЯ=значение` он разбирает
    как запуск команды с таким именем: шаг падает, а `bash -n` молчит.

    Чужие языки внутри тела пропускаются, и это третья правка этого места:
    сперва ругалось на "медиана|ошибки|=%s" внутри питоновского print, теперь
    -- на `г=O.кошелёк_готов()` в `python3 -c`, перенесённом обратной косой на
    следующую строку. Пропускаем: тело heredoc, хвост после `-c` в той же
    строке и строки-продолжения после `-c \\`. Приставку
    `ПЕРЕМ=значение python3 -c` при этом видно по-прежнему -- она как раз и
    была бы настоящей ошибкой.
    """
    замечания = []
    в_heredoc = None
    питон_дальше = False
    for стр in тело.splitlines():
        if в_heredoc is not None:
            if стр.rstrip() == в_heredoc and not стр[:1].isspace():
                в_heredoc = None
            continue
        m_h = HEREDOC.search(стр)
        if m_h:
            в_heredoc = m_h.group(1)
            continue
        if питон_дальше:
            питон_дальше = стр.rstrip().endswith("\\")
            continue
        без_комментария = стр.split("#", 1)[0]
        if ПЕРЕНОС_ПОСЛЕ_C.search(без_комментария.rstrip()):
            питон_дальше = True
            continue
        for ключ in (" python3 -c", " python -c", " -c "):
            п = без_комментария.find(ключ)
            if п >= 0:
                без_комментария = без_комментария[:п]
                break
        for m in НЕЛАТИНСКАЯ_ПЕРЕМЕННАЯ.finditer(без_комментария):
            имя_пер = m.group(1)
            if имя_пер.isascii():
                continue
            замечания.append(f"переменная shell '{имя_пер}' не "
                             "латиницей: bash так не умеет, шаг упадёт, "
                             "а bash -n этого не видит")
    return замечания


def _самопроверка() -> int:
    проверок = прошло = 0

    def сверить(что, дано, ждали):
        nonlocal проверок, прошло
        проверок += 1
        if дано == ждали:
            прошло += 1
        else:
            print(f"НЕ ПРОШЛО: {что}: дано {дано!r}, ждали {ждали!r}")

    # Ровно тот случай, что сломал прогон трекера: внутри комментария run.
    сломанный = (
        "jobs:\n  a:\n    steps:\n      - run: |\n"
        "          set -e\n"
        "          # прямо в строку ssh (${{ }} внутри shell)\n"
    )
    сверить("пустая подстановка в комментарии run",
            [с for с, _ in пустые_выражения(сломанный)], [6])
    сверить("без пробела внутри тоже пусто",
            [с for с, _ in пустые_выражения("x: ${{}}\n")], [1])
    сверить("перевод строки внутри -- тоже пусто",
            [с for с, _ in пустые_выражения("x: ${{\n   }}\n")], [1])
    сверить("живое выражение не трогаем",
            пустые_выражения("x: ${{ inputs.port }}\n"), [])
    сверить("два живых выражения в строке",
            пустые_выражения("a: ${{ inputs.a }} ${{ inputs.b }}\n"), [])
    сверить("незакрытая подстановка названа отдельно",
            [ч for _, ч in пустые_выражения("x: ${{ inputs.port\n")],
            ["${{ без закрывающих }}"])
    сверить("приём GitHub для печати самих скобок не ложная тревога",
            пустые_выражения("x: ${{ '${{' }}\n"), [])
    сверить("файл без подстановок", пустые_выражения("a: 1\nb: 2\n"), [])
    # Две поломки в одном файле -- обе, а не только первая: у Code-3 их
    # было ровно две, на строках 72 и 284.
    сверить("обе поломки, а не первая",
            [с for с, _ in пустые_выражения("a: ${{ }}\nb: ok\nc: ${{  }}\n")],
            [1, 3])

    # Настоящее присваивание нелатиницей -- ловим.
    сверить("нелатинское имя в shell ловится",
            len(нелатинские_переменные("ИМЯ=5\necho $ИМЯ\n")), 1)
    сверить("латинское имя не трогаем",
            нелатинские_переменные("IMJA=5\n"), [])
    # Ровно та строка из деплоя, на которую проверка ругалась зря.
    питон_переносом = (
        "  LANE_READY=$(ssh -n $SSH_OPTS root@$TARGET_HOST \"\n"
        "    PYTHONPATH=$CODE_DIR /home/bot/venv/bin/python -c \\\n"
        "      'import json, bloom_own_send as O; г=O.кошелёк_готов(); print(г)'\n"
        "  \")\n")
    сверить("питон после `-c \\` -- не замечание",
            нелатинские_переменные(питон_переносом), [])
    сверить("хвост после `-c` в той же строке -- не замечание",
            нелатинские_переменные("python3 -c 'г=1; print(г)'\n"), [])
    # А вот приставка перед командой -- настоящая ошибка, её не прячем.
    сверить("приставка ПЕРЕМ=... перед python3 -c видна",
            len(нелатинские_переменные("ПЕРЕМ=1 python3 -c 'print(1)'\n")), 1)
    сверить("тело heredoc не разбираем как shell",
            нелатинские_переменные("python3 <<PY\nг=1\nPY\n"), [])

    print(f"проверок {проверок}, прошло {прошло}, не прошло {проверок - прошло}")
    return 0 if прошло == проверок else 1


def main() -> int:
    плохо = []
    файлы = sorted(glob.glob(".github/workflows/*.yml")) + sorted(glob.glob(".github/workflows/*.yaml"))
    for f in файлы:
        сырой = open(f, encoding="utf-8").read()
        for строка, что in пустые_выражения(сырой):
            плохо.append((f, f"строка {строка}",
                          f"подстановка GitHub без выражения: {что!r} -- "
                          "GitHub ОТКАЗЫВАЕТСЯ разбирать весь файл "
                          "(An expression was expected), прогон нельзя "
                          "запустить вовсе; внутри run комментарий от этого "
                          "не спасает"))
        try:
            d = yaml.safe_load(open(f, encoding="utf-8"))
        except Exception as exc:
            плохо.append((f, "-", f"YAML: {str(exc).splitlines()[0]}"))
            continue
        if not isinstance(d, dict) or not isinstance(d.get("jobs"), dict):
            continue
        for j in d["jobs"].values():
            if not isinstance(j, dict):
                continue
            for st in j.get("steps") or []:
                r = (st or {}).get("run")
                if not isinstance(r, str):
                    continue
                имя = (st or {}).get("name", "?")
                tf = tempfile.NamedTemporaryFile("w", suffix=".sh", delete=False, encoding="utf-8")
                tf.write(r)
                tf.close()
                rc = subprocess.run(["bash", "-n", tf.name], capture_output=True, text=True)
                os.unlink(tf.name)
                if rc.returncode:
                    плохо.append((f, имя, f"shell: {rc.stderr.strip().splitlines()[0][:120]}"))
                # YAML снимает отступ блочного скаляра, поэтому в РАЗОБРАННОЙ
                # строке терминатор правильного heredoc стоит в нулевой
                # колонке -- это норма. Ошибка ровно одна: терминатора с
                # нулевым отступом нет вовсе. Тогда heredoc не закрыт, и
                # bash -n это пропускает, считая тело идущим до конца файла.
                # Случай "тело в нулевой колонке в ИСХОДНОМ файле" ловится
                # разбором YAML выше: такой файл просто не разбирается.
                строки = r.splitlines()
                for почему in нелатинские_переменные(r):
                    плохо.append((f, имя, почему))
                for стр in строки:
                    m = HEREDOC.search(стр)
                    if not m:
                        continue
                    метка = m.group(1)
                    закрыт = any(x.rstrip() == метка and not x[:1].isspace()
                                 for x in строки)
                    if not закрыт:
                        плохо.append((f, имя, f"heredoc <<{метка} НЕ закрыт: "
                                       "терминатор отступлен или отсутствует, "
                                       "bash -n этого не видит"))
    for f, имя, почему in плохо:
        print(f"{f} | {имя} | {почему}")
    print(f"\nпроверено файлов: {len(файлы)}, замечаний: {len(плохо)}")
    return 1 if плохо else 0


if __name__ == "__main__":
    if "--self-test" in sys.argv:
        sys.exit(_самопроверка())
    sys.exit(main())
