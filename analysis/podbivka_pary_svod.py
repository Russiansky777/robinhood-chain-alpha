#!/usr/bin/env python3
"""Подбивка: сводка пар полосы (data/podbivka/pary_polosa.json), офлайн.

Факт «по свопам, база кошелька»: xyk -- выход WSOL-хранилищ / in_sol − 1 (вход по
цепи совпал с in_sol до лампорта); кривая pump.fun -- лампорты кривой на выходе
за вычетом сбора 1.25 % (0.95 + 0.30 создателю) / in_sol − 1 (in_sol включает
сбор входа). Разница выгрузки и свопов -- back_sol больше SOL из свопа на
0.0011–0.0015 SOL у каждой позиции.
"""
from __future__ import annotations

import json
import statistics
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parent.parent
СБОР_КРИВОЙ = 0.0125


def ф(v, z="+.2f"):
    return "—" if v is None else format(v, z)


def мед(xs):
    xs = [x for x in xs if x is not None]
    return (round(statistics.median(xs), 2), len(xs)) if xs else (None, 0)


def main() -> int:
    д = json.loads((КОРЕНЬ / "data" / "podbivka" / "pary_polosa.json").read_text(encoding="utf-8"))
    ряды = []
    for р in д["ряды"]:
        if not р.get("факт_вход_лам"):
            continue
        in_lam = р["in_sol"] * 1e9
        if р.get("режим") == "curve":
            факт = (р["факт_выход_лам"] * (1 - СБОР_КРИВОЙ) / in_lam - 1) * 100
        else:
            факт = (р["факт_выход_лам"] / in_lam - 1) * 100
        р["факт_своп_пп"] = round(факт, 3)
        р["выгрузка_минус_своп_пп"] = round(р["факт_выгрузка_пп"] - факт, 3)
        р["лишнее_в_back_sol"] = round(р["back_sol"] - р["факт_выход_лам"] / 1e9 * ((1 - СБОР_КРИВОЙ) if р.get("режим") == "curve" else 1), 6)
        if р.get("сим_S0_72_пп") is not None:
            р["факт_минус_сим72"] = round(факт - р["сим_S0_72_пп"], 3)
        if р.get("сим_S0_слот_продажи_пп") is not None:
            р["факт_минус_сим_слот"] = round(факт - р["сим_S0_слот_продажи_пп"], 3)
            if р.get("сим_S0_72_пп") is not None:
                р["слот_выхода_пп"] = round(р["сим_S0_слот_продажи_пп"] - р["сим_S0_72_пп"], 3)
        ряды.append(р)
    md = ["# Подбивка: пары полосы против симулятора (сверка «+13 %»)", "",
          "Позиции полосы из выгрузки Code-1 (`nashi_sdelki_host.json`, b4542e3) с посадкой S+0 (слот входа = слоту "
          "источника) и S+1; по цепи -- сделка источника, наша покупка и продажа. Симулятор -- основной (как в "
          "таблицах): вход S+0 фактической тратой, выход +72 со вставкой нашей покупки.", "",
          "## Сводка", "",
          "| посадка | позиций | выгрузка back/in − 1, мед | по свопам, мед | лишнее в back_sol, SOL (мед) | итог службы pnl_sol < 0 |",
          "|---|---|---|---|---|---|"]
    for п in (0, 1):
        рр = [р for р in ряды if р["посадка"] == п]
        md.append(f"| S+{п} | {len(рр)} | {ф(мед([р['факт_выгрузка_пп'] for р in рр])[0])} | "
                  f"{ф(мед([р['факт_своп_пп'] for р in рр])[0])} | {statistics.median([р['лишнее_в_back_sol'] for р in рр]):.6f} | "
                  f"{sum(1 for р in рр if (р.get('pnl_sol') or 0) < 0)} из {len(рр)} |")
    с = [р for р in ряды if р.get("факт_минус_сим72") is not None]
    md += ["", "## Факт по свопам против симулятора (позиции с числом симулятора)", "",
           f"Позиций с числом: {len(с)} из {len(ряды)} (без числа: доля траты источника вне рамки 0.80–1.0 -- 5, "
           "история пула длиннее 150 страниц -- 4).", "",
           "Для кривой pump.fun вход по цепи -- лампорты кривой (без сбора 1.25 %), поэтому «вход в месте посадки» "
           "и «продажа» у кривой смещены на −1.2…−1.25 % учётом сбора, а не моделью; ниже -- отдельно xyk и кривая.", "",
           "| что | все: медиана (n) | xyk | кривая |", "|---|---|---|---|"]
    for имя, ключ in (("факт по свопам − симулятор S+0/+72", "факт_минус_сим72"),
                      ("факт по свопам − симулятор S+0, выход в фактическом слоте продажи", "факт_минус_сим_слот"),
                      ("слот выхода: симулятор в слоте продажи − симулятор +72", "слот_выхода_пп"),
                      ("вход: токены симулятора при S+0 против фактических, %", "вход_S0_к_факту_пп"),
                      ("вход: токены в фактическом месте посадки против фактических, %", "вход_место_к_факту_пп"),
                      ("продажа: фактические токены в состояние перед нашей продажей против факта, %",
                       "продажа_факт_токенов_к_факту_пп")):
        м, n = мед([р.get(ключ) for р in с])
        мx, nx = мед([р.get(ключ) for р in с if р.get("режим") == "xyk"])
        мc, nc = мед([р.get(ключ) for р in с if р.get("режим") == "curve"])
        md.append(f"| {имя} | {ф(м)} ({n}) | {ф(мx)} ({nx}) | {ф(мc)} ({nc}) |")
    md += ["", "## По сделкам", "",
           "| посадка | минт | режим | выгрузка | по свопам | сим S+0/+72 | сим в слоте продажи | удержание, слотов | "
           "вход S+0, % | вход в месте посадки, % | продажа, % | лишнее в back_sol | pnl_sol |",
           "|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for р in sorted(ряды, key=lambda р: (р["посадка"], р["mint"])):
        md.append(f"| S+{р['посадка']} | {р['mint'][:8]} | {р.get('режим') or '—'} | {ф(р['факт_выгрузка_пп'])} | "
                  f"{ф(р['факт_своп_пп'])} | {ф(р.get('сим_S0_72_пп'))} | {ф(р.get('сим_S0_слот_продажи_пп'))} | "
                  f"{р.get('удержание_слотов')} | {ф(р.get('вход_S0_к_факту_пп'))} | {ф(р.get('вход_место_к_факту_пп'))} | "
                  f"{ф(р.get('продажа_факт_токенов_к_факту_пп'))} | {р['лишнее_в_back_sol']} | {р.get('pnl_sol')} |")
    md.append("")
    (КОРЕНЬ / "docs" / "podbivka_2026-09-27_pary.md").write_text("\n".join(md), encoding="utf-8")
    print("\n".join(md[:30]))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
