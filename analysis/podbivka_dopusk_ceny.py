#!/usr/bin/env python3
"""Допуск по цене (slippage) по архиву: уход цены до нашего слота и итог по корзинам ухода.

Задание владельца 04.10. Сейчас допуск 35 % (скопирован у DBot), у lane_s0 -- 40 %; за двое
суток 8 отказов по цене (уход 35--69 % за 0--2 слота), узких промахов только 2 (+0.26 и
+0.60 п.п., оба 6qudAN2k). Числа -- по действующим источникам ТОРГУЮЩИХ групп.

ЧТО СЧИТАЕТСЯ. Для каждой первой покупки источника >= 2 SOL-экв (сигнал прохода архива):
  уход цены = (цена в нашем слоте / цена сразу после сделки источника - 1) x 100 %,
цена = quote/token по состояниям пула того же прохода (`модель.состояния.вход`): «S0» --
состояние ПОСЛЕ сделки источника, «S1» -- последнее состояние слота s0+1 (наш слот).
Корзины ухода: 0--10, 10--20, 20--35, 35--50, 50+ %.

По каждой корзине: n, медиана и среднее итога нашего входа (п.п. чистыми) при удержании +108
и БИЛЕТЕ ГРУППЫ источника, доля в плюсе, SOL в сутки. Итог считается
`podbivka_bilet.пп_по_состояниям` (место «S1», выход 108) -- та же формула, что в модели
прохода; своих копий формул здесь нет. SOL в сутки = сумма (п.п./100 x билет) / суток в окне.

S+2. В проходах архива состояния хранятся для S0, S0_дно и S1 -- состояния слота s0+2 там
нет, поэтому S+2 офлайн не считается. Точка «S2» добавлена в модель прохода
(podbivka_arhiv_den), так что в следующих ночных файлах она будет; пересчитывать прошлые
сутки ради неё не нужно.

Разрезы: всё; кривая pump.fun и Pump AMM отдельно; 6qudAN2k отдельно.
Выход: data/podbivka/dopusk_ceny.json и docs/podbivka_<метка>_dopusk_ceny.md.
Ничего не рекомендуется -- решает владелец.
"""
from __future__ import annotations

import argparse
import glob
import gzip
import json
import statistics
import sys
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import podbivka_bilet as B  # noqa: E402
import podbivka_cand2 as C2  # noqa: E402

КОРЕНЬ = C2.КОРЕНЬ
П = C2.П
WSOL = "So11111111111111111111111111111111111111112"
ВЫХОД = 108
# билеты групп (Правило 14, те же числа, что в недельном документе)
БИЛЕТ_ГРУППЫ = {"lane_s0": 0.5, "batch5": 0.3, "cand1": 0.1, "cand1_03": 0.3, "cand1_05": 0.5,
                "cand2": 0.1, "cand2_03": 0.3, "cand3": 0.1, "leader": 3.0, "konveyer": 0.1,
                "krug_001": 0.01}
КОРЗИНЫ = ((float("-inf"), 0.0, "ниже 0"), (0.0, 10.0, "0--10"), (10.0, 20.0, "10--20"),
           (20.0, 35.0, "20--35"), (35.0, 50.0, "35--50"), (50.0, float("inf"), "50+"))
ДОПУСКИ = (10.0, 20.0, 35.0, 50.0, float("inf"))
ШАБЛОНЫ = ("konv_*.json.gz", "cand2_*.json.gz", "zakem2_*.json.gz")


def цена(сост: list | None) -> float | None:
    """Цена пула = quote / token по состоянию [x=quote, y=token, слот]."""
    if not сост or len(сост) < 2:
        return None
    x, y = float(сост[0]), float(сост[1])
    return x / y if y > 0 else None


def уход_пп(с: dict) -> float | None:
    вх = ((с.get("модель") or {}).get("состояния") or {}).get("вход") or {}
    p0, p1 = цена(вх.get("S0")), цена(вх.get("S1"))
    if not p0 or not p1:
        return None
    return (p1 / p0 - 1) * 100


def корзина(у: float) -> str | None:
    for н, к, имя in КОРЗИНЫ:
        if н <= у < к:
            return имя
    return None


def группа_источника(адр: dict, a: str) -> str | None:
    гр = (адр.get(a) or {}).get("группы") or []
    торг = [г for г in гр if г in БИЛЕТ_ГРУППЫ]
    return торг[0] if торг else None


def стат(ряды: list, суток: float) -> dict:
    """n, медиана и среднее п.п., доля в плюсе, итог и SOL в сутки при билете группы."""
    if not ряды:
        return {"n": 0}
    пп = [r["пп"] for r in ряды]
    в_sol = sorted((r["пп"] / 100 * r["билет"] for r in ряды), reverse=True)
    sol = sum(в_sol)
    return {"n": len(ряды), "медиана_пп": round(statistics.median(пп), 2),
            "среднее_пп": round(statistics.mean(пп), 2),
            "в_плюсе": round(100 * sum(1 for x in пп if x > 0) / len(пп)),
            "итог_sol": round(sol, 6), "sol_в_сутки": round(sol / суток, 6) if суток else None,
            # хвост: корзины выше 20 % держатся на одной-двух сделках, это надо видеть
            "итог_без_верхних_2_sol": round(sum(в_sol[2:]), 6) if len(в_sol) > 2 else None}


def main() -> int:
    import podbivka_run as R  # noqa: PLC0415
    р = argparse.ArgumentParser()
    р.add_argument("--metka", default=time.strftime("%Y-%m-%d", time.gmtime()))
    р.add_argument("--shablony", default=",".join(ШАБЛОНЫ))
    р.add_argument("--otdelno", default="6qudAN2k", help="источник отдельным разрезом (начало адреса)")
    р.add_argument("--iz-json", action="store_true",
                   help="перестроить страницу по data/podbivka/dopusk_ceny.json, без чтения архива")
    а = р.parse_args()

    if а.iz_json:
        готовое = json.loads((П / "dopusk_ceny.json").read_text(encoding="utf-8"))
        ряды, счёт = готовое["ряды"], готовое["счёт"]
        сутки, файлы = set(готовое["сутки"]), [None] * готовое["файлов"]
    else:
        адр = json.loads((П / "arhiv_adresa.json").read_text(encoding="utf-8"))["адреса"]
        торгующие = set(json.loads(
            (П / "istochniki_torguyuschie.json").read_text(encoding="utf-8"))["адреса"])
        файлы = []
        for ш in а.shablony.split(","):
            файлы += sorted(glob.glob(str(П / "arhiv_den" / ш.strip())))
        ряды, сутки = [], set()
        счёт = {"сигналов": 0, "торгующих": 0, "нет_состояний": 0, "нет_пп": 0,
                "нет_группы": 0, "не_wsol": 0, "дублей_подписи": 0}
        видели: set = set()
        for f in файлы:
            д = json.loads(gzip.open(f).read())
            for с in д.get("сигналы") or []:
                счёт["сигналов"] += 1
                t = с.get("trader")
                if t not in торгующие:
                    continue
                счёт["торгующих"] += 1
                if с.get("signature") in видели:      # окна файлов перекрываются
                    счёт["дублей_подписи"] += 1
                    continue
                видели.add(с.get("signature"))
                if с.get("quoteMint") != WSOL:
                    счёт["не_wsol"] += 1
                    continue
                г = группа_источника(адр, t)
                if not г:
                    счёт["нет_группы"] += 1
                    continue
                у = уход_пп(с)
                if у is None:
                    счёт["нет_состояний"] += 1
                    continue
                к = корзина(у)
                if к is None:
                    continue
                б = БИЛЕТ_ГРУППЫ[г]
                пп = B.пп_по_состояниям(с, б, "S1", ВЫХОД)
                if пп is None:
                    счёт["нет_пп"] += 1
                    continue
                д_ = time.strftime("%Y-%m-%d", time.gmtime((с.get("timestamp") or 0) / 1000))
                сутки.add(д_)
                ряды.append({"источник": t, "группа": г, "билет": б, "пул": с.get("pool"),
                             "уход_пп": round(у, 2), "корзина": к, "пп": пп, "сутки": д_,
                             "подпись": с.get("signature"), "sol": с.get("sol")})


    if not ряды:
        print("нет рядов: нечего считать", flush=True)
        return 1
    суток = len(сутки)

    def разрез(выбор) -> dict:
        от = [r for r in ряды if выбор(r)]
        д_ = len({r["сутки"] for r in от}) or 1
        из_ = {"всего": стат(от, д_), "суток": д_, "по_корзинам": {}}
        for _, _, имя in КОРЗИНЫ:
            из_["по_корзинам"][имя] = стат([r for r in от if r["корзина"] == имя], д_)
        из_["допуски"] = {}
        for доп in ДОПУСКИ:
            из_["допуски"]["все" if доп == float("inf") else f"{доп:g}"] = стат(
                [r for r in от if r["уход_пп"] <= доп], д_)
        return из_

    разрезы = {
        "все торгующие": разрез(lambda r: True),
        "кривая pump.fun": разрез(lambda r: r["пул"] == "pump"),
        "Pump AMM": разрез(lambda r: r["пул"] == "pump-amm"),
        f"{а.otdelno} отдельно": разрез(lambda r: r["источник"].startswith(а.otdelno)),
    }
    итог = {"что": "допуск по цене: уход цены до нашего слота S+1 и итог по корзинам ухода",
            "окно_суток": суток, "сутки": sorted(сутки), "файлов": len(файлы), "счёт": счёт,
            "выход_слотов": ВЫХОД, "билеты_групп": БИЛЕТ_ГРУППЫ, "разрезы": разрезы,
            "ряды": ряды}
    out = П / "dopusk_ceny.json"
    out.write_text(json.dumps(итог, ensure_ascii=False, indent=1), encoding="utf-8")
    R.записано(out)

    def ф(v: dict, к: str, формат: str) -> str:
        return "—" if v.get(к) is None else format(v[к], формат)

    def таблица(заг: str, р_: dict) -> list:
        м = [f"### {заг}", "",
             f"Сделок {р_['всего'].get('n', 0)} за {р_['суток']} суток; итог "
             f"{ф(р_['всего'], 'итог_sol', '+.4f')} SOL, {ф(р_['всего'], 'sol_в_сутки', '+.6f')} SOL в сутки.",
             "", "| корзина ухода | n | медиана, п.п. | среднее, п.п. | в плюсе | итог SOL "
             "| итог без верхних 2 сделок, SOL | SOL в сутки |",
             "|---|---|---|---|---|---|---|---|"]
        for _, _, имя in КОРЗИНЫ:
            v = р_["по_корзинам"][имя]
            м.append(f"| {имя} % | {v.get('n', 0)} | {ф(v, 'медиана_пп', '+.2f')} "
                     f"| {ф(v, 'среднее_пп', '+.2f')} "
                     f"| {ф(v, 'в_плюсе', 'd') + '%' if v.get('n') else '—'} "
                     f"| {ф(v, 'итог_sol', '+.4f')} "
                     f"| {ф(v, 'итог_без_верхних_2_sol', '+.4f')} "
                     f"| {ф(v, 'sol_в_сутки', '+.6f')} |")
        м += ["", "| допуск (берём сделки с уходом ≤) | n | медиана, п.п. | итог SOL | SOL в сутки |",
              "|---|---|---|---|---|"]
        for к_, v in р_["допуски"].items():
            м.append(f"| {к_ if к_ == 'все' else к_ + ' %'} | {v.get('n', 0)} "
                     f"| {ф(v, 'медиана_пп', '+.2f')} | {ф(v, 'итог_sol', '+.4f')} "
                     f"| {ф(v, 'sol_в_сутки', '+.6f')} |")
        return м + [""]

    общ = разрезы["все торгующие"]
    лучший = max(общ["допуски"].items(), key=lambda kv: (kv[1].get("sol_в_сутки") or -1e9))
    тек = общ["допуски"].get("35") or {}
    разн = ((лучший[1].get("sol_в_сутки") or 0) - (тек.get("sol_в_сутки") or 0))
    к3550 = общ["по_корзинам"]["35--50"]

    md = [f"# Допуск по цене: уход цены до нашего слота и итог по корзинам ({а.metka})", "",
          f"Окно: {суток} суток архива ({min(сутки)} -- {max(сутки)}), файлов {len(файлы)}. "
          f"Действующие источники торгующих групп, первые покупки ≥ 2 SOL-экв, котировка WSOL. "
          f"Уход цены = (цена в нашем слоте S+1 / цена сразу после сделки источника − 1); цена "
          f"по состояниям пула того же прохода. Итог — п.п. чистыми при удержании +{ВЫХОД} и "
          f"билете группы источника, формула `podbivka_bilet.пп_по_состояниям` (место «S1»).", "",
          f"Сигналов в файлах {счёт['сигналов']}, из них у торгующих источников "
          f"{счёт['торгующих']}; в счёт пошли {len(ряды)}. Отброшено: котировка не WSOL "
          f"{счёт['не_wsol']}, нет торговой группы у источника {счёт['нет_группы']}, нет "
          f"состояний S0/S1 в проходе {счёт['нет_состояний']}, дублей подписи (окна файлов "
          f"перекрываются) {счёт['дублей_подписи']}, модель не дала п.п. {счёт['нет_пп']}. "
          f"Сделки, где цена ушла ВНИЗ, не выбрасываются: они идут корзиной «ниже 0» и входят в "
          f"любой допуск.", "",
          "S+2 здесь нет: в проходах архива хранятся состояния только S0, S0_дно и S1. Точка "
          "«S2» добавлена в модель прохода, в следующих ночных файлах она появится сама; "
          "пересчитывать прошлые сутки ради неё не нужно.", ""]
    for заг, р_ in разрезы.items():
        md += таблица(заг, р_)
    md += ["## Вывод", "",
           f"Лучший итог по архиву — допуск **{лучший[0] if лучший[0] == 'все' else лучший[0] + ' %'}**: "
           f"{ф(лучший[1], 'sol_в_сутки', '+.6f')} SOL в сутки против "
           f"{ф(тек, 'sol_в_сутки', '+.6f')} при нынешних 35 % — разница "
           f"{разн:+.6f} SOL в сутки; корзина 35--50 % даёт "
           f"{ф(к3550, 'итог_sol', '+.4f')} SOL при n {к3550.get('n', 0)} "
           f"(медиана {ф(к3550, 'медиана_пп', '+.2f')} п.п.), а без двух верхних сделок "
           f"{ф(к3550, 'итог_без_верхних_2_sol', '+.4f')} SOL.", "",
           "Хвост: корзины выше 20 % стоят на одной-двух сделках — без двух верхних каждая из "
           "них уходит в минус (столбец «итог без верхних 2 сделок»), поэтому разница между "
           "допусками 35 % и «все» меньше разброса хвоста. Кривая и Pump AMM расходятся: у "
           "кривой лучший допуск низкий, у Pump AMM итог растёт с допуском.", "",
           "Ничего не меняется и не рекомендуется — решает владелец.", ""]
    стр = КОРЕНЬ / "docs" / f"podbivka_{а.metka}_dopusk_ceny.md"
    стр.write_text("\n".join(md) + "\n", encoding="utf-8")
    R.записано(стр)
    print(f"{стр.name}: рядов {len(ряды)}, суток {суток}; лучший допуск {лучший[0]} "
          f"{лучший[1].get('sol_в_сутки')} против 35 % {тек.get('sol_в_сутки')}", flush=True)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
