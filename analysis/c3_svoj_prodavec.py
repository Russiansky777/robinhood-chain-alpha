def тип_пула(программа) -> dict | None:
    """Запись реестра по программе пула. Нет в реестре -- None, а не догадка."""
    return ТИПЫ.get(str(программа or ""))


def имя_типа(программа) -> str:
    т = тип_пула(программа)
    return (т or {}).get("имя") or f"неизвестный пул ({str(программа or '')[:8]})"


def умеет_котировать(программа) -> bool:
    т = тип_пула(программа) or {}
    return bool(т.get("модуль_котировки") and т.get("котировка"))


def умеет_продать(программа) -> bool:
    т = тип_пула(программа) or {}
    return bool(т.get("модуль_продажи") and т.get("продажа"))


def план_второго_мнения(программа) -> dict:
    """Чем котировать пул НАШЕЙ покупки. Чистая функция, ни сети, ни подписи.

    Отдаёт имена модуля и функции, а не сами объекты: импортировать подбивку
    должен тот, кто будет читать счета -- у него и узел, и его отказы.
    """
    т = тип_пула(программа)
    из_ = {"можно": False, "имя": имя_типа(программа), "модуль": None,
            "функция": None, "продажа_своим": умеет_продать(программа),
            "почему_нет": None}
    if т is None:
        из_["почему_нет"] = (f"программа пула {str(программа or '')[:8]} не в реестре "
                              "типов -- котировать нечем, и догадываться тут нельзя")
        return из_
    if not умеет_котировать(программа):
        из_["почему_нет"] = (f"{из_['имя']}: подбивки под этот тип нет -- своим "
                              "строителем его не котировать")
        return из_
    из_.update(можно=True, модуль=т["модуль_котировки"], функция=т["котировка"])
    return из_


def круг_001(программа, *, обкатан: bool) -> dict:
    """Нужен ли круг 0.01 на первую продажу этого типа своим путём (правило 8).

    `обкатан` приходит снаружи -- из отметки состояния службы. Своей памяти у
    этой функции нет намеренно: "кажется, уже обкатали" -- это не число.
    """
    из_ = {"размер_sol": None, "круг_нужен": False, "имя": имя_типа(программа),
            "почему": None}
    if not умеет_продать(программа):
        из_["почему"] = (f"{из_['имя']}: сборки продажи нет -- круг ставить не к "
                          "чему, продаёт Jupiter")
        return из_
    if обкатан:
        из_["почему"] = f"{из_['имя']}: тип уже обкатан своим путём, размер обычный"
        return из_
    из_.update(размер_sol=КРУГ_SOL, круг_нужен=True,
                почему=(f"{из_['имя']}: первая продажа своим путём -- круг "
                         f"{КРУГ_SOL} SOL (правило 8)"))
    return из_


def сводка() -> dict:
    """Что умеем на сегодня, числами -- для доклада и для деплоя."""
    кот = [п for п in ТИПЫ if умеет_котировать(п)]
    прод = [п for п in ТИПЫ if умеет_продать(п)]
    return {"типов": len(ТИПЫ), "котируем": len(кот), "продаём_своим": len(прод),
             "котируем_имена": sorted(ТИПЫ[п]["имя"] for п in кот),
             "продаём_имена": sorted(ТИПЫ[п]["имя"] for п in прод),
             "не_котируем_имена": sorted(ТИПЫ[п]["имя"] for п in ТИПЫ
                                          if п not in кот)}


