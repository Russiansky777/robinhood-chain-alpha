#!/usr/bin/env python3
"""Калибровка модели архива по живым сделкам полосы (задача владельца 08.10, п.1).

Зачем. Числа модели архива -- верхняя граница: вход «конец слота», издержки зашиты 0.002 SOL
на круг, наценка входа f и выхода g подогнаны по хранилищам окна прохода, а не по нашему
фактическому месту в блоке. Пока модель не сверена с деньгами по цепи, ретро-прогон нельзя
использовать для решения о билете 1-2 SOL. Здесь модель считается ДЛЯ ТОЙ ЖЕ сделки --
тот же сигнал источника (по подписи), наша посадка S+k, наш билет `size_sol`, наше
удержание, наши издержки по цепи -- и сравнивается с итогом по цепи.

Что берётся по факту, а не из модели:
  * билет -- `size_sol` (сколько SOL реально ушло в покупку);
  * издержки круга -- из разбора итога по цепи: (-покупка.все_sol - билет) + продажа.комиссия.
    Это чаевые, приоритет, тариф, комиссия и незакрытая рента -- в модели вместо них 0.002;
  * горизонт выхода -- ближайший сохранённый к `hold_slots_fact`;
  * место входа -- по `s_plus` (0/1/2), карта мест подбирается.
Подгоняются: карта мест, множители наценки входа `к_f` и выхода `к_g`. Критерий --
медиана расхождения (модель минус цепь) около нуля; остаточное расхождение по группам --
в таблице.

Выход: data/podbivka/kalibrovka.json, docs/podbivka_<метка>_kalibrovka.md.
Только чтение. Ничего не рекомендуется -- решает владелец.
"""
from __future__ import annotations

import argparse
import collections
import json
import os
import statistics
import sys
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import podbivka_bilet as B  # noqa: E402
import podbivka_paket_obshee as O  # noqa: E402
import podbivka_zhivye as Ж  # noqa: E402

КОРЕНЬ = O.КОРЕНЬ
П = O.П
# место входа модели по нашей фактической посадке; S0 -- сразу за сделкой источника,
# S0_дно -- конец его слота, S1/S2 -- конец следующего и через один
МЕСТА_ПО_ПОСАДКЕ = {0: "S0_дно", 1: "S1", 2: "S2"}
КАНДИДАТЫ_МЕСТ = {0: ("S0", "S0_дно"), 1: ("S0_дно", "S1"), 2: ("S1", "S2")}


def горизонты(р: dict) -> list:
    return sorted(int(k) for k in (р.get("выход") or {}) if str(k).isdigit())


def издержки_факт(с: dict) -> float | None:
    """Издержки круга по цепи: сколько SOL ушло сверх билета плюс комиссия продажи."""
    ч = с.get("итог_po_cepi_chasti") or {}
    пок, прод = ч.get("покупка") or {}, ч.get("продажа") or {}
    a = с.get("вложено")
    if not a or пок.get("все_sol") is None or прод.get("все_sol") is None:
        return None
    if пок.get("ошибка") or прод.get("ошибка"):
        return None
    return (-float(пок["все_sol"]) - a) + float(прод.get("комиссия_sol") or 0)


def пары(сделки: list, кэш_путь=None) -> list:
    """Живая сделка + сигнал источника из архива по подписи; только пригодные к модели."""
    по_подписи = {}
    for с in сделки:
        if с.get("source_sig"):
            по_подписи.setdefault(с["source_sig"], []).append(с)
    сигналы = {}
    for р in O.сигналы(фильтр=lambda r: r.get("подпись") in по_подписи, путь=кэш_путь):
        сигналы[р["подпись"]] = р
    из_ = []
    счёт = collections.Counter()
    for sig, сдс in по_подписи.items():
        р = сигналы.get(sig)
        if р is None:
            счёт["нет_в_архиве"] += len(сдс)
            continue
        г = горизонты(р)
        for с in сдс:
            if с.get("итог") is None or с["итог_откуда"] != "цепь":
                счёт["нет_итога_по_цепи"] += 1
                continue
            if not с.get("вложено"):
                счёт["нет_билета"] += 1
                continue
            из_иж = издержки_факт(с)
            if из_иж is None:
                счёт["нет_разбора_издержек"] += 1
                continue
            if not (р.get("вход") and г):
                счёт["нет_состояний"] += 1
                continue
            h_факт = с.get("hold_slots_fact") or с.get("hold_slots_plan")
            if not h_факт:
                счёт["нет_удержания"] += 1
                continue
            h = min(г, key=lambda x: abs(x - h_факт))
            из_.append({"сделка": с, "сигнал": р, "горизонт": h, "горизонт_факт": h_факт,
                        "издержки": из_иж})
            счёт["в_счёте"] += 1
    return из_, dict(счёт)


def модель(п: dict, места: dict, к_f: float, к_g: float, издержки: str = "факт") -> float | None:
    с, р = п["сделка"], п["сигнал"]
    место = места.get(с.get("s_plus"), МЕСТА_ПО_ПОСАДКЕ.get(1))
    из_ = п["издержки"] if издержки == "факт" else 0.002
    д = B.сделка_по_состояниям(O.как_сигнал(р), с["вложено"], место, п["горизонт"],
                               издержки=из_, к_f=к_f, к_g=к_g,
                               налог_bps=float(с.get("nalog_tokena_bps") or 0))
    return None if д is None else д["итог_sol"]


def расхождения(пары_: list, места: dict, к_f: float, к_g: float, издержки: str = "факт") -> list:
    из_ = []
    for п in пары_:
        м = модель(п, места, к_f, к_g, издержки)
        if м is None:
            continue
        из_.append({"группа": п["сделка"].get("group"), "ист": п["сделка"].get("source"),
                    "пул": п["сигнал"].get("пул"), "билет": п["сделка"]["вложено"],
                    "s_plus": п["сделка"].get("s_plus"), "модель": м,
                    "цепь": п["сделка"]["итог"], "разница": м - п["сделка"]["итог"]})
    return из_


def медиана(р: list, поле: str = "разница"):
    v = [x[поле] for x in р if x.get(поле) is not None]
    return statistics.median(v) if v else None


def подбор_к_g(пары_: list, места: dict, к_f: float, издержки: str,
               низ: float = 0.2, верх: float = 2.5, шагов: int = 40) -> float:
    """Медиана расхождения растёт по к_g монотонно -- деление отрезка пополам."""
    def м(k):
        v = медиана(расхождения(пары_, места, к_f, k, издержки))
        return v if v is not None else 0.0
    а, б = низ, верх
    if м(а) > 0:
        return а
    if м(б) < 0:
        return б
    for _ in range(шагов):
        с = (а + б) / 2
        if м(с) < 0:
            а = с
        else:
            б = с
    return round((а + б) / 2, 6)


def свод_групп(р: list) -> dict:
    из_: dict = {}
    for г in sorted({x["группа"] for x in р if x.get("группа")}):
        ч = [x for x in р if x["группа"] == г]
        из_[г] = {"n": len(ч),
                  "медиана_разницы_sol": round(statistics.median([x["разница"] for x in ч]), 6),
                  "среднее_разницы_sol": round(statistics.mean([x["разница"] for x in ч]), 6),
                  "медиана_модель_sol": round(statistics.median([x["модель"] for x in ч]), 6),
                  "медиана_цепь_sol": round(statistics.median([x["цепь"] for x in ч]), 6),
                  "итог_модель_sol": round(sum(x["модель"] for x in ч), 6),
                  "итог_цепь_sol": round(sum(x["цепь"] for x in ч), 6),
                  "модель_выше_доля": round(100 * sum(1 for x in ч if x["разница"] > 0) / len(ч))}
    return из_


def ф(v, формат="+.6f"):
    return "—" if v is None else format(v, формат)


def main() -> int:
    import podbivka_run as R  # noqa: PLC0415
    р_ = argparse.ArgumentParser()
    р_.add_argument("--metka", default=time.strftime("%Y-%m-%d", time.gmtime()))
    р_.add_argument("--s", default="2026-09-27T00:00:00Z")
    а = р_.parse_args()

    сделки = Ж.сделки(s=а.s)
    пары_, счёт = пары(сделки)
    if not пары_:
        print("нет пар живая сделка + сигнал архива", flush=True)
        return 1

    # --- ступень 0: как есть (издержки модели 0.002, места по посадке, множители 1)
    ступени = {}
    ступени["0. модель как есть (издержки 0.002)"] = {
        "места": dict(МЕСТА_ПО_ПОСАДКЕ), "к_f": 1.0, "к_g": 1.0, "издержки": "0.002"}
    ступени["1. издержки по цепи"] = {
        "места": dict(МЕСТА_ПО_ПОСАДКЕ), "к_f": 1.0, "к_g": 1.0, "издержки": "факт"}

    # --- ступень 2: карта мест -- перебор кандидатов по |медиане|
    лучшая, лучшее = dict(МЕСТА_ПО_ПОСАДКЕ), None
    for м0 in КАНДИДАТЫ_МЕСТ[0]:
        for м1 in КАНДИДАТЫ_МЕСТ[1]:
            for м2 in КАНДИДАТЫ_МЕСТ[2]:
                к = {0: м0, 1: м1, 2: м2}
                v = медиана(расхождения(пары_, к, 1.0, 1.0, "факт"))
                if v is None:
                    continue
                if лучшее is None or abs(v) < abs(лучшее):
                    лучшая, лучшее = к, v
    ступени["2. места подобраны"] = {"места": лучшая, "к_f": 1.0, "к_g": 1.0, "издержки": "факт"}

    # --- ступень 3: множитель выхода к_g до нуля медианы
    к_g = подбор_к_g(пары_, лучшая, 1.0, "факт")
    ступени["3. к_g подобран"] = {"места": лучшая, "к_f": 1.0, "к_g": к_g, "издержки": "факт"}

    итог: dict = {
        "что": "калибровка модели архива по живым сделкам полосы (п.1 задачи 08.10)",
        "источник_чисел": {"сделки": "data/sdelki_polosy_* ветки claude/nifty-sagan-r0polg",
                           "коммит_code1": os.environ.get("PODB_C1_REV", ""),
                           "кэш_архива": str(O.КЭШ)},
        "счёт_пар": счёт, "сделок_всего": len(сделки), "пар": len(пары_),
        "ступени": {}, "по_группам_к_g": {}}

    for имя, п in ступени.items():
        р = расхождения(пары_, п["места"], п["к_f"], п["к_g"], п["издержки"])
        итог["ступени"][имя] = {
            "параметры": {"места": {f"S+{k}": v for k, v in п["места"].items()},
                          "к_f": п["к_f"], "к_g": п["к_g"], "издержки": п["издержки"]},
            "n": len(р), "медиана_разницы_sol": round(медиана(р), 6) if р else None,
            "среднее_разницы_sol": round(statistics.mean([x["разница"] for x in р]), 6) if р else None,
            "итог_модель_sol": round(sum(x["модель"] for x in р), 6),
            "итог_цепь_sol": round(sum(x["цепь"] for x in р), 6),
            "по_группам": свод_групп(р)}

    # --- ступень 4: свой к_g на группу (сколько нужно, чтобы медиана группы была нулём)
    for г in sorted({п["сделка"].get("group") for п in пары_ if п["сделка"].get("group")}):
        ч = [п for п in пары_ if п["сделка"].get("group") == г]
        if len(ч) < 10:
            continue
        k = подбор_к_g(ч, лучшая, 1.0, "факт")
        р = расхождения(ч, лучшая, 1.0, k, "факт")
        итог["по_группам_к_g"][г] = {"n": len(р), "к_g": k,
                                     "медиана_разницы_sol": round(медиана(р), 6) if р else None,
                                     "медиана_цепь_sol": round(statistics.median(
                                         [x["цепь"] for x in р]), 6) if р else None}

    # --- вспомогательное: сколько промахнулись горизонтом и чем крыты пары
    итог["горизонт"] = {"распределение": dict(collections.Counter(
        f"{п['горизонт']} при факте {int(п['горизонт_факт'])}" for п in пары_).most_common(12)),
        "медиана_|промаха|_слотов": statistics.median(
            [abs(п["горизонт"] - п["горизонт_факт"]) for п in пары_])}
    итог["издержки_по_группам_sol"] = {
        г: round(statistics.median([п["издержки"] for п in пары_
                                    if п["сделка"].get("group") == г]), 6)
        for г in sorted({п["сделка"].get("group") for п in пары_ if п["сделка"].get("group")})}
    итог["калибровка"] = {"места": {f"S+{k}": v for k, v in лучшая.items()},
                          "к_f": 1.0, "к_g": к_g, "издержки": "факт по цепи, медиана по группе",
                          "издержки_медиана_sol": round(statistics.median(
                              [п["издержки"] for п in пары_]), 6)}

    out = П / "kalibrovka.json"
    out.write_text(json.dumps(итог, ensure_ascii=False, indent=1), encoding="utf-8")
    R.записано(out)

    md = [f"# Калибровка модели архива по живым сделкам ({а.metka})", "",
          f"Пар «живая сделка + сигнал источника в архиве» -- **{len(пары_)}** из {len(сделки)} "
          f"сделок окна. Не вошли: нет сигнала в архиве {счёт.get('нет_в_архиве', 0)}, нет итога "
          f"по цепи {счёт.get('нет_итога_по_цепи', 0)}, нет разбора издержек "
          f"{счёт.get('нет_разбора_издержек', 0)}, нет состояний пула {счёт.get('нет_состояний', 0)}. "
          f"Горизонт выхода -- ближайший сохранённый к фактическому удержанию, медиана промаха "
          f"{итог['горизонт']['медиана_|промаха|_слотов']:.0f} слотов.", "",
          "Расхождение = модель минус цепь, в SOL на сделку. Положительное значит, что модель "
          "обещает больше, чем пришло на счёт.", "",
          "| ступень | места S+0/S+1/S+2 | к_f | к_g | издержки | n | медиана расхождения | "
          "среднее | итог модели | итог по цепи |", "|---|---|---|---|---|---|---|---|---|---|"]
    for имя, v in итог["ступени"].items():
        p = v["параметры"]
        md.append(f"| {имя} | {p['места']['S+0']}/{p['места']['S+1']}/{p['места']['S+2']} "
                  f"| {p['к_f']:.3f} | {p['к_g']:.3f} | {p['издержки']} | {v['n']} "
                  f"| {ф(v['медиана_разницы_sol'])} | {ф(v['среднее_разницы_sol'])} "
                  f"| {ф(v['итог_модель_sol'])} | {ф(v['итог_цепь_sol'])} |")
    итоговая = итог["ступени"]["3. к_g подобран"]
    md += ["", "## Остаточное расхождение по группам (калиброванная модель)", "",
           "| группа | n | медиана расхождения SOL | среднее | медиана модели | медиана цепи "
           "| итог модели | итог цепи | модель выше, % | свой к_g | издержки медиана SOL |",
           "|---|---|---|---|---|---|---|---|---|---|---|"]
    for г, v in sorted(итоговая["по_группам"].items(), key=lambda kv: -kv[1]["n"]):
        св = итог["по_группам_к_g"].get(г) or {}
        md.append(f"| {г} | {v['n']} | {ф(v['медиана_разницы_sol'])} | {ф(v['среднее_разницы_sol'])} "
                  f"| {ф(v['медиана_модель_sol'])} | {ф(v['медиана_цепь_sol'])} "
                  f"| {ф(v['итог_модель_sol'])} | {ф(v['итог_цепь_sol'])} | {v['модель_выше_доля']} "
                  f"| {св.get('к_g', '—') if not св else format(св['к_g'], '.3f')} "
                  f"| {ф(итог['издержки_по_группам_sol'].get(г), '.6f')} |")
    md += ["", "## Подогнанные параметры", "",
           f"* место входа: S+0 -> **{лучшая[0]}**, S+1 -> **{лучшая[1]}**, S+2 -> **{лучшая[2]}**;",
           f"* множитель наценки входа к_f = **{1.0:.3f}** (не подгонялся: по итогу он не отделим "
           f"от к_g, а наценка выхода объясняет расхождение полностью);",
           f"* множитель наценки выхода к_g = **{к_g:.4f}**;",
           f"* издержки круга -- по цепи, медиана {итог['калибровка']['издержки_медиана_sol']:.6f} SOL "
           f"против 0.002 SOL в модели архива;",
           f"* остаточная медиана расхождения {ф(итоговая['медиана_разницы_sol'])} SOL на сделку.", "",
           "Ничего не меняется и не рекомендуется -- решает владелец.", ""]
    стр = КОРЕНЬ / "docs" / f"podbivka_{а.metka}_kalibrovka.md"
    стр.write_text("\n".join(md) + "\n", encoding="utf-8")
    R.записано(стр)
    print(f"{стр.name}: пар {len(пары_)}, к_g {к_g}, остаточная медиана "
          f"{итоговая['медиана_разницы_sol']}", flush=True)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
