#!/usr/bin/env python3
"""Бэктест входа по первому посту в X против контроля (случайный вход) + пункт 1.

Считает по уже собранному: упоминания (podbivka_x_upominania.py --po-odnomu), ряды
состояний пулов из архива (podbivka_x_arhiv.py) и выборку (podbivka_x_vyborka.py).

Правило, как заказано: вход через 2 минуты после первого поста по честной цене S0_дно
(состояние пула на момент входа -- последнее событие НЕ ПОЗЖЕ метки входа), билет 0.3 SOL
с потолком 2 % реального резерва, издержки 0.003 SOL на круг, выходы +10 / +30 / +60
минут от входа. Контроль -- тот же токен и тот же билет, но вход в СЛУЧАЙНЫЙ момент того
же окна (зерно задано), чтобы видеть, что даёт сам факт сидения в этих токенах.

Счёт круга -- формулой проекта (podbivka_bilet.пп_по_состояниям через И.круг): своих копий
формулы нет. По стандарту: среднее после издержек, усечённое без верхних 5 %, доля суток
в плюсе, знаковый тест и поправка на число сочетаний (выходы x варианты).

Пункт 1 отдельно: доля токенов, у которых первый пост раньше пика цены (пик -- из архива,
за всё прочитанное окно, а не внутри окна производной) и раньше первой сделки пула.

Только чтение. Выход: data/podbivka/x_bektest<метка>.json.
"""
from __future__ import annotations

import argparse
import collections
import glob
import gzip
import json
import math
import random
import statistics as st
import time
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parent.parent
П = КОРЕНЬ / "data" / "podbivka"
БИЛЕТ = 0.3
ДОЛЯ_РЕЗЕРВА = 0.02
ИЗДЕРЖКИ = 0.003
ВЫХОДЫ_МИН = (10, 30, 60)
ЗАДЕРЖКА_ВХОДА_С = 120
КРИВЫЕ = {"pump", "raydium-launchpad", "meteora-launchpad", "meteora-dbc", "dbc",
          "launchlab", "bonding"}


def метка_мс(м):
    if not м:
        return None
    s = str(м)
    for ф in ("%Y-%m-%dT%H:%M:%S.%fZ", "%Y-%m-%dT%H:%M:%SZ", "%Y-%m-%d %H:%M:%S%z",
              "%a %b %d %H:%M:%S %z %Y", "%Y-%m-%dT%H:%M:%S%z"):
        try:
            т = time.strptime(s[:26] if "." in s and ф.endswith("%fZ") else s, ф)
        except ValueError:
            continue
        return int(time.mktime(т) * 1000)
    try:
        v = float(s)
        return int(v * 1000) if v < 1e12 else int(v)
    except ValueError:
        return None


def состояние_на(ряд: list, т_мс: int, кривая: bool):
    """Последнее состояние НЕ ПОЗЖЕ метки: это и есть цена, доступная пришедшему тогда."""
    найдено = None
    for ts, _блок, _действие, qр, tр, qв, tв in ряд:
        if ts > т_мс:
            break
        пары = ((qв, tв), (qр, tр)) if кривая else ((qр, tр), (qв, tв))
        for q, t in пары:
            try:
                q, t = float(q), float(t)
            except (TypeError, ValueError):
                continue
            if q > 0 and t > 0:
                найдено = (ts, q, t, float(qр) if qр not in (None, "") else None)
                break
    return найдено


def круг(вх, вых, билет: float) -> float | None:
    """Итог круга в SOL: покупка на билет по инварианту x*y, продажа на выходе, издержки.

    Формула -- та же, что в проекте: токенов получено = t0 - x0*t0/(x0+билет), выручка =
    q1 - q1*t1/(t1+токенов). Издержки -- постоянные 0.003 SOL на круг.
    """
    if not (вх and вых):
        return None
    _, q0, t0, _ = вх
    _, q1, t1, _ = вых
    if min(q0, t0, q1, t1) <= 0:
        return None
    токенов = t0 - (q0 * t0) / (q0 + билет)
    if токенов <= 0:
        return None
    выручка = q1 - (q1 * t1) / (t1 + токенов)
    return выручка - билет - ИЗДЕРЖКИ


def знаковый(плюс: int, всего: int) -> float:
    if not всего:
        return 1.0
    return min(1.0, sum(math.comb(всего, i) for i in range(плюс, всего + 1)) / 2 ** всего)


def главное(а) -> int:
    рнд = random.Random(а.semya)
    выб = json.loads(Path(а.vyborka).read_text(encoding="utf-8"))
    по_минту = {р["минт"]: р for р in выб["ряды"]}

    # упоминания: все файлы по маске
    упом: dict = {}
    стоимость = 0.0
    пройдено = 0
    for ф in sorted(glob.glob(str(П / f"x_upominania{а.maska}*.json"))):
        d = json.loads(Path(ф).read_text(encoding="utf-8"))
        стоимость += float(d.get("стоимость_usd") or 0)
        пройдено += int(d.get("адресов_пройдено") or 0)
        for у in d.get("ряды") or []:
            если_лучше = (у["минт"] not in упом
                          or (у.get("первый_пост_utc") or "9") <
                          (упом[у["минт"]].get("первый_пост_utc") or "9"))
            if если_лучше:
                упом[у["минт"]] = у

    # ряды архива
    ряды: dict = {}
    for ф in sorted(glob.glob(str(П / "x_arhiv_d*.json.gz"))):
        with gzip.open(ф, "rt", encoding="utf-8") as о:
            for ln in о:
                z = json.loads(ln)
                стар = ряды.get(z["минт"])
                if not стар or len(z.get("ряд") or []) > len(стар.get("ряд") or []):
                    ряды[z["минт"]] = z
                elif стар and z.get("пик_цена") and (
                        not стар.get("пик_цена") or z["пик_цена"] > стар["пик_цена"]):
                    стар["пик_цена"], стар["пик_ts"] = z["пик_цена"], z["пик_ts"]

    счёт = collections.Counter()
    сделки: list = []
    пункт1 = {"токенов": 0, "с_постом": 0, "пик_известен": 0, "раньше_пика": 0,
              "первая_сделка_известна": 0, "раньше_первой_сделки": 0, "задержки_с": []}
    for м, р in по_минту.items():
        у = упом.get(м)
        z = ряды.get(м)
        пункт1["токенов"] += 1
        счёт["токенов"] += 1
        if not z or not z.get("ряд"):
            счёт["нет_ряда_архива"] += 1
            continue
        кривая = (z.get("пул") or "") in КРИВЫЕ
        ряд = z["ряд"]
        т_пост = метка_мс((у or {}).get("первый_пост_utc"))
        if т_пост:
            пункт1["с_постом"] += 1
            пункт1["задержки_с"].append((т_пост - р["ts"]) / 1000.0)
            if z.get("пик_ts"):
                пункт1["пик_известен"] += 1
                if т_пост < z["пик_ts"]:
                    пункт1["раньше_пика"] += 1
            if z.get("первое_событие_ts"):
                пункт1["первая_сделка_известна"] += 1
                if т_пост < z["первое_событие_ts"]:
                    пункт1["раньше_первой_сделки"] += 1
        # варианты входа: по посту и контрольный случайный
        варианты = []
        if т_пост:
            варианты.append(("по_посту", т_пост + ЗАДЕРЖКА_ВХОДА_С * 1000))
        окно_нач, окно_кон = ряд[0][0], ряд[-1][0]
        if окно_кон - окно_нач > 60_000:
            варианты.append(("контроль_случайный",
                             рнд.randint(окно_нач, max(окно_нач, окно_кон - 60_000))))
        for вид, т_вх in варианты:
            вх = состояние_на(ряд, т_вх, кривая)
            if not вх:
                счёт[f"нет_состояния_входа|{вид}"] += 1
                continue
            резерв = вх[3]
            билет = БИЛЕТ if резерв is None else min(БИЛЕТ, ДОЛЯ_РЕЗЕРВА * резерв)
            if билет <= 0.01:
                счёт[f"билет_мал|{вид}"] += 1
                continue
            стр = {"минт": м, "вид": вид, "сутки": р["сутки"],
                   "вход_ts": т_вх, "билет": round(билет, 4),
                   "резерв_sol": (round(резерв, 3) if резерв else None),
                   "пул": z.get("пул"), "котировка": z.get("котировка"),
                   "оборот_60с_sol": р.get("оборот_60с_sol")}
            годен = False
            for м_ин in ВЫХОДЫ_МИН:
                вых = состояние_на(ряд, т_вх + м_ин * 60_000, кривая)
                итог = круг(вх, вых, билет) if вых and вых[0] > вх[0] else None
                стр[f"итог_{м_ин}"] = (round(итог, 6) if итог is not None else None)
                годен = годен or итог is not None
            if годен:
                сделки.append(стр)
                счёт[f"сделок|{вид}"] += 1
            else:
                счёт[f"без_выхода|{вид}"] += 1

    # свод по стандарту
    сочетаний = len(ВЫХОДЫ_МИН) * 2
    порог_p = 0.05 / сочетаний
    таблица = []
    for вид in ("по_посту", "контроль_случайный"):
        for м_ин in ВЫХОДЫ_МИН:
            v = [с[f"итог_{м_ин}"] for с in сделки
                 if с["вид"] == вид and с.get(f"итог_{м_ин}") is not None]
            if not v:
                таблица.append({"вид": вид, "выход_мин": м_ин, "n": 0})
                continue
            по_суткам: dict = collections.defaultdict(float)
            for с in сделки:
                if с["вид"] == вид and с.get(f"итог_{м_ин}") is not None:
                    по_суткам[с["сутки"]] += с[f"итог_{м_ин}"]
            срез = sorted(v)
            убр = max(1, math.ceil(0.05 * len(срез)))
            усеч = срез[:-убр] if len(срез) > убр else срез
            плюс_сут = sum(1 for x in по_суткам.values() if x > 0)
            таблица.append({
                "вид": вид, "выход_мин": м_ин, "n": len(v),
                "среднее_sol": round(st.fmean(v), 5),
                "медиана_sol": round(st.median(v), 5),
                "сумма_sol": round(sum(v), 4),
                "усечённое_без_верхних5_sol": round(st.fmean(усеч), 5),
                "в_плюсе": sum(1 for x in v if x > 0),
                "доля_в_плюсе": round(sum(1 for x in v if x > 0) / len(v), 4),
                "суток": len(по_суткам), "суток_в_плюсе": плюс_сут,
                "p_знаковый_по_суткам": round(знаковый(плюс_сут, len(по_суткам)), 4),
                "прошло_по_стандарту": bool(
                    len(v) >= 100 and st.fmean(v) > 0 and st.fmean(усеч) > 0
                    and плюс_сут / max(1, len(по_суткам)) >= 0.6
                    and знаковый(плюс_сут, len(по_суткам)) < порог_p),
            })

    тело = {
        "что": "бэктест входа по первому посту в X против случайного входа",
        "когда": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
        "правило": {"билет_sol": БИЛЕТ, "потолок_доля_резерва": ДОЛЯ_РЕЗЕРВА,
                    "издержки_sol": ИЗДЕРЖКИ, "задержка_входа_с": ЗАДЕРЖКА_ВХОДА_С,
                    "выходы_мин": list(ВЫХОДЫ_МИН), "цена": "S0_дно -- состояние пула "
                    "на момент входа, последнее событие не позже метки",
                    "сочетаний": сочетаний, "порог_p": порог_p, "зерно": а.semya},
        "сбор_x": {"адресов_пройдено": пройдено, "стоимость_usd": round(стоимость, 4),
                   "с_постом": пункт1["с_постом"]},
        "пункт1": {
            "токенов": пункт1["токенов"], "с_постом": пункт1["с_постом"],
            "покрытие": (round(пункт1["с_постом"] / пункт1["токенов"], 4)
                         if пункт1["токенов"] else None),
            "пик_известен": пункт1["пик_известен"],
            "раньше_пика": пункт1["раньше_пика"],
            "доля_раньше_пика": (round(пункт1["раньше_пика"] / пункт1["пик_известен"], 4)
                                 if пункт1["пик_известен"] else None),
            "доля_раньше_пика_от_всех": (round(пункт1["раньше_пика"] / пункт1["токенов"], 4)
                                         if пункт1["токенов"] else None),
            "первая_сделка_известна": пункт1["первая_сделка_известна"],
            "раньше_первой_сделки": пункт1["раньше_первой_сделки"],
            "задержка_пост_минус_создание_с": {
                "n": len(пункт1["задержки_с"]),
                "медиана": (round(st.median(пункт1["задержки_с"]), 1)
                            if пункт1["задержки_с"] else None),
                "минимум": (round(min(пункт1["задержки_с"]), 1)
                            if пункт1["задержки_с"] else None)},
        },
        "счёт": dict(счёт), "таблица": таблица, "сделок": len(сделки),
        "оговорки": [
            "окно поиска X -- от создания до +15 минут: упоминания позже в счёт не идут, "
            "значит покрытие и доля «раньше пика» -- нижние границы",
            "удалённые посты и неполнота поиска X смещают выборку к выжившим",
            "цена входа -- последнее событие архива не позже метки входа; своё "
            "проскальзывание учтено инвариантом x*y на билет",
        ],
        "сделки": сделки,
    }
    ф = П / f"x_bektest{а.metka}.json"
    ф.write_text(json.dumps(тело, ensure_ascii=False, indent=1), encoding="utf-8")
    п1 = тело["пункт1"]
    print(f"пункт 1: токенов {п1['токенов']}, с постом {п1['с_постом']} "
          f"(покрытие {п1['покрытие']}), раньше пика {п1['раньше_пика']} из "
          f"{п1['пик_известен']} (доля {п1['доля_раньше_пика']})", flush=True)
    print("%-20s %6s %5s %11s %11s %13s %9s %8s %s" % (
        "вид", "выход", "n", "среднее", "медиана", "усечённое", "в плюсе", "сут+",
        "стандарт"), flush=True)
    for с in таблица:
        if not с.get("n"):
            print("%-20s %6s %5d" % (с["вид"], с["выход_мин"], 0), flush=True)
            continue
        print("%-20s %6s %5d %+11.5f %+11.5f %+13.5f %9s %4d/%-3d %s" % (
            с["вид"], с["выход_мин"], с["n"], с["среднее_sol"], с["медиана_sol"],
            с["усечённое_без_верхних5_sol"], с["доля_в_плюсе"], с["суток_в_плюсе"],
            с["суток"], "да" if с["прошло_по_стандарту"] else "нет"), flush=True)
    print(f"записано {ф}", flush=True)
    try:
        import sys  # noqa: PLC0415
        sys.path.insert(0, str(Path(__file__).resolve().parent))
        import podbivka_run as R  # noqa: PLC0415
        R.записано(ф)
    except Exception:  # noqa: BLE001, S110
        pass
    return 0


def main() -> int:
    р = argparse.ArgumentParser()
    р.add_argument("--vyborka", default=str(П / "x_vyborka_top300.json"))
    р.add_argument("--maska", default="_top300", help="маска файлов упоминаний")
    р.add_argument("--semya", type=int, default=20261018)
    р.add_argument("--metka", default="_top300")
    return главное(р.parse_args())


if __name__ == "__main__":
    raise SystemExit(main())
