# СЛОВО CODE-2 (docs/podbivka_{clmm,whirlpool}_kak_vstroit.md, 30.09): «переходы
# через тики проверены на 2 свопах; на переходе строитель ОТКАЗЫВАЕТ или
# берёт широкий пол min_out. Признак перехода в ответе модуля:
# q["тиков_пересечено"] > 0». Здесь это правило и стоит.
#
# ПО УМОЛЧАНИЮ -- ОТКАЗ. Широкий пол -- это осознанная трата: он пропускает
# сделку по цене, которую перенос на переходе пока не подтвердил. Поэтому режим
# включается флагом, И ЗАПАС ОБЯЗАН БЫТЬ НАЗВАН ЧИСЛОМ: своего числа здесь нет и
# выдумывать его нельзя -- без него режим сам отказывает.
РЕЖИМ_ПЕРЕХОДА = "BLOOM_CLMM_PEREHOD"
ЗАПАС_ПЕРЕХОДА = "BLOOM_CLMM_PEREHOD_ZAPAS"
ПЕРЕХОД_ОТКАЗ = "otkaz"
ПЕРЕХОД_ШИРОКИЙ_ПОЛ = "shirokij_pol"


def режим_перехода() -> str:
    зн = (os.environ.get(РЕЖИМ_ПЕРЕХОДА) or "").strip().lower()
    return зн if зн in (ПЕРЕХОД_ОТКАЗ, ПЕРЕХОД_ШИРОКИЙ_ПОЛ) else ПЕРЕХОД_ОТКАЗ


def запас_перехода():
    """Доля, на которую ДОПОЛНИТЕЛЬНО опускается пол min_out на переходе.

    None -- не названа. Пустая строка, ноль, отрицательное и >= 1 -- тоже не
    названа: пол, опущенный «на ноль», это обычный пол под непроверенной ценой.
    """
    зн = (os.environ.get(ЗАПАС_ПЕРЕХОДА) or "").strip()
    if not зн:
        return None
    try:
        д = float(зн)
    except ValueError:
        return None
    return д if 0.0 < д < 1.0 else None


def правило_перехода(тиков_пересечено, массивов_пройдено=None) -> dict:
    """Решение на переходе: отказать, расширить пол или ничего не менять.

    массивов_пройдено -- второй признак у CLMM (len(q["массивов"]) > 1): своп
    ушёл за границу массива, даже если инициализированных тиков не встретил.
    """
    больше_массива = bool(массивов_пройдено) and len(массивов_пройдено) > 1
    переход = bool((тиков_пересечено or 0) > 0) or больше_массива
    из_ = {"переход": переход, "тиков_пересечено": тиков_пересечено,
            "массивов_пройдено": (len(массивов_пройдено) if массивов_пройдено else None),
            "режим": режим_перехода(), "запас": None, "ok": True, "why_not": None}
    if not переход:
        return из_
    if из_["режим"] == ПЕРЕХОД_ОТКАЗ:
        из_.update(ok=False,
                    why_not=(f"своп переходит через тик (пересечено "
                              f"{тиков_пересечено}, массивов "
                              f"{из_['массивов_пройдено']}), а на переходе цена "
                              f"переносом пока не подтверждена -- отказ "
                              f"(режим {РЕЖИМ_ПЕРЕХОДА})"))
        return из_
    з = запас_перехода()
    if з is None:
        из_.update(ok=False,
                    why_not=(f"режим широкого пола включён, а запас не назван числом "
                              f"в {ЗАПАС_ПЕРЕХОДА} (нужна доля 0 < x < 1) -- своего "
                              f"числа здесь нет"))
        return из_
    из_["запас"] = з
    return из_


# ------------------------------------------------- налог перевода Token-2022

TOKEN_2022 = "TokenzQdBNbLqP5VEhdkAS6EPFLC1PHnBqCXEpPxuEb"
BASIS_POINT_MAX = 10_000
# Признак отказа «налог стороны не назван» -- ОДНОЙ строкой, потому что по ней
# отличает свой случай и проверка без денег, и (при встраивании) полоса. Строка,
# переписанная в одном месте из двух, молча ломает и то, и другое.
ПРИЗНАК_НАЛОГ_НЕ_НАЗВАН = "налог перевода не назван"


def без_налога(сумма: int, bps: int | None, максимум: int | None) -> int:
    """Сколько РЕАЛЬНО дойдёт до счёта при налоге перевода Token-2022.

    Округление то же, что в расширении TransferFee (вверх) и то же, что в
    переносе Code-2 (podbivka_dlmm_quote.налог_2022): fee = ceil(сумма*bps/10000),
    не больше максимума.
    """
    if not bps:
        return int(сумма)
    сбор = (int(сумма) * int(bps) + BASIS_POINT_MAX - 1) // BASIS_POINT_MAX
    if максимум is not None:
        сбор = min(сбор, int(максимум))
    return int(сумма) - сбор


def налог_назван(налог) -> bool:
    """Назван ли налог ЧИСЛОМ, а не «не знаю».

    ПОЧЕМУ НЕ ПРОСТО `налог is not None`. Полоса при промахе кеша отдаёт
    {"fee_bps": None} -- это её честное «не знаю» (bloom_detector.
    налог_минта_из_кеша). Естественная сборка пары даёт (None, None), а такой
    кортеж ИСТИНЕН: проверка «налог is None» его пропускала, вычет не делался, и
    в ответ уходило налог_выхода_учтён=True. То есть защита от молчаливого нуля
    сама молча возвращала ноль. Поэтому ставка обязана быть целым числом >= 0.
    """
    if not isinstance(налог, (tuple, list)) or not налог:
        return False
    bps = налог[0]
    if isinstance(bps, bool) or not isinstance(bps, int) or bps < 0:
        return False
    максимум = налог[1] if len(налог) > 1 else None
    if максимум is not None and (isinstance(максимум, bool)
                                  or not isinstance(максимум, int) or максимум < 0):
        return False
    return True


def _налог_сторон(налог_выхода, налог_входа, программа_выхода, программа_входа) -> dict:
    """Проверка, что налог сторон ИЗВЕСТЕН там, где он может быть.

    Налог живёт в расширении минта, а на горячем пути сетевых запросов нет: его
    читает и кэширует полоса (bloom_detector.налог_минта / налоги_минтов) и
    передаёт сюда парой (bps, максимум). Сторона на Token-2022 без НАЗВАННОГО
    ЧИСЛОМ налога -- ОТКАЗ, а не ноль: программа сравнивает порог с суммой ПОСЛЕ
    налога, и молчаливый ноль означал бы завышенный минимум и откат каждой покупки.
    Ставка 0 -- это ответ («минт без налога»), а None -- «не знаю», и это отказ.
    """
    для = {"выход": (налог_выхода, программа_выхода), "вход": (налог_входа, программа_входа)}
    for имя, (налог, программа) in для.items():
        if программа == TOKEN_2022 and not налог_назван(налог):
            return {"ok": False,
                    "why_not": (f"минт стороны {имя} на Token-2022, а "
                                 f"{ПРИЗНАК_НАЛОГ_НЕ_НАЗВАН} числом ({налог!r}) -- порог "
                                 "сравнивается с суммой ПОСЛЕ налога, и минимум вышел бы "
                                 "завышенным")}
    return {"ok": True}


def _счета(rpc_call, адреса: list, *, таймаут: float = 3.0) -> dict:
    """getMultipleAccounts одним запросом: адрес -> сырые байты (или None)."""
    из_ = {"ok": False, "данные": {}, "why_not": None, "slot": None, "мс": None}
    т0 = time.perf_counter()
    try:
        о = rpc_call("getMultipleAccounts",
                      [адреса, {"encoding": "base64", "commitment": "confirmed"}])
    except Exception as exc:  # noqa: BLE001
        из_["why_not"] = f"{type(exc).__name__}: {str(exc)[:120]}"
        из_["мс"] = round((time.perf_counter() - т0) * 1000.0, 2)
        return из_
    из_["мс"] = round((time.perf_counter() - т0) * 1000.0, 2)
    о = о if isinstance(о, dict) else {}
    рез = о.get("result") if "result" in о else о
    if not isinstance(рез, dict):
        из_["why_not"] = f"ответ узла не разобран: {str(о)[:120]}"
        return из_
    из_["slot"] = ((рез.get("context") or {}).get("slot")
                    if isinstance(рез.get("context"), dict) else None)
    значения = рез.get("value")
    if not isinstance(значения, list) or len(значения) != len(адреса):
        из_["why_not"] = "узел вернул не столько счетов, сколько спрашивали"
        return из_
    import base64  # noqa: PLC0415

    for адрес, зн in zip(адреса, значения):
        if not зн:
            из_["данные"][адрес] = None
            continue
        д = (зн.get("data") or [None, None])[0]
        try:
            из_["данные"][адрес] = base64.b64decode(д) if д else None
        except Exception:  # noqa: BLE001
            из_["данные"][адрес] = None
    из_["ok"] = True
    return из_


def котировка(*, пул: str, минт_базы: str, минт_котировки: str, лампорты: int,
               проскальзывание: float, rpc_call, сейчас: float | None = None,
               запас_массивов: int = ЗАПАС_МАССИВОВ,
               налог_выхода=None, налог_входа=None,
               программа_выхода: str | None = None,
               программа_входа: str | None = None) -> dict:
    """Минимум выхода по CLMM из ЖИВОГО состояния пула, конфига и массивов тиков.

    Возвращает тот же вид, что min_out_from_reserves: {ok, expected_out,
    min_out, ...} плюс адреса и старты массивов (их требует сборка) и цену чтений.

    Чтений два: [пул, расширение] и [пул, amm_config, массивы]. Второй запрос
    перечитывает пул ВМЕСТЕ с массивами -- чтобы состояние было из одного слота.
    Не хватило массива -- честный отказ («нет tick array N»), а не догадка.
    """
    из_ = {"ok": False, "why_not": None, "чтений": 0, "путь": "точная котировка CLMM"}
    if лампорты <= 0:
        из_["why_not"] = "сумма входа не положительна"
        return из_
    # НАЛОГ СТОРОН -- ДО ЛЮБЫХ ЧТЕНИЙ. Сторона на Token-2022 без переданного
    # налога перевода -- отказ; чтений за него не платим.
    н = _налог_сторон(налог_выхода, налог_входа, программа_выхода, программа_входа)
    if not н["ok"]:
        из_["why_not"] = н["why_not"]
        return из_
    try:
        Q = _порт()
    except Exception as exc:  # noqa: BLE001
        из_["why_not"] = f"перенос кода CLMM не загружен: {type(exc).__name__}"
        return из_

    адр_ext = Q.адрес_расширения(пул)
    ч1 = _счета(rpc_call, [пул, адр_ext])
    из_["чтений"] += 1
    из_["мс_чтение1"] = ч1.get("мс")
    if not ч1["ok"]:
        из_["why_not"] = f"пул не прочитан: {ч1['why_not']}"
        return из_
    данные_пула = ч1["данные"].get(пул)
    if not данные_пула:
        из_["why_not"] = "счёта пула нет на цепи"
        return из_
    try:
        pool = Q.разобрать_пул(данные_пула)
    except Exception as exc:  # noqa: BLE001
        из_["why_not"] = f"пул не разобрался: {type(exc).__name__}: {str(exc)[:120]}"
        return из_
    ext = None
    данные_ext = ч1["данные"].get(адр_ext)
    if данные_ext:
        try:
            ext = Q.разобрать_расширение(данные_ext)
        except Exception:  # noqa: BLE001
            ext = None

    # КУДА ИДЁТ СВОП. Платим котировкой и получаем базу: zero_for_one значит
    # «отдаём токен 0, получаем токен 1».
    if pool.get("token_mint_0") == минт_котировки:
        zero_for_one = True
    elif pool.get("token_mint_1") == минт_котировки:
        zero_for_one = False
    else:
        из_["why_not"] = ("минт котировки не совпал ни с одной стороной пула: "
                           f"{минт_котировки[:8]} против "
                           f"{str(pool.get('token_mint_0'))[:8]}/"
                           f"{str(pool.get('token_mint_1'))[:8]}")
        return из_
    ожидаемый_выход = (pool.get("token_mint_1") if zero_for_one
                       else pool.get("token_mint_0"))
    if минт_базы and ожидаемый_выход != минт_базы:
        из_["why_not"] = (f"сторона выхода пула {str(ожидаемый_выход)[:8]} не тот "
                           f"минт, который покупаем ({минт_базы[:8]})")
        return из_
    из_.update(zero_for_one=zero_for_one, tick_spacing=pool.get("tick_spacing"),
                tick_current=pool.get("tick_current"), amm_config=pool.get("amm_config"),
                расширение=адр_ext, расширение_есть=bool(данные_ext))

    try:
        старты = Q.нужные_массивы(pool, ext, zero_for_one, int(запас_массивов))
    except Exception as exc:  # noqa: BLE001
        из_["why_not"] = f"массивы тиков не выбрались: {type(exc).__name__}: {str(exc)[:120]}"
        return из_
    if not старты:
        из_["why_not"] = "в пуле не нашлось ни одного массива тиков"
        return из_
    адреса = [Q.адрес_массива(пул, с) for с in старты]
    # АДРЕСА МАССИВОВ ОТДАЮТСЯ НАРУЖУ: их требует сборка покупки -- массивы
    # тиков идут в хвост счетов инструкции, и брать их из чужой старой сделки
    # нельзя.
    из_["массивы_адреса"] = list(адреса)
    из_["массивы_старты"] = list(старты)
    конфиг_адрес = pool.get("amm_config")
    ч2 = _счета(rpc_call, [пул, конфиг_адрес] + адреса)
    из_["чтений"] += 1
    из_["мс_чтение2"] = ч2.get("мс")
    из_["мс_чтений_всего"] = round(float(из_.get("мс_чтение1") or 0.0)
                                    + float(ч2.get("мс") or 0.0), 2)
    if not ч2["ok"]:
        из_["why_not"] = f"массивы тиков не прочитаны: {ч2['why_not']}"
        return из_
    свежий = ч2["данные"].get(пул)
    if свежий:
        try:
            pool = Q.разобрать_пул(свежий)
        except Exception:  # noqa: BLE001
            pass
    данные_конфига = ч2["данные"].get(конфиг_адрес)
    if not данные_конфига:
        из_["why_not"] = f"счёта amm_config {конфиг_адрес} нет на цепи -- ставка комиссии неизвестна"
        return из_
    try:
        cfg = Q.разобрать_конфиг(данные_конфига)
    except Exception as exc:  # noqa: BLE001
        из_["why_not"] = f"amm_config не разобрался: {type(exc).__name__}"
        return из_
    # ШАГ ТИКА У ПУЛА И У КОНФИГА ОБЯЗАНЫ СОЙТИСЬ. Не сошлись -- прочитан не тот
    # конфиг, и ставка комиссии тоже не та; считать нечем.
    if cfg.get("tick_spacing") and pool.get("tick_spacing") \
            and int(cfg["tick_spacing"]) != int(pool["tick_spacing"]):
        из_["why_not"] = (f"шаг тика у пула {pool['tick_spacing']} и у конфига "
                           f"{cfg['tick_spacing']} разные -- конфиг не от этого пула")
        return из_
    из_["ставка_1e6"] = cfg.get("trade_fee_rate")
    массивы = {}
    не_прочитаны = []
    for с, адрес in zip(старты, адреса):
        д = ч2["данные"].get(адрес)
        if not д:
            не_прочитаны.append(с)
            continue
        try:
            arr = Q.разобрать_массив(д)
        except Exception:  # noqa: BLE001
            не_прочитаны.append(с)
            continue
        массивы[arr["start_tick_index"]] = arr
    из_["массивов"] = len(массивы)
    из_["массивы_не_прочитаны"] = не_прочитаны
    if not массивы:
        из_["why_not"] = f"ни один массив тиков не прочитан: {не_прочитаны}"
        return из_

    ts = int(сейчас if сейчас is not None else time.time())
    try:
        q = Q.котировка_точный_вход(pool, cfg, массивы, ext, int(лампорты),
                                     zero_for_one, ts)
    except Exception as exc:  # noqa: BLE001
        из_["why_not"] = f"котировка не посчиталась: {type(exc).__name__}: {str(exc)[:160]}"
        return из_
    ожидаем = int(q.get("amount_out") or 0)
    if ожидаем <= 0:
        из_["why_not"] = "котировка дала ноль на выходе"
        return из_
    остаток = int(q.get("остаток_входа") or 0)
    if остаток:
        # ВЕСЬ ВХОД ОБЯЗАН УЙТИ В ПУЛ, И ЭТО ТРЕБОВАНИЕ САМОЙ ПРОГРАММЫ, а не наша
        # осторожность: при sqrt_price_limit_x64 == 0 она проверяет
        # require_eq!(amount_specified, transfer_amount) -- «Doesn't allow partial
        # filled without specified limit_price» (instructions/swap_v2.rs, ed1eb41).
        # Значит такая покупка откатилась бы, сжёгши комиссию и приоритет.
        из_["why_not"] = (f"ликвидности хватило не на весь вход: остаток "
                           f"{остаток} из {int(лампорты)}")
        из_["остаток_входа"] = остаток
        return из_
    # ПЕРЕХОД ЧЕРЕЗ ТИК -- РЕШЕНИЕ ДО МИНИМУМА. Перенос Code-2 на переходах
    # подтверждён двумя свопами, поэтому по умолчанию тут отказ; широкий пол --
    # только флагом и только с названным запасом.
    пер = правило_перехода(q.get("тиков_пересечено"), q.get("массивов"))
    из_["переход"] = пер
    if not пер["ok"]:
        из_["why_not"] = пер["why_not"]
        return из_

    # НАЛОГ ПЕРЕВОДА НА МИНТЕ ВЫХОДА. Программа сравнивает other_amount_threshold
    # с тем, что РЕАЛЬНО пришло на наш счёт (swap_v2.rs: amount_result считается
    # как прирост output_token_account, дальше require_gte!(amount_result,
    # other_amount_threshold, TooLittleOutputReceived)), а порт отдаёт сырые
    # единицы пула. По живому сбору налог не ноль у 44 событий свопа CLMM из 637,
    # и у 7 из 12 пулов против SOL сторона базы -- Token-2022: без этого вычета
    # минимум был бы завышен, а сделка откатывалась бы на каждой попытке.
    сырой_выход = ожидаем
    if налог_назван(налог_выхода):
        ожидаем = без_налога(ожидаем, налог_выхода[0],
                              налог_выхода[1] if len(налог_выхода) > 1 else None)
        if ожидаем <= 0:
            из_["why_not"] = (f"налог перевода минта выхода съедает весь выход "
                               f"({сырой_выход} -> {ожидаем})")
            return из_
    доля = 1.0 - float(проскальзывание)
    if пер.get("запас"):
        # ШИРОКИЙ ПОЛ: пол опускается ДОПОЛНИТЕЛЬНО на названный запас. Число --
        # из окружения, своего здесь нет.
        доля *= (1.0 - float(пер["запас"]))
        из_["пол_расширен"] = float(пер["запас"])
    мин = int(ожидаем * доля)
    if мин <= 0:
        из_["why_not"] = "минимум выхода не положителен при этом проскальзывании"
        return из_
    комиссия = int(q.get("fee") or 0)
    из_.update(ok=True, expected_out=ожидаем, min_out=мин, fee=комиссия,
                выход_до_налога=сырой_выход,
                налог_выхода_учтён=налог_назван(налог_выхода), точная=True,
                protocol_fee=q.get("protocol_fee"), fund_fee=q.get("fund_fee"),
                fee_share=(комиссия / float(лампорты) if лампорты else None),
                тиков_пересечено=q.get("тиков_пересечено"),
                массивов_пройдено=q.get("массивов"),
                лимитных_ордеров=q.get("лимитных_ордеров"),
                динамическая=q.get("динамическая"), slot=ч2.get("slot"))
    return из_


