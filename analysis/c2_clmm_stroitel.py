def _данные_инструкции(ix: dict, B) -> bytes:
    сырые = ix.get("data")
    if not сырые:
        return b""
    try:
        return B.b58decode(сырые)
    except Exception:  # noqa: BLE001
        return b""


def вид_по_данным(данные: bytes, B) -> str | None:
    """Имя инструкции по дискриминатору Anchor. Незнакомый -- None."""
    if len(данные) < 8:
        return None
    for имя in ("swap_v2", "swap"):
        if данные[:8] == B.disc(имя):
            return имя
    return None


def шаблон(tx: dict, пул: str | None = None) -> dict:
    """Шаблон инструкции CLMM из транзакции источника.

    Берётся ИНСТРУКЦИЯ КАК ЕСТЬ: счета в её порядке, данные целиком. Вид
    определяется дискриминатором, а не числом счетов: у swap и swap_v2 хвост
    начинается на разных местах, и ошибка на единицу подставила бы массив
    тиков на место служебного счёта.

    пул задан -- берём инструкцию именно по нему (роутер трогает по нескольку
    пулов); пул не задан -- берём первую инструкцию свопа и читаем пул с места 2.
    """
    из_ = {"ok": False, "why_not": None}
    B = _кирпичи()
    for ix in B.all_instructions(tx):
        if ix.get("programId") != ПРОГРАММА:
            continue
        счета = list(ix.get("accounts") or [])
        данные = _данные_инструкции(ix, B)
        вид = вид_по_данным(данные, B)
        if вид is None:
            continue
        р = РАСКЛАДКИ[вид]
        if len(счета) <= р["фикс"]:
            из_["why_not"] = (f"{вид}: счетов {len(счета)}, а фиксированных по "
                               f"раскладке {р['фикс']} плюс хвост")
            continue
        мой_пул = счета[р["пул"]]
        if пул and мой_пул != пул:
            continue
        if len(данные) != ДЛИНА_ДАННЫХ:
            из_["why_not"] = (f"{вид}: данных {len(данные)} байт, по живым сделкам "
                               f"их {ДЛИНА_ДАННЫХ}")
            continue
        arg0, arg1 = struct.unpack_from("<QQ", данные, 8)
        return {"ok": True, "program": ПРОГРАММА, "вид": вид, "ix": вид,
                "accounts": счета, "data": данные, "arg0": arg0, "arg1": arg1,
                "writable": B.writable_map(tx), "пул": мой_пул,
                "остаток_с": р["остаток_с"],
                "хвост_источника": данные[24:],
                "точный_вход": данные[24:] == ХВОСТ_ТОЧНЫЙ_ВХОД}
    из_["why_not"] = из_["why_not"] or (
        f"инструкции swap/swap_v2 CLMM {'по пулу ' + пул if пул else ''} в транзакции нет")
    return из_


def минты_и_хранилища(tpl: dict, tx: dict) -> dict:
    """Минты и хранилища ПО НАПРАВЛЕНИЮ САМОЙ СДЕЛКИ источника.

    У swap_v2 минты стоят в инструкции (11 и 12). У swap (v1) их там нет вовсе,
    поэтому минты берутся из балансов транзакции по хранилищам пула -- это
    факт цепи, а не догадка. Программа токена у каждой стороны -- та, что
    стоит в балансах (Token-2022 отличается от SPL).
    """
    из_ = {"ok": False, "why_not": None}
    import c2_common as C  # noqa: PLC0415

    р = РАСКЛАДКИ[tpl["вид"]]
    счета = tpl["accounts"]
    хр_вх, хр_вых = счета[р["хранилище_входа"]], счета[р["хранилище_выхода"]]
    строки = {с["account"]: с for с in C.token_rows(tx).values()}
    св, сх = строки.get(хр_вх), строки.get(хр_вых)
    if not св or not сх:
        из_["why_not"] = "хранилищ пула нет в балансах транзакции"
        return из_
    программы = {}
    for когда in ("preTokenBalances", "postTokenBalances"):
        for б in ((tx.get("meta") or {}).get(когда) or []):
            if isinstance(б, dict) and б.get("mint"):
                программы.setdefault(б["mint"], б.get("programId"))
    минт_вх = счета[р["минт_входа"]] if р["минт_входа"] is not None else св.get("mint")
    минт_вых = счета[р["минт_выхода"]] if р["минт_выхода"] is not None else сх.get("mint")
    if not минт_вх or not минт_вых:
        из_["why_not"] = "минты сторон пула не восстановились"
        return из_
    return {"ok": True, "минт_входа": минт_вх, "минт_выхода": минт_вых,
            "хранилище_входа": хр_вх, "хранилище_выхода": хр_вых,
            "программа_входа": программы.get(минт_вх) or SPL_ТОКЕН,
            "программа_выхода": программы.get(минт_вых) or SPL_ТОКЕН,
            "вход_источника": св["post"] - св["pre"],
            "выход_источника": сх["pre"] - сх["post"]}


def развернуть(tpl: dict, мх: dict) -> dict:
    """Шаблон в сторону ПОКУПКИ: вход -- котировка, выход -- база.

    Сделка источника бывает продажей; тогда стороны в инструкции стоят
    наоборот. Переставляются РОВНО те места, что зависят от направления:
    счета пользователя вход/выход (3 и 4), хранилища (5 и 6) и -- у swap_v2 --
    минты хранилищ (11 и 12). Остальное у пула постоянно (по замеру Code-2:
    amm_config и observation не менялись ни в одной из 75 групп «пул +
    направление»).
    """
    р = РАСКЛАДКИ[tpl["вид"]]
    счета = list(tpl["accounts"])
    пары = [(р["счёт_входа"], р["счёт_выхода"]),
            (р["хранилище_входа"], р["хранилище_выхода"])]
    if р["минт_входа"] is not None:
        пары.append((р["минт_входа"], р["минт_выхода"]))
    for и, ж in пары:
        счета[и], счета[ж] = счета[ж], счета[и]
    новые_мх = dict(мх)
    новые_мх.update(минт_входа=мх["минт_выхода"], минт_выхода=мх["минт_входа"],
                    хранилище_входа=мх["хранилище_выхода"],
                    хранилище_выхода=мх["хранилище_входа"],
                    программа_входа=мх["программа_выхода"],
                    программа_выхода=мх["программа_входа"])
    return {"шаблон": dict(tpl, accounts=счета, развёрнут=True), "мх": новые_мх}


