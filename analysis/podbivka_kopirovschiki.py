#!/usr/bin/env python3
"""Копировщики, не маркетмейкеры: верхние 50 и их ведущие через то же сито на свежем окне. Офлайн.

Слово владельца 02.10:
  * из 10 485 кошельков сита (неделя 21–28.09, analysis/podbivka_snaipery_dengi.py) взять «за ведущим ≥ 0.3 и
    удержание ≤ 50 слотов» -- это отделяет копировщиков от маркетмейкеров, которые держат часами;
  * верхние 50 по итогу после приоритета -- таблица;
  * их ведущих, которых нет в нашем реестре, прогнать через то же сито на свежем окне (24.09 – 01.10, 8 суток,
    фаза 2 с метной «vedushie») и дать таблицу по тому же правилу: ≥ 50 покупок за окно и медианный билет ≥ 1 SOL-экв.
  * где в этом ряду 54ua.
Вход: data/podbivka/snaipery/dengi_svod.json (неделя), dengi_f2_vedushie_*.json.gz (свежее окно),
data/podbivka/arhiv_adresa.json. Выход: docs/podbivka_2026-10-02_kopirovschiki.md.
Чаевых и комиссии сети в архиве нет -- итог после приоритета (поле priorityFee), как и на странице снайперов.
"""
from __future__ import annotations

import glob
import json
import statistics
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import podbivka_snaipery_dengi as D  # noqa: E402

КОРЕНЬ = D.КОРЕНЬ
П = D.П
ЗА_ВЕДУЩИМ, УДЕРЖАНИЕ = 0.3, 50
ВЕРХ = 50
КТО = {"54uaRuJEc9BHY7uVMXtcf9JWcYDtB75hUeFJWeCxEkBE": "54ua",
       "BomGAZnAGwnjs3oaqNHm4Wk5sKctQi83PKVxjRuGGbrm": "BomG"}


def строка(a: str, v: dict, имя: str | None = None) -> str:
    вед = ", ".join(f"`{k[:8]}` {n}" for k, n in (v.get("ведущие") or {}).items()) or "—"
    уд = v.get("удержание_слотов_медиана")
    return (f"| `{a}`{' (' + имя + ')' if имя else ''} | {v['оборот_sol']} | {v['итог_после_prio_sol']} | "
            f"{v.get('покупок_сито') if v.get('покупок_сито') is not None else v.get('покупок_окна')} | "
            f"{v.get('билет_медиана')} | {уд if уд is not None else '—'} | "
            f"{v.get('за_ведущим') if v.get('за_ведущим') is not None else '—'} | {вед} |")


def main() -> int:
    import podbivka_run as R  # noqa: PLC0415
    св = json.loads((П / "dengi_svod.json").read_text(encoding="utf-8"))
    ряды = св["ряды"]
    адр = set(json.loads((КОРЕНЬ / "data" / "podbivka" / "arhiv_adresa.json").read_text(encoding="utf-8"))["адреса"])
    коп = [a for a, v in ряды.items()
           if (v.get("за_ведущим") or 0) >= ЗА_ВЕДУЩИМ and v.get("удержание_слотов_медиана") is not None
           and v["удержание_слотов_медиана"] <= УДЕРЖАНИЕ]
    по_итогу = sorted(коп, key=lambda a: -ряды[a]["итог_после_prio_sol"])
    верх = по_итогу[:ВЕРХ]
    вед_все = sorted({b for a in верх for b in (ряды[a]["ведущие"] or {})})
    вед_новые = [b for b in вед_все if b not in адр]

    # свежее окно по ведущим
    файлы = sorted(glob.glob(str(П / "dengi_f2_vedushie_*.json.gz")))
    ряды_в, дни_в = {}, []
    if файлы:
        пары, ведущие, покупки, дни_в = D.собрать_f2(файлы)
        ряды_в = D.ряды_по_парам(пары, ведущие, покупки, {"кошельки": {}})
        for w, v in ряды_в.items():
            сп = покупки.get(w) or []
            билеты = [q for _, q, _ in сп if q]
            v["покупок_окна"] = len(сп)
            v["билет_медиана"] = round(statistics.median(билеты), 4) if билеты else None
    годные = [w for w, v in ряды_в.items()
              if (v.get("покупок_окна") or 0) >= D.МИН_ПОКУПОК and (v.get("билет_медиана") or 0) >= D.МИН_БИЛЕТ]
    годные.sort(key=lambda w: -ряды_в[w]["итог_после_prio_sol"])

    загол = ("| адрес | оборот, SOL | итог после приоритета, SOL | покупок | билет, SOL | удержание, слотов | "
             "за ведущим | ведущие (раз за окно) |")
    линия = "|---|---|---|---|---|---|---|---|"
    md = ["# Подбивка: копировщики, не маркетмейкеры -- верхние 50 и их ведущие", "",
          f"Из {len(ряды)} кошельков сита (неделя 21.09 00Z – 28.09 00Z, "
          "`docs/podbivka_2026-10-02_snaipery_po_dengam.md`) отобраны те, у кого **доля покупок за ведущим "
          f"≥ {ЗА_ВЕДУЩИМ}** и **медианное удержание ≤ {УДЕРЖАНИЕ} слотов** -- это и отделяет копировщиков от "
          f"маркетмейкеров, которые держат часами. Таких **{len(коп)}**; ниже верхние {ВЕРХ} по итогу после "
          "приоритета. «Ведущий» -- кошелёк, покупавший тот же пул за ≤ 3 слота до него и сделавший это ≥ 5 раз "
          "за окно. Чаевых и комиссии сети в архиве нет -- итог после приоритета (`priorityFee`). "
          "Ничего не рекомендуется.", "",
          "**Оговорка к столбцу «ведущие»: мера несимметрична только на вид.** Среди пар «верхний 50 -- его "
          "ведущий» ВЗАИМНЫХ (A зовёт B ведущим, и B зовёт A) -- " + "{ВЗАИМНЫХ}" + ". Пример: `64hP97Bw` "
          "считает `SQHK48QT` ведущим 1753 раза, а `SQHK48QT` его же -- 1365 раз; `Ar2Y6o1Q` и `kEFiAX3j` -- "
          "665 против 661. Это значит, что оба постоянно сидят в одних пулах в пределах трёх слотов, и признак "
          "«за ведущим» у таких кошельков говорит о совместной толпе, а не о том, кто кого копирует. Для "
          "односторонних пар (как у 54ua: 9 ведущих, обратных ссылок нет) признак читается прямо.", "",
          "## A. Верхние 50 копировщиков (неделя 21–28.09)", "", загол, линия]
    вз = 0
    for a in верх:
        for b in (ряды[a]["ведущие"] or {}):
            обратно = (ряды_в.get(b) or {}).get("ведущие") or (ряды.get(b) or {}).get("ведущие") or {}
            вз += 1 if a in обратно else 0
    md = [x.replace("{ВЗАИМНЫХ}", str(вз)) for x in md]
    md += [строка(a, ряды[a], КТО.get(a)) for a in верх]

    md += ["", "## Б. Их ведущие, которых нет в нашем реестре, через то же сито на свежем окне", "",
           f"У верхних {ВЕРХ} ведущих всего {len(вед_все)}; нет в `data/podbivka/arhiv_adresa.json` -- "
           f"**{len(вед_новые)}**. По ним прогнана фаза 2 сита на окне **24.09 – 01.10** (8 суток, "
           f"{len(файлы)} файлов, строк {sum(d['строк'] for d in дни_в)}, ошибок чтения "
           f"{sum(len(d['ошибки']) for d in дни_в)}). Правило сита то же: **≥ {D.МИН_ПОКУПОК} покупок за окно и "
           f"медианный билет ≥ {D.МИН_БИЛЕТ:g} SOL-экв.** Его проходят **{len(годные)}** из {len(ряды_в)} "
           "ведущих, у которых в окне нашлись покупки. Покупок считается по разбору окна (до 1000 на кошелёк "
           "в сутки -- предел записи), поэтому у самых частых это нижняя оценка.", "",
           загол, линия]
    md += [строка(w, ряды_в[w]) for w in годные] or ["| — | | | | | | | |"]

    md += ["", "## Где в этом ряду 54ua", ""]
    for a, имя in КТО.items():
        v = ряды.get(a)
        if not v:
            md.append(f"- `{a}` ({имя}) -- в сито недели не попал, в этот ряд не входит.")
            continue
        if a in коп:
            md.append(f"- `{a}` ({имя}) -- **место {по_итогу.index(a) + 1} из {len(коп)}** копировщиков по итогу "
                      f"после приоритета: {v['итог_после_prio_sol']} SOL, оборот {v['оборот_sol']} SOL, покупок "
                      f"{v['покупок_сито']}, билет {v['билет_медиана']} SOL, удержание "
                      f"{v['удержание_слотов_медиана']} слотов, за ведущим {v['за_ведущим']}, ведущих "
                      f"{v['ведущих']}" + (f" -- в таблице A он {верх.index(a) + 1}-й." if a in верх else
                                           " -- в верхние 50 не вошёл."))
        else:
            md.append(f"- `{a}` ({имя}) -- под признак копировщика не подходит: за ведущим "
                      f"{v.get('за_ведущим')}, удержание {v.get('удержание_слотов_медиана')} слотов.")
    md.append("")
    out = КОРЕНЬ / "docs" / "podbivka_2026-10-02_kopirovschiki.md"
    out.write_text("\n".join(md) + "\n", encoding="utf-8")
    R.записано(out)
    дт = П / "kopirovschiki.json"
    дт.write_text(json.dumps({"копировщиков": len(коп), "верх": верх, "ведущих_всего": len(вед_все),
                              "ведущих_новых": len(вед_новые), "ведущие_годные": годные,
                              "ряды_ведущих": ряды_в}, ensure_ascii=False, indent=1), encoding="utf-8")
    R.записано(дт)
    print(out.name, "копировщиков", len(коп), "ведущих новых", len(вед_новые), "прошли сито", len(годные), flush=True)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
