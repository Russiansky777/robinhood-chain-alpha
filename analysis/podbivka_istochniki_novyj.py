#!/usr/bin/env python3
"""Поиск источников на ПЕРЕКАЛИБРОВАННОЙ модели: реестр и вселенная, билет 0.3.

Зачем. Сверка модели с 44 живыми сделками vol_4vw показала, что модель ЗАНИЖАЕТ итог на
0.0082 SOL на сделку (медиана 0.0063, ниже факта в 34 случаях из 44). Значит прежний поиск
источников мог выбрасывать годных. Этот проход считает то же сито, что volna/volna2, но:

  * вход поправлен измеренным множителем к_f (флаг --k-f; у кривой он прежде не действовал
    вовсе -- `сделка_по_состояниям` применяла к_f только к XYK-пулам);
  * закрыты три утечки заглядывания вперёд, которые были в volna2:
      -- сигнал без состояния пула на горизонте выхода там ОТБРАСЫВАЛСЯ («continue»), то
         есть в счёт шли только те, за кем кто-то торговал до выхода, а это известно лишь
         ПОСЛЕ входа. Здесь такой круг считается в НЕ ИЗМЕНИВШИЙСЯ пул: продали по той же
         цене, итог -- минус наценки и издержки;
      -- круг, который не посчитался (продать нечем, пул закрыт), там тоже отбрасывался;
         здесь это потеря билета целиком;
      -- пара состояний, у которой плечи разошлись в разные стороны при рухнувшем
         произведении, -- не наш пул, и в счёт не идёт (вид_состояния).
  * глубина -- условие ВХОДА: билет не больше ДОЛЯ_РЕЗЕРВА от резерва;
  * ожидание -- среднее после всех расходов, срезанные средние без верхних 1 и 5 %,
    медиана, ДИ бутстрэпом ПО СУТКАМ; подбор и проверка раздельно.

Рядом считается ТОТ ЖЕ сито на СТАРОЙ модели (к_f = 1 и прежнее обращение с пропусками),
чтобы в итоге сказать, сколько прошедших старая модель отбрасывала и почему.

Только чтение кэша сигналов ($PODB_PAKET_KESH/signaly.jsonl.gz). Выход:
data/podbivka/istochniki_novyj.json, docs/podbivka_istochniki_novyj.md.
"""
from __future__ import annotations

import argparse
import collections
import json
import statistics
import sys
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import podbivka_bilet as B           # noqa: E402
import podbivka_paket_obshee as O    # noqa: E402
import podbivka_zapuski_svod as Z    # noqa: E402

КОРЕНЬ = O.КОРЕНЬ
П = O.П
БИЛЕТ = 0.3
УДЕРЖАНИЯ = (36, 60, 108)
ДОПУСК = 0.40
ПОРОГ_ИСТОЧНИКА = 2.0
# Стандарт выборки владельца с 10.10: «нужно брать нормальную выборку, дабы исключить
# вероятность везения». Скользящая проверка по всему архиву, порог на КАЖДОМ окне, и
# поправка на перебор -- и аналитическая (p < 0.05/N), и контролем на перемешанных
# знаках суточных исходов.
N_МИН = 100                 # сделок на источник на ОКНЕ проверки
ДОЛЯ_СУТОК_В_ПЛЮСЕ = 0.60
ПОДБОР_СУТОК = 7
ПРОВЕРКА_СУТОК = 4
СДВИГ_СУТОК = 4
ОКОН_МИН = 2                # меньше двух окон проверки -- это не проверка
ПЕРЕСТАНОВОК = 2000
ДОЛЯ_РЕЗЕРВА = 0.02
ДОЛЯ_ГЛУБИНЫ = 0.8
СЕМЯ = 20261010


def круг(с: dict, б: float, место: str, H: int, изд: float, к_f: float,
         к_g: float) -> tuple:
    """(итог, вид). Пропуск состояния выхода и непосчитанный круг -- это итоги."""
    сост = (с.get("модель") or {}).get("состояния") or {}
    вх = (сост.get("вход") or {}).get(место)
    if not вх:
        return None, "без_входа"
    вых = (сост.get("выход") or {}).get(str(H))
    вид = Z.вид_состояния(вх, вых) if вых else "пусто"
    if вид == "не_тот_пул":
        return None, вид
    if вид == "закрыт":
        return -(б + изд), "нельзя_продать"
    if вид == "пусто":
        # круг в НЕ ИЗМЕНИВШИЙСЯ пул: за нами никто не пришёл
        с2 = {"pool": с["pool"], "модель": {**с["модель"],
              "состояния": {"вход": сост["вход"], "выход": {"0": вх}, "масштаб": 1.0}}}
        кр = B.сделка_по_состояниям(с2, б, место, 0, издержки=изд, к_f=к_f, к_g=к_g)
        if кр is None:
            return -(б + изд), "нельзя_продать"
        return кр["итог_sol"], "пусто"
    кр = B.сделка_по_состояниям(с, б, место, H, издержки=изд, к_f=к_f, к_g=к_g)
    if кр is None:
        return -(б + изд), "нельзя_продать"
    return кр["итог_sol"], "годно"


def проход(к_f: float, к_g: float, изд: float, старая: bool) -> dict:
    """Ряды по источнику. `старая` -- прежнее обращение с пропусками, для сравнения."""
    ряды: dict = collections.defaultdict(list)
    счёт: collections.Counter = collections.Counter()
    for р in O.сигналы():
        счёт["сигналов"] += 1
        if р.get("quoteMint") != O.WSOL or not р.get("первая"):
            continue
        if (р.get("sol") or 0) < ПОРОГ_ИСТОЧНИКА:
            continue
        ист = р.get("ист")
        вх = р.get("вход") or {}
        if not (ист and вх):
            continue
        с = O.как_сигнал(р)
        if с is None:
            счёт["модель_не_собралась"] += 1
            continue
        счёт["в_счёте"] += 1
        for H in УДЕРЖАНИЯ:
            if старая:
                if not (р.get("выход") or {}).get(str(H)):
                    счёт[f"старая_выброшено_без_выхода|{H}"] += 1
                    continue
                д = B.сделка_по_состояниям(с, БИЛЕТ, "S0_дно", H, издержки=изд,
                                           к_f=1.0, к_g=к_g)
                if д is None:
                    счёт[f"старая_выброшено_круг_нет|{H}"] += 1
                    continue
                итог, вид = д["итог_sol"], "годно"
            else:
                итог, вид = круг(с, БИЛЕТ, "S0_дно", H, изд, к_f, к_g)
                if итог is None:
                    счёт[f"новая_не_в_счёт|{вид}|{H}"] += 1
                    continue
            ряды[(ист, H)].append({"сутки": O.сутки(р), "итог": итог,
                                   "резерв": р.get("резерв_sol"), "вид": вид})
    return {"ряды": dict(ряды), "счёт": dict(счёт)}


def свод(ряды: list, дни: list) -> dict:
    v = [x["итог"] for x in ряды]
    if not v:
        return {"n": 0}
    по_суткам: dict = collections.defaultdict(list)
    for x in ряды:
        по_суткам[x["сутки"]].append(x["итог"])
    низ, верх = Z.ди_по_суткам(по_суткам, seed=СЕМЯ)
    рез = [x["резерв"] for x in ряды if x.get("резерв")]
    гл = (sum(1 for r in рез if БИЛЕТ <= ДОЛЯ_РЕЗЕРВА * r) / len(рез)) if рез else 0.0
    суммы = {д: sum(z) for д, z in по_суткам.items()}
    сут = len(по_суткам)
    плюс_сут = sum(1 for s in суммы.values() if s > 0)
    return {"n": len(v), "суток": сут,
            "итог_sol": round(sum(v), 6),
            "sol_в_сутки": round(sum(v) / max(1, сут), 6),
            "сделок_в_сутки": round(len(v) / max(1, сут), 1),
            "ожидание_sol": round(statistics.fmean(v), 6),
            "ожидание_пп": round(100 * statistics.fmean(v) / БИЛЕТ, 3),
            "ди_низ_sol": round(низ, 6) if низ is not None else None,
            "ди_верх_sol": round(верх, 6) if верх is not None else None,
            "без_верх_1_sol": round(Z.срезанное(v, 0.01), 6),
            "без_верх_5_sol": round(Z.срезанное(v, 0.05), 6),
            "медиана_пп": round(100 * statistics.median(v) / БИЛЕТ, 3),
            "в_плюсе_проц": round(100 * sum(1 for x in v if x > 0) / len(v), 2),
            "суток_в_плюсе": плюс_сут,
            "доля_суток_в_плюсе": round(плюс_сут / max(1, сут), 3),
            "худшие_сутки_sol": round(min(суммы.values()), 6),
            "глубина_доля": round(гл, 3), "глубина_ок": гл >= ДОЛЯ_ГЛУБИНЫ,
            "суммы_по_суткам": {д: round(s, 6) for д, s in sorted(суммы.items())},
            "виды": dict(collections.Counter(x["вид"] for x in ряды))}


def половины(ряды: list, дни: list) -> tuple:
    п = дни[:len(дни) // 2], дни[len(дни) // 2:]
    return (свод([x for x in ряды if x["сутки"] in п[0]], п[0]),
            свод([x for x in ряды if x["сутки"] in п[1]], п[1]))


def окна_скольжения(дни: list, подбор: int, проверка: int, сдвиг: int) -> list:
    """Подбор `подбор` суток -> проверка следующих `проверка`, сдвиг на `сдвиг`."""
    из_ = []
    н = 0
    while н + подбор + проверка <= len(дни):
        из_.append((дни[н:н + подбор], дни[н + подбор:н + подбор + проверка]))
        н += сдвиг
    return из_


def окно_прошло(пров: dict, пол: tuple) -> tuple:
    """Стандарт владельца с 10.10 -- на КАЖДОМ окне проверки."""
    нет = []
    if пров.get("n", 0) < N_МИН:
        нет.append(f"n {пров.get('n', 0)} < {N_МИН}")
    if (пров.get("ожидание_sol") or 0) <= 0:
        нет.append("среднее не больше нуля")
    if (пров.get("ди_низ_sol") or 0) <= 0:
        нет.append("нижняя граница ДИ по суткам не выше нуля")
    if (пров.get("без_верх_5_sol") or 0) <= 0:
        нет.append("без верхних 5 % не в плюсе")
    if (пров.get("доля_суток_в_плюсе") or 0) < ДОЛЯ_СУТОК_В_ПЛЮСЕ:
        нет.append(f"суток в плюсе {пров.get('доля_суток_в_плюсе')} < "
                   f"{ДОЛЯ_СУТОК_В_ПЛЮСЕ}")
    for имя, п_ in zip(("первая", "вторая"), пол):
        if not п_ or (п_.get("итог_sol") or 0) <= 0:
            нет.append(f"{имя} половина окна не в плюсе")
    if not пров.get("глубина_ок"):
        нет.append(f"билет больше {ДОЛЯ_РЕЗЕРВА:.0%} резерва более чем на "
                   f"{100 * (1 - ДОЛЯ_ГЛУБИНЫ):.0f} % сделок")
    return (not нет), нет


def p_по_знакам(суммы: dict, рнд, повторов: int = ПЕРЕСТАНОВОК) -> float | None:
    """p для «итог положителен» при случайных ЗНАКАХ суточных исходов.

    Нулевая гипотеза владельца: знак исхода каждых суток случаен. Сутки -- единица
    перестановки, потому что сделки одних суток зависимы. Статистика -- сумма по всем
    суткам: сколько перестановок дают сумму не хуже наблюдённой.
    """
    v = [s for s in суммы.values() if s is not None]
    if len(v) < 4:
        return None
    набл = sum(v)
    хуже = 0
    абс = [abs(s) for s in v]
    for _ in range(повторов):
        с_ = sum(a if рнд.random() < 0.5 else -a for a in абс)
        if с_ >= набл:
            хуже += 1
    return (хуже + 1) / (повторов + 1)


def разбор(п: dict, дни: list, рнд, перемешать: bool = False) -> dict:
    """Скользящая проверка по всему архиву. `перемешать` -- знаки суточных исходов
    случайны: это контроль на перебор, он показывает, сколько «прошедших» даёт чистая
    случайность при том же отборе."""
    из_: dict = {}
    окна = окна_скольжения(дни, ПОДБОР_СУТОК, ПРОВЕРКА_СУТОК, СДВИГ_СУТОК)
    for (ист, H), ряды in п["ряды"].items():
        if перемешать:
            знак = {д: (1 if рнд.random() < 0.5 else -1)
                    for д in {x["сутки"] for x in ряды}}
            ряды = [{**x, "итог": x["итог"] * знак[x["сутки"]]} for x in ряды]
        окон = []
        for подб_д, пров_д in окна:
            пров_р = [x for x in ряды if x["сутки"] in пров_д]
            if not пров_р:
                окон.append({"проверка_дни": [пров_д[0], пров_д[-1]], "n": 0,
                             "прошло": False, "почему_нет": ["сделок в окне нет"]})
                continue
            с_ = свод(пров_р, пров_д)
            пол = половины(пров_р, пров_д)
            да, почему = окно_прошло(с_, пол)
            окон.append({"проверка_дни": [пров_д[0], пров_д[-1]], "n": с_["n"],
                         "sol_в_сутки": с_["sol_в_сутки"],
                         "ожидание_sol": с_["ожидание_sol"],
                         "ди_низ_sol": с_["ди_низ_sol"],
                         "без_верх_5_sol": с_["без_верх_5_sol"],
                         "доля_суток_в_плюсе": с_["доля_суток_в_плюсе"],
                         "прошло": да, "почему_нет": почему})
        всего = свод(ряды, дни)
        годных = [o for o in окон if o["n"]]
        прошло = bool(годных) and len(годных) >= ОКОН_МИН and all(o["прошло"] for o in годных)
        p = p_по_знакам(всего.get("суммы_по_суткам") or {}, рнд)
        из_[f"{ист}|{H}"] = {"источник": ист, "удержание": H, "всё_окно": всего,
                             "окна": окон, "окон_годных": len(годных),
                             "окон_в_плюсе": sum(1 for o in окон if o["прошло"]),
                             "прошло": прошло, "p": p}
    return из_


def main() -> int:  # noqa: PLR0915
    import random  # noqa: PLC0415
    р_ = argparse.ArgumentParser()
    р_.add_argument("--k-f", type=float, default=1.0,
                    help="множитель наценки ВХОДА, измеренный на живых сделках")
    р_.add_argument("--k-g", type=float, default=None,
                    help="множитель выхода; по умолчанию из kalibrovka.json")
    р_.add_argument("--izderzhki", type=float, default=None)
    р_.add_argument("--peremeshat", type=int, default=3,
                    help="сколько прогонов отбора на перемешанных знаках суток")
    р_.add_argument("--bez-staroy", action="store_true",
                    help="не считать старую модель рядом")
    р_.add_argument("--metka", default="")
    а = р_.parse_args()
    кал = (json.loads((П / "kalibrovka.json").read_text(encoding="utf-8"))
           .get("калибровка") or {})
    к_g = а.k_g if а.k_g is not None else float(кал.get("к_g") or 1.0)
    изд = (а.izderzhki if а.izderzhki is not None
           else float(кал.get("издержки_медиана_sol") or 0.002))
    рнд = random.Random(СЕМЯ)
    print(f"к_f {а.k_f}, к_g {к_g}, издержки {изд}", flush=True)

    print("== новая модель", flush=True)
    нов = проход(а.k_f, к_g, изд, старая=False)
    ст = None
    if not а.bez_staroy:
        print("== старая модель (к_f 1.0, прежнее обращение с пропусками)", flush=True)
        ст = проход(1.0, к_g, изд, старая=True)

    дни = sorted({x["сутки"] for ряды in нов["ряды"].values() for x in ряды})
    окна = окна_скольжения(дни, ПОДБОР_СУТОК, ПРОВЕРКА_СУТОК, СДВИГ_СУТОК)
    print(f"суток {len(дни)}: {дни[0]} .. {дни[-1]}; окон скольжения {len(окна)} "
          f"(подбор {ПОДБОР_СУТОК} -> проверка {ПРОВЕРКА_СУТОК}, сдвиг {СДВИГ_СУТОК})",
          flush=True)
    р_нов = разбор(нов, дни, рнд)
    N = len({v["источник"] for v in р_нов.values()})
    порог_p = 0.05 / max(1, N)
    for v in р_нов.values():
        v["прошло_с_поправкой"] = bool(v["прошло"] and v["p"] is not None
                                       and v["p"] < порог_p)
    прошли_нов = {k for k, v in р_нов.items() if v["прошло_с_поправкой"]}

    # контроль на перебор: тот же отбор на перемешанных знаках суточных исходов
    перемешано = []
    for i in range(а.peremeshat):
        р_пер = разбор(нов, дни, random.Random(СЕМЯ + 1 + i), перемешать=True)
        k = sum(1 for v in р_пер.values()
                if v["прошло"] and v["p"] is not None and v["p"] < порог_p)
        перемешано.append(k)
        print(f"  перемешанные знаки, прогон {i + 1}: прошло {k}", flush=True)

    р_ст = разбор(ст, дни, random.Random(СЕМЯ)) if ст else {}
    прошли_ст = {k for k, v in р_ст.items()
                 if v["прошло"] and v["p"] is not None and v["p"] < порог_p}
    только_новая = sorted(прошли_нов - прошли_ст)

    тело = {"что": "поиск источников на перекалиброванной модели, стандарт выборки 10.10",
            "когда": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
            "стандарт": {"билет": БИЛЕТ, "удержания": list(УДЕРЖАНИЯ),
                         "допуск": ДОПУСК, "к_f": а.k_f, "к_g": к_g, "издержки": изд,
                         "порог_источника_sol": ПОРОГ_ИСТОЧНИКА,
                         "доля_резерва": ДОЛЯ_РЕЗЕРВА,
                         "n_мин_на_окне_проверки": N_МИН,
                         "доля_суток_в_плюсе_мин": ДОЛЯ_СУТОК_В_ПЛЮСЕ,
                         "подбор_суток": ПОДБОР_СУТОК,
                         "проверка_суток": ПРОВЕРКА_СУТОК,
                         "сдвиг_суток": СДВИГ_СУТОК, "окон_мин": ОКОН_МИН,
                         "кошельков_проверено_N": N,
                         "порог_p_с_поправкой": порог_p,
                         "перестановок": ПЕРЕСТАНОВОК},
            "окно": {"сутки": дни,
                     "окна_скольжения": [[a[0], a[-1], b[0], b[-1]] for a, b in окна]},
            "счёт_новая": нов["счёт"],
            "счёт_старая": (ст or {}).get("счёт"),
            "строк_новая": len(р_нов), "строк_старая": len(р_ст),
            "прошли_новая": len(прошли_нов), "прошли_старая": len(прошли_ст),
            "на_перемешанных_прошло": перемешано,
            "прошли_только_на_новой": только_новая,
            "строки": {k: v for k, v in sorted(
                р_нов.items(),
                key=lambda kv: -(kv[1]["всё_окно"].get("sol_в_сутки") or -1e9))[:200]},
            "старая_по_тем_же": {k: р_ст.get(k) for k in только_новая}}
    ф = П / f"istochniki_novyj{('_' + а.metka) if а.metka else ''}.json"
    ф.write_text(json.dumps(тело, ensure_ascii=False, indent=1), encoding="utf-8")
    try:
        import podbivka_run as R  # noqa: PLC0415
        R.записано(ф)
    except Exception:  # noqa: BLE001, S110
        pass
