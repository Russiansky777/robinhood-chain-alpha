def не_адрес(з) -> bool:
    return not isinstance(з, str) or not (32 <= len(з) <= 44)


def инструкция_свопа(tpl: dict, *, user: str, amount_in: int, min_out: int,
                      как_у_источника: bool = False):
    """Инструкция SwapBaseInV2: тег 16 + два u64, счета по раскладке.

    как_у_источника=True -- пересборка сделки источника байт в байт (для проверки
    без денег): наши токеновые места берутся ИЗ ШАБЛОНА, а не выводятся, потому что
    у источника там мог стоять счёт роутера, а не ATA подписанта.

    ФЛАГИ -- ПО ОБЪЯВЛЕНИЮ ПРОГРАММЫ, а не по флагам сделки источника: места 1, 3,
    4, 5, 6 объявлены [writable] (и ровно они записываемы у 22 из 22 живых
    инструкций), 0 и 2 -- нет, 7 -- [signer].
    """
    from solders.instruction import AccountMeta, Instruction  # noqa: PLC0415
    from solders.pubkey import Pubkey  # noqa: PLC0415

    B = _кирпичи()
    счета = list((tpl or {}).get("accounts") or [])
    if len(счета) != РАСКЛАДКА["счетов"]:
        raise ОшибкаСтроителя(f"счетов {len(счета)}, по раскладке {РАСКЛАДКА['счетов']}")
    if не_адрес(user):
        raise ОшибкаСтроителя("пользователь не адрес")
    if как_у_источника:
        подстановка = {РАСКЛАДКА["подписант"]: user}
    else:
        минт_вх = (tpl or {}).get("минт_входа")
        минт_вых = (tpl or {}).get("минт_выхода")
        прог_вх = (tpl or {}).get("программа_входа") or SPL_ТОКЕН
        прог_вых = (tpl or {}).get("программа_выхода") or SPL_ТОКЕН
        if не_адрес(минт_вх) or не_адрес(минт_вых):
            raise ОшибкаСтроителя("минты сторон пула не известны -- ATA не вывести")
        подстановка = {РАСКЛАДКА["подписант"]: user,
                        РАСКЛАДКА["счёт_входа"]: B.ata(user, минт_вх, прог_вх),
                        РАСКЛАДКА["счёт_выхода"]: B.ata(user, минт_вых, прог_вых)}
    записываемые = set(обязаны_быть_записываемыми(tpl))
    метки = []
    for и, адрес in enumerate(счета):
        а = подстановка.get(и, адрес)
        метки.append(AccountMeta(Pubkey.from_string(а),
                                 is_signer=(и == РАСКЛАДКА["подписант"]),
                                 is_writable=(и in записываемые)))
    данные = bytes([ТЕГ_V2_ВХОД]) + struct.pack("<QQ", int(amount_in), int(min_out))
    return Instruction(Pubkey.from_string(ПРОГРАММА), данные, метки)


def собрать_покупку(tpl: dict, *, user: str, payer: str, amount_in: int,
                     min_out: int, минт_базы: str, минт_котировки: str,
                     программа_базы: str = SPL_ТОКЕН,
                     программа_котировки: str = SPL_ТОКЕН,
                     cu_units: int = 200_000, cu_price_micro: int = 0,
                     чаевые=None, чаевые_первыми: bool = False,
                     оборачивать_sol: bool = True, nonce=None) -> dict:
    """Неподписанная транзакция покупки: бюджет, ATA, обёртка SOL, своп, чаевые.

    Порядок инструкций и вид ответа -- РОВНО как у прочих строителей полосы:
    иначе обратный разбор проверки без денег сравнивал бы разное.
    """
    import base64  # noqa: PLC0415

    from solders.hash import Hash  # noqa: PLC0415
    from solders.message import MessageV0  # noqa: PLC0415
    from solders.pubkey import Pubkey  # noqa: PLC0415
    from solders.signature import Signature  # noqa: PLC0415
    from solders.transaction import VersionedTransaction  # noqa: PLC0415

    # СТОРОНЫ ШАБЛОНА И АРГУМЕНТЫ ОБЯЗАНЫ СОВПАДАТЬ: иначе собрали бы ATA не того
    # минта, а шаблон отдал бы программе счёт другой стороны.
    for ключ, знач in (("минт_входа", минт_котировки), ("минт_выхода", минт_базы),
                        ("программа_входа", программа_котировки),
                        ("программа_выхода", программа_базы)):
        было = tpl.get(ключ)
        if было and знач and было != знач:
            raise ОшибкаСтроителя(
                f"{ключ} шаблона {str(было)[:8]} и аргумент {str(знач)[:8]} разные")
    # TOKEN-2022 У ЭТОЙ РАСКЛАДКИ НЕТ МЕСТА: программа токена одна, место 0.
    for имя, прог in (("базы", программа_базы), ("котировки", программа_котировки)):
        if прог == TOKEN_2022:
            raise ОшибкаСтроителя(f"{ПРИЗНАК_TOKEN_2022} (сторона {имя})")
    B = _кирпичи()
    ixs = []
    if nonce:
        ixs.append(B.advance_nonce(str(nonce[0]), str(nonce[1])))
    ixs.append(B.cu_limit(cu_units))
    if cu_price_micro:
        ixs.append(B.cu_price(cu_price_micro))
    ixs.append(B.ata_idempotent(payer, user, минт_базы, программа_базы))
    ixs.append(B.ata_idempotent(payer, user, минт_котировки, программа_котировки))
    if минт_котировки == WSOL and оборачивать_sol and amount_in:
        wsol = B.ata(user, WSOL, программа_котировки)
        ixs += [B.sol_transfer(user, wsol, amount_in), B.sync_native(wsol)]

    def _чаевые(ч):
        пары = (ч if isinstance(ч, (list, tuple)) and ч
                and isinstance(ч[0], (list, tuple)) else [ч])
        return [B.sol_transfer(payer, а, int(л)) for а, л in пары]

    if чаевые and чаевые_первыми:
        ixs += _чаевые(чаевые)
    ixs.append(инструкция_свопа(dict(tpl, минт_входа=минт_котировки,
                                      минт_выхода=минт_базы,
                                      программа_входа=программа_котировки,
                                      программа_выхода=программа_базы),
                                 user=user, amount_in=amount_in, min_out=min_out))
    if чаевые and not чаевые_первыми:
        ixs += _чаевые(чаевые)
    msg = MessageV0.try_compile(Pubkey.from_string(payer), ixs, [], Hash.default())
    n = msg.header.num_required_signatures
    vtx = VersionedTransaction.populate(msg, [Signature.default()] * n)
    сырое = bytes(vtx)
    return {"tx_base64": base64.b64encode(сырое).decode(), "size": len(сырое),
            "n_instructions": len(ixs), "quote_mint": минт_котировки,
            "base_mint": минт_базы}


def build_buy(tpl: dict, tx: dict | None = None, *, user: str, payer: str,
               amount_in: int, min_out: int, cu_units: int = 200_000,
               cu_price_micro: int = 0, tip=None, wrap_sol: bool = True,
               nonce=None, tip_first: bool = False) -> dict:
    """ТА ЖЕ ДВЕРЬ, ЧТО У c2_swap_build.build_buy -- полоса меняет только МОДУЛЬ.

    Стороны пула берутся ИЗ ШАБЛОНА (их прикрепляет подготовить), поэтому tx
    нужен лишь тогда, когда шаблон через подготовить не проходил.
    """
    свой = dict(tpl or {})
    минт_базы = свой.get(КЛЮЧ_БАЗЫ)
    минт_котировки = свой.get(КЛЮЧ_КОТИРОВКИ)
    if (not минт_базы or not минт_котировки) and tx is not None:
        ш = шаблон_со_сторонами(свой, tx)
        if not ш.get("ok"):
            raise ОшибкаСтроителя(f"стороны пула не восстановились: {ш.get('why_not')}")
        свой = ш["шаблон"]
        минт_базы, минт_котировки = свой.get(КЛЮЧ_БАЗЫ), свой.get(КЛЮЧ_КОТИРОВКИ)
    if not минт_базы or not минт_котировки:
        raise ОшибкаСтроителя(
            "в шаблоне нет сторон пула -- он не прошёл через подготовить()")
    return собрать_покупку(
        свой, user=user, payer=payer, amount_in=amount_in, min_out=min_out,
        минт_базы=минт_базы, минт_котировки=минт_котировки,
        программа_базы=свой.get(КЛЮЧ_ПРОГ_БАЗЫ) or SPL_ТОКЕН,
        программа_котировки=свой.get(КЛЮЧ_ПРОГ_КОТИРОВКИ) or SPL_ТОКЕН,
        cu_units=cu_units, cu_price_micro=cu_price_micro, чаевые=tip,
        чаевые_первыми=tip_first, оборачивать_sol=wrap_sol, nonce=nonce)


