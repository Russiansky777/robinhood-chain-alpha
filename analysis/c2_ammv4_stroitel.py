def выход_по_резервам(резерв_входа: int, резерв_выхода: int, вход: int, *,
                       числитель: int | None = None,
                       знаменатель: int | None = None) -> dict:
    """swap_base_in программы: комиссия с входа, потом x*y=k, всё в целых.

    Сверено до единицы на 22 из 22 живых свопов по резервам их же событий.
    """
    ч = int(СТАВКА_ЧИСЛИТЕЛЬ if числитель is None else числитель)
    з = int(СТАВКА_ЗНАМЕНАТЕЛЬ if знаменатель is None else знаменатель)
    if вход <= 0:
        raise ОшибкаСтроителя("сумма входа не положительна")
    if резерв_входа <= 0 or резерв_выхода <= 0:
        raise ОшибкаСтроителя("резерв пула не положителен")
    комиссия = -(-int(вход) * ч // з)          # ceil, как в программе
    чистый = int(вход) - комиссия
    if чистый <= 0:
        raise ОшибкаСтроителя("вход целиком съеден комиссией")
    выход = резерв_выхода * чистый // (резерв_входа + чистый)
    return {"выход": выход, "комиссия": комиссия, "чистый_вход": чистый,
            "ставка_числитель": ч, "ставка_знаменатель": з}


def котировка(*, пул: str, минт_базы: str, минт_котировки: str, лампорты: int,
               проскальзывание: float, rpc_call, хранилище_котировки: str | None = None,
               хранилище_базы: str | None = None, сейчас: float | None = None,
               налог_выхода=None, налог_входа=None, программа_выхода: str | None = None,
               программа_входа: str | None = None, ставка=None) -> dict:
    """Минимум выхода AMM v4 по ЖИВЫМ резервам двух хранилищ. Одно чтение.

    Вид ответа -- как у прочих строителей: {ok, expected_out, min_out, fee_share,
    чтений, точная, путь}.
    """
    из_ = {"ok": False, "why_not": None, "чтений": 0, "точная": True,
            "путь": "две резервы AMM v4 (x*y=k)"}
    if лампорты <= 0:
        из_["why_not"] = "сумма входа не положительна"
        return из_
    if not хранилище_котировки or not хранилище_базы:
        из_["why_not"] = "хранилища сторон не названы -- резервы читать нечем"
        return из_
    if хранилище_котировки == хранилище_базы:
        из_["why_not"] = "хранилища сторон совпали -- это одна и та же сторона"
        return из_
    # TOKEN-2022 У ЭТОЙ РАСКЛАДКИ НЕТ: программа токена одна (место 0).
    for имя, прог in (("выхода", программа_выхода), ("входа", программа_входа)):
        if прог == TOKEN_2022:
            из_["why_not"] = f"{ПРИЗНАК_TOKEN_2022} (сторона {имя})"
            return из_
    if rpc_call is None:
        из_["why_not"] = "узел недоступен, резервы пула не прочитать"
        return из_
    if not пул:
        из_["why_not"] = "адрес пула не назван -- ставку и need_take_pnl читать нечем"
        return из_
    # ОДНО ЧТЕНИЕ, ТРИ СЧЁТА: пул и два хранилища. Пул нужен не для цены как
    # таковой, а чтобы ставка комиссии и need_take_pnl были ПРОЧИТАНЫ, а не
    # предположены -- и он идёт в том же getMultipleAccounts, то есть бесплатно.
    ч = _счета(rpc_call, [пул, хранилище_котировки, хранилище_базы])
    из_["чтений"] = 1
    из_["мс_чтений_всего"] = ч.get("мс")
    из_["slot"] = ч.get("slot")
    if not ч["ok"]:
        из_["why_not"] = f"резервы не прочитаны: {ч['why_not']}"
        return из_
    р_кот = разобрать_хранилище(ч["данные"].get(хранилище_котировки),
                                 ждём_минт=минт_котировки,
                                 ждём_владельца=РАСПОРЯДИТЕЛЬ)
    if not р_кот["ok"]:
        из_["why_not"] = f"хранилище котировки: {р_кот['why_not']}"
        return из_
    р_баз = разобрать_хранилище(ч["данные"].get(хранилище_базы),
                                 ждём_минт=минт_базы,
                                 ждём_владельца=РАСПОРЯДИТЕЛЬ)
    if not р_баз["ok"]:
        из_["why_not"] = f"хранилище базы: {р_баз['why_not']}"
        return из_
    рп = разобрать_пул(ч["данные"].get(пул),
                        ждём_хранилища=(хранилище_котировки, хранилище_базы),
                        минты_хранилищ={хранилище_котировки: р_кот["минт"],
                                        хранилище_базы: р_баз["минт"]})
    if not рп["ok"]:
        из_["why_not"] = f"счёт пула: {рп['why_not']}"
        return из_
    из_.update(status=рп["status"], ставка_пула=(рп["fee_num"], рп["fee_den"]),
                pool_open_time=рп["pool_open_time"])
    любой_статус = (os.environ.get(ИМЯ_ФЛАГА_ЛЮБОЙ_СТАТУС) or "").strip() == "1"
    if рп["status"] != СТАТУС_СВОП and not любой_статус:
        из_["why_not"] = (f"status пула {рп['status']}, а на цепи наблюдался только "
                           f"{СТАТУС_СВОП} (SwapOnly) -- прочие разрешения у AMM v4 "
                           f"другие, вплоть до запрета свопа "
                           f"(снять: {ИМЯ_ФЛАГА_ЛЮБОЙ_СТАТУС}=1)")
        return из_
    когда = int(сейчас if сейчас is not None else time.time())
    if рп["pool_open_time"] and когда < рп["pool_open_time"]:
        из_["why_not"] = (f"пул откроется в {рп['pool_open_time']}, а сейчас {когда} "
                           f"-- своп до открытия откатится")
        return из_
    # РЕЗЕРВ -- БАЛАНС МИНУС need_take_pnl ТОЙ ЖЕ СТОРОНЫ, как считает программа.
    pnl_по_хранилищу = {рп["coin_vault"]: рп["pnl_coin"], рп["pc_vault"]: рп["pnl_pc"]}
    рез = {}
    for имя, адрес_, бал in (("входа", хранилище_котировки, р_кот["сумма"]),
                              ("выхода", хранилище_базы, р_баз["сумма"])):
        р_ = резерв_стороны(бал, int(pnl_по_хранилищу.get(адрес_) or 0))
        if not р_["ok"]:
            из_["why_not"] = f"резерв {имя}: {р_['why_not']}"
            return из_
        рез[имя] = р_["резерв"]
    из_.update(резерв_входа=рез["входа"], резерв_выхода=рез["выхода"],
                баланс_входа=р_кот["сумма"], баланс_выхода=р_баз["сумма"],
                pnl_входа=int(pnl_по_хранилищу.get(хранилище_котировки) or 0),
                pnl_выхода=int(pnl_по_хранилищу.get(хранилище_базы) or 0))
    # СТАВКА -- ИЗ САМОГО ПУЛА. Аргумент ставка= её переопределяет (для замеров),
    # константа 25/10000 осталась лишь как наблюдённое значение по умолчанию.
    ст = (ставка if isinstance(ставка, (tuple, list)) and len(ставка) == 2
          else (рп["fee_num"], рп["fee_den"]))
    try:
        q = выход_по_резервам(рез["входа"], рез["выхода"], int(лампорты),
                              числитель=ст[0], знаменатель=ст[1])
    except Exception as exc:  # noqa: BLE001
        из_["why_not"] = f"цена не посчиталась: {type(exc).__name__}: {str(exc)[:120]}"
        return из_
    ожидаем = int(q["выход"])
    if ожидаем <= 0:
        из_["why_not"] = "цена дала ноль на выходе"
        return из_
    # Налог перевода стороны выхода: у V2 его быть не может, но если вызывающий
    # его всё же назвал -- вычитаем, а не молчим.
    if налог_назван(налог_выхода):
        ожидаем = без_налога(ожидаем, налог_выхода[0],
                              налог_выхода[1] if len(налог_выхода) > 1 else None)
    if ожидаем <= 0:
        из_["why_not"] = "налог перевода минта выхода съедает весь выход"
        return из_
    мин = int(ожидаем * (1.0 - float(проскальзывание)))
    if мин <= 0:
        из_["why_not"] = "минимум выхода не положителен при этом проскальзывании"
        return из_
    # РЕЗЕРВЫ ПОСЛЕ СВОПА -- отдаём явно. Замечание Code-1: ни один из трёх прежних
    # строителей их не отдаёт, и правило тонкого пула у полосы уходит в ветку
    # «резерв неизвестен». У x*y=k это два вычитания, поэтому здесь они есть.
    из_.update(reserves_after=[рез["входа"] + q["чистый_вход"],
                                рез["выхода"] - ожидаем],
                резерв_входа_после=рез["входа"] + q["чистый_вход"],
                резерв_выхода_после=рез["выхода"] - ожидаем)
    из_.update(ok=True, expected_out=ожидаем, min_out=мин,
                fee=q["комиссия"], чистый_вход=q["чистый_вход"],
                ставка_числитель=q["ставка_числитель"],
                ставка_знаменатель=q["ставка_знаменатель"],
                fee_share=q["ставка_числитель"] / float(q["ставка_знаменатель"]))
    return из_


