    txs = []

    def обойти(o, глуб=0):
        if глуб > 8:
            return
        if isinstance(o, dict):
            if "meta" in o and "transaction" in o:
                txs.append(o)
                return
            for v in o.values():
                обойти(v, глуб + 1)
        elif isinstance(o, list):
            for v in o:
                обойти(v, глуб + 1)

