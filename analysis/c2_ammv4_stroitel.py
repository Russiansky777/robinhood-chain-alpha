def _поля_события(ев: dict):
    """Поля события свопа из РАЗОБРАННОГО Code-2 вида. Нет нужных -- None."""
    имена = (("amount_in", "вход"), ("direction", "направление"),
             ("pool_coin", "pool_coin"), ("pool_pc", "pool_pc"),
             ("out_amount", "выход"))
    з = {}
    for а, б in имена:
        v = ев.get(а)
        if v is None:
            v = ев.get(б)
        if v is None:
            return None
        з[б] = int(v)
    return (з["вход"], з["направление"], з["pool_coin"], з["pool_pc"], з["выход"])


def цена_из_снимка(снимок: dict, rpc_call, *, сейчас: float | None = None) -> dict:
    """То же, что цена_из_состояния, но БЕЗ шаблона -- по полям самого снимка.

    ЗАЧЕМ ОТДЕЛЬНАЯ ДВЕРЬ. Через шаблон проверка доходит только до тех снимков, чья
    СЛЕДУЮЩАЯ сделка сделана вариантом v2 (тег 16) -- иначе строитель честно
    отказывает ещё на шаблоне. Но чтение состояния от вида инструкции не зависит
    вовсе: формула swap_base_in у v1 и v2 одна, различается только раскладка
    счетов. Поэтому здесь адреса берутся из самого снимка (`пул`, `хранилища`), и
    состояние сверяется на ВСЕХ снимках, где у следующей сделки есть ray_log, --
    включая сделки вариантом v1, которые строитель не собирает.
    """
    из_ = {"ok": False, "why_not": None, "пул": (снимок or {}).get("пул")}
    tx = (снимок or {}).get("транзакция") or {}
    пул = (снимок or {}).get("пул")
    хр = list((снимок or {}).get("хранилища") or [])
    if not пул or len(хр) != 2:
        из_["why_not"] = "в снимке нет пула или двух хранилищ"
        return из_
    ев = событие_свопа(tx)
    if ев is None:
        из_["why_not"] = "у следующей сделки нет события ray_log этой программы"
        return из_
    ч = _счета(rpc_call, [пул] + хр)
    if not ч["ok"]:
        из_["why_not"] = f"состояние не прочитано: {ч['why_not']}"
        return из_
    разобранные = {}
    for а in хр:
        р = разобрать_хранилище(ч["данные"].get(а), ждём_владельца=РАСПОРЯДИТЕЛЬ)
        if not р["ok"]:
            из_["why_not"] = f"хранилище {а[:8]}: {р['why_not']}"
            return из_
        разобранные[а] = р
    рп = разобрать_пул(ч["данные"].get(пул), ждём_хранилища=tuple(хр),
                        минты_хранилищ={а: р["минт"] for а, р in разобранные.items()})
    if not рп["ok"]:
        из_["why_not"] = f"счёт пула: {рп['why_not']}"
        return из_
    бал = {"coin": разобранные[рп["coin_vault"]]["сумма"],
           "pc": разобранные[рп["pc_vault"]]["сумма"]}
    pc_в_coin = (ев["направление"] == НАПРАВЛЕНИЕ_PC_В_COIN)
    вх_бал, вых_бал = ((бал["pc"], бал["coin"]) if pc_в_coin
                        else (бал["coin"], бал["pc"]))
    вх_pnl, вых_pnl = ((рп["pnl_pc"], рп["pnl_coin"]) if pc_в_coin
                        else (рп["pnl_coin"], рп["pnl_pc"]))
    факт = int(ев["выход"])
    варианты = {"по_балансам": (вх_бал, вых_бал),
                "минус_pnl": (вх_бал - вх_pnl, вых_бал - вых_pnl),
                "по_логу": ((ев["pool_pc"], ев["pool_coin"]) if pc_в_coin
                             else (ев["pool_coin"], ев["pool_pc"]))}
    свод_ = {}
    for имя, (r_in, r_out) in варианты.items():
        try:
            q = выход_по_резервам(r_in, r_out, int(ев["amount_in"]),
                                  числитель=рп["fee_num"], знаменатель=рп["fee_den"])
        except Exception as exc:  # noqa: BLE001
            свод_[имя] = {"ok": False, "why_not": type(exc).__name__}
            continue
        свод_[имя] = {"ok": True, "наш": q["выход"], "до_единицы": q["выход"] == факт,
                       "отклонение_%": (round((q["выход"] - факт) / факт * 100, 6)
                                         if факт else None)}
    из_.update(ok=True, факт=факт, вход=int(ев["amount_in"]),
                status=рп["status"], ставка_пула=(рп["fee_num"], рп["fee_den"]),
                pnl=(рп["pnl_coin"], рп["pnl_pc"]), варианты=свод_,
                slot_чтения=(снимок or {}).get("slot"),
                slot_сделки=(снимок or {}).get("slot_сделки"))
    return из_


def резервы_из_балансов(tx: dict, tpl: dict) -> dict:
    """Балансы ДО сделки у двух хранилищ пула -- из метаданных той же транзакции.

    Это НЕ состояние в наш слот, а состояние перед сделкой источника. Годится
    ровно для двух вещей: сверить формулу и дать проверке без денег дойти до
    сборки там, где снимков состояния нет вовсе. Ценой в наш слот это не является
    и таковой нигде не называется.
    """
    import c2_common as C  # noqa: PLC0415

    счета = list((tpl or {}).get("accounts") or [])
    if len(счета) < РАСКЛАДКА["счетов"]:
        return {"ok": False, "why_not": "раскладка шаблона не опознана"}
    строки = {с["account"]: с for с in C.token_rows(tx).values()}
    с_coin = строки.get(счета[РАСКЛАДКА["хранилище_coin"]])
    с_pc = строки.get(счета[РАСКЛАДКА["хранилище_pc"]])
    if not с_coin or not с_pc:
        return {"ok": False, "why_not": "хранилищ пула нет в балансах транзакции"}
    return {"ok": True, "coin": с_coin["pre"], "pc": с_pc["pre"],
            "минт_coin": с_coin.get("mint"), "минт_pc": с_pc.get("mint")}


def узел_из_сделки(tx: dict, tpl: dict):
    """Подставной узел, отдающий два хранилища пула ИЗ БАЛАНСОВ ТОЙ ЖЕ СДЕЛКИ.

    ЗАЧЕМ. Сбора состояний по AMM v4 нет (его ещё не сделал никто), а без резервов
    проверка без денег не доходит до сборки и меряла бы одну раскладку. Узел
    собирает байты токенового счёта из ФАКТА цепи -- минт и баланс ДО сделки стоят
    в метаданных самой транзакции, владелец у хранилища всегда распорядитель
    программы. Ничего не выдумано: ни одно число здесь не взято с потолка.

    ЧЕМ ЭТО НЕ ЯВЛЯЕТСЯ: ценой в НАШ слот. Резервы здесь -- перед сделкой
    источника, поэтому отчёт называет такую цену «по балансам сделки», а не
    точной, и три числа по цене считаются отдельной графой.
    """
    б = резервы_из_балансов(tx, tpl)
    if not б.get("ok"):
        return None
    B = _кирпичи()
    счета = list((tpl or {}).get("accounts") or [])

    def байты(минт: str, сумма: int) -> bytes:
        return (bytes(B.b58decode(минт)) + bytes(B.b58decode(РАСПОРЯДИТЕЛЬ))
                + int(сумма).to_bytes(8, "little") + bytes(ДЛИНА_ТОКЕНОВОГО_СЧЁТА - 72))

    х_coin = счета[РАСКЛАДКА["хранилище_coin"]]
    х_pc = счета[РАСКЛАДКА["хранилище_pc"]]
    хранилища = {х_coin: байты(б["минт_coin"], б["coin"]),
                 х_pc: байты(б["минт_pc"], б["pc"])}
    # СЧЁТ ПУЛА В ОБРАЗЦАХ ТОЖЕ ОТСУТСТВУЕТ, а котировка его теперь читает (ставка
    # и need_take_pnl -- из него). Собираем его из ТОГО, ЧТО ТРАНЗАКЦИЯ ЗНАЕТ:
    # адреса хранилищ -- из её же инструкции, минты -- из её балансов. Остальные три
    # поля транзакция не знает, и они ДОПУЩЕНИЯ, названные по имени:
    #   status = 6 (единственное, наблюдённое на цепи -- 30 из 30),
    #   ставка = 25/10000 (та же, 30 из 30),
    #   need_take_pnl = 0 (у токенного пула так и есть; у SOL/USDC нет).
    # Сторожа разбора при этом работают по-настоящему: адреса хранилищ и их минты
    # обязаны совпасть, иначе разбор откажет.
    допущения = {"status": СТАТУС_СВОП, "ставка": (СТАВКА_ЧИСЛИТЕЛЬ,
                                                   СТАВКА_ЗНАМЕНАТЕЛЬ),
                 "need_take_pnl": (0, 0),
                 "почему": "в образцах нет счёта пула -- эти три поля приняты, а не "
                            "прочитаны; ценой в наш слот это не является"}

    def байты_пула() -> bytes:
        д = bytearray(РАЗМЕР_ПУЛА)
        сд = СМЕЩЕНИЯ_ПУЛА

        def пиши_u64(о: int, зн: int) -> None:
            д[о:о + 8] = int(зн).to_bytes(8, "little")

        def пиши_адрес(о: int, адрес: str) -> None:
            д[о:о + 32] = bytes(B.b58decode(адрес))

        пиши_u64(сд["status"], СТАТУС_СВОП)
        пиши_u64(сд["fee_num"], СТАВКА_ЧИСЛИТЕЛЬ)
        пиши_u64(сд["fee_den"], СТАВКА_ЗНАМЕНАТЕЛЬ)
        пиши_u64(сд["pnl_coin"], 0)
        пиши_u64(сд["pnl_pc"], 0)
        пиши_u64(сд["pool_open_time"], 0)
        пиши_адрес(сд["coin_vault"], х_coin)
        пиши_адрес(сд["pc_vault"], х_pc)
        пиши_адрес(сд["coin_mint"], б["минт_coin"])
        пиши_адрес(сд["pc_mint"], б["минт_pc"])
        return bytes(д)

    пул_адрес = счета[РАСКЛАДКА["пул"]]
    хранилища[пул_адрес] = байты_пула()
    _ = допущения

    def rpc_call(метод: str, параметры: list):
        if метод != "getMultipleAccounts":
            raise ОшибкаСтроителя(f"подставной узел знает только getMultipleAccounts, "
                                   f"а спросили {метод}")
        import base64  # noqa: PLC0415

        адреса = list(параметры[0])
        значения = []
        for а in адреса:
            д = хранилища.get(а)
            значения.append(None if д is None else
                            {"data": [base64.b64encode(д).decode(), "base64"],
                             "owner": SPL_ТОКЕН, "lamports": 2_039_280,
                             "executable": False, "rentEpoch": 0})
        return {"result": {"context": {"slot": (tx or {}).get("slot") or 0},
                           "value": значения}}

    return rpc_call


