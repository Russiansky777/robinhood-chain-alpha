def сверка_по_разобранным(сделки: list) -> dict:
    """Раскладка и цена по РАЗОБРАННЫМ инструкциям сбора (без целых транзакций).

    ЗАЧЕМ. В сборе Code-2 целая транзакция есть только у снимков; у 501 сделки
    лежат разобранные роли счетов и события. Байт в байт по ним не сверить -- байтов
    нет, -- зато сверяется то, что от байтов не зависит: стоит ли на каждом месте та
    роль, которую объявляет раскладка, и даёт ли наша формула РОВНО тот выход,
    который записан в событии этой же сделки.

    Числа считаются ОТДЕЛЬНО для пулов токенов и для пула SOL/USDC: второй -- обмен
    через агрегатор, и для строителя покупок он не показателен.
    """
    из_ = {"ok": False, "why_not": None}
    if not сделки:
        из_["why_not"] = "разобранных сделок в сборе нет"
        return из_
    группы = {"токены": _пустая_группа(), "sol_usdc": _пустая_группа()}
    # ДВА ВИДА СБОРА -- ОДИН СЧЁТ. amm4_sbor.json даёт список СДЕЛОК, у каждой ключ
    # "инструкции"; amm4_dlya_code3.json -- сразу список ИНСТРУКЦИЙ (у них на
    # верхнем уровне "роли"). Без этого второй файл считался как ноль инструкций,
    # и отчёт печатал "0 из 0" рядом со словом "сверено" -- то есть ничего.
    for с in сделки:
        плоско = ([с] if isinstance(с, dict) and isinstance(с.get("роли"), dict)
                  else (с.get("инструкции") or []))
        for их in плоско:
            роли = их.get("роли") or {}
            пул = роли.get("amm")
            г = группы["sol_usdc" if пул == ПУЛ_SOL_USDC else "токены"]
            г["инструкций"] += 1
            тег = их.get("тег")
            г["по_тегу"][str(тег)] = г["по_тегу"].get(str(тег), 0) + 1
            if тег != ТЕГ_V2_ВХОД:
                г["не_наш_тег"] += 1
                continue
            г["наш_тег"] += 1
            # РАСКЛАДКА: на своих местах -- свои роли. Роли назвал Code-2 при
            # разборе, места -- наша таблица; сверяем имена, а не порядок на глаз.
            если_счетов = их.get("счетов")
            если_длина = их.get("длина_данных")
            г["счетов_8"] += (если_счетов == РАСКЛАДКА["счетов"])
            г["данных_17"] += (если_длина == ДЛИНА_ДАННЫХ)
            г["программа_токена_spl"] += (роли.get("token_program") == SPL_ТОКЕН)
            г["распорядитель_на_месте"] += (роли.get("amm_authority") == РАСПОРЯДИТЕЛЬ)
            г["пул_назван"] += bool(пул)
            г["хранилища_названы"] += bool(роли.get("amm_coin_vault")
                                            and roles_pc(роли))
            г["роли_все"] += bool(
                роли.get("token_program") == SPL_ТОКЕН
                and роли.get("amm_authority") == РАСПОРЯДИТЕЛЬ
                and пул and роли.get("amm_coin_vault") and roles_pc(роли)
                # ИМЕНА НАШИХ ТРЁХ РОЛЕЙ -- КАК ИХ НАЗЫВАЕТ СБОР Code-2
                # (user_source / user_destination / user_owner), а не как их зовёт
                # doc-комментарий программы. Проверено по ключам самого сбора:
                # сверять по своим догадкам об именах -- значит мерить свою
                # догадку, и первый заход дал ровно ноль из 31 на этом.
                and роли.get("user_source") and роли.get("user_destination")
                and роли.get("user_owner"))
        # ЦЕНА против события той же сделки -- по резервам события (это проверка
        # формулы, состояния здесь нет).
        # ИМЯ КЛЮЧА СОБЫТИЙ У ДВУХ СБОРОВ РАЗНОЕ: "события" в amm4_sbor.json,
        # "события_ray_log" в amm4_dlya_code3.json. Искать только одно имя значило
        # бы печатать "0 из 0" там, где событий 38.
        события_ = (с.get("события") or с.get("события_ray_log")
                    or (плоско[0].get("события_ray_log") if плоско else None) or [])
        for ев in события_:
            пул = (ев.get("amm") or ев.get("pool")
                   or ((плоско or [{}])[0].get("роли") or {}).get("amm"))
            г = группы["sol_usdc" if пул == ПУЛ_SOL_USDC else "токены"]
            поля = _поля_события(ев)
            if поля is None:
                г["событий_без_полей"] += 1
                continue
            вход, направление, p_coin, p_pc, выход = поля
            г["событий"] += 1
            pc_в_coin = (направление == НАПРАВЛЕНИЕ_PC_В_COIN)
            r_in, r_out = ((p_pc, p_coin) if pc_в_coin else (p_coin, p_pc))
            try:
                q = выход_по_резервам(r_in, r_out, вход)
            except Exception:  # noqa: BLE001
                г["цена_не_посчиталась"] += 1
                continue
            if q["выход"] == выход:
                г["цена_до_единицы"] += 1
            else:
                г["цена_разошлась"] += 1
                if len(г["примеры_расхождений"]) < 3:
                    г["примеры_расхождений"].append(
                        {"наш": q["выход"], "факт": выход, "вход": вход})
    for г in группы.values():
        г["примеры_расхождений"] = г["примеры_расхождений"][:3]
    из_.update(ok=True, группы=группы)
    return из_


def roles_pc(роли: dict):
    """Имя роли pc-хранилища у Code-2 -- amm_pc_vault; вынесено, чтобы не путать."""
    return роли.get("amm_pc_vault")


