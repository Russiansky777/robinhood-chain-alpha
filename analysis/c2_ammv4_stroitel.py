# СМЕЩЕНИЯ ПОЛЕЙ AmmInfo -- СВЕРЕНЫ НА 30 ЖИВЫХ СЧЕТАХ ПУЛОВ, 30 из 30. Проверка
# самопроверяющаяся, поэтому это факт, а не раскладка «по документации»: адреса
# хранилищ, прочитанные по смещениям 336 и 368, обязаны совпасть с теми, что стоят
# в инструкции, а минты по 400 и 432 -- с минтами этих же хранилищ, прочитанными
# отдельно из их токеновых счетов. На сборе Code-2 (data/podbivka/amm4_sbor.json,
# 30 снимков) сошлось у всех 30; заодно у всех 30 ставка оказалась 25/10000 и
# status = 6.
РАЗМЕР_ПУЛА = 752
СМЕЩЕНИЯ_ПУЛА = {"status": 0, "fee_num": 176, "fee_den": 184,
                  "pnl_coin": 192, "pnl_pc": 200, "pool_open_time": 224,
                  "coin_vault": 336, "pc_vault": 368,
                  "coin_mint": 400, "pc_mint": 432}
# status = 6 (SwapOnly) -- единственное значение, наблюдённое на цепи (30 из 30).
# Прочие значения означают у AMM v4 другие разрешения, вплоть до запрета свопа, и
# на цепи мы их не видели -- поэтому отказ, а не попытка. Снять отказ можно
# переменной, не правя код: цена ошибки в другую сторону -- откат с чаевыми.
СТАТУС_СВОП = 6
ИМЯ_ФЛАГА_ЛЮБОЙ_СТАТУС = "BLOOM_AMMV4_LYUBOY_STATUS"


def разобрать_пул(данные: bytes, *, ждём_хранилища=None,
                   минты_хранилищ=None) -> dict:
    """Поля AmmInfo, нужные для цены, со СТОРОЖАМИ на смещения.

    Сторожа не украшение: если смещения не те, адреса хранилищ по 336/368 не
    совпадут с теми, что стоят в инструкции, а минты по 400/432 -- с минтами этих
    хранилищ. Тогда отказ, а не «резерв», из которого вышел бы завышенный минимум
    выхода и откат на каждой попытке.
    """
    из_ = {"ok": False, "why_not": None}
    if not данные or len(данные) != РАЗМЕР_ПУЛА:
        из_["why_not"] = (f"счёт пула длиной {0 if not данные else len(данные)}, "
                           f"а AmmInfo -- {РАЗМЕР_ПУЛА} байт")
        return из_
    B = _кирпичи()
    сд = СМЕЩЕНИЯ_ПУЛА

    def u64(о: int) -> int:
        return int.from_bytes(данные[о:о + 8], "little")

    def адрес(о: int) -> str:
        return B.b58encode(данные[о:о + 32])

    п = {"status": u64(сд["status"]), "fee_num": u64(сд["fee_num"]),
         "fee_den": u64(сд["fee_den"]), "pnl_coin": u64(сд["pnl_coin"]),
         "pnl_pc": u64(сд["pnl_pc"]), "pool_open_time": u64(сд["pool_open_time"]),
         "coin_vault": адрес(сд["coin_vault"]), "pc_vault": адрес(сд["pc_vault"]),
         "coin_mint": адрес(сд["coin_mint"]), "pc_mint": адрес(сд["pc_mint"])}
    if not п["fee_den"] or п["fee_num"] > п["fee_den"]:
        из_["why_not"] = (f"ставка комиссии пула {п['fee_num']}/{п['fee_den']} "
                           f"бессмысленна -- смещения не те")
        return из_
    if ждём_хранилища is not None:
        ждали = set(ждём_хранилища)
        если = {п["coin_vault"], п["pc_vault"]}
        if если != ждали:
            из_["why_not"] = (f"хранилища пула по смещениям ({п['coin_vault'][:8]}, "
                               f"{п['pc_vault'][:8]}) не те, что в инструкции -- "
                               f"смещения не те или счёт не этого пула")
            return из_
    if минты_хранилищ:
        для_coin = минты_хранилищ.get(п["coin_vault"])
        для_pc = минты_хранилищ.get(п["pc_vault"])
        if (для_coin and для_coin != п["coin_mint"]) or \
                (для_pc and для_pc != п["pc_mint"]):
            из_["why_not"] = ("минты по смещениям не совпали с минтами самих "
                               "хранилищ -- смещения не те")
            return из_
    из_.update(ok=True, **п)
    return из_


def резерв_стороны(баланс: int, pnl: int) -> dict:
    """Резерв программы: баланс хранилища МИНУС накопленная доля комиссии.

    Так считает сама программа (`need_take_pnl_coin/pc`), и на живых снимках это
    заметно: из 6 сделок, где состояние удалось сверить, вариант «минус pnl»
    сошёлся до единицы у 4, а «по балансам» -- у 3.
    """
    if pnl > баланс:
        return {"ok": False, "why_not": (f"need_take_pnl {pnl} больше баланса "
                                          f"хранилища {баланс} -- это не резерв")}
    return {"ok": True, "резерв": int(баланс) - int(pnl)}


# ------------------------- сверка цены и резервов по САМОЙ сделке источника

# Событие свопа AMM v4 -- строка `ray_log:` в логах, base64, 57 байт:
# log_type u8 (3 -- вход задан) + amount_in, minimum_out, direction, user_source,
# pool_coin, pool_pc, out_amount -- семь u64 LE. Разложение подтверждено фактом:
# amount_in и minimum_out совпали с аргументами инструкции у 21 из 22 живых сделок
# (у одной строки ray_log в логах нет вовсе), а формула по pool_coin/pool_pc даёт
# РОВНО out_amount у 22 из 22.
ТИП_СОБЫТИЯ_ВХОД = 3
ДЛИНА_СОБЫТИЯ = 57
# direction в событии: 1 -- pc -> coin, 2 -- coin -> pc. Установлено ЧИСЛОМ, а не
# по памяти: при обратном толковании формула не сходится ни на одной из 22 сделок,
# при этом -- на всех 22.
НАПРАВЛЕНИЕ_PC_В_COIN = 1


def событие_свопа(tx: dict, *, вход: int | None = None) -> dict | None:
    """Событие ray_log свопа этой программы (при нужде -- с этим amount_in)."""
    import base64  # noqa: PLC0415

    for L in ((tx or {}).get("meta") or {}).get("logMessages") or []:
        if "ray_log:" not in L:
            continue
        try:
            д = base64.b64decode(L.split("ray_log:")[1].strip())
        except Exception:  # noqa: BLE001
            continue
        if len(д) != ДЛИНА_СОБЫТИЯ or д[0] != ТИП_СОБЫТИЯ_ВХОД:
            continue
        (a_in, min_out, направление, источник_до,
         pool_coin, pool_pc, выход) = struct.unpack_from("<QQQQQQQ", д, 1)
        if вход is not None and a_in != вход:
            continue
        return {"amount_in": a_in, "minimum_out": min_out, "направление": направление,
                "источник_до": источник_до, "pool_coin": pool_coin, "pool_pc": pool_pc,
                "выход": выход}
    return None


def сверка_цены_по_событию(tx: dict, tpl: dict) -> dict:
    """Наша формула против ФАКТА той же сделки: до единицы или нет.

    Резервы берутся ИЗ СОБЫТИЯ (pool_coin/pool_pc) -- это те самые числа, по
    которым считала программа, поэтому сверка проверяет ФОРМУЛУ, а не чтение
    состояния. Отдельно считается, что было бы, если считать по БАЛАНСАМ ХРАНИЛИЩ
    той же транзакции: формально резерв это баланс минус need_take_pnl, и разница
    между двумя способами -- то самое число, ради которого счёт пула не читается.
    """
    из_ = {"ok": False, "why_not": None}
    ев = событие_свопа(tx, вход=(tpl or {}).get("arg0"))
    if ев is None:
        из_["why_not"] = "события ray_log этого свопа в логах нет"
        return из_
    pc_в_coin = (ев["направление"] == НАПРАВЛЕНИЕ_PC_В_COIN)
    р_вх = ев["pool_pc"] if pc_в_coin else ев["pool_coin"]
    р_вых = ев["pool_coin"] if pc_в_coin else ев["pool_pc"]
    try:
        q = выход_по_резервам(р_вх, р_вых, ев["amount_in"])
    except Exception as exc:  # noqa: BLE001
        из_["why_not"] = f"формула не посчиталась: {type(exc).__name__}: {exc}"
        return из_
    из_.update(ok=(q["выход"] == ев["выход"]), наш=q["выход"], факт=ев["выход"],
                разница=q["выход"] - ев["выход"], направление=ев["направление"],
                аргументы_совпали=(ев["amount_in"] == (tpl or {}).get("arg0")
                                    and ев["minimum_out"] == (tpl or {}).get("arg1")))
    # А ЕСЛИ СЧИТАТЬ ПО БАЛАНСАМ ХРАНИЛИЩ (как это и делает котировка на цепи)?
    б = резервы_из_балансов(tx, tpl)
    if б.get("ok"):
        р_вх_б = б["pc"] if pc_в_coin else б["coin"]
        р_вых_б = б["coin"] if pc_в_coin else б["pc"]
        try:
            q2 = выход_по_резервам(р_вх_б, р_вых_б, ев["amount_in"])
            из_["по_балансам"] = q2["выход"]
            из_["по_балансам_отклонение_пп"] = (
                round((q2["выход"] - ев["выход"]) / ев["выход"] * 100, 6)
                if ев["выход"] else None)
        except Exception:  # noqa: BLE001
            pass
    return из_


def цена_из_состояния(tx: dict, tpl: dict, *, rpc_call=None,
                       сейчас: float | None = None) -> dict:
    """Цена по ЗАПИСАННОМУ СОСТОЯНИЮ против фактического выхода следующей сделки.

    ЗАЧЕМ ОТДЕЛЬНО ОТ сверки по событию. Та проверяет ФОРМУЛУ: берёт резервы из
    события той же сделки, то есть ровно те числа, по которым считала программа.
    Здесь проверяется ЧТЕНИЕ СОСТОЯНИЯ: резервы берутся из счетов пула и хранилищ
    в слоте S, а сравниваются с выходом сделки, случившейся ПОЗЖЕ. Совпадения до
    единицы тут быть не обязано -- между чтением и сделкой пул мог двинуться, -- и
    поэтому наружу идёт ОТКЛОНЕНИЕ, а не «сошлось/не сошлось».

    Три варианта резерва считаются рядом, чтобы выбор был измерен, а не заявлен:
    по балансам хранилищ, баланс минус need_take_pnl (как считает программа) и по
    резервам из события (эталон формулы).
    """
    из_ = {"ok": False, "why_not": None}
    ев = событие_свопа(tx, вход=(tpl or {}).get("arg0"))
    if ев is None:
        из_["why_not"] = "события ray_log этой сделки в логах нет"
        return из_
    if rpc_call is None:
        из_["why_not"] = "состояния нет: узел не подан"
        return из_
    счета = list((tpl or {}).get("accounts") or [])
    if len(счета) < РАСКЛАДКА["счетов"]:
        из_["why_not"] = "раскладка шаблона не опознана"
        return из_
    пул = счета[РАСКЛАДКА["пул"]]
    х_coin = счета[РАСКЛАДКА["хранилище_coin"]]
    х_pc = счета[РАСКЛАДКА["хранилище_pc"]]
    ч = _счета(rpc_call, [пул, х_coin, х_pc])
    if not ч["ok"]:
        из_["why_not"] = f"состояние не прочитано: {ч['why_not']}"
        return из_
    р_coin = разобрать_хранилище(ч["данные"].get(х_coin), ждём_владельца=РАСПОРЯДИТЕЛЬ)
    р_pc = разобрать_хранилище(ч["данные"].get(х_pc), ждём_владельца=РАСПОРЯДИТЕЛЬ)
    if not р_coin["ok"] or not р_pc["ok"]:
        из_["why_not"] = (f"хранилища не разобраны: "
                           f"{р_coin.get('why_not') or р_pc.get('why_not')}")
        return из_
    рп = разобрать_пул(ч["данные"].get(пул), ждём_хранилища=(х_coin, х_pc),
                        минты_хранилищ={х_coin: р_coin["минт"], х_pc: р_pc["минт"]})
    if not рп["ok"]:
        из_["why_not"] = f"счёт пула: {рп['why_not']}"
        return из_
    из_.update(status=рп["status"], ставка_пула=(рп["fee_num"], рп["fee_den"]),
                pnl=(рп["pnl_coin"], рп["pnl_pc"]))
    pc_в_coin = (ев["направление"] == НАПРАВЛЕНИЕ_PC_В_COIN)
    вх_бал, вых_бал = ((р_pc["сумма"], р_coin["сумма"]) if pc_в_coin
                        else (р_coin["сумма"], р_pc["сумма"]))
    вх_pnl, вых_pnl = ((рп["pnl_pc"], рп["pnl_coin"]) if pc_в_coin
                        else (рп["pnl_coin"], рп["pnl_pc"]))
    варианты = {
        "по_балансам": (вх_бал, вых_бал),
        "минус_pnl": (вх_бал - вх_pnl, вых_бал - вых_pnl),
        "по_логу": ((ев["pool_pc"], ев["pool_coin"]) if pc_в_coin
                     else (ев["pool_coin"], ев["pool_pc"])),
    }
    факт = int(ев["выход"])
    из_["факт"] = факт
    для_сравнения = {}
    for имя, (r_in, r_out) in варианты.items():
        try:
            q = выход_по_резервам(r_in, r_out, int(ев["amount_in"]),
                                  числитель=рп["fee_num"], знаменатель=рп["fee_den"])
        except Exception as exc:  # noqa: BLE001
            для_сравнения[имя] = {"ok": False, "why_not": f"{type(exc).__name__}"}
            continue
        для_сравнения[имя] = {
            "ok": True, "наш": q["выход"], "до_единицы": q["выход"] == факт,
            "отклонение_%": (round((q["выход"] - факт) / факт * 100, 6)
                              if факт else None)}
    из_.update(ok=True, варианты=для_сравнения)
    return из_


