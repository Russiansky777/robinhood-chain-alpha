def _счета(rpc_call, адреса: list, *, таймаут: float = 3.0) -> dict:
    """getMultipleAccounts ОДНИМ запросом: адрес -> сырые байты (или None)."""
    из_ = {"ok": False, "данные": {}, "why_not": None, "slot": None, "мс": None}
    т0 = time.perf_counter()
    try:
        о = rpc_call("getMultipleAccounts",
                      [адреса, {"encoding": "base64", "commitment": "confirmed"}])
    except Exception as exc:  # noqa: BLE001
        из_["why_not"] = f"{type(exc).__name__}: {str(exc)[:120]}"
        из_["мс"] = round((time.perf_counter() - т0) * 1000.0, 2)
        return из_
    из_["мс"] = round((time.perf_counter() - т0) * 1000.0, 2)
    о = о if isinstance(о, dict) else {}
    рез = о.get("result") if "result" in о else о
    if not isinstance(рез, dict):
        из_["why_not"] = f"ответ узла не разобран: {str(о)[:120]}"
        return из_
    из_["slot"] = ((рез.get("context") or {}).get("slot")
                    if isinstance(рез.get("context"), dict) else None)
    значения = рез.get("value")
    if not isinstance(значения, list) or len(значения) != len(адреса):
        из_["why_not"] = "узел вернул не столько счетов, сколько спрашивали"
        return из_
    import base64  # noqa: PLC0415

    for адрес, зн in zip(адреса, значения):
        if not зн:
            из_["данные"][адрес] = None
            continue
        д = (зн.get("data") or [None, None])[0]
        try:
            из_["данные"][адрес] = base64.b64decode(д) if д else None
        except Exception:  # noqa: BLE001
            из_["данные"][адрес] = None
    из_["ok"] = True
    return из_


# Токеновый счёт SPL: mint 0..32, owner 32..64, amount 64..72 (little-endian) --
# это ABI программы токена, а не догадка. Но читаем со СТОРОЖЕМ: разобранный минт
# и владелец обязаны совпасть с ожидаемыми, иначе смещение не то, и тогда отказ, а
# не тихое число. Ошибка в смещении без сторожа дала бы «резерв», а с ним --
# завышенный минимум выхода и откат на каждой попытке.
ДЛИНА_ТОКЕНОВОГО_СЧЁТА = 165


def разобрать_хранилище(данные: bytes, *, ждём_минт: str | None = None,
                         ждём_владельца: str | None = None) -> dict:
    из_ = {"ok": False, "why_not": None}
    if not данные or len(данные) < 72:
        из_["why_not"] = f"счёт короче токенового ({0 if not данные else len(данные)} байт)"
        return из_
    B = _кирпичи()
    минт = B.b58encode(данные[0:32])
    владелец = B.b58encode(данные[32:64])
    сумма = int.from_bytes(данные[64:72], "little")
    if ждём_минт and минт != ждём_минт:
        из_["why_not"] = (f"минт хранилища прочитан как {минт[:8]}, а ждали "
                           f"{ждём_минт[:8]} -- смещения не те")
        return из_
    if ждём_владельца and владелец != ждём_владельца:
        из_["why_not"] = (f"владелец хранилища прочитан как {владелец[:8]}, а ждали "
                           f"{ждём_владельца[:8]} -- смещения не те")
        return из_
    return {"ok": True, "минт": минт, "владелец": владелец, "сумма": сумма,
            "длина": len(данные)}


