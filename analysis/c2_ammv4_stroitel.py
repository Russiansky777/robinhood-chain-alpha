def шаблон(tx: dict, пул: str | None = None, *,
            хранилище: str | None = None) -> dict:
    """Шаблон инструкции SwapBaseInV2 из транзакции источника.

    Вид -- по ТЕГУ (первый байт), а не по числу счетов: у V1 и V2 они разные, и
    ошибка здесь подставила бы наш кошелёк на место счёта рынка OpenBook.

    хранилище -- АДРЕС ХРАНИЛИЩА ПУЛА, а не пула: полоса адреса пула не знает, у
    неё на руках только хранилище (C.identify_pool). Без этого на сделке РОУТЕРА,
    где инструкций этой программы несколько, брался бы ПЕРВЫЙ пул -- то есть
    чужой. У AMM v4 это не редкость: все 22 живые инструкции в данных пришли
    именно из транзакций роутеров.
    """
    из_ = {"ok": False, "why_not": None}
    B = _кирпичи()
    for их in B.all_instructions(tx):
        if (их.get("programId") or их.get("program")) != ПРОГРАММА:
            continue
        счета = list(их.get("accounts") or [])
        try:
            данные = B.b58decode(их.get("data") or "")
        except Exception:  # noqa: BLE001
            continue
        тег = тег_инструкции(данные)
        if тег is None:
            continue
        if тег != ТЕГ_V2_ВХОД:
            из_["why_not"] = (
                f"у источника инструкция с тегом {тег}"
                + (f" ({ИМЕНА_ТЕГОВ[тег]})" if тег in ИМЕНА_ТЕГОВ else "")
                + ": раскладка и аргументы у неё другие, живых сделок с ней в "
                  "данных нет -- собирается только swap_base_in_v2 (тег 16)")
            continue
        if len(счета) != РАСКЛАДКА["счетов"]:
            из_["why_not"] = (f"тег 16, а счетов {len(счета)}: по исходнику и по 22 "
                               f"живым сделкам их {РАСКЛАДКА['счетов']}")
            continue
        if len(данные) != ДЛИНА_ДАННЫХ:
            из_["why_not"] = (f"данных {len(данные)} байт, по живым сделкам их "
                               f"{ДЛИНА_ДАННЫХ} (тег + два u64)")
            continue
        # ПОСТОЯННЫЕ СЧЕТА ПРОГРАММЫ ОБЯЗАНЫ СТОЯТЬ НА СВОИХ МЕСТАХ. Не стоят --
        # это не та раскладка, и подставлять в неё свой кошелёк нельзя.
        if счета[РАСКЛАДКА["программа_токена"]] != SPL_ТОКЕН:
            из_["why_not"] = (f"на месте 0 не SPL Token ({счета[0][:8]}) -- у "
                               f"раскладки V2 программа токена одна и она classic")
            continue
        if счета[РАСКЛАДКА["распорядитель"]] != РАСПОРЯДИТЕЛЬ:
            из_["why_not"] = (f"на месте 2 не распорядитель хранилищ AMM v4 "
                               f"({счета[2][:8]})")
            continue
        мой_пул = счета[РАСКЛАДКА["пул"]]
        if пул and мой_пул != пул:
            continue
        if хранилище and хранилище not in счета:
            continue
        arg0, arg1 = struct.unpack_from("<QQ", данные, 1)
        return {"ok": True, "program": ПРОГРАММА, "вид": ИМЕНА_ТЕГОВ[ТЕГ_V2_ВХОД],
                "ix": ИМЕНА_ТЕГОВ[ТЕГ_V2_ВХОД], "тег": тег,
                "accounts": счета, "data": данные, "arg0": arg0, "arg1": arg1,
                "writable": B.writable_map(tx), "пул": мой_пул,
                "хранилище_coin": счета[РАСКЛАДКА["хранилище_coin"]],
                "хранилище_pc": счета[РАСКЛАДКА["хранилище_pc"]],
                "хвост_источника": b""}
    из_["why_not"] = из_["why_not"] or (
        "инструкции swap_base_in_v2 AMM v4"
        + (f" по пулу {пул}" if пул else "")
        + (f" со хранилищем {хранилище}" if хранилище else "")
        + " в транзакции нет")
    return из_


def стороны(tpl: dict, tx: dict) -> dict:
    """Минты и программы токенов сторон coin и pc -- ИЗ БАЛАНСОВ транзакции.

    В инструкции V2 минтов нет вовсе (их восемь мест -- это программа, пул,
    распорядитель, два хранилища и три наших), поэтому минт каждой стороны
    берётся по её ХРАНИЛИЩУ из балансов сделки источника. Это факт цепи, а не
    догадка: хранилище и его минт стоят в одной строке баланса.
    """
    из_ = {"ok": False, "why_not": None}
    import c2_common as C  # noqa: PLC0415

    счета = tpl["accounts"]
    х_coin = счета[РАСКЛАДКА["хранилище_coin"]]
    х_pc = счета[РАСКЛАДКА["хранилище_pc"]]
    строки = {с["account"]: с for с in C.token_rows(tx).values()}
    с_coin, с_pc = строки.get(х_coin), строки.get(х_pc)
    if not с_coin or not с_pc:
        из_["why_not"] = "хранилищ пула нет в балансах транзакции"
        return из_
    программы = {}
    for когда in ("preTokenBalances", "postTokenBalances"):
        for б in ((tx.get("meta") or {}).get(когда) or []):
            if isinstance(б, dict) and б.get("mint"):
                программы.setdefault(б["mint"], б.get("programId"))
    минт_coin, минт_pc = с_coin.get("mint"), с_pc.get("mint")
    if not минт_coin or not минт_pc:
        из_["why_not"] = "минты сторон пула не восстановились"
        return из_
    return {"ok": True, "минт_coin": минт_coin, "минт_pc": минт_pc,
            "программа_coin": программы.get(минт_coin) or SPL_ТОКЕН,
            "программа_pc": программы.get(минт_pc) or SPL_ТОКЕН,
            "хранилище_coin": х_coin, "хранилище_pc": х_pc,
            "резерв_coin_до": с_coin["pre"], "резерв_pc_до": с_pc["pre"],
            "движение_coin": с_coin["post"] - с_coin["pre"],
            "движение_pc": с_pc["post"] - с_pc["pre"]}


