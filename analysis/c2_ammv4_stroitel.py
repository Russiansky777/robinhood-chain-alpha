BASIS_POINT_MAX = 10_000


def налог_назван(налог) -> bool:
    if not isinstance(налог, (tuple, list)) or not налог:
        return False
    try:
        return int(налог[0]) >= 0
    except (TypeError, ValueError):
        return False


def без_налога(сумма: int, bps: int | None, максимум: int | None) -> int:
    """Сумма после налога перевода Token-2022: fee = ceil(amount*bps/10000), с
    потолком. У раскладки V2 Token-2022 быть не может (программа токена одна), и
    строитель на такой стороне отказывает; функция оставлена для единого вида с
    прочими строителями и для проверки самого правила."""
    if not bps:
        return int(сумма)
    fee = -(-int(сумма) * int(bps) // BASIS_POINT_MAX)
    if максимум is not None:
        fee = min(fee, int(максимум))
    return max(0, int(сумма) - fee)


