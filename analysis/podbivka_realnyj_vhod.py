#!/usr/bin/env python3
"""Калиброванный прогон архива с РЕАЛЬНЫМ входом: можно ли ставить 1-2 SOL (задача 08.10).

Главный вопрос владельца: не удача ли ядро (lane_s0, cand2_03/DsqRyTUh) -- и где доказано
на большом числе ретро-сделок, что билет 1-2 SOL держится. Поэтому архив считается не
идеальным входом, а нашим:

п.2 РЕАЛЬНЫЙ ВХОД. Распределение посадки берётся из живых сделок (`podbivka_zhivye`):
доли S+0/S+1/S+2 по типу пула и по размеру покупки источника. Для каждого сигнала итог --
взвешенная сумма по этим долям, а не «лучшее место». Допуск по цене -- как в бою: если от
состояния сразу после сделки источника (S0) до нашего места цена ушла больше допуска
группы, сделки нет (в бою это отказ 6040/6042), и ветка даёт минус комиссию.

п.1 КАЛИБРОВКА. Множитель наценки выхода `к_g` и издержки круга -- из
`data/podbivka/kalibrovka.json` (там же остаточное расхождение по группам).

п.3 ПРОГОН. Билеты 0.5 / 1 / 2 SOL; сдвиг цены считается от РЕАЛЬНОГО резерва пула на
каждой сделке (он в состояниях входа). Подбор -- первые 2/3 суток, проверка -- последняя
треть, не меньше 4 суток. По каждому источнику с n >= 50: n, итог по билетам, медиана,
доля в плюсе, итог без 5 лучших, обе половины проверки, SOL в сутки, худшие сутки.

п.4 ПОПРАВКА НА УДАЧУ. Внутри каждых суток проверки метки источников перемешиваются
(n источника по суткам сохраняется, связь «источник -> исход» разрывается), 200 раз.
Сколько источников проходит порог случайно -- и какова доля перестановок, где случайный
источник того же объёма даёт итог не хуже настоящего.

п.5 ПОРОГ «можно 1-2 SOL»: на проверке n >= 100, медиана > 0, итог без 5 лучших > 0,
обе половины проверки в плюсе, выше уровня случайности, худшие сутки не хуже -2 SOL.

Выход: data/podbivka/realnyj_vhod.json, docs/podbivka_<метка>_realnyj_vhod.md.
Только чтение. Ничего не меняется и не рекомендуется -- решает владелец.
"""
