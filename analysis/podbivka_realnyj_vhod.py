def посадка_из_живых(сделки: list, кэш_путь=None) -> dict:
    """Доли S+0/S+1/S+2 и число чужих свопов в нашем слоте -- из живых сделок."""
    по_подписи = collections.defaultdict(list)
    for с in сделки:
        if с.get("source_sig") and с.get("s_plus") in (0, 1, 2):
            по_подписи[с["source_sig"]].append(с)
    сигналы = {}
    for р in O.сигналы(фильтр=lambda r: r.get("подпись") in по_подписи, путь=кэш_путь):
        сигналы[р["подпись"]] = р
    ряды = []
    for sig, сдс in по_подписи.items():
        р = сигналы.get(sig)
        for с in сдс:
            ряды.append({"s_plus": с["s_plus"], "пул": (р or {}).get("пул") or с.get("pool_program"),
                         "размер": корзина_размера((р or {}).get("sol")),
                         "есть_сигнал": р is not None,
                         "свопов_s1": ((р or {}).get("свопов") or {}).get("s1"),
                         "свопов_s2": ((р or {}).get("свопов") or {}).get("s2"),
                         "место_в_блоке": (с.get("our_block_index") or 0) - (с.get("source_block_index") or 0)
                         if с.get("our_block_index") is not None and с.get("source_block_index") is not None
                         else None,
                         "группа": с.get("group")})

    def доли(ч: list) -> dict | None:
        if not ч:
            return None
        c = collections.Counter(x["s_plus"] for x in ч)
        n = len(ч)
        return {"n": n, **{f"S+{k}": round(c[k] / n, 4) for k in (0, 1, 2)}}

    из_ = {"всего": доли(ряды), "по_пулу": {}, "по_размеру": {}, "по_пулу_и_размеру": {},
           "свопов_в_слоте": {}, "место_в_блоке": {}}
    for п in sorted({x["пул"] for x in ряды if x["пул"]}):
        из_["по_пулу"][п] = доли([x for x in ряды if x["пул"] == п])
    for р_ in sorted({x["размер"] for x in ряды}):
        из_["по_размеру"][р_] = доли([x for x in ряды if x["размер"] == р_])
    for п in sorted({x["пул"] for x in ряды if x["пул"]}):
        for р_ in sorted({x["размер"] for x in ряды}):
            ч = [x for x in ряды if x["пул"] == п and x["размер"] == р_]
            if len(ч) >= 20:
                из_["по_пулу_и_размеру"][f"{п}|{р_}"] = доли(ч)
    for поле in ("свопов_s1", "свопов_s2"):
        v = [x[поле] for x in ряды if x.get(поле) is not None]
        из_["свопов_в_слоте"][поле] = {"n": len(v), "медиана": statistics.median(v) if v else None,
                                       "среднее": round(statistics.mean(v), 2) if v else None,
                                       "ноль_доля": round(100 * sum(1 for y in v if y == 0) / len(v))
                                       if v else None} if v else None
    мб = [x["место_в_блоке"] for x in ряды if x.get("место_в_блоке") is not None and x["s_plus"] == 0]
    из_["место_в_блоке"] = {"n": len(мб), "медиана": statistics.median(мб) if мб else None,
                            "за_источником_доля": round(100 * sum(1 for y in мб if y > 0) / len(мб))
                            if мб else None}
    return из_


def веса(посадка: dict, пул: str, размер: str) -> dict:
    """Доли посадки для сигнала: пул+размер, иначе пул, иначе размер, иначе всего."""
    for ключ, где in ((f"{пул}|{размер}", "по_пулу_и_размеру"), (пул, "по_пулу"), (размер, "по_размеру")):
        v = (посадка.get(где) or {}).get(ключ)
        if v and v.get("n", 0) >= 20:
            return v
    return посадка["всего"]


