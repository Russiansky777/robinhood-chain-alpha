def цена(сост) -> float | None:
    if not сост:
        return None
    x, y = float(сост[0]), float(сост[1])
    return x / y if y else None


def итог_сигнала(р: dict, б: float, выход: int, w: dict, допуск: float,
                 издержки: float, к_g: float) -> dict | None:
    """Итог по сигналу с реальным входом: взвешенная сумма ветвей S+0/S+1/S+2 с допуском."""
    вх = р.get("вход") or {}
    p0 = цена(вх.get("S0")) or цена(вх.get("S0_дно"))
    сумма, вес_всего, отказов, ветки = 0.0, 0.0, 0.0, {}
    for k in (0, 1, 2):
        wk = w.get(f"S+{k}") or 0.0
        if wk <= 0:
            continue
        место = МЕСТА[k]
        pк = цена(вх.get(место))
        if pк is None:
            continue
        if p0 and допуск is not None and (pк / p0 - 1) > допуск:
            ветки[место] = -ОТКАЗ_SOL
            сумма += wk * (-ОТКАЗ_SOL)
            отказов += wk
            вес_всего += wk
            continue
        д = B.сделка_по_состояниям(O.как_сигнал(р), б, место, выход,
                                   издержки=издержки, к_g=к_g)
        if д is None:
            continue
        ветки[место] = д["итог_sol"]
        сумма += wk * д["итог_sol"]
        вес_всего += wk
    if вес_всего <= 0:
        return None
    return {"итог_sol": сумма / вес_всего, "отказов_доля": отказов / вес_всего, "ветки": ветки}


def прогон(посадка: dict, выход: int, издержки: float, к_g: float, кэш_путь=None) -> tuple:
    """Плоские ряды: источник, сутки, итог по каждому билету. Один проход по кэшу."""
    счёт = collections.Counter()
    ряды = []
    for р in O.сигналы(путь=кэш_путь):
        счёт["всего"] += 1
        if р.get("quoteMint") != O.WSOL:
            счёт["не_wsol"] += 1
            continue
        if not р.get("первая"):
            счёт["не_первая"] += 1
            continue
        if (р.get("sol") or 0) < 2.0:
            счёт["ниже_2_sol"] += 1
            continue
        вх = р.get("вход") or {}
        if not вх or not (р.get("выход") or {}).get(str(выход)):
            счёт["нет_состояний"] += 1
            continue
        w = веса(посадка, р.get("пул"), корзина_размера(р.get("sol")))
        строка = {"ист": р.get("ист"), "сутки": O.сутки(р), "пул": р.get("пул"),
                  "минт": р.get("минт"), "sol": р.get("sol"), "резерв_sol": р.get("резерв_sol"),
                  "итоги": {}, "отказы": {}}
        ок = False
        for б in БИЛЕТЫ:
            v = итог_сигнала(р, б, выход, w, ДОПУСК_ПО_УМОЛЧАНИЮ, издержки, к_g)
            if v is not None:
                строка["итоги"][б] = v["итог_sol"]
                строка["отказы"][б] = v["отказов_доля"]
                ок = True
        if not ок:
            счёт["нет_итога"] += 1
            continue
        счёт["в_счёте"] += 1
        ряды.append(строка)
    return ряды, dict(счёт)


def свод(ряды: list, б: float) -> dict:
    v = [x["итоги"][б] for x in ряды if б in x["итоги"]]
    if not v:
        return {"n": 0}
    верх = sorted(v, reverse=True)
    по_суткам: dict = collections.defaultdict(float)
    for x in ряды:
        if б in x["итоги"]:
            по_суткам[x["сутки"]] += x["итоги"][б]
    суток = len(по_суткам) or 1
    лучшие_сутки = max(по_суткам.values()) if по_суткам else 0.0
    return {"n": len(v), "суток": суток, "итог_sol": round(sum(v), 6),
            "итог_без_лучших_суток_sol": round(sum(v) - лучшие_сутки, 6),
            "доля_лучших_суток": round(100 * лучшие_сутки / sum(v), 1) if sum(v) > 0 else None,
            "минтов": len({x.get("минт") for x in ряды if б in x["итоги"] and x.get("минт")}),
            "медиана_sol": round(statistics.median(v), 6),
            "медиана_пп": round(100 * statistics.median(v) / б, 3),
            "в_плюсе": round(100 * sum(1 for y in v if y > 0) / len(v), 1),
            "итог_без_5_лучших_sol": round(sum(верх[5:]), 6) if len(верх) > 5 else None,
            "sol_в_сутки": round(sum(v) / суток, 6),
            "худшие_сутки_sol": round(min(по_суткам.values()), 6),
            "отказов_доля": round(100 * statistics.mean(
                [x["отказы"][б] for x in ряды if б in x.get("отказы", {})]), 1)
            if any(б in x.get("отказы", {}) for x in ряды) else None}


def проходит(пров: dict, половины: tuple, уровень_удачи: float | None) -> tuple:
    """Порог владельца (п.5). Возвращает (да/нет, список причин отказа)."""
    нет = []
    if пров.get("n", 0) < N_МИН_ПРОВЕРКА:
        нет.append(f"n на проверке {пров.get('n', 0)} < {N_МИН_ПРОВЕРКА}")
    if (пров.get("медиана_sol") or 0) <= 0:
        нет.append("медиана не больше нуля")
    if (пров.get("итог_без_5_лучших_sol") is None
            or пров["итог_без_5_лучших_sol"] <= 0):
        нет.append("без 5 лучших не в плюсе")
    for имя, п in zip(("первая половина проверки", "вторая половина проверки"), половины):
        if not п or (п.get("итог_sol") or 0) <= 0:
            нет.append(f"{имя} не в плюсе")
    if (пров.get("худшие_сутки_sol") or 0) < ХУДШИЕ_СУТКИ_ПРЕДЕЛ:
        нет.append(f"худшие сутки {пров.get('худшие_сутки_sol'):.2f} хуже {ХУДШИЕ_СУТКИ_ПРЕДЕЛ}")
    if уровень_удачи is not None and уровень_удачи > 0.05:
        нет.append(f"не выше уровня случайности (p={уровень_удачи:.3f})")
    return (not нет), нет


def строгий(подб: dict, пров: dict, половины: tuple) -> tuple:
    """Добавка подбивки к порогу: от чего порог владельца не защищает.

    Порог п.5 смотрит суммы по половинам проверки -- источник может пройти его, будучи
    плоским на подборе и собрав всё в одни сутки. Эти три условия закрывают дыру:
    подбор тоже должен держаться без пяти лучших сделок, проверка -- без лучших суток,
    и медиана должна быть выше нуля в обеих половинах проверки.
    """
    нет = []
    if (подб.get("итог_без_5_лучших_sol") or 0) <= 0:
        нет.append("подбор без 5 лучших не в плюсе")
    if (пров.get("итог_без_лучших_суток_sol") or 0) <= 0:
        нет.append("проверка без лучших суток не в плюсе")
    for имя, п in zip(("первая половина", "вторая половина"), половины):
        if not п or (п.get("медиана_пп") or 0) <= 0:
            нет.append(f"{имя} проверки: медиана не больше нуля")
    return (not нет), нет


