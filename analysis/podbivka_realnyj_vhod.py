def корзина_размера(sol) -> str:
    s = float(sol or 0)
    for н, в in РАЗМЕР_КОРЗИНЫ:
        if н <= s < в:
            return f"{н}-{'∞' if в > 1e8 else int(в)}"
    return "?"


