def перестановки(ряды_пров: list, б: float, повторов: int, метка: dict | None = None,
                 seed: int = 20261008) -> dict:
    """Метки перемешиваются внутри суток; n метки по суткам сохраняется.

    `метка` -- карта «источник -> метка» (например, группа); без неё метка -- сам источник.
    """
    по_суткам: dict = collections.defaultdict(list)
    for x in ряды_пров:
        if б not in x["итоги"]:
            continue
        м = x["ист"] if метка is None else метка.get(x["ист"])
        if м is None:
            continue
        по_суткам[x["сутки"]].append((м, x["итоги"][б]))
    настоящие: dict = collections.defaultdict(list)
    for д, пары in по_суткам.items():
        for a, v in пары:
            настоящие[a].append((д, v))
    рнд = random.Random(seed)
    превзошли: dict = collections.Counter()
    прошедших = []
    for _ in range(повторов):
        смесь: dict = collections.defaultdict(list)
        for д, пары in по_суткам.items():
            метки = [a for a, _ in пары]
            исходы = [v for _, v in пары]
            рнд.shuffle(метки)
            for a, v in zip(метки, исходы):
                смесь[a].append((д, v))
        прошло = 0
        for a, ряд in смесь.items():
            v = [x[1] for x in ряд]
            # p-значение считается ВСЕМ источникам, а не только прошедшим порог по n:
            # иначе у источника с n < предела «превзошли» остаётся нулём и p выходит
            # ложно значимым (1/(повторов+1)).
            if a in настоящие and sum(v) >= sum(y for _, y in настоящие[a]):
                превзошли[a] += 1
            if len(v) < N_МИН_ПРОВЕРКА:
                continue
            верх = sorted(v, reverse=True)
            по_д: dict = collections.defaultdict(float)
            for д, y in ряд:
                по_д[д] += y
            дни = sorted(по_д)
            п1 = sum(по_д[д] for д in дни[:len(дни) // 2])
            п2 = sum(по_д[д] for д in дни[len(дни) // 2:])
            ок = (statistics.median(v) > 0 and sum(верх[5:]) > 0 and п1 > 0 and п2 > 0
                  and min(по_д.values()) >= ХУДШИЕ_СУТКИ_ПРЕДЕЛ)
            if ок:
                прошло += 1
        прошедших.append(прошло)
    настоящих_прошло = None
    return {"повторов": повторов, "билет": б,
            "прошедших_случайно": {"среднее": round(statistics.mean(прошедших), 2),
                                   "медиана": statistics.median(прошедших),
                                   "p95": sorted(прошедших)[int(0.95 * (повторов - 1))],
                                   "максимум": max(прошедших)},
            "p_по_источникам": {a: round((превзошли[a] + 1) / (повторов + 1), 4)
                                for a in настоящие},
            "настоящих_прошло": настоящих_прошло}


