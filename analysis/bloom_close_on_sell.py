# Тариф сети за нашу транзакцию закрытия: одна подпись = 5 000 лампортов.
ТАРИФ_ЛАМПОРТЫ = 5_000
# Закрываем только если возврат заметно больше тарифа. 50 000 -- это десять
# тарифов: при ренте 2 039 280 запас громадный, а мусорный счёт на 6 000
# лампортов закрывать не станем.
ПОРОГ_ВЫГОДЫ_ЛАМПОРТЫ = 50_000
ОЖИДАНИЕ_S = 25.0


def включено() -> bool:
    return (os.environ.get("BLOOM_CLOSE_ON_SELL") or "0").strip() == "1"


def счета_минта(кошелёк: str, минт: str) -> list:
    """Адреса наших счетов этого минта: ATA для обеих программ токена."""
    из_ = []
    try:
        import c2_swap_build as B  # noqa: PLC0415
        for программа in (B.TOKEN_PROGRAM, C.TOKEN_2022 if hasattr(C, "TOKEN_2022")
                          else "TokenzQdBNbLqP5VEhdkAS6EPFLC1PHnBqCXEpPxuEb"):
            а = B.ata(кошелёк, минт, программа)
            if а and а not in из_:
                из_.append(а)
    except Exception:  # noqa: BLE001
        return []
    return из_


def выгодно(вернётся_лампортов: int) -> tuple:
    """(да, почему_нет). Закрытие обязано возвращать больше, чем стоит."""
    if вернётся_лампортов <= ТАРИФ_ЛАМПОРТЫ:
        return False, (f"вернётся {вернётся_лампортов} лампортов при тарифе "
                       f"{ТАРИФ_ЛАМПОРТЫ} -- закрытие в убыток")
    if вернётся_лампортов < ПОРОГ_ВЫГОДЫ_ЛАМПОРТЫ:
        return False, (f"вернётся всего {вернётся_лампортов} лампортов -- ниже порога "
                       f"{ПОРОГ_ВЫГОДЫ_ЛАМПОРТЫ}")
    return True, None


def годные_счета(чтение: dict, кошелёк: str) -> tuple:
    """(годные, отказы). Путь продажи не трогает завёрнутый SOL."""
    годные, отказы = [], []
    for с in (чтение.get("счета") or []):
        if с.get("is_native"):
            отказы.append({**с, "why_not": "счёт WSOL: этим путём не закрываем"})
            continue
        ок, почему = C.подходит_для_закрытия(с, кошелёк)
        (годные if ок else отказы).append(с if ок else {**с, "why_not": почему})
    return годные, отказы


def нет_открытой_позиции(минт: str, состояние=None) -> tuple:
    """(можно, почему_нет). Нет ли ОТКРЫТОЙ позиции с этим же минтом.

    ЗАЧЕМ. Путь закрытия при продаже идёт ПОСРЕДИ торговли -- общего окна «без
    покупок» у него нет и быть не может. Вместо окна здесь стоит узкая
    проверка: счёт этого минта закрывается только если ни одна ОТКРЫТАЯ
    позиция его не держит. Иначе закрытие сломало бы живую сделку, а не
    вернуло ренту.

    НЕЗНАНИЕ -- ЗАПРЕТ: журнал не прочитался -- отказ, а не "позиций нет".
    """
    if not минт:
        return False, "минт не известен -- закрывать нельзя"
    try:
        import bloom_exec_state as ST  # noqa: PLC0415

        сост = состояние if состояние is not None else ST.ExecState()
        открытые = сост.open_positions()
    except Exception as exc:  # noqa: BLE001
        return False, (f"открытые позиции не прочитать ({type(exc).__name__}) "
                        "-- закрывать счёт нельзя")
    свои = [p for p in (открытые or [])
            if str((p or {}).get("mint") or "") == str(минт)]
    if свои:
        return False, (f"открытых позиций с этим минтом {len(свои)}: счёт живой "
                        "сделки не закрываем")
    return True, ""


def закрыть_после_продажи(rpc, кошелёк: str, минт: str, *,
                          подпись_продажи: str | None = None,
                          ждать_s: float = ОЖИДАНИЕ_S) -> dict:
    """Закрыть пустой счёт минта и вернуть ренту. Сеть трогает только по флагу.

    Возвращает словарь для записи в позицию. Любой отказ -- словами, без
    исключений наружу: провал закрытия не должен мешать закрытию ПОЗИЦИИ.
    """
    из_ = {"ok": False, "why_not": None, "mint": минт, "wallet": кошелёк,
           "sell_signature": подпись_продажи, "signature": None,
           "rent_returned_sol": None, "accounts_closed": 0,
           "checked_accounts": [], "utc": time.strftime("%Y-%m-%dT%H:%M:%SZ",
                                                        time.gmtime())}
    if not включено():
        из_["why_not"] = "путь выключен (BLOOM_CLOSE_ON_SELL не равен 1)"
        return из_
    адреса = счета_минта(кошелёк, минт)
    из_["checked_accounts"] = адреса
    if not адреса:
        из_["why_not"] = "адреса счетов минта не выведены (нет solders?)"
        return из_
    try:
        чтение = C.прочитать_счета(rpc, адреса, кошелёк)
    except Exception as exc:  # noqa: BLE001
        из_["why_not"] = f"счета не прочитаны ({type(exc).__name__})"
        return из_
    if чтение.get("why_not"):
        из_["why_not"] = чтение["why_not"]
        return из_
    годные, отказы = годные_счета(чтение, кошелёк)
    из_["refused"] = [{"account": о.get("account"), "why_not": о.get("why_not")}
                      for о in отказы]
    if not годные:
        из_["why_not"] = "годных к закрытию счетов нет"
        return из_
    вернётся = sum(C.вернётся_лампортов(с) for с in годные)
    да, почему = выгодно(вернётся)
    из_["rent_expected_sol"] = round(вернётся / ЛАМПОРТОВ_В_SOL, 9)
    if not да:
        из_["why_not"] = почему
        return из_
    ключ = C.ключ_кошелька(кошелёк)
    if not ключ.get("ok"):
        из_["why_not"] = ключ.get("why_not")
        return из_
    # УЗКАЯ ПРОВЕРКА ВМЕСТО ОКНА «БЕЗ ПОКУПОК» (слово владельца 03.10:
    # BLOOM_CLOSE_ON_SELL=1). Окно требует стоящего рубильника полосы, а
    # продажа идёт посреди торговли: с общим окном этот путь отказывал бы
    # каждый раз. Здесь вместо него -- три поимённых условия: не WSOL (выше),
    # счёт пуст и наш (выше), и ни одной открытой позиции с этим минтом.
    можно_мин, почему_мин = нет_открытой_позиции(минт)
    из_["open_position_check"] = почему_мин or "открытых позиций с этим минтом нет"
    if not можно_мин:
        из_["why_not"] = почему_мин
        return из_
    try:
        рез = C.закрыть_живьём(rpc, кошелёк, [годные], секрет=ключ["секрет"],
                               ждать_s=ждать_s,
                               путь_продажи=(f"продажа минта {str(минт)[:12]}: "
                                              "позиция закрыта, открытых с этим "
                                              "минтом нет"))
    except Exception as exc:  # noqa: BLE001
        из_["why_not"] = f"закрытие не прошло ({type(exc).__name__})"
        return из_
    шаг = (рез.get("шаги") or [{}])[0]
    из_["ok"] = bool(рез.get("ok"))
    из_["why_not"] = рез.get("why_not") or шаг.get("why_not")
    из_["signature"] = шаг.get("подпись")
    из_["accounts_closed"] = int(рез.get("закрыто_счетов") or 0)
    из_["rent_returned_sol"] = (round(int(рез.get("вернулось_лампортов") or 0)
                                      / ЛАМПОРТОВ_В_SOL, 9))
    return из_


