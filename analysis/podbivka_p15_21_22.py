#!/usr/bin/env python3
"""Подбивка: п.15, п.21, п.22 (владелец 27.09), офлайн.

п.15  Предсказание штаба 02:38 на 139 кошельках «досчитать» (koshelki_dos), выход +72:
      (1) «не продал»: усечённое S+0 > 0?  (2) разрыв S+0 − S+1 (среднее) >= 3 п.п.?
      (3) кошельки с долей «продал в окне» > 30 %: среднее S+1 (и S+0) < 0?
      Рядом те же числа на 404 проходе (а) -- для сравнения.
п.21  Вне окна отбора (второй проход, покупки раньше 24.09 00:00Z): корзины
      «кривая pump.fun + не продал + возраст токена >= 10 мин» и «возраст 10–60 мин»,
      S+0 и S+1: n / среднее / усечённое. Для сравнения -- те же корзины в окне.
п.22  Pump AMM: 20 первых покупок с наибольшим расхождением калиброванной доли
      траты f (x0·dy / ((y0 − dy)·spent), spent -- трата кошелька источника по
      балансам) с ожиданием по сборам события 0.988.
Усечённое -- без ceil(5 % n) лучших.
"""
from __future__ import annotations

import csv
import glob
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import podbivka_m4_svod as M  # noqa: E402
import podbivka_p5_p13 as P13  # noqa: E402
import podbivka_tablicy as T  # noqa: E402

КОРЕНЬ = T.КОРЕНЬ
ГРАНЬ_ОТБОРА = 1790208000
PUMP_AMM = "pAMMBay6oceH9fJKBRHGP5D4bD4sWpmSwMn52FMfXEA"
КРИВАЯ = "6EF8rrecthR5Dkzon8Nwu78hRvfCKubJ14M5uBEwF6P"
ОЖИДАНИЕ_F = 0.988  # LP 20 + протокол 5 + создатель 85–95 б.п. (ошибка 8)


def кошельки(кат: str) -> dict:
    из_ = {}
    for к in T.читать(T.каталог_задачи(кат)):
        а = (к.get("строка") or {}).get("address")
        if а and not к.get("why_not") and not (к.get("скан") or {}).get("why_not"):
            из_[а] = T.пересчёт_порога(к.get("покупки") or [], а)
    return из_


def ст(пп, e):
    return M.стат([P13.чп(п.get("sim"), e, 72) for п in пп])


def я(с):
    return (f"{с['n']} / {M.ф(с['ср'])} / {M.ф(с['ус'])}" if с.get("n") else "0 / — / —")


def п15(кош: dict) -> dict:
    не = [п for пп in кош.values() for п in пп if п.get("продал_в_окне") is False]
    все = [п for пп in кош.values() for п in пп]
    продавцы = []
    for пп in кош.values():
        ф = [п.get("продал_в_окне") for п in пп if п.get("окно_продажи_полное", True)]
        if ф and sum(1 for x in ф if x) / len(ф) > 0.30:
            продавцы += пп
    return {"не_S0": ст(не, "S0"), "все_S0": ст(все, "S0"), "все_S1": ст(все, "S1"),
            "не_S1": ст(не, "S1"), "прод_S0": ст(продавцы, "S0"), "прод_S1": ст(продавцы, "S1"),
            "кош": len(кош), "кош_продавцов": sum(1 for пп in кош.values() if any(пп) and пп in [])}


def возраст_мин(п):
    в = п.get("возраст") or {}
    м = в.get("минут")
    if м is None:
        return None
    if в.get("старше_суток") or м >= 1440:
        return 1440.0
    if not в.get("точно") and м < 60:
        return None  # предел листания: возраст не определён
    return float(м)


def main() -> int:
    md = ["# Подбивка: п.15, п.21, п.22", ""]
    дос, а404 = кошельки("koshelki_dos"), кошельки("koshelki")

    # п.15
    md += ["## п.15 Предсказание штаба 02:38 на 139 «досчитать» (выход +72)", "",
           "| проверка | «досчитать» 139 | проход (а) 404 | да/нет на 139 |", "|---|---|---|---|"]
    r = {"139": п15(дос), "404": п15(а404)}
    for k, v in r.items():
        v["разрыв_все"] = (v["все_S0"]["ср"] - v["все_S1"]["ср"]) if v["все_S0"].get("n") and v["все_S1"].get("n") else None
        v["разрыв_не"] = (v["не_S0"]["ср"] - v["не_S1"]["ср"]) if v["не_S0"].get("n") and v["не_S1"].get("n") else None
    a, b = r["139"], r["404"]
    md.append(f"| 1. «не продал»: усечённое S+0 > 0 | n {a['не_S0'].get('n', 0)}, ус. {M.ф(a['не_S0'].get('ус'))} "
              f"(ср {M.ф(a['не_S0'].get('ср'))}) | n {b['не_S0']['n']}, ус. {M.ф(b['не_S0']['ус'])} | "
              f"{'да' if (a['не_S0'].get('ус') or -1) > 0 else 'нет'} |")
    md.append(f"| 2. разрыв S+0 − S+1 (среднее) >= 3 п.п. | все: {M.ф(a['разрыв_все'])}; «не продал»: {M.ф(a['разрыв_не'])} | "
              f"все: {M.ф(b['разрыв_все'])}; «не продал»: {M.ф(b['разрыв_не'])} | "
              f"{'да' if (a['разрыв_все'] or 0) >= 3 else 'нет'} (все), {'да' if (a['разрыв_не'] or 0) >= 3 else 'нет'} («не продал») |")
    md.append(f"| 3. кошельки с долей продаж > 30 %: минус | S+1: {я(a['прод_S1'])}; S+0: {я(a['прод_S0'])} | "
              f"S+1: {я(b['прод_S1'])}; S+0: {я(b['прод_S0'])} | "
              f"{'да' if (a['прод_S1'].get('ср') or 0) < 0 else 'нет'} (S+1), {'да' if (a['прод_S0'].get('ср') or 0) < 0 else 'нет'} (S+0) |")
    md += ["", "Ячейка для п.3: n / среднее / усечённое.", ""]

    # п.21
    вт = кошельки("koshelki_7d")
    def корз(пп, имя):
        из_ = []
        for п in пп:
            с = п.get("sim") or {}
            в = возраст_мин(п)
            if имя == "кривая + не продал + возраст >= 10 мин":
                if с.get("program") == КРИВАЯ and п.get("продал_в_окне") is False and в is not None and в >= 10:
                    из_.append(п)
            elif в is not None and 10 <= в < 60:
                из_.append(п)
        return из_
    md += ["## п.21 Лучший срез вне окна отбора (второй проход, 100 кошельков)", "",
           "Возраст «>= 10 мин» -- только где возраст определён (листание истории минта не упёрлось в предел).", "",
           "| корзина | часть | S+0: n / ср / ус. | S+1: n / ср / ус. |", "|---|---|---|---|"]
    for имя in ("кривая + не продал + возраст >= 10 мин", "возраст 10–60 мин"):
        for часть, усл in (("вне окна", lambda п: (п.get("blockTime") or 0) < ГРАНЬ_ОТБОРА),
                           ("в окне", lambda п: (п.get("blockTime") or 0) >= ГРАНЬ_ОТБОРА)):
            пп = корз([п for x in вт.values() for п in x if усл(п)], имя)
            md.append(f"| {имя} | {часть} | {я(ст(пп, 'S0'))} | {я(ст(пп, 'S1'))} |")
    md.append("")

    # п.22
    ряды = []
    for кат in ("koshelki", "koshelki_dos", "nashi", "koshelki_7d"):
        for f in glob.glob(str(КОРЕНЬ / "data" / "podbivka" / кат / "*.json")):
            if Path(f).name.startswith("_"):
                continue
            к = json.loads(Path(f).read_text(encoding="utf-8"))
            for п in к.get("покупки") or []:
                с = п.get("sim") or {}
                # Только покупки, где f вошла в рамку 0.80–1.0 и симулятор её применил
                # (вне рамки -- отказ «направление или хранилище не то», в числа не попали).
                if с.get("program") == PUMP_AMM and с.get("fee_factor") and 0.80 <= с["fee_factor"] <= 1.0 \
                        and not (с.get("why_not") or "").startswith("S+0"):
                    ряды.append({"signature": п["signature"], "slot": п.get("slot"), "wallet": п.get("wallet"),
                                 "mint": п.get("mint"), "pool_vault_token": с.get("pool_vault"),
                                 "pool_vault_quote": с.get("quote_vault"),
                                 "трата_sol": п.get("трата_sol"), "f_факт": с["fee_factor"],
                                 "f_ожидание": ОЖИДАНИЕ_F,
                                 "расхождение_пп": round((с["fee_factor"] / ОЖИДАНИЕ_F - 1) * 100, 2),
                                 "недошло_до_пула_sol": round((п.get("трата_sol") or 0) * (ОЖИДАНИЕ_F - с["fee_factor"]), 6)})
    уник = {r["signature"]: r for r in ряды}
    топ = sorted(уник.values(), key=lambda r: r["расхождение_пп"])[:20]
    out = КОРЕНЬ / "data" / "podbivka" / "pump_amm_top20.csv"
    with open(out, "w", encoding="utf-8", newline="") as ф:
        w = csv.DictWriter(ф, fieldnames=list(топ[0].keys()))
        w.writeheader()
        w.writerows(топ)
    md += ["## п.22 Pump AMM: 20 покупок с наибольшим расхождением доли траты", "",
           f"Первых покупок Pump AMM с f в рамке 0.80–1.0 (применена симулятором): {len(уник)}; "
           "покупки с f вне рамки -- отказ симулятора, в числа не попали и здесь не перечислены. f = x0·dy / ((y0 − dy)·spent) по балансам сделки источника "
           "(spent -- уменьшение SOL/WSOL кошелька источника), ожидание 0.988 -- по сборам события. "
           "«Недошло до пула» -- трата × (0.988 − f), приближённо. Полные строки (с минтом и хранилищами) -- "
           "`data/podbivka/pump_amm_top20.csv`.", "",
           "| подпись | пул: хранилище токена | трата, SOL | f факт | ожидание | расхождение, п.п. | недошло, SOL |",
           "|---|---|---|---|---|---|---|"]
    for r in топ:
        md.append(f"| {r['signature']} | {r['pool_vault_token']} | {r['трата_sol']} | {r['f_факт']:.4f} | 0.988 | "
                  f"{r['расхождение_пп']:+.2f} | {r['недошло_до_пула_sol']} |")
    md.append("")
    (КОРЕНЬ / "docs" / "podbivka_2026-09-27_p15_21_22.md").write_text("\n".join(md), encoding="utf-8")
    print("готово")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
