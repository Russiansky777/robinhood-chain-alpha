#!/usr/bin/env python3
"""Все свои модули, которые нужны доставленным, тоже доставлены на хост.

ЗАЧЕМ. 27.09 в 17:17:20Z пришёл ПЕРВЫЙ настоящий двухшаговый сигнал (batch5,
пул Pump AMM с котировкой не SOL) -- и сборка ответила
"двухшаговая сборка не загрузилась: ModuleNotFoundError":
bloom_lane_two_step.py не было в списке файлов, которые прогон деплоя копирует
на хост. Код был написан, проверен 52 самопроверками и закоммичен, а на хосте
его не существовало. Сигнал потерян молча -- в признаке жизни стадия
two_step_build просто посчиталась единицей.

ЧТО ПРОВЕРЯЕТСЯ. Оба прогона деплоя пишут в ОДИН каталог (/home/bot/
bloom_executor), значит на хосте лежит ОБЪЕДИНЕНИЕ их списков. По этому
объединению транзитивно ищутся импорты НАШИХ модулей из analysis/, и каждый
обязан быть в объединении. Импорты внутри функций считаются тоже: двухшаговая
сборка подтягивается лениво, и это ровно тот случай, который сломался.

Запускать без аргументов; код возврата 1, если чего-то не хватает.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parent.parent
АНАЛИЗ = КОРЕНЬ / "analysis"
ПРОГОНЫ = КОРЕНЬ / ".github" / "workflows"
# Строка списка файлов в прогоне деплоя: "for f in a.py b.py ...; do".
СПИСОК = re.compile(r"for f in ((?:[A-Za-z0-9_]+\.py\s+)*[A-Za-z0-9_]+\.py);\s*do")
ИМПОРТ = re.compile(r"^\s*(?:import|from)\s+([A-Za-z_][A-Za-z0-9_]*)", re.M)
ДЕПЛОИ = ("run_vps_deploy_bloom_detector_nl.yml",
          "run_vps_deploy_bloom_seller_nl.yml")
# Модули, которых в рабочем пути НЕТ, хотя импорт в рабочей части файла стоит:
# импорт ленивый, и зовут его только из самопроверки. Каждый случай назван
# здесь словами -- молча пропускать нельзя.
РАЗРЕШЕНО = {
    "solana_batch5_rpc_check": ("c2_common.load_rpc_check() зовётся только из "
                                 "самопроверки c2_common; в рабочем пути её нет"),
}


def свои_модули() -> set:
    return {ф.stem for ф in АНАЛИЗ.glob("*.py")}


def импорты(имя: str, свои: set) -> set:
    """Наши модули, которые импортирует рабочая часть файла (без самопроверки)."""
    ф = АНАЛИЗ / f"{имя}.py"
    if not ф.exists():
        return set()
    текст = ф.read_text(encoding="utf-8", errors="replace")
    рабочая = текст.split("\ndef self_test(")[0]
    return {м for м in ИМПОРТ.findall(рабочая) if м in свои and м != имя}


def main() -> int:
    свои = свои_модули()
    доставлены, плохо = set(), []
    for имя_прогона in ДЕПЛОИ:
        путь = ПРОГОНЫ / имя_прогона
        if not путь.exists():
            плохо.append(f"{имя_прогона}: прогона нет")
            continue
        найдено = СПИСОК.findall(путь.read_text(encoding="utf-8"))
        if not найдено:
            плохо.append(f"{имя_прогона}: списка файлов не нашли")
            continue
        for список in найдено:
            доставлены |= {ф[:-3] for ф in список.split()}
    очередь, видели = list(доставлены), set()
    while очередь:
        м = очередь.pop()
        if м in видели:
            continue
        видели.add(м)
        for нужен in импорты(м, свои):
            if нужен in доставлены:
                очередь.append(нужен)
            elif нужен not in РАЗРЕШЕНО:
                плохо.append(f"{м} импортирует {нужен}, а {нужен}.py ни один "
                              f"прогон деплоя на хост не кладёт")
    for с in sorted(set(плохо)):
        print(f"  ПЛОХО {с}")
    print(f"доставка модулей: файлов в деплое {len(доставлены)}, разобрано "
          f"{len(видели)}, разрешено по именам {len(РАЗРЕШЕНО)}, недостающих "
          f"{len(set(плохо))}")
    return 1 if плохо else 0


if __name__ == "__main__":
    raise SystemExit(main())
