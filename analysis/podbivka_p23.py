#!/usr/bin/env python3
"""Подбивка п.23: тонкие пулы -- наши источники speed_only с n >= 5 (как в п.17),
вход S+0 билетом 0.02 / 0.05 / 0.1 / 0.2 / 0.5 SOL, выход +72.

«потолок» -- наша покупка остаётся в пуле до выхода (модель симулятора);
«дно» -- наш след рассосался, продаём в состояние выхода как оно есть.
Валовой п.п. -- без издержек; чистый -- минус 0.002 SOL на сделку (как везде
в подбивке): при билете 0.02 это −10 п.п., при 0.5 -- −0.4.
Резерв SOL пула на входе (после сделки источника): xyk -- котировка, кривая --
реальный SOL кривой. Данные: data/podbivka/postobr/m7_*.jsonl.
"""
from __future__ import annotations

import glob
import json
import statistics
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import podbivka_m4_svod as M  # noqa: E402

КОРЕНЬ = Path(__file__).resolve().parent.parent
БИЛЕТЫ = ("0.02", "0.05", "0.1", "0.2", "0.5")


def main() -> int:
    ряды = [json.loads(l) for f in sorted(glob.glob(str(КОРЕНЬ / "data" / "podbivka" / "postobr" / "m7_*.jsonl")))
            for l in open(f, encoding="utf-8")]
    годные = [р for р in ряды if not р.get("why_not") and р.get("билеты_72")
              and not (р.get("режим") == "price" and ((р["билеты_72"].get("0.5") or {}).get("потолок") or {}).get("вал", 0) > 10_000)]
    по_ист: dict = {}
    for р in годные:
        по_ист.setdefault(р["wallet"], []).append(р)

    def знач(рр, b, вид, ч):
        return [((р["билеты_72"].get(b) or {}).get(вид) or {}).get(ч) for р in рр]

    def резерв(рр):
        v = [р["резерв_s0"] / 1e9 for р in рр if р.get("резерв_s0") and р.get("режим") != "price"]
        return round(statistics.median(v), 1) if v else None

    md = ["# Подбивка п.23: тонкие пулы -- билет 0.02…0.5 SOL при S+0, выход +72", "",
          f"Наши источники speed_only с n >= 5 (п.17): {len(по_ист)}; покупок с числом {len(годные)} из {len(ряды)}. "
          "Ячейка: среднее / усечённое (без ceil(5 % n) лучших), п.п. «Режим цена свопа» -- без проскальзывания, "
          "потолок = дно.", ""]
    for ч, заг in (("вал", "валовой (без 0.002 SOL)"), ("чист", "чистый (минус 0.002 SOL на сделку)")):
        md += [f"## Все вместе, {заг}", "",
               "| билет, SOL | n | потолок | дно |", "|---|---|---|---|"]
        for b in БИЛЕТЫ:
            п, д = M.стат(знач(годные, b, "потолок", ч)), M.стат(знач(годные, b, "дно", ч))
            md.append(f"| {b} | {п.get('n', 0)} | {M.ф(п.get('ср'))} / {M.ф(п.get('ус'))} | {M.ф(д.get('ср'))} / {M.ф(д.get('ус'))} |")
        md.append("")
    md += ["## Корзины по резерву SOL пула на входе, валовой потолок / дно (среднее)", "",
           "| резерв, SOL | n | " + " | ".join(f"{b}" for b in БИЛЕТЫ) + " |", "|---|---|" + "---|" * len(БИЛЕТЫ)]
    корз = (("< 10", 0, 10), ("10–30", 10, 30), ("30–100", 30, 100), ("100+", 100, 1e18))
    for имя, lo, hi in корз:
        рр = [р for р in годные if р.get("резерв_s0") and р.get("режим") != "price" and lo <= р["резерв_s0"] / 1e9 < hi]
        cells = []
        for b in БИЛЕТЫ:
            п, д = M.стат(знач(рр, b, "потолок", "вал")), M.стат(знач(рр, b, "дно", "вал"))
            cells.append(f"{M.ф(п.get('ср'))} / {M.ф(д.get('ср'))}")
        md.append(f"| {имя} | {len(рр)} | " + " | ".join(cells) + " |")
    md += ["", "## По источникам: чистый, среднее / усечённое; потолок | дно; резерв -- медиана, SOL", "",
           "| источник | n | резерв | " + " | ".join(f"{b} потолок | {b} дно" for b in БИЛЕТЫ) + " |",
           "|---|---|---|" + "---|---|" * len(БИЛЕТЫ)]
    for а, рр in sorted(по_ист.items(), key=lambda kv: -len(kv[1])):
        cells = []
        for b in БИЛЕТЫ:
            п, д = M.стат(знач(рр, b, "потолок", "чист")), M.стат(знач(рр, b, "дно", "чист"))
            cells += [f"{M.ф(п.get('ср'))} / {M.ф(п.get('ус'))}", f"{M.ф(д.get('ср'))} / {M.ф(д.get('ус'))}"]
        md.append(f"| {а[:8]} | {len(рр)} | {резерв(рр)} | " + " | ".join(cells) + " |")
    md.append("")
    (КОРЕНЬ / "docs" / "podbivka_2026-09-27_p23.md").write_text("\n".join(md), encoding="utf-8")
    print("\n".join(md[:40]))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
