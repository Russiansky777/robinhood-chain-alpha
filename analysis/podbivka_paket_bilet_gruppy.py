#!/usr/bin/env python3
"""Билет ПО ГРУППАМ (слово владельца 05.10): нынешний билет → предлагаемый, подбор и проверка.

Только чтение, офлайн по кэшу сигналов архива (`podbivka_paket_kesh.py`), новых проходов не
пускает. Для каждой ТОРГУЮЩЕЙ группы (по живой выгрузке Code-1
`data/podbivka/code1_sources_live.json`):

  * нынешний билет группы и число сигналов её источников в окне;
  * сетка билетов 0.05...3: SOL в сутки на подборе (ранние сутки) и на проверке (последние),
    медиана п.п., доля в плюсе, то же без двух лучших сделок. Итог -- формулой модели архива
    при входе S+1 и удержании группы (`podbivka_bilet.пп_по_состояниям`), ограничение
    `lane_open_max` группы соблюдается по слотам;
  * «ступень» -- лучший билет СЕТКИ по подбору, и что он даёт на проверке;
  * гибкий «2 % резерва» -- билет каждой сделки = 2 % резерва пула на входе, с потолком
    (--potolok, по умолчанию 3 SOL) и полом (--pol, 0.05): так билет сам подстраивается под
    глубину пула;
  * риск хвоста: худшие сутки по группе при нынешнем и предлагаемом билете, и сколько у
    группы ЗАВИСШИХ живых сделок по журналу (`closed_reason` говорит, что продавать было
    нечего) -- это не модель, а факт из выгрузок.

Выход: data/podbivka/paket_bilet_gruppy.json и docs/podbivka_<метка>_bilet_gruppy.md.
Ничего не рекомендуется -- решает владелец.
"""
from __future__ import annotations

import argparse
import collections
import glob
import json
import statistics
import sys
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import podbivka_nedelya_bilet as N  # noqa: E402
import podbivka_paket_bilet as БИ  # noqa: E402
import podbivka_paket_obshee as O  # noqa: E402

КОРЕНЬ = O.КОРЕНЬ
П = O.П


def зависшие_по_группам() -> dict:
    """Живые сделки, где продавать было нечего (остаток минта 0) -- факт из журнала."""
    по_cid: dict = {}
    файлы = [П / "sdelki" / "vse_s_2709.json"]
    файлы += [Path(f) for f in sorted(glob.glob(str(П / "sdelki" / "sdelki_polosy_*.json")))]
    файлы += [Path(f) for f in sorted(glob.glob(str(П / "mesto" / "vhod_*.json")))]
    for f in файлы:
        if not f.exists():
            continue
        try:
            д = json.loads(f.read_text(encoding="utf-8"))
        except ValueError:
            continue
        ряды = д.get("ряды") if isinstance(д, dict) else д
        for r in (ряды or []):
            if r.get("cid"):
                по_cid[r["cid"]] = r
    счёт: dict = collections.defaultdict(lambda: {"зависших": 0, "итог_зависших_sol": 0.0,
                                                  "живых_сделок": 0, "итог_живых_sol": 0.0})
    for r in по_cid.values():
        г = r.get("group")
        if not г:
            continue
        и, _ = N.итог_сделки(r)
        счёт[г]["живых_сделок"] += 1
        счёт[г]["итог_живых_sol"] += float(и or 0)
        пр = (r.get("closed_reason") or "").lower()
        if "продавать нечего" in пр or "остаток минта 0" in пр:
            счёт[г]["зависших"] += 1
            счёт[г]["итог_зависших_sol"] += float(и or 0)
    return {г: {**v, "итог_зависших_sol": round(v["итог_зависших_sol"], 6),
                "итог_живых_sol": round(v["итог_живых_sol"], 6)} for г, v in счёт.items()}


def main() -> int:
    import podbivka_run as R  # noqa: PLC0415
    р = argparse.ArgumentParser()
    р.add_argument("--metka", default=time.strftime("%Y-%m-%d", time.gmtime()))
    р.add_argument("--podbor-sutok", type=int, default=8)
    р.add_argument("--dolya-rezerva", type=float, default=0.02, help="гибкий билет: доля резерва")
    р.add_argument("--potolok", type=float, default=3.0)
    р.add_argument("--pol", type=float, default=0.05)
    а = р.parse_args()

    д = БИ.собрать(а.podbor_sutok)
    по_ист, окна = д["по_ист"], д["окна"]
    зав = зависшие_по_группам()

    по_группам: dict = collections.defaultdict(list)
    for a, сп in по_ист.items():
        for с in сп:
            с["ист"] = a
            по_группам[с["группа"]].append(с)

    группы = {}
    for г, сп in sorted(по_группам.items()):
        пол = O.ПОЛИТИКА.get(г) or {}
        взятые, отброшено = БИ.под_open_max(сп, int(пол.get("open_max") or 3))
        стр = {"нынешний_билет": пол.get("билет"), "open_max": пол.get("open_max"),
               "удержание_слотов": пол.get("удержание_слотов"),
               "сигналов": len(сп), "взято_под_open_max": len(взятые),
               "отброшено_open_max": отброшено,
               "источников": len({с["ист"] for с in сп}),
               "по_билетам": {}, "зависшие": зав.get(г, {})}
        рез = [с["р"].get("резерв_sol") for с in взятые if с["р"].get("резерв_sol")]
        стр["резерв_медиана_sol"] = round(statistics.median(рез), 2) if рез else None
        стр["резерв_p10_sol"] = (round(sorted(рез)[max(0, int(0.1 * len(рез)) - 1)], 2)
                                 if рез else None)
        for б in O.БИЛЕТЫ_СЕТКА:
            ряды = БИ.итоги(взятые, б)
            if not ряды:
                continue
            стр["по_билетам"][f"{б:g}"] = {"подбор": БИ.свод(ряды, окна["подбор"]),
                                           "проверка": БИ.свод(ряды, окна["проверка"]),
                                           "всё": БИ.свод(ряды, окна["все"]),
                                           "по_суткам": O.по_суткам_сумма(ряды)}
        # гибкий билет: доля резерва пула на входе, с полом и потолком
        гибкие = []
        for с in взятые:
            рез_ = с["р"].get("резерв_sol")
            if not рез_:
                continue
            б = min(max(а.dolya_rezerva * float(рез_), а.pol), а.potolok)
            п = O.пп(с["р"], б, "S1", с["удержание"])
            if п is None:
                continue
            гибкие.append({"сутки": с["сутки"], "пп": п, "sol": п / 100 * б, "билет": б})
        if гибкие:
            стр["гибкий_2pct"] = {
                "подбор": БИ.свод(гибкие, окна["подбор"]),
                "проверка": БИ.свод(гибкие, окна["проверка"]),
                "всё": БИ.свод(гибкие, окна["все"]),
                "билет_медиана": round(statistics.median([x["билет"] for x in гибкие]), 3),
                "по_суткам": O.по_суткам_сумма(гибкие)}
        с_подбором = [(к, v) for к, v in стр["по_билетам"].items()
                      if v["подбор"].get("sol_в_сутки") is not None]
        if с_подбором:
            стр["ступень_подбора"] = max(с_подбором,
                                         key=lambda kv: kv[1]["подбор"]["sol_в_сутки"])[0]
        группы[г] = стр

    def худшие(по_суткам: dict) -> float | None:
        return round(min(по_суткам.values()), 6) if по_суткам else None

    итог = {"что": "билет по группам: нынешний против ступени и гибкого «2 % резерва»",
            "источник_чисел": {"кэш": str(O.КЭШ), "политика": "data/podbivka/code1_sources_live.json",
                               "журнал": "data/podbivka/sdelki, data/podbivka/mesto"},
            "окна": окна, "доля_резерва": а.dolya_rezerva, "потолок": а.potolok, "пол": а.pol,
            "группы": группы}
    out = П / "paket_bilet_gruppy.json"
    out.write_text(json.dumps(итог, ensure_ascii=False, indent=1), encoding="utf-8")
    R.записано(out)

    def ф(v, формат="+.4f"):
        return "—" if v is None else format(v, формат)

    md = [f"# Билет по торгующим группам: нынешний против ступени и гибкого ({а.metka})", "",
          f"Офлайн по кэшу сигналов архива, новых проходов нет. Окно {окна['все'][0]} — "
          f"{окна['все'][-1]}: подбор {len(окна['подбор'])} суток, проверка "
          f"{len(окна['проверка'])} суток. Итог сделки — формулой модели архива при входе S+1 и "
          f"удержании группы; `lane_open_max` группы соблюдается по слотам. Гибкий билет = "
          f"{а.dolya_rezerva * 100:g} % резерва пула на входе, пол {а.pol:g}, потолок "
          f"{а.potolok:g} SOL. Зависшие — факт из журнала Code-1 (`closed_reason`: продавать "
          f"было нечего), не модель.", "",
          "| группа | n сигналов | нынешний билет | SOL/сутки подбор | SOL/сутки проверка "
          "| ступень подбора | её SOL/сутки на проверке | гибкий 2 %: медиана билета "
          "| гибкий SOL/сутки проверка | худшие сутки: нынешний / ступень / гибкий "
          "| зависших живых сделок | резерв пула медиана / p10 |",
          "|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for г, с in группы.items():
        б_тек = f"{с['нынешний_билет']:g}" if с["нынешний_билет"] else None
        тек = с["по_билетам"].get(б_тек or "", {})
        ст = с["по_билетам"].get(с.get("ступень_подбора") or "", {})
        гиб = с.get("гибкий_2pct") or {}
        md.append(
            f"| {г} | {с['взято_под_open_max']} | {б_тек or '—'} "
            f"| {ф(тек.get('подбор', {}).get('sol_в_сутки'), '+.6f')} "
            f"| {ф(тек.get('проверка', {}).get('sol_в_сутки'), '+.6f')} "
            f"| {с.get('ступень_подбора') or '—'} "
            f"| {ф(ст.get('проверка', {}).get('sol_в_сутки'), '+.6f')} "
            f"| {ф(гиб.get('билет_медиана'), '.3f')} "
            f"| {ф(гиб.get('проверка', {}).get('sol_в_сутки'), '+.6f')} "
            f"| {ф(худшие(тек.get('по_суткам') or {}), '+.4f')} / "
            f"{ф(худшие(ст.get('по_суткам') or {}), '+.4f')} / "
            f"{ф(худшие(гиб.get('по_суткам') or {}), '+.4f')} "
            f"| {(с['зависшие'] or {}).get('зависших', 0)} из "
            f"{(с['зависшие'] or {}).get('живых_сделок', 0)} "
            f"| {ф(с.get('резерв_медиана_sol'), '.1f')} / {ф(с.get('резерв_p10_sol'), '.1f')} |")

    # сводка по всем торгующим группам вместе
    сумма = {}
    for имя, выбор in (("нынешние билеты", "тек"), ("ступени подбора", "ступень"),
                       ("гибкий 2 % резерва", "гибкий")):
        под = пров = 0.0
        худ = None
        for г, с in группы.items():
            if выбор == "тек":
                v = с["по_билетам"].get(f"{с['нынешний_билет']:g}" if с["нынешний_билет"] else "", {})
            elif выбор == "ступень":
                v = с["по_билетам"].get(с.get("ступень_подбора") or "", {})
            else:
                v = с.get("гибкий_2pct") or {}
            под += (v.get("подбор", {}) or {}).get("sol_в_сутки") or 0
            пров += (v.get("проверка", {}) or {}).get("sol_в_сутки") or 0
            х = худшие(v.get("по_суткам") or {})
            худ = х if (худ is None or (х is not None and х < худ)) else худ
        сумма[имя] = {"sol_в_сутки_подбор": round(под, 6), "sol_в_сутки_проверка": round(пров, 6),
                      "худшие_сутки_группы": худ}
    итог["свод"] = сумма
    out.write_text(json.dumps(итог, ensure_ascii=False, indent=1), encoding="utf-8")

    md += ["", "## Свод по всем торгующим группам", "",
           "| набор билетов | SOL/сутки на подборе | SOL/сутки на проверке "
           "| худшие сутки у худшей группы |", "|---|---|---|---|"]
    for имя, v in сумма.items():
        md.append(f"| {имя} | {ф(v['sol_в_сутки_подбор'], '+.6f')} "
                  f"| {ф(v['sol_в_сутки_проверка'], '+.6f')} "
                  f"| {ф(v['худшие_сутки_группы'], '+.4f')} |")
    лучший = max(сумма.items(), key=lambda kv: kv[1]["sol_в_сутки_проверка"])
    md += ["", "## Вывод", "",
           f"На проверке лучший набор — **{лучший[0]}**: "
           f"{ф(лучший[1]['sol_в_сутки_проверка'], '+.6f')} SOL в сутки против "
           f"{ф(сумма['нынешние билеты']['sol_в_сутки_проверка'], '+.6f')} при нынешних билетах; "
           f"худшие сутки у худшей группы {ф(лучший[1]['худшие_сутки_группы'], '+.4f')} против "
           f"{ф(сумма['нынешние билеты']['худшие_сутки_группы'], '+.4f')}.", "",
           "Это числа модели на архиве при входе S+1: допуск по цене в них не применяется, а "
           "живая полоса часть сделок по нему отказывает, поэтому они верхняя граница. "
           "Ничего не меняется и не рекомендуется — решает владелец.", ""]
    стр_ф = КОРЕНЬ / "docs" / f"podbivka_{а.metka}_bilet_gruppy.md"
    стр_ф.write_text("\n".join(md) + "\n", encoding="utf-8")
    R.записано(стр_ф)
    print(f"{стр_ф.name}: групп {len(группы)}; на проверке нынешние "
          f"{сумма['нынешние билеты']['sol_в_сутки_проверка']}, ступени "
          f"{сумма['ступени подбора']['sol_в_сутки_проверка']}, гибкий "
          f"{сумма['гибкий 2 % резерва']['sol_в_сутки_проверка']}", flush=True)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
