def события_пула(tx: dict, пул: str) -> list:
    """События свопа DLMM ЭТОГО пула из транзакции источника, в порядке исполнения.

    Роутер трогает по нескольку пулов одной транзакцией, поэтому чужие события
    отбрасываются по адресу пула -- иначе цена считалась бы по чужому пулу.
    """
    B = _кирпичи()
    return [е for е in B.события_dlmm(tx or {}) if е.get("пул") == пул]


def наша_сторона_y(счета: list, минт_котировки: str) -> dict:
    """Наша покупка -- это swap_for_y или нет? Из мест минтов инструкции, без сети.

    swap_for_y = отдаём X, получаем Y. Покупка отдаёт КОТИРОВКУ, значит
    swap_for_y = (котировка стоит на месте минта X).
    """
    счета = list(счета or [])
    if len(счета) <= МЕСТО_МИНТА_Y:
        return {"ok": False, "why_not": "в инструкции нет мест минтов пула"}
    x, y = счета[МЕСТО_МИНТА_X], счета[МЕСТО_МИНТА_Y]
    if not x or not y or x == y:
        return {"ok": False, "why_not": "минты сторон пула не различаются"}
    if минт_котировки == x:
        return {"ok": True, "swap_for_y": True, "минт_базы": y, "минт_x": x, "минт_y": y}
    if минт_котировки == y:
        return {"ok": True, "swap_for_y": False, "минт_базы": x, "минт_x": x, "минт_y": y}
    return {"ok": False,
            "why_not": (f"котировка {минт_котировки[:8]} не совпала ни с одной "
                         f"стороной пула ({x[:8]}/{y[:8]})")}


def корзин_события(ев: dict) -> int | None:
    """Сколько корзин пересёк своп источника -- по его же событию."""
    н, к = (ев or {}).get("start_bin_id"), (ев or {}).get("end_bin_id")
    if not isinstance(н, int) or not isinstance(к, int):
        return None
    return abs(к - н) + 1


def корзин_нашего_размера(ев: dict, лампорты: int) -> dict:
    """Сколько корзин пересёк бы НАШ размер -- по событию источника.

    ЧТО ЗДЕСЬ ДОКАЗАНО, А ЧТО ОЦЕНКА, СКАЗАНО ПОЛЕМ, А НЕ УМОЛЧАНИЕМ.
      * наш вход НЕ БОЛЬШЕ его входа -> корзин НЕ БОЛЬШЕ, чем у него. Это верхняя
        граница, и она доказана: меньший вход не может уйти дальше по кривой.
      * наш вход БОЛЬШЕ -> из события не видно, сколько ликвидности лежит за его
        последней корзиной. Даём линейную оценку и честно помечаем
        `доказано=False`: за границей его свопа ликвидность может быть любой,
        вплоть до нуля.
    """
    из_ = {"корзин": None, "доказано": None, "корзин_у_источника": None,
            "вход_источника": None, "доля_размера": None, "почему": None}
    n = корзин_события(ев)
    вход = int((ев or {}).get("amount_in") or 0)
    из_.update(корзин_у_источника=n, вход_источника=вход)
    if n is None or вход <= 0:
        из_["почему"] = "в событии нет корзин или входа"
        return из_
    л = int(лампорты)
    if л <= 0:
        из_["почему"] = "наш размер не положителен"
        return из_
    из_["доля_размера"] = round(л / вход, 6)
    if л <= вход:
        из_.update(корзин=n, доказано=True)
        return из_
    # ceil без float: (a + b - 1) // b
    из_.update(корзин=(n * л + вход - 1) // вход, доказано=False,
                почему=f"{ПРИЗНАК_РАЗМЕР_БОЛЬШЕ}: {л} против {вход}")
    return из_


# ------------------------------------------------------------------ цена

def _назван(налог) -> bool:
    """Назван ли налог ЧИСЛОМ, а не «не знаю». То же правило, что у строителей:
    (None, None) -- истинный кортеж, и без этой проверки вычет молча не делался."""
    if not isinstance(налог, (tuple, list)) or not налог:
        return False
    bps = налог[0]
    if isinstance(bps, bool) or not isinstance(bps, int) or bps < 0:
        return False
    максимум = налог[1] if len(налог) > 1 else None
    return not (максимум is not None
                and (isinstance(максимум, bool) or not isinstance(максимум, int)
                     or максимум < 0))


def без_налога(сумма: int, bps: int | None, максимум: int | None) -> int:
    """Сумма после налога перевода Token-2022: вверх, как программа (округление
    в её пользу), и не больше максимума расширения."""
    if not bps:
        return int(сумма)
    сбор = (int(сумма) * int(bps) + 9999) // 10000
    if максимум is not None:
        сбор = min(сбор, int(максимум))
    return int(сумма) - сбор


def котировка_по_событию(ев: dict, *, swap_for_y: bool, лампорты: int,
                          проскальзывание: float, налог_выхода=None,
                          программа_выхода: str | None = None) -> dict:
    """ЦЕНА ИЗ СОБЫТИЯ. Ноль чтений, ноль обращений к переносу.

    Формула ровно та, которой считает замер (deploy/checks/dlmm_bez_chteniy_chislo.py):
    выход = наш вход * (его выход / его вход), целочисленно вниз. Иначе модуль и
    замер считали бы РАЗНОЕ, и сверка подтверждала бы саму себя.
    """
    из_ = {"ok": False, "why_not": None, "чтений": 0, "точная": False,
            "путь": "DLMM без чтений (цена из события источника)",
            "expected_out": None, "min_out": None, "выход_до_налога": None,
            "вход_источника": None, "выход_источника": None,
            "корзин_у_источника": None, "корзин_нашего_размера": None,
            "корзин_доказано": None, "мс": None}
    т0 = time.perf_counter()
    if not isinstance(ев, dict):
        из_["why_not"] = ПРИЗНАК_НЕТ_СОБЫТИЯ
        return из_
    if int(ев.get("swap_for_y") or 0) != int(bool(swap_for_y)):
        из_["why_not"] = (f"{ПРИЗНАК_ДРУГАЯ_СТОРОНА}: у него swap_for_y="
                           f"{int(ев.get('swap_for_y') or 0)}, у нас "
                           f"{int(bool(swap_for_y))}")
        return из_
    вход_ист = int(ев.get("amount_in") or 0)
    выход_ист = int(ев.get("amount_out") or 0)
    из_.update(вход_источника=вход_ист, выход_источника=выход_ист)
    if вход_ист <= 0 or выход_ист <= 0:
        из_["why_not"] = "в событии источника нулевой вход или выход"
        return из_
    л = int(лампорты)
    if л <= 0:
        из_["why_not"] = "сумма входа не положительна"
        return из_
    if программа_выхода == TOKEN_2022 and not _назван(налог_выхода):
        из_["why_not"] = (f"минт выхода на Token-2022, а {ПРИЗНАК_НАЛОГ_НЕ_НАЗВАН} "
                           f"числом ({налог_выхода!r})")
        return из_
    сырой = (л * выход_ист) // вход_ист
    if сырой <= 0:
        из_["why_not"] = "цена источника даёт ноль на нашем размере"
        return из_
    ожидаем = сырой
    if _назван(налог_выхода):
        ожидаем = без_налога(сырой, налог_выхода[0],
                              налог_выхода[1] if len(налог_выхода) > 1 else None)
    if ожидаем <= 0:
        из_["why_not"] = f"налог перевода съедает весь выход ({сырой})"
        return из_
    мин = int(ожидаем * (1.0 - float(проскальзывание)))
    if мин <= 0:
        из_["why_not"] = "минимум выхода не положителен при этом проскальзывании"
        return из_
    к = корзин_нашего_размера(ев, л)
    из_.update(ok=True, expected_out=ожидаем, min_out=мин, выход_до_налога=сырой,
                налог_выхода_учтён=_назван(налог_выхода),
                корзин_у_источника=к["корзин_у_источника"],
                корзин_нашего_размера=к["корзин"],
                корзин_доказано=к["доказано"],
                корзин_почему=к["почему"], доля_размера=к["доля_размера"],
                мс=round((time.perf_counter() - т0) * 1000.0, 4))
    return из_


def котировка(*, пул: str, минт_базы: str | None = None,
               минт_котировки: str, лампорты: int, проскальзывание: float,
               rpc_call=None, tx_источника: dict | None = None,
               счета: list | None = None, налог_выхода=None,
               программа_выхода: str | None = None, **_прочее) -> dict:
    """Та же подпись, что у котировок строителей -- но `rpc_call` НЕ ИСПОЛЬЗУЕТСЯ.

    Принят он только для совместимости вызова: путь стоит нуль чтений, и если он
    когда-нибудь начнёт читать, это перестанет быть правдой молча. Поэтому в
    ответе всегда `чтений: 0`, а сам аргумент здесь не трогается вовсе.
    """
    из_ = {"ok": False, "why_not": None, "чтений": 0, "точная": False}
    if not isinstance(tx_источника, dict):
        из_["why_not"] = "транзакции источника нет -- считать не из чего"
        return из_
    события = события_пула(tx_источника, пул)
    if not события:
        из_["why_not"] = ПРИЗНАК_НЕТ_СОБЫТИЯ
        return из_
    сч = список_счетов(tx_источника, пул) if счета is None else list(счета)
    с = наша_сторона_y(сч, минт_котировки)
    if not с.get("ok"):
        из_["why_not"] = f"сторона покупки не выведена: {с.get('why_not')}"
        return из_
    if минт_базы and с.get("минт_базы") != минт_базы:
        из_["why_not"] = (f"минт сигнала {минт_базы[:8]} не база этого пула "
                           f"({str(с.get('минт_базы'))[:8]})")
        return из_
    о = котировка_по_событию(события[0], swap_for_y=с["swap_for_y"],
                              лампорты=лампорты, проскальзывание=проскальзывание,
                              налог_выхода=налог_выхода,
                              программа_выхода=программа_выхода)
    о["минт_базы"] = с.get("минт_базы")
    о["swap_for_y"] = с["swap_for_y"]
    return о


def список_счетов(tx: dict, пул: str) -> list:
    """Счета инструкции DLMM этого пула в транзакции источника (для мест минтов)."""
    B = _кирпичи()
    for их in B.all_instructions(tx or {}):
        if их.get("programId") != ПРОГРАММА:
            continue
        счета = list(их.get("accounts") or [])
        # Пул у DLMM -- счёт 0 инструкции; сверяем прямо, чтобы на сделке роутера
        # не взять счета ЧУЖОГО пула той же программы.
        if счета and счета[0] == пул:
            return счета
    return []


# ------------------------------------------------- дверь для полосы: тень

def тень(tx_источника: dict | None, пул: str | None, к: dict | None, *,
          лампорты: int, минт_котировки: str,
          проскальзывание: float = 0.0, налог_выхода=None,
          программа_выхода: str | None = None) -> dict:
    """ГОДИЛСЯ ЛИ НУЛЬ ЧТЕНИЙ НА ЭТОМ СИГНАЛЕ. Той же формы, что тень одного чтения.

    Code-1 пишет это в `lane_dlmm_nol_godilos` / `lane_dlmm_nol_why_not`, как уже
    пишет `lane_dlmm_odno_godilos`. Решения тень не принимает и min_out для
    отправки не отдаёт: в ответе только числа.

    ЧТО ЗНАЧИТ `годилось`. Не «цена посчиталась», а «посчиталась И НЕ ЗАВЫШЕНА»
    против прежней точной цены полосы (`к["expected_out"]`). Завышение -- это
    min_out выше того, что пул отдаст, то есть откат: считать его удачей нельзя.
    Насколько завышено -- в `запас_нужен_%`: это и есть тот запас, который штабу
    пришлось бы отдавать с каждой покупки, если бы путь включили.
    """
    из_ = {"годилось": None, "почему_нет": None, "наш_выход": None,
            "выход_полосы": None, "отклонение_%": None, "запас_нужен_%": None,
            "корзин_у_источника": None, "корзин_нашего_размера": None,
            "корзин_доказано": None, "чтений": 0, "мс": None}
    if not isinstance(tx_источника, dict) or not пул:
        из_["почему_нет"] = "нет транзакции источника или пула"
        return из_
    т0 = time.perf_counter()
    try:
        о = котировка(пул=пул, минт_котировки=минт_котировки, лампорты=лампорты,
                       проскальзывание=проскальзывание, tx_источника=tx_источника,
                       налог_выхода=налог_выхода, программа_выхода=программа_выхода)
        из_["мс"] = round((time.perf_counter() - т0) * 1000.0, 4)
        из_.update(корзин_у_источника=о.get("корзин_у_источника"),
                    корзин_нашего_размера=о.get("корзин_нашего_размера"),
                    корзин_доказано=о.get("корзин_доказано"))
        if not о.get("ok"):
            из_["почему_нет"] = о.get("why_not")
            return из_
        из_["наш_выход"] = о.get("expected_out")
        факт = (к or {}).get("expected_out")
        if not isinstance(факт, int) or факт <= 0:
            # ЦЕНУ ПОЛОСЫ НЕ ПОДМЕНЯЕМ НУЛЁМ. Без неё сравнить не с чем, и это
            # не "годилось", а "не с чем сверить" -- иначе в выгрузке появилось
            # бы True там, где не сверяли ничего.
            из_["почему_нет"] = "точной цены полосы в ответе нет -- сверить не с чем"
            return из_
        из_["выход_полосы"] = факт
        откл = (о["expected_out"] - факт) / факт * 100.0
        из_["отклонение_%"] = round(откл, 4)
        из_["запас_нужен_%"] = round(max(0.0, откл), 4)
        из_["годилось"] = bool(о["expected_out"] <= факт)
    except Exception as exc:  # noqa: BLE001
        из_.update(годилось=None,
                    почему_нет=f"тень упала: {type(exc).__name__}: {str(exc)[:80]}")
    return из_


def откатный(why_not) -> bool:
    """Свои ли это причины -- те, при которых вызывающий идёт прежним путём."""
    т = str(why_not or "")
    return any(п in т for п in (ПРИЗНАК_ДРУГАЯ_СТОРОНА, ПРИЗНАК_НЕТ_СОБЫТИЯ,
                                 "транзакции источника нет",
                                 "сторона покупки не выведена"))


# ------------------------------------------------------------- самопроверка

def self_test() -> int:  # noqa: C901
    пройдено = провалено = 0

    def chk(что, ок, факт=None):
        nonlocal пройдено, провалено
        print(f"  [{'ok  ' if ок else 'ПРОВАЛ'}] {что}"
              + (f" -> {факт!r}" if факт is not None and not ок else ""))
        пройдено += bool(ок)
        провалено += (not ок)

    было = os.environ.pop(ИМЯ_ФЛАГА, None)
    было_гр = os.environ.pop(ИМЯ_ФЛАГА_ГРУППЫ, None)
    chk("по умолчанию тень ВЫКЛЮЧЕНА", включён() is False)
    os.environ[ИМЯ_ФЛАГА] = "1"
    chk("флаг 1 включает", включён() is True)
    os.environ[ИМЯ_ФЛАГА_ГРУППЫ] = "lane_s0"
    chk("список групп СИЛЬНЕЕ общего флага",
        включён("batch5") is False and включён("lane_s0") is True
        and включён(None) is False)
    for имя, зн in ((ИМЯ_ФЛАГА, было), (ИМЯ_ФЛАГА_ГРУППЫ, было_гр)):
        os.environ.pop(имя, None)
        if зн is not None:
            os.environ[имя] = зн

    # --- МЕСТА МИНТОВ БЕРУТСЯ У ДЕНЕЖНОГО ПУТИ, А НЕ ПЕРЕПИСАНЫ
    try:
        B = _кирпичи()
        k = B.DYN[ПРОГРАММА]
        chk("места минтов пула совпадают с c2_swap_build.DYN[DLMM]",
            (МЕСТО_МИНТА_X, МЕСТО_МИНТА_Y) == (k["ma"], k["mb"]),
            (МЕСТО_МИНТА_X, МЕСТО_МИНТА_Y, k["ma"], k["mb"]))
        chk("адрес программы совпадает с денежным путём", ПРОГРАММА == B.DLMM)
    except Exception as exc:  # noqa: BLE001
        chk("места минтов сверены с денежным путём", False,
            f"{type(exc).__name__}: {exc}")

    # --- СТОРОНА ПОКУПКИ
    сч = ["ПУЛ", "бит", "хрX", "хрY", "нашX", "нашY", "МИНТX", "МИНТY"]
    chk("котировка на месте X -> наша покупка swap_for_y=True",
        наша_сторона_y(сч, "МИНТX") == {"ok": True, "swap_for_y": True,
                                         "минт_базы": "МИНТY", "минт_x": "МИНТX",
                                         "минт_y": "МИНТY"})
    chk("котировка на месте Y -> swap_for_y=False",
        наша_сторона_y(сч, "МИНТY").get("swap_for_y") is False)
    chk("котировка не совпала ни с одной стороной -- отказ словами",
        (lambda р: р["ok"] is False and "не совпала" in р["why_not"])(
            наша_сторона_y(сч, "ЧУЖОЙ")))
    chk("коротких счетов не хватает -- отказ, а не IndexError",
        наша_сторона_y(["a", "b"], "МИНТX")["ok"] is False)

    # --- ЦЕНА ИЗ СОБЫТИЯ
    ев = {"пул": "P", "start_bin_id": -10, "end_bin_id": -8, "amount_in": 1000,
          "amount_out": 4000, "swap_for_y": 1}
    о = котировка_по_событию(ев, swap_for_y=True, лампорты=500,
                              проскальзывание=0.0)
    chk("цена из события: 500 при 1000 -> 4000 даёт 2000, чтений 0",
        о["ok"] and о["expected_out"] == 2000 and о["min_out"] == 2000
        and о["чтений"] == 0 and о["точная"] is False, о)
    chk("сторона другая -- отказ ПО ИМЕНИ",
        (lambda р: р["ok"] is False and ПРИЗНАК_ДРУГАЯ_СТОРОНА in р["why_not"])(
            котировка_по_событию(ев, swap_for_y=False, лампорты=500,
                                  проскальзывание=0.0)))
    chk("проскальзывание опускает минимум, а ожидание не трогает",
        (lambda р: р["expected_out"] == 2000 and р["min_out"] == 1800)(
            котировка_по_событию(ев, swap_for_y=True, лампорты=500,
                                  проскальзывание=0.1)))
    chk("нулевой вход события -- отказ, а не делёж на ноль",
        котировка_по_событию(dict(ев, amount_in=0), swap_for_y=True,
                              лампорты=5, проскальзывание=0.0)["ok"] is False)
    chk("целочисленно ВНИЗ: 3 при 1000 -> 4000 даёт 12, не 12.0",
        (lambda р: р["expected_out"] == 12 and isinstance(р["expected_out"], int))(
            котировка_по_событию(ев, swap_for_y=True, лампорты=3,
                                  проскальзывание=0.0)))
    chk("наш размер даёт ноль на выходе -- отказ, а не ноль",
        котировка_по_событию({"amount_in": 10 ** 9, "amount_out": 10,
                               "swap_for_y": 1, "start_bin_id": 0,
                               "end_bin_id": 0}, swap_for_y=True, лампорты=1,
                              проскальзывание=0.0)["ok"] is False)

    # --- НАЛОГ ВЫХОДА
    chk("минт выхода на Token-2022 без названного налога -- ОТКАЗ, а не ноль",
        (lambda р: р["ok"] is False and ПРИЗНАК_НАЛОГ_НЕ_НАЗВАН in р["why_not"])(
            котировка_по_событию(ев, swap_for_y=True, лампорты=500,
                                  проскальзывание=0.0, налог_выхода=(None, None),
                                  программа_выхода=TOKEN_2022)))
    chk("налог 100 bps вычитается вверх: 2000 -> 1980",
        (lambda р: р["ok"] and р["выход_до_налога"] == 2000
         and р["expected_out"] == 1980)(
            котировка_по_событию(ев, swap_for_y=True, лампорты=500,
                                  проскальзывание=0.0, налог_выхода=(100, None),
                                  программа_выхода=TOKEN_2022)))
    chk("максимум налога расширения уважается",
        без_налога(2000, 100, 5) == 1995)

    # --- КОРЗИНЫ
    chk("корзин у источника -- по его же событию (start -10, end -8 -> 3)",
        корзин_события(ев) == 3)
    к1 = корзин_нашего_размера(ев, 500)
    chk("наш размер МЕНЬШЕ -- верхняя граница ДОКАЗАНА и равна его числу",
        к1["корзин"] == 3 and к1["доказано"] is True, к1)
    к2 = корзин_нашего_размера(ев, 2500)
    chk("наш размер БОЛЬШЕ -- оценка помечена доказано=False и названа причина",
        к2["корзин"] == 8 and к2["доказано"] is False
        and ПРИЗНАК_РАЗМЕР_БОЛЬШЕ in (к2["почему"] or ""), к2)
    chk("равный размер -- всё ещё доказано",
        корзин_нашего_размера(ев, 1000)["доказано"] is True)

    # --- ТЕНЬ
    def _tx(ев_, счета_=None):
        """Транзакция источника с одним событием свопа DLMM этого пула."""
        B_ = _кирпичи()
        import struct as _st  # noqa: PLC0415

        # ТЕЛО СОБЫТИЯ -- РОВНО ТОЙ ДЛИНЫ, КОТОРУЮ ЖДЁТ РАЗБОР ДЕНЕЖНОГО ПУТИ
        # (c2_swap_build.DLMM_ДЛИНА_СВОПА минус 16 байт двух дискриминаторов).
        # Смещения тоже его: пул 0, корзины 64, суммы 72, сторона 88, сборы 89.
        from solders.pubkey import Pubkey as _Pk  # noqa: PLC0415
        пул_ = str(_Pk(bytes([7] * 32)))
        тело = B_.DLMM_ДЛИНА_СВОПА - 16
        т = bytearray(тело)
        т[0:32] = bytes(_Pk.from_string(пул_))
        т[64:72] = _st.pack("<ii", ев_["start_bin_id"], ев_["end_bin_id"])
        т[72:88] = _st.pack("<QQ", ев_["amount_in"], ев_["amount_out"])
        т[88] = int(ев_["swap_for_y"])
        т = bytes(т)
        данные = B_.DLMM_CPI_ДИСК + B_.DLMM_СВОП_ДИСК + т
        счета_ = счета_ or [пул_, "бит", "хрX", "хрY", "нашX", "нашY",
                             "МИНТX", "МИНТY"]
        return пул_, {"transaction": {"message": {"accountKeys": [], "instructions": [
                    {"programId": ПРОГРАММА, "accounts": счета_,
                     "data": B_.b58encode(_st.pack("<8s", b"\x00" * 8)
                                           + b"\x00" * 8)}]}},
                "meta": {"innerInstructions": [{"instructions": [
                    {"programId": ПРОГРАММА, "data": B_.b58encode(данные)}]}]}}

    try:
        пул_, tx_ = _tx(ев)
        chk("событие пула находится в транзакции источника",
            len(события_пула(tx_, пул_)) == 1, события_пула(tx_, пул_))
        chk("счета инструкции берутся по НАШЕМУ пулу (место 0)",
            список_счетов(tx_, пул_)[МЕСТО_МИНТА_X] == "МИНТX")
        т1 = тень(tx_, пул_, {"expected_out": 2000}, лампорты=500,
                   минт_котировки="МИНТX")
        chk("тень: цена сошлась с ценой полосы -> годилось True, запас 0 %",
            т1["годилось"] is True and т1["наш_выход"] == 2000
            and т1["запас_нужен_%"] == 0.0 and т1["чтений"] == 0, т1)
        т2 = тень(tx_, пул_, {"expected_out": 1900}, лампорты=500,
                   минт_котировки="МИНТX")
        chk("тень: ЗАВЫСИЛИ против полосы -> годилось False и назван нужный запас",
            т2["годилось"] is False and т2["запас_нужен_%"] > 5.2
            and т2["отклонение_%"] > 0, т2)
        т3 = тень(tx_, пул_, {"expected_out": 2100}, лампорты=500,
                   минт_котировки="МИНТX")
        chk("тень: занизили -> годилось True (занижение безопасно)",
            т3["годилось"] is True and т3["запас_нужен_%"] == 0.0, т3)
        т4 = тень(tx_, пул_, {}, лампорты=500, минт_котировки="МИНТX")
        chk("без точной цены полосы -- НЕ True, а «сверить не с чем»",
            т4["годилось"] is None and "сверить не с чем" in (т4["почему_нет"] or ""),
            т4)
        т5 = тень(tx_, пул_, {"expected_out": 2000}, лампорты=500,
                   минт_котировки="МИНТY")
        chk("наша сторона обратная событию -> тень отказывает ПО ИМЕНИ",
            т5["годилось"] is None
            and ПРИЗНАК_ДРУГАЯ_СТОРОНА in (т5["почему_нет"] or ""), т5)
        chk("тень НЕ отдаёт min_out для отправки -- решений не принимает",
            "min_out" not in т1 and "expected_out" not in т1)
        chk("откатными считаются только свои причины",
            откатный(ПРИЗНАК_ДРУГАЯ_СТОРОНА) and откатный(ПРИЗНАК_НЕТ_СОБЫТИЯ)
            and not откатный("узел не ответил"))
        chk("тень на пустой транзакции -- отказ, а не исключение",
            тень(None, пул_, {"expected_out": 1}, лампорты=1,
                  минт_котировки="МИНТX")["годилось"] is None)
    except Exception as exc:  # noqa: BLE001
        chk("проверки тени прошли без исключения", False,
            f"{type(exc).__name__}: {exc}")

    # --- ПОДПИСЬ КОТИРОВКИ: rpc_call принимается, но НЕ используется
    import inspect  # noqa: PLC0415

    chk("котировка принимает rpc_call (совместимость) и tx_источника",
        {"rpc_call", "tx_источника"} <= set(inspect.signature(котировка).parameters))
    chk("rpc_call в теле котировки не используется ни разу",
        "rpc_call" not in inspect.getsource(котировка).split('"""')[2])

    print(f"самопроверка DLMM без чтений: {пройдено}/{пройдено + провалено} пройдено")
    return 0 if провалено == 0 else 1


if __name__ == "__main__":
    raise SystemExit(self_test() if "--self-test" in sys.argv else 0)
