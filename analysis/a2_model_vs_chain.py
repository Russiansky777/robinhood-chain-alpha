def горизонт_для(держали, sig) -> tuple[float | None, str]:
    """Рост на ближайшей к фактическому удержанию РЕАЛЬНОЙ точке кэша.

    В кэше только 0/+30/+60 с. Интерполяция запрещена условием задачи,
    поэтому берётся ближняя точка и её имя пишется в выгрузку.
    """
    держали = держали if держали is not None else 30
    if abs(держали - 30) <= abs(держали - 60):
        return sig.get("growth_after_30s"), "growth_after_30s"
    return sig.get("growth_after_60s"), "growth_after_60s"


def посчитать(набор: list, idx: dict, minty: dict, depth: dict, изд_по_набору: dict,
              варианты: dict, по_подписи_сигнала: dict | None = None
              ) -> tuple[list, collections.Counter]:
    """по_подписи_сигнала -- индекс сигналов кэша толпы по подписи сделки
    источника. У наших покупок источник в учёте не заполнен (метка бота
    другая), зато журнал позиций Bloom хранит подпись сделки источника --
    сопоставляем по ней, а не по адресу."""
    строки = []
    отказы: collections.Counter = collections.Counter()
    for t in набор:
        c = None
        сс = t.get("_подпись_источника")
        if сс and по_подписи_сигнала:
            c = по_подписи_сигнала.get(сс)
        if c is None:
            c = A.найти_сигнал(idx, t.get("mint"), t.get("source_address"), t.get("buy_block_time"))
        if not c:
            отказы["сигнала источника нет в кэше толпы"] += 1
            continue
        sig = build_signal(c, minty, depth)
        рост, имя_горизонта = горизонт_для(t.get("held_seconds"), sig)
        if рост is None:
            отказы[f"нет {имя_горизонта} в кэше для этой сделки"] += 1
            continue
        размер = t["sol_in"]
        факт_пп = t["net_sol"] / размер * 100.0
        # --- модель ДО: как есть в night_edge_model
        до_sol, почему = net_pnl_sol(sig["spot_after"], рост, sig, size_sol=размер)
        if до_sol is None:
            отказы[почему or "модель не смогла посчитать"] += 1
            continue
        изд = изд_по_набору[t["_набор"]]
        строка = {
            "набор": t["_набор"], "задача": t.get("task_name"), "минт": t.get("mint"),
            "источник": c.get("source_remark") or t.get("source_address"),
            "источник_адрес": t.get("source_address"),
            "подпись_покупки": t.get("buy_signature"),
            "время_покупки_utc": iso(t.get("buy_block_time")),
            "держали_с": t.get("held_seconds"), "горизонт": имя_горизонта,
            "шагов_proxy": sig["hops_proxy"],
            "размер_sol": round(размер, 9), "заявка_sol": t.get("_заявка"),
            "рост_из_кэша": round(рост, 6),
            "ставка_налога_доля": t["_ставка_налога"],
            "налоговых_переводов": t["_налоговых_переводов"],
            "издержки_покупки_по_цепи_sol": (round(размер - t["_заявка"], 9)
                                             if t.get("_заявка") else None),
            "факт_пп": round(факт_пп, 4),
            "модель_до_пп": round(до_sol / размер * 100.0, 4),
            "расхождение_до_пп": round(до_sol / размер * 100.0 - факт_пп, 4),
        }
        for имя, кв in варианты.items():
            net, _ = A.чистый_результат_sol(
                рост, размер, кв["издержки"](изд),
                ставка_налога_доля=(t["_ставка_налога"] if кв["налог_по_переводам"] else 0.0),
                налоговых_переводов=(t["_налоговых_переводов"] if кв["налог_по_переводам"] else 0),
                учитывать_порчу=кв["порча"])
            if net is None:
                continue
            строка[f"модель_{имя}_пп"] = round(net / размер * 100.0, 4)
            строка[f"расхождение_{имя}_пп"] = round(net / размер * 100.0 - факт_пп, 4)
        строки.append(строка)
    return строки, отказы


def издержки_покупки_таблица(набор: list, изд_по_набору: dict) -> tuple[list, dict]:
    """Издержки покупки: что модель снимает с покупки против того, что по
    цепи реально ушло сверх заявки.

    Это единственная часть круга, которая измерена ПО ЦЕПИ у КАЖДОЙ
    закрытой сделки: sol_in (фактическая дельта кошелька) минус заявка
    (сколько площадка записала как отправленное в сделку). Цена на
    горизонте для этого не нужна, поэтому здесь участвуют все сделки, а не
    только те, чей сигнал есть в кэше толпы.
    """
    строки = []
    for t in набор:
        заявка = t.get("_заявка")
        if not заявка or not t.get("sol_in"):
            continue
        размер = t["sol_in"]
        цепь = размер - заявка
        # модель ДО: доля площадки (Bloom 1%) + налог в SOL + чаевые + сеть
        до = размер * (0.01 + t["_ставка_налога"]) + 0.002 + 0.000005
        изд = изд_по_набору[t["_набор"]]
        после = изд.фикс_покупки + заявка * изд.доля_площадки
        строки.append({
            "набор": t["_набор"], "задача": t.get("task_name"), "минт": t.get("mint"),
            "подпись_покупки": t.get("buy_signature"),
            "время_покупки_utc": iso(t.get("buy_block_time")),
            "заявка_sol": round(заявка, 9), "размер_sol": round(размер, 9),
            "цепь_sol": round(цепь, 9), "цепь_пп": round(цепь / заявка * 100, 4),
            "модель_до_sol": round(до, 9), "модель_до_пп": round(до / заявка * 100, 4),
            "модель_после_sol": round(после, 9), "модель_после_пп": round(после / заявка * 100, 4),
            "расхождение_до_пп": round((до - цепь) / заявка * 100, 4),
            "расхождение_после_пп": round((после - цепь) / заявка * 100, 4),
        })
    свод = {
        "сделок": len(строки),
        "цепь_пп": A.разброс([s["цепь_пп"] for s in строки]),
        "модель_до_пп": A.разброс([s["модель_до_пп"] for s in строки]),
        "модель_после_пп": A.разброс([s["модель_после_пп"] for s in строки]),
        "расхождение_до_пп": A.разброс([s["расхождение_до_пп"] for s in строки]),
        "расхождение_после_пп": A.разброс([s["расхождение_после_пп"] for s in строки]),
    }
    return строки, свод


def налог_таблица(набор: list) -> tuple[list, dict]:
    """Налог маршрута: сколько его снимает модель против того, сколько
    реально удержано по цепи (аудит комиссии на перевод, по балансам).

    Модель ДО: доля ставки снимается ДВАЖДЫ (по разу на сторону) с суммы
    сделки в SOL. По цепи налог удерживается В ТОКЕНАХ на КАЖДОМ переводе
    налогового минта, и переводов на круг бывает от 2 до 8.
    """
    строки = []
    for t in набор:
        row = t.get("_аудит")
        if not row or row.get("удержано_sol") is None:
            continue
        if row.get("налог_неполон_нет_курса"):
            continue
        размер = t["sol_in"]
        цепь = row["удержано_sol"]
        r = t["_ставка_налога"]
        k = t["_налоговых_переводов"]
        до = 2.0 * размер * r
        # после: множитель (1-r)^k на позицию в пуле
        позиция = max(0.0, размер - 0.0)
        после = позиция * (1.0 - (1.0 - r) ** max(0, int(k))) if r else 0.0
        строки.append({
            "набор": t["_набор"], "минт": t.get("mint"), "подпись_покупки": t.get("buy_signature"),
            "ставка_доля": r, "налоговых_переводов": k, "размер_sol": round(размер, 9),
            "цепь_sol": round(цепь, 9), "цепь_пп": round(цепь / размер * 100, 4),
            "модель_до_пп": round(до / размер * 100, 4),
            "модель_после_пп": round(после / размер * 100, 4),
            "расхождение_до_пп": round((до - цепь) / размер * 100, 4),
            "расхождение_после_пп": round((после - цепь) / размер * 100, 4),
        })
    налоговые = [s for s in строки if s["ставка_доля"] > 0]
    свод = {
        "сделок": len(строки), "из_них_налоговых": len(налоговые),
        "цепь_пп_налоговые": A.разброс([s["цепь_пп"] for s in налоговые]),
        "расхождение_до_пп_налоговые": A.разброс([s["расхождение_до_пп"] for s in налоговые]),
        "расхождение_после_пп_налоговые": A.разброс([s["расхождение_после_пп"] for s in налоговые]),
        "переводов_разброс": A.разброс([s["налоговых_переводов"] for s in налоговые]),
    }
    return строки, свод


def подбор_комиссии_пула(набор: list, idx: dict, minty: dict, depth: dict,
                         изд_по_набору: dict) -> dict:
    """ДИАГНОСТИКА, НЕ ИЗМЕРЕНИЕ. Какая ставка комиссии пула (bps на
    сторону) обнулила бы остаточную медиану расхождения. Ставка по
    pool_program в репозитории не найдена -- это объявленный пробел
    night_edge_model; число ниже говорит только, СОВПАДАЕТ ли остаток по
    величине с правдоподобной комиссией пула, и в модель не подставляется.
    """
    лучшая = None
    for bps in range(0, 201, 5):
        разности = []
        for t in набор:
            c = A.найти_сигнал(idx, t.get("mint"), t.get("source_address"), t.get("buy_block_time"))
            if not c:
                continue
            sig = build_signal(c, minty, depth)
            рост, _ = горизонт_для(t.get("held_seconds"), sig)
            if рост is None or not sig["target_tax_known"]:
                continue
            изд = изд_по_набору[t["_набор"]]
            проба = A.Издержки(изд.фикс_покупки, изд.фикс_продажи, изд.доля_площадки,
                               изд.порча_множителя, комиссия_пула_bps=bps, название=изд.название)
            net, _w = A.чистый_результат_sol(рост, t["sol_in"], проба,
                                             t["_ставка_налога"], t["_налоговых_переводов"])
            if net is None:
                continue
            разности.append(net / t["sol_in"] * 100 - t["net_sol"] / t["sol_in"] * 100)
        if not разности:
            continue
        м = abs(statistics.median(разности))
        if лучшая is None or м < лучшая[1]:
            лучшая = (bps, м, statistics.median(разности))
    if not лучшая:
        return {"известно": False}
    return {"известно": True, "bps_на_сторону": лучшая[0],
            "остаточная_медиана_пп": round(лучшая[2], 4),
            "оговорка": "подбор, а не измерение: ставка комиссии пула по pool_program "
                        "в репозитории отсутствует; в модель не подставлена"}


def по_размеру(строки: list, ключ_размера: str = "заявка_sol") -> dict:
    """Разбивка по размеру заявки -- без неё наши пробные сделки на 0.001 SOL
    перекашивают медиану: фиксированные лампорты у них больше самой ставки."""
    групп = collections.defaultdict(list)
    for s in строки:
        z = s.get(ключ_размера)
        if z is None:
            групп["заявка неизвестна"].append(s)
        elif z < 0.01:
            групп["до 0.01 SOL (пробные)"].append(s)
        elif z < 0.1:
            групп["0.01-0.1 SOL"].append(s)
        else:
            групп["0.1 SOL и больше"].append(s)
    return {k: {"сделок": len(v),
                "цепь_пп": A.разброс([x["цепь_пп"] for x in v]),
                "расхождение_до_пп": A.разброс([x["расхождение_до_пп"] for x in v]),
                "расхождение_после_пп": A.разброс([x["расхождение_после_пп"] for x in v])}
            for k, v in sorted(групп.items())}


def переводов_по_шагам(строки: list) -> dict:
    """Сколько налоговых переводов на круг бывает при данном ПРОКСИ числа
    шагов маршрута. Нужно для A1/A3: у будущего сигнала фактического числа
    переводов нет, а прокси шагов (котировка SOL / не SOL / split_route)
    есть. Считается только по налоговым сделкам -- у безналоговых переводов
    ноль по определению.
    """
    групп = collections.defaultdict(list)
    for s in строки:
        if s.get("ставка_налога_доля"):
            групп[s.get("шагов_proxy")].append(s["налоговых_переводов"])
    return {str(k): {"n": len(v), "медиана": A.med(v), "макс": max(v)}
            for k, v in sorted(групп.items()) if v}


