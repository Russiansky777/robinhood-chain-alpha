def по_источникам(строки: list, ключ: str) -> dict:
    групп = collections.defaultdict(list)
    for s in строки:
        групп[s["источник"] or "неизвестен"].append(s)
    out = {}
    for k, v in sorted(групп.items(), key=lambda kv: -len(kv[1])):
        out[k] = {"сделок": len(v), "расхождение": A.разброс([x[ключ] for x in v if x.get(ключ) is not None]),
                  "факт_медиана_пп": A.med([x["факт_пп"] for x in v])}
    return out


