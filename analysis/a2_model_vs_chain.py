def налог_по_сделке(row: dict | None, minty: dict) -> tuple[float, int]:
    """(ставка_доля, число налоговых переводов) по строке аудита.

    Ставка -- у самого торгуемого минта; переводы -- сумма переводов ВСЕХ
    налоговых минтов маршрута (цель + промежуточные). Именно это исходная
    модель считала "один раз на сторону".
    """
    if not row:
        return 0.0, 0
    переводов = 0
    ставки = []
    for m, n in (row.get("переводов_по_минтам") or {}).items():
        info = minty.get(m) or {}
        if info.get("таксируемый"):
            переводов += int(n or 0)
            ставки.append((info.get("ставка_комиссии_bps") or 0) / 10000.0)
    if not ставки:
        return 0.0, 0
    return max(ставки), переводов


def собрать_dbot(tr: list, aud_rows: dict, minty: dict) -> list:
    out = []
    for t in tr:
        if t.get("bot") != "dbot" or t.get("status") != "закрыта":
            continue
        if not t.get("sol_in") or t.get("net_sol") is None:
            continue
        row = aud_rows.get(t.get("buy_signature"))
        ставка, переводов = налог_по_сделке(row, minty)
        out.append({**t, "_аудит": row, "_ставка_налога": ставка, "_налоговых_переводов": переводов,
                    "_заявка": t.get("gross_sol_in"), "_набор": "DBot"})
    return out


def собрать_наши(tr: list, diag: dict | None, aud_rows: dict, minty: dict) -> list:
    """Наши покупки: Bloom, TradeWiz и полоса своей отправки.

    Заявка (интент) берётся из журнала позиций Bloom
    (data/bloom_seller_diag.json) по подписи покупки. Нет позиции -- заявка
    неизвестна, и это так и помечается, сделка не выбрасывается.
    """
    по_подписи = {}
    for r in ((diag or {}).get("positions_rows") or []):
        for s in (r.get("signatures") or []):
            по_подписи.setdefault(s, {}).update({k: v for k, v in r.items() if v is not None})
    # интент и налог лежат в событии 'intent' того же client_order_id
    по_cid: dict = {}
    for r in ((diag or {}).get("positions_rows") or []):
        cid = r.get("client_order_id")
        if cid:
            по_cid.setdefault(cid, {}).update({k: v for k, v in r.items() if v is not None})
    out = []
    for t in tr:
        if t.get("bot") not in ("bloom", "tradewiz"):
            continue
        if t.get("status") not in ("закрыта", "ручная продажа"):
            continue
        поз = по_подписи.get(t.get("buy_signature")) or {}
        cid = поз.get("client_order_id")
        поз = {**(по_cid.get(cid) or {}), **поз} if cid else поз
        row = aud_rows.get(t.get("buy_signature"))
        ставка, переводов = налог_по_сделке(row, minty)
        if not переводов and поз.get("taxed") and поз.get("tax_bps"):
            # налоговый статус известен от Bloom, но сделки нет в аудите:
            # число переводов неизвестно -- НЕ подставляем, помечаем
            ставка = (поз.get("tax_bps") or 0) / 10000.0
        out.append({**t, "_аудит": row, "_ставка_налога": ставка,
                    "_налоговых_переводов": переводов,
                    "_заявка": поз.get("sol_in"), "_позиция": поз, "_набор": "наши",
                    "_подпись_источника": поз.get("source_sig")})
    return out


