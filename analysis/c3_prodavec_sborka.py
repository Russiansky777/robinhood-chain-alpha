def _продажа_не_покупка(образец: dict, ш: dict) -> bool:
    """Инструкция продажи обязана отличаться от инструкции покупки того же пула."""
    import importlib  # noqa: PLC0415

    try:
        M = importlib.import_module(ТИПЫ[ш["program"]]["модуль"])
        _C, _B = _кирпичи()
        т = M.шаблон(образец["tx"], None, хранилище=образец.get("pool_vault"))
        п = M.под_покупку(т, образец["tx"],
                          минт_котировки=(образец.get("quote_mint") or _C.WSOL))
        if not п.get("ok"):
            return False
        и_пок = M.инструкция_свопа(п["шаблон"], user=КОШЕЛЁК_ПРОВЕРКИ,
                                   amount_in=1, min_out=1)
        и_прод = инструкция_продажи(ш, наш_кошелёк=КОШЕЛЁК_ПРОВЕРКИ, база_в=1,
                                    минимум_выхода=1)
        a = [str(m.pubkey) for m in и_пок.accounts]
        b = [str(m.pubkey) for m in и_прод.accounts]
        return a != b or bytes(и_пок.data) != bytes(и_прод.data)
    except Exception:  # noqa: BLE001
        return False


