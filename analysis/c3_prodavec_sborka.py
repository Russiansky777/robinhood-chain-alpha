def подготовить(tx_покупки: dict, *, программа: str, наш_кошелёк: str,
                 база_в: int, минт_базы: str | None = None,
                 минт_котировки: str | None = None, хранилище: str | None = None,
                 программа_базы: str = SPL_ТОКЕН,
                 резерв_базы=None, резерв_котировки=None, котировка_типа=None,
                 пол_лампорты: int = 0, запас: float | None = None,
                 продаём_всё: bool = True, cu_units=None,
                 приоритет_micro: int = 0) -> dict:
    """ПРОДАЖА одной транзакцией: бюджет, своп токен -> SOL, закрытие счетов.

    Зеркало покупки: шаблон -- из нашей же покупки, инструкция -- модуля типа,
    минимум -- от резервов или котировщика с полом из аргумента.
    """
    из_ = {"ok": False, "why_not": None, "способ": способ(программа),
            "метка": тип(программа).get("метка"), "program": программа,
            "tx_base64": None, "size": None, "n_instructions": None,
            "min_out": None, "min_out_откуда": None, "cu_units": None,
            "закрыт_счёт_токена": None, "закрыт_счёт_wsol": None,
            "имя_инструкции": None, "база_в": int(база_в or 0)}
    try:
        C, B = _кирпичи()
        from solders.hash import Hash  # noqa: PLC0415
        from solders.message import MessageV0  # noqa: PLC0415
        from solders.pubkey import Pubkey  # noqa: PLC0415
        from solders.signature import Signature  # noqa: PLC0415
        from solders.transaction import VersionedTransaction  # noqa: PLC0415
    except Exception as сбой:  # noqa: BLE001
        из_["why_not"] = f"модули не загружены: {type(сбой).__name__}"
        return из_
    кот = минт_котировки or C.WSOL
    ш = шаблон_продажи(tx_покупки, программа=программа, минт_базы=минт_базы,
                        минт_котировки=кот, хранилище=хранилище)
    из_["имя_инструкции"] = ш.get("имя_инструкции")
    if not ш.get("ok"):
        из_["why_not"] = ш.get("why_not")
        return из_
    мо = minimum_vyhoda(база_в=int(база_в), резерв_базы=резерв_базы,
                        резерв_котировки=резерв_котировки,
                        котировка_типа=котировка_типа,
                        пол_лампорты=пол_лампорты, запас=запас)
    из_.update(min_out=мо.get("min_out"), min_out_откуда=мо.get("откуда"))
    if not мо.get("ok"):
        из_["why_not"] = мо.get("why_not")
        return из_
    cu = предел_cu(программа, cu_units)
    из_["cu_units"] = cu
    try:
        ixs = [B.cu_limit(cu)]
        if приоритет_micro:
            ixs.append(B.cu_price(int(приоритет_micro)))
        ixs.append(инструкция_продажи(ш, наш_кошелёк=наш_кошелёк,
                                       база_в=int(база_в),
                                       минимум_выхода=int(мо["min_out"])))
        # ЗАКРЫТИЕ ТОКЕНОВОГО СЧЁТА -- ТОЛЬКО КОГДА ПРОДАЁТСЯ ВЕСЬ ОСТАТОК.
        if продаём_всё and (ш.get("минт_базы") or минт_базы):
            счёт_б = B.ata(наш_кошелёк, ш.get("минт_базы") or минт_базы,
                           программа_базы)
            ixs.append(инструкция_закрытия(счёт_б, наш_кошелёк, программа_базы))
            из_["закрыт_счёт_токена"] = счёт_б
        else:
            из_["закрыт_счёт_токена_почему_нет"] = PRICHINA_CHASTICHNO
        if кот == C.WSOL:
            счёт_w = B.ata(наш_кошелёк, C.WSOL, SPL_ТОКЕН)
            ixs.append(инструкция_закрытия(счёт_w, наш_кошелёк, SPL_ТОКЕН))
            из_["закрыт_счёт_wsol"] = счёт_w
        else:
            из_["закрыт_счёт_wsol_почему_нет"] = (
                f"котировка пула {кот[:8]} не WSOL -- закрывать нечего, "
                f"выручка приходит токеном")
        msg = MessageV0.try_compile(Pubkey.from_string(наш_кошелёк), ixs, [],
                                    Hash.default())
        сырое = bytes(VersionedTransaction.populate(
            msg, [Signature.default()] * msg.header.num_required_signatures))
    except Exception as сбой:  # noqa: BLE001
        из_["why_not"] = f"сборка продажи: {type(сбой).__name__}: {str(сбой)[:140]}"
        return из_
    из_.update(ok=True, tx_base64=base64.b64encode(сырое).decode(),
               size=len(сырое), n_instructions=len(ixs))
    return из_


