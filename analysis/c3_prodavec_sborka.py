def _kriwaja_v3_iz_pokupki(tx_покупки: dict) -> dict:
    """Наша покупка была v3? Тогда минт, программа токена и получатель buyback.

    Ищется инструкция программы кривой, дискриминатор которой IDL знает как
    buy_exact_quote_in_v3 или buy_v3. Всё, что нужно продаже, берётся по ИМЕНАМ
    IDL из той же инструкции: выдумывать тут нечего.
    """
    из_ = {"ok": False, "why_not": None}
    try:
        import c2_swap_build as B_  # noqa: PLC0415
        import c3_pump_sborka as PS  # noqa: PLC0415
    except Exception as сбой:  # noqa: BLE001
        из_["why_not"] = f"сборщик по IDL не доступен: {type(сбой).__name__}"
        return из_
    try:
        инстр = list(B_.all_instructions(tx_покупки))
    except Exception:  # noqa: BLE001
        инстр = []
    for и in инстр:
        if и.get("programId") != КРИВАЯ_ПРОГРАММА:
            continue
        try:
            данные = B_.b58decode(и["data"])
        except Exception:  # noqa: BLE001
            continue
        имя = PS.variant_po_disku("pump", данные[:8])
        прод = IDL_ПРОДАЖА_ПО_ПОКУПКЕ.get(имя or "")
        if not прод:
            continue
        имена = [а["name"] for а in PS.zagruzit_idl()["pump"]["ix"][имя]["accounts"]]
        по_именам = dict(zip(имена, list(и.get("accounts") or []), strict=False))
        минт = по_именам.get("base_mint")
        выкуп = по_именам.get("buyback_fee_recipient")
        if not (минт and выкуп):
            из_["why_not"] = (f"{имя}: в покупке нет base_mint или "
                              "buyback_fee_recipient")
            return из_
        try:
            тп = PS.programma_tokena_minta(
                минт, iz_signala=по_именам.get("base_token_program"))
        except PS.ОшибкаСборки as сбой:
            из_["why_not"] = str(сбой)
            return из_
        return {"ok": True, "pokupka": имя, "prodazha": прод, "base_mint": минт,
                "base_token_program": тп, "buyback_fee_recipient": выкуп,
                "quote_mint": по_именам.get("quote_mint")}
    return из_


def шаблон_продажи(tx_покупки: dict, *, программа: str,
                    минт_базы: str | None = None,
                    минт_котировки: str | None = None,
                    хранилище: str | None = None,
                    счёт_комиссии_базы: str | None = None) -> dict:
    """Шаблон ПРОДАЖИ (вход -- база, выход -- котировка) из нашей покупки.

    Возвращает {ok, why_not, способ, метка, program, accounts, writable, tpl,
    имя_инструкции, хвост, минт_базы, минт_котировки}. `tpl` -- шаблон того вида,
    который ждёт инструкция соответствующего модуля.
    """
    C, B = _кирпичи()
    из_ = {"ok": False, "why_not": None, "способ": способ(программа),
            "метка": тип(программа).get("метка"), "program": программа,
            "accounts": None, "writable": None, "tpl": None,
            "имя_инструкции": None, "хвост": None,
            "минт_базы": минт_базы, "минт_котировки": минт_котировки or C.WSOL}
    # ПОКУПКА БЫЛА v3 -- ПРОДАЁМ sell_v3 ПО ИМЕНАМ IDL, без карты мест.
    # ТОЛЬКО КОГДА ПОЗИЦИЯ ЧИСЛИТСЯ НА КРИВОЙ. Покупка на Pump AMM тоже могла бы
    # нести инструкцию кривой во внутренних (переезд в той же транзакции), и
    # продать купленное в пуле AMM на кривой значит отдать программе чужой счёт.
    v3 = ({"ok": False, "why_not": "программа позиции не кривая"}
          if программа != КРИВАЯ_ПРОГРАММА
          else _kriwaja_v3_iz_pokupki(tx_покупки))
    if v3.get("ok"):
        из_.update(ok=True, способ=SPOSOB_PO_IDL, program=КРИВАЯ_ПРОГРАММА,
                   po_idl=v3["prodazha"], имя_инструкции=v3["prodazha"],
                   минт_базы=v3["base_mint"],
                   программа_базы=v3["base_token_program"],
                   buyback_fee_recipient=v3["buyback_fee_recipient"],
                   tpl=None, accounts=None, writable=None,
                   минт_котировки=v3.get("quote_mint") or из_["минт_котировки"])
        return из_
    т = тип(программа)
    if not т:
        из_["why_not"] = f"тип пула не известен: {str(программа)[:8]}"
        return из_
    if т.get("способ") is None:
        из_["why_not"] = f"{PRICHINA_NET_SPOSOBA}: {т.get('почему_нет')}"
        return из_
    try:
        if т["способ"] == SPOSOB_IZ_POKUPKI:
            import bloom_lane_sell as LS  # noqa: PLC0415

            ш = LS.шаблон_продажи_из_покупки(tx_покупки, программа=программа,
                                              хранилище=хранилище)
            if not ш.get("ok"):
                из_["why_not"] = ш.get("why_not")
                return из_
            # МИНТ БАЗЫ -- ИЗ РАСКЛАДКИ, А НЕ ПУСТОЙ. Без него котировка продажи
            # и закрытие токенового счёта остались бы без минта: место 3 -- это
            # base_mint у обеих раскладок Pump AMM (SPECS и SPECS_ПРОДАЖИ).
            спец = (B.SPECS_ПРОДАЖИ.get(программа) or B.SPECS.get(программа) or {})
            м_б = спец.get("base_mint")
            база_pa = (ш["accounts"][м_б] if isinstance(м_б, int)
                       and len(ш["accounts"]) > м_б else None)
            из_.update(ok=True, accounts=list(ш["accounts"]), writable=ш["writable"],
                       tpl=ш, имя_инструкции="sell",
                       минт_базы=(минт_базы or база_pa))
            return из_
        if т["способ"] == SPOSOB_KRIVAYA:
            пок = инструкция_покупки(tx_покупки, программа=программа,
                                      хранилище=хранилище)
            if not пок.get("ok"):
                из_["why_not"] = пок.get("why_not")
                return из_
            диск = bytes(пок["data"][:8]).hex()
            # РАЗНОВИДНОСТЬ РЕШАЕТ ПОКУПКА, а не наше предпочтение: 18-счётная
            # покупка -> продажа sell (16 счетов), 27-счётная v2 -> sell_v2 (26).
            if диск in КРИВАЯ_V2_ПОКУПКИ:
                return _шаблон_кривая_v2(пок, программа=программа,
                                          минт_базы=минт_базы, B=B)
            if диск not in КРИВАЯ_ПОКУПКИ_18 or len(пок["accounts"]) != 18:
                из_["why_not"] = (f"{ПРИЧИНА_КРИВАЯ_ВАРИАНТ}: дискриминатор {диск}, "
                                   f"счетов {len(пок['accounts'])}")
                return из_
            счета = [пок["accounts"][j] for j in КРИВАЯ_МЕСТА_ПРОДАЖИ]
            # МИНТ БАЗЫ -- МЕСТО 2 РАСКЛАДКИ ПОКУПКИ (SPECS[кривая]["base_mint"]).
            спец = B.SPECS.get(программа) or {}
            м_б = спец.get("base_mint")
            база = минт_базы or (пок["accounts"][м_б]
                                 if isinstance(м_б, int) else None)
            if not база:
                из_["why_not"] = "минт базы не известен -- вход продажи назвать нечем"
                return из_
            tpl = {"ok": True, "program": программа, "accounts": счета,
                    "data": bytes(пок["data"]), "writable": пок["writable"],
                    "ix": "sell", "продажа": True}
            # ХВОСТ ДАННЫХ НЕ ПЕРЕНОСИТСЯ: у живых продаж данные ровно 24 байта
            # (дискриминатор и два u64), хвоста нет ни у одной из шести.
            из_.update(ok=True, accounts=счета, writable=пок["writable"], tpl=tpl,
                       имя_инструкции="sell", минт_базы=база, хвост=b"",
                       минт_котировки=None, нативная_котировка=True,
                       программа_базы=счета[9])
            return из_
        if т["способ"] == SPOSOB_DAMM1:
            пок = инструкция_покупки(tx_покупки, программа=программа,
                                      хранилище=хранилище)
            if not пок.get("ok"):
                из_["why_not"] = пок.get("why_not")
                return из_
            if len(пок["accounts"]) != DAMM1_СЧЕТОВ:
                из_["why_not"] = (f"счетов покупки {len(пок['accounts'])}, а раскладка "
                                   f"DAMM v1 снята на {DAMM1_СЧЕТОВ}")
                return из_
            if not счёт_комиссии_базы:
                из_["why_not"] = ПРИЧИНА_DAMM1_КОМИССИЯ
                return из_
            счета = list(пок["accounts"])
            м = DAMM1_МЕСТА
            счета[м["счёт_входа"]], счета[м["счёт_выхода"]] = (
                счета[м["счёт_выхода"]], счета[м["счёт_входа"]])
            счета[м["комиссия_входа"]] = счёт_комиссии_базы
            tpl = {"ok": True, "program": программа, "accounts": счета,
                    "data": bytes(пок["data"]), "writable": пок["writable"],
                    "ix": "swap", "продажа": True}
            права = dict(пок["writable"])
            # СЧЁТ КОМИССИИ ПИШЕТСЯ ПРОГРАММОЙ: в живых продажах он всегда с
            # правом записи, и без него программа отказала бы.
            права[счёт_комиссии_базы] = True
            из_.update(ok=True, accounts=счета, writable=права, tpl=tpl,
                       имя_инструкции="swap", минт_базы=минт_базы,
                       хвост=bytes(пок["data"][24:]),
                       счёт_комиссии_базы=счёт_комиссии_базы)
            return из_
        if т["способ"] == SPOSOB_TA_ZHE_RASKLADKA:
            пр = ТА_ЖЕ_РАСКЛАДКА[программа]
            пок = инструкция_покупки(tx_покупки, программа=программа,
                                      хранилище=хранилище)
            if not пок.get("ok"):
                из_["why_not"] = пок.get("why_not")
                return из_
            диск = bytes(пок["data"][:8]).hex()
            if диск not in пр["покупки"]:
                из_["why_not"] = (f"разновидность покупки не та, на которой проверена "
                                   f"продажа: дискриминатор {диск}")
                return из_
            if len(пок["accounts"]) != пр["счетов"]:
                из_["why_not"] = (f"счетов покупки {len(пок['accounts'])}, а продажа "
                                   f"проверена на {пр['счетов']}")
                return из_
            хвост = bytes(пок["data"][24:])
            if len(хвост) != пр["хвост"]:
                из_["why_not"] = (f"хвост данных покупки {len(хвост)} байт, а у "
                                   f"проверенной продажи {пр['хвост']}")
                return из_
            спец = B.SPECS.get(программа) or {}
            м_б = спец.get("base_mint")
            база = минт_базы or (пок["accounts"][м_б]
                                 if isinstance(м_б, int) else None)
            if not база:
                из_["why_not"] = "минт базы не известен -- вход продажи назвать нечем"
                return из_
            tpl = {"ok": True, "program": программа,
                    "accounts": list(пок["accounts"]), "data": bytes(пок["data"]),
                    "writable": пок["writable"], "ix": пр["ix_продажи"],
                    "продажа": True}
            из_.update(ok=True, accounts=list(пок["accounts"]),
                       writable=пок["writable"], tpl=tpl,
                       имя_инструкции=пр["ix_продажи"], минт_базы=база, хвост=хвост)
            return из_
        if т["способ"] == SPOSOB_PARY:
            import bloom_lane_two_step as TS  # noqa: PLC0415

            пок = инструкция_покупки(tx_покупки, программа=программа,
                                      хранилище=хранилище)
            if not пок.get("ok"):
                из_["why_not"] = пок.get("why_not")
                return из_
            tpl = {"ok": True, "program": программа, "accounts": пок["accounts"],
                    "data": пок["data"], "writable": пок["writable"],
                    "ix": "swap_base_input"}
            база = минт_базы or (пок["accounts"][11] if len(пок["accounts"]) > 11
                                 else None)
            if not база:
                из_["why_not"] = "минт базы не известен -- переворот CPMM не проверить"
                return из_
            перев = TS.перевернуть_cpmm(tpl, база)
            из_.update(ok=True, accounts=list(перев["accounts"]),
                       writable=пок["writable"], tpl=перев,
                       имя_инструкции="swap_base_input", минт_базы=база,
                       хвост=bytes(пок["data"][24:]))
            return из_
        if т["способ"] == SPOSOB_STROITEL:
            import importlib  # noqa: PLC0415

            M = importlib.import_module(т["модуль"])
            ш = M.шаблон(tx_покупки, None, хранилище=хранилище)
            if not ш.get("ok"):
                из_["why_not"] = f"шаблон покупки: {ш.get('why_not')}"
                return из_
            # ВХОД НА БАЗУ: под_покупку ставит входом ту сторону, минт которой ей
            # назвали. Минт базы -- наш токен, значит продажа.
            база = минт_базы or _минт_базы_по_шаблону(M, ш, tx_покупки,
                                                       из_["минт_котировки"])
            if not база:
                из_["why_not"] = "минт базы не выведен -- вход продажи назвать нечем"
                return из_
            п = M.под_покупку(ш, tx_покупки, минт_котировки=база)
            if not п.get("ok"):
                # НЕ ВСЕ СТРОИТЕЛИ ПРИНИМАЮТ БАЗУ КАК КОТИРОВКУ. У DBC
                # под_покупку сверяет НАЗНАЧЕННУЮ котировку пула и честно
                # отказывает. Тогда переставляются ровно те два места, которые
                # переставляет он сам при обратном направлении источника -- по
                # ЕГО ЖЕ раскладке (РАСКЛАДКА["счёт_входа"]/["счёт_выхода"]),
                # а не по нашей догадке.
                отк = _perevernut_po_raskladke(M, ш, tx_покупки)
                if not отк.get("ok"):
                    из_["why_not"] = (f"разворот под продажу: {п.get('why_not')}; "
                                       f"по раскладке: {отк.get('why_not')}")
                    return из_
                из_.update(ok=True, accounts=list(отк["шаблон"]["accounts"]),
                           writable=dict(отк["шаблон"].get("writable") or {}),
                           tpl=отк["шаблон"],
                           имя_инструкции=(отк["шаблон"].get("вид")
                                            or отк["шаблон"].get("ix")),
                           минт_базы=база, развёрнут=True,
                           разворот="по раскладке модуля")
                return из_
            tpl = п["шаблон"]
            из_.update(ok=True, accounts=list(tpl["accounts"]),
                       writable=dict(tpl.get("writable") or {}), tpl=tpl,
                       имя_инструкции=tpl.get("вид") or tpl.get("ix"),
                       минт_базы=база, развёрнут=bool(п.get("развёрнут")))
            return из_
        # flip: DLMM и DAMM v2 -- кирпичами c2_swap_build
        пок = инструкция_покупки(tx_покупки, программа=программа,
                                  хранилище=хранилище)
        if not пок.get("ok"):
            из_["why_not"] = пок.get("why_not")
            return из_
        tpl = {"ok": True, "program": программа, "accounts": пок["accounts"],
                "data": пок["data"], "writable": пок["writable"],
                "ix": _имя_по_диску(B, пок["data"])}
        if not tpl["ix"]:
            из_["why_not"] = (f"имя инструкции покупки не узнано по дискриминатору "
                               f"{пок['disc']}")
            return из_
        mv = B.mints_and_vaults(tpl, tx_покупки)
        база = минт_базы or (mv or {}).get("base_mint")
        if not база:
            из_["why_not"] = "минты и хранилища покупки не разобрались"
            return из_
        перев = B.flip_template(tpl, база)
        # НАШИ МЕСТА ВХОДА И ВЫХОДА МЕНЯЮТСЯ МЕСТАМИ -- ИНАЧЕ ЭТО НЕ ПРОДАЖА.
        # flip_template помечает шаблон (force_in) для c2_swap_build.swap_instruction,
        # который сам ставит наши счета по направлению; здесь инструкция собирается
        # своими руками, и без перестановки на месте входа остался бы счёт
        # КОТИРОВКИ -- программа сделала бы ещё одну покупку на размер остатка.
        # Места берутся из таблицы общего модуля (c2_swap_build.DYN), а не из
        # догадки, и проверены живыми сделками: у DAMM v2 в живых ПРОДАЖАХ на
        # месте 2 стоит счёт БАЗЫ (убыло), на месте 3 -- котировки, а в живых
        # покупках наоборот; у DLMM место 4 -- вход (убыло), 5 -- выход (пришло).
        к_ = (B.DYN.get(программа) or {})
        и_, ж_ = к_.get("in"), к_.get("out")
        счета_пр = list(перев["accounts"])
        if not isinstance(и_, int) or not isinstance(ж_, int) \
                or max(и_, ж_) >= len(счета_пр):
            из_["why_not"] = (f"места входа и выхода этого типа не названы в DYN: "
                               f"{и_}, {ж_}")
            return из_
        счета_пр[и_], счета_пр[ж_] = счета_пр[ж_], счета_пр[и_]
        перев = dict(перев, accounts=счета_пр)
        из_.update(ok=True, accounts=list(счета_пр),
                   writable=пок["writable"], tpl=перев, имя_инструкции=tpl["ix"],
                   минт_базы=база, хвост=bytes(пок["data"][24:]),
                   переставлены_места=[и_, ж_])
        return из_
    except Exception as сбой:  # noqa: BLE001
        из_["why_not"] = f"шаблон продажи: {type(сбой).__name__}: {str(сбой)[:140]}"
        return из_


def _пда(семена: list, программа) -> str:
    """PDA по семенам: байты как есть, строка длиной ключа -- как ключ."""
    from solders.pubkey import Pubkey  # noqa: PLC0415

    сем = []
    for с in семена:
        if isinstance(с, bytes):
            сем.append(с)
        else:
            try:
                сем.append(bytes(Pubkey.from_string(str(с))))
            except Exception:  # noqa: BLE001
                сем.append(str(с).encode())
    прог = (программа if isinstance(программа, bytes)
            else bytes(Pubkey.from_string(str(программа))))
    return str(Pubkey.find_program_address(сем, Pubkey.from_bytes(прог))[0])


def _ата(владелец: str, программа_токена: str, минт: str) -> str:
    """ATA по семенам IDL: (владелец, программа токена, минт) под программой ATA."""
    return _пда([владелец, программа_токена, минт], ATA_ПРОГРАММА)


