def _имя_по_диску(B, данные: bytes):
    for имя in ("swap", "swap2", "swap_v2", "swap_base_input", "swap_exact_in"):
        if данные[:8] == B.disc(имя):
            return имя
    return None


def _perevernut_po_raskladke(M, ш: dict, tx: dict) -> dict:
    """Переставить наши места входа и выхода по РАСКЛАДКЕ самого модуля типа.

    Стороны прикрепляются к шаблону ЗЕРКАЛЬНО: вход -- база, выход -- котировка.
    Без них инструкция_свопа честно отказывает «стороны пула не известны»: минтов
    в инструкции может не быть вовсе, и наши токеновые счета не вывести.
    """
    р = getattr(M, "РАСКЛАДКА", None)
    if not isinstance(р, dict):
        return {"ok": False, "why_not": "у модуля нет таблицы РАСКЛАДКА"}
    и, ж = р.get("счёт_входа"), р.get("счёт_выхода")
    счета = list(ш.get("accounts") or [])
    if not isinstance(и, int) or not isinstance(ж, int) or max(и, ж) >= len(счета):
        return {"ok": False,
                 "why_not": f"места входа и выхода не названы или вне списка: {и}, {ж}"}
    счета[и], счета[ж] = счета[ж], счета[и]
    стор = getattr(M, "стороны", None)
    с = стор(ш, tx) if callable(стор) else {}
    с = с if isinstance(с, dict) else {}
    if not с.get("минт_базы") or not с.get("минт_котировки"):
        return {"ok": False,
                 "why_not": f"стороны пула не разобрались: {с.get('why_not')}"}
    шаб = dict(ш, accounts=счета, развёрнут=True,
                минт_входа=с["минт_базы"], минт_выхода=с["минт_котировки"],
                программа_входа=с.get("программа_базы"),
                программа_выхода=с.get("программа_котировки"))
    return {"ok": True, "шаблон": шаб}


def _минт_базы_по_шаблону(M, ш: dict, tx: dict, минт_котировки: str):
    """Минт базы: сторона пула, которая НЕ котировка. По функциям самого модуля."""
    for имя in ("минты_и_хранилища", "шаблон_со_сторонами", "стороны"):
        фн = getattr(M, имя, None)
        if not callable(фн):
            continue
        о = фн(ш, tx)
        if not isinstance(о, dict) or not о.get("ok"):
            continue
        с = о.get("стороны") if isinstance(о.get("стороны"), dict) else о
        for ключ in ("минт_базы", "минт_выхода", "минт_b", "минт_a"):
            зн = с.get(ключ)
            if зн and зн != минт_котировки:
                return зн
        пара = [с.get("минт_a"), с.get("минт_b"), с.get("минт_coin"), с.get("минт_pc"),
                 с.get("минт_входа"), с.get("минт_выхода")]
        прочее = [з for з in пара if з and з != минт_котировки]
        if прочее:
            return прочее[0]
    return None


# ------------------------------------------------------- минимум выхода и пол

def minimum_vyhoda(*, база_в: int, резерв_базы=None, резерв_котировки=None,
                   котировка_типа=None, пол_лампорты: int = 0,
                   запас: float | None = None) -> dict:
    """Минимум выхода продажи и ПОЛ из аргумента. Политику полов не трогает.

    Два источника числа, в этом порядке:
      1. котировка_типа -- готовое число от котировщика этого типа (строитель или
         c2_swap_build), если полоса его уже посчитала;
      2. резервы -- кривая x*y=k минус запас, той же функцией, которой считает
         своя продажа Pump AMM (bloom_lane_sell.минимум_по_живым_резервам), чтобы
         два пути не считали по-разному.
    пол_лампорты -- НИЖНЯЯ граница от полосы. 0 означает "по любой цене" и
    выставляет min_out = 0: это решение правила 4, а не модуля.
    """
    из_ = {"ok": False, "min_out": None, "why_not": None, "откуда": None,
            "пол_лампорты": int(пол_лампорты or 0), "по_кривой": None}
    if int(база_в) <= 0:
        из_["why_not"] = "продавать нечего: количество не больше нуля"
        return из_
    # РЕЗЕРВЫ ПЕРЕДАНЫ, НО НЕ ПОЛОЖИТЕЛЬНЫ -- ЭТО ПОЛОМКА ЧИСЛА, А НЕ "ПО ЛЮБОЙ
    # ЦЕНЕ". Молча превратить ноль резерва в минимум 0 значило бы продать по
    # любой цене там, где полоса этого не говорила.
    for имя, зн in (("резерв базы", резерв_базы), ("резерв котировки", резерв_котировки)):
        if зн is not None and not (isinstance(зн, (int, float)) and зн > 0):
            из_["why_not"] = f"{имя} передан, но не положителен: {зн!r}"
            return из_
    число = None
    if isinstance(котировка_типа, int) and котировка_типа >= 0:
        число, из_["откуда"] = int(котировка_типа), "котировщик типа"
    elif резерв_базы and резерв_котировки:
        import bloom_lane_sell as LS  # noqa: PLC0415

        м = LS.минимум_по_живым_резервам(база_в=int(база_в),
                                         резерв_базы=int(резерв_базы),
                                         резерв_котировки=int(резерв_котировки),
                                         запас=запас)
        из_["по_кривой"] = м.get("po_krivoj")
        if not м.get("ok"):
            из_["why_not"] = м.get("why_not")
            return из_
        число, из_["откуда"] = int(м["min_out"]), "резервы минус запас"
    if число is None:
        # НИ КОТИРОВКИ, НИ РЕЗЕРВОВ. Это не повод продать по любой цене молча:
        # "по любой цене" говорит ПОЛОСА полом 0, и тогда ответ честный.
        if int(пол_лампорты or 0) == 0:
            из_.update(ok=True, min_out=0, откуда="пол 0 -- по любой цене")
            return из_
        из_["why_not"] = ("ни котировки типа, ни живых резервов -- минимум выхода "
                           "взять негде, а пол задан числом")
        return из_
    итог = max(int(число), int(пол_лампорты or 0))
    из_.update(ok=True, min_out=итог)
    if итог != число:
        из_["откуда"] = f"{из_['откуда']} поднят полом полосы"
    return из_


