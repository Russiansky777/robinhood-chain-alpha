def инструкция_продажи(ш: dict, *, наш_кошелёк: str, база_в: int,
                        минимум_выхода: int):
    """Инструкция продажи по шаблону. У каждого способа -- своя, чужими функциями."""
    from solders.instruction import AccountMeta, Instruction  # noqa: PLC0415
    from solders.pubkey import Pubkey  # noqa: PLC0415

    if not ш.get("ok"):
        raise ОшибкаПродавца(ш.get("why_not") or "шаблона продажи нет")
    _C, B = _кирпичи()
    сп, tpl = ш["способ"], ш["tpl"]
    if сп == SPOSOB_PO_IDL:
        import c3_pump_sborka as PS  # noqa: PLC0415

        собрано = PS.prodazha_krivoj_v3(
            base_mint=ш["минт_базы"], user=наш_кошелёк,
            buyback_fee_recipient=ш["buyback_fee_recipient"],
            base_token_program=ш["программа_базы"],
            amount=int(база_в), min_sol_output=int(минимум_выхода))
        return Instruction(
            Pubkey.from_string(собрано["programma"]),
            bytes.fromhex(собрано["data_hex"]),
            [AccountMeta(Pubkey.from_string(а["pubkey"]),
                         bool(а["isSigner"]), bool(а["isWritable"]))
             for а in собрано["accounts"]])
    if сп == SPOSOB_IZ_POKUPKI:
        import bloom_lane_sell as LS  # noqa: PLC0415

        return LS.инструкция_продажи(tpl, наш_кошелёк=наш_кошелёк,
                                      база_в=int(база_в),
                                      минимум_выхода=int(минимум_выхода))
    if сп == SPOSOB_STROITEL:
        import importlib  # noqa: PLC0415

        M = importlib.import_module(тип(ш["program"])["модуль"])
        return M.инструкция_свопа(tpl, user=наш_кошелёк, amount_in=int(база_в),
                                  min_out=int(минимум_выхода))
    # pary и flip -- кирпич c2_swap_build: имя инструкции и хвост от нашей покупки
    данные = (B.disc(ш["имя_инструкции"]) + struct.pack("<QQ", int(база_в),
                                                        int(минимум_выхода))
              + bytes(ш.get("хвост") or b""))
    метки = []
    for а in ш["accounts"]:
        метки.append(AccountMeta(Pubkey.from_string(а),
                                 is_signer=(а == наш_кошелёк),
                                 is_writable=bool((ш["writable"] or {}).get(а, False))))
    return Instruction(Pubkey.from_string(ш["program"]), данные, метки)


def инструкция_закрытия(счёт: str, владелец: str, программа_токена: str):
    """CloseAccount: остаток и рента уходят владельцу."""
    from solders.instruction import AccountMeta, Instruction  # noqa: PLC0415
    from solders.pubkey import Pubkey  # noqa: PLC0415

    метки = [AccountMeta(Pubkey.from_string(счёт), False, True),
             AccountMeta(Pubkey.from_string(владелец), False, True),
             AccountMeta(Pubkey.from_string(владелец), True, False)]
    return Instruction(Pubkey.from_string(программа_токена),
                       bytes([ЗАКРЫТЬ_СЧЁТ]), метки)


