П = O.П
МЕСТО = "S0_дно"      # по умолчанию; меняется флагом --mesto
MESTO_ЗАГЛУШКА = "S0_дно"
УДЕРЖАНИЯ = И.УДЕРЖАНИЯ
ДОЛЯ_РЕЗЕРВА = И.ДОЛЯ_РЕЗЕРВА
БИЛЕТ = И.БИЛЕТ
К_G_РЯДОМ = И.К_G_РЯДОМ
СЕМЯ = 20261010


def билет_по_глубине(р: dict, место: str = MESTO_ЗАГЛУШКА) -> float | None:
    """Предельный билет: не больше ДОЛЯ_РЕЗЕРВА от резерва пула на входе."""
    вх = (р.get("вход") or {}).get(место)
    if not вх:
        return None
    рез = float(вх[0]) / float(р.get("масштаб") or 1.0)
    б = ДОЛЯ_РЕЗЕРВА * рез
    return round(min(б, 3.0), 4) if б > 0.01 else None


def по_доле_слота(вх: dict, q: float) -> list | None:
    """Состояние слота источника, когда до нас прошла доля `q` его наплыва.

    Идём по инварианту x*y: x = x0 + q*(x_дно - x0), y = x0*y0/x. q = 0 -- сразу за
    сделкой источника (S0), q = 1 -- конец его слота (S0_дно), q = 0.5 -- середина
    наплыва. Доля блока, замеренная живьём при лаге 0 (медиана 0.784), читается как q,
    если свопы слота распределены по блоку ровно.
    """
    s0, sд = вх.get("S0"), вх.get("S0_дно")
    if not (s0 and sд):
        return None
    try:
        x0, y0, xд = float(s0[0]), float(s0[1]), float(sд[0])
    except (TypeError, ValueError, IndexError):
        return None
    x = x0 + q * (xд - x0)
    if x <= 0 or y0 <= 0 or x0 <= 0:
        return None
    return [x, x0 * y0 / x, *list(s0[2:])]


СЕТКА_ВЫХОДОВ = (6, 12, 24, 30, 36, 60, 72, 108, 150, 300)


def стоп_точка(вх: list, выход: dict, H: int, падение: float) -> int:
    """Первая точка сетки внутри удержания, где реальный резерв упал на `падение`.

    Стоп замерен ПО СЕТКЕ состояний выхода, а не по каждому событию: суточные файлы
    держат состояния только на этих отсечках. Так и подписано в выходных файлах.
    """
    try:
        x0 = float(вх[0])
    except (TypeError, ValueError, IndexError):
        return H
    порог = x0 * (1.0 - падение)
    for h in СЕТКА_ВЫХОДОВ:
        if h > H:
            break
        с = выход.get(str(h))
        if с:
            try:
                if float(с[0]) <= порог:
                    return h
            except (TypeError, ValueError, IndexError):
                continue
    return H


def середина_слота(вх: dict) -> list | None:
    """Состояние середины слота источника: половина наплыва слота уже прошла.

    Идём по инварианту x*y: x = (x0 + x_дно)/2, y = x0*y0/x. Это ровно половина наплыва
    слота источника по SOL, а не среднее двух цен.
    """
    s0, sд = вх.get("S0"), вх.get("S0_дно")
    if not (s0 and sд):
        return None
    try:
        x0, y0, xд = float(s0[0]), float(s0[1]), float(sд[0])
    except (TypeError, ValueError, IndexError):
        return None
    x = (x0 + xд) / 2.0
    if x <= 0 or y0 <= 0 or x0 <= 0:
        return None
    return [x, x0 * y0 / x, *list(s0[2:])]


def доли_по_источникам(база: float, низ: float = 0.05, верх: float = 0.6) -> dict:
    """Доля попадания отдельно по каждому источнику -- МОДЕЛЬ, не измерение.

    Архив не знает нашего места внутри блока источника. Он знает НАПЛЫВ в слоте
    источника: насколько цена ушла от S0 (сразу за его сделкой) к S0_дно (конец его
    слота). Чем больше наплыв, тем больше желающих стояло в том же слоте и тем меньше
    шанс попасть. Доля источника берётся обратно пропорционально его медианному наплыву
    и нормируется так, чтобы средняя по вселенной осталась равна `база`. По живым сделкам
    зависимости попадания от загрузки блока не видно, поэтому это чувствительность к
    допущению «доля плоская», а не измеренный закон.
    """
    наплыв: dict = collections.defaultdict(list)
    for р in O.сигналы():
        if р.get("quoteMint") != O.WSOL or not р.get("первая"):
            continue
        if (р.get("sol") or 0) < И.ПОРОГ_ИСТОЧНИКА:
            continue
        ист = р.get("ист")
        вх = р.get("вход") or {}
        s0, sд = вх.get("S0"), вх.get("S0_дно")
        if not (ист and s0 and sд):
            continue
        try:
            ц0 = float(s0[0]) / float(s0[1])
            цд = float(sд[0]) / float(sд[1])
        except (TypeError, ValueError, ZeroDivisionError, IndexError):
            continue
        if ц0 <= 0 or цд <= 0:
            continue
        наплыв[ист].append(max(0.0, цд / ц0 - 1.0))
    мед = {и: statistics.median(v) for и, v in наплыв.items() if v}
    if not мед:
        return {}
    общ = statistics.median(мед.values()) or 1e-9
    вес = {и: 1.0 / (1.0 + m / общ) for и, m in мед.items()}
    ср = statistics.fmean(вес.values()) or 1.0
    return {и: min(верх, max(низ, база * w / ср)) for и, w in вес.items()}


def проход(а, изд: float, место: str | None = None, доля: float | None = None,
           доли_ист: dict | None = None, мелкие: bool = False,
           удержания: tuple | None = None, стоп: float | None = None,
           часы: tuple | None = None, зеркало: bool = False) -> dict:
    """`удержания` -- свои отсечки вместо стандартных; `стоп` -- доля падения реального
    резерва, при которой выходим по сетке (рядом с обычным выходом); `часы` -- взять
    только сигналы этих часов UTC (срез «ночь» задаётся заранее, а не подбирается).

    Ключ ряда -- (источник, имя удержания, имя билета); имя удержания строковое, потому
    что рядом с «300» идёт «300|стоп30».
    """
    место = место or а.mesto
    доля = а.dolya if доля is None else доля
    удержания = удержания or УДЕРЖАНИЯ
    рнд = random.Random(СЕМЯ)
    ряды: dict = collections.defaultdict(list)
    счёт: collections.Counter = collections.Counter()
    for р in O.сигналы():
        счёт["сигналов"] += 1
        if р.get("quoteMint") != O.WSOL or not р.get("первая"):
            continue
        if (р.get("sol") or 0) < И.ПОРОГ_ИСТОЧНИКА:
            continue
        if часы is not None:
            if time.gmtime((р.get("ts") or 0) / 1000).tm_hour not in часы:
                счёт["не_тот_час"] += 1
                continue
        ист = р.get("ист")
        вх = р.get("вход") or {}
        if место == "S0_сер" and not вх.get("S0_сер"):
            сер = середина_слота(вх)
            if сер:
                вх["S0_сер"] = сер
                р["вход"] = вх
        elif место.startswith("S0_q") and not вх.get(место):
            сост = по_доле_слота(вх, float(место[4:]))
            if сост:
                вх[место] = сост
                р["вход"] = вх
        if not (ист and вх.get(место)):
            continue
        счёт["годных_сигналов"] += 1
        # прореживание: попали в блок источника только в доле --dolya случаев
        # (доли_ист -- отдельная доля на каждый источник, чувствительность)
        if рнд.random() > (доли_ист.get(ист, доля) if доли_ист else доля):
            счёт["мимо_блока_источника"] += 1
            continue
        счёт["вошли"] += 1
        с = O.как_сигнал(р)
        бг = билет_по_глубине(р, место)
        билеты = ((("0.01", 0.01), ("0.1", 0.1)) if мелкие else ()) + \
                 (("0.3", БИЛЕТ), ("глубина", бг))
        отсечки = []
        if зеркало:
            # зеркальный выход: продаём, когда продал источник. Состояние
            # «продажа_источника» -- это состояние СРАЗУ за его продажей, то есть до
            # толпы, которая за ним валится; значит это оптимистичная сторона, и так
            # оно и подписано. Потолок -- H300: если источник держит дольше, выходим
            # по 300 слотам.
            пс = р.get("первая_продажа_слотов")
            есть = bool((р.get("выход") or {}).get("продажа_источника"))
            цель = ("продажа_источника" if (есть and пс is not None and пс <= 300)
                    else 300)
            отсечки.append(("зеркало", цель))
            if стоп:
                отсечки.append(("зеркало|стоп{}".format(int(стоп * 100)),
                                стоп_точка(вх[место], р.get("выход") or {},
                                           пс if (пс and пс <= 300) else 300, стоп)))
        for H in удержания:
            отсечки.append((str(H), H))
            if стоп:
                отсечки.append((f"{H}|стоп{int(стоп * 100)}",
                                стоп_точка(вх[место], р.get("выход") or {}, H, стоп)))
        for имя_H, H in отсечки:
            for имя_б, б in билеты:
                if not б:
                    continue
                итоги = {}
                вид = None
                for кг in К_G_РЯДОМ:
                    и_, в_ = И.круг(с, б, место, H, изд, 1.0, кг)
                    вид = в_
                    if и_ is not None:
                        итоги[str(кг)] = и_
                if not итоги:
                    счёт[f"круг_нет|{вид}"] += 1
                    continue
                ряды[(ист, имя_H, имя_б)].append(
                    {"сутки": O.сутки(р), "итоги": итоги,
                     "итог": next(iter(итоги.values())),
                     "билет": б, "резерв": р.get("резерв_sol"), "вид": вид})
    return {"ряды": dict(ряды), "счёт": dict(счёт)}


def главное(а) -> int:  # noqa: PLR0915
    кал = (json.loads((П / "kalibrovka.json").read_text(encoding="utf-8"))
           .get("калибровка") or {})
    изд = float(кал.get("издержки_медиана_sol") or 0.002)
    print(f"доля попадания {а.dolya}, место {МЕСТО}, издержки {изд}", flush=True)
    п = проход(а, изд)
    дни = sorted({x["сутки"] for ряды in п["ряды"].values() for x in ряды})
    if not дни:
        print("сигналов не осталось", flush=True)
        return 2
    окна = И.окна_скольжения(дни, И.ПОДБОР_СУТОК, И.ПРОВЕРКА_СУТОК, И.СДВИГ_СУТОК)
    print(f"суток {len(дни)}: {дни[0]} .. {дни[-1]}; окон {len(окна)}; "
          f"счёт {п['счёт']}", flush=True)
    рнд = random.Random(СЕМЯ)
    по_кг = {}
    for кг in К_G_РЯДОМ:
        таб = {}
        for (ист, H, имя_б), ряды in п["ряды"].items():
            окон = []
            for _, пров_д in окна:
                пр = [x for x in ряды if x["сутки"] in пров_д]
                if not пр:
                    окон.append({"n": 0, "прошло": False})
                    continue
                с_ = И.свод(пр, пров_д, str(кг))
                пол = И.половины(пр, пров_д, str(кг))
                да, почему = И.окно_прошло(с_, пол)
                окон.append({"n": с_["n"], "sol_в_сутки": с_["sol_в_сутки"],
                             "прошло": да, "почему_нет": почему})
            всего = И.свод(ряды, дни, str(кг))
            p, p_пер = И.p_по_знакам(всего.get("суммы_по_суткам") or {}, рнд)
            годных = [o for o in окон if o["n"]]
            таб[f"{ист}|{H}|{имя_б}"] = {
                "источник": ист, "удержание": H, "билет": имя_б,
                "всё_окно": всего, "окна": окон, "окон_годных": len(годных),
                "окон_в_плюсе": sum(1 for o in окон if o["прошло"]),
                "прошло": bool(годных and len(годных) >= И.ОКОН_МИН
                               and all(o["прошло"] for o in годных)),
                "p": p, "p_перестановками": p_пер}
        по_кг[str(кг)] = таб
    осн = по_кг[str(а.k_g_osnovnaya)]
    N = len({v["источник"] for v in осн.values()})
    порог = 0.05 / max(1, N)
    for таб in по_кг.values():
        for v in таб.values():
            v["прошло_с_поправкой"] = bool(v["прошло"] and v["p"] is not None
                                           and v["p"] < порог)
    тело = {"что": "забор S+0: вход только в блок источника, цена S0_дно",
            "когда": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
            "допущения": {"место_входа": а.mesto, "доля_попадания": а.dolya,
                          "доля_откуда": "живые сделки vol_4vw: лаг 0 у 14 из 67 = 20.9 %; "
                                         "зависимости от загрузки блока не видно",
                          "мимо_блока": "сигнал выброшен без комиссии",
                          "издержки_sol": изд, "к_g_рядом": [str(x) for x in К_G_РЯДОМ],
                          "билеты": ["0.3", "предельный по глубине 2 % резерва"],
                          "N": N, "порог_p": порог},
            "окно": {"сутки": дни, "окон": len(окна)},
            "счёт": п["счёт"],
            "прошли": {кг: sorted(k for k, v in таб.items() if v["прошло_с_поправкой"])
                       for кг, таб in по_кг.items()},
            "таблица": [
                {"источник": v["источник"], "удержание": v["удержание"],
                 "билет": v["билет"], "n": (v["всё_окно"] or {}).get("n"),
                 "сделок_в_сутки": (v["всё_окно"] or {}).get("сделок_в_сутки"),
                 "sol_в_сутки": {кг: ((по_кг[кг].get(k) or {}).get("всё_окно") or {})
                                 .get("sol_в_сутки") for кг in по_кг},
                 "без_верх_5": (v["всё_окно"] or {}).get("без_верх_5_sol"),
                 "окон_в_плюсе": v["окон_в_плюсе"], "окон_годных": v["окон_годных"],
                 "p": v["p"], "глубина_ок": (v["всё_окно"] or {}).get("глубина_ок"),
                 "суток_в_плюсе": (v["всё_окно"] or {}).get("суток_в_плюсе"),
                 "суток": (v["всё_окно"] or {}).get("суток"),
                 "прошло": {кг: (по_кг[кг].get(k) or {}).get("прошло_с_поправкой")
                            for кг in по_кг}}
                for k, v in sorted(осн.items(),
                                   key=lambda kv: -((kv[1]["всё_окно"] or {})
                                                    .get("sol_в_сутки") or -1e9))[:120]]}
    ф = П / f"zabor_s0{а.metka}.json"
    ф.write_text(json.dumps(тело, ensure_ascii=False, indent=1), encoding="utf-8")
    try:
        import podbivka_run as R  # noqa: PLC0415
        R.записано(ф)
    except Exception:  # noqa: BLE001, S110
        pass
    print(json.dumps({k: v for k, v in тело.items()
                      if k not in ("таблица", "окно")}, ensure_ascii=False,
                     indent=1)[:1800], flush=True)
    print(f"\n{'источник':14}{'H':>4}{'билет':>9}{'n':>6}{'сд/сут':>8}"
          f"{'0.989':>10}{'1.000':>9}{'1.013':>9}{'без в5':>10}{'окон+':>7}{'p':>10}",
          flush=True)
    for r in тело["таблица"][:18]:
        s = r["sol_в_сутки"]
        print(f"{r['источник'][:12]:14}{r['удержание']:>4}{r['билет']:>9}{r['n']:>6}"
              f"{r['сделок_в_сутки']:>8}{(s.get('0.989') or 0):>+10.4f}"
              f"{(s.get('1.0') or 0):>+9.4f}{(s.get('1.013') or 0):>+9.4f}"
              f"{(r['без_верх_5'] or 0):>+10.4f}"
              f"{r['окон_в_плюсе']}/{r['окон_годных']:<4}"
              f"{(r['p'] if r['p'] is not None else 1):>10.2e}", flush=True)
    return 0


def main() -> int:
    р = argparse.ArgumentParser()
    р.add_argument("--dolya", type=float, default=0.209,
                   help="доля сигналов, в которых мы попали в блок источника")
    р.add_argument("--k-g-osnovnaya", type=float, default=1.0)
    р.add_argument("--mesto", default="S0_дно",
                   choices=("S0_дно", "S0_сер", "S1", "S2"))
    р.add_argument("--metka", default="")
    return главное(р.parse_args())


if __name__ == "__main__":
    raise SystemExit(main())
