"""BLAST 02.10 15:45Z: свод по цепи и спискам. Офлайн, по готовому data/podbivka/blast_15-45.json.

Собирает страницу docs/podbivka_2026-10-02_blast_15-45.md: 1) все транзакции пула в окне по слотам и крупные
покупки; 2) каждый адрес -- в наших списках или нет (реестр групп и log_only, cand2, cand3 / ведущие, сито
снайперов 10 485, GMGN, копировщики); 3) наш сигнал: источник, его слот и размер, слоты до нас; 4) верхние
покупатели через правило кандидатов по тем суточным файлам архива, где их сигналы уже есть (Правило 12 --
заново не считаем); 5) строка стоимости прохода метода по всем нашим сделкам за 7 суток.
"""
