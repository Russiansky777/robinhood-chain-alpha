КОРЕНЬ = PR.КОРЕНЬ
П = PR.П
НАШ_ВХОД_БИЛЕТ = 0.3          # правило кандидатов: главный билет
N_МИН, СР_МИН, ТОЛПА_МИН = 20, 2.0, 0.5


def списки() -> dict:
    """Словари «адрес -> имя списка»."""
    из_ = {}
    реестр = json.loads((П / "arhiv_adresa.json").read_text(encoding="utf-8"))["адреса"]
    из_["реестр"] = {a: ", ".join((v or {}).get("группы") or []) for a, v in реестр.items()}
    try:
        из_["ведущие_189"] = {a: "ведущие копировщиков (189, список cand3)"
                              for a in json.loads((П / "vedushie_adresa.json").read_text(encoding="utf-8"))["адреса"]}
    except FileNotFoundError:
        из_["ведущие_189"] = {}
    try:
        из_["gmgn"] = {a: "GMGN" for a in json.loads((П / "gmgn_adresa.json").read_text(encoding="utf-8"))["адреса"]}
    except FileNotFoundError:
        из_["gmgn"] = {}
    try:
        св = json.loads((П / "snaipery" / "dengi_svod.json").read_text(encoding="utf-8"))
        из_["сито"] = {a: f"сито снайперов по деньгам (10 485): итог {v.get('итог_после_prio_sol')} SOL, "
                          f"покупок {v.get('покупок_сито')}" for a, v in (св.get("ряды") or {}).items()}
    except FileNotFoundError:
        из_["сито"] = {}
    try:
        к = json.loads((П / "snaipery" / "kopirovschiki.json").read_text(encoding="utf-8"))
        из_["копировщики"] = {a: "верхние 50 копировщиков" for a in (к.get("верх") or [])}
        из_["копировщики"].update({a: "ведущие копировщиков, прошедшие сито" for a in (к.get("ведущие_годные") or [])})
    except FileNotFoundError:
        из_["копировщики"] = {}
    try:
        о = json.loads((П / "cand2_otbor.json").read_text(encoding="utf-8"))
        из_["cand2_отбор"] = {a: "прошёл отбор cand2" for a, v in (о.get("ряды") or {}).items()
                              if (v or {}).get("прошёл_отбор")}
    except FileNotFoundError:
        из_["cand2_отбор"] = {}
    try:
        c3 = json.loads((П / "cand3.json").read_text(encoding="utf-8"))
        из_["cand3"] = {a: "список cand3 по правилу" for a in (c3.get("список") or [])}
    except FileNotFoundError:
        из_["cand3"] = {}
    return из_


def где(a: str, сп: dict) -> str:
    есть = []
    for имя, карта in сп.items():
        if a in карта:
            есть.append(f"{имя}: {карта[a]}" if карта[a] else имя)
    return "; ".join(есть) or "нет ни в одном списке"


def по_правилу(адреса: list, шаблоны: list) -> dict:
    """Правило кандидатов по уже готовым суточным файлам архива (сигналы порога 2, окно отбора)."""
    цель = set(адреса)
    из_ = {a: {"сигналов": 0, "ячеек": 0, "никто": 0, "пп": [], "файлы": set()} for a in адреса}
    for шаб in шаблоны:
        for f in sorted(glob.glob(str(П / "arhiv_den" / шаб))):
            try:
                import gzip  # noqa: PLC0415
                д = json.loads(gzip.decompress(Path(f).read_bytes()))
            except (OSError, ValueError):
                continue
            for с in д.get("сигналы") or []:
                if с.get("trader") not in цель or not PR.окно(с, f):
                    continue
                к = из_[с["trader"]]
                к["сигналов"] += 1
                к["файлы"].add(Path(f).name.split("_")[0])
                if PR.в_ячейке(с, НАШ_ВХОД_БИЛЕТ):
                    к["ячеек"] += 1
                    к["пп"].append(PR.пп(с, НАШ_ВХОД_БИЛЕТ))
                    св = с.get("свопов") or {}
                    к["никто"] += 1 if (св.get("s1") or 0) + (св.get("s2") or 0) == 0 else 0
            del д
    for a, к in из_.items():
        s = PR.стат(к["пп"])
        толпа = round(1 - к["никто"] / к["ячеек"], 3) if к["ячеек"] else None
        к["итог"] = s
        к["толпа"] = толпа
        к["прошёл"] = bool(s.get("n", 0) >= N_МИН and (s.get("среднее") or -99) >= СР_МИН
                           and (s.get("медиана") or -99) > 0 and (толпа or 0) >= ТОЛПА_МИН)
        к["файлы"] = sorted(к["файлы"])
    return из_


def main() -> int:
    import podbivka_run as R  # noqa: PLC0415
    р = argparse.ArgumentParser()
    р.add_argument("--fayl", default="blast_15-45.json")
    р.add_argument("--shablony", default="cand2_*T16.json.gz,cand3_*T16.json.gz,porog14_*T16.json.gz",
                   help="через запятую: какие суточные файлы архива смотреть для п.4")
    а = р.parse_args()
    б = json.loads((П / а.fayl).read_text(encoding="utf-8"))
    сп = списки()
    стр = [r for r in б["строки"] if not r.get("why_not")]
    покупки = [r for r in стр if r.get("направление") == "покупка"]
    продажи = [r for r in стр if r.get("направление") == "продажа"]
    крупные = б.get("крупные_покупки") or []
    ор = б.get("ориентиры") or {}
    наша = next((v for k, v in ор.items() if len(k) > 40), None)
    ист = next((v for k, v in ор.items() if len(k) <= 40), None)

    def адр_строки(r: dict) -> str:
        return r.get("получил_токен") or r.get("подписант") or "—"

    участники: dict = {}
    for r in стр:
        for a in {адр_строки(r), r.get("подписант")}:
            if not a or a == "—":
                continue
            у = участники.setdefault(a, {"покупок": 0, "продаж": 0, "sol_покупок": 0.0, "sol_продаж": 0.0,
                                         "подписант_раз": 0, "первый_слот": None})
            if r.get("направление") == "покупка" and адр_строки(r) == a:
                у["покупок"] += 1
                у["sol_покупок"] = round(у["sol_покупок"] + (r.get("sol") or 0), 6)
            if r.get("направление") == "продажа" and (r.get("отдал_токен") == a or адр_строки(r) == a):
                у["продаж"] += 1
                у["sol_продаж"] = round(у["sol_продаж"] + (r.get("sol") or 0), 6)
            if r.get("подписант") == a:
                у["подписант_раз"] += 1
            у["первый_слот"] = min(x for x in (у["первый_слот"], r.get("слот")) if x) if r.get("слот") else у["первый_слот"]

    верх3 = [a for a, _ in sorted(участники.items(), key=lambda kv: -kv[1]["sol_покупок"])[:3]]
    правило = по_правилу(верх3, [x for x in а.shablony.split(",") if x]) if верх3 else {}

    сл_ист = (ист or {}).get("слот")
    сл_наш = (наша or {}).get("слот")
    сл_кр = min((r["слот"] for r in крупные), default=None)
    md = [f"# Подбивка: BLAST 02.10 15:45Z -- кто сделал движение в пуле PumpSwap", "",
          f"Минт `{б['минт']}`, пул `{б['пул']}` (PumpSwap / Pump AMM). Окно цепи "
          f"{б['окно'][0]} – {б['окно'][1]}: транзакций пула **{len(стр)}** (покупок {len(покупки)}, продаж "
          f"{len(продажи)}), слотов {len(б.get('по_слотам') or {})}. Владелец хранилищ пула опознан как "
          f"`{б.get('владелец_хранилищ_пула')}` (встречается в {б.get('доля_свопов_с_ним')} свопов окна) -- "
          "по нему и считается направление и размер; «кто получил токен» -- владелец токен-счёта из "
          "`postTokenBalances`, а не подписант. Ничего не рекомендуется.", "",
          "## 1. Цепь пула по слотам", "",
          "| слот | транзакций пула | покупок | продаж | SOL покупок | транзакций в блоке |", "|---|---|---|---|---|---|"]
    for сл, v in (б.get("по_слотам") or {}).items():
        md.append(f"| {сл} | {v['транзакций_пула']} | {v['покупок']} | {v['продаж']} | {v['sol_покупок']} | "
                  f"{v['транзакций_в_блоке']} |")
    md += ["", f"### Покупки ≥ {б['мин_sol']:g} SOL в {б['крупные_окно'][0]} – {б['крупные_окно'][1]}", "",
           "| UTC | слот | место в блоке | SOL | токенов | подписант | получил токен | в наших списках |",
           "|---|---|---|---|---|---|---|---|"]
    for r in крупные:
        a = адр_строки(r)
        md.append(f"| {r['utc']} | {r['слот']} | {r.get('место_в_блоке')}/{r.get('транзакций_в_блоке')} | "
                  f"{r['sol']:.3f} | {r['токенов']:.0f} | `{r['подписант']}` | `{a}` | {где(a, сп)} |")
    md += ["", "## 2. Участники окна и наши списки", "",
           "| адрес | покупок / SOL | продаж / SOL | подписант раз | первый слот | в наших списках |",
           "|---|---|---|---|---|---|"]
    for a, у in sorted(участники.items(), key=lambda kv: -kv[1]["sol_покупок"]):
        md.append(f"| `{a}` | {у['покупок']} / {у['sol_покупок']} | {у['продаж']} / {у['sol_продаж']} | "
                  f"{у['подписант_раз']} | {у['первый_слот']} | {где(a, сп)} |")
    md += ["", "## 3. Наш сигнал и расстояние по слотам", ""]
    if ист and not ист.get("why_not"):
        md.append(f"- Источник: подпись `{ист.get('signature', '')}` (`{ист.get('подписант')}` подписант, "
                  f"получил токен `{ист.get('получил_токен')}`), слот **{сл_ист}**, размер **{ист.get('sol')} SOL**, "
                  f"место в блоке {ист.get('место_в_блоке')}/{ист.get('транзакций_в_блоке')}, {ист.get('utc')}.")
    else:
        md.append(f"- Источник по префиксу не найден в окне: {json.dumps(ист, ensure_ascii=False)}")
    if наша and not наша.get("why_not"):
        md.append(f"- Наша покупка: `{наша.get('подписант')}`, слот **{сл_наш}**, {наша.get('sol')} SOL, "
                  f"место в блоке {наша.get('место_в_блоке')}/{наша.get('транзакций_в_блоке')}, {наша.get('utc')}.")
    if сл_кр and сл_ист:
        md.append(f"- Слотов между первой крупной покупкой окна (слот {сл_кр}) и источником: **{сл_ист - сл_кр}**.")
    if сл_ист and сл_наш:
        md.append(f"- Слотов между источником и нами: **{сл_наш - сл_ист}**.")
    md += ["", "## 4. Верхние покупатели через правило кандидатов (архив, окно 24.09 17Z – 01.10 17Z)", "",
           "Считается по уже готовым суточным файлам архива, заново архив не читается (Правило 12). Правило: "
           f"n ≥ {N_МИН} первых покупок, среднее ≥ +{СР_МИН:g} п.п. и медиана > 0 при нашем входе «конец слота» "
           f"на билете {НАШ_ВХОД_БИЛЕТ:g}, «толпа есть» ≥ {ТОЛПА_МИН:g}.", "",
           "| адрес | SOL покупок в окне BLAST | файлы архива | n | среднее, п.п. | медиана, п.п. | в плюсе | "
           "толпа | проходит правило |", "|---|---|---|---|---|---|---|---|---|"]
    for a in верх3:
        к = правило.get(a) or {}
        s = к.get("итог") or {"n": 0}
        md.append(f"| `{a}` | {участники[a]['sol_покупок']} | {', '.join(к.get('файлы') or []) or '—'} | "
                  f"{s.get('n', 0)} | " + (f"{s['среднее']:+.2f} | {s['медиана']:+.2f} | {s['в_плюсе']:.0%} | "
                                           if s.get("n") else "— | — | — | ")
                  + f"{к.get('толпа') if к.get('толпа') is not None else '—'} | "
                  + ("**да**" if к.get("прошёл") else "нет") + " |")
    md.append("")
    out = КОРЕНЬ / "docs" / "podbivka_2026-10-02_blast_15-45.md"
    out.write_text("\n".join(md) + "\n", encoding="utf-8")
    R.записано(out)
    дт = П / "blast_svod.json"
    дт.write_text(json.dumps({"участники": участники, "верх3": верх3,
                              "правило": {a: {k: v for k, v in (правило.get(a) or {}).items() if k != "пп"}
                                          for a in верх3},
                              "слоты": {"крупная": сл_кр, "источник": сл_ист, "мы": сл_наш}},
                             ensure_ascii=False, indent=1), encoding="utf-8")
    R.записано(дт)
    print(out.name, "участников", len(участники), "верх3", верх3, flush=True)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
