-- 01_pool_creation_blocks.sql
-- "Рождение" каждого пула — суррогат вместо настоящего PoolCreated/
-- Initialize события. Момент рождения пула = min(block_time) по этому
-- pool_address среди ВСЕХ свопов июля в query_02_swaps_raw_july.
--
-- Почему суррогат, а не настоящее событие создания пула (как было в
-- Sprint 1 изначально): полноценный гейт снайперов требовал бы join с
-- сырыми таблицами чейна (robinhood.transactions/traces,
-- erc20_robinhood.evt_transfer) — именно на несфильтрованном join с
-- robinhood.transactions пайплайн упёрся в 402 (см. docs/DATA_ACCESS.md,
-- "Инцидент: 402 на шаге 1"). По решению от 2026-08-31 сырые таблицы
-- чейна полностью убраны из Sprint 1: единственный источник — dex.trades
-- (курируемая, куда дешевле сканировать). Естественная плата за это —
-- пул не может "родиться" раньше своего первого ЗАСВОПАННОГО момента
-- (запись в dex.trades появляется только когда по пулу прошёл своп), то
-- есть эта метрика точна для пулов, где рождение = первый своп (что
-- верно для подавляющего большинства DEX-пулов — ликвидность и первый
-- своп добавляются почти всегда в одной транзакции или сразу следом).
-- Подробнее и обоснование, почему это приемлемый суррогат для Sprint 1,
-- а не финальный гейт — в docs/README.md, раздел "Гейт 1".
--
-- Не создаёт отдельной нагрузки на Dune: агрегирует уже отфильтрованный
-- (по дате/чейну/проекту) результат query_02, а не сканирует dex.trades
-- заново.

select
    pool_address,
    min(block_time) as pool_birth_time
from query_02_swaps_raw_july
group by pool_address
